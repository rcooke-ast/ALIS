"""Project bundles: a whole fit in one zip file (dashboard Stage 1).

The ALIS dashboard keeps each project in one file, ``project.model`` (D8). It is
an ordinary zip file, and ``run_alis project.model`` runs it without the
dashboard, with nothing unpacked to disk (D9)::

    manifest.json       format version, ALIS version, dates, the model's path,
                        the atomic table, the unblinding log, and a SHA-256
                        for every other member
    files/...           the model and its snips, at their relative paths on disk
    atomic/<name>       the atomic table the model uses (Q1.10)
    hidden.bin          hidden lines and files, compressed JSON (not readable)
    sources.json        the source spectra: path, SHA-256, size, dataset
    sources/...         source spectra embedded for archiving (optional)
    ui/...              the dashboard's own state (kept unchanged)
    runs/latest/...     the most recent run: run.json, input.mod, files/...
    runs/last_error.json  the last run that stopped with an error
    runs/0001/...       runs committed to the history (dashboard Stage 6)

**The files tree.** The root of ``files/`` is the lowest directory that holds the
model and all of its data, so the model text never needs to change (D7): a data
line is resolved exactly as on disk, relative to the model.

**Hidden values.** A model line with ``blind=True`` is stored as a placeholder
line, ``<hidden:n>``, with its real text kept in ``hidden.bin`` (D24, Q1.2). A
bundle run restores the lines in memory only. Of its outputs, the lines that
reveal blinded values are hidden the same way, and under ``run blind True`` the
whole ``.mod.out`` is. Hiding prevents accidental viewing, not a determined user
(QF.19(d)).

Generated by RJC and Claude.
"""

