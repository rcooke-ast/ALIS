"""Emit a standalone matplotlib script that reproduces a fit's figure.

ALIS already draws its own PDF (``out plots``). This is different: it writes a
*script*, so a publication figure can be edited -- panel order, labels, limits,
colours -- without re-running the fit or working inside ALIS. Stage 6.6 will
drive the same emitter from the GUI.

The emitted script is **self-contained**. The reference figures in
``context/plotting/`` all ``import plotting_routines as pr``, which is not
distributed; the handful of helpers they take from it are inlined here instead.
They are also Python 2 (``xrange``); what is written out is Python 3.

Layouts (RJC, Q5.7/Q5.9/Q5.11):

``metals``
    Three columns, as many rows as needed, transitions of the same ion adjacent.
``DH``
    Two columns. With **one** dataset the Lyman series runs down the left column
    and continues down the right; with **two** it is one dataset per column and
    one transition per row, so the same line can be compared across datasets;
    with more than two, the user picks by editing the emitted script (co-adding
    is deliberately out of scope until 6.6).

Generated by RJC and Claude.
"""

import os

import numpy as np

from alis import logger

msgs = logger.msgs()

# Velocity of light, km/s -- the same constant the reference scripts use.
CVEL = 299792.458

VALID_FORMATS = ("none", "metals", "DH")
DEFAULT_NUMCOL = {"metals": 3, "DH": 2}


def _keyword_ion(mkey):
    """The ``ion=`` of a model line, or None."""
    ion = mkey.get("ion", "") if hasattr(mkey, "get") else ""
    return ion or None


# The Lyman series is written in the model file as the pseudo-element 'Ly' with
# the series member as its "ion stage" -- 1Ly_a is Ly-alpha, 1Ly_b Ly-beta. On a
# figure those want to be Greek, and numbered once the letters run out, which is
# how the reference DH figures label them.
_LYMAN = {"a": r"$\alpha$", "b": r"$\beta$", "c": r"$\gamma$", "d": r"$\delta$"}


def _pretty_ion(ion, restwave):
    """'16O_I', 1302.1685 -> 'O I 1302' for a panel label.

    The isotope number is dropped: it is in the model file so the atomic mass
    can be looked up, but nobody labels a figure '16O'.
    """
    stem = ion.split("/")[0]
    parts = stem.split("_")
    element = parts[0].lstrip("0123456789") or parts[0]
    stage = parts[1] if len(parts) > 1 else ""
    if element == "Ly" and stage:
        low = stage.lower()
        if low in _LYMAN:
            member = _LYMAN[low]
        elif len(low) == 1 and low.isalpha():
            member = "{0:d}".format(ord(low) - ord("a") + 1)
        else:
            member = stage
        return "Ly{0:s} {1:.0f}".format(member, restwave)
    return "{0:s} {1:s} {2:.0f}".format(element, stage, restwave).strip()


def collect_panels(slf, params, vwindow=125.0):
    """One entry per transition the model actually places in the data.

    Each entry carries what the emitted script needs to draw the panel: the
    ``_fit.dat`` written by ``out fits``, how its columns are laid out, the
    observed centre wavelength, and a label.

    The transitions are found by asking each absorption component which of its
    lines fall in the snip's fitrange -- ``set_vars`` already does exactly that
    filtering for the fit itself, so a panel shows what was modelled rather than
    a guess from the wavelength range.

    A snip may hold several transitions, and they get a panel each: a fitrange
    covering O I 1302 and Si II 1304 spans ~460 km/s, far more than one velocity
    panel shows, so collapsing them to one would silently drop a line.
    Transitions closer together than ``vwindow`` *are* merged, keeping the
    strongest as the centre -- those are blends, which the reference figures
    also draw in a single panel.

    Generated by RJC and Claude.
    """
    panels = []
    funccall, funcinst = slf._funcarray[1], slf._funcarray[2]
    for sp in range(len(slf._posnfull)):
        for sn in range(len(slf._posnfull[sp]) - 1):
            wlo = slf._posnfit[sp][2 * sn + 0]
            whi = slf._posnfit[sp][2 * sn + 1]
            found = []
            for ival, mtyp in enumerate(slf._modpass["mtyp"]):
                if slf._modpass["emab"][ival] != "ab":
                    continue
                ion = _keyword_ion(slf._modpass["mkey"][ival])
                if ion is None or mtyp not in funcinst:
                    continue
                funcinst[mtyp]._keywd = slf._modpass["mkey"][ival]
                try:
                    got = funccall[mtyp].set_vars(
                        funcinst[mtyp],
                        params,
                        slf._levadd[ival] if hasattr(slf, "_levadd") else 0,
                        slf._modpass,
                        ival,
                        wvrng=[wlo, whi],
                        spid=str(slf._specid[sp]),
                        levid=getattr(slf, "_levadd", None),
                    )
                except Exception:  # a component that cannot be evaluated
                    continue  # here is simply not a panel
                got = np.asarray(got)
                if got.size == 0 or got.ndim != 2:
                    continue
                # columns: coldens, redshift, b, restwave, fvalue, gamma
                for row in got:
                    found.append((float(row[4]), float(row[3]), float(row[1]), ion))
            if not found:
                continue
            # Strongest first, then keep any line far enough from those already
            # taken to need a panel of its own.
            found.sort(key=lambda t: -t[0])
            centres = []
            for fval, restwave, zabs, ion in found:
                obs = restwave * (1.0 + zabs)
                if any(abs(CVEL * (obs - c) / c) < vwindow for c in centres):
                    continue
                centres.append(obs)
                panels.append(
                    dict(
                        datafile=_fit_filename(slf, sp, sn),
                        columns=_column_map(slf, sp, sn),
                        centre=obs,
                        restwave=restwave,
                        zabs=zabs,
                        ion=ion,
                        label=_pretty_ion(ion, restwave),
                        specid=str(slf._specid[sp]),
                        fitrange=(float(wlo), float(whi)),
                    )
                )
    return panels


def _column_map(slf, sp, sn):
    """{name: index} for the snip's data file, model appended last."""
    cols = slf._datopt["columns"][sp][sn]
    out = {}
    for name in cols.keys():
        idx = cols[name]
        if idx != -1:
            out[name] = int(idx)
    out["model"] = max(out.values()) + 1 if out else 1
    return out


def _fit_filename(slf, sp, sn):
    """The ``_fit`` file ``save_modelfits`` writes for this snip.

    Mirrors the naming there: the input snip name with ``_fit`` before the
    extension.
    """
    fname = slf._snipnames[sp][sn]
    fspl = fname.split(".")
    return ".".join(fspl[:-1]) + "_fit." + fspl[-1]


def _layout(fmt, panels, numcol, ndatasets):
    """(nrow, ncol, ordered panels) for the requested format."""
    if numcol in (None, "auto", ""):
        ncol = DEFAULT_NUMCOL.get(fmt, 3)
    else:
        ncol = int(numcol)
    ncol = max(1, ncol)
    if fmt == "metals":
        # Same element and ion adjacent, so a reader compares like with like.
        ordered = sorted(panels, key=lambda p: (p["ion"], p["restwave"]))
    elif fmt == "DH" and ndatasets == 2:
        # Columns are the datasets, rows the series: the same transition sits
        # side by side across datasets (context/plotting/DH_Lya-Ly7.py).
        specids = sorted({p["specid"] for p in panels})
        byline = {}
        for p in panels:
            byline.setdefault(round(p["restwave"], 3), {})[p["specid"]] = p
        ordered = []
        for restwave in sorted(byline, reverse=True):
            for sid in specids:
                if sid in byline[restwave]:
                    ordered.append(byline[restwave][sid])
        ncol = 2
    else:
        # One dataset (or more than two): the series runs down one column and
        # continues down the next, longest wavelength first.
        ordered = sorted(panels, key=lambda p: -p["restwave"])
        nrow = int(np.ceil(len(ordered) / float(ncol))) or 1
        columnwise = [None] * len(ordered)
        for i, p in enumerate(ordered):
            col, row = divmod(i, nrow)
            columnwise[row * ncol + col] = p
        ordered = [p for p in columnwise if p is not None]
    nrow = int(np.ceil(len(ordered) / float(ncol))) or 1
    return nrow, ncol, ordered


def _pair(value, default):
    """A 2-tuple from a setting that may be 'auto', a list, or a string."""
    if value in (None, "", "auto", "Auto", "AUTO"):
        return default
    if isinstance(value, str):
        value = value.split(",")
    return (float(value[0]), float(value[1]))


def build_script(slf, params, panels):
    """The text of the standalone script."""
    cfg = slf._argflag["plotscript"]
    fmt = cfg["format"]
    specids = {p["specid"] for p in panels}
    nrow, ncol, ordered = _layout(fmt, panels, cfg["numcol"], len(specids))
    vmin, vmax = _pair(cfg["velrange"], (-125.0, 125.0))
    fmin, fmax = _pair(cfg["ylim"], (-0.15, 1.3))
    nband = nrow * (2 if bool(cfg["residuals"]) else 1)
    figw, figh = _pair(cfg["figsize"], (2.4 * ncol + 0.6, 1.3 * nband + 0.9))
    fontsize = float(cfg["fontsize"])
    residuals = bool(cfg["residuals"])
    labels = bool(cfg["labels"])
    zref = ordered[0]["zabs"] if ordered else 0.0

    out = [
        '"""Plot the ALIS fit in {0:s}.'.format(
            os.path.basename(slf._argflag["run"]["modname"])
        )
    ]
    out += [
        "",
        "Written by ALIS (plotscript format {0:s}). It is a normal script:".format(fmt),
        "edit it freely -- the panel table below is the place to start.",
        "",
        "Reads the *_fit.dat files that 'out fits True' writes, so run the fit",
        "with that setting before running this.",
        '"""',
        "",
        "import numpy as np",
        "import matplotlib.gridspec as gridspec",
        "from matplotlib import pyplot as plt",
        "from matplotlib.ticker import FormatStrFormatter, MultipleLocator",
        "",
        "# ---------------------------------------------------------------- setup --",
        "VMIN, VMAX = {0!r}, {1!r}      # velocity range, km/s".format(vmin, vmax),
        "FMIN, FMAX = {0!r}, {1!r}      # normalised flux range".format(fmin, fmax),
        "FONTSIZE = {0!r}".format(fontsize),
        "NROW, NCOL = {0:d}, {1:d}".format(nrow, ncol),
        "ZREF = {0!r}   # velocities are relative to this redshift".format(zref),
        "RESIDUALS = {0!r}".format(residuals),
        "SHOWLABELS = {0!r}".format(labels),
        "OUTFILE = {0!r}".format(_figure_name(slf)),
        "",
        "CLDASH = [10, 5]   # continuum dash: 10 points on, 5 off",
        "ZLDASH = [5, 5]    # zero-level dash",
        "",
        "# One entry per panel, drawn in this order. 'columns' maps a quantity to",
        "# its column in the data file; 'centre' is the observed wavelength the",
        "# velocity scale is measured from.",
        "PANELS = [",
    ]
    for p in ordered:
        out.append("    dict(")
        out.append("        datafile={0!r},".format(p["datafile"]))
        out.append("        columns={0!r},".format(p["columns"]))
        out.append("        centre={0!r},".format(p["centre"]))
        out.append("        label={0!r},".format(p["label"]))
        out.append("        specid={0!r},".format(p["specid"]))
        out.append("    ),")
    out += [
        "]",
        "",
        "",
        "# ------------------------------------------------------------- routines --",
        "def process_data(cols, columns, centre):",
        '    """Normalise a snip and put it on a velocity scale.',
        "",
        "    Flux and model have the zero level removed and are divided by the",
        "    continuum, so both are on a 0-1 scale; 'shft' is the half-pixel offset",
        "    the model is drawn with, matching ALIS's own binning.",
        '    """',
        "    wave = cols[columns['wave']]",
        "    flux = cols[columns['flux']].copy()",
        "    error = cols[columns['error']].copy()",
        "    model = cols[columns['model']].copy()",
        "    if 'zerolevel' in columns:",
        "        zero = cols[columns['zerolevel']]",
        "        flux = flux - zero",
        "        model = model - zero",
        "    else:",
        "        zero = np.zeros_like(flux)",
        "    if 'continuum' in columns:",
        "        cont = cols[columns['continuum']] - zero",
        "        flux = flux / cont",
        "        error = error / cont",
        "        model = model / cont",
        "    velo = {0!r} * (wave - centre) / centre".format(CVEL),
        "    shft = velo[1:] - velo[:-1]",
        "    shft = np.append(velo[1] - velo[0], shft) * 0.5",
        "    return flux, error, model, velo, shft",
        "",
        "",
        "def standard_settings(ax, hidex=True, hidey=False):",
        '    """Axis furniture shared by every panel."""',
        "    lc, = ax.plot([VMIN, VMAX], [1.0, 1.0], linestyle='--', linewidth=1,",
        "                  color='dodgerblue')   # continuum",
        "    lz, = ax.plot([VMIN, VMAX], [0.0, 0.0], linestyle='--', linewidth=1,",
        "                  color='forestgreen')  # zero level",
        "    lc.set_dashes(CLDASH)",
        "    lz.set_dashes(ZLDASH)",
        "    ax.set_xlim([VMIN, VMAX])",
        "    ax.set_ylim([FMIN, FMAX])",
        "    ax.set_yticks([0.0, 0.5, 1.0])",
        "    ax.minorticks_on()",
        "    ax.xaxis.set_tick_params(which='major', length=6, width=1,",
        "                             labelsize=FONTSIZE)",
        "    ax.xaxis.set_tick_params(which='minor', length=3, width=1)",
        "    ax.tick_params(axis='y', which='major', labelsize=FONTSIZE)",
        "    ax.xaxis.set_minor_locator(MultipleLocator((VMAX - VMIN) / 10.0))",
        "    if hidex:",
        "        ax.xaxis.set_major_formatter(plt.NullFormatter())",
        "    else:",
        "        ax.xaxis.set_major_formatter(FormatStrFormatter(r'$%d$'))",
        "    if hidey:",
        "        ax.yaxis.set_major_formatter(plt.NullFormatter())",
        "    else:",
        "        ax.yaxis.set_major_formatter(FormatStrFormatter(r'$%.1f$'))",
        "",
        "",
        "# ----------------------------------------------------------------- plot --",
        "fig = plt.figure(figsize=({0!r}, {1!r}))".format(figw, figh),
        "gs = gridspec.GridSpec(NROW * (2 if RESIDUALS else 1), NCOL,",
        "                       figure=fig)",
        "# Margins are set in *inches* and converted, so the room left for the",
        "# shared labels stays the same whatever the panel count.",
        "gs.update(wspace=0.05, hspace=0.1,",
        "          left={0!r}, right={1!r}, bottom={2!r}, top={3!r})".format(
            round(0.75 / figw, 4),
            round(1.0 - 0.12 / figw, 4),
            round(0.72 / figh, 4),
            round(1.0 - 0.12 / figh, 4),
        ),
        "",
        "# Shared axis labels. The reference scripts overlay a frameless",
        "# add_subplot(111) for this; supxlabel/supylabel do the same job and get",
        "# the spacing right without a hand-tuned labelpad.",
        "fig.supylabel(r'Normalized Flux', fontsize=FONTSIZE + 1)",
        "fig.supxlabel(r'Velocity relative to $z=%.6f$ (km s$^{-1}$)' % ZREF,",
        "              fontsize=FONTSIZE + 1)",
        "",
        "for i, panel in enumerate(PANELS):",
        "    row, col = divmod(i, NCOL)",
        "    cols = np.loadtxt(panel['datafile'], unpack=True)",
        "    flux, error, model, velo, shft = process_data(",
        "        cols, panel['columns'], panel['centre'])",
        "    if RESIDUALS:",
        "        ax = fig.add_subplot(gs[2 * row, col])",
        "    else:",
        "        ax = fig.add_subplot(gs[row, col])",
        "    lastrow = (row == NROW - 1) or (i + NCOL >= len(PANELS))",
        "    standard_settings(ax, hidex=RESIDUALS or not lastrow, hidey=(col != 0))",
        "    ax.plot(velo, flux, drawstyle='steps', linewidth=1, color='k')",
        "    ax.plot(velo - shft, model, linestyle='-', linewidth=1, color='r')",
        "    if SHOWLABELS:",
        "        ax.annotate(panel['label'], xy=(0.04, 0.10),",
        "                    xycoords='axes fraction', fontsize=FONTSIZE,",
        "                    horizontalalignment='left', color='k')",
        "    if RESIDUALS:",
        "        axr = fig.add_subplot(gs[2 * row + 1, col])",
        "        good = error > 0.0",
        "        resid = np.zeros_like(flux)",
        "        resid[good] = (flux[good] - model[good]) / error[good]",
        "        axr.plot(velo, resid, drawstyle='steps', linewidth=1, color='0.4')",
        "        axr.axhline(0.0, linestyle='--', linewidth=1, color='forestgreen')",
        "        axr.set_xlim([VMIN, VMAX])",
        "        axr.set_ylim([-4.0, 4.0])",
        "        axr.set_yticks([-2.0, 0.0, 2.0])",
        "        axr.tick_params(labelsize=FONTSIZE - 2)",
        "        if col != 0:",
        "            axr.yaxis.set_major_formatter(plt.NullFormatter())",
        "        if not lastrow:",
        "            axr.xaxis.set_major_formatter(plt.NullFormatter())",
        "",
        "fig.savefig(OUTFILE)",
        "print('wrote ' + OUTFILE)",
        "",
    ]
    return "\n".join(out) + "\n"


def _figure_name(slf):
    stem = os.path.basename(slf._argflag["run"]["modname"])
    if stem.endswith(".mod"):
        stem = stem[: -len(".mod")]
    return stem + "_plot.pdf"


def script_name(slf):
    """Where the script is written: ``plotscript filename``, or the default."""
    given = slf._argflag["plotscript"]["filename"]
    if given:
        return given
    return slf._argflag["run"]["modname"] + ".plot.py"


def write_plotscript(slf, params):
    """Write the standalone plotting script, if one was asked for.

    Returns the path written, or None. Never raises: a fit that has completed
    should not be lost to a plotting problem, so anything unexpected is reported
    as a warning and the run carries on.

    Generated by RJC and Claude.
    """
    cfg = slf._argflag["plotscript"]
    fmt = str(cfg["format"]).strip()
    if fmt.lower() == "none" or fmt == "":
        return None
    if fmt not in VALID_FORMATS:
        msgs.error(
            "Unknown 'plotscript format' value: "
            + fmt
            + msgs.newline()
            + "Please choose from - "
            + ", ".join(VALID_FORMATS)
        )
    verbose = slf._argflag["out"]["verbose"]
    if not slf._argflag["out"]["fits"]:
        msgs.warn(
            "'plotscript' needs the per-snip fits that 'out fits True'"
            + msgs.newline()
            + "writes; the emitted script will not find"
            + " its data files.",
            verbose=verbose,
        )
    vmin, vmax = _pair(cfg["velrange"], (-125.0, 125.0))
    try:
        panels = collect_panels(slf, params, vwindow=0.5 * (vmax - vmin))
    except Exception as err:
        msgs.warn(
            "Could not work out the panels for the plotting script:"
            + msgs.newline()
            + str(err),
            verbose=verbose,
        )
        return None
    if not panels:
        msgs.warn(
            "No absorption transitions were found to plot;"
            + msgs.newline()
            + "not writing a plotting script.",
            verbose=verbose,
        )
        return None
    fname = script_name(slf)
    if os.path.exists(fname) and not (
        cfg["overwrite"] or slf._argflag["out"]["overwrite"]
    ):
        msgs.warn(
            "Plotting script already exists, not overwriting:" + msgs.newline() + fname,
            verbose=verbose,
        )
        return None
    try:
        text = build_script(slf, params, panels)
        with open(fname, "w") as fil:
            fil.write(text)
    except Exception as err:
        msgs.warn(
            "Could not write the plotting script:" + msgs.newline() + str(err),
            verbose=verbose,
        )
        return None
    msgs.info(
        "Wrote plotting script ({0:d} panels):".format(len(panels))
        + msgs.newline()
        + fname,
        verbose=verbose,
    )
    return fname
