"""CUDA implementation of the Voigt profile (Stage 4.2).

This module is the GPU counterpart of ``Voigt.call_CPU`` in
:mod:`alis.functions.voigt`, and reproduces it to well inside the 1e-12
absolute tolerance required of a ``call_GPU`` (stage doc Q4.3), in float64
throughout (Q4.6).

**Import this module lazily.** The ``@cuda.jit`` decorators below run at import
time, so importing numba at ALIS start-up is exactly what Task 4.1 forbids: a
CPU-only install must never touch numba. The module therefore lives beside
``voigt.py`` rather than inside it, and is imported from within
``Voigt.call_GPU()`` -- the kernel still belongs to the function it implements,
but the lazy boundary set up in :mod:`alis.gpu` is preserved. Nothing in ALIS
imports this module at start-up.

The Faddeeva function
---------------------
``call_CPU`` computes the Voigt profile as ``Re w(v + i a)`` via
``scipy.special.wofz``, which *is* Steven G. Johnson's Faddeeva package. The
device functions below are a float64 port of that same algorithm, taken from
the worked example in ``context/voigt_gpu/`` (whose C++ original is kept
alongside it). Reproducing the algorithm operation-for-operation, rather than
substituting a cheaper approximation, is what lets the GPU agree with the CPU
to ~1e-15 instead of the ~1e-6 a Voigt lookup table would give -- and the
finite-difference Jacobian, hence the covariance matrix, needs that.

The two read-only coefficient tables are held in **constant memory**
(``cuda.const.array_like``, plan Q4.11). That is the right choice here rather
than merely an adequate one: constant memory broadcasts at full speed when a
warp reads a single address, and both lookups are warp-uniform in this kernel
-- ``erfcx`` is indexed by the damping parameter ``a``, which is a property of
the transition and so is identical across all threads, and ``expa2n2`` is
indexed by a series counter that starts at 1 for every thread.

Generated by RJC and Claude.
"""

import math
from pathlib import Path

import numpy as np
from numba import cuda

