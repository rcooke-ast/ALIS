"""The dashboard's actions: one registry for the menus, the toolbar and the shortcuts.

Dashboard Stage 3.7 (F10). Every action the window offers is listed here once, with
its name, the text of its menu entry, its menu, its keyboard shortcut and its
tooltip. The menus, the toolbar and the shortcut sheet are all built from this list,
so they cannot disagree, and a later command search (F10, after v1) can use it too.
The handlers are bound by the window (``alis/dashboard/qt/window.py``); this module
needs no Qt.

Shortcuts are written in Qt's portable form (``Ctrl+S``), which is shown as ⌘S on
macOS.

Generated by RJC and Claude.
"""

