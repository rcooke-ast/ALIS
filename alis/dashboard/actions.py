def get(name):
    """The action with this name."""
    return BY_NAME[name]


def in_menu(menu):
    """
    The actions of one menu, in order.

    Generated by RJC and Claude.
    """
    return [action for action in ACTIONS if action.menu == menu]


def shortcut_sheet():
    """
    The shortcut sheet: every action, by menu, with its shortcut and what it does.

    Returns
    -------
    list of tuple
        ``(menu, text, shortcut, tip)``, in menu order.

    Generated by RJC and Claude.
    """
    out = []
    for menu in GROUPS:
        for action in in_menu(menu):
            text = action.text.rstrip("…")
            if action.submenu:
                text = "{0} › {1}".format(action.submenu, text)
            out.append((menu, text, action.shortcut, action.tip))
    return out


def duplicate_shortcuts():
    """
    Shortcuts given to more than one action (there must be none).

    Returns
    -------
    dict
        Shortcut to the names of its actions.

    Generated by RJC and Claude.
    """
    seen = {}
    for action in ACTIONS:
        if action.shortcut:
            seen.setdefault(action.shortcut.lower(), []).append(action.name)
    return {key: names for key, names in seen.items() if len(names) > 1}


