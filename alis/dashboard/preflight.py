"""The pre-flight check: what would stop a fit, and what is worth a look first.

Dashboard Stage 6.2 (S17; Q6.4, Q6.16). No Qt.

Run checks the project first. Each finding names its line of the ``.mod`` panel, or
its snip, so that a click shows it.

- **Run is refused** when ALIS would stop, or a bundle cannot run the model: the
  model does not read, or ALIS's loaders refuse it (``validate.check``); a "command
  line only" setting, or a data line that reads a file from disk
  (``bundle.unsupported``), with the way to run it (File → Export plain files…,
  then ``run_alis``); a starting value outside its limits; no free parameter, or
  more free parameters than fitted pixels.
- **Notes**, after which Run goes ahead: a free parameter that reaches no fitted
  pixel (ALIS's own influence table), so the data cannot constrain it; an ion in no
  snip; a starting value at one of its limits; a b_turb starting below 1 km/s (a
  preference); a snip with no continuum; the notices of an imported fit kept as
  imported (D20, D22); pixels fitted twice (D19); regions changed since the
  components were last edited; CPUs that leave none of this computer's, so that
  ALIS fits with one.

Blinding: no message gives a hidden value. A note that would reveal something of
one (a hidden value at its limit, or below 1 km/s) is not made.

Generated by RJC and Claude.
"""

from dataclasses import dataclass, field

from alis import bundle as B
from alis import load
from alis.config import ArgFlag
from alis.dashboard import blinding as BL
from alis.dashboard import markers as MK
from alis.dashboard import profile as PF
from alis.dashboard import settings as ST
from alis.dashboard import text as T
from alis.dashboard import validate as V

REFUSE, NOTE = "refuse", "note"
# The b_turb below which a starting value is noted, without preferences (km/s)
LOW_B = 1.0


@dataclass
class Finding:
    """
    One finding of the check.

    Attributes
    ----------
    kind : str
        :data:`REFUSE` or :data:`NOTE`.
    message : str
        What is wrong, through the blinding gate.
    line : int or None
        The model line it is about, from 0.
    snip : str or None
        The snip it is about (its specid).
    code : str
        What kind of finding it is, for tests and for the window.

    Generated by RJC and Claude.
    """

    kind: str
    message: str
    line: int | None = None
    snip: str | None = None
    code: str = ""


@dataclass
class Report:
    """
    The findings of the check.

    Generated by RJC and Claude.
    """

    findings: list = field(default_factory=list)

    @property
    def refusals(self):
        return [f for f in self.findings if f.kind == REFUSE]

    @property
    def notes(self):
        return [f for f in self.findings if f.kind == NOTE]

    @property
    def ok(self):
        """Whether Run may go ahead."""
        return not self.refusals

    def summary(self):
        """What the Run box says: "Pre-flight check: no problems; 2 notes"."""
        refused, notes = len(self.refusals), len(self.notes)
        if refused:
            text = "Pre-flight check: Run is refused ({0} problem{1})".format(
                refused, "" if refused == 1 else "s"
            )
        else:
            text = "Pre-flight check: no problems"
        if notes:
            text += "; {0} note{1}".format(notes, "" if notes == 1 else "s")
        return text

    def codes(self, kind=None):
        """The codes of the findings (of one kind)."""
        return [f.code for f in self.findings if kind is None or f.kind == kind]


def _pref(prefs, key, default):
    if prefs is None:
        return default
    try:
        return prefs[key]
    except KeyError:
        return default


def _first_places(pm):
    """Each ALIS parameter's defining place (the one with its starting value)."""
    out = {}
    for par in pm.params:
        if par.index >= 0 and par.first and par.index not in out:
            out[par.index] = par
    return out


def _name(par):
    """How a finding names a parameter: ``ColDens on line 24``."""
    return "{0} on line {1}".format(par.name, par.line + 1)


def _readable(project, problems, gate):
    """Refusals for a model that does not read, or that ALIS refuses."""
    out = []
    if project.paused:
        out.append(
            Finding(
                REFUSE,
                "The model does not read. Correct it in the .mod panel.",
                code="unreadable",
            )
        )
        return out
    for problem in problems:
        if problem.severity != V.ERROR:
            continue
        out.append(
            Finding(REFUSE, gate.message(problem.message), problem.line, code="alis")
        )
    return out


def _command_line(project):
    """
    Refusals for what a bundle cannot run (Q6.16(b)): read from the text, so that
    they are given even while the model does not read (a file it names, such as an
    LSF, is not in the project).

    Generated by RJC and Claude.
    """
    out = []
    for line in T.ModelText(project.text).lines:
        if line.block != "data" or line.kind != T.DATA:
            continue
        for reason in B.unsupported(ArgFlag(), [line.text]):
            out.append(
                Finding(
                    REFUSE,
                    "The data line {0}, so a project file cannot run it. {1}".format(
                        reason, ST.EXPORT_ADVICE
                    ),
                    line.num,
                    code="command_line",
                )
            )
    if project.paused:
        return out
    for item, _value, line in ST.command_line_only(project):
        out.append(
            Finding(
                REFUSE,
                "'{0}' can be run only on the command line, because a project file"
                " cannot run it. {1}".format(item.name, ST.EXPORT_ADVICE),
                line,
                code="command_line",
            )
        )
    return out


def _cpus(project, prefs):
    """A note when the CPUs asked for leave none of this computer's (``run ncpus
    0``, or -20 on a computer with 8), so that ALIS fits with one (Q6.24)."""
    used = ST.computer_used(project, prefs) if prefs is not None else {}
    value, from_model = used.get(("run", "ncpus"), (None, False))
    if value is None:
        written = ST.model_settings(project).get(("run", "ncpus"))
        value, from_model = (written[0], True) if written else (None, False)
    if value is None or not ST.leaves_no_cpu(value):
        return []
    line = ST.model_settings(project).get(("run", "ncpus"), (None, None))[1]
    where = (
        "the model's 'run ncpus {0}'".format(value)
        if from_model
        else "the CPUs preference ({0})".format(value)
    )
    return [
        Finding(
            NOTE,
            "ALIS will fit with 1 CPU: {0} leaves none of this computer's {1}. Use"
            " a number, or -1 for all bar one.".format(where, load.cpu_count()),
            line if from_model else None,
            code="cpus",
        )
    ]


def _limits(project, gate):
    """Starting values outside their limits (refused) or on them (noted)."""
    out = []
    limpar = ST.model_settings(project).get(("run", "limpar"))
    moved = False
    if limpar is not None:
        try:
            moved = bool(ST.check_value("run", "limpar", limpar[0]))
        except ST.SettingError:
            moved = False
    for par in _first_places(project.parsed).values():
        if not par.free:
            continue
        low, high = par.limits
        value = par.start
        outside = (low is not None and value < low) or (
            high is not None and value > high
        )
        on = (low is not None and value == low) or (high is not None and value == high)
        if outside and not moved:
            out.append(
                Finding(
                    REFUSE,
                    "The starting value of {0} is outside its limits: ALIS would"
                    " stop. Change the value or the limits.".format(_name(par)),
                    par.line,
                    code="outside_limits",
                )
            )
        elif (on or outside) and not gate.is_hidden(par):
            out.append(
                Finding(
                    NOTE,
                    "{0} starts at one of its limits.".format(_name(par)),
                    par.line,
                    code="at_limit",
                )
            )
    return out


def _low_b(project, gate, threshold):
    """b_turb starting below the threshold (``doc/ALIS_workflow.md`` §4.1.2)."""
    out = []
    for par in _first_places(project.parsed).values():
        if par.name != "bturb" or gate.is_hidden(par):
            continue
        if par.start < threshold:
            out.append(
                Finding(
                    NOTE,
                    "{0} starts below {1:g} km/s, where a fit can find it hard to"
                    " move.".format(_name(par), threshold),
                    par.line,
                    code="low_b",
                )
            )
    return out


def _free_and_fitted(project):
    """
    The free parameters, the fitted pixels and the influence of each parameter, by
    ALIS's own tables; None where the profile cannot be built.

    Generated by RJC and Claude.
    """
    free = {p.index for p in project.parsed.params if p.free and p.index >= 0}
    try:
        profile = PF.of(project)
    except PF.ProfileError:
        return free, None, None
    pixels = profile.fitted_pixels()
    reach = profile.influence()
    return free, pixels, reach


def _counts(project, free, pixels):
    out = []
    if not free:
        out.append(
            Finding(
                REFUSE,
                "No parameter is free, so there is nothing to fit.",
                code="no_free",
            )
        )
    elif pixels is not None:
        total = sum(pixels.values())
        if len(free) > total:
            out.append(
                Finding(
                    REFUSE,
                    "There are more free parameters ({0}) than fitted pixels ({1})."
                    " Fix some parameters, or fit more pixels.".format(
                        len(free), total
                    ),
                    code="too_many_free",
                )
            )
    return out


def _unreached(project, free, pixels, reach):
    """Free parameters that reach no fitted pixel."""
    if pixels is None or reach is None:
        return []
    reached = set()
    for index, count in pixels.items():
        if count > 0:
            reached |= reach.get(index, set())
    out = []
    places = _first_places(project.parsed)
    for index in sorted(free - reached):
        par = places.get(index)
        if par is None:
            continue
        out.append(
            Finding(
                NOTE,
                "{0} reaches no fitted pixel, so the data cannot constrain it.".format(
                    _name(par)
                ),
                par.line,
                code="unreached",
            )
        )
    return out


def _snips(project):
    out = []
    for snip in project.snips:
        from_data = "continuum" in str(snip.data.keyword("columns") or "")
        if snip.continuum is None and not from_data:
            out.append(
                Finding(
                    NOTE,
                    "The snip {0} has no continuum.".format(snip.specid),
                    snip.data.line,
                    snip.specid,
                    code="no_continuum",
                )
            )
    for one, two, count in MK.fitted_twice(project):
        out.append(
            Finding(
                NOTE,
                "{0} pixels are fitted twice, in {1} and {2}.".format(count, one, two),
                snip=one,
                code="fitted_twice",
            )
        )
    return out


def _structure(project):
    from alis.dashboard import components as C

    out = []
    for notice in project.notices:
        if notice.kind in ("untied", "isotopes"):
            out.append(
                Finding(
                    NOTE,
                    notice.message,
                    notice.lines[0] if notice.lines else None,
                    code="notice",
                )
            )
    try:
        bare = C.unsnipped_ions(project)
    except Exception:
        bare = []
    for system, row in bare:
        out.append(
            Finding(
                NOTE,
                "{0} (z = {1:.5f}) is in no snip, so its lines constrain nothing.".format(
                    row.name, system.z
                ),
                code="no_snip",
            )
        )
    marks = project.ui.get(MK.MARKS)
    if marks is not None and marks.get("regions") != MK.regions_fingerprint(project):
        out.append(
            Finding(
                NOTE,
                "The regions have changed since the components were last edited.",
                code="regions_changed",
            )
        )
    return out


def check(project, prefs=None, problems=None):
    """
    The pre-flight check of a project (S17).

    Parameters
    ----------
    project : Project
    prefs : Preferences, optional
        This computer's settings and the check's thresholds.
    problems : list of Problem, optional
        The validator's problems, when the window has them; checked again if not.

    Returns
    -------
    Report

    Generated by RJC and Claude.
    """
    gate = BL.Gate(project)
    if problems is None and not project.paused:
        problems = V.check(project)
    findings = _readable(project, problems or [], gate)
    findings += _command_line(project)
    if project.paused:
        return Report(findings)
    findings += _cpus(project, prefs)
    findings += _limits(project, gate)
    free, pixels, reach = _free_and_fitted(project)
    findings += _counts(project, free, pixels)
    findings += _unreached(project, free, pixels, reach)
    findings += _low_b(project, gate, _pref(prefs, "fit.low_b", LOW_B))
    findings += _snips(project)
    findings += _structure(project)
    return Report(findings)


__all__ = ["check", "Report", "Finding", "REFUSE", "NOTE", "LOW_B"]
