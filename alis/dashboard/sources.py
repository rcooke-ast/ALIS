"""Source spectra: where each one is, whether it has changed, and relinking (F13).

Dashboard Stage 3.9. A project records each source spectrum by path and SHA-256
(``sources.json`` in the bundle, Stage 1). On opening, and from File → Relink
spectra…, each source is reported as:

- ``present``: found where it was, unchanged;
- ``missing``: not found, neither at its path nor beside the bundle where it was;
- ``changed``: found, but its checksum differs: it is reported, and never accepted;
- ``embedded``: not found on disk, but a copy is embedded in the bundle, so it is
  never missing.

A moved spectrum is relinked by pointing to its new place; the file is accepted only
if its checksum matches (``alis.bundle.relink_source``).

Generated by RJC and Claude.
"""

import json
import os

from alis import bundle as B

PRESENT, MISSING, CHANGED, EMBEDDED = "present", "missing", "changed", "embedded"
# Checksums of files already read, by (path, modification time, size)
_SHA = {}
# Source spectra already read, by (checksum, column roles) (Stage 4)
_SPECTRA = {}


def file_sha256(path):
    """
    The SHA-256 of a file, read again only when the file changes.

    Generated by RJC and Claude.
    """
    info = os.stat(path)
    key = (os.path.abspath(path), info.st_mtime_ns, info.st_size)
    if key not in _SHA:
        if len(_SHA) > 200:
            _SHA.clear()
        with open(path, "rb") as fil:
            _SHA[key] = B.sha256(fil.read())
    return _SHA[key]


def location(entry, bundle_path=None):
    """
    Where a source is looked for: beside the bundle, at its path relative to it,
    when it is there; otherwise at its absolute path.

    Generated by RJC and Claude.
    """
    if bundle_path is not None and entry.get("relpath"):
        candidate = os.path.join(
            os.path.dirname(os.path.abspath(bundle_path)), entry["relpath"]
        )
        if os.path.isfile(candidate):
            return candidate
    return entry["path"]


def states(bundle, bundle_path=None):
    """
    The state of every source spectrum of a bundle.

    Returns
    -------
    list of tuple
        ``(entry, state)``, the state ``"present"``, ``"missing"``, ``"changed"`` or
        ``"embedded"``.

    Generated by RJC and Claude.
    """
    out = []
    for entry in bundle.sources:
        where = location(entry, bundle_path)
        if not os.path.isfile(where):
            embedded = entry.get("embedded")
            state = EMBEDDED if embedded and embedded in bundle.members else MISSING
        else:
            state = PRESENT if file_sha256(where) == entry["sha256"] else CHANGED
        out.append((entry, state))
    return out


def problems(bundle, bundle_path=None):
    """The sources that are missing or changed, as ``(entry, state)``."""
    return [(e, s) for e, s in states(bundle, bundle_path) if s in (MISSING, CHANGED)]


def relink(bundle, ident, newpath, bundle_path=None):
    """
    Point a moved source to its new place, if the file there is the same spectrum.

    Raises
    ------
    alis.bundle.BundleError
        If its checksum differs: a changed file is never accepted.

    Generated by RJC and Claude.
    """
    if file_sha256(newpath) != bundle.source(ident)["sha256"]:
        raise B.BundleError(
            "This file is not the same spectrum: its checksum differs from the"
            " one recorded when it was added.\n  " + newpath
        )
    B.relink_source(bundle, ident, newpath, bundle_path)


def spectrum(project, row, bundle_path=None):
    """
    A file row's source spectrum, read once per session by its checksum and its
    column roles (dashboard Stage 4), or None when it cannot be read: the row has no
    source, or it is missing, or it has changed (a changed file is never used).

    Parameters
    ----------
    project : Project
    row : Row
    bundle_path : str, optional
        The project's file, so that a source moved with it is found beside it.

    Returns
    -------
    alis.dashboard.modes.Spectrum or None

    Generated by RJC and Claude.
    """
    from alis.dashboard import modes

    entry = row.source
    if not entry:
        return None
    key = (entry["sha256"], json.dumps(row.columns or {}, sort_keys=True))
    if key in _SPECTRA:
        return _SPECTRA[key]
    where = location(entry, bundle_path)
    if os.path.isfile(where):
        if file_sha256(where) != entry["sha256"]:
            return None
        source = where
    else:
        embedded = entry.get("embedded")
        if not embedded or embedded not in project.bundle.members:
            return None
        source = project.bundle.members[embedded]
    mode = modes.get(project.ui.get("mode", "qso_abs_line"))
    try:
        spec = mode.load(source, row.columns)
    except modes.ModeError:
        return None
    if len(_SPECTRA) > 16:
        _SPECTRA.clear()
    _SPECTRA[key] = spec
    return spec


def describe(entry, state):
    """
    One line about a source, for the Relink dialog and the Data tab's marker.

    Generated by RJC and Claude.
    """
    name = os.path.basename(entry["path"])
    if state == MISSING:
        return "{0} is missing (it was at {1}).".format(name, entry["path"])
    if state == CHANGED:
        return "{0} has changed since it was added (its checksum differs).".format(name)
    if state == EMBEDDED:
        return "{0} is not on disk; the copy kept in the project is used.".format(name)
    return "{0} is present and unchanged.".format(name)


