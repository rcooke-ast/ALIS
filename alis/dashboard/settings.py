"""The settings of a fit: the model's own, this computer's, and the dashboard's.

Dashboard Stage 6.2 (F9, D38; Q6.4, Q6.6(a), Q6.16). No Qt.

- **Every setting** comes from ALIS's own list (``alis.config.ArgFlag``), with its
  default, its kind (a tick box, a whole number, a number, a word, a word from a
  list, or anything ALIS reads) and its one-line description (Q6.6(a)). None is
  kept here but who owns it.
- **The model's settings** are its ``par`` lines. Setting one writes or changes its
  line, and clearing one removes its lines, each one step of the history.
- **This computer's settings** (``run backend``, ``ncpus``, ``ngpus``; Q6.4(a)) are
  preferences of the computer (``fit.*``), given to each run on its command line,
  so that a model fitted on a laptop runs unchanged on a GPU machine. A model that
  sets one keeps its line, and its value is used.
- **The dashboard's own settings for its runs** (Q6.16(a)): ``out verbose 1``, no
  plot windows, the covariance and the report. They are given on the run's command
  line only, never written in the model, so ``run_alis`` on the project, or on its
  exported plain files on another machine, runs it exactly as written.
- **Command line only** (Q6.16(b)): ``sim random``, ``sim perturb``, ``sim
  beginfrom``, ``iterate model`` and ``generate data``, which a bundle cannot run.
  They can be written like any other; while one is set, the pre-flight check
  refuses Run and says how to run the model (File → Export plain files…, then
  ``run_alis``). Generating data from the dashboard is future work
  (``deferred_work.md`` §7.5).
- **Left out:** the settings ALIS does not use, and ``run modname``, which ALIS
  sets itself.

Generated by RJC and Claude.
"""

import copy
import os
from dataclasses import dataclass

from alis import load
from alis.config import ArgFlag, settings_help
from alis.dashboard import edit as E
from alis.dashboard import model as M
from alis.dashboard import text as T

# Kinds of value
BOOL, INT, FLOAT, WORD, CHOICE, ANY = "bool", "int", "float", "word", "choice", "any"
# Who owns a setting
MODEL, COMPUTER, DASHBOARD, COMMAND_LINE = "model", "computer", "dashboard", "command"

# The words ALIS takes for some settings
CHOICES = {
    ("run", "backend"): ("auto", "cpu", "gpu"),
    ("run", "datatype"): ("default", "HIRESredux", "UVESpopler"),
    ("run", "bintype"): ("km/s", "A", "Hz"),
    ("plot", "xaxis"): ("observed", "rest", "velocity"),
    ("plotscript", "format"): ("none", "metals", "DH"),
    ("sim", "convergetest"): ("maxdev", "scatter"),
}
# This computer's settings, and the preferences that hold them (Q6.4(a))
COMPUTER_SETTINGS = {
    ("run", "backend"): "fit.backend",
    ("run", "ncpus"): "fit.ncpus",
    ("run", "ngpus"): "fit.ngpus",
}
# What the dashboard's runs use, besides a covariance file (Q6.16(a))
DASHBOARD_SETTINGS = {
    ("out", "verbose"): "1",
    ("plot", "fits"): "False",
    ("out", "report"): "True",
    ("out", "covar"): None,
}
# The settings a bundle cannot run (bundle.unsupported; Q6.16(b))
COMMAND_LINE_ONLY = (
    ("sim", "random"),
    ("sim", "perturb"),
    ("sim", "beginfrom"),
    ("iterate", "model"),
    ("generate", "data"),
)
# Not offered, and why
LEFT_OUT = {
    ("run", "modname"): "ALIS sets it to the model's name when the model is run.",
    ("run", "last_update"): "ALIS does not use it.",
    ("run", "logn"): "ALIS does not use it.",
    ("out", "reletter"): "ALIS does not use it.",
    ("iterate", "data"): "ALIS does not use it.",
}
EXPORT_ADVICE = (
    "Export plain files (File → Export plain files…) and run run_alis on them, on"
    " this computer or another."
)


class SettingError(ValueError):
    """A value that ALIS refuses for a setting."""


@dataclass
class Setting:
    """
    One of ALIS's settings, as the dashboard offers it.

    Attributes
    ----------
    section, key : str
        ``run``, ``ncpus``.
    default : object
        ALIS's default.
    kind : str
        :data:`BOOL`, :data:`INT`, :data:`FLOAT`, :data:`WORD`, :data:`CHOICE` or
        :data:`ANY`.
    choices : tuple
        The words of a :data:`CHOICE`.
    help : str
        What it does, in one line (Q6.6(a)).
    owner : str
        :data:`MODEL`, :data:`COMPUTER`, :data:`DASHBOARD` or :data:`COMMAND_LINE`.

    Generated by RJC and Claude.
    """

    section: str
    key: str
    default: object
    kind: str
    choices: tuple
    help: str
    owner: str

    @property
    def name(self):
        """``run ncpus``."""
        return "{0} {1}".format(self.section, self.key)

    @property
    def default_text(self):
        """The default as a ``par`` line writes it."""
        return _text(self.default)


def _text(value):
    if value is None:
        return "None"
    if isinstance(value, (list, tuple)):
        return ",".join(_text(v) for v in value)
    return str(value)


def _kind(section, key, default):
    if (section, key) in CHOICES:
        return CHOICE
    if isinstance(default, bool):
        return BOOL
    if isinstance(default, int):
        return INT
    if isinstance(default, float):
        return FLOAT
    if isinstance(default, str):
        return WORD
    return ANY


def _owner(section, key):
    if (section, key) in COMPUTER_SETTINGS:
        return COMPUTER
    if (section, key) in DASHBOARD_SETTINGS:
        return DASHBOARD
    if (section, key) in COMMAND_LINE_ONLY:
        return COMMAND_LINE
    return MODEL


def catalogue():
    """
    Every setting the dashboard offers, by section, in ALIS's order (F9, Q6.16(b)).

    Generated by RJC and Claude.
    """
    cfg = ArgFlag()
    helps = settings_help()
    out = []
    for section in cfg.keys():
        for key in cfg[section].keys():
            if (section, key) in LEFT_OUT:
                continue
            default = copy.deepcopy(cfg[section][key])
            out.append(
                Setting(
                    section,
                    key,
                    default,
                    _kind(section, key, default),
                    CHOICES.get((section, key), ()),
                    helps[section][key],
                    _owner(section, key),
                )
            )
    return out


def setting(section, key):
    """One setting of :func:`catalogue`."""
    for item in catalogue():
        if (item.section, item.key) == (section, key):
            return item
    reason = LEFT_OUT.get((section, key))
    raise SettingError(
        "'{0} {1}' is not offered{2}".format(
            section, key, ": " + reason if reason else " (ALIS has no such setting)."
        )
    )


# -- The model's settings ------------------------------------------------------------


def check_value(section, key, value):
    """
    The value as ALIS reads it, or :class:`SettingError` with ALIS's reason.

    Parameters
    ----------
    section, key : str
    value : str
        The value as a ``par`` line writes it.

    Generated by RJC and Claude.
    """
    value = str(value).strip()
    if not value or len(value.split()) != 1:
        raise SettingError("A setting's value is one word, such as 4 or True.")
    item = setting(section, key)
    if item.kind == CHOICE and value not in item.choices:
        raise SettingError(
            "'{0}' takes one of: {1}.".format(item.name, ", ".join(item.choices))
        )
    argflag = ArgFlag()
    try:
        with M.alis_quietly():
            load.set_params(["{0} {1} {2}".format(section, key, value)], argflag)
    except M.AlisStop as stop:
        raise SettingError(M.plain(stop.message)) from None
    return argflag[section][key]


def model_settings(project):
    """
    The settings the model writes, ``{(section, key): (value, line)}``: the last
    line wins, as ALIS reads them.

    Generated by RJC and Claude.
    """
    out = {}
    for item in project.parsed.settings:
        out[(item.category, item.key)] = (item.value, item.line)
    return out


@dataclass
class Changed:
    """
    A setting the model writes: its value, its line, and ALIS's default.

    Generated by RJC and Claude.
    """

    setting: Setting
    value: str
    line: int
    differs: bool


def changed(project):
    """
    The settings the model writes whose values differ from ALIS's defaults, for the
    Run box's "Settings you changed" (D38): ALIS's own reading of each is compared
    with its default.

    Generated by RJC and Claude.
    """
    out = []
    offered = {(s.section, s.key): s for s in catalogue()}
    for (section, key), (value, line) in model_settings(project).items():
        item = offered.get((section, key))
        if item is None:
            continue
        try:
            read = check_value(section, key, value)
        except SettingError:
            read = None
        differs = read is None or read != item.default
        if differs:
            out.append(Changed(item, value, line, differs))
    out.sort(key=lambda c: c.line)
    return out


def set_step(project, section, key, value):
    """
    The step that writes ``section key value``: the last line that sets it is
    changed, or a line is added after the model's other settings.

    Raises
    ------
    SettingError
        If ALIS refuses the value.

    Generated by RJC and Claude.
    """
    project.require_reading()
    check_value(section, key, value)
    words = "{0} {1} {2}".format(section, key, str(value).strip())
    change = E.set_setting(project.parsed, section, key, str(value).strip())
    return project.step(change, "Set " + words)


def clear_step(project, section, key):
    """
    The step that returns a setting to ALIS's default: every line that sets it is
    removed (✕ in the Run box).

    Returns
    -------
    Step or None
        None when the model does not set it.

    Generated by RJC and Claude.
    """
    project.require_reading()
    pm = project.parsed
    lines = sorted(
        (s.line for s in pm.settings if (s.category, s.key) == (section, key)),
        reverse=True,
    )
    if not lines:
        return None
    patches = tuple(T.delete_lines(pm.text, num) for num in lines)
    change = T.Change(patches, "Clear {0} {1}".format(section, key))
    return project.step(change, "Return {0} {1} to its default".format(section, key))


# -- What the dashboard's runs are given (Q6.4, Q6.16(a)) ---------------------------


def computer_settings(prefs):
    """
    This computer's settings, from the preferences: ``{(section, key): value}``.

    Generated by RJC and Claude.
    """
    out = {}
    for name, pref in COMPUTER_SETTINGS.items():
        try:
            out[name] = prefs[pref]
        except (KeyError, TypeError):
            out[name] = ArgFlag()[name[0]][name[1]]
    return out


def cpus(value):
    """
    A number of CPUs as ALIS counts it when it reads a model (``load.cpucheck``):
    -1 is every CPU of this computer bar one, -2 bar two, and so on. ALIS does not
    count a setting given on its command line so, so the dashboard gives its runs
    the number itself (Stage 6.5).

    Parameters
    ----------
    value : int or str

    Returns
    -------
    int

    Raises
    ------
    SettingError
        If ALIS cannot read it as a number of CPUs.

    Generated by RJC and Claude.
    """
    try:
        number = int(str(value).strip())
    except ValueError:
        raise SettingError("'{0}' is not a number of CPUs.".format(value)) from None
    with M.alis_quietly():
        return int(load.cpucheck(number, verbose=-1))


def covar_name(project):
    """The covariance file the dashboard asks for: ``<model>.covar``."""
    stem = os.path.splitext(os.path.basename(project.model_member))[0]
    return stem + ".covar"


def run_settings(project, prefs=None):
    """
    The settings given to a run of the dashboard on its command line, as
    ``"section key value"``, never written in the model (Q6.16(a)): ``out verbose
    1``, no plot windows, the report, a covariance file unless the model names one,
    and this computer's settings unless the model sets them (its CPUs as a number,
    :func:`cpus`).

    Generated by RJC and Claude.
    """
    model = model_settings(project)
    out = []
    for (section, key), value in DASHBOARD_SETTINGS.items():
        if (section, key) == ("out", "covar"):
            written = model.get((section, key), ("", None))[0].strip("\"'")
            if written:
                continue
            value = covar_name(project)
        out.append("{0} {1} {2}".format(section, key, value))
    if prefs is not None:
        for (section, key), value in computer_settings(prefs).items():
            if (section, key) not in model:
                if (section, key) == ("run", "ncpus"):
                    # ALIS counts -1 as "all bar one" only in a model
                    value = cpus(value)
                out.append("{0} {1} {2}".format(section, key, value))
    return out


def computer_used(project, prefs):
    """
    The computer's settings a run uses, ``{(section, key): (value, from_model)}``:
    the model's own when it sets one (the Run box says so), or the preference.

    Generated by RJC and Claude.
    """
    model = model_settings(project)
    out = {}
    for name, value in computer_settings(prefs).items():
        if name in model:
            out[name] = (model[name][0], True)
        else:
            out[name] = (str(value), False)
    return out


def command_line_only(project):
    """
    The "command line only" settings the model sets to a value a bundle cannot run,
    ``[(Setting, value, line)]``.

    Generated by RJC and Claude.
    """
    out = []
    model = model_settings(project)
    for section, key in COMMAND_LINE_ONLY:
        if (section, key) not in model:
            continue
        value, line = model[(section, key)]
        try:
            read = check_value(section, key, value)
        except SettingError:
            continue
        if read in (None, False, "", '""', "''"):
            continue
        out.append((setting(section, key), value, line))
    return out


