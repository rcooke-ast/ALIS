"""The figures of the Figure tab (dashboard Stage 9; D28, D42, S22). No Qt.

A publication figure is drawn from a fit: the tab is enabled once the run the Fit tab
shows (the run chosen in its run history, the latest by default; never the fit in
progress) has a best fit, and every figure draws that run (point 2 of Stage 8, RJC's
response to Q9.1). While anything is hidden the tab is greyed, since a figure shows
the hidden lines' profiles (Q9.5).

- **The figures** (Q9.6): a project holds any number, kept in ``ui/project.json``
  under ``figures``, so that each change is one step of the history and undo is
  exact. Each has a name (Figure 1, Figure 2, …; the exported files are named after
  it, Q9.11), a grid of columns × rows, a size in inches, the spacing between its
  panels, a velocity range, the component its velocities are measured from, the
  residuals, the colours, the style, the shared axis titles, signed velocities and
  the components' numbers above their ticks (Q9.9, Q9.12). A new figure copies the
  shown figure's layout with every cell empty.
- **The cells** (Q9.7–Q9.9, Q9.12): each row of the grid is a list of cells, whose
  spans fill its columns; a panel spans one or more columns of its row, never more
  than one row. A cell shows one transition of a system in one snip (or nothing),
  with its x axis (velocity, observed or rest wavelength), its ranges, its titles
  and tick numbers, its label and the corner it sits in, a title above it, its y
  ticks, and the ions and components it ticks. Every option left unset follows the
  figure, or the cell's place in the grid.
- **Arranging** (D42, Q9.10): a transition dropped on a cell takes it (the one there
  goes back to Not shown); a drag between cells swaps them, or copies; a drag off
  the grid empties a cell. The same transition of the same system from the same snip
  may be shown twice, in one figure or across figures, but is reported, with the
  other panels named. A cell whose snip has been removed shows nothing, with a note,
  and shows its transition again if the snip comes back (undo).
- **Saved presets** (S22): a figure's layout, with each cell's transition by ion and
  wavelength, kept in the dashboard's folder (``~/.alis/figures/``) for every
  project.

Generated by RJC and Claude.
"""

