class FigureError(Exception):
    """A change to a figure that cannot be made: a message for the user."""


def unavailable(project, view):
    """
    Why the Figure tab is greyed, or ``""`` when it can be used.

    Parameters
    ----------
    project : Project
    view : results.View or None
        The run the Fit tab shows (a committed run, not the fit in progress).

    Returns
    -------
    str

    Generated by RJC and Claude.
    """
    if view is None or view.in_progress or X.best_fit_reason(project, view):
        return NO_FIT
    if X.blinded(project, view):
        return BLINDED
    if not view.has_best_fit:
        return NO_FIT
    return ""


# -- The transitions that cells can show -------------------------------------------


@dataclass(frozen=True)
class Entry:
    """
    A transition a cell can show: one transition of a system, in one snip.

    Attributes
    ----------
    specid : str
        The snip's.
    system : str
        The system's id.
    ion : str
    rest : float
        The rest wavelength in Å: the transition the snip was cut for, when it is of
        this ion, or else the ion's strongest inside the snip (as the Components
        tab's panels, D61).
    line : str
        ``"Si II 1260.4"`` or ``"Lyβ 1025.7"``.
    dataset : str
        The snip's dataset (its row's name).

    Generated by RJC and Claude.
    """

    specid: str
    system: str
    ion: str
    rest: float
    line: str
    dataset: str

    @property
    def key(self):
        """What a cell keeps of it."""
        return key_of(self.specid, self.system, self.ion, self.rest)

    @property
    def name(self):
        """``"Si II 1260.4 · HIRES"``."""
        return "{0} · {1}".format(self.line, self.dataset)


def key_of(specid, system, ion, rest):
    """A cell's transition, as ``ui/project.json`` keeps it."""
    return {"specid": specid, "system": system, "ion": ion, "rest": round(rest, 4)}


def same(one, two):
    """Whether two kept transitions are the same: one transition of one system,
    from one snip (Q9.10)."""
    if not one or not two:
        return False
    return (
        one["specid"] == two["specid"]
        and one["system"] == two["system"]
        and one["ion"] == two["ion"]
        and abs(float(one["rest"]) - float(two["rest"])) <= SAME_REST
    )


def line_text(ion, rest):
    """``"Si II 1260.4"``; ``"Lyβ 1025.7"``; ``"D Lyβ 1025.4"``."""
    mass, element, stage = P.split_ion(ion)
    element = "D" if (element == "H" and mass == 2) else element
    return C.L.line_name(element, stage, rest)


def _main_ions(ions):
    """The ions, an element's rarer isotopes left out when its main one is there
    (D I is shown in H I's panels, D36)."""
    groups = {}
    for ion in ions:
        _, elem, stage = P.split_ion(ion)
        groups.setdefault((elem, stage), []).append(ion)
    out = []
    for (elem, _), found in groups.items():
        main = [i for i in found if P.split_ion(i)[0] == P.MAIN_ISOTOPE.get(elem)]
        out.append(main[0] if main else found[0])
    return out


def transitions(project):
    """
    Every transition a cell can show: for each snip with its pixels, each system's
    ions (isotopes with their element) with a transition inside it, the datasets in
    order (the reference first).

    Returns
    -------
    list of Entry

    Generated by RJC and Claude.
    """
    extents = C._extents(project)
    cut = C.L.snip_transitions(project)
    out = []
    for system in project.systems:
        ions = _main_ions(C.system_ions(project, system))
        for ion in ions:
            for row, snip, inside in C.ion_snips(project, system, ion, extents=extents):
                rest = inside.rest
                own = cut.get(snip.specid)
                if (
                    own is not None
                    and own.system == system.id
                    and own.ion == ion
                    and any(
                        abs(own.rest - r) <= 0.01 for r in [inside.rest] + inside.others
                    )
                ):
                    rest = own.rest
                out.append(
                    Entry(
                        snip.specid,
                        system.id,
                        ion,
                        rest,
                        line_text(ion, rest),
                        row.name,
                    )
                )
    return out


def entry_of(project, kept, found=None):
    """The :class:`Entry` a cell keeps, or None when it is no longer there."""
    if not kept:
        return None
    for entry in transitions(project) if found is None else found:
        if same(entry.key, kept):
            return entry
    return None


# -- The figures ----------------------------------------------------------------------


def figures(project):
    """The project's figures, in order (dicts, not to be changed in place)."""
    return project.ui.get(FIGURES_KEY, [])


def figure(project, fid):
    """
    A figure by its id.

    Raises
    ------
    FigureError

    Generated by RJC and Claude.
    """
    for fig in figures(project):
        if fig["id"] == fid:
            return fig
    raise FigureError("There is no figure {0}.".format(fid))


def blank_cell(span=1):
    """An empty cell."""
    cell = copy.deepcopy(CELL_DEFAULTS)
    cell["span"] = span
    return cell


def blank_rows(columns, rows):
    """The cells of an empty grid."""
    return [[blank_cell() for _ in range(columns)] for _ in range(rows)]


def _with_figures(project, found, description):
    """The step that replaces the figures with ``found``."""
    ui = copy.deepcopy(project.ui)
    if found:
        ui[FIGURES_KEY] = found
    else:
        ui.pop(FIGURES_KEY, None)
    return project.set_ui(ui, description)


def _changed(project, fid, change, description):
    """
    The step that changes one figure: ``change`` gets a copy and changes it.

    Generated by RJC and Claude.
    """
    found = copy.deepcopy(figures(project))
    for fig in found:
        if fig["id"] == fid:
            change(fig)
            return _with_figures(project, found, description)
    raise FigureError("There is no figure {0}.".format(fid))


def _next_id(found):
    numbers = [int(f["id"][1:]) for f in found if f["id"][1:].isdigit()]
    return "f{0:d}".format(max(numbers, default=0) + 1)


def next_name(project):
    """``"Figure 1"``, ``"Figure 2"``, …: the first that is free."""
    taken = {f["name"].lower() for f in figures(project)}
    num = 1
    while "figure {0:d}".format(num) in taken:
        num += 1
    return "Figure {0:d}".format(num)


def new_figure(project, like=None, layout=None):
    """
    The step that adds a figure (Create new figure, Q9.6): with the layout of figure
    ``like`` (its grid, spans, axes, labels, size, spacing, ranges, residuals,
    colours and style) and every cell empty, or with ``layout`` (a figure's options
    and cells, from a preset), or else the defaults.

    Returns
    -------
    tuple
        ``(Step, str)``: the step, and the new figure's id.

    Generated by RJC and Claude.
    """
    found = copy.deepcopy(figures(project))
    fig = copy.deepcopy(DEFAULTS)
    fig["cells"] = blank_rows(fig["columns"], fig["rows"])
    if like is not None:
        source = copy.deepcopy(figure(project, like))
        for key in DEFAULTS:
            fig[key] = source.get(key, fig[key])
        fig["cells"] = source["cells"]
        for row in fig["cells"]:
            for cell in row:
                # The layout is kept; what the cell shows, and its words, are not
                cell["show"] = None
                cell["label"] = ""
                cell["title"] = ""
                cell["ions"] = None
                cell["components"] = None
    elif layout is not None:
        for key in DEFAULTS:
            fig[key] = copy.deepcopy(layout.get(key, fig[key]))
        if layout.get("cells"):
            fig["cells"] = copy.deepcopy(layout["cells"])
    fig["id"] = _next_id(found)
    fig["name"] = next_name(project)
    fig = {"id": fig.pop("id"), "name": fig.pop("name"), **fig}
    found.append(fig)
    return _with_figures(project, found, "Create " + fig["name"]), fig["id"]


def check_name(project, name, fid=None):
    """
    The name a figure can take, or a :class:`FigureError` saying why not.

    Generated by RJC and Claude.
    """
    name = " ".join(name.split())
    if not name:
        raise FigureError("Give the figure a name.")
    if not _NAME.match(name):
        raise FigureError(
            "A figure's name names its files, so it may hold only letters, digits,"
            " spaces, hyphens, underscores and dots."
        )
    for fig in figures(project):
        if fig["id"] != fid and fig["name"].lower() == name.lower():
            raise FigureError("Another figure is called {0}.".format(fig["name"]))
    return name


def rename(project, fid, name):
    """The step that renames a figure (Rename…)."""
    name = check_name(project, name, fid)
    old = figure(project, fid)["name"]

    def change(fig):
        fig["name"] = name

    return _changed(project, fid, change, "Rename {0} as {1}".format(old, name))


def delete(project, fid):
    """The step that deletes a figure (Delete figure…), which Undo takes back."""
    name = figure(project, fid)["name"]
    found = [copy.deepcopy(f) for f in figures(project) if f["id"] != fid]
    return _with_figures(project, found, "Delete " + name)


# -- The grid -------------------------------------------------------------------------


def cell_at(fig, row, col):
    """
    The cell whose span covers column ``col`` of row ``row``, and the column it
    starts at.

    Returns
    -------
    tuple
        ``(cell, start)``.

    Raises
    ------
    FigureError

    Generated by RJC and Claude.
    """
    if not 0 <= row < len(fig["cells"]):
        raise FigureError("The figure has no row {0:d}.".format(row + 1))
    start = 0
    for cell in fig["cells"][row]:
        if start <= col < start + cell["span"]:
            return cell, start
        start += cell["span"]
    raise FigureError("The figure has no column {0:d}.".format(col + 1))


def places(fig):
    """Every cell, as ``(row, start, cell)``."""
    out = []
    for num, cells in enumerate(fig["cells"]):
        start = 0
        for cell in cells:
            out.append((num, start, cell))
            start += cell["span"]
    return out


def _fit_row(cells, columns):
    """A row's cells cut or filled to ``columns`` columns; the cells that no longer
    fit are dropped (their transitions go back to Not shown)."""
    out, used = [], 0
    for cell in cells:
        if used >= columns:
            break
        cell = copy.deepcopy(cell)
        cell["span"] = min(cell["span"], columns - used)
        out.append(cell)
        used += cell["span"]
    while used < columns:
        out.append(blank_cell())
        used += 1
    return out


def set_grid(project, fid, columns, rows):
    """
    The step that gives a figure ``columns`` × ``rows`` cells: a grid made smaller
    sends the cells that no longer fit back to Not shown, and cuts a span at the new
    edge (D42).

    Generated by RJC and Claude.
    """
    columns, rows = int(columns), int(rows)
    if not (1 <= columns <= 8 and 1 <= rows <= 20):
        raise FigureError("A figure has 1 to 8 columns and 1 to 20 rows.")

    def change(fig):
        cells = fig["cells"][:rows]
        cells += [[] for _ in range(rows - len(cells))]
        fig["cells"] = [_fit_row(c, columns) for c in cells]
        fig["columns"], fig["rows"] = columns, rows

    return _changed(
        project, fid, change, "Make the grid {0:d} × {1:d}".format(columns, rows)
    )


def set_span(project, fid, row, col, span):
    """
    The step that makes a cell span ``span`` columns of its row (Q9.7): the cells it
    comes to cover leave the row, their transitions back to Not shown; a smaller span
    gives back empty cells. A span cannot pass the row's end.

    Generated by RJC and Claude.
    """
    fig = figure(project, fid)
    cell, start = cell_at(fig, row, col)
    span = int(span)
    if not 1 <= span <= fig["columns"] - start:
        raise FigureError(
            "This panel can span 1 to {0:d} columns: it starts in column {1:d} of"
            " {2:d}.".format(fig["columns"] - start, start + 1, fig["columns"])
        )

    def change(fig):
        cells = fig["cells"][row]
        index = next(k for k, c in enumerate(cells) if c is _find(fig, row, start))
        mine = cells[index]
        old = mine["span"]
        mine["span"] = span
        if span > old:
            # Take the columns it now covers from the cells after it
            need, after = span - old, index + 1
            while need > 0 and after < len(cells):
                nxt = cells[after]
                if nxt["span"] <= need:
                    need -= nxt["span"]
                    del cells[after]
                else:
                    nxt["span"] -= need
                    nxt["show"] = None
                    need = 0
        else:
            for _ in range(old - span):
                cells.insert(index + 1, blank_cell())

    return _changed(
        project,
        fid,
        change,
        "Span {0:d} column{1}".format(span, "" if span == 1 else "s"),
    )


def _find(fig, row, start):
    """The cell starting at ``start`` in row ``row`` of ``fig`` (itself, not a
    copy)."""
    cell, found = cell_at(fig, row, start)
    if found != start:
        raise FigureError("No panel starts in column {0:d}.".format(start + 1))
    return cell


# -- Arranging (D42, Q9.10) -----------------------------------------------------------


def place(project, fid, row, col, kept):
    """
    The step that shows a transition in a cell, dropped from Not shown: the one the
    cell showed goes back to Not shown.

    Parameters
    ----------
    kept : dict
        :attr:`Entry.key`.

    Generated by RJC and Claude.
    """
    fig = figure(project, fid)
    _, start = cell_at(fig, row, col)
    text = line_text(kept["ion"], float(kept["rest"]))

    def change(fig):
        cell = _find(fig, row, start)
        cell["show"] = dict(kept)
        cell["label"] = ""

    return _changed(project, fid, change, "Show {0}".format(text))


def move(project, fid, source, target, copy_it=False):
    """
    The step of a drag between two cells (D42, Q9.10): the two swap what they show
    (with their labels, titles and ticks), or, with the copy key held, the target
    shows the source's transition too.

    Parameters
    ----------
    source, target : tuple
        ``(row, column)`` of each cell.

    Generated by RJC and Claude.
    """
    fig = figure(project, fid)
    one, one_start = cell_at(fig, *source)
    two, two_start = cell_at(fig, *target)
    if (source[0], one_start) == (target[0], two_start):
        raise FigureError("A panel cannot be dragged onto itself.")
    if not one["show"]:
        raise FigureError("That panel is empty.")
    carried = ("show", "label", "title", "ions", "components")

    def change(fig):
        mine = _find(fig, source[0], one_start)
        theirs = _find(fig, target[0], two_start)
        if copy_it:
            for key in carried:
                theirs[key] = copy.deepcopy(mine[key])
        else:
            for key in carried:
                mine[key], theirs[key] = theirs[key], mine[key]

    text = line_text(one["show"]["ion"], float(one["show"]["rest"]))
    return _changed(
        project, fid, change, ("Copy {0}" if copy_it else "Move {0}").format(text)
    )


def remove(project, fid, row, col):
    """The step of a drag off the grid: the cell is emptied, its transition back in
    Not shown (D42)."""
    fig = figure(project, fid)
    cell, start = cell_at(fig, row, col)
    if not cell["show"]:
        raise FigureError("That panel is empty.")
    text = line_text(cell["show"]["ion"], float(cell["show"]["rest"]))

    def change(fig):
        mine = _find(fig, row, start)
        for key in ("show", "label", "title", "ions", "components"):
            mine[key] = copy.deepcopy(CELL_DEFAULTS[key])

    return _changed(project, fid, change, "Take {0} off the grid".format(text))


def shown(fig):
    """The transitions a figure shows, as ``(row, start, kept)``."""
    return [(r, s, c["show"]) for r, s, c in places(fig) if c["show"]]


def not_shown(project, fid, found=None):
    """
    The figure's Not shown tray: the transitions it does not show, in order.

    Returns
    -------
    list of Entry

    Generated by RJC and Claude.
    """
    fig = figure(project, fid)
    showing = [k for _, _, k in shown(fig)]
    found = transitions(project) if found is None else found
    return [e for e in found if not any(same(e.key, k) for k in showing)]


def panel_name(fig, row, start):
    """``"Figure 1, row 2, column 1"``."""
    return "{0}, row {1:d}, column {2:d}".format(fig["name"], row + 1, start + 1)


def elsewhere(project, kept, fid=None, place_=None):
    """
    Where else a transition is shown: every panel of every figure that shows it,
    but the one at ``place_`` (``(row, start)``) of figure ``fid``.

    Returns
    -------
    list of str
        :func:`panel_name` of each.

    Generated by RJC and Claude.
    """
    out = []
    for fig in figures(project):
        for row, start, other in shown(fig):
            if fig["id"] == fid and (row, start) == place_:
                continue
            if same(other, kept):
                out.append(panel_name(fig, row, start))
    return out


def duplicates(project):
    """
    The transitions shown in more than one panel (Q9.10), each with the panels that
    show it.

    Returns
    -------
    list of tuple
        ``(kept, [panel names])``.

    Generated by RJC and Claude.
    """
    out = []
    for fig in figures(project):
        for row, start, kept in shown(fig):
            if any(same(kept, k) for k, _ in out):
                continue
            where = elsewhere(project, kept)
            if len(where) > 1:
                out.append((kept, where))
    return out


def duplicate_text(kept, where):
    """The warning of a transition shown twice (Q9.10)."""
    return "{0} (snip {1}) is shown in {2:d} panels: {3}.".format(
        line_text(kept["ion"], float(kept["rest"])),
        kept["specid"],
        len(where),
        "; ".join(where),
    )


def missing(project, fid, found=None):
    """
    The cells whose snip, system or transition is no longer in the project, with a
    note each; they show nothing until it comes back (undo).

    Returns
    -------
    list of tuple
        ``(row, start, note)``.

    Generated by RJC and Claude.
    """
    found = transitions(project) if found is None else found
    out = []
    for row, start, kept in shown(figure(project, fid)):
        if entry_of(project, kept, found) is None:
            out.append(
                (
                    row,
                    start,
                    "{0} (snip {1}) is no longer in the project, so this panel is"
                    " empty.".format(
                        line_text(kept["ion"], float(kept["rest"])), kept["specid"]
                    ),
                )
            )
    return out


# -- Options --------------------------------------------------------------------------


def _check_range(value, what):
    if value is None:
        return None
    low, high = (float(v) for v in value)
    if not low < high:
        raise FigureError(
            "{0}: the first number must be below the second.".format(what)
        )
    return [low, high]


def set_option(project, fid, key, value):
    """
    The step that changes one of a figure's options (Layout): ``size``,
    ``spacing``, ``vrange``, ``zero``, ``residuals``, ``colours``, ``style``,
    ``titles``, ``signed`` or ``numbered``.

    Generated by RJC and Claude.
    """
    if key not in DEFAULTS or key == "preset":
        raise FigureError("A figure has no option {0}.".format(key))
    if key == "vrange":
        value = _check_range(value, "The velocity range")
    elif key == "size":
        value = [float(v) for v in value]
        if not all(0.5 <= v <= 30.0 for v in value):
            raise FigureError("A figure is 0.5 to 30 inches across and down.")
    elif key == "spacing":
        value = [float(v) for v in value]
        if not all(0.0 <= v <= 2.0 for v in value):
            raise FigureError("The spacing between panels is 0 to 2.")
    elif key == "residuals" and value not in RESIDUALS:
        raise FigureError("Residuals are none, a strip or inside each panel.")
    elif key == "colours" and value not in COLOURS:
        raise FigureError("The colours are colour-blind safe or the published ones.")
    elif key == "titles":
        value = [bool(v) for v in value]
    elif key in ("signed", "numbered"):
        value = bool(value)
    elif key in ("zero", "style"):
        value = str(value or "")

    def change(fig):
        fig[key] = value

    return _changed(project, fid, change, "Change the figure's {0}".format(key))


def _check_cell(key, value):
    """A cell's option as it is kept, or a :class:`FigureError`."""
    if key == "axis":
        if value not in AXES:
            raise FigureError("A panel's x axis is velocity, or a wavelength.")
    elif key == "xrange":
        value = _check_range(value, "The x range")
    elif key == "yrange":
        value = _check_range(value, "The flux range")
    elif key == "yticks":
        if value is not None:
            value = sorted(float(v) for v in value)
    elif key == "corner":
        if value not in CORNERS:
            raise FigureError("A label sits in a corner of its panel.")
    elif key in ("label", "title"):
        value = str(value)
    elif key in ("xtitle", "ytitle"):
        value = bool(value)
    elif key in ("xnumbers", "ynumbers", "yright"):
        value = None if value is None else bool(value)
    elif key in ("ions", "components"):
        value = None if value is None else [str(v) for v in value]
    else:
        raise FigureError("A panel has no option {0}.".format(key))
    return value


def set_cell(project, fid, row, col, key, value, every=False):
    """
    The step that changes one of a cell's options, or, with ``every``, sets it on
    every panel of the figure (Apply to all panels, RJC's response to Q9.8).

    A velocity range applied to all becomes the figure's velocity range, and the
    velocity panels' own ranges are cleared; a wavelength range cannot be, since each
    wavelength panel covers its own lines. A panel whose x axis changes from the
    figure's turns its own x title on (Q9.9), and its own range is cleared.

    Generated by RJC and Claude.
    """
    fig = figure(project, fid)
    cell, start = cell_at(fig, row, col)
    value = _check_cell(key, value)
    if every and key == "xrange":
        if cell["axis"] != VELOCITY:
            raise FigureError(
                "A wavelength range cannot be applied to all panels: each wavelength"
                " panel covers its own lines."
            )

        def change(fig):
            if value is not None:
                fig["vrange"] = value
            for _, _, other in places(fig):
                if other["axis"] == VELOCITY:
                    other["xrange"] = None

        return _changed(project, fid, change, "Apply the velocity range to all panels")
    if every and key not in SHARED:
        raise FigureError("This option is set panel by panel.")

    def change(fig):
        targets = [c for _, _, c in places(fig)] if every else [_find(fig, row, start)]
        for target in targets:
            if key == "axis" and target["axis"] != value:
                target["xrange"] = None
                target["xtitle"] = value != VELOCITY or target["xtitle"]
            target[key] = copy.deepcopy(value)

    return _changed(
        project,
        fid,
        change,
        ("Set {0} on all panels" if every else "Set the panel's {0}").format(key),
    )


# -- What follows the figure or the cell's place (Q9.9) -----------------------------


def numbers(fig, row, start):
    """
    Whether a panel's x and y axes are numbered, and the y numbers' side, as
    ``(x, y, right)``: as the cell sets them, or else as the reference scripts number
    theirs: x on the panels with no panel below them (or one with another x axis),
    y on the first panel of a row and, on its right, on the last (16 of the 21
    scripts), and none between; an empty cell counts as no panel.

    Generated by RJC and Claude.
    """
    cell, start = cell_at(fig, row, start)
    # The first and last panels of a row that show something
    drawn = [s for r, s, c in places(fig) if r == row and c["show"]]
    first = not [s for s in drawn if s < start]
    last = not [s for s in drawn if s > start]
    xnum = cell["xnumbers"]
    if xnum is None:
        xnum = True
        if row + 1 < len(fig["cells"]):
            below = [
                c
                for r, s, c in places(fig)
                if r == row + 1 and s < start + cell["span"] and start < s + c["span"]
            ]
            xnum = not below or any(
                not c["show"]
                or c["axis"] != cell["axis"]
                or c["xrange"] != cell["xrange"]
                for c in below
            )
    right = cell["yright"]
    if right is None:
        right = last and not first
    ynum = cell["ynumbers"]
    if ynum is None:
        ynum = first or last
    return bool(xnum), bool(ynum), bool(right)


def x_range(fig, cell, rest=None, z=0.0):
    """
    A panel's x range: its own, or the figure's velocity range, in Å about the
    transition (rest wavelength ``rest`` at redshift ``z``) for a wavelength axis
    (Q9.8 (i)): observed, or in the rest frame.

    Generated by RJC and Claude.
    """
    if cell["xrange"] is not None:
        return list(cell["xrange"])
    low, high = fig["vrange"]
    if cell["axis"] == VELOCITY or rest is None:
        return [low, high]
    centre = rest * (1.0 + z) if cell["axis"] == OBSERVED else rest
    return [centre * (1.0 + low / C.C_KMS), centre * (1.0 + high / C.C_KMS)]


# -- Saved presets (S22) --------------------------------------------------------------


def presets_folder(home):
    """The folder of the saved presets."""
    return os.path.join(home, PRESETS_FOLDER)


def saved_presets(home):
    """The names of the presets the user has saved, in order."""
    folder = presets_folder(home)
    if not os.path.isdir(folder):
        return []
    return sorted(f[: -len(".json")] for f in os.listdir(folder) if f.endswith(".json"))


def save_preset(project, fid, name, home, builtin=()):
    """
    Save a figure's layout as a preset of the user's own (S22): its options and
    cells, each cell's transition kept by ion and wavelength (and whether its system
    is the primary one), so that another project can use it.

    Returns
    -------
    str
        The file written.

    Generated by RJC and Claude.
    """
    name = " ".join(name.split())
    if not name or not _NAME.match(name):
        raise FigureError(
            "A preset's name may hold only letters, digits, spaces, hyphens,"
            " underscores and dots."
        )
    if name.lower() in [b.lower() for b in builtin]:
        raise FigureError("{0} is one of the dashboard's own presets.".format(name))
    fig = copy.deepcopy(figure(project, fid))
    primary = {s.id for s in project.systems if s.primary}
    for row in fig["cells"]:
        for cell in row:
            kept = cell["show"]
            if kept:
                cell["show"] = {
                    "ion": kept["ion"],
                    "rest": kept["rest"],
                    "primary": kept["system"] in primary,
                }
    data = {k: fig[k] for k in DEFAULTS if k not in ("zero", "preset")}
    data["cells"] = fig["cells"]
    data["preset"] = name
    folder = presets_folder(home)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, name + ".json")
    with open(path, "w") as handle:
        json.dump(data, handle, indent=1)
    return path


def load_preset(project, name, home):
    """
    A saved preset as a layout for :func:`new_figure` or :func:`refill`: each cell's
    transition is the project's first with its ion and wavelength (in a system of
    the same kind, primary or not, where there is one); a cell whose transition the
    project does not have is left empty.

    Returns
    -------
    dict

    Generated by RJC and Claude.
    """
    path = os.path.join(presets_folder(home), name + ".json")
    try:
        with open(path) as handle:
            data = json.load(handle)
    except (OSError, ValueError) as err:
        raise FigureError("The preset {0} cannot be read: {1}".format(name, err))
    found = transitions(project)
    primary = {s.id for s in project.systems if s.primary}
    used = []
    for row in data.get("cells", []):
        for cell in row:
            for key, value in CELL_DEFAULTS.items():
                cell.setdefault(key, copy.deepcopy(value))
            want = cell["show"]
            cell["show"] = None
            if not want:
                continue
            matches = [
                e
                for e in found
                if e.ion == want.get("ion")
                and abs(e.rest - float(want.get("rest", 0.0))) <= 0.01
                and not any(same(e.key, u) for u in used)
            ]
            matches.sort(key=lambda e: (e.system in primary) != want.get("primary"))
            if matches:
                cell["show"] = matches[0].key
                used.append(matches[0].key)
    return data


def refill(project, fid, layout, description):
    """
    The step that gives a figure a layout (a preset, D28): its options and cells;
    its name stays, and its velocity zero unless the layout chooses one.

    Generated by RJC and Claude.
    """

    def change(fig):
        for key in DEFAULTS:
            # The velocity zero stays, unless the preset chooses one (blends)
            if key in layout and (key != "zero" or layout[key]):
                fig[key] = copy.deepcopy(layout[key])
        if layout.get("cells"):
            fig["cells"] = copy.deepcopy(layout["cells"])
            fig["rows"] = len(fig["cells"])
            fig["columns"] = sum(c["span"] for c in fig["cells"][0])

    return _changed(project, fid, change, description)


