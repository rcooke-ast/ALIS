# -- The preferences ---------------------------------------------------------------


class Preferences:
    """
    The user's preferences: the shipped defaults, overridden by ``dashboard.json``.

    Parameters
    ----------
    folder : str, optional
        The folder of the dashboard's files; by default :func:`home`.

    Attributes
    ----------
    folder : str
    values : dict
        Every preference by key, as used.
    messages : list of str
        What was wrong with the file when it was read: bad values and unknown keys.

    Generated by RJC and Claude.
    """

    def __init__(self, folder=None):
        self.folder = folder or home()
        self.values = {spec.key: _copy(spec.default) for spec in SPECS}
        self.messages = []

    @property
    def path(self):
        """The user's file, ``dashboard.json``."""
        return os.path.join(self.folder, PREFERENCES)

    @classmethod
    def load(cls, folder=None):
        """
        The defaults, overridden by the user's file when there is one.

        A value the preference cannot take falls back to the default, and an unknown
        key is ignored; each gives a message (in :attr:`messages`, and as an ALIS
        warning).

        Generated by RJC and Claude.
        """
        prefs = cls(folder)
        if not os.path.isfile(prefs.path):
            return prefs
        try:
            with open(prefs.path, encoding="utf-8") as fil:
                data = json.load(fil)
            if not isinstance(data, dict):
                raise ValueError("it does not hold sections of preferences")
        except (OSError, ValueError) as err:
            prefs._note(
                "The preferences in {0} cannot be read ({1}); the defaults are"
                " used.".format(prefs.path, err)
            )
            return prefs
        for section, entries in data.items():
            if not isinstance(entries, dict):
                prefs._note(
                    "Unknown preference '{0}' in {1} is ignored.".format(
                        section, prefs.path
                    )
                )
                continue
            for name, value in entries.items():
                key = "{0}.{1}".format(section, name)
                spec = SPEC.get(key)
                if spec is None:
                    prefs._note(
                        "Unknown preference '{0}' in {1} is ignored.".format(
                            key, prefs.path
                        )
                    )
                    continue
                try:
                    prefs.values[key] = spec.check(value)
                except PreferenceError as err:
                    prefs._note(
                        "The preference '{0}' in {1}: {2}; the default, {3}, is"
                        " used.".format(key, prefs.path, err, _show(spec.default))
                    )
        return prefs

    def _note(self, message):
        """Keep a message about the file, and give it as a warning."""
        self.messages.append(message)
        msgs.warn(message)

    def __getitem__(self, key):
        return self.get(key)

    def get(self, key):
        """
        A preference's value.

        Generated by RJC and Claude.
        """
        if key not in SPEC:
            raise KeyError("There is no preference '{0}'".format(key))
        return _copy(self.values[key])

    def set(self, key, value):
        """
        Change a preference, checked as when it is read.

        Raises
        ------
        PreferenceError

        Generated by RJC and Claude.
        """
        if key not in SPEC:
            raise KeyError("There is no preference '{0}'".format(key))
        self.values[key] = SPEC[key].check(value)

    def reset(self, key=None):
        """Put one preference, or all of them, back to the default."""
        for spec in SPECS if key is None else [SPEC[key]]:
            self.values[spec.key] = _copy(spec.default)

    def changed(self):
        """
        The preferences that differ from the defaults, in sections, as the file
        holds them.

        Generated by RJC and Claude.
        """
        out = {}
        for spec in SPECS:
            value = self.values[spec.key]
            if spec.kind is list:
                same = _copy(value) == _copy(spec.default)
                value = [list(v) for v in value]
            else:
                same = value == spec.default
            if not same:
                out.setdefault(spec.section, {})[spec.name] = value
        return out

    def save(self):
        """
        Write what differs from the defaults to ``dashboard.json``.

        Generated by RJC and Claude.
        """
        write_json(self.path, self.changed())

    def settings(self):
        """The settings of a new project's model, as ``(category, key, value)``."""
        return _copy(self.values["new_project.settings"])


def _copy(value):
    """A copy of a value; a list of settings is held as ``(category, key, value)``."""
    return [tuple(v) for v in value] if isinstance(value, (list, tuple)) else value


def _show(value):
    """A default, as the messages give it."""
    if isinstance(value, list):
        return "the shipped settings"
    return "{0:g}".format(value)


# -- Recent projects ---------------------------------------------------------------


class Recent:
    """
    The recent projects, newest first, in ``recent.json``.

    The dashboard writes the list; the user does not edit it, so it is kept apart
    from the preferences (Q3.3). It holds at most ``length`` projects.

    Parameters
    ----------
    folder : str, optional
        The folder of the dashboard's files; by default :func:`home`.
    length : int
        The most projects kept (the ``recent.length`` preference).

    Generated by RJC and Claude.
    """

    def __init__(self, folder=None, length=10):
        self.folder = folder or home()
        self.length = length
        self.entries = []
        self._read()

    @property
    def path(self):
        """The file, ``recent.json``."""
        return os.path.join(self.folder, RECENT)

    def _read(self):
        """Read the list, ignoring a file that cannot be read."""
        try:
            with open(self.path, encoding="utf-8") as fil:
                data = json.load(fil)
            self.entries = [
                e
                for e in data.get("projects", [])
                if isinstance(e, dict) and isinstance(e.get("path"), str)
            ][: self.length]
        except (OSError, ValueError, AttributeError):
            self.entries = []

    def paths(self):
        """
        The recent projects' paths, newest first.

        Generated by RJC and Claude.
        """
        return [e["path"] for e in self.entries]

    def add(self, path):
        """
        Put a project at the top of the list, and write the list.

        Generated by RJC and Claude.
        """
        path = os.path.abspath(path)
        stamp = datetime.datetime.now().astimezone().isoformat(timespec="seconds")
        self.entries = [e for e in self.entries if e["path"] != path]
        self.entries.insert(0, {"path": path, "opened": stamp})
        del self.entries[self.length :]
        self.save()

    def remove(self, path):
        """Take a project off the list (one that no longer exists), and write it."""
        path = os.path.abspath(path)
        self.entries = [e for e in self.entries if e["path"] != path]
        self.save()

    def save(self):
        """Write the list."""
        write_json(self.path, {"projects": self.entries})


