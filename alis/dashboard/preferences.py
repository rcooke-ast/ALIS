"""The user's preferences, and the other files the dashboard keeps for itself.

Dashboard Stage 3.2 (RJC, Q2.2; Q3.3). The dashboard keeps its own files in one
folder, ``~/.alis/``, or the folder that ``$ALIS_HOME`` names:

- ``dashboard.json``: the user's preferences. ALIS ships the defaults
  (:data:`SPECS`); the file holds only what the user has changed, and overrides them.
  A bad value falls back to the default, and an unknown key is ignored, each with a
  message;
- ``recent.json``: the recent projects, which the dashboard writes and the user does
  not, so they are kept apart from the preferences (:class:`Recent`);
- ``recovery/``: the recovery copies of autosave (:mod:`~alis.dashboard.session`).

The preferences are JSON, in sections, so that they need only the standard library
and can be edited by hand::

    {"components": {"columns": 2}, "autosave": {"interval": 120}}

Generated by RJC and Claude.
"""

