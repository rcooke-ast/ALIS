class PreferenceError(ValueError):
    """A value that a preference cannot take."""


def home():
    """
    The folder of the dashboard's own files: ``$ALIS_HOME``, or ``~/.alis``.

    Returns
    -------
    str

    Generated by RJC and Claude.
    """
    return os.environ.get(HOME_ENV) or os.path.join(os.path.expanduser("~"), ".alis")


def recovery_dir(folder=None):
    """The folder of the recovery copies (``recovery/`` in :func:`home`)."""
    return os.path.join(folder or home(), RECOVERY)


def write_json(path, data):
    """
    Write JSON to ``path`` atomically: to a temporary file beside it, then renamed.

    Generated by RJC and Claude.
    """
    folder = os.path.dirname(os.path.abspath(path))
    os.makedirs(folder, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=folder, prefix=".", suffix=".json.tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fil:
            json.dump(data, fil, indent=1)
            fil.write("\n")
        os.replace(tmp, path)
    except BaseException:
        if os.path.exists(tmp):
            os.remove(tmp)
        raise


