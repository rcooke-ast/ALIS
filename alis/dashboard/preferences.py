@dataclass(frozen=True)
class Spec:
    """
    One preference: its key, its default, and what values it may take.

    Attributes
    ----------
    key : str
        ``"section.name"``, as the file names it.
    default : object
    kind : type
        ``int``, ``float``, ``str`` (a word, one of ``choices``) or ``list`` (the
        settings of a new model).
    low, high : float or None
        The range of a number.
    title : str
        What the Preferences dialog calls it.
    unit : str
    help : str
        One sentence for the dialog's tooltip.
    choices : tuple
        The words a ``str`` preference takes.

    Generated by RJC and Claude.
    """

    key: str
    default: object
    kind: type
    low: float | None = None
    high: float | None = None
    title: str = ""
    unit: str = ""
    help: str = ""
    choices: tuple = ()

    @property
    def section(self):
        """The section of the file it is written in."""
        return self.key.split(".")[0]

    @property
    def name(self):
        """Its name within the section."""
        return self.key.split(".", 1)[1]

    def check(self, value):
        """
        The value as this preference holds it, or :class:`PreferenceError`.

        Generated by RJC and Claude.
        """
        if self.kind is list:
            return check_settings(value)
        if self.kind is str:
            if not isinstance(value, str) or (
                self.choices and value not in self.choices
            ):
                raise PreferenceError(
                    "{0!r} is not one of {1}".format(value, ", ".join(self.choices))
                )
            return value
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise PreferenceError("{0!r} is not a number".format(value))
        if self.kind is int and float(value) != int(value):
            raise PreferenceError("{0!r} is not a whole number".format(value))
        value = self.kind(value)
        if (self.low is not None and value < self.low) or (
            self.high is not None and value > self.high
        ):
            raise PreferenceError(
                "{0!r} is not between {1:g} and {2:g}".format(
                    value, self.low, self.high
                )
            )
        return value


def check_settings(value):
    """
    The settings of a new model, checked as ALIS reads each one.

    Parameters
    ----------
    value : list
        ``[[category, key, value], ...]``.

    Returns
    -------
    list of tuple

    Raises
    ------
    PreferenceError
        If one is not a setting ALIS knows, or has a value ALIS refuses.

    Generated by RJC and Claude.
    """
    if not isinstance(value, (list, tuple)):
        raise PreferenceError("{0!r} is not a list of settings".format(value))
    out = []
    for entry in value:
        if not isinstance(entry, (list, tuple)) or len(entry) != 3:
            raise PreferenceError(
                '{0!r} is not a setting such as ["run", "ncpus", "4"]'.format(entry)
            )
        cat, key, val = (str(part) for part in entry)
        argflag = ArgFlag()
        if cat not in argflag.keys() or key not in argflag[cat].keys():
            raise PreferenceError("'{0} {1}' is not an ALIS setting".format(cat, key))
        try:
            with M.alis_quietly():
                load.set_params(["{0} {1} {2}".format(cat, key, val)], argflag)
        except M.AlisStop:
            raise PreferenceError(
                "'{0}' is not a value of '{1} {2}'".format(val, cat, key)
            ) from None
        out.append((cat, key, val))
    return out


