"""Set LSFSpline knots…: the dialog that builds an ``lsfspline``'s starting values.

Dashboard Stage 12, Task 12.10 (point 7, Prompt 3; Q12.8, Q12.9, Q12.11). Offered by
the Snip box (a snip's own resolution) and the Data tab (a dataset's). It draws, with
pyqtgraph (D2):

- the knots, as squares, joined by a thin faint black line in order of velocity;
- the kernel as ALIS makes it (:func:`alis.dashboard.lsfknots.kernel`), a red line
  of normal weight, and its FWHM, marked at half its peak with its value.

A knot is dragged (the edges sideways only, the centre not at all), stopping at the
rules (heights within [0, 1], at least one sub-pixel from its neighbours); a
double-click adds a knot; Delete knot (also the right-click menu and the Delete key)
removes the selected inner knot. Delta Function, after a question, puts five knots
in place of every knot: a very narrow profile, whose edges follow the FWHM until a
knot is moved, added or removed. Apply makes the step; Cancel changes nothing.

Generated by RJC and Claude.
"""

import numpy as np
import pyqtgraph as pg
from qtpy import QtCore, QtWidgets

from alis.dashboard import lsfknots as LK
from alis.dashboard.qt import plots as PL
from alis.dashboard.qt import style as STY
from alis.dashboard.qt import widgets as W

TITLE = "Set LSFSpline knots"
DELTA = "Delta Function"
DELTA_QUESTION = "All the knots will be cleared, and replaced by a delta function."
DELETE = "Delete knot"
SMOOTHING = "Smoothing, FWHM (km/s)"
# How near a knot a press must be to take it, in pixels
GRAB = 12.0


class KnotsBox(pg.ViewBox):
    """
    The plot's view box: a left drag moves the knot it starts on, a double-click
    adds one, a right-click offers Delete knot.

    Generated by RJC and Claude.
    """

    dragged = QtCore.Signal(float, float, float, float, str)
    doubleClicked = QtCore.Signal(float, float)
    rightClicked = QtCore.Signal(float, float, object)

    def __init__(self):
        super().__init__()
        self.setMouseEnabled(x=False, y=False)
        self.setMenuEnabled(False)

    def mouseDragEvent(self, ev, axis=None):
        if ev.button() != QtCore.Qt.MouseButton.LeftButton:
            ev.ignore()
            return
        ev.accept()
        start = self.mapSceneToView(ev.buttonDownScenePos())
        now = self.mapSceneToView(ev.scenePos())
        state = "start" if ev.isStart() else ("finish" if ev.isFinish() else "move")
        self.dragged.emit(start.x(), start.y(), now.x(), now.y(), state)

    def mouseClickEvent(self, ev):
        pos = self.mapSceneToView(ev.scenePos())
        if ev.button() == QtCore.Qt.MouseButton.RightButton:
            ev.accept()
            self.rightClicked.emit(pos.x(), pos.y(), ev.screenPos())
            return
        if ev.button() == QtCore.Qt.MouseButton.LeftButton and ev.double():
            ev.accept()
            self.doubleClicked.emit(pos.x(), pos.y())
            return
        super().mouseClickEvent(ev)


class KnotsDialog(QtWidgets.QDialog):
    """
    Set LSFSpline knots… for a snip's own resolution or a dataset's.

    Parameters
    ----------
    project : Project
    target : Snip or Row
    knots : lsfknots.Knots
        The knots it starts from (:func:`lsfknots.knots_of`).
    ask : callable
        The window's question (``ask(kind, title, text, choices)``), for Delta
        Function's.

    Attributes
    ----------
    knots : lsfknots.Knots
        As the dialog has them now.
    step : float
        spix: one sub-pixel at ``nsubpixel_min``, the closest two knots may be.

    Generated by RJC and Claude.
    """

    def __init__(self, project, target, knots, ask, parent=None):
        super().__init__(parent)
        self.setWindowTitle(TITLE)
        self.resize(760, 520)
        self.project, self.target, self.ask = project, target, ask
        self.knots = knots.copy()
        self.step = LK.spix(project, target)
        snips = [s for s in getattr(target, "snips", [target]) if s.pixels is not None]
        self.snip = snips[0]
        self.wave = float(np.median(self.snip.pixels.wave))
        self.pixel = max(LK.pixel_kms(s) or 0.0 for s in snips)
        self.asked = LK.model_subpixels(project, self.snip)
        self.selected = None
        self._drag = None
        layout = QtWidgets.QVBoxLayout(self)
        self.box = KnotsBox()
        self.plot = pg.PlotWidget(viewBox=self.box)
        self.plot.setBackground(STY.GREY["base"])
        item = self.plot.getPlotItem()
        item.hideButtons()
        item.setLabel("bottom", "Velocity (km/s)")
        item.setLabel("left", "Kernel")
        self.line = pg.PlotDataItem(pen=pg.mkPen((0, 0, 0, 90), width=1))
        self.curve = pg.PlotDataItem(pen=pg.mkPen("#d62728", width=1.8))
        self.half = pg.PlotDataItem(
            pen=pg.mkPen("#d62728", width=1, style=QtCore.Qt.PenStyle.DashLine)
        )
        self.dots = pg.ScatterPlotItem(symbol="s", size=10)
        self.fwhm_text = pg.TextItem("", color="#d62728", anchor=(0.5, 1.2))
        for one in (self.line, self.curve, self.half, self.dots, self.fwhm_text):
            self.plot.addItem(one)
        self.box.setYRange(-0.04, 1.08, padding=0)
        self.box.dragged.connect(self._dragged)
        self.box.doubleClicked.connect(lambda x, y: self.add_knot(x, y))
        self.box.rightClicked.connect(self._menu)
        layout.addWidget(self.plot, 1)
        row = QtWidgets.QHBoxLayout()
        row.addWidget(QtWidgets.QLabel(SMOOTHING))
        self.smoothing = QtWidgets.QDoubleSpinBox()
        self.smoothing.setObjectName("knots_smoothing")
        self.smoothing.setDecimals(3)
        self.smoothing.setRange(0.0, 1000.0)
        self.smoothing.setSingleStep(0.1)
        self.smoothing.setValue(self.knots.smoothing)
        self.smoothing.setToolTip(
            "The FWHM of the Gaussian that smooths the knots' lines, in km/s"
        )
        self.smoothing.valueChanged.connect(self.set_smoothing)
        row.addWidget(self.smoothing)
        self.delta = QtWidgets.QPushButton(DELTA)
        self.delta.setObjectName("knots_delta")
        self.delta.setToolTip(
            "A very narrow profile in place of the knots: smoothed, a Gaussian of the"
            " FWHM; its knots can then be moved as any other"
        )
        self.delta.clicked.connect(self.delta_function)
        row.addWidget(self.delta)
        self.delete = QtWidgets.QPushButton(DELETE)
        self.delete.setObjectName("knots_delete")
        self.delete.setToolTip("Remove the selected knot (also the Delete key)")
        self.delete.clicked.connect(lambda: self.delete_knot(self.selected))
        row.addWidget(self.delete)
        row.addStretch(1)
        layout.addLayout(row)
        self.note = W.muted("")
        self.note.setObjectName("knots_note")
        self.note.setWordWrap(True)
        layout.addWidget(self.note)
        self.buttons = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Apply
            | QtWidgets.QDialogButtonBox.StandardButton.Cancel
        )
        self.apply_button = self.buttons.button(
            QtWidgets.QDialogButtonBox.StandardButton.Apply
        )
        self.apply_button.clicked.connect(self.accept)
        self.buttons.rejected.connect(self.reject)
        layout.addWidget(self.buttons)
        self.redraw()
        self._home()

    # -- drawing ----------------------------------------------------------------------

    def _home(self):
        reach = LK.half_width(self.knots)
        self.box.setXRange(-1.1 * reach, 1.1 * reach, padding=0)

    def broken(self):
        """What the knots break of the rules (:func:`lsfknots.check_knots`)."""
        return LK.check_knots(self.knots, self.step)

    def redraw(self):
        """The knots, their line, the kernel and its FWHM, and what breaks a rule."""
        v, h = self.knots.velocities, self.knots.heights
        self.line.setData(v, h)
        bad = self._too_close()
        brushes = []
        for n in range(len(v)):
            if n in bad:
                colour = "#d62728"
            elif n == self.selected:
                colour = PL.COLOURS["tick_selected"]
            elif self.knots.fixed(n):
                colour = "#555555"
            else:
                colour = "#1f77b4"
            brushes.append(pg.mkBrush(colour))
        self.dots.setData(v, h, brush=brushes, pen=pg.mkPen("#222222"))
        broken = self.broken()
        self.width = None
        if not broken:
            nsub = LK.subpixels(
                self.project, self.snip, self.knots.smoothing, self.asked
            )
            vel, ker = LK.kernel(self.knots, self.wave, self.pixel, nsub)
            self.curve.setData(vel, ker)
            self.width = LK.fwhm(vel, ker)
        else:
            self.curve.setData([], [])
        if self.width is not None:
            self.half.setData([-0.5 * self.width, 0.5 * self.width], [0.5, 0.5])
            self.fwhm_text.setText("FWHM {0:.2f} km/s".format(self.width))
            self.fwhm_text.setPos(0.0, 0.5)
        else:
            self.half.setData([], [])
            self.fwhm_text.setText("")
        self.note.setText(" ".join(broken))
        self.apply_button.setEnabled(not broken)
        self.apply_button.setToolTip(
            " ".join(broken) if broken else "Write these knots as one step"
        )
        inner = self.selected is not None and not self.knots.fixed(self.selected)
        self.delete.setEnabled(inner)

    def _too_close(self):
        v = self.knots.velocities
        out = set()
        for n in range(len(v) - 1):
            if v[n + 1] - v[n] < self.step * (1.0 - 1.0e-9):
                out |= {n, n + 1}
        return out

    @property
    def fwhm_shown(self):
        """The FWHM marked on the plot, in km/s, or None."""
        return self.width

    # -- the knots ----------------------------------------------------------------------

    def nearest(self, x, y):
        """The knot nearest a point of the plot, within :data:`GRAB` pixels, or None."""
        if not self.knots.velocities:
            return None
        here = self.box.mapViewToScene(QtCore.QPointF(x, y))
        best, near = None, GRAB
        for n, (v, h) in enumerate(self.knots.points):
            at = self.box.mapViewToScene(QtCore.QPointF(v, h))
            dist = float(np.hypot(at.x() - here.x(), at.y() - here.y()))
            if dist <= near:
                best, near = n, dist
        return best

    def select(self, index):
        self.selected = index
        self.redraw()

    def move_knot(self, index, velocity, height):
        """
        Move a knot as a drag does: the centre not at all, an edge sideways only,
        every knot at least one sub-pixel from its neighbours and its height within
        [0, 1]. A knot moved ends Delta Function's following of the FWHM.

        Returns
        -------
        tuple
            Where the knot is now.

        Generated by RJC and Claude.
        """
        k = self.knots
        last = len(k.velocities) - 1
        if index is None or index == k.centre():
            return k.points[index] if index is not None else None
        v = float(velocity)
        if index > 0:
            v = max(v, k.velocities[index - 1] + self.step)
        if index < last:
            v = min(v, k.velocities[index + 1] - self.step)
        k.velocities[index] = v
        if index not in (0, last):
            k.heights[index] = float(min(max(height, 0.0), 1.0))
        self.redraw()
        return k.points[index]

    def add_knot(self, velocity, height):
        """A knot added at a point (a double-click), between the edges, its height
        within [0, 1]; none within one sub-pixel of another (the status says why)."""
        k = self.knots
        v = float(velocity)
        if not k.velocities[0] < v < k.velocities[-1]:
            self.note.setText("A knot is added between the edges.")
            return None
        if any(abs(v - other) < self.step for other in k.velocities):
            self.note.setText(
                "No knot is added within one sub-pixel ({0:.3f} km/s) of another.".format(
                    self.step
                )
            )
            return None
        at = int(np.searchsorted(k.velocities, v))
        k.velocities.insert(at, v)
        k.heights.insert(at, float(min(max(height, 0.0), 1.0)))
        self.selected = at
        self.redraw()
        return at

    def delete_knot(self, index):
        """Remove an inner knot (not an edge, nor the centre)."""
        k = self.knots
        if index is None or k.fixed(index):
            return False
        del k.velocities[index]
        del k.heights[index]
        self.selected = None
        self.redraw()
        return True

    def set_smoothing(self, value):
        """A new smoothing: the delta function's edges follow it (Q12.9 (ii))."""
        self.knots = LK.with_smoothing(self.knots, float(value), self.step)
        if self.smoothing.value() != float(value):
            self.smoothing.blockSignals(True)
            self.smoothing.setValue(float(value))
            self.smoothing.blockSignals(False)
        self.redraw()

    def delta_function(self):
        """Delta Function: after the question, five knots in place of every knot."""
        choice = self.ask(
            "delta_function", DELTA, DELTA_QUESTION, ["Confirm", "Cancel"]
        )
        if choice != "Confirm":
            return False
        self.knots = LK.delta_knots(self.smoothing.value(), self.step)
        self.selected = None
        self.redraw()
        self._home()
        return True

    # -- the mouse and the keys --------------------------------------------------------

    def _dragged(self, x0, y0, x, y, state):
        if state == "start":
            self._drag = self.nearest(x0, y0)
            if self._drag is not None:
                self.select(self._drag)
            return
        if self._drag is None:
            return
        self.move_knot(self._drag, x, y)
        if state == "finish":
            self._drag = None

    def _menu(self, x, y, screen):
        index = self.nearest(x, y)
        if index is None:
            return
        self.select(index)
        menu = QtWidgets.QMenu(self)
        action = menu.addAction(DELETE)
        action.setEnabled(not self.knots.fixed(index))
        if menu.exec(screen.toPoint() if hasattr(screen, "toPoint") else screen):
            self.delete_knot(index)

    def keyPressEvent(self, event):
        if event.key() in (QtCore.Qt.Key.Key_Delete, QtCore.Qt.Key.Key_Backspace):
            self.delete_knot(self.selected)
            return
        super().keyPressEvent(event)

    # -- the result ----------------------------------------------------------------------

    def step_of(self):
        """The step Apply makes (:func:`lsfknots.knots_step`)."""
        return LK.knots_step(self.project, self.target, self.knots, self.step)


