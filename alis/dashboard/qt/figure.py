    # -- the project ------------------------------------------------------------------

    def shown(self, session):
        """
        The run the figures draw, and why the tab is greyed (``""`` when it is not).

        Returns
        -------
        tuple
            ``(View or None, str)``.

        Generated by RJC and Claude.
        """
        fit_tab = getattr(self.main, "fit_tab", None)
        if session is None or fit_tab is None:
            return None, FG.NO_FIT
        fit_tab.use(session)
        view, _ = fit_tab.committed_view()
        return view, FG.unavailable(session.project, view)

    def current_id(self):
        """The id of the figure shown, or None."""
        found = FG.figures(self.session.project) if self.session else []
        if not found:
            return None
        fid = self.session.view.get(SHOWN_FIGURE)
        ids = [f["id"] for f in found]
        return fid if fid in ids else ids[0]

    def current(self):
        """The figure shown (a dict), or None."""
        fid = self.current_id()
        return None if fid is None else FG.figure(self.session.project, fid)

    def entry_of(self, cell):
        return FG.entry_of(self.session.project, cell["show"], self.found)

    def ions_of(self, entry):
        """The ions a panel can tick, as ``(ion, name)``."""
        if entry is None:
            return []
        system = self.session.project.system(entry.system)
        ions = FS._ticked_ions(self.session.project, system)
        return [(ion, P.ion_name(ion)) for ion in ions]

    def components_of(self, entry):
        if entry is None:
            return []
        system = self.session.project.system(entry.system)
        return [c.id for c in system.components if c.main is not None]

    def home(self):
        """The dashboard's folder, where saved presets are kept (S22)."""
        prefs = getattr(self.main, "prefs", None)
        return getattr(prefs, "folder", None) or tempfile.gettempdir()

    # -- refresh --------------------------------------------------------------------

    def refresh(self, session):
        """Draw the panes from the project; the preview stays as it was drawn."""
        self.session = session
        self.view, self.reason = self.shown(session)
        if self.reason:
            self.run_label.setText(self.reason)
        else:
            text = "The figures draw the best fit of {0}, the run the Fit tab shows."
            self.run_label.setText(text.format(self.view.name))
        if session is None or self.reason:
            return
        self._building = True
        try:
            self.found = FG.transitions(session.project)
            self._fill_layout()
            self._fill_panels()
        finally:
            self._building = False
        self._mark_preview()

    def _fill_layout(self):
        project = self.session.project
        found = FG.figures(project)
        fig = self.current()
        self.figure_menu.clear()
        for item in found:
            self.figure_menu.addItem(item["name"], item["id"])
        if fig is not None:
            self.figure_menu.setCurrentIndex([f["id"] for f in found].index(fig["id"]))
        has = fig is not None
        self.empty_note.setVisible(not has)
        for widget in (
            self.figure_menu,
            self.rename_button,
            self.delete_button,
            self.controls,
            self.draw_button,
            self.export_button,
        ):
            widget.setEnabled(has)
        self.preset_menu.clear()
        for name in FP.PRESETS:
            self.preset_menu.addItem(name, name)
            self.preset_menu.setItemData(
                self.preset_menu.count() - 1,
                FP.DESCRIPTIONS[name],
                QtCore.Qt.ItemDataRole.ToolTipRole,
            )
        for name in FG.saved_presets(self.home()):
            self.preset_menu.addItem(name + " (yours)", name)
        self.system_menu.clear()
        for system in project.systems:
            if not system.primary:
                self.system_menu.addItem(system.name, system.id)
        self.system_menu.setVisible(self.system_menu.count() > 0)
        self.zero_menu.clear()
        gate = BL.Gate(project)
        default = X.default_component(project, self.view, gate)
        self.zero_menu.addItem("Default ({0})".format(default or "none"), "")
        for cid, label in X.reference_components(project, gate):
            self.zero_menu.addItem(label, cid)
        if not has:
            return
        if fig["preset"]:
            at = self.preset_menu.findData(fig["preset"])
            if at >= 0:
                self.preset_menu.setCurrentIndex(at)
        self.columns.setValue(fig["columns"])
        self.rows.setValue(fig["rows"])
        self.size_w.setValue(fig["size"][0])
        self.size_h.setValue(fig["size"][1])
        self.space_x.setValue(fig["spacing"][0])
        self.space_y.setValue(fig["spacing"][1])
        self.v_low.setValue(fig["vrange"][0])
        self.v_high.setValue(fig["vrange"][1])
        at = self.zero_menu.findData(fig["zero"])
        self.zero_menu.setCurrentIndex(max(at, 0))
        self.residuals.setCurrentIndex(FG.RESIDUALS.index(fig["residuals"]))
        self.colours.setCurrentIndex(FG.COLOURS.index(fig["colours"]))
        self.style_menu.setCurrentIndex(1 if fig["style"] else 0)
        self.style_menu.setToolTip(fig["style"] or "The style shipped with ALIS")
        self.shared_x.setChecked(fig["titles"][0])
        self.shared_y.setChecked(fig["titles"][1])
        self.signed.setChecked(fig["signed"])
        self.numbered.setChecked(fig["numbered"])

    def _fill_panels(self):
        project = self.session.project
        while self.grid_layout.count():
            item = self.grid_layout.takeAt(0)
            widget = item.widget()
            if widget is not None:
                # Gone at once: a cell taken from the layout still sits on its
                # parent until it is deleted
                widget.hide()
                widget.setParent(None)
                widget.deleteLater()
        self.cells = {}
        self.tray.clear()
        fig = self.current()
        if fig is None:
            return
        fid = fig["id"]
        gone = {(r, s): note for r, s, note in FG.missing(project, fid, self.found)}
        for row, start, cell in FG.places(fig):
            text, mark = "", ""
            if cell["show"]:
                entry = self.entry_of(cell)
                if entry is None:
                    mark = gone.get((row, start), "")
                else:
                    text = entry.name
                    if cell["span"] > 1:
                        text += " · {0} columns".format(cell["span"])
                    if cell["axis"] != FG.VELOCITY:
                        text += " · " + FG.AXIS_NAMES[cell["axis"]].lower()
                    others = FG.elsewhere(project, cell["show"], fid, (row, start))
                    if others:
                        mark = "Also shown in " + "; ".join(others) + "."
            widget = CellWidget(self, row, start, text, mark)
            self.grid_layout.addWidget(widget, row, start, 1, cell["span"])
            self.cells[(row, start)] = widget
        for col in range(fig["columns"]):
            self.grid_layout.setColumnStretch(col, 1)
        # The cells at the top, at their own height
        self.grid_layout.setRowStretch(len(fig["cells"]), 1)
        tray = FG.not_shown(project, fid, self.found)
        names = [e.name for e in tray]
        for entry in tray:
            others = FG.elsewhere(project, entry.key)
            text = entry.name
            if names.count(entry.name) > 1:
                # Two snips of one dataset that hold the same line
                text += " · snip " + entry.specid
            if others:
                figures = sorted({o.split(",")[0] for o in others})
                text += " · " + ", ".join(figures)
            item = QtWidgets.QListWidgetItem(text)
            item.setData(QtCore.Qt.ItemDataRole.UserRole, entry.key)
            if others:
                item.setToolTip("Also shown in " + "; ".join(others) + ".")
            self.tray.addItem(item)

