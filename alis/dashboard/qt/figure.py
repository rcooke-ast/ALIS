    # -- arranging (D42, Q9.10) ----------------------------------------------------------

    def dropped(self, row, start, data, copy_it=False):
        """A drop on a cell: a transition from the tray, or another cell."""
        if data.hasFormat(ENTRY_MIME):
            key = json.loads(bytes(data.data(ENTRY_MIME)).decode())
            self.place(key, row, start)
        elif data.hasFormat(CELL_MIME):
            self.move((*_cell_of(data),), (row, start), copy_it)

    def place(self, key, row, start):
        """A transition dropped on a cell; a transition shown elsewhere is warned."""
        project = self.session.project
        fid = self.current_id()
        others = FG.elsewhere(project, key)
        self._act("place", lambda: self._do(FG.place(project, fid, row, start, key)))
        if others:
            self._warn_twice(key, others)

    def move(self, source, target, copy_it=False):
        """A drag between cells: a swap, or with the copy key a copy (warned)."""
        project = self.session.project
        fid = self.current_id()
        cell, _ = FG.cell_at(self.current(), *source)
        key = cell["show"]
        self._act(
            "move", lambda: self._do(FG.move(project, fid, source, target, copy_it))
        )
        if copy_it and key:
            self._warn_twice(key, FG.elsewhere(project, key, fid, target))

    def take_off(self, row, start):
        """A panel dragged onto the tray: off the grid."""
        project = self.session.project
        fid = self.current_id()
        self._act("remove", lambda: self._do(FG.remove(project, fid, row, start)))

    def _warn_twice(self, key, others):
        """A transition shown in another panel too (Q9.10): said in the status bar,
        and marked on the cells."""
        text = "{0} is also shown in {1}.".format(
            FG.line_text(key["ion"], float(key["rest"])), "; ".join(others)
        )
        if self.main is not None:
            self.main.statusBar().showMessage(text, 10000)

    # -- the preview (S22, Q9.3) --------------------------------------------------------

    def _state(self):
        """What a preview was drawn from: the figure, and the run."""
        fig = self.current()
        if fig is None or self.view is None:
            return None
        return json.dumps(fig, sort_keys=True) + "|" + self.view.name

    def _mark_preview(self):
        if self.process is not None:
            return
        if self.drawn is None:
            self.preview_note.setText(BEFORE)
        elif self._state() != self.drawn_state:
            self.preview_note.setText(STALE)
        else:
            self.preview_note.setText(
                "Preview · {0:g} × {1:g} in".format(*self.current()["size"])
            )

    @property
    def stale(self):
        """Whether the preview shown was drawn from another figure or run."""
        return self.drawn is not None and self._state() != self.drawn_state

    def folder(self):
        """The preview's own folder, for the session."""
        if self._folder is None:
            self._folder = tempfile.TemporaryDirectory(prefix="alis_figure_")
        return self._folder.name

    def draw_or_stop(self):
        if self.process is not None:
            self.stop()
        else:
            self.draw()

    def draw(self):
        """
        Draw preview: write the figure's script and what it reads into the preview's
        folder, and run it in a process of its own (S22).

        Generated by RJC and Claude.
        """
        fig = self.current()
        if fig is None:
            return
        project = self.session.project
        name = X.project_name(self.session)
        try:
            out, notes = FS.files(project, self.view, fig["id"], name)
        except FG.FigureError as err:
            self._failed(str(err))
            return
        folder = os.path.join(self.folder(), fig["id"])
        paths = FS.write(folder, out)
        script = next(p for p in paths if p.endswith(".py"))
        png = os.path.join(folder, "preview.png")
        if os.path.exists(png):
            os.remove(png)
        ratio = self.picture.devicePixelRatioF() or 1.0
        width = max(200, self.picture.width()) * ratio
        dpi = FS.preview_dpi(width, fig)
        self.drawn_dpi = dpi
        self.notes.setText(" ".join("Not drawn: " + n for n in notes))
        state = self._state()
        process = QtCore.QProcess(self)
        process.setWorkingDirectory(folder)
        env = QtCore.QProcessEnvironment.systemEnvironment()
        env.insert("MPLBACKEND", "Agg")
        process.setProcessEnvironment(env)
        command = FS.command(script, png, dpi)
        process.finished.connect(
            lambda code, _status: self._drawn(process, code, png, state, ratio)
        )
        self.process = process
        self.draw_button.setText("Stop")
        self.preview_note.setText(DRAWING)
        process.start(command[0], command[1:])

    def stop(self):
        """Stop: the drawing ends, and the last preview stays."""
        process = self.process
        if process is None:
            return
        self.process = None
        process.kill()
        process.waitForFinished(5000)
        self.draw_button.setText("Draw preview")
        self._mark_preview()

    def _drawn(self, process, code, png, state, ratio):
        if process is not self.process:
            return
        self.process = None
        self.draw_button.setText("Draw preview")
        error = bytes(process.readAllStandardError()).decode("utf-8", "replace")
        if code != 0 or not os.path.exists(png):
            self._failed(FS.last_line(error))
            return
        image = QtGui.QPixmap(png)
        image.setDevicePixelRatio(ratio)
        self.drawn = png
        self.drawn_state = state
        self._show_picture(image)
        self._mark_preview()

    def _show_picture(self, image):
        self.picture.setText("")
        size = self.picture.size() * self.picture.devicePixelRatioF()
        if image.width() > size.width() or image.height() > size.height():
            image = image.scaled(
                size,
                QtCore.Qt.AspectRatioMode.KeepAspectRatio,
                QtCore.Qt.TransformationMode.SmoothTransformation,
            )
            image.setDevicePixelRatio(self.picture.devicePixelRatioF())
        self.picture.setPixmap(image)

    def _failed(self, message):
        """A preview that could not be drawn: its message in its place (D86)."""
        self.drawn = None
        self.drawn_state = None
        self.picture.setPixmap(QtGui.QPixmap())
        self.picture.setText(message)
        self.picture.setWordWrap(True)
        self.preview_note.setText("The preview could not be drawn.")

    def wait_for_preview(self, timeout=120000):
        """Wait for a drawing to end (tests)."""
        if self.process is not None:
            self.process.waitForFinished(timeout)
            QtWidgets.QApplication.processEvents()

    # -- Export figure… (Q9.11) ---------------------------------------------------------

    def export_figure(self):
        """Export figure…: the Export dialog with only this figure ticked."""
        if self.main is not None:
            self.main.export(figures=[self.current_id()])


