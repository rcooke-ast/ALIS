class CellWidget(QtWidgets.QFrame):
    """
    A cell of the grid's picture: what it shows, a mark when it needs attention, and
    its options button; a drag source and a drop target.

    Generated by RJC and Claude.
    """

    def __init__(self, tab, row, start, text, mark="", parent=None):
        super().__init__(parent)
        self.tab, self.row, self.start = tab, row, start
        self.setObjectName("figureCell")
        self.setFrameShape(QtWidgets.QFrame.Shape.StyledPanel)
        self.setAcceptDrops(True)
        self.setSizePolicy(
            QtWidgets.QSizePolicy.Policy.Ignored, QtWidgets.QSizePolicy.Policy.Fixed
        )
        self.setFixedHeight(46)
        layout = QtWidgets.QGridLayout(self)
        layout.setContentsMargins(5, 2, 2, 2)
        layout.setHorizontalSpacing(2)
        line, _, rest = text.partition(" · ")
        self.label = W.ElidedLabel(line or "Empty")
        if not text:
            self.label.setObjectName("muted")
        self.label.setToolTip(text)
        self.detail = W.ElidedLabel(rest)
        self.detail.setObjectName("muted")
        self.detail.setToolTip(text)
        layout.addWidget(self.detail, 1, 0)
        self.mark = QtWidgets.QLabel("!" if mark else "")
        self.mark.setObjectName("figureMark")
        self.mark.setToolTip(mark)
        # The line takes the cell's width; a mark, when there is one, beside it
        if mark:
            layout.addWidget(self.label, 0, 0)
            layout.addWidget(self.mark, 0, 1)
        else:
            layout.addWidget(self.label, 0, 0, 1, 2)
        self.options = QtWidgets.QToolButton()
        self.options.setText("⚙")
        self.options.setToolTip("This panel's options")
        self.options.setAutoRaise(True)
        self.options.clicked.connect(lambda: tab.edit_cell(row, start))
        layout.addWidget(self.options, 1, 1)
        layout.setColumnStretch(0, 1)
        for label in (self.label, self.detail):
            font = label.font()
            if font.pointSizeF() > 0:
                font.setPointSizeF(font.pointSizeF() * 0.9)
            elif font.pixelSize() > 0:
                font.setPixelSize(max(8, round(font.pixelSize() * 0.9)))
            label.setFont(font)
            label.setMinimumWidth(1)
            label.setSizePolicy(
                QtWidgets.QSizePolicy.Policy.Ignored,
                QtWidgets.QSizePolicy.Policy.Preferred,
            )
        self._pressed = None
        self.filled = bool(text)
        if self.filled:
            self.setCursor(QtCore.Qt.CursorShape.OpenHandCursor)

    def mousePressEvent(self, event):
        self._pressed = event.position().toPoint()
        super().mousePressEvent(event)

    def mouseMoveEvent(self, event):
        if self._pressed is None or not self.filled:
            return
        if (event.position().toPoint() - self._pressed).manhattanLength() < 8:
            return
        data = QtCore.QMimeData()
        data.setData(CELL_MIME, "{0},{1}".format(self.row, self.start).encode())
        drag = QtGui.QDrag(self)
        drag.setMimeData(data)
        drag.exec(
            QtCore.Qt.DropAction.MoveAction | QtCore.Qt.DropAction.CopyAction,
            QtCore.Qt.DropAction.MoveAction,
        )
        self._pressed = None

    def dragEnterEvent(self, event):
        if event.mimeData().hasFormat(CELL_MIME) or event.mimeData().hasFormat(
            ENTRY_MIME
        ):
            event.acceptProposedAction()

    def dragMoveEvent(self, event):
        self.dragEnterEvent(event)

    def dropEvent(self, event):
        event.acceptProposedAction()
        copy_it = bool(
            event.modifiers()
            & (
                QtCore.Qt.KeyboardModifier.ControlModifier
                | QtCore.Qt.KeyboardModifier.AltModifier
            )
        )
        self.tab.dropped(self.row, self.start, event.mimeData(), copy_it)


class Tray(QtWidgets.QListWidget):
    """
    The Not shown tray: the transitions the figure does not show, dragged onto the
    grid; a panel dragged here is taken off it.

    Generated by RJC and Claude.
    """

    def __init__(self, tab, parent=None):
        super().__init__(parent)
        self.tab = tab
        self.setObjectName("figureTray")
        self.setDragEnabled(True)
        self.setAcceptDrops(True)
        self.setDragDropMode(QtWidgets.QAbstractItemView.DragDropMode.DragDrop)

    def mimeTypes(self):
        return [ENTRY_MIME]

    def mimeData(self, items):
        data = QtCore.QMimeData()
        if items:
            key = items[0].data(QtCore.Qt.ItemDataRole.UserRole)
            data.setData(ENTRY_MIME, json.dumps(key).encode())
        return data

    def dragEnterEvent(self, event):
        if event.mimeData().hasFormat(CELL_MIME):
            event.acceptProposedAction()

    def dragMoveEvent(self, event):
        self.dragEnterEvent(event)

    def dropEvent(self, event):
        if event.mimeData().hasFormat(CELL_MIME):
            event.acceptProposedAction()
            row, start = _cell_of(event.mimeData())
            self.tab.take_off(row, start)


def _cell_of(data):
    row, start = bytes(data.data(CELL_MIME)).decode().split(",")
    return int(row), int(start)


def _range_text(value):
    return "" if value is None else "{0:g} to {1:g}".format(*value)


def _parse_range(text):
    """``"-150 to 150"`` (or two numbers) as a pair, ``""`` as None."""
    text = text.strip()
    if not text:
        return None
    parts = text.replace(",", " ").replace(" to ", " ").split()
    try:
        low, high = (float(p) for p in parts)
    except ValueError:
        raise FG.FigureError("Give a range as two numbers, such as -150 to 150.")
    return [low, high]


def _parse_numbers(text):
    text = text.strip()
    if not text:
        return None
    try:
        return [float(p) for p in text.replace(",", " ").split()]
    except ValueError:
        raise FG.FigureError("Give the tick positions as numbers, such as 0, 0.5, 1.")


class OptionsDialog(QtWidgets.QDialog):
    """
    A panel's options in one place (RJC's response to Q9.8): its label and corner, its
    title, its x axis and range, its flux range and ticks, its numbers and their
    side, its titles, and the ions and components it ticks (Q9.12). Each change is a
    step at once; Apply to all panels sets an option on every panel of the figure.

    Generated by RJC and Claude.
    """

    def __init__(self, tab, row, start, parent=None):
        super().__init__(parent)
        self.tab, self.row, self.start = tab, row, start
        fig = tab.current()
        cell, _ = FG.cell_at(fig, row, start)
        entry = tab.entry_of(cell)
        self.setWindowTitle(
            "Panel options · "
            + (entry.name if entry else FG.panel_name(fig, row, start))
        )
        self.setMinimumWidth(520)
        form = QtWidgets.QGridLayout()
        self.fields, self.everywhere = {}, {}
        line = [0]

        def add(key, title, widget, shared=False):
            form.addWidget(QtWidgets.QLabel(title), line[0], 0)
            form.addWidget(widget, line[0], 1)
            if shared:
                button = QtWidgets.QPushButton("Apply to all panels")
                button.clicked.connect(lambda _=False, k=key: self.apply_all(k))
                form.addWidget(button, line[0], 2)
                self.everywhere[key] = button
            self.fields[key] = widget
            line[0] += 1

        label = QtWidgets.QLineEdit(cell["label"])
        label.setPlaceholderText(FS.label_text(entry.ion, entry.rest) if entry else "")
        label.editingFinished.connect(lambda: self.change("label", label.text()))
        add("label", "Label", label)
        corner = QtWidgets.QComboBox()
        corner.addItems([c.capitalize() for c in FG.CORNERS])
        corner.setCurrentIndex(FG.CORNERS.index(cell["corner"]))
        corner.currentIndexChanged.connect(
            lambda n: self.change("corner", FG.CORNERS[n])
        )
        add("corner", "Label's corner", corner, shared=True)
        title = QtWidgets.QLineEdit(cell["title"])
        title.editingFinished.connect(lambda: self.change("title", title.text()))
        add("title", "Title above", title)
        axis = QtWidgets.QComboBox()
        axis.addItems([FG.AXIS_NAMES[a] for a in FG.AXES])
        axis.setCurrentIndex(FG.AXES.index(cell["axis"]))
        axis.currentIndexChanged.connect(lambda n: self.change("axis", FG.AXES[n]))
        add("axis", "x axis", axis, shared=True)
        xrange_ = QtWidgets.QLineEdit(_range_text(cell["xrange"]))
        xrange_.setPlaceholderText(
            "the figure's velocity range"
            if cell["axis"] == FG.VELOCITY
            else "Å: the velocity range at the transition"
        )
        xrange_.editingFinished.connect(
            lambda: self.change("xrange", lambda: _parse_range(xrange_.text()))
        )
        add("xrange", "x range", xrange_, shared=cell["axis"] == FG.VELOCITY)
        yrange = QtWidgets.QLineEdit(_range_text(cell["yrange"]))
        yrange.setPlaceholderText("by the residuals drawn")
        yrange.editingFinished.connect(
            lambda: self.change("yrange", lambda: _parse_range(yrange.text()))
        )
        add("yrange", "Flux range", yrange, shared=True)
        yticks = QtWidgets.QLineEdit(
            ", ".join("{0:g}".format(v) for v in cell["yticks"] or [])
        )
        yticks.setPlaceholderText("0, 0.5, 1")
        yticks.editingFinished.connect(
            lambda: self.change("yticks", lambda: _parse_numbers(yticks.text()))
        )
        add("yticks", "Flux ticks at", yticks, shared=True)
        for key, title_ in (("xnumbers", "x numbers"), ("ynumbers", "Flux numbers")):
            box = QtWidgets.QComboBox()
            box.addItems([AUTO, SHOWN, HIDDEN])
            value = cell[key]
            box.setCurrentIndex(0 if value is None else (1 if value else 2))
            box.currentIndexChanged.connect(
                lambda n, k=key: self.change(k, (None, True, False)[n])
            )
            add(key, title_, box, shared=True)
        side = QtWidgets.QComboBox()
        side.addItems([AUTO, "Left", "Right"])
        side.setCurrentIndex(
            0 if cell["yright"] is None else (2 if cell["yright"] else 1)
        )
        side.currentIndexChanged.connect(
            lambda n: self.change("yright", (None, False, True)[n])
        )
        add("yright", "Flux numbers' side", side, shared=True)
        for key, title_ in (
            ("xtitle", "Its own x title"),
            ("ytitle", "Its own y title"),
        ):
            check = QtWidgets.QCheckBox()
            check.setChecked(cell[key])
            check.toggled.connect(lambda on, k=key: self.change(k, on))
            add(key, title_, check, shared=True)
        ions = QtWidgets.QListWidget()
        ions.setMaximumHeight(90)
        for ion, name in tab.ions_of(entry):
            item = QtWidgets.QListWidgetItem(name)
            item.setData(QtCore.Qt.ItemDataRole.UserRole, ion)
            ticked = cell["ions"] is None or ion in cell["ions"]
            item.setCheckState(
                QtCore.Qt.CheckState.Checked
                if ticked
                else QtCore.Qt.CheckState.Unchecked
            )
            ions.addItem(item)
        ions.itemChanged.connect(lambda _item: self.change("ions", self._ticked(ions)))
        add("ions", "Ions ticked", ions)
        comps = QtWidgets.QListWidget()
        comps.setMaximumHeight(90)
        for cid in tab.components_of(entry):
            item = QtWidgets.QListWidgetItem(cid)
            item.setData(QtCore.Qt.ItemDataRole.UserRole, cid)
            ticked = cell["components"] is None or cid in cell["components"]
            item.setCheckState(
                QtCore.Qt.CheckState.Checked
                if ticked
                else QtCore.Qt.CheckState.Unchecked
            )
            comps.addItem(item)
        comps.itemChanged.connect(
            lambda _item: self.change("components", self._ticked(comps))
        )
        add("components", "Components ticked", comps)
        layout = QtWidgets.QVBoxLayout(self)
        layout.addLayout(form)
        self.message = W.muted("")
        self.message.setWordWrap(True)
        layout.addWidget(self.message)
        box = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Close
        )
        box.rejected.connect(self.reject)
        box.accepted.connect(self.accept)
        layout.addWidget(box)

    @staticmethod
    def _ticked(listing):
        """The ticked items, or None when every one is (follow the panel)."""
        out, every = [], True
        for num in range(listing.count()):
            item = listing.item(num)
            if item.checkState() == QtCore.Qt.CheckState.Checked:
                out.append(item.data(QtCore.Qt.ItemDataRole.UserRole))
            else:
                every = False
        return None if every else out

    def value(self, key):
        """An option's value as the dialog now holds it."""
        widget = self.fields[key]
        if key == "corner":
            return FG.CORNERS[widget.currentIndex()]
        if key == "axis":
            return FG.AXES[widget.currentIndex()]
        if key in ("xrange", "yrange"):
            return _parse_range(widget.text())
        if key == "yticks":
            return _parse_numbers(widget.text())
        if key in ("xnumbers", "ynumbers"):
            return (None, True, False)[widget.currentIndex()]
        if key == "yright":
            return (None, False, True)[widget.currentIndex()]
        if key in ("xtitle", "ytitle"):
            return widget.isChecked()
        return widget.text()

    def change(self, key, value, every=False):
        """Make the change as a step; a refusal is said in the dialog. ``value`` may
        be a function that reads it from a field."""
        try:
            if callable(value):
                value = value()
            self.tab.set_cell(self.row, self.start, key, value, every)
        except FG.FigureError as err:
            self.message.setText(str(err))
            return
        self.message.setText("")

    def apply_all(self, key):
        """Apply to all panels: this option, as the dialog holds it."""
        try:
            value = self.value(key)
        except FG.FigureError as err:
            self.message.setText(str(err))
            return
        self.change(key, value, every=True)


