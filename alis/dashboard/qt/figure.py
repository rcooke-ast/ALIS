    def _act(self, name, handler):
        """Run a handler through the window (errors reported); a change that cannot be
        made is told as a message (D86)."""

        def guarded():
            try:
                handler()
            except FG.FigureError as err:
                self.main.tell("Figure", str(err))

        if self.main is not None:
            self.main._run("figure." + name, guarded)
        else:
            guarded()

    def _do(self, step):
        if step is not None and step:
            self.session.history.do(step)

    def set_cell(self, row, start, key, value, every=False):
        """A cell's option, or every cell's (Apply to all panels), as one step."""
        step = FG.set_cell(
            self.session.project, self.current_id(), row, start, key, value, every
        )
        self._run_step("cell", step)

    def _run_step(self, name, step):
        if self.main is not None:
            self.main._run("figure." + name, lambda: self._do(step))
        else:
            self._do(step)

    def _option(self, key, value):
        if self._building or self.current_id() is None:
            return
        self._act(
            key,
            lambda: self._do(
                FG.set_option(self.session.project, self.current_id(), key, value)
            ),
        )

    def _option_pair(self, key):
        if self._building or self.current_id() is None:
            return
        spins = {
            "size": (self.size_w, self.size_h),
            "spacing": (self.space_x, self.space_y),
            "vrange": (self.v_low, self.v_high),
        }[key]
        value = [spins[0].value(), spins[1].value()]
        if value == list(self.current()[key]):
            return
        self._option(key, value)

    def _titles_changed(self, _on=None):
        self._option("titles", [self.shared_x.isChecked(), self.shared_y.isChecked()])

    def _zero_chosen(self, index):
        if index >= 0:
            self._option("zero", self.zero_menu.itemData(index) or "")

    def _grid_changed(self, _value=None):
        if self._building or self.current_id() is None:
            return
        fig = self.current()
        columns, rows = self.columns.value(), self.rows.value()
        if (columns, rows) == (fig["columns"], fig["rows"]):
            return
        self._act(
            "grid",
            lambda: self._do(
                FG.set_grid(self.session.project, fig["id"], columns, rows)
            ),
        )

    def _style_chosen(self, index):
        if self._building or self.current_id() is None:
            return
        if index == 0:
            self._option("style", "")
            return
        path = self.main.choose(
            "open",
            "Choose a style file",
            "",
            "matplotlib styles (*.mplstyle *rc);;All files (*)",
        )
        if path:
            self._option("style", path)
        else:
            self.refresh(self.session)

    def _figure_chosen(self, index):
        if self._building or index < 0:
            return
        self.session.set_view(SHOWN_FIGURE, self.figure_menu.itemData(index))
        self.refresh(self.session)

