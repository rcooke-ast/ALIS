def muted(text):
    """A grey label."""
    label = QtWidgets.QLabel(text)
    label.setObjectName("muted")
    return label


def column(*widgets, stretch=None, width=None):
    """
    A column of panes, with stretch factors.

    Parameters
    ----------
    *widgets : QWidget
    stretch : list of int, optional
        The stretch of each.
    width : int, optional
        A preferred width (the mockups' column width), used as the minimum.

    Generated by RJC and Claude.
    """
    holder = QtWidgets.QWidget()
    layout = QtWidgets.QVBoxLayout(holder)
    layout.setContentsMargins(0, 0, 0, 0)
    layout.setSpacing(8)
    stretch = stretch or [1] * len(widgets)
    for widget, factor in zip(widgets, stretch):
        layout.addWidget(widget, factor)
    if width is not None:
        # Small enough that the .mod panel beside the tabs can be made wide
        holder.setMinimumWidth(int(width * 0.4))
    return holder


def row(*widgets, stretch=None):
    """
    A row of columns, with stretch factors (the mockups' widths).

    Generated by RJC and Claude.
    """
    holder = QtWidgets.QWidget()
    layout = QtWidgets.QHBoxLayout(holder)
    layout.setContentsMargins(8, 8, 8, 8)
    layout.setSpacing(8)
    stretch = stretch or [1] * len(widgets)
    for widget, factor in zip(widgets, stretch):
        layout.addWidget(widget, factor)
    return holder


