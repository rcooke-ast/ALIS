"""Small widgets the dashboard's windows share: panes, banners, the pill, the strip.

Dashboard Stage 3.5. Each is drawn with the look of :mod:`~alis.dashboard.qt.style`.

Generated by RJC and Claude.
"""

from qtpy import QtCore, QtGui, QtWidgets

NOT_BUILT = "Not built yet"


class Pane(QtWidgets.QFrame):
    """
    A titled pane, as the mockups draw each part of a tab.

    Parameters
    ----------
    title : str
    body : QWidget or str, optional
        Its content; a string makes a placeholder line ("Not built yet: ...").
    extra : list of QWidget, optional
        Widgets at the right of the title row.

    Generated by RJC and Claude.
    """

    def __init__(self, title, body=None, extra=(), parent=None):
        super().__init__(parent)
        self.setObjectName("pane")
        layout = QtWidgets.QVBoxLayout(self)
        layout.setContentsMargins(1, 1, 1, 1)
        layout.setSpacing(0)
        header = QtWidgets.QFrame()
        header.setObjectName("paneHeader")
        row = QtWidgets.QHBoxLayout(header)
        row.setContentsMargins(8, 4, 8, 4)
        self.title = QtWidgets.QLabel(title)
        self.title.setObjectName("paneTitle")
        row.addWidget(self.title)
        row.addStretch(1)
        for widget in extra:
            row.addWidget(widget)
        layout.addWidget(header)
        holder = QtWidgets.QWidget()
        inner = QtWidgets.QVBoxLayout(holder)
        inner.setContentsMargins(8, 6, 8, 6)
        if body is None or isinstance(body, str):
            text = NOT_BUILT + (": " + body if body else ".")
            self.body = QtWidgets.QLabel(text)
            self.body.setObjectName("placeholder")
            self.body.setWordWrap(True)
            self.body.setAlignment(
                QtCore.Qt.AlignmentFlag.AlignTop | QtCore.Qt.AlignmentFlag.AlignLeft
            )
        else:
            self.body = body
        inner.addWidget(self.body)
        layout.addWidget(holder, 1)


class Banner(QtWidgets.QFrame):
    """
    A message across the top of the tabs, with buttons (hidden when empty).

    Generated by RJC and Claude.
    """

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setObjectName("banner")
        row = QtWidgets.QHBoxLayout(self)
        row.setContentsMargins(10, 6, 10, 6)
        self.icon = QtWidgets.QLabel()
        self.label = QtWidgets.QLabel()
        self.label.setWordWrap(True)
        self.label.setTextFormat(QtCore.Qt.TextFormat.PlainText)
        row.addWidget(self.icon)
        row.addWidget(self.label, 1)
        self.buttons = QtWidgets.QHBoxLayout()
        row.addLayout(self.buttons)
        self.hide()

    def show_message(self, text, kind="warning", buttons=()):
        """
        Show a message.

        Parameters
        ----------
        text : str
        kind : str
            ``"warning"``, ``"error"`` or ``"info"``.
        buttons : list of (str, callable)

        Generated by RJC and Claude.
        """
        self.setProperty("kind", kind)
        self.style().unpolish(self)
        self.style().polish(self)
        self.icon.setText({"error": "✕", "warning": "!", "info": "i"}[kind])
        self.label.setText(text)
        # Old buttons leave at once: deleteLater alone would leave them drawn where
        # they were until the event loop runs
        while self.buttons.count():
            old = self.buttons.takeAt(0).widget()
            if old is not None:
                old.hide()
                old.setParent(None)
                old.deleteLater()
        for title, handler in buttons:
            button = QtWidgets.QPushButton(title)
            button.clicked.connect(handler)
            self.buttons.addWidget(button)
        self.show()

    def clear(self):
        """Hide the banner."""
        self.label.setText("")
        self.hide()


class Pill(QtWidgets.QLabel):
    """
    The toolbar's blinding pill: what is blinded (D24).

    Generated by RJC and Claude.
    """

    def __init__(self, parent=None):
        super().__init__("Not blinded", parent)
        self.setObjectName("pill")
        self.setToolTip("What is blinded in this project")

    def set_text(self, text):
        """Show what is blinded, dark when anything is."""
        self.setText(text)
        self.setProperty("blinded", "false" if text == "Not blinded" else "true")
        self.style().unpolish(self)
        self.style().polish(self)


class Strip(QtWidgets.QToolButton):
    """
    The collapsed ``.mod`` panel: a narrow strip at the right, with its name
    written upwards ("▸ .mod editor").

    Generated by RJC and Claude.
    """

    def __init__(self, text, parent=None):
        super().__init__(parent)
        self.setObjectName("strip")
        self._text = text
        self.setToolTip("Show the .mod panel")
        self.setFixedWidth(24)
        self.setSizePolicy(
            QtWidgets.QSizePolicy.Policy.Fixed, QtWidgets.QSizePolicy.Policy.Expanding
        )

    def text(self):
        """The strip's label."""
        return self._text

    def paintEvent(self, event):
        """Draw the background, then the label turned to read upwards."""
        super().paintEvent(event)
        painter = QtGui.QPainter(self)
        painter.setPen(self.palette().color(QtGui.QPalette.ColorRole.ButtonText))
        # Turned a quarter clockwise, the glyphs stand to the right of their baseline
        height = painter.fontMetrics().ascent()
        painter.translate((self.width() - height) / 2, 12)
        painter.rotate(90)
        painter.drawText(0, 0, self._text)
        painter.end()


class ElidedLabel(QtWidgets.QLabel):
    """
    A label that ends its text with "…" when there is no room for all of it; the
    whole text is its tooltip.

    Generated by RJC and Claude.
    """

    def setText(self, text):
        super().setText(text)
        self.setToolTip(text)

    def paintEvent(self, event):
        painter = QtGui.QPainter(self)
        painter.setPen(self.palette().color(QtGui.QPalette.ColorRole.WindowText))
        text = self.fontMetrics().elidedText(
            self.text(), QtCore.Qt.TextElideMode.ElideRight, self.width()
        )
        painter.drawText(
            self.rect(),
            QtCore.Qt.AlignmentFlag.AlignLeft | QtCore.Qt.AlignmentFlag.AlignVCenter,
            text,
        )
        painter.end()


