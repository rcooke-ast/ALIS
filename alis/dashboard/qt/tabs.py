from alis.dashboard.qt.regions import RegionsTab

# The view state's key of the run chosen in the run history (None: the latest)
SHOWN_RUN = "shown_run"

# The base of every tab (kept here by name; it lives in widgets.py, which the tabs'
# own modules import)
Tab = W.Tab


class FitTab(Tab):
    """
    The Fit tab (D38–D41): its sub-tabs Inspect, Results and Compare, and the run
    they show (the latest, or the one chosen in the run history; the fit in
    progress while a run goes). Its own keys act while it has the focus: [ and ]
    step through Inspect's View menu.

    Generated by RJC and Claude.
    """

    name = "Fit"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.main = None
        self.session = None
        self._views = {}
        self.tab_buttons = []
        self.subtabs = QtWidgets.QTabWidget()
        self.subtabs.setObjectName("fitTabs")
        self.inspect = InspectTab()
        self.results = ResultsTab()
        self.compare = CompareTab()
        for tab in (self.inspect, self.results, self.compare):
            tab.holder = self
            self.subtabs.addTab(tab, tab.name)
        self.layout_.setContentsMargins(4, 4, 4, 0)
        self.layout_.addWidget(self.subtabs)

    def attach(self, window):
        """The main window, which the sub-tabs use too."""
        super().attach(window)
        for tab in (self.inspect, self.results, self.compare):
            tab.attach(window)

    def refresh(self, session):
        """Redraw the sub-tabs (each only while it is shown)."""
        self.use(session)
        for tab in (self.inspect, self.results, self.compare):
            tab.refresh(session)

    def use(self, session):
        """The session whose runs the tab shows (other tabs may ask first)."""
        if session is not self.session:
            self._views = {}
        self.session = session

    # -- the shown run (Q6.5) -----------------------------------------------------

    def running(self):
        """The run going for this project, or None."""
        fit = getattr(self.main, "fit", None)
        if fit is None or not fit.active or fit.session is not self.session:
            return None
        return fit.job

    def shown_number(self):
        """The committed run chosen in the run history, or None (the latest)."""
        if self.session is None:
            return None
        return self.session.view.get(SHOWN_RUN)

    def shown_record(self):
        """The run shown when no run goes: chosen in the run history, or the
        latest."""
        if self.session is None:
            return None
        return RS.shown_record(self.session.project, self.shown_number())

    def show_run(self, number):
        """
        Show a run of the run history on Inspect and Results (None: the latest).

        Generated by RJC and Claude.
        """
        if self.session is None:
            return
        self.session.set_view(SHOWN_RUN, None if number is None else int(number))
        self.refresh(self.session)

    def shown_view(self, job=None):
        """
        The run the sub-tabs show (Q6.5, Q6.15): the fit in progress while a run
        goes, or the run chosen in the run history (the latest by default), as a
        :class:`~alis.dashboard.results.View`; and why there is none.

        Returns
        -------
        tuple
            ``(View or None, str)``.

        Generated by RJC and Claude.
        """
        if self.session is None:
            return None, ""
        project = self.session.project
        gate = BL.Gate(project)
        job = self.running() if job is None else job
        if job is not None:
            try:
                return RS.View(project, run=job), ""
            except RS.ResultsError as err:
                return None, gate.message(str(err))
        record = self.shown_record()
        if record is None:
            return None, NO_RUN
        return self.view_of(record)

    def view_of(self, record):
        """
        A run of the project as a :class:`~alis.dashboard.results.View`, kept while
        the run and the project stay as they are (a few at once: Compare shows two);
        and why it has no best fit.

        Returns
        -------
        tuple
            ``(View or None, str)``.

        Generated by RJC and Claude.
        """
        project = self.session.project
        gate = BL.Gate(project)
        key = (
            record.prefix,
            record.bundle.members.get(record.prefix + "run.json"),
            CO._state_key(project),
        )
        view = self._views.get(key)
        if view is None:
            try:
                view = RS.View(project, record=record)
            except RS.ResultsError as err:
                return None, gate.message(str(err))
            if len(self._views) >= 4:
                self._views.clear()
            self._views[key] = view
        why = view.why_not()
        if why:
            return None, gate.message(why)
        return view, ""

    def progressed(self, job):
        """The run has reported: Inspect and Results follow it."""
        self.inspect.progressed(job)
        self.results.progressed(job)

    def show_items(self, items):
        self.inspect.show_items(items)

    def bind_action(self, name, action):
        """The tab's own actions: ‹ and › on Inspect and on Compare."""
        self.tab_buttons.append(self.inspect.bind_action(name, action))
        self.compare.bind_action(name, action)

    def _viewing(self):
        """The sub-tab whose View menu ‹ and › step through: Compare's when it is
        shown, else Inspect's."""
        if self.subtabs.currentWidget() is self.compare:
            return self.compare
        return self.inspect

    def do_previous_view(self):
        self._viewing().do_previous_view()

    def do_next_view(self):
        self._viewing().do_next_view()


class PlotTab(Tab):
    """
    The Plot tab (D42): built after v1, shown but disabled.

    Generated by RJC and Claude.
    """

    name = "Plot"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.layout_pane = W.Pane(
            "Layout", "the preset, the grid, the figure size and the style."
        )
        self.preview = W.Pane("Preview", "the figure, drawn by the plotting script.")
        self.panels = W.Pane("Panels", "the transitions, dragged onto the grid.")
        self.layout_.addWidget(
            W.row(
                W.column(self.layout_pane, width=400),
                W.column(self.preview, width=660),
                W.column(self.panels, width=322),
                stretch=[400, 660, 322],
            )
        )


