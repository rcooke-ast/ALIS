# The base of every tab (kept here by name; it lives in widgets.py, which the tabs'
# own modules import)
Tab = W.Tab


class ResultsTab(Tab):
    """
    The Fit tab's Results sub-tab (D40): the results, the run history, and the fit
    statistics above the correlations.

    Generated by RJC and Claude.
    """

    name = "Results"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.table = W.Pane(
            "Results", "each parameter's value and error, its tie state and flags."
        )
        self.correlations = W.Pane("Correlations", "the correlation matrix.")
        self.stats = W.Pane("Fit statistics", "χ², degrees of freedom, iterations.")
        self.history = W.Pane(
            "Run history", "the committed runs, each with your description."
        )
        # Run history beside the results, and the correlations below the
        # statistics (RJC's review swapped the two)
        self.layout_.addWidget(
            W.row(
                W.column(self.table, width=640),
                W.column(self.history, width=364),
                W.column(self.stats, self.correlations, stretch=[1, 2], width=370),
                stretch=[640, 364, 370],
            )
        )


class CompareTab(Tab):
    """
    The Fit tab's Compare sub-tab (D41).

    Generated by RJC and Claude.
    """

    name = "Compare"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.choose = W.Pane("Compare", "choose any two runs.")
        self.parameters = W.Pane(
            "Parameters",
            "the quantities both runs share, their difference and its size in σ.",
        )
        self.view = W.Pane(
            "View", "both models on the same data, with their difference in σ."
        )
        self.choose.setMaximumHeight(90)
        body = W.row(
            W.column(self.parameters, width=610),
            W.column(self.view, width=772),
            stretch=[610, 772],
        )
        body.layout().setContentsMargins(0, 0, 0, 0)
        holder = W.column(self.choose, body, stretch=[0, 1])
        holder.layout().setContentsMargins(8, 8, 8, 8)
        self.layout_.addWidget(holder)


class FitTab(Tab):
    """
    The Fit tab (D38–D41): its sub-tabs Inspect, Results and Compare. Its own keys
    act while it has the focus: [ and ] step through Inspect's View menu.

    Generated by RJC and Claude.
    """

    name = "Fit"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.tab_buttons = []
        self.subtabs = QtWidgets.QTabWidget()
        self.subtabs.setObjectName("fitTabs")
        self.inspect = InspectTab()
        self.inspect.holder = self
        self.results = ResultsTab()
        self.compare = CompareTab()
        for tab in (self.inspect, self.results, self.compare):
            self.subtabs.addTab(tab, tab.name)
        self.layout_.setContentsMargins(4, 4, 4, 0)
        self.layout_.addWidget(self.subtabs)

    def attach(self, window):
        """The main window, which the sub-tabs use too."""
        super().attach(window)
        for tab in (self.inspect, self.results, self.compare):
            tab.attach(window)

    def refresh(self, session):
        """Redraw the sub-tabs (each only while it is shown)."""
        for tab in (self.inspect, self.results, self.compare):
            tab.refresh(session)

    def show_items(self, items):
        self.inspect.show_items(items)

    def bind_action(self, name, action):
        """The tab's own actions: Inspect's ‹ and ›."""
        self.tab_buttons.append(self.inspect.bind_action(name, action))

    def do_previous_view(self):
        self.inspect.do_previous_view()

    def do_next_view(self):
        self.inspect.do_next_view()


