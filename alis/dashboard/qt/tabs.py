"""The five tabs, as frames of the agreed layout (D34–D42, Q3.4).

Dashboard Stage 3.5. Each tab holds the panes of its layout in the mockups
(``doc/dashboard/mockups/``), each pane titled and saying what it will hold, in the
same columns and proportions. Stages 4–6 replace the placeholders with the panels
(the ``gui-component`` skill). The Fit tab has its three sub-tabs, and the Plot tab
is built after v1.

Generated by RJC and Claude.
"""

from qtpy import QtWidgets

from alis.dashboard import blinding as BL
from alis.dashboard import continuum as CO
from alis.dashboard import results as RS
from alis.dashboard.qt import widgets as W
from alis.dashboard.qt.components import ComponentsTab
from alis.dashboard.qt.data import DataTab
