    def add_at(self, widget, x):
        """
        Add a component at a panel's velocity, with its first guesses; in the Lyα
        forest, a line of the forest at that wavelength.

        Generated by RJC and Claude.
        """
        self._disarm()
        project = self.session.project
        system, ion = self.current()
        if ion == FOREST:
            wave = widget.panel.centre * (1.0 + x / C.C_KMS)
            step, guess = C.interloper(
                project, wave, specid=widget.panel.snip.specid, prefs=self.prefs()
            )
            self._do(step)
            return
        if system is None:
            return
        z = system.z + x * (1.0 + system.z) / C.C_KMS
        step, guesses = C.new_component(project, system, z, self.prefs())
        self._do(step)
        project = self.session.project
        system = project.system(system.id)
        comp = min(system.components, key=lambda c: abs(c.z - z))
        self.selected = comp.label or comp.id
        self.notes[self.selected] = {i: g.note for i, g in guesses.items()}

    # -- dragging (S13, Q5.4, Q5.12, Q5.17) -----------------------------------------

    def nearest(self, widget, x):
        """
        The component nearest a velocity in a panel (Q5.23): by its ticks at the
        snip's strongest transition and, thin, at the others; not by the locked
        lines of other systems or of the forest.

        Returns
        -------
        tuple
            ``(component, the tick's velocity)``, or ``(None, None)``.

        Generated by RJC and Claude.
        """
        best = None
        for line in widget.view.ticks():
            key = getattr(line, "key", None)
            if not key or key[0] != "component":
                continue
            away = abs(line.value() - x)
            if best is None or away < best[0]:
                best = (away, key, line.value())
        if best is None:
            return None, None
        return self._component_of(best[1]), best[2]

    def _start_drag(self, comp, ion, kind):
        """What a drag starts from: the values, and the panels' χ²."""
        line = comp.lines_of(ion)[0] if ion and comp.lines_of(ion) else None
        logn = line.param("ColDens").start if line is not None else None
        bpar = line.param("bturb") if line is not None else None
        tpar = line.param("temperature") if line is not None else None
        btot = None
        if line is not None:
            btot = C.total_b(
                self.session.project.registry,
                ion,
                bpar.start if bpar is not None else 0.0,
                tpar.start if tpar is not None else 0.0,
            )
        chi2 = sum(w.curve.chi2 for w in self.panel_widgets if w.curve is not None)
        self._drag = {
            "comp": comp,
            "ion": ion,
            "kind": kind,
            "logn": logn,
            "b": btot,
            "z": C.component_z(comp, self._linked),
            "chi2": chi2,
            "changes": [],
            "held": frozenset(self.drag_keys.held),
        }

    def _tick_bases(self, comp):
        """The ticks of a component in every panel, with where they are."""
        out = []
        for widget in self.panel_widgets:
            for line in widget.view.ticks():
                key = getattr(line, "key", None) or ()
                if key[:2] in (("component", comp.id), ("isotope", comp.id)):
                    out.append((line, line.value()))
        return out

    def _box_dragged(self, widget, x0, y0, x, y, state):
        """
        A drag in a panel (Q5.23). It moves the component nearest where it starts,
        selecting it, by the drag's movement (never to the pointer): above the
        continuum its z; below it, log N (vertically, 2 dex over the panel's height,
        down deepens) and b (by how much farther from the component the pointer
        is) together, N held keeping b and B held keeping log N. ALIS's model
        follows; the text changes once, when the drag ends.

        Generated by RJC and Claude.
        """
        system, ion = self.current()
        if state == "start":
            self._drag = None
            if self.armed() or self.armed(INTERLOPER) or system is None:
                return
            if ion in (None, FOREST):
                return
            comp, at = self.nearest(widget, x0)
            if comp is None:
                return
            if (comp.label or comp.id) != self.selected:
                self.select(comp)
            if not comp.lines_of(ion):
                # Excluded from the ion (or never in it): selected, not dragged
                return
            axes = C.draggable(comp, ion)
            kind = "z" if y0 > 1.0 else "shape"
            if kind == "z" and not axes["z"]:
                return
            if kind == "shape" and not (axes["logn"] or axes["b"]):
                return
            self._start_drag(comp, ion, kind)
            self._drag.update(widget=widget, x0=x0, y0=y0, at=at, axes=axes, values={})
            if kind == "z":
                self._drag["ticks"] = self._tick_bases(comp)
            return
        drag = self._drag
        if drag is None:
            return
        finished = state == "finish"
        if drag["kind"] == "z":
            dv = x - drag["x0"]
            for line, base in drag["ticks"]:
                line.setValue(base + dv)
            vel = P.velocity(drag["z"], system.z) + dv
            self._drag_to(dict(z=system.z + vel * (1.0 + system.z) / C.C_KMS), finished)
            return
        held = frozenset(self.drag_keys.held)
        if held != drag["held"]:
            # A key pressed or let go: the drag goes on from here
            drag.update(held=held, x0=x, y0=y)
            drag["logn"] = drag["values"].get("logn", drag["logn"])
            drag["b"] = drag["values"].get("b", drag["b"])
        axes = drag["axes"]
        only_n = "n" in held and "b" not in held
        only_b = "b" in held and "n" not in held
        (_, _), (vy0, vy1) = drag["widget"].view.view_range()
        yspan = max(vy1 - vy0, 1e-9)
        values = {}
        if axes["logn"] and not only_b:
            values["logn"] = drag["logn"] + 2.0 * (drag["y0"] - y) / yspan
        if axes["b"] and not only_n:
            wider = abs(x - drag["at"]) - abs(drag["x0"] - drag["at"])
            values["b"] = max(drag["b"] + wider, 0.0)
        drag["values"] = values
        self._drag_to(values, finished)

    def _drag_to(self, values, finished):
        """The values a drag gives, drawn now or soon (throttled); written when it
        ends."""
        drag = self._drag
        if drag is None:
            return
        project = self.session.project
        try:
            changes = C.drag(
                project, drag["comp"], drag["ion"], prefs=self.prefs(), **values
            )
        except C.DragError as err:
            self._drag = None
            self._warn("Drag", str(err))
            self._act("components.drag", lambda: None)
            return
        drag["changes"] = changes
        if finished:
            self._preview_timer.stop()
            self._preview_now()
            self._drag = None
            comp = drag["comp"]
            self._act(
                "components.drag",
                lambda: self._do(C.drag_step(self.session.project, comp, changes)),
            )
            return
        if not self._preview_timer.isActive():
            rate = max(float(self._pref("components.preview_rate")), 1.0)
            self._preview_timer.start(int(1000.0 / rate))
            self._preview_now()

    def _preview_now(self):
        """Draw the model with the drag's values (ALIS's own, S13)."""
        drag = self._drag
        if drag is None or not drag["changes"]:
            return
        try:
            profile = PR.of(self.session.project)
            values = profile.values(C.drag_values(drag["changes"]))
            curves = profile.evaluate(
                values, snips=[w.panel.snip.data.index for w in self.panel_widgets]
            )
        except PR.ProfileError as err:
            self.panel_note.setText(str(err))
            return
        chi2 = 0.0
        for widget in self.panel_widgets:
            curve = curves.get(widget.panel.snip.data.index)
            if curve is None:
                continue
            widget.view.set_model(widget.panel.velocity, curve.model)
            widget.resid.set_residuals(widget.panel.velocity, curve.residuals)
            chi2 += curve.chi2
        text = self.readout(drag["changes"], chi2 - drag["chi2"])
        for widget in self.panel_widgets:
            widget.readout.setText(text)

    def readout(self, changes, dchi2):
        """
        What a drag shows in the panels' corner, through the gate: log N and b, or
        only the change in χ² for a hidden value (D24, QF.20(d)).

        Generated by RJC and Claude.
        """
        gate = self.gate or BL.Gate(self.session.project)
        if any(gate.is_hidden(par) for par, _ in changes):
            return "Δχ² {0:+.1f}".format(dchi2)
        parts = []
        names = {"ColDens": "log N {0:.2f}", "bturb": "b_turb {0:.2f} km/s"}
        names.update({"temperature": "T {0:.0f} K"})
        for par, value in changes:
            if par.name in names:
                parts.append(names[par.name].format(value))
            elif par.name == "redshift":
                system, _ = self.current()
                vel = P.velocity(value, system.z) if system is not None else 0.0
                parts.append("v {0:+.2f} km/s".format(vel))
        return " · ".join(dict.fromkeys(parts))

    # -- the keys and buttons ------------------------------------------------------

    def _ion_items(self):
        out = []
        for num in range(self.tree.topLevelItemCount()):
            head = self.tree.topLevelItem(num)
            for k in range(head.childCount()):
                out.append(head.child(k))
        return out

    def _step(self, by):
        items = self._ion_items()
        if not items:
            return
        current = self.tree.currentItem()
        num = items.index(current) if current in items else -1
        num = max(0, min(len(items) - 1, num + by))
        self.tree.setCurrentItem(items[num])

    def do_previous(self):
        """↑: the ion above."""
        self._step(-1)

    def do_next(self):
        """↓: the ion below."""
        self._step(1)

    def do_add_ion(self):
        """Add ion…: an ion for every component of the system (Q5.7)."""
        system, ion = self.current()
        if system is None or ion == FOREST:
            return
        project = self.session.project
        inside, others = C.addable_ions(project, system)
        dialog = D.IonDialog(system.name, inside, others, self)
        if not self.main.run_dialog(dialog) or dialog.chosen() is None:
            return
        new = dialog.chosen()
        step, _ = C.add_ion(project, system, new, self.prefs())
        self._do(step)
        self.state = {"system": system.id, "ion": new}
        self._remember()

    def do_add_system(self):
        """Add system…: as on the Data tab."""
        dialog = D.AskDialog(
            "Add a system",
            [("z", "z", "", "number"), ("name", "Name (optional)", "", "text")],
            "Add",
        )
        if self.main.run_dialog(dialog):
            values = dialog.values()
            self._do(
                DS.add_system_step(self.session.project, values["z"], values["name"])
            )


