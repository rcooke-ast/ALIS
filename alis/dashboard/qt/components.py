    def _fill_navigator(self):
        """
        The systems, their ions and the Lyα forest; the ion shown selected (the
        first ion of the primary system when none is).

        Generated by RJC and Claude.
        """
        project = self.session.project
        self.tree.clear()
        systems, forest = C.navigator(project)
        chosen = None
        first = None
        for system, rows in systems:
            title = system.name + (" · primary" if system.primary else "")
            head = QtWidgets.QTreeWidgetItem([title, ""])
            head.setFlags(QtCore.Qt.ItemFlag.ItemIsEnabled)
            head.setFirstColumnSpanned(True)
            font = head.font(0)
            font.setBold(True)
            head.setFont(0, font)
            head.setData(0, ROLE, ("system", system.id))
            self.tree.addTopLevelItem(head)
            for row in rows:
                item = QtWidgets.QTreeWidgetItem([row.name, row.detail])
                item.setData(0, ROLE, ("ion", system.id, row.ion))
                item.setForeground(1, self.palette().placeholderText())
                item.setToolTip(0, row.detail)
                item.setToolTip(1, row.detail)
                head.addChild(item)
                # The systems come primary first: its first ion is shown by default
                first = item if first is None else first
                if self.state.get("system") == system.id and (
                    self.state.get("ion") in row.ions
                ):
                    chosen = item
        if forest is not None:
            head = QtWidgets.QTreeWidgetItem(["Generic absorbers", ""])
            head.setFlags(QtCore.Qt.ItemFlag.ItemIsEnabled)
            head.setFirstColumnSpanned(True)
            font = head.font(0)
            font.setBold(True)
            head.setFont(0, font)
            self.tree.addTopLevelItem(head)
            item = QtWidgets.QTreeWidgetItem(["Lyα forest", forest.detail])
            item.setData(0, ROLE, (FOREST,))
            item.setForeground(1, self.palette().placeholderText())
            head.addChild(item)
            if self.state.get("ion") == FOREST:
                chosen = item
        self.tree.expandAll()
        if chosen is None:
            chosen = first
        if chosen is not None:
            self.tree.setCurrentItem(chosen)
            self._take(chosen)
        self.tree_note.setText("" if systems else NO_SYSTEM)

    def _take(self, item):
        """The state from a navigator item."""
        data = item.data(0, ROLE)
        if not data:
            return
        kept = {
            k: self.state[k] for k in ("dataset", "columns", "range") if k in self.state
        }
        if data[0] == FOREST:
            self.state = {"ion": FOREST}
        elif data[0] == "ion":
            self.state = {"system": data[1], "ion": data[2]}
        self.state.update(kept)
        self._remember()

    def _item_chosen(self, current, previous=None):
        if current is None or self._filling:
            return
        if not current.flags() & QtCore.Qt.ItemFlag.ItemIsSelectable:
            return
        self._take(current)
        self._filling = True
        try:
            self._fill_tools()
        finally:
            self._filling = False
        self._fill_panels()
        self._fill_cards()
        self._update_actions()
        self._highlight(self._ion_lines())

    def _ion_lines(self):
        """The voigt lines of the ion shown, its isotopes' too, or the forest's."""
        project = self.session.project
        system, ion = self.current()
        if ion == FOREST:
            return list(project.absorbers)
        if system is None or ion is None:
            return []
        rows = C.navigator_ions(project, system)
        ions = next((r.ions for r in rows if r.ion == ion), [ion])
        return [ln for c in system.components for i in ions for ln in c.lines_of(i)]

    def _highlight(self, items):
        """
        Highlight items' lines in the ``.mod`` panel (S16), its cursor and the focus
        left where they are.

        Generated by RJC and Claude.
        """
        panel = getattr(self.main, "panel", None)
        if panel is None or self.session is None or self.session.project.paused:
            return
        panel.select_items(items, move=False)

    def _update_actions(self):
        system, ion = self.current()
        action = self.actions_.get("components.add_ion")
        if action is not None:
            action.setEnabled(system is not None and ion != FOREST)

    def show_items(self, items):
        """
        Show what the line under the ``.mod`` panel's cursor describes (S16): a voigt
        line's ion, its component selected; a line of the Lyα forest; for a link or a
        ``fix`` or ``lim param`` line, the parameter it constrains.

        Generated by RJC and Claude.
        """
        if self.session is None or self.session.project.paused:
            return
        project = self.session.project
        panel = getattr(self.main, "panel", None)
        place = C.at_line(project, panel.cursor_line()) if panel is not None else None
        if place is None:
            comp = next(
                (i for i in items if isinstance(i, P.Component) and i.ions), None
            )
            if comp is None or comp.system is None:
                return
            place = C.Place(comp.system, comp.ions[0], comp)
        if place.forest:
            if self.state.get("ion") != FOREST:
                self.show_ion(self.state.get("system"), FOREST)
            return
        system, ion = self.current()
        if system is None or system.id != place.system.id or ion != place.ion:
            self.show_ion(place.system.id, place.ion)
        comp = place.component
        if comp is not None and self.selected != (comp.label or comp.id):
            self.select(comp)

    def show_ion(self, system_id, ion):
        """Show an ion of a system (the navigator follows)."""
        self.state.update({"system": system_id, "ion": ion})
        self._remember()
        if self.session is not None:
            self.refresh(self.session)

