    def _fill_panels(self):
        """
        The panels of what is shown, each with its data, model, regions, ticks and
        residuals.

        Generated by RJC and Claude.
        """
        self._clear_panels()
        if self.session is None:
            return
        project = self.session.project
        system, ion = self.current()
        self._linked = C.linked_values(project)
        self._fill_notices(system, ion)
        notes = []
        if ion == FOREST:
            found = C.forest_panels(project, self.dataset())
            missing = []
        elif system is None or ion is None:
            self.panel_note.setText(NO_SYSTEM if system is None else NO_ION)
            return
        else:
            found, missing = C.panels(project, system, ion, self.dataset())
            if not found and not missing:
                notes.append(NO_PANEL.format(P.ion_name(ion)))
        notes += missing
        curves = {}
        try:
            profile = PR.of(project)
            curves = profile.evaluate(snips=[p.snip.data.index for p in found])
        except PR.ProfileError as err:
            notes.append(str(err))
        half = self.half_range()
        # No more columns than panels: one panel takes the whole width
        ncol = max(1, min(self.columns(), len(found)))
        for num, panel in enumerate(found):
            widget = PanelWidget(panel)
            self._draw_panel(widget, curves.get(panel.snip.data.index), system, ion)
            self._connect(widget)
            self.grid.addWidget(widget, num // ncol, num % ncol)
            self.panel_widgets.append(widget)
        self._show_armed()
        for col in range(4):
            self.grid.setColumnStretch(col, 1 if col < ncol else 0)
        nrows = (len(found) + ncol - 1) // ncol
        for num, widget in enumerate(self.panel_widgets):
            widget.view.set_labels(top=False, bottom=num // ncol == nrows - 1)
        self.panel_note.setText("  ·  ".join(notes))
        if self.panel_widgets:
            self.zoom.attach(*[w.view for w in self.panel_widgets])
            for widget in self.panel_widgets:
                widget.view.set_home((-half, half), NORMALISED_Y)
                widget.view.home()
            self.zoom.remember()

