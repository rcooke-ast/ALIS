    def bind_action(self, name, action):
        """
        The tab's own actions: Add ion… and Add system… under the navigator, and the
        keys.

        Generated by RJC and Claude.
        """
        self.actions_[name] = action
        if name in ("components.add_ion", "components.add_system"):
            button = QtWidgets.QToolButton()
            button.setDefaultAction(action)
            button.setObjectName(name.replace(".", "_"))
            self.nav_buttons.addWidget(button)
            self.tab_buttons.append(button)
        elif name in ("components.add_component", INTERLOPER):
            button = QtWidgets.QToolButton()
            button.setDefaultAction(action)
            button.setObjectName(name.replace(".", "_"))
            if name == INTERLOPER:
                self.panel_tools.insertWidget(1, button)
            else:
                button.setStyleSheet("font-weight: 600;")
                self.panel_tools.insertWidget(0, button)
            self.tab_buttons.append(button)
        else:
            self.tab_buttons.append(KeyHolder(self.tree, action))

    # -- acting ---------------------------------------------------------------------------

    def _act(self, name, handler):
        """Run a handler through the window (typing read first, errors reported)."""
        if self.main is not None:
            self.main._run(name, handler)
        else:
            handler()

    def _do(self, step):
        """Make a step through the history."""
        if step is not None and step:
            self.session.history.do(step)

    def _warn(self, title, text):
        if self.main is not None:
            self.main.tell(title, text, "warning")

    def prefs(self):
        """The user's preferences, or None (the defaults)."""
        return getattr(self.main, "prefs", None)

    # -- the state ----------------------------------------------------------------------

    def _system(self):
        """The system of the ion shown, or the primary."""
        if self.session is None:
            return None
        systems = self.session.project.systems
        ident = self.state.get("system")
        for system in systems:
            if system.id == ident:
                return system
        return next((s for s in systems if s.primary), systems[0] if systems else None)

    def current(self):
        """What is shown: ``(system, ion)``, ``(None, FOREST)``, or ``(None, None)``."""
        if self.state.get("ion") == FOREST:
            return None, FOREST
        system = self._system()
        if system is None or not self.state.get("ion"):
            return system, None
        return system, self.state["ion"]

    def _remember(self):
        """Keep what the tab shows in the view state (saved with the project)."""
        if self.session is not None:
            data = {k: self.state[k] for k in VIEW_KEYS if k in self.state}
            self._seen_view = data
            self.session.set_view("components", data)

    def _pref(self, key):
        prefs = self.prefs()
        try:
            return prefs[key] if prefs is not None else PF.SPEC[key].default
        except KeyError:
            return PF.SPEC[key].default

    # -- refreshing ---------------------------------------------------------------------

    def refresh(self, session):
        """
        Redraw the tab from the project (after every step, undo and redo); while
        another tab is shown, only once it is shown again.

        Generated by RJC and Claude.
        """
        if self._drag is not None and session is self.session:
            # Not while a drag goes on: it would take away what is being dragged;
            # the step the drag ends with refreshes the tab
            return
        if session is not self.session:
            self.state, self._seen_view = {}, None
            self._drag = None
        self.session = session
        if session is None or session.project.paused:
            return
        if self.main is not None and self.main.tabs.currentWidget() is not self:
            self._stale = True
            return
        self._stale = False
        stored = session.view.get("components") or {}
        if stored != self._seen_view:
            self.state = {k: stored[k] for k in VIEW_KEYS if k in stored}
            self._seen_view = dict(stored)
        self.gate = BL.Gate(session.project)
        self._filling = True
        try:
            self._fill_navigator()
            self._fill_tools()
        finally:
            self._filling = False
        self._fill_panels()
