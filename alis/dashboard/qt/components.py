    def _component_of(self, key):
        """The component a tick names, or None."""
        system, _ = self.current()
        if system is None or not key or key[0] != "component":
            return None
        for comp in system.components:
            if comp.id == key[1]:
                return comp
        return None

    def _connect(self, widget):
        view = widget.view
        view.clicked.connect(lambda x, y, w=widget: self._panel_clicked(w, x, y))
        view.tickClicked.connect(self._tick_clicked)
        view.dragged.connect(
            lambda x0, y0, x, y, state, w=widget: self._box_dragged(
                w, x0, y0, x, y, state
            )
        )
        view.contextRequested.connect(lambda x, y, pos, w=widget: self._menu(w, x, pos))

    def _tick_clicked(self, key):
        comp = self._component_of(key)
        if comp is None:
            return
        # The click reaches the panel too, after the tick: it must not clear this
        self._tick_hit = True
        self.select(comp)

    def _panel_clicked(self, widget, x, y):
        """A click in a panel: adds a component when armed; else clears the
        selection (a click never adds a component unless armed, Q5.15(b))."""
        if self._tick_hit:
            self._tick_hit = False
            return
        if self.armed():
            self._act("components.add_component", lambda: self.add_at(widget, x))
            return
        if self.armed(INTERLOPER):
            self._disarm()
            self._menu(widget, x)
            return
        # The component nearest the click is selected (Q5.23); with none, the
        # panel's snip is highlighted in the .mod panel (S16)
        comp, _ = self.nearest(widget, x)
        if comp is None:
            self._highlight([widget.panel.snip])
        else:
            self.select(comp)

