class NavigatorDelegate(QtWidgets.QStyledItemDelegate):
    """
    The navigator's rows: an ion's name, and under it what it has, muted ("8
    snips · 2 comp. · with D I"); a system's title in bold.

    Generated by RJC and Claude.
    """

    def _detail(self, index):
        return index.siblingAtColumn(1).data() or ""

    def sizeHint(self, option, index):
        size = super().sizeHint(option, index)
        if self._detail(index):
            size.setHeight(size.height() * 2)
        return size

    def paint(self, painter, option, index):
        detail = self._detail(index)
        if not detail:
            super().paint(painter, option, index)
            return
        self.initStyleOption(option, index)
        name = option.text
        option.text = ""
        style = (
            option.widget.style() if option.widget else QtWidgets.QApplication.style()
        )
        style.drawControl(
            QtWidgets.QStyle.ControlElement.CE_ItemViewItem,
            option,
            painter,
            option.widget,
        )
        rect = option.rect.adjusted(4, 1, -2, -1)
        half = rect.height() // 2
        selected = option.state & QtWidgets.QStyle.StateFlag.State_Selected
        painter.save()
        font = option.font
        font.setBold(True)
        painter.setFont(font)
        role = (
            option.palette.ColorRole.HighlightedText
            if selected
            else option.palette.ColorRole.Text
        )
        painter.setPen(option.palette.color(role))
        top = QtCore.QRect(rect.left(), rect.top(), rect.width(), half)
        painter.drawText(top, QtCore.Qt.AlignmentFlag.AlignVCenter, name)
        font.setBold(False)
        if font.pointSizeF() > 0:
            font.setPointSizeF(font.pointSizeF() * 0.9)
        elif font.pixelSize() > 0:
            font.setPixelSize(max(1, int(font.pixelSize() * 0.9)))
        painter.setFont(font)
        if not selected:
            painter.setPen(
                option.palette.color(option.palette.ColorRole.PlaceholderText)
            )
        low = QtCore.QRect(rect.left(), rect.top() + half, rect.width(), half)
        metrics = QtGui.QFontMetrics(font)
        text = metrics.elidedText(
            detail, QtCore.Qt.TextElideMode.ElideRight, low.width()
        )
        painter.drawText(low, QtCore.Qt.AlignmentFlag.AlignVCenter, text)
        painter.restore()


