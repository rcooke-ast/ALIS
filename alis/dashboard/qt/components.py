    def owns(self, widget):
        """Whether a widget is one of the panels, or inside one."""
        if not isinstance(widget, QtWidgets.QWidget) or not self.isVisible():
            return False
        return any(w is widget or w.isAncestorOf(widget) for w in self.panel_widgets)

    def _escape_pressed(self):
        """Esc: an armed button waits no more; else the selection is cleared."""
        if self.armed() or self.armed(INTERLOPER):
            self._disarm()
        elif self.selected is not None:
            self.select(None)

    def armed(self, name="components.add_component"):
        """Whether + Add component (or Add interloper…) waits for a click."""
        action = self.actions_.get(name)
        return action is not None and action.isChecked()

    def _show_armed(self):
        cursor = (
            QtCore.Qt.CursorShape.CrossCursor
            if self.armed() or self.armed(INTERLOPER)
            else QtCore.Qt.CursorShape.ArrowCursor
        )
        for widget in self.panel_widgets:
            widget.view.viewport().setCursor(cursor)

    def _disarm(self, *names):
        for name in names or ("components.add_component", INTERLOPER):
            action = self.actions_.get(name)
            if action is not None and action.isChecked():
                action.setChecked(False)
        self._show_armed()

    def do_add_component(self):
        """+ Add component: the next click in a panel adds one (Esc cancels)."""
        if self.armed():
            self._disarm(INTERLOPER)
        self._show_armed()

    def do_add_interloper(self):
        """Add interloper…: the next click in a panel offers its choices (S14)."""
        if self.armed(INTERLOPER):
            self._disarm("components.add_component")
        self._show_armed()

