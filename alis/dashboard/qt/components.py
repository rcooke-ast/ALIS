class DragKeys(QtCore.QObject):
    """
    The keys held during a drag (Q5.23): N keeps b as it is, B keeps log N. Pressed
    while the pointer is over a panel, or a panel has the focus, they are the
    panel's, and nothing else receives them.

    Generated by RJC and Claude.
    """

    KEYS = {QtCore.Qt.Key.Key_N: "n", QtCore.Qt.Key.Key_B: "b"}

    def __init__(self, tab):
        super().__init__(tab)
        self.tab = tab
        self.held = set()

    def eventFilter(self, obj, event):
        kind = event.type()
        if kind == QtCore.QEvent.Type.ApplicationDeactivate:
            self.held.clear()
            return False
        if kind not in (QtCore.QEvent.Type.KeyPress, QtCore.QEvent.Type.KeyRelease):
            return False
        name = self.KEYS.get(event.key())
        mods = QtCore.Qt.KeyboardModifier
        if name is None or event.modifiers() & (
            mods.ControlModifier | mods.AltModifier | mods.MetaModifier
        ):
            return False
        if kind == QtCore.QEvent.Type.KeyRelease:
            if name in self.held and not event.isAutoRepeat():
                self.held.discard(name)
                return True
            return name in self.held
        if name in self.held:
            return True
        pointer = QtWidgets.QApplication.widgetAt(QtGui.QCursor.pos())
        if self.tab.owns(obj) or self.tab.owns(pointer):
            self.held.add(name)
            return True
        return False


