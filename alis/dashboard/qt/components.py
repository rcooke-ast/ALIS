    def _draw_panel(self, widget, curve, system, ion):
        """One panel: the data and the model over the continuum, and its ticks."""
        project = self.session.project
        panel = widget.panel
        snip = panel.snip
        pix = snip.pixels
        view = widget.view
        widget.curve = curve
        cont = curve.continuum if curve is not None else CO.evaluate(project, snip)
        view.set_data(panel.velocity, pix.flux, pix.error, pix.bad)
        view.set_normalised(cont)
        if curve is not None:
            view.set_model(panel.velocity, curve.model)
            widget.resid.set_residuals(panel.velocity, curve.residuals)
        view.set_regions("fit", panel.regions)
        self._draw_overlays(widget, system, ion)

    def _draw_overlays(self, widget, system, ion):
        """A panel's ticks, the selected component's highlighted."""
        project = self.session.project
        panel = widget.panel
        half = self.half_range()
        if ion == FOREST:
            ticks = C.forest_ticks(project, panel, half, self._linked)
        else:
            ticks = C.panel_ticks(project, system, ion, panel, half, self._linked)
        comp = self.selected_component()
        # Many components in a panel: only the selected one is labelled
        labelled = [t for t in ticks if t.key[0] == "component" and t.label]
        crowded = len(labelled) > CROWDED
        # Many other lines (the forest, at a wide range): they go unlabelled too
        locked = [t for t in ticks if t.key[0] == "line" and t.label]
        busy = crowded or len(locked) > CROWDED
        drawn = []
        moves = {}
        for tick in ticks:
            item = {
                "x": tick.x,
                "label": tick.label,
                "kind": tick.kind,
                "key": tick.key,
            }
            if tick.key[0] == "component":
                item["selected"] = comp is not None and tick.key[1] == comp.id
                # A component's own tick moves its z; not where it is excluded, nor
                # when a link computes its z (Q5.9)
                if tick.key not in moves:
                    owner = self._component_of(tick.key)
                    moves[tick.key] = owner is not None and C.draggable(owner)["z"]
                item["movable"] = tick.kind == "own" and moves[tick.key]
                if crowded and not item["selected"]:
                    item["label"] = ""
            elif busy:
                item["label"] = ""
            drawn.append(item)
        widget.view.set_ticks(drawn)

