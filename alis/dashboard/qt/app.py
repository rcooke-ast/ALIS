"""The dashboard's application, as the ``alis`` command starts it (F14).

Dashboard Stage 3.4. ``alis [path]`` gives :func:`run` a
:class:`~alis.dashboard.session.Target`: the start page, a project to open, or a fit
to import.

Generated by RJC and Claude.
"""

import sys

from qtpy import QtWidgets

from alis.dashboard import preferences as PR
from alis.dashboard.qt import style
from alis.dashboard.qt import window as WN


def make_application(argv=None):
    """
    The Qt application, with the dashboard's look (one per process).

    Generated by RJC and Claude.
    """
    app = QtWidgets.QApplication.instance()
    if app is None:
        app = QtWidgets.QApplication(list(argv or sys.argv[:1]))
    app.setApplicationName(WN.TITLE)
    app.setOrganizationName("ALIS")
    style.apply(app)
    return app


def open_window(target, prefs=None, folder=None, registry=None):
    """
    The main window, showing what the command was given.

    Generated by RJC and Claude.
    """
    window = WN.MainWindow(prefs or PR.Preferences.load(folder), folder, registry)
    window.show()
    window.launch(target)
    return window


def run(target):
    """
    Start the dashboard and wait until it is closed.

    Parameters
    ----------
    target : Target

    Returns
    -------
    int
        The exit status.

    Generated by RJC and Claude.
    """
    app = make_application()
    window = open_window(target)
    status = app.exec()
    del window
    return status


__all__ = ["make_application", "open_window", "run"]
