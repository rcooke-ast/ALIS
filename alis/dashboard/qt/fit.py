    def _fill_run_box(self):
        project = self.session.project
        prefs = self.prefs()
        used = ST.computer_used(project, prefs) if prefs is not None else {}
        notes = []
        for name, (widget, label, pref) in self.computer.items():
            value, from_model = used.get(name, (str(self._pref(pref)), False))
            widget.blockSignals(True)
            if isinstance(widget, QtWidgets.QComboBox):
                index = widget.findText(str(value))
                if index < 0:
                    widget.addItem(str(value))
                    index = widget.count() - 1
                widget.setCurrentIndex(index)
            else:
                try:
                    widget.setValue(int(float(value)))
                except ValueError:
                    pass
            widget.blockSignals(False)
            widget.setEnabled(not from_model)
            setting = "{0} {1}".format(*name)
            if from_model:
                tip = (
                    "The model sets '{0} {1}', which is used. Return it to its default"
                    " (✕ below) to use this computer's setting.".format(setting, value)
                )
                notes.append("The model's own {0} is used.".format(setting))
            else:
                tip = PF.SPEC[pref].help
            widget.setToolTip(tip)
            label.setToolTip(tip)
        self.computer_note.setText(" ".join(notes))
        self.computer_note.setVisible(bool(notes))
        self._fill_settings()
        self._fill_preflight()

    def _computer_changed(self, *args):
        """Backend, CPUs or GPUs changed: a preference of this computer."""
        prefs = self.prefs()
        if self._filling or prefs is None:
            return
        for widget, _, pref in self.computer.values():
            if not widget.isEnabled():
                continue
            if isinstance(widget, QtWidgets.QComboBox):
                value = widget.currentText()
            else:
                value = widget.value()
            try:
                prefs.set(pref, value)
            except PF.PreferenceError as err:
                self._warn("Preferences", str(err))
                return
        try:
            prefs.save()
        except OSError as err:
            self._warn("Preferences", "The preferences cannot be saved: " + str(err))
        self._report_key = None
        self._fill_preflight()
        if self.main is not None:
            self.main.refresh_markers()

    def _clear_settings(self):
        while self.settings_grid.count():
            widget = self.settings_grid.takeAt(0).widget()
            if widget is not None:
                widget.hide()
                widget.setParent(None)
                widget.deleteLater()
        self.setting_rows = []

    def _fill_settings(self):
        """The settings the model changes, each edited in place or cleared (✕)."""
        self._clear_settings()
        changed = ST.changed(self.session.project)
        for row, item in enumerate(changed):
            setting = item.setting
            name = QtWidgets.QLabel(setting.name)
            tip = "{0} ALIS's default: {1}.".format(setting.help, setting.default_text)
            name.setToolTip(tip)
            edit = QtWidgets.QLineEdit(item.value)
            edit.setObjectName("setting_{0}_{1}".format(setting.section, setting.key))
            edit.setToolTip(tip)
            clear = QtWidgets.QToolButton()
            clear.setText("✕")
            clear.setAutoRaise(True)
            clear.setObjectName("clear_{0}_{1}".format(setting.section, setting.key))
            clear.setToolTip(
                "Return to ALIS's default ({0}): the line is removed".format(
                    setting.default_text
                )
            )
            if (setting.section, setting.key) == ("run", "blind"):
                # Only Model → Unblind… takes blinding away
                edit.setReadOnly(True)
                clear.setEnabled(False)
                edit.setToolTip("Only Model → Unblind… changes it.")
            edit.editingFinished.connect(
                lambda i=item, e=edit: self._setting_typed(i, e)
            )
            clear.clicked.connect(lambda _=False, i=item: self._setting_cleared(i))
            self.settings_grid.addWidget(name, row, 0)
            self.settings_grid.addWidget(edit, row, 1)
            self.settings_grid.addWidget(clear, row, 2)
            self.setting_rows.append((item, edit, clear))
        if not changed:
            label = W.muted("None: ALIS's defaults are used.")
            self.settings_grid.addWidget(label, 0, 0, 1, 3)

    def _setting_typed(self, item, edit):
        """A setting's value typed in place: one step."""
        if self._filling or edit.isReadOnly():
            return
        text = edit.text().strip()
        if text == item.value.strip():
            return
        setting = item.setting

        def do():
            try:
                step = ST.set_step(
                    self.session.project, setting.section, setting.key, text
                )
            except ST.SettingError as err:
                edit.setText(item.value)
                self._warn("Settings", str(err))
                return
            self.session.history.do(step)

        self._act("fit.setting", do)

    def _setting_cleared(self, item):
        """✕: the setting returned to ALIS's default (its lines removed), one step."""
        setting = item.setting

        def do():
            step = ST.clear_step(self.session.project, setting.section, setting.key)
            if step is not None:
                self.session.history.do(step)

        self._act("fit.clear_setting", do)

    def show_all_settings(self):
        """
        All settings…: every setting of ALIS; what is changed there is one step.

        Generated by RJC and Claude.
        """
        project = self.session.project
        project.require_reading()
        dialog = D.AllSettingsDialog(project, self.prefs(), self)
        if not self.main.run_dialog(dialog):
            return
        changes = dialog.changes()
        if not changes:
            return
        history = self.session.history
        text = "Change {0} setting{1}".format(
            len(changes), "" if len(changes) == 1 else "s"
        )
        with history.group(text):
            for section, key, value in changes:
                if value is None:
                    step = ST.clear_step(project, section, key)
                else:
                    step = ST.set_step(project, section, key, value)
                if step is not None:
                    history.do(step)

    # -- the pre-flight check (S17) -------------------------------------------------

    def _report_state(self, project):
        """What the pre-flight check depends on: the model, the files, the
        preferences, and the validator's problems."""
        prefs = self.prefs()
        values = (
            tuple(
                prefs[k] for k in ("fit.backend", "fit.ncpus", "fit.ngpus", "fit.low_b")
            )
            if prefs is not None
            else ()
        )
        problems = getattr(getattr(self.main, "panel", None), "problems", None) or []
        return (
            CO._state_key(project),
            values,
            tuple((p.line, p.message) for p in problems),
        )

    def check(self):
        """
        The pre-flight check of the project as it stands, kept until the project,
        the preferences or the validator's problems change.

        Generated by RJC and Claude.
        """
        project = self.session.project
        key = self._report_state(project)
        if key != self._report_key or self.report is None:
            panel = getattr(self.main, "panel", None)
            problems = panel.problems if panel is not None else None
            self.report = PC.check(project, self.prefs(), problems)
            self._report_key = key
        return self.report

    def report_for(self, project):
        """The pre-flight check's report, when it is that of the project as it is
        now; else None (the Fit marker uses it)."""
        if self.report is None or self.session is None:
            return None
        if self.session.project is not project:
            return None
        if self._report_state(project) != self._report_key:
            return None
        return self.report

    def set_report(self, report):
        """The report of the check that Run made (the window)."""
        self.report = report
        if self.session is not None:
            self._report_key = self._report_state(self.session.project)
        self._fill_preflight(check=False)

    def _fill_preflight(self, check=True):
        report = self.check() if check else self.report
        if report is None:
            return
        kind = "refuse" if not report.ok else ("note" if report.notes else "ok")
        icon = {"refuse": "✕", "note": "!", "ok": "✓"}[kind]
        colour = {
            "refuse": STY.OKABE_ITO["vermillion"],
            "note": STY.OKABE_ITO["orange"],
            "ok": STY.OKABE_ITO["blue"],
        }[kind]
        text = html.escape(report.summary())
        if report.findings:
            shown = self.findings.isVisible()
            text = '{0} <a href="findings">{1}</a>'.format(
                text, "hide" if shown else "show"
            )
        self.preflight.setText(
            '<span style="color:{0}; font-weight:600;">{1}</span> {2}'.format(
                colour, icon, text
            )
        )
        self.preflight.setProperty("kind", kind)
        self.findings.clear()
        for finding in report.refusals + report.notes:
            mark = "✕" if finding.kind == PC.REFUSE else "•"
            item = QtWidgets.QListWidgetItem("{0} {1}".format(mark, finding.message))
            item.setData(ROLE, (finding.line, finding.snip))
            where = []
            if finding.line is not None:
                where.append("line {0}".format(finding.line + 1))
            if finding.snip:
                where.append("snip " + finding.snip)
            item.setToolTip(
                "Click to show " + " and ".join(where) if where else finding.message
            )
            self.findings.addItem(item)
        if not report.findings:
            self.findings.setVisible(False)

    def _toggle_findings(self):
        self.findings.setVisible(not self.findings.isVisible())
        self._fill_preflight(check=False)

