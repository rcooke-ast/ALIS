    def _curves(self, found):
        """
        The curves of the panels' snips, by data line index, for the model shown;
        and a note when they cannot be drawn.

        Generated by RJC and Claude.
        """
        project = self.session.project
        if self.mode == FV.FINAL:
            try:
                return self.shown.curves(), ""
            except RS.ResultsError as err:
                return {}, self.gate.message(str(err))
        try:
            profile = PR.of(project)
            return profile.evaluate(snips=[p.snip.data.index for p in found]), ""
        except PR.ProfileError as err:
            return {}, self.gate.message(str(err))

    def _fill_panels(self):
        """
        The panels of the View menu's choice, with the model shown.

        Generated by RJC and Claude.
        """
        self._clear_panels()
        if self.session is None:
            return
        project = self.session.project
        choice = self.choice()
        found = FV.panels(project, choice, self.axis())
        curves, note = self._curves(found)
        single = choice.kind == FV.SNIP or len(found) == 1
        ncol = 1 if single else max(1, min(self.columns(), len(found)))
        self.columns_box.setEnabled(not single)
        self.columns_label.setEnabled(not single)
        notes = [note] if note else []
        if not found:
            notes.append("No snip to show.")
        for num, panel in enumerate(found):
            widget = InspectPanel(panel)
            if single:
                widget.resid.setFixedHeight(70)
            self._draw_panel(widget, curves.get(panel.snip.data.index))
            self.grid.addWidget(widget, num // ncol, num % ncol)
            self.panel_widgets.append(widget)
        for col in range(4):
            self.grid.setColumnStretch(col, 1 if col < ncol else 0)
        nrows = (len(found) + ncol - 1) // ncol
        for row in range(max(self.grid.rowCount(), nrows + 1)):
            self.grid.setRowStretch(row, 0)
        # One snip fills the view; several keep their height, and scroll
        self.grid.setRowStretch(0 if single else nrows, 1)
        for num, widget in enumerate(self.panel_widgets):
            widget.view.set_labels(top=False, bottom=num // ncol == nrows - 1)
        self.panel_note.setText("  ·  ".join(notes))
        self.panel_note.setVisible(bool(notes))
        self._fill_shown()
        if self.panel_widgets:
            link = choice.kind in (FV.ION, FV.FOREST) and self.axis() == FV.VELOCITY
            self.zoom.attach(*[w.view for w in self.panel_widgets], link=link)
            for widget in self.panel_widgets:
                if link:
                    # One ion's panels share the Components tab's velocity range
                    half = self.half_range()
                    _, yrange = widget.view._home or (None, None)
                    widget.view.set_home((-half, half), yrange)
                widget.view.home()
            self.zoom.remember()
        self._drawn_at = time.time()

    def _fill_shown(self):
        """What the panels show, and the notice of the fit in progress."""
        job = self.running()
        if self.mode == FV.FINAL and self.shown is not None:
            self.shown_label.setText("Final · " + self.shown.name)
        else:
            self.shown_label.setText(INITIAL_TITLE)
        if job is not None and self.mode == FV.FINAL:
            self.notice.show_message(FV.notice_text(job), "info")
        else:
            self.notice.clear()

    def _draw_panel(self, widget, curve):
        """
        One panel: the data over the shown model's continuum, the model, the regions,
        the residuals, the ticks and the marks.

        Generated by RJC and Claude.
        """
        project = self.session.project
        panel = widget.panel
        snip = panel.snip
        pix = snip.pixels
        view = widget.view
        widget.curve = curve
        final = self.mode == FV.FINAL
        if curve is not None and curve.wave.size == pix.wave.size:
            wave, flux, error, bad = curve.wave, curve.flux, curve.error, pix.bad
        elif curve is not None:
            wave, flux, error, bad = curve.wave, curve.flux, curve.error, None
        else:
            wave, flux, error, bad = pix.wave, pix.flux, pix.error, pix.bad
        x = panel.x(wave)
        if curve is not None:
            cont = curve.continuum
        else:
            cont = CO.evaluate(project, snip, wave=wave)
        view.set_data(x, flux, error, bad)
        view.set_normalised(cont)
        if curve is not None:
            view.set_model(x, curve.model)
            # Grey bands where the pixels are not fitted (RJC's review); their
            # residuals drawn or not, as chosen
            counted = RS.counted(curve)
            resid = curve.residuals
            if self.residuals_shown() == FV.FITTED_PIXELS:
                resid = np.where(counted, resid, np.nan)
            widget.resid.set_residuals(x, resid)
            widget.resid.set_unfitted(FV.unfitted_spans(x, counted))
        else:
            view.set_model(None, None)
            widget.resid.set_residuals(None, None)
            widget.resid.set_unfitted([])
        view.set_regions("fit", panel.regions())
        view.set_ticks(self._ticks(panel, final))
        model = self.shown.model if final and self.shown is not None else project
        quality = None
        if curve is not None:
            nsig = float(model.parsed.argflag["out"]["reportsig"])
            quality = RS.quality(curve, nsig)
        if quality is None:
            note = FV.NOT_FITTED if final and curve is None else FV.NO_PIXELS
            widget.marks.setText(marks_html(None, note))
        else:
            widget.marks.setText(marks_html(quality))
        view.set_home(panel.home(), NORMALISED_Y if cont is not None else None)

    def _ticks(self, panel, final):
        """A panel's ticks, labelled unless crowded."""
        try:
            found = FV.ticks(self.session.project, panel, self.shown if final else None)
        except (PR.ProfileError, RS.ResultsError):
            return []
        own = [t for t in found if t["key"][0] == "component" and t["label"]]
        others = [t for t in found if t["key"][0] != "component" and t["label"]]
        crowded = len(own) > CROWDED
        busy = crowded or len(others) > CROWDED
        for tick in found:
            if (tick["key"][0] == "component" and crowded) or (
                tick["key"][0] != "component" and busy
            ):
                tick["label"] = ""
        return found

    # -- the chips (S18, D39) -------------------------------------------------------

    def _clear_chips(self):
        while self.chip_layout.count():
            item = self.chip_layout.takeAt(0)
            widget = item.widget() if item is not None else None
            if widget is not None:
                widget.hide()
                widget.setParent(None)
                widget.deleteLater()
        self.chip_widgets = []

    def _fill_chips(self):
        """A chip per snip, with the marks of the model the panels draw."""
        self._clear_chips()
        if self.session is None:
            return
        choice = self.choice()
        initial = self.mode == FV.INITIAL
        for chip in FV.chips(self.session.project, self.shown, initial=initial):
            widget = Chip(chip, choice.kind == FV.SNIP and chip.key == choice.key)
            widget.clicked.connect(self.show_choice)
            self.chip_layout.addWidget(widget)
            self.chip_widgets.append(widget)

    # -- the fit in progress (Q6.15) ------------------------------------------------

    def progressed(self, job):
        """
        The run has reported: its progress drawn; the fit in progress redrawn when
        it is shown, no sooner than the last drawing allows (a fast fit skips
        iterations rather than falling behind).

        Generated by RJC and Claude.
        """
        if self.session is None or not self._visible():
            return
        self._fill_progress()
        if self.mode == FV.FINAL:
            self._fill_shown()
        if self.state.get("model", FV.FINAL) != FV.FINAL or job.values is None:
            return
        if self._redraw_timer.isActive():
            return
        wait = max(REDRAW, 2000.0 * self._cost)
        due = self._drawn_at * 1000.0 + wait - time.time() * 1000.0
        self._redraw_timer.start(int(max(due, 0)))

    def _redraw_progress(self):
        """Draw the fit in progress in the panels and chips, keeping their zoom."""
        job = self.running()
        if job is None or self.session is None:
            return
        start = time.time()
        try:
            view = RS.View(self.session.project, run=job)
        except RS.ResultsError:
            return
        if not view.has_best_fit:
            return
        first = self.mode != FV.FINAL
        self.shown = view
        self.mode = self._mode(view)
        if self.mode != FV.FINAL:
            return
        if first or not self.panel_widgets:
            self._filling = True
            try:
                self._fill_toggles()
            finally:
                self._filling = False
            self._fill_panels()
        else:
            try:
                curves = view.curves()
            except RS.ResultsError:
                curves = {}
            for widget in self.panel_widgets:
                self._draw_panel(widget, curves.get(widget.panel.snip.data.index))
            # Drawn now: no note says it is not
            self.panel_note.setText("")
            self.panel_note.setVisible(False)
            self._fill_shown()
        self._fill_chips()
        self._cost = time.time() - start
        self._drawn_at = time.time()


