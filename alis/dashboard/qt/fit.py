    # -- acting ---------------------------------------------------------------------------

    def _act(self, name, handler):
        """Run a handler through the window (typing read first, errors reported)."""
        if self.main is not None:
            self.main._run(name, handler)
        else:
            handler()

    def _warn(self, title, text):
        if self.main is not None:
            self.main.tell(title, text, "warning")

    def prefs(self):
        """The user's preferences, or None (the defaults)."""
        return getattr(self.main, "prefs", None)

    def _pref(self, key):
        prefs = self.prefs()
        try:
            return prefs[key] if prefs is not None else PF.SPEC[key].default
        except KeyError:
            return PF.SPEC[key].default

    def job(self):
        """The run going for this project, or the one that has just ended, or None."""
        fit = getattr(self.main, "fit", None)
        if fit is None or fit.job is None or fit.session is not self.session:
            return None
        return fit.job

    def running(self):
        """The run going for this project, or None."""
        fit = getattr(self.main, "fit", None)
        if fit is None or not fit.active or fit.session is not self.session:
            return None
        return fit.job

    # -- the state ----------------------------------------------------------------------

    def _visible(self):
        """Whether the sub-tab is on the screen."""
        if self.main is None:
            return True
        if self.main.tabs.currentWidget() is not self.holder:
            return False
        return self.holder is None or self.holder.subtabs.currentWidget() is self

    def _remember(self):
        """Keep what the sub-tab shows in the view state (saved with the project)."""
        if self.session is not None:
            data = {k: self.state[k] for k in VIEW_KEYS if k in self.state}
            self._seen = dict(data)
            self.session.set_view("fit", data)

