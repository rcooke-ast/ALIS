    # -- the panels -----------------------------------------------------------------

    def _clear_panels(self):
        for widget in self.panel_widgets:
            self.grid.removeWidget(widget)
            widget.hide()
            widget.setParent(None)
            widget.deleteLater()
        self.panel_widgets = []

    def _curves(self, found):
        """
        The curves of the panels' snips, by data line index, for the model shown;
        and a note when they cannot be drawn.

        Generated by RJC and Claude.
        """
        project = self.session.project
        if self.mode == FV.FINAL:
            try:
                return self.shown.curves(), ""
            except RS.ResultsError as err:
                return {}, self.gate.message(str(err))
        try:
            profile = PR.of(project)
            return profile.evaluate(snips=[p.snip.data.index for p in found]), ""
        except PR.ProfileError as err:
            return {}, self.gate.message(str(err))

    def _fill_panels(self):
        """
        The panels of the View menu's choice, with the model shown.

        Generated by RJC and Claude.
        """
        self._clear_panels()
        if self.session is None:
            return
        project = self.session.project
        choice = self.choice()
        found = FV.panels(project, choice, self.axis())
        curves, note = self._curves(found)
        single = choice.kind == FV.SNIP or len(found) == 1
        ncol = 1 if single else max(1, min(self.columns(), len(found)))
        self.columns_box.setEnabled(not single)
        self.columns_label.setEnabled(not single)
        notes = [note] if note else []
        if not found:
            notes.append("No snip to show.")
        for num, panel in enumerate(found):
            widget = InspectPanel(panel)
            if single:
                widget.resid.setFixedHeight(70)
            self._draw_panel(widget, curves.get(panel.snip.data.index))
            self.grid.addWidget(widget, num // ncol, num % ncol)
            self.panel_widgets.append(widget)
        for col in range(4):
            self.grid.setColumnStretch(col, 1 if col < ncol else 0)
        nrows = (len(found) + ncol - 1) // ncol
        for row in range(max(self.grid.rowCount(), nrows + 1)):
            self.grid.setRowStretch(row, 0)
        # One snip fills the view; several keep their height, and scroll
        self.grid.setRowStretch(0 if single else nrows, 1)
        for num, widget in enumerate(self.panel_widgets):
            widget.view.set_labels(top=False, bottom=num // ncol == nrows - 1)
        self.panel_note.setText("  ·  ".join(notes))
        self.panel_note.setVisible(bool(notes))
        self._fill_shown()
        if self.panel_widgets:
            link = choice.kind in (FV.ION, FV.FOREST) and self.axis() == FV.VELOCITY
            self.zoom.attach(*[w.view for w in self.panel_widgets], link=link)
            for widget in self.panel_widgets:
                if link:
                    # One ion's panels share the Components tab's velocity range
                    half = self.half_range()
                    _, yrange = widget.view._home or (None, None)
                    widget.view.set_home((-half, half), yrange)
                widget.view.home()
            self.zoom.remember()
        self._drawn_at = time.time()

    def _fill_shown(self):
        """What the panels show, and the notice of the fit in progress."""
        job = self.running()
        if self.mode == FV.FINAL and self.shown is not None:
            self.shown_label.setText("Final · " + self.shown.name)
        else:
            self.shown_label.setText(INITIAL_TITLE)
        if job is not None and self.mode == FV.FINAL:
            self.notice.show_message(FV.notice_text(job), "info")
        else:
            self.notice.clear()

    def _draw_panel(self, widget, curve):
        """
        One panel: the data over the shown model's continuum, the model, the regions,
        the residuals, the ticks and the marks.

        Generated by RJC and Claude.
        """
        project = self.session.project
        panel = widget.panel
        snip = panel.snip
        pix = snip.pixels
        view = widget.view
        widget.curve = curve
        final = self.mode == FV.FINAL
        if curve is not None and curve.wave.size == pix.wave.size:
            wave, flux, error, bad = curve.wave, curve.flux, curve.error, pix.bad
        elif curve is not None:
            wave, flux, error, bad = curve.wave, curve.flux, curve.error, None
        else:
            wave, flux, error, bad = pix.wave, pix.flux, pix.error, pix.bad
        x = panel.x(wave)
        if curve is not None:
            cont = curve.continuum
        else:
            cont = CO.evaluate(project, snip, wave=wave)
        view.set_data(x, flux, error, bad)
        # Normalised, or as they are with the continuum drawn (item 10 of Stage 7)
        raw = self.scale_shown() == FV.CONTINUUM
        view.set_normalised(None if raw else cont)
        if raw and cont is not None:
            view.set_continuum(x, cont)
        else:
            view.set_continuum(None, None)
        if curve is not None:
            view.set_model(x, curve.model)
            # Grey bands where the pixels are not fitted (RJC's review); their
            # residuals drawn or not, as chosen
            counted = RS.counted(curve)
            resid = curve.residuals
            if self.residuals_shown() == FV.FITTED_PIXELS:
                resid = np.where(counted, resid, np.nan)
            widget.resid.set_residuals(x, resid)
            widget.resid.set_unfitted(FV.unfitted_spans(x, counted))
        else:
            view.set_model(None, None)
            widget.resid.set_residuals(None, None)
            widget.resid.set_unfitted([])
        view.set_regions("fit", panel.regions())
        view.set_ticks(self._ticks(panel, final))
        model = self.shown.model if final and self.shown is not None else project
        quality = None
        if curve is not None:
            nsig = float(model.parsed.argflag["out"]["reportsig"])
            quality = RS.quality(curve, nsig)
        if quality is None:
            note = FV.NOT_FITTED if final and curve is None else FV.NO_PIXELS
            widget.marks.setText(marks_html(None, note))
        else:
            widget.marks.setText(marks_html(quality))
        marked = self._draw_review(widget, curve, final)
        yrange = NORMALISED_Y if cont is not None and not raw else None
        if yrange is not None and marked is not None and np.isfinite(marked).any():
            # The marked pixels are within the panel's range, while they are reviewed
            low, high = np.nanmin(marked), np.nanmax(marked)
            span = 0.05 * (max(high, yrange[1]) - min(low, yrange[0]))
            yrange = (min(yrange[0], low - span), max(yrange[1], high + span))
        view.set_home(panel.home(), yrange)

    def _ticks(self, panel, final):
        """A panel's ticks, labelled unless crowded."""
        try:
            found = FV.ticks(self.session.project, panel, self.shown if final else None)
        except (PR.ProfileError, RS.ResultsError):
            return []
        own = [t for t in found if t["key"][0] == "component" and t["label"]]
        others = [t for t in found if t["key"][0] != "component" and t["label"]]
        crowded = len(own) > CROWDED
        busy = crowded or len(others) > CROWDED
        for tick in found:
            if (tick["key"][0] == "component" and crowded) or (
                tick["key"][0] != "component" and busy
            ):
                tick["label"] = ""
        return found

    # -- Review clipped pixels (S29, D27, Q6.11) ------------------------------------

    def _state_now(self):
        """What a review of clipped pixels is made for: the model and the shown run."""
        record = self.holder.shown_record() if self.holder is not None else None
        return (
            CO._state_key(self.session.project),
            None if record is None else record.prefix,
            None if record is None else record.info.get("finished"),
        )

    def review_outliers(self):
        """
        Review clipped pixels… (S29, D27, Q6.11): the fitted pixels whose residual
        from the shown best fit is beyond the preference (5σ) are marked on the
        panels; lone pixels and pairs are ticked (✕), three or more in a row are not
        (○: they may be absorption the model misses). A click on one ticks or
        unticks it; each panel has Accept all and Reject all. Nothing leaves the fit
        until Apply.

        Generated by RJC and Claude.
        """
        if self.session is None:
            return
        if self.running() is not None:
            self._warn(
                "Review clipped pixels", "Wait for the fit to end, or stop it, first."
            )
            return
        self.refresh(self.session)
        if self.shown is None:
            self._warn("Review clipped pixels", NO_RUN)
            return
        threshold = self._pref("fit.outlier_sigma")
        try:
            found = RS.outliers(
                self.shown.curves(), self.session.project, threshold, self.prefs()
            )
        except RS.ResultsError as err:
            self._warn("Review clipped pixels", self.gate.message(str(err)))
            return
        if not found:
            if self.main is not None:
                self.main.tell(
                    "Review clipped pixels",
                    "No fitted pixel is beyond {0:g}σ of the best fit of {1}.".format(
                        threshold, self.shown.name
                    ),
                )
            return
        self.review = {i: [out, out.ticked.copy()] for i, out in found.items()}
        self._review_key = self._state_now()
        if self.mode != FV.FINAL:
            self.state["model"] = FV.FINAL
            self._remember()
            self._filling = True
            try:
                self._fill_toggles()
            finally:
                self._filling = False
        self._fill_review_banner()
        self._fill_panels()

    def _fill_review_banner(self):
        if not self.review:
            self.review_banner.clear()
            return
        total = sum(out.count for out, _ in self.review.values())
        ticked = sum(int(np.count_nonzero(t)) for _, t in self.review.values())
        threshold = self._pref("fit.outlier_sigma")
        self.review_banner.show_message(
            "Review clipped pixels: {0} fitted pixel{1} beyond {2:g}σ of the best fit,"
            " in {3} snip{4}. Apply leaves the {5} ticked (✕) out of the fit; three or"
            " more in a row are not ticked (○), since they may be absorption the model"
            " misses. Click a pixel to tick or untick it.".format(
                total,
                "" if total == 1 else "s",
                threshold,
                len(self.review),
                "" if len(self.review) == 1 else "s",
                ticked,
            ),
            "info",
            [
                ("Apply", lambda: self._act("fit.apply_outliers", self.apply_review)),
                ("Cancel", self.end_review),
            ],
        )

    def _draw_review(self, widget, curve, final):
        """A panel's marked pixels, while the review goes; their heights, or None."""
        index = widget.panel.snip.data.index
        entry = (self.review or {}).get(index) if final else None
        shown = entry is not None and curve is not None
        widget.accept_all.setVisible(shown)
        widget.reject_all.setVisible(shown)
        if not shown:
            widget.view.set_marked(None)
            return None
        out, ticked = entry
        flux = curve.flux[out.pixels]
        if curve.continuum is not None:
            with np.errstate(divide="ignore", invalid="ignore"):
                flux = flux / curve.continuum[out.pixels]
        widget.view.set_marked(widget.panel.x(out.wave), flux, ticked)
        if getattr(widget, "reviewed", False):
            return flux
        widget.reviewed = True
        widget.view.markClicked.connect(lambda n, i=index: self.toggle_pixel(i, n))
        widget.accept_all.clicked.connect(
            lambda _=False, i=index: self.tick_all(i, True)
        )
        widget.reject_all.clicked.connect(
            lambda _=False, i=index: self.tick_all(i, False)
        )
        return flux

    def _redraw_review(self, index):
        for widget in self.panel_widgets:
            if widget.panel.snip.data.index == index:
                self._draw_review(widget, widget.curve, self.mode == FV.FINAL)
        self._fill_review_banner()

    def toggle_pixel(self, index, n):
        """A click on a marked pixel: tick or untick it."""
        if self.review and index in self.review:
            ticked = self.review[index][1]
            ticked[n] = not ticked[n]
            self._redraw_review(index)

    def tick_all(self, index, on):
        """Accept all (tick) or Reject all (untick) of one panel's marked pixels."""
        if self.review and index in self.review:
            self.review[index][1][:] = on
            self._redraw_review(index)

    def chosen_outliers(self):
        """The ticked pixels, by specid: their wavelengths."""
        out = {}
        for entry, ticked in (self.review or {}).values():
            waves = entry.wave[ticked]
            if waves.size:
                out.setdefault(entry.specid, []).extend(waves.tolist())
        return out

    def apply_review(self):
        """
        Apply: the ticked pixels left out of the fit, as Tweak dataset regions
        leaves pixels out, as one step that undo reverses; then Run is offered.

        Generated by RJC and Claude.
        """
        chosen = self.chosen_outliers()
        self.end_review()
        if not chosen:
            return
        step = RS.outliers_step(self.session.project, chosen)
        self.session.history.do(step)
        if self.main is None:
            return
        self.main.panel.redraw()
        choice = self.main.ask(
            "outliers_run",
            "Leave out outliers",
            "{0}. Run the fit again now, without them?".format(step.description),
            ["Run", "Later"],
            default="Run",
        )
        if choice == "Run":
            self.main.start_run()

    def end_review(self):
        """Cancel: the review is over, nothing is changed."""
        self.review, self._review_key = None, None
        self.review_banner.clear()
        for widget in self.panel_widgets:
            widget.view.set_marked(None)
            widget.accept_all.hide()
            widget.reject_all.hide()

    # -- the chips (S18, D39) -------------------------------------------------------

    def _clear_chips(self):
        while self.chip_layout.count():
            item = self.chip_layout.takeAt(0)
            widget = item.widget() if item is not None else None
            if widget is not None:
                widget.hide()
                widget.setParent(None)
                widget.deleteLater()
        self.chip_widgets = []

    def _fill_chips(self):
        """A chip per snip, with the marks of the model the panels draw."""
        self._clear_chips()
        if self.session is None:
            return
        choice = self.choice()
        initial = self.mode == FV.INITIAL
        for chip in FV.chips(self.session.project, self.shown, initial=initial):
            widget = Chip(chip, choice.kind == FV.SNIP and chip.key == choice.key)
            widget.clicked.connect(self.show_choice)
            self.chip_layout.addWidget(widget)
            self.chip_widgets.append(widget)

    # -- the fit in progress (Q6.15) ------------------------------------------------

    def progressed(self, job):
        """
        The run has reported: its progress drawn; the fit in progress redrawn when
        it is shown, no sooner than the last drawing allows (a fast fit skips
        iterations rather than falling behind).

        Generated by RJC and Claude.
        """
        if self.session is None or not self._visible():
            return
        self._fill_progress()
        if self.mode == FV.FINAL:
            self._fill_shown()
        if self.state.get("model", FV.FINAL) != FV.FINAL or job.values is None:
            return
        if self._redraw_timer.isActive():
            return
        wait = max(REDRAW, 2000.0 * self._cost)
        due = self._drawn_at * 1000.0 + wait - time.time() * 1000.0
        self._redraw_timer.start(int(max(due, 0)))

    def _redraw_progress(self):
        """Draw the fit in progress in the panels and chips, keeping their zoom."""
        job = self.running()
        if job is None or self.session is None:
            return
        start = time.time()
        try:
            view = RS.View(self.session.project, run=job)
        except RS.ResultsError:
            return
        if not view.has_best_fit:
            return
        first = self.mode != FV.FINAL
        self.shown = view
        self.mode = self._mode(view)
        if self.mode != FV.FINAL:
            return
        if first or not self.panel_widgets:
            self._filling = True
            try:
                self._fill_toggles()
            finally:
                self._filling = False
            self._fill_panels()
        else:
            try:
                curves = view.curves()
            except RS.ResultsError:
                curves = {}
            for widget in self.panel_widgets:
                self._draw_panel(widget, curves.get(widget.panel.snip.data.index))
            # Drawn now: no note says it is not
            self.panel_note.setText("")
            self.panel_note.setVisible(False)
            self._fill_shown()
        self._fill_chips()
        self._cost = time.time() - start
        self._drawn_at = time.time()


