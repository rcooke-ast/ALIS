    def _shown_view(self):
        """
        The run Final shows (Q6.5, Q6.15): the fit in progress while a run goes, or
        the latest run; and why there is none.

        Generated by RJC and Claude.
        """
        project = self.session.project
        job = self.running()
        if job is not None:
            try:
                return RS.View(project, run=job), ""
            except RS.ResultsError as err:
                return None, self.gate.message(str(err))
        record = R.latest(project.bundle)
        if record is None:
            return None, NO_RUN
        key = (
            record.prefix,
            record.bundle.members.get(record.prefix + "run.json"),
            CO._state_key(project),
        )
        view = self._views.get(key)
        if view is None:
            try:
                view = RS.View(project, record=record)
            except RS.ResultsError as err:
                return None, self.gate.message(str(err))
            self._views = {key: view}
        why = view.why_not()
        if why:
            return None, self.gate.message(why)
        return view, ""

