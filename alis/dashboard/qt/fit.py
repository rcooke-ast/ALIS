class ProgressChart(pg.PlotWidget):
    """
    χ² against iteration (D38): the run in colour, with a dot at its last
    iteration, and the run before it in grey; linear or log.

    Generated by RJC and Claude.
    """

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setBackground(STY.GREY["base"])
        item = self.getPlotItem()
        item.hideButtons()
        item.setMenuEnabled(False)
        item.setMouseEnabled(x=False, y=False)
        item.setLabel("bottom", "Iteration")
        item.setLabel("left", "χ²")
        for name in ("left", "bottom"):
            axis = item.getAxis(name)
            axis.setPen(pg.mkPen("#7a7a7a"))
            axis.setTextPen(pg.mkPen(STY.GREY["text"]))
            axis.enableAutoSIPrefix(False)
        self.previous = pg.PlotDataItem(pen=pg.mkPen("#a8a8a8", width=1.4))
        self.current = pg.PlotDataItem(pen=pg.mkPen(STY.OKABE_ITO["blue"], width=1.8))
        self.dot = pg.PlotDataItem(
            pen=None,
            symbol="o",
            symbolSize=7,
            symbolBrush=pg.mkBrush(STY.OKABE_ITO["blue"]),
            symbolPen=None,
        )
        for curve in (self.previous, self.current, self.dot):
            self.addItem(curve)
        self.log = False

    def set_progress(self, progress, log=False):
        """
        Draw a :class:`~alis.dashboard.fitview.Progress`.

        Generated by RJC and Claude.
        """
        self.log = bool(log)

        def arrays(points):
            if not points:
                return np.zeros(0), np.zeros(0)
            data = np.asarray(points, dtype=float)
            keep = np.isfinite(data[:, 1]) & ((data[:, 1] > 0) | (not self.log))
            return data[keep, 0], data[keep, 1]

        self.getPlotItem().setLogMode(y=self.log)
        x, y = arrays(progress.previous)
        self.previous.setData(x, y)
        x, y = arrays(progress.current)
        self.current.setData(x, y)
        self.dot.setData(x[-1:], y[-1:])
        self.getPlotItem().enableAutoRange()

    def drawn(self):
        """The points drawn: ``(current, previous)`` as lists of (x, y) (tests)."""
        out = []
        for curve in (self.current, self.previous):
            x, y = curve.getData()
            out.append([] if x is None else list(zip(x.tolist(), y.tolist())))
        return out


def _segment(texts, objects, tips):
    """Two or more exclusive toggles in a row (Linear | Log)."""
    holder = QtWidgets.QWidget()
    row = QtWidgets.QHBoxLayout(holder)
    row.setContentsMargins(0, 0, 0, 0)
    row.setSpacing(0)
    group = QtWidgets.QButtonGroup(holder)
    group.setExclusive(True)
    buttons = []
    for text, name, tip in zip(texts, objects, tips):
        button = QtWidgets.QToolButton()
        button.setText(text)
        button.setObjectName(name)
        button.setToolTip(tip)
        button.setCheckable(True)
        button.setAutoRaise(True)
        group.addButton(button)
        row.addWidget(button)
        buttons.append(button)
    holder.group = group
    return holder, buttons


def _choice_box(name, options):
    """
    A drop-down of exclusive choices (Velocity / Wavelength; RJC's review of Stage
    7), each ``(value, text, tip)``: the value is the item's data, and the tip its
    tooltip and, while it is chosen, the box's.

    Generated by RJC and Claude.
    """
    box = QtWidgets.QComboBox()
    box.setObjectName(name)
    box.setSizeAdjustPolicy(QtWidgets.QComboBox.SizeAdjustPolicy.AdjustToContents)
    for value, text, tip in options:
        box.addItem(text, value)
        box.setItemData(box.count() - 1, tip, TIP)

    def tip(index):
        box.setToolTip(box.itemData(index, TIP) or "")

    box.currentIndexChanged.connect(tip)
    tip(box.currentIndex())
    return box


