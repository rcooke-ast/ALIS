    # -- refreshing ---------------------------------------------------------------------

    def refresh(self, session):
        """
        Redraw the sub-tab from the project (after every step, undo and redo, and
        when a run ends); while it is not on the screen, only once it is.

        Generated by RJC and Claude.
        """
        if session is not self.session:
            self.state, self._seen = {}, None
            self.report, self._report_key = None, None
        self.session = session
        if session is None or session.project.paused:
            return
        if not self._visible():
            self._stale = True
            return
        self._stale = False
        stored = session.view.get("fit") or {}
        if stored != self._seen:
            self.state = {k: stored[k] for k in VIEW_KEYS if k in stored}
            self._seen = dict(stored)
        self.gate = BL.Gate(session.project)
        if self.review is not None and self._review_key != self._state_now():
            # The model or the shown run changed: the review is over
            self.end_review()
        self._filling = True
        try:
            self._fill_run_box()
            self._fill_menu()
            self._fill_toggles()
        finally:
            self._filling = False
        self._fill_progress()
        self._fill_panels()
        self._fill_chips()

    def _tab_shown(self, *args):
        if self._stale and self._visible():
            self.refresh(self.session)

