class FitRun(QtCore.QObject):
    """
    The run going: started by the window, its messages taken ten times a second,
    stopped or cancelled, and taken into the project when it ends.

    Signals
    -------
    progressed()
        A new iteration, a change of state (stopping, storing), or a second gone.
    ended(str)
        The run has ended, with its status (``runs.COMPLETED``, ``INTERRUPTED``,
        ``ERROR``, ``CANCELLED``…), and has been taken into the project.

    Generated by RJC and Claude.
    """

    progressed = QtCore.Signal()
    ended = QtCore.Signal(str)

    def __init__(self, parent=None):
        super().__init__(parent)
        self.job = None
        self.session = None
        self._tick = 0.0
        self._ended = True
        self.timer = QtCore.QTimer(self)
        self.timer.setInterval(POLL)
        self.timer.timeout.connect(self.poll)

    @property
    def active(self):
        """Whether a run is going."""
        return self.job is not None and not self._ended

    def start(self, session, settings, python=None, cwd=None, command=None):
        """
        Start a run of the session's project, as it stands.

        Parameters
        ----------
        session : Session
        settings : list of str
            Given on the run's command line (``settings.run_settings``).
        command : str, optional
            What ``run.json`` records as the command.

        Returns
        -------
        runs.Run

        Generated by RJC and Claude.
        """
        extra = {} if command is None else {"command": command}
        job = R.Run(session, settings=settings, python=python, cwd=cwd, **extra)
        return self.start_job(session, job)

    def start_job(self, session, job):
        """
        Start a job for the session (a run, or random restarts: ``runs.Restarts``).

        Generated by RJC and Claude.
        """
        self.job, self.session, self._ended = job, session, False
        job.start()
        self._tick = time.time()
        self.timer.start()
        self.progressed.emit()
        return job

    def stop(self):
        """Stop: end the fit at its current iteration; pressed again, Cancel."""
        if not self.active:
            return
        if self.job.stopping:
            self.cancel()
            return
        self.job.stop()
        self.progressed.emit()

    def cancel(self):
        """Cancel: end the process at once, keeping nothing (not while it stores)."""
        if self.active and self.job.cancel():
            self._end()

    def poll(self):
        """Take the run's messages; end it when it has ended."""
        job = self.job
        if job is None or self._ended:
            self.timer.stop()
            return
        messages = job.update()
        if job.finished:
            self._end()
            return
        now = time.time()
        if messages or now - self._tick >= 1.0:
            self._tick = now
            self.progressed.emit()

    def _end(self):
        """The run has ended: take it into the project, and say so."""
        self.timer.stop()
        self._ended = True
        job = self.job
        if job.status != R.CANCELLED and self.session is not None:
            job.take(self.session)
        self.ended.emit(job.status)

    def wait(self, timeout=600.0):
        """
        Wait for the run to end, the window still drawn (closing the dashboard with
        Stop).

        Returns
        -------
        bool
            Whether it ended.

        Generated by RJC and Claude.
        """
        start = time.time()
        while self.active and time.time() - start < timeout:
            QtWidgets.QApplication.processEvents(
                QtCore.QEventLoop.ProcessEventsFlag.AllEvents, 50
            )
            self.poll()
            if self.active:
                time.sleep(0.02)
        return not self.active

    def detach(self):
        """
        Leave the run going alone (closing the dashboard, Keep it running): it stores
        its result in the project's file, which shows it when next opened.

        Generated by RJC and Claude.
        """
        if self.active:
            self.timer.stop()
            self.job.process.detach()
        self.job, self.session, self._ended = None, None, True


