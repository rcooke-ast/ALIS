def marks_html(quality, note=""):
    """
    A snip's two marks, each with its colour and its icon (D39, D43), or the note
    that says why there are none.

    Generated by RJC and Claude.
    """
    if quality is None:
        return '<span style="color:{0};">{1}</span>'.format(
            STY.GREY["muted"], html.escape(note)
        )
    parts = []
    for text, mark in FV.mark_texts(quality):
        back, fore = STY.MARK_COLOURS[mark]
        parts.append(
            '<span style="background:{0}; color:{1};">&nbsp;{2} {3}&nbsp;</span>'.format(
                back, fore, html.escape(text), mark
            )
        )
    return "&nbsp;".join(parts)


