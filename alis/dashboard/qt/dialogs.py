class AskDialog(QtWidgets.QDialog):
    """
    A few values: each a line of text, or a number (a redshift, a FWHM).

    Parameters
    ----------
    title : str
    fields : list of tuple
        ``(key, label, value, kind)``: kind ``"text"`` or ``"number"``.
    action : str
        The OK button's text.

    Generated by RJC and Claude.
    """

    def __init__(self, title, fields, action="OK", note="", parent=None):
        super().__init__(parent)
        self.setWindowTitle(title)
        self.setMinimumWidth(380)
        form = QtWidgets.QFormLayout()
        self.edits = {}
        self.kinds = {}
        for key, label, value, kind in fields:
            edit = QtWidgets.QLineEdit("" if value is None else str(value))
            edit.textChanged.connect(self._update)
            form.addRow(label, edit)
            self.edits[key] = edit
            self.kinds[key] = kind
        layout = QtWidgets.QVBoxLayout(self)
        if note:
            hint = W.muted(note)
            hint.setWordWrap(True)
            layout.addWidget(hint)
        layout.addLayout(form)
        self.error = QtWidgets.QLabel("")
        self.error.setStyleSheet("color: #D55E00;")
        layout.addWidget(self.error)
        self.box = _buttons(self, action)
        layout.addWidget(self.box)
        self._update()

    def set(self, key, text):
        """Type a value (tests)."""
        self.edits[key].setText(text)

    def values(self):
        """The values, numbers as floats."""
        out = {}
        for key, edit in self.edits.items():
            text = edit.text().strip()
            if self.kinds[key] == "number":
                try:
                    out[key] = float(text)
                except ValueError:
                    out[key] = None
            else:
                out[key] = text
        return out

    def problem(self):
        """What stops the values being used, or ``""``."""
        for key, value in self.values().items():
            if self.kinds[key] == "number" and value is None:
                return "Type a number."
        return ""

    def _update(self):
        problem = self.problem()
        self.error.setText(problem)
        self.box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok).setEnabled(
            not problem
        )


