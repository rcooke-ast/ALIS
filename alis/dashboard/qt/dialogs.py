    # -- the spectra ----------------------------------------------------------------

    def run_spectrum_dialog(self, dialog):
        """Show a spectrum's dialog (tests answer it)."""
        return dialog.exec()

    def ask_spectrum(self, entry=None):
        """
        Add a spectrum, or change one, in its own dialog.

        Returns
        -------
        dict or None
            The spectrum, or None when cancelled.

        Generated by RJC and Claude.
        """
        dialog = SpectrumDialog(self.folder.text(), self.default_fwhm, entry, self)
        if not self.run_spectrum_dialog(dialog):
            return None
        new = dialog.entry()
        if entry is None:
            self.add_spectrum(new["path"], new["roles"], new["fwhm"])
        else:
            entry.update(new)
            self._fill()
        return new

    def add_spectrum(self, path, roles=None, fwhm=None):
        """
        Add a text spectrum to the table: its roles guessed when not given.

        Returns
        -------
        str
            What stops it being added, or ``""``.

        Generated by RJC and Claude.
        """
        path = os.path.abspath(path)
        if any(e["path"] == path for e in self.entries):
            return "This spectrum is in the list already."
        if MO.file_kind(path) != MO.ASCII:
            return "Only text (ascii) spectra can be added now."
        try:
            _, guessed, ncols, _ = MO.preview(path)
        except (MO.ModeError, OSError, ValueError) as err:
            return "The file cannot be read: {0}".format(err)
        roles = dict(roles) if roles is not None else guessed
        problem = MO.check_roles(roles, ncols)
        if problem:
            return problem
        fwhm = self.default_fwhm if fwhm is None else float(fwhm)
        self.entries.append({"path": path, "roles": roles, "fwhm": fwhm})
        self._fill()
        return ""

    def edit_spectrum(self, row):
        """Change a spectrum's FWHM or columns, in its dialog."""
        if 0 <= row < len(self.entries):
            self.ask_spectrum(self.entries[row])

    def _remove_spectrum(self):
        row = self.spectra.currentRow()
        if 0 <= row < len(self.entries):
            del self.entries[row]
            self._fill()

    def _selection(self):
        self.remove.setEnabled(bool(self.spectra.selectedItems()))

    def _fill(self):
        """
        The table of spectra: file, wavelength range, pixels, FWHM, contents.

        Generated by RJC and Claude.
        """
        self.spectra.setRowCount(0)
        for entry in self.entries:
            facts = spectrum_facts(entry["path"], entry["roles"])
            row = self.spectra.rowCount()
            self.spectra.insertRow(row)
            cells = (
                os.path.basename(entry["path"]),
                facts.get("range", facts.get("error", "")),
                "{0:,}".format(facts["pixels"]) if "pixels" in facts else "",
                "{0:g}".format(entry["fwhm"]),
                facts.get("contains", ""),
            )
            for col, text in enumerate(cells):
                item = QtWidgets.QTableWidgetItem(text)
                tip = entry["path"]
                if facts.get("notes"):
                    tip += "\n" + " ".join(facts["notes"])
                item.setToolTip(tip)
                self.spectra.setItem(row, col, item)
        self._selection()
        self._update()

    def sources(self):
        """The spectra, in order."""
        return [e["path"] for e in self.entries]

    # -- the project ----------------------------------------------------------------

    def path(self):
        """The project's file: ``<folder>/<name>.model``."""
        name = self.name.text().strip()
        if name.endswith(B.SUFFIX):
            name = name[: -len(B.SUFFIX)]
        return os.path.join(self.folder.text().strip(), name + B.SUFFIX)

    def values(self):
        """
        What the dialog collected.

        Returns
        -------
        dict
            ``path``, ``sources``, ``columns`` and ``fwhms`` (each by spectrum),
            ``z`` (or None), ``blind`` and ``mode``.

        Generated by RJC and Claude.
        """
        text = self.redshift.text().strip()
        return {
            "path": self.path(),
            "sources": self.sources(),
            "columns": {e["path"]: dict(e["roles"]) for e in self.entries},
            "fwhms": {e["path"]: e["fwhm"] for e in self.entries},
            "z": float(text) if text else None,
            "blind": self.blind.isChecked(),
            "mode": self.mode.currentData(),
        }

    def problem(self):
        """What stops the project being made, or ``""``."""
        name = self.name.text().strip()
        if not name:
            return "Give the project a name."
        if os.sep in name or "/" in name:
            return "The name cannot hold a folder: choose the folder below it."
        if not os.path.isdir(self.folder.text().strip()):
            return "The folder does not exist."
        if not self.entries:
            return "Add at least one spectrum."
        text = self.redshift.text().strip()
        if text:
            try:
                float(text)
            except ValueError:
                return "The redshift is not a number."
        return ""

    def _update(self):
        self.where.setText("The project is written to " + self.path())
        problem = self.problem()
        self.error.setText(problem)
        ok = self.box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok)
        ok.setEnabled(not problem)


