class PreferencesDialog(QtWidgets.QDialog):
    """
    The user's preferences, from the shipped defaults (``preferences.SPECS``).

    Generated by RJC and Claude.
    """

    def __init__(self, prefs, parent=None):
        super().__init__(parent)
        self.prefs = prefs
        self.setWindowTitle("Preferences")
        self.setMinimumWidth(520)
        layout = QtWidgets.QVBoxLayout(self)
        if prefs.messages:
            note = W.muted("\n".join(prefs.messages))
            note.setWordWrap(True)
            layout.addWidget(note)
        form = QtWidgets.QFormLayout()
        self.fields = {}
        for spec in PR.SPECS:
            value = prefs.get(spec.key)
            if spec.kind is int:
                field = QtWidgets.QSpinBox()
                field.setRange(int(spec.low), int(spec.high))
                field.setValue(value)
            elif spec.kind is float:
                field = QtWidgets.QDoubleSpinBox()
                field.setDecimals(3)
                field.setRange(spec.low, spec.high)
                field.setValue(value)
            else:
                field = QtWidgets.QPlainTextEdit()
                field.setFont(
                    QtGui.QFontDatabase.systemFont(
                        QtGui.QFontDatabase.SystemFont.FixedFont
                    )
                )
                field.setPlainText("\n".join(" ".join(s) for s in value))
                field.setMinimumHeight(140)
            if spec.unit and spec.kind is not list:
                field.setSuffix(" " + spec.unit)
            field.setToolTip(spec.help)
            self.fields[spec.key] = field
            form.addRow(spec.title, field)
        layout.addLayout(form)
        layout.addWidget(W.muted("Kept in " + prefs.path))
        self.error = QtWidgets.QLabel("")
        self.error.setStyleSheet("color: #D55E00;")
        self.error.setWordWrap(True)
        layout.addWidget(self.error)
        box = _buttons(self, "Save")
        reset = box.addButton(
            "Restore defaults", QtWidgets.QDialogButtonBox.ButtonRole.ResetRole
        )
        reset.clicked.connect(self.restore_defaults)
        layout.addWidget(box)

    def restore_defaults(self):
        """Put every field back to the shipped default."""
        for spec in PR.SPECS:
            field = self.fields[spec.key]
            if spec.kind is list:
                field.setPlainText("\n".join(" ".join(s) for s in spec.default))
            else:
                field.setValue(spec.default)

    def collect(self):
        """
        Set the preferences from the fields.

        Raises
        ------
        PreferenceError
            With the first value that cannot be taken.

        Generated by RJC and Claude.
        """
        for spec in PR.SPECS:
            field = self.fields[spec.key]
            if spec.kind is list:
                lines = [ln.split() for ln in field.toPlainText().splitlines()]
                value = [ln for ln in lines if ln]
                value = [
                    ln[:2] + [" ".join(ln[2:])] if len(ln) > 3 else ln for ln in value
                ]
            else:
                value = field.value()
            try:
                self.prefs.set(spec.key, value)
            except PR.PreferenceError as err:
                raise PR.PreferenceError("{0}: {1}".format(spec.title, err)) from None

    def accept(self):
        """Check and keep the preferences, then write them."""
        try:
            self.collect()
        except PR.PreferenceError as err:
            self.error.setText(str(err))
            return
        self.prefs.save()
        super().accept()


