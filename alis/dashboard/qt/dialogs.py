class ColumnRoles(QtWidgets.QTableWidget):
    """
    The columns of a text spectrum: a role for each, chosen from a menu above its
    first values (S3). The roles start from D13's rule; a column with no role is
    ignored, and is not loaded.

    Generated by RJC and Claude.
    """

    changed = QtCore.Signal()

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setEditTriggers(QtWidgets.QAbstractItemView.EditTrigger.NoEditTriggers)
        self.horizontalHeader().setSectionResizeMode(
            QtWidgets.QHeaderView.ResizeMode.Stretch
        )
        self.setMinimumHeight(170)
        self.combos = []
        self.ncols = 0

    def show_file(self, rows, roles, ncols):
        """
        Show a file's first rows, with the menus set to ``roles``.

        Generated by RJC and Claude.
        """
        self.clear()
        self.ncols = ncols
        self.setColumnCount(ncols)
        self.setRowCount(len(rows) + 1)
        self.setHorizontalHeaderLabels(
            ["Column {0}".format(n + 1) for n in range(ncols)]
        )
        self.setVerticalHeaderLabels(["Role"] + [str(n + 1) for n in range(len(rows))])
        by_column = {col: role for role, col in roles.items()}
        self.combos = []
        for col in range(ncols):
            combo = QtWidgets.QComboBox()
            for role in MO.ROLES:
                combo.addItem(MO.ROLE_TITLES[role], role)
            combo.addItem(MO.IGNORE, "")
            combo.setCurrentIndex(combo.findData(by_column.get(col) or ""))
            combo.currentIndexChanged.connect(lambda _: self.changed.emit())
            self.setCellWidget(0, col, combo)
            self.combos.append(combo)
            for num, row in enumerate(rows, 1):
                self.setItem(
                    num, col, QtWidgets.QTableWidgetItem("{0:.8g}".format(row[col]))
                )

    def choices(self):
        """The role chosen for each column (None for Ignore)."""
        return [combo.currentData() or None for combo in self.combos]

    def set_role(self, col, role):
        """Choose a column's role (None for Ignore)."""
        self.combos[col].setCurrentIndex(self.combos[col].findData(role or ""))


class SpectrumDialog(QtWidgets.QDialog):
    """
    One spectrum of a new project (RJC's review): where the file is, its FWHM, and,
    for a text (ASCII) file, the role of each column, guessed first. Each role but
    Ignore goes to one column only, and wavelength, flux and error are needed: until
    they are, the spectrum is not added.

    Parameters
    ----------
    folder : str
        Where the file chooser starts.
    fwhm : float
        The FWHM it starts with, in km/s (the preferences').
    entry : dict, optional
        A spectrum already in the list, to change.

    Generated by RJC and Claude.
    """

    def __init__(self, folder, fwhm=7.0, entry=None, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Add a spectrum (ascii)")
        self.setMinimumWidth(640)
        self.folder = folder
        self.ncols = 0
        form = QtWidgets.QFormLayout()
        self.file = QtWidgets.QLineEdit()
        self.file.setPlaceholderText("a text table of wavelength, flux, error, …")
        self.file.editingFinished.connect(lambda: self.set_file(self.file.text()))
        browse = QtWidgets.QPushButton("Choose…")
        browse.clicked.connect(self._choose)
        place = QtWidgets.QHBoxLayout()
        place.addWidget(self.file, 1)
        place.addWidget(browse)
        form.addRow("File", place)
        self.fwhm = QtWidgets.QDoubleSpinBox()
        self.fwhm.setRange(0.001, 100000.0)
        self.fwhm.setDecimals(3)
        self.fwhm.setSuffix(" km/s")
        self.fwhm.setValue(fwhm)
        self.fwhm.setToolTip("The instrumental resolution, as a FWHM in km/s")
        form.addRow("FWHM", self.fwhm)
        self.about = W.muted("")
        self.about.setWordWrap(True)
        form.addRow("Columns", self.about)
        self.columns = ColumnRoles()
        self.columns.changed.connect(self._update)
        form.addRow("", self.columns)
        hint = W.muted(
            "Wavelength, flux and error are needed. Continuum and mask are optional:"
            " the flux and error are multiplied by a continuum, and a pixel whose"
            " mask is 1 is left out of the fit. A column set to Ignore is not loaded."
        )
        hint.setWordWrap(True)
        form.addRow("", hint)
        self.error = QtWidgets.QLabel("")
        self.error.setStyleSheet("color: #D55E00;")
        self.error.setWordWrap(True)
        layout = QtWidgets.QVBoxLayout(self)
        layout.addLayout(form)
        layout.addWidget(self.error)
        self.box = _buttons(self, "Add" if entry is None else "Keep")
        layout.addWidget(self.box)
        self.columns.hide()
        if entry is not None:
            self.fwhm.setValue(entry["fwhm"])
            self.set_file(entry["path"], entry["roles"])
        self._update()

    def _choose(self):
        path, _ = QtWidgets.QFileDialog.getOpenFileName(
            self,
            "A spectrum",
            self.folder,
            "Spectra (*.dat *.txt *.asc);;All files (*)",
        )
        if path:
            self.set_file(path)

    def set_file(self, path, roles=None):
        """
        Read a file's first rows, and guess its column roles (or take ``roles``).

        Generated by RJC and Claude.
        """
        path = os.path.abspath(path) if path else ""
        self.file.setText(path)
        self.ncols = 0
        self.columns.hide()
        self.about.setText("")
        if not path:
            self._update()
            return
        kind = MO.file_kind(path)
        if kind == MO.FITS:
            self.about.setText(
                "This is a FITS file: PypeIt spec1d files are read with"
                " Add spectra (spec1d), in a mode that comes later."
            )
        elif kind != MO.ASCII:
            self.about.setText("This file is not a table of numbers.")
        else:
            try:
                rows, guessed, ncols, npix = MO.preview(path)
            except (MO.ModeError, OSError, ValueError) as err:
                self.about.setText("The file cannot be read: {0}".format(err))
            else:
                self.ncols = ncols
                self.columns.show_file(rows, roles or guessed, ncols)
                self.columns.show()
                self.about.setText(
                    "{0} columns, {1:,} rows. The roles are guessed; change any that"
                    " are wrong.".format(ncols, npix)
                )
        self._update()

    def problem(self):
        """What stops the spectrum being added, or ``""``."""
        if not self.file.text():
            return "Choose a file."
        if not self.ncols:
            return "This file cannot be read as a text spectrum."
        return MO.check_roles(self.columns.choices(), self.ncols)

    def _update(self):
        problem = self.problem()
        self.error.setText(problem)
        self.box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok).setEnabled(
            not problem
        )

    def entry(self):
        """
        The spectrum, as the New project dialog keeps it.

        Returns
        -------
        dict
            ``path``, ``fwhm``, ``roles``.

        Generated by RJC and Claude.
        """
        return {
            "path": self.file.text(),
            "fwhm": float(self.fwhm.value()),
            "roles": MO.roles_of(self.columns.choices()),
        }


