"""The dashboard's dialogs.

Dashboard Stage 3 (Q3.12, Q2.2, F10, F13, D24; Q3.9, Q3.13):

- :class:`NewProjectDialog`: a new project, from one or more spectra (Q3.12);
- :class:`PreferencesDialog`: the user's preferences (Q2.2);
- :class:`ShortcutsDialog`: every action and its shortcut (F10);
- :class:`RelinkDialog`: source spectra that have moved or changed (F13);
- :class:`UnblindDialog`: unblinding, with a note and an explicit confirmation (D24);
- :class:`BlindLinesDialog`: the lines to blind, with no values (Q3.13);
- :class:`PlanDialog` (Stage 4): what a removal or a merge changes, line by line,
  before it is made (S27, Q4.9);
- :class:`AskDialog` (Stage 4): a few values, such as a name or a redshift.

Each shows values only through the blinding gate, and names no design document.

Generated by RJC and Claude.
"""

