class ShortcutsDialog(QtWidgets.QDialog):
    """
    Every action, by menu, with its shortcut (F10). Built from the same registry as
    the menus and the toolbar.

    Parameters
    ----------
    qactions : dict
        The window's actions by name, for the shortcuts as this platform shows them.

    Generated by RJC and Claude.
    """

    def __init__(self, qactions, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Keyboard shortcuts")
        self.resize(640, 640)
        layout = QtWidgets.QVBoxLayout(self)
        self.table = QtWidgets.QTableWidget(0, 4)
        self.table.setHorizontalHeaderLabels(
            ["Menu", "Action", "Shortcut", "What it does"]
        )
        self.table.verticalHeader().hide()
        self.table.setEditTriggers(
            QtWidgets.QAbstractItemView.EditTrigger.NoEditTriggers
        )
        self.table.setSelectionBehavior(
            QtWidgets.QAbstractItemView.SelectionBehavior.SelectRows
        )
        native = QtGui.QKeySequence.SequenceFormat.NativeText
        for action in A.ACTIONS:
            qaction = qactions.get(action.name)
            keys = qaction.shortcut().toString(native) if qaction is not None else ""
            text = action.text.rstrip("…")
            if action.submenu:
                text = "{0} › {1}".format(action.submenu, text)
            row = self.table.rowCount()
            self.table.insertRow(row)
            for col, value in enumerate((action.menu, text, keys, action.tip)):
                item = QtWidgets.QTableWidgetItem(value)
                if action.later:
                    item.setForeground(QtGui.QColor("#9a9a9a"))
                self.table.setItem(row, col, item)
        header = self.table.horizontalHeader()
        header.setSectionResizeMode(QtWidgets.QHeaderView.ResizeMode.ResizeToContents)
        header.setStretchLastSection(True)
        layout.addWidget(self.table)
        layout.addWidget(
            W.muted("Every action can also be reached from the menus and the toolbar.")
        )
        box = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Close
        )
        box.rejected.connect(self.reject)
        layout.addWidget(box)

    def rows(self):
        """The sheet's rows, as text: ``(menu, action, shortcut, tip)``."""
        return [
            tuple(self.table.item(r, c).text() for c in range(4))
            for r in range(self.table.rowCount())
        ]


