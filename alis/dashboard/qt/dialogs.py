def _buttons(dialog, ok_text):
    """OK and Cancel, with the OK button's own text."""
    box = QtWidgets.QDialogButtonBox(
        QtWidgets.QDialogButtonBox.StandardButton.Ok
        | QtWidgets.QDialogButtonBox.StandardButton.Cancel
    )
    box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok).setText(ok_text)
    box.accepted.connect(dialog.accept)
    box.rejected.connect(dialog.reject)
    return box


def spectrum_facts(path, roles):
    """
    What the spectra table shows of a text spectrum: its wavelength range, number of
    pixels and what it contains.

    Returns
    -------
    dict
        ``range``, ``pixels`` and ``contains``, or ``error`` when it cannot be read.

    Generated by RJC and Claude.
    """
    try:
        spec = MO.get().load(path, roles)
    except (MO.ModeError, OSError, ValueError, IndexError, KeyError) as err:
        return {"error": "cannot be read: {0}".format(err)}
    contains = [MO.ROLE_TITLES[r].lower() for r in MO.ROLES if r in roles]
    return {
        "range": "{0:.1f}–{1:.1f} Å".format(
            float(spec.wave.min()), float(spec.wave.max())
        ),
        "pixels": spec.wave.size,
        "contains": ", ".join(contains),
        "notes": spec.notes,
    }


