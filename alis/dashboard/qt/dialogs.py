class RelinkDialog(QtWidgets.QDialog):
    """
    The source spectra that are missing or changed, each with "Locate…" (F13).

    A file is accepted only if its checksum matches; a changed file is reported,
    never accepted.

    Parameters
    ----------
    session : Session
    choose : callable
        ``choose(entry)`` gives the path the user points to, or None (the window's
        file dialog; a test gives its own).

    Generated by RJC and Claude.
    """

    def __init__(self, session, choose, parent=None):
        super().__init__(parent)
        self.session = session
        self.choose = choose
        self.setWindowTitle("Relink spectra")
        self.setMinimumWidth(680)
        layout = QtWidgets.QVBoxLayout(self)
        intro = QtWidgets.QLabel(
            "These source spectra are not where the project expects them, or have"
            " changed. Point to each moved file: it is accepted only if it is the"
            " same spectrum (its checksum matches)."
        )
        intro.setWordWrap(True)
        layout.addWidget(intro)
        self.table = QtWidgets.QTableWidget(0, 3)
        self.table.setHorizontalHeaderLabels(["Spectrum", "State", ""])
        self.table.verticalHeader().hide()
        self.table.horizontalHeader().setSectionResizeMode(
            0, QtWidgets.QHeaderView.ResizeMode.Stretch
        )
        layout.addWidget(self.table)
        self.message = QtWidgets.QLabel("")
        self.message.setWordWrap(True)
        layout.addWidget(self.message)
        box = QtWidgets.QDialogButtonBox(
            QtWidgets.QDialogButtonBox.StandardButton.Close
        )
        box.rejected.connect(self.reject)
        layout.addWidget(box)
        self.relinked = []
        self.fill()

    def entries(self):
        """Every source with its state."""
        return SR.states(self.session.project.bundle, self.session.path)

    def fill(self):
        """
        One row per source that is missing or changed.

        Generated by RJC and Claude.
        """
        self.table.setRowCount(0)
        for entry, state in self.entries():
            if state not in (SR.MISSING, SR.CHANGED):
                continue
            row = self.table.rowCount()
            self.table.insertRow(row)
            name = QtWidgets.QTableWidgetItem(os.path.basename(entry["path"]))
            name.setToolTip(entry["path"])
            self.table.setItem(row, 0, name)
            self.table.setItem(
                row, 1, QtWidgets.QTableWidgetItem(SR.describe(entry, state))
            )
            button = QtWidgets.QPushButton("Locate…")
            button.clicked.connect(lambda _=False, e=entry: self.locate(e))
            self.table.setCellWidget(row, 2, button)
        if not self.table.rowCount():
            self.message.setText("Every source spectrum is present and unchanged.")

    def locate(self, entry):
        """
        Point a source to a file, accepted only if its checksum matches.

        Returns
        -------
        bool

        Generated by RJC and Claude.
        """
        path = self.choose(entry)
        if not path:
            return False
        try:
            SR.relink(self.session.project.bundle, entry["id"], path, self.session.path)
        except (B.BundleError, OSError) as err:
            self.message.setText(str(err))
            return False
        self.relinked.append(entry["id"])
        self.fill()
        self.message.setText(
            "{0} was relinked to {1}. Save the project to keep it.".format(
                os.path.basename(entry["path"]), path
            )
        )
        return True


