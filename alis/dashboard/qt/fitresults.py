"""The Fit tab's Results sub-tab (dashboard Stage 6.6; S19, S20, D40, D51, F7, D26;
Q6.7, Q6.8, Q6.12, Q6.15, Q6.23).

- **The results table** of the shown run ("Results · run 3"), or, while a run goes,
  the values in progress under its notice, with no errors: each system with its
  ions and components (log N, z with its velocity in the system, b, T), the Lyα
  forest, the continua and the instrument, each row with its value, error, state
  (● free, ■ fixed, ⛓ tied, ƒ linked) and flags. A collapsed group shows its
  flagged rows; a click on its title opens or closes it. A row selected highlights
  its lines in the ``.mod`` panel (S16). Copy as table copies the rows, through
  the gate. Continue from best fit… copies the shown run's best fit into the
  model, after a preview, as one step.
- **The run history** (F7, D26, Q6.7): the latest run, with Commit…, which asks
  for a description; then the committed runs, newest first, each with its
  description (a double-click edits it), χ²ν, when and where ("cmd" for a run made
  by ``run_alis``, S31). Selecting a run shows it on Inspect and Results; Remove…
  removes a committed run after a confirmation. Committing, describing and
  removing are saved with Save, and are not steps of the history.
- **Fit statistics**: χ² and its start, degrees of freedom, χ²ν, iterations, the run
  time, why the fit stopped, and where and when it ran.
- **Correlations** (D51): the correlation matrix of a group's free parameters, from
  the run's covariance, in a colour-blind-safe diverging scale (D43), the pair and
  its coefficient on hover. A correlation reveals no value: hidden parameters are
  included, by name.

Every value passes the blinding gate.

Generated by RJC and Claude.
"""

