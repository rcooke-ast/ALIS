ROLE = QtCore.Qt.ItemDataRole.UserRole
COLUMNS = ("Parameter", "Value", "Error", "v (km/s)", "State", "Flags")
HISTORY = ("Run", "Description", "χ²ν", "When", "Where")
# What the sub-tab keeps in the view state (ui/view.json)
VIEW = "results"
# The least time between two drawings of the values in progress (ms)
REDRAW = 1000
# Flags that ask for a look, and their colour (each also has its icon, D43)
ATTENTION = {
    "at limit": STY.OKABE_ITO["vermillion"],
    RS.NEGATIVE: STY.OKABE_ITO["vermillion"],
    "unconstrained": "#9a6b00",
    "not tied": "#9a6b00",
    "z not tied": "#9a6b00",
}
# A correlation's colours: +1 vermillion, −1 blue (D43), through white
POSITIVE = QtGui.QColor(STY.OKABE_ITO["vermillion"])
NEGATIVE = QtGui.QColor(STY.OKABE_ITO["blue"])
# Names are written beside the matrix while a cell is at least this tall (px)
NAMED_CELL = 11


def _flag_colour(flag):
    for start, colour in ATTENTION.items():
        if flag.startswith(start):
            return colour
    return None


def flag_text(flags):
    """A row's flags, each that asks for a look with its icon (D43)."""
    return "; ".join(("! " if _flag_colour(f) else "") + f for f in flags)


class CorrelationView(QtWidgets.QWidget):
    """
    A correlation matrix (D51): each cell coloured from blue (−1) through white to
    vermillion (+1), the parameters' names beside it while there is room, and the
    pair and its coefficient under the mouse (the tooltip).

    Generated by RJC and Claude.
    """

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setMouseTracking(True)
        self.setMinimumSize(160, 160)
        self.names = []
        self.matrix = np.zeros((0, 0))
        self._geometry = None

    def set_correlation(self, correlation):
        """
        Draw a :class:`~alis.dashboard.results.Correlation`, or nothing (None).

        Generated by RJC and Claude.
        """
        if correlation is None:
            self.names, self.matrix = [], np.zeros((0, 0))
        else:
            self.names = list(correlation.names)
            self.matrix = np.asarray(correlation.matrix, dtype=float)
        self.setToolTip("")
        self.update()

    @staticmethod
    def colour(value):
        """The colour of a coefficient."""
        if not np.isfinite(value):
            return QtGui.QColor(STY.GREY["light"])
        end = POSITIVE if value >= 0 else NEGATIVE
        frac = min(abs(float(value)), 1.0)
        mix = [int(round(255 + (c - 255) * frac)) for c in end.getRgb()[:3]]
        return QtGui.QColor(*mix)

    def _layout(self):
        """The left and top of the matrix, and its cell's size."""
        count = len(self.names)
        if not count:
            return 0, 0, 0
        metrics = self.fontMetrics()
        width, height = self.width() - 4, self.height() - 4
        cell = max(1, min(width, height) // count)
        left = 0
        if cell >= NAMED_CELL:
            left = min(max(metrics.horizontalAdvance(n) for n in self.names) + 6, 150)
            cell = max(1, min(width - left, height) // count)
            if cell < NAMED_CELL:
                left = 0
                cell = max(1, min(width, height) // count)
        return left + 2, 2, cell

    def paintEvent(self, event):
        painter = QtGui.QPainter(self)
        painter.fillRect(self.rect(), QtGui.QColor(STY.GREY["base"]))
        count = len(self.names)
        if not count:
            painter.end()
            return
        left, top, cell = self._layout()
        self._geometry = (left, top, cell)
        grid = cell >= 4
        pen = QtGui.QPen(QtGui.QColor("#dddddd"))
        for i in range(count):
            for j in range(count):
                rect = QtCore.QRect(left + j * cell, top + i * cell, cell, cell)
                painter.fillRect(rect, self.colour(self.matrix[i, j]))
                if grid:
                    painter.setPen(pen)
                    painter.drawRect(rect.adjusted(0, 0, -1, -1))
        if left > 2:
            painter.setPen(QtGui.QColor(STY.GREY["text"]))
            metrics = self.fontMetrics()
            for i, name in enumerate(self.names):
                text = metrics.elidedText(
                    name, QtCore.Qt.TextElideMode.ElideRight, left - 6
                )
                rect = QtCore.QRect(0, top + i * cell, left - 4, cell)
                painter.drawText(
                    rect,
                    QtCore.Qt.AlignmentFlag.AlignRight
                    | QtCore.Qt.AlignmentFlag.AlignVCenter,
                    text,
                )
        painter.end()

    def cell_at(self, x, y):
        """The pair ``(i, j)`` under a point, or None."""
        if self._geometry is None:
            self._geometry = self._layout()
        left, top, cell = self._geometry
        count = len(self.names)
        if not count or not cell:
            return None
        j, i = (x - left) // cell, (y - top) // cell
        if 0 <= i < count and 0 <= j < count:
            return int(i), int(j)
        return None

    def pair_text(self, i, j):
        """``"H I a1 log N – H I a1 z: +0.53"``."""
        value = self.matrix[i, j]
        return "{0} – {1}: {2}{3:.2f}".format(
            self.names[i], self.names[j], "−" if value < 0 else "+", abs(value)
        )

    def mouseMoveEvent(self, event):
        pos = event.position().toPoint() if hasattr(event, "position") else event.pos()
        found = self.cell_at(pos.x(), pos.y())
        tip = "" if found is None else self.pair_text(*found)
        if tip != self.toolTip():
            self.setToolTip(tip)
            if tip:
                QtWidgets.QToolTip.showText(event.globalPosition().toPoint(), tip, self)
        super().mouseMoveEvent(event)

    def resizeEvent(self, event):
        self._geometry = None
        super().resizeEvent(event)


class ResultsTab(W.Tab):
    """
    The Fit tab's Results sub-tab (D40): the results table, the run history, the fit
    statistics, and the correlations below them.

    Actions: Continue from best fit… and Commit run… (the Fit menu's), Copy as table,
    Remove…; a click on a group's title opens or closes it; a double-click on a
    committed run's description edits it.

    Generated by RJC and Claude.
    """

    name = "Results"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.main = None
        self.holder = None
        self.session = None
        self.view = None
        self.groups = []
        self.history_rows = []
        self._stale = False
        self._filling = False
        self._drawn_at = 0.0
        self._redraw_timer = QtCore.QTimer(self)
        self._redraw_timer.setSingleShot(True)
        self._redraw_timer.timeout.connect(self._redraw_progress)
        self._build_table()
        self._build_history()
        self._build_statistics()
        self._build_correlations()
        # The run history beside the results, and the correlations below the
        # statistics (RJC's review of the mockups)
        self.layout_.addWidget(
            W.row(
                W.column(self.table_pane, width=640),
                W.column(self.history_pane, width=364),
                W.column(self.stats_pane, self.corr_pane, stretch=[1, 2], width=370),
                stretch=[640, 364, 370],
            )
        )

    # -- building -----------------------------------------------------------------------

    def _build_table(self):
        body = QtWidgets.QWidget()
        box = QtWidgets.QVBoxLayout(body)
        box.setContentsMargins(0, 0, 0, 0)
        box.setSpacing(4)
        self.notice = W.Banner()
        box.addWidget(self.notice)
        self.table_note = W.muted("")
        self.table_note.setWordWrap(True)
        box.addWidget(self.table_note)
        self.tree = QtWidgets.QTreeWidget()
        self.tree.setObjectName("results_table")
        self.tree.setColumnCount(len(COLUMNS))
        self.tree.setHeaderLabels(list(COLUMNS))
        self.tree.setRootIsDecorated(False)
        self.tree.setItemsExpandable(False)
        self.tree.setUniformRowHeights(True)
        self.tree.setAlternatingRowColors(True)
        header = self.tree.header()
        header.setStretchLastSection(True)
        for col, width in enumerate((150, 88, 92, 58, 70)):
            self.tree.setColumnWidth(col, width)
        self.tree.itemClicked.connect(self._item_clicked)
        self.tree.currentItemChanged.connect(self._row_selected)
        box.addWidget(self.tree, 1)
        self.continue_button = QtWidgets.QToolButton()
        self.continue_button.setObjectName("fit_continue")
        self.copy_button = QtWidgets.QToolButton()
        self.copy_button.setText("Copy as table")
        self.copy_button.setObjectName("results_copy")
        self.copy_button.setToolTip(
            "Copy every row as tab-separated text, hidden values masked"
        )
        self.copy_button.clicked.connect(lambda: self._act("results.copy", self.copy))
        self.table_pane = W.Pane(
            "Results", body, extra=[self.continue_button, self.copy_button]
        )

    def _build_history(self):
        body = QtWidgets.QWidget()
        box = QtWidgets.QVBoxLayout(body)
        box.setContentsMargins(0, 0, 0, 0)
        box.setSpacing(4)
        self.history = QtWidgets.QTableWidget(0, len(HISTORY))
        self.history.setObjectName("run_history")
        self.history.setHorizontalHeaderLabels(list(HISTORY))
        self.history.verticalHeader().setVisible(False)
        self.history.setSelectionBehavior(
            QtWidgets.QAbstractItemView.SelectionBehavior.SelectRows
        )
        self.history.setSelectionMode(
            QtWidgets.QAbstractItemView.SelectionMode.SingleSelection
        )
        self.history.setEditTriggers(
            QtWidgets.QAbstractItemView.EditTrigger.DoubleClicked
            | QtWidgets.QAbstractItemView.EditTrigger.EditKeyPressed
        )
        head = self.history.horizontalHeader()
        head.setSectionResizeMode(1, QtWidgets.QHeaderView.ResizeMode.Stretch)
        for col in (0, 2, 3, 4):
            head.setSectionResizeMode(
                col, QtWidgets.QHeaderView.ResizeMode.ResizeToContents
            )
        self.history.itemSelectionChanged.connect(self._history_selected)
        self.history.itemChanged.connect(self._history_edited)
        self.history.cellDoubleClicked.connect(self._history_double_clicked)
        box.addWidget(self.history, 1)
        buttons = QtWidgets.QHBoxLayout()
        buttons.setContentsMargins(0, 0, 0, 0)
        self.commit_button = QtWidgets.QToolButton()
        self.commit_button.setObjectName("fit_commit")
        buttons.addWidget(self.commit_button)
        self.remove_button = QtWidgets.QToolButton()
        self.remove_button.setText("Remove…")
        self.remove_button.setObjectName("remove_run")
        self.remove_button.setToolTip("Remove the selected committed run")
        self.remove_button.clicked.connect(
            lambda: self._act("results.remove", self.remove_selected)
        )
        buttons.addWidget(self.remove_button)
        buttons.addStretch(1)
        box.addLayout(buttons)
        note = W.muted(
            "Only committed runs are kept: the next run replaces the latest one."
            " Committing asks for a short description, which a double-click edits."
            ' Select a run to show it on Inspect and here. "cmd" is a run made with'
            " run_alis."
        )
        note.setWordWrap(True)
        box.addWidget(note)
        self.history_pane = W.Pane("Run history", body)

