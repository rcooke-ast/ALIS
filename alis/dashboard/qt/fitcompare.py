"""The Fit tab's Compare sub-tab (dashboard Stage 6.7; D41; Q6.9, Q0.9, Q0.11).

- **Choose** any two runs, the committed runs and the latest (the first, then the
  second; by default the newest committed run, or the one before it when the latest
  run is committed, then the latest run); Swap; Restore …'s model… replaces the model and its snips with the
  second run's, as one step, after a preview of what changes.
- **Parameters** (Q6.9): the quantities both runs share, matched across different
  parametrisations (``compare.py``): each ion's total log N and each isotope's
  ratio in each system, the components matched by velocity (v, b, T) and how many
  each ion has, the FWHMs, χ²ν, the degrees of freedom and the iterations; each
  with both values, Δ (second − first) and |Δ|/σ, σ the larger of the two errors.
  A blinded quantity shows only |Δ|/σ, with no sign (Q0.9, Q0.11).
- **The view** (D41): both best fits on the same data (the first solid, the second
  dashed), over the first's continuum, with their difference in units of the
  data's errors underneath; Inspect's View menu, ‹ › (the keys [ and ]), Columns,
  and the zoom bar.

Every value passes the blinding gate; the profiles of hidden components are drawn
(D24).

Generated by RJC and Claude.
"""

