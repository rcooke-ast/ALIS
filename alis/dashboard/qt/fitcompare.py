ROLE = QtCore.Qt.ItemDataRole.UserRole
# The latest run, in the menus and the view state
LATEST = "latest"
VIEW = "compare"
NEED_TWO = "Compare needs two runs: commit a run, then run the fit again."


class CompareTab(W.Tab):
    """
    The Fit tab's Compare sub-tab (D41): two runs, their matched quantities, and
    both best fits on the same data.

    Actions: Swap, Restore …'s model…, and ‹ › (the keys [ and ], while the Fit tab
    has the focus).

    Generated by RJC and Claude.
    """

    name = "Compare"

    def __init__(self, parent=None):
        super().__init__(parent)
        self.main = None
        self.holder = None
        self.session = None
        self.rows = []
        self.views = (None, None)
        self.panel_widgets = []
        self._choices = []
        self._stale = False
        self._filling = False
        self._build_choose()
        self._build_parameters()
        self._build_view()
        body = W.row(
            W.column(self.parameters, width=610),
            W.column(self.view_pane, width=772),
            stretch=[610, 772],
        )
        body.layout().setContentsMargins(0, 0, 0, 0)
        holder = W.column(self.choose, body, stretch=[0, 1])
        holder.layout().setContentsMargins(8, 8, 8, 8)
        self.layout_.addWidget(holder)

    # -- building -----------------------------------------------------------------------

    def _build_choose(self):
        body = QtWidgets.QWidget()
        row = QtWidgets.QHBoxLayout(body)
        row.setContentsMargins(0, 0, 0, 0)
        row.addWidget(QtWidgets.QLabel("Compare"))
        self.first_menu = QtWidgets.QComboBox()
        self.first_menu.setObjectName("compare_first")
        self.second_menu = QtWidgets.QComboBox()
        self.second_menu.setObjectName("compare_second")
        for menu in (self.first_menu, self.second_menu):
            menu.setToolTip("Any committed run, or the latest run")
            menu.setMinimumContentsLength(12)
            menu.setSizeAdjustPolicy(
                QtWidgets.QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon
            )
            menu.currentIndexChanged.connect(self._run_chosen)
        row.addWidget(self.first_menu, 1)
        row.addWidget(QtWidgets.QLabel("with"))
        row.addWidget(self.second_menu, 1)
        row.addStretch(1)
        self.swap_button = QtWidgets.QPushButton("Swap")
        self.swap_button.setObjectName("compare_swap")
        self.swap_button.setToolTip("Swap the two runs")
        self.swap_button.clicked.connect(lambda: self._act("compare.swap", self.swap))
        row.addWidget(self.swap_button)
        self.restore_button = QtWidgets.QPushButton("Restore…")
        self.restore_button.setObjectName("compare_restore")
        self.restore_button.clicked.connect(
            lambda: self._act("compare.restore", self.restore)
        )
        row.addWidget(self.restore_button)
        self.choose = W.Pane("Compare", body)
        self.choose.setMaximumHeight(90)

    def _build_parameters(self):
        body = QtWidgets.QWidget()
        box = QtWidgets.QVBoxLayout(body)
        box.setContentsMargins(0, 0, 0, 0)
        self.table_note = W.muted("")
        self.table_note.setWordWrap(True)
        box.addWidget(self.table_note)
        self.tree = QtWidgets.QTreeWidget()
        self.tree.setObjectName("compare_table")
        self.tree.setColumnCount(6)
        self.tree.setRootIsDecorated(False)
        self.tree.setItemsExpandable(False)
        self.tree.setUniformRowHeights(True)
        self.tree.setAlternatingRowColors(True)
        for col, width in enumerate((170, 120, 120, 70, 54)):
            self.tree.setColumnWidth(col, width)
        self.tree.header().setStretchLastSection(True)
        box.addWidget(self.tree, 1)
        self.parameters_note = W.muted("")
        self.parameters_note.setWordWrap(True)
        box.addWidget(self.parameters_note)
        self.parameters = W.Pane("Parameters", body)

    def _build_view(self):
        body = QtWidgets.QWidget()
        box = QtWidgets.QVBoxLayout(body)
        box.setContentsMargins(0, 0, 0, 0)
        box.setSpacing(4)
        top = QtWidgets.QHBoxLayout()
        top.setContentsMargins(0, 0, 0, 0)
        top.addWidget(QtWidgets.QLabel("View"))
        self.view_menu = QtWidgets.QComboBox()
        self.view_menu.setObjectName("compare_view")
        self.view_menu.setMinimumContentsLength(18)
        self.view_menu.setSizeAdjustPolicy(
            QtWidgets.QComboBox.SizeAdjustPolicy.AdjustToMinimumContentsLengthWithIcon
        )
        self.view_menu.currentIndexChanged.connect(self._view_chosen)
        top.addWidget(self.view_menu, 1)
        self.step_buttons = QtWidgets.QHBoxLayout()
        self.step_buttons.setSpacing(0)
        top.addLayout(self.step_buttons)
        self.columns_label = QtWidgets.QLabel("Columns")
        top.addWidget(self.columns_label)
        self.columns_box = QtWidgets.QSpinBox()
        self.columns_box.setObjectName("compare_columns")
        self.columns_box.setRange(1, 4)
        self.columns_box.setToolTip(
            "Used when more than one snip is shown; the same setting as the"
            " Components tab"
        )
        self.columns_box.valueChanged.connect(self._columns_chosen)
        top.addWidget(self.columns_box)
        top.addStretch(1)
        self.zoom = PL.ZoomBar()
        top.addWidget(self.zoom)
        box.addLayout(top)
        self.legend = W.muted("")
        self.legend.setTextFormat(QtCore.Qt.TextFormat.RichText)
        box.addWidget(self.legend)
        self.panel_note = W.muted("")
        self.panel_note.setWordWrap(True)
        box.addWidget(self.panel_note)
        self.scroll = QtWidgets.QScrollArea()
        self.scroll.setWidgetResizable(True)
        self.scroll.setFrameShape(QtWidgets.QFrame.Shape.NoFrame)
        holder = QtWidgets.QWidget()
        self.grid = QtWidgets.QGridLayout(holder)
        self.grid.setContentsMargins(0, 0, 0, 0)
        self.grid.setSpacing(4)
        self.scroll.setWidget(holder)
        box.addWidget(self.scroll, 1)
        self.view_pane = W.Pane("View", body)

    def attach(self, window):
        """The main window; the sub-tab draws itself when it is shown."""
        super().attach(window)
        window.tabs.currentChanged.connect(self._tab_shown)
        if self.holder is not None:
            self.holder.subtabs.currentChanged.connect(self._tab_shown)

    def bind_action(self, name, action):
        """‹ and › beside the View menu (the Fit tab's own actions)."""
        button = QtWidgets.QToolButton()
        button.setDefaultAction(action)
        button.setObjectName("compare_" + name.split(".", 1)[1])
        button.setText("‹" if name.endswith("previous_view") else "›")
        button.setAutoRaise(True)
        self.step_buttons.addWidget(button)
        return button

    # -- acting ---------------------------------------------------------------------------

    def _act(self, name, handler):
        if self.main is not None:
            self.main._run(name, handler)
        else:
            handler()

    def prefs(self):
        return getattr(self.main, "prefs", None)

    def _pref(self, key):
        prefs = self.prefs()
        try:
            return prefs[key] if prefs is not None else PF.SPEC[key].default
        except KeyError:
            return PF.SPEC[key].default

    def _state(self):
        return dict((self.session.view.get(VIEW) or {}) if self.session else {})

    def _remember(self, **changes):
        if self.session is not None:
            state = self._state()
            state.update(changes)
            self.session.set_view(VIEW, state)

    # -- refreshing ---------------------------------------------------------------------

    def _visible(self):
        if self.main is None:
            return True
        if self.main.tabs.currentWidget() is not self.holder:
            return False
        return self.holder is None or self.holder.subtabs.currentWidget() is self

    def _tab_shown(self, *args):
        if self._stale and self._visible():
            self.refresh(self.session)

    def refresh(self, session):
        """
        Redraw the sub-tab from the project; while it is not on the screen, only once
        it is.

        Generated by RJC and Claude.
        """
        self.session = session
        if session is None or session.project.paused:
            return
        if not self._visible():
            self._stale = True
            return
        self._stale = False
        self._fill_menus()
        self._fill_views()
        self._fill_table()
        self._fill_view_menu()
        self._fill_panels()

    # -- the two runs ---------------------------------------------------------------

    @staticmethod
    def _key(row):
        return LATEST if row.key is None else row.key

    def _defaults(self, rows):
        """
        The pair compared by default (RJC's review): the latest run against the newest
        committed run, or, when the latest run is that committed run, against the
        committed run before it.

        Generated by RJC and Claude.
        """
        latest = next((r for r in rows if r.latest), None)
        if latest is None:
            return None, None
        second = self._key(latest)
        others = [r for r in rows if r.key is not None and not r.latest]
        first = self._key(others[0]) if others else second
        return first, second

    def _fill_menus(self):
        project = self.session.project
        rows = RS.history(project)
        self.history = rows
        state = self._state()
        keys = [self._key(r) for r in rows]
        first, second = self._defaults(rows)
        first = state.get("first", first) if state.get("first") in keys else first
        second = state.get("second", second) if state.get("second") in keys else second
        self._filling = True
        try:
            for menu, chosen in ((self.first_menu, first), (self.second_menu, second)):
                menu.clear()
                for row in rows:
                    text = (
                        "Latest run" if row.key is None else "Run {0}".format(row.key)
                    )
                    if row.description:
                        text += " · " + row.description
                    if row.status:
                        text += " (" + row.status + ")"
                    menu.addItem(text, self._key(row))
                index = menu.findData(chosen)
                menu.setCurrentIndex(max(index, 0))
        finally:
            self._filling = False
        self.chosen = (self.first_menu.currentData(), self.second_menu.currentData())
        second_name = self._name(self.chosen[1])
        self.restore_button.setText(
            "Restore {0}'s model…".format(second_name) if second_name else "Restore…"
        )
        self.restore_button.setEnabled(self.chosen[1] is not None)
        self.restore_button.setToolTip(
            "Replace the model and its snips with those of the second run, as one"
            " step, after a preview"
        )
        self.swap_button.setEnabled(len(rows) > 1)

    def _name(self, key):
        if key is None:
            return ""
        return "the latest run" if key == LATEST else "run {0}".format(key)

    def _record(self, key):
        project = self.session.project
        if key == LATEST:
            return R.latest(project.bundle)
        try:
            return R.run_of(project.bundle, int(key))
        except (R.RunError, TypeError, ValueError):
            return None

    def _fill_views(self):
        views = []
        self.why = ""
        for key in self.chosen:
            record = None if key is None else self._record(key)
            view, why = (None, NEED_TWO)
            if record is not None and self.holder is not None:
                view, why = self.holder.view_of(record)
            views.append(view)
            if view is None and not self.why:
                self.why = why
        self.views = tuple(views)

    def _run_chosen(self, index):
        if self._filling or self.session is None:
            return
        self._remember(
            first=self.first_menu.currentData(), second=self.second_menu.currentData()
        )
        self.refresh(self.session)

    def choose_runs(self, first, second):
        """
        Compare two runs (``"latest"`` or a committed run's number): as the menus
        choose them.

        Generated by RJC and Claude.
        """
        self._remember(first=first, second=second)
        self.refresh(self.session)

    def swap(self):
        """Swap: the second run first."""
        first, second = self.chosen
        self.choose_runs(second, first)

    def restore(self):
        """
        Restore the second run's model…: the model, its snips and the run's project
        data, as one step, after a preview of what changes (Q6.7).

        Generated by RJC and Claude.
        """
        key = self.chosen[1]
        record = self._record(key) if key is not None else None
        if record is None:
            return
        project = self.session.project
        number = None if key == LATEST else int(key)
        step = R.restore_step(project, number)
        try:
            run_model = RS.model_of(project, record=record)
        except RS.ResultsError as err:
            self.main.tell("Restore", BL.Gate(project).message(str(err)), "warning")
            return
        lines, snips = CM.restore_preview(project, step, run_model)
        dialog = D.RestoreDialog(self._name(key), lines, snips, self)
        if not self.main.run_dialog(dialog):
            return
        self.session.history.do(step)
        self.main.panel.redraw()

    # -- the parameters (Q6.9) -------------------------------------------------------

    def _fill_table(self):
        self.tree.clear()
        self.rows = []
        first, second = self.chosen
        names = [self._name(k) for k in (first, second)]
        short = [
            ("latest" if k == LATEST else "run {0}".format(k)) if k else ""
            for k in (first, second)
        ]
        self.tree.setHeaderLabels(
            [
                "Parameter",
                short[0].capitalize(),
                short[1].capitalize(),
                "Δ ({0} − {1})".format(short[1], short[0]) if all(short) else "Δ",
                "|Δ|/σ",
                "",
            ]
        )
        self.names = names
        within = self._pref("fit.match_kms")
        self.parameters_note.setText(
            "Components are matched by system, ion and velocity, within {0:g} km/s."
            " σ is the larger of the two runs' errors; — where a run gives none (no"
            " covariance, or stopped before the end).".format(within)
        )
        if None in self.views:
            self.table_note.setText(self.why or NEED_TWO)
            self.table_note.show()
            return
        try:
            self.rows = CM.compare(self.views[0], self.views[1], self.prefs())
        except CM.CompareError as err:
            self.table_note.setText(BL.Gate(self.session.project).message(str(err)))
            self.table_note.show()
            return
        note = ""
        if first == second:
            note = "The same run is chosen twice."
        self.table_note.setText(note)
        self.table_note.setVisible(bool(note))
        group, head = None, None
        for row in self.rows:
            if row.group != group:
                group = row.group
                head = QtWidgets.QTreeWidgetItem([group])
                font = head.font(0)
                font.setBold(True)
                head.setFont(0, font)
                self.tree.addTopLevelItem(head)
                head.setFirstColumnSpanned(True)
                head.setExpanded(True)
            item = QtWidgets.QTreeWidgetItem(
                [row.name, row.first, row.second, row.delta, row.sigma, row.note]
            )
            for col in (1, 2, 3, 4):
                item.setTextAlignment(
                    col,
                    QtCore.Qt.AlignmentFlag.AlignRight
                    | QtCore.Qt.AlignmentFlag.AlignVCenter,
                )
            if row.nsigma is not None and row.nsigma > 3.0:
                item.setForeground(4, QtGui.QColor(STY.OKABE_ITO["vermillion"]))
                item.setText(4, row.sigma + " !")
            if row.note:
                item.setForeground(5, QtGui.QColor(STY.GREY["muted"]))
                item.setToolTip(5, row.note)
            head.addChild(item)

    def shown_rows(self):
        """The table as its cells (tests)."""
        out = []
        for num in range(self.tree.topLevelItemCount()):
            head = self.tree.topLevelItem(num)
            out.append([head.text(0)])
            for k in range(head.childCount()):
                child = head.child(k)
                out.append([child.text(c) for c in range(6)])
        return out

    # -- the view (D41) -------------------------------------------------------------

    def _fill_view_menu(self):
        project = self.session.project
        self._choices = FV.choices(project)
        self._filling = True
        try:
            self.view_menu.clear()
            heading = ""
            model = self.view_menu.model()
            for num, choice in enumerate(self._choices):
                if choice.heading and choice.heading != heading:
                    heading = choice.heading
                    self.view_menu.addItem(heading, None)
                    item = model.item(self.view_menu.count() - 1)
                    item.setEnabled(False)
                    font = item.font()
                    font.setBold(True)
                    item.setFont(font)
                self.view_menu.addItem(
                    ("    " if choice.heading else "") + choice.title, num
                )
            wanted = self._state().get("view")
            if wanted is None and len(self._choices) > 1:
                # One snip at a time, as the mockup shows it
                one = [c for c in self._choices if c.kind == FV.SNIP]
                wanted = list(one[0].key) if one else None
            index = self.view_menu.findData(FV.find(self._choices, wanted))
            self.view_menu.setCurrentIndex(max(index, 0))
            stored = self.session.view.get("components") or {}
            self.columns_box.setValue(
                int(stored.get("columns", self._pref("components.columns")))
            )
        finally:
            self._filling = False

    def choice(self):
        if not self._choices:
            return FV.Choice(FV.ALL, (FV.ALL,), "")
        wanted = self._state().get("view")
        if wanted is None:
            one = [c for c in self._choices if c.kind == FV.SNIP]
            wanted = list(one[0].key) if one else None
        return self._choices[FV.find(self._choices, wanted)]

    def _view_chosen(self, index):
        if self._filling or index < 0:
            return
        num = self.view_menu.itemData(index)
        if num is None:
            return
        self.show_choice(self._choices[num].key)

    def show_choice(self, key):
        """Show a View menu choice: all snips, an ion, a snip."""
        self._remember(view=list(key))
        self._filling = True
        try:
            index = self.view_menu.findData(FV.find(self._choices, key))
            self.view_menu.setCurrentIndex(max(index, 0))
        finally:
            self._filling = False
        self._fill_panels()

    def do_previous_view(self):
        self._step(-1)

    def do_next_view(self):
        self._step(1)

    def _step(self, by):
        if self.session is None or not self._choices:
            return
        key = FV.step(self._choices, list(self.choice().key), by)
        if key is not None:
            self.show_choice(key)

    def _columns_chosen(self, value):
        if self._filling or self.session is None:
            return
        stored = dict(self.session.view.get("components") or {})
        stored["columns"] = int(value)
        self.session.set_view("components", stored)
        self._fill_panels()

    def _clear_panels(self):
        for widget in self.panel_widgets:
            self.grid.removeWidget(widget)
            widget.hide()
            widget.setParent(None)
            widget.deleteLater()
        self.panel_widgets = []

    def _curves(self, view):
        if view is None:
            return {}
        try:
            return view.curves()
        except RS.ResultsError:
            return {}

    def _fill_panels(self):
        """
        The panels of the View menu's choice: the data over the first run's
        continuum, both best fits, and their difference in σ.

        Generated by RJC and Claude.
        """
        self._clear_panels()
        if self.session is None:
            return
        project = self.session.project
        choice = self.choice()
        found = FV.panels(project, choice, FV.VELOCITY)
        one, two = (self._curves(v) for v in self.views)
        single = choice.kind == FV.SNIP or len(found) == 1
        stored = self.session.view.get("components") or {}
        columns = int(stored.get("columns", self._pref("components.columns")))
        ncol = 1 if single else max(1, min(columns, len(found)))
        self.columns_box.setEnabled(not single)
        self.columns_label.setEnabled(not single)
        names = [n for n in getattr(self, "names", ["", ""])]
        if all(names):
            self.legend.setText(
                "<span>data</span> &nbsp; <span style='color:{0};'>━ {1}</span>"
                " &nbsp; <span style='color:{2};'>╍ {3} (dashed)</span> &nbsp;"
                " below: ({3} − {1})/σ".format(
                    PL.COLOURS["model"], names[0], PL.COLOURS["model2"], names[1]
                )
            )
        notes = []
        if None in self.views:
            notes.append(self.why or NEED_TWO)
        for num, panel in enumerate(found):
            widget = InspectPanel(panel)
            if single:
                widget.resid.setFixedHeight(70)
            index = panel.snip.data.index
            self._draw_panel(widget, one.get(index), two.get(index))
            self.grid.addWidget(widget, num // ncol, num % ncol)
            self.panel_widgets.append(widget)
        for col in range(4):
            self.grid.setColumnStretch(col, 1 if col < ncol else 0)
        nrows = (len(found) + ncol - 1) // ncol
        for row in range(max(self.grid.rowCount(), nrows + 1)):
            self.grid.setRowStretch(row, 0)
        self.grid.setRowStretch(0 if single else nrows, 1)
        for num, widget in enumerate(self.panel_widgets):
            widget.view.set_labels(top=False, bottom=num // ncol == nrows - 1)
        self.panel_note.setText("  ·  ".join(notes))
        self.panel_note.setVisible(bool(notes))
        if self.panel_widgets:
            link = choice.kind in (FV.ION, FV.FOREST)
            self.zoom.attach(*[w.view for w in self.panel_widgets], link=link)
            for widget in self.panel_widgets:
                if link:
                    half = float(
                        stored.get("range", self._pref("components.velocity_range"))
                    )
                    _, yrange = widget.view._home or (None, None)
                    widget.view.set_home((-half, half), yrange)
                widget.view.home()
            self.zoom.remember()

    def _draw_panel(self, widget, first, second):
        """One panel: the data over the first's continuum, both models, and their
        difference in units of the data's errors."""
        panel = widget.panel
        pix = panel.snip.pixels
        widget.curves = (first, second)
        base = first if first is not None else second
        if base is not None:
            wave, flux, error = base.wave, base.flux, base.error
            bad = pix.bad if base.wave.size == pix.wave.size else None
            cont = base.continuum
        else:
            wave, flux, error, bad = pix.wave, pix.flux, pix.error, pix.bad
            cont = None
        x = panel.x(wave)
        view = widget.view
        view.set_data(x, flux, error, bad)
        view.set_normalised(cont)
        view.set_model(*((x, first.model) if first is not None else (None, None)))
        if second is not None and second.wave.size == wave.size:
            view.set_second_model(x, second.model)
        else:
            view.set_second_model(None, None)
        if first is not None and second is not None and second.wave.size == wave.size:
            with np.errstate(divide="ignore", invalid="ignore"):
                diff = np.where(error > 0, (second.model - first.model) / error, np.nan)
            widget.resid.set_residuals(x, diff)
            widget.resid.set_unfitted(FV.unfitted_spans(x, RS.counted(first)))
            biggest = np.nanmax(np.abs(diff[RS.counted(first)])) if diff.size else 0.0
            widget.marks.setText(
                "largest difference {0:.1f}σ".format(biggest)
                if np.isfinite(biggest)
                else ""
            )
        else:
            widget.resid.set_residuals(None, None)
            widget.resid.set_unfitted([])
            widget.marks.setText(FV.NOT_FITTED if base is None else "")
        view.set_regions("fit", panel.regions())
        view.set_home(panel.home(), NORMALISED_Y if cont is not None else None)


