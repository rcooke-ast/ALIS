    # -- acting ---------------------------------------------------------------------------

    def _act(self, name, handler):
        """Run a handler through the window (typing read first, errors reported)."""
        if self.main is not None:
            self.main._run("data." + name, handler)
        else:
            handler()

    def _do(self, step):
        """Make a step through the history."""
        if step is not None and step:
            self.session.history.do(step)

    def _gate(self):
        return BL.Gate(self.session.project)

    def _pref(self, key, default):
        """A preference, or its default without a window (tests)."""
        prefs = getattr(self.main, "prefs", None)
        try:
            return prefs[key] if prefs is not None else default
        except KeyError:
            return default

    # -- refreshing ---------------------------------------------------------------------

    def refresh(self, session):
        """
        Redraw the tab from the project (after every step, undo and redo).

        Generated by RJC and Claude.
        """
        self.session = session
        if session is None:
            return
        project = session.project
        if project.paused:
            return
        gate = self._gate()
        self._refresh_systems(project, gate)
        self._refresh_files(project, gate)
        self._refresh_coverage(project)
        self._refresh_blinding(project)
        self._refresh_spectrum(project)

    def _primary(self, project):
        return next((s for s in project.systems if s.primary), None)

    def _refresh_systems(self, project, gate):
        primary = self._primary(project)
        if not self.z_edit.hasFocus():
            self.z_edit.setText(gate.system_z(primary) if primary else "")
        self.others.clear()
        snip_map = L.snip_transitions(project)
        for system in project.systems:
            if system.primary:
                continue
            names = DS.system_lines(project, system, snip_map)
            text = system.name + (" · " + ", ".join(names) if names else "")
            item = QtWidgets.QListWidgetItem(gate.message(text))
            item.setData(QtCore.Qt.ItemDataRole.UserRole, system.id)
            self.others.addItem(item)
        if not self.others.count():
            item = QtWidgets.QListWidgetItem("No other systems")
            item.setFlags(QtCore.Qt.ItemFlag.NoItemFlags)
            self.others.addItem(item)
        generic = DS.generic_summary(project)
        self.generic.setText("Generic absorbers · " + generic if generic else "")
        self.generic.setVisible(bool(generic))
        self.systems_note.setVisible(project.inferred)
        self.confirm.setVisible(project.inferred)
        self.files_note.setText(
            (INFERRED + " ") * project.inferred
            + "Click a badge to free, fix or tie a value to another dataset;"
            " double-click a value to type it. Right-click a row for more."
        )

    def _states(self, project):
        path = self.session.path
        out = {}
        for entry, state in SR.states(project.bundle, path):
            out[entry["id"]] = state
        return out

    def _spectrum_of(self, row):
        return SR.spectrum(self.session.project, row, self.session.path)

    def _refresh_files(self, project, gate):
        states = self._states(project)
        rows = project.rows
        keep = self.selected
        self.table.blockSignals(True)
        self.table.setRowCount(len(rows))
        for num, row in enumerate(rows):
            spec = self._spectrum_of(row) if row.source else None
            state = states.get(row.source["id"]) if row.source else None
            cells = [
                "◉" if row.reference else "○",
                row.name,
                DS.contents(row, spec),
                self._value_text(gate, row, "resolution"),
                self._shift_text(gate, row),
                "On" if row.zero is not None else "Off",
                DS.checksum(state) + (" · Relink…" if state == SR.MISSING else ""),
            ]
            for col, text in enumerate(cells):
                item = QtWidgets.QTableWidgetItem(text)
                item.setData(QtCore.Qt.ItemDataRole.UserRole, row.id)
                if col == 0:
                    item.setTextAlignment(QtCore.Qt.AlignmentFlag.AlignCenter)
                    item.setToolTip(
                        "The reference: its shift is 0"
                        if row.reference
                        else "Click to make this the reference"
                    )
                if col in (3, 4):
                    what = "resolution" if col == 3 else "shift"
                    item.setToolTip(self._badge_tip(project, row, what))
                if col == 5:
                    item.setToolTip("Click to switch the zero level on or off")
                if col == 6 and state == SR.MISSING:
                    item.setToolTip("The file has moved: click to relink it")
                self.table.setItem(num, col, item)
        self.table.blockSignals(False)
        self.table.resizeColumnsToContents()
        ids = [r.id for r in rows]
        if keep not in ids:
            keep = ids[0] if ids else None
        self.selected = keep
        if keep is not None:
            self.table.selectRow(ids.index(keep))

    def _badge(self, project, row, what):
        state = DS.state_of(row, what)
        if state is None:
            return ""
        if DS.tied_to(project, row, what):
            state = DS.TIED
        return BADGES[state]

    def _badge_tip(self, project, row, what):
        state = DS.state_of(row, what)
        if state is None:
            return ""
        others = DS.tied_to(project, row, what)
        if others:
            return BADGE_TIPS[DS.TIED] + " (" + ", ".join(r.name for r in others) + ")"
        return BADGE_TIPS[state] + "; click the badge to change it"

    def _value_text(self, gate, row, what):
        if not row.snips:
            entry = next(
                (
                    e
                    for e in self.session.project.ui.get("rows", [])
                    if e.get("id") == row.id
                ),
                {},
            )
            return "{0:g}".format(entry["fwhm"]) if "fwhm" in entry else "—"
        par = row.snips[0].data.param(what)
        if par is None:
            return "—"
        return gate.value(par) + " " + self._badge(self.session.project, row, what)

    def _shift_text(self, gate, row):
        if row.reference:
            return "0 · reference"
        if not row.snips:
            return "free, once it has a snip"
        par = row.snips[0].data.param("shift")
        if par is None or "shift" not in row.snips[0].data.keywords:
            return "0"
        return gate.value(par) + " " + self._badge(self.session.project, row, "shift")

    def _refresh_coverage(self, project):
        rows = project.rows
        self.coverage.setVisible(len(rows) > 1)
        if len(rows) < 2:
            return
        primary = self._primary(project)
        if primary is None:
            self.grid.setRowCount(0)
            return
        covs = []
        for row in rows:
            spec = self._spectrum_of(row) if row.source else None
            if spec is not None:
                covs.append(L.coverage_of_spectrum(row.id, row.name, spec))
            else:
                covs.append(L.coverage_of_snips(row))
        grid = L.coverage_grid(project, primary, covs)
        self.grid.setColumnCount(1 + len(rows))
        self.grid.setHorizontalHeaderLabels(["Transition"] + [r.name for r in rows])
        self.grid.setRowCount(len(grid))
        self._grid = grid
        for num, entry in enumerate(grid):
            self.grid.setItem(num, 0, QtWidgets.QTableWidgetItem(entry.name))
            for col, cov in enumerate(covs, 1):
                item = QtWidgets.QTableWidgetItem(CELLS[entry.cells[cov.row]])
                item.setTextAlignment(QtCore.Qt.AlignmentFlag.AlignCenter)
                self.grid.setItem(num, col, item)
        self.grid.resizeColumnsToContents()

    def _refresh_blinding(self, project):
        self.blind_all.blockSignals(True)
        self.blind_all.setChecked(project.parsed.blind)
        self.blind_all.setEnabled(not project.parsed.blind)
        self.blind_all.blockSignals(False)
        items = BL.blinded_items(project)
        if items:
            self.blinded.setText("Blinded: " + ", ".join(items))
        elif project.parsed.blind:
            self.blinded.setText("Every best-fit value is hidden.")
        else:
            self.blinded.setText("Nothing is blinded in this project.")

    def _row(self, ident=None):
        project = self.session.project
        ident = self.selected if ident is None else ident
        for row in project.rows:
            if row.id == ident:
                return row
        return None

    def _refresh_spectrum(self, project):
        row = self._row()
        title = "Spectrum"
        if row is None:
            self.spectrum.title.setText(title)
            self.view.set_pieces([])
            self._drawn = None
            return
        spec = self._spectrum_of(row) if row.source else None
        if row.source:
            name = row.source["path"].replace("\\", "/").split("/")[-1]
            title += " · " + name
        else:
            title += " · " + row.name
        if spec is None and row.snips:
            title += " · its snips, each scaled to its peak"
        self.spectrum.title.setText(title)
        key = (
            row.id,
            row.source["sha256"] if row.source and spec is not None else None,
            tuple((s.member, id(s.pixels)) for s in row.snips) if spec is None else (),
        )
        if key != self._drawn:
            if spec is not None:
                self.view.set_data(spec.wave, spec.flux, spec.error, spec.mask)
            else:
                pieces = []
                for snip in row.snips:
                    pix = snip.pixels
                    if pix is None or not pix.wave.size:
                        continue
                    peak = np.nanpercentile(pix.flux, 98)
                    pieces.append((pix.wave, pix.flux / peak if peak else pix.flux))
                self.view.set_pieces(pieces)
            self.view.home()
            self.zoom.attach(self.view)
            self.zoom.remember()
            self._drawn = key
        self._draw_ids()

    def _draw_ids(self):
        if self.session is None or self.session.project.paused:
            return
        project = self.session.project
        primary = self._primary(project)
        on = self.show_ids.isChecked() and primary is not None
        self.all_lines.setEnabled(on)
        if primary is not None:
            self.show_ids.setText("Transitions of " + primary.name)
        if not on or self.view._wave is None:
            self.view.set_line_ids([])
            return
        (x0, x1), _ = self.view.view_range()
        ids, hidden = L.line_ids(
            project,
            x0,
            x1,
            reference=primary.id,
            show_all=self.all_lines.isChecked(),
            strong=self._pref("lines.strength", L.STRONG),
            systems=[primary],
        )
        self.view.set_line_ids([(i.observed, i.label, i.kind) for i in ids], hidden)

