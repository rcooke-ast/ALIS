    def identify_at(self, wave):
        """
        Open the Identify panel for a wavelength (the click, or a test).

        Generated by RJC and Claude.
        """
        project = self.session.project
        atom = L.atomic(project.registry)
        data_max = (
            float(np.nanmax(self.view._wave)) if self.view._wave is not None else None
        )
        cands, first = L.identify(atom, wave, data_max, [s.z for s in project.systems])
        self._candidates = cands
        self.view.set_marker(wave)
        self.identify_panel.show_for(wave, cands, first)
        holder = self.identify_panel.parentWidget()
        self.identify_panel.adjustSize()
        pos = self.view.box.mapViewToDevice(QtCore.QPointF(wave, 0.0))
        x = 20 if pos is None else int(pos.x()) + 12
        x = max(0, min(x, holder.width() - self.identify_panel.width()))
        self.identify_panel.move(x, 10)

