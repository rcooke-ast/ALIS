    def badge_menu(self, row, what, choice=None):
        """
        The badge's menu: Free, Fixed, or Tie to <row> (D35, Q0.8). ``choice`` makes
        the choice without the menu (tests).

        Generated by RJC and Claude.
        """
        project = self.session.project
        options = [("Free", DS.FREE, None), ("Fixed", DS.FIXED, None)]
        for other in project.rows:
            if other.id != row.id and other.snips:
                options.append(("Tie to " + other.name, DS.TIED, other))
        if choice is None:
            menu = QtWidgets.QMenu(self)
            actions = {
                menu.addAction(text): (state, other) for text, state, other in options
            }
            picked = menu.exec(QtGui.QCursor.pos())
            if picked is None:
                return
            state, other = actions[picked]
        else:
            state, other = next((s, o) for t, s, o in options if t == choice)
        self._act(
            "badge",
            lambda: self._do(DS.set_state_step(project, row, what, state, other)),
        )

