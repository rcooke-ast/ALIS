"""The Data tab (dashboard Stage 4.6; D35, S24, S25, D14–D16, F13, S3, Q4.14).

At the left, **Systems**, **Coverage** (with several files) and **Blinding**; at the
right, the **Datasets** table and the **Spectrum** of the selected row.

- **Systems** (D15, D16, S24 as revised in D35): the primary z, typed (Enter makes it
  one step); ⌖ Identify a feature…, which arms the spectrum: a click there opens a
  panel with Element → Ion → Transition menus, each transition with the z it implies,
  then "Set as primary z" or "Add as a new system"; the other systems, each with its
  transitions, and a right-click menu (Rename…, Make primary, Set z…, Remove…); the
  generic absorbers; Add system…. An imported fit's systems were worked out from the
  model: the pane says so, and Confirm keeps them (Q2.4, Q4.14).
- **Coverage** (Q0.5): ■ a snip, □ covered by the source, · not covered; a
  double-click opens the transition on the Regions tab.
- **Blinding** (D24, Q3.9): Blind the whole fit, what is blinded (no values), Blind
  lines… and Unblind….
- **Datasets** (S25, D14, D35, Q0.8): one row per file: the reference (◉), the
  file, its contents, its FWHM and shift (each with a badge: ● free, ■ fixed, ⛓ tied;
  a click on the badge offers Free, Fixed and Tie to <row>; a double-click on the
  value types a new one), its zero level (Off/On) and its checksum (Relink…). Add
  file… opens Stage 3's spectrum dialog; a right-click offers Make reference,
  Rename…, Column roles… and Remove….
- **Spectrum** (D35, S5): the selected row's source spectrum, or its snips each
  scaled to its own peak; Flux | Log; the primary system's transitions (with the number
  left unlabelled, and All lines); the zoom bar.

Every action is a step of the history, made through the window (``window._run``),
and every value is shown through the blinding gate.

Generated by RJC and Claude.
"""

