    def show_items(self, items):
        """
        Select what a line of the .mod panel describes: its row (S16).

        Generated by RJC and Claude.
        """
        if self.session is None:
            return
        for item in items:
            row = getattr(item, "row", None) if not hasattr(item, "snips") else item
