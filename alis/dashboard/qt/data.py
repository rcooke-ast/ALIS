class IdentifyPanel(QtWidgets.QFrame):
    """
    The panel Identify a feature opens beside a clicked point (D35): Element → Ion →
    Transition, each transition with the z it implies; Set as primary z, Add as a new
    system, Cancel.

    Signals
    -------
    chosen(str, float)
        ``"primary"`` or ``"new"``, and the redshift.

    Generated by RJC and Claude.
    """

    chosen = QtCore.Signal(str, float)

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setObjectName("pane")
        self.setAutoFillBackground(True)
        layout = QtWidgets.QVBoxLayout(self)
        layout.setContentsMargins(10, 8, 10, 8)
        self.where = QtWidgets.QLabel("")
        layout.addWidget(self.where)
        row = QtWidgets.QHBoxLayout()
        self.element = QtWidgets.QComboBox()
        self.stage = QtWidgets.QComboBox()
        self.transition = QtWidgets.QComboBox()
        self.transition.setMinimumWidth(190)
        for label, box in (
            ("Element", self.element),
            ("Ion", self.stage),
            ("Transition", self.transition),
        ):
            row.addWidget(QtWidgets.QLabel(label))
            row.addWidget(box)
        layout.addLayout(row)
        self.z = QtWidgets.QLabel("")
        layout.addWidget(self.z)
        buttons = QtWidgets.QHBoxLayout()
        self.primary = QtWidgets.QPushButton("Set as primary z")
        self.new = QtWidgets.QPushButton("Add as a new system")
        self.cancel = QtWidgets.QPushButton("Cancel")
        for button in (self.primary, self.new, self.cancel):
            buttons.addWidget(button)
        layout.addLayout(buttons)
        self.menus = {}
        self.element.currentIndexChanged.connect(self._fill_stages)
        self.stage.currentIndexChanged.connect(self._fill_transitions)
        self.transition.currentIndexChanged.connect(self._show_z)
        self.primary.clicked.connect(lambda: self._choose("primary"))
        self.new.clicked.connect(lambda: self._choose("new"))
        self.cancel.clicked.connect(self.hide)
        self.hide()

    def show_for(self, wave, candidates, first):
        """
        Offer the transitions that could make a feature at ``wave``.

        Parameters
        ----------
        wave : float
        candidates : list of lines.Candidate
        first : int or None
            The first choice.

        Generated by RJC and Claude.
        """
        self.menus = L.candidate_menus(candidates)
        self.where.setText("Clicked at {0:.2f} Å. Choose the transition:".format(wave))
        pick = candidates[first] if first is not None else None
        self.element.blockSignals(True)
        self.element.clear()
        for elem in self.menus:
            self.element.addItem(elem)
        self.element.blockSignals(False)
        if pick is not None:
            self.element.setCurrentText(pick.line.element)
        self._fill_stages()
        if pick is not None:
            self.stage.setCurrentText(pick.line.stage)
            self._fill_transitions()
            for num in range(self.transition.count()):
                if self.transition.itemData(num) is pick:
                    self.transition.setCurrentIndex(num)
        self._show_z()
        self.show()
        self.raise_()

    def _fill_stages(self):
        self.stage.blockSignals(True)
        self.stage.clear()
        for stage in self.menus.get(self.element.currentText(), {}):
            self.stage.addItem(stage)
        self.stage.blockSignals(False)
        self._fill_transitions()

    def _fill_transitions(self):
        self.transition.blockSignals(True)
        self.transition.clear()
        stages = self.menus.get(self.element.currentText(), {})
        for cand in stages.get(self.stage.currentText(), []):
            self.transition.addItem(
                "{0}    z = {1:.5f}".format(cand.name, cand.z), cand
            )
        self.transition.blockSignals(False)
        self._show_z()

    def current(self):
        """The candidate chosen, or None."""
        return self.transition.currentData()

    def _show_z(self):
        cand = self.current()
        self.z.setText("→ z = {0:.6f}".format(cand.z) if cand is not None else "")
        self.primary.setEnabled(cand is not None)
        self.new.setEnabled(cand is not None)

    def _choose(self, what):
        cand = self.current()
        if cand is not None:
            self.hide()
            self.chosen.emit(what, cand.z)


