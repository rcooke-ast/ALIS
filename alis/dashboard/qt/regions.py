    def _fill_orders(self, project, snip, function, order):
        """The table of orders (S8): χ², Δχ² and ΔBIC against the order chosen."""
        try:
            guess = CO.guess(
                project,
                snip,
                function,
                self._max_order(),
                orders=[o for o in (order - 1, order, order + 1) if o >= 0],
                **self._options(),
            )
            table = guess.table(order) if order in guess.fits else []
        except CO.ContinuumError:
            table = []
        self.orders.setRowCount(len(table))
        for num, (n, chi2, dchi2, dbic) in enumerate(table):
            cells = (
                str(n),
                "{0:.1f}".format(chi2),
                "{0:+.1f}".format(dchi2) if n != order else "—",
                "{0:+.1f}".format(dbic) if n != order else "—",
            )
            for col, text in enumerate(cells):
                item = QtWidgets.QTableWidgetItem(text)
                if n == order:
                    font = item.font()
                    font.setBold(True)
                    item.setFont(font)
                self.orders.setItem(num, col, item)

    def _fill_sharing(self, project, snip):
        """Sharing the continuum with the same transition in other datasets (S10)."""
        line = snip.continuum
        notes = []
        if line.line in project.hidden_lines():
            notes.append(
                "This continuum is hidden: it is drawn, and its coefficients are not"
                " shown."
            )
        others = [s for s in project.snips if s.specid in line.specids]
        others = [s for s in others if s.specid != snip.specid]
        if others:
            names = [s.row.name if s.row is not None else s.specid for s in others]
            notes.append("Shared with {0}.".format(", ".join(names)))
            button = QtWidgets.QPushButton("Unshare")
            button.setObjectName("unshare")
            button.clicked.connect(lambda: self._act("regions.unshare", self.unshare))
            self.share_row.addWidget(button)
        else:
            trans = self._snip_map.get(snip.specid)
            same = {}
            if trans is not None:
                same = SN.snips_of(
                    project, trans.system, trans.ion, trans.rest, self._snip_map
                )
            for row_id, other in same.items():
                if other.specid == snip.specid:
                    continue
                button = QtWidgets.QPushButton("Share with " + self._row_name(row_id))
                button.setObjectName("share_" + row_id)
                why = CO.shareable(project, [snip, other])
                button.setEnabled(not why)
                button.setToolTip(
                    why or "One continuum for this transition in both datasets"
                )
                button.clicked.connect(
                    lambda _=False, o=other.specid: self._act(
                        "regions.share", lambda: self.share_with(o)
                    )
                )
                self.share_row.addWidget(button)
        self.share_row.addStretch(1)
        self.share_label.setText(" ".join(notes))

