    def _fill_elements(self):
        system = self._system()
        self.element_box.clear()
        self.ion_box.clear()
        self._elements = {}
        if system is None:
            return
        atom = L.atomic(self.session.project.registry)
        snipped = L.snipped_by_ion(self._snip_map, system.id)
        found = L.elements_on_data(
            atom,
            system.z,
            self._coverages(),
            snipped,
            half_width=self._pref("regions.half_width", L.HALF_WIDTH),
        )
        if not self._spectra:
            # Without a source only the snipped transitions are listed: offer only
            # the elements and stages that have one
            found = {
                elem: [
                    st for st in stages if snipped.get(atom.main_ion.get((elem, st)))
                ]
                for elem, stages in found.items()
            }
            found = {elem: stages for elem, stages in found.items() if stages}
        self._elements = found
        for element in found:
            self.element_box.addItem(element)
        ion = self.state.get("ion")
        if ion is not None:
            for (elem, stage), main in atom.main_ion.items():
                if main == ion and stage in found.get(elem, ()):
                    self.state["element"], self.state["stage"] = elem, stage
        element = self.state.get("element")
        if element not in found:
            element = next(iter(found), None)
        if element is None:
            self.state.pop("element", None)
            return
        self.state["element"] = element
        self.element_box.setCurrentIndex(self.element_box.findText(element))
        stages = found[element]
        stage = self.state.get("stage")
        if stage not in stages:
            stage = stages[0]
        self.state["stage"] = stage
        for name in stages:
            self.ion_box.addItem(name)
        self.ion_box.setCurrentIndex(stages.index(stage))

