    def bind_action(self, name, action):
        """
        The tab's own actions: what acts on the spectra above them (SNIP, CLEAR, Add
        region, Exclude pixels), what acts on the continuum in its box (Auto first
        guess, Add knot, Normalised), and the keys.

        Generated by RJC and Claude.
        """
        self.actions_[name] = action
        if name in TOOL_BUTTONS:
            button = QtWidgets.QToolButton()
            button.setDefaultAction(action)
            button.setObjectName(name.replace(".", "_"))
            if name == "regions.snip":
                button.setStyleSheet("font-weight: 600;")
            if name == "regions.draw":
                line = QtWidgets.QFrame()
                line.setFrameShape(QtWidgets.QFrame.Shape.VLine)
                line.setFrameShadow(QtWidgets.QFrame.Shadow.Sunken)
                self.tool_layout.addWidget(line)
                self.tool_layout.addWidget(QtWidgets.QLabel("Fit regions:"))
            self.tool_layout.addWidget(button)
            self.tab_buttons.append(button)
        elif name in CONTINUUM_BUTTONS:
            button = QtWidgets.QToolButton()
            button.setDefaultAction(action)
            button.setObjectName(name.replace(".", "_"))
            self._continuum_buttons[name] = button
            self._order_continuum_tools()
            self.tab_buttons.append(button)
        else:
            holder = {
                "regions.remove_region": self.holder,
                "regions.order_down": self.order_down,
                "regions.order_up": self.order_up,
                "regions.previous_element": self.prev_element,
                "regions.next_element": self.next_element,
            }.get(name, self.listing)
            if isinstance(holder, QtWidgets.QToolButton):
                holder.setToolTip(action.toolTip())
            self.tab_buttons.append(KeyHolder(holder, action))

    def _order_continuum_tools(self):
        """Auto first guess, Add knot and Clear knots, then Normalised at the right."""
        while self.continuum_tools.count():
            self.continuum_tools.takeAt(0)
        names = ("regions.auto", "regions.knot")
        for name in names:
            if name in self._continuum_buttons:
                self.continuum_tools.addWidget(self._continuum_buttons[name])
        self.continuum_tools.addWidget(self.clear_knots)
        self.continuum_tools.addStretch(1)
        if "regions.normalised" in self._continuum_buttons:
            self.continuum_tools.addWidget(
                self._continuum_buttons["regions.normalised"]
            )

    # -- acting ---------------------------------------------------------------------------

    def _act(self, name, handler):
        """Run a handler through the window (typing read first, errors reported)."""
        if self.main is not None:
            self.main._run(name, handler)
        else:
            handler()

    def _do(self, step):
        """Make a step through the history."""
        if step is not None and step:
            self.session.history.do(step)

    def _warn(self, title, text):
        if self.main is not None:
            self.main.tell(title, text, "warning")

    def _pref(self, key, default):
        prefs = getattr(self.main, "prefs", None)
        try:
            return prefs[key] if prefs is not None else default
        except KeyError:
            return default

    def _options(self):
        """The continuum's fitting preferences."""
        return {
            "clip": (
                self._pref("continuum.clip_below", CO.CLIP[0]),
                self._pref("continuum.clip_above", CO.CLIP[1]),
            ),
            "line_kms": self._pref("continuum.line_width", CO.LINE_KMS),
        }

    def _max_order(self):
        return self._pref("continuum.max_order", CO.AUTO_MAX)

    # -- the state ----------------------------------------------------------------------

    def _system(self):
        if self.session is None:
            return None
        systems = self.session.project.systems
        ident = self.state.get("system")
        for system in systems:
            if system.id == ident:
                return system
        return next((s for s in systems if s.primary), systems[0] if systems else None)

    def _remember(self):
        """Keep where the tab is in the view state (saved with the project)."""
        if self.session is not None:
            data = {
                k: self.state[k] for k in ("system", "ion", "rest") if k in self.state
            }
            data["row"] = self.selected
            self._seen_view = data
            self.session.set_view("regions", data)

    def current_line(self):
        """The transition shown, as a ``lines.Line``, or None."""
        ion, rest = self.state.get("ion"), self.state.get("rest")
        if ion is None or rest is None or self.session is None:
            return None
        atom = L.atomic(self.session.project.registry)
        for line in atom.ion_lines(ion):
            if abs(line.rest - rest) < 0.01:
                return line
        return None

    def current_strip(self):
        """The selected dataset's spectrum, or None."""
        for strip in self.strips:
            if strip.row_id == self.selected:
                return strip
        return None

    def current_snip(self):
        """The selected dataset's snip of the transition shown, or None."""
        strip = self.current_strip()
        if strip is None or strip.snip is None:
            return None
        return self._snip(strip.snip.specid)

    def _snip(self, specid):
        """The project's snip of a specid now, or None (merged or cleared)."""
        try:
            return self.session.project.snip(specid)
        except P.ProjectError:
            return None

    def _row_name(self, row_id):
        for row in self.session.project.rows:
            if row.id == row_id:
                return row.name
        return ""

