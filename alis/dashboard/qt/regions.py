def swatch(kind, size=14):
    """
    A small picture of one item of the key, drawn as the spectrum draws it.

    Generated by RJC and Claude.
    """
    pix = QtGui.QPixmap(size * 2, size)
    pix.fill(QtCore.Qt.GlobalColor.transparent)
    paint = QtGui.QPainter(pix)
    paint.setRenderHint(QtGui.QPainter.RenderHint.Antialiasing)
    rect = QtCore.QRectF(1, 2, size * 2 - 2, size - 4)
    middle = QtCore.QPointF(size, 1), QtCore.QPointF(size, size - 1)
    if kind in ("fit", "other"):
        paint.fillRect(rect, QtGui.QColor(*PL.COLOURS[kind]))
    elif kind == "shared":
        brush = QtGui.QBrush(
            QtGui.QColor(PL.COLOURS["shared"]), QtCore.Qt.BrushStyle.BDiagPattern
        )
        paint.fillRect(rect, brush)
    elif kind == "edge":
        paint.setPen(QtGui.QPen(QtGui.QColor(PL.COLOURS["edge"]), 4))
        paint.drawLine(*middle)
    elif kind == "continuum":
        pen = QtGui.QPen(QtGui.QColor(PL.COLOURS["continuum"]), 2)
        pen.setStyle(QtCore.Qt.PenStyle.DashLine)
        paint.setPen(pen)
        paint.drawLine(
            QtCore.QPointF(1, size / 2), QtCore.QPointF(size * 2 - 1, size / 2)
        )
    elif kind == "knot":
        paint.setPen(QtGui.QPen(QtGui.QColor(PL.COLOURS["knot"]), 2))
        paint.drawRect(QtCore.QRectF(size - 4, size / 2 - 4, 8, 8))
    else:
        colour, _, style = PL.LINE_ID_STYLE[{"ids_other": "other"}.get(kind, kind)]
        pen = QtGui.QPen(QtGui.QColor(colour), 2)
        pen.setStyle(style)
        paint.setPen(pen)
        paint.drawLine(*middle)
    paint.end()
    return pix


def compact(table, rows):
    """A table with short rows, as high as its header and ``rows`` rows."""
    table.verticalHeader().setDefaultSectionSize(22)
    table.verticalHeader().setMinimumSectionSize(18)
    table.setMaximumHeight(26 + 22 * rows)


def flam_bar(below):
    """
    The fλ column's bar: full for the strongest transition, a fifth shorter for
    each factor of ten below it.

    Generated by RJC and Claude.
    """
    pix = QtGui.QPixmap(BAR_WIDTH, 10)
    pix.fill(QtCore.Qt.GlobalColor.transparent)
    paint = QtGui.QPainter(pix)
    width = max(2, int(round(BAR_WIDTH * max(0.0, 1.0 - 0.2 * below))))
    paint.fillRect(QtCore.QRectF(0, 1, width, 8), QtGui.QColor(PL.COLOURS["data"]))
    paint.end()
    return QtGui.QIcon(pix)


