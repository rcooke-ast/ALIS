    def refresh(self, session):
        """
        Redraw the tab from the project (after every step, undo and redo); while
        another tab is shown, only once it is shown again.

        Generated by RJC and Claude.
        """
        if session is not self.session:
            self.state, self.selected, self._seen_view = {}, None, None
            self._shown_key = None
        self.session = session
        if session is None or session.project.paused:
            return
        if self.main is not None and self.main.tabs.currentWidget() is not self:
            self._stale = True
            return
        self._stale = False
        stored = session.view.get("regions") or {}
        if stored != self._seen_view:
            # Set elsewhere (the Data tab's coverage grid, a project opened)
            self.state = {
                k: stored[k] for k in ("system", "ion", "rest") if k in stored
            }
            self.selected = stored.get("row")
            self._seen_view = dict(stored)
        project = session.project
        self._spectra = {}
        for row in project.rows:
            spec = SR.spectrum(project, row, session.path)
            if spec is not None:
                self._spectra[row.id] = spec
        self._snip_map = L.snip_transitions(project)
        self._filling = True
        try:
            self._fill_systems()
            self._fill_elements()
            self._fill_list()
        finally:
            self._filling = False
        self._fill_strips()
        self._fill_boxes()

    def _tab_shown(self, index):
        if self.main.tabs.widget(index) is self and self._stale:
            self.refresh(self.session)

    def _coverages(self):
        """Where each row has data: its source, or else its snips (D12)."""
        out = []
        for row in self.session.project.rows:
            spec = self._spectra.get(row.id)
            if spec is not None:
                out.append(L.coverage_of_spectrum(row.id, row.name, spec))
            else:
                out.append(L.coverage_of_snips(row))
        return out

