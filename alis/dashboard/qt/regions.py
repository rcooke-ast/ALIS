    @staticmethod
    def _buffer_text(snip, buffers):
        """
        The buffers in Å, as the mockup gives them: "Buffer 1.57 Å blue, 2.84 Å red
        · needs ≥ 0.26 Å ✓".

        Generated by RJC and Claude.
        """
        if not buffers:
            return ""
        wave = snip.pixels.wave[SN.fitted(snip)]
        edge = {"blue": float(wave.min()), "red": float(wave.max())}
        have = [
            "{0:.2f} Å {1}".format(b.have * edge[b.side] / C_KMS, b.side)
            for b in buffers
        ]
        need = max(b.need * edge[b.side] / C_KMS for b in buffers)
        short = [b.side for b in buffers if not b.ok]
        return "Buffer {0} · needs ≥ {1:.2f} Å {2}".format(
            ", ".join(have),
            need,
            (
                "✓"
                if not short
                else "! (too narrow on the {0})".format(" and ".join(short))
            ),
        )

    def _fill_datasets(self, project):
        """Each dataset's snip of the transition: fitted, shared, regions' origin."""
        self.datasets.setRowCount(len(self._rows))
        for num, (row, one) in enumerate(self._rows):
            one = project.snip(one.specid) if one is not None else None
            if one is None or one.pixels is None:
                cells = [row.name, "—", "—", "no snip"]
            else:
                shared = sum(p.count for p in SN.shared_pixels(project, one))
                cells = [
                    row.name,
                    str(int(SN.fitted(one).sum())),
                    str(shared),
                    SN.origin(project, one),
                ]
            for col, text in enumerate(cells):
                self.datasets.setItem(num, col, QtWidgets.QTableWidgetItem(text))
            if row.id == self.selected:
                self.datasets.selectRow(num)

    def _update_snip(self, found=()):
        """SNIP: while a dataset whose source covers the transition has no snip."""
        action = self.actions_.get("regions.snip")
        if action is None:
            return
        spec = A.get("regions.snip")
        if not self._spectra:
            action.setEnabled(False)
            action.setToolTip(
                "SNIP needs a source spectrum, which this project does not have"
            )
            return
        action.setToolTip(spec.tip)
        action.setEnabled(any(snip is None for _, snip in found))

