        """‹ ›: the ion stage below or above (no further than the first or last)."""
        count = self.ion_box.count()
        index = min(max(self.ion_box.currentIndex() + by, 0), count - 1)
        if count and index != self.ion_box.currentIndex():
            self.ion_box.setCurrentIndex(index)

