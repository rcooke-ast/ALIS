    def _draw_strip(self, strip, row, snip, line, system):
        project = self.session.project
        view = strip.view
        shift = SN.row_shift(row)
        view.set_velocity_centre(line.rest * (1.0 + system.z) * (1.0 + shift / C_KMS))
        spec = self._spectra.get(row.id)
        if snip is not None and snip.pixels is not None:
            pix = snip.pixels
            view.set_data(pix.wave, pix.flux, pix.error, pix.bad)
            curve = CO.evaluate(project, snip)
            strip.curve = curve
            normalised = self._normalised() and curve is not None
            view.set_normalised(curve if normalised else None)
            if curve is not None:
                view.set_continuum(pix.wave, curve)
            low, high = snip.extent
            if spec is not None and not normalised:
                width = high - low
                sel = (spec.wave >= low - 0.6 * width) & (
                    spec.wave <= high + 0.6 * width
                )
                view.set_context(spec.wave[sel], spec.flux[sel])
            view.set_regions(
                "fit", SN.regions_of(snip), movable=self._mode in REGION_TOOLS
            )
            view.set_regions("other", self._other_regions(row, snip, low, high))
            view.set_regions("shared", self._shared_spans(snip))
            view.set_edges(low, high)
            knots = CO.knots_of(project, snip)
            if normalised:
                knots = [(x, y / strip.continuum_at(x)) for x, y in knots]
            view.set_knots(knots)
            pad = 0.04 * (high - low)
            view.set_home((low - pad, high + pad), NORMALISED_Y if normalised else None)
        elif spec is not None:
            low, high = SN.window(
                line.rest,
                system.z,
                shift,
                self._pref("regions.half_width", L.HALF_WIDTH),
            )
            width = high - low
            sel = (spec.wave >= low - 0.5 * width) & (spec.wave <= high + 0.5 * width)
            view.set_data(spec.wave[sel], spec.flux[sel], spec.error[sel])
            view.set_home((low, high))
        view.home()

    def _other_regions(self, row, snip, low, high):
        """The regions other snips of the row fit within this snip's extent."""
        out = []
        for other in row.snips:
            if other.specid == snip.specid or other.pixels is None:
                continue
            for a, b in SN.regions_of(other):
                if b >= low and a <= high:
                    out.append((max(a, low), min(b, high)))
        return out

    def _shared_spans(self, snip):
        """The pixels the snip shares with another, as wavelength spans."""
        spans = []
        wave = snip.pixels.wave
        for pair in SN.shared_pixels(self.session.project, snip):
            mask = np.zeros(wave.size, dtype=bool)
            mask[pair.pixels_of(snip)] = True
            spans += P.mask_regions(wave, mask)
        return spans

