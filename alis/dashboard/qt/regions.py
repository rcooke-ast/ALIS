class Strip(QtWidgets.QFrame):
    """
    One dataset's spectrum of the transition shown, with its title.

    Generated by RJC and Claude.
    """

    def __init__(self, row_id, parent=None):
        super().__init__(parent)
        self.row_id = row_id
        self.snip = None
        self.curve = None
        self.setObjectName("spectrumStrip")
        layout = QtWidgets.QVBoxLayout(self)
        layout.setContentsMargins(4, 2, 4, 2)
        layout.setSpacing(0)
        self.title = QtWidgets.QLabel("")
        layout.addWidget(self.title)
        self.view = PL.SpectrumView()
        self.view.setMinimumHeight(110)
        layout.addWidget(self.view, 1)
        self.set_selected(False)

    def set_selected(self, on):
        """Frame the selected dataset's spectrum."""
        colour = PL.COLOURS["selected"] if on else "transparent"
        self.setStyleSheet(
            "QFrame#spectrumStrip {{ border: 2px solid {0}; border-radius: 4px; }}"
            "".format(colour)
        )
        font = self.title.font()
        font.setBold(on)
        self.title.setFont(font)

    def continuum_at(self, x):
        """The continuum drawn at a wavelength, or None."""
        if self.curve is None or self.snip is None or self.snip.pixels is None:
            return None
        return float(np.interp(x, self.snip.pixels.wave, self.curve))


