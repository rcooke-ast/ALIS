    def show_items(self, items):
        """
        Select what a line of the .mod panel describes: its snip's transition and
        dataset, or the snip of a continuum (S16).

        Generated by RJC and Claude.
        """
        if self.session is None or self.session.project.paused:
            return
        snip_map = L.snip_transitions(self.session.project)
        for item in items:
            specid = getattr(item, "specid", None)
            if specid is None and hasattr(item, "specids"):
                specids = item.specids
                specid = specids[0] if specids else None
            trans = snip_map.get(specid) if specid else None
            if trans is None or not trans.system:
                continue
            snip = self.session.project.snip(specid)
            row = snip.row.id if snip is not None and snip.row is not None else None
            self.show_transition(trans.system, trans.ion, trans.rest, row)
            return

    def show_transition(self, system, ion, rest, row=None):
        """
        Show a transition of a system (an id), and select a dataset.

        Generated by RJC and Claude.
        """
        same = (
            self.state.get("system") == system
            and self.state.get("ion") == ion
            and abs(self.state.get("rest", -1.0) - rest) < 0.01
        )
        if same and (row is None or row == self.selected):
            return
        self.state = {"system": system, "ion": ion, "rest": rest}
        if row is not None:
            self.selected = row
        self._remember()
        self.refresh(self.session)

