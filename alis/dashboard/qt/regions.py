    def copy_regions(self, only_empty=False):
        """
        Use the selected dataset's regions in every other dataset of the transition
        (D18), or only in those with none: an imported fit's datasets may have regions
        of their own; edits made here are the same in every dataset already (Q4.19).

        Generated by RJC and Claude.
        """
        snip = self.current_snip()
        if snip is None:
            return
        project = self.session.project
        targets = [
            project.snip(one.specid)
            for _, one in self._rows
            if one is not None and one.specid != snip.specid
        ]
        if not targets:
            self._warn(
                "Copy regions",
                "No other dataset has a snip of this transition: SNIP cuts one.",
            )
            return
        try:
            step = SN.copy_regions_step(project, snip, targets, only_empty=only_empty)
        except SN.SnipError as error:
            self._warn("Copy regions", str(error))
            return
        self._do(step)

