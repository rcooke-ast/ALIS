    def draw(self, row_id, low, high, linked=True):
        """
        A region added on a dataset's spectrum, as one step: on a transition that is
        not a snip there yet, SNIP first (Q4.2(c)); the region is then added in every
        dataset of the transition (Q4.19), or in this one alone (``linked`` False:
        Tweak dataset regions).

        Generated by RJC and Claude.
        """
        line = self.current_line()
        if line is None:
            return
        history = self.session.history
        with history.group("Add a fit region to {0}".format(line.name)):
            if self._snip_of_row(row_id) is None:
                try:
                    step = SN.snip_step(
                        self.session.project,
                        self._system(),
                        line,
                        self._spectra,
                        half_width=self._pref("regions.half_width", L.HALF_WIDTH),
                        max_order=self._max_order(),
                        **self._options(),
                    )
                except SN.SnipError as error:
                    self._warn("Add region", str(error))
                    return
                history.do(step)
            snip = self._snip_of_row(row_id)
            if snip is None:
                return
            self.edit_regions(snip, [("add", low, high)], "Add a fit region to", linked)

    def edit_regions(self, snip, edits, what, linked=True):
        """
        Add or take out wavelength spans of the fit, the same in every dataset of the
        transition (Q4.19), or in the snip's dataset alone (``linked`` False):
        ``edits`` as :func:`snips.linked_step` takes them.

        Generated by RJC and Claude.
        """
        project = self.session.project
        snip_map = L.snip_transitions(project)
        if linked:
            name = SN.linked_name(project, snip, what, snip_map)
        else:
            trans = SN.transition_name(snip_map.get(snip.specid)) or snip.specid
            row = snip.row.name if snip.row is not None else snip.specid
            name = "{0} {1} in {2}".format(what, trans, row)
        self._do(SN.linked_step(project, snip, edits, name, snip_map, linked=linked))

    def exclude(self, row_id, low, high, linked=False):
        """
        Leave the pixels between two wavelengths out of the fit (a right-drag): in
        this dataset alone (a cosmic ray, a bad pixel), or in every dataset.

        Generated by RJC and Claude.
        """
        snip = self._snip_of_row(row_id)
        if snip is None or snip.pixels is None:
            return
        if linked:
            self.edit_regions(snip, [("remove", low, high)], "Exclude pixels of")
        else:
            self._do(SN.mask_step(self.session.project, snip, low, high))

    def _edge(self, strip, side, x, done):
        if not done or strip.snip is None:
            return
        snip = self._snip(strip.snip.specid)
        low, high = snip.extent
        low, high = (x, high) if side == "low" else (low, x)
        low, high = min(low, high), max(low, high)
        self._act("regions.edges", lambda: self.move_edges(strip.row_id, low, high))

    def move_edges(self, row_id, low, high):
        """
        Move a snip's edges (S6): outwards, more pixels are cut from the source.

        Generated by RJC and Claude.
        """
        snip = self._snip_of_row(row_id)
        if snip is None:
            return
        try:
            step = SN.edges_step(
                self.session.project, snip, low, high, self._spectra.get(row_id)
            )
        except SN.SnipError as error:
            self._warn("The snip's edges", str(error))
            return
        self._do(step)

    def _region_moved(self, strip, index, low, high):
        if strip.snip is None:
            return
        self._act("regions.region", lambda: self.move_region(strip, index, low, high))

    def move_region(self, strip, index, low, high):
        """
        A fit region's edges dragged: the pixels between each old edge and its new
        place are added or taken out, in every dataset (Q4.19); what was excluded
        inside the region stays excluded.

        Generated by RJC and Claude.
        """
        snip = self._snip(strip.snip.specid)
        regions = SN.regions_of(snip)
        if snip is None or not 0 <= index < len(regions):
            return
        old_low, old_high = regions[index]
        low, high = sorted((float(low), float(high)))
        tiny = 1.0e-9 * old_high
        edits = []
        if low < old_low:
            edits.append(("add", low, old_low))
        elif low > old_low:
            edits.append(("remove", old_low, low - tiny))
        if high > old_high:
            edits.append(("add", old_high, high))
        elif high < old_high:
            edits.append(("remove", high + tiny, old_high))
        if edits:
            self.edit_regions(snip, edits, "Move a fit region of", self._linked())

    def do_remove_region(self):
        """
        Delete: remove the fit region last clicked in the selected dataset's spectrum
        (as the right-click menu does).

        Generated by RJC and Claude.
        """
        if self._last_click is None or self._last_click[0] != self.selected:
            return
        snip = self.current_snip()
        if snip is None or snip.pixels is None:
            return
        x = self._last_click[1]
        for a, b in SN.regions_of(snip):
            if a <= x <= b:
                self.edit_regions(
                    snip, [("drop", a, b)], "Remove a fit region of", self._linked()
                )
                return

    def context_actions(self, strip, x):
        """
        What a right-click on a spectrum offers: ``[(text, handler), ...]``. With
        several datasets, a region is removed from every dataset or from this one
        alone; while tweaking, the pixel clicked can be left out of this dataset.

        Generated by RJC and Claude.
        """
        out = []
        if strip.snip is None or strip.snip.pixels is None:
            return out
        snip = self._snip(strip.snip.specid)
        regions = SN.regions_of(snip)
        several = len(self._rows) > 1
        what = "Remove a fit region of"

        def remove(a, b, linked):
            return lambda: self._act(
                "regions.region",
                lambda: self.edit_regions(snip, [("drop", a, b)], what, linked),
            )

        for a, b in regions:
            if not a <= x <= b:
                continue
            if several:
                out.append(
                    ("Remove this region from every dataset", remove(a, b, True))
                )
                out.append(
                    ("Remove this region from this dataset only", remove(a, b, False))
                )
            else:
                out.append(("Remove this region", remove(a, b, True)))
            if self._mode == "regions.tweak":
                out.append(
                    (
                        "Exclude this pixel",
                        lambda: self._act(
                            "regions.exclude",
                            lambda: self.exclude(strip.row_id, x, x, False),
                        ),
                    )
                )
        if regions and several:
            out.append(
                (
                    "Use these regions in every dataset",
                    lambda: self._act("regions.copy", lambda: self.copy_regions(False)),
                )
            )
        return out

    def _menu(self, strip, x, pos):
        self.select_row(strip.row_id)
        self._last_click = (strip.row_id, x)
        entries = self.context_actions(strip, x)
        if not entries:
            return
        menu = QtWidgets.QMenu(self)
        for text, handler in entries:
            menu.addAction(text, handler)
        point = pos.toPoint() if hasattr(pos, "toPoint") else QtGui.QCursor.pos()
        menu.exec(point)

