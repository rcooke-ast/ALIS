def _first_family(families, fallback):
    """The first of some font families that is installed."""
    have = set(QtGui.QFontDatabase.families())
    for family in families:
        if family in have:
            return family
    return fallback


def ui_font():
    """
    The window's font: the system's own sans-serif, at 13 px.

    Generated by RJC and Claude.
    """
    font = QtGui.QFont(_first_family(UI_FAMILIES, QtGui.QFont().family()))
    font.setPixelSize(13)
    return font


def mono_font():
    """
    The ``.mod`` panel's font: a fixed-width face, at 12 px.

    Generated by RJC and Claude.
    """
    fixed = QtGui.QFontDatabase.systemFont(QtGui.QFontDatabase.SystemFont.FixedFont)
    font = QtGui.QFont(_first_family(MONO_FAMILIES, fixed.family()))
    font.setStyleHint(QtGui.QFont.StyleHint.Monospace)
    font.setPixelSize(12)
    return font


def palette():
    """
    The light palette (Q3.10).

    Generated by RJC and Claude.
    """
    pal = QtGui.QPalette()
    role = QtGui.QPalette.ColorRole
    group = QtGui.QPalette.ColorGroup
    colours = {
        role.Window: GREY["window"],
        role.WindowText: GREY["text"],
        role.Base: GREY["base"],
        role.AlternateBase: "#f5f5f5",
        role.Text: GREY["text"],
        role.Button: "#f0f0f0",
        role.ButtonText: GREY["text"],
        role.ToolTipBase: "#ffffe8",
        role.ToolTipText: GREY["text"],
        role.Highlight: OKABE_ITO["blue"],
        role.HighlightedText: "#ffffff",
        role.Link: OKABE_ITO["blue"],
        role.PlaceholderText: GREY["muted"],
    }
    for name, colour in colours.items():
        pal.setColor(name, QtGui.QColor(colour))
    for name in (role.WindowText, role.Text, role.ButtonText):
        pal.setColor(group.Disabled, name, QtGui.QColor("#9a9a9a"))
    return pal


def apply(app):
    """
    Give the application the dashboard's look.

    Parameters
    ----------
    app : QApplication

    Generated by RJC and Claude.
    """
    fusion = QtWidgets.QStyleFactory.create("Fusion")
    app.setStyle(fusion)
    # The style sheet wraps the style, so the base style is recorded here
    app.setProperty("alis_style", fusion.metaObject().className())
    app.setPalette(palette())
    app.setFont(ui_font())
    app.setStyleSheet(SHEET.format(**GREY))


def _glyph_icon(fill, glyph, glyph_colour="#ffffff", outline=None, size=14):
    """
    A round icon holding one glyph, drawn at twice the size for sharp screens.

    Generated by RJC and Claude.
    """
    scale = 2
    pix = QtGui.QPixmap(size * scale, size * scale)
    pix.fill(QtCore.Qt.GlobalColor.transparent)
    painter = QtGui.QPainter(pix)
    painter.setRenderHint(QtGui.QPainter.RenderHint.Antialiasing)
    rect = QtCore.QRectF(1, 1, size * scale - 2, size * scale - 2)
    if outline is not None:
        painter.setPen(QtGui.QPen(QtGui.QColor(outline), 3))
        painter.setBrush(QtCore.Qt.BrushStyle.NoBrush)
        painter.drawEllipse(rect.adjusted(2, 2, -2, -2))
    else:
        painter.setPen(QtCore.Qt.PenStyle.NoPen)
        painter.setBrush(QtGui.QColor(fill))
        painter.drawEllipse(rect)
    if glyph:
        font = QtGui.QFont(ui_font())
        font.setPixelSize(int(size * scale * 0.68))
        font.setBold(True)
        painter.setFont(font)
        painter.setPen(QtGui.QColor(glyph_colour))
        painter.drawText(rect, QtCore.Qt.AlignmentFlag.AlignCenter, glyph)
    painter.end()
    pix.setDevicePixelRatio(scale)
    return QtGui.QIcon(pix)


def marker_icon(state):
    """
    A tab marker's icon: ✓ blue, ↻ orange, ! vermillion, or a hollow grey circle.

    Generated by RJC and Claude.
    """
    if state == MK.NONE:
        return _glyph_icon(None, "", outline=MARKER_COLOURS[state])
    dark = "#2b1d00" if state == MK.STALE else "#ffffff"
    return _glyph_icon(MARKER_COLOURS[state], MK.ICONS[state], dark)


def problem_icon(severity):
    """A problem's icon: ✕ for an error, ! for a warning."""
    dark = "#2b1d00" if severity == "warning" else "#ffffff"
    return _glyph_icon(SEVERITY_COLOURS[severity], SEVERITY_ICONS[severity], dark)


