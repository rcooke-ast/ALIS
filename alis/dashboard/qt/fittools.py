"""The Fit tab's tools (dashboard Stage 6.8; S21; Q6.10, Q6.18, Q6.22): the random
restarts' window.

- **Random restarts…** shows the restarts kept with the shown run: ALIS's own
  assessment of them (for each free parameter, the largest |Δ|/σ across the
  restarts, or their scatter over σ, flagged beyond ``sim convergesig``, and ALIS's
  line of summary), each restart's χ², and χ² against a parameter chosen in a menu.
  From it: run new restarts (how many, a preference), Export restarts…, and continue
  from a restart that reached a lower χ² than the run.
- **Blinding** (Q6.18(c)): a hidden parameter's values are neither shown nor
  plotted (it is not in the chart's menu); its |Δ|/σ is shown, unsigned.

Generated by RJC and Claude.
"""

import numpy as np
import pyqtgraph as pg
from qtpy import QtCore, QtGui, QtWidgets

from alis.dashboard import blinding as BL
from alis.dashboard import restarts as RT
from alis.dashboard.qt import style as STY
from alis.dashboard.qt import widgets as W

# What the window was closed to do
RUN, EXPORT, CONTINUE = "run", "export", "continue"


class RestartsDialog(QtWidgets.QDialog):
    """
    The random restarts of the shown run: their assessment, their χ², and χ² against a
    parameter; Run restarts, Export restarts…, Continue from a better restart.

    Parameters
    ----------
    view : results.View
        The shown run.
    found : restarts.Kept or None
        The restarts kept with it.
    count : int
        How many to run (the preference).
    why : str
        Why no restarts can be run from this run (no covariance), or ``""``.

    Attributes
    ----------
    choice : str or None
        ``"run"``, ``"export"`` or ``"continue"`` when the window was closed to do
        one of them.
    restart : int
        The restart to continue from.

    Generated by RJC and Claude.
    """

    def __init__(self, view, found, count=10, why="", parent=None):
        super().__init__(parent)
        self.view = view
        self.found = found
        self.choice = None
        self.restart = None
        self.setWindowTitle("Random restarts of " + view.name)
        self.setMinimumSize(860, 620)
        layout = QtWidgets.QVBoxLayout(self)
        self.assessed = None if found is None else RT.assess(view, found)
        settings = (found.settings if found else None) or RT.sim_settings(view)
        self.intro = QtWidgets.QLabel(self._intro(settings))
        self.intro.setWordWrap(True)
        layout.addWidget(self.intro)
        self.summary = QtWidgets.QLabel(self._summary())
        self.summary.setObjectName("restarts_summary")
        self.summary.setWordWrap(True)
        self.summary.setTextFormat(QtCore.Qt.TextFormat.RichText)
        layout.addWidget(self.summary)
        middle = QtWidgets.QHBoxLayout()
        self.table = QtWidgets.QTreeWidget()
        self.table.setObjectName("restarts_assessment")
        test = str(settings.get("convergetest", "maxdev")).lower()
        self.table.setHeaderLabels(
            [
                "Parameter",
                "Best fit",
                "σ",
                "scatter/σ" if test == "scatter" else "largest |Δ|/σ",
                "",
            ]
        )
        self.table.setRootIsDecorated(False)
        self.table.header().setSectionResizeMode(
            QtWidgets.QHeaderView.ResizeMode.ResizeToContents
        )
        self._fill_table(settings)
        middle.addWidget(self.table, 3)
        right = QtWidgets.QVBoxLayout()
        top = QtWidgets.QHBoxLayout()
        top.addWidget(QtWidgets.QLabel("χ² against"))
        self.menu = QtWidgets.QComboBox()
        self.menu.setObjectName("restarts_parameter")
        top.addWidget(self.menu, 1)
        right.addLayout(top)
        self.chart = pg.PlotWidget()
        self.chart.setBackground(STY.GREY["base"])
        self.chart.getPlotItem().setLabel("left", "χ²")
        self.chart.getPlotItem().getAxis("left").enableAutoSIPrefix(False)
        self.chart.getPlotItem().getAxis("bottom").enableAutoSIPrefix(False)
        self.chart.setMinimumHeight(240)
        right.addWidget(self.chart, 1)
        self.list = QtWidgets.QTableWidget(0, 4)
        self.list.setObjectName("restarts_list")
        self.list.setHorizontalHeaderLabels(["Restart", "χ²", "Iterations", "Status"])
        self.list.verticalHeader().setVisible(False)
        self.list.setEditTriggers(
            QtWidgets.QAbstractItemView.EditTrigger.NoEditTriggers
        )
        self.list.horizontalHeader().setSectionResizeMode(
            QtWidgets.QHeaderView.ResizeMode.ResizeToContents
        )
        self.list.horizontalHeader().setStretchLastSection(True)
        self.list.setMaximumHeight(170)
        right.addWidget(self.list)
        middle.addLayout(right, 2)
        layout.addLayout(middle, 1)
        self._fill_menu()
        self._fill_list()
        self.menu.currentIndexChanged.connect(self._draw)
        self._draw()
        buttons = QtWidgets.QHBoxLayout()
        buttons.addWidget(QtWidgets.QLabel("Run"))
        self.count = QtWidgets.QSpinBox()
        self.count.setObjectName("restarts_count")
        self.count.setRange(2, 1000)
        self.count.setValue(max(2, int(count)))
        buttons.addWidget(self.count)
        self.run_button = QtWidgets.QPushButton("restarts")
        self.run_button.setObjectName("restarts_run")
        self.run_button.setEnabled(not why)
        self.run_button.setToolTip(
            why
            or "Fit again from starts drawn about the best fit of {0}. One set of"
            " restarts is kept with a run: new ones replace these, after a"
            " question".format(view.name)
        )
        self.run_button.clicked.connect(lambda: self._close(RUN))
        buttons.addWidget(self.run_button)
        buttons.addStretch(1)
        self.continue_button = QtWidgets.QPushButton("Continue from the best restart…")
        self.continue_button.setObjectName("restarts_continue")
        better = self.assessed.better if self.assessed else []
        self.continue_button.setVisible(bool(better))
        if better:
            self.continue_button.setText("Continue from restart {0}…".format(better[0]))
            self.continue_button.setToolTip(
                "Restart {0} reached a lower χ² than {1}: copy its best fit into the"
                " model".format(better[0], view.name)
            )
        self.continue_button.clicked.connect(
            lambda: self._close(CONTINUE, better[0] if better else None)
        )
        buttons.addWidget(self.continue_button)
        self.export_button = QtWidgets.QPushButton("Export restarts…")
        self.export_button.setObjectName("restarts_export")
        self.export_button.setEnabled(found is not None and bool(found.restarts))
        self.export_button.clicked.connect(lambda: self._close(EXPORT))
        buttons.addWidget(self.export_button)
        close = QtWidgets.QPushButton("Close")
        close.clicked.connect(self.reject)
        buttons.addWidget(close)
        layout.addLayout(buttons)

    # -- filling --------------------------------------------------------------------

    def _intro(self, settings):
        found = self.found
        kept = 0 if found is None else len(found.restarts)
        text = (
            "Each restart fits the model of {0} again from a start drawn as sim perturb"
            " draws it after sim beginfrom: about the best fit, from its covariance,"
            " within ±{1:g} of each value and the limits. ".format(
                self.view.name, float(settings.get("maxperturb", 0.1))
            )
        )
        if kept:
            text += "{0} restart{1} kept with the run.".format(
                kept, "" if kept == 1 else "s"
            )
        else:
            text += "No restarts yet."
        return text

    def _summary(self):
        found = self.assessed
        if found is None:
            return ""
        if found.converged is None and not found.summary:
            return "Too few restarts finished to assess them."
        mark, colour = (
            ("✓", STY.OKABE_ITO["blue"])
            if found.converged
            else ("✕", STY.OKABE_ITO["vermillion"])
        )
        return '<span style="color:{0}; font-weight:600;">{1}</span> {2}'.format(
            colour, mark, BL.Gate(self.view.project).message(found.summary)
        )

    def _fill_table(self, settings):
        self.table.clear()
        if self.assessed is None:
            return
        tolerance = float(settings.get("convergesig", 3.0))
        for index, name, best, sigma, metric, passed in self.assessed.rows:
            item = QtWidgets.QTreeWidgetItem(
                [
                    name,
                    best,
                    "{0:.3g}".format(sigma),
                    "{0:.2f}".format(metric),
                    "✓" if passed else "✕ beyond {0:g}σ".format(tolerance),
                ]
            )
            item.setData(0, QtCore.Qt.ItemDataRole.UserRole, index)
            if not passed:
                for col in (3, 4):
                    item.setForeground(col, QtGui.QColor(STY.OKABE_ITO["vermillion"]))
            self.table.addTopLevelItem(item)

    def plottable(self):
        """The parameters the chart offers: free, and not hidden."""
        out = []
        if self.assessed is None:
            return out
        for index, name, best, *_ in self.assessed.rows:
            if best != BL.MASK:
                out.append((index, name))
        return out

    def _fill_menu(self):
        self.menu.clear()
        for index, name in self.plottable():
            self.menu.addItem(name, index)
        self.menu.setEnabled(self.menu.count() > 0)

    def _fill_list(self):
        found = self.found
        rows = [] if found is None else list(enumerate(found.restarts, start=1))
        self.list.setRowCount(len(rows))
        for num, (number, restart) in enumerate(rows):
            cells = [
                str(number),
                "—" if restart.chi2 is None else "{0:.4f}".format(restart.chi2),
                "" if restart.iterations is None else str(restart.iterations),
                restart.status or "",
            ]
            for col, text in enumerate(cells):
                self.list.setItem(num, col, QtWidgets.QTableWidgetItem(text))

    def _draw(self, *args):
        """χ² against the parameter chosen: the restarts, and the run's best fit."""
        self.chart.clear()
        index = self.menu.currentData()
        found = self.found
        if index is None or found is None:
            return
        points = [
            (r.values[index], r.chi2)
            for r in found.restarts
            if r.values and r.chi2 is not None
        ]
        if points:
            data = np.asarray(points, dtype=float)
            self.chart.plot(
                data[:, 0],
                data[:, 1],
                pen=None,
                symbol="o",
                symbolSize=8,
                symbolBrush=pg.mkBrush(STY.OKABE_ITO["blue"]),
                symbolPen=None,
                name="restarts",
            )
        if found.chi2 is not None:
            self.chart.plot(
                [found.best[index]],
                [found.chi2],
                pen=None,
                symbol="star",
                symbolSize=14,
                symbolBrush=pg.mkBrush(STY.OKABE_ITO["vermillion"]),
                symbolPen=None,
                name="the run",
            )
        self.chart.getPlotItem().setLabel("bottom", self.menu.currentText())

    def drawn(self):
        """The chart's points: ``(restarts, run)`` as lists of (x, y) (tests)."""
        out = []
        for item in self.chart.getPlotItem().listDataItems():
            x, y = item.getData()
            out.append(list(zip(np.asarray(x).tolist(), np.asarray(y).tolist())))
        return out

    # -- closing --------------------------------------------------------------------

    def _close(self, choice, restart=None):
        self.choice = choice
        self.restart = restart
        self.accept()


__all__ = ["RestartsDialog", "RUN", "EXPORT", "CONTINUE"]
