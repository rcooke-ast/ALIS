class StartPage(QtWidgets.QFrame):
    """
    What the window shows with no project open: New project, Open, Import a fit, the
    recent projects, and unsaved work to recover.

    Generated by RJC and Claude.
    """

    def __init__(self, window):
        super().__init__(window)
        self.window = window
        self.setObjectName("startPage")
        outer = QtWidgets.QVBoxLayout(self)
        outer.setContentsMargins(60, 50, 60, 40)
        title = QtWidgets.QLabel(TITLE)
        title.setObjectName("startTitle")
        outer.addWidget(title)
        outer.addWidget(
            W.muted("Prepare, run and inspect ALIS fits. ALIS " + alis.__version__)
        )
        buttons = QtWidgets.QHBoxLayout()
        for name in ("file.new", "file.open", "file.import"):
            button = QtWidgets.QPushButton(A.get(name).text)
            button.setToolTip(A.get(name).tip)
            button.setMinimumHeight(34)
            button.clicked.connect(window.qactions[name].trigger)
            buttons.addWidget(button)
        buttons.addStretch(1)
        outer.addSpacing(16)
        outer.addLayout(buttons)
        outer.addSpacing(20)
        lists = QtWidgets.QHBoxLayout()
        self.recent = QtWidgets.QListWidget()
        self.recent.itemActivated.connect(self._open_recent)
        self.recent.itemDoubleClicked.connect(self._open_recent)
        lists.addWidget(W.Pane("Recent projects", self.recent), 3)
        self.orphans = QtWidgets.QListWidget()
        recover = QtWidgets.QPushButton("Recover")
        recover.clicked.connect(self._recover)
        discard = QtWidgets.QPushButton("Discard")
        discard.clicked.connect(self._discard)
        holder = QtWidgets.QWidget()
        box = QtWidgets.QVBoxLayout(holder)
        box.setContentsMargins(0, 0, 0, 0)
        box.addWidget(self.orphans, 1)
        row = QtWidgets.QHBoxLayout()
        row.addWidget(recover)
        row.addWidget(discard)
        row.addStretch(1)
        box.addLayout(row)
        self.orphan_pane = W.Pane("Unsaved work to recover", holder)
        lists.addWidget(self.orphan_pane, 2)
        outer.addLayout(lists, 1)
        self.messages = W.muted("")
        self.messages.setWordWrap(True)
        outer.addWidget(self.messages)

    def refresh(self):
        """
        List the recent projects and the unsaved work.

        Generated by RJC and Claude.
        """
        window = self.window
        self.recent.clear()
        recent = PR.Recent(window.folder, window.prefs["recent.length"])
        for path in recent.paths():
            item = QtWidgets.QListWidgetItem(
                "{0}    {1}".format(os.path.basename(path), os.path.dirname(path))
            )
            item.setData(QtCore.Qt.ItemDataRole.UserRole, path)
            if not os.path.exists(path):
                item.setText(item.text() + "    (missing)")
                item.setForeground(QtGui.QColor("#9a9a9a"))
            self.recent.addItem(item)
        if not recent.paths():
            self.recent.addItem("No recent projects.")
        self.orphans.clear()
        for note in S.orphans(window.folder):
            item = QtWidgets.QListWidgetItem(
                "{0}    autosaved {1}".format(
                    note.get("name", ""), note["written"][:16]
                )
            )
            item.setData(QtCore.Qt.ItemDataRole.UserRole, note)
            self.orphans.addItem(item)
        self.orphan_pane.setVisible(self.orphans.count() > 0)
        self.messages.setText("\n".join(window.prefs.messages))

    def _open_recent(self, item):
        path = item.data(QtCore.Qt.ItemDataRole.UserRole)
        if path:
            self.window.open_path(path)

    def _recover(self):
        item = self.orphans.currentItem()
        if item is not None:
            self.window.recover_orphan(item.data(QtCore.Qt.ItemDataRole.UserRole))

    def _discard(self):
        item = self.orphans.currentItem()
        if item is not None:
            S.discard_recovery(item.data(QtCore.Qt.ItemDataRole.UserRole))
            self.refresh()


class MainWindow(QtWidgets.QMainWindow):
    """
    The dashboard's window.

    Parameters
    ----------
    prefs : Preferences, optional
        The user's preferences; read from the folder if not given.
    folder : str, optional
        The folder of the dashboard's own files (``~/.alis``).
    registry : Registry, optional
        ALIS's functions and atomic data, shared by the projects opened (tests).

    Generated by RJC and Claude.
    """

    def __init__(self, prefs=None, folder=None, registry=None):
        super().__init__()
        self.prefs = prefs or PR.Preferences.load(folder)
        self.folder = folder or self.prefs.folder
        self.registry = registry
        self.session = None
        self.markers = {}
        self.qactions = {}
        self._disk_seen = None
        self.setWindowTitle(TITLE)
        self.resize(1440, 900)
        self._build_actions()
        self._build_menus()
        self._build_toolbar()
        self._build_central()
        self._build_status()
        self.autosave_timer = QtCore.QTimer(self)
        self.autosave_timer.timeout.connect(self.autosave)
        self.disk_timer = QtCore.QTimer(self)
        self.disk_timer.setInterval(DISK_CHECK)
        self.disk_timer.timeout.connect(self.watch_disk)
        self._apply_prefs()
        self.show_start()

    # -- building -------------------------------------------------------------------

    def _build_actions(self):
        """
        One QAction per entry of the registry, each bound to ``do_<name>``.

        Generated by RJC and Claude.
        """
        native = QtGui.QKeySequence.SequenceFormat.NativeText
        for spec in A.ACTIONS:
            if spec.scope:
                # A tab's own actions are built with the tab (_build_scoped)
                continue
            action = QtGui.QAction(spec.text, self)
            action.setObjectName(spec.name)
            if spec.shortcut:
                action.setShortcut(QtGui.QKeySequence(spec.shortcut))
                action.setShortcutContext(QtCore.Qt.ShortcutContext.WindowShortcut)
            tip = spec.tip
            if spec.shortcut:
                tip += " ({0})".format(action.shortcut().toString(native))
            action.setToolTip(tip)
            action.setStatusTip(spec.tip)
            action.setCheckable(spec.checkable)
            handler = getattr(self, "do_" + spec.name.replace(".", "_"))
            action.triggered.connect(
                lambda checked=False, h=handler, n=spec.name: self._run(n, h)
            )
            self.addAction(action)
            self.qactions[spec.name] = action
        self.qactions["file.preferences"].setMenuRole(
            QtGui.QAction.MenuRole.PreferencesRole
        )
        self.qactions["file.quit"].setMenuRole(QtGui.QAction.MenuRole.QuitRole)
        self.qactions["help.about"].setMenuRole(QtGui.QAction.MenuRole.AboutRole)

    def _build_menus(self):
        """
        The menus, from the registry, with a line between sections.

        Generated by RJC and Claude.
        """
        bar = self.menuBar()
        bar.setNativeMenuBar(False)
        self.menus = {}
        for title in A.MENUS:
            menu = bar.addMenu(title)
            self.menus[title] = menu
            section, submenus = None, {}
            for spec in A.in_menu(title):
                if section is not None and spec.section != section:
                    menu.addSeparator()
                section = spec.section
                target = menu
                if spec.submenu:
                    if spec.submenu not in submenus:
                        submenus[spec.submenu] = menu.addMenu(spec.submenu)
                    target = submenus[spec.submenu]
                target.addAction(self.qactions[spec.name])
                if spec.name == "file.open":
                    self.recent_menu = menu.addMenu("Open recent")
                    self.recent_menu.aboutToShow.connect(self._fill_recent)

    def _fill_recent(self):
        """The Open recent menu."""
        self.recent_menu.clear()
        paths = PR.Recent(self.folder, self.prefs["recent.length"]).paths()
        for path in paths:
            action = self.recent_menu.addAction(os.path.basename(path))
            action.setToolTip(path)
            action.setEnabled(os.path.exists(path))
            action.triggered.connect(
                lambda _=False, p=path: self._run("recent", lambda: self.open_path(p))
            )
        if not paths:
            self.recent_menu.addAction("No recent projects").setEnabled(False)

