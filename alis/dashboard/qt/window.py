    def _build_scoped(self):
        """
        The tabs' own actions (Stage 4): each belongs to its tab's widgets, so that
        its shortcut (a single key) acts only while that tab has the focus, and is
        bound to the tab's ``do_<what>``; the tab places it on its buttons.

        Generated by RJC and Claude.
        """
        native = QtGui.QKeySequence.SequenceFormat.NativeText
        tabs = {w.name: w for w in self.tab_widgets}
        for spec in A.ACTIONS:
            if not spec.scope:
                continue
            tab = tabs[spec.scope]
            action = QtGui.QAction(spec.text, tab)
            action.setObjectName(spec.name)
            action.setCheckable(spec.checkable)
            tip = spec.tip
            if spec.shortcut:
                action.setShortcut(QtGui.QKeySequence(spec.shortcut))
                action.setShortcutContext(
                    QtCore.Qt.ShortcutContext.WidgetWithChildrenShortcut
                )
                tip += " ({0})".format(action.shortcut().toString(native))
            action.setToolTip(tip)
            action.setStatusTip(spec.tip)
            handler = getattr(tab, "do_" + spec.name.split(".", 1)[1], None)
            if handler is not None:
                action.triggered.connect(
                    lambda checked=False, h=handler, n=spec.name: self._run(n, h)
                )
            tab.addAction(action)
            self.qactions[spec.name] = action
            tab.bind_action(spec.name, action)

    def _build_dock(self):
        """
        The .mod panel's dock, at the right: its width is set by dragging its edge,
        and it can become a window of its own and come back (RJC's review).

        Generated by RJC and Claude.
        """
        self.dock = QtWidgets.QDockWidget(".mod panel", self)
        self.dock.setObjectName("modDock")
        self.dock.setFeatures(
            QtWidgets.QDockWidget.DockWidgetFeature.DockWidgetFloatable
            | QtWidgets.QDockWidget.DockWidgetFeature.DockWidgetClosable
            | QtWidgets.QDockWidget.DockWidgetFeature.DockWidgetMovable
        )
        self.dock.setAllowedAreas(
            QtCore.Qt.DockWidgetArea.RightDockWidgetArea
            | QtCore.Qt.DockWidgetArea.LeftDockWidgetArea
        )
        self.dock.setWidget(self.panel)
        # Docked, the panel's own header is its title bar
        self._no_title = QtWidgets.QWidget()
        self.dock.setTitleBarWidget(self._no_title)
        self.addDockWidget(QtCore.Qt.DockWidgetArea.RightDockWidgetArea, self.dock)
        # The window's shortcuts also work in the panel's own window
        self.panel.addActions(list(self.qactions.values()))
        self.panel.set_panel_actions(
            [self.qactions[a.name] for a in A.in_menu(A.PANEL)]
        )
        self.dock.visibilityChanged.connect(self._dock_shown)
        self.dock.topLevelChanged.connect(self._dock_floated)

