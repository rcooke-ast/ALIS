    def blind_lines(self, lines, ask=True):
        """
        Write ``blind=True`` on model lines, as one step that undo does not pass.

        Generated by RJC and Claude.
        """
        project = self.session.project
        project.require_reading()
        if not lines:
            return
        if ask:
            choice = self.ask(
                "blind_line",
                "Blind this line",
                "The values of this line will be hidden from now on. This cannot be"
                " undone: only Model → Unblind… shows them again.",
                ["Blind", "Cancel"],
                icon="warning",
            )
            if choice != "Blind":
                return
        history = self.session.history
        with history.group(
            "Blind {0} line{1}".format(len(lines), "" if len(lines) == 1 else "s")
        ):
            for line in lines:
                item = project.parsed.item_at(line)
                history.edit(E.set_blind(project.parsed, item), "Blind a line")
        self.panel.redraw()

