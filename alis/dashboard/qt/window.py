    def _build_actions(self):
        """
        One QAction per entry of the registry, each bound to ``do_<name>``.

        Generated by RJC and Claude.
        """
        native = QtGui.QKeySequence.SequenceFormat.NativeText
        for spec in A.ACTIONS:
            if spec.scope:
                # A tab's own actions are built with the tab (_build_scoped)
                continue
            action = QtGui.QAction(spec.text, self)
            action.setObjectName(spec.name)
            if spec.shortcut:
                action.setShortcut(QtGui.QKeySequence(spec.shortcut))
                action.setShortcutContext(QtCore.Qt.ShortcutContext.WindowShortcut)
            tip = spec.tip
            if spec.shortcut:
                tip += " ({0})".format(action.shortcut().toString(native))
            action.setToolTip(tip)
            # Kept, for a tooltip that gives way to a reason for a while (Run's)
            action.setProperty("tip", tip)
            action.setStatusTip(spec.tip)
            action.setCheckable(spec.checkable)
            handler = getattr(self, "do_" + spec.name.replace(".", "_"))
            action.triggered.connect(
                lambda checked=False, h=handler, n=spec.name: self._run(n, h)
            )
            self.addAction(action)
            self.qactions[spec.name] = action
        self.qactions["file.preferences"].setMenuRole(
            QtGui.QAction.MenuRole.PreferencesRole
        )
        self.qactions["file.quit"].setMenuRole(QtGui.QAction.MenuRole.QuitRole)
        self.qactions["help.about"].setMenuRole(QtGui.QAction.MenuRole.AboutRole)

    def _build_menus(self):
        """
        The menus, from the registry, with a line between sections.

        Generated by RJC and Claude.
        """
        bar = self.menuBar()
        bar.setNativeMenuBar(False)
        self.menus = {}
        for title in A.MENUS:
            menu = bar.addMenu(title)
            self.menus[title] = menu
            section, submenus = None, {}
            for spec in A.in_menu(title):
                if section is not None and spec.section != section:
                    menu.addSeparator()
                section = spec.section
                target = menu
                if spec.submenu:
                    if spec.submenu not in submenus:
                        submenus[spec.submenu] = menu.addMenu(spec.submenu)
                    target = submenus[spec.submenu]
                target.addAction(self.qactions[spec.name])
                if spec.name == "file.open":
                    self.recent_menu = menu.addMenu("Open recent")
                    self.recent_menu.aboutToShow.connect(self._fill_recent)

    def _fill_recent(self):
        """The Open recent menu."""
        self.recent_menu.clear()
        paths = PR.Recent(self.folder, self.prefs["recent.length"]).paths()
        for path in paths:
            action = self.recent_menu.addAction(os.path.basename(path))
            action.setToolTip(path)
            action.setEnabled(os.path.exists(path))
            action.triggered.connect(
                lambda _=False, p=path: self._run("recent", lambda: self.open_path(p))
            )
        if not paths:
            self.recent_menu.addAction("No recent projects").setEnabled(False)
            return
        self.recent_menu.addSeparator()
        clear = self.recent_menu.addAction("Clear recent projects…")
        clear.triggered.connect(lambda: self._run("recent", self.clear_recent))

    def clear_recent(self):
        """
        Empty the recent projects, after asking once: only the list changes, never
        a project's file (item 7 of Stage 7).

        Generated by RJC and Claude.
        """
        choice = self.ask(
            "clear_recent",
            "Clear recent projects",
            "Empty the list of recent projects? The projects themselves are not"
            " changed.",
            ["Clear list", "Cancel"],
        )
        if choice != "Clear list":
            return
        PR.Recent(self.folder, self.prefs["recent.length"]).clear()
        if self.session is None:
            self.start.refresh()

