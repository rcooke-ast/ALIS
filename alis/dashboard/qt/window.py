    def set_panel_open(self, show, width=None, store=True):
        """
        Show the .mod panel, or hide it to the strip at the right.

        Generated by RJC and Claude.
        """
        self.dock.setVisible(show)
        self.strip.setVisible(not show and self.stack.currentIndex() == 1)
        if show and not self.dock.isFloating():
            width = width or (
                self.session.view.get("mod_panel", {}).get("width", 460)
                if self.session
                else 460
            )
            self.resizeDocks(
                [self.dock], [int(width)], QtCore.Qt.Orientation.Horizontal
            )
        self.qactions["view.mod_panel"].setChecked(show)
        if store:
            self._remember_panel()

    def set_panel_window(self, own, store=True):
        """
        Move the .mod panel to a window of its own, or back into the dashboard.
        Either way it is the same panel, working on the same project.

        Generated by RJC and Claude.
        """
        if own == self.dock.isFloating():
            return
        self.dock.setTitleBarWidget(None if own else self._no_title)
        self.dock.setFloating(own)
        if own:
            geometry = None
            if self.session is not None:
                geometry = self.session.view.get("mod_panel", {}).get("geometry")
            if geometry:
                self.dock.setGeometry(*geometry)
            else:
                top = self.geometry()
                self.dock.setGeometry(top.right() - 520, top.top() + 80, 560, 760)
            self.dock.setWindowTitle(
                "{0} — .mod".format(self.session.name if self.session else TITLE)
            )
            self.dock.show()
        if store:
            self._remember_panel()

    def _dock_shown(self, shown):
        """The panel was shown or hidden (its window closed, or Hide)."""
        if self.session is None:
            return
        self.strip.setVisible(not self.dock.isVisible())
        self.qactions["view.mod_panel"].setChecked(self.dock.isVisible())

    def _dock_floated(self, floating):
        """The panel became a window of its own, or came back (dragged or not)."""
        self.dock.setTitleBarWidget(None if floating else self._no_title)
        self.panel.set_window_mode(floating)
        self.qactions["view.mod_window"].setChecked(floating)
        self._remember_panel()

    def _remember_panel(self):
        """Keep the panel's state in the view: shown, width, own window."""
        if self.session is None:
            return
        current = dict(self.session.view.get("mod_panel", {}))
        new = dict(current)
        # A window not yet shown has not shown its panel either
        if self.isVisible():
            new["open"] = bool(self.dock.isVisible())
        new["window"] = bool(self.dock.isFloating())
        if self.dock.isVisible() and not self.dock.isFloating():
            new["width"] = int(self.dock.width())
        if self.dock.isFloating():
            geo = self.dock.geometry()
            new["geometry"] = [geo.x(), geo.y(), geo.width(), geo.height()]
        if new != current:
            self.session.set_view("mod_panel", new)

