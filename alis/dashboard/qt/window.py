        self.fit = FT.FitRun(self)
        self.fit.progressed.connect(self._fit_progressed)
        self.fit.ended.connect(self._fit_ended)
        self.setWindowTitle(TITLE)
        self.resize(1440, 900)
        self._build_actions()
