    def run_restarts(self, view, count, seed=None):
        """
        Run random restarts of a run (Q6.22(a)): starts drawn as sim perturb draws
        them after sim beginfrom, each fitted in turn by one process; their results
        kept with the run when they end.

        Returns
        -------
        bool
            Whether they were started.

        Generated by RJC and Claude.
        """
        if self.fit.active:
            self.tell("Random restarts", "A fit is running already: stop it first.")
            return False
        if seed is None:
            seed = int.from_bytes(os.urandom(4), "little")
        settings = dict(RT.sim_settings(view), count=int(count), seed=int(seed))
        try:
            starts = RT.draw_starts(view, count, seed=seed)
        except RT.RestartsError as err:
            self.tell("Random restarts", str(err), "warning")
            return False
        bundles = [RT.restart_bundle(view, start) for start in starts]
        job = R.Restarts(
            self.session,
            bundles,
            settings=SE.run_settings(self.session.project, self.prefs),
            taker=RT.taker(view, starts, settings),
        )
        self.statusBar().clearMessage()
        self.fit.start_job(self.session, job)
        return True

