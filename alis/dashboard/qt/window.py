    def watch_disk(self):
        """
        Notice a bundle changed on disk while it is open (S31, Q3.8).

        Generated by RJC and Claude.
        """
        session = self.session
        if session is None or session.path is None:
            return
        state = session.check_disk()
        if state == S.RUNS and self.fit.active and self.fit.session is session:
            # The dashboard's own run, storing its result: taken in when it ends
            return
        if state == S.RUNS:
            session.take_runs()
            self.statusBar().showMessage(
                "A run finished outside the dashboard; the Fit tab shows it.", 10000
            )
            self.refresh()
            return
        if state == S.SAME:
            return
        stamp = os.path.getmtime(session.path) if state == S.CHANGED else state
        if stamp == self._disk_seen:
            return
        self._disk_seen = stamp
        if state == S.MISSING:
            self.disk_banner.show_message(
                "The project file has been deleted or moved. Save writes it again.",
                "warning",
                [("Save", lambda: self._run("file.save", self.do_file_save))],
            )
        elif session.dirty:
            self.disk_banner.show_message(
                "The project file was changed by another program. You have unsaved"
                " changes: Save will ask whether to overwrite it, reload it, or save"
                " as another file.",
                "warning",
                [("Reload", self._reload), ("Dismiss", self.disk_banner.clear)],
            )
        else:
            self.disk_banner.show_message(
                "The project file was changed by another program.",
                "warning",
                [("Reload", self._reload), ("Dismiss", self.disk_banner.clear)],
            )

