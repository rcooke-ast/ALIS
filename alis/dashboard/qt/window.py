    # -- questions to the user (tests answer them) ----------------------------------

    def ask(self, kind, title, text, choices, default=None, icon="question"):
        """
        Ask the user to choose, in a message box.

        Parameters
        ----------
        kind : str
            What is asked, so that a test can answer it.
        choices : list of str
            The buttons; the last is the one Escape gives.

        Returns
        -------
        str
            The choice.

        Generated by RJC and Claude.
        """
        box = QtWidgets.QMessageBox(self)
        box.setWindowTitle(title)
        box.setText(text)
        box.setIcon(
            {
                "question": QtWidgets.QMessageBox.Icon.Question,
                "warning": QtWidgets.QMessageBox.Icon.Warning,
                "info": QtWidgets.QMessageBox.Icon.Information,
            }[icon]
        )
        buttons = {}
        for num, choice in enumerate(choices):
            role = (
                QtWidgets.QMessageBox.ButtonRole.RejectRole
                if num == len(choices) - 1
                else QtWidgets.QMessageBox.ButtonRole.AcceptRole
            )
            buttons[box.addButton(choice, role)] = choice
        if default in choices:
            box.setDefaultButton([b for b, c in buttons.items() if c == default][0])
        box.exec()
        return buttons.get(box.clickedButton(), choices[-1])

    def tell(self, title, text, icon="info"):
        """Tell the user something, with one OK button."""
        self.ask("tell", title, text, ["OK"], icon=icon)

    def choose(self, kind, title, start="", filters=""):
        """
        Ask for a file or a folder.

        Parameters
        ----------
        kind : str
            ``"open"``, ``"save"``, ``"folder"``, or ``"open_many"`` for one file or
            several.

        Returns
        -------
        str, list of str, or None
            A list for ``"open_many"``.

        Generated by RJC and Claude.
        """
        dialog = QtWidgets.QFileDialog
        if kind == "open_many":
            paths, _ = dialog.getOpenFileNames(self, title, start, filters)
            return list(paths) or None
        if kind == "folder":
            path = dialog.getExistingDirectory(self, title, start)
        elif kind == "save":
            path, _ = dialog.getSaveFileName(self, title, start, filters)
        else:
            path, _ = dialog.getOpenFileName(self, title, start, filters)
        return path or None

    def run_dialog(self, dialog):
        """Show a dialog and wait for it (tests answer it)."""
        return dialog.exec()

    def _run(self, name, handler):
        """
        Run an action: what was typed is read first; an unexpected error is
        reported, with its traceback on the terminal (Q2.5).

        Generated by RJC and Claude.
        """
        if not name.startswith("edit.") or name in ("edit.undo", "edit.redo"):
            self.panel.flush()
        try:
            handler()
        except BL.RevealError as error:
            self._refused(str(error))
        except Exception as error:
            # The traceback goes to the terminal (Q2.5)
            V.unexpected(error)
            self.tell("Unexpected error", UNEXPECTED, icon="warning")
        self.refresh()

    # -- the project ----------------------------------------------------------------

    def launch(self, target):
        """
        Open what the ``alis`` command was given (F14).

        Generated by RJC and Claude.
        """
        if target.kind == S.OPEN:
            self.open_path(target.path)
        elif target.kind == S.IMPORT:
            self.import_path(target.path)
        else:
            self.show_start()

    def show_start(self):
        """The start page, with no project open."""
        self.session = None
        self.panel.set_session(None)
        self.dock.hide()
        self.strip.hide()
        self.start.refresh()
        self.stack.setCurrentIndex(0)
        self.autosave_timer.stop()
        self.disk_timer.stop()
        self.refresh()

    def set_session(self, session, notes=()):
        """
        Show a session: the workspace, the panel and the view it was left in.

        Generated by RJC and Claude.
        """
        self.session = session
        self._disk_seen = None
        self.stack.setCurrentIndex(1)
        self.panel.set_session(session, self.prefs)
        view = session.view
        tab = view.get("tab", "Data")
        names = [w.name for w in self.tab_widgets]
        self.tabs.setCurrentIndex(names.index(tab) if tab in names[:4] else 0)
        panel = view.get("mod_panel", {})
        self.set_panel_window(panel.get("window", False), store=False)
        self.set_panel_open(
            panel.get("open", True), panel.get("width", 460), store=False
        )
        self.disk_banner.clear()
        self.notice_banner.clear()
        if session.project.inferred:
            self.notice_banner.show_message(
                "This fit was imported: the systems, components and datasets were"
                " worked out from its labels and redshifts. Please check that they"
                " were read correctly before changing anything.",
                "info",
                [("Hide", self.notice_banner.clear)],
            )
        if notes:
            self.tell("New project", "\n".join(notes))
        self.autosave_timer.start()
        self.disk_timer.start()
        self.refresh()

    def close_session(self):
        """
        Close the project: offer to save unsaved changes first.

        Returns
        -------
        bool
            False when the user cancelled.

        Generated by RJC and Claude.
        """
        if self.session is None:
            return True
        self.panel.flush()
        session = self.session
        if self.fit.active and self.fit.session is session:
            if not self._close_run():
                return False
        if session.dirty:
            choice = self.ask(
                "unsaved",
                "Unsaved changes",
                "{0} has changes that are not saved. Save them?".format(session.name),
                ["Save", "Don't save", "Cancel"],
                default="Save",
            )
            if choice == "Cancel":
                return False
            if choice == "Save" and not self.save():
                return False
        session.close()
        self.show_start()
        return True

    def open_path(self, path):
        """
        Open a project: offer its recovery copy when newer, and relinking when a
        source spectrum is missing or changed.

        Generated by RJC and Claude.
        """
        if not self.close_session():
            return
        note = S.find_recovery(path, self.folder)
        recover = None
        if note is not None:
            choice = self.ask(
                "recover",
                "Recover unsaved changes",
                "A recovery copy of {0}, autosaved {1}, holds changes that were not"
                " saved. Recover them?".format(
                    os.path.basename(path), note["written"][:16].replace("T", " ")
                ),
                ["Recover", "Open the saved project", "Cancel"],
                default="Recover",
            )
            if choice == "Cancel":
                return
            if choice == "Recover":
                recover = note
        try:
            session = S.Session.open(
                path, self.prefs, self.folder, recover=recover, registry=self.registry
            )
        except (B.BundleError, OSError) as err:
            self.tell("Open", "The project cannot be opened:\n" + str(err), "warning")
            return
        if recover is None and note is not None:
            S.discard_recovery(note)
        PR.Recent(self.folder, self.prefs["recent.length"]).add(path)
        self.set_session(session)
        if SR.problems(session.project.bundle, session.path):
            choice = self.ask(
                "relink",
                "Source spectra",
                "Some source spectra of this project are missing or have changed."
                " Relink them now?",
                ["Relink…", "Later"],
                default="Relink…",
            )
            if choice == "Relink…":
                self.do_file_relink()

    def import_path(self, path):
        """
        Import an existing fit into a new, unsaved project (F4).

        Generated by RJC and Claude.
        """
        if not self.close_session():
            return
        try:
            session = S.Session.import_model(
                path, self.prefs, self.folder, registry=self.registry
            )
        except Exception as err:
            self.tell("Import", "The fit cannot be imported:\n" + str(err), "warning")
            return
        self.set_session(session)

    def recover_orphan(self, note):
        """Reopen unsaved work from its recovery copy (the start page)."""
        session = S.Session.from_recovery(note, self.prefs, self.folder, self.registry)
        S.discard_recovery(note)
        self.set_session(session)
        session.autosave()

    def save(self, path=None):
        """
        Save, asking what to do when the project changed on disk (Q3.8).

        Returns
        -------
        bool
            Whether the project was saved.

        Generated by RJC and Claude.
        """
        session = self.session
        if session.path is None and path is None:
            return self.save_as()
        try:
            session.save(path)
        except S.Conflict:
            choice = self.ask(
                "conflict",
                "The project changed on disk",
                "{0} was changed by another program since it was opened or saved."
                " Overwrite it with this version, reload it (losing the changes"
                " made here), or save this version as another file?".format(
                    session.name
                ),
                ["Overwrite", "Reload", "Save as…", "Cancel"],
                icon="warning",
            )
            if choice == "Overwrite":
                session.save(overwrite=True)
            elif choice == "Reload":
                session.reload()
                self.set_session(session)
                return False
            elif choice == "Save as…":
                return self.save_as()
            else:
                return False
        self.disk_banner.clear()
        self._disk_seen = None
        self.refresh()
        return True

    def save_as(self):
        """Save to a file the user chooses."""
        path = self.choose(
            "save",
            "Save the project as",
            self.session.suggested_path(),
            "ALIS projects (*.model)",
        )
        if not path:
            return False
        if not path.endswith(B.SUFFIX):
            path += B.SUFFIX
        self.session.save(path)
        self.refresh()
        return True

