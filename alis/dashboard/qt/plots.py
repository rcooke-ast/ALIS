class ResidualView(pg.PlotWidget):
    """
    The strip under a panel (Stage 5): (data − model)/σ as steps, with ±1σ dashed,
    on the panel's x axis.

    Generated by RJC and Claude.
    """

    LIMIT = 4.0

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setBackground(ST.GREY["base"])
        item = self.getPlotItem()
        item.hideButtons()
        item.setMenuEnabled(False)
        item.setMouseEnabled(x=False, y=False)
        for name in ("left", "bottom"):
            axis = item.getAxis(name)
            axis.setPen(pg.mkPen("#7a7a7a"))
            axis.setTextPen(pg.mkPen(ST.GREY["text"]))
            axis.enableAutoSIPrefix(False)
        item.getAxis("left").setTicks([[(-1.0, "−1σ"), (1.0, "+1σ")]])
        item.getAxis("bottom").setStyle(showValues=False)
        for level in (-1.0, 1.0):
            self.addItem(
                pg.InfiniteLine(
                    level,
                    angle=0,
                    pen=pg.mkPen(
                        COLOURS["zero"], width=1, style=QtCore.Qt.PenStyle.DashLine
                    ),
                ),
                ignoreBounds=True,
            )
        self.addItem(
            pg.InfiniteLine(0.0, angle=0, pen=pg.mkPen(COLOURS["zero"], width=1)),
            ignoreBounds=True,
        )
        self._item = None
        self.setYRange(-self.LIMIT, self.LIMIT, padding=0)

    def set_unfitted(self, spans):
        """
        Shade the stretches whose pixels are not fitted, light grey (the Fit tab,
        Stage 6.5), to the step edges of the residuals drawn (:func:`pixel_spans`);
        an empty list removes them.

        Generated by RJC and Claude.
        """
        for item in getattr(self, "_unfitted", []):
            self.removeItem(item)
        self._unfitted = []
        x = getattr(self, "_x", None)
        if x is not None and x.size:
            spans = pixel_spans(x, spans)
        for low, high in spans:
            item = pg.LinearRegionItem(
                (low, high), movable=False, brush=pg.mkBrush(*COLOURS["unfitted"])
            )
            item.setZValue(-10)
            for line in item.lines:
                line.setPen(pg.mkPen(None))
            self.addItem(item, ignoreBounds=True)
            self._unfitted.append(item)

    def unfitted(self):
        """The shaded stretches, ``[(low, high)]`` (tests)."""
        return [tuple(item.getRegion()) for item in getattr(self, "_unfitted", [])]

    def set_residuals(self, x, values):
        """
        Draw the residuals; values beyond ±4σ sit on the edge.

        Generated by RJC and Claude.
        """
        if self._item is not None:
            self.removeItem(self._item)
            self._item = None
        self._x = None if x is None else np.asarray(x, dtype=float)
        if x is None:
            return
        values = np.clip(np.asarray(values, dtype=float), -self.LIMIT, self.LIMIT)
        sx, sy = step_curve(self._x, values)
        self._item = pg.PlotDataItem(sx, sy, pen=pg.mkPen(COLOURS["residual"], width=1))
        self.addItem(self._item)
        self.setYRange(-self.LIMIT, self.LIMIT, padding=0)


