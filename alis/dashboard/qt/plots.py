    def _place_ids(self, *args):
        """Put the line IDs at the top of the view, three rows, no overlaps."""
        if not self._ids and not self._lists.get("note"):
            return
        (x0, x1), (y0, y1) = self.box.viewRange()
        if self.log:
            y0, y1 = 10.0**y0, 10.0**y1
        height = y1 - y0
        width = max(self.box.width(), 1.0)
        per_pixel = (x1 - x0) / width
        ends = [-np.inf, -np.inf, -np.inf]
        for wave, tick, text in sorted(self._ids, key=lambda t: t[0]):
            top = y1 - 0.02 * height
            tick.setData([wave, wave], [top - 0.10 * height, top - 0.04 * height])
            half = 3.2 * len(text.toPlainText()) * per_pixel
            placed = False
            for row, end in enumerate(ends):
                if wave - half > end:
                    ends[row] = wave + half
                    text.setPos(wave, top - 0.11 * height - row * 0.07 * height)
                    text.setVisible(x0 <= wave <= x1)
                    placed = True
                    break
            if not placed:
                text.setVisible(False)
        for note in self._lists.get("note", []):
            note.setPos(x1, y1)

