class SpectrumView(pg.PlotWidget):
    """
    One spectrum, with its overlays.

    Signals
    -------
    clicked(x, y)
        A click, in data coordinates (Identify a feature).
    spanned(mode, low, high)
        A span drawn in draw or mask mode (a click in mask mode is a span of one
        point).
    edgeMoved(side, x, finished)
        A snip edge dragged: ``"low"`` or ``"high"``.
    edgesMoved(side, x, finished)
        A snip edge dragged by its top grip, which moves that edge of every snip
        of the transition (Stage 10, point 1).
    regionMoved(index, low, high)
        A fit region's edges dragged (when they are movable).
    knotMoved(index, x, y)
        A knot dragged, when the drag ends.
    tickClicked(key)
        A component's tick clicked (Stage 5).
    dragged(x0, y0, x, y, state)
        A left drag where drags edit (:meth:`set_edits`): where it started, where
        it is, and ``"start"``, ``"move"`` or ``"finish"``.

    Generated by RJC and Claude.
    """

    clicked = QtCore.Signal(float, float)
    contextRequested = QtCore.Signal(float, float, object)
    spanned = QtCore.Signal(str, float, float)
    edgeMoved = QtCore.Signal(str, float, bool)
    edgesMoved = QtCore.Signal(str, float, bool)
    regionMoved = QtCore.Signal(int, float, float)
    knotMoved = QtCore.Signal(int, float, float)
    tickClicked = QtCore.Signal(object)
    markClicked = QtCore.Signal(int)
    dragged = QtCore.Signal(float, float, float, float, str)

    # The title of the x axis: the Components tab's panels draw in velocity
    x_title = "Wavelength (Å)"

    def __init__(self, parent=None):
        self.box = SpectrumBox()
        self.top = VelocityAxis()
        super().__init__(parent, viewBox=self.box, axisItems={"top": self.top})
        self.setBackground(ST.GREY["base"])
        item = self.getPlotItem()
        item.showAxis("top", False)
        item.setLabel("bottom", self.x_title)
        item.setLabel("left", "Flux")
        item.hideButtons()
        item.setMenuEnabled(False)
        for name in ("left", "bottom", "top"):
            axis = item.getAxis(name)
            axis.setPen(pg.mkPen("#7a7a7a"))
            axis.setTextPen(pg.mkPen(ST.GREY["text"]))
            # The values as they are: no "(x0.001)" in the axis's title
            axis.enableAutoSIPrefix(False)
        self.box.setAutoVisible(y=True)
        self.box.clicked.connect(self.clicked)
        self.box.dragged.connect(self.dragged)
        self.box.rightClicked.connect(self.contextRequested)
        self.box.spanned.connect(lambda mode, a, b, _f: self.spanned.emit(mode, a, b))
        self._items = {}
        self._lists = {}
        self._ids = []
        self._wave = None
        self._home = None
        self.log = False
        self.zero = pg.InfiniteLine(
            0.0,
            angle=0,
            pen=pg.mkPen(COLOURS["zero"], width=1, style=QtCore.Qt.PenStyle.DashLine),
        )
        self.addItem(self.zero, ignoreBounds=True)
        self.box.sigYRangeChanged.connect(self._place_ids)
        self.box.sigXRangeChanged.connect(self._place_ids)

    # -- the data -----------------------------------------------------------------------

    def _curve(self, key, x, y, pen, connect="finite"):
        old = self._items.pop(key, None)
        if old is not None:
            self.removeItem(old)
        if x is None:
            return None
        item = pg.PlotDataItem(x, y, pen=pen, connect=connect)
        self.addItem(item)
        item.setDownsampling(auto=True, method="peak")
        item.setClipToView(True)
        self._items[key] = item
        return item

    def set_data(self, wave, flux, error=None, bad=None):
        """
        Draw a spectrum: the data as steps, the error thin and grey, and its bad
        pixels as grey crosses.

        Parameters
        ----------
        wave, flux : array
        error : array, optional
        bad : array of bool, optional

        Generated by RJC and Claude.
        """
        for key in [k for k in self._items if k.startswith("piece")]:
            self.removeItem(self._items.pop(key))
        wave = np.asarray(wave, dtype=float)
        flux = np.asarray(flux, dtype=float)
        self._wave = wave
        self._flux = flux
        self._error = None if error is None else np.asarray(error, dtype=float)
        self._bad = None if bad is None else np.asarray(bad, dtype=bool)
        self._redraw_data()

    def _redraw_data(self):
        wave, flux = self._wave, getattr(self, "_flux", None)
        if wave is None or flux is None:
            return
        scale = self._norm if getattr(self, "_norm", None) is not None else None
        with np.errstate(divide="ignore", invalid="ignore"):
            shown = tame(flux / scale if scale is not None else flux)
        x, y = step_curve(wave, shown)
        self._curve("data", x, y, pg.mkPen(COLOURS["data"], width=1))
        if self._error is not None:
            err = self._error / scale if scale is not None else self._error
            # An error of 0 or less marks a pixel that cannot be fitted (often a
            # huge negative sentinel): it is not drawn
            with np.errstate(invalid="ignore"):
                err = tame(np.where(self._error > 0, err, np.nan))
            ex, ey = broken_line(wave, err)
            self._curve("error", ex, ey, pg.mkPen(COLOURS["error"], width=1))
        else:
            self._curve("error", None, None, None)
        old = self._items.pop("bad", None)
        if old is not None:
            self.removeItem(old)
        if self._bad is not None and self._bad.any():
            sel = self._bad & np.isfinite(shown)
            item = pg.ScatterPlotItem(
                wave[sel],
                shown[sel],
                symbol="x",
                size=7,
                pen=pg.mkPen(COLOURS["bad"]),
                brush=None,
            )
            self.addItem(item)
            self._items["bad"] = item

    def set_context(self, wave=None, flux=None, steps=None):
        """
        Draw the data around a snip faintly (its source beyond its edges), so that an
        edge can be dragged out over real data; None removes it. ``steps``, the
        curve already made by :func:`step_curve`, is drawn as it is (a whole
        source, made once: Stage 10, point 2).

        Generated by RJC and Claude.
        """
        if steps is None and wave is None:
            self._curve("context", None, None, None)
            return
        x, y = step_curve(wave, flux) if steps is None else steps
        item = self._curve("context", x, y, pg.mkPen("#b9b9b9", width=1))
        item.setZValue(-5)

    def set_pieces(self, pieces):
        """
        Draw separate pieces of data, each as steps (a dataset's snips, when it has
        no source spectrum, each scaled to its own peak: D35).

        Parameters
        ----------
        pieces : list of (wave, flux)

        Generated by RJC and Claude.
        """
        for key in [k for k in self._items if k.startswith("piece")]:
            self.removeItem(self._items.pop(key))
        self._curve("data", None, None, None)
        self._curve("error", None, None, None)
        waves = []
        for num, (wave, flux) in enumerate(pieces):
            x, y = step_curve(wave, flux)
            self._curve(
                "piece{0}".format(num), x, y, pg.mkPen(COLOURS["data"], width=1)
            )
            waves.append(np.asarray(wave, dtype=float))
        self._wave = np.concatenate(waves) if waves else None
        self._flux, self._error, self._bad = None, None, None
        self._pieces_flux = (
            np.concatenate([np.asarray(f, dtype=float) for _, f in pieces])
            if pieces
            else None
        )

