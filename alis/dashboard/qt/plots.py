# -- What is drawn ----------------------------------------------------------------------


def gaps(wave, split=SPLIT):
    """
    The indices after which the data have a gap: a step of more than ``split`` times
    the median step.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    if wave.size < 3:
        return np.zeros(0, dtype=int)
    step = np.diff(wave)
    median = np.median(step[step > 0]) if np.any(step > 0) else 0.0
    if median <= 0:
        return np.zeros(0, dtype=int)
    return np.flatnonzero(step > split * median)


# A value this many times a spectrum's typical size, or more, is not drawn: Qt drops
# a path that reaches it (a junk pixel's huge sentinel, as the last pixel of
# metal_line_abs's data), taking the whole spectrum with it (Stage 6.8)
WILD = 1.0e4


def tame(values):
    """
    Values to draw, with those far beyond the spectrum's typical size (``WILD``
    times its median size, or its 90th percentile when that is zero) made gaps.

    Generated by RJC and Claude.
    """
    values = np.asarray(values, dtype=float)
    finite = np.isfinite(values)
    if not finite.any():
        return values
    sizes = np.abs(values[finite])
    typical = float(np.median(sizes)) or float(np.percentile(sizes, 90))
    if not typical > 0.0:
        return values
    with np.errstate(invalid="ignore"):
        return np.where(np.abs(values) > WILD * typical, np.nan, values)


# How near the cursor a fit region's edge is drawn and picked, in pixels (Stage 10,
# point 6), and how wide it is drawn: as the snip's edges
EDGE_PICK = 6.0
EDGE_WIDTH = 3


def _show_near_cursor(line):
    """
    A movable fit region's edge: not drawn until the cursor is within
    :data:`EDGE_PICK` pixels, then drawn :data:`EDGE_WIDTH` wide with the ↔ cursor,
    and kept drawn while it is dragged.

    Generated by RJC and Claude.
    """
    line.setHoverPen(pg.mkPen(COLOURS["fit_edge"], width=EDGE_WIDTH))
    # pyqtgraph picks a line within (marker size + half its widest pen + 1) pixels;
    # an edge has no marker, so the marker size gives the reach
    line._maxMarkerSize = EDGE_PICK - EDGE_WIDTH / 2.0 - 1.0
    line._boundingRect = None
    line.setCursor(QtCore.Qt.CursorShape.SizeHorCursor)
    line.sigDragged.connect(lambda ln: ln.setMouseHover(True))


class EdgeLine(pg.InfiniteLine):
    """
    A snip's edge: one line, which a drag begun at its top grip (``top_grip``)
    moves for every snip of the transition (``every`` while it is dragged), and a
    drag begun anywhere else for this snip alone (Stage 10, point 1).

    Generated by RJC and Claude.
    """

    # Where the top grip sits along the line (a fraction of the view's height), and
    # where along the line a drag begins at it
    TOP = 0.93
    GRIP = 0.86

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.top_grip = False
        self.every = False

    def along(self, pos):
        """How far along the visible line a point (the line's own) is, 0 to 1."""
        left, right = self._endPoints
        if right == left:
            return 0.5
        return (pos.x() - left) / (right - left)

    def mouseDragEvent(self, ev):
        if ev.isStart():
            self.every = self.top_grip and self.along(ev.buttonDownPos()) >= self.GRIP
        super().mouseDragEvent(ev)
        if ev.isFinish():
            self.every = False


def step_curve(wave, flux, split=SPLIT):
    """
    The data as steps centred on the pixels: two points per pixel, at the edges
    half way to its neighbours, with a break at each gap: a NaN in the flux, at the
    gap's edge, so that x stays finite and in order (pyqtgraph clips a curve to the
    view by bisecting its x, and a NaN there stops it short: Stage 10, point 2).

    Returns
    -------
    tuple
        ``(x, y)``.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    flux = np.asarray(flux, dtype=float)
    if wave.size == 0:
        return np.zeros(0), np.zeros(0)
    if wave.size == 1:
        return np.array([wave[0], wave[0]]), np.array([flux[0], flux[0]])
    left, right = pixel_edges(wave, split)
    breaks = gaps(wave, split)
    x = np.empty(2 * wave.size)
    y = np.empty(2 * wave.size)
    x[0::2], x[1::2] = left, right
    y[0::2], y[1::2] = flux, flux
    if breaks.size:
        at = 2 * breaks + 2
        x = np.insert(x, at, x[at - 1])
        y = np.insert(y, at, np.nan)
    return x, y


def pixel_edges(wave, split=SPLIT):
    """
    The edges of each pixel's step, where :func:`step_curve` draws them: half way
    to its neighbours, and beside a gap (or at an end) as far from the pixel as its
    other edge.

    Returns
    -------
    tuple
        ``(left, right)``, arrays of the pixels' size.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    if wave.size < 2:
        return wave.copy(), wave.copy()
    step = np.diff(wave)
    mid = 0.5 * (wave[1:] + wave[:-1])
    left = np.concatenate(([wave[0] - 0.5 * step[0]], mid))
    right = np.concatenate((mid, [wave[-1] + 0.5 * step[-1]]))
    # Either side of a gap, a pixel's edge is as far from it as its other edge
    for k in gaps(wave, split):
        right[k] = wave[k] + (wave[k] - left[k])
        left[k + 1] = wave[k + 1] - (right[k + 1] - wave[k + 1])
    return left, right


def pixel_spans(x, spans, split=SPLIT):
    """
    Shaded spans that end at the pixels' step edges (Stage 8, point 3): each span
    holds the pixels whose centres lie in it, and goes from its first pixel's left
    edge to its last pixel's right edge, so that a pixel is shaded exactly when it
    is in. A run broken by a gap in the data gives a span on each side; a span with
    no pixel in it is left out.

    Parameters
    ----------
    x : array
        The pixels' centres on the axis, in increasing order.
    spans : list of (low, high)
        By the pixels' centres (a fit region, :func:`project.mask_regions`), or any
        range of the axis.

    Returns
    -------
    list of tuple

    Generated by RJC and Claude.
    """
    x = np.asarray(x, dtype=float)
    if x.size == 0:
        return []
    left, right = pixel_edges(x, split)
    step = np.diff(x)
    tol = 1.0e-6 * (float(np.median(np.abs(step))) if step.size else 1.0)
    cuts = set(gaps(x, split).tolist())
    out = []
    for low, high in spans:
        low, high = min(low, high), max(low, high)
        idx = np.flatnonzero((x >= low - tol) & (x <= high + tol))
        if not idx.size:
            continue
        start = idx[0]
        for prev, num in zip(idx[:-1], idx[1:]):
            if num != prev + 1 or prev in cuts:
                out.append((float(left[start]), float(right[prev])))
                start = num
        out.append((float(left[start]), float(right[idx[-1]])))
    return out


def broken_line(wave, values, split=SPLIT):
    """
    A line through the pixels, with a break at each gap of the data: a NaN in the
    values, at the gap's edge, as :func:`step_curve` breaks.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    values = np.asarray(values, dtype=float)
    breaks = gaps(wave, split)
    if not breaks.size:
        return wave, values
    return (
        np.insert(wave, breaks + 1, wave[breaks]),
        np.insert(values, breaks + 1, np.nan),
    )


def nice_step(span, target=6):
    """A round step that gives about ``target`` ticks over ``span``."""
    if span <= 0:
        return 1.0
    raw = span / target
    power = 10.0 ** np.floor(np.log10(raw))
    for factor in (1.0, 2.0, 2.5, 5.0, 10.0):
        if raw <= factor * power:
            return factor * power
    return 10.0 * power


def signed(value):
    """
    A velocity tick, signed (D43): ``+100``, ``−100``, ``0``.

    Generated by RJC and Claude.
    """
    if abs(value) < 1e-9:
        return "0"
    text = "{0:g}".format(abs(value))
    return ("+" if value > 0 else "−") + text


