"""The spectrum view: one pyqtgraph widget for every spectrum of the dashboard.

Dashboard Stage 4.5 (D38, D43). The Data and Regions tabs (and the Fit tab later)
draw their spectra with :class:`SpectrumView`, controlled by a :class:`ZoomBar`:

- **The zoom bar** (D38, Stage 0's draft 6): ⌂ home, ← back, → forward, ✥ pan, ⬚ zoom
  box, and + / − (zoom along the wavelength axis only). The wheel zooms the wavelength
  axis. Each bar keeps its own history of zooms for ← and →; the views it controls
  share their wavelength axis.
- **Drawing:** the data as steps centred on the pixels, broken where the data have a
  gap; the error, thin and grey; the continuum, dashed; the zero line, dashed grey;
  bad pixels as grey crosses. Large spectra are downsampled (peak) and clipped to the
  view.
- **Overlays:** fit regions, regions fitted by another snip, pixels fitted twice
  (hatched), the snip's edges (orange handles), the continuum's knots, line IDs (ticks
  and labels, each kind with its colour and its line style), and a marker for a
  clicked point.
- **Modes:** pan, zoom box, draw (a drag gives a span), mask (a click or a drag gives a
  span), click (a click gives a point: Identify a feature).
- **Axes:** wavelength in Å below; above, when a centre is set, velocity in km/s,
  signed (+100, −100, 0; D43). The Components tab's panels draw in velocity
  instead (``x_title``).
- **The model** (Stage 5): ALIS's model of the snip, divided by the continuum when
  the data are; the **ticks** of components (draggable, Stage 5.5), excluded ones
  faint and dashed, other systems' lines grey; and a :class:`ResidualView` strip,
  (data − model)/σ with ±1σ, which on the Fit tab shades the pixels that are not
  fitted.

The view draws what it is given and reports what the user does with signals; it
changes nothing in the project. It shows no parameter value: the line IDs name
transitions, and a hidden value never reaches it.

Generated by RJC and Claude.
"""

