class VelocityAxis(pg.AxisItem):
    """
    The top axis: velocity relative to a centre wavelength, in km/s, signed.

    Generated by RJC and Claude.
    """

    def __init__(self, *args, **kwargs):
        super().__init__("top", *args, **kwargs)
        self.centre = None

    def tickValues(self, minVal, maxVal, size):
        """Round velocities, placed at their wavelengths."""
        if self.centre is None or not np.isfinite(minVal) or not np.isfinite(maxVal):
            return []
        vlo = C_KMS * (minVal / self.centre - 1.0)
        vhi = C_KMS * (maxVal / self.centre - 1.0)
        step = nice_step(vhi - vlo, max(int(size / 90), 2))
        first = np.ceil(vlo / step) * step
        vels = np.arange(first, vhi + 0.5 * step, step)
        return [(step, list(self.centre * (1.0 + vels / C_KMS)))]

    def tickStrings(self, values, scale, spacing):
        """Each tick's velocity, signed."""
        if self.centre is None:
            return ["" for _ in values]
        return [signed(round(C_KMS * (v / self.centre - 1.0), 6)) for v in values]


class SpectrumBox(pg.ViewBox):
    """
    The view box: the wheel zooms the wavelength axis only; a drag pans, zooms to a
    box, or gives a span (draw, mask); a click gives a point.

    Generated by RJC and Claude.
    """

    clicked = QtCore.Signal(float, float)
    rightClicked = QtCore.Signal(float, float, object)
    spanned = QtCore.Signal(str, float, float, bool)
    dragged = QtCore.Signal(float, float, float, float, str)
    userChanged = QtCore.Signal()

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.mode = PAN
        self._span = None
        # Drags edit (the Components tab's panels, Q5.23): a left drag gives its
        # points, a right drag pans
        self.edits = False
        self.setMouseMode(pg.ViewBox.PanMode)

    def set_mode(self, mode):
        """Pan, zoom box, draw, mask or click."""
        self.mode = mode
        self.setMouseMode(pg.ViewBox.RectMode if mode == ZOOM else pg.ViewBox.PanMode)

    def wheelEvent(self, ev, axis=None):
        """Zoom the wavelength axis only (D38)."""
        super().wheelEvent(ev, axis=0)
        self.userChanged.emit()

    def mouseClickEvent(self, ev):
        """A left click gives its point; other clicks as pyqtgraph has them."""
        if ev.button() == QtCore.Qt.MouseButton.LeftButton:
            pos = self.mapSceneToView(ev.scenePos())
            ev.accept()
            if self.mode == MASK:
                self.spanned.emit(MASK, pos.x(), pos.x(), True)
            self.clicked.emit(pos.x(), pos.y())
            return
        if ev.button() == QtCore.Qt.MouseButton.RightButton:
            pos = self.mapSceneToView(ev.scenePos())
            ev.accept()
            self.rightClicked.emit(pos.x(), pos.y(), ev.screenPos())
            return
        super().mouseClickEvent(ev)

    def mouseDragEvent(self, ev, axis=None):
        """
        Draw and mask take a span: in draw mode a left drag draws and a right drag
        masks (as ``prepfit`` does), in mask mode a left drag masks; where drags
        edit (Q5.23), a left drag gives its points and a right drag pans; pan and
        zoom box as pyqtgraph does them.

        Generated by RJC and Claude.
        """
        button = ev.button()
        if self.edits and button == QtCore.Qt.MouseButton.RightButton:
            # A right drag pans
            ev.accept()
            last = self.mapSceneToView(ev.lastScenePos())
            here = self.mapSceneToView(ev.scenePos())
            self.translateBy(x=last.x() - here.x(), y=last.y() - here.y())
            if ev.isFinish():
                self.userChanged.emit()
            return
        if (
            self.edits
            and self.mode == PAN
            and button == QtCore.Qt.MouseButton.LeftButton
        ):
            ev.accept()
            start = self.mapSceneToView(ev.buttonDownScenePos())
            here = self.mapSceneToView(ev.scenePos())
            state = "start" if ev.isStart() else "finish" if ev.isFinish() else "move"
            self.dragged.emit(start.x(), start.y(), here.x(), here.y(), state)
            return
        kind = None
        if self.mode == DRAW and button == QtCore.Qt.MouseButton.LeftButton:
            kind = DRAW
        elif self.mode == DRAW and button == QtCore.Qt.MouseButton.RightButton:
            kind = MASK
        elif self.mode == MASK and button == QtCore.Qt.MouseButton.LeftButton:
            kind = MASK
        if kind is not None:
            ev.accept()
            start = self.mapSceneToView(ev.buttonDownScenePos()).x()
            here = self.mapSceneToView(ev.scenePos()).x()
            low, high = sorted((start, here))
            if self._span is None:
                colour = COLOURS["drawing" if kind == DRAW else "masking"]
                self._span = pg.LinearRegionItem(
                    (low, high), movable=False, brush=pg.mkBrush(*colour)
                )
                self.addItem(self._span, ignoreBounds=True)
            self._span.setRegion((low, high))
            if ev.isFinish():
                self.removeItem(self._span)
                self._span = None
                self.spanned.emit(kind, low, high, True)
            return
        super().mouseDragEvent(ev, axis)
        if ev.isFinish():
            self.userChanged.emit()


