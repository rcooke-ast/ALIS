"""The ``.mod`` panel's text while the user types: the logic, with no Qt.

Dashboard Stage 3.6 (D7, F2, F8; Q3.5). The panel shows the text through the blinding
gate (``Gate.view()``, a :class:`~alis.dashboard.blinding.MaskedView`). Reading the
model again takes 0.03–0.4 s, too long for every key, so typing works in two steps:

- **At each key**, :class:`LiveText` turns the change of the panel's text into a
  patch of the real text, and keeps the two in step: the masks move with the text
  around them. Nothing is read yet.
- **After a pause**, :meth:`LiveText.pending` gives every patch since the last
  reading as one change, which the panel gives to the history as typing (grouped by
  pause, F2). The project then reads the text again, and the panel is redrawn from
  the gate.

An edit that cuts into a mask is not made at the key: the panel asks for the new
value in a small box (the user sees only what they type, QF.20(c)), and
:meth:`LiveText.replace_masked` makes it as one patch. An edit that replaces whole
masks (deleting a hidden line, or selecting it and typing another) is made as it is,
since it shows nothing. A key typed just before or just after a mask does not touch
it, so the label next to a hidden value, or the space before it, can be edited.

Generated by RJC and Claude.
"""

import re
from dataclasses import dataclass

from alis.dashboard import blinding as BL
from alis.dashboard import text as T


def diff(old, new, cursor=None):
    """
    The one span of ``old`` that an edit replaced to give ``new``.

    Where repeated characters make the span ambiguous, the cursor's position after
    the edit (in ``new``) decides: the edit ends at the cursor.

    Parameters
    ----------
    old, new : str
    cursor : int, optional

    Returns
    -------
    tuple
        ``(start, end, typed)``: ``old[start:end]`` became ``typed``.

    Generated by RJC and Claude.
    """
    # The common suffix first, ending no later than the cursor (slices compare in C)
    room = min(len(old), len(new))
    if cursor is not None:
        room = min(room, len(new) - cursor)
    low, high = 0, max(room, 0)
    while low < high:
        mid = (low + high + 1) // 2
        if old[len(old) - mid :] == new[len(new) - mid :]:
            low = mid
        else:
            high = mid - 1
    suffix = low
    # Then the common prefix, before the suffix
    low, high = 0, min(len(old), len(new)) - suffix
    while low < high:
        mid = (low + high + 1) // 2
        if old[:mid] == new[:mid]:
            low = mid
        else:
            high = mid - 1
    prefix = low
    return prefix, len(old) - suffix, new[prefix : len(new) - suffix]


@dataclass(frozen=True)
class MaskEdit:
    """
    An edit that touches a mask: the panel asks for the new value.

    Attributes
    ----------
    start, end : int
        The span of the panel's text the edit replaced.
    typed : str
        What was typed, without mask characters.

    Generated by RJC and Claude.
    """

    start: int
    end: int
    typed: str


class LiveText:
    """
    The panel's text and the real text, kept in step between two readings.

    Parameters
    ----------
    view : MaskedView
        The panel's text as last drawn from the gate.

    Attributes
    ----------
    real : str
        The real text, with the patches typed since the last reading.
    shown : str
        What the panel shows.
    segments : list of tuple
        ``(shown start, shown end, real start, real end)`` of each mask.
    patches : list of Patch
        The patches of the real text since the last reading, in order.

    Generated by RJC and Claude.
    """

    def __init__(self, view):
        self.base = view.mtext.text
        self.real = view.mtext.text
        self.shown, self.segments = _normalise(view.text, view.segments)
        self.patches = []

    def touched(self, start, end):
        """
        The masks an edit of ``[start, end)`` touches: those it overlaps, or, for an
        insertion, those it falls strictly inside.

        Generated by RJC and Claude.
        """
        masks = [s for s in self.segments if s[4]]
        if start == end:
            return [s for s in masks if s[0] < start < s[1]]
        return [s for s in masks if s[0] < end and s[1] > start]

    def _real(self, pos):
        """The real offset of a position of the panel's text, outside the masks."""
        shift = 0
        for dstart, dend, rstart, rend, _ in self.segments:
            if pos >= dend:
                shift += (rend - rstart) - (dend - dstart)
        return pos + shift

    def edit(self, new, cursor=None):
        """
        Follow the panel's text to ``new``.

        Returns
        -------
        Patch, MaskEdit or None
            The patch of the real text that the edit makes (it is kept); a
            :class:`MaskEdit` when the edit touches a mask (nothing is kept, and the
            panel puts its text back); or None when nothing changed.

        Generated by RJC and Claude.
        """
        start, end, typed = diff(self.shown, new, cursor)
        if start == end and not typed:
            return None
        touched = self.touched(start, end)
        # An edit that cuts into a mask asks for the value; one that replaces whole
        # masks (deleting or retyping a hidden line) shows nothing, and is made
        if any(s[0] < start or s[1] > end for s in touched) or (
            touched and start == end
        ):
            return MaskEdit(start, end, typed.replace(BL.MASK[0], ""))
        rstart, rend = self._real(start), self._real(end)
        patch = T.Patch(rstart, self.real[rstart:rend], typed)
        self._apply(patch, start, end, typed)
        return patch

    def _apply(self, patch, start, end, typed):
        """
        Make a patch, and move the masks and line endings after it. A line ending
        inside the edit has gone with it (a mask cannot be there).

        Generated by RJC and Claude.
        """
        self.real = patch.apply(self.real)
        self.shown = self.shown[:start] + typed + self.shown[end:]
        dshift = len(typed) - (end - start)
        rshift = len(patch.new) - len(patch.old)
        kept = []
        for ds, de, rs, rend, mask in self.segments:
            if de <= start:
                kept.append((ds, de, rs, rend, mask))
            elif ds >= end:
                kept.append(
                    (ds + dshift, de + dshift, rs + rshift, rend + rshift, mask)
                )
        self.segments = kept
        self.patches.append(patch)

    def replace_masked(self, start, end, value):
        """
        The patch that gives the hidden value an edit touched a new value, typed in
        the panel's box (QF.20(c)). It stays hidden, since its line or label still
        is.

        Parameters
        ----------
        start, end : int
            The span of the panel's text the edit replaced (:class:`MaskEdit`).
        value : str
            The new value.

        Returns
        -------
        Patch

        Generated by RJC and Claude.
        """
        touched = self.touched(start, end)
        if not touched:
            raise BL.BlindingError("The edit does not touch a hidden value.")
        first, last = touched[0], touched[-1]
        dstart, dend = min(start, first[0]), max(end, last[1])
        # Only masks lie inside the span: a mask never holds a line ending
        rstart = first[2] if dstart == first[0] else self._real(dstart)
        rend = last[3] if dend == last[1] else self._real(dend)
        patch = T.Patch(rstart, self.real[rstart:rend], value)
        self.real = patch.apply(self.real)
        self.patches.append(patch)
        return patch

    @property
    def dirty(self):
        """Whether there are patches the history has not been given."""
        return bool(self.patches)

    def pending(self, description="Typing"):
        """
        Every patch since the last reading, as one change of the text the project
        holds.

        Generated by RJC and Claude.
        """
        return T.Change(tuple(self.patches), description)


def _normalise(text, masks):
    """
    The panel's text as Qt's editor holds it, with every line ending a ``\\n``, and
    the segments that map it to the real text: each mask, and each ``\\r\\n``
    (one character shown, two real).

    Parameters
    ----------
    text : str
        The masked view's text.
    masks : list of tuple
        Its masks, ``(start, end, real start, real end)``.

    Returns
    -------
    tuple
        ``(shown, segments)``, each segment ``(shown start, shown end, real start,
        real end, is a mask)``.

    Generated by RJC and Claude.
    """
    crlf = [m.start() for m in re.finditer("\r\n", text)]
    if not crlf:
        shown = text.replace("\r", "\n")
        return shown, [(a, b, c, d, True) for a, b, c, d in masks]
    shift = 0  # real minus view, from the masks before
    segments, removed = [], 0
    marks = sorted([(m[0], 0, m) for m in masks] + [(i, 1, None) for i in crlf])
    for pos, kind, mask in marks:
        if kind == 0:
            dstart, dend, rstart, rend = mask
            segments.append((dstart - removed, dend - removed, rstart, rend, True))
            shift += (rend - rstart) - (dend - dstart)
        else:
            real = pos + shift
            segments.append((pos - removed, pos - removed + 1, real, real + 2, False))
            removed += 1
    shown = text.replace("\r\n", "\n").replace("\r", "\n")
    return shown, segments


def position(text, offset):
    """
    The ``(line, column)`` of an offset of a text.

    Generated by RJC and Claude.
    """
    offset = max(0, min(offset, len(text)))
    line = text.count("\n", 0, offset)
    start = text.rfind("\n", 0, offset) + 1
    return line, offset - start


def offset(text, line, column):
    """
    The offset of a line and column of a text, clamped to the line's end.

    Generated by RJC and Claude.
    """
    lines = text.split("\n")
    line = max(0, min(line, len(lines) - 1))
    start = sum(len(lines[n]) + 1 for n in range(line))
    return start + max(0, min(column, len(lines[line])))


