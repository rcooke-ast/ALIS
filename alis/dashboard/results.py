@dataclass
class HistoryRow:
    """
    A row of the run history: the latest run (until it is committed), or a
    committed run.

    Attributes
    ----------
    key : int or None
        The committed run's number, or None for the latest run not yet committed.
    run : str
        ``"Latest"``, ``"3"``, or ``"3 · latest"`` for the latest run committed.
    description : str
        The user's own description, through the gate; ``""`` until committed.
    reduced : str
        χ²ν, or ``"—"``.
    when : str
        When the run ended (or was imported).
    where : str
        ``"dashboard"``, ``"cmd · gpu-box"`` (``run_alis project.model``, S31) or
        ``"imported"``.
    status : str
        How it ended, when it did not complete: ``"stopped"``, ``"no fit"``.
    tip : str
        Where, when and how, in a sentence.
    record : RunRecord
    latest : bool
        Whether it is the latest run.

    Generated by RJC and Claude.
    """

    key: object
    run: str
    description: str
    reduced: str
    when: str
    where: str
    status: str
    tip: str
    record: object = field(repr=False)
    latest: bool = False

    @property
    def committable(self):
        """The latest run, not yet committed: Commit… keeps it."""
        return self.key is None


_STATUS_WORDS = {R.INTERRUPTED: "stopped", R.STOPPED: "no fit", R.ERROR: "error"}


def reduced_chi2(record):
    """
    A run's χ²ν: from ``run.json``, or from its ``.mod.out``'s header (an imported
    fit); None when neither gives it.

    Generated by RJC and Claude.
    """
    found = record.reduced_chi2
    if found is not None:
        return found
    head = _header(record.mod_out() or "")
    chi2, dof = head.get("Bestfit Chi-Squared"), head.get("Degrees-of-Freedom")
    if isinstance(chi2, float) and isinstance(dof, int) and dof:
        return chi2 / dof
    found = head.get("Reduced Chi-Squared")
    return found if isinstance(found, float) else None


def _history_row(record, gate, key, latest):
    reduced = reduced_chi2(record)
    origin = record.origin
    host = record.host
    if origin == R.COMMAND:
        where = "cmd" + (" · " + host if host else "")
    elif origin == R.IMPORTED:
        where = "imported"
    else:
        where = "dashboard"
    if key is None:
        run = "Latest"
    else:
        run = str(key) + (" · latest" if latest else "")
    status = _STATUS_WORDS.get(record.status, "")
    when = when_text(record.finished, short=True) if record.finished else ""
    how = {
        R.DASHBOARD: "Run from the dashboard",
        R.COMMAND: "Run with run_alis",
        R.IMPORTED: "Imported with the model",
    }.get(origin, "Run")
    tip = how + (" on " + host if host and origin != R.IMPORTED else "")
    tip += (", " + when_text(record.finished)) if record.finished else ""
    if status:
        tip += (
            "; "
            + {
                "stopped": "stopped before the end, so it has no errors",
                "no fit": "ALIS ended it without a fit",
                "error": "it stopped with an error",
            }[status]
        )
    return HistoryRow(
        key=key,
        run=run,
        description=gate.message(record.description),
        reduced="—" if reduced is None else "{0:.3f}".format(reduced),
        when=when,
        where=where,
        status=status,
        tip=tip + ".",
        record=record,
        latest=latest,
    )


def history(project):
    """
    The run history (F7, D26): the latest run first while it is not committed, then
    the committed runs, newest first; the latest run, once committed, is its
    committed row.

    Returns
    -------
    list of HistoryRow

    Generated by RJC and Claude.
    """
    gate = BL.Gate(project)
    out = []
    latest = R.latest(project.bundle)
    number = None if latest is None else latest.committed_as
    if latest is not None and number is None:
        out.append(_history_row(latest, gate, None, True))
    for record in R.committed(project.bundle):
        out.append(_history_row(record, gate, record.number, record.number == number))
    return out


def shown_record(project, number=None):
    """
    The run the Fit tab shows (Q6.5): committed run ``number``, chosen in the run
    history, or the latest run (also when that run has been removed); None when
    the project has no run.

    Generated by RJC and Claude.
    """
    if number is not None:
        try:
            return R.run_of(project.bundle, int(number))
        except (R.RunError, TypeError, ValueError):
            pass
    return R.latest(project.bundle)


def _ion_name(ion):
    """An ion, or a ratio of two, as people write it."""
    if ion and "/" in ion:
        return "/".join(P.ion_name(i) for i in ion.split("/"))
    return FOREST_NAMES.get(ion, P.ion_name(ion))


def _system_name(system):
    """A system's name for a title: its own, or what it is when its name is only its
    redshift (an inferred system)."""
    if system.name and not system.name.startswith("z ="):
        return system.name
    return "Primary system" if system.primary else "System " + system.id


def _format(kind, value, error):
    """The format of a row's value and error."""
    if kind in _DECIMALS:
        return "{{0:.{0}f}}".format(_DECIMALS[kind])
    return "{0:.6g}"


def _state(pm, par):
    """A parameter's state and detail (the label it is tied by, or its link)."""
    if par.linked:
        for link in pm.links:
            if par.label and link.target.lower() == par.label.lower():
                return LINKED, "{0} = {1}".format(link.target, link.expression)
        return LINKED, ""
    if par.fixed:
        return FIXED, par.label
    label = pm.labels.get(par.label) if par.label else None
    if label is not None and len(label.params) > 1:
        return TIED, par.label
    return FREE, ""


def _untied_flags(model):
    """
    The flags of an imported fit's parameters that are not tied as the dashboard
    ties them (D20, D22): an isotope's z, b_turb or T not shared with its element's
    main isotope, and a component's redshift not tied to the component's.

    Returns
    -------
    dict
        ``(line, parameter name)`` to its flags.

    Generated by RJC and Claude.
    """
    out = {}
    for comp in model.components:
        for (_, _), ions in comp.isotopes.items():
            main = P._main_isotope(ions)
            if not comp.lines_of(main):
                continue
            ref = comp.lines_of(main)[0]
            for ion in ions:
                if ion == main:
                    continue
                for line in comp.lines_of(ion):
                    for name in ("redshift", "bturb", "temperature"):
                        if not P._shared(ref.param(name), line.param(name)):
                            out.setdefault((line.line, name), []).append(
                                "not tied to " + P.ion_name(main)
                            )
        if len(comp.lines) > 1:
            for line in comp.lines:
                if not comp.label or line.param("redshift").label != comp.label:
                    out.setdefault((line.line, "redshift"), []).append(
                        "z not tied to " + comp.id
                    )
    return out


def _resolution(text):
    """Half a unit of the last digit of a value as written, or None."""
    if not text:
        return None
    found = _NUMBER.match(text.strip())
    if not found or not (found.group(1) or found.group(2)):
        return None
    decimals = len(found.group(2))
    exponent = int(found.group(3) or 0)
    return 0.5 * 10.0 ** (exponent - decimals)


def at_limit(param, value, text=None):
    """
    The bound a value is on (Q6.12), or None: one of the parameter's limits (a
    ``lim`` line, or the function's own), equal to the value to the precision it is
    written with (``text``, from the ``.mod.out``), as the minimiser leaves a
    parameter that presses on its bound.

    Generated by RJC and Claude.
    """
    tol = _resolution(text) or 0.0
    for bound in param.limits:
        if bound is None:
            continue
        if abs(value - bound) <= max(tol, 1.0e-10 * max(1.0, abs(bound))):
            return bound
    return None


def own_limit(pm, param):
    """
    The function whose own limit bounds a parameter (Q7.14), or ``""`` when a
    ``lim`` command sets its limits: no line of the model says where it comes from.

    Generated by RJC and Claude.
    """
    line = pm.item_at(param.line)
    function = getattr(line, "function", "") or ""
    label = (param.label or "").lower()
    for cmd in pm.commands:
        if cmd.kind != "lim":
            continue
        if cmd.target == "param" and label and cmd.name.lower() == label:
            return ""
        if cmd.target == function and cmd.name == param.name:
            return ""
    return function


def unconstrained(param, value, error, prefs=None, hidden=False, kind=None):
    """
    Whether a value's error marks it unconstrained (Q6.12): larger than 1 dex for a
    log N, than 10 km/s (as a velocity) for a redshift, and than the value for b, T
    and the others; each threshold a preference. For a hidden value, only the tests
    that do not involve the value are made.

    Generated by RJC and Claude.
    """
    kind = kind or param.name
    owner = param.owner
    linear = (
        isinstance(owner, M.ModelLine)
        and str(owner.keyword("logN", "True")).lower() == "false"
    )
    if kind == "ColDens" and not linear:
        return error > _pref(prefs, "fit.loose_logn")
    if kind == "redshift":
        return C_KMS * error / (1.0 + value) > _pref(prefs, "fit.loose_kms")
    if hidden:
        return False
    return error > _pref(prefs, "fit.loose_fraction") * abs(value)


def _header(text):
    """The numbers and reason of a ``.mod.out``'s header."""
    out = {}
    for line in text.splitlines()[:16]:
        found = _HEADER.match(line)
        if not found:
            continue
        name, value = found.group(1), found.group(2)
        try:
            out[name] = (
                float(value) if "." in value or "e" in value.lower() else int(value)
            )
        except ValueError:
            out[name] = value
    return out


def _seconds(started, finished):
    try:
        one = datetime.datetime.fromisoformat(started)
        two = datetime.datetime.fromisoformat(finished)
    except (TypeError, ValueError):
        return None
    return (two - one).total_seconds()


# -- The fit-quality marks (S18, D39) -------------------------------------------------


def _mark(value, nsig):
    if value > nsig:
        return BAD
    if value > min(WARN_SIGMA, nsig):
        return WARN
    return GOOD


@dataclass
class Quality:
    """
    The fit quality of one snip's best fit, as ``alis/report.py`` computes it.

    Attributes
    ----------
    npix : int
        The fitted pixels with a valid error.
    chi2, reduced : float
        χ² and χ²/N.
    deviation : float
        (χ²ν − 1)/√(2/N): flagged only above.
    runs_z : float
        The runs test's z: flagged either way.
    nsig : float
        ``out reportsig``.

    Generated by RJC and Claude.
    """

    npix: int
    chi2: float
    reduced: float
    deviation: float
    runs_z: float
    nsig: float = 3.0

    @property
    def chi2_mark(self):
        """✓, ! or ✕ for χ²ν."""
        return _mark(self.deviation, self.nsig)

    @property
    def runs_mark(self):
        """✓, ! or ✕ for the runs test."""
        return _mark(abs(self.runs_z), self.nsig)

    @property
    def flagged(self):
        """Whether the report flags the snip."""
        return BAD in (self.chi2_mark, self.runs_mark)


def counted(curve):
    """
    The pixels of a curve that the marks count, as ALIS's report counts them: those
    ALIS fits (inside the fit regions, not left out, not bad) with σ > 0 and a model
    (Stage 6.5: the Fit tab shades the others in the residual strip).

    Generated by RJC and Claude.
    """
    with np.errstate(invalid="ignore"):
        return curve.fitted & (curve.error > 0) & np.isfinite(curve.model)


def residuals(curve):
    """
    The residuals of a curve over its fitted pixels, in their order, as the report
    takes them: (data − model)/σ where σ > 0.

    Generated by RJC and Claude.
    """
    good = counted(curve)
    return (curve.flux[good] - curve.model[good]) / curve.error[good]


def quality(curve, nsig=3.0):
    """
    The fit-quality marks of one curve (S18, Q6.6(b)), or None with no fitted pixel.

    Generated by RJC and Claude.
    """
    stats = report.region_stats(residuals(curve), nsig)
    if stats is None:
        return None
    return Quality(
        stats["npix"],
        stats["chi2"],
        stats["redchi2"],
        stats["dev"],
        stats["runs_z"],
        float(nsig),
    )


# -- Writing best-fit values ----------------------------------------------------------


def _written(view, index, value):
    """A best-fit value as it is written into the model: as the ``.mod.out`` writes
    it, or to ten figures."""
    text = view.texts.get(index)
    if text is not None:
        try:
            if float(text) == value:
                return E.format_value(text)
        except ValueError:
            pass
    return E.format_value(float(value), 10)


def _requires_record(view):
    if view.in_progress:
        raise ResultsError(
            "The fit is still running: wait for it to end, or stop it, first."
        )
    why = view.why_not()
    if why:
        raise ResultsError(why)


def _hide(project, view, step, lines):
    """
    The step, hiding also the lines that receive a best-fit value: under global
    blind every one of them, and otherwise those whose values ALIS offsets (S20).

    Generated by RJC and Claude.
    """
    if view.gate.global_blind:
        hide = set(lines)
    else:
        offsets = {
            item.line for item in project.parsed.lines if "blindrange" in item.keywords
        }
        hide = set(lines) & offsets
    if not hide:
        return step
    old = set(project.extra_hidden) if step.hidden is None else set(step.hidden[0])
    new = set(project.extra_hidden) if step.hidden is None else set(step.hidden[1])
    step.hidden = (old, new | hide)
    return step


def _line_name(project, num):
    """What a line of the model is, for a plan: "O I a1", "the continuum of H1"."""
    for comp in project.components:
        for line in comp.lines + comp.ratios:
            if line.line == num:
                return "{0} {1}".format(_ion_name(line.ion), comp.id)
    for line in project.absorbers:
        if line.line == num:
            return "a line of the Lyα forest"
    for snip in project.snips:
        if snip.continuum is not None and snip.continuum.line == num:
            return "the continuum of " + ",".join(
                snip.continuum.specids or [snip.specid]
            )
        if snip.data.line == num:
            return "the data line of " + snip.specid
    return "line {0}".format(num + 1)


@dataclass
class Plan:
    """
    What a copy of best-fit values does, for its preview (S20).

    Attributes
    ----------
    step : Step or None
        None when nothing would change.
    changed : list
        ``(line, what, names)``: each line that receives values, what it is, and
        the parameters it receives (no value: they may be hidden).
    skipped : list
        ``(line, what, names, reason)``: each line whose parameters keep their
        values.

    Generated by RJC and Claude.
    """

    step: object = None
    changed: list = field(default_factory=list)
    skipped: list = field(default_factory=list)

    @property
    def lines(self):
        """The lines that receive values."""
        return [c[0] for c in self.changed]


def _add_name(table, line, what, name, extra=None):
    for entry in table:
        if entry[0] == line and entry[3:] == ([extra] if extra is not None else []):
            if name not in entry[2]:
                entry[2].append(name)
            return
    table.append([line, what, [name]] + ([extra] if extra is not None else []))


def continue_plan(project, view):
    """
    Continue from best fit (S20, Q6.8): the step that copies the shown run's
    best-fit value of every free parameter unchanged since the run into the model,
    and what it changes and skips.

    A parameter is unchanged when every place it is written is on a line that is the
    same line as in the run's model (:func:`match_lines`), with the same value
    written; one changed since the run keeps its value, and the plan lists it.
    Linked parameters are left to ALIS, and fixed ones keep their values. An
    interrupted run can be continued from.

    Returns
    -------
    Plan

    Raises
    ------
    ResultsError
        For the fit in progress, or a run with no best fit.

    Generated by RJC and Claude.
    """
    project.require_reading()
    _requires_record(view)
    pm, run_pm = project.parsed, view.model.parsed
    back = {new: old for old, new in view.lines.items()}
    theirs = _places(run_pm)
    by_index = {}
    for par in pm.params:
        if par.index >= 0:
            by_index.setdefault(par.index, []).append(par)
    plan = Plan()
    patches, lines = [], []
    for index, places in by_index.items():
        first = places[0]
        if first.linked or first.fixed:
            continue
        run_index, reason = None, ""
        for place in places:
            old = back.get(place.line)
            match = None if old is None else theirs.get((old, place.role, place.slot))
            if match is None:
                reason = "new or changed since the run"
                break
            if (match.value_token is None) != (place.value_token is None) or (
                place.value_token is not None
                and match.value_token.text != place.value_token.text
            ):
                reason = "changed since the run"
                break
            if match.label != place.label or (
                run_index is not None and match.index != run_index
            ):
                reason = "tied differently since the run"
                break
            run_index = match.index
        if reason:
            for place in places:
                what = _line_name(project, place.line)
                _add_name(
                    plan.skipped,
                    place.line,
                    what,
                    _SHORT.get(place.name, place.name),
                    reason,
                )
            continue
        value = view.values.get(run_index)
        if value is None:
            continue
        text = _written(view, run_index, value)
        if float(text) == first.start:
            continue
        for place in places:
            if place.value_token is None:
                patches.extend(E.set_value(pm, place, text, everywhere=False).patches)
            else:
                patches.append(T.replace_token(pm.text, place.value_token, text))
            _add_name(
                plan.changed,
                place.line,
                _line_name(project, place.line),
                _SHORT.get(place.name, place.name),
            )
            lines.append(place.line)
    plan.changed = [tuple(c) for c in sorted(plan.changed)]
    plan.skipped = [tuple(c) for c in sorted(plan.skipped)]
    if patches:
        change = T.Change.from_spans(patches, "Continue from the best fit")
        step = project.step(
            change, "Continue from the best fit of {0}".format(view.name)
        )
        plan.step = _hide(project, view, step, set(lines))
    return plan


# -- Use best fit: one component (Q6.17) ----------------------------------------------


def run_component(view, comp):
    """
    The run's component for a component of the project: the one with its redshift
    label, or, without a label, the one whose line is the same line; or None.

    Generated by RJC and Claude.
    """
    model = view.model
    if comp.label:
        for other in model.components:
            if other.label == comp.label:
                return other
        return None
    back = {new: old for old, new in view.lines.items()}
    old = back.get(comp.main.line)
    for other in model.components:
        if any(ln.line == old for ln in other.lines):
            return other
    return None


def _component_values(view, comp):
    """The values a component receives: ``[(Param, run index)]`` by its lines."""
    theirs = run_component(view, comp)
    if theirs is None:
        return []
    out, seen = [], set()
    for line in comp.lines + comp.ratios:
        match = [ln for ln in theirs.lines + theirs.ratios if ln.ion == line.ion]
        if not match:
            continue
        for name in VOIGT:
            par, src = line.param(name), match[0].param(name)
            if par is None or src is None or not par.free or par.index in seen:
                continue
            seen.add(par.index)
            out.append((par, src.index))
    return out


def component_reason(project, view, comp):
    """
    Why Use best fit cannot copy a component, or ``""`` when it can (the button's
    tooltip).

    Generated by RJC and Claude.
    """
    if view is None:
        return "There is no run to copy from."
    if view.in_progress:
        return "The fit is still running."
    why = view.why_not()
    if why:
        return why
    if run_component(view, comp) is None:
        if comp.label:
            return "{0} has no component with the redshift label {1}.".format(
                view.name.capitalize(), comp.label
            )
        return "{0} has no component {1}.".format(view.name.capitalize(), comp.id)
    if not _component_values(view, comp):
        return "Component {0} has no free value that {1} fitted.".format(
            comp.id, view.name
        )
    return ""


def component_step(project, view, comp):
    """
    Use best fit on a component card (Q6.17): the step that copies the shown run's
    best-fit z, b_turb, T and each ion's log N of the component into its lines, even
    into lines changed since the run. An ion the run did not have keeps its values.
    One step, whose description names no value.

    Raises
    ------
    ResultsError

    Generated by RJC and Claude.
    """
    project.require_reading()
    why = component_reason(project, view, comp)
    if why:
        raise ResultsError(why)
    pm = project.parsed
    patches, lines = [], set()
    for par, index in _component_values(view, comp):
        value = view.values.get(index)
        if value is None:
            continue
        text = _written(view, index, value)
        change = E.set_value(pm, par, text, everywhere=True)
        patches.extend(change.patches)
        places = pm.labels[par.label].params if par.label in pm.labels else [par]
        lines |= {p.line for p in places}
    step = project.step(
        T.Change.from_spans(patches, "Use the best fit"),
        "Use the best fit of component {0}".format(comp.id),
    )
    return _hide(project, view, step, lines)


