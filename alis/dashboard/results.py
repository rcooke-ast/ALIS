@dataclass
class ContinuumCopy:
    """
    A snip's continuum line refitted to the run's best-fit continuum (Q6.20).

    Attributes
    ----------
    line : ModelLine
        The continuum line (the current model's), shared by ``snips``.
    snips : list of Snip
        The snips the line is the continuum of, that the run fitted.
    wave : dict
        Specid to the snip's pixels.
    run, copy : dict
        Specid to the run's best-fit continuum, and to the copy, on those pixels.
    largest, rms : float
        How far the copy departs from the run's continuum over the fitted pixels,
        in units of the data's errors.
    step : Step

    Generated by RJC and Claude.
    """

    line: object = field(repr=False)
    snips: list = field(repr=False)
    wave: dict = field(repr=False)
    run: dict = field(repr=False)
    copy: dict = field(repr=False)
    largest: float
    rms: float
    step: object = field(repr=False)


def continuum_reason(project, view, snip):
    """
    Why Use best fit cannot copy a snip's continuum, or ``""`` when it can.

    Generated by RJC and Claude.
    """
    if view is None:
        return "There is no run to copy from."
    if view.in_progress:
        return "The fit is still running."
    why = view.why_not()
    if why:
        return why
    line = snip.continuum
    if line is None or line.function not in CO.FUNCTIONS:
        return "This snip has no continuum line to copy into."
    if snip.pixels is None:
        return "The snip's file cannot be read."
    try:
        CO._check_free(line)
    except CO.ContinuumError as err:
        return str(err)
    theirs = view.run_snip(snip)
    if theirs is None:
        return "{0} did not fit {1}.".format(view.name.capitalize(), snip.specid)
    if theirs.continuum is None or theirs.continuum.function not in CO.FUNCTIONS:
        return "{0} has no continuum line for {1}.".format(
            view.name.capitalize(), snip.specid
        )
    return ""


def continuum_copy(project, view, snip):
    """
    Use best fit in the Continuum box (Q6.17, Q6.20): the snip's continuum line,
    with its function, order, range and ``scale=`` factors, fitted to the run's
    best-fit continuum on the pixels of the snips that share it, weighted by the
    data's errors. For an order raised or unchanged (or a range or function
    changed), this gives the run's continuum exactly; for an order lowered, the
    nearest curve of that order. One step.

    Returns
    -------
    ContinuumCopy

    Raises
    ------
    ResultsError

    Generated by RJC and Claude.
    """
    project.require_reading()
    why = continuum_reason(project, view, snip)
    if why:
        raise ResultsError(why)
    line = snip.continuum
    vector = view.vector()
    registry = project.registry
    function, order = line.function, CO.order_of(line)
    shared = [s for s in project.snips if s.continuum is line and s.pixels is not None]
    used, waves, targets, xs, errors, fits = [], {}, {}, [], [], []
    for one in shared:
        theirs = view.run_snip(one)
        if theirs is None or theirs.continuum is None:
            continue
        pix = one.pixels
        target = CO.evaluate(view.model, theirs, wave=pix.wave, values=vector)
        if target is None:
            continue
        used.append(one)
        waves[one.specid] = pix.wave
        targets[one.specid] = target
        xs.append(CO.model_wave(project, one, pix.wave))
        errors.append(pix.error)
    designs = []
    for one, x in zip(used, xs):
        designs.append(
            CO.basis(registry, function, x, order, CO.xrange_of(project, one, line))
        )
    design = np.vstack(designs)
    target = np.concatenate([targets[s.specid] for s in used])
    error = np.concatenate(errors)
    with np.errstate(invalid="ignore"):
        good = np.isfinite(target) & np.isfinite(error) & (error > 0)
        good &= np.all(np.isfinite(design), axis=1)
    good &= np.concatenate([s.pixels.fittable for s in used])
    if np.count_nonzero(good) < design.shape[1]:
        raise ResultsError("There are too few good pixels to fit the continuum to.")
    coef = CO._solve(design[good], target[good], 1.0 / error[good] ** 2)
    # Terms the curve does not need (above the run's order) are written as zero
    peak = np.max(np.abs(target[good]))
    reach = np.max(np.abs(design[good]), axis=0)
    coef[np.abs(coef) * reach <= 1.0e-12 * peak] = 0.0
    copies, devs = {}, []
    start = 0
    for one, block in zip(used, designs):
        stop = start + block.shape[0]
        copies[one.specid] = block @ coef
        fitted = S.fitted(one)
        with np.errstate(divide="ignore", invalid="ignore"):
            dev = np.abs(copies[one.specid] - targets[one.specid]) / one.pixels.error
        devs.append(dev[fitted & np.isfinite(dev)])
        start = stop
    devs = np.concatenate(devs) if devs else np.array([])
    scale = CO.scales(project, line)
    pm = project.parsed
    patches = []
    for k, par in enumerate(line.params):
        factor = scale[k] if k < len(scale) else 1.0
        value = coef[k] / factor if factor else coef[k]
        text = E.format_value(float(value), 10)
        if par.value_token is None:
            patches.extend(E.set_value(pm, par, text, everywhere=False).patches)
        elif par.value_token.text != text:
            patches.append(T.replace_token(pm.text, par.value_token, text))
    step = project.step(
        T.Change.from_spans(patches, "Use the best-fit continuum"),
        "Use the best-fit continuum of {0}".format(
            ",".join(line.specids or [snip.specid])
        ),
    )
    step = _hide(project, view, step, {line.line} if patches else set())
    return ContinuumCopy(
        line=line,
        snips=used,
        wave=waves,
        run=targets,
        copy=copies,
        largest=float(np.max(devs)) if devs.size else 0.0,
        rms=float(np.sqrt(np.mean(devs**2))) if devs.size else 0.0,
        step=step,
    )


@dataclass
class Departure:
    """
    How far a snip's continuum, as it stands, departs from a run's best-fit
    continuum (Q6.20): the run's continuum on the snip's pixels, and the largest
    and rms departure over its fitted pixels, in units of the data's errors.

    Generated by RJC and Claude.
    """

    wave: np.ndarray = field(repr=False)
    run: np.ndarray = field(repr=False)
    largest: float = 0.0
    rms: float = 0.0


def continuum_departure(project, view, snip):
    """
    The departure of a snip's continuum from the shown run's best-fit continuum
    (the Continuum box, after Use best fit, Q6.20), or None when there is none to
    compare.

    Returns
    -------
    Departure or None

    Generated by RJC and Claude.
    """
    if continuum_reason(project, view, snip):
        return None
    theirs = view.run_snip(snip)
    pix = snip.pixels
    try:
        vector = view.vector()
    except ResultsError:
        return None
    run = CO.evaluate(view.model, theirs, wave=pix.wave, values=vector)
    now = CO.evaluate(project, snip)
    if run is None or now is None:
        return None
    fitted = S.fitted(snip)
    with np.errstate(divide="ignore", invalid="ignore"):
        dev = np.abs(now - run) / pix.error
    dev = dev[fitted & np.isfinite(dev)]
    return Departure(
        pix.wave,
        run,
        float(np.max(dev)) if dev.size else 0.0,
        float(np.sqrt(np.mean(dev**2))) if dev.size else 0.0,
    )


# -- Outliers (S29, D27, Q6.11) -------------------------------------------------------


@dataclass
class Outliers:
    """
    The fitted pixels of one snip whose residual from the best fit is beyond the
    threshold (Review clipped pixels…).

    Attributes
    ----------
    index : int
        The snip's data line index.
    specid : str
    pixels : numpy.ndarray
        Their places among the curve's pixels.
    wave : numpy.ndarray
    sigma : numpy.ndarray
        Their residuals, (data − model)/σ.
    ticked : numpy.ndarray
        Proposed to be left out: lone pixels and pairs, not three or more in a row.

    Generated by RJC and Claude.
    """

    index: int
    specid: str
    pixels: np.ndarray = field(repr=False)
    wave: np.ndarray = field(repr=False)
    sigma: np.ndarray = field(repr=False)
    ticked: np.ndarray = field(repr=False)

    @property
    def count(self):
        return int(self.pixels.size)


def outliers(curves, project, threshold=None, prefs=None):
    """
    The outliers of each snip's best fit (Q6.11): fitted pixels whose residual is
    beyond ``threshold`` σ (the preference, 5σ by default), by data line index.

    Generated by RJC and Claude.
    """
    threshold = _pref(prefs, "fit.outlier_sigma") if threshold is None else threshold
    specids = {s.data.index: s.specid for s in project.snips}
    out = {}
    for index, curve in curves.items():
        if curve is None:
            continue
        with np.errstate(invalid="ignore", divide="ignore"):
            resid = (curve.flux - curve.model) / curve.error
            hit = curve.fitted & (curve.error > 0) & (np.abs(resid) > threshold)
        places = np.flatnonzero(hit)
        if not places.size:
            continue
        ticked = np.ones(places.size, dtype=bool)
        edges = np.flatnonzero(np.diff(places) != 1) + 1
        for run in np.split(np.arange(places.size), edges):
            if run.size >= RUN_LENGTH:
                ticked[run] = False
        out[index] = Outliers(
            index,
            specids.get(index, curve.specid),
            places,
            curve.wave[places],
            resid[places],
            ticked,
        )
    return out


def outliers_step(project, chosen):
    """
    Apply: the step that leaves the chosen pixels out of the fit, as Tweak dataset
    regions leaves pixels out (the snip's fit mask, Stage 4), as one step.

    Parameters
    ----------
    chosen : dict
        Specid to the wavelengths of the pixels to leave out.

    Returns
    -------
    Step

    Generated by RJC and Claude.
    """
    project.require_reading()
    total = 0
    makers = []
    for specid, waves in chosen.items():
        waves = np.asarray(waves, dtype=float)
        if not waves.size:
            continue
        snip = project.snip(specid)
        leave = np.isin(snip.pixels.wave, waves) & S.fitted(snip)
        count = int(np.count_nonzero(leave))
        if not count:
            continue
        total += count

        def make(pr, specid=specid, waves=waves):
            one = pr.snip(specid)
            mask = S.fitted(one) & ~np.isin(one.pixels.wave, waves)
            return S.set_mask_step(pr, one, mask, "Leave out outliers")

        makers.append(make)
    description = "Leave out {0} outlier{1}".format(total, "" if total == 1 else "s")
    return S.compose(project, description, makers)


