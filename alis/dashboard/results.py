def copy_text(groups):
    """
    The rows of the table as tab-separated text ("Copy as table"), every value as
    the gate shows it.

    Generated by RJC and Claude.
    """
    lines = ["\t".join(("Parameter", "Value", "Error", "State", "Flags"))]
    for group in groups:
        lines.append(group.title)
        for row in group.rows:
            state = row.state + (" " + row.detail if row.detail else "")
            lines.append(
                "\t".join((row.name, row.value, row.error, state, "; ".join(row.flags)))
            )
    return "\n".join(lines) + "\n"


def statistics_rows(stats):
    """
    The Fit statistics pane's rows (S19, S31): ``[(name, text)]``, each through the
    gate already (the reason is masked by :meth:`View.statistics`; the others are
    numbers that reveal no value).

    Generated by RJC and Claude.
    """
    out = []

    def number(value, fmt):
        return "—" if value is None else fmt.format(value)

    chi2 = number(stats.chi2, "{0:.4f}")
    if stats.chi2_initial is not None:
        chi2 += " (initial {0:.4f})".format(stats.chi2_initial)
    out.append(("χ²", chi2))
    out.append(("Degrees of freedom", number(stats.dof, "{0:d}")))
    out.append(("χ²ν", number(stats.reduced, "{0:.4f}")))
    out.append(("Iterations", number(stats.iterations, "{0}")))
    if stats.seconds is not None:
        out.append(("Run time", _duration(stats.seconds)))
    if stats.status == "running":
        out.append(("Stopped because", "the fit is still running"))
    elif stats.reason:
        out.append(("Stopped because", stats.reason))
    if stats.convergence is not None:
        out.append(("Convergence", convergence_text(stats.convergence)))
    where = {R.DASHBOARD: "the dashboard", R.COMMAND: "the command line"}.get(
        stats.origin, "imported with the model"
    )
    if stats.host:
        where += " on " + stats.host
    out.append(("Run from", where))
    if stats.command and stats.origin == R.COMMAND:
        out.append(("Command", stats.command))
    if stats.finished:
        out.append(("Finished", when_text(stats.finished)))
    if stats.description:
        out.append(("Description", stats.description))
    return out


def _duration(seconds):
    """``41 s``, ``3.2 min``, ``1.4 h``."""
    if seconds < 60:
        return "{0:.0f} s".format(seconds)
    if seconds < 3600:
        return "{0:.1f} min".format(seconds / 60.0)
    return "{0:.1f} h".format(seconds / 3600.0)


def when_text(stamp, short=False):
    """An ISO time as ``2026-10-03 22:14`` (``short``: ``3 Oct 22:14``), or the text
    as it is."""
    try:
        moment = datetime.datetime.fromisoformat(str(stamp))
    except ValueError:
        return str(stamp)
    if short:
        return "{0} {1}".format(moment.day, moment.strftime("%b %H:%M"))
    return moment.strftime("%Y-%m-%d %H:%M")


def convergence_text(found):
    """
    The result of ALIS's convergence check as ``run.json`` records it (Task 6.8):
    "Converged", or "Not converged for 3 of 41 parameters".

    Generated by RJC and Claude.
    """
    if isinstance(found, dict):
        bad, total = found.get("failed"), found.get("total")
        if found.get("converged"):
            return "Converged"
        if bad is not None and total:
            return "Not converged for {0} of {1} parameters".format(bad, total)
        return "Not converged"
    return "Converged" if found else "Not converged"


