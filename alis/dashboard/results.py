"""The results of a run: its best fit, marks, table, correlations and statistics;
Continue from best fit, Use best fit, and the outliers.

Dashboard Stage 6.3 (S18–S20, S29, D27, D39, D40, D51; Q6.5, Q6.6(b), Q6.8, Q6.11,
Q6.12, Q6.15, Q6.17, Q6.20). No Qt: the Fit tab, the component cards and the
Continuum box show what this module gives, and give its steps to the history.

- **The shown run** (:class:`View`): the latest run, a committed one, or the fit in
  progress. Its model is read as a project of its own (:func:`model_of`): the model
  that was run, on the snips as they are now (a snip's file removed since is taken
  from the run), so that its results are grouped as the run's model was, whatever
  has changed since. Its lines are matched to the current model's
  (:func:`match_lines`) by what each line is, whatever its values.
- **The best fit of each snip** (D60, Q6.5, Q6.15): ``profile.py`` evaluates the
  run's model with its best-fit values (or the values in progress), links applied,
  as ALIS evaluates it, and each snip's continuum with the same values. A snip of
  the project that the run did not have has none.
- **The marks** (S18, D39, Q6.6(b)): χ²ν and the runs test of each snip's best fit,
  computed by ``alis/report.py``'s own functions on the fitted pixels; each is ✓,
  ! beyond 2σ, or ✕ beyond ``out reportsig`` (χ²ν only above, as the report flags
  it; the runs test either way).
- **The table** (S19, D40): each system (the primary first) with its ions and
  components (log N, z with its velocity in the system, b and T), the Lyα forest,
  the continua, the instrument and anything else; each row with its value, error,
  state (free, fixed, tied, linked) and flags: "at limit" (the value on a bound, to
  the precision of the run's values, Q6.12), "unconstrained" (an error larger than
  a preference's threshold), "blinded", and the imported fit's isotopes and
  components that are not tied (D20, D22). A continuum's coefficients are flagged
  neither "at limit" nor "unconstrained"; the continuum is flagged "negative" when
  its best fit is below zero at a pixel of its snip from its first fitted pixel to
  its last (Q6.23, Q6.28).
- **Correlations** (D51) of the free parameters of a group, from the covariance;
  **statistics**, from ``run.json`` and the ``.mod.out``'s header.
- **Continue from best fit** (S20, Q6.8): every free parameter unchanged since the
  run receives its best fit, as one step; those changed since keep their values,
  and the plan lists them. Linked parameters are left to ALIS.
- **Use best fit** (Q6.17, Q6.20): one component's z, b_turb, T and log N of each
  of its ions (matched by its redshift label), even into lines changed since the
  run; one continuum, its line's function, order, range and ``scale=`` kept, fitted
  to the run's best-fit continuum on the snip's pixels, with how far the copy
  departs from it in units of the data's errors.
- **Outliers** (S29, D27, Q6.11): the fitted pixels whose residual from the best fit
  is beyond a threshold; lone pixels and pairs are ticked, three or more in a row are
  not, since they may be absorption the model misses; the ticked ones are left out of
  the fit as one step.
- **Blinding** (D24, D49): a value passes the run's gate (:class:`RunGate`): masked
  when hidden in the run's model or in the current one, under global blind, or when
  ALIS offsets it (``blindrange``). Errors, χ², the marks, the correlations and the
  outliers reveal no value and are shown. A flag that would tell something of a
  hidden value is not made. A step's description names no value; a value copied
  into a hidden line stays hidden, and under global blind (or into a line ALIS
  offsets) every line that receives one is hidden (``Project.mark_hidden``, S20).

Generated by RJC and Claude.
"""

