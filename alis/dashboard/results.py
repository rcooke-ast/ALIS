# -- Matching the run's model to the current one --------------------------------------


def _shapes(pm):
    """
    What each line of a model is, whatever its values: its text with each value of
    a parameter, and a data line's fit range, put as ``#``, its ``blind=`` word
    left out (a line blinded since the run is the same line, and its values stay
    hidden), and its spaces made single.

    Generated by RJC and Claude.
    """
    spans = {}
    for par in pm.params:
        tok = par.value_token
        if tok is not None:
            spans.setdefault(tok.line, []).append((tok.start, tok.end, "#"))
    for item in pm.data:
        kw = item.keywords.get("fitrange")
        if kw is not None and kw.val.text:
            spans.setdefault(kw.val.line, []).append((kw.val.start, kw.val.end, "#"))
    for item in list(pm.lines) + list(pm.data):
        kw = item.keywords.get("blind")
        if kw is not None:
            spans.setdefault(kw.token.line, []).append(
                (kw.token.start, kw.token.end, "")
            )
    out = []
    for line in pm.text:
        text = line.text
        for start, end, put in sorted(set(spans.get(line.num, ())), reverse=True):
            text = text[:start] + put + text[end:]
        out.append(" ".join(text.split()))
    return out


def match_lines(old, new):
    """
    The lines of two readings of a model that are the same line, whatever their
    values: ``{line of old: line of new}``. A line whose function, ion, labels or
    keywords changed is not matched.

    Parameters
    ----------
    old, new : ParsedModel

    Generated by RJC and Claude.
    """
    matcher = difflib.SequenceMatcher(None, _shapes(old), _shapes(new), autojunk=False)
    out = {}
    for tag, i1, i2, j1, _ in matcher.get_opcodes():
        if tag == "equal":
            for k in range(i2 - i1):
                out[i1 + k] = j1 + k
    return out


def _places(pm):
    """Every place of a parameter, by its line, role and slot."""
    return {(p.line, p.role, p.slot): p for p in pm.params}


# -- The run's model, as a project of its own ----------------------------------------

_MODELS = {}


def _digest(*parts):
    digest = hashlib.sha1()
    for part in parts:
        if isinstance(part, str):
            part = part.encode("utf-8")
        elif not isinstance(part, bytes):
            part = json.dumps(part, sort_keys=True, default=str).encode("utf-8")
        digest.update(hashlib.sha1(part).digest())
    return digest.hexdigest()


class _Entry:
    """A run's model and its profile, built once."""

    def __init__(self, model):
        self.model = model
        self._profile = None
        self._error = None

    def profile(self):
        if self._profile is None and self._error is None:
            try:
                self._profile = PR.Profile(self.model)
            except PR.ProfileError as err:
                self._error = str(err)
        if self._profile is None:
            raise ResultsError(self._error)
        return self._profile


def _entry(project, record=None, run=None):
    """
    The cached model of a run (see :func:`model_of`).

    Generated by RJC and Claude.
    """
    if run is not None:
        src = run.bundle
        member = src.model_member
        stored = src.members[member]
        hidden = src.hidden_model_lines()
        files = {
            m: c for m, c in src.members.items() if m.startswith(B.TREE) and m != member
        }
        ui = src.members.get(P.PROJECT_JSON)
        ui = None if ui is None else json.loads(ui.decode("utf-8"))
    else:
        member = record.info.get("model") or project.model_member
        stored = record.bundle.members.get(record.prefix + "input.mod")
        if stored is None:
            raise ResultsError("The run did not keep the model it fitted.")
        hidden = dict(
            record.bundle.hidden["lines"].get(record.prefix + "input.mod", {})
        )
        files = {m: c for m, c in record.inputs().items() if m.startswith(B.TREE)}
        ui = record.ui()
    files.update(project.files)
    files.pop(member, None)
    if ui is None:
        ui = project.ui
    key = _digest(
        str(id(project.registry)),
        member,
        stored,
        hidden,
        ui,
        *[m.encode("utf-8") + hashlib.sha1(files[m]).digest() for m in sorted(files)],
    )
    found = _MODELS.get(key)
    if found is not None:
        return found
    members = dict(files)
    members[member] = stored
    if ui:
        members[P.PROJECT_JSON] = json.dumps(ui, indent=1).encode("utf-8")
    bundle = B.Bundle(
        members=members,
        manifest=dict(project.bundle.manifest, model=member),
        hidden={"lines": {member: hidden} if hidden else {}, "files": {}},
        sources=project.bundle.sources,
    )
    if len(_MODELS) > 8:
        _MODELS.clear()
    found = _Entry(P.Project(bundle, registry=project.registry))
    _MODELS[key] = found
    return found


def model_of(project, record=None, run=None):
    """
    A run's model, read as a project of its own: the model that was run (its hidden
    lines restored), with the snips as they are now, and the run's
    ``ui/project.json`` when it kept one.

    Parameters
    ----------
    project : Project
    record : RunRecord, optional
        A run the project holds.
    run : runs.Run, optional
        The fit in progress.

    Returns
    -------
    Project

    Raises
    ------
    ResultsError

    Generated by RJC and Claude.
    """
    return _entry(project, record=record, run=run).model


_RECORDS = {}


def _record_data(record, registry):
    """
    A run's values, errors, covariance and words, read once for each run (they
    depend on the run alone, not on the model as it is now).

    Generated by RJC and Claude.
    """
    members = record.members()
    key = _digest(
        str(id(registry)),
        record.prefix,
        *[
            m.encode("utf-8") + hashlib.sha1(record.bundle.members[m]).digest()
            for m in members
        ],
    )
    found = _RECORDS.get(key)
    if found is None:
        found = (
            record.values(registry),
            record.errors(registry),
            record.covariance(),
            record.texts(registry),
        )
        if len(_RECORDS) > 8:
            _RECORDS.clear()
        _RECORDS[key] = found
    values, errors, covariance, texts = found
    return (
        None if values is None else dict(values),
        None if errors is None else dict(errors),
        covariance,
        dict(texts),
    )


# -- The gate of a run ----------------------------------------------------------------


class RunGate:
    """
    The blinding gate of a run's values (D24, D49): a value is masked when its
    parameter is hidden in the run's model or in the current one (by its line, or its
    label), under global blind in either, or when ALIS offsets it (``blindrange``).
    Errors are shown (QF.20(b)).

    Parameters
    ----------
    project : Project
        The project as it is now.
    model : Project
        The run's model.
    lines : dict
        :func:`match_lines` from the run's model to the current one.

    Generated by RJC and Claude.
    """

    def __init__(self, project, model, lines):
        self.now = BL.Gate(project)
        self.run = BL.Gate(model)
        self.global_blind = self.now.global_blind or self.run.global_blind
        self._lines = lines
        self._labels = self.now.hidden_labels

    def is_hidden(self, param):
        """Whether a parameter of the run's model is hidden (its values masked)."""
        if self.run.is_hidden(param):
            return True
        num = self._lines.get(param.line)
        if num is not None and num in self.now.hidden_lines:
            return True
        return bool(param.label) and param.label in self._labels

    def masked(self, param):
        """Whether a parameter's best-fit value is masked."""
        return (
            self.global_blind
            or self.is_hidden(param)
            or param.index in self.run.offset_index
        )

    def best_fit(self, param, value, fmt="{0:.8g}"):
        """A best-fit value (or one of the fit in progress), or the mask."""
        if value is None:
            return ""
        return BL.MASK if self.masked(param) else fmt.format(value)

    def error(self, param, value, fmt="{0:.3g}"):
        """An error: shown, even for a hidden parameter (QF.20(b))."""
        return "" if value is None else fmt.format(value)

    def message(self, text):
        """A message, passed through both gates."""
        return self.now.message(self.run.message(text))


# -- The shown run --------------------------------------------------------------------


class View:
    """
    A run as the Fit tab shows it: the latest run, a committed one, or the fit in
    progress (Q6.15).

    Parameters
    ----------
    project : Project
        The project as it is now.
    record : RunRecord, optional
        A run the project holds.
    run : runs.Run, optional
        The fit in progress (its values are those of its latest iteration).

    Attributes
    ----------
    model : Project
        The run's model (:func:`model_of`).
    values : dict or None
        The best-fit values (or those in progress), by the run's ALIS numbers; never
        shown but through :attr:`gate`.
    errors : dict or None
        None for the fit in progress and an interrupted run (Q6.3).
    covariance : numpy.ndarray or None
    texts : dict
        The ``.mod.out``'s words for the values (their precision).
    lines : dict
        The run's model's lines matched to the current model's (:func:`match_lines`).
    gate : RunGate
    in_progress : bool

    Raises
    ------
    ResultsError
        If the run did not keep its model.

    Generated by RJC and Claude.
    """

    def __init__(self, project, record=None, run=None):
        if (record is None) == (run is None):
            raise ResultsError("A view shows one run.")
        self.project = project
        self.record = record
        self.run = run
        self._entry = _entry(project, record=record, run=run)
        self.model = self._entry.model
        registry = project.registry
        self.in_progress = run is not None
        if run is not None:
            self.values = (
                None
                if run.values is None
                else {i: float(v) for i, v in enumerate(run.values)}
            )
            self.errors = self.covariance = None
            self.texts = {}
        else:
            self.values, self.errors, self.covariance, self.texts = _record_data(
                record, registry
            )
        self.lines = match_lines(self.model.parsed, project.parsed)
        self.gate = RunGate(project, self.model, self.lines)
        self._curves = None
        # What the tab calls it, when not the run's own name (a restart, Stage 6.8)
        self.label = None

    @classmethod
    def latest(cls, project):
        """The latest run of a project, or None."""
        record = R.latest(project.bundle)
        return None if record is None else cls(project, record=record)

    @property
    def name(self):
        """How the tab names the run: "run 3", "the latest run", "the fit in
        progress"."""
        if self.label:
            return self.label
        if self.in_progress:
            return "the fit in progress"
        number = self.record.number
        return "the latest run" if number is None else "run {0}".format(number)

    @property
    def interrupted(self):
        return self.record is not None and self.record.status == R.INTERRUPTED

    # -- whether there is a best fit ------------------------------------------------

    def why_not(self):
        """
        Why the run has no best fit to show, or ``""`` when it has one.

        Generated by RJC and Claude.
        """
        if self.model.paused:
            return "The model of {0} does not read.".format(self.name)
        if not self.values:
            if self.in_progress:
                return "The fit has not finished its first iteration yet."
            return "{0} has no best-fit values.".format(self.name.capitalize())
        missing = [
            p
            for p in self.model.parsed.params
            if p.index >= 0 and p.free and p.index not in self.values
        ]
        if missing:
            return "The outputs of {0} do not give every best-fit value.".format(
                self.name
            )
        return ""

    @property
    def has_best_fit(self):
        return not self.why_not()

    def profile(self):
        """
        The profile of the run's model.

        Raises
        ------
        ResultsError

        Generated by RJC and Claude.
        """
        return self._entry.profile()

    def vector(self):
        """
        Every parameter of the run's model, by its ALIS number: the best fit (or the
        values in progress), with the links applied as ALIS applies them.

        Raises
        ------
        ResultsError
            If there is no best fit.

        Generated by RJC and Claude.
        """
        why = self.why_not()
        if why:
            raise ResultsError(why)
        prof = self.profile()
        size = prof.start.size
        changes = {i: v for i, v in self.values.items() if 0 <= i < size}
        try:
            return prof.values(changes)
        except PR.ProfileError as err:
            raise ResultsError(str(err)) from None

    # -- the snips ------------------------------------------------------------------

    def run_snip(self, snip):
        """
        The run's snip for a snip of the project: the one with its specid (the same
        place among those that share one), or None.

        Generated by RJC and Claude.
        """
        same = [s for s in self.project.snips if s.specid == snip.specid]
        theirs = [s for s in self.model.snips if s.specid == snip.specid]
        place = next((k for k, s in enumerate(same) if s is snip), 0)
        if place < len(theirs):
            return theirs[place]
        return None

    def curves(self):
        """
        The best fit of each snip of the project (or the fit in progress), by its data
        line index: a :class:`~alis.dashboard.profile.Curve` with the best-fit
        continuum, or None for a snip the run did not fit.

        Raises
        ------
        ResultsError
            If there is no best fit, or ALIS cannot evaluate it.

        Generated by RJC and Claude.
        """
        if self._curves is not None:
            return self._curves
        vector = self.vector()
        prof = self.profile()
        try:
            found = prof.evaluate(vector)
        except PR.ProfileError as err:
            raise ResultsError(str(err)) from None
        out = {}
        for snip in self.project.snips:
            theirs = self.run_snip(snip)
            curve = None if theirs is None else found.get(theirs.data.index)
            if curve is not None:
                cont = CO.evaluate(self.model, theirs, wave=curve.wave, values=vector)
                curve = dataclasses.replace(
                    curve, index=snip.data.index, continuum=cont
                )
            out[snip.data.index] = curve
        self._curves = out
        return out

    def unfitted(self):
        """The data line indices of the project's snips that the run did not fit."""
        return [i for i, c in self.curves().items() if c is None]

    def marks(self):
        """
        The fit-quality marks of each snip's best fit (S18), by data line index;
        None for a snip the run did not fit, or with no fitted pixel.

        Generated by RJC and Claude.
        """
        nsig = float(self.model.parsed.argflag["out"]["reportsig"])
        return {
            i: (None if c is None else quality(c, nsig))
            for i, c in self.curves().items()
        }

    def negative(self, line):
        """
        Whether a continuum line's best fit is below zero at a pixel of a snip it is
        the continuum of (Q6.23), from the snip's first fitted pixel to its last, gaps
        between its regions included (Q6.28): beyond them the continuum is
        extrapolated and constrains nothing. Zero is allowed, and its coefficients
        may be negative. False when there is no best fit. A hidden continuum is
        flagged too: Inspect draws it, so the flag tells nothing the drawing does
        not.

        Parameters
        ----------
        line : ModelLine
            A continuum line of the run's model.

        Generated by RJC and Claude.
        """
        try:
            vector = self.vector()
        except ResultsError:
            return False
        for snip in self.model.snips:
            if snip.continuum is not line or snip.pixels is None:
                continue
            fitted = np.flatnonzero(S.fitted(snip))
            if not fitted.size:
                continue
            curve = CO.evaluate(self.model, snip, values=vector)
            if curve is None:
                continue
            span = curve[fitted[0] : fitted[-1] + 1]
            with np.errstate(invalid="ignore"):
                if np.any(span < 0.0):
                    return True
        return False

    # -- the table ------------------------------------------------------------------

    def _value(self, par):
        return None if not self.values else self.values.get(par.index)

    def _error(self, par):
        if not self.errors or par.fixed:
            return None
        err = self.errors.get(par.index)
        if err is None or (par.linked and not err):
            return None
        return err

    def _current_lines(self, par):
        pm = self.model.parsed
        places = [p for p in pm.params if p.index == par.index] or [par]
        out = []
        for place in places:
            num = self.lines.get(place.line)
            if num is not None and num not in out:
                out.append(num)
        return out

    def _row(self, par, name, kind, prefs, group, ion="", system=None, extra=()):
        value = self._value(par)
        error = self._error(par)
        fmt = _format(kind, value, error)
        state, detail = _state(self.model.parsed, par)
        hidden = self.gate.masked(par)
        flags = list(extra)
        if self.gate.is_hidden(par) or par.index in self.gate.run.offset_index:
            flags.insert(0, "blinded")
        # A continuum's coefficients are flagged neither way: a polynomial's higher
        # terms are often consistent with zero (Q6.23)
        if value is not None and state not in (FIXED, LINKED) and kind != COEFFICIENT:
            bound = at_limit(par, value, self.texts.get(par.index))
            if bound is not None and not hidden:
                own = own_limit(self.model.parsed, par)
                flags.append(
                    "at limit ({0:g}{1})".format(
                        bound, ", {0}'s own".format(own) if own else ""
                    )
                )
            elif error is not None and unconstrained(
                par, value, error, prefs, hidden=hidden, kind=kind
            ):
                flags.append("unconstrained")
        vel = ""
        if kind == "redshift" and system is not None and value is not None:
            vel = self.gate.best_fit(
                par, P.velocity(value, system.z), "{0:+.2f}"
            ).replace("-", "−")
        return Row(
            name=name,
            param=par,
            kind=kind,
            value=self.gate.best_fit(par, value, fmt),
            error=self.gate.error(par, error, fmt),
            state=state,
            detail=detail,
            flags=flags,
            lines=self._current_lines(par),
            velocity=vel,
            group=group,
            ion=ion,
        )

    def table(self, prefs=None):
        """
        The results table (S19): its groups, each with its rows.

        Each ALIS parameter has one row, where it first appears: the systems (the
        primary first; for each ion, each component's log N, z, b and T), the Lyα
        forest, the continua, the instrument (FWHMs, shifts, zero levels), and any
        other line. Fixed parameters left at their defaults are left out.

        Returns
        -------
        list of Group

        Raises
        ------
        ResultsError
            If the run's model does not read.

        Generated by RJC and Claude.
        """
        model = self.model
        if model.paused:
            raise ResultsError("The model of {0} does not read.".format(self.name))
        pm = model.parsed
        seen = set()
        loose = _untied_flags(model)
        groups = []

        def add(rows, par, *args, **kwargs):
            if par is None or par.index < 0 or par.index in seen:
                return
            if not par.given and not par.free:
                return
            seen.add(par.index)
            rows.append(self._row(par, *args, **kwargs))

        for system in model.systems:
            rows = []
            key = "system:" + system.id
            for ion in system.ions:
                for comp in system.components:
                    if ion not in comp.ions:
                        continue
                    lines = comp.lines_of(ion) or [
                        ln for ln in comp.ratios if ln.ion.split("/")[0] == ion
                    ]
                    if not lines:
                        continue
                    line = lines[0]
                    who = "{0} {1}".format(_ion_name(line.ion), comp.id)
                    for name in VOIGT:
                        par = line.param(name)
                        extra = loose.get((line.line, name), ())
                        add(
                            rows,
                            par,
                            "{0} {1}".format(who, _SHORT[name]),
                            name,
                            prefs,
                            key,
                            ion=ion,
                            system=system,
                            extra=extra,
                        )
            title = "{0}, z = {1}".format(
                _system_name(system), self.gate.run.system_z(system)
            )
            groups.append(
                Group(SYSTEM, title, rows, key, False, len(system.components))
            )
        rows = []
        for line in model.absorbers:
            zpar = line.param("redshift")
            ztext = self.gate.best_fit(zpar, self._value(zpar), "{0:.4f}")
            who = "{0} z={1}".format(FOREST_NAMES.get(line.ion, line.ion), ztext)
            for name in VOIGT:
                add(
                    rows,
                    line.param(name),
                    who + " " + _SHORT[name],
                    name,
                    prefs,
                    FOREST,
                )
        if model.absorbers:
            groups.append(
                Group(
                    FOREST,
                    "Lyα forest ({0} lines)".format(len(model.absorbers)),
                    rows,
                    FOREST,
                    True,
                    len(model.absorbers),
                )
            )
        conts = []
        for snip in model.snips:
            line = snip.continuum
            if line is not None and line not in conts:
                conts.append(line)
        rows = []
        for line in conts:
            who = ",".join(line.specids) or "all"
            # The continuum is flagged once, on its first row (Q6.23)
            flag = [NEGATIVE] if self.negative(line) else []
            for k, par in enumerate(line.params):
                before = len(rows)
                add(
                    rows,
                    par,
                    "{0} c{1}".format(who, k),
                    COEFFICIENT,
                    prefs,
                    CONTINUA,
                    extra=flag,
                )
                if len(rows) > before:
                    flag = []
        if conts:
            functions = sorted({ln.function for ln in conts})
            groups.append(
                Group(
                    CONTINUA,
                    "Continua ({0} {1})".format(len(conts), ", ".join(functions)),
                    rows,
                    CONTINUA,
                    True,
                    len(conts),
                )
            )
        rows = []
        for item in pm.data:
            for par in item.params:
                what = "FWHM" if par.role == "resolution" else "Shift"
                # Named, as a zero level is, by the snips that share it
                sids = [
                    d.specid
                    for d in pm.data
                    if any(p.index == par.index for p in d.params)
                ]
                add(
                    rows,
                    par,
                    "{0} · {1}".format(what, model.specids_name(sids or [item.specid])),
                    par.role,
                    prefs,
                    INSTRUMENT,
                )
        for line in pm.lines:
            if line.section == "zerolevel":
                for par in line.params:
                    who = self.model.zero_level_name(line)
                    add(
                        rows, par, "Zero level · " + who, "zerolevel", prefs, INSTRUMENT
                    )
        # Open: the shifts and zero levels are fitted values, which a closed group
        # would hide unless flagged
        if rows:
            groups.append(Group(INSTRUMENT, "Instrument", rows, INSTRUMENT, False, 0))
        rows = []
        for line in model.others:
            if line in conts or line.section == "zerolevel":
                continue
            who = line.function + (" " + _ion_name(line.ion) if line.ion else "")
            for par in line.params:
                add(rows, par, "{0} {1}".format(who, par.name), par.name, prefs, OTHER)
        if rows:
            groups.append(Group(OTHER, "Other", rows, OTHER, True, 0))
        return groups

    # -- correlations (D51) ---------------------------------------------------------

    def correlation_groups(self, groups=None):
        """
        The groups the correlation menu offers: ``[(key, title)]``: everything, each
        system and each of its ions, and the continua.

        Generated by RJC and Claude.
        """
        groups = self.table() if groups is None else groups
        out = [(ALL, "Everything")]
        for group in groups:
            if group.kind == SYSTEM:
                out.append((group.key, group.title))
                ions = []
                for row in group.rows:
                    if row.ion and row.ion not in ions:
                        ions.append(row.ion)
                for ion in ions:
                    out.append(
                        (
                            group.key + ":" + ion,
                            "{0} ({1})".format(_ion_name(ion), group.title),
                        )
                    )
            elif group.kind == CONTINUA:
                out.append((CONTINUA, "Continua"))
        return out

    def correlations(self, key=ALL, groups=None):
        """
        The correlation matrix of the free parameters of a group (D51), from the
        run's covariance. A correlation reveals no value, so hidden parameters are
        included, by name.

        Parameters
        ----------
        key : str
            From :meth:`correlation_groups`.

        Returns
        -------
        Correlation or None
            None when the run has no covariance.

        Generated by RJC and Claude.
        """
        covar = self.covariance
        if covar is None:
            return None
        groups = self.table() if groups is None else groups
        rows = []
        for group in groups:
            for row in group.rows:
                if row.state not in (FREE, TIED):
                    continue
                if key == ALL or key == row.group or key == row.group + ":" + row.ion:
                    rows.append(row)
        rows = [
            r
            for r in rows
            if r.param.index < covar.shape[0]
            and covar[r.param.index, r.param.index] > 0
        ]
        index = [r.param.index for r in rows]
        sub = covar[np.ix_(index, index)]
        sd = np.sqrt(np.diag(sub))
        matrix = sub / np.outer(sd, sd) if len(index) else sub
        return Correlation([r.name for r in rows], matrix, index)

    # -- statistics -----------------------------------------------------------------

    def statistics(self):
        """
        The fit statistics (S19): χ² (and its starting value), degrees of freedom,
        χ²ν, iterations, the run time, why the fit stopped, the convergence check's
        result, and where and when the run took place (S31).

        Generated by RJC and Claude.
        """
        if self.in_progress:
            run = self.run
            dof = run.dof
            return Statistics(
                name=self.name,
                status="running",
                chi2=run.chi2,
                dof=dof,
                reduced=(run.chi2 / dof) if run.chi2 is not None and dof else None,
                iterations=run.iteration,
                seconds=run.elapsed,
                origin=R.DASHBOARD,
            )
        record = self.record
        info = record.info
        head = _header(record.mod_out() or "")
        chi2 = info.get("chi2_final", head.get("Bestfit Chi-Squared"))
        dof = info.get("dof", head.get("Degrees-of-Freedom"))
        dof = None if dof is None else int(dof)
        seconds = _seconds(info.get("started"), info.get("finished"))
        if seconds is None and "Running Time (hrs)" in head:
            seconds = head["Running Time (hrs)"] * 3600.0
        reason = info.get("reason") or head.get("Convergence Reason", "")
        if record.status == R.INTERRUPTED:
            reason = "Stopped by the user"
        return Statistics(
            name=self.name,
            status=record.status,
            chi2=chi2,
            chi2_initial=info.get("chi2_initial", head.get("Initial Chi-Squared")),
            dof=dof,
            reduced=(chi2 / dof) if chi2 is not None and dof else None,
            iterations=info.get("iterations", head.get("Num. of Iterations")),
            seconds=seconds,
            reason=self.gate.message(str(reason)),
            convergence=info.get("convergence"),
            host=record.host,
            command=info.get("command", ""),
            finished=record.finished or "",
            origin=record.origin,
            description=record.description,
        )


