"""The plotting script of a figure (dashboard Stage 9, Task 9.4; D42, S22; Q9.2). No Qt.

The dashboard writes a figure as a standalone Python 3 script for the user to run
and edit (RJC's response to Q9.2: the dashboard's own emitter; ``alis/plotscript.py``
stays for ``run_alis``):

- it needs numpy and matplotlib alone: the helpers the reference scripts take from
  ``plotting_routines`` (not distributed) are written into it, the signed tick
  numbers of ``plot_pm`` among them;
- every colour, line width, font size and range is a named variable at its top
  (D42), with the details not set in the window (Q9.12): the dashes of the continuum
  and zero lines, the ticks' heights, the residuals' offset and scale, and the
  spacing of the x ticks;
- its data are the snips' files that Export writes beside it (D88), their columns
  found by the names in their headers, so it runs anywhere without ALIS or the
  project; the wavelengths are corrected for each snip's shift (Q9.8 (iii));
- it uses the shipped style, ``alis/data/alis_publication.mplstyle``, written
  beside it, or the style file chosen; LaTeX draws its text where ``latex`` and
  ``dvipng`` are installed, matplotlib's own text otherwise (Q0.10);
- run with no argument it writes ``<project>_<figure>.pdf`` (no creation date, so
  the same figure gives the same file); given a file and ``--dpi``, that file at that
  resolution, which is how the dashboard draws its preview (S22).

The colours are colour-blind safe by default (D42, Q0.7): the model in vermillion,
and the ticks of the first two ions in bluish green and blue, from the Okabe–Ito
palette that the window uses (D43); further ions' ticks are grey. Data, continuum,
zero level and residuals are drawn in neutral inks, so that colour marks only the
model and the ions. The published colours are the reference scripts' red, green
and blue.

Generated by RJC and Claude.
"""

