# The flux range of a panel with no range of its own, by the residuals drawn (the
# reference scripts': metals.py, metals_v2.py, model_fits.py), and where the
# residuals sit
FLUX_RANGES = {
    FG.NO_RESIDUALS: (-0.15, 1.3),
    FG.STRIP: (-0.6, 1.4),
    FG.INSIDE: (-0.35, 1.35),
}
RESIDUAL_OFFSETS = {FG.NO_RESIDUALS: -0.3, FG.STRIP: -0.3, FG.INSIDE: -0.2}
# In normalised flux, at the default range: the residuals' height per σ, a label's
# height in a lower corner (just above the zero level, D110), and the ticks
RESIDUAL_SCALE = 0.05
LOWER_LABEL = 0.07
TICK_FLUX = (1.03, 1.15)


def flux_range(residuals, low=None):
    """
    A panel's flux range: the figure's default for its residuals, or from ``low`` to
    the flux that puts the continuum (1) at the same height in the panel as at the
    default range, so that the continuum, the ticks, the residuals and the label sit
    alike in every panel (RJC's Prompt 5 of Stage 10).

    Returns
    -------
    list
        ``[low, high]``.

    Generated by RJC and Claude.
    """
    base_low, base_high = FLUX_RANGES[residuals]
    if low is None:
        return [base_low, base_high]
    continuum = (1.0 - base_low) / (base_high - base_low)
    return [float(low), round(low + (1.0 - low) / continuum, 6)]


def panel_fractions(residuals):
    """
    Where the residuals, a label in a lower corner and the ticks sit, as fractions
    of a panel's height: at the default flux range, exactly where they sit in flux
    (:data:`RESIDUAL_OFFSETS`, :data:`LOWER_LABEL`, :data:`TICK_FLUX`); a panel
    with its own range keeps them at the same places in it, so that they stay in
    view (Stage 10, point 13).

    Returns
    -------
    dict
        ``residual_offset``, ``residual_scale``, ``lower`` and ``ticks``.

    Generated by RJC and Claude.
    """
    low, high = FLUX_RANGES[residuals]
    span = high - low

    def fraction(flux):
        return round((flux - low) / span, 12)

    return {
        "residual_offset": fraction(RESIDUAL_OFFSETS[residuals]),
        "residual_scale": round(RESIDUAL_SCALE / span, 12),
        "lower": fraction(LOWER_LABEL),
        "ticks": tuple(fraction(v) for v in TICK_FLUX),
    }


