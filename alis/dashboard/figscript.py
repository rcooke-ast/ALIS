# -- Words: plain and LaTeX ----------------------------------------------------------


def tex(text):
    """A plain label in LaTeX: its specials escaped, its Greek letters as maths, its
    ions' stages in small capitals ("Si II" as ``Si\\,\\textsc{ii}``)."""
    out = text
    for char, word in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%")):
        out = out.replace(char, word)
    for char, word in (("#", r"\#"), ("_", r"\_"), ("Å", r"\AA{}")):
        out = out.replace(char, word)
    for char, word in GREEK.items():
        out = out.replace(char, "$" + word + "$")
    words = out.split(" ")
    for num in range(len(words) - 1):
        stage = words[num + 1]
        bare = stage.rstrip("*")
        if (
            bare
            and set(bare) <= set("IVX")
            and words[num].isalpha()
            and words[num][:1].isupper()
            and len(words[num]) <= 2
        ):
            star = "$^{*}$" if stage.endswith("*") else ""
            words[num + 1] = "\\textsc{" + bare.lower() + "}" + star
            words[num] += "\\,"
    return " ".join(words).replace("\\, ", "\\,").replace("$ $", "~")


def label_text(ion, rest):
    """A panel's label: ``"Si II λ1260"``, ``"Lyβ"``, ``"D I Lyβ"``."""
    mass, element, stage = P.split_ion(ion)
    deuterium = element == "H" and mass == 2
    name = L.line_name("D" if deuterium else element, stage, rest)
    if name.startswith(("Ly", "D Ly")):
        lyman = name.rsplit(" ", 1)[0]
        return lyman.replace("D Ly", "D I Ly")
    shown = "D" if deuterium else element
    # Rounded down, as the field names a transition (Stage 10, point 12)
    return "{0} {1} λ{2:d}".format(shown, stage, PS.whole_angstroms(rest))


def _texts(plain):
    """``(plain, LaTeX)``."""
    return (plain, tex(plain)) if plain else ("", "")


def axis_title(axis, z):
    """The title of an x axis: ``(plain, LaTeX)``."""
    if axis == FG.VELOCITY:
        zstr = "{0:.6f}".format(z)
        return (
            "Velocity relative to z_abs = {0} (km/s)".format(zstr),
            r"Velocity Relative to $z_{\rm abs}=\,$" + "$" + zstr + r"$~(km s$^{-1}$)",
        )
    if axis == FG.REST:
        return ("Rest-frame wavelength (Å)", r"Rest-frame wavelength (\AA)")
    return ("Observed wavelength (Å)", r"Observed wavelength (\AA)")


Y_TITLE = ("Normalized Flux", "Normalized Flux")


def _ion_order(ion):
    mass, element, stage = P.split_ion(ion)
    number = L.SYMBOLS.index(element) if element in L.SYMBOLS else len(L.SYMBOLS)
    return (number, L.roman(stage), mass or 0)


def x_spacing(low, high):
    """The major and minor spacing of the velocity ticks, as the reference scripts
    space theirs: 50 and 25 km/s over ±125, 100 and 25 over ±190."""
    width = high - low
    major = 50.0 if width <= 260.0 else (100.0 if width <= 600.0 else 200.0)
    return major, (25.0 if major <= 100.0 else major / 4.0)


# -- What the script draws -----------------------------------------------------------


def _ticked_ions(project, system):
    """Every ion of a system's components, those given as a ratio among them (D I
    as ``2H_I/1H_I``), and of its line IDs."""
    out = []
    for comp in system.components:
        for ion in comp.ions:
            if ion not in out:
                out.append(ion)
    for ion in C.system_ions(project, system):
        if ion not in out:
            out.append(ion)
    return out


def _vector(view):
    try:
        return view.vector()
    except Exception as err:
        raise ScriptError(BL.Gate(view.project).message(str(err))) from None


def describe(project, view, fid, name):
    """
    What a figure's script draws: its variables and its panels, as plain data.

    Parameters
    ----------
    project : Project
    view : results.View
        The run the figure draws.
    fid : str
    name : str
        The project's name, as Export names its files.

    Returns
    -------
    tuple
        ``(data, files, notes)``: the script's data (a dict), the snips' files it
        reads (data line index to file name), and what it leaves out, and why.

    Raises
    ------
    ScriptError

    Generated by RJC and Claude.
    """
    why = FG.unavailable(project, view)
    if why:
        raise ScriptError(why)
    fig = FG.figure(project, fid)
    gate = BL.Gate(project)
    vector = _vector(view)
    zero = fig["zero"] or X.default_component(project, view, gate)
    z_zero = X._reference_z(project, view, vector, zero, gate) if zero else None
    if z_zero is None:
        raise ScriptError(
            "The figure's velocities need a component to be measured from, and"
            " none can be: add a component, or choose one."
        )
    zs = {}
    for comp in project.components:
        found = X._reference_z(project, view, vector, comp.id, gate)
        if found is not None:
            zs[comp.id] = found
    names = X.file_names(project, name, gate)
    found = FG.transitions(project)
    atom = L.atomic(project.registry)
    zero_system = next((c.system.id for c in project.components if c.id == zero), "")
    colours = COLOURS[fig["colours"]]
    residuals = fig["residuals"]
    panels, files, notes, ions = [], {}, [], []
    for row, start, cell in FG.places(fig):
        if not cell["show"]:
            continue
        entry = FG.entry_of(project, cell["show"], found)
        if entry is None:
            notes.append(
                "{0}: its snip is no longer in the project.".format(
                    FG.panel_name(fig, row, start)
                )
            )
            continue
        snip = project.snip(entry.specid)
        system = project.system(entry.system)
        if system.id == zero_system:
            zref, of = z_zero, zero
        else:
            # Another system (an interloper): from its own strongest component
            of = FP.strongest(project, system, view)
            zref = zs.get(of, system.z)
        axis = cell["axis"]
        xrange = FG.x_range(fig, cell, entry.rest, zref)
        centre = entry.rest * (1.0 + zref)
        if axis == FG.VELOCITY:
            window = [centre * (1.0 + v / C_KMS) for v in xrange]
        elif axis == FG.OBSERVED:
            window = list(xrange)
        else:
            window = [w * (1.0 + zref) for w in xrange]
        # Every component of every ion of the system with a transition in range, as
        # the panel's options choose them, on any x axis (RJC's Prompt 4: a
        # wavelength panel ticks the components too, and numbers them)
        ticks = []
        chosen = cell["ions"] or _ticked_ions(project, system)
        comps = [
            c
            for c in system.components
            if c.main is not None
            and c.id in zs
            and (cell["components"] is None or c.id in cell["components"])
        ]
        for ion in chosen:
            marks = []
            for line in atom.ion_lines(ion):
                for comp in comps:
                    if ion not in comp.ions:
                        continue
                    obs = line.rest * (1.0 + zs[comp.id])
                    if window[0] <= obs <= window[1]:
                        marks.append((round(line.rest, 6), comp.id))
            if marks:
                ticks.append([P.ion_name(ion), marks])
                if ion not in ions:
                    ions.append(ion)
        xnum, side = FG.numbers(fig, row, start)
        label = cell["label"] or label_text(entry.ion, entry.rest)
        files[snip.data.index] = names[snip.data.index]
        panels.append(
            {
                "name": entry.name,
                "row": row,
                "column": start,
                "span": cell["span"],
                "file": names[snip.data.index],
                "rest": round(entry.rest, 6),
                "z": zref,
                "of": of,
                "axis": axis,
                "xrange": [round(v, 6) for v in xrange],
                "yrange": flux_range(residuals, cell["ymin"]),
                "yticks": list(cell["yticks"] or [0.0, 0.5, 1.0]),
                "label": _texts(label),
                "corner": cell["corner"],
                "title": _texts(cell["title"]),
                "xtitle": axis_title(axis, zref) if cell["xtitle"] else ("", ""),
                "ytitle": Y_TITLE if cell["ytitle"] else ("", ""),
                "xnumbers": xnum,
                "yside": side,
                "ticks": ticks,
            }
        )
    if not panels:
        raise ScriptError("The figure shows no panel yet: drag a transition onto it.")
    # The ions' colours, in a fixed order across the figure
    palette = colours["TICKS"]
    tick_colours = {}
    for num, ion in enumerate(sorted(ions, key=_ion_order)):
        tick_colours[P.ion_name(ion)] = (
            palette[num] if num < len(palette) else colours["OTHER_TICK_COLOUR"]
        )
    axes = {p["axis"] for p in panels}
    shared_x = ("", "")
    if fig["titles"][0] and len(axes) == 1:
        shared_x = axis_title(axes.pop(), z_zero)
    shared_y = Y_TITLE if fig["titles"][1] else ("", "")
    low, high = fig["vrange"]
    major, minor = x_spacing(low, high)
    margins = fig["margins"] or auto_margins(panels, shared_x, shared_y, fig["rows"])
    data = {
        "colours": {k: v for k, v in colours.items() if k != "TICKS"},
        "tick_colours": tick_colours,
        "size": tuple(fig["size"]),
        "spacing": tuple(
            fig["spacing"] or auto_spacing(panels, fig["rows"], fig["size"], margins)
        ),
        "grid": (fig["rows"], fig["columns"]),
        "residuals": residuals,
        **panel_fractions(residuals),
        "signed": fig["signed"],
        "numbered": fig["numbered"],
        "shared_x": shared_x,
        "shared_y": shared_y,
        "margins": tuple(margins),
        "x_major": major,
        "x_minor": minor,
        "z_zero": z_zero,
        "zero": zero,
        "components": {cid: zs[cid] for cid in sorted(zs)},
        "panels": panels,
    }
    return data, files, notes


def auto_margins(panels, shared_x, shared_y, rows):
    """
    The margins a figure needs, in inches (left, right, bottom, top): room for the
    numbers, the shared titles, the panels' own titles at the figure's edges, and the
    titles above the first row (RJC's Prompt 4: an x title was cut off).

    Generated by RJC and Claude.
    """
    title = 0.3
    left = 0.45 + (title if shared_y[0] else 0.0)
    right = 0.1
    bottom = 0.4 + (title if shared_x[0] else 0.0)
    top = 0.1
    if any(p["yside"] in (FG.RIGHT, FG.BOTH) for p in panels):
        right += 0.4
    if any(
        p["ytitle"][0] and p["yside"] != FG.RIGHT and p["column"] == 0 for p in panels
    ):
        left += title
    if any(p["ytitle"][0] and p["yside"] == FG.RIGHT for p in panels):
        right += title
    if any(p["xtitle"][0] and p["row"] == rows - 1 for p in panels):
        bottom += title
    if any(p["title"][0] and p["row"] == 0 for p in panels):
        top += 0.25
    return [round(v, 2) for v in (left, right, bottom, top)]


# The room a panel's own x numbers and x title take below it, in inches
NUMBERS_ROOM = 0.25
TITLE_ROOM = 0.3


def auto_spacing(panels, rows, size, margins):
    """
    The spacing a figure needs, as matplotlib's (between columns, between rows):
    the scripts' default (:data:`FG.SPACING`), unless a panel with a panel below
    it has its own x numbers or x title, whose room the rows then get, so that they
    do not meet the panel below (Stage 10, refining D111).

    Generated by RJC and Claude.
    """
    across, down = FG.SPACING
    room = 0.0
    for panel in panels:
        # Only a panel directly below can meet its numbers and title
        low, high = panel["column"], panel["column"] + panel["span"]
        below = any(
            other["row"] == panel["row"] + 1
            and other["column"] < high
            and low < other["column"] + other["span"]
            for other in panels
        )
        if below:
            need = (NUMBERS_ROOM if panel["xnumbers"] else 0.0) + (
                TITLE_ROOM if panel["xtitle"][0] else 0.0
            )
            room = max(room, need)
    if rows < 2 or room == 0.0:
        return [across, down]
    # A gap of g inches between rows of panels a high: down = g / a, where
    # rows × a + (rows − 1) × g fills the height inside the margins
    height = size[1] - margins[2] - margins[3]
    gap = room + 0.05
    tall = (height - (rows - 1) * gap) / rows
    if tall <= 0.0:
        return [across, down]
    # No more than Layout's limit
    return [across, round(min(2.0, max(down, gap / tall)), 3)]


def spacing_of(project, fid):
    """
    A figure's spacing: its own, or that it would be given (for the Layout pane).

    Generated by RJC and Claude.
    """
    fig = FG.figure(project, fid)
    if fig["spacing"]:
        return list(fig["spacing"])
    panels = _layout_panels(fig)
    return auto_spacing(panels, fig["rows"], fig["size"], margins_of(project, fid))


def _layout_panels(fig):
    """The panels a figure shows, with what their room depends on (the Layout
    pane's margins and spacing, as the script works them out)."""
    panels = []
    for row, start, cell in FG.places(fig):
        if not cell["show"]:
            continue
        xnum, side = FG.numbers(fig, row, start)
        panels.append(
            {
                "row": row,
                "column": start,
                "span": cell["span"],
                "xtitle": ("x",) if cell["xtitle"] else ("",),
                "ytitle": ("y",) if cell["ytitle"] else ("",),
                "title": (cell["title"],),
                "yside": side,
                "xnumbers": xnum,
            }
        )
    return panels


def margins_of(project, fid):
    """
    A figure's margins: its own, or those it would be given (the panels it shows, as
    the script draws them; for the Layout pane).

    Generated by RJC and Claude.
    """
    fig = FG.figure(project, fid)
    if fig["margins"]:
        return list(fig["margins"])
    panels = _layout_panels(fig)
    axes = {c["axis"] for _, _, c in FG.places(fig) if c["show"]}
    shared_x = ("x",) if fig["titles"][0] and len(axes) == 1 else ("",)
    shared_y = ("y",) if fig["titles"][1] else ("",)
    return auto_margins(panels, shared_x, shared_y, fig["rows"])


def _literal(value):
    return pprint.pformat(value, width=84, sort_dicts=False)


def script_name(name, figure_name):
    """``J1358p6522_Figure_1``: the stem of a figure's script and PDF (Q9.11)."""
    return "{0}_{1}".format(X._safe(name), X._safe(figure_name))


