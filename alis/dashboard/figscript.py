def files(project, view, fid, name, style=None):
    """
    Everything a figure's script needs, as ``{file name: bytes}``: the script, the
    snips' files it reads (Export's, with the columns it reads), and the style.

    Parameters
    ----------
    style : str, optional
        A style file the user chose; by default the shipped one (D42).

    Returns
    -------
    tuple
        ``(files, notes)``.

    Raises
    ------
    ScriptError

    Generated by RJC and Claude.
    """
    fig = FG.figure(project, fid)
    style = style or fig["style"] or STYLE
    style_name = os.path.basename(style)
    text, reads, notes = script(project, view, fid, name, style_name)
    out = {script_name(name, fig["name"]) + ".py": text.encode("utf-8")}
    try:
        tables = X.tables(project, name, list(KEYS), view)
    except X.ExportError as err:
        raise ScriptError(str(err)) from None
    for table in tables:
        if table.index in reads:
            out[table.name] = table.text().encode("utf-8")
    try:
        with open(style, "rb") as handle:
            out[style_name] = handle.read()
    except OSError as err:
        raise ScriptError(
            "The style file {0} cannot be read: {1}".format(style, err.strerror)
        ) from None
    return out, notes


def plan(project, view, fids, name, folder, snips=False):
    """
    What exporting figures writes (Q9.6, Q9.11): for each, its script
    (``<project>_<figure>.py``), the snips' files it draws (unless the snips are
    written with the export already, with the columns it reads), and the style,
    once; as ``{path: bytes}``.

    Returns
    -------
    tuple
        ``(planned, scripts, notes)``: the files, the scripts' paths (each draws its
        PDF when run, :func:`run`), and what was left out.

    Raises
    ------
    ScriptError
        For a figure that cannot be written (no best fit, anything hidden, no panel).

    Generated by RJC and Claude.
    """
    planned, scripts, notes = {}, [], []
    snip_names = set(X.file_names(project, name).values()) if snips else set()
    for fid in fids:
        fig = FG.figure(project, fid)
        try:
            found, more = files(project, view, fid, name)
        except ScriptError as err:
            raise ScriptError("{0}: {1}".format(fig["name"], err)) from None
        for base, content in found.items():
            if base in snip_names:
                continue
            path = os.path.join(folder, base)
            planned[path] = content
            if base.endswith(".py"):
                scripts.append(path)
        notes += ["{0}: {1}".format(fig["name"], n) for n in more]
    return planned, scripts, notes


def pdf_of(script):
    """The PDF a script draws when run with no argument."""
    return os.path.splitext(script)[0] + ".pdf"


def write(folder, written):
    """Write ``{file name: bytes}`` into a folder; return the paths."""
    os.makedirs(folder, exist_ok=True)
    paths = []
    for base, content in written.items():
        path = os.path.join(folder, base)
        with open(path, "wb") as handle:
            handle.write(content)
        paths.append(path)
    return paths


def last_line(text):
    """The last line of a script's error output: its message, never the traceback
    (D86)."""
    found = [ln.strip() for ln in (text or "").splitlines() if ln.strip()]
    return found[-1] if found else "The script stopped without a message."


def command(path, out=None, dpi=None):
    """The command that runs a script, into ``out`` at ``dpi``."""
    cmd = [sys.executable, path]
    if out is not None:
        cmd.append(out)
    if dpi is not None:
        cmd += ["--dpi", "{0:g}".format(dpi)]
    return cmd


def run(path, out=None, dpi=None, env=None, timeout=TIMEOUT):
    """
    Run a figure's script in its folder, with the Agg backend (S22).

    Raises
    ------
    ScriptError
        With the script's last line, when it fails or takes too long.

    Generated by RJC and Claude.
    """
    environ = dict(os.environ if env is None else env)
    environ["MPLBACKEND"] = "Agg"
    try:
        done = subprocess.run(
            command(path, out, dpi),
            cwd=os.path.dirname(os.path.abspath(path)),
            env=environ,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        raise ScriptError(
            "The script took longer than {0:d} s to draw the figure.".format(timeout)
        ) from None
    if done.returncode != 0:
        raise ScriptError(last_line(done.stderr))
    return done


def preview_dpi(width_px, fig):
    """The resolution that draws a figure ``width_px`` pixels across."""
    return max(10.0, float(width_px) / float(fig["size"][0]))


