"""The Figure tab's presets (dashboard Stage 9, Task 9.3; D28, QF.27). No Qt.

Each preset fills a figure from the project as the matching reference scripts of
``context/plotting_examples/`` do, and sets their labels and numbering:

- **metals:** three columns, as many rows as needed, the transitions of each ion
  adjacent, ordered by element, stage and wavelength, the reference dataset's snip of
  each; ±125 km/s (``metals*.py``);
- **DH:** two columns of the Lyman series. With one dataset the series runs down the
  left column and on down the right (``DH_Lya-Ly14.py``); with two, one dataset per
  column and one member per row, each column titled with its dataset
  (``DH_Lya-Ly7*.py``); with more, the first two (``plotscript.py``'s rule). The
  panels tick H I and D I, each in its own colour; ±190 km/s;
- **blends:** one column of a chosen system's lines (an interloper), each titled with
  the line of the primary system it blends, and a residual strip; the velocities from
  the interloper's strongest component (``blends_*.py``);
- **helium:** two columns of He I lines, with the residuals inside each panel, the
  velocities from the strongest line (``model_fits*.py``).

``DH_Lyseries.py`` has no preset: with a span and a rest-wavelength panel the user
builds its layout by hand, and can save it as a preset of their own (S22).

Generated by RJC and Claude.
"""

import copy
import math

from alis.dashboard import figure as FG
from alis.dashboard import lines as L
from alis.dashboard import project as P
from alis.dashboard import results as RS

METALS, DH, BLENDS, HELIUM = "metals", "DH", "blends", "helium"
PRESETS = (METALS, DH, BLENDS, HELIUM)
DESCRIPTIONS = {
    METALS: "The metal lines of one system, three columns",
    DH: "The Lyman series of H I and D I, two columns",
    BLENDS: "An interloper's lines, one column, each titled with the line it blends",
    HELIUM: "The He I lines, two columns, residuals in the panels",
}
# Inches of figure height per row, from the reference scripts (4.5 in for metals'
# three rows, 9 in for DH's seven, 9 in for the blends' seven, 5 in for helium's two)
ROW_HEIGHT = {METALS: 1.5, DH: 9.0 / 7.0, BLENDS: 9.0 / 7.0, HELIUM: 2.5}
WIDTH = {METALS: 7.0, DH: 7.0, BLENDS: 3.6, HELIUM: 7.0}
VRANGE = {METALS: [-125.0, 125.0], DH: [-190.0, 190.0]}


class PresetError(FG.FigureError):
    """A preset that the project cannot fill."""


def _order(entry):
    """Element (by atomic number), stage, wavelength."""
    _, element, stage = P.split_ion(entry.ion)
    number = L.SYMBOLS.index(element) if element in L.SYMBOLS else len(L.SYMBOLS)
    return (number, L.roman(stage), entry.rest)


def _rows_in_order(project):
    """The datasets' names, the reference first."""
    return [r.name for r in sorted(project.rows, key=lambda r: not r.reference)]


def _one_per_transition(found, project):
    """One entry per (ion, transition): the first dataset's that has it."""
    order = _rows_in_order(project)
    best = {}
    for entry in found:
        key = (entry.system, entry.ion, round(entry.rest, 2))
        rank = order.index(entry.dataset) if entry.dataset in order else len(order)
        if key not in best or rank < best[key][0]:
            best[key] = (rank, entry)
    return [e for _, e in best.values()]


def _cell(entry, **options):
    cell = FG.blank_cell()
    cell["show"] = entry.key
    cell.update(options)
    return cell


def _grid(cells, columns, by_column=False):
    """Cells laid out ``columns`` across (down each column first if ``by_column``),
    the rows filled with empty cells."""
    rows = max(1, math.ceil(len(cells) / columns))
    grid = [[FG.blank_cell() for _ in range(columns)] for _ in range(rows)]
    for num, cell in enumerate(cells):
        row, col = (num % rows, num // rows) if by_column else divmod(num, columns)
        grid[row][col] = cell
    return grid


def _layout(name, grid, **options):
    layout = copy.deepcopy(FG.DEFAULTS)
    rows, columns = len(grid), sum(c["span"] for c in grid[0])
    layout.update(
        preset=name,
        columns=columns,
        rows=rows,
        size=[WIDTH[name], round(ROW_HEIGHT[name] * rows, 2)],
        vrange=list(VRANGE.get(name, FG.DEFAULTS["vrange"])),
        cells=grid,
    )
    layout.update(options)
    return layout


def _primary(project):
    for system in project.systems:
        if system.primary:
            return system
    return project.systems[0] if project.systems else None


def _system(project, ident):
    for system in project.systems:
        if system.id == ident:
            return system
    raise PresetError("There is no system {0}.".format(ident))


def strongest(project, system, view=None):
    """
    A system's component with the highest column density (its main line's log N:
    the run's best fit, else its starting value), or ``""``.

    Generated by RJC and Claude.
    """
    vector = None
    if view is not None and not view.in_progress:
        try:
            vector = view.vector()
        except RS.ResultsError:
            vector = None
    best = None
    for comp in system.components:
        if comp.main is None:
            continue
        par = comp.main.param("ColDens")
        if par is None:
            continue
        value = par.start
        if vector is not None and 0 <= par.index < len(vector):
            value = float(vector[par.index])
        if str(comp.main.keyword("logN", "True")).lower() == "false":
            value = math.log10(max(value, 1.0e-300))
        if best is None or value > best[0]:
            best = (value, comp.id)
    return "" if best is None else best[1]


def metals(project, found, system=None):
    """The metals preset's layout (``metals*.py``)."""
    system = system or _primary(project)
    if system is None:
        raise PresetError("The metals preset needs a system with metal lines.")
    lines = [
        e
        for e in found
        if e.system == system.id and P.split_ion(e.ion)[1] not in ("H", "D", "He")
    ]
    lines = sorted(_one_per_transition(lines, project), key=_order)
    if not lines:
        raise PresetError("{0} has no metal line in a snip.".format(system.name))
    return _layout(METALS, _grid([_cell(e) for e in lines], 3))


def dh_members(project, system=None):
    """
    The Lyman members of H I that have a snip, in the system (the primary by
    default), Lyα first: what the DH preset may start from (Stage 10).

    Returns
    -------
    list of tuple
        ``(rest, name)``: ``(1215.6701, "Lyα")``.

    Generated by RJC and Claude.
    """
    system = system or _primary(project)
    if system is None:
        return []
    rests = sorted(
        {
            round(e.rest, 4)
            for e in FG.transitions(project)
            if e.system == system.id and e.ion == "1H_I"
        },
        reverse=True,
    )
    return [(rest, L.line_name("H", "I", rest).split()[0]) for rest in rests]


def dh(project, found, system=None, start=None):
    """
    The DH preset's layout (``DH_*.py``): the Lyman series in two columns, from Lyα,
    or from the member at ``start`` Å up the series (``DH_Ly8-Ly14*.py``: Stage 10).
    """
    system = system or _primary(project)
    series = [
        e
        for e in found
        if system is not None and e.system == system.id and e.ion == "1H_I"
    ]
    if not series:
        raise PresetError("The DH preset needs the Lyman series of H I in the snips.")
    if start is not None:
        series = [e for e in series if e.rest <= start + 0.01]
        if not series:
            raise PresetError("No Lyman member from that one up has a snip.")
    order = _rows_in_order(project)
    datasets = [d for d in order if any(e.dataset == d for e in series)]
    if len(datasets) == 1:
        members = sorted(series, key=lambda e: -e.rest)
        return _layout(
            DH, _grid([_cell(e) for e in members], 2, by_column=True), dh_from=start
        )
    # One dataset per column, one member per row, each column titled
    left, right = datasets[:2]
    rests = sorted({round(e.rest, 2) for e in series}, reverse=True)
    grid = []
    for rest in rests:
        row = []
        for dataset in (left, right):
            entry = next(
                (
                    e
                    for e in series
                    if e.dataset == dataset and abs(e.rest - rest) < 0.01
                ),
                None,
            )
            row.append(FG.blank_cell() if entry is None else _cell(entry))
        grid.append(row)
    for col, dataset in enumerate((left, right)):
        grid[0][col]["title"] = "{0} data".format(dataset)
    return _layout(DH, grid, dh_from=start)


def blends(project, found, system=None, view=None):
    """
    The blends preset's layout (``blends_*.py``): one column of an interloper's lines
    (the first system that is not the primary, unless one is chosen), each titled with
    the primary system's line in the same snip.

    Generated by RJC and Claude.
    """
    primary = _primary(project)
    if system is None:
        system = next((s for s in project.systems if not s.primary), None)
    if system is None or (primary is not None and system.id == primary.id):
        raise PresetError("The blends preset needs an interloper: a second system.")
    lines = sorted(
        _one_per_transition([e for e in found if e.system == system.id], project),
        key=lambda e: -e.rest,
    )
    if not lines:
        raise PresetError("{0} has no line in a snip.".format(system.name))
    cut = L.snip_transitions(project)
    cells = []
    for entry in lines:
        title = ""
        own = cut.get(entry.specid)
        if own is not None and primary is not None and own.system == primary.id:
            title = "{0} blend".format(FG.line_text(own.ion, own.rest))
        else:
            near = [
                e
                for e in found
                if primary is not None
                and e.specid == entry.specid
                and e.system == primary.id
            ]
            if near:
                title = "{0} blend".format(near[0].line)
        cells.append(_cell(entry, title=title))
    return _layout(
        BLENDS,
        _grid(cells, 1),
        zero=strongest(project, system, view),
        residuals=FG.STRIP,
    )


def helium(project, found, system=None, view=None):
    """The helium preset's layout (``model_fits*.py``): two columns of He I lines,
    residuals inside each panel."""
    lines = [
        e
        for e in found
        if P.split_ion(e.ion)[1] == "He" and (system is None or e.system == system.id)
    ]
    lines = sorted(_one_per_transition(lines, project), key=lambda e: -e.rest)
    if not lines:
        raise PresetError("The helium preset needs He I lines in the snips.")
    return _layout(HELIUM, _grid([_cell(e) for e in lines], 2), residuals=FG.INSIDE)


BUILDERS = {METALS: metals, DH: dh, BLENDS: blends, HELIUM: helium}


def layout(project, name, system=None, view=None, home=None, start=None):
    """
    A preset's layout for the project: one of :data:`PRESETS`, or a preset the user
    has saved in ``home`` (S22).

    Parameters
    ----------
    system : str, optional
        The system the preset is drawn for (blends: the interloper).
    view : results.View, optional
        The run the figure draws, for the strongest component.
    start : float, optional
        The DH preset's first member, by its rest wavelength (Lyα by default).

    Raises
    ------
    PresetError

    Generated by RJC and Claude.
    """
    if name not in BUILDERS:
        if home is not None and name in FG.saved_presets(home):
            return FG.load_preset(project, name, home)
        raise PresetError("There is no preset {0}.".format(name))
    found = FG.transitions(project)
    chosen = None if system is None else _system(project, system)
    if name in (BLENDS, HELIUM):
        return BUILDERS[name](project, found, chosen, view)
    if name == DH:
        return dh(project, found, chosen, start)
    return BUILDERS[name](project, found, chosen)


def guess(project):
    """
    The preset a project's first figure starts from: DH when the primary system has
    H I and D I, helium when it has He I, else metals.

    Generated by RJC and Claude.
    """
    primary = _primary(project)
    ions = [] if primary is None else primary.ions
    elements = {P.split_ion(i)[1] for i in ions}
    if "1H_I" in ions and any(P.split_ion(i)[:2] == (2, "H") for i in ions):
        return DH
    if "He" in elements:
        return HELIUM
    return METALS


def apply(project, fid, name, system=None, view=None, home=None, start=None):
    """
    The step that fills a figure from a preset (D28): its grid, cells and options;
    its name stays. ``start`` is the DH preset's first member (Stage 10).

    Generated by RJC and Claude.
    """
    found = layout(project, name, system, view, home, start)
    return FG.refill(project, fid, found, "Apply the {0} preset".format(name))


def first_figure(project, view=None, home=None):
    """
    The step that creates a project's first figure, filled from the preset that
    suits it (:func:`guess`), or empty when that preset finds nothing.

    Returns
    -------
    tuple
        ``(Step, str)``.

    Generated by RJC and Claude.
    """
    try:
        found = layout(project, guess(project), view=view, home=home)
    except PresetError:
        found = None
    return FG.new_figure(project, layout=found)


