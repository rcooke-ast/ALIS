"""The parsed model: settings, data lines, model lines, commands, links and labels.

Dashboard Stage 2.3. A :class:`ParsedModel` is rebuilt from the model text after
every edit, so it can never disagree with the text (D7). It holds:

- the settings, and the data lines (file, ``specid``, fitrange, resolution, shift and
  their other keywords);
- the model lines of each section (emission, absorption, zerolevel), with their
  function, ion, parameters, labels and keywords;
- the ``fix`` and ``lim`` commands, and the links;
- a table of labels: where each label is used, and whether it is free, fixed, tied or
  linked.

Every item knows its line, and every parameter the positions of its value and label,
so that a panel item can find its ``.mod`` lines (S16) and a problem can be placed on
its line (F5).

What the parameters *mean* is decided by ALIS itself. The model block is read by
``alis.load.load_model``, ``load_links`` and ``load_parinfo``, run quietly on fresh
function instances, and their result is matched to the words of the text. The parsed
model therefore agrees with ALIS on the number of parameters, which are tied, which
are free and which line each comes from, by construction rather than by imitation;
``tests/test_dashboard_model.py`` checks the matching on every model.

Generated by RJC and Claude.
"""

