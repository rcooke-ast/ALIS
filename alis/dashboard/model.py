# -- ALIS, run quietly -------------------------------------------------------------


class AlisStop(Exception):
    """ALIS stopped with an error message (``msgs.error``)."""

    def __init__(self, message):
        super().__init__(message)
        self.message = message


class _Quiet(logging.Filter):
    """
    Collect the messages the current thread sends to the ``alis`` logger.

    The messages are kept rather than printed, so that reading a model at every pause
    does not fill the terminal. Messages from other threads pass unchanged.

    Generated by RJC and Claude.
    """

    def __init__(self):
        super().__init__()
        self.thread = threading.get_ident()
        self.records = []

    def filter(self, record):
        if record.thread != self.thread:
            return True
        self.records.append(record)
        return False


@contextmanager
def alis_quietly():
    """
    Run ALIS code with its messages collected instead of printed (Q2.5).

    Yields a list that receives each message as ``(levelno, text)``. When ALIS stops
    with ``msgs.error``, the exit is turned into :class:`AlisStop`, which carries
    the error's message.

    Generated by RJC and Claude.
    """
    quiet = _Quiet()
    msgs.addFilter(quiet)
    collected = []
    try:
        yield collected
    except SystemExit:
        errors = [
            r.getMessage() for r in quiet.records if r.levelno >= logging.CRITICAL
        ]
        raise AlisStop(errors[-1] if errors else "ALIS stopped.") from None
    finally:
        msgs.removeFilter(quiet)
        collected.extend((r.levelno, r.getMessage()) for r in quiet.records)


def plain(message):
    """
    An ALIS message on one line: its continuation indents become single spaces.

    Generated by RJC and Claude.
    """
    return " ".join(message.split())


# -- ALIS's functions and atomic data ----------------------------------------------


class Registry:
    """
    ALIS's model functions and atomic data, shared by every parse of one project.

    Parameters
    ----------
    atomic : alis.config.AtomicData
        The atomic data, as ``alis.load.load_atomic`` returns them.

    Attributes
    ----------
    atomic : alis.config.AtomicData
    names : list of str
        The model functions ALIS knows.
    ions : set of str
        The ions of the atomic data, such as ``1H_I``.

    Generated by RJC and Claude.
    """

    def __init__(self, atomic):
        self.atomic = atomic
        self._probe = self.instances()[2]
        self.names = list(self._probe)
        self.ions = set(np.asarray(atomic["Ion"]).astype(str))

    @classmethod
    def load(cls, name=load.DEFAULT_ATOMIC, content=None):
        """
        Read an atomic table and make a registry from it.

        Parameters
        ----------
        name : str
            The table's name, as ``run atomic`` gives it, or its path.
        content : bytes, optional
            The table's bytes, as a project bundle holds them (Stage 1.5).

        Returns
        -------
        Registry

        Generated by RJC and Claude.
        """
        argflag = ArgFlag()
        argflag["out"]["verbose"] = -1
        argflag["run"]["atomic"] = name
        reader = SimpleNamespace(_argflag=argflag)
        table = None if content is None else (name, content)
        with alis_quietly():
            atomic = load.load_atomic(reader, table=table)
        return cls(atomic)

    def instances(self):
        """
        A fresh set of ALIS's function instances, as ``[names, classes, instances]``.

        ``fix`` and ``lim`` commands change the instances they are applied to, so
        every reading of a model needs fresh ones.

        Generated by RJC and Claude.
        """
        with alis_quietly():
            inst = base.call(getinst=True, verbose=-1, atomic=self.atomic)
        return [list(inst), {k: type(v) for k, v in inst.items()}, inst]

    def function(self, name):
        """
        An instance of model function ``name``, for its description only.

        Its parameter names are ``_parid``, their number ``_pnumr`` and its keywords
        the keys of ``_keywd``.

        Generated by RJC and Claude.
        """
        return self._probe[name]

    def transitions(self, ion):
        """
        The transitions of an ion, as arrays ``(wavelength, fvalue)``.

        Generated by RJC and Claude.
        """
        sel = np.asarray(self.atomic["Ion"]).astype(str) == ion
        return (
            np.asarray(self.atomic["Wavelength"])[sel].astype(float),
            np.asarray(self.atomic["fvalue"])[sel].astype(float),
        )

    def mass(self, ion):
        """The atomic mass of an ion's isotope (``1H_I`` gives that of 1H)."""
        elements = np.asarray(self.atomic["Element"]).astype(str)
        sel = np.where(elements == ion.split("_")[0])[0]
        return float(self.atomic["AtomicMass"][sel[0]]) if sel.size else None


# -- What the model is made of -----------------------------------------------------


@dataclass
class Keyword:
    """
    A ``key=value`` word of a line.

    Attributes
    ----------
    name : str
    value : str
    token : Token
        The whole word.
    key, val : Token
        Its two halves.

    Generated by RJC and Claude.
    """

    name: str
    value: str
    token: T.Token
    key: T.Token
    val: T.Token


@dataclass
class Param:
    """
    One parameter, where it is written, and what ALIS makes of it.

    A parameter written in several places with one label is one ALIS parameter; each
    place is a ``Param``, and they share ``index``.

    Attributes
    ----------
    name : str
        ALIS's name for it, such as ``ColDens`` or ``value``.
    slot : int
        Its place in its line's list of parameters.
    value : float
        The value ALIS reads here (its default, when nothing is written).
    label : str
        Its label, or ``""``.
    token : Token or None
        The word that holds it (``13.0ra``, ``ColDens=13.0ra``, or an argument of a
        resolution function); None when ALIS used its default.
    value_token, label_token : Token or None
        The value and the label within that word.
    named : bool
        Written as ``name=value``.
    line : int
        The line it is written on.
    owner : ModelLine or DataLine
        The line's item.
    role : str
        ``"model"``, ``"resolution"`` or ``"shift"``.
    index : int
        ALIS's number for the parameter (its place in ``modpass['p0']``).
    first : bool
        This place defines the parameter's starting value.
    fixed, linked : bool
        Whether ALIS holds it fixed, or computes it from a link.
    limits : tuple
        ``(low, high)``, None where there is no limit.
    start : float
        The parameter's starting value, as ALIS starts it.

    :attr:`written` is the value as written. ALIS reads the same value since
    ``base.tie_value`` (Q2.12); it used to strip the label's characters, so that
    ``11.2878481n1a`` was read as ``11.287848``.

    Generated by RJC and Claude.
    """

    name: str
    slot: int
    value: float
    label: str
    token: T.Token | None
    value_token: T.Token | None
    label_token: T.Token | None
    named: bool
    line: int
    owner: object = field(repr=False)
    role: str = "model"
    index: int = -1
    first: bool = True
    fixed: bool = False
    linked: bool = False
    limits: tuple = (None, None)
    start: float = 0.0

    @property
    def given(self):
        """Whether the parameter is written on its line."""
        return self.token is not None

    @property
    def written(self):
        """The value as written, or None when nothing is written."""
        return None if self.value_token is None else _float(self.value_token.text)

    @property
    def free(self):
        """Whether the fit varies it."""
        return not self.fixed and not self.linked


@dataclass
class Setting:
    """
    A setting outside the blocks, such as ``run ncpus 4``.

    Generated by RJC and Claude.
    """

    line: int
    category: str
    key: str
    value: str
    tokens: tuple
    known: bool


@dataclass
class Call:
    """
    A resolution or shift function on a data line, such as ``vfwhm(6.974va)``.

    Generated by RJC and Claude.
    """

    name: str
    text: str
    token: T.Token | None
    args: list


@dataclass
class DataLine:
    """
    One line of the data block: one snip, or one fitted range of a spectrum.

    Attributes
    ----------
    line : int
    file : Token
        The data file as written on the line.
    keywords : dict
        ``Keyword`` by name.
    specid : str
        Its ``specid``, or ``"None"`` when it has none (as ALIS names it).
    resolution, shift : Call or None
        The functions ALIS reads (None for no shift).
    params : list of Param
        The parameters of the resolution and the shift.
    index : int
        Its place among the data lines.

    Generated by RJC and Claude.
    """

    line: int
    file: T.Token
    keywords: dict
    specid: str
    resolution: Call | None
    shift: Call | None
    params: list = field(default_factory=list)
    index: int = 0

    def keyword(self, name, default=None):
        """The value of keyword ``name``, or ``default``."""
        kw = self.keywords.get(name)
        return default if kw is None else kw.value

    def path(self, datadirc=""):
        """The data file's path, as ``load_data`` resolves it."""
        return datadirc + self.file.text

    @property
    def fitrange(self):
        """
        The fitted range: ``("range", low, high)``, ``("columns",)``, ``("all",)``,
        or None when the line has none.
        """
        value = self.keyword("fitrange")
        if value is None:
            return None
        parts = value.strip("[]()").split(",")
        if parts == ["columns"]:
            return ("columns",)
        if parts == ["all"]:
            return ("all",)
        nums = [_float(p) for p in parts]
        if len(nums) != 2 or None in nums:
            return None
        return ("range", nums[0], nums[1])

    def param(self, role):
        """The first parameter of the resolution or the shift, or None."""
        for par in self.params:
            if par.role == role:
                return par
        return None


@dataclass
class ModelLine:
    """
    One model function of the model block, such as a ``voigt`` or a ``legendre``.

    Attributes
    ----------
    line : int
    function : str
    section : str
        ``"emission"``, ``"absorption"`` or ``"zerolevel"``.
    tokens : tuple
        The words after the function's name.
    keywords : dict
        ``Keyword`` by name.
    params : list of Param
    index : int
        ALIS's count of the model's functions (``cntr``).

    Generated by RJC and Claude.
    """

    line: int
    function: str
    section: str
    tokens: tuple
    keywords: dict
    params: list = field(default_factory=list)
    index: int = 0

    def keyword(self, name, default=None):
        """The value of keyword ``name``, or ``default``."""
        kw = self.keywords.get(name)
        return default if kw is None else kw.value

    @property
    def ion(self):
        """The ``ion=`` keyword, or None."""
        return self.keyword("ion")

    @property
    def ratio(self):
        """Whether the line gives a column-density ratio, ``ion=2H_I/1H_I``."""
        return self.ion is not None and "/" in self.ion

    @property
    def specids(self):
        """The specids it applies to (empty: every specid)."""
        value = self.keyword("specid")
        return [s for s in value.split(",") if s] if value else []

    @property
    def blind(self):
        """Whether the line carries ``blind=True``."""
        return str(self.keyword("blind", "")).lower() == "true"

    @property
    def variable(self):
        """Whether the line holds a parameter for links (``variable``, ``random``)."""
        return self.function in VARIABLES

    def param(self, name):
        """The parameter called ``name``, or None."""
        for par in self.params:
            if par.name == name:
                return par
        return None


