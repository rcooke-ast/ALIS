@dataclass
class Label:
    """
    A label and every parameter that carries it.

    Attributes
    ----------
    name : str
    params : list of Param
        In ALIS's order; the first defines the starting value.
    commands : list of Command
        The ``fix param`` and ``lim param`` commands that name it.
    links : list of Link
        The links that compute it or depend on it.

    Generated by RJC and Claude.
    """

    name: str
    params: list = field(default_factory=list)
    commands: list = field(default_factory=list)
    links: list = field(default_factory=list)

    @property
    def fixed(self):
        """Whether the parameter is held fixed."""
        return bool(self.params) and self.params[0].fixed

    @property
    def linked(self):
        """Whether a link computes the parameter."""
        return bool(self.params) and self.params[0].linked

    @property
    def state(self):
        """``"linked"``, ``"fixed"``, ``"tied"`` (free, in several places), ``"free"``.

        Generated by RJC and Claude.
        """
        if self.linked:
            return "linked"
        if self.fixed:
            return "fixed"
        return "tied" if len(self.params) > 1 else "free"


def _keywords(tokens):
    """The ``key=value`` words of a line, by name (the last wins, as in ALIS)."""
    found = {}
    for tok in tokens:
        halves = T.split_keyword(tok)
        if halves is not None:
            key, val = halves
            found[key.text] = Keyword(key.text, val.text, tok, key, val)
    return found


def _float(text):
    """A number, or None."""
    try:
        return float(text)
    except ValueError:
        return None


# -- The parsed model --------------------------------------------------------------


class ParsedModel:
    """
    A model as ALIS reads it, with the position of everything in it.

    Parameters
    ----------
    mtext : ModelText or str
        The model's text.
    registry : Registry
        ALIS's functions and atomic data.

    Attributes
    ----------
    text : ModelText
    settings : list of Setting
    data : list of DataLine
    lines : list of ModelLine
        The model functions, in order.
    commands : list of Command
    links : list of Link
    params : list of Param
        Every parameter, in every place it is written, in ALIS's order.
    labels : dict
        ``Label`` by name.
    argflag : alis.config.ArgFlag
        The settings, with the model's own applied.
    problems : list of Problem
        What stopped ALIS reading the model, and its warnings.
    ok : bool
        ALIS read the model's settings, data lines, model and links.

    Generated by RJC and Claude.
    """

    def __init__(self, mtext, registry):
        self.text = mtext if isinstance(mtext, T.ModelText) else T.ModelText(mtext)
        self.registry = registry
        self.settings, self.data, self.lines = [], [], []
        self.commands, self.links, self.params = [], [], []
        self.labels = {}
        self.problems = list(self.text.problems)
        self.argflag = ArgFlag()
        self.argflag["out"]["verbose"] = -1
        self.modpass = None
        self.parinfo = None
        self._by_line = {}
        self._read_settings()
        self._read_data()
        self._read_model()
        self._read_links()
        self.ok = not self.errors
        if self.ok:
            self._read_with_alis()
            self.ok = not self.errors

    # -- the problems ---------------------------------------------------------------

    @property
    def errors(self):
        """
        The problems that stop ALIS reading the model.

        An unknown ion (source ``"check"``) is an error of the model, but ALIS reads
        the model none the less, and stops only when it fits.
        """
        return [
            p for p in self.problems if p.severity == "error" and p.source != "check"
        ]

    def _problem(self, line, message, severity="error", source="model"):
        self.problems.append(T.Problem(line, severity, message, source))

    # -- settings -------------------------------------------------------------------

    def _read_settings(self):
        """
        Read each setting with ALIS's ``set_params``, one line at a time.

        Generated by RJC and Claude.
        """
        seen = {}
        for line in self.text.of_kind(T.SETTING):
            words = line.words
            cat = words[0]
            key = words[1] if len(words) > 1 else ""
            value = words[2] if len(words) > 2 else ""
            known = cat in self.argflag.keys() and key in self.argflag[cat].keys()
            item = Setting(line.num, cat, key, value, line.tokens, known)
            self.settings.append(item)
            self._by_line[line.num] = item
            try:
                with alis_quietly():
                    load.set_params([line.text], self.argflag)
            except AlisStop:
                if not known:
                    self._problem(
                        line.num, "Unknown setting: '{0}'.".format(" ".join(words[:2]))
                    )
                else:
                    self._problem(
                        line.num,
                        "Bad value for the setting '{0} {1}':"
                        " '{2}'.".format(cat, key, value),
                    )
                continue
            if (cat, key) in seen:
                self._problem(
                    line.num,
                    "'{0} {1}' is also set on line {2}; the last"
                    " value is used.".format(cat, key, seen[(cat, key)] + 1),
                    severity="warning",
                )
            seen[(cat, key)] = line.num

    @property
    def datadirc(self):
        """The ``run datadirc`` setting."""
        return self.argflag["run"]["datadirc"]

    @property
    def blind(self):
        """Whether ``run blind True`` is set (global blind, D24)."""
        return bool(self.argflag["run"]["blind"])

    # -- data lines -----------------------------------------------------------------

    def _read_data(self):
        """
        Read the data lines, with the checks ``load_data`` makes before loading.

        Generated by RJC and Claude.
        """
        for index, line in enumerate(self.text.of_kind(T.DATA)):
            words = line.tokens[1:]
            for tok in words:
                halves = T.split_keyword(tok)
                if halves is None:
                    self._problem(
                        line.num,
                        "'{0}' is not a keyword: data lines take"
                        " the file, then key=value words.".format(tok.text),
                    )
                elif halves[0].text not in DATA_KEYWORDS:
                    self._problem(
                        line.num,
                        "Unknown keyword on a data line: '{0}'.".format(halves[0].text),
                    )
            kws = _keywords(words)
            item = DataLine(
                line.num,
                line.tokens[0],
                kws,
                kws["specid"].value if "specid" in kws else "None",
                None,
                None,
                index=index,
            )
            self._check_data_line(item)
            item.resolution = self._call(kws.get("resolution"), NO_RESOLUTION)
            item.shift = self._call(kws.get("shift"), NO_SHIFT)
            self.data.append(item)
            self._by_line[line.num] = item

    @staticmethod
    def _call(kw, default):
        """The resolution or shift function of a data line."""
        if kw is None or kw.value.lower() == "none":
            return None if default == NO_SHIFT else Call("vfwhm", default, None, [])
        name, args = T.function_args(kw.val)
        return Call(name.text, kw.value, kw.val, args)

    def _check_data_line(self, item):
        """
        The checks of ``load_data``'s first pass over the data lines.

        Generated by RJC and Claude.
        """
        num = item.line
        columns = []
        if "columns" in item.keywords:
            columns = [
                c.split(":")[0].strip()
                for c in item.keyword("columns").strip("[]()").split(",")
            ]
            bad = [c for c in columns if c not in DATA_COLUMNS]
            if bad:
                self._problem(num, "Unknown column name: '{0}'.".format(bad[0]))
            if "flux" not in columns or "error" not in columns:
                self._problem(
                    num, "'columns' must name at least the flux and error" " columns."
                )
        for key in ("fitrange", "loadrange"):
            value = item.keyword(key)
            if value is None:
                continue
            parts = value.strip("[]()").split(",")
            if parts == ["columns"]:
                if key not in columns:
                    self._problem(
                        num,
                        "{0}=columns needs a '{0}' column in" " 'columns'.".format(key),
                    )
            elif parts == ["all"]:
                pass
            elif len(parts) == 2 and None not in map(_float, parts):
                if float(parts[1]) <= float(parts[0]):
                    self._problem(
                        num,
                        "The upper limit of {0} must be greater than"
                        " the lower.".format(key),
                    )
            else:
                self._problem(
                    num, "{0} must be [low,high], 'all' or 'columns'.".format(key)
                )
        if "fitrange" not in item.keywords:
            self._problem(num, "The data line has no fitrange.")
        bintype = item.keyword("bintype")
        if bintype is not None and bintype not in ("km/s", "A", "Hz"):
            self._problem(num, "Unknown bintype: '{0}'.".format(bintype))
        if item.keyword("resolution") == "columns" and "resolution" not in columns:
            self._problem(
                num, "resolution=columns needs a 'resolution' column in" " 'columns'."
            )

    @property
    def specids(self):
        """The specids in ALIS's order (first appearance), ``"None"`` for none."""
        found = []
        for item in self.data:
            if item.specid not in found:
                found.append(item.specid)
        return found

    # -- the model block ------------------------------------------------------------

    def _read_model(self):
        """
        Read the sections, the model functions and the ``fix``/``lim`` commands.

        Generated by RJC and Claude.
        """
        section, seen_zero = None, False
        for line in self.text.lines:
            if line.kind == T.SECTION:
                section = line.words[0]
                if section == "zerolevel":
                    if seen_zero:
                        self._problem(
                            line.num, "The zerolevel section may be given" " only once."
                        )
                    seen_zero = True
            elif line.kind in (T.FIX, T.LIM):
                words = line.words
                if len(words) != 4:
                    self._problem(
                        line.num,
                        "'{0}' takes three words: a function (or"
                        " 'param'), a parameter (or a label) and a value.".format(
                            words[0]
                        ),
                    )
                    continue
                item = Command(
                    line.num, words[0], words[1], words[2], words[3], line.tokens
                )
                self.commands.append(item)
                self._by_line[line.num] = item
                if item.target != "param":
                    self._check_command(item)
            elif line.kind == T.FUNCTION:
                name = line.words[0]
                if name not in self.registry.names:
                    self._problem(
                        line.num, "Unknown model function: '{0}'.".format(name)
                    )
                elif section is None:
                    self._problem(
                        line.num,
                        "A model function must come after"
                        " 'emission', 'absorption' or 'zerolevel'.",
                    )
                item = ModelLine(
                    line.num,
                    name,
                    section or "",
                    line.tokens[1:],
                    _keywords(line.tokens[1:]),
                    index=len(self.lines),
                )
                self.lines.append(item)
                self._by_line[line.num] = item
                ion = item.ion
                if ion is not None and name in ION_FUNCTIONS:
                    for part in ion.split("/"):
                        if part not in self.registry.ions:
                            self._problem(
                                line.num,
                                "Unknown ion: '{0}'.".format(part),
                                source="check",
                            )

    def _check_command(self, item):
        """A function-wide ``fix`` or ``lim`` names a function and its parameter."""
        if item.target not in self.registry.names:
            self._problem(
                item.line, "Unknown model function: '{0}'.".format(item.target)
            )
        elif item.name not in self.registry.function(item.target)._parid:
            self._problem(
                item.line,
                "'{0}' has no parameter called '{1}'.".format(item.target, item.name),
            )

    # -- links ----------------------------------------------------------------------

    def _read_links(self):
        """
        Read the links, as ``load_links`` splits them.

        Generated by RJC and Claude.
        """
        for line in self.text.of_kind(T.LINK):
            body = line.text[line.content[0] : line.content[1]]
            try:
                left, right = body.split("=")
                target, deps = left.strip().split("(")
                deps = [d.strip() for d in deps.rstrip(") ").split(",")]
            except ValueError:
                self._problem(
                    line.num,
                    "A link has the form 'va(vb,vc) = vb + vc'," " with one '='.",
                )
                continue
            start = line.content[0]
            target = target.strip()
            tcol = line.text.index(target, start)
            ttok = T.Token(target, line.num, tcol, tcol + len(target))
            dtoks, col = [], line.text.index("(", tcol)
            for dep in deps:
                col = line.text.index(dep, col)
                dtoks.append(T.Token(dep, line.num, col, col + len(dep)))
                col += len(dep)
            item = Link(line.num, target, deps, right.strip(), ttok, dtoks)
            self.links.append(item)
            self._by_line[line.num] = item

    # -- ALIS's reading -------------------------------------------------------------

    def _modlines(self):
        """The lines ``load_input`` gives ``load_model``: the model block's content."""
        return [
            ln
            for ln in self.text.lines
            if ln.kind in (T.SECTION, T.FIX, T.LIM, T.FUNCTION)
        ]

    def _alis_state(self):
        """
        The attributes ALIS's model loaders read, made from the text alone.

        ``_resn`` and ``_shft`` hold, per specid, the resolution and shift of each of
        its data lines, as ``load_data`` sets them.

        Generated by RJC and Claude.
        """
        specids = self.specids
        resn = {s: [] for s in specids}
        shft = {s: [] for s in specids}
        self._entries = {s: [] for s in specids}
        for item in self.data:
            resn[item.specid].append(item.resolution.text)
            shft[item.specid].append(
                NO_SHIFT if item.shift is None else item.shift.text
            )
            self._entries[item.specid].append(item)
        state = SimpleNamespace()
        state._argflag = copy.deepcopy(self.argflag)
        state._argflag["out"]["verbose"] = -1
        state._specid = np.array(specids)
        state._resn = [np.array(resn[s]) for s in specids]
        state._shft = [np.array(shft[s]) for s in specids]
        state._atomic = self.registry.atomic
        state._funcarray = self.registry.instances()
        state._modlines = [ln.text for ln in self._modlines()]
        return state

    def _read_with_alis(self):
        """
        Read the model block and the links with ALIS's own loaders.

        Generated by RJC and Claude.
        """
        state = self._alis_state()
        lnklines = [ln.text for ln in self.text.of_kind(T.LINK)]
        stage = "model"
        try:
            with alis_quietly() as notes:
                state._modpass = load.load_model(state, state._modlines)
                mtie = copy.deepcopy(state._modpass["mtie"])
                stage = "links"
                state._links = load.load_links(state, lnklines)
                stage = "limits"
                parinfo, _ = load.load_parinfo(state)
        except AlisStop as stop:
            self._place_alis_error(stop.message, stage)
            return
        except Exception as err:
            # ALIS failed without a message of its own: a crash on bad input
            self._problem(
                self._locate(str(err)),
                "ALIS could not read the model"
                " ({0}: {1}).".format(type(err).__name__, err),
            )
            return
        warnings = [m for level, m in notes if level >= logging.WARNING]
        placed = {}
        if any(self._locate(m) is None for m in warnings):
            # A warning that quotes no line: find the line that gives it
            for num, level, message in self._first_pass()[1]:
                placed.setdefault(message, num)
        for message in warnings:
            num = self._locate(message)
            self._problem(
                placed.get(message, num) if num is None else num,
                plain(message),
                severity="warning",
                source="alis",
            )
        self.modpass = state._modpass
        self.parinfo = parinfo
        self._match(mtie, state._links)

    def _locate(self, message, prefer=()):
        """
        The line an ALIS message is about, found from the text it quotes.

        A message that quotes a whole line is placed on that line. One that quotes
        only a name in single quotes (a label, a link) is placed on the first line
        that has that word, looking first at the lines of the kinds in ``prefer``.

        Generated by RJC and Claude.
        """
        flat = plain(message)
        best, size = None, 0
        for line in self.text.lines:
            if line.kind not in T.CONTENT:
                continue
            content = plain(line.text[line.content[0] : line.content[1]])
            if content and content in flat and len(content) > size:
                best, size = line.num, len(content)
        if best is None:
            for line in self.text.lines:
                tail = plain(" ".join(line.words[1:]))
                if line.kind == T.FUNCTION and tail and tail in flat:
                    return line.num
        if best is None:
            quoted = re.findall(r"'([^'\s]+)'", flat)
            kinds = list(prefer) + [k for k in T.CONTENT if k not in prefer]
            for kind in kinds:
                for line in self.text.of_kind(kind):
                    names = set(line.words) | set(
                        re.findall(r"[A-Za-z_]\w*", line.text)
                    )
                    if any(q in names for q in quoted):
                        return line.num
        return best

    def _place_alis_error(self, message, stage):
        """
        Put an error of ALIS's model loaders on its line.

        Errors of a model function are found by reading each function alone, as
        ``load_model`` does in its first pass; the others by the text they quote.

        Generated by RJC and Claude.
        """
        num = None
        if stage == "model":
            num = self._first_pass()[0]
        if num is None:
            prefer = (T.LINK,) if stage == "links" else (T.FIX, T.LIM)
            num = self._locate(message, prefer)
        self._problem(num, plain(message), source="alis")

    def _first_pass(self):
        """
        Read each model function alone, as ``load_model``'s first pass does.

        Returns
        -------
        tuple
            ``(line, notes)``: the first line that ALIS cannot read (None if every
            line reads), and ``(line, level, message)`` for each message ALIS gave.

        Generated by RJC and Claude.
        """
        state = self._alis_state()
        funcs = state._funcarray
        modpass = ModelPass()
        notes = []
        for cntr, item in enumerate(self.lines):
            if item.function not in funcs[0]:
                return item.line, notes
            line = self.text[item.line]
            instr = line.text[line.tokens[0].end : line.content[1]].strip()
            try:
                with alis_quietly() as said:
                    load.call_function_load(
                        funcs[1][item.function],
                        funcs[2][item.function],
                        instr,
                        cntr,
                        modpass,
                        state._specid,
                    )
            except Exception:
                return item.line, notes
            finally:
                notes += [(item.line, level, text) for level, text in said]
        return None, notes

    # -- matching ALIS's parameters to the words ------------------------------------

    def _slots(self, inst, words, nslots, ratio):
        """
        The word that holds each of a line's parameters (None for a default).

        Named parameters (``ColDens=14.0``) go to their own places, and the others
        fill the remaining places in order, as the functions' ``load`` methods do.

        Returns
        -------
        list
            ``(word, named)`` or None, for each place.

        Generated by RJC and Claude.
        """
        parid = list(inst._parid)
        slots = [None] * nslots
        positional = []
        for tok in words:
            halves = T.split_keyword(tok)
            if halves is None and ":" not in tok.text:
                positional.append(tok)
            elif halves is None:
                continue
            elif halves[0].text in parid:
                place = parid.index(halves[0].text)
                if place < nslots and (place == 0 or not ratio):
                    slots[place] = (tok, True)
        for place in range(nslots):
            if slots[place] is None and positional:
                slots[place] = (positional.pop(0), False)
        return slots

    def _make_params(self, owner, role, inst, words, mpar, line):
        """
        One ``Param`` per parameter of a line, from its words and ALIS's values.

        Generated by RJC and Claude.
        """
        ratio = isinstance(owner, ModelLine) and owner.ratio
        slots = self._slots(inst, words, len(mpar), ratio)
        parid = list(inst._parid)
        out = []
        for place, value in enumerate(mpar):
            name = parid[place] if place < len(parid) else parid[-1]
            if ratio and place == 0:
                name = parid[0]
            token = named = vtok = ltok = None
            if slots[place] is not None:
                token, named = slots[place]
                vword = T.split_keyword(token)[1] if named else token
                vtok, ltok = T.split_value(vword)
            out.append(
                Param(
                    name,
                    place,
                    float(value),
                    ltok.text if ltok is not None else "",
                    token,
                    vtok,
                    ltok,
                    bool(named),
                    line,
                    owner,
                    role,
                )
            )
        return out

    def _match(self, mtie, links):
        """
        Give every place a parameter is written its ALIS number, label and state.

        ``mtie`` is ALIS's tie table before the links changed it.

        Generated by RJC and Claude.
        """
        modpass, parinfo = self.modpass, self.parinfo
        funcs = self.registry
        places = []
        for item in self.lines:
            inst = funcs.function(item.function)
            item.params = self._make_params(
                item, "model", inst, item.tokens, modpass["mpar"][item.index], item.line
            )
            places.append(item.params)
        entries = [it for s in self.specids for it in self._entries[s]]
        for item in entries:
            res = item.resolution
            inst = funcs.function(res.name)
            pars = self._make_params(
                item,
                "resolution",
                inst,
                res.args,
                modpass["mpar"][len(places)],
                item.line,
            )
            item.params = list(pars)
            places.append(pars)
        for item in entries:
            call = item.shift
            name = "Ashift" if call is None else call.name
            args = [] if call is None else call.args
            pars = self._make_params(
                item,
                "shift",
                funcs.function(name),
                args,
                modpass["mpar"][len(places)],
                item.line,
            )
            item.params += pars
            places.append(pars)
        # ALIS's numbering: a new number for each untied place and each label's
        # first place, in order
        tpar = modpass["tpar"]
        first_of = {num: lab for lab, num in tpar}
        linked = set(links["opA"])
        count = 0
        for cntr, pars in enumerate(places):
            for place, par in enumerate(pars):
                tie = mtie[cntr][place]
                if tie >= 0:
                    par.label = tpar[tie][0]
                    par.index = tpar[tie][1]
                    par.first = False
                else:
                    par.index = count
                    if count in first_of:
                        par.label = first_of[count]
                    count += 1
                info = parinfo[par.index]
                par.fixed = bool(info["fixed"] == 1)
                par.linked = par.label in linked
                par.limits = tuple(
                    info["limits"][k] if info["limited"][k] else None for k in range(2)
                )
                par.start = float(modpass["p0"][par.index])
                self.params.append(par)
                if par.label:
                    self.labels.setdefault(par.label, Label(par.label)).params.append(
                        par
                    )
        for cmd in self.commands:
            if cmd.target == "param" and cmd.name in self.labels:
                self.labels[cmd.name].commands.append(cmd)
        for link in self.links:
            for name in [link.target] + link.deps:
                if name in self.labels:
                    self.labels[name].links.append(link)

    # -- looking things up ----------------------------------------------------------

    @property
    def n_params(self):
        """The number of ALIS parameters (``len(modpass['p0'])``)."""
        return 0 if self.modpass is None else len(self.modpass["p0"])

    @property
    def n_free(self):
        """The number of parameters the fit varies (neither fixed nor linked)."""
        return len({p.index for p in self.params if p.free})

    def defining(self):
        """Each ALIS parameter once: the place that defines it, in ALIS's order."""
        return [p for p in self.params if p.first]

    def item_at(self, num):
        """
        The item on line ``num``: a Setting, DataLine, ModelLine, Command or Link.

        Generated by RJC and Claude.
        """
        return self._by_line.get(num)

    def params_on(self, num):
        """The parameters written on line ``num``."""
        return [p for p in self.params if p.line == num]

    def param_at(self, num, col):
        """
        The parameter whose word covers column ``col`` of line ``num``, or None.

        Generated by RJC and Claude.
        """
        for par in self.params_on(num):
            if par.token is not None and par.token.start <= col < par.token.end:
                return par
        return None

    def function_lines(self, function=None, section=None):
        """
        The model functions, optionally of one function or one section.

        Generated by RJC and Claude.
        """
        return [
            item
            for item in self.lines
            if (function is None or item.function == function)
            and (section is None or item.section == section)
        ]

    def data_line(self, specid):
        """The data lines of a specid."""
        return [item for item in self.data if item.specid == specid]

    def label_uses(self, name):
        """
        Every place a label is named: parameters, commands and links.

        Generated by RJC and Claude.
        """
        lab = self.labels.get(name)
        if lab is None:
            return (
                [],
                [c for c in self.commands if c.target == "param" and c.name == name],
                [k for k in self.links if name in [k.target] + k.deps],
            )
        return lab.params, lab.commands, lab.links


_NUMBER_WORD = re.compile(r"^[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$")


def is_number(text):
    """Whether ``text`` is a plain number, with no label."""
    return bool(_NUMBER_WORD.match(text))


