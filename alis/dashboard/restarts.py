"""Random restarts of a run (dashboard Stage 6.8; S21; Q6.10, Q6.18, Q6.22). No Qt.

- **The starts** (Q6.22(a)) are drawn as ALIS's ``sim perturb`` draws them after
  ``sim beginfrom`` the shown run (``simulate.perturb``): about the run's best fit,
  from its covariance (its rows of zeros left out, and the rest factored by
  Cholesky), each draw clamped to ±``sim maxperturb`` of its value, and then to the
  parameter's limits; fixed and linked parameters keep their values, and ALIS
  computes the linked ones again from the draws.
- **Each restart** is the run's own model with the draws written as its starting
  values (:func:`restart_bundle`), fitted by the dashboard's process, one after
  another (``runs.Restarts``).
- **What is kept** (Q6.18(a)): ``restarts.json`` with the run the restarts started
  from (committed with it, saved with Save): each restart's starting values,
  best-fit values and errors (every parameter, by ALIS's number), χ², degrees of
  freedom, iterations and status; the run's best fit, its errors and χ²; and the
  settings of the draws. While anything of the run is hidden, the whole file is
  kept hidden in the bundle, as a run's outputs are, until Unblind.
- **The assessment** (:func:`assess`): as ``convergence.assess_restarts`` assesses
  restarts (``sim convergetest`` and ``sim convergesig``): for each free parameter,
  the largest |Δ|/σ across the restarts (or their scatter over σ), flagged beyond
  the tolerance, and ALIS's own line of summary. A restart that reaches a lower χ²
  than the run is offered to continue from.
- **Export restarts…** (Q6.18(b)): the table in the form ``sim perturb`` writes its
  own (``<model>.perturb_0-10``: one row per fit, the first the starting values,
  here the run's best fit), with a header naming the columns and χ² as the last
  column, so that ``numpy.loadtxt`` reads it. A hidden parameter's columns are left
  out, and the header says so (Q6.18(c)).

Generated by RJC and Claude.
"""

import contextlib
import copy
import dataclasses
