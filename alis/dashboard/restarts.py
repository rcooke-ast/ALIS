MEMBER = "restarts.json"
FORMAT = 1


class RestartsError(Exception):
    """Restarts that cannot be drawn, kept or exported as asked."""


# -- The starts (Q6.22) -----------------------------------------------------------------


def sim_settings(view):
    """The run's ``sim`` settings that the draws and the assessment use."""
    sim = view.model.parsed.argflag["sim"]
    return {
        "maxperturb": float(sim["maxperturb"]),
        "convergetest": str(sim["convergetest"]),
        "convergesig": float(sim["convergesig"]),
    }


def draw_starts(view, count, maxperturb=None, seed=None):
    """
    The starts of ``count`` restarts, as ``sim perturb`` draws them after ``sim
    beginfrom`` the run: about its best fit, from its covariance, clamped to
    ±``maxperturb`` of each value and then to the limits.

    Parameters
    ----------
    view : results.View
        A run with a best fit and a covariance.
    count : int
    maxperturb : float, optional
        ``sim maxperturb`` (the run's by default).
    seed : int, optional

    Returns
    -------
    numpy.ndarray
        ``(count, parameters)``: every parameter by ALIS's number.

    Raises
    ------
    RestartsError

    Generated by RJC and Claude.
    """
    if view.in_progress or not view.has_best_fit:
        raise RestartsError(view.why_not() or "The fit is still running.")
    covar = view.covariance
    if covar is None or view.interrupted:
        raise RestartsError(
            "{0} has no covariance to draw the starts from (out covar).".format(
                view.name.capitalize()
            )
        )
    best = np.asarray(view.vector(), dtype=float)
    if covar.shape[0] != best.size:
        raise RestartsError("The run's covariance does not match its parameters.")
    if maxperturb is None:
        maxperturb = sim_settings(view)["maxperturb"]
    perror = np.sqrt(np.clip(np.diag(covar), 0.0, None))
    # The rows (and columns) that are all zero are left out, as sim perturb does
    zero = np.where(np.all(covar == 0.0, axis=0) & np.all(covar == 0.0, axis=1))[0]
    keep = np.setdiff1d(np.arange(covar.shape[0]), zero)
    try:
        upper = np.linalg.cholesky(covar[np.ix_(keep, keep)])
    except np.linalg.LinAlgError:
        raise RestartsError(
            "The run's covariance cannot be factored (it is not positive"
            " definite), so no starts can be drawn from it."
        ) from None
    rng = np.random.default_rng(seed)
    draws = upper @ rng.standard_normal((keep.size, int(count)))
    where = {int(k): n for n, k in enumerate(keep)}
    limits = _limits(view)
    out = np.tile(best, (int(count), 1))
    for sim in range(int(count)):
        for pw in range(best.size):
            if not perror[pw] > 0.0 or pw not in where:
                continue
            shift = float(draws[where[pw], sim])
            value = best[pw]
            if value != 0.0:
                if shift / value > maxperturb:
                    new = value * (1.0 + maxperturb)
                elif shift / value < -maxperturb:
                    new = value * (1.0 - maxperturb)
                else:
                    new = value + shift
            else:
                new = value + shift
            low, high = limits.get(pw, (None, None))
            if low is not None and new < low:
                new = low
            if high is not None and new > high:
                new = high
            out[sim, pw] = new
    return out


def _limits(view):
    """Each parameter's limits, by ALIS's number."""
    out = {}
    for par in view.model.parsed.params:
        if par.index >= 0 and par.index not in out:
            out[par.index] = tuple(par.limits)
    return out


def restart_bundle(view, start):
    """
    One restart: the run's model, its free parameters' starting values replaced by
    a draw, on the snips as they are now; a bundle to hand to the fitting process.

    Generated by RJC and Claude.
    """
    model = view.model
    pm = model.parsed
    patches, done = [], set()
    for par in pm.params:
        if par.index < 0 or not par.free or par.index in done:
            continue
        done.add(par.index)
        text = E.format_value(float(start[par.index]), 10)
        patches.extend(E.set_value(pm, par, text, everywhere=True).patches)
    change = T.Change.from_spans(patches, "Restart")
    text = change.apply(model.text)
    bundle = model.to_bundle()
    # The run's model is read with the project's atomic table
    for name, data in view.project.bundle.members.items():
        if name.startswith(B.ATOMIC) and name not in bundle.members:
            bundle.members[name] = data
    member = bundle.model_member
    store = {}
    hidden = B.hide_lines(text, model.hidden_lines(), store)
    bundle.members[member] = hidden.encode("utf-8")
    if store:
        bundle.hidden["lines"][member] = store
    else:
        bundle.hidden["lines"].pop(member, None)
    for name in [m for m in bundle.members if m.startswith(B.RUNS)]:
        del bundle.members[name]
    for kind in ("lines", "files"):
        for name in [m for m in bundle.hidden[kind] if m.startswith(B.RUNS)]:
            del bundle.hidden[kind][name]
    return bundle


# -- One restart's result ----------------------------------------------------------------


@dataclass
class Restart:
    """
    One restart: where it started, where it ended, and how.

    Attributes
    ----------
    start, values, errors : list of float
        Every parameter by ALIS's number (``errors`` empty for one stopped before
        the end).
    chi2 : float
    dof, iterations : int
    status : str

    Generated by RJC and Claude.
    """

    start: list
    values: list = field(default_factory=list)
    errors: list = field(default_factory=list)
    chi2: float = None
    dof: int = None
    iterations: int = None
    status: str = ""

    def to_json(self):
        return dataclasses.asdict(self)


def result_of(start, info, mod_out, covar, registry):
    """
    A restart from what the fitting process sent back: its ``run.json`` fields, its
    ``.mod.out`` and its covariance's text.

    Generated by RJC and Claude.
    """
    size = len(start)
    values, errors = [], []
    status = info.get("status", "completed")
    if mod_out:
        values = list(map(float, start))
        found = R.out_values(mod_out, registry) or {}
        for i, v in found.items():
            if 0 <= i < size:
                values[i] = float(v)
        if status != R.INTERRUPTED:
            matrix = None
            if covar:
                try:
                    matrix = np.loadtxt(io.StringIO(covar), ndmin=2)
                except ValueError:
                    matrix = None
            errs = R.out_errors(mod_out, registry, matrix) or {}
            errors = [float(errs.get(i, 0.0)) for i in range(size)]
    return Restart(
        start=list(map(float, start)),
        values=values,
        errors=errors,
        chi2=info.get("chi2_final"),
        dof=info.get("dof"),
        iterations=info.get("iterations"),
        status=status,
    )


# -- What is kept with the run (Q6.18(a)) -------------------------------------------------


@dataclass
class Kept:
    """
    The restarts kept with a run (``restarts.json``).

    Attributes
    ----------
    best, perror : list of float
        The run's best fit and errors (its covariance's diagonal), by ALIS's
        number.
    chi2 : float
        The run's χ².
    restarts : list of Restart
    settings : dict
        ``maxperturb``, ``convergetest``, ``convergesig``, ``count``, ``seed``.
    started, finished : str

    Generated by RJC and Claude.
    """

    best: list
    perror: list
    chi2: float = None
    restarts: list = field(default_factory=list)
    settings: dict = field(default_factory=dict)
    started: str = ""
    finished: str = ""

    def to_text(self):
        data = {
            "format": FORMAT,
            "best": self.best,
            "perror": self.perror,
            "chi2": self.chi2,
            "settings": self.settings,
            "started": self.started,
            "finished": self.finished,
            "restarts": [r.to_json() for r in self.restarts],
        }
        return json.dumps(data, indent=1)

    @classmethod
    def from_text(cls, text):
        data = json.loads(text)
        return cls(
            best=data.get("best", []),
            perror=data.get("perror", []),
            chi2=data.get("chi2"),
            restarts=[Restart(**r) for r in data.get("restarts", [])],
            settings=data.get("settings", {}),
            started=data.get("started", ""),
            finished=data.get("finished", ""),
        )


def new_kept(view, settings):
    """The record the restarts of a run start as (with none yet)."""
    perror = np.sqrt(np.clip(np.diag(view.covariance), 0.0, None))
    stats = view.statistics()
    return Kept(
        best=[float(v) for v in view.vector()],
        perror=[float(v) for v in perror],
        chi2=stats.chi2,
        settings=dict(settings),
        started=B.now(),
    )


def kept(record):
    """
    The restarts kept with a run, or None.

    Generated by RJC and Claude.
    """
    member = record.prefix + MEMBER
    bundle = record.bundle
    text = bundle.hidden["files"].get(member)
    if text is None:
        data = bundle.members.get(member)
        if data is None:
            return None
        text = data.decode("utf-8")
    try:
        return Kept.from_text(text)
    except (ValueError, TypeError, KeyError):
        return None


def keep(bundle, prefix, found, hidden=False):
    """
    Keep restarts with the run under ``prefix`` (the latest run, or a committed one):
    hidden whole while anything of the run is hidden.

    Generated by RJC and Claude.
    """
    member = prefix + MEMBER
    text = found.to_text()
    bundle.members.pop(member, None)
    bundle.hidden["files"].pop(member, None)
    if hidden:
        bundle.hidden["files"][member] = text
    else:
        bundle.members[member] = text.encode("utf-8")


def anything_hidden(view):
    """Whether any value of a run is hidden (its restarts are then kept hidden)."""
    gate = view.gate
    if gate.global_blind:
        return True
    return any(gate.masked(p) for p in view.model.parsed.params if p.index >= 0)


# -- The assessment (convergence.assess_restarts) -------------------------------------------


@dataclass
class Assessment:
    """
    The restarts assessed (S21): a row per free parameter, and ALIS's summary.

    Attributes
    ----------
    rows : list of tuple
        ``(index, name, best, sigma, metric, passed)``: ``best`` through the gate,
        ``metric`` the largest |Δ|/σ (or the scatter over σ), unsigned.
    converged : bool or None
    failed, free : int
    summary : str
        ALIS's line of summary ("CONVERGED -- all 41 free parameters agree within
        3.0 sigma across restarts.").
    report : str
        ALIS's whole report (``<model>.converge``).
    better : list of int
        The restarts (numbered from 1) that reach a lower χ² than the run, best
        first.

    Generated by RJC and Claude.
    """

    rows: list
    converged: object
    failed: int
    free: int
    summary: str
    report: str
    better: list = field(default_factory=list)


def names(view):
    """
    Each parameter's name, by ALIS's number: its ion, component and parameter, with
    its label ("O I a1 log N [da]"); "parameter 7" for one the table does not list.

    Generated by RJC and Claude.
    """
    out = {}
    try:
        groups = view.table()
    except RS.ResultsError:
        groups = []
    for group in groups:
        for row in group.rows:
            label = row.param.label
            out[row.param.index] = row.name + (" [" + label + "]" if label else "")
    return out


def _metric(column, best, sigma, test):
    if test == "scatter":
        return float(np.std(column) / sigma)
    return float(np.max(np.abs(column - best)) / sigma)


def assess(view, found, prefs=None):
    """
    The restarts of a run assessed as ``convergence.assess_restarts`` assesses them:
    for every free parameter (σ > 0), the largest |Δ|/σ across the restarts (``sim
    convergetest maxdev``) or their scatter over σ (``scatter``), passed within ``sim
    convergesig``; and ALIS's own report and summary.

    Generated by RJC and Claude.
    """
    done = [r for r in found.restarts if r.values]
    settings = found.settings
    test = str(settings.get("convergetest", "maxdev")).lower()
    xsig = float(settings.get("convergesig", 3.0))
    best = np.asarray(found.best, dtype=float)
    perror = np.asarray(found.perror, dtype=float)
    labels = names(view)
    rows = []
    if done:
        matrix = np.array([r.values for r in done], dtype=float)
        for j in np.where(perror > 0.0)[0]:
            metric = _metric(matrix[:, j], best[j], perror[j], test)
            par = _param(view, int(j))
            shown = (
                BL.MASK
                if par is not None and view.gate.masked(par)
                else "{0:.8g}".format(best[j])
            )
            rows.append(
                (
                    int(j),
                    labels.get(int(j), "parameter {0}".format(j)),
                    shown,
                    float(perror[j]),
                    metric,
                    metric <= xsig,
                )
            )
    converged, failed, free, report = _alis_assessment(
        view, done, best, perror, settings
    )
    summary = ""
    for line in report.splitlines():
        if line.startswith("# Result:"):
            summary = line[len("# Result:") :].strip()
    better = []
    if found.chi2 is not None:
        lower = [
            (r.chi2, n + 1)
            for n, r in enumerate(found.restarts)
            if r.chi2 is not None
            and r.chi2 < found.chi2 - 1.0e-6 * max(1.0, found.chi2)
        ]
        better = [n for _, n in sorted(lower)]
    if failed is None:
        failed = sum(1 for r in rows if not r[5])
        free = len(rows)
        converged = None if not done else failed == 0
    return Assessment(rows, converged, failed, free, summary, report, better)


def _param(view, index):
    for par in view.model.parsed.params:
        if par.index == index:
            return par
    return None


def _alis_assessment(view, done, best, perror, settings):
    """ALIS's own assessment (``convergence.assess_restarts``), in memory."""
    if len(done) < 2:
        return None, None, None, ""
    stub = types.SimpleNamespace()
    stub._outputs = outputs.MemoryOutputs()
    stub._argflag = {
        "sim": {
            "convergetest": settings.get("convergetest", "maxdev"),
            "convergesig": settings.get("convergesig", 3.0),
            "newstart": True,
        },
        "out": {"verbose": -1, "modelname": "restarts"},
        "run": {"modname": view.model.bundle.model_name},
    }
    matrix = np.array([r.values for r in done], dtype=float)
    with contextlib.redirect_stdout(io.StringIO()), M.alis_quietly():
        found = convergence.assess_restarts(stub, matrix, best, perror)
    report = stub._outputs.files.get("restarts.converge", b"").decode("utf-8")
    # The draws do not fit fresh noise: ALIS's note on that is not for these
    report = "\n".join(
        line for line in report.splitlines() if not line.startswith("# Starts drawn")
    )
    if found is None:
        return None, None, None, report
    converged, failed, free = found
    return converged, failed, free, report


# -- Export restarts… (Q6.18(b, c)) ----------------------------------------------------------


def export_text(view, found):
    """
    The restarts as ``sim perturb`` writes its own (``<model>.perturb_0-10``): one row
    per fit, the first the run's best fit (where they started from), then each
    restart's best fit; every parameter by ALIS's number, and χ² as the last column;
    a header, in ``#`` lines, naming each column. A hidden parameter's columns are
    left out, and the header says so.

    Returns
    -------
    str

    Generated by RJC and Claude.
    """
    labels = names(view)
    size = len(found.best)
    hidden = set()
    for par in view.model.parsed.params:
        if 0 <= par.index < size and view.gate.masked(par):
            hidden.add(par.index)
    columns = [i for i in range(size) if i not in hidden]
    lines = [
        "# The random restarts of {0}, in the form of sim perturb's output: the first"
        " row is the run's best fit, where they started from; then one row per"
        " restart, its best fit.".format(view.name),
        "# Draws as sim perturb after sim beginfrom: about the best fit, from its"
        " covariance, within ±{0:g} of each value and the limits.".format(
            float(found.settings.get("maxperturb", 0.1))
        ),
    ]
    if hidden:
        lines.append(
            "# {0} hidden parameter{1} left out (blinded): ALIS's numbers {2}.".format(
                len(hidden),
                "" if len(hidden) == 1 else "s",
                ", ".join(str(i) for i in sorted(hidden)),
            )
        )
    lines.append("# Columns:")
    for n, i in enumerate(columns):
        lines.append(
            "#   {0:d}: {1} (ALIS parameter {2:d})".format(
                n + 1, labels.get(i, "parameter {0}".format(i)), i
            )
        )
    lines.append("#   {0:d}: chi2".format(len(columns) + 1))
    rows = [(found.best, found.chi2)]
    rows += [(r.values, r.chi2) for r in found.restarts if r.values]
    for values, chi2 in rows:
        cells = ["{0:.10e}".format(float(values[i])) for i in columns]
        cells.append("{0:.10e}".format(float("nan") if chi2 is None else chi2))
        lines.append(" ".join(cells))
    return "\n".join(lines) + "\n"


def export_name(view, found):
    """``<model>.perturb_0-10``, as sim perturb names its file."""
    model = view.model.bundle.model_name
    stem = model[: -len(".mod")] if model.endswith(".mod") else model
    count = len([r for r in found.restarts if r.values])
    width = int(math.log10(max(count, 1))) + 1
    return "{0}.perturb_{1:0{3}d}-{2:0{3}d}".format(stem, 0, count, width)


# -- Running them -------------------------------------------------------------------------


def taker(view, starts, settings):
    """
    What keeps a restarts job's results (``runs.Restarts``'s ``taker``): with the run
    they started from, in the session's bundle (saved with Save), and with its
    committed copy when the latest run is committed; hidden whole while anything of
    the run is hidden. Nothing is kept when that run has gone meanwhile.

    Generated by RJC and Claude.
    """
    record = view.record
    found = new_kept(view, settings)
    hidden = anything_hidden(view)
    registry = view.project.registry
    finished = record.info.get("finished")

    def take(session, job):
        bundle = session.project.bundle
        try:
            now = (
                R.latest(bundle)
                if record.number is None
                else R.run_of(bundle, record.number)
            )
        except R.RunError:
            now = None
        if now is None or now.info.get("finished") != finished:
            return False
        for number, info, mod_out, covar, _ in sorted(job.results, key=lambda r: r[0]):
            found.restarts.append(
                result_of(starts[number - 1], info, mod_out, covar, registry)
            )
        if not found.restarts:
            return False
        found.finished = B.now()
        keep(bundle, now.prefix, found, hidden)
        if now.latest and now.committed_as is not None:
            keep(bundle, R._prefix(now.committed_as), found, hidden)
        session.runs_changed()
        return True

    return take


# -- Continuing from a restart -------------------------------------------------------------


def restart_view(view, found, number):
    """
    A view of restart ``number`` (from 1), for Continue from best fit: the run's
    view with that restart's best fit.

    Generated by RJC and Claude.
    """
    restart = found.restarts[number - 1]
    out = copy.copy(view)
    out.values = {i: float(v) for i, v in enumerate(restart.values)}
    out.errors = None
    out.texts = {}
    out._curves = None
    out.label = "restart {0} of {1}".format(number, view.name)
    return out


