"""The fitting process: a project run by ALIS in memory (dashboard Stage 6.1).

Run as ``python -m alis.dashboard.runner`` by :class:`alis.dashboard.runs.Process`
(F6; Q6.14, Q6.15, Q6.19). It is the dashboard's own ``run_alis project.model``:

- **What it is handed** on its standard input: one line of JSON (the header: the
  project's file, if it has one, the settings given on the command line, the
  command recorded in ``run.json``, and the size of what follows), then the
  project's bytes, as Save would write them but never written to a file
  (``bundle.to_bytes``). Lines after that are commands: ``stop``.
- **The run**, all in memory, as ``run_alis project.model`` runs a bundle
  (``bundle.execute``): the data, the atomic table, and the hidden lines restored
  in memory only.
- **What it sends** on its standard output, one line of JSON per message:
  ``started``; ``iteration`` after each iteration of the fit, with its χ², degrees
  of freedom and parameter values, from ALIS's per-iteration hook (Q6.19(b));
  ``warning``; ``storing``; ``runs`` (the run itself, for a project with no file);
  and ``finished``, with the run's status. ALIS's own printout goes nowhere, and its
  messages pass the bundle's mask of hidden lines.
- **Stop:** the ``stop`` command ends the fit at its current iteration, as
  ``Ctrl+\\`` does (status −20, "interrupted"), and the run is kept.
- **Where the result goes** (Q6.14(b)): into the project's file, under its lock,
  as ``run_alis project.model`` stores a run (``bundle.store``); or, for a project
  with no file (or a file that cannot be written), back to the dashboard as a
  ``runs`` message. A run whose dashboard has closed carries on, and stores its
  result in the file all the same.

Generated by RJC and Claude.
"""

import argparse
import base64
import json
import logging
import os
import sys
import threading
import time
import traceback

PROTOCOL = 1
STOP = b"stop"
UI_JSON = "ui/project.json"


def _plain(value):
    """A number or array from numpy, as JSON writes it."""
    if hasattr(value, "tolist"):
        return value.tolist()
    return str(value)


class Channel:
    """
    The messages to the dashboard, one line of JSON each. Once the dashboard has
    gone (its end of the pipe closed), nothing more is sent and the run goes on.

    Generated by RJC and Claude.
    """

    def __init__(self, fd):
        self._out = os.fdopen(fd, "w", encoding="utf-8")
        self._lock = threading.Lock()
        self.lost = False

    def send(self, event, **fields):
        if self.lost:
            return
        fields["event"] = event
        line = json.dumps(fields, default=_plain)
        with self._lock:
            try:
                self._out.write(line + "\n")
                self._out.flush()
            except (OSError, ValueError):
                self.lost = True


class Commands(threading.Thread):
    """
    The commands that follow the project on the standard input: ``stop``.

    Generated by RJC and Claude.
    """

    def __init__(self, stream):
        super().__init__(daemon=True)
        self._stream = stream
        self.stop = False

    def run(self):
        try:
            for line in self._stream:
                if line.strip() == STOP:
                    self.stop = True
        except (OSError, ValueError):
            pass


class _Warnings(logging.Handler):
    """
    ALIS's warnings, sent to the dashboard after the bundle's mask; and its last
    error, which ends the run.

    Generated by RJC and Claude.
    """

    def __init__(self, channel):
        super().__init__(level=logging.WARNING)
        self._channel = channel
        self.error = ""

    def emit(self, record):
        if record.levelno >= logging.CRITICAL:
            self.error = record.getMessage()
        elif record.levelno >= logging.WARNING:
            self._channel.send("warning", message=record.getMessage())


def _masked(message, store):
    """A message with the model's hidden lines masked, as ALIS's own are."""
    from alis import bundle as B

    record = logging.LogRecord("alis", logging.ERROR, "", 0, message, (), None)
    B._MaskHidden(store).filter(record)
    return record.getMessage()


def _read_exactly(stream, size):
    data = stream.read(size)
    if data is None or len(data) != size:
        raise EOFError("The project was not handed over whole.")
    return data


class Job:
    """
    One run of a project handed over through the standard input.

    Generated by RJC and Claude.
    """

    def __init__(self, header, data, channel, commands):
        self.header = header
        self.data = data
        self.channel = channel
        self.commands = commands
        self.progress = []
        self.convergence = []
        self.start = time.time()

    def hook(self, iteration, chi2, values, dof, convtest):
        """ALIS's per-iteration hook (Q6.19(b)): report, and say whether to stop."""
        point = [int(iteration), float(chi2)]
        (self.convergence if convtest else self.progress).append(point)
        self.channel.send(
            "iteration",
            iteration=int(iteration),
            chi2=float(chi2),
            dof=int(dof),
            values=[float(v) for v in values],
            convtest=bool(convtest),
            elapsed=round(time.time() - self.start, 3),
        )
        return self.commands.stop

    def _settings(self):
        """The settings: the defaults, then those given on the command line."""
        from alis import load

        overrides = []
        lines, verbose = [], None
        for line in self.header.get("settings", []):
            words = line.split()
            # ALIS takes the verbosity as run_alis -v gives it, not through --set
            if words[:2] == ["out", "verbose"] and len(words) == 3:
                verbose = int(words[2])
            else:
                lines.append(line)
        argv = argparse.Namespace(set=lines, verbose=verbose)
        argflag = load.optarg(argv=argv, overrides=overrides, verbose=-1)
        return argflag, overrides

    def _store(self, bundle, result):
        """Store the result in the project's file, or send it back."""
        from alis import bundle as B

        path = self.header.get("path")
        if path:
            try:
                B.store(path, result)
                return "file"
            except (B.BundleError, OSError) as err:
                self.channel.send(
                    "warning",
                    message="The run could not be stored in the project's file, so"
                    " the dashboard keeps it until the project is saved: " + str(err),
                )
        for member in [m for m in bundle.members if m.startswith(B.RUNS)]:
            del bundle.members[member]
        B.store(bundle, result)
        runs = {
            m: base64.b64encode(c).decode("ascii")
            for m, c in bundle.members.items()
            if m.startswith(B.RUNS)
        }
        hidden = {
            kind: {m: v for m, v in bundle.hidden[kind].items() if m.startswith(B.RUNS)}
            for kind in ("lines", "files")
        }
        self.channel.send("runs", members=runs, hidden=hidden)
        return "memory"

    def run(self):
        """Run the project, store its result, and report how it ended."""
        from alis import bundle as B
        from alis import logger

        msgs = logger.msgs()
        started = B.now()
        store = {}
        bundle = None
        warnings = _Warnings(self.channel)
        msgs.addHandler(warnings)
        command = self.header.get("command") or "alis (dashboard)"
        try:
            bundle = B.read(self.data)
            store = bundle.hidden_model_lines()
            argflag, overrides = self._settings()
            self.channel.send("started", pid=os.getpid(), time=started)
            result = B.execute(
                bundle, argflag, overrides, command, iterhook=self.hook, started=started
            )
        except (Exception, SystemExit) as err:
            message = (
                warnings.error
                or "".join(traceback.format_exception_only(type(err), err)).strip()
            )
            result = B.RunResult(
                info={},
                error={
                    "time": B.now(),
                    "message": _masked(message, store),
                    "command": command,
                },
            )
        finally:
            msgs.removeHandler(warnings)
        if result.keeps_latest:
            final = result.info.get("chi2_final"), result.info.get("iterations")
            if None not in final and (
                not self.progress or self.progress[-1][0] < final[1]
            ):
                self.progress.append([int(final[1]), float(final[0])])
            result.info["origin"] = "dashboard"
            result.info["progress"] = self.progress
            if self.convergence:
                result.info["convergence_progress"] = self.convergence
            if bundle is not None and UI_JSON in bundle.members:
                result.inputs[UI_JSON] = bundle.members[UI_JSON]
        self.channel.send("storing")
        stored = None
        if bundle is not None or self.header.get("path"):
            if bundle is None:
                bundle = B.Bundle()
            stored = self._store(bundle, result)
        if result.error is not None:
            status = "error"
        elif result.exit is not None:
            status = "stopped"
        else:
            status = result.info.get("status", "completed")
        info = result.info
        self.channel.send(
            "finished",
            status=status,
            message=(result.error or {}).get("message", ""),
            chi2=info.get("chi2_final"),
            dof=info.get("dof"),
            iterations=info.get("iterations"),
            stored=stored,
            model_sha256=info.get("model_sha256"),
        )
        return 0


def main():
    """
    The fitting process (``python -m alis.dashboard.runner``).

    Generated by RJC and Claude.
    """
    # The messages go to the original standard output; ALIS's own printout, and
    # anything else written to it or to the standard error, goes nowhere, so that
    # a dashboard that has closed cannot stop the fit by a broken pipe
    channel = Channel(os.dup(1))
    quiet = os.open(os.devnull, os.O_WRONLY)
    os.dup2(quiet, 1)
    os.dup2(quiet, 2)
    os.environ["MPLBACKEND"] = "Agg"
    stdin = sys.stdin.buffer
    try:
        header = json.loads(stdin.readline().decode("utf-8"))
        if header.get("protocol") != PROTOCOL:
            raise ValueError("The dashboard and its fitting process differ in version.")
        data = _read_exactly(stdin, int(header["size"]))
    except (OSError, ValueError, KeyError, EOFError) as err:
        channel.send("finished", status="error", message=str(err), stored=None)
        return 1
    commands = Commands(stdin)
    commands.start()
    return Job(header, data, channel, commands).run()


if __name__ == "__main__":
    sys.exit(main())
