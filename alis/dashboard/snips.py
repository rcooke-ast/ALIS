"""Snips: SNIP and CLEAR, regions and masks, edges, copying, buffers, shared pixels.

Dashboard Stage 4.2 (S6, S7, S26, D18, D19; Q0.6, Q2.7, Q2.10, Q4.2, Q4.3, Q4.9,
Q4.11, Q4.15, Q4.17). No Qt: the Regions tab asks this module for every step, and
gives it to the history.

- **SNIP** (Q0.6, Q4.2) cuts one transition from every file row whose source
  spectrum covers it: the source's pixels within ± a half-width (300 km/s, a
  preference) of the transition, as a starting extent the user then moves. A snip is
  written in ``prepfit``'s four-column format at full precision, with a fifth
  ``badpix`` column when its source has a bad-pixel mask (Q4.17). It has no fit region
  until one is drawn. Its data line follows the row's resolution and shift; its
  continuum is the first guess (``continuum.py``); its specid is added to every
  absorption line whose transition falls in it (Q4.3). One step.
- **CLEAR** removes a snip, as ``remove.plan_snip`` plans it, with its record in
  ``ui/project.json``. One step.
- **Regions and masks** (S6, S7): a region is added, moved or removed, and pixels are
  masked by hand; a pixel that cannot be fitted (bad, NaN, an error ≤ 0) never is.
- **Edges** (S6, Q2.7, Q4.9(a)): moving an edge inwards keeps the lines that stay;
  moving one outwards keeps the old lines byte for byte and adds the source's pixels
  at full precision.
- **Copying regions** (D18) to the same transition in other rows, moved by the
  difference of their shifts.
- **The buffer** a snip has beyond its fitted pixels, against what its resolution
  needs (``getminmax``, as ALIS and the validator compute it).
- **Pixels fitted twice** (S26, D19, ``load.find_shared_pixels``) and their fixes:
  keep them in one snip only, or merge the snips (Q4.9: their lines kept, as one file
  in order of wavelength; the first snip's specid kept and the second's replaced in
  every line; always confirmed).

Every step is made on the project, read, and taken back, so that what it returns is
one step whose parts each saw the model as the parts before it left it.

Generated by RJC and Claude.
"""

