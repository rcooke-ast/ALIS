def strips(project, system, line, spectra, snip_map=None):
    """
    The datasets the Regions tab shows a transition in (D36): every row with a snip of
    it, and every row whose source spectrum has pixels there, in the rows' order.

    Returns
    -------
    list of tuple
        ``(row, snip or None)``.

    Generated by RJC and Claude.
    """
    have = snips_of(project, system.id, line.ion, line.rest, snip_map)
    out = []
    for row in project.rows:
        if row.id in have:
            out.append((row, have[row.id]))
            continue
        spec = spectra.get(row.id)
        if spec is None:
            continue
        cov = L.Coverage(row.id, row.name, spec.wave, np.isfinite(spec.wave))
        obs = line.rest * (1.0 + system.z) * (1.0 + row_shift(row) / C_KMS)
        if L.place(obs, [cov], half_width=0.0)[0]:
            out.append((row, None))
    return out


def summary(project, snip):
    """
    The Snip box's figures (S6): extent, pixels, fitted pixels and regions, and the
    buffers.

    Returns
    -------
    dict
        ``extent``, ``npix``, ``nfit``, ``nregions``, ``buffers``.

    Generated by RJC and Claude.
    """
    pix = snip.pixels
    if pix is None:
        return {"extent": None, "npix": 0, "nfit": 0, "nregions": 0, "buffers": []}
    mask = fitted(snip)
    return {
        "extent": snip.extent,
        "npix": int(pix.wave.size),
        "nfit": int(np.count_nonzero(mask)),
        "nregions": len(P.mask_regions(pix.wave, mask)),
        "buffers": buffers(project, snip),
    }


def transition_name(trans):
    """A snip's transition as people write it (``Ly8 923.2``), or ``""``."""
    if trans is None:
        return ""
    return L.line_name(*_named(trans))


def shared_text(pairs, snip, snip_map):
    """
    What the Snip box says of pixels fitted twice (D19, S26): "36 fitted pixels are
    also fitted by other snips (18 with Ly8 923.2, 18 with Ly6 930.7)."

    Generated by RJC and Claude.
    """
    if not pairs:
        return ""
    total = 0
    parts = []
    for pair in pairs:
        other = pair.other(snip)
        count = pair.count
        total += count
        name = transition_name(snip_map.get(other.specid)) or other.specid
        parts.append("{0} with {1}".format(count, name))
    return (
        "{0} fitted pixel{1} {2} also fitted by other snips ({3}). Each pixel should"
        " enter χ² once.".format(
            total,
            "" if total == 1 else "s",
            "is" if total == 1 else "are",
            ", ".join(parts),
        )
    )


def same_pairs(project, snip, pair, snip_map=None):
    """
    The same overlap in the other datasets (for "Apply the fix to all datasets"):
    the pairs of snips of the same two transitions, in every other row, that share
    pixels.

    Returns
    -------
    list of tuple
        ``(snip, Shared)``: in each other row, its snip of this transition and the
        pair.

    Generated by RJC and Claude.
    """
    snip_map = L.snip_transitions(project) if snip_map is None else snip_map
    mine = snip_map.get(snip.specid)
    theirs = snip_map.get(pair.other(snip).specid)
    if mine is None or theirs is None:
        return []
    out = []
    for row in project.rows:
        if snip.row is not None and row.id == snip.row.id:
            continue
        one = snips_of(project, mine.system, mine.ion, mine.rest, snip_map).get(row.id)
        two = snips_of(project, theirs.system, theirs.ion, theirs.rest, snip_map).get(
            row.id
        )
        if one is None or two is None:
            continue
        for found in shared_pixels(project, one):
            if found.other(one).specid == two.specid:
                out.append((one, found))
    return out


def keep_all_step(project, snip, also=()):
    """
    "Keep them in this snip only", in this dataset and in the others with the same
    overlap (``same_pairs``), as one step (D19).

    Generated by RJC and Claude.
    """
    names = [snip.specid] + [one.specid for one, _ in also]
    makers = [lambda proj, n=name: keep_step(proj, proj.snip(n)) for name in names]
    count = sum(p.count for p in shared_pixels(project, snip))
    count += sum(pair.count for _, pair in also)
    where = "" if not also else " in {0} datasets".format(len(names))
    return compose(
        project,
        "Keep {0} shared pixels in one snip only{1}".format(count, where),
        makers,
    )


def merge_all_plan(project, a, b, also=(), spectra=None, **kwargs):
    """
    "Merge the snips…", in this dataset and in the others with the same overlap
    (``same_pairs``): one plan, whose preview is this dataset's, and one step (D19,
    Q4.9).

    Parameters
    ----------
    spectra : dict, optional
        Row id to source spectrum, to fill a gap between snips that do not overlap.

    Generated by RJC and Claude.
    """
    spectra = spectra or {}

    def spec_of(snip):
        return spectra.get(snip.row.id) if snip.row is not None else None

    first = merge_plan(project, a, b, spec_of(a), **kwargs)
    if not also:
        return first
    pairs = [(a.specid, b.specid, spec_of(a))]
    for one, pair in also:
        pairs.append((one.specid, pair.other(one).specid, spec_of(one)))
    makers = [
        lambda proj, x=x, y=y, sp=sp: merge_plan(
            proj, proj.snip(x), proj.snip(y), sp, **kwargs
        ).step
        for x, y, sp in pairs
    ]
    description = "Merge {0} into {1} in {2} datasets".format(
        first.replaced, first.keep, len(pairs)
    )
    step = compose(project, description, makers)
    plan = R.Plan(
        description,
        first.plan.lines,
        [],
        None,
        first.plan.notes
        + [
            "The same merge is made in {0} other dataset{1}: {2}.".format(
                len(also),
                "" if len(also) == 1 else "s",
                ", ".join("{0} into {1}".format(y, x) for x, y, _ in pairs[1:]),
            )
        ],
        None,
    )
    return MergePlan(description, first.keep, first.replaced, plan, step)


def origin(project, snip):
    """
    Where a snip's regions came from (D18): ``drawn here``, ``copied from HIRES``, or
    ``no regions``.

    Generated by RJC and Claude.
    """
    if snip.pixels is None or not fitted(snip).any():
        return "no regions"
    record = project.ui.get(SNIPS, {}).get(snip.specid, {})
    if record.get("copied_from"):
        return "copied from " + record["copied_from"]
    return "drawn here"


