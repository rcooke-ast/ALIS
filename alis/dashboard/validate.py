"""The validator: problems with a model, each placed on its line (F5, Stage 2.6).

The model is checked at two levels.

- **At every keystroke**, :func:`quick` checks what can be checked from the parsed
  model, and from the snips' pixels:

  - the block structure;
  - unknown functions and ions;
  - a ``1e4``-style label, which ALIS reads as the value 1 with the label ``e4``;
  - a ``specid`` with no data line, or with no continuum;
  - tied labels given different starting values (``ALIS_workflow.md`` §2.5);
  - a fitrange with no pixels;
  - a buffer narrower than the convolution needs.

- **After a pause**, :func:`full` runs ALIS's own loaders on a copy of the model, with
  the data in memory (Stage 1.2): the settings, the data, the model, the links, the
  parameters, their influence and the sub-pixel grid. A filter on the ``alis`` logger
  collects ALIS's warnings and errors and keeps them off the terminal; the exit of
  ``msgs.error`` is caught (Q2.5). An unexpected exception writes its traceback to
  the terminal, and is reported as an unexpected error (RJC, Q2.5).

Each problem has a line (None for the model as a whole), a severity (``"error"`` or
``"warning"``) and a message. No message refers to the design documents (D44).

Generated by RJC and Claude.
"""

import hashlib
import logging
import posixpath
import re
import traceback
from types import SimpleNamespace

import numpy as np

from alis import bundle as B
from alis import load, logger
from alis.config import ArgFlag
from alis.dashboard import model as M
from alis.dashboard import project as P
from alis.dashboard import text as T

msgs = logger.msgs()

ERROR = "error"
WARNING = "warning"
C_KMS = 299792.458
UNEXPECTED = (
    "The ALIS dashboard has encountered an unexpected error while checking"
    " the model. The terminal window shows the details."
)
# ALIS's warnings that do not apply in the dashboard: a blind project still keeps its
# best-fit outputs, hidden in the bundle (Stage 1.6)
IGNORED = ("For a blind analysis",)
_PIXELS = {}
# The messages of the checks (no design-document references, D44)
EXPONENT = (
    "'{0}' is read by ALIS as the value {1} with the label '{2}', not as a"
    " number. Write the exponent with a sign ({1}E+{3}), or rename the label."
)
NO_DATA = "There is no data line with specid '{0}'."
NO_CONTINUUM = "Specid '{0}' has no continuum: no emission model applies to it."
TIED_VALUES = (
    "'{0}' is also used on line {1} with the value {2}. ALIS starts every"
    " '{0}' at {2}, so the {3} written here is not used."
)
NO_PIXELS = "The fitted range holds no pixels of this data line's file."
BUFFER = (
    "On its {0} side, this snip has {1:.1f} km/s of data beyond the fitted"
    " pixels, but the instrumental resolution needs {2:.1f} km/s. The model may"
    " be wrong near the edge of the fit: widen the snip."
)
UNSUPPORTED = "The dashboard cannot run this model as it is: {0}."


def _problem(line, severity, message):
    return T.Problem(line, severity, message, "check")


# -- The checks made at every keystroke --------------------------------------------


def _exponent_labels(pm):
    """
    A label that is ``e`` or ``E`` followed by digits: ALIS reads ``1e4`` as the value
    1 with the label ``e4`` (``alis.functions.base.check_tie_label``).

    Generated by RJC and Claude.
    """
    out = []
    words = []
    for item in pm.lines:
        words += [tok for tok in item.tokens if "=" not in tok.text]
        if item.function in pm.registry.names:
            parid = pm.registry.function(item.function)._parid
            words += [kw.val for name, kw in item.keywords.items() if name in parid]
    for item in pm.data:
        for call in (item.resolution, item.shift):
            if call is not None:
                words += call.args
    for tok in words:
        if not M.is_number(tok.text) and tok.text[:1] not in "+-.0123456789":
            continue
        value, label = T.split_value(tok)
        if label is not None and label.text[:1] in "eE" and label.text[1:].isdigit():
            out.append(
                _problem(
                    tok.line,
                    ERROR,
                    EXPONENT.format(tok.text, value.text, label.text, label.text[1:]),
                )
            )
    return out


def _covers(item, specid, single):
    """Whether a model line applies to a specid."""
    return specid in item.specids or (single and not item.specids)


def _specids(pm):
    """
    A specid that a model line names but no data line has, and a specid that no
    emission model (continuum) covers.

    Generated by RJC and Claude.
    """
    out = []
    data = set(pm.specids)
    single = len(pm.specids) == 1
    for item in pm.lines:
        for sid in item.specids:
            if sid not in data:
                out.append(_problem(item.line, ERROR, NO_DATA.format(sid)))
    emission = [ln for ln in pm.lines if ln.section == "emission"]
    for item in pm.data:
        if not any(_covers(ln, item.specid, single) for ln in emission):
            out.append(_problem(item.line, ERROR, NO_CONTINUUM.format(item.specid)))
    return out


def _tied_values(pm):
    """
    Places of one label written with different values: ALIS starts the parameter at
    the first and ignores the others (``ALIS_workflow.md`` §2.5).

    Generated by RJC and Claude.
    """
    out = []
    for label in pm.labels.values():
        if label.linked or len(label.params) < 2:
            continue
        first = label.params[0]
        if first.written is None:
            continue
        for par in label.params[1:]:
            if par.written is not None and par.written != first.written:
                out.append(
                    _problem(
                        par.line,
                        WARNING,
                        TIED_VALUES.format(
                            label.name,
                            first.line + 1,
                            first.value_token.text,
                            par.value_token.text,
                        ),
                    )
                )
    return out


def _pixels_of(item, content):
    """The pixels of a data line's file, read once for each content."""
    key = (hashlib.sha1(content).hexdigest(), item.keyword("columns"))
    if key not in _PIXELS:
        if len(_PIXELS) > 2000:
            _PIXELS.clear()
        _PIXELS[key] = P.read_snip(content, item)
    return _PIXELS[key]


def _fitted(item, pixels):
    """The pixels a data line fits, as a boolean array, or None if unknown."""
    form = item.fitrange
    if form is None:
        return None
    if form[0] == "all":
        return np.ones(pixels.wave.size, dtype=bool)
    if form[0] == "range":
        return (pixels.wave >= form[1]) & (pixels.wave <= form[2])
    if pixels.mask is None:
        return None
    return pixels.mask != 0


def _buffer(pm, item, pixels, fitted):
    """
    The data beyond the fitted pixels that the convolution needs, from ALIS's own
    ``getminmax`` (as ALIS checks ``bufferpix``).

    Generated by RJC and Claude.
    """
    call = item.resolution
    if call is None or not call.args or call.name not in pm.registry.names:
        return None
    inst = pm.registry.function(call.name)
    wave = pixels.wave[fitted]
    span = [float(wave.min()), float(wave.max())]
    try:
        with M.alis_quietly():
            need = inst.getminmax([a.text for a in call.args], span)
    except Exception:
        return None
    low, high = float(pixels.wave.min()), float(pixels.wave.max())
    short = []
    if low > need[0] + 1.0e-9 * low:
        short.append(
            (
                "blue",
                C_KMS * (wave.min() - low) / wave.min(),
                C_KMS * (wave.min() - need[0]) / wave.min(),
            )
        )
    if high < need[1] - 1.0e-9 * high:
        short.append(
            (
                "red",
                C_KMS * (high - wave.max()) / wave.max(),
                C_KMS * (need[1] - wave.max()) / wave.max(),
            )
        )
    return short


def _data_checks(pm, data):
    """
    A fitrange with no pixels, and a buffer narrower than the convolution needs.

    Parameters
    ----------
    data : dict
        Each data file's bytes, by its path as ``load_data`` resolves it.

    Generated by RJC and Claude.
    """
    out = []
    for item in pm.data:
        key = load.memory_key(data, item.path(pm.datadirc))
        if key is None:
            continue
        pixels = _pixels_of(item, data[key])
        if pixels is None:
            continue
        fitted = _fitted(item, pixels)
        if fitted is None:
            continue
        if not fitted.any():
            out.append(_problem(item.line, ERROR, NO_PIXELS))
            continue
        for side, have, need in _buffer(pm, item, pixels, fitted) or []:
            out.append(_problem(item.line, WARNING, BUFFER.format(side, have, need)))
    return out


def quick(pm, data=None):
    """
    The checks made at every keystroke (F5).

    Parameters
    ----------
    pm : ParsedModel
    data : dict, optional
        Each data file's bytes, by its path as ``load_data`` resolves it (a bundle's
        ``data_for_run()``), for the checks of the pixels.

    Returns
    -------
    list of Problem
        In line order.

    Generated by RJC and Claude.
    """
    mine = []
    mine += _exponent_labels(pm)
    mine += _specids(pm)
    if pm.ok:
        mine += _tied_values(pm)
        if data is not None and not pm.argflag["generate"]["data"]:
            mine += _data_checks(pm, data)
    exponent_lines = {
        p.line for p in mine if "is read by ALIS as the value" in p.message
    }
    specid_lines = {
        p.line for p in mine if p.message.startswith("There is no data line")
    }
    theirs = []
    for prob in pm.problems:
        if prob.line in exponent_lines and "Ambiguous parameter" in prob.message:
            continue
        if prob.line in specid_lines and "There is no data with specid" in (
            prob.message
        ):
            continue
        theirs.append(prob)
    return order(theirs + mine)


def order(problems):
    """
    Problems without repeats, in line order (the whole model's first).

    Generated by RJC and Claude.
    """
    seen, out = set(), []
    for prob in problems:
        key = (prob.line, prob.severity, prob.message)
        if key not in seen:
            seen.add(key)
            out.append(prob)
    return sorted(
        out, key=lambda p: (-1 if p.line is None else p.line, p.severity != ERROR)
    )


# -- The full check, with ALIS's loaders -------------------------------------------


def unexpected(error=None):
    """
    Report an unexpected error: its traceback goes to the terminal, and the
    dashboard shows a short message (RJC, Q2.5).

    Returns
    -------
    Problem

    Generated by RJC and Claude.
    """
    detail = traceback.format_exc() if error is not None else ""
    msgs.bug(
        "The ALIS dashboard has encountered an unexpected error."
        + msgs.newline()
        + detail.rstrip().replace("\n", msgs.newline())
    )
    return T.Problem(None, ERROR, UNEXPECTED, "dashboard")


def _locate(pm, message):
    """
    The line of an ALIS message: a data file or a specid it names, the line it
    quotes, or the line of an ion whose isotope it names.

    Generated by RJC and Claude.
    """
    for item in pm.data:
        path = item.path(pm.datadirc)
        if path in message or posixpath.normpath(path) in message:
            return item.line
    num = pm._locate(message, (T.FIX, T.LIM, T.LINK))
    if num is not None:
        return num
    words = set(re.findall(r"[\w.]+", message))
    for item in pm.data:
        if "specid=" + item.specid in message:
            return item.line
    for item in pm.lines:
        ion = item.ion or ""
        if ion and (ion in words or ion.split("_")[0] in words):
            return item.line
    return None


def full(text, data, registry, pm=None):
    """
    Run ALIS's own loaders on a copy of the model, with its data in memory.

    Parameters
    ----------
    text : str
        The model, its hidden lines restored.
    data : dict
        Each data file's bytes, by its path as ``load_data`` resolves it.
    registry : Registry
        ALIS's functions and the project's atomic data.
    pm : ParsedModel, optional
        The text, parsed (to place the messages); read again if not given.

    Returns
    -------
    list of Problem

    Generated by RJC and Claude.
    """
    pm = pm or M.ParsedModel(text, registry)
    problems = []
    state = SimpleNamespace(_argflag=ArgFlag())
    state._argflag["out"]["verbose"] = -1
    try:
        with M.alis_quietly() as notes:
            _, datlines, modlines, lnklines = load.load_input(
                state, textstr=text.splitlines(keepends=True)
            )
            for reason in B.unsupported(state._argflag, datlines):
                problems.append(_problem(None, WARNING, UNSUPPORTED.format(reason)))
            if not state._argflag["generate"]["data"]:
                state._atomic = registry.atomic
                state._funcarray = registry.instances()
                load.load_data(state, datlines, data=data)
                state._modpass = load.load_model(state, modlines)
                state._links = load.load_links(state, lnklines)
                state._modlines = modlines
                _, state._levadd = load.load_parinfo(state)
                load.load_par_influence(state, state._modpass["p0"])
                load.load_subpixels(state, state._modpass["p0"])
    except M.AlisStop as stop:
        problems.append(
            T.Problem(_locate(pm, stop.message), ERROR, M.plain(stop.message), "alis")
        )
    except Exception as error:
        return [unexpected(error)]
    for level, message in notes:
        if message.startswith(IGNORED):
            continue
        if level >= logging.WARNING and level < logging.CRITICAL:
            problems.append(
                T.Problem(_locate(pm, message), WARNING, M.plain(message), "alis")
            )
    return order(problems)


def check(project, include_full=True):
    """
    Every problem of a project's model: the quick checks, and the full check.

    Generated by RJC and Claude.
    """
    try:
        data = project.data_for_run()
        problems = quick(project.parsed, data)
        if include_full and not [p for p in problems if p.severity == ERROR]:
            problems += full(project.text, data, project.registry, project.parsed)
    except Exception as error:
        return [unexpected(error)]
    return order(problems)


