"""A snip's or a dataset's resolution: ALIS's functions, as the dashboard offers them.

Dashboard Stage 8, Task 8.8 (point 1; D14, D35, D83; Q8.6, Q8.7, Q8.8). No Qt.

ALIS has nine functions for a data line's ``resolution=``. The dashboard offers
those of one parameter or one file, and names the others:

- **a value** (typed with its unit, and badged free, fixed or tied): ``vfwhm``
  (FWHM in km/s), ``Afwhm`` (FWHM in Å) and ``vsigma`` (σ in km/s);
- **a file:** ``lsffile``, a kernel read from a text file, which is copied into the
  project (Q8.7). A file of several kernels is written with ``index:``, the first
  column by default, so that a fit gives the same result every time;
- **keywords** (Q8.8): ``lsf`` (HST's COS and STIS, through linetools, an optional
  dependency) and ``apod`` (an apodisation of the kind named), typed in one field as
  ALIS writes them;
- **several parameters:** ``voigtconv``, ``multivfwhm`` and ``lsfspline``, set in
  the ``.mod`` panel until they are fully supported.

This module knows the functions: the word each writes, the text a cell shows, the
checks of what is typed, and whether linetools is installed. The steps that write
them are ``datasets.resolution_step`` and ``datasets.snip_resolution_step``.

Generated by RJC and Claude.
"""

import importlib.util
import io
import math
import os
import posixpath
from dataclasses import dataclass

import numpy as np

from alis.dashboard import edit as E

C_KMS = 299792.458
# FWHM over σ, for a Gaussian
FWHM_SIGMA = 2.0 * math.sqrt(2.0 * math.log(2.0))

VALUE, FILE, KEYWORDS, SEVERAL = "value", "file", "keywords", "several"


@dataclass(frozen=True)
class Function:
    """
    One of ALIS's resolution functions, as the dashboard offers it.

    Attributes
    ----------
    name : str
        ALIS's name, as written on a data line.
    kind : str
        ``"value"``, ``"file"``, ``"keywords"`` or ``"several"``.
    what : str
        What it is, for the menu.
    unit : str
        The unit of its value (``"km/s"``, ``"Å"``), or ``""``.
    default : str
        The keywords it starts from (ALIS's own defaults).
    bins : str
        The bins ALIS needs for it (``bintype``): ``"km/s"``, ``"A"`` or ``"Hz"``.

    Generated by RJC and Claude.
    """

    name: str
    kind: str
    what: str
    unit: str = ""
    default: str = ""
    bins: str = "km/s"

    @property
    def offered(self):
        """Whether the Snip box and the Data tab can set it (not several
        parameters)."""
        return self.kind != SEVERAL


FUNCTIONS = (
    Function("vfwhm", VALUE, "FWHM in km/s", "km/s"),
    Function("Afwhm", VALUE, "FWHM in Å", "Å", bins="A"),
    Function("vsigma", VALUE, "σ in km/s", "km/s"),
    Function("lsffile", FILE, "a kernel from a file"),
    Function(
        "lsf",
        KEYWORDS,
        "HST COS or STIS",
        default="name:COS,grating:G130M,life_position:1,cen_wave:1309",
    ),
    Function("apod", KEYWORDS, "an apodisation", default="kind:uniform", bins="Hz"),
    Function("voigtconv", SEVERAL, "a Voigt profile"),
    Function("multivfwhm", SEVERAL, "several Gaussians"),
    Function("lsfspline", SEVERAL, "a spline"),
)
BY_NAME = {f.name: f for f in FUNCTIONS}

# What a user is told of a function of several parameters (Q8.8)
SEVERAL_NOTE = "{0} has several parameters: set them in the .mod panel"
# What a user is told of lsf where linetools is not installed (Q8.8's response)
LINETOOLS_MARK = "needs linetools"
LINETOOLS_NOTE = (
    "lsf needs linetools, which is not installed here. Install it with"
    " `pip install linetools`, then open the dashboard again."
)
# apod's kinds (alis/functions/apod.py)
APOD_KINDS = ("uniform", "hanning", "hamming", "bartlett", "blackmann", "welch", "new")
# What lsf needs for each instrument (alis/functions/lsf.py, linetools)
LSF_NEEDS = {
    "COS": ("grating", "life_position", "cen_wave"),
    "STIS": ("grating", "slit"),
}


class ResolutionError(Exception):
    """A resolution that cannot be written as asked."""


def function(name):
    """The :class:`Function` of a name, or None for one ALIS does not have."""
    return BY_NAME.get(name)


def linetools_installed():
    """Whether linetools, which ``lsf`` needs, can be imported here."""
    return importlib.util.find_spec("linetools") is not None


def needs_linetools(call):
    """Whether a resolution is ``lsf`` and linetools is not installed (Q8.8)."""
    return call is not None and call.name == "lsf" and not linetools_installed()


def keywords_of(call):
    """
    The keywords of a resolution, as written: ``"name:COS,grating:G130M"``, without
    its value when one is written first.

    Generated by RJC and Claude.
    """
    return ",".join(a.text for a in call.args if _key_value(a.text) is not None)


def _key_value(text):
    """``(key, value)`` of a keyword argument (``name:COS``), or None for a value."""
    key, sep, value = text.replace("=", ":", 1).partition(":")
    if not sep:
        return None
    return key.strip(), value.strip()


def keyword_dict(text):
    """The keywords of a field or a call, by name."""
    out = {}
    for part in text.split(","):
        pair = _key_value(part)
        if pair is not None:
            out[pair[0]] = pair[1]
    return out


def file_of(call):
    """The file an ``lsffile`` resolution names, as written, or None."""
    if call is None or call.name != "lsffile":
        return None
    return keyword_dict(keywords_of(call)).get("name") or None


def word(name, value=None, label="", keywords=""):
    """
    The word a data line's ``resolution=`` takes.

    Parameters
    ----------
    name : str
        The function.
    value : float, optional
        Its value, for a function of one value.
    label : str
        The value's label (upper case when it is fixed).
    keywords : str
        Its keywords, as ALIS writes them (``name:COS,grating:G130M``).

    Returns
    -------
    str
        ``vfwhm(7.0fwhm1)``, ``lsffile(name:../lsf/k.dat,index:0)``,
        ``apod(kind:uniform)``.

    Generated by RJC and Claude.
    """
    func = BY_NAME[name]
    if func.kind == VALUE:
        if value is None:
            raise ResolutionError("{0} needs a value.".format(name))
        return "{0}({1})".format(name, E.format_value(value) + (label or ""))
    return "{0}({1})".format(name, keywords.strip().strip(","))


def bins_patches(pm, item, name):
    """
    The patches that give a data line the bins its resolution function needs:
    ``bintype=A`` for ``Afwhm`` and ``bintype=Hz`` for ``apod`` where the model's
    ``run bintype`` is another, and none where it is the same (ALIS stops when they
    differ, as ``afwhm.py`` and ``vfwhm.py`` check).

    Generated by RJC and Claude.
    """
    func = BY_NAME.get(name)
    need = func.bins if func is not None else "km/s"
    default = pm.argflag["run"]["bintype"] or "km/s"
    have = item.keyword("bintype")
    if need == default:
        if have is None:
            return []
        return list(E.remove_keyword(pm, item, "bintype").patches)
    if have == need:
        return []
    return list(E.set_keyword(pm, item, "bintype", need).patches)


def convert(old, value, new, wave):
    """
    A value of one function of one value as another's (the menu's starting value):
    FWHM and σ in km/s, and a FWHM in Å at an observed wavelength. None when it
    cannot be converted.

    Generated by RJC and Claude.
    """
    if value is None or old not in ("vfwhm", "Afwhm", "vsigma"):
        return None
    kms = float(value)
    if old == "vsigma":
        kms *= FWHM_SIGMA
    elif old == "Afwhm":
        if not wave:
            return None
        kms = C_KMS * kms / float(wave)
    if new == "vfwhm":
        return kms
    if new == "vsigma":
        return kms / FWHM_SIGMA
    if new == "Afwhm" and wave:
        return kms * float(wave) / C_KMS
    return None


def describe(call, gate, par):
    """
    A resolution as the Data tab's cell and the Snip box show it: ``6.285 km/s``,
    ``0.042 Å``, ``σ 7.0 km/s``, ``file test_lsf.dat``, ``lsf name:COS,…``,
    ``apod kind:uniform``, or the name of a function of several parameters. Values
    go through the blinding gate (D24).

    Generated by RJC and Claude.
    """
    if call is None:
        return "—"
    func = BY_NAME.get(call.name)
    if func is None:
        return call.text
    if func.kind == VALUE:
        if par is None:
            return "—"
        text = gate.value(par) + " " + func.unit
        return "σ " + text if call.name == "vsigma" else text
    if func.kind == FILE:
        name = file_of(call)
        return "file " + (posixpath.basename(name) if name else "?")
    if func.kind == KEYWORDS:
        return "{0} {1}".format(call.name, keywords_of(call)).strip()
    return call.name + " (in the .mod panel)"


def check_keywords(registry, name, text):
    """
    The keywords typed for ``lsf`` or ``apod``, checked as ALIS reads them: each one
    the function takes (``registry``, the model's), and what the instrument or the
    kind needs (Q8.8).

    Returns
    -------
    str
        The keywords, tidied (``name:COS,grating:G130M``).

    Raises
    ------
    ResolutionError
        With the reason.

    Generated by RJC and Claude.
    """
    func = BY_NAME[name]
    parts = [p.strip() for p in text.split(",") if p.strip()]
    if not parts:
        raise ResolutionError(
            "{0} needs its keywords, such as {1}.".format(name, func.default)
        )
    pairs = []
    for part in parts:
        pair = _key_value(part)
        if pair is None or not pair[0] or not pair[1]:
            raise ResolutionError(
                "'{0}' is not a keyword: write key:value, such as {1}.".format(
                    part, func.default.split(",")[0]
                )
            )
        pairs.append(pair)
    keys = dict(pairs)
    known = set(_function_keywords(registry, name))
    for key, _ in pairs:
        if key not in known:
            raise ResolutionError(
                "{0} has no keyword '{1}': it takes {2}.".format(
                    name, key, ", ".join(sorted(known))
                )
            )
    if name == "apod":
        if keys.get("kind") not in APOD_KINDS:
            raise ResolutionError(
                "apod's kind is one of {0}.".format(", ".join(APOD_KINDS))
            )
    elif name == "lsf":
        inst = keys.get("name", "COS")
        if inst not in LSF_NEEDS:
            raise ResolutionError("lsf's name is COS or STIS.")
        missing = [k for k in LSF_NEEDS[inst] if k not in keys]
        if missing:
            raise ResolutionError(
                "lsf for {0} needs {1}.".format(inst, " and ".join(missing))
            )
    return ",".join("{0}:{1}".format(k, v) for k, v in pairs)


def _function_keywords(registry, name):
    """The keywords a function takes, but those of blinding."""
    inst = registry.function(name)
    return [
        k for k in inst._keywd if k not in ("blind", "blindseed", "blindrange", "input")
    ]


@dataclass
class Kernels:
    """
    An LSF file, read as ``lsffile`` reads it: its first column the wavelength
    offsets, then one kernel per column.

    Attributes
    ----------
    name : str
        The file's name.
    content : bytes
    count : int
        How many kernels it holds.
    fwhm : list of float
        Each kernel's FWHM in Å.

    Generated by RJC and Claude.
    """

    name: str
    content: bytes
    count: int
    fwhm: list


def read_kernels(path):
    """
    An LSF file chosen for ``lsffile``, read and checked as ALIS reads it.

    Raises
    ------
    ResolutionError
        When it cannot be read, with the reason.

    Generated by RJC and Claude.
    """
    name = os.path.basename(path)
    try:
        with open(path, "rb") as handle:
            content = handle.read()
    except OSError as error:
        raise ResolutionError("{0} cannot be read: {1}".format(name, error)) from None
    return parse_kernels(name, content)


def parse_kernels(name, content):
    """
    An LSF file's bytes (one chosen, or one the project holds), read and checked as
    ``lsffile`` reads them.

    Raises
    ------
    ResolutionError
        When they cannot be read, with the reason.

    Generated by RJC and Claude.
    """
    try:
        data = np.loadtxt(io.BytesIO(content), ndmin=2)
    except ValueError as error:
        raise ResolutionError("{0} cannot be read: {1}".format(name, error)) from None
    if data.shape[1] < 2 or data.shape[0] < 3:
        raise ResolutionError(
            "{0} needs a column of wavelength offsets (Å) and at least one column"
            " of kernel values, over three rows or more.".format(name)
        )
    if not np.all(np.isfinite(data)):
        raise ResolutionError("{0} holds values that are not numbers.".format(name))
    offsets = data[:, 0]
    if np.any(np.diff(offsets) <= 0.0):
        raise ResolutionError(
            "{0}'s first column (the wavelength offsets) must increase.".format(name)
        )
    widths = [_half_width(offsets, data[:, n]) for n in range(1, data.shape[1])]
    if not all(w > 0.0 for w in widths):
        raise ResolutionError("{0} has a kernel with no peak.".format(name))
    return Kernels(name, content, data.shape[1] - 1, widths)


def _half_width(offsets, kernel):
    """The full width at half maximum of one kernel, in the offsets' unit."""
    peak = float(np.max(kernel))
    if not peak > 0.0:
        return 0.0
    above = np.flatnonzero(kernel >= 0.5 * peak)
    return float(offsets[above[-1]] - offsets[above[0]]) or float(
        np.median(np.diff(offsets))
    )


def project_kernels(project, call):
    """The kernels of the LSF file an ``lsffile`` resolution names, as the project
    holds it, or None."""
    name = file_of(call)
    if name is None:
        return None
    content = project.data_for_run().get(os.path.normpath(name))
    if content is None:
        return None
    try:
        return parse_kernels(posixpath.basename(name), content)
    except ResolutionError:
        return None


def kernel_index(call):
    """The kernel an ``lsffile`` resolution names (``index:``), the first when it
    names none."""
    try:
        return max(int(keyword_dict(keywords_of(call)).get("index", 0)), 0)
    except ValueError:
        return 0


def kernel_kms(fwhm_a, wave):
    """A kernel's FWHM in Å as km/s at an observed wavelength."""
    return C_KMS * float(fwhm_a) / float(wave)


