"""The model of each snip, as ALIS computes it (dashboard Stage 5.1; S13, D24).

No Qt: the Components tab and the Regions tab's Model switch draw what this module
evaluates.

- **ALIS's own model.** A :class:`Profile` builds ALIS's state for the project in
  memory, as ``run_alis`` builds it up to the fit (``main.py``): the data, the model
  and its links, the parameter information, the influence of each parameter, the
  sub-pixels, and the links applied to the starting values. It evaluates the model
  with ``model_eval.model_func`` on every pixel ALIS loads, so what is drawn is what
  ALIS fits: the same atomic data, sub-pixellation and convolution.
- **Some snips only.** ``model_func`` evaluates only the snips its influence table
  names for the parameter it is given. The profile gives it a table of its own,
  naming the snips wanted, so that a drag evaluates the snips on the screen and no
  others.
- **Values from a drag.** :meth:`Profile.values` changes some parameters (by ALIS's
  numbers, :attr:`alis.dashboard.model.Param.index`) and applies the links, as ALIS
  does before an evaluation; :meth:`Profile.affected` names the snips whose model
  those changes reach (the lines that carry them or are linked to them, and, for a
  voigt line, the snips where one of its transitions falls before or after).
- **The pixels.** ALIS loads only the pixels its fit and convolution need, so a
  snip's model is placed on the snip's own pixels by wavelength, and is NaN where
  ALIS has none.
- **χ²** on the fitted pixels, summed as ALIS sums it.
- **Blinding (D24).** A blinded component's curve may be drawn, but nothing here
  returns a parameter's value: a :class:`Curve` holds the snip's pixels, the model
  and its χ², and an error names no value.

Generated by RJC and Claude.
"""

import re
import time
from dataclasses import dataclass
from types import SimpleNamespace

import numpy as np

from alis import load, model_eval
from alis.config import ArgFlag
from alis.dashboard import continuum as CO
from alis.dashboard import model as M

# The parameter number given to model_func to evaluate the snips of a table of our
# own: ALIS's parameters are numbered from 0
SELECTED = -1

_TIED = re.compile(r"p\[(\d+)\]")

_PROFILES = {}


class ProfileError(Exception):
    """ALIS cannot evaluate the model as it stands."""


@dataclass
class Curve:
    """
    The model of one snip.

    Attributes
    ----------
    index : int
        The snip's data line (``DataLine.index``).
    specid : str
    wave : numpy.ndarray
        The snip's pixels, in the data's frame.
    flux, error : numpy.ndarray
    model : numpy.ndarray
        ALIS's model on those pixels; NaN where ALIS loads no pixel.
    continuum : numpy.ndarray or None
        The snip's continuum line on those pixels, as ALIS evaluates it; None when
        the snip has no continuum line.
    fitted : numpy.ndarray
        The pixels ALIS fits (bool).
    chi2 : float
        χ² on the fitted pixels.

    Generated by RJC and Claude.
    """

    index: int
    specid: str
    wave: np.ndarray
    flux: np.ndarray
    error: np.ndarray
    model: np.ndarray
    continuum: np.ndarray | None
    fitted: np.ndarray
    chi2: float

    def __repr__(self):
        return "Curve(index={0}, specid={1!r}, {2} pixels, {3} fitted)".format(
            self.index, self.specid, self.wave.size, int(self.fitted.sum())
        )

    @property
    def normalised(self):
        """The model divided by the continuum, or None without one."""
        if self.continuum is None:
            return None
        with np.errstate(divide="ignore", invalid="ignore"):
            return self.model / self.continuum

    @property
    def data_normalised(self):
        """The data divided by the continuum, or None without one."""
        if self.continuum is None:
            return None
        with np.errstate(divide="ignore", invalid="ignore"):
            return self.flux / self.continuum

    @property
    def residuals(self):
        """(data − model)/σ; NaN where there is no model or no valid error."""
        with np.errstate(divide="ignore", invalid="ignore"):
            out = (self.flux - self.model) / self.error
        out[~(self.error > 0)] = np.nan
        return out


def _load(project):
    """
    ALIS's state for the project, as ``ClassMain`` builds it up to the fit.

    Returns
    -------
    state : SimpleNamespace
    ptied : list of str
        The link of each parameter (``""`` for none), as ``main.py`` makes it.

    Generated by RJC and Claude.
    """
    state = SimpleNamespace(_argflag=ArgFlag())
    state._argflag["out"]["verbose"] = -1
    _, datlines, modlines, lnklines = load.load_input(
        state, textstr=project.text.splitlines(keepends=True)
    )
    if not [d for d in datlines if d.split("#")[0].strip()]:
        raise ProfileError("The model has no data to evaluate it on.")
    # The model is drawn, not written: no file of the fit's outputs
    state._argflag["out"]["verbose"] = -1
    state._argflag["out"]["wavecorr"] = False
    state._atomic = project.registry.atomic
    state._funcarray = project.registry.instances()
    load.load_data(state, datlines, data=project.data_for_run())
    state._modpass = load.load_model(state, modlines)
    state._links = load.load_links(state, lnklines)
    state._modlines = modlines
    # As main.py, from here to its "NOW PREPARE TO FIT THE DATA!"
    parinfo, state._levadd = load.load_parinfo(state)
    state._pinfl = load.load_par_influence(state, state._modpass["p0"])
    (
        state._wavespx,
        state._contspx,
        state._zerospx,
        state._posnspx,
        state._nexbins,
    ) = load.load_subpixels(state, state._modpass["p0"])
    ptied = []
    count = 0
    for info in parinfo:
        if "tied" in info.keys():
            tied = info["tied"].replace("numpy", "np")
            ptied.append(tied.strip())
            state._modpass["mlnk"].append([-2 - count, tied])
            count += 1
        else:
            ptied.append("")
    state._ptied = ptied
    state._qanytied = int(any(ptied))
    if state._qanytied:
        state._modpass["p0"] = load.load_tied(state._modpass["p0"], ptied)
    return state, ptied


class Profile:
    """
    The model of every snip of a project, as ALIS computes it.

    Parameters
    ----------
    project : alis.dashboard.project.Project

    Raises
    ------
    ProfileError
        The model does not read, or ALIS cannot load it as it is.

    Attributes
    ----------
    start : numpy.ndarray
        The starting values, links applied (read-only; use :meth:`values`).
    cost : float
        The time the last evaluation took, in seconds.

    Generated by RJC and Claude.
    """

    def __init__(self, project):
        if project.paused:
            raise ProfileError(
                "The model does not read, so it cannot be drawn. Correct it in the"
                " .mod panel."
            )
        self.project = project
        try:
            with M.alis_quietly():
                self.state, self._ptied = _load(project)
        except ProfileError:
            raise
        except BaseException as err:
            if isinstance(err, KeyboardInterrupt):
                raise
            # ALIS's message may quote a line, and so a hidden value
            raise ProfileError(
                "ALIS cannot evaluate the model as it is ({0}).".format(
                    type(err).__name__
                )
            ) from None
        self.start = np.array(self.state._modpass["p0"], dtype=float)
        self.start.setflags(write=False)
        self.cost = 0.0
        self._places()
        self._owners()

    # -- where each snip is in ALIS's arrays ------------------------------------------

    def _places(self):
        """
        Each snip's place in ALIS's arrays, its pixels, fitted pixels and range.

        Generated by RJC and Claude.
        """
        state, project = self.state, self.project
        by_specid = {}
        for item in project.parsed.data:
            by_specid.setdefault(item.specid, []).append(item.index)
        snips = {s.data.index: s for s in project.snips}
        self._where = {}  # data line index -> (sp, sn)
        self._snips = {}  # data line index -> Snip
        self._pixels = {}  # data line index -> (offset, wave, flux, error)
        self._fitted = {}  # data line index -> mask over ALIS's pixels
        self._range = {}  # data line index -> the range ALIS sets its lines in
        self.by_specid = {}
        shind = np.where(np.array(state._modpass["emab"]) == "sh")[0][0]
        p0 = state._modpass["p0"]
        for sp in range(len(state._posnfull)):
            specid = str(state._specid[sp])
            order = by_specid.get(specid, [])
            for sn in range(len(state._posnfull[sp]) - 1):
                low, high = state._posnfull[sp][sn], state._posnfull[sp][sn + 1]
                index = order[sn] if sn < len(order) else None
                # The range model_func gives the lines: the pixels, shifted
                mtyp = state._modpass["mtyp"][shind]
                inst, cls = state._funcarray[2][mtyp], state._funcarray[1][mtyp]
                inst._keywd = state._modpass["mkey"][shind]
                pars = cls.set_vars(
                    inst, p0, state._levadd[shind], state._modpass, shind
                )
                shind += 1
                if index is None:
                    continue
                x = state._wavefull[sp][low:high]
                moved = cls.call_CPU(inst, x, pars)
                self._range[index] = (float(np.min(moved)), float(np.max(moved)))
                self._where[index] = (sp, sn)
                self.by_specid.setdefault(specid, []).append(index)
                window = (x >= state._posnfit[sp][2 * sn]) & (
                    x <= state._posnfit[sp][2 * sn + 1]
                )
                self._fitted[index] = window & np.isin(x, state._wavefit[sp])
                snip = snips.get(index)
                self._snips[index] = snip
                self._pixels[index] = self._snip_pixels(snip, sp, low, high)

    def _snip_pixels(self, snip, sp, low, high):
        """
        Where ALIS's pixels fall among the snip's: ``(offset, wave, flux, error)``.

        ALIS's pixels are a run of the snip's; when they are not (or the snip's file
        is not in the bundle), the snip is drawn on ALIS's pixels alone.

        Generated by RJC and Claude.
        """
        state = self.state
        x = state._wavefull[sp][low:high]
        pix = None if snip is None else snip.pixels
        if pix is not None and pix.wave.size >= x.size and x.size:
            offset = int(np.searchsorted(pix.wave, x[0]))
            if np.array_equal(pix.wave[offset : offset + x.size], x):
                return offset, pix.wave, pix.flux, pix.error
        return (
            0,
            np.array(x, dtype=float),
            np.array(state._fluxfull[sp][low:high], dtype=float),
            np.array(state._fluefull[sp][low:high], dtype=float),
        )

    # -- what a parameter reaches ------------------------------------------------------

    def _owners(self):
        """
        The lines each ALIS parameter is written on, and the parameters linked to
        each one.

        Generated by RJC and Claude.
        """
        pm = self.project.parsed
        self._owner = {}
        for par in pm.params:
            if par.index >= 0:
                self._owner.setdefault(par.index, [])
                if par.owner not in self._owner[par.index]:
                    self._owner[par.index].append(par.owner)
        # A link is written p[3] = p[7] + p[9]; set_vars computes the same
        # expressions (modpass["mlnk"] holds them too)
        self._linked = {}
        for i, tied in enumerate(self._ptied):
            for j in _TIED.findall(tied):
                self._linked.setdefault(int(j), set()).add(i)

    def _reached(self, indices):
        """The parameters that change when ``indices`` change: they, and those
        linked to them, followed through every link."""
        out, todo = set(), list(indices)
        while todo:
            i = todo.pop()
            if i in out:
                continue
            out.add(i)
            todo.extend(self._linked.get(i, ()))
        return out

    def _specids_of(self, line):
        """The specids ALIS applies a model line to."""
        mkey = self.state._modpass["mkey"]
        if 0 <= line.index < len(mkey):
            return [str(s) for s in mkey[line.index].get("specid", [])]
        return [str(s) for s in line.specids]

    def _falls_in(self, line, values_list):
        """The snips where a transition of a voigt line falls, at any of the
        redshifts ``values_list`` give it (ALIS's own test, ``voigt.set_vars``)."""
        zpar = line.param("redshift")
        atomic = self.state._atomic
        sel = np.asarray(atomic["Ion"]).astype(str) == line.ion
        rest = np.asarray(atomic["Wavelength"])[sel].astype(float)
        out = set()
        for specid in self._specids_of(line):
            for index in self.by_specid.get(specid, []):
                low, high = self._range[index]
                for values in values_list:
                    z = values[zpar.index] if zpar is not None else 0.0
                    obs = rest * (1.0 + z)
                    if np.any((obs >= low) & (obs <= high)):
                        out.add(index)
                        break
        return out

    def affected(self, changes, values=None):
        """
        The snips whose model changes when some parameters change.

        Parameters
        ----------
        changes : dict or iterable of int
            ALIS's parameter numbers (the keys of a dict of new values).
        values : numpy.ndarray, optional
            The values after the change (from :meth:`values`); by default the
            starting values with ``changes`` applied, when it is a dict.

        Returns
        -------
        set of int
            Data line indices.

        Generated by RJC and Claude.
        """
        if values is None:
            values = self.values(changes) if isinstance(changes, dict) else self.start
        reached = self._reached(int(i) for i in changes)
        lines = []
        for i in reached:
            for owner in self._owner.get(i, ()):
                if owner not in lines:
                    lines.append(owner)
        out = set()
        ions = set()
        for owner in lines:
            if isinstance(owner, M.DataLine):
                out.add(owner.index)
                continue
            if owner.variable:
                continue  # it acts through its links only
            if owner.function == "voigt" and owner.ion and not owner.ratio:
                ions.add(owner.ion)
                out |= self._falls_in(owner, [self.start, values])
            else:
                for specid in self._specids_of(owner):
                    out.update(self.by_specid.get(specid, []))
        # A ratio line (2H_I/1H_I) takes its column density from its denominator
        for line in self.project.parsed.lines:
            if line.function == "voigt" and line.ratio:
                if line.ion.split("/")[1] in ions:
                    for specid in self._specids_of(line):
                        out.update(self.by_specid.get(specid, []))
        return out & set(self._where)

    # -- evaluating --------------------------------------------------------------------

    def values(self, changes=None):
        """
        The parameters with some changed, the links applied as ALIS applies them.

        Parameters
        ----------
        changes : dict, optional
            ALIS's parameter number to its new value (as ALIS holds it: log N, z,
            b in km/s...).

        Returns
        -------
        numpy.ndarray

        Generated by RJC and Claude.
        """
        p = np.array(self.start, dtype=float)
        for i, value in (changes or {}).items():
            p[int(i)] = float(value)
        if self.state._qanytied:
            with M.alis_quietly():
                try:
                    p = load.load_tied(p, self._ptied)
                except BaseException as err:
                    if isinstance(err, KeyboardInterrupt):
                        raise
                    raise ProfileError(
                        "A link cannot be computed with these values."
                    ) from None
        return p

    @property
    def snips(self):
        """The data line indices of the snips ALIS evaluates, in its order."""
        return list(self._where)

    def evaluate(self, values=None, snips=None):
        """
        ALIS's model of some snips.

        Parameters
        ----------
        values : numpy.ndarray, optional
            Every parameter (from :meth:`values`); the starting values by default.
        snips : iterable of int, optional
            The data line indices to evaluate; every snip by default.

        Returns
        -------
        dict
            Data line index to :class:`Curve`.

        Generated by RJC and Claude.
        """
        state = self.state
        p = self.start if values is None else np.asarray(values, dtype=float)
        p = np.array(p, dtype=float)  # model_func may write into it
        wanted = set(self._where) if snips is None else set(snips) & set(self._where)
        tic = time.perf_counter()
        with M.alis_quietly():
            try:
                if wanted == set(self._where):
                    model = model_eval.model_func(
                        state, state._wavefull, p, state._posnfull, output=1
                    )
                else:
                    state._pinfl = [self._table(wanted), None]
                    model = model_eval.model_func(
                        state,
                        state._wavefull,
                        p,
                        state._posnfull,
                        ddpid=SELECTED,
                        output=1,
                    )
            except BaseException as err:
                if isinstance(err, KeyboardInterrupt):
                    raise
                raise ProfileError(
                    "ALIS cannot evaluate the model with these values ({0}).".format(
                        type(err).__name__
                    )
                ) from None
        self.cost = time.perf_counter() - tic
        out = {}
        for index in wanted:
            sp, sn = self._where[index]
            low, high = state._posnfull[sp][sn], state._posnfull[sp][sn + 1]
            out[index] = self._curve(index, model[sp][low:high])
        return out

    def _table(self, wanted):
        """An influence table naming the snips ``wanted`` (see :data:`SELECTED`)."""
        state = self.state
        table = []
        for sp in range(len(state._posnfull)):
            table.append(
                [np.array([], dtype=int) for _ in range(len(state._posnfull[sp]) - 1)]
            )
        for index in wanted:
            sp, sn = self._where[index]
            table[sp][sn] = np.array([SELECTED], dtype=int)
        return table

    def _curve(self, index, model):
        """A :class:`Curve` from ALIS's model on its own pixels."""
        state = self.state
        sp, sn = self._where[index]
        low, high = state._posnfull[sp][sn], state._posnfull[sp][sn + 1]
        offset, wave, flux, error = self._pixels[index]
        full = np.full(wave.size, np.nan)
        full[offset : offset + model.size] = model
        fitted = np.zeros(wave.size, dtype=bool)
        fitted[offset : offset + model.size] = self._fitted[index]
        mask = self._fitted[index]
        resid = (state._fluxfull[sp][low:high] - model) / state._fluefull[sp][low:high]
        chi2 = float(np.sum(resid[mask] ** 2))
        return Curve(
            index=index,
            specid=str(state._specid[sp]),
            wave=wave,
            flux=flux,
            error=error,
            model=full,
            continuum=self._continuum(index, wave),
            fitted=fitted,
            chi2=chi2,
        )

    def _continuum(self, index, wave):
        """The snip's continuum on its pixels (computed once: drags leave it)."""
        cache = self.__dict__.setdefault("_conts", {})
        if index not in cache:
            snip = self._snips.get(index)
            cache[index] = (
                None if snip is None else CO.evaluate(self.project, snip, wave=wave)
            )
        return cache[index]

    def chi2(self, curves):
        """The χ² of some curves, summed."""
        return float(sum(c.chi2 for c in curves.values()))


def of(project):
    """
    The project's :class:`Profile`, kept while the project's text and files are
    unchanged.

    Raises
    ------
    ProfileError

    Generated by RJC and Claude.
    """
    key = (id(project.registry), CO._state_key(project))
    found = _PROFILES.get(key)
    if found is not None and found.project is project:
        return found
    if len(_PROFILES) > 8:
        _PROFILES.clear()
    found = Profile(project)
    _PROFILES[key] = found
    return found


