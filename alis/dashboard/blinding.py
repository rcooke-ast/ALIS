"""The blinding gate: every value bound for the screen passes through it.

Dashboard Stage 2.7 (F8, D24, QF.20). A :class:`Gate` is made for a project, and
everything a panel, a table, a tooltip, the ``.mod`` panel, a message or a plot label
shows of a parameter goes through it:

- **Hidden values are masked.** A hidden value shows as ``▒▒▒▒`` with its tie label
  (``▒▒▒▒da``). The values of a line with ``blind=True`` are hidden (D24), and so are
  those of the lines hidden by S20. Hiding follows the model: a label whose value is
  set on a hidden line is hidden wherever it is used, a parameter computed by a link
  from a hidden one is hidden, and so is what is derived from a hidden value (a
  component's velocity from its redshift, the limits of a hidden label).
- **Global blind** (``run blind True``) hides every best-fit value, but not the starting
  values (QF.20(a)).
- **Shown:** errors, and changes in χ² (QF.20(b), (d)).
- **Masked:** ``blindrange`` offsets (and their ``blindseed``) (QF.20).
- **Typing over a mask** stores the typed value, hidden (:class:`MaskedView`,
  QF.20(c)).
- **Unblinding** (:func:`unblind`) is an explicit action that the user confirms, is
  logged in the bundle, switches blinding off in the text, and cannot be undone
  (Q2.11).

Generated by RJC and Claude.
"""

import re

from alis import bundle as B
from alis import logger
from alis.dashboard import edit as E
from alis.dashboard import model as M
from alis.dashboard import project as P
from alis.dashboard import text as T

msgs = logger.msgs()

MASK = "▒▒▒▒"
# Keywords whose values reveal a blinded offset (D24, QF.20)
OFFSET_KEYWORDS = ("blindrange", "blindseed")
# Keywords that are never values, even on a hidden line
NAME_KEYWORDS = ("specid", "ion", "blind", "logN", "continuum", "freq")
_NUMBER = re.compile(r"(?<![\w.▒])[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?(?![\w▒])")
_LINE_REF = re.compile(r"(lines? )(\d+)")
_WORD = re.compile(r"\S+")
# A number anywhere in a word, as a keyword's value may hold several
_ANY_NUMBER = re.compile(r"[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?")
# A value followed by its label, inside any word: 1.0da, vfwhm(7.0VA)
_LABELLED = re.compile(r"([-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]\d+)?)([A-Za-z_]\w*)")


class BlindingError(Exception):
    """A blinding action that cannot be done as asked."""


class RevealError(BlindingError):
    """An edit that would show a hidden value without unblinding (Q3.14)."""


REVEAL = (
    "This change would show values that are hidden, so it was not made. To show"
    " hidden values, choose Model → Unblind…"
)


def _numeric(text):
    """Whether a keyword's value is one number or a list of numbers."""
    parts = text.strip("[]()").split(",")
    return bool(parts) and all(M.is_number(p) for p in parts if p)


def _words(line_text):
    """
    The words of a line with their columns, without the comment marks of a line
    that has been commented out.

    Generated by RJC and Claude.
    """
    for match in _WORD.finditer(line_text):
        word = match.group()
        stripped = word.lstrip("#")
        if stripped:
            yield stripped, match.start() + len(word) - len(stripped)


def line_value_spans(line_text):
    """
    The columns of every value written on a line, found from its words alone.

    This masks a hidden line whatever the state of the text: a line that has been
    commented out (which a bundle hides too), and a text that does not read, when
    the parsed model has no parameters to give (Stage 3).

    Parameters
    ----------
    line_text : str

    Returns
    -------
    list of (start, end)

    Generated by RJC and Claude.
    """
    spans = []
    for word, start in _words(line_text):
        if "=" in word:
            name, value = word.split("=", 1)
            if name in NAME_KEYWORDS:
                continue
            base = start + len(name) + 1
            spans += [
                (base + m.start(), base + m.end()) for m in _ANY_NUMBER.finditer(value)
            ]
            continue
        token = T.Token(word, 0, start, start + len(word))
        value, _ = T.split_value(token)
        if value.text and M.is_number(value.text):
            spans.append((value.start, value.end))
    return spans


def labelled_value_spans(line_text, labels):
    """
    The columns of the values on a line that carry one of ``labels``.

    Generated by RJC and Claude.
    """
    spans = []
    for word, start in _words(line_text):
        if "=" in word and word.split("=", 1)[0] in NAME_KEYWORDS:
            continue
        for match in _LABELLED.finditer(word):
            if match.group(2) in labels:
                spans.append((start + match.start(1), start + match.end(1)))
    return spans


def _merge(spans):
    """
    Spans in order, with those that overlap joined: ``(line, start, end)``.

    Generated by RJC and Claude.
    """
    out = []
    for line, start, end in sorted(spans):
        if out and out[-1][0] == line and start < out[-1][2]:
            out[-1] = (line, out[-1][1], max(end, out[-1][2]))
        else:
            out.append((line, start, end))
    return out


class Gate:
    """
    The blinding gate of one project.

    Parameters
    ----------
    project : Project or ParsedModel
        A project (whose hidden lines include those hidden by S20), or a parsed model
        alone (whose hidden lines are those with ``blind=True``).
    hidden_lines : iterable of int, optional
        The hidden lines, instead of the project's.

    Attributes
    ----------
    pm : ParsedModel
    hidden_lines : set of int
    global_blind : bool
        ``run blind True``.
    hidden_index : set of int
        The ALIS numbers of the hidden parameters.
    complete : bool
        The text reads, so the gate knows every parameter. While it does not read,
        every value of a hidden line is masked from its words, and so is every
        value carrying a label that was hidden when the text last read.

    Generated by RJC and Claude.
    """

    def __init__(self, project, hidden_lines=None):
        if isinstance(project, P.Project):
            self.project = project
            self.pm = project.parsed
            lines = project.hidden_lines() if hidden_lines is None else hidden_lines
        else:
            self.project = None
            self.pm = project
            lines = (
                B.blind_line_numbers(project.text.text)
                if hidden_lines is None
                else hidden_lines
            )
        self.hidden_lines = set(lines)
        self.global_blind = self.pm.blind
        self.hidden_index = self._hidden_parameters()
        self.complete = bool(self.pm.ok)
        self._last_labels = set()
        last = getattr(self.project, "last_read", None)
        if not self.complete and last is not None:
            self._last_labels = Gate(last).hidden_labels

    # -- what is hidden -------------------------------------------------------------

    def _hidden_parameters(self):
        """
        The ALIS numbers of the hidden parameters: those set on a hidden line, and
        those computed by a link from a hidden one.

        Generated by RJC and Claude.
        """
        hidden = {
            p.index for p in self.pm.params if p.first and p.line in self.hidden_lines
        }
        names = {p.label for p in self.pm.params if p.index in hidden and p.label}
        changed = True
        while changed:
            changed = False
            for link in self.pm.links:
                if link.target not in names and set(link.deps) & names:
                    names.add(link.target)
                    changed = True
        for name in names:
            label = self.pm.labels.get(name)
            if label is not None:
                hidden |= {p.index for p in label.params}
        return hidden

    @property
    def hidden_labels(self):
        """The labels of the hidden parameters (as last read, while the text does
        not read)."""
        return {
            p.label for p in self.pm.params if p.index in self.hidden_index and p.label
        } | self._last_labels

    def is_hidden(self, param):
        """
        Whether a parameter's value is hidden here: it is hidden, or it is written on
        a hidden line.

        Generated by RJC and Claude.
        """
        return param.index in self.hidden_index or param.line in self.hidden_lines

    def hidden_values(self):
        """
        Every hidden value as written, for tests and for masking messages.

        Generated by RJC and Claude.
        """
        out = set()
        for par in self.pm.params:
            if self.is_hidden(par) and par.value_token is not None:
                out.add(par.value_token.text)
        for num in self.hidden_lines:
            if num < len(self.pm.text):
                text = self.pm.text[num].text
                out |= {text[a:b] for a, b in line_value_spans(text)}
        return out

    # -- what is shown --------------------------------------------------------------

    @staticmethod
    def _format(value, digits):
        return "{0:.{1}g}".format(value, digits)

    def value(self, param, value=None, digits=8):
        """
        A parameter's starting value, for a panel: its value, or the mask.

        Parameters
        ----------
        param : Param
        value : float, optional
            The value to show (by default the parameter's starting value).
        digits : int
            Significant figures.

        Returns
        -------
        str

        Generated by RJC and Claude.
        """
        if self.is_hidden(param):
            return MASK
        return self._format(param.start if value is None else value, digits)

    def word(self, param):
        """A parameter as the ``.mod`` writes it: ``13.0da``, or ``▒▒▒▒da``."""
        if param.value_token is None:
            return "" if not self.is_hidden(param) else MASK
        value = MASK if self.is_hidden(param) else param.value_token.text
        return value + param.label

    def best_fit(self, param, value, digits=8):
        """
        A best-fit value: masked under global blind, or when the parameter is hidden
        (D24, QF.20(a)).

        Generated by RJC and Claude.
        """
        if self.global_blind or self.is_hidden(param):
            return MASK
        return self._format(value, digits)

    def error(self, param, value, digits=3):
        """An error is shown, even for a hidden parameter (QF.20(b))."""
        return self._format(value, digits)

    def chi2_change(self, value, digits=6):
        """A change in χ² is shown, even while a hidden component is dragged
        (QF.20(d))."""
        return self._format(value, digits)

    def sigma_change(self, param, change, sigma, value_change=None):
        """
        The change of a parameter between two runs (Compare, D41): for a hidden
        parameter, only its size in σ, with no sign (Q0.9, Q0.11).

        Generated by RJC and Claude.
        """
        if self.is_hidden(param) or self.global_blind:
            return "{0:.1f}σ".format(abs(change) / sigma) if sigma else MASK
        text = "{0:+.4g}".format(change if value_change is None else value_change)
        return text + (" ({0:+.1f}σ)".format(change / sigma) if sigma else "")

    def keyword(self, item, name):
        """
        A keyword's value for the screen: ``blindrange`` and ``blindseed`` are
        always masked, and so is any number on a hidden line.

        Generated by RJC and Claude.
        """
        kw = item.keywords.get(name)
        if kw is None:
            return ""
        if name in OFFSET_KEYWORDS:
            return MASK
        if (
            item.line in self.hidden_lines
            and name not in NAME_KEYWORDS
            and (_numeric(kw.value))
        ):
            return MASK
        return kw.value

    def velocity(self, component, digits=4):
        """A component's velocity in its system, masked if its redshift is hidden."""
        zpar = component.main.param("redshift")
        if zpar is not None and self.is_hidden(zpar):
            return MASK
        return self._format(component.velocity, digits)

    def redshift(self, component, digits=10):
        """A component's redshift."""
        zpar = component.main.param("redshift")
        if zpar is not None and self.is_hidden(zpar):
            return MASK
        return self._format(component.z, digits)

    def system_z(self, system, digits=8):
        """
        A system's redshift: masked when it was taken from a hidden component.

        Generated by RJC and Claude.
        """
        for comp in system.components:
            zpar = comp.main.param("redshift")
            if zpar is not None and self.is_hidden(zpar) and comp.z == system.z:
                return MASK
        return self._format(system.z, digits)

    # -- the .mod panel -------------------------------------------------------------

    def _masked_spans(self):
        """
        The spans of the text the ``.mod`` panel masks: ``(line, start, end)``.

        Generated by RJC and Claude.
        """
        pm = self.pm
        spans = set()
        for par in pm.params:
            if par.value_token is not None and self.is_hidden(par):
                tok = par.value_token
                spans.add((tok.line, tok.start, tok.end))
        items = list(pm.lines) + list(pm.data)
        for item in items:
            for name, kw in item.keywords.items():
                hide = name in OFFSET_KEYWORDS or (
                    item.line in self.hidden_lines
                    and name not in NAME_KEYWORDS
                    and _numeric(kw.value)
                )
                if hide and kw.val.text:
                    spans.add((kw.val.line, kw.val.start, kw.val.end))
        labels = self.hidden_labels
        for cmd in pm.commands:
            if cmd.target == "param" and cmd.name in labels and len(cmd.tokens) > 3:
                tok = cmd.tokens[3]
                spans.add((tok.line, tok.start, tok.end))
        # Every value of a hidden line, from its words: this also covers a line that
        # has been commented out, and a text that does not read
        for num in self.hidden_lines:
            if num < len(pm.text):
                for start, end in line_value_spans(pm.text[num].text):
                    spans.add((num, start, end))
        # The offsets of a blind range, wherever they are written
        for line in pm.text:
            for word, start in _words(line.text):
                name = word.split("=", 1)[0]
                if (
                    "=" in word
                    and name in OFFSET_KEYWORDS
                    and len(word) > len(name) + 1
                ):
                    spans.add((line.num, start + len(name) + 1, start + len(word)))
        if not self.complete and labels:
            for line in pm.text:
                if line.kind not in T.CONTENT:
                    continue
                words = line.words
                if words[:2] in (["lim", "param"], ["fix", "param"]):
                    if len(words) > 3 and words[2] in labels:
                        tok = line.tokens[3]
                        spans.add((line.num, tok.start, tok.end))
                    continue
                for start, end in labelled_value_spans(line.text, labels):
                    spans.add((line.num, start, end))
        return _merge(spans)

    def view(self):
        """
        The ``.mod`` panel's text, with every hidden value masked.

        Returns
        -------
        MaskedView

        Generated by RJC and Claude.
        """
        return MaskedView(self.pm.text, self._masked_spans())

    def message(self, text):
        """
        A message for the screen (a problem, a notice, an ALIS message): when it
        mentions a hidden value, label or line, its numbers are masked, except the
        line numbers it gives.

        Generated by RJC and Claude.
        """
        values = self.hidden_values()
        labels = self.hidden_labels
        lines = {
            M.plain(self.pm.text[n].text)
            for n in self.hidden_lines
            if n < len(self.pm.text)
        }
        flat = M.plain(text)
        mentions = (
            any(
                re.search(r"(?<![\w.]){0}(?![\w])".format(re.escape(v)), text)
                for v in values
            )
            or any(
                re.search(r"(?<![\w]){0}(?![\w])".format(re.escape(lab)), text)
                for lab in labels
            )
            or any(line and line in flat for line in lines)
        )
        if not mentions:
            return text
        refs = {}

        def keep(match):
            # A key with no digits, so that the numbers' mask leaves it alone
            key = "\x00{0}\x00".format(
                "".join(chr(97 + int(d)) for d in str(len(refs)))
            )
            refs[key] = match.group(0)
            return key

        out = _LINE_REF.sub(keep, text)
        out = _NUMBER.sub(MASK, out)
        for key, original in refs.items():
            out = out.replace(key, original)
        return out

    def problem(self, prob):
        """A problem, its message passed through :meth:`message`."""
        return T.Problem(
            prob.line, prob.severity, self.message(prob.message), prob.source
        )


class MaskedView:
    """
    The ``.mod`` panel's text, with the hidden values masked, and the way back from
    an edit made on it to an edit of the real text.

    Parameters
    ----------
    mtext : ModelText
        The real text.
    spans : list of (line, start, end)
        The spans to mask, in order.

    Attributes
    ----------
    text : str
        What the panel shows.

    Generated by RJC and Claude.
    """

    def __init__(self, mtext, spans):
        self.mtext = mtext
        self.segments = []  # (display start, display end, real start, real end)
        parts, real_pos, disp_pos = [], 0, 0
        for line, start, end in spans:
            rstart, rend = mtext.offset(line, start), mtext.offset(line, end)
            parts.append(mtext.text[real_pos:rstart])
            disp_pos += rstart - real_pos
            parts.append(MASK)
            self.segments.append((disp_pos, disp_pos + len(MASK), rstart, rend))
            disp_pos += len(MASK)
            real_pos = rend
        parts.append(mtext.text[real_pos:])
        self.text = "".join(parts)

    def lines(self):
        """The panel's text, line by line."""
        return self.text.splitlines()

    def _real(self, pos):
        """The real offset of a display offset outside the masks."""
        shift = 0
        for dstart, dend, rstart, rend in self.segments:
            if pos >= dend:
                shift += (rend - rstart) - (dend - dstart)
            elif pos > dstart:
                raise BlindingError("The position is inside a masked value.")
        return pos + shift

    def to_real(self, start, end, new):
        """
        The change of the real text that an edit of the panel's text makes.

        An edit that touches a masked value replaces the whole value with what is
        typed (QF.20(c)): the value stays hidden, because its line or label still is.
        Deleting part of a mask, with nothing typed, changes nothing.

        Parameters
        ----------
        start, end : int
            The span of the panel's text that the edit replaces.
        new : str
            The text typed in its place.

        Returns
        -------
        Change

        Generated by RJC and Claude.
        """
        touched = [
            s
            for s in self.segments
            if s[0] < end and s[1] > start or (start == end and s[0] <= start <= s[1])
        ]
        if not touched:
            rstart, rend = self._real(start), self._real(end)
            return T.Change(
                (T.Patch(rstart, self.mtext.text[rstart:rend], new),), "Edit the model"
            )
        typed = new.replace(MASK[0], "")
        first, last = touched[0], touched[-1]
        if not typed.strip() and (start > first[0] or end < last[1]):
            return T.Change((), "")
        dstart = min(start, first[0])
        dend = max(end, last[1])
        rstart = first[2] if dstart == first[0] else self._real(dstart)
        rend = last[3] if dend == last[1] else self._real(dend)
        return T.Change(
            (T.Patch(rstart, self.mtext.text[rstart:rend], typed),),
            "Edit a hidden value",
        )


# -- What is blinded, and the guard of the history (Stage 3, Q3.9, Q3.13, Q3.14) ------


def blinded_items(project):
    """
    What is blinded, as the toolbar's pill names it: the ions, or the labels or
    functions, of the hidden lines.

    Returns
    -------
    list of str

    Generated by RJC and Claude.
    """
    pm = project.parsed
    names = []
    for num in project.hidden_lines():
        item = pm.item_at(num)
        if item is None or not hasattr(item, "function"):
            continue
        if item.ion:
            name = P.ion_name(item.ion.split("/")[0])
        else:
            labels = [p.label for p in item.params if p.label]
            name = labels[0] if labels else item.function
        if name not in names:
            names.append(name)
    return names


def pill_text(project):
    """
    The toolbar's blinding pill: what is blinded (D24).

    Generated by RJC and Claude.
    """
    items = blinded_items(project)
    parts = []
    if project.parsed.blind:
        parts.append("Blind analysis")
    if items:
        shown = ", ".join(items[:3]) + (" …" if len(items) > 3 else "")
        parts.append("Blinded: " + shown)
    return " · ".join(parts) if parts else "Not blinded"


def _real_spans(gate):
    """The real-text offsets of the values a gate masks."""
    return {(rstart, rend) for _, _, rstart, rend in gate.view().segments}


def _value_spans(gate):
    """
    The real-text offsets of every value a panel could show: every parameter's
    value, and every number on every content line and hidden line.

    Generated by RJC and Claude.
    """
    mtext = gate.pm.text
    spans = set()
    for par in gate.pm.params:
        tok = par.value_token
        if tok is not None:
            start = mtext.offset(tok.line, tok.start)
            spans.add((start, start + len(tok.text)))
    for line in mtext:
        if line.kind in T.CONTENT or line.num in gate.hidden_lines:
            for start, end in line_value_spans(line.text):
                spans.add((line.offset + start, line.offset + end))
    return spans


def _follow(span, change):
    """
    Where a span of the text is after a change, or None if the change touched it.

    Generated by RJC and Claude.
    """
    start, end = span
    for patch in change.patches:
        if end <= patch.start:
            continue
        if start >= patch.end:
            shift = len(patch.new) - len(patch.old)
            start, end = start + shift, end + shift
            continue
        return None
    return start, end


class Guard:
    """
    Watches each step of the history for blinding (Q3.14).

    - A step that would show a hidden value (``blind=False`` typed over
      ``blind=True``, ``run blind False``) is refused: :meth:`check` raises
      :class:`RevealError`, and the history undoes it. Only unblinding shows hidden
      values. A value deleted or typed over is not shown, so deleting a hidden line
      whole is allowed.
    - A step that hides something (``run blind True``, or ``blind=True`` on a line,
      however it was made) is reported, so that undo stops at it: undoing it would
      show what it hid.

    Generated by RJC and Claude.
    """

    def __init__(self, project):
        self.project = project

    def snapshot(self):
        """
        What is hidden, and what is shown, before a step.

        Generated by RJC and Claude.
        """
        gate = Gate(self.project)
        hidden = _real_spans(gate)
        return {
            "text": self.project.text,
            "hidden": hidden,
            "shown": _value_spans(gate) - hidden,
            "global": gate.global_blind,
        }

    def check(self, snap, step):
        """
        Judge a step that has just been made.

        Returns
        -------
        bool
            Whether the step hides something (undo stops at it).

        Raises
        ------
        RevealError
            If the step shows a hidden value.

        Generated by RJC and Claude.
        """
        change = step.text if step.text is not None else T.Change((), "")
        gate = Gate(self.project)
        hidden = _real_spans(gate)
        text = self.project.text
        for span in snap["hidden"]:
            moved = _follow(span, change)
            if moved is None or moved in hidden:
                continue
            # The same value, still in the text, and no longer masked
            if text[moved[0] : moved[1]] == snap["text"][span[0] : span[1]]:
                raise RevealError(REVEAL)
        if snap["global"] and not gate.global_blind:
            raise RevealError(REVEAL)
        if gate.global_blind and not snap["global"]:
            return True
        for span in snap["shown"]:
            moved = _follow(span, change)
            if moved is not None and moved in hidden:
                return True
        return False


def strings(project, gate=None, problems=()):
    """
    Every string the panels show of a project's values, as the gate gives them.

    This is the list a panel draws from (Stage 3–6): the parameter tables and their
    tooltips, the component cards, the rows of the Data tab, the systems, the
    continua, the ``.mod`` panel, the problems and notices, and the plot labels. The
    tests search it for hidden values.

    Generated by RJC and Claude.
    """
    gate = gate or Gate(project)
    pm = project.parsed
    out = [gate.view().text]
    for par in pm.params:
        shown = gate.value(par)
        out.append(shown)
        out.append(gate.word(par))
        out.append("{0} = {1} ({2})".format(par.name, shown, par.label or "free"))
        out.append(gate.best_fit(par, par.start))
        out.append(gate.error(par, 0.01))
    for row in project.rows:
        for par in (row.fwhm, row.shift):
            if par is not None:
                out.append("{0}: {1} = {2}".format(row.name, par.name, gate.value(par)))
    for system in project.systems:
        out.append("{0}: z = {1}".format(system.name, gate.system_z(system)))
        for comp in system.components:
            out.append(
                "{0}  v = {1} km/s  z = {2}".format(
                    comp.id, gate.velocity(comp), gate.redshift(comp)
                )
            )
            for line in comp.lines:
                for name in ("ColDens", "bturb", "temperature"):
                    par = line.param(name)
                    if par is not None:
                        out.append(
                            "{0} {1} {2} = {3}".format(
                                comp.id, P.ion_name(line.ion), name, gate.value(par)
                            )
                        )
            mode, value = comp.temperature_mode
            temp = comp.main.param("temperature")
            out.append(
                "{0} T: {1} {2}".format(
                    comp.id, mode, "" if value is None else gate.value(temp, value)
                )
            )
    for line in project.parsed.lines:
        for name in line.keywords:
            out.append("{0}={1}".format(name, gate.keyword(line, name)))
    for notice in project.notices:
        out.append(gate.message(notice.message))
    for prob in problems:
        out.append(gate.problem(prob).message)
    return out


def unblind(project, confirmed=False, note="", history=None):
    """
    Unblind a project: the explicit action of D24, which the user confirms.

    The hidden lines are put back in plain form and the time is logged in the
    bundle's manifest (``bundle.unblind``). The text is switched to ``blind=False``
    and ``run blind False``, so nothing is masked again. It cannot be undone, and the
    undo history is cleared (Q2.11).

    Parameters
    ----------
    project : Project
    confirmed : bool
        The user has confirmed (Stage 3 asks).
    note : str
        Recorded with the time.
    history : History, optional
        Cleared.

    Raises
    ------
    BlindingError
        If the user has not confirmed.

    Generated by RJC and Claude.
    """
    if not confirmed:
        raise BlindingError("Unblinding must be confirmed by the user.")
    pm = project.parsed
    patches = []
    for item in pm.lines:
        if item.blind:
            patches.append(
                T.replace_token(pm.text, item.keywords["blind"].val, "False")
            )
    found = False
    for setting in pm.settings:
        if (setting.category, setting.key) == ("run", "blind"):
            found = True
            if setting.value != "False":
                patches.append(T.replace_token(pm.text, setting.tokens[2], "False"))
    change = T.Change.from_spans(patches, "Unblind")
    if not found and pm.blind:
        # ALIS blinds a model that does not say (run blind is True by default)
        after = E.reread(pm, change)
        change = change.then(E.set_setting(after, "run", "blind", "False"))
    step = P.Step(
        "Unblind",
        change,
        {},
        None,
        (set(project.extra_hidden), set()),
    )
    project.apply(step)
    B.unblind(project.bundle, note)
    msgs.info("The project was unblinded" + (": " + note if note else "."))
    if history is not None:
        history.clear()
    return step


