"""Removal with dependents: plans that list every line they change (S27, D23).

Dashboard Stage 2.9. Removing a component, an ion, a snip, a system or a dataset
first makes a :class:`Plan`, which the user sees as the list of ``.mod`` lines that
will change (QF.28), and the plan is then applied as one step (F2). A plan follows
the removal through the model until nothing more depends on what goes:

- the lines to delete (voigt lines, data lines, continua, zero levels);
- the specids to drop from other lines, deleting a line left with none;
- ``fix param`` and ``lim param`` lines, and links, that use a label no longer used by
  any parameter;
- ratio lines (``ion=2H_I/1H_I``) left with no line of their denominator, and
  ``variable`` lines whose links are all gone;
- ties left with one member, and labels whose starting value moves to another line,
  as notes (the labels stay: they are never renamed).

The snip files of deleted data lines leave the bundle too, unless another line,
commented out or not, names them; and the system or dataset leaves
``ui/project.json``.

Generated by RJC and Claude.
"""

import copy
import posixpath
import re
from dataclasses import dataclass, field

from alis.dashboard import project as P
from alis.dashboard import text as T

DELETE = "delete"
EDIT = "edit"


@dataclass
class PlanLine:
    """
    One line a removal changes.

    Attributes
    ----------
    line : int
    action : str
        ``"delete"`` or ``"edit"``.
    reason : str
        Why, in words for the user.
    before : str
        The line now.
    after : str or None
        The line after the removal (None when deleted).

    Generated by RJC and Claude.
    """

    line: int
    action: str
    reason: str
    before: str
    after: str | None = None


@dataclass
class Plan:
    """
    What a removal changes, before it is made.

    Attributes
    ----------
    description : str
    lines : list of PlanLine
        In line order.
    files : list of str
        The bundle members that go (snip files).
    ui : dict or None
        The new ``ui/project.json``, when it changes.
    notes : list of str
        What changes without a line changing: ties left with one member, starting
        values that move.
    change : Change
        The change to the text.

    Generated by RJC and Claude.
    """

    description: str
    lines: list = field(default_factory=list)
    files: list = field(default_factory=list)
    ui: dict | None = None
    notes: list = field(default_factory=list)
    change: T.Change | None = None

    def step(self, project):
        """
        The step that makes the removal, as one undoable step.

        Generated by RJC and Claude.
        """
        step = project.step(self.change or T.Change(), self.description)
        step.files = {
            m: (project.files[m], None) for m in self.files if m in project.files
        }
        if self.ui is not None:
            step.ui = (copy.deepcopy(project.ui), copy.deepcopy(self.ui))
        return step

    def preview(self, gate):
        """
        The plan's lines for the screen, through the blinding gate (F8).

        Returns
        -------
        list of tuple
            ``(line, action, reason, before, after)``.

        Generated by RJC and Claude.
        """
        view = gate.view().lines()
        out = []
        for entry in self.lines:
            hidden = entry.line in gate.hidden_lines
            before = view[entry.line] if entry.line < len(view) else entry.before
            after = entry.after
            if after is not None and hidden:
                after = gate.message(after)
            out.append((entry.line, entry.action, entry.reason, before, after))
        return out


class _Removal:
    """
    The work of making a plan: what goes, followed to a fixed point.

    Generated by RJC and Claude.
    """

    def __init__(self, project, description):
        project.require_reading()
        self.project = project
        self.pm = project.parsed
        self.description = description
        self.delete = {}  # line -> reason
        self.drop = {}  # specid -> reason

    def delete_line(self, num, reason):
        if num not in self.delete:
            self.delete[num] = reason

    def _live_specids(self):
        """The specids that some data line still has."""
        return {d.specid for d in self.pm.data if d.line not in self.delete}

    def _new_specids(self, item):
        return [s for s in item.specids if s not in self.drop]

    def _used_labels(self):
        """The labels used by a parameter on a line that stays."""
        return {
            p.label for p in self.pm.params if p.label and p.line not in self.delete
        }

    def settle(self):
        """
        Follow the removal until nothing more depends on what goes.

        Generated by RJC and Claude.
        """
        pm = self.pm
        before = None
        while before != (len(self.delete), len(self.drop)):
            before = (len(self.delete), len(self.drop))
            live = self._live_specids()
            for item in pm.data:
                if item.line in self.delete and item.specid not in live:
                    self.drop.setdefault(item.specid, "its data line is removed")
            for item in pm.lines:
                if item.line in self.delete or not item.specids:
                    continue
                if not self._new_specids(item):
                    self.delete_line(item.line, "it applies only to removed snips")
            used = self._used_labels()
            for cmd in pm.commands:
                if cmd.target == "param" and cmd.name not in used:
                    self.delete_line(
                        cmd.line, "its label '{0}' is no longer used".format(cmd.name)
                    )
            for link in pm.links:
                gone = [n for n in [link.target] + link.deps if n not in used]
                if gone:
                    self.delete_line(
                        link.line, "its label '{0}' is no longer used".format(gone[0])
                    )
            self._ratios()
            self._variables()

    def _ratios(self):
        """A ratio line whose denominator ion has no line left on its snips."""
        for item in self.pm.lines:
            if item.line in self.delete or not item.ratio:
                continue
            denom = item.ion.split("/")[1]
            sids = set(self._new_specids(item))
            left = [
                ln
                for ln in self.pm.lines
                if ln.line not in self.delete
                and ln.ion == denom
                and (not sids or not ln.specids or sids & set(ln.specids))
            ]
            if not left:
                self.delete_line(
                    item.line,
                    "no {0} line is left for its ratio".format(P.ion_name(denom)),
                )

    def _variables(self):
        """A variable whose links are all removed."""
        links = [k for k in self.pm.links if k.line not in self.delete]
        for item in self.pm.lines:
            if item.line in self.delete or not item.variable:
                continue
            label = item.params[0].label if item.params else ""
            had = [k for k in self.pm.links if label in [k.target] + k.deps]
            has = [k for k in links if label in [k.target] + k.deps]
            if had and not has:
                self.delete_line(item.line, "the links that used it are removed")

    def notes(self):
        """
        Ties left with one member, and starting values that move to another line.

        Generated by RJC and Claude.
        """
        out = []
        for name, label in sorted(self.pm.labels.items()):
            places = [p for p in label.params if p.line not in self.delete]
            if not places or len(places) == len(label.params):
                continue
            if len(places) == 1 and len(label.params) > 1:
                out.append(
                    "'{0}' will be used on line {1} only: it is no longer tied"
                    " to anything.".format(name, places[0].line + 1)
                )
            first = label.params[0]
            if first.line in self.delete and places[0].written != first.written:
                out.append(
                    "'{0}' will start from the value on line {1}, {2}, instead"
                    " of {3}.".format(
                        name,
                        places[0].line + 1,
                        places[0].value_token.text,
                        first.value_token.text,
                    )
                )
        return out

    def files(self):
        """
        The snip files that no line names any more, live or commented out.

        Generated by RJC and Claude.
        """
        out = []
        kept = [d for d in self.pm.data if d.line not in self.delete]
        # A commented-out data line can be switched back on, so its file stays
        # (as bundle.pack keeps it, Q1.11)
        opened, closed = self.pm.text.block_lines("data")
        comments = [
            ln.text
            for ln in self.pm.text.lines
            if ln.kind == T.COMMENT
            and opened is not None
            and opened < ln.num < (closed or 0)
        ]
        for item in self.pm.data:
            if item.line not in self.delete:
                continue
            member = self.project.member_of(item)
            if any(self.project.member_of(d) == member for d in kept):
                continue
            name = posixpath.basename(item.file.text)
            if any(
                re.search(r"(?<![\w.]){0}(?![\w.])".format(re.escape(name)), c)
                for c in comments
            ):
                continue
            if member not in out:
                out.append(member)
        return out

    def empty_sections(self):
        """
        The headers of sections (emission, absorption, zerolevel) that the removal
        leaves with nothing in them but blank lines.

        Generated by RJC and Claude.
        """
        pm = self.pm
        headers = [ln.num for ln in pm.text.lines if ln.kind == T.SECTION]
        for num in headers:
            if num in self.delete:
                continue
            end = num + 1
            while end < len(pm.text) and pm.text[end].kind not in (T.SECTION, T.BLOCK):
                end += 1
            body = [
                k
                for k in range(num + 1, end)
                if pm.text[k].kind != T.BLANK and k not in self.delete
            ]
            emptied = any(k in self.delete for k in range(num + 1, end))
            if emptied and not body:
                self.delete_line(num, "its section is left empty")

    def plan(self, ui=None, empty_sections=False):
        """
        The plan: every line that changes, and the change to the text.

        Parameters
        ----------
        ui : dict, optional
            The new ``ui/project.json``.
        empty_sections : bool
            Also delete the header of a section the removal leaves empty (CLEAR
            takes away the section SNIP added, Stage 4).

        Generated by RJC and Claude.
        """
        self.settle()
        if empty_sections:
            self.empty_sections()
        pm = self.pm
        entries, patches = [], []
        for num in sorted(self.delete):
            entries.append(PlanLine(num, DELETE, self.delete[num], pm.text[num].text))
            patches.append(T.delete_lines(pm.text, num))
        for item in pm.lines:
            if item.line in self.delete or not item.specids:
                continue
            new = self._new_specids(item)
            if new == item.specids:
                continue
            kw = item.keywords["specid"]
            patch = T.replace_token(pm.text, kw.val, ",".join(new))
            after = T.ModelText(patch.apply(pm.text.text))[item.line].text
            gone = [s for s in item.specids if s not in new]
            entries.append(
                PlanLine(
                    item.line,
                    EDIT,
                    "the specid{0} {1} {2} removed".format(
                        "s" if len(gone) > 1 else "",
                        ", ".join(gone),
                        "are" if len(gone) > 1 else "is",
                    ),
                    pm.text[item.line].text,
                    after,
                )
            )
            patches.append(patch)
        entries.sort(key=lambda e: e.line)
        change = T.Change.from_spans(patches, self.description)
        return Plan(self.description, entries, self.files(), ui, self.notes(), change)


def _ui_without(project, key, ident, field_name="id"):
    """``ui/project.json`` without one system or row, or None if it has none."""
    entries = project.ui.get(key)
    if not entries:
        return None
    data = copy.deepcopy(project.ui)
    data[key] = [e for e in entries if e.get(field_name) != ident]
    return data if data[key] != entries else None


def plan_component(project, component):
    """
    The plan that removes a component: its voigt lines (D23).

    A ratio line (``2H_I/1H_I``) stays while other lines of its denominator remain.

    Generated by RJC and Claude.
    """
    work = _Removal(project, "Remove component " + component.id)
    for line in component.lines:
        work.delete_line(line.line, "it is a line of component " + component.id)
    return work.plan()


def plan_ion(project, component, ion):
    """
    The plan that removes one ion of a component.

    An ion given as a ratio (D I as ``2H_I/1H_I``) is one line for every component it
    applies to, so removing it removes it from all of them; the plan says so.

    Generated by RJC and Claude.
    """
    name = P.ion_name(ion)
    work = _Removal(project, "Remove {0} from component {1}".format(name, component.id))
    for line in component.lines_of(ion):
        work.delete_line(
            line.line, "it is {0} in component {1}".format(name, component.id)
        )
    for line in component.ratios:
        if line.ion.split("/")[0] == ion:
            others = [
                c.id
                for c in project.components
                if line in c.ratios and c is not component
            ]
            reason = "it gives {0} as a ratio".format(name)
            if others:
                reason += ", in components {0} too".format(", ".join(others))
            work.delete_line(line.line, reason)
    return work.plan()


def plan_snip(project, snip, empty_sections=False):
    """
    The plan that removes a snip: its data line, and what applies only to it.

    Parameters
    ----------
    empty_sections : bool
        Also delete the header of a section left empty (CLEAR, Stage 4).

    Generated by RJC and Claude.
    """
    work = _Removal(project, "Remove snip " + snip.specid)
    work.delete_line(snip.line, "it is the data line of snip " + snip.specid)
    return work.plan(empty_sections=empty_sections)


def plan_system(project, system):
    """
    The plan that removes a system: every line of its components.

    Generated by RJC and Claude.
    """
    work = _Removal(project, "Remove system " + system.name)
    for comp in system.components:
        for line in comp.lines:
            work.delete_line(line.line, "it is a line of system " + system.name)
    return work.plan(_ui_without(project, "systems", system.id))


def plan_dataset(project, row):
    """
    The plan that removes a dataset (a row of the Data tab): its data lines, with
    their shifts and resolutions, and their continua and zero level.

    Generated by RJC and Claude.
    """
    work = _Removal(project, "Remove dataset " + row.name)
    for snip in row.snips:
        work.delete_line(snip.line, "it is a data line of " + row.name)
    return work.plan(_ui_without(project, "rows", row.id))


