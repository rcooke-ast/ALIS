"""Loading snips and a ``.mod`` from an earlier analysis.

Dashboard Stage 7.1 (Q7.1–Q7.4). An analysis made with ALIS before the dashboard has
a full spectrum, snips that ``prepfit`` cut from it (``<stem>_1H_I_1215.7_reg.dat``:
wave, flux and error, and a fit range of 0s and 1s), and a ``.mod`` that names the
snips. The user starts a new project from the spectrum, then brings in the rest:

- **Load snips…** (the Regions tab) reads one file or several. Each file is matched
  to the file row whose source spectrum it was cut from: every pixel's wavelength
  must be one of the source's pixels, with the same flux and error there. The snip is
  placed at the transition its file name names, in the system whose redshift puts the
  transition inside it (Q7.4). A snip that shares pixels with one already in the
  project replaces it, once the user agrees (Q7.2). If any file fails, nothing is
  loaded. The snips are added as SNIP adds its own (``snips.add_snip_makers``), in
  one step.
- **Load a .mod…** (the File menu, the ``.mod`` panel) reads a ``.mod`` as
  ``bundle.pack`` packs it. Its snips are matched as Load snips matches them, and
  replace the project's. Its text, as written, becomes the model (Q7.1). ``run
  blind`` follows the project; the settings and the FWHM are the ``.mod``'s (Q7.3).
  Its components join the project's systems, or form systems that stay marked as
  guessed until Confirm (D58). One step.

No Qt: the windows ask this module for a plan, show its problems or what it replaces,
and give its step to the history.

Generated by RJC and Claude.
"""

