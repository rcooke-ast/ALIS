def read_mod(modfile, registry=None):
    """
    A ``.mod`` and the snips it names, read as ``bundle.pack`` packs them (without
    the earlier run's outputs), as a project of its own.

    Raises
    ------
    LoadError
        When it cannot be packed, or does not read.

    Generated by RJC and Claude.
    """
    name = os.path.basename(modfile)
    try:
        packed = B.pack(modfile, with_outputs=False)
    except B.BundleError as err:
        raise LoadError(str(err)) from None
    except (OSError, ValueError) as err:
        raise LoadError("{0} cannot be read: {1}".format(name, err)) from None
    except SystemExit:
        # ALIS's own reader ends with a message on the terminal
        raise LoadError(
            "ALIS cannot read {0}: its message is on the terminal.".format(name)
        ) from None
    old = P.Project(packed, registry)
    if old.paused:
        found = [
            (
                "line {0}: {1}".format(p.line + 1, p.message)
                if p.line is not None
                else p.message
            )
            for p in old.parsed.errors[:5]
        ]
        raise LoadError("{0} does not read:\n".format(name) + "\n".join(found))
    return old


def mod_hints(modfile):
    """
    Where a ``.mod``'s snips are, and its FWHM, as written (Q7.9): the New project
    dialog of Open a fit (.mod)… starts there, with that FWHM.

    Returns
    -------
    tuple
        ``(folder, fwhm)``: the folder of its first data line's file (the ``.mod``'s
        own when there is none), and the first ``vfwhm`` in km/s, or None.

    Generated by RJC and Claude.
    """
    home = os.path.dirname(os.path.abspath(modfile))
    try:
        with open(modfile) as handle:
            lines = handle.read().splitlines()
    except OSError:
        return home, None
    datadirc, folder, fwhm, inside = "", None, None, False
    for line in lines:
        words = line.split("#", 1)[0].split()
        if not words:
            continue
        if words[:2] == ["run", "datadirc"] and len(words) > 2:
            datadirc = words[2]
        elif words[:2] == ["data", "read"]:
            inside = True
        elif words[:2] == ["data", "end"]:
            inside = False
        elif inside and folder is None:
            path = os.path.join(home, datadirc, words[0])
            folder = os.path.dirname(os.path.normpath(path))
            found = re.search(r"vfwhm\(([-+0-9.eE]+)", line)
            if found is not None:
                fwhm = float(found.group(1))
    if folder is None or not os.path.isdir(folder):
        folder = home
    return folder, fwhm


def _data_shift(item):
    """A data line's shift in km/s: its ``vshift``'s starting value, or 0."""
    if item.shift is not None and item.shift.name == "vshift":
        par = item.param("shift")
        if par is not None and par.start is not None:
            return float(par.start)
    return 0.0


def _datadirc_start(project, datadirc):
    """The folder in the bundle that a data line's path starts from."""
    model_dir = posixpath.dirname(project.model_member)
    return posixpath.normpath(posixpath.join(model_dir, datadirc or "."))


def _fwhm_notes(project, old, rows_of):
    """
    What the user is told when the ``.mod``'s FWHM differs from the one given for a
    file (Q7.3).
    """
    notes = []
    hidden = set(B.blind_line_numbers(old.text))
    for row in project.rows:
        default = DS.default_fwhm(project, row)
        if default is None:
            continue
        for item in old.parsed.data:
            if rows_of.get(item.line) != row.id or item.line in hidden:
                continue
            word = item.keyword("resolution") or ""
            par = item.param("resolution")
            if not word.startswith("vfwhm") or par is None or par.start is None:
                continue
            if abs(par.start - default) > 1.0e-9 * max(1.0, abs(default)):
                notes.append(
                    "The .mod's FWHM for {0} is {1} km/s; {2} km/s was given when"
                    " the file was added. The .mod's is used, and Reset FWHM returns"
                    " to {2} km/s.".format(
                        row.name, E.format_value(par.start), E.format_value(default)
                    )
                )
            break
    return notes


def load_mod_plan(project, modfile, spectra):
    """
    The plan of Load a .mod…: the ``.mod``'s snips matched to the project's spectra,
    and the step that makes its text the model and its snips the project's (Q7.1,
    Q7.3).

    Parameters
    ----------
    project : Project
    modfile : str
    spectra : dict
        Row id to its source spectrum.

    Returns
    -------
    ModPlan

    Raises
    ------
    LoadError
        When the ``.mod`` cannot be read.

    Generated by RJC and Claude.
    """
    name = os.path.basename(modfile)
    old = read_mod(modfile, project.registry)
    description = "Load {0}".format(name)
    problems, found = [], []
    for snip in old.snips:
        fname = posixpath.basename(snip.member)
        if snip.pixels is None:
            problems.append((fname, "it is not a table of numbers."))
            continue
        px = snip.pixels
        try:
            match = match_row(project, spectra, px.wave, px.flux, px.error)
        except LoadError as err:
            problems.append((fname, str(err)))
            continue
        found.append((snip, match))
    if problems:
        return ModPlan(description, modfile, problems)
    pm = old.parsed
    start = _datadirc_start(project, pm.datadirc)
    freed = [s.member for s in project.snips]
    # A project whose text does not read keeps the blinding it last read with
    blind = (project.last_read or project.parsed).blind
    patches, new_files, rows_of = [], {}, {}
    for snip, match in found:
        item = snip.data
        rows_of[item.line] = match.row.id
        rel = item.path(pm.datadirc).replace("\\", "/")
        member = posixpath.normpath(posixpath.join(start, rel))
        if (
            not member.startswith(B.TREE)
            or member == project.model_member
            or (member in new_files and new_files[member] != old.files[snip.member])
        ):
            # Its path from the model would leave the project's files: beside the
            # model's other snips instead
            stem, suffix = _member_name(posixpath.basename(snip.member))
            folder = posixpath.normpath(
                posixpath.join(posixpath.dirname(project.model_member), "..", "data")
            )
            member = SN.free_member(project, folder, stem, new_files, freed, suffix)
            patches.append(
                T.replace_token(pm.text, item.file, posixpath.relpath(member, start))
            )
        new_files[member] = old.files[snip.member]
    if pm.blind != blind:
        change = E.set_setting(pm, "run", "blind", "True" if blind else "False")
        patches += list(change.patches)
    text = T.Change.from_spans(patches).apply(old.text) if patches else old.text
    # The files: the project's snips go, the .mod's come
    files = {}
    for snip in project.snips:
        if snip.member in project.files and snip.member not in new_files:
            files[snip.member] = (project.files[snip.member], None)
    for member, content in new_files.items():
        if project.files.get(member) != content:
            files[member] = (project.files.get(member), content)
    # ui/project.json: the rows hold the .mod's snips; each snip's transition is
    # recorded where it can be placed, and guessed otherwise (Q7.4)
    ui = project.working_structure()
    ui.pop(CO.KNOTS, None)
    ui.pop(P.KEPT_NOTICES, None)
    ui.pop(SN.SNIPS, None)
    atom = L.atomic(project.registry)
    for entry in ui.get("rows", []):
        entry["specids"] = list(
            dict.fromkeys(s.specid for s, m in found if m.row.id == entry.get("id"))
        )
    for snip, match in found:
        line = L.named_line(atom, posixpath.basename(snip.member))
        extent = snip.extent
        if line is None or extent is None:
            continue
        system = L.placing_system(
            project.systems, line.rest, extent, _data_shift(snip.data)
        )
        if system is None:
            continue
        ui.setdefault(SN.SNIPS, {})[snip.specid] = {
            "system": system.id,
            "ion": str(line.ion),
            "rest": float(line.rest),
            "row": match.row.id,
        }
        for entry in ui.get("systems", []):
            if entry.get("id") == system.id:
                known = entry.setdefault("lines", [])
                if not any(
                    e.get("ion") == line.ion
                    and abs(float(e.get("wave", -1.0)) - line.rest) < 0.01
                    for e in known
                ):
                    known.append({"ion": str(line.ion), "wave": float(line.rest)})
    fwhm = {}
    for item in pm.data:
        par = item.param("resolution")
        if par is not None and par.start is not None:
            fwhm.setdefault(item.specid, float(par.start))
    if fwhm:
        ui[P.IMPORTED_FWHM] = fwhm
    else:
        ui.pop(P.IMPORTED_FWHM, None)
    old_hidden = set(project.extra_hidden)

    def replace(proj):
        return P.Step(
            "",
            T.Change((T.Patch(0, proj.text, text),)) if text != proj.text else None,
            files,
            (copy.deepcopy(proj.ui), ui),
            (old_hidden, set()) if old_hidden else None,
        )

    def guessed(proj):
        # Systems inferred from the components stay marked guessed, with the Data
        # tab's "!", until Confirm (D58)
        if not any(s.inferred for s in proj.systems):
            return None
        data = proj.structure()
        data[P.GUESSED] = True
        return proj.set_ui(data)

    step = SN.compose(project, description, [replace, guessed])
    step.description = description
    # The preview: the lines of the model that go, and what comes
    lines = []
    if not project.paused:
        for line in project.parsed.text.lines:
            if line.kind in _MODEL_KINDS:
                lines.append(
                    R.PlanLine(line.num, R.DELETE, "replaced by the .mod", line.text)
                )
    snip_map = L.snip_transitions(project) if not project.paused else {}
    loaded = [(s.specid, posixpath.basename(s.member), m.row.name) for s, m in found]
    notes = [
        "Its model, as written, replaces the project's; run blind stays as the"
        " project has it ({0}).".format("blinded" if blind else "not blinded")
    ]
    if loaded:
        notes.append(
            "Snips loaded from beside it: {0}.".format(
                "; ".join(
                    "{0} (specid {1}, from {2})".format(f, s, r) for s, f, r in loaded
                )
            )
        )
    else:
        notes.append("It names no snips.")
    if project.snips:
        named = [
            SN.transition_name(snip_map.get(s.specid)) or s.specid
            for s in project.snips
        ]
        notes.append("The project's snips that go: {0}.".format(", ".join(named)))
    notes += _fwhm_notes(project, old, rows_of)
    plan = R.Plan(description, lines, notes=notes)
    return ModPlan(
        description,
        modfile,
        [],
        loaded,
        list(project.snips),
        notes,
        plan,
        step,
    )


