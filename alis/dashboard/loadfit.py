@dataclass
class Holders:
    """
    Which of the project's spectra hold each of a fit's snips, and why the others
    do not (Stage 11).

    Attributes
    ----------
    rows : list of tuple
        ``(row id, name)`` for each row with a source spectrum, in order.
    held : dict
        Specid to ``{row id: index}``: the source's pixel for each of the snip's.
    reasons : dict
        Specid to ``{row id: reason}`` for each row that does not hold it.
    cannot : dict
        Specid to ``{row id: reason}`` for each row that cannot take it, even cut
        again: too few pixels that can be fitted over its range (D113).

    Generated by RJC and Claude.
    """

    rows: list = field(default_factory=list)
    held: dict = field(default_factory=dict)
    reasons: dict = field(default_factory=dict)
    cannot: dict = field(default_factory=dict)

    def name(self, row_id):
        """A row's name."""
        return dict(self.rows).get(row_id, row_id)

    def holding(self, specid):
        """The rows that hold a snip, in order."""
        held = self.held.get(specid, {})
        return [rid for rid, _ in self.rows if rid in held]

    def also(self, specid, row_id):
        """The names of the other rows that hold a snip."""
        return [self.name(r) for r in self.holding(specid) if r != row_id]

    def why(self, specid):
        """Why no spectrum holds a snip: every spectrum's reason."""
        found = self.reasons.get(specid, {})
        return reasons_text([found[rid] for rid, _ in self.rows if rid in found])


def _good_counts(spec, sort):
    """The running count of a source's pixels that can be fitted, in wavelength
    order, so that those within a range are counted at once."""
    order = sort[0]
    good = L.good_pixels(
        spec.wave[order],
        spec.flux[order],
        spec.error[order],
        None if spec.mask is None else spec.mask[order],
    )
    return np.concatenate(([0], np.cumsum(good)))


def snip_holders(project, fit, spectra):
    """
    For each of a fit's snips, the rows whose source spectrum holds it
    (:func:`compare`: every pixel on the source's, with its flux and error), and for
    every other row why it does not, and whether it could take it cut again. Each
    source's wavelengths are sorted once.

    Parameters
    ----------
    project : Project
    fit : Fit
    spectra : dict
        Row id to its source spectrum; rows without one are left out.

    Returns
    -------
    Holders

    Generated by RJC and Claude.
    """
    rows = [(r.id, r.name) for r in project.rows if spectra.get(r.id) is not None]
    sorts = {rid: sorting(spectra[rid]) for rid, _ in rows}
    counts = {rid: _good_counts(spectra[rid], sorts[rid]) for rid, _ in rows}
    out = Holders(rows)
    for snip in fit.snips:
        held, reasons, cannot = {}, {}, {}
        px = snip.pixels
        for rid, name in rows:
            if px is None:
                reasons[rid] = cannot[rid] = "it is not a table of numbers."
                continue
            index, _, reason = compare(
                spectra[rid], name, px.wave, px.flux, px.error, sorts[rid]
            )
            if index is not None:
                held[rid] = index
                continue
            reasons[rid] = reason
            low, high = snip.extent
            srt = sorts[rid][1]
            good = counts[rid][np.searchsorted(srt, high, "right")]
            good -= counts[rid][np.searchsorted(srt, low, "left")]
            if good < SN.MIN_PIXELS:
                cannot[rid] = (
                    "{0} has {1} that can be fitted over its range ({2:.2f}–{3:.2f}"
                    " Å); a snip needs at least {4}.".format(
                        name, _count(int(good), "pixel"), low, high, SN.MIN_PIXELS
                    )
                )
        out.held[snip.specid] = held
        out.reasons[snip.specid] = reasons
        out.cannot[snip.specid] = cannot
    return out


@dataclass
class Assignment:
    """
    Where each of a fit's snips goes, as the dialog that assigns them returns it.

    Attributes
    ----------
    rows : dict
        Specid to the row it is assigned to, or None for a snip of none of the
        spectra (the dialog's right-hand list).
    load : dict
        Specid to False for a snip of none of the spectra that is left out (its
        Load tick off); the others are loaded.
    unassigned : str
        How the unassigned snips are loaded: :data:`ONE` dataset for each of the
        fit's datasets, or :data:`EACH` snip its own.

    Generated by RJC and Claude.
    """

    rows: dict = field(default_factory=dict)
    load: dict = field(default_factory=dict)
    unassigned: str = ONE

    def fate(self, specid, holders):
        """What becomes of a snip: :data:`HELD`, :data:`CUT`, :data:`UNASSIGNED` or
        :data:`LEFT_OUT`."""
        row = self.rows.get(specid)
        if row is None:
            return UNASSIGNED if self.load.get(specid, True) else LEFT_OUT
        return HELD if row in holders.held.get(specid, {}) else CUT

    def unassigned_specids(self, fit):
        """The snips loaded unassigned, in the model's order."""
        return [
            s.specid
            for s in fit.snips
            if self.rows.get(s.specid) is None and self.load.get(s.specid, True)
        ]


def best_guess(fit, holders):
    """
    The dashboard's best guess of where each snip goes: the row that holds it. One
    that several rows hold goes to the row that holds most of the other snips of its
    dataset (the first, if equal). One that no row holds is unassigned.

    Returns
    -------
    Assignment

    Generated by RJC and Claude.
    """
    order = [rid for rid, _ in holders.rows]
    rows = {}
    for dataset in fit.datasets:
        counts = {
            rid: sum(1 for sid in dataset.specids if rid in holders.held.get(sid, {}))
            for rid in order
        }
        for sid in dataset.specids:
            have = holders.holding(sid)
            rows[sid] = (
                max(have, key=lambda r: (counts[r], -order.index(r))) if have else None
            )
    return Assignment({s.specid: rows.get(s.specid) for s in fit.snips})


def unassigned_groups(fit, assignment):
    """
    The datasets the unassigned snips are loaded in: one for each of the fit's
    datasets, named after it (Q11.11), or one for each snip, named after its file.

    Returns
    -------
    list of tuple
        ``(name, specids)``.

    Generated by RJC and Claude.
    """
    loose = assignment.unassigned_specids(fit)
    if assignment.unassigned == EACH:
        return [(_member_name(fit.file_name(s))[0], [s]) for s in loose]
    out = []
    for dataset in fit.datasets:
        mine = [s for s in loose if s in dataset.specids]
        if mine:
            out.append(("{0} (unassigned)".format(dataset.name), mine))
    return out


def unassigned_overlaps(fit, assignment):
    """
    The unassigned snips that would share a dataset and overlap in wavelength, for
    the warning that advises a dataset for each (Prompt 4). Two that only meet at an
    edge do not overlap.

    Returns
    -------
    list of tuple
        ``(file name, file name, low, high)``: the two snips, and where they
        overlap in Å.

    Generated by RJC and Claude.
    """
    out = []
    for _, specids in unassigned_groups(fit, assignment):
        for one, two in itertools.combinations(specids, 2):
            first, second = fit.snip(one).extent, fit.snip(two).extent
            if first is None or second is None:
                continue
            low, high = max(first[0], second[0]), min(first[1], second[1])
            if low < high:
                out.append((fit.file_name(one), fit.file_name(two), low, high))
    return out


def _step_edges(wave):
    """The edges of each pixel's step: half way to its neighbours, and at an end as
    far from the pixel as its other edge."""
    wave = np.asarray(wave, dtype=float)
    if wave.size < 2:
        return wave.copy(), wave.copy()
    mid = 0.5 * (wave[1:] + wave[:-1])
    left = np.concatenate(([wave[0] - (mid[0] - wave[0])], mid))
    right = np.concatenate((mid, [wave[-1] + (wave[-1] - mid[-1])]))
    return left, right


def cut_again(spec, snip, sort=None, fitted=None):
    """
    A snip cut again from a source that does not hold it (Q11.9, Q11.10 (iii)): the
    source's pixels over the snip's own wavelength range, its fit range carried
    over by wavelength. A new pixel is fitted when its whole step lies within a
    fitted run of the old snip's, from its first pixel's step edge to its last's
    (D97), and it can be fitted.

    Parameters
    ----------
    spec : modes.Spectrum
    snip : Snip or FileSnip
    sort : tuple, optional
        The source's :func:`sorting`, when it has been made already.
    fitted : numpy.ndarray, optional
        The old snip's fitted pixels; by default its fit range
        (``snips.fitted``).

    Returns
    -------
    tuple
        ``(index, fit)``: the source's pixels in order of wavelength, and which of
        them are fitted.

    Generated by RJC and Claude.
    """
    order, srt = sorting(spec) if sort is None else sort
    low, high = snip.extent
    index = order[
        np.searchsorted(srt, low, "left") : np.searchsorted(srt, high, "right")
    ]
    wave = spec.wave[index]
    old_wave = snip.pixels.wave
    old_left, old_right = _step_edges(old_wave)
    old_fit = SN.fitted(snip) if fitted is None else np.asarray(fitted, dtype=bool)
    left, right = _step_edges(wave)
    step = np.diff(wave)
    tol = 1.0e-6 * (float(np.median(np.abs(step))) if step.size else 1.0)
    fit = np.zeros(wave.size, dtype=bool)
    edges = np.flatnonzero(np.diff(np.concatenate(([0], old_fit.astype(np.int8), [0]))))
    for first, stop in zip(edges[::2], edges[1::2]):
        fit |= (left >= old_left[first] - tol) & (right <= old_right[stop - 1] + tol)
    fit &= L.good_pixels(
        wave,
        spec.flux[index],
        spec.error[index],
        None if spec.mask is None else spec.mask[index],
    )
    return index, fit


def _cut_line(pm, item, word, has_bad):
    """
    The patch that points a data line at a snip cut again: its file, and its
    columns and fit range as the new file has them.

    Generated by RJC and Claude.
    """
    line = pm.text[item.line]
    edits = [(item.file.start, item.file.end, word)]
    added = []
    for name, value in (
        ("columns", SN.COLUMNS_BAD if has_bad else SN.COLUMNS),
        ("fitrange", "columns"),
    ):
        kw = item.keywords.get(name)
        if kw is not None:
            edits.append((kw.val.start, kw.val.end, value))
        else:
            added.append("{0}={1}".format(name, value))
    if added:
        end = line.content[1]
        edits.append((end, end, "   " + "   ".join(added)))
    text = line.text
    for first, stop, new in sorted(edits, reverse=True):
        text = text[:first] + new + text[stop:]
    return T.Patch(pm.text.offset(item.line), line.text, text)


def _cut_base(atom, row, fname):
    """A snip cut again's file name, as SNIP names its files:
    ``<row>_<El>_<stage>_<λ>``, or ``<row>_<old name>`` for a name that names no
    transition."""
    stem = re.sub(r"[^\w.+-]", "_", row.name)
    line = L.named_line(atom, fname)
    if line is None:
        return "{0}_{1}".format(stem, _member_name(fname)[0])
    return "{0}_{1}_{2}_{3:.1f}".format(
        stem, line.element, line.stage.replace("*", "s"), line.rest
    )


def _line_numbers(nums):
    nums = [n + 1 for n in nums]
    if len(nums) == 1:
        return "line {0}".format(nums[0])
    return "lines {0} and {1}".format(", ".join(str(n) for n in nums[:-1]), nums[-1])


def load_mod_plan(project, modfile, spectra, assignment=None, fit=None, holders=None):
    """
    The plan of Load a .mod…: the ``.mod``'s snips placed as an assignment says, and
    the step that makes its text the model and its snips the project's (Q7.1, Q7.3).

    Each snip has one of four fates (Stage 11, Q11.9): **held**, assigned to a row
    whose spectrum holds it, and loaded as it is; **cut again**, assigned to a row
    whose spectrum does not hold it, its pixels cut from that spectrum over its own
    range (:func:`cut_again`), its model values as the ``.mod`` has them;
    **unassigned**, loaded as it is in a dataset with no source
    (:func:`unassigned_groups`); or **left out**, its data line removed with the
    lines that only it uses, as CLEAR removes a snip.

    Parameters
    ----------
    project : Project
    modfile : str
    spectra : dict
        Row id to its source spectrum.
    assignment : Assignment, optional
        Where each snip goes; by default the best guess (:func:`best_guess`).
    fit, holders : optional
        The ``.mod`` read (:func:`read_fit`), and its snips' holders
        (:func:`snip_holders`), when they have been made already.

    Returns
    -------
    ModPlan

    Raises
    ------
    LoadError
        When the ``.mod`` cannot be read.

    Generated by RJC and Claude.
    """
    name = os.path.basename(modfile)
    fit = read_fit(modfile, project.registry) if fit is None else fit
    holders = snip_holders(project, fit, spectra) if holders is None else holders
    assignment = best_guess(fit, holders) if assignment is None else assignment
    old = fit.old
    description = "Load {0}".format(name)
    rows = {r.id: r for r in project.rows}
    sorts = {}
    problems, found, cuts, gone = [], [], {}, []
    fates = {}
    for snip in old.snips:
        fname = posixpath.basename(snip.member)
        fate = assignment.fate(snip.specid, holders)
        row_id = assignment.rows.get(snip.specid)
        fates[snip.specid] = fate
        if fate == LEFT_OUT:
            gone.append(snip)
            continue
        if snip.pixels is None:
            problems.append((fname, "it is not a table of numbers."))
            continue
        if fate == UNASSIGNED:
            continue
        if row_id not in rows or spectra.get(row_id) is None:
            problems.append(
                (fname, "it is assigned to {0}, which has no source.".format(row_id))
            )
            continue
        if fate == HELD:
            found.append((snip, Match(rows[row_id], holders.held[snip.specid][row_id])))
            continue
        why = holders.cannot.get(snip.specid, {}).get(row_id)
        if why:
            problems.append((fname, why))
            continue
        spec = spectra[row_id]
        sort = sorts.setdefault(row_id, sorting(spec))
        index, fitted = cut_again(spec, snip, sort)
        cuts[snip.specid] = (index, fitted)
        found.append((snip, Match(rows[row_id], index)))
    if problems:
        return ModPlan(description, modfile, problems, fit=fit, holders=holders)
    pm = old.parsed
    atom = L.atomic(project.registry)
    start = _datadirc_start(project, pm.datadirc)
    freed = [s.member for s in project.snips]
    # A project whose text does not read keeps the blinding it last read with
    blind = (project.last_read or project.parsed).blind
    patches, new_files, rows_of, cut_files = [], {}, {}, {}
    groups = unassigned_groups(fit, assignment)
    loose = [old.snip(s) for _, specids in groups for s in specids]
    for snip in [s for s, _ in found] + loose:
        item = snip.data
        rel = item.path(pm.datadirc).replace("\\", "/")
        member = posixpath.normpath(posixpath.join(start, rel))
        outside = not member.startswith(B.TREE) or member == project.model_member
        folder = posixpath.dirname(member)
        if outside:
            folder = posixpath.normpath(
                posixpath.join(posixpath.dirname(project.model_member), "..", "data")
            )
        if snip.specid in cuts:
            # Cut again: a new file, named as SNIP names its files
            row = next(m.row for s, m in found if s is snip)
            rows_of[item.line] = row.id
            index, fitted = cuts[snip.specid]
            spec = spectra[row.id]
            bad = None if spec.mask is None else spec.mask[index]
            base = _cut_base(atom, row, posixpath.basename(snip.member))
            member = SN.free_member(project, folder, base, new_files, freed)
            new_files[member] = SN.snip_bytes(
                spec.wave[index], spec.flux[index], spec.error[index], fitted, bad
            )
            cut_files[snip.specid] = member
            patches.append(
                _cut_line(pm, item, posixpath.relpath(member, start), bad is not None)
            )
            continue
        match = next((m for s, m in found if s is snip), None)
        if match is not None:
            rows_of[item.line] = match.row.id
        if outside or (
            member in new_files and new_files[member] != old.files[snip.member]
        ):
            # Its path from the model would leave the project's files: beside the
            # model's other snips instead
            stem, suffix = _member_name(posixpath.basename(snip.member))
            member = SN.free_member(project, folder, stem, new_files, freed, suffix)
            patches.append(
                T.replace_token(pm.text, item.file, posixpath.relpath(member, start))
            )
        new_files[member] = old.files[snip.member]
    removal = None
    if gone:
        # Left out: as CLEAR removes a snip, with the lines that only it uses
        removal = R.plan_snips(old, gone, "Leave out snips")
        patches += list(removal.change.patches)
    if pm.blind != blind:
        change = E.set_setting(pm, "run", "blind", "True" if blind else "False")
        patches += list(change.patches)
    text = T.Change.from_spans(patches).apply(old.text) if patches else old.text
    # The files: the project's snips go, the .mod's come
    files = {}
    for snip in project.snips:
        if snip.member in project.files and snip.member not in new_files:
            files[snip.member] = (project.files[snip.member], None)
    for member, content in new_files.items():
        if project.files.get(member) != content:
            files[member] = (project.files.get(member), content)
    # ui/project.json: the rows hold the .mod's snips, and the unassigned snips have
    # rows of their own, with no source; each snip's transition is recorded where it
    # can be placed, and guessed otherwise (Q7.4)
    ui = project.working_structure()
    ui.pop(CO.KNOTS, None)
    ui.pop(P.KEPT_NOTICES, None)
    ui.pop(SN.SNIPS, None)
    reference = _loaded_reference(project, found)
    entries = ui.setdefault("rows", [])
    for entry in entries:
        entry["specids"] = list(
            dict.fromkeys(s.specid for s, m in found if m.row.id == entry.get("id"))
        )
        if reference is not None:
            entry["reference"] = entry.get("id") == reference.id
    placed = [(s, m.row.id) for s, m in found]
    ids = {e.get("id") for e in entries}
    names = {e.get("name") for e in entries}
    unassigned_rows = []
    for group, specids in groups:
        num = len(entries) + 1
        while "r{0}".format(num) in ids:
            num += 1
        ident, label, more = "r{0}".format(num), group, 2
        while label in names:
            label, more = "{0} {1}".format(group, more), more + 1
        ids.add(ident)
        names.add(label)
        entries.append(
            {
                "id": ident,
                "name": label,
                "specids": list(specids),
                "reference": False,
                "source": None,
                "columns": None,
                "unassigned": True,
            }
        )
        unassigned_rows.append((label, specids))
        placed += [(old.snip(s), ident) for s in specids]
    for snip, row_id in placed:
        line = L.named_line(atom, posixpath.basename(snip.member))
        extent = snip.extent
        if line is None or extent is None:
            continue
        system = L.placing_system(
            project.systems, line.rest, extent, _data_shift(snip.data)
        )
        if system is None:
            continue
        ui.setdefault(SN.SNIPS, {})[snip.specid] = {
            "system": system.id,
            "ion": str(line.ion),
            "rest": float(line.rest),
            "row": row_id,
        }
        for entry in ui.get("systems", []):
            if entry.get("id") == system.id:
                known = entry.setdefault("lines", [])
                if not any(
                    e.get("ion") == line.ion
                    and abs(float(e.get("wave", -1.0)) - line.rest) < 0.01
                    for e in known
                ):
                    known.append({"ion": str(line.ion), "wave": float(line.rest)})
    fwhm = {}
    kept = {s.specid for s, _ in placed}
    for item in pm.data:
        par = item.param("resolution")
        if item.specid in kept and par is not None and par.start is not None:
            fwhm.setdefault(item.specid, float(par.start))
    if fwhm:
        ui[P.IMPORTED_FWHM] = fwhm
    else:
        ui.pop(P.IMPORTED_FWHM, None)
    old_hidden = set(project.extra_hidden)

    def replace(proj):
        return P.Step(
            "",
            T.Change((T.Patch(0, proj.text, text),)) if text != proj.text else None,
            files,
            (copy.deepcopy(proj.ui), ui),
            (old_hidden, set()) if old_hidden else None,
        )

    def guessed(proj):
        # Systems inferred from the components stay marked guessed, with the Data
        # tab's "!", until Confirm (D58)
        if not any(s.inferred for s in proj.systems):
            return None
        data = proj.structure()
        data[P.GUESSED] = True
        return proj.set_ui(data)

    step = SN.compose(project, description, [replace, guessed])
    step.description = description
    # The preview: the lines of the model that go, and what comes
    lines = []
    if not project.paused:
        for line in project.parsed.text.lines:
            if line.kind in _MODEL_KINDS:
                lines.append(
                    R.PlanLine(line.num, R.DELETE, "replaced by the .mod", line.text)
                )
    snip_map = L.snip_transitions(project) if not project.paused else {}
    held = [(s, m) for s, m in found if s.specid not in cuts]
    loaded = [(s.specid, posixpath.basename(s.member), m.row.name) for s, m in found]
    for label, specids in unassigned_rows:
        loaded += [(sid, fit.file_name(sid), label) for sid in specids]
    notes = [
        "Its model, as written, replaces the project's; run blind stays as the"
        " project has it ({0}).".format("blinded" if blind else "not blinded")
    ]
    if held:
        notes.append(
            "Snips loaded from beside it: {0}.".format(
                "; ".join(
                    "{0} (specid {1}, from {2})".format(
                        posixpath.basename(s.member), s.specid, m.row.name
                    )
                    for s, m in held
                )
            )
        )
    elif not old.snips:
        notes.append("It names no snips.")
    for snip, match in found:
        if snip.specid not in cuts:
            continue
        low, high = snip.extent
        notes.append(
            "{0} (specid {1}) is cut again from {2}, as {3}: its pixels become"
            " {2}'s over its own range ({4:.2f}–{5:.2f} Å), and its fit range is"
            " carried over.".format(
                posixpath.basename(snip.member),
                snip.specid,
                match.row.name,
                posixpath.basename(cut_files[snip.specid]),
                low,
                high,
            )
        )
    for label, specids in unassigned_rows:
        notes.append(
            "Loaded unassigned, with no source, in {0}: {1}.".format(
                label, ", ".join(fit.file_name(s) for s in specids)
            )
        )
    if gone:
        deleted = [e.line for e in removal.lines if e.action == R.DELETE]
        edited = [e.line for e in removal.lines if e.action == R.EDIT]
        words = "of {0}, {1} {2}".format(
            name, _line_numbers(deleted), "goes" if len(deleted) == 1 else "go"
        )
        if edited:
            words += ", and {0} {1} their specids".format(
                _line_numbers(edited), "loses" if len(edited) == 1 else "lose"
            )
        notes.append(
            "Left out: {0}; {1}.".format(
                ", ".join(posixpath.basename(s.member) for s in gone), words
            )
        )
    if project.snips:
        named = [
            SN.transition_name(snip_map.get(s.specid)) or s.specid
            for s in project.snips
        ]
        notes.append("The project's snips that go: {0}.".format(", ".join(named)))
    notes += _reference_notes(project, found, reference, name)
    notes += _fwhm_notes(project, old, rows_of)
    plan = R.Plan(description, lines, notes=notes)
    return ModPlan(
        description,
        modfile,
        [],
        loaded,
        list(project.snips),
        notes,
        plan,
        step,
        fit,
        holders,
        assignment,
        fates,
    )


