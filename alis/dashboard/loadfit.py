NO_NAME = (
    "its file name names no transition. prepfit names a snip"
    " <stem>_<ion>_<wavelength>_reg.dat, as in J0133_1H_I_1215.7_reg.dat."
)


class LoadError(Exception):
    """A file that cannot be loaded, and why."""


# -- Reading a snip file -------------------------------------------------------------


@dataclass
class OldSnip:
    """
    A snip read from a file: ``prepfit``'s, or one the dashboard exported.

    Attributes
    ----------
    path : str
    content : bytes
        The file, as read.
    wave, flux, error : numpy.ndarray
    fit : numpy.ndarray or None
        The fit range (True for a fitted pixel), when the file has one.
    bad : numpy.ndarray or None
        The bad-pixel mask (True for a bad pixel), when the file has one.

    Generated by RJC and Claude.
    """

    path: str
    content: bytes = field(repr=False)
    wave: np.ndarray = field(repr=False)
    flux: np.ndarray = field(repr=False)
    error: np.ndarray = field(repr=False)
    fit: np.ndarray | None = field(default=None, repr=False)
    bad: np.ndarray | None = field(default=None, repr=False)

    @property
    def name(self):
        """The file's name."""
        return os.path.basename(self.path)

    @property
    def extent(self):
        """Its wavelength range, ``(low, high)``."""
        return float(np.nanmin(self.wave)), float(np.nanmax(self.wave))


def _flags(values, message):
    """A column of 0s and 1s as booleans, or LoadError with ``message``."""
    if not np.all(np.isin(values, (0.0, 1.0))):
        raise LoadError(message)
    return values != 0


def read_snip_file(path, content=None):
    """
    Read a snip file: a table of 3 to 5 columns, wave, flux and error, then a fit
    range of 0s and 1s (``prepfit``'s fourth column), then a bad-pixel mask of 0s and
    1s (D52).

    Parameters
    ----------
    path : str
    content : bytes, optional
        The file, when it has been read already.

    Returns
    -------
    OldSnip

    Raises
    ------
    LoadError

    Generated by RJC and Claude.
    """
    if content is None:
        try:
            with open(path, "rb") as fil:
                content = fil.read()
        except OSError as err:
            raise LoadError("it cannot be read ({0}).".format(err.strerror or err))
    try:
        with warnings.catch_warnings():
            # An empty file is reported below, not warned about
            warnings.simplefilter("ignore", UserWarning)
            table = np.loadtxt(io.BytesIO(content), dtype=float, ndmin=2)
    except ValueError:
        raise LoadError(
            "it is not a table of numbers with the same number of columns on every"
            " line."
        ) from None
    if not table.size:
        raise LoadError("it holds no pixels.")
    ncols = table.shape[1]
    if not MIN_COLUMNS <= ncols <= MAX_COLUMNS:
        raise LoadError(
            "it has {0} column{1}. A snip has wave, flux and error, perhaps followed"
            " by a fit range of 0s and 1s and a bad-pixel mask.".format(
                ncols, "" if ncols == 1 else "s"
            )
        )
    fit = bad = None
    if ncols >= 4:
        fit = _flags(table[:, 3], "its fourth column is not a fit range of 0s and 1s.")
    if ncols == 5:
        bad = _flags(
            table[:, 4], "its fifth column is not a bad-pixel mask of 0s and 1s."
        )
    return OldSnip(path, content, table[:, 0], table[:, 1], table[:, 2], fit, bad)


# -- Matching a snip to its source spectrum -----------------------------------------


@dataclass
class Match:
    """
    The file row a snip was cut from.

    Attributes
    ----------
    row : Row
    index : numpy.ndarray
        The source's pixel for each of the snip's pixels.

    Generated by RJC and Claude.
    """

    row: object = field(repr=False)
    index: np.ndarray = field(repr=False)


def sorting(spec):
    """
    A source's finite wavelengths in order, made once for every snip compared with
    it (Stage 11: a spectrum of 100,000 pixels is not sorted again for each).

    Returns
    -------
    tuple
        ``(order, sorted)``: the pixels' indices in order of wavelength, and their
        wavelengths.

    Generated by RJC and Claude.
    """
    swave = np.asarray(spec.wave, dtype=float)
    good = np.flatnonzero(np.isfinite(swave))
    order = good[np.argsort(swave[good], kind="stable")]
    return order, swave[order]


def positions(spec, wave, sort=None):
    """
    The source pixel nearest each wavelength, and whether the wavelength is on it
    (within :data:`WAVE_TOLERANCE` of the pixel's width).

    Parameters
    ----------
    spec : modes.Spectrum
    wave : numpy.ndarray
    sort : tuple, optional
        The source's :func:`sorting`, when it has been made already.

    Returns
    -------
    tuple
        ``(index, on)``: arrays of int and bool, one value per wavelength.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    order, srt = sorting(spec) if sort is None else sort
    if srt.size < 2:
        return np.zeros(wave.size, dtype=int), np.zeros(wave.size, dtype=bool)
    pos = np.clip(np.searchsorted(srt, wave), 1, srt.size - 1)
    left, right = srt[pos - 1], srt[pos]
    with np.errstate(invalid="ignore"):
        near = np.where(np.abs(wave - left) <= np.abs(right - wave), pos - 1, pos)
        on = np.abs(srt[near] - wave) <= WAVE_TOLERANCE * (right - left)
    return order[near], on


def _same(values, source, scale):
    """Whether each value is the source's, to :data:`VALUE_TOLERANCE` of ``scale``."""
    with np.errstate(invalid="ignore"):
        close = np.abs(values - source) <= VALUE_TOLERANCE * scale
    return close | (values == source) | (np.isnan(values) & np.isnan(source))


def _count(num, what):
    return "{0} {1}{2}".format(num, what, "" if num == 1 else "s")


def compare(spec, name, wave, flux, error, sort=None):
    """
    Whether a snip's pixels are a source spectrum's: each wavelength one of its
    pixels, and the flux and error equal there.

    Parameters
    ----------
    spec : modes.Spectrum
    name : str
        The source's row, for the reason.
    wave, flux, error : numpy.ndarray
    sort : tuple, optional
        The source's :func:`sorting`, when it has been made already.

    Returns
    -------
    tuple
        ``(index, score, reason)``: the source's pixel for each of the snip's pixels
        (None when they do not match), the number of pixels that match, and why
        they do not.

    Generated by RJC and Claude.
    """
    npix = wave.size
    sort = sorting(spec) if sort is None else sort
    swave = sort[1]
    if not swave.size:
        return None, 0, "{0} has no wavelengths.".format(name)
    if np.nanmax(wave) < swave[0] or np.nanmin(wave) > swave[-1]:
        return (
            None,
            0,
            "it is outside the range of {0} ({1:.2f}–{2:.2f} Å).".format(
                name, swave[0], swave[-1]
            ),
        )
    index, on = positions(spec, wave, sort)
    if not on.all():
        off = npix - int(np.count_nonzero(on))
        return (
            None,
            int(np.count_nonzero(on)),
            "{0} of its {1} are not on {2}'s pixels.".format(
                off, _count(npix, "pixel"), name
            ),
        )
    if np.unique(index).size < npix:
        return None, 0, "some of its pixels repeat one pixel of {0}.".format(name)
    sflux = np.asarray(spec.flux, dtype=float)[index]
    serror = np.asarray(spec.error, dtype=float)[index]
    with np.errstate(invalid="ignore"):
        scale = np.where(np.isfinite(serror) & (serror > 0), serror, np.abs(sflux))
    scale = np.where(np.isfinite(scale), scale, 0.0)
    flux_off = ~_same(np.asarray(flux, dtype=float), sflux, scale)
    error_off = ~_same(np.asarray(error, dtype=float), serror, scale)
    if flux_off.any() or error_off.any():
        what = []
        if flux_off.any():
            what.append(
                "its flux differs from {0}'s at {1}".format(
                    name, _count(int(np.count_nonzero(flux_off)), "pixel")
                )
            )
        if error_off.any():
            what.append(
                "its error differs from {0}'s at {1}".format(
                    name, _count(int(np.count_nonzero(error_off)), "pixel")
                )
            )
        score = npix - int(np.count_nonzero(flux_off | error_off))
        return None, score, " and ".join(what) + " of its {0}.".format(npix)
    return index, npix, ""


def reasons_text(reasons):
    """
    Why no spectrum holds a snip, every spectrum's reason in the rows' order
    (Stage 11): one reason as it is, several joined by semicolons.

    Generated by RJC and Claude.
    """
    if not reasons:
        return "the project has no source spectrum to check it against."
    if len(reasons) == 1:
        return reasons[0]
    return "; ".join(r.rstrip(".") for r in reasons) + "."


def match_row(project, spectra, wave, flux, error):
    """
    The file row whose source spectrum a snip's pixels come from: the first that
    matches (:func:`compare`).

    Parameters
    ----------
    project : Project
    spectra : dict
        Row id to its source spectrum (``modes.Spectrum``); rows without one are
        left out.
    wave, flux, error : numpy.ndarray

    Returns
    -------
    Match

    Raises
    ------
    LoadError
        With every spectrum's reason (:func:`reasons_text`).

    Generated by RJC and Claude.
    """
    reasons = []
    for row in project.rows:
        spec = spectra.get(row.id)
        if spec is None:
            continue
        index, _, reason = compare(spec, row.name, wave, flux, error)
        if index is not None:
            return Match(row, index)
        reasons.append(reason)
    raise LoadError(reasons_text(reasons))


def place(project, name, extent, shift=0.0):
    """
    The transition a snip's file name names, and the system whose redshift puts it
    inside the snip (Q7.4).

    Returns
    -------
    tuple
        ``(system, line)``: a System, and a ``lines.Line``.

    Raises
    ------
    LoadError
        When the name names no transition, or no system puts it inside the snip.

    Generated by RJC and Claude.
    """
    line = L.named_line(L.atomic(project.registry), name)
    if line is None:
        raise LoadError(NO_NAME)
    if not project.systems:
        raise LoadError(
            "{0} cannot be placed: the project has no system yet. Set the primary"
            " redshift on the Data tab first.".format(line.name)
        )
    system = L.placing_system(project.systems, line.rest, extent, shift)
    if system is None:
        raise LoadError(
            "{0} is not inside it at the redshift of any system. Set the redshift on"
            " the Data tab, or add the system, first.".format(line.name)
        )
    return system, line


