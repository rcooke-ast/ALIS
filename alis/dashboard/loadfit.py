@dataclass
class Loaded:
    """
    A snip file, matched and placed.

    Attributes
    ----------
    old : OldSnip
    match : Match or None
        Its pixels in its row's source; None for a snip loaded unassigned.
    system : System
    line : lines.Line
    fate : str
        :data:`HELD`, :data:`CUT` or :data:`UNASSIGNED` (Stage 11).
    unassigned : Row or None
        The dataset with no source that an unassigned snip goes to.
    fitted : numpy.ndarray or None
        A snip cut again's fitted pixels.

    Generated by RJC and Claude.
    """

    old: OldSnip
    match: Match = field(repr=False)
    system: object = field(repr=False)
    line: object = field(repr=False)
    fate: str = "held"
    unassigned: object = field(default=None, repr=False)
    fitted: object = field(default=None, repr=False)

    @property
    def row(self):
        return self.match.row if self.match is not None else self.unassigned


@dataclass
class SnipsPlan:
    """
    What Load snips… does, before it is done.

    Attributes
    ----------
    description : str
    loaded : list of Loaded
    problems : list of tuple
        ``(file name, reason)`` for each file that cannot be loaded; with any,
        nothing is loaded.
    replaced : list of tuple
        ``(snip, loaded)``: each snip in the project that a loaded file replaces
        (Q7.2).
    plan : remove.Plan or None
        The lines the replacements remove, for the preview.
    step : Step or None
        None when there are problems.
    files : FileFit or None
        The files, as the dialog that assigns snips shows them (Stage 11).
    holders : Holders or None
    assignment : Assignment or None

    Generated by RJC and Claude.
    """

    description: str
    loaded: list = field(default_factory=list)
    problems: list = field(default_factory=list)
    replaced: list = field(default_factory=list)
    plan: object = field(default=None, repr=False)
    step: object = field(default=None, repr=False)
    files: object = field(default=None, repr=False)
    holders: object = field(default=None, repr=False)
    assignment: object = field(default=None, repr=False)

    @property
    def ok(self):
        """Whether every file can be loaded."""
        return not self.problems

    def preview(self, gate):
        """The lines the replacements remove, through the blinding gate."""
        return self.plan.preview(gate) if self.plan is not None else []

    @property
    def notes(self):
        """What the user is told before agreeing to the replacements."""
        out = []
        for snip, loaded in self.replaced:
            out.append(
                "{0} replaces the snip {1} of {2} in {3}.".format(
                    loaded.old.name, snip.specid, loaded.line.name, loaded.row.name
                )
            )
        for item in self.loaded:
            if item.fate == CUT:
                out.append(
                    "{0} is cut again from {1}: its pixels become {1}'s over its own"
                    " range, and its fit range is carried over.".format(
                        item.old.name, item.row.name
                    )
                )
            elif item.fate == UNASSIGNED:
                out.append(
                    "{0} is loaded unassigned, with no source, in {1}.".format(
                        item.old.name, item.row.name
                    )
                )
        return out

    def message(self):
        """The problems, one line per file, for the user."""
        return problems_text(self.problems, "Nothing was loaded.")


def problems_text(problems, ending):
    """
    The files that cannot be loaded, and why, one line each, then ``ending``.

    Generated by RJC and Claude.
    """
    lines = ["{0}: {1}".format(name, reason) for name, reason in problems]
    return "\n".join(lines + ["", ending])


def _member_name(name):
    """A file's name as a bundle member's: its stem and its suffix, made safe."""
    safe = re.sub(r"[^\w.+-]", "_", name)
    for suffix in ("_reg.dat", ".dat", ".txt", ".ascii"):
        if safe.endswith(suffix) and len(safe) > len(suffix):
            return safe[: -len(suffix)], suffix
    stem, suffix = posixpath.splitext(safe)
    return stem or "snip", suffix


def _content(loaded, spec):
    """
    A loaded snip's file as it is stored: as read, with a fit range of 0s added
    when it has none (no fit region until one is drawn, as for SNIP), and its
    source's bad pixels added when the source has a mask and the file does not
    (D52).

    Returns
    -------
    tuple
        ``(bytes, has_bad)``.

    Generated by RJC and Claude.
    """
    old = loaded.old
    content, has_bad = old.content, old.bad is not None
    if old.fit is None:
        content, _ = P.add_mask_column(content, np.zeros(old.wave.size, dtype=bool))
    if not has_bad and spec.mask is not None:
        content, _ = P.add_mask_column(content, spec.mask[loaded.match.index])
        has_bad = True
    return content, has_bad


def _clear_maker(specid):
    """A maker (for ``snips.compose``) that removes a snip as CLEAR removes it."""

    def make(proj):
        return SN.clear_plan(proj, proj.snip(specid)).step(proj)

    return make


def _snips_description(loaded, replaced):
    names = ", ".join(item.line.name for item in loaded)
    desc = "Load {0} ({1})".format(_count(len(loaded), "snip"), names)
    if replaced:
        desc += ", replacing {0}".format(len(replaced))
    return desc


def read_snip_files(project, paths):
    """
    The files Load snips… is given, read (:func:`read_snip_file`), each naming its
    transition (before the dialog that assigns them opens).

    Returns
    -------
    tuple
        ``(files, problems)``: a :class:`FileFit`, or None when there are
        problems, and ``(file name, reason)`` for each file that cannot be read or
        names no transition.

    Generated by RJC and Claude.
    """
    if not paths:
        return None, [("", "no file was chosen.")]
    atom = L.atomic(project.registry)
    olds, problems = [], []
    for path in paths:
        name = os.path.basename(path)
        try:
            old = read_snip_file(path)
            if L.named_line(atom, name) is None:
                raise LoadError(NO_NAME)
        except LoadError as err:
            problems.append((name, str(err)))
            continue
        olds.append(old)
    return (None if problems else FileFit(olds)), problems


def _unassigned_rows(project, groups, taken_ids=(), taken_names=()):
    """
    The rows of the unassigned snips' datasets, with no source, and their entries
    for ``ui/project.json``: new ids and names that no row uses.

    Returns
    -------
    list of tuple
        ``(Row, entry, specids)``.

    Generated by RJC and Claude.
    """
    entries = project.ui.get("rows", [])
    ids = {e.get("id") for e in entries} | {r.id for r in project.rows}
    ids |= set(taken_ids)
    names = {e.get("name") for e in entries} | {r.name for r in project.rows}
    names |= set(taken_names)
    out = []
    for group, specids in groups:
        num = len(ids) + 1
        while "r{0}".format(num) in ids:
            num += 1
        ident, label, more = "r{0}".format(num), group, 2
        while label in names:
            label, more = "{0} {1}".format(group, more), more + 1
        ids.add(ident)
        names.add(label)
        entry = {
            "id": ident,
            "name": label,
            "specids": [],
            "reference": False,
            "source": None,
            "columns": None,
            "unassigned": True,
        }
        out.append((P.Row(ident, label, unassigned=True), entry, list(specids)))
    return out


def load_snips_plan(
    project,
    paths,
    spectra,
    max_order=CO.AUTO_MAX,
    line_kms=CO.LINE_KMS,
    clip=CO.CLIP,
    assignment=None,
    files=None,
    holders=None,
):
    """
    The plan of Load snips…: each file placed as an assignment says, at its
    transition; the snips it replaces; and the step that loads them all.

    As a fit's snips (Stage 11, Q11.10 (iv)), each file is **held** (on its row's
    source pixels: loaded as it is), **cut again** from the spectrum it is given,
    **unassigned** (loaded as it is in a dataset with no source) or **left out**.
    A file that cannot be read, or names no transition, or whose transition no
    system puts inside it, stops the whole load (Q7.4).

    Parameters
    ----------
    project : Project
    paths : list of str
    spectra : dict
        Row id to its source spectrum.
    assignment : Assignment, optional
        Where each file goes; by default the best guess.
    files, holders : optional
        The files read (:func:`read_snip_files`) and their holders
        (:func:`snip_holders`), when they have been made already.

    Returns
    -------
    SnipsPlan

    Generated by RJC and Claude.
    """
    project.require_reading()
    if files is None:
        files, problems = read_snip_files(project, paths)
        if problems:
            return SnipsPlan("Load snips", [], problems)
    holders = snip_holders(project, files, spectra) if holders is None else holders
    assignment = best_guess(files, holders) if assignment is None else assignment
    rows = {r.id: r for r in project.rows}
    made = _unassigned_rows(project, unassigned_groups(files, assignment))
    loose = {sid: row for row, _, specids in made for sid in specids}
    problems, loaded = [], []
    for snip in files.snips:
        old, sid = snip.old, snip.specid
        fate = assignment.fate(sid, holders)
        if fate == LEFT_OUT:
            continue
        row_id = assignment.rows.get(sid)
        match, fitted = None, None
        try:
            if fate == HELD:
                match = Match(rows[row_id], holders.held[sid][row_id])
            elif fate == CUT:
                why = holders.cannot.get(sid, {}).get(row_id)
                if why:
                    raise LoadError(why)
                index, fitted = cut_again(spectra[row_id], snip, fitted=snip.fitted)
                match = Match(rows[row_id], index)
            shift = SN.row_shift(match.row) if match is not None else 0.0
            system, line = place(project, old.name, old.extent, shift)
        except LoadError as err:
            problems.append((old.name, str(err)))
            continue
        loaded.append(Loaded(old, match, system, line, fate, loose.get(sid), fitted))
    # Two files that share pixels of one spectrum (Q7.2)
    for one, two in itertools.combinations(loaded, 2):
        if (
            one.match is not None
            and two.match is not None
            and one.row.id == two.row.id
            and np.intersect1d(one.match.index, two.match.index).size
        ):
            problems.append(
                (
                    one.old.name,
                    "it shares pixels of {0} with {1}: load one of them.".format(
                        one.row.name, two.old.name
                    ),
                )
            )
    description = _snips_description(loaded, [])
    found = dict(files=files, holders=holders, assignment=assignment)
    if problems:
        return SnipsPlan(description, loaded, problems, **found)
    # The snips of the same rows that share their pixels, which they replace
    replaced = []
    for item in loaded:
        if item.match is None:
            continue
        spec = spectra[item.row.id]
        for snip in item.row.snips:
            if snip.pixels is None or any(s is snip for s, _ in replaced):
                continue
            index, on = positions(spec, snip.pixels.wave)
            if np.intersect1d(item.match.index, index[on]).size:
                replaced.append((snip, item))
    freed_files = [s.member for s, _ in replaced]
    freed_specids = [s.specid for s, _ in replaced]
    taken_files, taken_specids, news = [], [], []
    atom = L.atomic(project.registry)
    for item in loaded:
        row = item.row
        stem, suffix = _member_name(item.old.name)
        if item.fate == CUT:
            spec = spectra[row.id]
            index = item.match.index
            bad = None if spec.mask is None else spec.mask[index]
            content = SN.snip_bytes(
                spec.wave[index], spec.flux[index], spec.error[index], item.fitted, bad
            )
            has_bad = bad is not None
            stem, suffix = _cut_base(atom, row, item.old.name), "_reg.dat"
        elif item.fate == UNASSIGNED:
            content, has_bad = item.old.content, item.old.bad is not None
            if item.old.fit is None:
                content, _ = P.add_mask_column(
                    content, np.zeros(item.old.wave.size, dtype=bool)
                )
        else:
            content, has_bad = _content(item, spectra[row.id])
        member = SN.free_member(
            project,
            SN.snip_folder(project, row),
            stem,
            taken_files,
            freed_files,
            suffix,
        )
        specid = SN.new_specid(
            project, row, item.system, item.line, taken_specids, freed_specids
        )
        taken_files.append(member)
        taken_specids.append(specid)
        low, high = item.old.extent
        news.append(
            SN.NewSnip(
                row,
                member,
                specid,
                content,
                has_bad,
                low,
                high,
                SN.row_shift(row) if item.match is not None else 0.0,
                item.system.id,
                str(item.line.ion),
                float(item.line.rest),
            )
        )
    plan = None
    if replaced:
        lines, seen = [], set()
        for snip, _ in replaced:
            for entry in SN.clear_plan(project, snip).lines:
                if entry.line not in seen:
                    seen.add(entry.line)
                    lines.append(entry)
        plan = R.Plan(description, sorted(lines, key=lambda e: e.line))
    entries = [entry for _, entry, specids in made if specids]

    def add_rows(proj):
        # The unassigned snips' datasets, with no source, before their snips
        if not entries:
            return None
        data = proj.working_structure()
        data.setdefault("rows", []).extend(copy.deepcopy(entries))
        return proj.set_ui(data, "")

    makers = [add_rows] + [_clear_maker(s.specid) for s, _ in replaced]
    makers += SN.add_snip_makers(news, max_order, line_kms, clip)
    try:
        step = SN.compose(project, "", makers)
    except CO.ContinuumError as err:
        names = ", ".join(item.old.name for item in loaded)
        return SnipsPlan(
            description,
            loaded,
            [(names, "the continuum's first guess failed: {0}".format(err))],
            **found,
        )
    description = _snips_description(loaded, replaced)
    step.description = description
    if plan is not None:
        plan.description = description
    return SnipsPlan(description, loaded, [], replaced, plan, step, **found)


