def dataset_fwhm(fit, spec):
    """
    The FWHM of the fit's dataset whose snips a spectrum holds (the dataset with
    most of them, the first if equal), for the New project dialog of Open a fit
    (Stage 11); None when it holds none, or that dataset's resolution is not a
    ``vfwhm``.

    Generated by RJC and Claude.
    """
    sort = sorting(spec)
    best, count = None, 0
    for dataset in fit.datasets:
        held = 0
        for sid in dataset.specids:
            px = fit.snip(sid).pixels
            if px is None:
                continue
            index, _, _ = compare(spec, "", px.wave, px.flux, px.error, sort)
            held += index is not None
        if held > count:
            best, count = dataset, held
    return best.fwhm if best is not None else None


