# -- What can be written --------------------------------------------------------------


def best_fit_reason(project, view):
    """
    Why the best-fitting model cannot be written, or ``""`` (Q7.16(c), (e)).

    Generated by RJC and Claude.
    """
    if view is None:
        return NO_RUN
    if view.in_progress:
        return IN_PROGRESS
    if view.record is None or view.record.mod_out() is None:
        return "The shown run wrote no best-fitting model."
    return ""


def blinded(project, view=None):
    """Whether anything an export writes is hidden."""
    if project.hidden_lines() or project.parsed.blind:
        return True
    return view is not None and view.gate.global_blind


def run_reason(view):
    """Why the columns of a best fit cannot be written, or ``""``."""
    if view is None:
        return NO_RUN
    if view.in_progress:
        return IN_PROGRESS
    return ""


# -- The snips' files -------------------------------------------------------------------


def _safe(text):
    """A name for a file: its spaces and slashes as underscores."""
    return re.sub(r"[\s/\\]+", "_", text.strip()) or "project"


def project_name(session):
    """The project's name, as the files are named: without ``.model``."""
    name = os.path.basename(session.name)
    if name.endswith(B.SUFFIX):
        name = name[: -len(B.SUFFIX)]
    return _safe(name)


def file_names(project, name, gate=None):
    """
    The file of each snip, by its data line index (Q7.16(b)): the project's name, the
    ion with no space or mass number and the rest wavelength of the transition it was
    cut for, and its system's redshift to four places (``zabsBLIND`` while it is
    hidden).

    Generated by RJC and Claude.
    """
    gate = gate or BL.Gate(project)
    cut = L.snip_transitions(project)
    systems = {s.id: s for s in project.systems}
    out, taken = {}, set()
    for snip in project.snips:
        parts = [_safe(name)]
        trans = cut.get(snip.specid)
        if trans is None:
            parts.append(_safe(snip.specid))
        else:
            # No mass number, even for a rarer isotope ("13C IV" is CIV)
            ion = re.sub(r"^\d+", "", P.ion_name(trans.ion).replace(" ", ""))
            parts.append(ion)
            parts.append("{0:.2f}".format(trans.rest))
            system = systems.get(trans.system)
            if system is not None:
                hidden = gate.system_z(system) == BL.MASK
                parts.append("zabs" + (BLIND if hidden else "{0:.4f}".format(system.z)))
        stem = "_".join(parts)
        found, num = stem, 1
        while found in taken:
            num += 1
            found = "{0}_{1}".format(stem, num)
        taken.add(found)
        out[snip.data.index] = found + "_fit.dat"
    return out


def _transitions(project, snip, atom, gate):
    """
    The header's lines for the systems' transitions inside a snip: one line for
    each system with one, its redshift left out while it is hidden.

    Generated by RJC and Claude.
    """
    extent = snip.extent
    if extent is None:
        return []
    out = []
    for system in project.systems:
        ions = []
        for comp in system.components:
            ions += [i for i in comp.ions if i not in ions]
        found = [
            "{0} {1:.2f}".format(P.ion_name(ion), line.rest)
            for ion in ions
            for line in atom.ion_lines(ion)
            if extent[0] <= line.rest * (1.0 + system.z) <= extent[1]
        ]
        if not found:
            continue
        where = "at z = " + (
            "{0:.4f}".format(system.z) if gate.system_z(system) != BL.MASK else BLIND
        )
        out.append("Transitions {0}: {1}".format(where, ", ".join(found)))
    return out


def _zero_line(model, specid):
    """The zero level that covers a snip, or None."""
    for line in model.parsed.function_lines("constant", section="zerolevel"):
        if not line.specids or specid in line.specids:
            return line
    return None


def _fill(curve, wave):
    """A curve's arrays when they are on these pixels; else None."""
    if curve is None or curve.wave.size != wave.size:
        return None
    if not np.allclose(curve.wave, wave, equal_nan=True):
        return None
    return curve


@dataclass
class Table:
    """
    One snip's file.

    Attributes
    ----------
    index : int
        The snip's data line index.
    name : str
    words : list of str
        The columns it has, as its header names them.
    data : numpy.ndarray
        Pixels by columns.
    header : list of str
        Its ``#`` lines, the column names last.
    notes : list of str
        What was left out, and why.

    Generated by RJC and Claude.
    """

    index: int
    name: str
    words: list
    data: np.ndarray
    header: list = field(default_factory=list)
    notes: list = field(default_factory=list)

    def text(self):
        """The file's text."""
        formats = [_FORMATS.get(w, "%.8g") for w in self.words]
        rows = []
        for row in self.data:
            rows.append(
                " ".join(
                    (f % int(v)) if f == "%d" else (f % v) for f, v in zip(formats, row)
                )
            )
        return "\n".join(["# " + h for h in self.header] + rows) + "\n"


def reference_components(project, gate=None):
    """
    The components a velocity can be measured from (RJC's Prompt 8), as ``(id,
    label)``: those with a line, whose redshift is shown.

    Generated by RJC and Claude.
    """
    gate = gate or BL.Gate(project)
    out = []
    for system in project.systems:
        for comp in system.components:
            z = gate.redshift(comp)
            if comp.main is None or z == BL.MASK:
                continue
            label = "{0} · z = {1}".format(comp.id, z)
            # An unnamed system is named by its redshift, which says nothing more
            if not system.name.startswith("z ="):
                label += " · " + system.name
            out.append((comp.id, label))
    return out


def _reference_z(project, view, vector, cid, gate):
    """
    The redshift a velocity is measured from: the component's best fit (with a run)
    or its starting value; None while it is hidden, or with no such component.

    Generated by RJC and Claude.
    """
    comp = next((c for c in project.components if c.id == cid), None)
    if comp is None or comp.main is None or gate.redshift(comp) == BL.MASK:
        return None
    if view is not None and vector is not None:
        theirs = next((c for c in view.model.components if c.id == cid), None)
        main = None if theirs is None else theirs.main
        par = None if main is None else main.param("redshift")
        if par is not None and par.index >= 0:
            return None if view.gate.masked(par) else float(vector[par.index])
    return float(C.component_z(comp, C.linked_values(project)))


def _shift_wave(model, item, wave, values, hide):
    """
    A snip's wavelengths with its shift taken out (RJC's Prompt 8), as ALIS shifts
    the wavelengths it evaluates the model on, by whichever of its shift functions the
    data line names (``Ashift``, ``vshift``, ``vshiftscale``, ``polyshift``); None
    while a shift parameter is hidden. ``vshiftscale`` and ``polyshift`` scale about
    the middle pixel of the array they are given, here the snip's whole file.

    Generated by RJC and Claude.
    """
    wave = np.asarray(wave, dtype=float)
    pars = [p for p in item.params if p.role == "shift"]
    if any(hide(p) for p in pars):
        return None
    if item.shift is None or not pars:
        return wave
    numbers = np.array(
        [
            p.start if values is None or p.index < 0 else float(values[p.index])
            for p in pars
        ]
    )
    inst = model.registry.function(item.shift.name)
    return np.asarray(inst.call_CPU(wave, numbers), dtype=float)


def tables(project, name, keys, view=None, velocity_of=""):
    """
    The snips' files (Q7.16): one :class:`Table` each, with the columns ``keys`` in
    their order. A snip with no zero level in the model has 0 for one (ALIS's
    default).

    Parameters
    ----------
    project : Project
    name : str
        The project's name.
    keys : list of str
        :data:`COLUMNS` keys.
    view : results.View, optional
        The run whose best fit is written.
    velocity_of : str, optional
        The component the velocity is measured from (the first that can be, by
        default).

    Raises
    ------
    ExportError
        When ALIS cannot evaluate the model, or a best fit is asked for without one.

    Generated by RJC and Claude.
    """
    why = run_reason(view)
    if why and any(k in NEEDS_RUN for k in keys):
        raise ExportError(why)
    if view is not None and view.in_progress:
        view = None
    gate = BL.Gate(project)
    try:
        start = PR.of(project).evaluate()
    except PR.ProfileError as err:
        raise ExportError(str(err)) from None
    best, vector = {}, None
    if view is not None:
        try:
            best = view.curves()
            vector = view.vector()
        except Exception as err:
            raise ExportError(gate.message(str(err))) from None
    zref = None
    if any(k in VELOCITIES for k in keys):
        if not velocity_of:
            found = reference_components(project, gate)
            velocity_of = found[0][0] if found else ""
        zref = _reference_z(project, view, vector, velocity_of, gate)
    names = file_names(project, name, gate)
    atom = L.atomic(project.registry)
    cut = L.snip_transitions(project)
    stamp = datetime.date.today().isoformat()
    source = (
        "the best fit of {0}".format(view.name)
        if view is not None
        else "the starting model"
    )
    out = []
    for snip in project.snips:
        pix = snip.pixels
        if pix is None:
            continue
        notes = []
        mine = _fill(start.get(snip.data.index), pix.wave)
        fit = _fill(best.get(snip.data.index), pix.wave) if view is not None else None
        if view is not None and fit is None:
            notes.append("the run did not fit this snip as it is now")
        trans = cut.get(snip.specid)
        values = _columns(project, snip, view, vector, mine, fit, gate, notes)
        asked = [k for k in VELOCITIES if k in keys]
        if asked and zref is not None and trans is not None:
            for key in asked:
                if VELOCITIES[key] in values:
                    redshift = values[VELOCITIES[key]] / trans.rest - 1.0
                    values[key] = P.velocity(redshift, zref)
        elif asked:
            notes.append(
                "the velocities, as the transition the snip was cut for is not known"
                if trans is None
                else "the velocities, as no component's redshift can be shown"
            )
        words, cols = [], []
        for key in keys:
            if key in values:
                words.append(BY_KEY[key].word)
                cols.append(values[key])
        header = ["ALIS dashboard export of {0}, {1}".format(name, stamp)]
        header.append(
            "Snip {0}{1}".format(
                snip.specid,
                (
                    ""
                    if trans is None
                    else ", cut for {0} {1:.2f}".format(
                        P.ion_name(trans.ion), trans.rest
                    )
                ),
            )
        )
        header += _transitions(project, snip, atom, gate)
        header.append("Continuum and zero level: " + source)
        written = [k for k in VELOCITIES if k in keys and k in values]
        if written:
            on = {
                "velocity": "Velocity on the wavelength",
                "cvelocity": "Corrected velocity on the corrected wavelength",
            }
            header.append(
                "Velocities: km/s from {0} at z = {1:.6f} ({2}), for {3} {4:.2f}; "
                "{5}".format(
                    velocity_of,
                    zref,
                    "its best fit" if view is not None else "its starting value",
                    P.ion_name(trans.ion),
                    trans.rest,
                    ", ".join(on[k] for k in written),
                )
            )
        if "cwave" in values and "cwave" in keys:
            shift = snip.data.shift
            header.append(
                "Corrected wavelength: "
                + (
                    "the snip has no shift, so it is the wavelength"
                    if shift is None
                    else "the wavelength with its " + shift.name + " taken out"
                )
            )
        if any(k in NORMAL_KEYS for k in keys):
            header.append(
                "Normalised columns: {0}: {1}".format(
                    NORMALISED[0].lower() + NORMALISED[1:],
                    "; ".join(BY_KEY[k].tip for k in NORMAL_KEYS if k in keys),
                )
            )
        header += ["Not written: " + n for n in notes]
        header.append(" ".join(words))
        data = np.column_stack(cols) if cols else np.zeros((pix.wave.size, 0))
        index = snip.data.index
        out.append(Table(index, names[index], words, data, header, notes))
    return out


def _columns(project, snip, view, vector, mine, fit, gate, notes):
    """Every column a snip can have, by key; those it cannot have are left out."""
    pix = snip.pixels
    size = pix.wave.size
    nan = np.full(size, np.nan)
    out = {
        "wave": pix.wave,
        "flux": pix.flux,
        "error": pix.error,
        "fitrange": SN.fitted(snip).astype(int),
    }
    if mine is not None:
        out["start"] = mine.model
    # The zero level and the continuum: the best fit's, or the starting model's
    if view is not None:
        model, run_snip, hide = view.model, view.run_snip(snip), view.gate.masked
    else:
        model, run_snip, hide = project, snip, gate.is_hidden
    zero = None if run_snip is None else _zero_line(model, run_snip.specid)
    zeros = None
    if zero is None:
        # No zero level in the model: ALIS's default
        zeros = np.zeros(size)
    elif hide(zero.params[0]):
        notes.append("the zero level, which is hidden")
    else:
        par = zero.params[0]
        value = par.start if vector is None else float(vector[par.index])
        zeros = np.full(size, value)
    if zeros is not None:
        out["zero"] = zeros
    cont_line = None if run_snip is None else run_snip.continuum
    if cont_line is not None and any(hide(p) for p in cont_line.params):
        notes.append("the continuum, which is hidden")
        cont = None
    elif run_snip is None:
        cont = None
    else:
        cont = CO.evaluate(model, run_snip, wave=pix.wave, values=vector)
        if cont is None:
            # No continuum line: ALIS's continuum is 1
            cont = np.ones(size)
    if cont is not None:
        out["continuum"] = cont
    # The wavelength with the shift taken out (RJC's Prompt 8)
    if run_snip is not None:
        cwave = _shift_wave(model, run_snip.data, pix.wave, vector, hide)
        if cwave is None:
            notes.append(
                "the corrected wavelength and velocity, as the shift is hidden"
            )
        else:
            out["cwave"] = cwave
    if fit is not None:
        out["model"] = fit.model
        with np.errstate(divide="ignore", invalid="ignore"):
            resid = (pix.flux - fit.model) / pix.error
        resid[~(pix.error > 0)] = np.nan
        out["residual"] = resid
    elif view is not None:
        out["model"] = nan
        out["residual"] = nan
    # The normalised columns (RJC's Prompt 7): the zero level taken away, over the
    # continuum less the zero level; neither may be hidden
    if cont is not None and zeros is not None:
        base = cont - zeros
        with np.errstate(divide="ignore", invalid="ignore"):
            out["nflux"] = (pix.flux - zeros) / base
            out["nerror"] = pix.error / base
            if "model" in out:
                out["nmodel"] = (out["model"] - zeros) / base
    elif run_snip is not None:
        notes.append("the normalised columns, which would show a hidden value")
    return out


# -- The models -------------------------------------------------------------------------


def masked_start(project):
    """The model as it stands, each hidden value written as ``BLIND``."""
    return BL.Gate(project).view(mask=BLIND).text


def _copy_key(line):
    """A model line as ALIS's copy of it is matched: its words, the blind ones left
    out."""
    return " ".join(w for w in line.split() if not re.match(r"blind\w*=", w))


def masked_best(view, registry, text=None):
    """
    The shown run's ``.mod.out`` (or ``text``, one like it), its hidden values
    written as ``BLIND``: each best-fit value the gate masks (a hidden parameter's,
    every one under global blind, and those ALIS offsets); every ``blindseed`` and
    ``blindrange``, which would undo the offsets; and the lines of the input model
    ALIS copies into it, masked as the ``.mod`` panel masks them.

    Generated by RJC and Claude.
    """
    text = view.record.mod_out() if text is None else text
    mtext = T.ModelText(text)
    pm = M.ParsedModel(mtext, registry)
    run = view.model.parsed
    hidden = {p.index for p in run.params if view.gate.masked(p)}
    spans = {
        (p.value_token.line, p.value_token.start, p.value_token.end)
        for p in pm.params
        if p.index in hidden and p.value_token is not None
    }
    out = BL.MaskedView(mtext, sorted(spans), BLIND).text.split("\n")
    # The input model's lines, as the panel shows them; a line hidden since the run
    # is masked whole
    shown = view.gate.run.view(mask=BLIND).lines()
    copies = {}
    for num in range(min(len(run.text), len(shown))):
        if shown[num] != run.text[num].text:
            copies[_copy_key(run.text[num].text)] = shown[num]
    for par in run.params:
        if view.gate.is_hidden(par) and par.line < len(run.text):
            copies.setdefault(_copy_key(run.text[par.line].text), None)
    for num, line in enumerate(out):
        body = line.lstrip()
        key = _copy_key(body.lstrip("#"))
        if not body.startswith("#") or key not in copies:
            continue
        if copies[key] is not None:
            out[num] = "#   " + copies[key]
        else:
            masked = BL.MaskedView(
                T.ModelText(line),
                [(0, a, b) for a, b in BL.line_value_spans(line)],
                BLIND,
            )
            out[num] = masked.text
    text = "\n".join(out)
    return re.sub(r"(?<!\S)(blindseed|blindrange)=\S+", r"\1=" + BLIND, text)


def _set_word(line, key, value):
    """A data line with ``key=value``, replaced or added."""
    pattern = r"(?<!\S){0}=\S+".format(re.escape(key))
    if re.search(pattern, line):
        return re.sub(pattern, "{0}={1}".format(key, value), line, count=1)
    return line.rstrip() + "  {0}={1}".format(key, value)


def point_at(text, registry, files):
    """
    A model's text with its data lines naming the snips' exported files (Q7.16(d)):
    ``files`` maps a data line index to ``(file name, [(column word, place), ...])``.
    ``run datadirc`` becomes ``./``.

    Generated by RJC and Claude.
    """
    pm = M.ParsedModel(T.ModelText(text), registry)
    lines = [pm.text[n].text for n in range(len(pm.text))]
    for item in pm.data:
        if item.index not in files:
            continue
        name, columns = files[item.index]
        line = lines[item.line]
        tok = item.file
        line = line[: tok.start] + name + line[tok.end :]
        line = _set_word(
            line,
            "columns",
            "[" + ",".join("{0}:{1}".format(w, n) for w, n in columns) + "]",
        )
        line = _set_word(line, "fitrange", "columns")
        lines[item.line] = line
    out = "\n".join(lines) + ("\n" if text.endswith("\n") else "")
    return re.sub(r"(?m)^(\s*run\s+datadirc\s+)\S+", r"\g<1>./", out)


