@dataclass
class Choice:
    """
    What the dialog asks for.

    Attributes
    ----------
    snips, start, best, everything : bool
    columns : list of str
        :data:`COLUMNS` keys, in their order.
    folder : str
    velocity_of : str
        The component the Velocity column is measured from.

    Generated by RJC and Claude.
    """

    snips: bool = True
    start: bool = True
    best: bool = True
    everything: bool = False
    columns: list = field(default_factory=lambda: [c.key for c in COLUMNS if c.default])
    folder: str = ""
    velocity_of: str = ""


def plan(session, choice, view=None):
    """
    The files an export writes but "everything" (:func:`everything`), as
    ``{path: bytes}``, and notes for the user.

    Raises
    ------
    ExportError

    Generated by RJC and Claude.
    """
    project = session.project
    out, notes = {}, []
    folder = choice.folder
    name = project_name(session)
    # Data line index to the snip's file and the columns ALIS reads in it
    files = {}
    if choice.snips:
        found = tables(project, name, choice.columns, view, choice.velocity_of)
        for table in found:
            out[os.path.join(folder, table.name)] = table.text().encode("utf-8")
            if all(w in table.words for w in FOR_ALIS):
                places = [(w, table.words.index(w)) for w in FOR_ALIS]
                files[table.index] = (table.name, places)
        if found and not files:
            notes.append(
                "The models keep their own data lines: the snips were written"
                " without their wavelength, flux, error and fit range."
            )
    bundle = session.to_bundle()
    if blinded(project, view) and (choice.start or choice.best):
        notes.append(HIDDEN.format(name))
    if choice.start:
        text = masked_start(project)
        if files:
            text = point_at(text, project.registry, files)
        out[os.path.join(folder, name + "_start.mod")] = text.encode("utf-8")
    if choice.best:
        why = best_fit_reason(project, view)
        if why:
            raise ExportError("The best-fitting model cannot be written. " + why)
        text = masked_best(view, project.registry)
        if files:
            ours = {}
            for snip in project.snips:
                theirs = view.run_snip(snip)
                if theirs is not None and snip.data.index in files:
                    ours[theirs.data.index] = files[snip.data.index]
            text = point_at(text, view.model.registry, ours)
        out[os.path.join(folder, name + "_bestfit.mod.out")] = text.encode("utf-8")
    if choice.start or choice.best:
        atomic = B.atomic_to_write(bundle)
        if atomic is not None:
            table_name, table = atomic
            out[os.path.join(folder, table_name)] = table
            notes.append(
                "The project's atomic table differs from the one installed with"
                " ALIS, so it is written beside the models: " + table_name
            )
    return out, notes


def everything(session, folder, overwrite=False):
    """Everything run_alis needs, for File ▸ Export… (:func:`extract`)."""
    return extract(
        session.to_bundle(), session.project, project_name(session), folder, overwrite
    )


def extract(bundle, project, name, folder, overwrite=False):
    """
    Everything run_alis needs (``bundle.extract``, D10), its hidden values written as
    ``BLIND``: for File ▸ Export… and for ``run_alis --extract`` alike (RJC's
    Prompt 6). A project with nothing hidden is written as it is, byte for byte.

    Parameters
    ----------
    bundle : Bundle
    project : Project
        The bundle's project.
    name : str
        The project's name, for the note.
    folder : str
    overwrite : bool

    Raises
    ------
    bundle.BundleError
        When a file exists already and ``overwrite`` is not set.

    Generated by RJC and Claude.
    """
    try:
        view = RS.View.latest(project)
    except RS.ResultsError:
        view = None
    hidden = blinded(project, view)
    written, notes = B.extract(
        bundle,
        folder,
        overwrite=overwrite,
        model_text=masked_start(project) if hidden else None,
        blind_comments=True,
    )
    if hidden:
        notes.append(HIDDEN.format(name))
        # The bundle's .mod.out writes ALIS's offsets, and the seed that undoes them
        for path in written:
            if view is None or not path.endswith(".mod.out"):
                continue
            if view.record.mod_out() is not None:
                with open(path, "w") as fil:
                    fil.write(masked_best(view, project.registry))
    return written, notes


def write(planned, overwrite=False):
    """
    Write the planned files.

    Raises
    ------
    FileExistsError
        When one exists already and ``overwrite`` is not set.

    Generated by RJC and Claude.
    """
    if not overwrite:
        there = [p for p in planned if os.path.exists(p)]
        if there:
            raise FileExistsError(there[0])
    for path, data in planned.items():
        os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
        with open(path, "wb") as fil:
            fil.write(data)
    return sorted(planned)


