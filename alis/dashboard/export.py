"""Exporting only what is needed (RJC's review of Stage 7, Q7.16). No Qt.

File ▸ Export… writes, to a folder of the user's choice, any of:

- **the snips**, one ASCII file each, named after the project, the transition the
  snip was cut for and its system's redshift
  (``J101155p294141_HI_1215.67_zabs2.5020_fit.dat``; ``_2``, ``_3`` when two would
  share a name), with the columns chosen under a ``#`` header that names them, the
  snip's transitions and where the fit came from. Wavelength, Flux, Error, Fit range
  (1 for a fitted pixel, 0 otherwise), Zero level (0, ALIS's default, for a snip
  with none in the model; RJC's review), Continuum and Best-fit model by default;
  Velocity (from a component chosen, on the wavelength), Starting model, Corrected
  wavelength (the snip's shift taken out) and Corrected velocity (on it; RJC's
  Prompts 8 and 9), Normalised flux, error and best-fit model
  (the zero level taken away, over the continuum less the zero level; RJC's Prompt
  7), and Residual on request;
- **the starting model**, the ``.mod`` as it stands;
- **the best-fitting model**, the ``.mod.out`` of the run the Fit tab shows
  (``<project>_bestfit.mod.out``);
- **everything** ``run_alis`` needs: the model, every snip and the latest run's
  outputs, as Export plain files… wrote them before (``bundle.extract``).

The best fit is the shown run's: the Best-fit model and Residual columns need one,
and the Continuum and Zero level are its own (the starting model's without a run).
When the snips are written with their wavelength, flux, error and fit range, the
models' data lines name the snip files instead, so that ``run_alis`` runs either
model in that folder.

Hidden values stay hidden (RJC's response to Q7.16): each is written as ``BLIND`` in
the models (and in "everything"), with the lines of the input model that ALIS copies
into the ``.mod.out`` masked whole when they hold one; a hidden redshift is
``zabsBLIND`` in a file's name; a continuum or zero level whose value is hidden is
left out of its snip's file, and the header says so. A blinded project's exported
models therefore run only once it is unblinded; ``run_alis`` runs the project itself.

Generated by RJC and Claude.
"""

