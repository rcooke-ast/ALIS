"""The Data tab's edits: file rows and systems (dashboard Stage 4.4).

No Qt. Each function returns one step for the history, or a plan to show first.

- **File rows** (S25, D14, D35, Q0.5, Q0.8): the reference (its shift fixed at 0, the
  old reference's freed); the FWHM and the shift (a value, free, fixed, or tied to
  another row); the zero level on and off; a new file as a row (Stage 3's dialog, S3);
  a row renamed; a row's column roles, while it has no snips (Q4.14). Rows are never
  merged (Q4.14). Removing a row is ``remove.plan_dataset``.
- **Systems** (D15, D16, S24): the redshift (which moves nothing, D16), a new system,
  a name, the primary; removing one is ``remove.plan_system``.
- **An imported fit's structure** (Q2.4, Q4.14): the systems and rows guessed from
  the model are written into ``ui/project.json`` by the first edit, or by
  ``project.confirm_structure()``.

Generated by RJC and Claude.
"""

import copy
import os

from alis import bundle as B
from alis.dashboard import edit as E
from alis.dashboard import modes
from alis.dashboard import project as P
from alis.dashboard import text as T

FREE, FIXED, TIED = "free", "fixed", "tied"


class DatasetError(Exception):
    """A Data tab action that cannot be done as asked."""


def _structure(project):
    """
    ``ui/project.json`` with its rows and systems written out (Q2.4), still marked
    guessed for an imported fit until it is confirmed (Q4.18).
    """
    return project.working_structure()


def _ui_step(project, ui, description):
    return P.Step(description, ui=(copy.deepcopy(project.ui), copy.deepcopy(ui)))


def _entry(ui, key, ident):
    for entry in ui.get(key, []):
        if entry.get("id") == ident:
            return entry
    raise DatasetError("There is no {0} {1}.".format(key[:-1], ident))


def keep_structure(project, step):
    """
    A step that also writes out an imported fit's guessed systems and rows, when
    ``ui/project.json`` does not hold them yet (Q2.4, Q4.14): rows are guessed from
    shared resolution labels, so an edit such as a tie would otherwise merge two rows,
    and datasets are never merged. The structure stays marked guessed, and the Data
    tab's "!" stays, until the user confirms it (Q4.18).

    Generated by RJC and Claude.
    """
    if step is None or ("rows" in project.ui and "systems" in project.ui):
        return step
    if step.ui is not None:
        return step
    step.ui = (copy.deepcopy(project.ui), project.working_structure())
    return step


def _then(project, steps, description):
    """
    Steps made one after the other on the project, as one step (each sees the model
    as the one before left it).

    Generated by RJC and Claude.
    """
    done = []
    try:
        for make in steps:
            step = make(project)
            if step is None or not step:
                continue
            project.apply(step)
            done.append(step)
    finally:
        for step in reversed(done):
            project.revert(step)
    if not done:
        return P.Step(description)
    out = done[0]
    for step in done[1:]:
        out = out.then(step)
    out.description = description
    return out


# -- File rows ------------------------------------------------------------------------


def state_of(row, what):
    """
    A row's FWHM or shift as its badge shows it (D35): ``"free"``, ``"fixed"`` or
    ``"tied"`` (its label shared with another row), or None when it has none.

    Parameters
    ----------
    what : str
        ``"resolution"`` or ``"shift"``.

    Generated by RJC and Claude.
    """
    par = row.snips[0].data.param(what) if row.snips else None
    if par is None:
        return None
    return FIXED if par.fixed else FREE


def tied_to(project, row, what):
    """
    The other rows whose FWHM or shift is the same parameter as this row's (Q0.8).

    Generated by RJC and Claude.
    """
    par = row.snips[0].data.param(what) if row.snips else None
    if par is None or not par.label:
        return []
    out = []
    for other in project.rows:
        if other is row or not other.snips:
            continue
        theirs = other.snips[0].data.param(what)
        if theirs is not None and theirs.label == par.label:
            out.append(other)
    return out


def set_value_step(project, row, what, value):
    """
    The step that sets a row's FWHM or shift (``edit.set_fwhm``, ``edit.set_shift``).

    Generated by RJC and Claude.
    """
    project.require_reading()
    if not row.snips:
        # A row with no snips keeps its starting FWHM in ui/project.json
        if what != "resolution":
            raise DatasetError("A dataset with no snips has no shift yet.")
        ui = _structure(project)
        _entry(ui, "rows", row.id)["fwhm"] = float(value)
        return _ui_step(
            project, ui, "Set the FWHM of {0} to {1}".format(row.name, value)
        )
    pm = project.parsed
    lines = row.data_lines
    if what == "resolution":
        change = E.set_fwhm(pm, lines, value)
        name = "FWHM"
    else:
        number = [r.id for r in project.rows].index(row.id) + 1
        change = E.set_shift(pm, lines, value, E.new_row_labels(pm, number)["shift"])
        name = "shift"
    return keep_structure(
        project,
        project.step(
            change,
            "Set the {0} of {1} to {2}".format(name, row.name, E.format_value(value)),
        ),
    )


def set_state_step(project, row, what, state, other=None):
    """
    The step that makes a row's FWHM or shift free, fixed, or tied to another row's
    (its badge, D35, Q0.8).

    Parameters
    ----------
    state : str
        ``"free"``, ``"fixed"`` or ``"tied"``.
    other : Row, optional
        The row to tie to.

    Generated by RJC and Claude.
    """
    project.require_reading()
    if not row.snips:
        raise DatasetError("Cut a snip of {0} first.".format(row.name))
    pm = project.parsed
    name = "FWHM" if what == "resolution" else "shift"
    if state == TIED:
        if other is None or not other.snips:
            raise DatasetError("Choose a dataset with snips to tie to.")
        change = E.tie_rows(pm, row.data_lines, other.data_lines, what)
        return keep_structure(
            project,
            project.step(
                change, "Tie the {0} of {1} to {2}".format(name, row.name, other.name)
            ),
        )
    par = row.snips[0].data.param(what)
    if par is None:
        raise DatasetError("{0} has no {1} to change.".format(row.name, name))
    if not par.label:
        number = [r.id for r in project.rows].index(row.id) + 1
        label = E.new_row_labels(pm, number)[what]
        if state == FIXED:
            label = label.upper()
        change = _label_rows(pm, row.data_lines, what, label)
    elif state == FIXED:
        change = E.fix(pm, par)
    else:
        change = E.free(pm, par)
    return keep_structure(
        project,
        project.step(
            change,
            "{0} the {1} of {2}".format(
                "Fix" if state == FIXED else "Free", name, row.name
            ),
        ),
    )


def _label_rows(pm, lines, what, label):
    """Give a row's resolution or shift one label on every data line."""
    patches = []
    for item in lines:
        par = item.param(what)
        if par is None or par.token is None or par.value_token is None:
            continue
        word = par.value_token.text + label
        patches.append(T.replace_token(pm.text, par.token, word))
    return T.Change.from_spans(patches, "")


def set_reference_step(project, row):
    """
    The step that makes a row the reference (D14): its shift fixed at 0 (its lines
    lose their shift), and the old reference's shift freed (a new free shift where it
    had none).

    Generated by RJC and Claude.
    """
    project.require_reading()
    old = next((r for r in project.rows if r.reference), None)
    if old is not None and old.id == row.id:
        raise DatasetError("{0} is the reference already.".format(row.name))
    number = [r.id for r in project.rows].index(old.id) + 1 if old else 1

    def new_ref(proj):
        here = proj.row(row.id)
        pm = proj.parsed
        patches = []
        for item in here.data_lines:
            if "shift" in item.keywords:
                patches.append(_remove_word(pm, item, "shift"))
        if not patches:
            return None
        return proj.step(T.Change.from_spans(patches, ""), "")

    def old_ref(proj):
        if old is None:
            return None
        there = proj.row(old.id)
        if not there.snips:
            return None
        pm = proj.parsed
        par = there.snips[0].data.param("shift")
        if par is None or "shift" not in there.snips[0].data.keywords:
            # No shift written (ALIS's default, none): a new free one
            label = E.new_row_labels(pm, number)["shift"]
            return proj.step(E.set_shift(pm, there.data_lines, 0.0, label), "")
        if par.fixed:
            if par.label:
                return proj.step(E.free(pm, par), "")
            label = E.new_row_labels(pm, number)["shift"]
            return proj.step(_label_rows(pm, there.data_lines, "shift", label), "")
        return None

    def flags(proj):
        ui = _structure(proj)
        for entry in ui.get("rows", []):
            entry["reference"] = entry.get("id") == row.id
        return _ui_step(proj, ui, "")

    return _then(
        project, [new_ref, old_ref, flags], "Make {0} the reference".format(row.name)
    )


def _remove_word(pm, item, name):
    """The patch that removes ``name=...`` from a data line, with its gap."""
    kw = item.keywords[name]
    line = pm.text[item.line]
    start = kw.token.start
    while start > 0 and line.text[start - 1] in " \t":
        start -= 1
    offset = pm.text.offset(item.line)
    return T.Patch(offset + start, line.text[start : kw.token.end], "")


def zero_level_step(project, row, on):
    """
    The step that switches a row's zero level on (one free ``constant`` with its
    specids, D14) or off (its specids removed from the constant, which goes when it
    has none left).

    Generated by RJC and Claude.
    """
    project.require_reading()
    pm = project.parsed
    if not row.snips:
        ui = _structure(project)
        _entry(ui, "rows", row.id)["zerolevel"] = bool(on)
        return _ui_step(
            project,
            ui,
            "Zero level of {0}: {1}".format(row.name, "on" if on else "off"),
        )
    if on:
        if row.zero is not None:
            raise DatasetError("{0} has a zero level already.".format(row.name))
        change = E.add_zero_level(pm, row.specids, 0.0)
    else:
        if row.zero is None:
            raise DatasetError("{0} has no zero level.".format(row.name))
        change = E.set_zero_level(pm, row.specids, None)
    return keep_structure(
        project,
        project.step(
            change, "Zero level of {0}: {1}".format(row.name, "on" if on else "off")
        ),
    )


def zero_level_shared(project, row):
    """The other rows that share this row's zero level (it is tied, Q0.8)."""
    if row.zero is None:
        return []
    return [
        r
        for r in project.rows
        if r is not row and r.specids and set(r.specids) <= set(row.zero.specids)
    ]


def add_file_step(project, path, columns=None, fwhm=7.0, bundle_path=None):
    """
    The step that adds a spectrum as a new file row (Add file…, S3, D35): its source
    recorded by path and checksum, its column roles and its starting FWHM; it has no
    snips until they are cut on the Regions tab.

    Parameters
    ----------
    path : str
    columns : dict, optional
        The column roles from Stage 3's dialog; D13's rule by default.
    fwhm : float
        In km/s.
    bundle_path : str, optional
        The project's file, so that the source is also kept by its path from it.

    Generated by RJC and Claude.
    """
    project.require_reading()
    mode = modes.get(project.ui.get("mode", "qso_abs_line"))
    try:
        spec = mode.load(path, columns)
    except modes.ModeError as error:
        raise DatasetError(str(error)) from None
    ui = _structure(project)
    names = {e.get("name") for e in ui.get("rows", [])}
    stem = os.path.splitext(os.path.basename(path))[0]
    name, extra = stem, 2
    while name in names:
        name, extra = "{0}_{1}".format(stem, extra), extra + 1
    copy_ = copy.deepcopy(project.bundle)
    entry = B.add_source(copy_, path, dataset=name, bundle_path=bundle_path)
    ids = {e.get("id") for e in ui.get("rows", [])}
    num = len(ui.get("rows", [])) + 1
    while "r{0}".format(num) in ids:
        num += 1
    ui.setdefault("rows", []).append(
        {
            "id": "r{0}".format(num),
            "name": name,
            "specids": [],
            "reference": not ui["rows"],
            "source": entry["id"],
            "columns": spec.columns,
            "fwhm": float(fwhm),
        }
    )
    step = _ui_step(project, ui, "Add the file " + os.path.basename(path))
    step.sources = (copy.deepcopy(project.bundle.sources), copy.deepcopy(copy_.sources))
    return step


def rename_row_step(project, row, name):
    """
    The step that renames a row (its name in ``ui/project.json``).

    Generated by RJC and Claude.
    """
    name = name.strip()
    if not name:
        raise DatasetError("A dataset needs a name.")
    ui = _structure(project)
    if any(e.get("name") == name and e.get("id") != row.id for e in ui.get("rows", [])):
        raise DatasetError("Another dataset is called {0}.".format(name))
    _entry(ui, "rows", row.id)["name"] = name
    return _ui_step(project, ui, "Rename {0} to {1}".format(row.name, name))


def columns_step(project, row, columns):
    """
    The step that changes a row's column roles (Q4.14): only while it has no snips,
    since its snips were cut with the roles it had.

    Generated by RJC and Claude.
    """
    if row.snips:
        raise DatasetError(
            "The snips of {0} were cut with its column roles; CLEAR them before"
            " changing the roles.".format(row.name)
        )
    problem = modes.check_roles(columns, max(columns.values()) + 1 if columns else 0)
    if problem and "no column" not in problem:
        raise DatasetError(problem)
    ui = _structure(project)
    _entry(ui, "rows", row.id)["columns"] = dict(columns)
    return _ui_step(project, ui, "Change the columns of " + row.name)


# -- Systems (D15, D16, S24) ------------------------------------------------------------


def _auto_name(entry):
    """Whether a system's name is the one made from its redshift."""
    try:
        return entry.get("name") == "z = {0:.5f}".format(float(entry.get("z")))
    except (TypeError, ValueError):
        return False


def set_z_step(project, system, z):
    """
    The step that sets a system's redshift (D16): it re-centres the views, and moves
    no snip and no component.

    Generated by RJC and Claude.
    """
    z = float(z)
    if z < 0:
        raise DatasetError("A redshift cannot be negative.")
    ui = _structure(project)
    entry = _entry(ui, "systems", system.id)
    if _auto_name(entry):
        entry["name"] = "z = {0:.5f}".format(z)
    entry["z"] = z
    return _ui_step(project, ui, "Set the redshift of {0}".format(system.name))


def add_system_step(project, z, name=None, primary=None):
    """
    The step that adds a system (Add system…, Identify a feature, D15): the primary
    when there is none yet.

    Generated by RJC and Claude.
    """
    z = float(z)
    if z < 0:
        raise DatasetError("A redshift cannot be negative.")
    ui = _structure(project)
    systems = ui.setdefault("systems", [])
    letters = {e.get("id") for e in systems}
    ident = next(chr(c) for c in range(ord("a"), ord("z") + 1) if chr(c) not in letters)
    if primary is None:
        primary = not any(e.get("primary") for e in systems)
    if primary:
        for entry in systems:
            entry["primary"] = False
    systems.append(
        {
            "id": ident,
            "name": (name or "").strip() or "z = {0:.5f}".format(z),
            "z": z,
            "primary": bool(primary),
            "lines": [],
        }
    )
    return _ui_step(project, ui, "Add a system at z = {0:.5f}".format(z))


def rename_system_step(project, system, name):
    """
    The step that renames a system.

    Generated by RJC and Claude.
    """
    name = name.strip()
    if not name:
        raise DatasetError("A system needs a name.")
    ui = _structure(project)
    _entry(ui, "systems", system.id)["name"] = name
    return _ui_step(project, ui, "Rename {0} to {1}".format(system.name, name))


def make_primary_step(project, system):
    """
    The step that makes a system the primary (D15).

    Generated by RJC and Claude.
    """
    ui = _structure(project)
    _entry(ui, "systems", system.id)
    for entry in ui["systems"]:
        entry["primary"] = entry.get("id") == system.id
    return _ui_step(project, ui, "Make {0} the primary system".format(system.name))


# -- What the Data tab says (no Qt) ------------------------------------------------------

ROLE_NAMES = {
    "wave": "wave",
    "flux": "flux",
    "error": "error",
    "continuum": "continuum",
    "mask": "mask",
}


def contents(row, spectrum=None):
    """
    A row's Contents cell (D35): ``wave, flux, error · 40,402 px · 3650–6305 Å``, with
    its snips when it has some; or ``23 snips · no source spectrum``.

    Generated by RJC and Claude.
    """
    nsnips = len(row.snips)
    snips = "{0} snip{1}".format(nsnips, "" if nsnips == 1 else "s")
    if spectrum is not None:
        roles = sorted((spectrum.columns or {}).items(), key=lambda kv: kv[1])
        names = ", ".join(ROLE_NAMES.get(r, r) for r, _ in roles) or "wave, flux, error"
        text = "{0} · {1:,} px · {2:.0f}–{3:.0f} Å".format(
            names,
            spectrum.wave.size,
            float(spectrum.wave.min()),
            float(spectrum.wave.max()),
        )
        return text + (" · " + snips if nsnips else "")
    if row.source is not None:
        return snips + " · source spectrum not found"
    return snips + " · no source spectrum"


CHECKSUM_TEXT = {
    "present": "✓ unchanged",
    "missing": "moved",
    "changed": "changed",
    "embedded": "embedded",
}


def checksum(state):
    """
    A row's Checksum cell (F13): ``✓ unchanged``, ``moved`` (with Relink…),
    ``changed`` or ``embedded``; ``—`` for a row with no source.

    Generated by RJC and Claude.
    """
    return CHECKSUM_TEXT.get(state, "—") if state else "—"


def system_lines(project, system, snip_map=None):
    """
    The transitions a system's row names (D35): those it has snips of, then those
    named among its line IDs; ``H I 1215.7, H I 1025.7``.

    Generated by RJC and Claude.
    """
    from alis.dashboard import lines as L

    snip_map = L.snip_transitions(project) if snip_map is None else snip_map
    found = []
    for trans in snip_map.values():
        if trans is not None and trans.system == system.id:
            found.append((trans.ion, trans.rest))
    for entry in system.lines:
        if entry.get("ion") and entry.get("wave") is not None:
            found.append((entry["ion"], float(entry["wave"])))
    names = []
    for ion, rest in sorted(
        set((i, round(r, 3)) for i, r in found), key=lambda t: t[1]
    ):
        mass, element, stage = P.split_ion(ion)
        element = "D" if (element == "H" and mass == 2) else element
        name = "{0} {1} {2:.1f}".format(element, stage, rest)
        if name not in names:
            names.append(name)
    return names


def generic_summary(project):
    """
    The generic absorbers' row (D15): ``Lyα forest · 57 components``, or None.

    Generated by RJC and Claude.
    """
    if not project.absorbers:
        return None
    kinds = []
    for line in project.absorbers:
        name = "Lyα forest" if line.ion == "1Ly_a" else "H I blends"
        if name not in kinds:
            kinds.append(name)
    count = len(project.absorbers)
    return "{0} · {1} component{2}".format(
        ", ".join(kinds), count, "" if count == 1 else "s"
    )


