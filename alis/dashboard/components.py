C_KMS = 299792.458
# N = AOD_CONSTANT ∫τ dv / (f λ), with v in km/s and λ in Å
AOD_CONSTANT = 3.768e14
# The fraction of a Gaussian line's optical depth within ±½ FWHM: erf(√ln 2)
WINDOW_FRACTION = math.erf(math.sqrt(math.log(2.0)))
# b² = b_turb² + THERMAL T / A (voigt.parin), in km/s, K and atomic mass units
THERMAL = 0.01662892444
# Detections, saturation and upper limits, in σ (Q5.13, Q5.16)
DETECTION = 3.0
SATURATION = 3.0
# The label letters of the Lyα forest's lines
FOREST_LETTER = "ly"
# How values are written when the dashboard sets them (log N, z, b, T)
_DIGITS = {"ColDens": "{0:.4f}", "redshift": "{0:.10g}", "bturb": "{0:.3f}"}
_DIGITS["temperature"] = "{0:.1f}"


class ComponentError(Exception):
    """A component action that cannot be done as asked."""


def _pref(prefs, key):
    """A preference: the user's, or the default."""
    if prefs is not None:
        try:
            return prefs[key]
        except KeyError:
            pass
    return PF.SPEC[key].default


def written(name, value):
    """A value as the dashboard writes it: log N to 4 decimals, z to 10 figures."""
    text = _DIGITS.get(name, "{0!r}").format(float(value))
    if not any(c in text for c in ".eEn"):
        text += ".0"
    return E.format_value(text)


# -- b, thermal and turbulent ------------------------------------------------------


def thermal_b2(registry, ion, temperature):
    """The thermal part of b², in (km/s)², as ALIS's voigt adds it."""
    return THERMAL * max(float(temperature), 0.0) / registry.mass(ion.split("/")[0])


def total_b(registry, ion, bturb, temperature):
    """An ion's total b, in km/s: b_turb and the thermal part added in quadrature."""
    return math.sqrt(float(bturb) ** 2 + thermal_b2(registry, ion, temperature))


# -- Snips and transitions -----------------------------------------------------------


def _good(snip):
    """The snip's pixels that can be used: finite, with an error, not bad."""
    pix = snip.pixels
    good = np.isfinite(pix.flux) & np.isfinite(pix.error) & (pix.error > 0)
    if pix.bad is not None:
        good &= ~pix.bad
    return good


def _model_extent(project, snip):
    """A snip's extent in the model's frame (its shift removed), or None."""
    extent = snip.extent
    if extent is None:
        return None
    ends = CO.model_wave(project, snip, np.array(extent, dtype=float))
    return float(ends.min()), float(ends.max())


def snips_holding(project, ion, z):
    """
    The snips that hold a transition of an ion at a redshift (the rule of Q4.3).

    Returns
    -------
    list of Snip

    Generated by RJC and Claude.
    """
    waves, _ = project.registry.transitions(ion.split("/")[0])
    out = []
    for snip in project.snips:
        extent = _model_extent(project, snip)
        if extent is None:
            continue
        obs = waves * (1.0 + z)
        if np.any((obs >= extent[0]) & (obs <= extent[1])):
            out.append(snip)
    return out


def system_snips(project, system):
    """The snips cut for a system's transitions (as SNIP records them)."""
    trans = L.snip_transitions(project)
    return [
        s
        for s in project.snips
        if trans.get(s.specid) is not None and trans[s.specid].system == system.id
    ]


def specids_for(project, ion, z, system=None):
    """
    The specids of a new line: the snips that hold one of its transitions, or the
    system's snips when none does (ALIS needs a specid on every line when there are
    several, Q5.7), or every snip.

    Generated by RJC and Claude.
    """
    found = snips_holding(project, ion, z)
    if not found and system is not None:
        found = system_snips(project, system)
    if not found:
        found = list(project.snips)
    out = []
    for snip in found:
        if snip.specid not in out:
            out.append(snip.specid)
    return out


def fwhm_kms(project, snip, wave):
    """
    A snip's instrumental FWHM in km/s at an observed wavelength: from ``vfwhm``,
    ``vsigma`` or ``Afwhm``; otherwise two pixels.

    Generated by RJC and Claude.
    """
    item = snip.data
    par = item.param("resolution")
    name = item.resolution.name if item.resolution is not None else ""
    if par is not None:
        if name == "vfwhm":
            return abs(float(par.start))
        if name == "vsigma":
            return abs(float(par.start)) * 2.0 * math.sqrt(2.0 * math.log(2.0))
        if name == "Afwhm":
            return C_KMS * abs(float(par.start)) / float(wave)
    pix = snip.pixels.wave
    step = np.median(np.abs(np.diff(pix))) if pix.size > 1 else 0.0
    return 2.0 * C_KMS * float(step) / float(wave)


# -- The first guess of log N (S12, Q5.13, Q5.16) ---------------------------------


@dataclass
class Estimate:
    """
    The apparent column density of one transition, in one snip.

    Attributes
    ----------
    ion : str
    rest, f : float
    specid : str
    kind : str
        ``"detected"``, ``"saturated"`` or ``"undetected"``.
    logn : float or None
        log N from ∫τ_a dv (None when it is not positive).
    limit : float
        The 3σ upper limit of log N.

    Generated by RJC and Claude.
    """

    ion: str
    rest: float
    f: float
    specid: str
    kind: str
    logn: float | None
    limit: float


@dataclass
class Guess:
    """
    A new line's starting log N, and how it was found.

    Attributes
    ----------
    ion : str
    logn : float
    note : str
        ``""``, ``"saturated"``, ``"not detected"`` or ``"no data"``: for the card.
    estimates : list of Estimate

    Generated by RJC and Claude.
    """

    ion: str
    logn: float
    note: str = ""
    estimates: list = field(default_factory=list, repr=False)


def estimate(project, snip, ion, rest, f, z, b, curve=None):
    """
    The apparent column density of one transition in one snip (Q5.6, Q5.13).

    Parameters
    ----------
    curve : profile.Curve, optional
        The snip's current model; its continuum alone is used without one.

    Returns
    -------
    Estimate or None
        None when the snip has no usable pixel within the window.

    Generated by RJC and Claude.
    """
    if snip.pixels is None or f <= 0.0:
        return None
    pix = snip.pixels
    centre = rest * (1.0 + z)
    vel = C_KMS * (CO.model_wave(project, snip, pix.wave) / centre - 1.0)
    obs = float(CO.data_wave(project, snip, np.array([centre]))[0])
    fwhm = math.hypot(fwhm_kms(project, snip, obs), 2.0 * math.sqrt(math.log(2.0)) * b)
    model = None if curve is None else np.array(curve.model, dtype=float)
    cont = curve.continuum if curve is not None else CO.evaluate(project, snip)
    if model is None:
        model = None if cont is None else np.array(cont, dtype=float)
    elif cont is not None:
        model = np.where(np.isfinite(model), model, cont)
    if model is None:
        return None
    sel = (np.abs(vel) <= 0.5 * fwhm) & _good(snip) & np.isfinite(model) & (model > 0)
    if not sel.any():
        return None
    dv = np.abs(np.gradient(vel))[sel] if pix.wave.size > 1 else np.array([fwhm])
    flux, error, level = pix.flux[sel], pix.error[sel], model[sel]
    saturated = bool(np.any(flux < SATURATION * error))
    clipped = np.maximum(flux, error)
    tau = np.log(level / clipped)
    integral = float(np.sum(tau * dv))
    sigma = float(np.sqrt(np.sum((error / clipped * dv) ** 2)))
    scale = AOD_CONSTANT / (f * rest) / WINDOW_FRACTION
    logn = math.log10(scale * integral) if integral > 0 else None
    limit = math.log10(scale * DETECTION * sigma) if sigma > 0 else float("inf")
    if saturated:
        kind = "saturated"
    elif integral >= DETECTION * sigma and logn is not None:
        kind = "detected"
    else:
        kind = "undetected"
    return Estimate(ion, float(rest), float(f), snip.specid, kind, logn, limit)


def first_guess(project, ion, z, bturb, temperature, curves=None, prefs=None):
    """
    A new line's starting log N, from every transition of the ion inside a snip
    (Q5.13, Q5.16).

    Parameters
    ----------
    curves : dict, optional
        The current model of the snips (``profile.Profile.evaluate``), by data line
        index; without it, each snip's continuum stands for the model.

    Returns
    -------
    Guess

    Generated by RJC and Claude.
    """
    registry = project.registry
    b = total_b(registry, ion, bturb, temperature)
    waves, fvals = registry.transitions(ion.split("/")[0])
    found = []
    for snip in snips_holding(project, ion, z):
        extent = _model_extent(project, snip)
        curve = None if curves is None else curves.get(snip.data.index)
        for rest, f in zip(waves, fvals):
            if not extent[0] <= rest * (1.0 + z) <= extent[1]:
                continue
            est = estimate(project, snip, ion, rest, f, z, b, curve)
            if est is not None:
                found.append(est)
    detected = [e.logn for e in found if e.kind == "detected"]
    saturated = [e.logn for e in found if e.kind == "saturated" and e.logn is not None]
    limits = [e.limit for e in found if e.kind == "undetected"]
    if detected:
        return Guess(ion, min(detected), "", found)
    if any(e.kind == "saturated" for e in found):
        logn = max([_pref(prefs, "components.saturated_logn")] + saturated)
        return Guess(ion, logn, "saturated", found)
    if limits and math.isfinite(min(limits)):
        return Guess(ion, min(limits), "not detected", found)
    return Guess(ion, _pref(prefs, "components.nodata_logn"), "no data", found)


def _current_curves(project, ions, zs):
    """The current model of the snips that hold one of ``ions`` at a redshift of
    ``zs``, or None when ALIS cannot evaluate the model (the continuum then stands
    for it)."""
    try:
        profile = PR.of(project)
    except PR.ProfileError:
        return None
    wanted = set()
    for ion in ions:
        for z in np.atleast_1d(zs):
            wanted |= {s.data.index for s in snips_holding(project, ion, float(z))}
    try:
        return profile.evaluate(snips=wanted)
    except PR.ProfileError:
        return None


# -- The ions of a system --------------------------------------------------------


def _ratio_ions(system):
    """The ions a system gives only as a ratio (D I as ``2H_I/1H_I``)."""
    out = set()
    for comp in system.components:
        for line in comp.ratios:
            out.add(line.ion.split("/")[0])
    return out


def system_ions(project, system):
    """
    The ions a new component of a system gets a line for: those of its components
    (excluded ones too, since a component is in every ion by default) and its line
    IDs; not an ion given as a ratio, nor the Lyα forest's.

    Generated by RJC and Claude.
    """
    ratio = _ratio_ions(system)
    out = []
    names = []
    for comp in system.components:
        names += [ln.ion for ln in comp.lines] + list(comp.excluded)
    names += [entry.get("ion") for entry in system.lines]
    for ion in names:
        if not ion or ion in out or ion in ratio or ion in P.GENERIC_IONS:
            continue
        out.append(ion)
    return out


def addable_ions(project, system):
    """
    The ions Add ion… offers (Q5.7): first those with a transition inside any snip
    at the system's redshift, whatever the snip was cut for, then every other ion of
    the atomic data. Ions already in the system are left out.

    Returns
    -------
    tuple
        ``(in_snips, others)``, lists of ions.

    Generated by RJC and Claude.
    """
    have = set(system_ions(project, system)) | _ratio_ions(system)

    def order(ion):
        mass, element, stage = P.split_ion(ion)
        return (L.SYMBOLS.index(element), L.roman(stage), mass, ion)

    # The ions of chemical elements, in the order of the periodic table
    every = sorted(
        (ion for ion in L.atomic(project.registry).by_ion if ion not in have),
        key=order,
    )
    inside = [ion for ion in every if snips_holding(project, ion, system.z)]
    return inside, [ion for ion in every if ion not in inside]


# -- The navigator (S30, D37, Q5.14) ----------------------------------------------


@dataclass
class NavIon:
    """
    One row of the ion navigator: an ion with its isotopes (D I with H I).

    Attributes
    ----------
    ion : str
        The element's main ion in the system.
    ions : list of str
        It and its isotopes in the system.
    snips : int
        The snips that hold one of its transitions at the system's redshift: its
        panels (Q5.19).
    components : int
        The system's components with a line of one of ``ions``.

    Generated by RJC and Claude.
    """

    ion: str
    ions: list
    snips: int
    components: int

    @property
    def name(self):
        return P.ion_name(self.ion)

    @property
    def detail(self):
        """``"8 snips · 2 comp. · with D I"``, as the navigator says it."""
        parts = [
            (
                "{0} snip{1}".format(self.snips, "" if self.snips == 1 else "s")
                if self.snips
                else "no snip"
            ),
            "{0} comp.".format(self.components),
        ]
        others = [P.ion_name(i) for i in self.ions if i != self.ion]
        if others:
            parts.append("with " + ", ".join(others))
        return " · ".join(parts)


@dataclass
class NavForest:
    """The Lyα forest's group: its lines and the snips that hold them (Q5.14)."""

    lines: int
    snips: int

    @property
    def detail(self):
        return "{0} comp. in {1} snip{2}".format(
            self.lines, self.snips, "" if self.snips == 1 else "s"
        )


@dataclass
class PanelTransition:
    """
    The transitions of an ion inside one snip (Q5.19): the strongest, whose
    components are the ones drawn to edit, and the others, which show the same
    components.

    Attributes
    ----------
    ion : str
    rest : float
        The strongest transition's rest wavelength, the panel's zero velocity.
    f : float
    others : list of float
        The rest wavelengths of the others inside the snip, strongest first.

    Generated by RJC and Claude.
    """

    ion: str
    rest: float
    f: float
    others: list = field(default_factory=list)

    @property
    def line(self):
        """The strongest: ``"O I 1302.2"`` or ``"Lyβ 1025.7"``."""
        mass, element, stage = P.split_ion(self.ion)
        element = "D" if (element == "H" and mass == 2) else element
        return L.line_name(element, stage, self.rest)

    @property
    def name(self):
        """``"O I 1302.2"``, or ``"O I 988.8 (+2)"`` with two others in the snip."""
        return self.line + (" (+{0})".format(len(self.others)) if self.others else "")


def _extents(project):
    """Every snip's extent in the model's frame, by ``id(snip)``."""
    return {id(s): _model_extent(project, s) for s in project.snips}


def _inside(project, snip, ion, z, extents=None):
    """The transitions of an ion at a redshift inside a snip, or None."""
    if extents is not None and id(snip) in extents:
        extent = extents[id(snip)]
    else:
        extent = _model_extent(project, snip)
    if extent is None:
        return None
    found = [
        (line.rest, line.fval)
        for line in L.atomic(project.registry).ion_lines(ion)
        if extent[0] <= line.rest * (1.0 + z) <= extent[1]
    ]
    if not found:
        return None
    found.sort(key=lambda t: -t[0] * t[1])
    (rest, f), others = found[0], [r for r, _ in found[1:]]
    return PanelTransition(ion, rest, f, others)


def ion_snips(project, system, ion, rows=None, extents=None):
    """
    The snips that hold a transition of an ion at the system's redshift, one panel
    each (Q5.19): ordered by the strength (fλ) of each one's strongest transition,
    then by dataset, the reference first.

    Returns
    -------
    list of tuple
        ``(row, snip, PanelTransition)``.

    Generated by RJC and Claude.
    """
    if extents is None:
        extents = _extents(project)
    out = []
    for row in _rows_in_order(project) if rows is None else rows:
        for snip in row.snips:
            if snip.pixels is None:
                continue
            trans = _inside(project, snip, ion, system.z, extents)
            if trans is not None:
                out.append((row, snip, trans))
    # A stable sort: the datasets stay in order for each transition
    out.sort(key=lambda t: -t[2].rest * t[2].f)
    return out


def navigator(project):
    """
    The ion navigator (S30, Q5.14): each system, the primary first, with its ions
    (isotopes inside their element), then the Lyα forest of the whole project.

    Returns
    -------
    tuple
        ``(systems, forest)``: a list of ``(System, [NavIon])``, and a
        :class:`NavForest`, or None when the project has no line of the forest.

    Generated by RJC and Claude.
    """
    extents = _extents(project)
    out = []
    for system in project.systems:
        groups = {}
        for ion in system_ions(project, system) + sorted(_ratio_ions(system)):
            _, elem, stage = P.split_ion(ion)
            groups.setdefault((elem, stage), []).append(ion)
        rows = []
        for (elem, stage), ions in groups.items():
            main = [i for i in ions if P.split_ion(i)[0] == P.MAIN_ISOTOPE.get(elem)]
            ion = main[0] if main else ions[0]
            ions = [ion] + [i for i in ions if i != ion]
            ncomp = sum(1 for c in system.components if any(i in c.ions for i in ions))
            count = len(ion_snips(project, system, ion, extents=extents))
            rows.append(NavIon(ion, ions, count, ncomp))
        out.append((system, rows))
    forest = None
    if project.absorbers:
        specids = {s for line in project.absorbers for s in line.specids}
        forest = NavForest(len(project.absorbers), len(specids))
    return out, forest


def navigator_ions(project, system):
    """The navigator's rows of one system: its ions, each with its isotopes."""
    systems, _ = navigator(project)
    for found, rows in systems:
        if found.id == system.id:
            return rows
    return []


# -- The panels (D37, Q5.2, Q5.3, Q5.14, Q5.19) -----------------------------------

ALL = "all"


@dataclass
class Panel:
    """
    One panel: a snip of one dataset, on the velocity axis of the ion's strongest
    transition inside it (in the Lyα forest, of the transition the snip was cut
    for), in the model's frame (the row's shift removed, Q5.2, Q5.19).

    Attributes
    ----------
    title : str
        ``"O I 1302.2 · HIRES"``, ``"O I 988.8 (+2) · HIRES"``, or, in a snip cut
        for another transition, ``"O I 929.5 (+2) · Ly7 926.2 snip · HIRES"``.
    transition : PanelTransition
    row : Row
    snip : Snip
    centre : float
        The wavelength of zero velocity, in the model's frame.
    velocity : numpy.ndarray
        The snip's pixels as velocities.
    regions : list of tuple
        The fit regions, as velocity spans.

    Generated by RJC and Claude.
    """

    title: str
    transition: object
    row: object
    snip: object
    centre: float
    velocity: np.ndarray = field(repr=False, default=None)
    regions: list = field(default_factory=list)


def _rows_in_order(project):
    """The datasets, the reference first."""
    rows = list(project.rows)
    return sorted(rows, key=lambda r: not r.reference)


def _panel(project, title, trans, row, snip, centre):
    vel = C_KMS * (CO.model_wave(project, snip, snip.pixels.wave) / centre - 1.0)
    regions = []
    for low, high in S.regions_of(snip):
        ends = CO.model_wave(project, snip, np.array([low, high]))
        regions.append(tuple(C_KMS * (ends / centre - 1.0)))
    return Panel(title, trans, row, snip, centre, vel, regions)


def panel_datasets(project, system, ion):
    """
    The datasets the Dataset menu lists for an ion (Q5.2): those with a snip that
    holds one of its transitions, the reference first.

    Generated by RJC and Claude.
    """
    held = {id(row) for row, _, _ in ion_snips(project, system, ion)}
    return [row for row in _rows_in_order(project) if id(row) in held]


def panels(project, system, ion, dataset=ALL):
    """
    The panels of an ion (D37, Q5.2, Q5.19): one per snip of the chosen dataset (or
    of every dataset) that holds one of its transitions, on the velocity axis of the
    strongest of them inside it, ordered by that transition's strength.

    Parameters
    ----------
    dataset : str
        A row id, or :data:`ALL`.

    Returns
    -------
    tuple
        ``(panels, missing)``: the panels, and the transitions that lead a panel of
        another dataset but that no snip of the chosen one holds (``"O I 988.8:
        not in PROCHASKA"``).

    Generated by RJC and Claude.
    """
    found = ion_snips(project, system, ion)
    cut = L.snip_transitions(project)
    out, held = [], set()
    for row, snip, trans in found:
        if dataset != ALL and row.id != dataset:
            continue
        held.update([trans.rest] + trans.others)
        title = [trans.name]
        # A snip cut for another transition is named, as two can hold the same one
        own = cut.get(snip.specid)
        if own is not None and (own.ion != ion or abs(own.rest - trans.rest) > 0.01):
            title.append(PanelTransition(own.ion, own.rest, 0.0).line + " snip")
        title.append(row.name)
        centre = trans.rest * (1.0 + system.z)
        out.append(_panel(project, " · ".join(title), trans, row, snip, centre))
    missing = []
    if dataset != ALL:
        name = next((r.name for r in project.rows if r.id == dataset), dataset)
        for _, _, trans in found:
            text = "{0}: not in {1}".format(trans.line, name)
            if trans.rest not in held and text not in missing:
                missing.append(text)
    return out, missing


def forest_panels(project, dataset=ALL):
    """
    The Lyα forest's panels (Q5.14): one for each snip that holds one of its lines,
    in the velocity frame of the transition that snip was cut for.

    Generated by RJC and Claude.
    """
    specids = {s for line in project.absorbers for s in line.specids}
    trans = L.snip_transitions(project)
    out = []
    for row in _rows_in_order(project):
        if dataset != ALL and row.id != dataset:
            continue
        for snip in row.snips:
            if snip.specid not in specids or snip.pixels is None:
                continue
            own = trans.get(snip.specid)
            if own is None:
                continue
            try:
                system = project.system(own.system)
                z = system.z
            except P.ProjectError:
                z = project.systems[0].z if project.systems else 0.0
            ion = own.ion
            item = PanelTransition(ion, own.rest, 0.0)
            title = "{0} · {1}".format(item.name, row.name)
            out.append(_panel(project, title, item, row, snip, own.rest * (1.0 + z)))
    return out


@dataclass
class Tick:
    """
    A tick of a panel: a component of the ion, an isotope's line, or another
    system's or the forest's line, at its velocity.

    Attributes
    ----------
    x : float
        Its velocity in the panel, in km/s.
    label : str
    kind : str
        ``"own"``, ``"echo"`` (the same component in another transition of the
        snip), ``"excluded"``, ``"isotope"``, ``"other"`` or ``"forest"``.
    key : tuple
        ``("component", id)``, ``("isotope", id, ion)`` or ``("line", line)``.

    Generated by RJC and Claude.
    """

    x: float
    label: str
    kind: str
    key: tuple


def linked_values(project):
    """
    The values ALIS computes for the parameters a link computes (Q5.9), by ALIS's
    number: what their cards and ticks show, since the value written for them is
    not the one fitted. Empty when no link computes one, or the model cannot be
    evaluated.

    Generated by RJC and Claude.
    """
    indices = {p.index for p in project.parsed.params if p.linked}
    if not indices:
        return {}
    try:
        values = PR.of(project).values()
    except PR.ProfileError:
        return {}
    return {i: float(values[i]) for i in indices}


def shown(param, linked=None):
    """
    A parameter's value as the tab shows it: what its link computes (``linked``,
    from :func:`linked_values`), or its starting value.
    """
    if linked and param.linked and param.index in linked:
        return linked[param.index]
    return param.start


def component_z(comp, linked=None):
    """A component's redshift as the tab shows it (what a link computes)."""
    zpar = comp.main.param("redshift") if comp.main is not None else None
    return comp.z if zpar is None else shown(zpar, linked)


def _line_ticks(project, line, panel, label, kind, half, linked=None):
    """The ticks of one voigt line's transitions inside a panel's window."""
    out = []
    zpar = line.param("redshift")
    if zpar is None or panel.snip.specid not in line.specids:
        return out
    ion = line.ion.split("/")[0]
    waves, _ = project.registry.transitions(ion)
    z = shown(zpar, linked)
    for rest in waves:
        vel = C_KMS * (rest * (1.0 + z) / panel.centre - 1.0)
        if abs(vel) <= half:
            out.append(Tick(float(vel), label, kind, ("line", line.line)))
    return out


def panel_ticks(project, system, ion, panel, half=None, linked=None):
    """
    The ticks of a panel (D37): every component of the system at its velocity
    (excluded from the ion, or never in it: faint and dashed, Q5.15), and again in
    each other transition of the ion inside the snip, unlabelled (only the strongest
    one's are dragged, Q5.19); its isotopes' lines; and the lines of other systems
    and of the forest that fall in the panel (drawn, but locked, S30).

    Parameters
    ----------
    half : float, optional
        The panel's half-range in km/s (the preference by default).
    linked : dict, optional
        :func:`linked_values`: a redshift a link computes is drawn where ALIS puts
        it.

    Returns
    -------
    list of Tick

    Generated by RJC and Claude.
    """
    half = PF.SPEC["components.velocity_range"].default if half is None else half
    out = []
    _, elem, stage = P.split_ion(ion)
    group = [ion] + [
        i
        for i in system_ions(project, system) + sorted(_ratio_ions(system))
        if i != ion and P.split_ion(i)[1:] == (elem, stage)
    ]
    trans = panel.transition
    shifts = [C_KMS * (rest / trans.rest - 1.0) for rest in trans.others]
    for comp in system.components:
        vel = P.velocity(component_z(comp, linked), system.z)
        own = ion in comp.ions
        kind = "own" if own else "excluded"
        key = ("component", comp.id)
        out.append(Tick(float(vel), comp.id, kind, key))
        for shift in shifts:
            out.append(Tick(float(vel + shift), "", "echo" if own else kind, key))
        for iso in group[1:]:
            if iso not in comp.ions:
                continue
            waves, _ = project.registry.transitions(iso)
            for num, rest in enumerate([trans.rest] + trans.others):
                near = waves[np.argmin(np.abs(waves - rest))]
                if abs(near - rest) > 1.0:
                    continue
                shift = C_KMS * (near / trans.rest - 1.0)
                out.append(
                    Tick(
                        float(vel + shift),
                        "" if num else P.ion_name(iso),
                        "isotope",
                        ("isotope", comp.id, iso),
                    )
                )
    for other in project.systems:
        if other is system:
            continue
        for comp in other.components:
            for line in comp.lines:
                label = "{0} ({1})".format(P.ion_name(line.ion), other.id)
                out += _line_ticks(project, line, panel, label, "other", half, linked)
    for line in project.absorbers:
        out += _line_ticks(project, line, panel, "Lyα", "forest", half, linked)
    return out


def forest_ticks(project, panel, half=None, linked=None):
    """The ticks of a Lyα forest panel: its lines where their transitions fall."""
    half = PF.SPEC["components.velocity_range"].default if half is None else half
    out = []
    for line in project.absorbers:
        for tick in _line_ticks(project, line, panel, "", "own", half, linked):
            out.append(tick)
    return out


