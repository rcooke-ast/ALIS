@dataclass
class Place:
    """
    What a line of the ``.mod`` describes, for the Components tab to show (S16).

    Attributes
    ----------
    system : System or None
    ion : str or None
        The navigator's ion: the element's main ion for an isotope (H I for D I).
    component : Component or None
    forest : bool
        A line of the Lyα forest.

    Generated by RJC and Claude.
    """

    system: object = field(default=None, repr=False)
    ion: str = None
    component: object = field(default=None, repr=False)
    forest: bool = False


def _shown_ion(project, system, ion):
    """The navigator's ion that holds an ion: its element's main ion."""
    for row in navigator_ions(project, system):
        if ion in row.ions:
            return row.ion
    return ion


def at_line(project, num):
    """
    What line ``num`` of the ``.mod`` describes (S16): a voigt line's component and
    ion, a ratio line's ion, a line of the Lyα forest; for a link, or a ``fix`` or
    ``lim param`` line, the parameter it constrains. None for anything else.

    Returns
    -------
    Place or None

    Generated by RJC and Claude.
    """
    if num is None:
        return None
    for comp in project.components:
        for line in comp.lines:
            if line.line == num:
                return Place(
                    comp.system, _shown_ion(project, comp.system, line.ion), comp
                )
        for line in comp.ratios:
            if line.line == num:
                ion = line.ion.split("/")[0]
                return Place(comp.system, _shown_ion(project, comp.system, ion))
    if any(line.line == num for line in project.absorbers):
        return Place(forest=True)
    pm = project.parsed
    item = pm.item_at(num)
    label = None
    if isinstance(item, M.Link):
        label = item.target
    elif isinstance(item, M.Command) and item.target == "param":
        label = item.name
    found = pm.labels.get(label) if label else None
    for par in found.params if found is not None else []:
        if par.line != num:
            place = at_line(project, par.line)
            if place is not None:
                return place
    return None


def unsnipped_ions(project):
    """
    The ions of the systems that are in no snip (Q5.7): their lines constrain
    nothing until a snip holds one of their transitions.

    Returns
    -------
    list of tuple
        ``(System, NavIon)``.

    Generated by RJC and Claude.
    """
    systems, _ = navigator(project)
    return [
        (system, row)
        for system, rows in systems
        for row in rows
        if not row.snips and row.components
    ]


# -- Notices of an imported model (Q0.3, D20, D22) ----------------------------------


def notices_for(project, system, ion=None):
    """
    The notices shown above an ion's panels: those of the system's components that
    are about the ion or its isotopes (every one of the system's, with no ion).

    Returns
    -------
    list of Notice

    Generated by RJC and Claude.
    """
    if system is None:
        return []
    element = P.split_ion(ion)[1:] if ion else None
    out = []
    for notice in project.notices:
        comp = notice.item
        if comp is None or comp.system is None or comp.system.id != system.id:
            continue
        if element is not None:
            ions = {project.parsed.item_at(n).ion or "" for n in notice.lines}
            if not any(i and P.split_ion(i.split("/")[0])[1:] == element for i in ions):
                continue
        out.append(notice)
    return out


