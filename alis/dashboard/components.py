"""Components: adding, the first guess, drags, temperatures, excluding, interlopers.

Dashboard Stages 5.2–5.8 (S11, S12, S14, S15, D20–D23; Q0.3, Q5.6, Q5.7, Q5.9,
Q5.12–Q5.19).
No Qt: the Components tab asks this module for every step, and gives it to the
history.

- **A new component** (S11, D20) takes the next labels of its system's scheme
  (``za1``, ``ba1``, ``ta1``, Q2.3) and a line for every ion of the system, each
  with the specids of the snips that hold one of its transitions (Q4.3), or the
  system's snips when none does (Q5.7); b_turb and the temperature come from the
  preferences, and each ion's log N from the first guess. One step.
- **The first guess of log N** (S12, Q5.6, Q5.13, Q5.16), for every ion of the
  component: each of the ion's transitions inside a snip gives
  N = 3.768×10¹⁴ ∫τ_a dv / (fλ) over ±½ FWHM_line around the component's velocity,
  divided by 0.76 (the fraction of a Gaussian within ±½ FWHM), with
  τ_a = ln(M/F) against the current model M, so that what the model already holds
  is not counted twice. Estimates detected at 3σ and not saturated (no pixel within
  3σ of zero) count, and the lowest is taken, since a blend only adds absorption.
  With none: the highest lower limit of the saturated ones, or 15.0 if larger; else
  the lowest 3σ upper limit; else, with no data there, 12.0.
- **Drags** (Q5.4, Q5.12, Q5.17, Q5.23): a drag in a panel gives values by
  ALIS's parameter numbers, for the profile to evaluate; the line's total b gives b_turb
  for the temperature mode (or T, in the pure thermal mode); every value stays
  within its limits: the model's (``lim`` lines, and voigt.py's own), or, for log N,
  the dashboard's range. When the drag ends, the values are written as one step.
- **Temperature modes** (D21): 0, 100 or 10⁴ K fixed, any other value fixed, T free,
  or pure thermal (b_turb fixed at 0, T free); a change of mode keeps the line's
  width where it can.
- **Excluding and including** (Q5.15, Q5.18): an ion's line is commented out of a
  component, with the lines that use only its labels (each with a note), and
  brought back with its log N and the component's current z, b and T.
- **Interlopers** (S14, Q5.14): at a clicked wavelength, a line of the Lyα forest
  (Lyα alone or every Lyman line, free or fixed), or a component of another system
  whose transition (a line ID) falls there.
- **Links** (S15, Q5.9): what a link computes is shown as ALIS computes it, and is
  not dragged; dragging what it reads moves it.
- **Notices** (Q0.3, D20, D22): those about an ion, shown above its panels with
  their fixes.

Generated by RJC and Claude.
"""

