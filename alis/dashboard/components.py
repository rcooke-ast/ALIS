def param_state(project, comp, param):
    """
    A parameter as its card's badge shows it: ``"linked"`` (computed by a link,
    Q5.9), ``"tied"`` (its label is also used outside the component), ``"fixed"`` or
    ``"free"``; and, for a tied or linked one, what it is tied to or computed from.

    Returns
    -------
    tuple
        ``(state, detail)``: detail is the link's expression, or the places it is
        tied to (``"a2 O I"``).

    Generated by RJC and Claude.
    """
    pm = project.parsed
    if param.linked:
        for link in pm.links:
            if param.label and link.target.lower() == param.label.lower():
                return LINKED, "{0} = {1}".format(link.target, link.expression)
        return LINKED, ""
    if param.label:
        own = {ln.line for ln in comp.lines + comp.ratios}
        places = {}
        for other in project.components:
            for line in other.lines + other.ratios:
                places[line.line] = "{0} {1}".format(other.id, P.ion_name(line.ion))
        for line in project.absorbers:
            places[line.line] = "the Lyα forest"
        others = []
        label = pm.labels.get(param.label)
        for place in label.params if label is not None else []:
            if place.line in own:
                continue
            name = places.get(place.line, "line {0}".format(place.line + 1))
            if name not in others:
                others.append(name)
        if others:
            return TIED, ", ".join(others)
    return (FIXED if param.fixed else FREE), ""


