# -- Steps: one change of the text -----------------------------------------------


def _chain(pm, makers):
    """
    One change from several, each made on the model the ones before left.

    Each maker takes the model and a function that says where a line of the first
    model is now, and returns a change (or None).

    Generated by RJC and Claude.
    """
    original = pm.text
    change = T.Change((), "")
    for maker in makers:

        def where(num, done=change):
            return done.map_line(original, num)

        part = maker(pm, where)
        if part is None or not part.patches:
            continue
        change = change.then(part)
        pm = E.reread(pm, part)
    return change, pm


def _system_end(system):
    """The last live line of a system's components, or None."""
    nums = [ln.line for c in system.components for ln in c.lines]
    return max(nums) if nums else None


def new_component(project, system, z, prefs=None):
    """
    The step that adds a component to a system at a redshift (S11, D20, Q5.6).

    Returns
    -------
    tuple
        ``(step, guesses)``: the step, and each ion's :class:`Guess`.

    Raises
    ------
    ComponentError
        When the system has no ion.

    Generated by RJC and Claude.
    """
    project.require_reading()
    ions = system_ions(project, system)
    if not ions:
        raise ComponentError(
            "System {0} has no ion yet: add one with Add ion… first.".format(
                system.name
            )
        )
    pm = project.parsed
    labels = E.new_component(pm, system.id)
    bturb = _pref(prefs, "components.start_b")
    temperature = _pref(prefs, "components.temperature")
    fixed = {"redshift": False, "bturb": False, "temperature": True}
    curves = _current_curves(project, ions, z)
    guesses = {}
    for ion in ions:
        guesses[ion] = first_guess(project, ion, z, bturb, temperature, curves, prefs)
    after = _system_end(system)

    def maker(ion, first):
        def make(pm, where):
            return E.add_ion(
                pm,
                ion,
                written("ColDens", guesses[ion].logn),
                written("redshift", z),
                written("bturb", bturb),
                written("temperature", temperature),
                specids_for(project, ion, z, system),
                labels=labels,
                fixed=fixed,
                after=where(after) if first and after is not None else None,
            )

        return make

    change, _ = _chain(pm, [maker(ion, k == 0) for k, ion in enumerate(ions)])
    step = project.step(change, "Add a component to {0}".format(system.name))
    return step, guesses


def _main_word(comp, name):
    """A component's value of z, b_turb or T as written, its label, and whether it
    is fixed: the line that defines the component (D20)."""
    par = comp.main.param(name)
    if par is None:
        return None, "", False
    text = par.value_token.text if par.value_token is not None else repr(par.start)
    return text, par.label, par.fixed


def add_ion(project, system, ion, prefs=None):
    """
    The step that adds an ion to every component of a system (Q5.7), each line with
    its first guess of log N and the component's z, b_turb and T; to a system with
    no component yet, the ion joins its line IDs, so that its first component gets
    a line of it.

    Returns
    -------
    tuple
        ``(step, guesses)``: guesses by component id.

    Generated by RJC and Claude.
    """
    project.require_reading()
    if not system.components:
        return _add_line_id(project, system, ion), {}
    guesses, makers = {}, []
    curves = _current_curves(project, [ion], [c.z for c in system.components])
    for comp in system.components:
        words = {name: _main_word(comp, name) for name in E.COMPONENT_PREFIX}
        b = comp.main.param("bturb")
        t = comp.main.param("temperature")
        guess = first_guess(
            project,
            ion,
            comp.z,
            b.start if b is not None else _pref(prefs, "components.start_b"),
            t.start if t is not None else 0.0,
            curves,
            prefs,
        )
        guesses[comp.id] = guess
        makers.append(_add_line_maker(project, system, comp, ion, guess.logn, words))
    change, _ = _chain(project.parsed, makers)
    return project.step(change, "Add {0}".format(P.ion_name(ion))), guesses


def _add_line_id(project, system, ion):
    """
    The step that names an ion among a system's line IDs (``ui/project.json``), so
    that the system's next component gets a line of it: Add ion… on a system that
    has no component yet.

    Generated by RJC and Claude.
    """
    lines = L.atomic(project.registry).ion_lines(ion)
    if not lines:
        raise ComponentError("{0} has no transition.".format(P.ion_name(ion)))
    strongest = max(lines, key=lambda ln: ln.rest * ln.fval)
    ui = project.working_structure()
    for entry in ui.get("systems", []):
        if entry.get("id") == system.id:
            known = entry.setdefault("lines", [])
            if not any(e.get("ion") == ion for e in known):
                known.append({"ion": ion, "wave": float(strongest.rest)})
    return project.set_ui(ui, "Add {0}".format(P.ion_name(ion)))


def _add_line_maker(project, system, comp, ion, logn, words):
    """A maker of a component's line for one more ion."""
    labels = {n: w[1] for n, w in words.items() if w[1]}
    fixed = {n: w[2] for n, w in words.items() if w[1]}
    values = {n: (w[0] if w[0] is not None else "0.0") for n, w in words.items()}
    last = comp.lines[-1].line

    def make(pm, where):
        # With a label, add_ion finds the component's lines; without, its last line,
        # wherever the lines added before have moved it
        after = None if comp.label else where(last)
        return E.add_ion(
            pm,
            ion,
            written("ColDens", logn),
            values["redshift"],
            values["bturb"],
            values["temperature"],
            specids_for(project, ion, comp.z, system),
            labels=labels,
            fixed=fixed,
            after=after,
        )

    return make


# -- Drags (Q5.4, Q5.12, Q5.17) ---------------------------------------------------


class DragError(ComponentError):
    """A value that a drag cannot change: a linked parameter."""


def bounds(param, prefs=None):
    """
    The range a drag may move a parameter in: the model's limits (``lim`` lines,
    and voigt.py's own, such as b_turb ≥ 0.5 km/s), and for log N, where the model
    sets none, the dashboard's range (Q5.17).

    Returns
    -------
    tuple
        ``(low, high)``, None for no bound.

    Generated by RJC and Claude.
    """
    low, high = param.limits
    if param.name == "ColDens":
        if low is None:
            low = _pref(prefs, "components.logn_min")
        if high is None:
            high = _pref(prefs, "components.logn_max")
    if param.name == "temperature" and low is None:
        low = 0.0
    return low, high


def clamp(value, low, high):
    """A value within ``[low, high]`` (None for no bound)."""
    if low is not None:
        value = max(value, low)
    if high is not None:
        value = min(value, high)
    return value


def _check_drag(param):
    if param is None:
        raise DragError("This line has no such parameter.")
    if param.linked:
        raise DragError(
            "This {0} is computed by a link: change it in the .mod panel.".format(
                param.name
            )
        )


def drag(project, comp, ion, z=None, logn=None, b=None, prefs=None):
    """
    The values a drag gives (Q5.12): the parameters by ALIS's number, and the
    parameters themselves, each value within its bounds.

    Parameters
    ----------
    comp : Component
    ion : str
        The ion whose panel the drag is in.
    z : float, optional
        The component's redshift (its tick).
    logn : float, optional
        The ion's log N.
    b : float, optional
        The ion's total b, in km/s: b_turb for the temperature mode follows, or T in
        the pure thermal mode.

    Returns
    -------
    list of tuple
        ``(Param, value)``: one place of each ALIS parameter it changes.

    Raises
    ------
    DragError

    Generated by RJC and Claude.
    """
    out = []
    if z is not None:
        zpars = {ln.param("redshift").index: ln.param("redshift") for ln in comp.lines}
        for par in zpars.values():
            _check_drag(par)
            out.append((par, clamp(float(z), *bounds(par, prefs))))
    lines = comp.lines_of(ion)
    if (logn is not None or b is not None) and not lines:
        raise DragError(
            "Component {0} has no {1} line.".format(comp.id, P.ion_name(ion))
        )
    if logn is not None:
        for line in lines:
            par = line.param("ColDens")
            _check_drag(par)
            out.append((par, clamp(float(logn), *bounds(par, prefs))))
    if b is not None:
        line = lines[0]
        bpar, tpar = line.param("bturb"), line.param("temperature")
        mode = comp.temperature_mode[0]
        registry = project.registry
        if mode == "thermal":
            _check_drag(tpar)
            mass = registry.mass(ion.split("/")[0])
            value = float(b) ** 2 * mass / THERMAL
            out.append((tpar, clamp(value, *bounds(tpar, prefs))))
        else:
            _check_drag(bpar)
            temp = tpar.start if tpar is not None else 0.0
            b2 = float(b) ** 2 - thermal_b2(registry, ion, temp)
            out.append((bpar, clamp(math.sqrt(max(b2, 0.0)), *bounds(bpar, prefs))))
    return out


def _linked(param):
    return param is not None and param.linked


def draggable(comp, ion=None):
    """
    What a drag can move in a component (Q5.9): not what a link computes.

    Returns
    -------
    dict
        ``{"z": bool, "logn": bool, "b": bool}``: its z, and the two directions
        of a drag below the continuum in the ion's panels (b is T in the pure
        thermal mode).

    Generated by RJC and Claude.
    """
    lines = comp.lines_of(ion) if ion else []
    name = "temperature" if comp.temperature_mode[0] == "thermal" else "bturb"
    return {
        "z": not any(_linked(ln.param("redshift")) for ln in comp.lines),
        "logn": bool(lines) and not any(_linked(ln.param("ColDens")) for ln in lines),
        "b": bool(lines) and not _linked(lines[0].param(name)),
    }


def drag_values(changes):
    """The parameters for :meth:`profile.Profile.values` from :func:`drag`."""
    return {par.index: value for par, value in changes}


def drag_step(project, comp, changes):
    """
    The step that writes a drag's values when it ends: one step, whose description
    names no value (it may be hidden, D24).

    Generated by RJC and Claude.
    """
    project.require_reading()

    def setter(par, value):
        def make(pm, where):
            return E.set_value(pm, E._same(pm, par), written(par.name, value))

        return make

    change, _ = _chain(project.parsed, [setter(par, value) for par, value in changes])
    return project.step(change, "Drag component {0}".format(comp.id))


# -- Temperature modes (D21) --------------------------------------------------------


MODES = ("preset", "fixed", "free", "thermal")


def temperature(project, comp, mode, value=None):
    """
    The step that sets a component's temperature mode (D21).

    Parameters
    ----------
    mode : str
        ``"preset"`` or ``"fixed"`` (T fixed at ``value``), ``"free"`` (T free), or
        ``"thermal"`` (b_turb fixed at 0, T free).
    value : float, optional
        The temperature of a fixed mode, in K.

    Returns
    -------
    Step

    Raises
    ------
    ComponentError, alis.dashboard.edit.LabelNeeded

    Generated by RJC and Claude.
    """
    project.require_reading()
    if mode not in MODES:
        raise ComponentError("Unknown temperature mode: {0}.".format(mode))
    if mode in ("preset", "fixed") and (value is None or float(value) < 0.0):
        raise ComponentError("A fixed temperature needs a value of 0 K or more.")
    main = comp.main
    bpar, tpar = main.param("bturb"), main.param("temperature")
    if bpar is None or tpar is None:
        raise ComponentError("This component's lines have no b_turb or T.")
    registry = project.registry
    current = comp.temperature_mode[0]
    width = total_b(registry, main.ion, bpar.start, tpar.start)
    makers = []

    def do(fn, par, *args):
        makers.append(lambda pm, where: fn(pm, E._same(pm, par), *args))

    if mode in ("preset", "fixed"):
        do(E.set_value, tpar, written("temperature", value))
        if not tpar.fixed:
            do(E.fix, tpar)
        if current == "thermal":
            b2 = width**2 - thermal_b2(registry, main.ion, value)
            low = bounds(bpar)[0] or 0.0
            do(E.set_value, bpar, written("bturb", max(math.sqrt(max(b2, 0.0)), low)))
            do(E.free, bpar)
    elif mode == "free":
        if tpar.fixed:
            do(E.free, tpar)
        if current == "thermal":
            do(E.set_value, bpar, written("bturb", max(width, bounds(bpar)[0] or 0.0)))
            do(E.free, bpar)
    else:  # thermal
        mass = registry.mass(main.ion.split("/")[0])
        do(E.set_value, tpar, written("temperature", width**2 * mass / THERMAL))
        if tpar.fixed:
            do(E.free, tpar)
        do(E.set_value, bpar, written("bturb", 0.0))
        if not bpar.fixed:
            do(E.fix, bpar)
    change, _ = _chain(project.parsed, makers)
    names = {"preset": "fixed", "fixed": "fixed", "free": "free", "thermal": "thermal"}
    return project.step(change, "Temperature of {0}: {1}".format(comp.id, names[mode]))


# -- Excluding and including (Q5.15, Q5.18) ---------------------------------------


@dataclass
class Exclusion:
    """
    What excluding an ion from a component comments out (its preview).

    Attributes
    ----------
    entries : list of remove.PlanLine
        Each line, why, as it is and as it will be.
    change : Change
    last : bool
        The ion is the component's last: excluding it leaves no line, so the
        component is removed instead (after the user agrees).
    others : list of str
        The other components a ratio line also applies to.

    Generated by RJC and Claude.
    """

    entries: list
    change: object
    last: bool = False
    others: list = field(default_factory=list)

    @property
    def description(self):
        return self.change.description

    @property
    def lines(self):
        """The lines it comments out (as a removal plan has them)."""
        return self.entries

    @property
    def notes(self):
        if not self.others:
            return []
        return [
            "The ratio line applies to components {0} too: they are excluded with"
            " it.".format(", ".join(self.others))
        ]

    # Its lines for the screen, through the gate, as a removal plan gives them
    preview = R.Plan.preview


def is_excluded(comp, ion):
    """Whether a component is excluded from an ion (its line commented out)."""
    if ion in comp.excluded:
        return True
    return any(
        item.voigt and item.ion and "/" in item.ion and item.note[0] == ion
        for item in comp.excluded_with
    )


def _comment(text, note=None):
    """A line commented out: ``#`` in front, and an exclusion's note after."""
    return "#" + text + ("" if note is None else "  " + note)


def _uncomment(text, note=None):
    """A line commented out by :func:`_comment`, as it was."""
    at = len(text) - len(text.lstrip())
    text = text[:at] + text[at + 1 :] if text[at : at + 1] == "#" else text
    if note is not None:
        if text.endswith("  " + note):
            return text[: -len(note) - 2]
        return re.sub(r"\s*" + re.escape(note) + r"\s*$", "", text)
    return text


def exclusion(project, comp, ion):
    """
    What excluding a component from an ion comments out (Q5.15, Q5.18): the ion's
    line, an ion's ratio line, and the lines that use a label only they carry (each
    with a note, so that Include brings them back).

    Returns
    -------
    Exclusion

    Raises
    ------
    ComponentError
        When the component's lines share no redshift label (the label ties a
        commented-out line to its component), or it has no line of the ion.

    Generated by RJC and Claude.
    """
    project.require_reading()
    if not comp.label:
        raise ComponentError(
            "The lines of component {0} do not share a redshift label: tie them"
            " first (the notice above the panels).".format(comp.id)
        )
    own = comp.lines_of(ion)
    ratios = [ln for ln in comp.ratios if ln.ion.split("/")[0] == ion]
    if not own and not ratios:
        raise ComponentError(
            "Component {0} has no {1} line.".format(comp.id, P.ion_name(ion))
        )
    live_ions = {ln.ion for ln in comp.lines}
    last = not ratios and live_ions <= {ion}
    work = R._Removal(project, "")
    for line in own:
        work.delete_line(line.line, "it is {0} in {1}".format(P.ion_name(ion), comp.id))
    others = []
    for line in ratios:
        others += [
            c.id for c in project.components if line in c.ratios and c is not comp
        ]
        work.delete_line(line.line, "it gives {0} as a ratio".format(P.ion_name(ion)))
    work.settle()
    pm = project.parsed
    note = P.EXCLUDED_NOTE.format(ion, comp.label)
    entries, patches = [], []
    for num in sorted(work.delete):
        text = pm.text[num].text
        new = _comment(text, None if any(ln.line == num for ln in own) else note)
        entries.append(R.PlanLine(num, "comment", work.delete[num], text, new))
        patches.append(T.replace_line(pm.text, num, new))
    change = T.Change.from_spans(
        patches, "Exclude {0} from {1}".format(P.ion_name(ion), comp.id)
    )
    return Exclusion(entries, change, last, sorted(set(others)))


def exclude(project, comp, ion):
    """
    The step that excludes a component from an ion (Q5.15).

    Raises
    ------
    ComponentError
        When it is the component's last ion: the component is removed instead
        (``remove.plan_component``), once the user agrees.

    Generated by RJC and Claude.
    """
    plan = exclusion(project, comp, ion)
    if plan.last:
        raise ComponentError(
            "{0} is the last ion of component {1}: excluding it removes the"
            " component.".format(P.ion_name(ion), comp.id)
        )
    return project.step(plan.change, plan.change.description)


def include(project, comp, ion, prefs=None):
    """
    The step that includes a component in an ion again (Q5.15): its commented-out
    line comes back with its log N, and the component's current z, b_turb and T
    (they are tied, so they must agree) and the specids of the ion's snips now; the
    lines excluded with it come back too. A component that never had the ion gets a
    new line, with a first guess.

    Returns
    -------
    tuple
        ``(step, guess)``; the guess is None when the old line came back.

    Generated by RJC and Claude.
    """
    project.require_reading()
    pm = project.parsed
    num = comp.excluded.get(ion)
    note = P.EXCLUDED_NOTE.format(ion, comp.label)
    noted = [i for i in comp.excluded_with if i.note[0] == ion]
    if num is None and not noted:
        if ion in comp.ions:
            raise ComponentError(
                "Component {0} already has {1}.".format(comp.id, P.ion_name(ion))
            )
        words = {name: _main_word(comp, name) for name in E.COMPONENT_PREFIX}
        b = comp.main.param("bturb")
        t = comp.main.param("temperature")
        bturb = b.start if b is not None else 0.0
        temp = t.start if t is not None else 0.0
        curves = _current_curves(project, [ion], comp.z)
        guess = first_guess(project, ion, comp.z, bturb, temp, curves, prefs)
        maker = _add_line_maker(project, comp.system, comp, ion, guess.logn, words)
        change, _ = _chain(pm, [maker])
        step = project.step(
            change, "Include {0} in {1}".format(P.ion_name(ion), comp.id)
        )
        return step, guess
    patches = []
    if num is not None:
        patches.append(T.replace_line(pm.text, num, _uncomment(pm.text[num].text)))
    for item in noted:
        text = pm.text[item.line].text
        patches.append(T.replace_line(pm.text, item.line, _uncomment(text, note)))
    first = T.Change.from_spans(patches, "")
    after = E.reread(pm, first)
    second = T.Change((), "")
    if num is not None:
        second = _agree(project, after, comp, num, ion)
    change = T.Change(
        first.patches + second.patches,
        "Include {0} in {1}".format(P.ion_name(ion), comp.id),
    )
    return project.step(change, change.description), None


def _agree(project, pm, comp, num, ion):
    """
    The change that gives a line brought back the component's current z, b_turb
    and T, and the specids of the ion's snips now: nothing when they agree.

    Generated by RJC and Claude.
    """
    item = pm.item_at(num)
    main = pm.item_at(comp.main.line)
    patches = []
    for name in E.COMPONENT_PREFIX:
        par, ref = item.param(name), main.param(name)
        if par is None or ref is None or par.value_token is None:
            continue
        if ref.value_token is None or par.value_token.text == ref.value_token.text:
            continue
        patches.append(T.replace_token(pm.text, par.value_token, ref.value_token.text))
    kw = item.keywords.get("specid")
    if kw is not None:
        new = specids_for(project, ion, comp.z, comp.system)
        if set(new) != set(item.specids):
            patches.append(T.replace_token(pm.text, kw.val, ",".join(new)))
    return T.Change.from_spans(patches, "")


# -- Interlopers (S14, Q5.14) -----------------------------------------------------


def forest_temperature_label(project):
    """The fixed temperature label the Lyα forest's lines share, or ``""``."""
    labels = set()
    for line in project.absorbers:
        par = line.param("temperature")
        if par is None or not par.label or not par.fixed:
            return ""
        labels.add(par.label)
    return labels.pop() if len(labels) == 1 else ""


def interloper(project, wave, ion="1Ly_a", fixed=False, specid=None, prefs=None):
    """
    The step that adds a line of the Lyα forest (S14): its Lyα at a wavelength of
    the model's frame, log N from the first guess, b of 20 km/s and T fixed at 0
    (the forest's own label when its lines share one); fixed or free.

    Parameters
    ----------
    wave : float
        The wavelength of its Lyα, in the model's frame (Å).
    ion : str
        ``"1Ly_a"`` or ``"1H_IB"``.
    specid : str, optional
        The snip clicked, used when no snip holds a transition of the line.

    Returns
    -------
    tuple
        ``(step, guess)``.

    Generated by RJC and Claude.
    """
    project.require_reading()
    if ion not in P.GENERIC_IONS:
        raise ComponentError(
            "An interloper is a line of " + " or ".join(P.GENERIC_IONS)
        )
    pm = project.parsed
    waves, _ = project.registry.transitions(ion)
    z = float(wave) / float(waves[0]) - 1.0
    curves = _current_curves(project, [ion], z)
    bturb = _pref(prefs, "components.forest_b")
    guess = first_guess(project, ion, z, bturb, 0.0, curves, prefs)
    scheme = E.new_component(pm, FOREST_LETTER)
    tlabel = forest_temperature_label(project) or scheme["temperature"].upper()
    labels, fix = {"temperature": tlabel}, {"temperature": True}
    if fixed:
        for name in ("redshift", "bturb"):
            labels[name], fix[name] = scheme[name], True
        labels["ColDens"], fix["ColDens"] = "n" + scheme["redshift"][1:], True
    specids = [s.specid for s in snips_holding(project, ion, z)]
    if not specids:
        specids = [specid] if specid else [s.specid for s in project.snips]
    lines = [ln.line for ln in project.absorbers]
    change = E.add_ion(
        pm,
        ion,
        written("ColDens", guess.logn),
        written("redshift", z),
        written("bturb", bturb),
        written("temperature", 0.0),
        specids,
        labels=labels,
        fixed=fix,
        after=max(lines) if lines else None,
    )
    return project.step(change, "Add an interloper"), guess


# How far from a click the transitions of other systems are offered (S14), in km/s
INTERLOPER_KMS = 300.0
# The most of them offered
INTERLOPER_CHOICES = 8


@dataclass
class Interloper:
    """
    One choice of Add interloper (S14, Q5.14): a line of the Lyα forest whose Lyα is
    at the clicked wavelength, or a component of another system whose transition
    falls there.

    Attributes
    ----------
    text : str
        As the menu says it.
    wave : float
        The clicked wavelength, in the model's frame (Å).
    ion : str
        ``"1Ly_a"`` or ``"1H_IB"`` for the forest; the transition's ion otherwise.
    fixed : bool
        A line of the forest with z, b and log N fixed.
    system : System or None
        The other system, or None for the forest.
    z : float or None
        The component's redshift, for another system.

    Generated by RJC and Claude.
    """

    text: str
    wave: float
    ion: str
    fixed: bool = False
    system: object = field(default=None, repr=False)
    z: float = None


def interloper_choices(project, wave, shown=None, near_kms=INTERLOPER_KMS):
    """
    The choices of Add interloper at a clicked wavelength (S14, Q5.14): a line of
    the Lyα forest (Lyα alone, or every Lyman line), free or fixed; then the
    components of other systems whose transitions (their line IDs) fall within
    ``near_kms`` of the click, nearest first.

    Parameters
    ----------
    wave : float
        The clicked wavelength, in the model's frame (Å).
    shown : System, optional
        The system shown, which is not offered.

    Returns
    -------
    list of Interloper

    Generated by RJC and Claude.
    """
    out = [
        Interloper("Lyα forest line", wave, "1Ly_a"),
        Interloper("Lyα forest line, fixed", wave, "1Ly_a", True),
        Interloper("H I blend, every Lyman line", wave, "1H_IB"),
        Interloper("H I blend, every Lyman line, fixed", wave, "1H_IB", True),
    ]
    others = [s for s in project.systems if shown is None or s.id != shown.id]
    if not others:
        return out
    low = wave * (1.0 - near_kms / C_KMS)
    high = wave * (1.0 + near_kms / C_KMS)
    ids, _ = L.line_ids(project, low, high, systems=others)
    found = []
    for lid in ids:
        if not lid.system:
            continue
        system = project.system(lid.system)
        if lid.ion not in system_ions(project, system):
            continue
        z = wave / lid.rest - 1.0
        text = "{0} of z = {1:.5f}, at {2:+.0f} km/s".format(
            lid.label, system.z, P.velocity(z, system.z)
        )
        away = abs(C_KMS * (lid.observed / wave - 1.0))
        found.append((away, Interloper(text, wave, lid.ion, False, system, z)))
    found.sort(key=lambda t: t[0])
    return out + [choice for _, choice in found[:INTERLOPER_CHOICES]]


def add_interloper(project, choice, specid=None, prefs=None):
    """
    The step of one choice of Add interloper: a line of the Lyα forest, or a
    component of the other system, with a line for each of its ions (D20).

    Parameters
    ----------
    choice : Interloper
    specid : str, optional
        The snip clicked, used when no snip holds a transition of a forest line.

    Returns
    -------
    tuple
        ``(step, guesses)``: each ion's :class:`Guess`.

    Generated by RJC and Claude.
    """
    if choice.system is None:
        step, guess = interloper(
            project, choice.wave, choice.ion, choice.fixed, specid, prefs
        )
        return step, {choice.ion: guess}
    return new_component(project, choice.system, choice.z, prefs)


