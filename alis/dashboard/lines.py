@dataclass
class Candidate:
    """
    A transition that could make a feature at a clicked wavelength.

    Attributes
    ----------
    line : Line
    z : float
        The redshift it implies, ``λ / λ₀ − 1``.

    Generated by RJC and Claude.
    """

    line: Line
    z: float

    @property
    def name(self):
        """``Lyβ 1025.7``."""
        return self.line.name


def identify(atom, wave, data_max=None, systems_z=(), near_kms=500.0):
    """
    The transitions that could make a feature at ``wave``, with the redshift each
    implies; only those giving z ≥ 0 (S24, D35).

    Parameters
    ----------
    atom : Atomic
    wave : float
        The clicked wavelength, in Å.
    data_max : float, optional
        The reddest wavelength of the data: the first choice is the strongest
        transition whose system's Lyα would fall at or below it ("within the data's
        Lyα reach").
    systems_z : iterable of float
        The redshifts of the systems already known: a transition that puts the click
        within ``near_kms`` of one of them is the first choice (the user is
        refining a redshift, as the mockup shows), the strongest such.
    near_kms : float

    Returns
    -------
    tuple
        ``(candidates, first)``: the candidates, strongest first, and the index of
        the first choice (None when there is none).

    Generated by RJC and Claude.
    """
    found = []
    for line in atom.main_lines():
        if line.rest <= wave:
            found.append(Candidate(line, wave / line.rest - 1.0))
    found.sort(key=lambda c: -(c.line.strength if c.line.strength is not None else -99))
    first = None
    for k, cand in enumerate(found):
        if any(abs(C_KMS * (cand.z - z) / (1.0 + z)) <= near_kms for z in systems_z):
            return found, k
    for k, cand in enumerate(found):
        if cand.line.strength is None:
            continue
        if data_max is None or (1.0 + cand.z) * LYA <= data_max * (1.0 + 1.0e-9):
            first = k
            break
    if first is None and found:
        first = 0
    return found, first


def candidate_menus(candidates):
    """
    The candidates as the three menus of Identify a feature: element → stage →
    transitions (D35). Elements come H first, then by solar abundance; transitions
    strongest first.

    Returns
    -------
    dict
        ``{element: {stage: [Candidate, ...]}}``, in menu order.

    Generated by RJC and Claude.
    """
    tree = {}
    for cand in candidates:
        line = cand.line
        tree.setdefault(line.element, {}).setdefault(line.stage, []).append(cand)
    order = {s: k for k, s in enumerate(SYMBOLS)}

    def elem_key(elem):
        return (elem != "H", -SOLAR.get(elem, -99.0), order.get(elem, 999))

    out = {}
    for elem in sorted(tree, key=elem_key):
        out[elem] = {
            stage: sorted(tree[elem][stage], key=lambda c: -c.line.flam)
            for stage in sorted(tree[elem], key=roman)
        }
    return out


# -- The transitions of the snips ------------------------------------------------------


@dataclass(frozen=True)
class SnipTransition:
    """
    The transition a snip was cut for.

    Attributes
    ----------
    system : str
        The system's id, or ``""`` when no system has it.
    ion : str
    rest : float

    Generated by RJC and Claude.
    """

    system: str
    ion: str
    rest: float


SNIPS_KEY = "snips"


def snip_transitions(project):
    """
    The transition of each snip, by specid: as SNIP records it in
    ``ui/project.json``, or else guessed (from the transition its file name names,
    or the transition of a system's ions nearest the snip's middle).

    Returns
    -------
    dict
        Specid to :class:`SnipTransition`, or None for a snip whose transition is
        not known.

    Generated by RJC and Claude.
    """
    atom = atomic(project.registry)
    recorded = project.ui.get(SNIPS_KEY, {})
    out = {}
    for snip in project.snips:
        rec = recorded.get(snip.specid)
        if rec and rec.get("ion") and rec.get("rest") is not None:
            out[snip.specid] = SnipTransition(
                rec.get("system", ""), rec["ion"], float(rec["rest"])
            )
        else:
            out[snip.specid] = _guess_transition(project, atom, snip)
    return out


def _guess_transition(project, atom, snip):
    """
    The transition of a snip that SNIP did not record (an imported fit).

    Generated by RJC and Claude.
    """
    extent = snip.extent
    if extent is None:
        return None
    middle = 0.5 * (extent[0] + extent[1])
    base = posixpath.basename(snip.data.file.text)
    match = _NAMED.search(base)
    if match:
        element, stage, text = match.group(2), match.group(3), match.group(4)
        named = float(text)
        ion = atom.main_ion.get((element, stage))
        if "." in text:
            # Named to a tenth of an Å: the nearest line
            near = [
                ln for ln in atom.ion_lines(ion or "") if abs(ln.rest - named) <= 0.06
            ]
            pick = min(near, key=lambda ln: abs(ln.rest - named)) if near else None
        else:
            # Named in whole Å (``_O_I_988_``): the strongest line it may mean
            near = [
                ln
                for ln in atom.ion_lines(ion or "")
                if int(ln.rest) == int(named) or round(ln.rest) == int(named)
            ]
            pick = max(near, key=lambda ln: ln.fval) if near else None
        if pick is not None:
            line = pick
            best = None
            for system in project.systems:
                obs = line.rest * (1.0 + system.z)
                if extent[0] <= obs <= extent[1]:
                    gap = abs(obs - middle)
                    if best is None or gap < best[0]:
                        best = (gap, system.id)
            return SnipTransition(best[1] if best else "", line.ion, line.rest)
    best = None
    for system in project.systems:
        for ion in system.ions:
            for line in atom.ion_lines(ion):
                obs = line.rest * (1.0 + system.z)
                if extent[0] <= obs <= extent[1]:
                    gap = abs(obs - middle)
                    if best is None or gap < best[0]:
                        best = (gap, SnipTransition(system.id, line.ion, line.rest))
    return best[1] if best else None


def snipped_by_ion(snip_map, system):
    """
    The rest wavelengths with a snip for one system, by ion.

    Generated by RJC and Claude.
    """
    out = {}
    for trans in snip_map.values():
        if trans is not None and trans.system == system:
            out.setdefault(trans.ion, []).append(trans.rest)
    return out


# -- Coverage (Q0.5) -----------------------------------------------------------------

SNIP, COVERED, NONE = "snip", "covered", "none"


@dataclass
class GridRow:
    """
    One transition of the coverage grid, and its cell for each file row.

    Attributes
    ----------
    ion : str
    rest : float
    name : str
    cells : dict
        Row id to ``"snip"`` (■ it has a snip), ``"covered"`` (□ its source covers
        it, with no snip yet) or ``"none"`` (· not covered).

    Generated by RJC and Claude.
    """

    ion: str
    rest: float
    name: str
    cells: dict = field(default_factory=dict)


def coverage_grid(project, system, coverages, snip_map=None, half_width=HALF_WIDTH):
    """
    The coverage grid of a system (Q0.5): one row per transition that has a snip or
    is named among its line IDs, by rest wavelength; one cell per file row.

    Parameters
    ----------
    project : Project
    system : System
    coverages : list of Coverage
        One per file row.
    snip_map : dict, optional
        From :func:`snip_transitions`.

    Returns
    -------
    list of GridRow

    Generated by RJC and Claude.
    """
    atom = atomic(project.registry)
    snip_map = snip_transitions(project) if snip_map is None else snip_map
    wanted = {}
    for specid, trans in snip_map.items():
        if trans is not None and trans.system == system.id:
            wanted[(trans.ion, round(trans.rest, 3))] = trans.rest
    for entry in system.lines:
        if entry.get("ion") and entry.get("wave") is not None:
            wanted[(entry["ion"], round(float(entry["wave"]), 3))] = float(
                entry["wave"]
            )
    by_row = {}
    for snip in project.snips:
        trans = snip_map.get(snip.specid)
        if trans is not None and trans.system == system.id and snip.row is not None:
            by_row.setdefault(snip.row.id, set()).add((trans.ion, round(trans.rest, 3)))
    out = []
    for key, rest in sorted(wanted.items(), key=lambda kv: kv[1]):
        ion = key[0]
        mass, element, stage = P.split_ion(ion)
        name = line_name(
            "D" if (element == "H" and mass == 2) else element, stage, rest
        )
        row = GridRow(ion, rest, name)
        for cov in coverages:
            if key in by_row.get(cov.row, set()):
                row.cells[cov.row] = SNIP
            elif cov.source and place(rest * (1.0 + system.z), [cov], half_width)[0]:
                row.cells[cov.row] = COVERED
            else:
                row.cells[cov.row] = NONE
        out.append(row)
    return out


