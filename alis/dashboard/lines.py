"""Transitions, line IDs, flags and coverage (dashboard Stage 4.1; S2, S5, D36).

No Qt: the Data and Regions tabs ask this module what to list and what to label, and
draw what it says.

- **Lines.** Every transition of ALIS's atomic table that belongs to a chemical
  element, with its ion, element, stage, rest wavelength and f-value. The transition
  list folds isotopes into their element: it lists the main isotope's transitions
  only, since D I is fitted in H I's snips (D36).
- **Where the data are.** A :class:`Coverage` holds the pixels of one file row: those
  of its source spectrum, or those of its snips when it has none (D12). Its good
  pixels (finite, with a positive error, not marked bad) form segments; a jump in
  wavelength splits them.
- **The transition list** (S2, D36): the transitions of one ion that fall on the
  data, ranked by fλ, with lines closer together than the resolution in one row
  ("O I 971.7 ×3"), flagged "gap" (no good pixels there) or "edge" (closer to an end
  of the data than a snip's half-width); no forest or telluric flags (Q4.5). A
  transition that already has a snip is listed whatever its flags.
- **Line IDs** (S5, Q4.4): for every system, the transitions of its ions (in the
  model, or named as its line IDs), the strong lines (by fλ and the solar abundance,
  as ``prepfit`` ranks them), or every line; and the number left unlabelled.
- **Identify a feature** (S24, D35): the transitions that could make a feature at a
  clicked wavelength, each with the redshift it implies.
- **Coverage** (Q0.5): which transitions of a system each file row has a snip of, or
  covers.
- **Snips' transitions:** the transition each snip was cut for, as SNIP records it
  in ``ui/project.json``, or guessed from its file name and its extent.

Generated by RJC and Claude.
"""

