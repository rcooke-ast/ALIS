"""Compare two runs (dashboard Stage 6.7; D41; Q6.9, Q0.9, Q0.11). No Qt.

- **The quantities of a run** (:func:`quantities`), which two parametrisations of
  one absorber share (Q6.9(a)):
  - each ion's total log N in each system: the components' column densities, in
    log or linear form (``logN=False``, ``ColDensScale``), or through a ratio line
    (``ion=2H_I/1H_I``, whose column density is the ratio times its element's);
  - each isotope's ratio to its element (log D/H): from the two column densities,
    over the components that have both, or the ratio itself, whether it is fitted
    or computed by a link (a ``variable``);
  - each component of each ion (with its own lines): its velocity in its system,
    b and T; and how many components each ion has;
  - each dataset's FWHM, and χ²ν, the degrees of freedom and the iterations.
- **Errors** (Q6.9(b)): each quantity's error is propagated from the run's
  covariance, through its derivatives in the free parameters it depends on, links
  included. A quantity of one free parameter takes that parameter's error when the
  run has no covariance; otherwise it has none ("—").
- **The comparison** (:func:`compare`): the components of an ion are matched by
  system, ion and velocity (the nearest within a preference, 10 km/s); each row
  gives both values, Δ (the second run's less the first's) and |Δ|/σ, σ the larger
  of the two errors (Q6.9(c)), the runs fitting the same data.
- **Blinding** (Q0.9, Q0.11): a quantity derived from a value hidden in either run
  (or in the model as it is now, or under global blind) shows only |Δ|/σ, with no
  value and no sign; a χ², a count of components and a correlation are shown.

Generated by RJC and Claude.
"""

import difflib
import math
from dataclasses import dataclass, field

import numpy as np

from alis.dashboard import blinding as BL
from alis.dashboard import project as P
from alis.dashboard import results as RS

C_KMS = 299792.458
MINUS = "−"
NONE = "—"
# The groups of the table, after the systems
INSTRUMENT, FIT = "Instrument", "Fit"


class CompareError(Exception):
    """Two runs that cannot be compared as asked."""


@dataclass
class Quantity:
    """
    One quantity of a run.

    Attributes
    ----------
    key : tuple
        What it is, the same in both runs: ``("logN", system, ion)``, ``("ratio",
        system, isotope, element)``, ``("count", system, ion)``, ``("fwhm",
        specid)``, ``("stat", name)``; a component's are matched by velocity
        (:class:`Component`).
    name : str
        ``"log N(O I)"``.
    group : str
        Its system's name, ``"Instrument"`` or ``"Fit"``.
    value : float or None
    sigma : float or None
        None when the run gives no error; 0 for a fixed value.
    hidden : bool
        Derived from a hidden value.
    decimals : int
    fixed : bool
    unit : str

    Generated by RJC and Claude.
    """

    key: tuple
    name: str
    group: str
    value: float = None
    sigma: float = None
    hidden: bool = False
    decimals: int = 3
    fixed: bool = False
    unit: str = ""


@dataclass
class Component:
    """
    A component of one ion of a run, for matching by velocity: its v, b and T.

    Generated by RJC and Claude.
    """

    system: str
    ion: str
    ident: str
    velocity: float
    group: str
    quantities: dict = field(default_factory=dict)
    hidden: bool = False


@dataclass
class Row:
    """
    A row of Compare's table (D41): both runs' values, Δ and |Δ|/σ, through the
    gate.

    Generated by RJC and Claude.
    """

    group: str
    name: str
    first: str
    second: str
    delta: str
    sigma: str
    note: str = ""
    hidden: bool = False
    key: tuple = ()
    nsigma: float = None


# -- One run's quantities -------------------------------------------------------------


class _Run:
    """
    A run's best fit, its covariance and errors, and the parameters each value
    depends on.

    Generated by RJC and Claude.
    """

    def __init__(self, view):
        self.view = view
        self.pm = view.model.parsed
        self.profile = view.profile()
        self.vector = view.vector()
        size = self.profile.start.size
        self.changes = {i: v for i, v in (view.values or {}).items() if 0 <= i < size}
        self.covariance = None if view.interrupted else view.covariance
        self.errors = view.errors or {}
        self.labels = {name.lower(): label for name, label in self.pm.labels.items()}
        self.links = {link.target.lower(): link for link in self.pm.links}

    def sources(self, params):
        """
        The free parameters (ALIS's numbers) that some parameters depend on: each
        free one itself, and for a linked one, those its link reads.

        Generated by RJC and Claude.
        """
        out, todo, seen = set(), [p for p in params if p is not None], set()
        while todo:
            par = todo.pop()
            if par.linked:
                link = self.links.get((par.label or "").lower())
                if link is None:
                    continue
                for dep in link.deps:
                    if dep.lower() in seen:
                        continue
                    seen.add(dep.lower())
                    label = self.labels.get(dep.lower())
                    if label is not None:
                        todo.extend(label.params)
            elif par.free and par.index >= 0:
                out.add(par.index)
        return out

    def hidden(self, params):
        """Whether a value derived from these parameters is hidden."""
        gate = self.view.gate
        for par in params:
            if par is not None and gate.masked(par):
                return True
        return False

    def sigma(self, func, params):
        """
        The error of ``func(vector)``: from the covariance, through its derivatives
        in the free parameters it depends on; 0 when it depends on fixed values
        alone; None when the run has no covariance and it depends on more than one
        free parameter, or none of their errors.

        Generated by RJC and Claude.
        """
        found = sorted(self.sources(params))
        if not found:
            return 0.0
        base = func(self.vector)
        grads = []
        for k in found:
            err = self.errors.get(k)
            if self.covariance is not None and k < self.covariance.shape[0]:
                err = math.sqrt(max(self.covariance[k, k], 0.0))
            step = 1.0e-4 * err if err else 1.0e-7 * max(1.0, abs(self.vector[k]))
            changes = dict(self.changes)
            changes[k] = self.vector[k] + step
            try:
                moved = self.profile.values(changes)
            except Exception:
                return None
            grads.append((func(moved) - base) / step)
        jac = np.asarray(grads)
        cov = self.covariance
        if cov is not None and max(found) < cov.shape[0]:
            sub = cov[np.ix_(found, found)]
            if np.any(np.diag(sub) > 0):
                return float(math.sqrt(max(jac @ sub @ jac, 0.0)))
        if len(found) == 1 and self.errors.get(found[0]) is not None:
            return float(abs(jac[0]) * self.errors[found[0]])
        return None


def _log_n(line, vector):
    """A line's log N (``logN=False`` lines hold N over ``ColDensScale``)."""
    par = line.param("ColDens")
    value = vector[par.index]
    if str(line.keyword("logN", "True")).lower() == "false":
        scale = float(line.keyword("ColDensScale", 1.0) or 1.0)
        return math.log10(max(value * scale, 1.0e-300))
    return value


def _log_ratio(line, vector):
    """A ratio line's log ratio."""
    value = vector[line.param("ColDens").index]
    if str(line.keyword("logN", "True")).lower() == "false":
        return math.log10(max(value, 1.0e-300))
    return value


def _system_name(system):
    return RS._system_name(system)


def _components(model, system, ion):
    return [c for c in system.components if c.lines_of(ion)]


def quantities(view, prefs=None):
    """
    A run's quantities (Q6.9(a)): the systems' totals and isotope ratios, the
    components of each ion, the instrument and the fit.

    Parameters
    ----------
    view : results.View
        A run with a best fit.

    Returns
    -------
    tuple
        ``(dict of key to Quantity, list of Component)``.

    Raises
    ------
    CompareError
        If the run has no best fit.

    Generated by RJC and Claude.
    """
    try:
        run = _Run(view)
    except RS.ResultsError as err:
        raise CompareError(str(err)) from None
    model = view.model
    vector = run.vector
    out, comps = {}, []

    def add(quantity):
        out[quantity.key] = quantity

    for system in model.systems:
        group = _system_name(system)
        ions = []
        for comp in system.components:
            for ion in comp.ions:
                if ion not in ions:
                    ions.append(ion)
        own = {}
        for ion in ions:
            lines = [ln for c in system.components for ln in c.lines_of(ion)]
            ratios = [
                (c, ln)
                for c in system.components
                for ln in c.ratios
                if ln.ion.split("/")[0] == ion
            ]
            parts = []
            for line in lines:
                parts.append(((line,), lambda v, ln=line: _log_n(ln, v)))
            for comp, ratio in ratios:
                denom = ratio.ion.split("/")[1]
                for line in comp.lines_of(denom):
                    parts.append(
                        (
                            (ratio, line),
                            lambda v, r=ratio, ln=line: _log_ratio(r, v)
                            + _log_n(ln, v),
                        )
                    )
            if not parts:
                continue
            params = [ln.param("ColDens") for pieces, _ in parts for ln in pieces]

            def total(v, parts=parts):
                return math.log10(sum(10.0 ** f(v) for _, f in parts))

            name = "log N({0})".format(RS._ion_name(ion))
            add(
                Quantity(
                    ("logN", system.id, ion),
                    name,
                    group,
                    total(vector),
                    run.sigma(total, params),
                    run.hidden(params),
                    3,
                    unit="",
                )
            )
            own[ion] = lines
            add(
                Quantity(
                    ("count", system.id, ion),
                    "{0} components".format(RS._ion_name(ion)),
                    group,
                    float(len(_components(model, system, ion)) or len(ratios)),
                    None,
                    False,
                    0,
                )
            )
        # Isotope ratios: each isotope to its element's main isotope (log D/H)
        for ion in ions:
            mass, element, stage = P.split_ion(ion)
            mains = [
                i
                for i in ions
                if P.split_ion(i)[1:] == (element, stage)
                and i != ion
                and P._main_isotope([i, ion]) == i
            ]
            if not mains:
                continue
            main = mains[0]
            ratio_lines = [
                ln
                for c in system.components
                for ln in c.ratios
                if ln.ion == "{0}/{1}".format(ion, main)
            ]
            if ratio_lines:
                line = ratio_lines[0]
                params = [line.param("ColDens")]

                def ratio(v, line=line):
                    return _log_ratio(line, v)

            else:
                both = [
                    c for c in system.components if c.lines_of(ion) and c.lines_of(main)
                ]
                if not both:
                    continue
                tops = [c.lines_of(ion)[0] for c in both]
                bottoms = [c.lines_of(main)[0] for c in both]
                params = [ln.param("ColDens") for ln in tops + bottoms]

                def ratio(v, tops=tops, bottoms=bottoms):
                    top = sum(10.0 ** _log_n(ln, v) for ln in tops)
                    bottom = sum(10.0 ** _log_n(ln, v) for ln in bottoms)
                    return math.log10(top / bottom)

            name = "log {0}/{1}".format(_element_symbol(ion), _element_symbol(main))
            add(
                Quantity(
                    ("ratio", system.id, ion, main),
                    name,
                    group,
                    ratio(vector),
                    run.sigma(ratio, params),
                    run.hidden(params),
                    3,
                )
            )
        # The components of each ion with lines of its own
        for ion, lines in own.items():
            if not lines:
                continue
            for comp in _components(model, system, ion):
                line = comp.lines_of(ion)[0]
                zpar = line.param("redshift")
                velocity = P.velocity(vector[zpar.index], system.z)
                found = Component(
                    system.id,
                    ion,
                    comp.id,
                    velocity,
                    group,
                    hidden=run.hidden([zpar]),
                )
                parts = (
                    (
                        "v",
                        zpar,
                        lambda v, i=zpar.index: P.velocity(v[i], system.z),
                        2,
                        "km/s",
                    ),
                    ("b", line.param("bturb"), None, 2, "km/s"),
                    ("T", line.param("temperature"), None, 0, "K"),
                )
                for what, par, func, decimals, unit in parts:
                    if par is None or par.index < 0:
                        continue
                    if func is None:

                        def func(v, i=par.index):
                            return v[i]

                    found.quantities[what] = Quantity(
                        (what,),
                        what,
                        group,
                        func(vector),
                        run.sigma(func, [par]),
                        run.hidden([par]),
                        decimals,
                        fixed=bool(par.fixed),
                        unit=unit,
                    )
                comps.append(found)
    # The instrument: each FWHM parameter, named by the datasets that share it
    sharing = {}
    for row in model.rows:
        par = row.fwhm
        if par is not None and par.index >= 0:
            sharing.setdefault(par.index, (par, []))[1].append(row.name)
    for index, (par, names) in sharing.items():

        def fwhm(v, i=index):
            return v[i]

        add(
            Quantity(
                ("fwhm",) + tuple(names),
                "FWHM " + ", ".join(names),
                INSTRUMENT,
                fwhm(vector),
                run.sigma(fwhm, [par]),
                run.hidden([par]),
                3,
                fixed=bool(par.fixed),
                unit="km/s",
            )
        )
    stats = view.statistics()
    for name, value, decimals in (
        ("χ²ν", stats.reduced, 3),
        ("Degrees of freedom", stats.dof, 0),
        ("Iterations", stats.iterations, 0),
    ):
        if value is not None:
            add(
                Quantity(("stat", name), name, FIT, float(value), None, False, decimals)
            )
    return out, comps


def _element_symbol(ion):
    """``2H_I`` as D, ``1H_I`` as H; other ions by their element."""
    mass, element, stage = P.split_ion(ion)
    if element == "H":
        return "D" if mass == 2 else ("T" if mass == 3 else "H")
    return "{0}{1}".format(mass, element) if mass else element


# -- Matching and comparing ------------------------------------------------------------


def match_components(first, second, within=10.0):
    """
    The components of two runs matched by system, ion and velocity (Q6.9(a)): each
    pair the nearest in velocity within ``within`` km/s, the nearest pairs first.

    Returns
    -------
    list of tuple
        ``(first's Component or None, second's or None)``, in the order of the
        first run's components (those only in the second after).

    Generated by RJC and Claude.
    """
    pairs = []
    for i, one in enumerate(first):
        for j, two in enumerate(second):
            if (one.system, one.ion) != (two.system, two.ion):
                continue
            gap = abs(one.velocity - two.velocity)
            if gap <= within:
                pairs.append((gap, i, j))
    pairs.sort()
    taken_i, taken_j, match = set(), set(), {}
    for _, i, j in pairs:
        if i in taken_i or j in taken_j:
            continue
        taken_i.add(i)
        taken_j.add(j)
        match[i] = j
    out = [
        (one, second[match[i]] if i in match else None) for i, one in enumerate(first)
    ]
    out += [(None, two) for j, two in enumerate(second) if j not in taken_j]
    return out


def _number(value, decimals, sign=False):
    """A value with its decimals (thousands grouped for a whole number), with a
    true minus."""
    plus = "+" if sign else ""
    if decimals == 0 and abs(value) >= 1000.0:
        text = "{0:{1},.0f}".format(value, plus)
    else:
        text = "{0:{1}.{2}f}".format(value, plus, decimals)
    return text.replace("-", MINUS)


def _signed(value, decimals):
    """A change, signed; one that rounds to zero is written +0."""
    if round(value, decimals) == 0:
        value = 0.0
    return _number(value, decimals, sign=True)


def _value_text(quantity, hidden):
    if quantity is None or quantity.value is None:
        return ""
    if hidden:
        return BL.MASK
    text = _number(quantity.value, quantity.decimals)
    if quantity.fixed:
        return text + " (fixed)"
    if quantity.sigma:
        return "{0} ± {1}".format(text, _number(quantity.sigma, quantity.decimals))
    return text


def _row(group, name, one, two, key, note=""):
    """A row of the table from the two runs' quantities (either may be None)."""
    hidden = bool((one and one.hidden) or (two and two.hidden))
    delta = sigma_text = ""
    nsigma = None
    if one is not None and two is not None and None not in (one.value, two.value):
        change = two.value - one.value
        decimals = max(one.decimals, two.decimals)
        delta = BL.MASK if hidden else _signed(change, decimals)
        errors = [q.sigma for q in (one, two)]
        if one.key[0] in ("count", "stat"):
            sigma_text = ""
        elif None in errors:
            sigma_text = NONE
        else:
            sigma = max(errors)
            if sigma > 0:
                nsigma = abs(change) / sigma
                sigma_text = "{0:.1f}σ".format(nsigma)
            else:
                sigma_text = NONE
        if hidden and not sigma_text:
            sigma_text = NONE
    if hidden and not note:
        note = "blinded: only the size of the change is shown"
    return Row(
        group,
        name,
        _value_text(one, hidden),
        _value_text(two, hidden),
        delta,
        sigma_text,
        note,
        hidden,
        key,
        nsigma,
    )


def compare(first, second, prefs=None):
    """
    Compare two runs (D41, Q6.9): their matched quantities, each with both values,
    Δ (the second's less the first's) and |Δ|/σ, through the gate.

    Parameters
    ----------
    first, second : results.View
    prefs : Preferences, optional
        ``fit.match_kms``.

    Returns
    -------
    list of Row
        By group: each system (its totals, ratios and counts, then its components),
        the instrument, the fit.

    Raises
    ------
    CompareError

    Generated by RJC and Claude.
    """
    within = RS._pref(prefs, "fit.match_kms")
    one, comps_one = quantities(first, prefs)
    two, comps_two = quantities(second, prefs)
    groups, rows = [], {}

    def put(row):
        if row.group not in rows:
            groups.append(row.group)
            rows[row.group] = []
        rows[row.group].append(row)

    keys = list(one) + [k for k in two if k not in one]
    ordered = [k for k in keys if k[0] in ("logN", "ratio", "count")]
    ordered.sort(key=lambda k: (k[1], ("logN", "ratio", "count").index(k[0])))
    for key in ordered:
        a, b = one.get(key), two.get(key)
        group = (a or b).group
        put(_row(group, (a or b).name, a, b, key))
    for a, b in match_components(comps_one, comps_two, within):
        comp = a or b
        ident = a.ident if a is not None else b.ident
        note = ""
        if a is not None and b is not None and a.ident != b.ident:
            note = "{0} in the second run".format(b.ident)
        elif a is None:
            note = "only in the second run"
        elif b is None:
            note = "only in the first run"
        for what in ("v", "b", "T"):
            qa = a.quantities.get(what) if a is not None else None
            qb = b.quantities.get(what) if b is not None else None
            if qa is None and qb is None:
                continue
            unit = (qa or qb).unit
            name = "{0} {1} {2}{3}".format(
                RS._ion_name(comp.ion), ident, what, " (" + unit + ")" if unit else ""
            )
            put(
                _row(
                    comp.group, name, qa, qb, ("component", comp.ion, ident, what), note
                )
            )
    for key in keys:
        if key[0] not in ("fwhm", "stat"):
            continue
        a, b = one.get(key), two.get(key)
        put(_row((a or b).group, (a or b).name, a, b, key))
    out = []
    for group in groups:
        out.extend(rows[group])
    return out


# -- Restore a run's model (Q6.7) -------------------------------------------------------


def restore_preview(project, step, run_model):
    """
    What Restore run N's model… changes, for its preview: the model's lines that
    change (each through the gate of the model it is in), and the snips.

    Parameters
    ----------
    project : Project
    step : Step
        ``runs.restore_step``.
    run_model : Project
        The run's model (``results.model_of``).

    Returns
    -------
    tuple
        ``(lines, snips)``: ``[(kind, text)]`` with kind ``"-"`` (now) or ``"+"``
        (the run's), and the snips' names that change.

    Generated by RJC and Claude.
    """
    now = BL.Gate(project).view().text.splitlines()
    then = BL.Gate(run_model).view().text.splitlines()
    lines = []
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(
        None, now, then, autojunk=False
    ).get_opcodes():
        if tag == "equal":
            continue
        lines += [("-", now[k]) for k in range(i1, i2)]
        lines += [("+", then[k]) for k in range(j1, j2)]
    snips = sorted(m.rsplit("/", 1)[-1] for m in (step.files or {}))
    return lines, snips


