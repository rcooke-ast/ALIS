"""Lining the model's values up in columns (dashboard Stage 3, Q3.17(a)).

RJC asked for the ``.mod`` text to be easier to read: every column density starting
in the same column, every redshift in the next, and so on for the other lines. The
text is authoritative and is kept as written (D7), so aligning is an action the user
chooses (Model → Align columns), made as one undoable step. A new project's model is
written aligned, and lines the dashboard adds take the columns of their neighbours
(``text.layout_like``).

Aligning changes only spaces between the words of a line, so ALIS reads exactly the
same model. Lines are aligned in groups:

- the settings;
- the data lines;
- consecutive lines of one function in one section of the model block (the
  ``voigt`` lines of the absorption section, the ``legendre`` lines of the emission
  section, ...);
- the ``fix`` and ``lim`` commands.

In a group, the k-th value of every line starts in the same column, two spaces after
the widest k-th value before it; the keywords that follow the values (``specid=``,
``blind=``) start together after the widest run of values, each keyword in its own
column when every line gives them in the same order. A blank line, a block marker or a section starts a
new group; comment lines inside a group are left as they are. Links are not
aligned. A line's trailing comment is kept as written.

Generated by RJC and Claude.
"""

from alis.dashboard import text as T

# The spaces between two columns
GAP = 2
# Lines that end a group; comment lines do not
_BREAKS = (T.BLANK, T.BLOCK, T.SECTION, T.LINK, T.HIDDEN)


def _key(line, section):
    """The group a line belongs to, or None."""
    if line.kind == T.SETTING:
        return ("setting",)
    if line.kind == T.DATA:
        return ("data",)
    if line.kind in (T.FIX, T.LIM):
        return ("command",)
    if line.kind == T.FUNCTION and line.tokens:
        return ("function", section, line.tokens[0].text)
    return None


def groups(mtext):
    """
    The groups of lines aligned together.

    Parameters
    ----------
    mtext : ModelText

    Returns
    -------
    list of list of Line

    Generated by RJC and Claude.
    """
    out, current, key, section = [], [], None, ""
    for line in mtext:
        if line.kind == T.SECTION and line.tokens:
            section = line.tokens[0].text
        if line.kind == T.BLOCK:
            section = ""
        this = _key(line, section)
        if this is None:
            if line.kind in _BREAKS:
                if current:
                    out.append(current)
                current, key = [], None
            continue
        if this != key and current:
            out.append(current)
            current = []
        key = this
        current.append(line)
    if current:
        out.append(current)
    return out


def _split(words):
    """
    A line's words as its head (the function or setting, and its values, with any
    keyword among them such as ``ion=``) and its tail (the keywords after the last
    value).

    Generated by RJC and Claude.
    """
    last = max([n for n, word in enumerate(words) if "=" not in word] + [0])
    return words[: last + 1], words[last + 1 :]


def _name(word):
    return word.split("=", 1)[0]


def _keyword_columns(tails):
    """
    The column of each keyword of each line's tail: by name when every line gives its
    keywords in one order (a keyword a line lacks leaves a gap), otherwise by place.

    Returns
    -------
    tuple
        ``(columns, widths)``: for each line the column of each keyword, and the
        width of each column.

    Generated by RJC and Claude.
    """
    order = []
    for tail in tails:
        last = -1
        for word in tail:
            name = _name(word)
            if name not in order:
                order.insert(last + 1, name)
            last = order.index(name)
    by_name = all(
        [order.index(_name(w)) for w in tail]
        == sorted(order.index(_name(w)) for w in tail)
        and len({_name(w) for w in tail}) == len(tail)
        for tail in tails
    )
    columns = [
        [order.index(_name(w)) if by_name else n for n, w in enumerate(tail)]
        for tail in tails
    ]
    widths = {}
    for tail, cols in zip(tails, columns):
        for word, col in zip(tail, cols):
            widths[col] = max(widths.get(col, 0), len(word))
    return columns, widths


def _join(words, columns, widths):
    """Words placed in their columns, two spaces apart, with no trailing spaces."""
    out = ""
    for col in range(max(columns, default=-1) + 1):
        word = words[columns.index(col)] if col in columns else ""
        out += word.ljust(widths[col]) + " " * GAP
    return out.rstrip()


def aligned_lines(group):
    """
    The text of each line of a group, aligned: the values by their place, then the
    keywords after them, by name.

    Returns
    -------
    list of str

    Generated by RJC and Claude.
    """
    heads, tails = zip(*[_split([tok.text for tok in line.tokens]) for line in group])
    head_widths = {}
    for head in heads:
        for num, word in enumerate(head):
            head_widths[num] = max(head_widths.get(num, 0), len(word))
    columns, tail_widths = _keyword_columns(tails)
    head_width = sum(head_widths.values()) + GAP * len(head_widths)
    indent = group[0].indent
    out = []
    for line, head, tail, cols in zip(group, heads, tails, columns):
        text = _join(head, list(range(len(head))), head_widths)
        if tail:
            text = text.ljust(head_width) + _join(tail, cols, tail_widths)
        out.append(indent + text + line.text[line.content[1] :])
    return out


def align(mtext, description="Align columns"):
    """
    The change that lines the model's values up in columns.

    Parameters
    ----------
    mtext : ModelText or ParsedModel

    Returns
    -------
    Change
        Empty when the model is aligned already.

    Generated by RJC and Claude.
    """
    mtext = getattr(mtext, "text", mtext)
    if not isinstance(mtext, T.ModelText):
        mtext = T.ModelText(mtext)
    patches = []
    for group in groups(mtext):
        for line, new in zip(group, aligned_lines(group)):
            if new != line.text:
                patches.append(T.replace_line(mtext, line.num, new))
    return T.Change.from_spans(patches, description)


def aligned(text):
    """
    A model's text, aligned.

    Generated by RJC and Claude.
    """
    return align(T.ModelText(text)).apply(text)


__all__ = ["align", "aligned", "aligned_lines", "groups", "GAP"]
