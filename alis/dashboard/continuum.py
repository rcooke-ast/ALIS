"""The continuum: evaluated as ALIS does, first guess, order, knots, sharing.

Dashboard Stage 4.3 (S8, S9, S10, D17). No Qt.

- **Evaluated by ALIS's own functions.** A continuum line is drawn with the class
  ALIS fits it with (``legendre``, ``chebyshev``, ``polynomial``, ``constant``),
  called through ALIS's ``call_CPU`` with the line's coefficients times its
  ``scale=`` factors, on the snip's wavelengths moved by its row's shift, as ALIS
  moves them. Its range is ``min=``/``max=`` when the line gives them; otherwise the
  range of the wavelengths ALIS evaluates it on, taken from ALIS's own loaders. A fit
  basis is the same functions called with one coefficient at a time, so the curve
  the dashboard fits is the curve ALIS evaluates.
- **The first guess** (S8, Q4.6, Q4.16, Q4.19): the snip's good pixels, leaving out
  ±15 km/s around the transitions of the model's absorption lines and of the systems'
  line IDs, are clipped in three passes of rising order: a straight line, then one
  order higher, then one more, each fitted to the pixels the last kept and rejecting
  those far below it (2.5σ: absorption) or above it (3σ). Every order is then fitted
  to the pixels left, and the one with the lowest BIC, up to 5, is chosen.
- **Knots** (Q4.7, Q4.13): points the starting continuum passes through; every refit
  is held through them (a least-squares fit with equality constraints). They set only
  the starting coefficients: ALIS then fits the continuum freely. They are kept in
  ``ui/project.json``, by snip.
- **The table of orders:** χ², Δχ² and ΔBIC for the orders either side of the
  current one, on the same pixels.
- **Sharing** (S10, Q4.8): one Legendre for the snips of one transition in several
  file rows, with one ``min=``/``max=`` (the union of their ranges).

A continuum the dashboard writes has its coefficients scaled to order unity by
``scale=`` factors (powers of ten), and a Legendre has ``min=``/``max=`` (the snip's
range), so that what is drawn does not depend on how finely ALIS sub-pixellates.

Generated by RJC and Claude.
"""

import copy
import hashlib
import math
from dataclasses import dataclass, field
from types import SimpleNamespace

