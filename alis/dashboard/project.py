def _column_map(item):
    """
    The columns of a data line's file, as ``load_data`` reads ``columns=``.

    Generated by RJC and Claude.
    """
    cols = {"wave": 0, "flux": 1, "error": 2}
    value = item.keyword("columns")
    if value is None:
        return cols
    for k, part in enumerate(value.strip("[]()").split(",")):
        bits = part.strip().split(":")
        if len(bits) == 2:
            cols[bits[0].strip()] = int(bits[1])
        else:
            cols[bits[0].strip()] = k
    return cols


def _data_rows(content):
    """
    The lines of a text table that hold numbers, as ``np.loadtxt`` reads it.

    Returns
    -------
    tuple
        ``(lines, rows)``: every line as ``(text, ending, offset)``, and for each
        number line its index and the column spans of its words.

    Generated by RJC and Claude.
    """
    text = content.decode("utf-8")
    lines = T.split_lines(text)
    rows = []
    for num, (body, _, _) in enumerate(lines):
        stop = body.find("#")
        stop = len(body) if stop < 0 else stop
        words = [(m.start(), m.end()) for m in re.finditer(r"\S+", body[:stop])]
        if words:
            rows.append((num, words))
    return text, lines, rows


def read_snip(content, item):
    """
    Read a snip's pixels for a data line, or None when it is not a text table.

    Generated by RJC and Claude.
    """
    try:
        text, lines, rows = _data_rows(content)
    except UnicodeDecodeError:
        return None
    cols = _column_map(item)
    table = []
    for num, words in rows:
        body = lines[num][0]
        try:
            table.append([float(body[a:b]) for a, b in words])
        except ValueError:
            return None
    if not table:
        return None
    ncols = len(table[0])

    def column(name):
        idx = cols.get(name, -1)
        if idx < 0 or any(idx >= len(r) for r in table):
            return None
        return np.array([r[idx] for r in table])

    wave, flux, error = column("wave"), column("flux"), column("error")
    if wave is None or flux is None or error is None:
        return None
    return SnipData(wave, flux, error, column("fitrange"), [r[0] for r in rows], ncols)


def _mask_word(value, examples):
    """
    The text of a mask value, in the style of the file's other mask values.

    Generated by RJC and Claude.
    """
    for word in examples:
        try:
            if float(word) == value:
                return word
        except ValueError:
            continue
    sample = examples[0] if examples else "0"
    match = re.match(r"^[-+]?\d\.(\d+)[eE][-+]\d+$", sample)
    if match:
        return "{0:.{1}e}".format(value, len(match.group(1)))
    if "." in sample:
        return "{0:.1f}".format(value)
    return "{0:d}".format(int(value))


def set_mask(content, item, mask):
    """
    A snip's bytes with a new fit mask: only the mask column of the lines whose
    mask changes is rewritten, character for character (Q2.7).

    Parameters
    ----------
    content : bytes
    item : DataLine
        Its data line, which names the ``fitrange`` column.
    mask : array of bool
        One value per pixel.

    Returns
    -------
    bytes

    Generated by RJC and Claude.
    """
    text, lines, rows = _data_rows(content)
    idx = _column_map(item).get("fitrange", -1)
    if idx < 0:
        raise ProjectError("The data line names no fitrange column.")
    if len(rows) != len(mask):
        raise ProjectError("The mask does not fit the snip.")
    examples = [
        lines[num][0][a:b]
        for num, words in rows[:200]
        for k, (a, b) in enumerate(words)
        if k == idx
    ]
    patches = []
    for (num, words), keep in zip(rows, mask):
        body, _, offset = lines[num]
        a, b = words[idx]
        old = body[a:b]
        try:
            same = (float(old) != 0) == bool(keep)
        except ValueError:
            same = False
        if not same:
            new = _mask_word(1.0 if keep else 0.0, examples)
            patches.append(T.Patch(offset + a, old, new))
    return T.Change.from_spans(patches).apply(text).encode("utf-8")


def add_mask_column(content, mask):
    """
    A snip's bytes with a fit mask added as a new last column (Q2.10).

    The other columns keep their text, so the data do not change.

    Returns
    -------
    tuple
        ``(bytes, column)``: the new file, and the mask's column number.

    Generated by RJC and Claude.
    """
    text, lines, rows = _data_rows(content)
    if len(rows) != len(mask):
        raise ProjectError("The mask does not fit the snip.")
    first = lines[rows[0][0]][0]
    ncols = len(rows[0][1])
    sample = first[rows[0][1][0][0] : rows[0][1][0][1]]
    style = re.match(r"^[-+]?\d\.(\d+)[eE][-+]\d+$", sample)
    patches = []
    for (num, words), keep in zip(rows, mask):
        body, _, offset = lines[num]
        value = 1.0 if keep else 0.0
        word = (
            "{0:.{1}e}".format(value, len(style.group(1)))
            if style
            else "{0:d}".format(int(value))
        )
        end = words[-1][1]
        patches.append(T.Patch(offset + end, "", " " + word))
    return T.Change.from_spans(patches).apply(text).encode("utf-8"), ncols


def cut_snip(content, low, high):
    """
    A snip's bytes keeping only the pixels from ``low`` to ``high`` (Q2.7): the lines
    that are kept are not changed.

    Generated by RJC and Claude.
    """
    text, lines, rows = _data_rows(content)
    drop = set()
    for num, words in rows:
        body = lines[num][0]
        wave = float(body[words[0][0] : words[0][1]])
        if wave < low or wave > high:
            drop.add(num)
    out = [
        body + ending for num, (body, ending, _) in enumerate(lines) if num not in drop
    ]
    return "".join(out).encode("utf-8")


