class Project:
    """
    A dashboard project, held in memory.

    Parameters
    ----------
    bundle : alis.bundle.Bundle
        The bundle, as read or packed.
    registry : Registry, optional
        ALIS's functions and atomic data; by default made from the bundle's packed
        atomic table (Q1.10).

    Attributes
    ----------
    bundle : Bundle
        The bundle as it was opened (the project's state is held apart from it).
    text : str
        The model text, hidden lines restored.
    files : dict
        Every member of the files tree except the model, as bytes.
    ui : dict
        ``ui/project.json`` (empty when the bundle has none).
    extra_hidden : set of int
        Lines hidden besides those with ``blind=True`` (best-fit values copied in
        under global blind, S20).
    parsed : ParsedModel
    last_read : ParsedModel or None
        The last reading of the text that ALIS read.
    paused : bool
        The text does not read, so panel edits wait (QF.3).

    Generated by RJC and Claude.
    """

    def __init__(self, bundle, registry=None):
        self.bundle = bundle
        if registry is None:
            registry = M.Registry.load(*bundle.atomic_table())
        self.registry = registry
        self.model_member = bundle.model_member
        self.model_dir = bundle.model_dir
        stored = bundle.model_text()
        self.text = bundle.model_text(restore=True)
        blind = set(B.blind_line_numbers(self.text))
        placeholders = {
            ln.num for ln in T.ModelText(stored).lines if ln.kind == T.HIDDEN
        }
        self.extra_hidden = placeholders - blind
        self.files = {
            m: c
            for m, c in bundle.members.items()
            if m.startswith(B.TREE) and m != self.model_member
        }
        self.ui = {}
        if PROJECT_JSON in bundle.members:
            self.ui = json.loads(bundle.members[PROJECT_JSON].decode("utf-8"))
        self.parsed = None
        # The last reading of the text that ALIS read: the blinding gate takes the
        # hidden labels from it while the text does not read (Stage 3)
        self.last_read = None
        self.paused = False
        self.rows, self.snips, self.systems = [], [], []
        self.absorbers, self.others, self.notices = [], [], []
        self._snip_cache = {}
        self._rebuild()

    # -- opening and saving ---------------------------------------------------------

    @classmethod
    def open(cls, path, registry=None):
        """
        Open a project bundle (``project.model``).

        Generated by RJC and Claude.
        """
        return cls(B.read(path), registry)

    @classmethod
    def import_model(cls, modfile, registry=None, sources=()):
        """
        Open an existing fit, a plain ``.mod`` with its snips (F4, D12).

        The bundle is made by ``alis.bundle.pack`` (Stage 1), with the outputs of an
        earlier run as its latest run. The project then infers its rows, systems and
        components (Q2.4), and lists the notices of what breaks D20 or D22.

        Generated by RJC and Claude.
        """
        return cls(B.pack(modfile, sources=sources), registry)

    def hidden_lines(self):
        """
        Every line hidden in the bundle: those with ``blind=True`` (D24), and the
        others marked hidden (S20).

        Generated by RJC and Claude.
        """
        nlines = len(self.parsed.text)
        return sorted(
            set(B.blind_line_numbers(self.text))
            | {n for n in self.extra_hidden if n < nlines}
        )

    def model_bytes(self):
        """
        The model as it is stored in the bundle, with its hidden lines as
        placeholders, and the hidden lines.

        Returns
        -------
        tuple
            ``(bytes, store)``.

        Generated by RJC and Claude.
        """
        store = {}
        hidden = B.hide_lines(self.text, self.hidden_lines(), store)
        return hidden.encode("utf-8"), store

    def to_bundle(self):
        """
        The bundle as it should now be written: the model with its hidden lines
        hidden again, the files, and ``ui/project.json``.

        Generated by RJC and Claude.
        """
        out = copy.deepcopy(self.bundle)
        for member in [m for m in out.members if m.startswith(B.TREE)]:
            del out.members[member]
        data, store = self.model_bytes()
        out.members[self.model_member] = data
        if store:
            out.hidden["lines"][self.model_member] = store
        else:
            out.hidden["lines"].pop(self.model_member, None)
        out.members.update(self.files)
        if self.ui:
            out.members[PROJECT_JSON] = json.dumps(self.ui, indent=1).encode("utf-8")
        else:
            out.members.pop(PROJECT_JSON, None)
        return out

    def save(self, path):
        """
        Write the project to ``path``, atomically and under the bundle's lock.

        Members that ALIS and this project do not use (committed runs, the latest
        run, other ``ui/`` files) are kept as they are on disk (Q1.7).

        Generated by RJC and Claude.
        """
        new = self.to_bundle()

        def change(old):
            for member in [m for m in old.members if m.startswith(B.TREE)]:
                del old.members[member]
            old.members.update(
                {m: c for m, c in new.members.items() if m.startswith(B.TREE)}
            )
            old.hidden["lines"][self.model_member] = new.hidden["lines"].get(
                self.model_member, {}
            )
            if PROJECT_JSON in new.members:
                old.members[PROJECT_JSON] = new.members[PROJECT_JSON]
            else:
                old.members.pop(PROJECT_JSON, None)

        if os.path.exists(path):
            B.update(path, change)
        else:
            B.write(new, path)

    def data_for_run(self):
        """
        Every file of the tree, by its path from the model, as ``load_data`` looks it
        up (``alis.bundle.Bundle.data_for_run``).

        Generated by RJC and Claude.
        """
        data = {}
        for member, content in self.files.items():
            rel = posixpath.relpath(member[len(B.TREE) :], self.model_dir or ".")
            data[os.path.normpath(rel)] = content
        return data

    def model_changed_since_run(self):
        """
        Whether the model has changed since its latest run (F12, Q2.9).

        Returns
        -------
        bool or None
            None when there is no latest run.

        Generated by RJC and Claude.
        """
        info = self.bundle.members.get(B.LATEST + "run.json")
        if info is None:
            return None
        ran = json.loads(info.decode("utf-8")).get("model_sha256")
        return B.sha256(self.model_bytes()[0]) != ran

    # -- changing it ----------------------------------------------------------------

    def step(self, change, description=""):
        """
        A step that makes a change to the text, following the hidden lines.

        Generated by RJC and Claude.
        """
        old = set(self.extra_hidden)
        new = set()
        for num in old:
            if num < len(self.parsed.text):
                moved = change.map_line(self.parsed.text, num)
                if moved is not None:
                    new.add(moved)
        return Step(
            description or change.description,
            change,
            {},
            None,
            (old, new) if old != new else None,
        )

    def apply(self, step):
        """
        Make a step: change the text, the files, ``ui/project.json`` and the hidden
        lines, then build the concepts again.

        Generated by RJC and Claude.
        """
        if step.text is not None:
            self.text = step.text.apply(self.text)
        for member, (_, new) in step.files.items():
            if new is None:
                self.files.pop(member, None)
            else:
                self.files[member] = new
        if step.ui is not None:
            self.ui = copy.deepcopy(step.ui[1])
        if step.hidden is not None:
            self.extra_hidden = set(step.hidden[1])
        self._rebuild()

    def revert(self, step):
        """Undo a step."""
        self.apply(step.inverse())

    def edit(self, change, description=""):
        """
        Make a change to the text as one step, and return the step.

        Generated by RJC and Claude.
        """
        step = self.step(change, description)
        self.apply(step)
        return step

    def mark_hidden(self, line):
        """
        A step that hides one more line in the bundle (best-fit values copied in
        under global blind, S20).

        Generated by RJC and Claude.
        """
        old = set(self.extra_hidden)
        return Step("Hide a line", None, {}, None, (old, old | {line}))

    def require_reading(self):
        """
        Stop a panel edit while the text does not read (QF.3).

        Raises
        ------
        ProjectError

        Generated by RJC and Claude.
        """
        if self.paused:
            raise ProjectError(
                "The model does not read. Correct it in the .mod panel"
                " first; the panels will follow."
            )

    # -- building the concepts ------------------------------------------------------

    def _rebuild(self):
        """
        Read the text again and build the concepts, unless it does not read.

        Generated by RJC and Claude.
        """
        parsed = M.ParsedModel(self.text, self.registry)
        if parsed.ok:
            self.last_read = parsed
        if not parsed.ok and self.parsed is not None:
            self.parsed = parsed
            self.paused = True
            return
        self.parsed = parsed
        self.paused = not parsed.ok
        if self.paused:
            return
        self._build_snips()
        self._build_rows()
        self._build_systems()
        self._build_notices()

    def member_of(self, item):
        """
        The bundle member of a data line's file, as ``load_data`` resolves it.

        Generated by RJC and Claude.
        """
        rel = item.path(self.parsed.datadirc).replace("\\", "/")
        return B.TREE + posixpath.normpath(posixpath.join(self.model_dir or ".", rel))

    def _build_snips(self):
        """One snip per data line, with its pixels and its continuum."""
        pm = self.parsed
        continua = pm.function_lines(section="emission")
        single = len(pm.specids) == 1
        self.snips = []
        for item in pm.data:
            member = self.member_of(item)
            content = self.files.get(member)
            pixels = None
            if content is not None:
                key = (
                    member,
                    hashlib.sha1(content).hexdigest(),
                    item.keyword("columns"),
                )
                if key not in self._snip_cache:
                    self._snip_cache[key] = read_snip(content, item)
                pixels = self._snip_cache[key]
            cont = None
            for line in continua:
                if line.function in CONTINUUM_FUNCTIONS and (
                    item.specid in line.specids or (single and not line.specids)
                ):
                    cont = line
                    break
            self.snips.append(Snip(item.specid, item, member, None, cont, pixels))

    def snip(self, specid):
        """The snip of a specid (the first, if there are several)."""
        for snip in self.snips:
            if snip.specid == specid:
                return snip
        raise ProjectError("There is no snip with specid " + specid)

    # -- rows (D35) -----------------------------------------------------------------

    @staticmethod
    def _stem(item):
        """The part of a snip's file name before its transition (Q2.4)."""
        base = posixpath.basename(item.file.text)
        match = _TRANSITION.search(base)
        return base[: match.start()] if match else posixpath.splitext(base)[0]

    def _build_rows(self):
        """
        The rows: from ``ui/project.json``, or inferred (Q2.4).

        Data lines that share a resolution label form one row; the others are
        grouped by the stem of their file names.

        Generated by RJC and Claude.
        """
        by_specid = {s.specid: s for s in self.snips}
        placed = set()
        self.rows = []
        for num, entry in enumerate(self.ui.get("rows", [])):
            snips = [by_specid[s] for s in entry.get("specids", []) if s in by_specid]
            # A file row of a new project has no snips until its first is cut
            if not snips and not entry.get("source"):
                continue
            row = Row(
                entry.get("id", "r{0}".format(num + 1)),
                entry.get("name", "Row {0}".format(num + 1)),
                snips,
                bool(entry.get("reference")),
                None,
                entry.get("columns"),
            )
            if entry.get("source"):
                try:
                    row.source = self.bundle.source(entry["source"])
                except B.BundleError:
                    row.source = None
            self.rows.append(row)
            placed |= {s.specid for s in snips}
        groups = {}
        for snip in self.snips:
            if snip.specid in placed:
                continue
            par = snip.data.param("resolution")
            if par is not None and par.label:
                key = ("label", par.label)
            else:
                key = ("stem", self._stem(snip.data))
            groups.setdefault(key, []).append(snip)
        for key, snips in groups.items():
            names = {s.data.keyword("label") for s in snips}
            stems = {self._stem(s.data) for s in snips}
            if len(names) == 1 and None not in names:
                name = names.pop()
            elif len(stems) == 1:
                name = stems.pop()
            else:
                name = "Dataset {0}".format(len(self.rows) + 1)
            self.rows.append(Row("r{0}".format(len(self.rows) + 1), name, snips))
        if self.rows and not any(r.reference for r in self.rows):
            self._infer_reference()
        for row in self.rows:
            for snip in row.snips:
                snip.row = row
            row.zero = (
                E.zero_level_line(self.parsed, row.specids) if row.specids else None
            )

    def _infer_reference(self):
        """The reference row: the first whose shift is absent or fixed at 0 (D14)."""
        for row in self.rows:
            shift = row.shift
            if shift is None or (shift.fixed and shift.start == 0.0):
                row.reference = True
                return
        self.rows[0].reference = True

    def row(self, ident):
        """The row with an id or a name."""
        for row in self.rows:
            if ident in (row.id, row.name):
                return row
        raise ProjectError("There is no row " + str(ident))

    # -- systems and components (D15, D20) ------------------------------------------

    def _voigt_lines(self):
        """The absorption voigt lines: physical, generic, and ratios."""
        physical, generic, ratios = [], [], []
        for line in self.parsed.function_lines("voigt"):
            if line.section != "absorption":
                continue
            if line.ratio:
                ratios.append(line)
            elif line.ion in GENERIC_IONS:
                generic.append(line)
            else:
                physical.append(line)
        return physical, generic, ratios

    def _build_systems(self):
        """
        The systems and their components: from ``ui/project.json``, or inferred.

        Generated by RJC and Claude.
        """
        physical, generic, ratios = self._voigt_lines()
        self.absorbers = generic
        comps = self._components(physical)
        systems = []
        for entry in self.ui.get("systems", []):
            systems.append(
                System(
                    entry["id"],
                    entry.get("name", entry["id"]),
                    float(entry["z"]),
                    bool(entry.get("primary")),
                    [],
                    list(entry.get("lines", [])),
                    False,
                )
            )
        rest = []
        for comp in comps:
            near = [s for s in systems if abs(velocity(comp.z, s.z)) <= SYSTEM_DV]
            if near:
                best = min(near, key=lambda s: abs(velocity(comp.z, s.z)))
                best.components.append(comp)
            else:
                rest.append(comp)
        systems += self._infer_systems(rest, systems)
        if systems and not any(s.primary for s in systems):
            max(systems, key=lambda s: (len(s.ions), len(s.components))).primary = True
        systems.sort(key=lambda s: (not s.primary, s.z))
        for system in systems:
            system.components.sort(key=lambda c: c.z)
            for num, comp in enumerate(system.components, 1):
                comp.system = system
                comp.id = "{0}{1}".format(system.id, num)
                comp.velocity = velocity(comp.z, system.z)
        self._attach_ratios(ratios, comps)
        self.systems = systems
        used = {id(ln) for c in comps for ln in c.lines + c.ratios}
        used |= {id(ln) for ln in generic}
        self.others = [ln for ln in self.parsed.lines if id(ln) not in used]

    def _infer_systems(self, comps, existing):
        """
        Systems for components that no system holds: redshifts within 500 km/s of
        each other form one (Q2.4).

        Generated by RJC and Claude.
        """
        letters = [s.id for s in existing]
        groups = []
        for comp in sorted(comps, key=lambda c: c.z):
            if groups and abs(velocity(comp.z, groups[-1][-1].z)) <= SYSTEM_DV:
                groups[-1].append(comp)
            else:
                groups.append([comp])
        out = []
        ranked = sorted(
            groups,
            key=lambda g: (
                -len({i for c in g for i in c.ions}),
                -sum(len(c.lines) for c in g),
            ),
        )
        for group in ranked:
            letter = next(
                chr(c) for c in range(ord("a"), ord("z") + 1) if chr(c) not in letters
            )
            letters.append(letter)
            # The system's redshift comes from a component whose redshift is not
            # hidden: otherwise every other component's velocity would reveal it
            top = max(
                group, key=lambda c: (not self._z_hidden(c), len(c.ions), len(c.lines))
            )
            out.append(
                System(
                    letter,
                    "z = {0:.5f}".format(top.z),
                    top.z,
                    False,
                    list(group),
                    [],
                    True,
                )
            )
        return out

    def _z_hidden(self, comp):
        """
        Whether a component's redshift is set on a hidden line (D24).

        Generated by RJC and Claude.
        """
        zpar = comp.main.param("redshift")
        if zpar is None:
            return False
        if zpar.label and zpar.label in self.parsed.labels:
            zpar = self.parsed.labels[zpar.label].params[0]
        return zpar.line in self.hidden_lines()

    def _components(self, lines):
        """
        The components: lines that share a redshift label, then untied lines within
        0.1 km/s of a component or of each other (Q2.4).

        Generated by RJC and Claude.
        """
        comps, loose = [], []
        by_label = {}
        for line in lines:
            zpar = line.param("redshift")
            if zpar is None:
                continue
            if zpar.label:
                if zpar.label not in by_label:
                    by_label[zpar.label] = Component("", None, zpar.start, zpar.label)
                    comps.append(by_label[zpar.label])
                by_label[zpar.label].lines.append(line)
            else:
                loose.append(line)
        for line in loose:
            z = line.param("redshift").start
            near = [c for c in comps if abs(velocity(z, c.z)) <= COMPONENT_DV]
            if near:
                min(near, key=lambda c: abs(velocity(z, c.z))).lines.append(line)
            else:
                comps.append(Component("", None, z, "", [line]))
        for comp in comps:
            comp.lines.sort(key=lambda ln: ln.line)
        return comps

    @staticmethod
    def _attach_ratios(ratios, comps):
        """A ratio line joins every component of its denominator ion it shares a
        snip with (``2H_I/1H_I`` joins the components of ``1H_I``)."""
        for line in ratios:
            denom = line.ion.split("/")[1]
            sids = set(line.specids)
            for comp in comps:
                if any(
                    ln.ion == denom and (not sids or sids & set(ln.specids))
                    for ln in comp.lines
                ):
                    comp.ratios.append(line)

    @property
    def components(self):
        """Every component of every system."""
        return [c for s in self.systems for c in s.components]

    def system(self, ident):
        """The system with an id or a name."""
        for system in self.systems:
            if ident in (system.id, system.name):
                return system
        raise ProjectError("There is no system " + str(ident))

    def component(self, ident):
        """The component with an id, such as ``a1``."""
        for comp in self.components:
            if comp.id == ident:
                return comp
        raise ProjectError("There is no component " + str(ident))

    # -- notices (Q0.3, Q2.4) -------------------------------------------------------

    @property
    def inferred(self):
        """
        Whether the rows or systems were inferred rather than read (Q2.4): the
        project data do not list them (a new project lists them, perhaps empty).
        """
        return "systems" not in self.ui or "rows" not in self.ui

    def _build_notices(self):
        """
        The notices of an imported model, each with its fix.

        Generated by RJC and Claude.
        """
        self.notices = []
        if self.inferred:
            self.notices.append(
                Notice(
                    "inferred",
                    "The systems, components and datasets of this model were"
                    " worked out from its labels and redshifts. Please check that they"
                    " were read correctly before changing anything.",
                )
            )
        for comp in self.components:
            self._untied_notices(comp)
            self._isotope_notices(comp)

    def _untied_notices(self, comp):
        """
        A component whose lines do not share one redshift label (D20).

        Generated by RJC and Claude.
        """
        loose = [
            ln
            for ln in comp.lines
            if ln.param("redshift").label != comp.label or not comp.label
        ]
        if len(comp.lines) < 2 or not loose:
            return
        ions = []
        for ln in loose:
            name = ion_name(ln.ion)
            if name not in ions:
                ions.append(name)
        message = (
            "In component {0}, the redshift of {1} is not tied to the"
            " component's. Tie it so that every ion shares one redshift.".format(
                comp.id, ", ".join(ions)
            )
        )
        letter = comp.system.id

        def fix(pm, comp=comp, letter=letter):
            return tie_component(pm, comp, "redshift", letter)

        self.notices.append(
            Notice("untied", message, [ln.line for ln in loose], comp, fix)
        )

    def _isotope_notices(self, comp):
        """
        Isotopes of one element that do not share z, b_turb and T (D22).

        Generated by RJC and Claude.
        """
        for (elem, stage), ions in comp.isotopes.items():
            main = _main_isotope(ions)
            minor = [i for i in ions if i != main and comp.lines_of(i)]
            if not comp.lines_of(main):
                continue
            ref = comp.lines_of(main)[0]
            for ion in minor:
                bad = []
                for name in ("redshift", "bturb", "temperature"):
                    for line in comp.lines_of(ion):
                        if not _shared(ref.param(name), line.param(name)):
                            bad.append(name)
                            break
                if not bad:
                    continue
                what = ", ".join(
                    {"redshift": "z", "bturb": "b_turb", "temperature": "T"}[b]
                    for b in bad
                )
                message = (
                    "In component {0}, {1} does not share {2} with {3}."
                    " Isotopes must share z, b_turb and T.".format(
                        comp.id, ion_name(ion), what, ion_name(main)
                    )
                )

                def fix(pm, comp=comp, ion=ion, main=main, bad=tuple(bad)):
                    return tie_isotope(pm, comp, ion, main, bad)

                lines = [ln.line for ln in comp.lines_of(ion)]
                self.notices.append(Notice("isotopes", message, lines, comp, fix))

    def fix_notice(self, notice):
        """
        The step that applies a notice's one-click fix.

        Generated by RJC and Claude.
        """
        self.require_reading()
        if notice.fix is None:
            raise ProjectError("This notice has nothing to fix.")
        return self.step(notice.fix(self.parsed), "Fix: " + notice.kind)

    # -- regions (Q2.7, Q2.10) ------------------------------------------------------

    def set_regions(self, snip, regions):
        """
        The step that sets a snip's fit regions.

        A mask column changes character for character (Q2.7). A data line with
        ``fitrange=[lo,hi]`` (or ``all``) keeps that form for one region, and for
        more is switched to ``fitrange=columns`` with a mask column added to its file
        (Q2.10). A file read by other data lines too is copied first, so that they
        are not changed.

        Parameters
        ----------
        snip : Snip
        regions : list of (low, high)

        Returns
        -------
        Step

        Generated by RJC and Claude.
        """
        self.require_reading()
        pm = self.parsed
        item = snip.data
        form = item.fitrange
        regions = sorted((float(a), float(b)) for a, b in regions)
        if form is not None and form[0] in ("range", "all") and len(regions) == 1:
            low, high = regions[0]
            value = "[{0},{1}]".format(E.format_value(low), E.format_value(high))
            change = E.set_keyword(pm, item, "fitrange", value)
            return self.step(change, "Set the fit region of " + snip.specid)
        if snip.pixels is None:
            raise ProjectError(
                "The snip's file cannot be read, so its regions cannot" " be set."
            )
        if not regions and (form is None or form[0] != "columns"):
            raise ProjectError("A data line needs at least one fit region.")
        wave = snip.pixels.wave
        mask = np.zeros(wave.size, dtype=bool)
        for low, high in regions:
            mask |= (wave >= low) & (wave <= high)
        content = self.files[snip.member]
        if form is not None and form[0] == "columns" and snip.pixels.mask is not None:
            new = set_mask(content, item, mask)
            return Step(
                "Set the fit regions of " + snip.specid,
                files={snip.member: (content, new)},
            )
        return self._convert_to_mask(snip, mask)

    def _convert_to_mask(self, snip, mask):
        """
        Switch a data line to ``fitrange=columns``, with a mask column (Q2.10).

        Generated by RJC and Claude.
        """
        pm = self.parsed
        item = snip.data
        content = self.files[snip.member]
        new, col = add_mask_column(content, mask)
        member = snip.member
        change = T.Change((), "")
        shared = [d for d in pm.data if d is not item and self.member_of(d) == member]
        if shared:
            # A copy beside the file, for this data line alone
            stem, ext = posixpath.splitext(member)
            num, member = 1, "{0}_{1}{2}".format(stem, item.specid, ext)
            while member in self.files:
                num += 1
                member = "{0}_{1}{2}{3}".format(stem, item.specid, num, ext)
            rel = posixpath.join(
                posixpath.dirname(item.file.text), posixpath.basename(member)
            )
            word = T.replace_token(pm.text, item.file, rel)
            change = T.Change((word,), "")
        files = {member: (self.files.get(member), new)}
        pm2 = E.reread(pm, change) if change else pm
        item2 = pm2.data[item.index]
        change = change.then(E.set_keyword(pm2, item2, "fitrange", "columns"))
        pm3 = E.reread(pm, change)
        item3 = pm3.data[item.index]
        cols = item3.keyword("columns")
        if cols is None:
            value = "[wave:0,flux:1,error:2,fitrange:{0}]".format(col)
        else:
            inner = cols.strip("[]()")
            value = "[{0},fitrange:{1}]".format(inner, col)
        change = change.then(E.set_keyword(pm3, item3, "columns", value))
        step = self.step(change, "Set the fit regions of " + snip.specid)
        step.files = files
        return step

    def set_snip_edges(self, snip, low, high):
        """
        The step that moves a snip's edges inwards, keeping the lines of the pixels
        that stay unchanged (RJC, Q2.7).

        Moving an edge outwards needs the source spectrum (Stage 4).

        Generated by RJC and Claude.
        """
        self.require_reading()
        extent = snip.extent
        if extent is None:
            raise ProjectError("The snip's file cannot be read.")
        if low < extent[0] or high > extent[1]:
            raise ProjectError(
                "Moving a snip's edge outwards needs its source" " spectrum."
            )
        shared = [
            d
            for d in self.parsed.data
            if d is not snip.data and self.member_of(d) == snip.member
        ]
        if shared:
            raise ProjectError(
                "Other data lines read this file too, so its edges" " cannot be moved."
            )
        content = self.files[snip.member]
        return Step(
            "Move the edges of " + snip.specid,
            files={snip.member: (content, cut_snip(content, low, high))},
        )

    # -- ui/project.json (Q2.2) -----------------------------------------------------

    def structure(self):
        """
        What ``ui/project.json`` would hold for the systems and rows as they are now.

        Generated by RJC and Claude.
        """
        data = copy.deepcopy(self.ui)
        data["format"] = PROJECT_FORMAT
        data.setdefault("mode", "qso_abs_line")
        data["systems"] = [
            {
                "id": s.id,
                "name": s.name,
                "z": s.z,
                "primary": s.primary,
                "lines": s.lines or [{"ion": i} for i in s.ions],
            }
            for s in self.systems
        ]
        data["rows"] = [
            {
                "id": r.id,
                "name": r.name,
                "specids": r.specids,
                "reference": r.reference,
                "source": r.source["id"] if r.source else None,
                "columns": r.columns,
            }
            for r in self.rows
        ]
        return data

    def set_ui(self, data, description="Change the project"):
        """
        A step that replaces ``ui/project.json``.

        Generated by RJC and Claude.
        """
        return Step(description, ui=(copy.deepcopy(self.ui), copy.deepcopy(data)))

    def confirm_structure(self):
        """
        The step that keeps what was inferred, once the user has checked it (Q2.4).

        Generated by RJC and Claude.
        """
        return self.set_ui(self.structure(), "Confirm the systems and datasets")

    # -- the map between items and lines (S16, Q2.9) --------------------------------

    def lines_of(self, item):
        """
        The ``.mod`` lines an item is written on (cross-highlighting, S16).

        Parameters
        ----------
        item : Snip, Row, Component, System, Notice, or a parsed-model item

        Returns
        -------
        list of int

        Generated by RJC and Claude.
        """
        if isinstance(item, Snip):
            out = [item.line]
            if item.continuum is not None:
                out.append(item.continuum.line)
            return sorted(set(out))
        if isinstance(item, Row):
            out = [s.line for s in item.snips]
            if item.zero is not None:
                out.append(item.zero.line)
            return sorted(set(out))
        if isinstance(item, Component):
            return sorted({ln.line for ln in item.lines + item.ratios})
        if isinstance(item, System):
            return sorted({n for c in item.components for n in self.lines_of(c)})
        if isinstance(item, Notice):
            return list(item.lines)
        if hasattr(item, "line"):
            return [item.line]
        return []

    def items_at(self, line):
        """
        What a line of the ``.mod`` describes (S16): the snips, rows, components and
        systems written on it.

        Generated by RJC and Claude.
        """
        found = []
        for group in (self.snips, self.rows, self.components, self.systems):
            for item in group:
                if line in self.lines_of(item):
                    found.append(item)
        item = self.parsed.item_at(line)
        if item is not None and not found:
            found.append(item)
        return found


def _main_isotope(ions):
    """The main isotope among ions of one element (D22)."""
    for ion in ions:
        mass, elem, _ = split_ion(ion)
        if MAIN_ISOTOPE.get(elem) == mass:
            return ion
    return ions[0]


def _shared(one, two):
    """Whether two places of a parameter are the same ALIS parameter."""
    if one is None or two is None:
        return True
    return one.index == two.index


