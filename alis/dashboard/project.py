def split_ion(ion):
    """
    Split an ion into its mass number, element and stage: ``2H_I`` gives
    ``(2, "H", "I")``. An ion that does not have that form gives ``(None, ion, "")``.

    Generated by RJC and Claude.
    """
    match = _ION.match(ion or "")
    if match is None:
        return None, ion, ""
    return int(match.group(1)), match.group(2), match.group(3)


def ion_name(ion):
    """An ion as people write it: ``16O_I`` is ``O I``, ``2H_I`` is ``D I``."""
    mass, elem, stage = split_ion(ion)
    if elem == "H" and mass == 2:
        return "D " + stage
    if mass is not None and elem in MAIN_ISOTOPE and mass != MAIN_ISOTOPE[elem]:
        return "{0}{1} {2}".format(mass, elem, stage)
    return "{0} {1}".format(elem, stage) if stage else ion


def velocity(z, zref):
    """The velocity of redshift ``z`` relative to ``zref``, in km/s."""
    return C_KMS * (z - zref) / (1.0 + zref)


# -- Steps: what changes, so that it can be undone (F2) ----------------------------


@dataclass
class Step:
    """
    One change to a project, which can be undone exactly.

    Attributes
    ----------
    description : str
    text : Change or None
        The change to the model text.
    files : dict
        Bundle member to ``(old, new)`` bytes; None for a member that does not
        exist.
    ui : tuple or None
        ``(old, new)`` of ``ui/project.json``, as dicts.
    hidden : tuple or None
        ``(old, new)`` of the lines hidden besides those with ``blind=True``.

    Generated by RJC and Claude.
    """

    description: str = ""
    text: T.Change | None = None
    files: dict = field(default_factory=dict)
    ui: tuple | None = None
    hidden: tuple | None = None

    def __bool__(self):
        return (
            bool(self.text)
            or bool(self.files)
            or self.ui is not None
            or (self.hidden is not None and self.hidden[0] != self.hidden[1])
        )

    def inverse(self):
        """The step that undoes this one."""
        return Step(
            self.description,
            None if self.text is None else self.text.inverse(),
            {k: (new, old) for k, (old, new) in self.files.items()},
            None if self.ui is None else (self.ui[1], self.ui[0]),
            None if self.hidden is None else (self.hidden[1], self.hidden[0]),
        )

    def then(self, other):
        """
        This step followed by ``other``, as one step (typing and drags, F2).

        Generated by RJC and Claude.
        """
        if self.text is None:
            text = other.text
        elif other.text is None:
            text = self.text
        else:
            text = self.text.then(other.text)
        files = dict(self.files)
        for key, (old, new) in other.files.items():
            files[key] = (files[key][0] if key in files else old, new)
        ui = (
            self.ui
            if other.ui is None
            else (other.ui if self.ui is None else (self.ui[0], other.ui[1]))
        )
        hidden = (
            self.hidden
            if other.hidden is None
            else (
                other.hidden
                if self.hidden is None
                else (self.hidden[0], other.hidden[1])
            )
        )
        return Step(self.description or other.description, text, files, ui, hidden)


