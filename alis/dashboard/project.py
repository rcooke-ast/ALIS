@dataclass
class Snip:
    """
    One data line and its file.

    Attributes
    ----------
    specid : str
    data : DataLine
    member : str
        The file's member in the bundle (``files/...``).
    row : Row or None
    continuum : ModelLine or None
    pixels : SnipData or None
        None when the file is not in the bundle or is not a text table.

    Generated by RJC and Claude.
    """

    specid: str
    data: object = field(repr=False)
    member: str
    row: object = field(default=None, repr=False)
    continuum: object = field(default=None, repr=False)
    pixels: SnipData | None = field(default=None, repr=False)

    @property
    def line(self):
        """The data line's line in the text."""
        return self.data.line

    @property
    def extent(self):
        """The snip's wavelength range, ``(low, high)``, or None."""
        if self.pixels is None or not self.pixels.wave.size:
            return None
        return float(self.pixels.wave.min()), float(self.pixels.wave.max())

    @property
    def regions(self):
        """
        The fitted wavelength ranges, as ``[(low, high), ...]`` (Q2.7, Q2.10).

        From the mask column for ``fitrange=columns``, from the token for
        ``fitrange=[low,high]``, and the whole snip for ``fitrange=all``.
        """
        form = self.data.fitrange
        if form is None:
            return []
        if form[0] == "range":
            return [(form[1], form[2])]
        if form[0] == "all":
            return [self.extent] if self.extent else []
        if self.pixels is None or self.pixels.mask is None:
            return []
        return mask_regions(self.pixels.wave, self.pixels.mask != 0)


def mask_regions(wave, mask):
    """
    The runs of a mask, as wavelength ranges from their first to their last pixel.

    Generated by RJC and Claude.
    """
    out = []
    edges = np.flatnonzero(np.diff(np.concatenate(([0], mask.astype(np.int8), [0]))))
    for start, stop in zip(edges[::2], edges[1::2]):
        out.append((float(wave[start]), float(wave[stop - 1])))
    return out


