"""The project: the dashboard's concepts, built from the model text and the bundle.

Dashboard Stage 2.5. A :class:`Project` holds one bundle (``alis/bundle.py``, Stage 1)
in memory: the model text with its hidden lines restored, the snips and the other
files of the bundle, and ``ui/project.json``, the project data that the ``.mod``
cannot hold (Q2.2). From these it builds what the panels show:

- **rows** (D35): one per file, or per dataset of an imported model, with its FWHM,
  shift, zero level and reference flag;
- **snips**: one per data line, with its regions (Q2.7, Q2.10) and its continuum;
- **systems** (D15), their **components** (D20), each component's ions and isotopes
  (D22) and temperature mode (D21);
- **generic absorbers** (``1Ly_a``, ``1H_IB``) and the model's other lines;
- **notices** for an imported model: components whose lines are not tied (D20),
  isotopes that do not share z, b and T (D22), each with a one-click fix, and a
  general notice to check what was inferred (Q0.3, Q2.4).

The text is authoritative (D7). Every change to the project is a :class:`Step`,
which changes the text, a file, ``ui/project.json`` or the set of hidden lines, and can
be undone exactly (F2). After each step the concepts are built again. While the text
does not read, the concepts stay as they were and panel edits pause (QF.3).

Generated by RJC and Claude.
"""

