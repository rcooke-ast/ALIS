def _scheme_label(pm, letter, name):
    """A new label of the scheme for one parameter of a component (Q2.3)."""
    return E.new_component(pm, letter)[name]


def tie_component(pm, comp, name, letter):
    """
    Tie one parameter of every line of a component to one label (D20's fix).

    The label is the component's own when it has one, and a new one of the scheme
    otherwise; every line takes the first line's value.

    Returns
    -------
    Change

    Generated by RJC and Claude.
    """
    lines = [pm.item_at(ln.line) for ln in comp.lines]
    pars = [ln.param(name) for ln in lines]
    ref = pars[0]
    label = comp.label if name == "redshift" and comp.label else ref.label
    if not label:
        label = E._fixed_case(_scheme_label(pm, letter, name), ref.fixed)
    value = (
        ref.value_token.text
        if ref.value_token is not None
        else (E.format_value(ref.value))
    )
    patches = []
    for par in pars:
        if par.label == label or par.token is None:
            continue
        word = (par.name + "=" if par.named else "") + value + label
        patches.append(T.replace_token(pm.text, par.token, word))
    return T.Change.from_spans(patches, "Tie the {0} of {1}".format(name, comp.id))


def tie_isotope(pm, comp, ion, main, names):
    """
    Tie an isotope's z, b_turb and T to those of the main isotope (D22's fix).

    Parameters of the main isotope that have no label get one from the scheme.

    Returns
    -------
    Change

    Generated by RJC and Claude.
    """
    ref = pm.item_at(comp.lines_of(main)[0].line)
    letter = comp.system.id
    patches = []
    for name in names:
        par = ref.param(name)
        label = par.label
        if not label:
            label = E._fixed_case(_scheme_label(pm, letter, name), par.fixed)
            patches.append(
                T.replace_token(
                    pm.text,
                    par.token,
                    (par.name + "=" if par.named else "")
                    + par.value_token.text
                    + label,
                )
            )
        value = par.value_token.text
        for line in comp.lines_of(ion):
            other = pm.item_at(line.line).param(name)
            if other.token is None or other.label == label:
                continue
            word = (other.name + "=" if other.named else "") + value + label
            patches.append(T.replace_token(pm.text, other.token, word))
    return T.Change.from_spans(patches, "Tie {0} to {1}".format(ion, main))


