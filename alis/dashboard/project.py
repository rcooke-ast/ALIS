@dataclass
class Component:
    """
    A velocity component (D20): voigt lines of one system that share one redshift.

    Attributes
    ----------
    id : str
        The system's letter and the component's number, e.g. ``a1``.
    system : System
    z : float
    label : str
        The redshift label the lines share, or ``""``.
    lines : list of ModelLine
        Its voigt lines.
    ratios : list of ModelLine
        Lines that give an ion as a ratio to one of its ions (``2H_I/1H_I``).
    velocity : float
        Relative to the system's redshift, in km/s.

    Generated by RJC and Claude.
    """

    id: str
    system: object = field(repr=False)
    z: float
    label: str = ""
    lines: list = field(default_factory=list, repr=False)
    ratios: list = field(default_factory=list, repr=False)
    velocity: float = 0.0

    @property
    def ions(self):
        """Its ions, in the order they first appear."""
        found = []
        for line in self.lines:
            if line.ion not in found:
                found.append(line.ion)
        for line in self.ratios:
            ion = line.ion.split("/")[0]
            if ion not in found:
                found.append(ion)
        return found

    def lines_of(self, ion):
        """The lines of one ion."""
        return [ln for ln in self.lines if ln.ion == ion]

    @property
    def isotopes(self):
        """
        Its isotopes: ``{(element, stage): [ions]}`` where there is more than one.
        """
        groups = {}
        for ion in self.ions:
            _, elem, stage = split_ion(ion)
            groups.setdefault((elem, stage), []).append(ion)
        return {k: v for k, v in groups.items() if len(v) > 1}

    @property
    def main(self):
        """The line that defines the component: the first of its first ion."""
        return self.lines[0]

    @property
    def temperature_mode(self):
        """
        The temperature mode (D21), as ``(mode, value)``.

        ``("preset", T)`` for T fixed at 0, 100 or 10⁴ K; ``("fixed", T)`` for T fixed
        at another value; ``("thermal", None)`` for b_turb fixed at 0 with T free;
        ``("free", None)`` for T free; ``("linked", None)`` for T from a link.
        """
        temp = self.main.param("temperature")
        bturb = self.main.param("bturb")
        if temp is None:
            return ("free", None)
        if temp.linked:
            return ("linked", None)
        if temp.fixed:
            for preset in PRESETS:
                if abs(temp.start - preset) <= 1.0e-6 * max(1.0, preset):
                    return ("preset", preset)
            return ("fixed", temp.start)
        if bturb is not None and bturb.fixed and bturb.start == 0.0:
            return ("thermal", None)
        return ("free", None)


