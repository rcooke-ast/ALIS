class Process:
    """
    The fitting process, watched without blocking: messages are read on a thread
    and taken with :meth:`messages`.

    Parameters
    ----------
    data : bytes
        The project, as Save would write it.
    header : dict
        What the process is told besides (``path``, ``settings``, ``command``).
    python : str, optional
        The Python to run it with; by default this one.
    cwd : str, optional
        Where it runs.

    Generated by RJC and Claude.
    """

    def __init__(self, data, header, python=None, cwd=None):
        self.data = data
        self.header = dict(header, size=len(data), protocol=PROTOCOL)
        self.python = python or sys.executable
        self.cwd = cwd
        self.popen = None
        self.storing = False
        self.cancelled = False
        self._queue = queue.Queue()
        self._reader = None

    def start(self):
        """Start the process, and hand it the project."""
        env = dict(os.environ, MPLBACKEND="Agg", PYTHONUNBUFFERED="1")
        self.popen = subprocess.Popen(
            [self.python, "-m", RUNNER],
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            cwd=self.cwd,
            env=env,
            start_new_session=True,
        )
        self._reader = threading.Thread(target=self._read, daemon=True)
        self._reader.start()
        threading.Thread(target=self._hand_over, daemon=True).start()

    def _hand_over(self):
        try:
            line = json.dumps(self.header).encode("utf-8") + b"\n"
            self.popen.stdin.write(line + self.data)
            self.popen.stdin.flush()
        except (OSError, ValueError):
            pass

    def _read(self):
        try:
            for line in self.popen.stdout:
                try:
                    message = json.loads(line.decode("utf-8"))
                except ValueError:
                    continue
                if message.get("event") == "storing":
                    self.storing = True
                self._queue.put(message)
        except (OSError, ValueError):
            pass
        self._queue.put(None)

    def messages(self):
        """The messages that have arrived since the last call; None marks the end."""
        out = []
        while True:
            try:
                out.append(self._queue.get_nowait())
            except queue.Empty:
                return out

    @property
    def running(self):
        return self.popen is not None and self.popen.poll() is None

    @property
    def returncode(self):
        return None if self.popen is None else self.popen.poll()

    def stop(self):
        """Ask the fit to stop at its current iteration (Stop)."""
        try:
            self.popen.stdin.write(b"stop\n")
            self.popen.stdin.flush()
        except (OSError, ValueError, AttributeError):
            pass

    def cancel(self):
        """
        End the process at once (Cancel), unless it is storing its result.

        Returns
        -------
        bool
            Whether it was ended.

        Generated by RJC and Claude.
        """
        if not self.running or self.storing:
            return False
        # The process leads its own session, so its group holds ALIS's workers too
        try:
            os.killpg(self.popen.pid, signal.SIGKILL)
        except (OSError, AttributeError):
            self.popen.kill()
        self.cancelled = True
        return True

    def detach(self):
        """
        Let the process go on alone (the dashboard is closing, Keep it running): it
        stores its result in the project's file all the same.

        Generated by RJC and Claude.
        """
        for stream in (self.popen.stdin, self.popen.stdout):
            try:
                stream.close()
            except (OSError, ValueError):
                pass

    def wait(self, timeout=None):
        return self.popen.wait(timeout)


class Run:
    """
    A run of a project: started from a session, watched, and taken in at its end.

    Parameters
    ----------
    session : Session
        The project; its file, if it has one, receives the result.
    settings : list of str
        The settings given to the run on its command line (``"out verbose 1"``):
        the dashboard's own (:func:`alis.dashboard.settings.run_settings`), and any
        a tool adds (the convergence check).
    command : str
        What ``run.json`` records as the command.
    python, cwd : str, optional
        For :class:`Process`.

    Attributes
    ----------
    iteration, chi2, dof : int, float, int
        The latest iteration reported, or None.
    values : list of float or None
        The parameter values of that iteration, by ALIS's number: the fit in
        progress (shown only through the gate).
    progress : list
        ``[[iteration, χ²], …]`` of the fit.
    status : str or None
        How the run ended, once it has.
    message : str
        The error that stopped it, masked.
    warnings : list of str
    stored : str or None
        ``"file"`` or ``"memory"``.
    model_sha256 : str
        The model handed to the run.
    bundle : Bundle
        The project as it was handed to the run (without its runs): the model of
        the fit in progress (Stage 6.3).

    Generated by RJC and Claude.
    """

    kind = "run"

    def __init__(
        self, session, settings=(), command="alis (dashboard)", python=None, cwd=None
    ):
        self.path = (
            session.path if session.path and os.path.exists(session.path) else None
        )
        bundle = session.to_bundle()
        for member in [m for m in bundle.members if m.startswith(B.RUNS)]:
            del bundle.members[member]
        for kind in ("lines", "files"):
            for member in [m for m in bundle.hidden[kind] if m.startswith(B.RUNS)]:
                del bundle.hidden[kind][member]
        self.model_sha256 = B.sha256(bundle.members[bundle.model_member])
        self.bundle = bundle
        self.settings = list(settings)
        header = {"path": self.path, "settings": self.settings, "command": command}
        self.process = Process(B.to_bytes(bundle), header, python=python, cwd=cwd)
        self._begin()

    def _begin(self):
        """What the run has reported: nothing yet."""
        self.iteration = self.chi2 = self.dof = self.values = None
        self.convtest = False
        self.progress = []
        self.status = None
        self.message = ""
        self.warnings = []
        self.stored = None
        self.sent = None
        self.started = None
        self.elapsed = 0.0
        self.stopping = False
        self._ended = False

    def start(self):
        self.started = time.time()
        self.process.start()

    @property
    def finished(self):
        """Whether the run has ended (finished, failed or cancelled)."""
        return self.status is not None

    def update(self):
        """
        Take the process's messages, and return them.

        Generated by RJC and Claude.
        """
        messages = self.process.messages()
        for msg in messages:
            if msg is None:
                self._ended = True
                continue
            event = msg.get("event")
            if event == "iteration":
                self.iteration, self.chi2 = msg["iteration"], msg["chi2"]
                self.dof, self.values = msg.get("dof"), msg.get("values")
                self.convtest = bool(msg.get("convtest"))
                self.elapsed = msg.get("elapsed", self.elapsed)
                if not self.convtest:
                    self.progress.append([self.iteration, self.chi2])
            elif event == "warning":
                self.warnings.append(msg.get("message", ""))
            elif event == "runs":
                self.sent = (msg.get("members", {}), msg.get("hidden", {}))
            elif event == "finished":
                self.status = msg.get("status")
                self.message = msg.get("message", "")
                self.stored = msg.get("stored")
                if msg.get("chi2") is not None:
                    self.chi2 = msg["chi2"]
        if self.status is None and (self._ended or self.process.cancelled):
            if self.process.cancelled:
                self.status = CANCELLED
            elif self.process.returncode is not None or self._ended:
                self.status = ERROR
                self.message = (
                    "The fitting process stopped unexpectedly (exit code {0}).".format(
                        self.process.returncode
                    )
                )
        return [m for m in messages if m is not None]

    def stop(self):
        """Stop: end the fit at its current iteration, and keep it."""
        self.stopping = True
        self.process.stop()

    def cancel(self):
        """Cancel: end the process at once, and keep nothing."""
        if self.process.cancel():
            self.status = CANCELLED
            return True
        return False

    def wait(self, timeout=None, interval=0.1):
        """
        Wait for the run to end, taking its messages (for scripts and tests).

        Generated by RJC and Claude.
        """
        start = time.time()
        while not self.finished:
            self.update()
            if timeout is not None and time.time() - start > timeout:
                raise RunError("The run did not end within {0} s.".format(timeout))
            if not self.finished:
                time.sleep(interval)
        try:
            self.process.wait(timeout=30)
        except subprocess.TimeoutExpired:
            pass
        return self.status

    def take(self, session):
        """
        Take the ended run into the session's project: from its file, where the
        process stored it, or as the process sent it back.

        Returns
        -------
        bool
            Whether the project's runs changed.

        Generated by RJC and Claude.
        """
        if self.stored == "file":
            return session.take_runs(force=True)
        if self.stored == "memory" and self.sent is not None:
            apply_runs(session.project.bundle, *self.sent)
            session.runs_changed()
            return True
        return False


class Restarts(Run):
    """
    Random restarts (Stage 6.8; S21, Q6.22): several models (a run's own model, each
    started from a draw) fitted one after another by one fitting process, which
    sends each one's result back and stores nothing. Stop ends the restart being
    fitted, and the others are not begun; Cancel ends them all and keeps nothing.

    Parameters
    ----------
    session : Session
    bundles : list of Bundle
        One per restart (``restarts.restart_bundle``).
    settings : list of str
    taker : callable, optional
        ``taker(session, job)`` keeps the results when the restarts end.

    Attributes
    ----------
    total : int
    restart : int or None
        The restart being fitted, from 1.
    results : list of tuple
        ``(restart, info, mod_out, covar, message)`` of each restart that has ended.

    Generated by RJC and Claude.
    """

    kind = "restarts"

    def __init__(
        self,
        session,
        bundles,
        settings=(),
        command="alis (dashboard, random restarts)",
        python=None,
        cwd=None,
        taker=None,
    ):
        if not bundles:
            raise RunError("There is no restart to fit.")
        self.path = None
        self.bundle = bundles[0]
        self.model_sha256 = B.sha256(self.bundle.members[self.bundle.model_member])
        self.settings = list(settings)
        data = [B.to_bytes(b) for b in bundles]
        header = {
            "path": None,
            "settings": self.settings,
            "command": command,
            "restarts": [len(d) for d in data],
        }
        self.process = Process(b"".join(data), header, python=python, cwd=cwd)
        self.total = len(bundles)
        self.restart = None
        self.results = []
        self.taker = taker
        self._begin()

    def update(self):
        """Take the process's messages, the restarts' among them."""
        messages = super().update()
        for msg in messages:
            event = msg.get("event")
            if event == "restart_started":
                self.restart = msg.get("restart")
                self.progress = []
                self.iteration = self.chi2 = self.values = None
            elif event == "restart":
                self.results.append(
                    (
                        msg.get("restart"),
                        msg.get("info", {}),
                        msg.get("mod_out", ""),
                        msg.get("covar", ""),
                        msg.get("message", ""),
                    )
                )
        return messages

    def take(self, session):
        """Keep the restarts' results with the run they started from."""
        if self.taker is None:
            return False
        return bool(self.taker(session, self))


