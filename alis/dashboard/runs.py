"""Runs of a project: running a fit, the latest run, and the committed runs.

Dashboard Stage 6.1 (F6, F7, D26, S31; Q6.2, Q6.3, Q6.7, Q6.14, Q6.15, Q6.19). No Qt.

- **A run** (:class:`Run`) fits the project as it stands, unsaved changes included,
  in a separate process (:mod:`alis.dashboard.runner`), so that the window stays
  responsive and Stop works. The project is handed to the process through a pipe,
  as the bytes Save would write, never written to a file (Q6.14(a)). The process
  reports the χ² and the parameter values of each iteration (Q6.15(a)), and stores
  its result in the project's file at once, under the bundle's lock, as
  ``run_alis project.model`` does: the model on disk changes only with Save. A
  project with no file gets the result back, and keeps it in memory, and in its
  recovery copy, until it is saved (Q6.14(b)).
- **Stop** ends the fit at its current iteration, and the run is kept as
  "interrupted"; **Cancel** ends the process at once, and nothing is kept (Q6.3).
  Once the process has begun to store its result, Cancel waits for it.
- **The runs a project holds** (:class:`RunRecord`): the latest run, and the
  committed runs, numbered in the order they are committed, never reusing a number
  (Q6.7). A committed run keeps its ``run.json`` (with the user's description), its
  input model, its outputs, and the snips it fitted, which ``runs/files/`` holds
  once each. Committing, describing and removing a run change no model text and are
  not steps of the history; Save writes them, like the model. Restoring a run's
  model and snips is one step.
- **What a run holds:** its best-fit values and errors (read from its ``.mod.out``)
  and its covariance, by ALIS's number for each parameter
  (:attr:`alis.dashboard.model.Param.index`). Values are never shown from here: the
  tab shows them through the blinding gate.

Generated by RJC and Claude.
"""

