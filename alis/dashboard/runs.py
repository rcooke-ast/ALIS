_NUMBERED = re.compile(r"^runs/(\d{4,})/")
_NUMBER = re.compile(r"^[-+]?(\d+\.?\d*|\.\d+)([eEdD][-+]?\d+)?")


class RunError(Exception):
    """A run, or a change to the runs, that cannot be made as asked."""


# -- The runs a bundle holds ----------------------------------------------------------


def _prefix(number):
    return "{0}{1:04d}/".format(B.RUNS, number)


def _json(bundle, member):
    data = bundle.members.get(member)
    if data is None:
        return None
    try:
        return json.loads(data.decode("utf-8"))
    except ValueError:
        return None


class RunRecord:
    """
    One run that a bundle holds: the latest run, or a committed one.

    Parameters
    ----------
    bundle : Bundle
    prefix : str
        ``runs/latest/`` or ``runs/0003/``.

    Generated by RJC and Claude.
    """

    def __init__(self, bundle, prefix):
        self.bundle = bundle
        self.prefix = prefix
        self.info = _json(bundle, prefix + "run.json") or {}

    def __repr__(self):
        return "RunRecord({0!r}, {1})".format(self.prefix, self.status)

    # -- what run.json says ---------------------------------------------------------

    @property
    def latest(self):
        """Whether this is the latest run."""
        return self.prefix == B.LATEST

    @property
    def number(self):
        """The committed run's number, or None for the latest run."""
        found = _NUMBERED.match(self.prefix)
        return int(found.group(1)) if found else None

    @property
    def committed_as(self):
        """The number the latest run was committed as, or None."""
        return self.number if not self.latest else self.info.get("committed_as")

    @property
    def description(self):
        return self.info.get("description", "")

    @property
    def status(self):
        return self.info.get("status", "")

    @property
    def origin(self):
        """``dashboard``, ``cmd`` (``run_alis project.model``) or ``imported``."""
        if self.status == "imported":
            return IMPORTED
        return self.info.get("origin", COMMAND)

    @property
    def chi2(self):
        return self.info.get("chi2_final")

    @property
    def dof(self):
        return self.info.get("dof")

    @property
    def reduced_chi2(self):
        """χ² over the degrees of freedom, or None."""
        if self.chi2 is None or not self.dof:
            return None
        return self.chi2 / self.dof

    @property
    def iterations(self):
        return self.info.get("iterations")

    @property
    def finished(self):
        return self.info.get("finished") or self.info.get("imported")

    @property
    def host(self):
        return self.info.get("host", "")

    @property
    def progress(self):
        """The χ² of each iteration, ``[[iteration, χ²], …]`` (dashboard runs only)."""
        return list(self.info.get("progress", []))

    @property
    def model_sha256(self):
        return self.info.get("model_sha256")

    # -- what it holds --------------------------------------------------------------

    def members(self):
        """Every member of this run."""
        return sorted(m for m in self.bundle.members if m.startswith(self.prefix))

    def outputs(self):
        """The output members, as ``run.json`` lists them (hidden ones included)."""
        return sorted(self._member(m) for m in self.info.get("outputs", {}))

    def _member(self, member):
        """An output's member under this run's prefix."""
        if member.startswith(B.LATEST) and not self.latest:
            return self.prefix + member[len(B.LATEST) :]
        return member

    def output(self, suffix):
        """The first output whose name ends with ``suffix``, or None."""
        for member in sorted(self.info.get("outputs", {})):
            if member.endswith(suffix):
                return self._member(member)
        return None

    def text(self, member):
        """
        An output's text, its hidden lines restored in memory (a file hidden whole
        included). Never shown unmasked: the tab shows values through the gate.

        Generated by RJC and Claude.
        """
        hidden = self.bundle.hidden
        if member in hidden["files"]:
            return hidden["files"][member]
        return self.bundle.text(member, restore=True)

    def model_text(self):
        """The model that was run, its hidden lines restored."""
        return self.text(self.prefix + "input.mod")

    def mod_out(self):
        """The ``.mod.out``'s text, or None."""
        member = self.output(".mod.out")
        return None if member is None else self.text(member)

    def inputs(self):
        """The snips (and the project data) the run fitted, by their member."""
        out = {}
        for member, digest in self.info.get("inputs", {}).items():
            data = self.bundle.members.get(B.RUN_FILES + digest)
            if data is not None:
                out[member] = data
        return out

    def ui(self):
        """``ui/project.json`` as the run had it, or None."""
        data = self.inputs().get(UI_JSON)
        return None if data is None else json.loads(data.decode("utf-8"))

    # -- its values, errors and covariance ------------------------------------------

    def parsed(self, registry):
        """
        The ``.mod.out`` read by the dashboard's parser, or None: its parameters
        carry ALIS's numbers, and their values are the best fit.

        Generated by RJC and Claude.
        """
        text = self.mod_out()
        if text is None:
            return None
        return M.ParsedModel(T.ModelText(text), registry)

    def values(self, registry):
        """
        The best-fit value of each parameter, by ALIS's number.

        ALIS writes a line with a ``blindrange`` with an offset added to each of its
        values (``parout``); the offset is taken away again here, so that these are
        the values that were fitted (never shown: the gate masks them, Stage 6.3).

        Returns
        -------
        dict or None
            None when the run has no ``.mod.out``.

        Generated by RJC and Claude.
        """
        text = self.mod_out()
        return None if text is None else out_values(text, registry)

    def texts(self, registry):
        """
        Each parameter's value as the ``.mod.out`` writes it, by ALIS's number (its
        precision), for the parameters written there; a value of a line with a
        ``blindrange`` is left out, since it holds ALIS's offset.

        Generated by RJC and Claude.
        """
        pm = self.parsed(registry)
        if pm is None:
            return {}
        offsets = blind_offsets(pm)
        out = {}
        for par in pm.params:
            if par.index < 0 or par.index in out or par.value_token is None:
                continue
            if offsets.get(par.line):
                continue
            out[par.index] = par.value_token.text
        return out

    def errors(self, registry):
        """
        The error of each parameter, by ALIS's number: from the ``.mod.out``'s
        errors, and for the instrument (FWHM, shifts) from the covariance or the
        ``.mod.out``'s lists of them. An interrupted run's are its values (ALIS sets
        them so), and are not returned.

        Returns
        -------
        dict or None

        Generated by RJC and Claude.
        """
        if self.status == INTERRUPTED:
            return None
        text = self.mod_out()
        if text is None:
            return None
        return out_errors(text, registry, self.covariance())

    def covariance(self):
        """
        The run's covariance matrix (``out covar``), by ALIS's numbers, or None.

        Generated by RJC and Claude.
        """
        member = self.output(".covar")
        if member is None:
            return None
        try:
            covar = np.loadtxt(io.StringIO(self.text(member)), ndmin=2)
        except ValueError:
            return None
        return covar if covar.shape[0] == covar.shape[1] else None


def out_values(text, registry):
    """
    The best-fit value of each parameter of a ``.mod.out``, by ALIS's number.

    ALIS writes a line with a ``blindrange`` with an offset added to each of its
    values (``parout``); the offset is taken away again here, so that these are the
    values that were fitted.

    Generated by RJC and Claude.
    """
    pm = M.ParsedModel(T.ModelText(text), registry)
    offsets = blind_offsets(pm)
    out, offset_only = {}, set()
    for par in pm.params:
        if par.index < 0:
            continue
        offset = offsets.get(par.line, 0.0) if par.given else 0.0
        if par.index in out and (offset or par.index not in offset_only):
            continue
        # A place written without an offset is the more precise
        if offset and par.written is not None:
            out[par.index] = par.written - offset
            offset_only.add(par.index)
        else:
            out[par.index] = par.value
            offset_only.discard(par.index)
    return out


def out_errors(text, registry, covar=None):
    """
    The error of each parameter of a ``.mod.out``, by ALIS's number: from its
    errors block, and for the instrument (FWHM, shifts) from the covariance or its
    lists of them.

    Generated by RJC and Claude.
    """
    pm = M.ParsedModel(T.ModelText(text), registry)
    out = _model_errors(text, pm)
    others = _instrument_errors(text, pm)
    for par in pm.params:
        if par.index < 0 or par.index in out or par.role == "model":
            continue
        if covar is not None and par.index < covar.shape[0]:
            out[par.index] = float(np.sqrt(max(covar[par.index, par.index], 0.0)))
        elif par.index in others:
            out[par.index] = others[par.index]
    return out


def blind_offset(mkey):
    """
    The offset ALIS adds to the values it writes of a line with a ``blindrange``
    (``parout``: a uniform draw from the range, seeded by ``blindseed``, or 0).

    Generated by RJC and Claude.
    """
    limits = mkey.get("blindrange", [])
    if len(limits) != 2:
        return 0.0
    rng = np.random.RandomState(mkey.get("blindseed", 0))
    return float(rng.uniform(int(limits[0]), int(limits[1])))


def blind_offsets(pm):
    """
    The offset of each model line with a ``blindrange``, by its line in the text.

    Generated by RJC and Claude.
    """
    mkey = pm.modpass["mkey"] if pm.modpass else []
    out = {}
    for line in pm.lines:
        if "blindrange" not in line.keywords or not 0 <= line.index < len(mkey):
            continue
        offset = blind_offset(mkey[line.index])
        if offset:
            out[line.line] = offset
    return out


def _words(line):
    """A line's words, with the position of each."""
    return [(m.start(), m.group()) for m in re.finditer(r"\S+", line)]


def _number(word):
    """The number a word starts with (after ``name=``), or None."""
    found = _NUMBER.match(word.split("=", 1)[1] if "=" in word else word)
    if not found:
        return None
    return float(found.group().replace("d", "e").replace("D", "e"))


def _model_errors(text, pm):
    """
    The errors of the model's parameters, from the ``.mod.out``'s "Errors" block,
    which ALIS writes line for line, word for word, as the model block.

    Generated by RJC and Claude.
    """
    mtext = pm.text
    lines = [ln for ln in mtext.lines if ln.block == "model"]
    shown = [ln for ln in lines if ln.kind in (T.SECTION, T.FUNCTION)]
    after = max((ln.num for ln in lines), default=-1)
    raw = text.splitlines()
    errors, state = [], "before"
    for line in raw[after + 1 :]:
        if state == "before":
            if line.strip() == "# Errors:":
                state = "heading"
            continue
        if state == "heading":
            state = "errors"
            if line.strip() == "#":
                continue
        if not line.strip() or not line.startswith("#"):
            break
        errors.append(line[1:])
    if len(errors) != len(shown):
        return {}
    out = {}
    for model_line, error_line in zip(shown, errors):
        words = [tok.start for tok in model_line.tokens]
        err_words = [w for _, w in _words(error_line)]
        if len(err_words) != len(words):
            continue
        for par in pm.params:
            if par.role != "model" or par.token is None or par.line != model_line.num:
                continue
            if par.index < 0 or par.index in out:
                continue
            try:
                place = words.index(par.token.start)
            except ValueError:
                continue
            value = _number(err_words[place])
            if value is not None:
                out[par.index] = value
    return out


def _instrument_errors(text, pm):
    """
    The errors of the FWHMs and shifts, from the ``.mod.out``'s "Convolution
    Models" and "Shift Models", each matched to its parameter by its label, or by
    its value when it has none.

    Generated by RJC and Claude.
    """
    out = {}
    raw = text.splitlines()
    for title, role in (
        ("# Convolution Models:", "resolution"),
        ("# Shift Models:", "shift"),
    ):
        try:
            start = next(i for i, ln in enumerate(raw) if ln.strip() == title)
        except StopIteration:
            continue
        values, errors, target = [], [], None
        for line in raw[start + 1 :]:
            if not line.strip() or not line.startswith("#"):
                break
            body = line[1:].strip()
            if body == "Errors:":
                target = errors
                continue
            if not body:
                continue
            (errors if target is errors else values).append(body.split()[-1])
        pars = [p for p in pm.params if p.role == role and p.value_token is not None]
        for value, error in zip(values, errors):
            num = _number(error)
            if num is None:
                continue
            for par in pars:
                label = par.label_token.text if par.label_token is not None else ""
                written = par.value_token.text + label
                if (label and value.endswith(label)) or value == written:
                    out.setdefault(par.index, num)
    return out


def latest(bundle):
    """The latest run, or None."""
    if B.LATEST + "run.json" not in bundle.members:
        return None
    return RunRecord(bundle, B.LATEST)


def committed(bundle):
    """The committed runs, newest first."""
    numbers = set()
    for member in bundle.members:
        found = _NUMBERED.match(member)
        if found and member.endswith("/run.json"):
            numbers.add(int(found.group(1)))
    return [RunRecord(bundle, _prefix(n)) for n in sorted(numbers, reverse=True)]


def run_of(bundle, number=None):
    """Run ``number``, or the latest run when it is None."""
    if number is None:
        return latest(bundle)
    if _prefix(number) + "run.json" not in bundle.members:
        raise RunError("There is no run {0}.".format(number))
    return RunRecord(bundle, _prefix(number))


def last_error(bundle):
    """``runs/last_error.json``, when it is newer than the latest run; else None."""
    error = _json(bundle, B.LAST_ERROR)
    if error is None:
        return None
    run = latest(bundle)
    if run is not None and (run.info.get("finished") or "") > error.get("time", ""):
        return None
    return error


# -- Committing, describing, removing (Q6.7) ------------------------------------------


def _next_number(bundle):
    index = _json(bundle, INDEX) or {}
    used = [r.number for r in committed(bundle)]
    return max([int(index.get("last", 0))] + used) + 1


def _copy_run(bundle, src, dst):
    """Copy every member of a run, and its hidden lines and files, to ``dst``."""
    for member in [m for m in bundle.members if m.startswith(src)]:
        bundle.members[dst + member[len(src) :]] = bundle.members[member]
    for kind in ("lines", "files"):
        store = bundle.hidden[kind]
        for member in [m for m in store if m.startswith(src)]:
            store[dst + member[len(src) :]] = copy.deepcopy(store[member])


def _drop_run(bundle, prefix):
    for member in [m for m in bundle.members if m.startswith(prefix)]:
        del bundle.members[member]
    for kind in ("lines", "files"):
        store = bundle.hidden[kind]
        for member in [m for m in store if m.startswith(prefix)]:
            del store[member]


def _write_info(bundle, prefix, info):
    bundle.members[prefix + "run.json"] = json.dumps(info, indent=1).encode("utf-8")


def commit(bundle, description, when=None):
    """
    Commit the latest run to the run history, with the user's description (D40).

    Parameters
    ----------
    bundle : Bundle
        The project's bundle, in memory; Save writes it.
    description : str
    when : str, optional
        When it was committed; by default now.

    Returns
    -------
    int
        The run's number.

    Raises
    ------
    RunError
        If there is no latest run, or it is committed already.

    Generated by RJC and Claude.
    """
    run = latest(bundle)
    if run is None:
        raise RunError("There is no run to commit.")
    if run.committed_as is not None:
        raise RunError(
            "This run is committed already, as run {0}.".format(run.committed_as)
        )
    number = _next_number(bundle)
    prefix = _prefix(number)
    _copy_run(bundle, B.LATEST, prefix)
    info = dict(run.info)
    info["outputs"] = {
        prefix + m[len(B.LATEST) :]: v for m, v in info.get("outputs", {}).items()
    }
    info.update(
        {"number": number, "description": description, "committed": when or B.now()}
    )
    _write_info(bundle, prefix, info)
    latest_info = dict(run.info)
    latest_info["committed_as"] = number
    _write_info(bundle, B.LATEST, latest_info)
    bundle.members[INDEX] = json.dumps({"last": number}, indent=1).encode("utf-8")
    return number


def describe(bundle, number, description):
    """
    Change a committed run's description.

    Generated by RJC and Claude.
    """
    run = run_of(bundle, number)
    info = dict(run.info)
    info["description"] = description
    _write_info(bundle, run.prefix, info)


def remove(bundle, number):
    """
    Remove a committed run (the window asks first). Its number is not used again.

    Generated by RJC and Claude.
    """
    run = run_of(bundle, number)
    if run.latest:
        raise RunError("The latest run is not committed, so it cannot be removed.")
    index = _json(bundle, INDEX) or {}
    last = max(int(index.get("last", 0)), number)
    _drop_run(bundle, run.prefix)
    bundle.members[INDEX] = json.dumps({"last": last}, indent=1).encode("utf-8")
    now = latest(bundle)
    if now is not None and now.committed_as == number:
        info = dict(now.info)
        info.pop("committed_as", None)
        _write_info(bundle, B.LATEST, info)
    B.prune_run_files(bundle)


def committed_state(bundle):
    """
    A fingerprint of what the dashboard owns of the runs: the committed runs, the
    index, and which run the latest was committed as.

    Generated by RJC and Claude.
    """
    parts = []
    for member in sorted(bundle.members):
        if _NUMBERED.match(member) or member == INDEX:
            parts.append((member, B.sha256(bundle.members[member])))
    run = latest(bundle)
    parts.append(("latest", None if run is None else run.committed_as))
    return json.dumps(parts)


# -- Merging the runs of two bundles (Save, taking runs in, recovery) ----------------


def take_latest(target, source):
    """
    Put ``source``'s latest run and last error in ``target``, keeping ``target``'s
    committed runs (the dashboard's own, maybe not yet saved).

    Generated by RJC and Claude.
    """
    committed_as = None
    now = latest(target)
    _drop_run(target, B.LATEST)
    target.members.pop(B.LAST_ERROR, None)
    for member, data in source.members.items():
        if member.startswith(B.LATEST) or member == B.LAST_ERROR:
            target.members[member] = data
        elif member.startswith(B.RUN_FILES):
            target.members.setdefault(member, data)
    for kind in ("lines", "files"):
        target.hidden[kind].update(
            {
                m: copy.deepcopy(v)
                for m, v in source.hidden[kind].items()
                if m.startswith(B.LATEST)
            }
        )
    new = latest(target)
    if now is not None and new is not None and now.committed_as is not None:
        if _same_run(now.info, new.info):
            committed_as = now.committed_as
    if committed_as is not None:
        info = dict(new.info)
        info["committed_as"] = committed_as
        _write_info(target, B.LATEST, info)
    B.prune_run_files(target)


def _same_run(one, two):
    keys = ("started", "finished", "model_sha256", "host")
    return all(one.get(k) == two.get(k) for k in keys)


def take_committed(target, source):
    """
    Put ``source``'s committed runs and index in ``target``, replacing its own.

    Generated by RJC and Claude.
    """
    for run in committed(target):
        _drop_run(target, run.prefix)
    target.members.pop(INDEX, None)
    for run in committed(source):
        _copy_run_between(source, target, run.prefix)
    if INDEX in source.members:
        target.members[INDEX] = source.members[INDEX]
    for member, data in source.members.items():
        if member.startswith(B.RUN_FILES):
            target.members.setdefault(member, data)
    now, mine = latest(target), latest(source)
    if now is not None:
        info = dict(now.info)
        info.pop("committed_as", None)
        if mine is not None and mine.committed_as and _same_run(now.info, mine.info):
            info["committed_as"] = mine.committed_as
        _write_info(target, B.LATEST, info)
    B.prune_run_files(target)


def _copy_run_between(source, target, prefix):
    for member, data in source.members.items():
        if member.startswith(prefix):
            target.members[member] = data
    for kind in ("lines", "files"):
        target.hidden[kind].update(
            {
                m: copy.deepcopy(v)
                for m, v in source.hidden[kind].items()
                if m.startswith(prefix)
            }
        )


def apply_runs(bundle, members, hidden):
    """
    Take in a run sent back by the fitting process (a project with no file): its
    latest run, or its error, keeping the committed runs.

    Parameters
    ----------
    bundle : Bundle
        The project's bundle, in memory.
    members : dict
        ``runs/`` member to its bytes, base64-encoded.
    hidden : dict
        Their hidden lines and files.

    Generated by RJC and Claude.
    """
    sent = B.Bundle(
        members={m: base64.b64decode(c) for m, c in members.items()},
        hidden={
            "lines": dict(hidden.get("lines", {})),
            "files": dict(hidden.get("files", {})),
        },
    )
    if B.LATEST + "run.json" in sent.members:
        take_latest(bundle, sent)
    elif B.LAST_ERROR in sent.members:
        bundle.members[B.LAST_ERROR] = sent.members[B.LAST_ERROR]


# -- Restoring a run's model (Q6.7) ---------------------------------------------------


def restore_step(project, number):
    """
    The step that replaces the model and its snips with a committed run's (or the
    latest run's, for ``None``), and ``ui/project.json`` with the run's when it kept
    it: one step, which one undo reverses.

    Generated by RJC and Claude.
    """
    run = run_of(project.bundle, number)
    if run is None:
        raise RunError("There is no run to restore.")
    text = run.model_text()
    stored = run.bundle.text(run.prefix + "input.mod")
    blind = set(B.blind_line_numbers(text))
    marks = {ln.num for ln in T.ModelText(stored).lines if ln.kind == T.HIDDEN}
    inputs = run.inputs()
    files = {}
    snips = {m: c for m, c in inputs.items() if m.startswith(B.TREE)}
    if snips or not inputs:
        for member in set(project.files) | set(snips):
            old, new = project.files.get(member), snips.get(member)
            if old != new:
                files[member] = (old, new)
    ui = run.ui()
    name = "run {0}".format(number) if number is not None else "the latest run"
    step = P.Step(
        "Restore the model of " + name,
        T.Change((T.Patch(0, project.text, text),)) if text != project.text else None,
        files,
        None if ui is None or ui == project.ui else (copy.deepcopy(project.ui), ui),
        (
            (set(project.extra_hidden), marks - blind)
            if set(project.extra_hidden) != marks - blind
            else None
        ),
    )
    return step


