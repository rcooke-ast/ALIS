"""What the Fit tab's Inspect sub-tab shows: the View menu, the panels, the chips,
the progress of a run and the words of the status bar.

Dashboard Stage 6.4 (D38, D39, F6, S18; Q6.5, Q6.15). No Qt: ``qt/fit.py`` draws what
this module gives.

- **The View menu** (D38): every snip; one ion of a system, grouped as the
  Components tab's navigator (an element's isotopes with it), or the Lyα forest;
  one snip. ‹ › step through it.
- **The panels:** one per snip of the choice, on a velocity axis in the model's
  frame (relative to the ion's strongest transition inside the snip when an ion is
  shown, as the Components tab draws it; otherwise relative to the transition the
  snip was cut for, as the Lyα forest's panels), or in wavelength. A snip whose
  transition is not known is drawn in wavelength.
- **Initial | Final** (Q6.5, Q6.15): the model as it stands now, which the next run
  starts from, or the shown run's best fit (or the fit in progress). The data are
  divided by the shown model's own continuum, and the components' ticks are drawn
  at the shown model's redshifts, locked.
- **The chips** (S18, D39): each snip with the marks of the model the panels
  draw, Initial's or Final's (RJC's review), χ²ν and the runs test as
  ``alis/report.py`` computes them (``results.quality``).
- **The progress** (D38): χ² against iteration of the run going, or of the latest
  run, with the run before it in grey; and what the status bar says of a run.

Nothing here shows a parameter's value: the ticks are drawn without one, as
blinded profiles are (D24), and χ², the marks and the panels reveal none.

Generated by RJC and Claude.
"""

import time
from dataclasses import dataclass, field

import numpy as np

from alis.dashboard import components as C
from alis.dashboard import continuum as CO
from alis.dashboard import lines as L
from alis.dashboard import profile as PR
from alis.dashboard import project as P
from alis.dashboard import results as RS
from alis.dashboard import runs as R
from alis.dashboard import snips as S

C_KMS = 299792.458
# What the View menu shows
ALL, ION, FOREST, SNIP = "all", "ion", "forest", "snip"
# Initial | Final (Q6.5), the axis, and the residuals of every pixel or the fitted
INITIAL, FINAL = "initial", "final"
ALL_PIXELS, FITTED_PIXELS = "all", "fitted"
VELOCITY, WAVELENGTH = "velocity", "wavelength"
# The View menu's headings
BY_ION, ONE_SNIP = "By ion", "One snip"
MINUS = "−"


# -- The View menu (D38) --------------------------------------------------------------


@dataclass(frozen=True)
class Choice:
    """
    One entry of the View menu.

    Attributes
    ----------
    kind : str
        :data:`ALL`, :data:`ION`, :data:`FOREST` or :data:`SNIP`.
    key : tuple
        What the view state keeps: ``("all",)``, ``("ion", system id, ion)``,
        ``("forest",)`` or ``("snip", member, specid)``.
    title : str
        ``"All snips (12)"``, ``"H I with D I · 8 snips"``, ``"Ly8 923.2 · H1"``.
    heading : str
        The heading it sits under: ``""``, :data:`BY_ION` or :data:`ONE_SNIP`.

    Generated by RJC and Claude.
    """

    kind: str
    key: tuple
    title: str
    heading: str = ""


def _plural(num, word):
    return "{0} {1}{2}".format(num, word, "" if num == 1 else "s")


def _shown_snips(project):
    """The snips that can be drawn: those whose pixels were read."""
    return [s for s in project.snips if s.pixels is not None and s.pixels.wave.size]


def snip_key(snip):
    """A snip's key in the View menu and in the view state: its file and specid."""
    return (SNIP, snip.member, snip.specid)


def _transition_line(own):
    """``"Ly8 923.2"`` or ``"O I 1302.2"``, for a snip's recorded transition."""
    return C.PanelTransition(own.ion, own.rest, 0.0).line


def snip_title(project, snip, own=None):
    """
    A snip's name in the View menu, its chip and its panel: the transition it was
    cut for and its specid (``"Ly8 923.2 · H1"``), with its dataset when several
    snips share the specid; its wavelength range when its transition is not known.

    Parameters
    ----------
    own : SnipTransition, optional
        The snip's transition (``lines.snip_transitions``); found if not given.

    Generated by RJC and Claude.
    """
    if own is None:
        own = L.snip_transitions(project).get(snip.specid)
    if own is not None:
        parts = [_transition_line(own), snip.specid]
    else:
        extent = snip.extent
        parts = [snip.specid]
        if extent is not None:
            parts.append("{0:.1f}–{1:.1f} Å".format(*extent))
    shared = [s for s in project.snips if s.specid == snip.specid]
    if len(shared) > 1 and snip.row is not None:
        parts.append(snip.row.name)
    return " · ".join(parts)


def choices(project):
    """
    The View menu (D38): all snips; each ion of each system that a snip holds
    (isotopes with their element), the primary system first, and the Lyα forest;
    each snip.

    Returns
    -------
    list of Choice

    Generated by RJC and Claude.
    """
    shown = _shown_snips(project)
    out = [Choice(ALL, (ALL,), "All snips ({0})".format(len(shown)))]
    systems, forest = C.navigator(project)
    several = len(systems) > 1
    for system, rows in systems:
        for row in rows:
            if not row.snips:
                continue
            name = row.name
            others = [P.ion_name(i) for i in row.ions if i != row.ion]
            if others:
                name += " with " + ", ".join(others)
            if several:
                name = "{0}: {1}".format(system.name, name)
            title = "{0} · {1}".format(name, _plural(row.snips, "snip"))
            out.append(Choice(ION, (ION, system.id, row.ion), title, BY_ION))
    if forest is not None and forest.snips:
        title = "Lyα forest · {0}".format(_plural(forest.snips, "snip"))
        out.append(Choice(FOREST, (FOREST,), title, BY_ION))
    own = L.snip_transitions(project)
    for snip in shown:
        title = snip_title(project, snip, own.get(snip.specid))
        out.append(Choice(SNIP, snip_key(snip), title, ONE_SNIP))
    return out


def find(found, key):
    """
    The place of a key in the View menu, or 0 (all snips) when it is not there (an
    ion removed, a snip cleared).

    Generated by RJC and Claude.
    """
    if key:
        key = tuple(key)
        for num, choice in enumerate(found):
            if choice.key == key:
                return num
    return 0


def step(found, key, by):
    """The key ‹ › go to from ``key``: ``by`` places on, round the menu."""
    if not found:
        return None
    return found[(find(found, key) + by) % len(found)].key


# -- The panels -----------------------------------------------------------------------


@dataclass
class Panel:
    """
    One panel of the Inspect sub-tab: one snip, on its axis.

    Attributes
    ----------
    title : str
    snip : Snip
    centre : float or None
        The wavelength of zero velocity, in the model's frame; None when the snip's
        transition is not known (drawn in wavelength).
    transition : PanelTransition or None
        The transition at zero velocity, and the ion's others in the snip (their
        ticks repeat the components').
    system : System or None
        The system whose components are ticked.
    ion : str or None
        The ion ticked, or :data:`FOREST`.
    axis : str
        :data:`VELOCITY` or :data:`WAVELENGTH`, as asked.
    project : Project

    Generated by RJC and Claude.
    """

    title: str
    snip: object = field(repr=False)
    centre: float | None
    transition: object = field(repr=False, default=None)
    system: object = field(repr=False, default=None)
    ion: str | None = None
    axis: str = VELOCITY
    project: object = field(repr=False, default=None)

    @property
    def key(self):
        return snip_key(self.snip)

    @property
    def velocity(self):
        """Whether the panel is drawn in velocity (it has a transition to be so)."""
        return self.axis == VELOCITY and self.centre is not None

    def x(self, wave):
        """
        Wavelengths of the snip (the data's frame) on the panel's axis.

        Generated by RJC and Claude.
        """
        wave = np.asarray(wave, dtype=float)
        if not self.velocity:
            return wave
        moved = CO.model_wave(self.project, self.snip, wave)
        return C_KMS * (moved / self.centre - 1.0)

    def from_velocity(self, vel):
        """Velocities relative to the centre, on the panel's axis."""
        vel = np.asarray(vel, dtype=float)
        if self.velocity or self.centre is None:
            return vel
        moved = self.centre * (1.0 + vel / C_KMS)
        return CO.data_wave(self.project, self.snip, moved)

    def regions(self):
        """The snip's fit regions on the panel's axis."""
        out = []
        for low, high in S.regions_of(self.snip):
            ends = self.x(np.array([low, high]))
            out.append((float(ends.min()), float(ends.max())))
        return out

    def home(self):
        """The snip's extent on the panel's axis."""
        ends = self.x(self.snip.pixels.wave)
        return float(np.nanmin(ends)), float(np.nanmax(ends))

    def half_range(self):
        """The largest velocity of the snip from the centre, in km/s."""
        if self.centre is None:
            return 0.0
        moved = CO.model_wave(self.project, self.snip, self.snip.pixels.wave)
        return float(np.nanmax(np.abs(C_KMS * (moved / self.centre - 1.0))))


def _system_of(project, ident):
    try:
        return project.system(ident)
    except P.ProjectError:
        return None


def _snip_panel(project, snip, own, axis):
    """A snip's panel, about the transition it was cut for."""
    title = snip_title(project, snip, own)
    if own is None:
        return Panel(title, snip, None, axis=axis, project=project)
    system = _system_of(project, own.system)
    if system is None and project.systems:
        primary = [s for s in project.systems if s.primary]
        system = primary[0] if primary else project.systems[0]
    z = system.z if system is not None else 0.0
    inside = C._inside(project, snip, own.ion, z)
    rests = [] if inside is None else [inside.rest] + list(inside.others)
    others = [r for r in rests if abs(r - own.rest) > 0.01]
    trans = C.PanelTransition(own.ion, own.rest, 0.0, others)
    centre = own.rest * (1.0 + z)
    return Panel(title, snip, centre, trans, system, own.ion, axis, project)


def panels(project, choice, axis=VELOCITY):
    """
    The panels of a View menu choice.

    Parameters
    ----------
    project : Project
    choice : Choice
    axis : str
        :data:`VELOCITY` or :data:`WAVELENGTH`.

    Returns
    -------
    list of Panel

    Generated by RJC and Claude.
    """
    if choice.kind == ION:
        system = _system_of(project, choice.key[1])
        if system is None:
            return []
        ion = choice.key[2]
        found, _ = C.panels(project, system, ion, C.ALL)
        return [
            Panel(p.title, p.snip, p.centre, p.transition, system, ion, axis, project)
            for p in found
        ]
    if choice.kind == FOREST:
        return [
            Panel(p.title, p.snip, p.centre, p.transition, None, FOREST, axis, project)
            for p in C.forest_panels(project, C.ALL)
        ]
    own = L.snip_transitions(project)
    shown = _shown_snips(project)
    if choice.kind == SNIP:
        shown = [s for s in shown if snip_key(s) == tuple(choice.key)]
    return [_snip_panel(project, s, own.get(s.specid), axis) for s in shown]


def ticks(project, panel, view=None):
    """
    The ticks of a panel, on its axis, locked (no drags on the Fit tab): the
    components of its system at the shown model's redshifts, as the Components tab
    draws them, or the Lyα forest's lines.

    Parameters
    ----------
    project : Project
    panel : Panel
    view : results.View, optional
        The shown run (Final): its model, at its best fit (or the fit in progress).
        None draws the model as it stands (Initial).

    Returns
    -------
    list of dict
        ``x``, ``label``, ``kind`` and ``key``, as ``SpectrumView.set_ticks`` takes
        them.

    Generated by RJC and Claude.
    """
    if panel.transition is None or panel.centre is None:
        return []
    if view is None:
        model, values, linked = project, None, C.linked_values(project)
    else:
        try:
            values = view.vector()
        except RS.ResultsError:
            return []
        model, linked = view.model, None
    half = panel.half_range()
    if panel.ion == FOREST:
        found = C.forest_ticks(model, panel, half, linked, values)
    elif panel.system is None or panel.ion is None:
        return []
    else:
        system = _system_of(model, panel.system.id)
        if system is None:
            return []
        found = C.panel_ticks(model, system, panel.ion, panel, half, linked, values)
    out = []
    for tick in found:
        if abs(tick.x) > half:
            continue
        out.append(
            {
                "x": float(panel.from_velocity(tick.x)),
                "label": tick.label,
                "kind": tick.kind,
                "key": tick.key,
            }
        )
    return out


def unfitted_spans(x, counted):
    """
    The stretches of a panel's axis whose pixels the marks do not count (outside the
    fit regions, left out, bad): each from halfway to its neighbouring pixels, for
    the residual strip's grey bands (Stage 6.5, RJC's review).

    Parameters
    ----------
    x : array
        The pixels on the panel's axis, in order.
    counted : array of bool
        ``results.counted`` of the panel's curve.

    Returns
    -------
    list of tuple
        ``(low, high)`` on the axis.

    Generated by RJC and Claude.
    """
    x = np.asarray(x, dtype=float)
    counted = np.asarray(counted, dtype=bool)
    idx = np.flatnonzero(~counted)
    if x.size < 2 or not idx.size:
        return []
    edges = np.empty(x.size + 1)
    edges[1:-1] = 0.5 * (x[1:] + x[:-1])
    edges[0] = x[0] - 0.5 * (x[1] - x[0])
    edges[-1] = x[-1] + 0.5 * (x[-1] - x[-2])
    breaks = np.flatnonzero(np.diff(idx) > 1)
    starts = np.r_[idx[0], idx[breaks + 1]]
    ends = np.r_[idx[breaks], idx[-1]]
    out = []
    for start, end in zip(starts, ends):
        low, high = edges[start], edges[end + 1]
        if np.isfinite(low) and np.isfinite(high):
            out.append((float(min(low, high)), float(max(low, high))))
    return out


# -- The chips (S18, D39) --------------------------------------------------------------


def signed(value, decimals=1):
    """A number with its sign, as the axes write it (D43): ``−4.2``, ``+1.3``."""
    text = "{0:.{1}f}".format(abs(value), decimals)
    if float(text) == 0.0:
        return text
    return ("+" if value > 0 else MINUS) + text


def mark_texts(quality):
    """
    The two marks of a snip's fit: ``[("χ²ν 1.02", "✓"), ("runs −4.2", "✕")]``.

    Generated by RJC and Claude.
    """
    return [
        ("χ²ν {0:.2f}".format(quality.reduced), quality.chi2_mark),
        ("runs " + signed(quality.runs_z), quality.runs_mark),
    ]


def worst(quality):
    """The worse of a fit's two marks."""
    order = (RS.GOOD, RS.WARN, RS.BAD)
    marks = (quality.chi2_mark, quality.runs_mark)
    return max(marks, key=order.index)


@dataclass
class Chip:
    """
    A snip's chip in the "All snips" strip.

    Attributes
    ----------
    key : tuple
        The snip's key (:func:`snip_key`).
    title : str
    quality : results.Quality or None
        The marks of the Final model; None with ``note`` saying why.
    note : str

    Generated by RJC and Claude.
    """

    key: tuple
    title: str
    quality: object = None
    note: str = ""


NO_RUN = "no run yet"
NOT_FITTED = "not fitted by this run"
NO_PIXELS = "no fitted pixel"


def chips(project, view=None, initial=False):
    """
    A chip for each snip, with the marks of the model the panels draw (S18; RJC's
    review of Task 6.5): Final's (the shown run's best fit, or the fit in progress)
    or, with ``initial``, those of the model as it stands.

    Parameters
    ----------
    project : Project
    view : results.View, optional
        The shown run; None when there is none.
    initial : bool
        The marks of the model as it stands (Initial).

    Returns
    -------
    list of Chip

    Generated by RJC and Claude.
    """
    marks, unfitted, note = {}, set(), NO_RUN
    if initial:
        nsig = float(project.parsed.argflag["out"]["reportsig"])
        note = NO_PIXELS
        try:
            curves = PR.of(project).evaluate()
            marks = {i: RS.quality(c, nsig) for i, c in curves.items()}
        except PR.ProfileError as err:
            note = str(err)
    elif view is not None and view.has_best_fit:
        try:
            marks = view.marks()
            unfitted = set(view.unfitted())
            note = NO_PIXELS
        except RS.ResultsError as err:
            note = str(err)
    elif view is not None:
        note = view.why_not().rstrip(".")
    own = L.snip_transitions(project)
    out = []
    for snip in _shown_snips(project):
        index = snip.data.index
        quality = marks.get(index)
        text = ""
        if quality is None:
            text = NOT_FITTED if index in unfitted else note
        out.append(
            Chip(
                snip_key(snip),
                snip_title(project, snip, own.get(snip.specid)),
                quality,
                text,
            )
        )
    return out


# -- The progress and the status bar (D38, F6) ----------------------------------------


@dataclass
class Progress:
    """
    The progress chart: χ² against iteration.

    Attributes
    ----------
    current : list
        ``[[iteration, χ²], …]`` of the run going, or of the latest run.
    previous : list
        The run before it, drawn in grey.
    name : str
        Which run is drawn ("the fit in progress", "the latest run").
    note : str
        What the grey curve is, or why only the end is known.

    Generated by RJC and Claude.
    """

    current: list
    previous: list
    name: str
    note: str = ""


def _points(record):
    """A run's χ² against iteration: its progress, or only its end (S31)."""
    points = record.progress
    if points:
        return points
    if record.iterations is not None and record.chi2 is not None:
        return [[int(record.iterations), float(record.chi2)]]
    return []


def progress(project, job=None):
    """
    The progress chart (D38): the run going (``job``) against the latest run, or the
    latest run against the newest committed run before it. A run made on the
    command line records only its end (S31).

    Parameters
    ----------
    project : Project
    job : runs.Run, optional
        The run going, or the run that has just ended.

    Returns
    -------
    Progress

    Generated by RJC and Claude.
    """
    latest = R.latest(project.bundle)
    if job is not None and not job.finished:
        previous = [] if latest is None else _points(latest)
        note = "Grey: the latest run." if previous else ""
        return Progress(list(job.progress), previous, "the fit in progress", note)
    if latest is None:
        return Progress([], [], "", "No fit has run yet.")
    current = _points(latest)
    previous, note = [], ""
    for record in R.committed(project.bundle):
        if record.number != latest.committed_as:
            previous = _points(record)
            note = "Grey: run {0}.".format(record.number) if previous else ""
            break
    if current and not latest.progress:
        note = ("Only the end of this run is known. " + note).strip()
    elif not current:
        note = ("Its χ² against iteration is not known. " + note).strip()
    return Progress(current, previous, "the latest run", note)


def clock(seconds):
    """``0:41`` or ``1:02:03``."""
    seconds = int(max(seconds, 0))
    hours, rest = divmod(seconds, 3600)
    minutes, secs = divmod(rest, 60)
    if hours:
        return "{0}:{1:02d}:{2:02d}".format(hours, minutes, secs)
    return "{0}:{1:02d}".format(minutes, secs)


def status_text(job, now=None):
    """
    What the status bar says of the run going: ``"Running · iteration 9 · χ² 3796.2
    · 0:41"``, or that it is stopping, or storing its result.

    Generated by RJC and Claude.
    """
    now = time.time() if now is None else now
    elapsed = clock(now - job.started) if job.started else "0:00"
    if job.process.storing:
        return "Storing the result of the fit · " + elapsed
    if job.stopping:
        where = (
            " at the end of iteration {0}".format(job.iteration)
            if job.iteration is not None
            else ""
        )
        return "Stopping the fit{0}… · {1}".format(where, elapsed)
    if job.iteration is None:
        return "Running · starting · " + elapsed
    what = "Convergence check" if job.convtest else "Running"
    return "{0} · iteration {1} · χ² {2:.1f} · {3}".format(
        what, job.iteration, job.chi2, elapsed
    )


def marker_text(job):
    """The Fit marker's tip while a run goes: ``"Running: iteration 9."``."""
    if job.iteration is None:
        return "Running: starting."
    return "Running: iteration {0}.".format(job.iteration)


def notice_text(job):
    """
    The notice above the fit in progress (Q6.15(a)).

    Generated by RJC and Claude.
    """
    if job.iteration is None:
        return "The fit in progress: its model is drawn after its first iteration."
    return (
        "The fit in progress: the model is redrawn after each iteration (iteration"
        " {0}, χ² {1:.1f})".format(job.iteration, job.chi2)
    )


