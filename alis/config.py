@dataclass
class ColumnMap(_DictLike):
    """Column indices for a loaded data file (formerly the ``wfe`` dict).

    Maps each data quantity to its column index in the input file; ``-1``
    means "not present". Built per data line in ``load.load_data`` (and
    overridden by the ``columns`` keyword, whose allowed names are exactly
    these fields), then stored in ``datopt['columns']``. ``wfe['flux']``
    access and ``.keys()`` (used by ``save``) are preserved via
    :class:`_DictLike`; field order matches the original dict literal.

    Generated by RJC and Claude.
    """

    wave: int = 0
    flux: int = 1
    error: int = 2
    continuum: int = -1
    zerolevel: int = -1
    systematics: int = -1
    fitrange: int = -1
    loadrange: int = -1
    resolution: int = -1


@dataclass
class ColumnPosition(_DictLike):
    """Row of each loaded column within the compacted data array.

    Formerly the ``ucind`` dict in ``load.load_userdata``: as the used
    columns are packed into ``datain``, this records the row index of each
    present column (``-1`` = not loaded). Only present columns are assigned;
    absent ones are read only under an ``if wfe['x'] != -1`` guard.
    ``ucind['wave']`` access is preserved via :class:`_DictLike`.

    Generated by RJC and Claude.
    """

    wave: int = -1
    flux: int = -1
    error: int = -1
    continuum: int = -1
    zerolevel: int = -1
    systematics: int = -1
    fitrange: int = -1
    loadrange: int = -1
    resolution: int = -1


@dataclass
class LinkPass(_DictLike):
    """Linked-parameter relations (formerly the ``lnkpass`` / ``slf._links``
    dict).

    Built in ``load.load_links`` and consumed by every function's
    ``set_pinfo``. The three parallel lists describe, for entry ``k``: the
    tied parameter (``opA``), the parameters it is linked to (``opB``), and
    the relational expression (``exp``). ``links['opA']`` access is
    preserved via :class:`_DictLike`.

    Generated by RJC and Claude.
    """

    opA: list = field(default_factory=list)  # First tied parameter
    opB: list = field(default_factory=list)  # Array of linked parameters
    exp: list = field(default_factory=list)  # The relational expression


@dataclass
class ArgFlag(_DictLike):
    """The full ALIS settings structure (formerly the ``argflag`` dict).

    Sections are accessible either as attributes (``cfg.run.ncpus``) or,
    for backward compatibility during the migration, dict-style
    (``cfg['run']['ncpus']``).
    """

    run: RunConfig = field(default_factory=RunConfig)
    chisq: ChisqConfig = field(default_factory=ChisqConfig)
    plot: PlotConfig = field(default_factory=PlotConfig)
    out: OutConfig = field(default_factory=OutConfig)
    sim: SimConfig = field(default_factory=SimConfig)
    generate: GenerateConfig = field(default_factory=GenerateConfig)
    iterate: IterateConfig = field(default_factory=IterateConfig)
