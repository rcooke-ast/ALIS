"""Typed configuration dataclasses for ALIS (Stage 2.1).

The ``argflag`` settings structure -- historically a nested string-keyed
dict of dicts built in ``load.load_settings`` -- is represented here as
typed dataclasses. To keep the Stage 0 regression suite green while the
rest of the code base still uses ``argflag['section']['key']`` syntax, the
dataclasses expose dict-like access through :class:`_DictLike` (Q2.3:
incremental migration with dict-style access during the transition).

Field names, default values and default types mirror the original
``initialise()`` defaults exactly, so settings-file parsing
(``load.set_params``), which introspects value types, is unchanged.

Generated by RJC and Claude.
"""

from dataclasses import dataclass, field, fields
from typing import Any, Optional


def _s(default, help):
    """
    A setting's field: its default, and a one-line description of what it does,
    which ``run_alis --list-settings`` and the dashboard's settings show
    (dashboard Stage 6, Q6.6(a)).

    Generated by RJC and Claude.
    """
    return field(default=default, metadata={"help": help})


class _DictLike:
    """Mixin giving a dataclass ``d['key']`` access during the migration.

    Only the operations the code base actually performs on ``argflag`` are
    implemented: subscripted get/set, ``keys()`` and ``in`` membership.
    Iteration and ``.items()``/``.values()`` are intentionally omitted --
    nothing uses them (checked in Stage 2.1).

    Generated by RJC and Claude.
    """

    def __getitem__(self, key: str) -> Any:
        if key in self.__dataclass_fields__:
            return getattr(self, key)
        raise KeyError(key)

    def __setitem__(self, key: str, value: Any) -> None:
        if key not in self.__dataclass_fields__:
            raise KeyError(key)
        setattr(self, key, value)

    def keys(self):
        return list(self.__dataclass_fields__)

    def __contains__(self, key: str) -> bool:
        return key in self.__dataclass_fields__


@dataclass
class RunConfig(_DictLike):
    """The ``run`` settings section."""

    last_update: str = _s(
        "Last updated 27th May 2024", "Not used (when the settings were last revised)."
    )
    atomic: str = _s(
        "atomic.ecsv", "The atomic data file (one shipped with ALIS, or a path)."
    )
    datadirc: str = _s("", "The folder of the data files, relative to the model.")
    modname: str = _s(
        "model.mod", "The model file's name; ALIS sets it when the model is run."
    )
    convergence: bool = _s(
        False, "After the fit, check that it has converged (run convcriteria)."
    )
    convnostop: bool = _s(False, "Keep checking the convergence until it is reached.")
    convcriteria: float = _s(
        0.2, "Converged: no parameter changes by this many of its 1σ errors."
    )
    datatype: str = _s(
        "default", "The data files' format: default, HIRESredux or UVESpopler."
    )
    limpar: bool = _s(
        False, "Move starting values that lie outside their limits onto them."
    )
    ncpus: int = _s(-1, "CPUs to use: a number, -1 for all bar one, -2 all bar two.")
    # 0 uses the CPU (was None; settings.alis said 0 -- Q6.21)
    ngpus: int = _s(0, "GPUs to use; 0 uses the CPU (see run backend).")
    # Stage 4.3a: which parallel backend computes the Jacobian -- "cpu", "gpu",
    # or "auto" (time one Jacobian on each and commit the fit to the faster).
    # Force cpu/gpu for reproducibility: auto's choice can vary run to run when
    # the two are close, which flips CPU-bitwise vs GPU-1e-12 numerics.
    backend: str = _s(
        "auto", "What computes the Jacobian: cpu, gpu, or auto (the faster)."
    )
    # Stage 4.3: minimum sub-pixels x profile rows for a model component group
    # to be sent to the GPU (below it, the launch costs more than the kernel
    # saves and the CPU path is used). Ignored unless ngpus > 0.
    gputhresh: int = _s(
        10000, "Smallest model group (sub-pixels × profiles) sent to a GPU."
    )
    # Stage 4.5: hand the derivative workers their read-only arrays through
    # shared memory instead of pickling a copy per chunk. Set False if the
    # machine has little /dev/shm (a container's default is 64 MB); the fit
    # then behaves exactly as it did before 4.5, and falls back automatically
    # if a segment cannot be created anyway.
    shmem: bool = _s(True, "Share the workers' read-only arrays through /dev/shm.")
    nsubpix: int = _s(5, "Sub-pixel oversampling, for integrating the profiles.")
    nsubmin: int = _s(5, "The fewest sub-pixels per pixel.")
    nsubmax: int = _s(21, "The most sub-pixels per pixel.")
    warn_subpix: int = _s(
        100, "Warn when a snip needs more sub-pixels per pixel than this."
    )
    renew_subpix: bool = _s(False, "Work out the sub-pixels again at every evaluation.")
    blind: bool = _s(True, "Blind analysis: no best-fit value is shown or written.")
    bintype: str = _s(
        "km/s", "The pixels' binning, unless a data line says: km/s, A or Hz."
    )
    logn: bool = _s(True, "Not used.")
    capvalue: Optional[float] = _s(None, "Cap the model at this value (None: no cap).")
    # Stage 3.1/3.4: reuse unchanged model components in derivatives
    cache: bool = _s(
        True, "Reuse unchanged model components when computing derivatives."
    )


@dataclass
class ChisqConfig(_DictLike):
    """The ``chisq`` settings section."""

    miniter: int = _s(0, "The fewest iterations before the fit may stop.")
    # maxiter and fstep are the values the shipped settings.alis carried, not the
    # ones this dataclass used to declare (20000 and 1.0). Until Stage 6.1 the
    # file was read over the dataclass on every run, so the file's values were
    # what every fit actually used and these were documentation that lied. The
    # file is gone; these are now the single source of truth (Q6.21).
    maxiter: int = _s(2000, "The most iterations; the fit stops there.")
    atol: float = _s(
        1.0e-10, "Stop when an iteration reduces χ² by less than this fraction."
    )
    xtol: float = _s(
        1.0e-10, "Stop when the parameters change by at most this fraction."
    )
    ftol: float = _s(
        1.0e-10, "Stop when actual and predicted reductions of χ² are at most this."
    )
    gtol: float = _s(
        1.0e-10, "Stop when the residuals are this near orthogonal to the Jacobian."
    )
    # factor above machine precision for the derivative step
    fstep: float = _s(20.0, "The derivative step, as a factor above machine precision.")


