"""Typed configuration dataclasses for ALIS (Stage 2.1).

The ``argflag`` settings structure -- historically a nested string-keyed
dict of dicts built in ``load.load_settings`` -- is represented here as
typed dataclasses. To keep the Stage 0 regression suite green while the
rest of the code base still uses ``argflag['section']['key']`` syntax, the
dataclasses expose dict-like access through :class:`_DictLike` (Q2.3:
incremental migration with dict-style access during the transition).

Field names, default values and default types mirror the original
``initialise()`` defaults exactly, so settings-file parsing
(``load.set_params``), which introspects value types, is unchanged.

Generated by RJC and Claude.
"""

from dataclasses import dataclass, field
from typing import Any, Optional


class _DictLike:
    """Mixin giving a dataclass ``d['key']`` access during the migration.

    Only the operations the code base actually performs on ``argflag`` are
    implemented: subscripted get/set, ``keys()`` and ``in`` membership.
    Iteration and ``.items()``/``.values()`` are intentionally omitted --
    nothing uses them (checked in Stage 2.1).

    Generated by RJC and Claude.
    """

    def __getitem__(self, key: str) -> Any:
        if key in self.__dataclass_fields__:
            return getattr(self, key)
        raise KeyError(key)

    def __setitem__(self, key: str, value: Any) -> None:
        if key not in self.__dataclass_fields__:
            raise KeyError(key)
        setattr(self, key, value)

    def keys(self):
        return list(self.__dataclass_fields__)

    def __contains__(self, key: str) -> bool:
        return key in self.__dataclass_fields__


@dataclass
class RunConfig(_DictLike):
    """The ``run`` settings section."""

    prognm: str = "alis.py"
    last_update: str = "Last updated 27th May 2024"
    atomic: str = "atomic.xml"
    datadirc: str = ""
    modname: str = "model.mod"
    convergence: bool = False
    convnostop: bool = False
    convcriteria: float = 0.2
    datatype: str = "default"
    limpar: bool = False
    ncpus: int = -1
    ngpus: Optional[int] = None
    # Stage 4.3a: which parallel backend computes the Jacobian -- "cpu", "gpu",
    # or "auto" (time one Jacobian on each and commit the fit to the faster).
    # Force cpu/gpu for reproducibility: auto's choice can vary run to run when
    # the two are close, which flips CPU-bitwise vs GPU-1e-12 numerics.
    backend: str = "auto"
    # Stage 4.3: minimum sub-pixels x profile rows for a model component group
    # to be sent to the GPU (below it, the launch costs more than the kernel
    # saves and the CPU path is used). Ignored unless ngpus > 0.
    gputhresh: int = 10000
    nsubpix: int = 5
    nsubmin: int = 5
    nsubmax: int = 21
    warn_subpix: int = 100
    renew_subpix: bool = False
    blind: bool = True
    bintype: str = "km/s"
    logn: bool = True
    capvalue: Optional[float] = None
    cache: bool = True  # Stage 3.1/3.4: reuse unchanged model components in derivatives


