    continuum: int = -1
    zerolevel: int = -1
    systematics: int = -1
    fitrange: int = -1
    loadrange: int = -1
    resolution: int = -1
    # A bad-pixel mask: 1 marks a pixel that is never fitted (dashboard Q4.17)
    badpix: int = -1


