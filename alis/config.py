@dataclass
class PlotScriptConfig(_DictLike):
    """The ``plotscript`` settings section (Stage 5.3).

    Controls the standalone matplotlib script ALIS can emit alongside the fit,
    so a publication figure can be tweaked outside ALIS. ``format`` selects the
    layout and defaults to ``none``, which emits nothing; every other setting
    defaults to the convention of the reference figures in ``context/plotting``,
    so an emitted script is unchanged unless it is asked for.

    Fields that must accept both a word and a number (``numcol``) or a word and
    a list (``velrange``, ``ylim``, ``figsize``) default to ``None``, because
    ``load.set_params`` converts a setting by the *type of its default* and only
    the ``None`` branch infers int/float/list/str. ``None`` means "auto".

    Generated by RJC and Claude.
    """

    # none | metals | DH
    format: str = _s(
        "none", "Write a matplotlib script of the fit: none, metals or DH."
    )
    # auto, or an integer
    numcol: Optional[Any] = _s(
        None, "The script's columns of panels: auto, or a number."
    )
    residuals: bool = _s(False, "The script draws the residuals.")
    # auto, or e.g. -150,150
    velrange: Optional[Any] = _s(
        None, "The script's velocity range: auto, or e.g. -150,150."
    )
    # auto, or e.g. -0.15,1.3
    ylim: Optional[Any] = _s(None, "The script's y range: auto, or e.g. -0.15,1.3.")
    # auto, or e.g. 7.0,4.5
    figsize: Optional[Any] = _s(
        None, "The script's figure size in inches: auto, or e.g. 7.0,4.5."
    )
    fontsize: float = _s(11.0, "The script's font size, in points.")
    labels: bool = _s(True, "The script labels the panels.")
    # default: <model>.mod.plot.py
    filename: str = _s("", "The script's file name (empty: <model>.mod.plot.py).")
    overwrite: bool = _s(False, "Overwrite an existing script.")


