"""ALIS logging (Stage 2.5) -- replaces alis/almsgs.py.

:class:`AlisLogger` is a :class:`logging.Logger` subclass that keeps ALIS's
historical ``msgs`` API (``info`` / ``warn`` / ``error`` / ``bug`` / ``work`` /
``simulate`` / ``test`` / ``newline`` / ``indent`` / ``input`` /
``alisheader`` / ``signal_handler``) while routing everything through stdlib
``logging`` (real levels, handlers and formatters). The console format keeps
ALIS's coloured ``[LEVEL] ::`` prefixes via :class:`AlisFormatter`, using custom
levels for the SIMULATE / TEST / BUG / PROGRESS bands.

Behaviour preserved from ``almsgs``:

- ``error()`` prints ``[ERROR]`` then calls ``sys.exit()`` -- it is control
  flow, not just a message (Q2.6).
- ``newline()`` / ``indent()`` return the continuation-indent strings that are
  embedded inside message text throughout the code base.

Multiprocessing-aware: :func:`msgs` configures the ``"alis"`` logger with a
stderr handler in *every* process. Spawned ``Pool`` workers re-import this
module and reconfigure, so log records emitted inside worker processes are
emitted (survive) rather than dropped by the default handler-less logger.

Generated by RJC and Claude.
"""

import logging
import sys

# --- custom levels for the ALIS message bands -------------------------------
# Chosen so the default level (see set_verbosity) shows the same messages as
# the old msgs did. PROGRESS (work) sits below INFO (dev reminders); SIMULATE
# and TEST just above INFO; BUG just below CRITICAL.
PROGRESS = 15
TEST = 24
SIMULATE = 25
BUG = 45
logging.addLevelName(PROGRESS, "PROGRESS")
logging.addLevelName(TEST, "TEST")
logging.addLevelName(SIMULATE, "SIMULATE")
logging.addLevelName(BUG, "BUG")


class Colors:
    """ANSI colour codes for coloured console text (as in the old almsgs)."""

    start = "\x1B["
    end = "\x1B[" + "0m"
    black_CL = "1;30m"
    blue_CL = "1;34m"
    yellow_CL = "1;33m"
    green_CL = "1;32m"
    red_CL = "1;31m"
    purple_CL = "1;35m"
    white_RD = "1;37;41m"
    white_GR = "1;37;42m"
    white_BK = "1;37;40m"
    white_BL = "1;37;44m"


def _band(colour, label):
    """Build a coloured ``[LABEL]`` prefix in the historical ALIS style."""
    return Colors.start + colour + label + Colors.end + " "


# level name -> coloured prefix (reproduces almsgs exactly)
_PREFIX = {
    "INFO": _band(Colors.green_CL, "[INFO]    ::"),
    "WARNING": _band(Colors.red_CL, "[WARNING] ::"),
    # error prefix historically began with a newline
    "ERROR": "\n" + _band(Colors.white_RD, "[ERROR]   ::"),
    "SIMULATE": _band(Colors.white_BL, "[SIMULATE]::"),
    "TEST": _band(Colors.white_BL, "[TEST]    ::"),
    "BUG": _band(Colors.white_BK, "[BUG]     ::"),
    # work() historically printed a two-line [WORK IN ] / [PROGRESS] banner
    "PROGRESS": (Colors.start + Colors.black_CL + "[WORK IN ]::" + Colors.end
                 + "\n" + _band(Colors.yellow_CL, "[PROGRESS]::")),
}


class AlisFormatter(logging.Formatter):
    """Render records with ALIS's coloured ``[LEVEL] ::`` prefixes."""

    def format(self, record):
        prefix = _PREFIX.get(record.levelname,
                             _band(Colors.green_CL, "[%s] ::" % record.levelname))
        return prefix + record.getMessage()


class AlisLogger(logging.Logger):
    """A logging.Logger that also speaks the historical ``msgs`` API."""

    def _emit(self, level, msg):
        if self.isEnabledFor(level):
            # () = no %-args; ALIS messages are always pre-formatted.
            self._log(level, msg, ())

    # -- message bands (verbose kwarg kept for call-site compatibility) ------
    def info(self, msg, verbose=None):
        self._emit(logging.INFO, msg)

    def warn(self, msg, verbose=None):
        self._emit(logging.WARNING, msg)

    def simulate(self, msg, verbose=None):
        self._emit(SIMULATE, msg)

    def test(self, msg, verbose=None):
        self._emit(TEST, msg)

    def bug(self, msg, verbose=None):
        self._emit(BUG, msg)

    def work(self, msg, verbose=None):
        self._emit(PROGRESS, msg)

    def error(self, msg, verbose=None):
        # Preserve almsgs semantics: report then terminate (Q2.6). Emit at
        # CRITICAL so it is never filtered by the configured level; the
        # formatter renders the [ERROR] prefix for CRITICAL records.
        self._emit(logging.CRITICAL, msg)
        sys.exit()

    # -- inline string helpers (embedded inside message text) ---------------
    def newline(self, verbose=None):
        return "\n             "

    def indent(self, verbose=None):
        return "             "

    def input(self):
        return Colors.start + Colors.blue_CL + "[INPUT]   ::" + Colors.end + " "

    # -- misc -----------------------------------------------------------------
    def alisheader(self, prognm, verbose=2):
        header = "##  "
        header += Colors.start + Colors.white_GR + "ALIS : "
        header += "Absorption LIne Software v1.0" + Colors.end + "\n"
        header += "##  "
        header += "Usage : "
        header += "python %s [options] model.mod" % (prognm)
        return header

    def signal_handler(self, signalnum, handler):
        if signalnum == 2:
            self.info("Ctrl+C was pressed. Ending processes...")
            sys.exit()


# The error band must render its own [ERROR] prefix even though it is emitted at
# CRITICAL level, so give CRITICAL the ERROR prefix.
_PREFIX["CRITICAL"] = _PREFIX["ERROR"]


def msgs():
    """Return the shared, configured ``"alis"`` :class:`AlisLogger`.

    Idempotent and per-process: the first call in any process (including a
    spawned ``Pool`` worker) attaches a stderr handler so records survive.

    Generated by RJC and Claude.
    """
    logging.setLoggerClass(AlisLogger)
    try:
        log = logging.getLogger("alis")
    finally:
        logging.setLoggerClass(logging.Logger)
    if not getattr(log, "_alis_configured", False):
        handler = logging.StreamHandler(sys.stderr)
        handler.setFormatter(AlisFormatter())
        log.addHandler(handler)
        log.setLevel(logging.DEBUG)  # default: show all bands (as msgs did)
        log.propagate = False
        log._alis_configured = True
    return log


def set_verbosity(verbose):
    """Set the console level from an ALIS verbosity (0/1/2).

    0 -> WARNING, 1 -> INFO, 2 -> DEBUG (show everything, incl. PROGRESS).
    Anything else leaves the level unchanged. ``error``/``bug`` (>= ERROR)
    always show.

    Generated by RJC and Claude.
    """
    mapping = {0: logging.WARNING, 1: logging.INFO, 2: logging.DEBUG}
    level = mapping.get(verbose)
    if level is not None:
        msgs().setLevel(level)
