"""Where a fit's output files go (dashboard Stage 1.4).

Every output ALIS writes after a fit -- the ``.mod.out``, the ``_fit.dat`` files,
the covariance matrix and its image, the report, the PDF, the plotting script and
the convergence files -- is opened through one writer, held by the fit as
``slf._outputs``. There are two kinds:

``DiskOutputs``
    The default. Files are written to disk exactly as ALIS always has, and the
    callers still ask before overwriting a file unless ``out overwrite`` is set.
``MemoryOutputs``
    Used when a project bundle is run (``run_alis project.model``). Files are
    kept in memory by path and never prompt; a file written twice is replaced.
    The bundle stores them afterwards, so nothing is written to disk (D9).

Some outputs reveal blinded values. A writer is told which, with ``hide``, so
that a bundle can store them hidden. On disk, a blind run never writes them in
the first place (``load.check_argflag``), so ``hide`` does nothing there.

Generated by RJC and Claude.
"""

import io
import os


class DiskOutputs:
    """
    Write output files to disk (the default).

    Generated by RJC and Claude.
    """

    in_memory = False

    def exists(self, path):
        """Whether ``path`` already exists, so the caller may ask first."""
        return os.path.exists(path)

    def open(self, path, mode="w"):
        """Open ``path`` for writing, in text ("w") or binary ("wb") mode."""
        return open(path, mode)

    def remove(self, path):
        """Remove ``path``."""
        os.remove(path)

    def rename(self, src, dst):
        """Rename ``src`` to ``dst``."""
        os.rename(src, dst)

    def hide(self, path, lines=None):
        """Nothing to do on disk: a blind run does not write these outputs."""
        return None


class _MemoryText(io.StringIO):
    """A text file that hands its contents to a ``MemoryOutputs`` when closed."""

    def __init__(self, owner, key):
        super().__init__()
        self._owner, self._key = owner, key

    def close(self):
        if not self.closed:
            text = self.getvalue()
            self._owner.files[self._key] = text.encode("utf-8")
            self._owner.hide_secret_lines(self._key, text)
        super().close()


class _MemoryBinary(io.BytesIO):
    """A binary file that hands its contents to a ``MemoryOutputs`` when closed."""

    def __init__(self, owner, key):
        super().__init__()
        self._owner, self._key = owner, key

    def close(self):
        if not self.closed:
            self._owner.files[self._key] = self.getvalue()
        super().close()


class MemoryOutputs:
    """
    Keep output files in memory, by path (for a project bundle).

    Attributes
    ----------
    files : dict
        Normalised path, relative to the directory the fit runs in, to the
        file's bytes.
    hidden : dict
        Path to the outputs that reveal blinded values: ``None`` when the whole
        file is hidden, or the set of its line numbers (from 0) that are.
    secret_lines : list of str
        The hidden lines of the model that was run. Any line of a text output
        that repeats one (such as the copy of the input model at the end of a
        ``.mod.out``) is hidden as well.

    Generated by RJC and Claude.
    """

    in_memory = True

    def __init__(self, secret_lines=()):
        self.files = {}
        self.hidden = {}
        self.secret_lines = [ln.strip() for ln in secret_lines if ln.strip()]

    def hide_secret_lines(self, path, text):
        """Hide every line of ``text`` that repeats a hidden model line."""
        if not self.secret_lines:
            return
        lines = [num for num, line in enumerate(text.split("\n"))
                 if any(secret in line for secret in self.secret_lines)]
        if lines:
            self.hide(path, lines=lines)

    @staticmethod
    def key(path):
        """The normalised form of ``path`` under which a file is kept."""
        return os.path.normpath(path)

    def exists(self, path):
        """Never true: a run's outputs replace the previous run's, unasked."""
        return False

    def open(self, path, mode="w"):
        """A file-like object whose contents are kept when it is closed."""
        if mode not in ("w", "wb"):
            raise ValueError("MemoryOutputs only writes new files, not mode " + mode)
        key = self.key(path)
        if mode == "w":
            return _MemoryText(self, key)
        return _MemoryBinary(self, key)

    def remove(self, path):
        """Forget ``path``, if it was written."""
        self.files.pop(self.key(path), None)
        self.hidden.pop(self.key(path), None)

    def rename(self, src, dst):
        """Keep the file written as ``src`` under ``dst`` instead."""
        src, dst = self.key(src), self.key(dst)
        self.files[dst] = self.files.pop(src)
        if src in self.hidden:
            self.hidden[dst] = self.hidden.pop(src)

    def hide(self, path, lines=None):
        """
        Mark ``path`` as revealing blinded values.

        Parameters
        ----------
        path : str
            The output file.
        lines : iterable of int, optional
            The line numbers (from 0) that reveal them. None hides the whole file.
        """
        key = self.key(path)
        if lines is None:
            self.hidden[key] = None
        elif self.hidden.get(key, set()) is not None:
            self.hidden[key] = set(self.hidden.get(key, set())) | set(lines)


_DISK = DiskOutputs()


def of(slf):
    """
    The writer a fit's outputs go through: ``slf._outputs``, or the disk.

    Generated by RJC and Claude.
    """
    return getattr(slf, "_outputs", None) or _DISK
