"""Convert an ALIS VOTable atomic-data file (``atomic.xml``) to ECSV.

ALIS reads ``alis/data/atomic.ecsv`` by default from Stage 5.2 onwards. The
VOTable format is still accepted so an existing ``.xml`` keeps working, but it
is deprecated: run this script once to bring your own file forward, or ask RJC
to fold the new transitions into the shipped ``atomic.ecsv``.

ECSV was chosen because it is plain text with a self-describing header, so the
table can be read and edited without a VOTable parser, and there is no
hand-maintained ``nrows`` attribute to fall out of step with the data.

Usage
-----
    python convert_xmlFormat_to_ecsvFormat.py atomic.xml atomic.ecsv

    # ...and, for the shipped file, appending specific transitions from a
    # second VOTable (Stage 5.2 used this for 15 3He I lines):
    python convert_xmlFormat_to_ecsvFormat.py atomic.xml atomic.ecsv \
        --append-from other.xml --append-wave 515.644042,522.240605,...

Every value is transcribed unchanged. The conversion is checked cell by cell
against the source afterwards and the script fails loudly if anything differs,
because a silent transcription error in the atomic data would corrupt every fit
that uses the affected transition.

Generated by RJC and Claude.
"""

import argparse
import os
import re
import sys
import warnings

import numpy as np
from astropy.table import Column, Table, vstack


def _alis_validation():
    """The loader's validation helpers, imported on demand.

    They live with the loader so ALIS and this script apply the same rules and
    the unit tests can exercise them directly. Imported here rather than at
    module scope so that running the script from inside ``alis/data/`` -- which
    is not on the path as a package -- still works.
    """
    repo = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
    if repo not in sys.path:
        sys.path.insert(0, repo)
    from alis.load import ATOMIC_COLUMNS, duplicate_transitions

    return ATOMIC_COLUMNS, duplicate_transitions


# The unit strings are taken verbatim from the VOTable's FIELD attributes
# rather than from astropy's parsed `field.unit`, which normalises them:
# "1.66053886x10-24g" comes back as "1.66054e-24 g", losing digits from what
# is meant to be documentation of the file's own convention. ECSV stores an
# unrecognised unit string as written and reads it back unchanged, so the
# original survives the round trip.
_FIELD_RE = re.compile(r"<FIELD\b[^>]*\bname=\"([^\"]+)\"[^>]*>", re.IGNORECASE)
_UNIT_RE = re.compile(r"\bunit=\"([^\"]*)\"", re.IGNORECASE)


def verbatim_units(xml_path):
    """Map column name -> the ``unit`` string exactly as the VOTable spells it.

    Columns with no ``unit`` attribute are absent from the mapping.
    """
    with open(xml_path, encoding="utf-8", errors="replace") as fil:
        text = fil.read()
    units = {}
    for match in _FIELD_RE.finditer(text):
        tag = match.group(0)
        name = match.group(1)
        unit = _UNIT_RE.search(tag)
        if unit is not None:
            units[name] = unit.group(1)
    return units


def read_votable(xml_path):
    """Read a VOTable into a Table, preserving names, dtypes and unit strings."""
    from astropy.io.votable import parse_single_table

    with warnings.catch_warnings():
        # VOTables in the wild trip a lot of spec-conformance warnings; they
        # say nothing about the values, which is all this script transcribes.
        warnings.simplefilter("ignore")
        votable = parse_single_table(xml_path)
    arr = votable.array
    units = verbatim_units(xml_path)

    columns = []
    for field in votable.fields:
        name = field.name
        data = arr[name]
        if data.dtype.kind in ("O", "S", "U"):
            # char columns arrive as object arrays of bytes or str
            data = np.array(
                [d.decode() if isinstance(d, bytes) else str(d) for d in data]
            )
        col = Column(data, name=name, description=field.description)
        if name in units:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                col.unit = units[name]
        columns.append(col)
    return Table(columns)


def select_waves(table, waves, rtol=0.0, atol=1.0e-9):
    """Rows whose ``RestWave`` matches one of ``waves``.

    Errors if any requested wavelength matches other than exactly one row --
    appending the wrong transition, or silently appending none, is precisely
    the failure this script exists to prevent.
    """
    keep = []
    for want in waves:
        hit = np.where(np.isclose(table["RestWave"], want, rtol=rtol, atol=atol))[0]
        if hit.size != 1:
            raise SystemExit(
                f"--append-wave {want!r} matched {hit.size} rows, expected exactly 1"
            )
        keep.append(int(hit[0]))
    return table[keep]


def write_ecsv(table, path):
    """Write ECSV with the data columns padded so they line up.

    ECSV's space delimiter tolerates runs of spaces, so alignment costs nothing
    at read time and makes the table readable in a plain editor -- which is the
    reason for moving off VOTable in the first place.
    """
    import io

    buf = io.StringIO()
    table.write(buf, format="ascii.ecsv", overwrite=True)
    lines = buf.getvalue().splitlines()
    header = [ln for ln in lines if ln.startswith("#")]
    body = [ln.split() for ln in lines if not ln.startswith("#")]
    if body:
        widths = [max(len(row[i]) for row in body) for i in range(len(body[0]))]
        body = [
            " ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)).rstrip()
            for row in body
        ]
    with open(path, "w", encoding="utf-8") as fil:
        fil.write("\n".join(header + body) + "\n")


def cells_equal(a, b):
    """Exact equality, treating NaN as equal to NaN (the file uses NaN freely)."""
    if isinstance(a, (float, np.floating)) and isinstance(b, (float, np.floating)):
        return (a == b) or (np.isnan(a) and np.isnan(b))
    return a == b


def verify(ecsv_path, expected):
    """Re-read the written ECSV and compare it cell by cell with ``expected``."""
    got = Table.read(ecsv_path, format="ascii.ecsv")
    problems = []
    if len(got) != len(expected):
        problems.append(f"row count {len(got)} != {len(expected)}")
    if list(got.colnames) != list(expected.colnames):
        problems.append(f"columns {got.colnames} != {expected.colnames}")
    if problems:
        return problems
    for name in expected.colnames:
        for i, (x, y) in enumerate(zip(got[name], expected[name])):
            if not cells_equal(x, y):
                problems.append(f"row {i}, column {name}: {x!r} != {y!r}")
                if len(problems) > 20:
                    problems.append("... further differences suppressed")
                    return problems
    return problems


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("xml", help="input VOTable, e.g. atomic.xml")
    parser.add_argument("ecsv", help="output ECSV, e.g. atomic.ecsv")
    parser.add_argument(
        "--append-from", metavar="XML", help="a second VOTable to take extra rows from"
    )
    parser.add_argument(
        "--append-wave",
        metavar="W1,W2,...",
        help="comma-separated RestWave values to take from --append-from",
    )
    args = parser.parse_args(argv)

    table = read_votable(args.xml)
    nbase = len(table)
    print(f"read {nbase} rows from {args.xml}")

    nextra = 0
    if args.append_from or args.append_wave:
        if not (args.append_from and args.append_wave):
            parser.error("--append-from and --append-wave must be given together")
        waves = [float(w) for w in args.append_wave.split(",") if w.strip()]
        extra = select_waves(read_votable(args.append_from), waves)
        nextra = len(extra)
        table = vstack([table, extra], join_type="exact")
        print(f"appended {nextra} rows from {args.append_from}")

    write_ecsv(table, args.ecsv)
    print(f"wrote {len(table)} rows to {args.ecsv}")

    problems = verify(args.ecsv, table)
    if problems:
        print("\nVERIFICATION FAILED -- the ECSV does not match the source:")
        for line in problems:
            print(f"    {line}")
        return 1
    print(f"verified {len(table)} rows x {len(table.colnames)} columns, all identical")

    atomic_columns, duplicate_transitions = _alis_validation()
    missing = [c for c in atomic_columns if c not in table.colnames]
    if missing:
        print(f"\nWARNING: ALIS also needs these columns: {', '.join(missing)}")

    # Reported, never modified -- genuine isotope structure is indistinguishable
    # from a mislabelling here, so it needs a person to look. The shipped file
    # has four legitimate groups (6/7Li, 12/13C, 54/56/57/58Fe).
    dupes = duplicate_transitions(table)
    if dupes:
        print(f"\n{len(dupes)} transition(s) appear under more than one MassNumber.")
        print("Check these are real isotopes and not the same line entered twice:")
        for element, ion, wave, mnums in dupes:
            print(
                f"    {element:4s} {ion:4s} {wave:14.4f}   MassNumber "
                f"{', '.join(str(m) for m in mnums)}"
            )
    return 0


if __name__ == "__main__":
    sys.exit(main())
