class _ListSettings(argparse.Action):
    """``--list-settings``: print every setting and exit (Stage 6.1, Q6.24).

    The defaults live in ``alis.config.ArgFlag`` and nowhere else since the
    shipped ``settings.alis`` was removed (Q6.21), so this is generated from the
    dataclass and cannot go stale. It works from an installed wheel, with no
    source checkout to read.

    Generated by RJC and Claude.
    """

    def __init__(self, option_strings, dest, **kwargs):
        super().__init__(option_strings, dest, nargs=0, **kwargs)

    def __call__(self, parser, namespace, values, option_string=None):
        from alis.config import ArgFlag

        cfg = ArgFlag()
        print("ALIS settings. Put any of these in the 'par' block of a model")
        print("file, or pass them on the command line as --set 'section key value'.")
        for section in cfg.keys():
            print("\n[{0:s}]".format(section))
            for key in cfg[section].keys():
                print("  {0:<14s} {1!r}".format(key, cfg[section][key]))
        parser.exit()


def _description():
    """The `--help` preamble: name, version, and nothing that lies.

    Colour is applied only when stdout is a terminal -- the banner used to embed
    ANSI escapes unconditionally, so they appeared literally whenever `--help`
    was piped or redirected. The version comes from `alis.__version__` rather
    than the hard-coded "v1.0" the banner carried (Stage 6.1, Q6.19).

    Generated by RJC and Claude.
    """
    import alis

    title = "ALIS : Absorption LIne Software v{0:s}".format(alis.__version__)
    if sys.stdout.isatty():
        from alis.logger import Colors

        title = Colors.start + Colors.white_GR + title + Colors.end
    return title


def parser(options=None):
    parser = argparse.ArgumentParser(
        prog="run_alis",
        description=_description(),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("alis_modfile", type=str, help="ALIS model file (.mod)")
    parser.add_argument("-c", "--cpus", type=int, help="(all but one) number of CPU cores to use")
    # The count is required, not optional: with nargs="?" a bare `-g` swallows
    # the model file ("invalid int value: 'fit.mod'"), because argparse cannot
    # tell an optional value from the positional (Stage 6.1).
    parser.add_argument("-g", "--ngpus", type=int, metavar="N",
                        help="number of GPUs to use (0 uses the CPU)")
    parser.add_argument("-p", "--plot", type=str,
                        help="(3x3) plot model fits with MxN panels; use -p 0 for no screen plots")
    parser.add_argument("-x", "--xaxis", type=int, choices=[0, 1, 2],
                        help="(0) plot observed [0] or rest [1] wavelength, or velocity [2]")
    parser.add_argument("-j", "--justplot", default=False, action="store_true",
                        help="plot the data and the input model without fitting")
    parser.add_argument("-l", "--labels", default=False, action="store_true",
                        help="label the absorption components when plotting")
    parser.add_argument("-v", "--verbose", type=int, choices=[0, 1, 2],
                        help="(2) level of screen output")
    parser.add_argument("-q", "--quiet", default=False, action="store_true",
                        help="only warnings and errors (same as -v 0)")
    parser.add_argument("-a", "--repeat", type=int, help="repeat the fit N times")
    parser.add_argument("-r", "--random", type=int, help="number of random simulations to perform")
    parser.add_argument("-s", "--startid", type=int, help="starting ID for the simulations")
    parser.add_argument("-f", "--fits", default=False, action="store_true",
                        help="write the data and best-fit model to *_fit.dat files")
    parser.add_argument("-m", "--model", default=False, action="store_true",
                        help="write the best-fitting model file (.mod.out)")
    parser.add_argument("-o", "--outname", type=str, default=None,
                        help="name for the output model file")
    parser.add_argument("-w", "--writeover", default=False, action="store_true",
                        help="overwrite existing output files without asking")
    # Any setting at all, so the command line cannot fall behind the config the
    # way it did through Stages 4 and 5 (Q6.7). Repeatable.
    parser.add_argument("--set", action="append", metavar="'section key value'",
                        help="set any setting, e.g. --set 'run backend cpu'; repeatable")
    parser.add_argument("--list-settings", action=_ListSettings,
                        help="print every available setting with its default, and exit")

    if options is None:
        pargs = parser.parse_args()
    else:
        pargs = parser.parse_args(options)
    #
    return pargs

def main(args):
    from alis import logger
    from alis import load
    from alis import main as alismain
    msgs = logger.msgs()

    msgs.work("Read in resolution from column of data",verbose=2)
    msgs.work("With voigt function, if the user says to put an O I profile in specid A, make sure there is actually an O I line in specid A.",verbose=2)
    msgs.work("Prepare a separate .py file for user-created functions",verbose=2)
    msgs.work("Assign a number to every warning and error -- describe this in the manual",verbose=2)
    msgs.work("If emission is not specified for a specid before absorption (in a model with several specid's), the specid printed as an error is always one before",verbose=2)
    # The settings the command line changed, so the writer can record them in
    # the .mod.out and a re-run of that file reproduces this one (Q6.12/Q6.20).
    overrides = []
    argflag = load.optarg(argv=args, overrides=overrides)
    # The model file comes from the parser, not from sys.argv[-1]: the latter is
    # only the model file when no option follows it, so 'run_alis fit.mod -w'
    # used to try to fit a file called '-w' (Stage 6.1). argparse has already
    # validated and bound the positional, so use what it bound.
    argflag['run']['modname'] = args.alis_modfile
    alismain.ClassMain(argflag, cli_overrides=overrides)


def console_entry():
    """Console-script entry point for ``run_alis``.

    Zero-argument wrapper used by the ``[project.scripts]`` entry in
    pyproject.toml: parse the command line then run the fit. Replaces the
    former bin/run_alis script.

    Generated by RJC and Claude.
    """
    args = parser()
    main(args)


if __name__ == "__main__":
    # Executed directly as a script (e.g. by the regression harness,
    # which runs this file to guarantee it exercises this checkout).
    # Clearing __spec__ mirrors the historical bin/run_alis launcher and
    # avoids a multiprocessing 'spawn' re-import issue.
    __spec__ = None
    console_entry()

