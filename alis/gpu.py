"""GPU backend detection and device selection (Stage 4.1).

ALIS runs on the CPU by default. GPU support is an optional install extra
(``pip install alis[gpu]``), which pulls in ``numba``; the CUDA toolkit itself
must come from the user's own driver/toolkit installation -- it is not
pip-installed by the extra.

**Nothing here imports numba at module scope.** Every ``numba``/CUDA import
happens lazily, inside the functions below, and only when the GPU backend is
actually being probed or selected. A CPU-only install therefore never imports
numba and needs no CUDA toolchain, which is the Stage 4 requirement (plan Q4;
stage doc Task 4.1).

Every entry point is safe to call on a machine with no GPU, no CUDA driver and
no numba installed: they report unavailability rather than raising, so the
caller can fall back to the CPU with a clear message.

Generated by RJC and Claude.
"""

import importlib.util
import sys

from alis import logger

msgs = logger.msgs()

# Cached probe result: (n_devices, reason). ``None`` means "not probed yet".
# The probe imports numba and initialises a CUDA context, which is slow, so it
# is done at most once per process.
_PROBE = None

# The "you have GPUs but are not using them" notice (Q4.10) is printed at most
# once per process -- ``resolve_backend`` is called once per ``alfit``, and a
# single ALIS run may build several (the fit, the convergence tests, each
# simulation).
_NOTICE_SHOWN = False


def _probe():
    """Detect usable CUDA devices, importing numba lazily.

    Returns
    -------
    tuple[int, str]
        ``(n_devices, reason)``. ``n_devices`` is 0 when the GPU backend is
        unusable, in which case ``reason`` explains why (empty otherwise).

    Generated by RJC and Claude.
    """
    global _PROBE
    if _PROBE is not None:
        return _PROBE
    try:
        from numba import cuda
    except ImportError:
        _PROBE = (0, "numba is not installed (pip install 'alis[gpu]')")
        return _PROBE
    try:
        if not cuda.is_available():
            _PROBE = (0, "no CUDA-capable GPU or driver was detected")
            return _PROBE
        ndev = len(cuda.list_devices())
    except Exception as err:
        # A broken/partial CUDA installation must degrade to CPU, not abort
        # the fit -- hence the deliberately broad except.
        _PROBE = (0, f"CUDA is present but unusable ({err})")
        return _PROBE
    if ndev == 0:
        _PROBE = (0, "no CUDA-capable GPU or driver was detected")
    else:
        _PROBE = (ndev, "")
    return _PROBE


def is_available():
    """Return True if at least one usable CUDA device is present.

    Never raises, and never imports numba on a CPU-only install beyond the
    single guarded attempt in :func:`_probe`.

    Generated by RJC and Claude.
    """
    return _probe()[0] > 0


def device_count():
    """Return the number of usable CUDA devices (0 if the GPU is unavailable).

    Generated by RJC and Claude.
    """
    return _probe()[0]


def unavailable_reason():
    """Return why the GPU backend is unusable, or "" if it is usable.

    Generated by RJC and Claude.
    """
    return _probe()[1]


def select_device(rank, verbose=2):
    """Bind the current process to CUDA device ``rank``.

    Used by the GPU worker processes (Task 4.3), which are sized to ``ngpus``
    with one device bound per worker. CUDA contexts do not survive ``fork``, so
    the workers must be started with the ``spawn`` method and call this in the
    child.

    Parameters
    ----------
    rank : int
        Zero-based device index; must be < :func:`device_count`.
    verbose : int, optional
        ALIS verbosity level for the confirmation message.

    Returns
    -------
    bool
        True if the device was selected; False if the GPU is unavailable or
        ``rank`` is out of range (the caller then falls back to the CPU).

    Generated by RJC and Claude.
    """
    ndev = device_count()
    if ndev == 0:
        msgs.warn("Cannot select a GPU: " + unavailable_reason(), verbose=verbose)
        return False
    if not 0 <= rank < ndev:
        msgs.warn(
            f"GPU rank {rank} is out of range (only {ndev} available)", verbose=verbose
        )
        return False
    from numba import cuda

    cuda.select_device(rank)
    return True


def current_device():
    """Return the CUDA device id bound to this process, or -1 if none is.

    Used by the GPU worker tests to confirm that each worker really did bind a
    distinct device, and useful when diagnosing a multi-GPU run.

    Generated by RJC and Claude.
    """
    if device_count() == 0:
        return -1
    from numba import cuda

    try:
        return int(cuda.current_context().device.id)
    except Exception:
        return -1


def _available_notice(verbose):
    """Tell the user about idle GPUs (Q4.10), at most once per process.

    ALIS stays on the CPU unless ``run ngpus`` is set explicitly (Q4.10), so a
    user on a GPU machine would otherwise never discover that the option
    exists. ``numba`` is looked up with :func:`importlib.util.find_spec`, which
    does *not* import it: on a CPU-only install (no ``gpu`` extra) there is
    nothing to advertise and nothing is imported, preserving the Task 4.1 lazy
    boundary.

    Generated by RJC and Claude.
    """
    global _NOTICE_SHOWN
    if _NOTICE_SHOWN:
        return
    _NOTICE_SHOWN = True
    if "numba" not in sys.modules:
        try:
            if importlib.util.find_spec("numba") is None:
                return
        except (ImportError, ValueError):
            # No numba, or something unimportable sitting under that name.
            return
    ndev = device_count()
    if ndev == 0:
        return
    msgs.info(
        f"{ndev:d} CUDA GPU(s) detected but not in use -- set "
        f"'run ngpus N' (N <= {ndev:d}) to fit on them",
        verbose=verbose,
    )


BACKENDS = ("auto", "cpu", "gpu")


def resolve_backend(backend, ngpus, verbose=2):
    """Choose the parallel backend for one fit (Tasks 4.3 / 4.3a).

    The backend is an **either-or** choice, made once per fit: the Jacobian's
    derivative columns are computed either by the CPU ``Pool`` (sized to
    ``ncpus``) or by the GPU ``Pool`` (sized to ``ngpus``, one device per
    worker), never both (Q4.8). Committing the whole fit to one backend keeps
    it under a single numerical gate.

    ``run backend``:

    ``cpu``
        The CPU Pool, GPUs ignored -- and nothing is probed, so this is also
        the cheapest and the most reproducible setting.
    ``gpu``
        The GPU Pool, on ``ngpus`` devices or on every device present when
        ``ngpus`` is unset.
    ``auto`` (the default)
        CPU unless ``run ngpus`` is explicitly greater than zero (Q4.10); when
        it is, the answer is deferred to a timing probe -- see
        ``alfit._probe_backends``.

    An unusable or under-provisioned GPU degrades to a warning rather than an
    error, so a model file written on a GPU machine still runs everywhere.

    Parameters
    ----------
    backend : str or None
        The ``run backend`` setting; ``None`` is treated as ``"auto"``.
    ngpus : int or None
        The ``run ngpus`` setting. ``None`` or ``<= 0`` means "unset".
    verbose : int, optional
        ALIS verbosity level for the messages.

    Returns
    -------
    tuple[str, int]
        ``("cpu", 0)``, ``("gpu", n)``, or ``("probe", n)`` -- the last meaning
        "run one Jacobian on each backend and keep the faster", with ``n`` the
        number of devices the GPU side would use.

    Generated by RJC and Claude.
    """
    choice = "auto" if backend is None else str(backend).strip().lower()
    if choice not in BACKENDS:
        msgs.warn(
            f"Unknown 'run backend' value {backend!r}; using 'auto' "
            "(choose from " + ", ".join(BACKENDS) + ")",
            verbose=verbose,
        )
        choice = "auto"
    try:
        nreq = 0 if ngpus is None else int(ngpus)
    except (TypeError, ValueError):
        msgs.warn(f"Ignoring unreadable 'run ngpus' value: {ngpus!r}", verbose=verbose)
        nreq = 0

    if choice == "cpu":
        # An explicit choice: say nothing about idle GPUs and do not probe for
        # them either -- this is what the Stage 0 harness sets, and it keeps a
        # CPU-only run free of any CUDA cost (Q4.2).
        if nreq > 0:
            msgs.info(
                f"'run backend cpu' overrides 'run ngpus {nreq:d}'", verbose=verbose
            )
        return "cpu", 0

    if choice == "auto" and nreq <= 0:
        # Q4.10: stay on the CPU until the user asks for GPUs by name.
        _available_notice(verbose)
        return "cpu", 0

    ndev = device_count()
    if ndev == 0:
        asked = "'run backend gpu'" if choice == "gpu" else f"'run ngpus {nreq:d}'"
        msgs.warn(
            f"{asked} was requested but no GPU is usable: " + unavailable_reason(),
            verbose=verbose,
        )
        msgs.info("Falling back to the CPU backend", verbose=verbose)
        return "cpu", 0
    if nreq <= 0:
        # 'backend gpu' with ngpus unset: use every device present.
        nreq = ndev
    elif nreq > ndev:
        msgs.warn(
            f"'run ngpus {nreq:d}' was requested but only {ndev:d} "
            "CUDA GPU(s) are present",
            verbose=verbose,
        )
        nreq = ndev
    if choice == "gpu":
        msgs.info(f"Using the GPU backend on {nreq:d} device(s)", verbose=verbose)
        return "gpu", nreq
    msgs.info(
        f"'run backend auto': will time one Jacobian on the CPU and on "
        f"{nreq:d} GPU(s), then commit the fit to the faster",
        verbose=verbose,
    )
    return "probe", nreq


def reset_probe_cache():
    """Forget the cached probe result so the next call re-detects.

    Only needed by the unit tests, which simulate machines with and without a
    GPU; production code probes once per process.

    Generated by RJC and Claude.
    """
    global _PROBE, _NOTICE_SHOWN
    _PROBE = None
    _NOTICE_SHOWN = False
