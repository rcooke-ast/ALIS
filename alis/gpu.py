"""GPU backend detection and device selection (Stage 4.1).

ALIS runs on the CPU by default. GPU support is an optional install extra
(``pip install alis[gpu]``), which pulls in ``numba``; the CUDA toolkit itself
must come from the user's own driver/toolkit installation -- it is not
pip-installed by the extra.

**Nothing here imports numba at module scope.** Every ``numba``/CUDA import
happens lazily, inside the functions below, and only when the GPU backend is
actually being probed or selected. A CPU-only install therefore never imports
numba and needs no CUDA toolchain, which is the Stage 4 requirement (plan Q4;
stage doc Task 4.1).

Every entry point is safe to call on a machine with no GPU, no CUDA driver and
no numba installed: they report unavailability rather than raising, so the
caller can fall back to the CPU with a clear message.

Generated by RJC and Claude.
"""

from alis import logger

msgs = logger.msgs()

# Cached probe result: (n_devices, reason). ``None`` means "not probed yet".
# The probe imports numba and initialises a CUDA context, which is slow, so it
# is done at most once per process.
_PROBE = None


def _probe():
    """Detect usable CUDA devices, importing numba lazily.

    Returns
    -------
    tuple[int, str]
        ``(n_devices, reason)``. ``n_devices`` is 0 when the GPU backend is
        unusable, in which case ``reason`` explains why (empty otherwise).

    Generated by RJC and Claude.
    """
    global _PROBE
    if _PROBE is not None:
        return _PROBE
    try:
        from numba import cuda
    except ImportError:
        _PROBE = (0, "numba is not installed (pip install 'alis[gpu]')")
        return _PROBE
    try:
        if not cuda.is_available():
            _PROBE = (0, "no CUDA-capable GPU or driver was detected")
            return _PROBE
        ndev = len(cuda.list_devices())
    except Exception as err:
        # A broken/partial CUDA installation must degrade to CPU, not abort
        # the fit -- hence the deliberately broad except.
        _PROBE = (0, f"CUDA is present but unusable ({err})")
        return _PROBE
    if ndev == 0:
        _PROBE = (0, "no CUDA-capable GPU or driver was detected")
    else:
        _PROBE = (ndev, "")
    return _PROBE


def is_available():
    """Return True if at least one usable CUDA device is present.

    Never raises, and never imports numba on a CPU-only install beyond the
    single guarded attempt in :func:`_probe`.

    Generated by RJC and Claude.
    """
    return _probe()[0] > 0


def device_count():
    """Return the number of usable CUDA devices (0 if the GPU is unavailable).

    Generated by RJC and Claude.
    """
    return _probe()[0]


def unavailable_reason():
    """Return why the GPU backend is unusable, or "" if it is usable.

    Generated by RJC and Claude.
    """
    return _probe()[1]


def select_device(rank, verbose=2):
    """Bind the current process to CUDA device ``rank``.

    Used by the GPU worker processes (Task 4.3), which are sized to ``ngpus``
    with one device bound per worker. CUDA contexts do not survive ``fork``, so
    the workers must be started with the ``spawn`` method and call this in the
    child.

    Parameters
    ----------
    rank : int
        Zero-based device index; must be < :func:`device_count`.
    verbose : int, optional
        ALIS verbosity level for the confirmation message.

    Returns
    -------
    bool
        True if the device was selected; False if the GPU is unavailable or
        ``rank`` is out of range (the caller then falls back to the CPU).

    Generated by RJC and Claude.
    """
    ndev = device_count()
    if ndev == 0:
        msgs.warn("Cannot select a GPU: " + unavailable_reason(), verbose=verbose)
        return False
    if not 0 <= rank < ndev:
        msgs.warn(
            f"GPU rank {rank} is out of range (only {ndev} available)", verbose=verbose
        )
        return False
    from numba import cuda

    cuda.select_device(rank)
    return True


def reset_probe_cache():
    """Forget the cached probe result so the next call re-detects.

    Only needed by the unit tests, which simulate machines with and without a
    GPU; production code probes once per process.

    Generated by RJC and Claude.
    """
    global _PROBE
    _PROBE = None
