"""Screenshots of the dashboard's Components tab, for review.

Dashboard Stage 5.7 (Q5.1). Opens the window off-screen at 1440x900 (D43) and saves
one PNG per screen:

- J1358p6522, imported, its D I blinded as in the mockups: O I (the ``components``
  mockup), and H I with D I, a2 selected (the ``components_hd`` mockup), in the
  two columns the tab starts with (Q5.21);
- the screens with no mockup: a new project from ``metal_line_abs``'s spectrum, after
  one click at O I 1302 (one component with O I and Si II, their first guesses);
  J1358p6522's snip from Ly8 to the Lyman limit, one panel (Q5.19), in one column
  at ±2000 km/s, the .mod panel closed;
  the same component dragged below the continuum (the model drawn as it goes); Q1243p307's O I
  in "All datasets"; J1358p6522's Lyα forest; ``examples/blind`` (a hidden
  component: masks, and only Δχ² in a drag); Add ion…; an ion excluded from a
  component; the Regions tab's Model switch; an ion in no snip (the tab's "!");
  Add interloper's menu on Q1243p307; and ``summed_coldens``'s links.

Run it from the repository root::

    python doc/dashboard/stage5/take_screenshots.py OUTDIR

Generated by RJC and Claude.
"""

import os
import shutil
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "doc/dashboard/skeleton"))

from take_screenshots import BLIND, J1358, Q1243, blind_d_i, pump, shoot  # noqa: E402

SPECTRUM = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"
SUMMED = ROOT / "examples/summed_coldens/model/fit_spectra.mod"
COLUMNS = {str(SPECTRUM): {"wave": 0, "flux": 1, "error": 2}}


def dialog_shot(dialog, path, size=(560, 520)):
    """Show a dialog and save it."""
    dialog.resize(*size)
    dialog.show()
    pump(0.3)
    shoot(dialog, path)
    dialog.hide()


def components(window):
    window.tabs.setCurrentIndex(2)
    pump(0.5)
    return window.tab_widgets[2]


def choose(tab, name):
    for item in tab._ion_items():
        if item.text(0) == name:
            tab.tree.setCurrentItem(item)
            pump(0.8)
            return
    raise ValueError(name)


def metal_project(window, tmp):
    """metal_line_abs's spectrum: O I 1302 and Si II 1304 merged, with a continuum."""
    from alis.dashboard import continuum as CO
    from alis.dashboard import lines as L
    from alis.dashboard import session as S
    from alis.dashboard import snips as SN
    from alis.dashboard import sources as SR

    session, _ = S.Session.new(
        str(tmp / "OI_SiII.model"),
        [str(SPECTRUM)],
        z=0.0,
        columns=COLUMNS,
        prefs=window.prefs,
        folder=window.folder,
    )
    window.set_session(session)
    project = session.project
    spectra = {r.id: SR.spectrum(project, r) for r in project.rows}
    atom = L.atomic(project.registry)
    for ion, rest, low, high, fit in (
        ("16O_I", 1302.16849, 1300.5, 1303.4, (1301.0, 1303.4)),
        ("28Si_II", 1304.3702, 1303.1, 1306.0, (1303.1, 1305.0)),
    ):
        line = next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)
        session.history.do(
            SN.snip_step(session.project, session.project.systems[0], line, spectra)
        )
        snip = session.project.snips[-1]
        spec = spectra[session.project.rows[0].id]
        session.history.do(SN.edges_step(session.project, snip, low, high, spec))
        snip = session.project.snips[-1]
        session.history.do(SN.add_region_step(session.project, snip, *fit))
    project = session.project
    plan = SN.merge_plan(project, project.snip("OI_1302"), project.snip("SiII_1304"))
    session.history.do(plan.step)
    session.history.do(CO.auto_step(session.project, session.project.snips[0]))
    window.refresh()
    return components(window)


def interloper_menu(tab):
    """Add interloper's menu at another system's line in one of the panels."""
    for item in tab._ion_items():
        tab.tree.setCurrentItem(item)
        pump(0.5)
        for widget in tab.panel_widgets:
            for tick in widget.view.ticks():
                if tick.kind == "other" and abs(tick.value()) < 150.0:
                    menu = tab.interloper_menu(widget, tick.value())
                    if menu is not None and len(menu.actions()) > 6:
                        return menu
    return None


def main(outdir):
    """
    Take every screenshot.

    Generated by RJC and Claude.
    """
    from alis.dashboard import components as C
    from alis.dashboard import edit as E
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP
    from alis.dashboard.qt import dialogs as D

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    window.ask = lambda kind, title, text, choices, **kw: (
        "Don't save" if "Don't save" in choices else choices[-1]
    )
    pump(0.5)
    tmp = Path(tempfile.mkdtemp())

    # J1358p6522 imported: O I (components), H I with D I, a2 selected
    # (components_hd)
    if J1358.exists():
        window.import_path(str(J1358))
        pump(1.0)
        blind_d_i(window)
        window.set_panel_open(True, 420)
        tab = components(window)
        choose(tab, "O I")
        pump(1.0)
        shoot(window, outdir / "components_j1358_oi.png")
        choose(tab, "H I")
        tab.select(window.session.project.component("a2"))
        pump(1.0)
        shoot(window, outdir / "components_j1358_hd.png")
        # Ly8 to the Lyman limit: one snip, one panel (Q5.19), in one column at
        # ±2000 km/s, the .mod panel closed
        window.set_panel_open(False)
        tab.columns_box.setValue(1)
        tab.range_box.setCurrentIndex(tab.range_box.findData(2000.0))
        pump(1.0)
        bar = tab.scroll.verticalScrollBar()
        bar.setValue(bar.maximum())
        pump(0.5)
        shoot(window, outdir / "components_lyman.png")
        tab.range_box.setCurrentIndex(tab.range_box.findData(200.0))
        tab.columns_box.setValue(2)
        window.set_panel_open(True, 420)
        # The Lyα forest
        window.set_panel_open(False)
        for item in tab._ion_items():
            if item.text(0) == "Lyα forest":
                tab.tree.setCurrentItem(item)
        pump(1.0)
        shoot(window, outdir / "components_forest.png")
        # The Regions tab's Model switch: Lyβ, normalised
        window.tabs.setCurrentIndex(1)
        regions = window.tab_widgets[1]
        pump(0.5)
        for num in range(regions.listing.topLevelItemCount()):
            item = regions.listing.topLevelItem(num)
            if item.text(1).startswith("Lyβ"):
                regions.listing.setCurrentItem(item)
        regions.actions_["regions.normalised"].trigger()
        regions.actions_["regions.model"].trigger()
        pump(1.0)
        shoot(window, outdir / "regions_model.png")
        regions.actions_["regions.model"].trigger()
        regions.actions_["regions.normalised"].trigger()

    # A new project from metal_line_abs's spectrum: one click at O I 1302
    tab = metal_project(window, tmp)
    window.set_panel_open(True, 420)
    choose(tab, "O I")
    tab.actions_["components.add_component"].trigger()
    tab.panel_widgets[0].view.clicked.emit(0.0, 0.5)
    pump(1.0)
    shoot(window, outdir / "components_new.png")
    # A drag below the continuum, down and outwards: the model drawn as it goes
    view = tab.panel_widgets[0].view
    view.dragged.emit(8.0, 0.6, 8.0, 0.6, "start")
    view.dragged.emit(8.0, 0.6, 10.5, 0.48, "move")
    tab._preview_now()
    pump(0.5)
    shoot(window, outdir / "components_drag.png")
    view.dragged.emit(8.0, 0.6, 10.5, 0.48, "finish")
    pump(0.5)
    # Si II excluded from a1 (its card greyed, its tick faint and dashed)
    choose(tab, "Si II")
    tab.card_widgets["a1"].toggle.click()
    pump(1.0)
    shoot(window, outdir / "components_excluded.png")
    window.session.history.undo()
    window.refresh()
    # Add ion…
    project = window.session.project
    system = project.systems[0]
    inside, others = C.addable_ions(project, system)
    dialog = D.IonDialog(system.name, inside, others)
    dialog_shot(dialog, outdir / "components_add_ion.png", (360, 460))
    # An ion in no snip: the tab's "!" (Q5.7)
    window.session.history.do(C.add_ion(project, system, "12C_II")[0])
    window.refresh()
    choose(tab, "C II")
    pump(0.8)
    shoot(window, outdir / "components_marker.png")
    window.session.history.undo()
    window.refresh()
    window.set_panel_open(False)

    # Q1243p307: O I in "All datasets"
    if Q1243.exists():
        window.import_path(str(Q1243))
        pump(1.0)
        tab = components(window)
        choose(tab, "O I")
        index = tab.dataset_box.findText("All datasets")
        tab.dataset_box.setCurrentIndex(index)
        pump(1.0)
        shoot(window, outdir / "components_q1243.png")
        # Add interloper's menu where another system's line falls (S14)
        menu = interloper_menu(tab)
        if menu is not None:
            menu.popup(window.pos())
            pump(0.5)
            shoot(menu, outdir / "components_interloper.png")
            menu.hide()

    # examples/summed_coldens: what links compute (Q5.9)
    folder = tmp / "summed"
    shutil.copytree(str(SUMMED.parent.parent), str(folder))
    window.import_path(str(folder / "model" / SUMMED.name))
    pump(1.0)
    window.set_panel_open(True, 420)
    tab = components(window)
    choose(tab, "H I")
    ra = next(c for c in window.session.project.components if c.label == "ra")
    tab.select(ra)
    pump(1.0)
    shoot(window, outdir / "components_linked.png")
    window.set_panel_open(False)

    # examples/blind: a hidden component, and a drag of it
    folder = tmp / "blind"
    shutil.copytree(str(BLIND.parent.parent), str(folder))
    window.import_path(str(folder / "model" / BLIND.name))
    pump(1.0)
    session = window.session
    for role, value in (("ColDens", 13.4729), ("redshift", 0.000173)):
        pm = session.project.parsed
        line = [ln for ln in pm.function_lines("voigt") if ln.ion == "28Si_II"][0]
        session.project.edit(E.set_value(pm, line.param(role), value))
    window.refresh()
    tab = components(window)
    choose(tab, "Si II")
    comp = [c for c in session.project.components if "28Si_II" in c.ions][0]
    view = tab.panel_widgets[0].view
    x = next(t.value() for t in view.ticks() if t.key == ("component", comp.id))
    view.dragged.emit(x + 5.0, 0.6, x + 5.0, 0.6, "start")
    view.dragged.emit(x + 5.0, 0.6, x + 7.0, 0.5, "move")
    tab._preview_now()
    pump(0.8)
    shoot(window, outdir / "components_blind.png")


if __name__ == "__main__":
    main(sys.argv[1])
