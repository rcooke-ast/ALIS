TITLE = "Dashboard Components Tab"


def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    for anchor, eyebrow, title, shot, slug, check, differ in SECTIONS:
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        diffs = "".join("<li>{0}</li>".format(esc(t)) for t in differ)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            "</ul></div><div><h3>Differences from the mockup</h3><ul>{4}</ul>"
            '</div></div><div class="compare both"><figure><figcaption>Components'
            " tab (Stage 5)</figcaption>{5}</figure><figure><figcaption>Mockup"
            ' (Stage 0)</figcaption><div class="stage">{6}</div></figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                diffs,
                image(shots, shot, "Screenshot: " + title),
                mockup_window(slug),
            )
        )
    new = "".join(
        '<figure id="{0}">{1}<figcaption><b>{2}</b>{3}</figcaption></figure>'.format(
            anchor, image(shots, name, title), esc(title), esc(text)
        )
        for anchor, title, name, text in NEW
        if (shots / name).exists()
    )
    toc = "".join(
        '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
            esc(e[1]), e[0], esc(e[2])
        )
        for e in SECTIONS
    ) + (
        '<li><span class="grp">No mockup</span><a href="#more">Add interloper…,'
        " links, an ion in no snip, the Lyman limit, a click, a drag, an exclusion,"
        " three datasets, the forest, a hidden component, Add ion…, the Regions"
        " tab's Model switch</a></li>"
    )
    decide = "".join("<li>{0}</li>".format(esc(t)) for t in DECIDE)
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 5 · the'
        " Components tab, draft 4</div><h1>{title}</h1>"
        '<p class="lede">The Components tab of the ALIS dashboard, as Stage 5'
        " finishes it, beside the mockups of Stage 0. Each screenshot is taken"
        " off-screen"
        " at 1440×900 from real data: <code>VMP_DLA/J1358p6522</code> (its fit"
        " imported, D I blinded as in the mockups), <code>DH/Q1243p307</code>"
        " (three datasets), <code>metal_line_abs</code> (a new project from its"
        " spectrum), <code>examples/blind</code> and"
        " <code>examples/summed_coldens</code>.</p>"
        '<p class="lede">Every action is one step of the history (undo takes it'
        " back), every value passes the blinding gate, and the model drawn is"
        " ALIS's own. Leave a comment on anything to change before the stage is"
        " closed.</p>"
        '<div class="decide"><h2>Decided on this page (draft 2)</h2><ol>{decide}'
        "</ol></div>"
        '<div class="decide"><h2>What this review covers</h2><ul>{covered}</ul>'
        "</div>"
        '<ul class="toc">{toc}</ul>'
        '<div class="layoutbar">Layout: <button type="button" data-layout="both"'
        ' aria-pressed="true">Side by side</button><button type="button"'
        ' data-layout="stack" aria-pressed="false">One above the other</button>'
        "</div>{sections}"
        '<section class="mock" id="more"><div class="eyebrow">No mockup</div>'
        '<h2>Screens with no mockup</h2><div class="newgrid">{new}</div>'
        "</section></div>{script}\n"
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        decide=decide,
        covered=covered,
        toc=toc,
        sections="".join(sections),
        new=new,
        script=LAYOUT_SCRIPT,
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
