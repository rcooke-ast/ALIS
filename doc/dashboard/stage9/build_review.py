def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    anchor, eyebrow, title, shot, slug, check, differ = MAIN
    main = (
        '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
        '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
        "</ul></div><div><h3>Differences from the mockup</h3><ul>{4}</ul>"
        '</div></div><div class="compare both"><figure><figcaption>Figure tab'
        " (Stage 9)</figcaption>{5}</figure><figure><figcaption>Plot mockup"
        ' (Stage 0)</figcaption><div class="stage">{6}</div></figure></div>'
        "</section>"
    ).format(
        anchor,
        esc(eyebrow),
        esc(title),
        "".join("<li>{0}</li>".format(esc(t)) for t in check),
        "".join("<li>{0}</li>".format(esc(t)) for t in differ),
        image(shots, shot, "Screenshot: " + title),
        mockup_window(slug),
    )
    sections = []
    for anchor, eyebrow, title, names, check in SECTIONS:
        found = [n for n in names if (shots / n).exists()]
        if not found:
            continue
        pictures = "".join(
            "<figure>{0}</figure>".format(image(shots, n, title)) for n in found
        )
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul></div></div><div class="newgrid">{4}</div></section>'.format(
                anchor,
                esc(eyebrow),
                esc(title),
                "".join("<li>{0}</li>".format(esc(t)) for t in check),
                pictures,
            )
        )
    toc = '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
        esc(MAIN[1]), MAIN[0], esc(MAIN[2])
    ) + "".join(
        '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
            esc(e[1]), e[0], esc(e[2])
        )
        for e in SECTIONS
        if any((shots / n).exists() for n in e[3])
    )
    decide = "".join("<li>{0}</li>".format(esc(t)) for t in DECIDE)
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 9 · the'
        " Figure tab, draft 3</div><h1>{title}</h1>"
        '<p class="lede">The Figure tab: a publication figure from a fit, beside the'
        " Plot mockup of Stage 0. Each screenshot is taken off-screen at 1440×900,"
        " the .mod panel closed as the mockup has it. The runs are the fits'"
        " reference outputs, and every preview is drawn by the figure's own"
        " script, with LaTeX, as Draw preview draws it.</p>"
        '<div class="decide"><h2>Questions for this review</h2><ol>{decide}'
        "</ol></div>"
        '<div class="decide"><h2>What this review covers</h2><ul>{covered}</ul>'
        "</div>"
        '<ul class="toc">{toc}</ul>'
        '<div class="layoutbar">Layout: <button type="button" data-layout="both"'
        ' aria-pressed="true">Side by side</button><button type="button"'
        ' data-layout="stack" aria-pressed="false">One above the other</button>'
        "</div>{main}{sections}</div>{script}\n"
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        decide=decide,
        covered=covered,
        toc=toc,
        main=main,
        sections="".join(sections),
        script=LAYOUT_SCRIPT,
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
