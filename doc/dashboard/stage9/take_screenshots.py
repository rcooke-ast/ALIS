"""Screenshots of the Figure tab, for the review that closes Stage 9.

Opens the window off-screen at 1440x900 (D43), the .mod panel closed as the Plot
mockup of Stage 0 has it, and saves one PNG per screen:

- each preset on a fit: DH on J1358p6522 (one dataset) and Q1243p307 (two, one per
  column), helium on tet02OriA, metals on metal_line_abs, blends on a synthetic
  interloper (RJC's projects are skipped where absent);
- two figures, the second showing a transition the first shows (Q9.10);
- DH_Lyseries.py's layout: a panel spanning three columns, in rest wavelength (Q9.7,
  Q9.8);
- a panel's options (Q9.8, Q9.12);
- the preview beside the PDF that Export figure… writes (S22, Q9.11);
- a blinded project: the tab greyed, and the figure greyed in Export (Q9.5).

The runs are the fits' reference outputs (no fit is run). Run it from the repository
root::

    python doc/dashboard/stage9/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
import subprocess
import sys
import tempfile
import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _skeleton():
    """The skeleton's screenshot helpers."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
pump, shoot = _SK.pump, _SK.shoot

EXAMPLES = ROOT / "examples"
CONTEXT = ROOT / "context/fitting_examples"
METAL = EXAMPLES / "metal_line_abs/model/fit_spectra.mod"
BLIND = EXAMPLES / "blind/model/fit_spectra.mod"
J1358 = CONTEXT / "VMP_DLA/J1358p6522/model/J1358p6522.mod"
Q1243 = CONTEXT / "DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
HELIUM = (
    CONTEXT / "helium34/tet02OriA/model/fit_polyvoigt_linear_Thermal_FINAL_MODEL.mod"
)
FIGURE = 4


def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def imported(window, model, mod_out=None):
    """A fit imported with its reference outputs as its run."""
    from test_dashboard_results import store_run

    window.import_path(str(model))
    pump(1.5)
    if mod_out is None:
        store_run(window.session.project, model, status="imported", started=None)
    else:
        store_run(window.session.project, model, mod_out=mod_out, covar=False)
    window.session.runs_changed()
    window.set_panel_open(False)
    window.refresh()
    window.tabs.setCurrentIndex(FIGURE)
    pump(0.6)
    return window.figure_tab


def drawn(tab):
    """Draw the preview, and wait for it."""
    tab.draw_button.click()
    tab.wait_for_preview()
    pump(0.6)


def screens(window, work, outdir):
    """The screens, each a function that saves its PNG."""
    from dashboard_synthetic import write_shifted_fit  # noqa: F401
    from test_dashboard_figpresets import write_blend
    from test_dashboard_figscript import write_lyman_limit
    from test_dashboard_results import _blind_out, store_run

    from alis import bundle as B
    from alis.dashboard import figpresets as FP
    from alis.dashboard import figure as FG
    from alis.dashboard import runs as R
    from alis.dashboard.qt import figure as QF

    def preset_screen(model, name, preset=None, **kwargs):
        if not model.exists():
            print("skipped", name, "(absent)")
            return None
        tab = imported(window, model, **kwargs)
        tab.create_button.click()
        pump(0.3)
        if preset is not None:
            tab.preset_menu.setCurrentIndex(tab.preset_menu.findData(preset))
            tab.apply_button.click()
        drawn(tab)
        shoot(window, outdir / (name + ".png"))
        return tab

    def dh_j1358():
        preset_screen(J1358, "dh_j1358")
        done(window)

    def dh_q1243():
        preset_screen(Q1243, "dh_q1243")
        done(window)

    def helium():
        preset_screen(HELIUM, "helium")
        done(window)

    def metals():
        preset_screen(METAL, "metals", mod_out=None)
        done(window)

    def blends():
        model = write_blend(work / "blend")
        tab = imported(window, model, mod_out=model.read_text())
        tab.create_button.click()
        tab.preset_menu.setCurrentIndex(tab.preset_menu.findData(FP.BLENDS))
        tab.apply_button.click()
        drawn(tab)
        shoot(window, outdir / "blends.png")
        done(window)

    def two_figures():
        if not J1358.exists():
            return
        tab = imported(window, J1358)
        tab.create_button.click()
        drawn(tab)
        lya = FG.cell_at(tab.current(), 0, 0)[0]["show"]
        tab.create_button.click()
        pump(0.3)
        tab.place(lya, 0, 0)
        pump(0.3)
        shoot(window, outdir / "two_figures.png")
        done(window)

    def lyseries():
        model = write_lyman_limit(work / "ll")
        tab = imported(window, model, mod_out=model.read_text())
        tab.create_button.click()
        project = window.session.project
        found = FG.transitions(project)
        lya = next(e for e in found if e.line == "Lyα 1215.7")
        limit = next(e for e in found if e.specid == "1")
        fid = tab.current_id()
        history = window.session.history
        # Each step is made from the project as it then is
        history.do(FG.set_grid(project, fid, 3, 3))
        history.do(FG.set_option(project, fid, "size", [7.0, 6.0]))
        history.do(FG.set_option(project, fid, "spacing", [0.2, 0.45]))
        history.do(FG.place(project, fid, 0, 0, lya.key))
        history.do(FG.place(project, fid, 1, 0, limit.key))
        history.do(FG.set_span(project, fid, 1, 0, 3))
        for key, value in (
            ("axis", FG.REST),
            ("xrange", [913.15, 915.2]),
            ("label", "Lyman limit"),
        ):
            history.do(FG.set_cell(project, fid, 1, 0, key, value))
        history.do(FG.place(project, fid, 2, 1, lya.key))
        window.refresh()
        drawn(tab)
        shoot(window, outdir / "lyseries.png")
        done(window)

    def options():
        model = METAL
        tab = imported(window, model)
        tab.create_button.click()
        dialog = QF.OptionsDialog(tab, 0, 0, window)
        dialog.show()
        pump(0.5)
        shoot(dialog, outdir / "options.png")
        dialog.close()
        done(window)

    def export_pdf():
        tab = imported(window, METAL)
        tab.create_button.click()
        drawn(tab)
        folder = work / "paper"

        def answer(dialog):
            dialog.folder.setText(str(folder))
            dialog.show()
            pump(0.4)
            shoot(dialog, outdir / "export_dialog.png")
            return 1

        window.run_dialog = answer
        tab.export_button.click()
        window.run_dialog = lambda dialog: 0
        pdf = folder / "metal_Figure_1.pdf"
        subprocess.run(
            [
                "sips",
                "-s",
                "format",
                "png",
                "-Z",
                "1400",
                str(pdf),
                "--out",
                str(outdir / "export_pdf.png"),
            ],
            check=True,
            capture_output=True,
        )
        Path(outdir / "export_preview.png").write_bytes(Path(tab.drawn).read_bytes())
        print("wrote", outdir / "export_pdf.png")
        done(window)

    def blinded():
        path = work / "blind.model"
        B.pack_to(str(BLIND), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        project = window.session.project
        offset = R.blind_offset({"blindrange": [-1.0e6, 1.0e6], "blindseed": 1234})
        out = (METAL.parent / (METAL.name + ".out.reference")).read_text()
        store_run(project, METAL, mod_out=_blind_out(out, offset))
        step, _ = FG.new_figure(project)
        window.session.history.do(step)
        window.session.runs_changed()
        window.set_panel_open(False)
        window.refresh()
        window.tabs.setCurrentIndex(3)
        window.fit_tab.subtabs.setCurrentIndex(1)
        pump(0.6)
        shoot(window, outdir / "blinded.png")

        def answer(dialog):
            dialog.show()
            pump(0.4)
            shoot(dialog, outdir / "blinded_export.png")
            return 0

        window.run_dialog = answer
        window.qactions["file.export"].trigger()
        window.run_dialog = lambda dialog: 0
        done(window)

    return [
        dh_j1358,
        dh_q1243,
        helium,
        metals,
        blends,
        two_figures,
        lyseries,
        options,
        export_pdf,
        blinded,
    ]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage9_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    # Questions take their last choice (Cancel), and dialogs are cancelled, unless a
    # screen answers them itself; an imported fit opens without a spectrum
    window.ask = lambda kind, title, text, choices, **kw: (
        "Open without a spectrum"
        if "Open without a spectrum" in choices
        else choices[-1]
    )
    window.tell = lambda title, text, icon="info": None
    window.run_dialog = lambda dialog: 0
    failed = []
    for screen in screens(window, work, outdir):
        if only and screen.__name__ not in only:
            continue
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage9_shots", sys.argv[2:])
