"""Screenshots of what changed in Stage 7, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen:

- the start page's recent projects, with Remove from list and Clear list…;
- the toolbar's Run, beside Save;
- the Add a spectrum dialog with a file chosen (item 8);
- Open a fit (.mod)…'s question, and its preview offering a new project (item 3);
- the cards of a fit in J101155p294141's shape: D I as a ratio row (item 5);
- a fit in J013301m400628's shape with a1 excluded from both ions (item 2);
- a pure-thermal component's card, with its limits in the .mod panel (items 11, 12);
- Inspect with the continuum, after a real fit of metal_line_abs (item 10);
- the Regions tab's Snip box, with a snip's own shift and zero level (items 9, 14);
- the toolbar of a new project, Run greyed while there is nothing to fit (review);
- File ▸ Export…'s dialog, after the metal_line_abs run (Q7.16).

Run it from the repository root::

    python doc/dashboard/stage7/take_screenshots.py OUTDIR

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import time
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _skeleton():
    """The skeleton's screenshot helpers."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
pump, shoot = _SK.pump, _SK.shoot

METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
SPECTRUM = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"
J0133 = ROOT / "context/fitting_examples/Temperature/J013301m400628/J013301m400628.dat"


def answered(window, answers):
    """The window's questions, answered from ``answers`` (by kind), else Cancel."""

    def ask(kind, title, text, choices, default=None, icon="question"):
        answer = answers.get(kind)
        return answer if answer in choices else choices[-1]

    window.ask = ask


def question(window, title, text, choices, default):
    """A question as ``window.ask`` shows it, shown rather than run."""
    from qtpy import QtWidgets

    box = QtWidgets.QMessageBox(window)
    box.setWindowTitle(title)
    box.setText(text)
    box.setIcon(QtWidgets.QMessageBox.Icon.Question)
    for num, choice in enumerate(choices):
        role = (
            QtWidgets.QMessageBox.ButtonRole.RejectRole
            if num == len(choices) - 1
            else QtWidgets.QMessageBox.ButtonRole.AcceptRole
        )
        button = box.addButton(choice, role)
        if choice == default:
            box.setDefaultButton(button)
    box.show()
    return box


def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def components(window, ion="H I"):
    window.tabs.setCurrentIndex(2)
    tab = window.tab_widgets[2]
    for item in tab._ion_items():
        if item.text(0) == ion:
            tab.tree.setCurrentItem(item)
    pump(0.8)
    return tab


def main(outdir):
    """
    Take every screenshot.

    Generated by RJC and Claude.
    """
    from dashboard_synthetic import (
        write_linked_fit,
        write_ratio_fit,
        write_thermal_fit,
    )

    from alis import bundle as B
    from alis.dashboard import components as C
    from alis.dashboard import datasets as DS
    from alis.dashboard import export as X
    from alis.dashboard import fitview as FV
    from alis.dashboard import lines as L
    from alis.dashboard import preferences as PR
    from alis.dashboard import session as S
    from alis.dashboard import snips as SN
    from alis.dashboard import sources as SR
    from alis.dashboard.qt import app as APP
    from alis.dashboard.qt import dialogs as D
    from alis.dashboard.qt import window as WN

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage7_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    answered(window, {})
    # The start page's recent projects (item 7)
    recent = PR.Recent(window.folder)
    for name in ("J193957m100241", "J101155p294141", "metal_line_abs"):
        path = work / (name + ".model")
        B.pack_to(str(METAL), str(path), with_outputs=False)
        recent.add(str(path))
    window.show_start()
    window.start.recent.setCurrentRow(1)
    pump(0.5)
    shoot(window, outdir / "start_recent.png")
    # Open a fit (.mod)…'s question (item 3)
    box = question(
        window,
        "Open a fit",
        "Open old.mod with the full spectrum its snips were cut from? This is the"
        " recommended way: the snips are checked against it, and new snips can be"
        " cut from it. Without it, the fit opens with its snips alone.",
        [WN.WITH_SPECTRUM, "Open without a spectrum", "Cancel"],
        WN.WITH_SPECTRUM,
    )
    pump(0.3)
    shoot(box, outdir / "open_fit_question.png")
    box.close()
    # The Add a spectrum dialog, a file chosen (item 8)
    dialog = D.SpectrumDialog(str(work))
    dialog.show()
    dialog.set_file(str(J0133 if J0133.exists() else SPECTRUM))
    pump(0.3)
    shoot(dialog, outdir / "spectrum_dialog.png")
    dialog.close()
    # D I as a ratio, on the cards (item 5)
    window.import_path(str(write_ratio_fit(work / "ratio")))
    pump(1.0)
    components(window)
    shoot(window, outdir / "cards_ratio.png")
    # a1 excluded from both ions (item 2)
    done(window)
    window.import_path(str(write_linked_fit(work / "linked")))
    pump(1.0)
    session = window.session
    for ion in ("1H_I", "2H_I"):
        project = session.project
        session.history.do(C.exclude(project, project.component("a1"), ion))
    window.refresh()
    components(window)
    shoot(window, outdir / "cards_excluded.png")
    # Pure thermal: its limits, and a drag across moving T (items 11, 12)
    done(window)
    window.import_path(str(write_thermal_fit(work / "thermal")))
    pump(1.0)
    session = window.session
    session.history.do(
        C.temperature(session.project, session.project.components[0], "thermal")
    )
    window.set_panel_open(True)
    window.refresh()
    components(window)
    shoot(window, outdir / "cards_thermal.png")
    window.set_panel_open(False)
    # Run on the toolbar, and Inspect with the continuum (items 13, 10)
    done(window)
    path = work / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    pump(1.0)
    window.prefs.set("fit.ncpus", 1)
    shoot(window.toolbar, outdir / "toolbar.png")
    window.qactions["fit.run"].trigger()
    start = time.time()
    while window.fit.active and time.time() - start < 600:
        pump(0.2)
    pump(0.5)
    window.tabs.setCurrentIndex(3)
    inspect = window.fit_tab.inspect
    inspect.select("scale", FV.CONTINUUM)
    pump(0.8)
    shoot(window, outdir / "inspect_continuum.png")
    inspect.select("scale", FV.NORMALISED)
    # File ▸ Export…'s dialog, after the run (Q7.16)
    view, _ = window.shown_run()
    dialog = D.ExportDialog(
        str(work),
        lambda: None,
        X.run_reason(view),
        X.best_fit_reason(window.session.project, view),
        X.reference_components(window.session.project),
    )
    # The velocities and the corrected wavelength ticked (Prompts 8, 9)
    dialog.tick("velocity")
    dialog.tick("cwave")
    dialog.tick("cvelocity")
    dialog.show()
    pump(0.3)
    shoot(dialog, outdir / "export_dialog.png")
    dialog.close()
    # A snip's own shift and zero level, in the Snip box (items 9, 14)
    done(window)
    project_path = work / "snips.model"
    session, _ = S.Session.new(str(project_path), [str(SPECTRUM)], z=0.0)
    window.set_session(session)
    # No snip yet: Run greyed (RJC's review)
    pump(0.5)
    shoot(window.toolbar, outdir / "toolbar_greyed.png")
    project = session.project
    spectra = {r.id: SR.spectrum(project, r) for r in project.rows}
    atom = L.atomic(project.registry)
    for ion, rest, low, high in (
        ("16O_I", 1302.16849, 1301.8, 1302.5),
        ("28Si_II", 1304.3702, 1304.0, 1304.7),
    ):
        line = next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)
        session.history.do(
            SN.snip_step(session.project, project.systems[0], line, spectra)
        )
        snip = session.project.snips[-1]
        session.history.do(SN.add_region_step(session.project, snip, low, high))
    snip = session.project.snips[-1]
    session.history.do(DS.snip_shift_step(session.project, snip, True))
    session.history.do(
        DS.snip_zero_step(session.project, session.project.snips[-1], True)
    )
    window.refresh()
    window.tabs.setCurrentIndex(1)
    tab = window.tab_widgets[1]
    tab.element_box.setCurrentIndex(tab.element_box.findText("Si"))
    tab.ion_box.setCurrentIndex(tab.ion_box.findText("II"))
    for num in range(tab.listing.topLevelItemCount()):
        item = tab.listing.topLevelItem(num)
        if item.text(1).startswith("Si II 1304"):
            tab.listing.setCurrentItem(item)
    pump(0.8)
    shoot(window, outdir / "snip_box.png")
    window.tabs.setCurrentIndex(0)
    pump(0.5)
    shoot(window, outdir / "data_own.png")
    session.discard_recovery()
    window.session = None


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage7_shots")
