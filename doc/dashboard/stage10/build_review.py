def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    told = {}
    notes_file = shots / "messages.txt"
    if notes_file.exists():
        for line in notes_file.read_text().splitlines():
            screen, _title, text = line.split("\t", 2)
            told[screen] = text
    sections = []
    toc = []
    for anchor, eyebrow, title, shot, check in SECTIONS:
        if not (shots / shot).exists():
            continue
        items = [t.format(message=told.get("snip_j0035", "")) for t in check]
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in items)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul></div></div><div class="compare"><figure>{4}</figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                image(shots, shot, "Screenshot: " + title),
            )
        )
        toc.append(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(eyebrow), anchor, esc(title)
            )
        )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 10 ·'
        " feedback from users, draft 3</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 10, after the 13 points of the'
        " Feedback list and the three items carried over from Stage 9: one section"
        " per change, each with what to check. Each screenshot is taken off-screen at"
        " 1440×900, of your J0035m0918 and J1358p6522 and of a synthetic fit in the"
        " shape of J101155p294141.</p>"
        '<p class="lede">Draft 2 adds your Prompt 5: a panel\'s flux set by its'
        " lowest value, its highest worked out (Labels rounded down, below)."
        " Draft 3 adds your Prompt 6: the Lyα forest's lines adjusted as"
        " components.</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing new to see</h2><ul>'
        "{covered}</ul></div>"
        '<ul class="toc">{toc}</ul>{sections}</div>\n'
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        covered=covered,
        toc="".join(toc),
        sections="".join(sections),
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
