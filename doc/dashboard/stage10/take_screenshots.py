"""Screenshots of what changed in Stage 10, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen:

- SNIP on J0035m0918's Al II 1670, which passes over UVES2010 (Task 10.1);
- D I labelled beside Lyβ, by the default line IDs and by This transition (Tasks
  10.2, 10.4);
- the Transitions pane: the list by wavelength, and the system's snips (10.5, 10.6);
- Adjust fit regions, a region's edge under the cursor, and a snip's two grips
  (10.7, 10.8, 10.10);
- the whole source around a snip, zoomed out (10.9);
- the cards' T fields, free and fixed (10.11);
- J1358p6522's Lyα forest, a line selected on its card and in its panels (Prompt 6);
- J1358p6522's figures: the metals preset with a panel from a flux of its own
  (10.12, 10.13, Prompt 5), the DH preset from Ly8 (10.14), and a wavelength panel above
  velocity ones with the spacing worked out (10.15).

RJC's projects are skipped where absent; the messages the window shows are written
beside the screenshots (``messages.txt``). Run it from the repository root::

    python doc/dashboard/stage10/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _skeleton():
    """The skeleton's screenshot helpers."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
pump, shoot = _SK.pump, _SK.shoot

CONTEXT = ROOT / "context"
J0035 = CONTEXT / "feedback01/J0035m0918.model"
J1358 = CONTEXT / "fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
REGIONS, COMPONENTS, FIGURE = 1, 2, 4


def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def regions_of(window, path):
    """RJC's J0035m0918 on the Regions tab, or None where it or its sources are
    absent."""
    if not path.exists():
        return None
    window.open_path(str(path))
    pump(1.0)
    window.set_panel_open(False)
    window.tabs.setCurrentIndex(REGIONS)
    pump(0.8)
    tab = window.tab_widgets[REGIONS]
    return tab if tab._spectra else None


def figure_of(window, model):
    """A fit imported with its reference outputs as its run, on the Figure tab."""
    from test_dashboard_results import store_run

    window.import_path(str(model))
    pump(1.5)
    store_run(window.session.project, model, status="imported", started=None)
    window.session.runs_changed()
    window.set_panel_open(False)
    window.refresh()
    window.tabs.setCurrentIndex(FIGURE)
    pump(0.6)
    return window.figure_tab


def drawn(tab):
    """Draw the preview, and wait for it."""
    tab.draw_button.click()
    tab.wait_for_preview()
    pump(0.6)


def screens(window, outdir, told):
    """The screens, each a function that saves its PNG."""
    from dashboard_synthetic import write_ratio_fit

    from alis.dashboard import figpresets as FP
    from alis.dashboard import figure as FG
    from alis.dashboard import lines as L

    def show(tab, ion, rest):
        tab.show_transition(window.session.project.systems[0].id, ion, rest)
        pump(0.8)

    def snip_j0035():
        tab = regions_of(window, J0035)
        if tab is None:
            return
        show(tab, "27Al_II", 1670.7886)
        told.clear()
        tab.actions_["regions.snip"].trigger()
        pump(1.0)
        with open(outdir / "messages.txt", "a") as out:
            for title, text in told:
                out.write("snip_j0035\t{0}\t{1}\n".format(title, text))
        shoot(window, outdir / "snip_j0035.png")
        done(window)

    def ids_lyb():
        tab = regions_of(window, J0035)
        if tab is None:
            return
        show(tab, "1H_I", 1025.7223)
        shoot(window, outdir / "ids_model.png")
        tab.line_ids_menu.setCurrentIndex(tab.line_ids_menu.findData(L.TRANSITION))
        pump(0.5)
        shoot(window, outdir / "ids_transition.png")
        done(window)

    def tools():
        tab = regions_of(window, J0035)
        if tab is None:
            return
        show(tab, "16O_I", 1302.16849)
        menu = tab.regions_menu
        menu.setCurrentIndex(menu.findText("all spectra"))
        menu.activated.emit(menu.currentIndex())
        pump(0.5)
        # A region's edge as the cursor finds it
        fit = tab.strips[0].view._lists.get("fit") or []
        if fit:
            fit[0].lines[1].setMouseHover(True)
        shoot(window, outdir / "tools.png")
        shoot(tab.transitions, outdir / "transitions_pane.png")
        # Zoomed out over the whole source around the snip
        low, high = tab.strips[0].snip.extent
        middle, width = 0.5 * (low + high), high - low
        tab.strips[0].view.box.setXRange(
            middle - 6 * width, middle + 6 * width, padding=0
        )
        pump(0.8)
        shoot(window, outdir / "zoom_out.png")
        done(window)

    def card_t():
        work = Path(tempfile.mkdtemp(prefix="stage10_"))
        window.import_path(str(write_ratio_fit(work / "fit")))
        pump(1.5)
        window.tabs.setCurrentIndex(COMPONENTS)
        pump(0.6)
        comp = window.tab_widgets[COMPONENTS]
        for item in comp._ion_items():
            if item.text(0) == "H I":
                comp.tree.setCurrentItem(item)
        pump(0.8)
        menu = comp.card_widgets["a2"].temp.menu()
        next(a for a in menu.actions() if a.text() == "100 K · fixed").trigger()
        pump(0.8)
        edit = window.tab_widgets[COMPONENTS].card_widgets["a1"].values["temperature"]
        edit.setText("12000")
        edit.editingFinished.emit()
        pump(0.8)
        shoot(window, outdir / "card_t.png")
        done(window)

    def forest():
        if not J1358.exists():
            return
        # Imported with its reference outputs as its run: Use best fit can copy
        figure_of(window, J1358)
        window.tabs.setCurrentIndex(COMPONENTS)
        pump(0.6)
        tab = window.tab_widgets[COMPONENTS]
        for item in tab._ion_items():
            if item.text(0) == "Lyα forest":
                tab.tree.setCurrentItem(item)
        pump(1.0)
        keys = [t.key for t in tab.panel_widgets[0].view.ticks()]
        key = next(k for k in keys if k and k[0] == "component")
        tab.select(window.session.project.component(key[1]))
        pump(0.5)
        shoot(window, outdir / "forest.png")
        done(window)

    def figures():
        if not J1358.exists():
            return
        tab = figure_of(window, J1358)
        project = window.session.project
        tab.create_button.click()
        pump(0.5)
        # Metals, a panel from 0.5 (its highest flux worked out: Prompt 5), its
        # label in the lower left
        tab.preset_menu.setCurrentIndex(tab.preset_menu.findData(FP.METALS))
        tab.apply_button.click()
        fid = tab.current_id()
        for key, value in (("ymin", 0.5), ("corner", "lower left")):
            window.session.history.do(FG.set_cell(project, fid, 0, 0, key, value))
        window.refresh()
        drawn(tab)
        shoot(window, outdir / "fig_metals.png")
        # DH from Ly8
        tab.preset_menu.setCurrentIndex(tab.preset_menu.findData(FP.DH))
        pump(0.3)
        ly8 = tab.from_menu.findText("from Ly8")
        if ly8 >= 0:
            tab.from_menu.setCurrentIndex(ly8)
            tab.apply_button.click()
            drawn(tab)
            shoot(window, outdir / "fig_dh_ly8.png")
        # DH from Lyα, its first panel in rest wavelength: the rows make room
        tab.from_menu.setCurrentIndex(0)
        tab.apply_button.click()
        fid = tab.current_id()
        window.session.history.do(
            FG.set_cell(window.session.project, fid, 0, 0, "axis", FG.REST)
        )
        window.refresh()
        drawn(tab)
        shoot(window, outdir / "fig_spacing.png")
        done(window)

    return [snip_j0035, ids_lyb, tools, card_t, forest, figures]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    (outdir / "messages.txt").write_text("")
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    told = []
    # Questions take their last choice (Cancel) and dialogs are cancelled; what the
    # window tells is kept, for the page
    window.ask = lambda kind, title, text, choices, **kw: choices[-1]
    window.tell = lambda title, text, icon="info": told.append((title, text))
    window.run_dialog = lambda dialog: 0
    failed = []
    for screen in screens(window, outdir, told):
        if only and screen.__name__ not in only:
            continue
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage10_shots", sys.argv[2:])
