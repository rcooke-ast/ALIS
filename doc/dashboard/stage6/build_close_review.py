TITLE = "Dashboard Fit Results"


def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    for anchor, eyebrow, title, shot, slug, check, differ in SECTIONS:
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        diffs = "".join("<li>{0}</li>".format(esc(t)) for t in differ)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            "</ul></div><div><h3>Differences from the mockup</h3><ul>{4}</ul>"
            '</div></div><div class="compare both"><figure><figcaption>{1}'
            " (Stage 6)</figcaption>{5}</figure><figure><figcaption>Mockup"
            ' (Stage 0)</figcaption><div class="stage">{6}</div></figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                diffs,
                image(shots, shot, "Screenshot: " + title),
                mockup_window(slug),
            )
        )
    new = "".join(
        '<figure id="{0}">{1}<figcaption><b>{2}</b>{3}</figcaption></figure>'.format(
            anchor, image(shots, name, title), esc(title), esc(text)
        )
        for anchor, title, name, text in NEW
        if (shots / name).exists()
    )
    toc = "".join(
        '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
            esc(e[1]), e[0], esc(e[2])
        )
        for e in SECTIONS
    ) + (
        '<li><span class="grp">No mockup</span><a href="#more">Compare on Ly8, Reset'
        " FWHM, Use best fit on a card and in the Continuum box, random restarts and"
        " their window, the convergence check, Review clipped pixels</a></li>"
    )
    decide = "".join("<li>{0}</li>".format(esc(t)) for t in DECIDE)
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 6 · the'
        " Fit tab's Results and Compare, and its tools, draft 2</div><h1>{title}</h1>"
        '<p class="lede">The second review of Stage 6, which completes the'
        " dashboard's version 1: the Fit tab's Results and Compare sub-tabs beside"
        " their Stage 0 mockups, and the tools with no mockup (Use best fit, Reset"
        " FWHM, random restarts, the convergence check, Review clipped pixels). Each"
        " screenshot is taken off-screen at 1440×900, and every run on this page is"
        " a real fit made from the window: <code>VMP_DLA/J1358p6522</code> (imported,"
        " D I blinded as in the mockups) and <code>metal_line_abs</code>.</p>"
        '<p class="lede">Every value passes the blinding gate. Leave a comment on'
        " anything to change; the changes are made before the stage closes.</p>"
        '<div class="decide"><h2>Questions for this review</h2><ol>{decide}'
        "</ol></div>"
        '<div class="decide"><h2>What this review covers</h2><ul>{covered}</ul>'
        "</div>"
        '<ul class="toc">{toc}</ul>'
        '<div class="layoutbar">Layout: <button type="button" data-layout="both"'
        ' aria-pressed="true">Side by side</button><button type="button"'
        ' data-layout="stack" aria-pressed="false">One above the other</button>'
        "</div>{sections}"
        '<section class="mock" id="more"><div class="eyebrow">No mockup</div>'
        '<h2>Screens with no mockup</h2><div class="newgrid">{new}</div>'
        "</section></div>{script}\n"
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        decide=decide,
        covered=covered,
        toc=toc,
        sections="".join(sections),
        new=new,
        script=LAYOUT_SCRIPT,
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
