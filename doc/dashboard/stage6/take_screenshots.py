"""Screenshots of the Fit tab's Inspect sub-tab, and of running a fit, for review.

Dashboard Stage 6.5 (Q6.1). Opens the window off-screen at 1440x900 (D43) and saves
one PNG per screen. Every run here is a real fit, made from the window:

- J1358p6522, imported, its D I blinded as in the mockups, saved, and fitted once
  from the dashboard; then, O I started 0.3 dex higher, run again and caught at its
  seventh iteration or after: Ly8 923.2 (the ``fit_inspect`` mockup), with the fit in
  progress, its notice, the progress against the first run, and the run in the
  status bar;
- J1358p6522 after the first run: Ly8 with the residuals of the fitted pixels only;
  all snips; H I with D I beside the .mod panel; O I
  1302 in wavelength; the pre-flight check's notes;
- metal_line_abs, fitted from the window: Initial and Final;
- metal_line_abs with ``sim perturb 10``: Run refused, and what it says;
- All settings…, and the question when the project closes during a run.

Run it from the repository root::

    python doc/dashboard/stage6/take_screenshots.py OUTDIR

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import time
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "doc/dashboard/skeleton"))

from take_screenshots import J1358, blind_d_i, pump, shoot  # noqa: E402

METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


def inspect(window):
    """The Fit tab's Inspect sub-tab, shown."""
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(0)
    pump(0.5)
    return window.fit_tab.inspect


def wait_run(window, until=None, timeout=600.0):
    """Let the run go on until it ends, or until ``until()`` holds."""
    start = time.time()
    while window.fit.active and time.time() - start < timeout:
        if until is not None and until(window.fit.job):
            return
        pump(0.1)
    pump(0.5)


def boxes(window, outdir):
    """
    The window's questions, answered as a script would, each saved as a PNG the
    first time its kind is asked (``window.next_shot`` names the file).

    Generated by RJC and Claude.
    """
    from qtpy import QtWidgets

    def ask(kind, title, text, choices, default=None, icon="question"):
        name = window.next_shot.pop(kind, None)
        if name is not None:
            box = QtWidgets.QMessageBox(window)
            box.setWindowTitle(title)
            box.setText(text)
            box.setIcon(
                QtWidgets.QMessageBox.Icon.Warning
                if icon == "warning"
                else QtWidgets.QMessageBox.Icon.Question
            )
            for choice in choices:
                box.addButton(choice, QtWidgets.QMessageBox.ButtonRole.AcceptRole)
            box.show()
            pump(0.3)
            shoot(box, outdir / name)
            box.hide()
        answer = window.answers.get(kind)
        return answer if answer in choices else choices[-1]

    window.next_shot = {}
    window.answers = {}
    window.ask = ask


def main(outdir):
    """
    Take every screenshot.

    Generated by RJC and Claude.
    """
    from alis import bundle as B
    from alis.dashboard import edit as E
    from alis.dashboard import fitview as FV
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP
    from alis.dashboard.qt import dialogs as D

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    boxes(window, outdir)
    window.answers["unsaved"] = "Don't save"
    pump(0.5)
    tmp = Path(tempfile.mkdtemp())

    if J1358.exists():
        # J1358p6522, its D I blinded as in the mockups, saved, and fitted once
        window.import_path(str(J1358))
        pump(1.0)
        blind_d_i(window)
        window.save_as = lambda: True
        window.session.save(str(tmp / "J1358p6522.model"))
        window.notice_banner.clear()
        tab = inspect(window)
        window.set_panel_open(False)
        window.start_run()
        wait_run(window)
        print("first run:", window.fit.job.status, window.fit.job.chi2)
        # O I started 0.3 dex higher, and run again, caught at its seventh
        # iteration: Ly8 923.2 (the mockup), the first run in grey
        session = window.session
        oxygen = next(
            ln for ln in session.project.parsed.lines if ln.ion == "16O_I"
        ).param("ColDens")
        session.history.do(
            session.project.step(
                E.set_value(session.project.parsed, oxygen, oxygen.start + 0.3),
                "Start O I higher",
            )
        )
        window.refresh()
        key = next(c.key for c in tab._choices if c.title == "Ly8 923.2 · H1")
        tab.show_choice(key)
        window.start_run()
        wait_run(window, until=lambda job: (job.iteration or 0) >= 7)
        pump(0.8)
        shoot(window, outdir / "inspect_running.png")
        window.fit.cancel()
        wait_run(window)
        session.history.undo()
        window.refresh()
        # The residuals of the fitted pixels only (RJC's review)
        tab.select("residuals", FV.FITTED_PIXELS)
        pump(0.8)
        shoot(window, outdir / "inspect_fitted_residuals.png")
        tab.select("residuals", FV.ALL_PIXELS)
        # After the first run: every snip, the latest run's best fit
        tab.show_choice(("all",))
        pump(1.0)
        shoot(window, outdir / "inspect_all.png")
        # H I with D I, beside the .mod panel
        window.set_panel_open(True, 460)
        tab.show_choice(("ion", "a", "1H_I"))
        pump(1.0)
        shoot(window, outdir / "inspect_ion.png")
        # O I 1302 in wavelength; the pre-flight check's notes shown
        window.set_panel_open(False)
        key = next(c.key for c in tab._choices if c.title == "O I 1302.2 · O4")
        tab.show_choice(key)
        tab.select("axis", FV.WAVELENGTH)
        tab.show_findings(True)
        pump(1.0)
        shoot(window, outdir / "inspect_wavelength.png")
        tab.select("axis", FV.VELOCITY)
        tab.show_findings(False)

    # metal_line_abs, fitted from the window: Initial and Final
    path = tmp / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    pump(1.0)
    window.notice_banner.clear()
    tab = inspect(window)
    window.set_panel_open(True, 460)
    window.start_run()
    wait_run(window)
    print("metal run:", window.fit.job.status, window.fit.job.chi2)
    tab.select("model", FV.INITIAL)
    pump(0.8)
    shoot(window, outdir / "inspect_metal_initial.png")
    tab.select("model", FV.FINAL)
    pump(0.8)
    shoot(window, outdir / "inspect_metal_final.png")

    # All settings…
    dialog = D.AllSettingsDialog(window.session.project, window.prefs, window)
    dialog.resize(1000, 640)
    dialog.filter.setText("chisq")
    dialog.show()
    pump(0.5)
    shoot(dialog, outdir / "all_settings.png")
    dialog.hide()

    # The question when the project closes during a run
    window.start_run()
    wait_run(window, until=lambda job: job.iteration is not None)
    if window.fit.active:
        window.next_shot["running"] = "closing.png"
        window.answers["running"] = "Don't close"
        window._close_run()
        window.fit.cancel()
        wait_run(window)

    # Run refused: sim perturb is for the command line only
    session = window.session
    project = session.project
    session.history.do(
        project.step(E.set_setting(project.parsed, "sim", "perturb", "10"), "Set")
    )
    window.refresh()
    window.next_shot["tell"] = "refused_box.png"
    window.start_run()
    pump(0.8)
    shoot(window, outdir / "inspect_refused.png")
    window.session.discard_recovery()


if __name__ == "__main__":
    main(sys.argv[1])
