"""Screenshots of the Fit tab's Results and Compare sub-tabs, and its tools, for the
review that closes Stage 6 (Task 6.11, Q6.1).

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen. Every
run here is a real fit, made from the window:

- J1358p6522, imported, its D I blinded as in the mockups, saved, fitted, and the
  run committed; then D I made a ratio to H I (``2H_I/1H_I``, still blinded) and
  fitted again: Results (beside the ``fit_results`` mockup), Compare of the two runs
  (beside ``fit_compare``), and Inspect's Final of the latest run;
- metal_line_abs, imported, its FWHM freed and fitted: Continue from best fit and
  the Data tab's Reset FWHM (↺); Use best fit on a card and in the Continuum box;
  random restarts and their window; ALIS's convergence check in Fit statistics;
  and Review clipped pixels… with outliers added to its data.

Run it from the repository root::

    python doc/dashboard/stage6/take_close_screenshots.py OUTDIR

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import time
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]


def _skeleton():
    """The skeleton's screenshot helpers (this folder has a module of that name)."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
J1358, blind_d_i, pump, shoot = _SK.J1358, _SK.blind_d_i, _SK.pump, _SK.shoot

METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


def wait_run(window, until=None, timeout=900.0):
    """Let the run go on until it ends, or until ``until(job)`` holds."""
    start = time.time()
    while window.fit.active and time.time() - start < timeout:
        if until is not None and until(window.fit.job):
            return
        pump(0.1)
    pump(0.5)


def boxes(window):
    """The window's questions, answered as a script would (``window.answers``)."""

    def ask(kind, title, text, choices, default=None, icon="question"):
        answer = window.answers.get(kind)
        return answer if answer in choices else choices[-1]

    window.answers = {}
    window.ask = ask


def show(window, sub):
    """The Fit tab's sub-tab ``sub`` (0 Inspect, 1 Results, 2 Compare), shown."""
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(sub)
    window.refresh()
    pump(0.8)


def ratio_model(text):
    """J1358p6522's D I line as a ratio to H I (``2H_I/1H_I``), its blinding kept."""
    import re

    found = re.search(r"^ *voigt +ion=2H_I .*$", text, re.M)
    words = found.group(0).split()
    keep = [w for w in words if w.startswith(("specid=", "blind="))]
    line = "  voigt   ion=2H_I/1H_I   -4.6   " + "   ".join(keep)
    return text[: found.start()] + line + text[found.end() :]


def j1358(window, outdir, tmp):
    """J1358p6522: two runs, Results, Compare, Final."""
    from alis.dashboard import text as T

    window.import_path(str(J1358))
    pump(1.0)
    blind_d_i(window)
    window.session.save(str(tmp / "J1358p6522.model"))
    window.notice_banner.clear()
    window.set_panel_open(False)
    show(window, 0)
    window.start_run()
    wait_run(window)
    print("J1358 run 1:", window.fit.job.status, window.fit.job.chi2)
    window.on_dialog = lambda dialog: dialog.set("description", "D I's own N") or 1
    window.do_fit_commit()
    session = window.session
    project = session.project
    text = ratio_model(project.text)
    session.history.do(
        project.step(T.Change((T.Patch(0, project.text, text),)), "D I as a ratio")
    )
    window.refresh()
    window.start_run()
    wait_run(window)
    print("J1358 run 2:", window.fit.job.status, window.fit.job.chi2)
    show(window, 1)
    results = window.fit_tab.results
    results.show_run(1)
    pump(0.8)
    shoot(window, outdir / "results.png")
    results.show_run(None)
    show(window, 2)
    compare = window.fit_tab.compare
    key = next(c.key for c in compare._choices if c.title == "Lyα 1215.7 · H8")
    compare.show_choice(key)
    pump(1.0)
    shoot(window, outdir / "compare.png")
    key = next(c.key for c in compare._choices if c.title == "Ly8 923.2 · H1")
    compare.show_choice(key)
    pump(1.0)
    shoot(window, outdir / "compare_ly8.png")


def metal(window, outdir, tmp):
    """metal_line_abs: Continue and Reset FWHM, Use best fit, restarts, the
    convergence check, Review clipped pixels."""
    import numpy as np

    from alis.dashboard import datasets as DS
    from alis.dashboard import edit as E
    from alis.dashboard import snips as SN
    from alis.dashboard.qt import fittools as FTL

    window.import_path(str(METAL))
    pump(1.0)
    window.session.save(str(tmp / "metal.model"))
    window.notice_banner.clear()
    session = window.session
    project = session.project
    session.history.do(
        DS.set_state_step(project, project.rows[0], "resolution", DS.FREE)
    )
    window.set_panel_open(True, 460)
    show(window, 0)
    window.start_run()
    wait_run(window)
    print("metal run:", window.fit.job.status, window.fit.job.chi2)
    # Continue from best fit: the FWHM moves from the 7 km/s it was imported with
    window.on_dialog = lambda dialog: 1
    window.do_fit_continue()
    window.tabs.setCurrentIndex(0)
    window.refresh()
    pump(0.8)
    shoot(window, outdir / "reset_fwhm.png")
    # Use best fit on a card, after b_turb was changed
    oxygen = next(ln for ln in project.parsed.lines if ln.ion == "16O_I")
    session.history.do(
        project.step(E.set_value(project.parsed, oxygen.param("bturb"), 9.0), "b")
    )
    window.tabs.setCurrentIndex(2)
    tab = window.tab_widgets[2]
    tab.show_ion(project.systems[0].id, "16O_I")
    window.refresh()
    pump(0.8)
    shoot(window, outdir / "card.png")
    comp = project.systems[0].components[0]
    tab.card_widgets[comp.id].best.click()
    # Use best fit in the Continuum box, its order raised
    window.tabs.setCurrentIndex(1)
    regions = window.tab_widgets[1]
    regions.show_items([project.snips[0]])
    window.refresh()
    regions._act("regions.order_up", regions.do_order_up)
    regions._act("regions.best_fit", regions.use_best_fit)
    window.qactions["regions.model"].trigger()
    pump(0.8)
    shoot(window, outdir / "continuum.png")
    window.qactions["regions.model"].trigger()
    # Random restarts, run from the window, and their window
    window.set_panel_open(False)
    show(window, 0)

    def run_them(dialog):
        if isinstance(dialog, FTL.RestartsDialog):
            dialog.count.setValue(8)
            dialog.run_button.click()
            return 1
        return 0

    window.on_dialog = run_them
    window.do_fit_restarts()
    wait_run(window, until=lambda job: (job.restart or 0) >= 3)
    pump(0.5)
    shoot(window, outdir / "restarts_running.png")
    wait_run(window)

    def look(dialog):
        dialog.resize(900, 640)
        dialog.show()
        pump(0.6)
        shoot(dialog, outdir / "restarts.png")
        dialog.hide()
        return 0

    window.on_dialog = look
    window.do_fit_restarts()
    # ALIS's convergence check, then Fit statistics
    window.on_dialog = lambda dialog: 1
    window.do_fit_convergence()
    wait_run(window)
    print("convergence:", window.fit.job.status)
    show(window, 1)
    shoot(window, outdir / "results_metal.png")
    # Review clipped pixels…, with outliers added to the data
    snip = project.snips[0]
    fitted = np.flatnonzero(SN.fitted(snip))
    places = [fitted[40], fitted[150], fitted[151], fitted[152]]
    session.history.do(_push(project, snip, places, 25.0))
    show(window, 0)
    window.do_fit_outliers()
    pump(0.8)
    shoot(window, outdir / "review.png")
    window.fit_tab.inspect.end_review()


def _push(project, snip, places, sigma):
    """The step that moves some pixels of a snip's file by ``sigma`` errors."""
    from alis.dashboard import project as P

    member = snip.member
    old = project.files[member]
    lines = old.decode("utf-8").splitlines(keepends=True)
    rows = snip.pixels.rows
    for place in places:
        words = lines[rows[place]].split()
        flux, err = float(words[1]), float(words[2])
        words[1] = repr(flux + sigma * err)
        lines[rows[place]] = " ".join(words) + "\n"
    return P.Step("Add outliers", files={member: (old, "".join(lines).encode("utf-8"))})


def main(outdir):
    """
    Take every screenshot.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    boxes(window)
    window.answers["unsaved"] = "Don't save"
    window.answers["outliers_run"] = "Later"
    window.run_dialog = lambda dialog: (window.on_dialog or (lambda d: 0))(dialog)
    window.on_dialog = None
    pump(0.5)
    tmp = Path(tempfile.mkdtemp())
    start = time.time()
    if J1358.exists():
        j1358(window, outdir, tmp)
    metal(window, outdir, tmp)
    window.session.discard_recovery()
    print("done in {0:.0f} s".format(time.time() - start))


if __name__ == "__main__":
    main(sys.argv[1])
