def load_j1358():
    """
    Load everything the mockups use from the J1358p6522 fit.

    Returns
    -------
    dict
        ``spec`` (the full spectrum), ``mod`` (the input model, read with
        ``read_blocks``), ``out`` (the reference ``.mod.out``), ``snips``
        (per specid: name, file, snip, fit, continuum coefficients, badge),
        ``voigt`` and ``verr`` (best-fit voigt lines and their errors),
        ``covar`` and ``stats`` (the header numbers of the ``.mod.out``).

    Generated by RJC and Claude.
    """
    spec = np.loadtxt(os.path.join(J13, "data", "J1358p6522_fluxcal.dat"))
    mod = read_blocks(os.path.join(J13, "model", "J1358p6522.mod"))
    out = read_blocks(os.path.join(J13, "model",
                                   "J1358p6522.mod.out.reference"))
    snips = {}
    for line in mod["data"]:
        dln = parse_data_line(line)
        if dln is None:
            continue
        sid = dln["kw"]["specid"]
        base = os.path.basename(dln["file"])
        snp = read_snip(os.path.join(J13, "data", base))
        fit = read_fit(os.path.join(J13, "data", "reference_fits",
                                    base.replace(".dat", "_fit.dat")))
        ion, rest = J13_SNIPS[sid]
        snips[sid] = {"ion": ion, "rest": rest, "file": base, "snip": snp,
                      "fit": fit, "coef": legendre_coeffs(out["model"], sid),
                      "badge": region_badge(fit)}
    voigt = [parse_voigt(ln) for ln in out["model"]
             if ln.strip().startswith("voigt")]
    verr = [parse_voigt(ln) for ln in out["errors"]
            if ln.strip().startswith("voigt")]
    stats = {}
    for line in out["text"].splitlines()[:12]:
        if "=" in line:
            key, val = line.lstrip("#").split("=", 1)
            stats[key.strip()] = val.strip()
    covar = np.loadtxt(os.path.join(J13, "model", "J1358p6522.covar.reference"))
    return {"spec": spec, "mod": mod, "out": out, "snips": snips,
            "voigt": voigt, "verr": verr, "covar": covar, "stats": stats}


def load_q1243():
    """
    Load the dataset structure and the O I 1302.2 snips of Q1243p307.

    Returns
    -------
    dict
        ``datasets`` (per label: resolution, shift and the transitions it
        covers), ``others`` (the other systems and their snips), ``extents``
        (the wavelength range of every snip) and ``oi`` (per label: the
        O I 1302.2 and Si II 1304.4 snips, the shared-pixel masks, and the
        frame shift in km/s).

    Generated by RJC and Claude.
    """
    mod = read_blocks(os.path.join(
        Q12, "model", "Q1243p307_converge_newstart76.mod"))
    datasets, others, extents = {}, {}, []
    for line in mod["data"]:
        dln = parse_data_line(line)
        if dln is None:
            continue
        base = os.path.basename(dln["file"])
        name = base[len("Q1243p307_"):-len("_reg.dat")]
        kw = dln["kw"]
        wav = np.loadtxt(os.path.join(Q12, "data", base), usecols=0)
        extents.append((float(wav.min()), float(wav.max())))
        if name.startswith("zabs"):
            zstr, trans = name.split("_", 1)
            others.setdefault(zstr, []).append(trans.replace("_", " "))
            continue
        for pre in ("prochaska_", "kirkman_"):
            name = name.replace(pre, "")
        dset = datasets.setdefault(kw["label"], {
            "resolution": kw["resolution"], "shift": kw.get("shift", ""),
            "trans": []})
        dset["trans"].append(name.replace("_", " "))
    oi = {}
    for label, pre, shift in (("HIRES", "", 0.0),
                              ("PROCHASKA", "prochaska_", 0.0),
                              ("KIRKMAN", "kirkman_", KIRKMAN_SHIFT)):
        o_snp = read_snip(os.path.join(Q12, "data",
                                       f"Q1243p307_{pre}O_I_1302.2_reg.dat"))
        s_snp = read_snip(os.path.join(Q12, "data",
                                       f"Q1243p307_{pre}Si_II_1304.4_reg.dat"))
        oi[label] = {"oi": o_snp, "si": s_snp,
                     "shared": shared_pixel_mask(o_snp, s_snp),
                     "shared_si": shared_pixel_mask(s_snp, o_snp),
                     "shift": shift}
    return {"datasets": datasets, "others": others, "extents": extents,
            "oi": oi}


