GREEK = {2: "Lyα", 3: "Lyβ", 4: "Lyγ", 5: "Lyδ", 6: "Lyε"}


def trans_name(elem, stage, lam):
    """
    Display name of a transition; Lyman lines get their usual names.

    Parameters
    ----------
    elem, stage : str
        Element and ionisation stage.
    lam : float
        Rest wavelength in Angstroms.

    Returns
    -------
    str
        For example 'Ly7 926.2' or 'O I 1302.2'.

    Generated by RJC and Claude.
    """
    if elem == "H" and stage == "I":
        upper = int(round(1.0 / np.sqrt(1.0 - 911.7536 / lam)))
        return f"{GREEK.get(upper, f'Ly{upper - 1}')} {lam:.1f}"
    return f"{elem} {stage} {lam:.1f}"


def j13_flagger(j13):
    """
    Flags for a transition observed at a given wavelength in J1358p6522.

    Parameters
    ----------
    j13 : dict
        The J1358p6522 data.

    Returns
    -------
    callable
        Maps an observed wavelength to a list of flags ('gap', 'forest',
        'edge'), or None when the spectrum does not reach it.

    Generated by RJC and Claude.
    """
    wave = j13["spec"][:, 0]
    wlo, whi = wave.min(), wave.max()
    lya = 1215.6701 * (1 + Z_J13)

    def flag(obs):
        if not wlo < obs < whi:
            return None
        near = np.searchsorted(wave, obs)
        dist = min(abs(wave[min(near, wave.size - 1)] - obs),
                   abs(wave[max(near - 1, 0)] - obs))
        flags = ["gap"] if dist > 2.0 else []
        if obs < lya - 1.0:
            flags.append("forest")
        if obs - wlo < 15 or whi - obs < 15:
            flags.append("edge")
        return flags

    return flag


def browser_rows(atom, elem, stage, zsys, flagger, snipped, fmin=1.0e-3):
    """
    The transitions of one ion that the data cover, ranked by f lambda (S2).

    Isotopes are not listed separately: only the most abundant one is used.
    Transitions with no data (outside every file, or in a gap) are left out,
    unless they already have a snip (draft 3).

    Parameters
    ----------
    atom : dict
        Atomic data.
    elem, stage : str
        Element and ionisation stage.
    zsys : float
        Redshift of the system chosen in the list.
    flagger : callable
        Maps an observed wavelength to a list of flags, or None to skip it.
    snipped : list of float
        Rest wavelengths that already have a snip.
    fmin : float
        Weakest oscillator strength listed.

    Returns
    -------
    list of dict
        ``name``, ``obs``, ``flam``, ``flags`` and ``snip`` per transition.

    Generated by RJC and Claude.
    """
    sel = (atom["element"] == elem) & (atom["ion"] == stage)
    mass = np.bincount(atom["mass"][sel]).argmax()
    sel &= (atom["mass"] == mass) & (atom["fval"] > fmin)
    rows = []
    for lam, fval in sorted(zip(atom["wave"][sel], atom["fval"][sel])):
        flags = flagger(lam * (1 + zsys))
        if flags is None:
            continue
        snip = any(abs(lam - s) < 0.6 for s in snipped)
        if not snip and ("gap" in flags or "no data" in flags):
            continue
        # Lines closer than 0.05 A (fine-structure blends) share one row
        if rows and lam - rows[-1]["rest"] < 0.05:
            rows[-1]["flam"] += fval * lam
            rows[-1]["nblend"] += 1
            continue
        rows.append({"name": trans_name(elem, stage, lam), "rest": lam,
                     "obs": lam * (1 + zsys), "flam": fval * lam,
                     "flags": flags, "nblend": 1, "snip": snip})
    for row in rows:
        if row["nblend"] > 1:
            row["name"] += f" ×{row['nblend']}"
    rows.sort(key=lambda r: -r["flam"])
    return rows


def transition_browser(rows, system, elem, stages, stage, current, nrows=21):
    """
    The transition list: choose a system, element and ion stage (S2).

    Parameters
    ----------
    rows : list of dict
        Rows from ``browser_rows``.
    system : str
        The system shown, e.g. 'z = 3.067258 · primary'.
    elem : str
        The element shown.
    stages : tuple of str
        Ion stages that have transitions for this element.
    stage : str
        The ion stage shown.
    current : str
        Name of the transition shown in the main panel.
    nrows : int
        How many rows to show.

    Returns
    -------
    str
        HTML.

    Generated by RJC and Claude.
    """
    stg = "".join(
        f"<b>{s}</b>" if s == stage else
        (f"<span>{s}</span>" if s in stages else f'<span class="off">{s}</span>')
        for s in ("I", "II", "III", "IV"))
    out = [f'<div class="bhead">System <span class="sel wide">{system} ▾'
           '</span></div>'
           f'<div class="bhead">Element <span class="sel">{elem} ▾</span>'
           '<span class="btn xs">‹</span><span class="btn xs">›</span>'
           f'<span class="grow"></span><span class="seg sm">{stg}</span></div>'
           '<table class="covlist"><tr><th></th><th>Transition</th>'
           '<th>λ<sub>obs</sub></th><th>fλ</th><th></th></tr>']
    fmax = np.log10(rows[0]["flam"])
    for row in rows[:nrows]:
        frac = max(0.05, 1 - (fmax - np.log10(row["flam"])) / 4.0)
        flags = "".join(f'<span class="flag {f.replace(" ", "")}">{f}</span>'
                        for f in row["flags"])
        cls = " cur" if row["name"] == current else ""
        dot = '<span class="dot">●</span>' if row["snip"] else ""
        out.append(f'<tr class="{"snip" if row["snip"] else ""}{cls}">'
                   f'<td>{dot}</td><td>{row["name"]}</td>'
                   f'<td class="num">{row["obs"]:.1f}</td>'
                   f'<td><i class="bar" style="width:{36 * frac:.0f}px"></i>'
                   f'</td><td>{flags}</td></tr>')
    if len(rows) > nrows:
        out.append(f'<tr class="divider"><td colspan="5">{len(rows) - nrows} '
                   'weaker transitions ▾</td></tr>')
    out.append('</table><div class="muted small">Only transitions with data '
               'are listed. Click one to show it; <b>SNIP</b> makes it a snip '
               '(<span class="dot">●</span>), <b>CLEAR</b> undoes that.</div>')
    return "".join(out)


