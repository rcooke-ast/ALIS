def find_comp(j13, ion, zapprox, specid=None):
    """
    Index of the best-fit voigt line of an ion nearest a redshift.

    Parameters
    ----------
    j13 : dict
        The J1358p6522 data.
    ion : str
        Ion string, e.g. '1H_I'.
    zapprox : float
        Approximate redshift.
    specid : str, optional
        Only consider lines fitted to this specid.

    Returns
    -------
    int
        Index into ``j13['voigt']`` (and ``j13['verr']``).

    Generated by RJC and Claude.
    """
    best, dist = 0, np.inf
    for i, comp in enumerate(j13["voigt"]):
        if comp["ion"] != ion:
            continue
        if specid is not None and specid not in comp["specid"]:
            continue
        if abs(comp["z"][0] - zapprox) < dist:
            best, dist = i, abs(comp["z"][0] - zapprox)
    return best


