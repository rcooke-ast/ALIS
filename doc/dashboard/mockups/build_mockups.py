def correlation_svg(j13, cell=16):
    """
    Correlation matrix of the primary system's parameters (S19).

    Parameters are matched to their slots in the covariance file by their
    errors, because the file also holds slots for fixed and tied parameters.

    Parameters
    ----------
    j13 : dict
        The J1358p6522 data.
    cell : int
        Size of one cell in pixels.

    Returns
    -------
    str
        SVG.

    Generated by RJC and Claude.
    """
    sig = np.sqrt(np.abs(np.diag(j13["covar"])))
    picks = [("1H_I", 3.067258, "N", "N(H I)₁"), ("1H_I", 3.067258, "z", "z₁"),
             ("1H_I", 3.067258, "b", "b(H I)₁"),
             ("1H_I", 3.067162, "N", "N(H I)₂"), ("1H_I", 3.067162, "z", "z₂"),
             ("1H_I", 3.067162, "b", "b(H I)₂"),
             ("2H_I", 3.067258, "N", "N(D I)"), ("2H_I", 3.067258, "b", "b(D I)"),
             ("16O_I", 3.067258, "N", "N(O I)"), ("16O_I", 3.067258, "b", "b(O I)")]
    idx, names = [], []
    for ion, zap, par, name in picks:
        err = j13["verr"][find_comp(j13, ion, zap)][par][0]
        best = int(np.argmin(np.abs(sig - err)))
        if abs(sig[best] - err) < 1e-3 * err:
            idx.append(best)
            names.append(name)
    cov = j13["covar"][np.ix_(idx, idx)]
    corr = cov / np.outer(np.sqrt(np.diag(cov)), np.sqrt(np.diag(cov)))
    x0, y0 = 62, 6
    nn = len(idx)
    out = []
    for i in range(nn):
        out.append(f'<text class="tk" x="{x0 - 4}" '
                   f'y="{y0 + cell * i + cell / 2 + 3:.0f}" text-anchor="end">'
                   f'{names[i]}</text>')
        for j in range(nn):
            val = corr[i, j]
            col = (f"rgba(213,94,0,{abs(val):.2f})" if val > 0
                   else f"rgba(0,114,178,{abs(val):.2f})")
            out.append(f'<rect x="{x0 + cell * j}" y="{y0 + cell * i}" '
                       f'width="{cell - 1}" height="{cell - 1}" fill="{col}" '
                       f'stroke="#ddd"><title>{names[i]} – {names[j]}: '
                       f'{val:+.2f}</title></rect>')
            if cell >= 22 and i != j and abs(val) >= 0.3:
                out.append(f'<text class="cv" x="{x0 + cell * j + cell / 2:.0f}"'
                           f' y="{y0 + cell * i + cell / 2 + 3:.0f}" '
                           f'text-anchor="middle">{val:+.1f}</text>')
    yk = y0 + cell * nn + 16
    out.append(f'<text class="tk" x="{x0}" y="{yk}">orange: +1 · blue: −1 · '
               'values shown where |r| ≥ 0.3</text>')
    return (f'<svg class="plot" width="{x0 + cell * nn + 8}" height="{yk + 6}" '
            f'viewBox="0 0 {x0 + cell * nn + 8} {yk + 6}">{"".join(out)}</svg>')


def results_table(j13):
    """
    The full results table (S19) for the Results sub-tab.

    Parameters
    ----------
    j13 : dict
        The J1358p6522 data.

    Returns
    -------
    str
        HTML.

    Generated by RJC and Claude.
    """
    rows = []

    def add(name, idx, par, fmt, blind=False, flag=""):
        comp, err = j13["voigt"][idx], j13["verr"][idx]
        val = BLIND if blind else fmt.format(comp[par][0])
        lab = comp[par][1]
        tie = state("tied", lab) if lab and lab.islower() else (
            state("fixed") if lab else state("free"))
        rows.append(f'<tr><td>{name}</td><td class="num">{val}</td>'
                    f'<td class="num">± {fmt.format(err[par][0])}</td>'
                    f'<td>{tie}</td><td>{flag}</td></tr>')

    rows.append('<tr class="group"><td colspan="5">▾ Primary system, '
                'z = 3.067258</td></tr>')
    for ion, zap, lab in (("1H_I", 3.067258, "H I c1"),
                          ("1H_I", 3.067162, "H I c2")):
        i = find_comp(j13, ion, zap)
        add(f"{lab} log N", i, "N", "{:.3f}")
        add(f"{lab} z", i, "z", "{:.7f}")
        add(f"{lab} b", i, "b", "{:.2f}")
    i = find_comp(j13, "2H_I", 3.067258)
    add("D I c1 log N", i, "N", "{:.3f}", blind=True,
        flag='<span class="flag">blinded</span>')
    add("D I c1 b", i, "b", "{:.2f}",
        flag='<span class="flag edge">not tied to H I</span>')
    i = find_comp(j13, "16O_I", 3.067258, "O4")
    add("O I c1 log N", i, "N", "{:.3f}")
    add("O I c1 b", i, "b", "{:.2f}")
    rows.append('<tr class="group"><td colspan="5">▸ Lyα forest '
                '(57 components) · flagged rows shown</td></tr>')
    for i, comp in enumerate(j13["voigt"]):
        if comp["ion"] != "1Ly_a":
            continue
        bval, berr = comp["b"][0], j13["verr"][i]["b"][0]
        if bval < 0.5:
            flag = '<span class="flag bad">at limit (0.2)</span>'
        elif berr > bval:
            flag = '<span class="flag edge">unconstrained</span>'
        else:
            continue
        add(f"Lyα z={comp['z'][0]:.4f} b", i, "b", "{:.2f}", flag=flag)
    rows.append('<tr class="group"><td colspan="5">▸ Continua (12 Legendre '
                'polynomials) · ▸ Instrument: FWHM 6.931 ± 0.171 km/s</td></tr>')
    return ('<table class="grid tight results"><tr><th>Parameter</th>'
            '<th>Value</th><th>Error</th><th>State</th><th>Flags</th></tr>'
            + "".join(rows) + "</table>")


