def read_blocks(path):
    """
    Split an ALIS model file (``.mod`` or ``.mod.out``) into its blocks.

    Parameters
    ----------
    path : str
        Path to the model file.

    Returns
    -------
    dict
        ``text`` (the whole file), ``settings`` (lines before ``data read``),
        ``data`` and ``model`` (the lines inside those blocks) and ``errors``
        (the de-commented model lines of the ``# Errors`` block of a
        ``.mod.out``; empty for a ``.mod``).

    Generated by RJC and Claude.
    """
    with open(path) as fil:
        text = fil.read()
    head, rest = text.split("data read", 1)
    data, rest = rest.split("data end", 1)
    model, rest = rest.split("model read", 1)[1].split("model end", 1)
    errors = []
    if "# Errors:" in rest:
        # The errors block repeats the model lines, commented out with '#',
        # and ends at the first blank line
        for line in rest.split("# Errors:", 1)[1].splitlines()[1:]:
            if not line.strip():
                break
            line = line.lstrip("#").rstrip()
            if line.strip().startswith(("legendre", "voigt")):
                errors.append(line)
    return {"text": text, "settings": head.splitlines(),
            "data": data.splitlines(), "model": model.splitlines(),
            "errors": errors}


def parse_data_line(line):
    """
    Parse one line of a ``data read`` block.

    Parameters
    ----------
    line : str
        The line, which may be commented out.

    Returns
    -------
    dict or None
        ``file`` (the path as written) and ``kw`` (the keyword values), or
        None for a blank or commented line.

    Generated by RJC and Claude.
    """
    line = line.strip()
    if not line or line.startswith("#"):
        return None
    toks = line.split()
    kw = dict(t.split("=", 1) for t in toks[1:] if "=" in t)
    return {"file": toks[0], "kw": kw}


_NUM = re.compile(r"^([-+]?\d*\.?\d+(?:[eE][-+]?\d+)?)(.*)$")


def split_value(token):
    """
    Split a parameter token such as ``3.0672596274ra`` into value and label.

    Parameters
    ----------
    token : str
        A model parameter as written in a ``.mod`` file.

    Returns
    -------
    tuple of (float, str)
        The value and its label ('' when there is none).

    Generated by RJC and Claude.
    """
    mtch = _NUM.match(token)
    return float(mtch.group(1)), mtch.group(2)


def parse_voigt(line):
    """
    Parse one ``voigt`` line of a model block.

    Parameters
    ----------
    line : str
        A model line beginning with ``voigt`` (not commented out).

    Returns
    -------
    dict
        ``ion``; ``N``, ``z``, ``b``, ``T`` as (value, label) pairs; and
        ``specid`` (a list of the specids it applies to).

    Generated by RJC and Claude.
    """
    toks = line.split()
    kw = dict(t.split("=", 1) for t in toks[1:] if "=" in t)
    pars = [split_value(t) for t in toks[1:] if "=" not in t]
    return {"ion": kw["ion"], "N": pars[0], "z": pars[1], "b": pars[2],
            "T": pars[3], "specid": kw["specid"].split(",")}


def legendre_coeffs(model_lines, specid):
    """
    Return the scaled Legendre continuum coefficients for one specid.

    ALIS multiplies each coefficient by its ``scale=`` factor; with that
    applied, evaluating on the snip's wavelength range mapped to [-1, 1]
    reproduces the continuum column of ``_fit.dat`` (log, Task 0.1).

    Parameters
    ----------
    model_lines : list of str
        The lines of a model block.
    specid : str
        The specid whose continuum is wanted.

    Returns
    -------
    numpy.ndarray
        The scaled coefficients.

    Generated by RJC and Claude.
    """
    for line in model_lines:
        toks = line.split()
        if toks and toks[0] == "legendre" and "specid=" + specid in toks:
            coef = [float(t) for t in toks[1:] if "=" not in t]
            scl = [t for t in toks if t.startswith("scale=")][0][6:].split(",")
            return np.array(coef) * np.array([float(s) for s in scl])
    raise ValueError("No legendre line for specid " + specid)


def read_fit(path):
    """
    Read a seven-column ``_fit.dat`` file written by ALIS.

    Parameters
    ----------
    path : str
        Path to the file.

    Returns
    -------
    dict
        Arrays ``wave``, ``flux``, ``err``, ``mask`` (bool), ``cont`` and
        ``model``. Sentinel values (outside the fit range) become NaN.

    Generated by RJC and Claude.
    """
    dat = np.loadtxt(path, ndmin=2)
    out = {"wave": dat[:, 0], "flux": dat[:, 1], "err": dat[:, 2],
           "mask": dat[:, 3] > 0.5}
    for key, col in (("cont", 4), ("model", 6)):
        arr = dat[:, col].copy()
        arr[arr < SENTINEL] = np.nan
        out[key] = arr
    return out


def read_snip(path):
    """
    Read a four-column snip (wave, flux, error, 0/1 fit mask).

    Parameters
    ----------
    path : str
        Path to the snip.

    Returns
    -------
    dict
        Arrays ``wave``, ``flux``, ``err`` and ``mask`` (bool).

    Generated by RJC and Claude.
    """
    dat = np.loadtxt(path, ndmin=2)
    return {"wave": dat[:, 0], "flux": dat[:, 1], "err": dat[:, 2],
            "mask": dat[:, 3] > 0.5}


def eval_legendre(coef, wave, wmin, wmax):
    """
    Evaluate a Legendre continuum on a wavelength grid.

    Parameters
    ----------
    coef : numpy.ndarray
        Scaled coefficients (see ``legendre_coeffs``).
    wave : numpy.ndarray
        Wavelengths at which to evaluate.
    wmin, wmax : float
        The snip's wavelength range, which maps to [-1, 1].

    Returns
    -------
    numpy.ndarray
        The continuum.

    Generated by RJC and Claude.
    """
    xval = 2.0 * (wave - wmin) / (wmax - wmin) - 1.0
    return legendre.legval(xval, coef)


def shared_pixel_mask(snip_a, snip_b):
    """
    Flag the fitted pixels of one snip that are also fitted in another.

    Pixels are matched on wavelength and flux/error, as in QF.21, so a snip
    that was multiplied by a continuum still matches its source.

    Parameters
    ----------
    snip_a, snip_b : dict
        Snips as returned by ``read_snip``.

    Returns
    -------
    numpy.ndarray
        Boolean array over ``snip_a``'s pixels.

    Generated by RJC and Claude.
    """
    def keys(snp):
        with np.errstate(all="ignore"):
            ratio = snp["flux"] / snp["err"]
        return set(zip(np.round(snp["wave"][snp["mask"]], 6),
                       np.round(ratio[snp["mask"]], 5)))

    other = keys(snip_b)
    with np.errstate(all="ignore"):
        ratio = snip_a["flux"] / snip_a["err"]
    pairs = zip(np.round(snip_a["wave"], 6), np.round(ratio, 5))
    hit = np.array([p in other for p in pairs])
    return hit & snip_a["mask"]


def region_badge(fit):
    """
    Grade the fit of one snip, as ``alis/report.py`` does.

    The reduced chi-squared and the runs test are graded separately and both
    are shown (Q0.4: keep both, and let the user judge).

    Parameters
    ----------
    fit : dict
        A fit as returned by ``read_fit``.

    Returns
    -------
    dict
        ``redchi2``, ``dev`` (its deviation from 1 in sigma), ``runs`` (the
        runs-test z), ``npix``, and the grades ``g_chi`` and ``g_runs``.

    Generated by RJC and Claude.
    """
    use = fit["mask"] & np.isfinite(fit["model"])
    resid = (fit["flux"][use] - fit["model"][use]) / fit["err"][use]
    npix = resid.size
    redchi2 = float(np.sum(resid**2)) / npix
    dev = (redchi2 - 1.0) / np.sqrt(2.0 / npix)
    runs = float(_runs_z(resid))
    return {"redchi2": redchi2, "dev": dev, "runs": runs, "npix": npix,
            "g_chi": grade(dev), "g_runs": grade(abs(runs))}


