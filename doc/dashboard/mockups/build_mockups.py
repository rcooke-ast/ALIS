def ion_lines(atom, ionstr, fmin=1.0e-3):
    """
    Rest wavelengths of an ALIS ion string such as ``16O_I`` or ``1Ly_a``.

    Parameters
    ----------
    atom : dict
        Atomic data from ``load_atomic``.
    ionstr : str
        The ion as written in a ``.mod`` (mass number, element, ion stage).
    fmin : float
        Weakest oscillator strength kept.

    Returns
    -------
    numpy.ndarray
        Rest wavelengths in Angstroms.

    Generated by RJC and Claude.
    """
    if ionstr == "1Ly_a":
        return np.array([1215.6701])
    mtch = re.match(r"^(\d+)([A-Za-z]+)_([IVX]+)$", ionstr)
    mass, elem, stage = int(mtch.group(1)), mtch.group(2), mtch.group(3)
    sel = ((atom["element"] == elem) & (atom["ion"] == stage)
           & (atom["mass"] == mass) & (atom["fval"] > fmin))
    return atom["wave"][sel]


def nearest_rest(atom, elem, stage, approx, mass=None):
    """
    The tabulated rest wavelength closest to an approximate value.

    Parameters
    ----------
    atom : dict
        Atomic data from ``load_atomic``.
    elem, stage : str
        Element and ionisation stage, e.g. 'O' and 'I'.
    approx : float
        Approximate rest wavelength.
    mass : int, optional
        Mass number (e.g. 2 for D I).

    Returns
    -------
    tuple of (float, float)
        Rest wavelength and oscillator strength.

    Generated by RJC and Claude.
    """
    sel = (atom["element"] == elem) & (atom["ion"] == stage)
    if mass is not None:
        sel &= atom["mass"] == mass
    idx = np.flatnonzero(sel)
    best = idx[np.argmin(np.abs(atom["wave"][idx] - approx))]
    return float(atom["wave"][best]), float(atom["fval"][best])


ION_CLASS = {"1H_I": "t-h", "2H_I": "t-d", "16O_I": "t-o", "1Ly_a": "t-x"}


def feature_ticks(plot, j13, atom, specid, rest, zsys, own, y_lo, y_hi):
    """
    Mark every fitted component that absorbs in one velocity panel.

    Parameters
    ----------
    plot : Plot
        The panel (x axis in km/s).
    j13 : dict
        The J1358p6522 data from ``load_j1358``.
    atom : dict
        Atomic data.
    specid : str
        The snip shown in the panel; only components fitted to it are drawn.
    rest : float
        Rest wavelength that defines zero velocity in the panel.
    zsys : float
        System redshift.
    own : tuple of str
        Ion strings being edited; others are drawn locked (grey).
    y_lo, y_hi : float
        Vertical extent of the ticks in data units.

    Returns
    -------
    str
        SVG markup.

    Generated by RJC and Claude.
    """
    out = []
    for comp in j13["voigt"]:
        if specid not in comp["specid"]:
            continue
        zcomp = comp["z"][0]
        fmin = 1.0e-4 if comp["ion"] in own else 0.003
        for lam in ion_lines(atom, comp["ion"], fmin=fmin):
            vv = float(vel(lam * (1.0 + zcomp), rest, zsys))
            if not plot.xlim[0] < vv < plot.xlim[1]:
                continue
            if comp["ion"] in own:
                cls = ION_CLASS.get(comp["ion"], "t-x")
                out.append(plot.vline(vv, f"tick-own {cls}", y_lo, y_hi))
                xx = float(plot.px(vv))
                out.append(f'<circle class="grab {cls}" cx="{xx:.1f}" '
                           f'cy="{float(plot.py(y_hi)):.1f}" r="3.2"/>')
            else:
                out.append(plot.vline(vv, "tick-lock", y_lo, y_hi))
    return "".join(out)


def normalised(info):
    """
    Data and model of one J1358p6522 snip divided by its continuum.

    Parameters
    ----------
    info : dict
        One entry of ``load_j1358()['snips']``.

    Returns
    -------
    dict
        ``wave``, ``flux``, ``model`` and ``resid`` (``(data - model)/error``
        on fitted pixels, NaN elsewhere), plus ``cont``.

    Generated by RJC and Claude.
    """
    fit = info["fit"]
    wave = fit["wave"]
    cont = eval_legendre(info["coef"], wave, wave.min(), wave.max())
    resid = np.where(fit["mask"] & np.isfinite(fit["model"]),
                     (fit["flux"] - fit["model"]) / fit["err"], np.nan)
    return {"wave": wave, "flux": fit["flux"] / cont,
            "model": fit["model"] / cont, "resid": resid, "cont": cont}


