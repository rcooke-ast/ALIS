def main():
    """
    Build every mockup page, the index and, optionally, the combined page.

    Generated by RJC and Claude.
    """
    parser = argparse.ArgumentParser(
        description="Build the static mockups of the ALIS dashboard.")
    parser.add_argument("--publish", metavar="DIR",
                        help="also write all mockups as one page to DIR")
    args = parser.parse_args()

    atom = load_atomic()
    j13 = load_j1358()
    q12 = load_q1243()
    dh = load_dh_run()
    mlines = masked_mod_lines(j13["mod"]["text"])
    pages = [page_data_new(j13, atom), page_data_datasets(q12),
             page_regions(j13, atom, mlines), page_regions_datasets(q12, atom),
             page_components(j13, atom, "O I"),
             page_components(j13, atom, "H I"),
             page_fit_inspect(j13, atom), page_fit_results(j13),
             page_fit_compare(j13, dh, atom), page_plot(j13, atom)]
    for page in pages:
        with open(os.path.join(HERE, page["slug"] + ".html"), "w") as fil:
            fil.write(page_document(page))
    with open(os.path.join(HERE, "index.html"), "w") as fil:
        fil.write(index_document(pages))
    msgs.info(f"Wrote {len(pages)} mockup pages and index.html to {HERE}")
    if args.publish:
        os.makedirs(args.publish, exist_ok=True)
        path = os.path.join(args.publish, "alis_dashboard_mockups.html")
        with open(path, "w") as fil:
            fil.write(combined_page(pages))
        msgs.info("Wrote the combined page " + path)


if __name__ == "__main__":
    main()
