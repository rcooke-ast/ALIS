def nice_ticks(lo, hi, nmax=7):
    """
    Choose round tick values between two limits.

    Parameters
    ----------
    lo, hi : float
        The axis limits.
    nmax : int
        Roughly the most ticks wanted.

    Returns
    -------
    numpy.ndarray
        The tick values inside [lo, hi].

    Generated by RJC and Claude.
    """
    raw = (hi - lo) / max(nmax, 1)
    mag = 10.0 ** np.floor(np.log10(raw))
    step = mag * min((m for m in (1, 2, 2.5, 5, 10) if m * mag >= raw))
    start = np.ceil(lo / step) * step
    ticks = np.round(np.arange(start, hi + 1e-9 * step, step) / step) * step
    ticks[np.abs(ticks) < 1e-6 * step] = 0.0
    return ticks


def fmt_tick(val, signed=False):
    """
    Format a tick label without trailing zeros.

    Parameters
    ----------
    val : float
        The tick value.
    signed : bool
        Give positive values a '+' (velocity axes); zero stays unsigned.

    Returns
    -------
    str
        The label, using a true minus sign.

    Generated by RJC and Claude.
    """
    txt = f"{val + 0.0:.6g}"
    if "." in txt:
        txt = txt.rstrip("0").rstrip(".")
    if signed and val > 0:
        txt = "+" + txt
    return txt.replace("-", "−")


class Plot:
    """
    A rectangular plot area inside an SVG, with linear axes.

    Every method returns SVG markup as a string; ``Svg`` collects the pieces.

    Generated by RJC and Claude.
    """

    count = 0

    def __init__(self, x0, y0, wid, hgt, xlim, ylim):
        """
        Set up the plot area.

        Parameters
        ----------
        x0, y0 : float
            Top-left corner of the plot area, in SVG pixels.
        wid, hgt : float
            Size of the plot area, in SVG pixels.
        xlim, ylim : tuple of float
            Data limits of the x and y axes.

        Generated by RJC and Claude.
        """
        Plot.count += 1
        self.cid = f"clip{Plot.count}"
        self.x0, self.y0, self.wid, self.hgt = x0, y0, wid, hgt
        self.xlim, self.ylim = xlim, ylim

    def px(self, xval):
        """Map data x to SVG x. Generated by RJC and Claude."""
        xval = np.asarray(xval, dtype=float)
        frac = (xval - self.xlim[0]) / (self.xlim[1] - self.xlim[0])
        return self.x0 + frac * self.wid

    def py(self, yval):
        """Map data y to SVG y. Generated by RJC and Claude."""
        yval = np.asarray(yval, dtype=float)
        frac = (yval - self.ylim[0]) / (self.ylim[1] - self.ylim[0])
        return self.y0 + (1.0 - frac) * self.hgt

    def defs(self):
        """Return the clip path of this plot area. Generated by RJC and Claude."""
        return (f'<clipPath id="{self.cid}"><rect x="{self.x0:.1f}" '
                f'y="{self.y0:.1f}" width="{self.wid:.1f}" '
                f'height="{self.hgt:.1f}"/></clipPath>')

    def clip(self, inner):
        """
        Clip markup to the plot area.

        Parameters
        ----------
        inner : str
            SVG markup.

        Returns
        -------
        str
            The markup wrapped in a clipped group.

        Generated by RJC and Claude.
        """
        return f'<g clip-path="url(#{self.cid})">{inner}</g>'

    def line(self, xval, yval, cls, step=False):
        """
        Draw a curve, downsampled to about two points per screen pixel.

        Parameters
        ----------
        xval, yval : numpy.ndarray
            The data, sorted in x. NaNs break the curve.
        cls : str
            CSS class of the path.
        step : bool
            Draw as a histogram-style step curve (used for data).

        Returns
        -------
        str
            A clipped ``<path>``.

        Generated by RJC and Claude.
        """
        xval = np.asarray(xval, dtype=float)
        yval = np.asarray(yval, dtype=float)
        keep = (xval >= self.xlim[0] - 0.02 * (self.xlim[1] - self.xlim[0])) & (
            xval <= self.xlim[1] + 0.02 * (self.xlim[1] - self.xlim[0]))
        xval, yval = xval[keep], yval[keep]
        if xval.size > 2:
            # Break the curve across gaps in the coverage
            dxs = np.diff(xval)
            gaps = np.flatnonzero(dxs > 20.0 * np.median(dxs))
            xval = np.insert(xval, gaps + 1, xval[gaps] + 0.5 * dxs[gaps])
            yval = np.insert(yval, gaps + 1, np.nan)
        good = np.isfinite(yval)
        # Split into runs of finite values
        cuts = np.flatnonzero(np.diff(good.astype(int)) != 0) + 1
        parts = []
        for seg in np.split(np.arange(xval.size), cuts):
            if seg.size < 2 or not good[seg[0]]:
                continue
            parts.append(self._segment(self.px(xval[seg]), self.py(yval[seg]),
                                       step))
        if not parts:
            return ""
        return self.clip(f'<path class="{cls}" d="{" ".join(parts)}"/>')

    def _segment(self, pxs, pys, step):
        """
        Build path data for one finite run of points.

        Parameters
        ----------
        pxs, pys : numpy.ndarray
            SVG coordinates.
        step : bool
            Draw as a step curve when not downsampled.

        Returns
        -------
        str
            SVG path data.

        Generated by RJC and Claude.
        """
        npix = max(int(abs(pxs[-1] - pxs[0])), 2)
        if pxs.size > 2 * npix:
            # Min/max envelope per screen pixel keeps narrow features visible
            col = np.floor(pxs - pxs[0]).astype(int)
            starts = np.flatnonzero(np.r_[True, col[1:] != col[:-1]])
            lo = np.minimum.reduceat(pys, starts)
            hi = np.maximum.reduceat(pys, starts)
            xs = pxs[starts]
            pts = np.empty((2 * xs.size, 2))
            pts[0::2, 0], pts[1::2, 0] = xs, xs
            pts[0::2, 1], pts[1::2, 1] = lo, hi
            body = " ".join(f"{a:.1f} {b:.1f}" for a, b in pts[1:])
            return f"M{pts[0, 0]:.1f} {pts[0, 1]:.1f} L{body}"
        if not step:
            body = " ".join(f"{a:.1f} {b:.1f}" for a, b in zip(pxs[1:], pys[1:]))
            return f"M{pxs[0]:.1f} {pys[0]:.1f} L{body}"
        edges = np.r_[pxs[0] - 0.5 * (pxs[1] - pxs[0]),
                      0.5 * (pxs[1:] + pxs[:-1]),
                      pxs[-1] + 0.5 * (pxs[-1] - pxs[-2])]
        path = [f"M{edges[0]:.1f} {pys[0]:.1f}"]
        for i in range(pxs.size):
            if i > 0:
                path.append(f"V{pys[i]:.1f}")
            path.append(f"H{edges[i + 1]:.1f}")
        return "".join(path)

    def spans(self, lo, hi, cls, y_lo=None, y_hi=None):
        """
        Shade vertical bands between pairs of x values.

        Parameters
        ----------
        lo, hi : sequence of float
            Start and end of each band, in data units.
        cls : str
            CSS class of the rectangles.
        y_lo, y_hi : float, optional
            Vertical extent in data units (default: the whole plot).

        Returns
        -------
        str
            Clipped rectangles.

        Generated by RJC and Claude.
        """
        top = self.y0 if y_hi is None else float(self.py(y_hi))
        bot = self.y0 + self.hgt if y_lo is None else float(self.py(y_lo))
        rects = []
        for a, b in zip(lo, hi):
            xa, xb = float(self.px(a)), float(self.px(b))
            rects.append(f'<rect class="{cls}" x="{xa:.1f}" y="{top:.1f}" '
                         f'width="{max(xb - xa, 0.6):.1f}" '
                         f'height="{bot - top:.1f}"/>')
        return self.clip("".join(rects))

    def hline(self, yval, cls):
        """Draw a horizontal line across the plot. Generated by RJC and Claude."""
        yy = float(self.py(yval))
