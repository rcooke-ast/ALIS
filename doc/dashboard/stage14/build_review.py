def names_table():
    """The old names and the new, with ALIS's defaults."""
    rows = "".join(
        "<tr><td><code>{0}</code></td><td><code>{1}</code></td>"
        '<td class="num">{2}</td><td class="note">{3}</td></tr>'.format(
            esc(old) if old else "—", esc(new), esc(default), esc(what)
        )
        for old, new, default, what in NAMES
    )
    return (
        '<div class="tablewrap"><table><thead><tr><th>Old name</th><th>New name</th>'
        "<th>Default</th><th>What it does</th></tr></thead><tbody>{0}</tbody>"
        "</table></div>".format(rows)
    )


def data_line(shots):
    """lsf_spline's data line, as its .mod.out writes it."""
    found = json.loads((shots / "spline_subpixels.json").read_text())
    line = esc(found["data_line"]).replace("nsubpixel=", "<mark>nsubpixel=</mark>", 1)
    return (
        '<div class="dataline"><code>{0}</code></div>'
        '<p class="tests">A data line of examples/lsf_spline\'s .mod.out.</p>'.format(
            line
        )
    )


def _fmt_runtime(seconds):
    return "{0:.1f}".format(seconds)


def moved_table(shots):
    """Every case whose reference was regenerated, and its drawn fits."""
    rows = json.loads((shots / "moved.json").read_text())
    body = []
    for row in rows:
        old, new = row["chi2"]
        batches = (
            row["batch"][0]
            if row["batch"][0] == row["batch"][1]
            else "{0} → {1}".format(*row["batch"])
        )
        if row["blind"]:
            which, model = "blind", "—"
        else:
            which = row["which"]
            model = "{0:.3f}".format(row["model"])
        body.append(
            '<tr{cls}><td>{case}</td><td class="num">{old:.2f}</td>'
            '<td class="num">{new:.2f}</td><td class="num">{pct:+.3f}%</td>'
            '<td class="num">{sig:.2f}</td><td>{which}</td><td class="num">{model}'
            '</td><td class="num">{t0} → {t1}</td><td>{batch}</td>'
            '<td class="note">{start}</td></tr>'.format(
                cls=' class="drawn"' if row.get("figure") else "",
                case=esc(row["case"]),
                old=old,
                new=new,
                pct=row["percent"],
                sig=row["sigma"],
                which=esc(which),
                model=model,
                t0=_fmt_runtime(row["runtime"][0]),
                t1=_fmt_runtime(row["runtime"][1]),
                batch=esc(batches),
                start=esc(row["start"] and "Started from " + row["start"]),
            )
        )
    table = (
        '<div class="tablewrap"><table><thead><tr><th>Case</th><th>χ² before</th>'
        "<th>χ² after</th><th>Δχ²</th><th>Largest Δ (σ)</th><th>Which</th>"
        "<th>Model Δ (σ)</th><th>Runtime (s)</th><th>Batch</th><th>Start</th></tr>"
        "</thead><tbody>{0}</tbody></table></div>"
        '<p class="tests">Largest Δ: the largest change of a parameter, in units of'
        " its old 1σ error. Model Δ: the largest change of the model at a pixel, in"
        " units of its error. In bold, the cases drawn below. {1} cases.</p>".format(
            "".join(body), len(rows)
        )
    )
    figures = [
        (
            row["figure"],
            "{0}: before and after".format(row["case"]),
            None,
        )
        for row in rows
        if row.get("figure")
    ]
    return table, figures


def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    spline = json.loads((shots / "spline_subpixels.json").read_text())
    numbers = {
        "without_n": spline["without"]["nsubpixel"],
        "without_max": spline["without"]["max"],
        "without_n01": spline["without"]["above_0p1"],
        "with_n": spline["with"]["nsubpixel"],
        "with_max": spline["with"]["max"],
        "pixels": spline["pixels"],
    }
    sections, toc = [], []
    for anchor, eyebrow, title, figures, check, ask, extra in SECTIONS:
        figures = list(figures)
        before = ""
        if extra == "names_table":
            before = names_table()
        elif extra == "data_line":
            before = data_line(shots)
        elif extra == "moved_table":
            before, drawn = moved_table(shots)
            figures += drawn
        present = [f for f in figures if (shots / f[0]).exists()]
        notes = "".join("<li>{0}</li>".format(esc(t.format(**numbers))) for t in check)
        label = "A question."
        if ask and ask.startswith("(Answered, "):
            # An answered question stays in place: its comment thread is anchored
            # to it
            label, ask = ask[1 : ask.index(")")], ask[ask.index(")") + 2 :]
        question = (
            '<div class="ask"><b>{0}</b> {1}</div>'.format(esc(label), esc(ask))
            if ask
            else ""
        )
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul>{4}</div></div>{5}<div class="figs">{6}</div></section>'.format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                question,
                before,
                "".join(figure(shots, *f) for f in present),
            )
        )
        toc.append(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(eyebrow.split(" · ")[0]), anchor, esc(title)
            )
        )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    tests = ", ".join("<code>{0}</code>".format(esc(t)) for t in TESTS)
    body = (
        "<title>{title}</title>\n"
        "{fonts}<style>{css}{page}{figs}{tables}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 14 ·'
        " ALIS's sub-pixels, draft {draft}</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 14: its key item, the sub-pixels'
        " (deferred_work.md §7.10): a .mod.out records the sub-pixels its fit used"
        " and is evaluated on them, ALIS warns where a profile has too few, and"
        " nsubpixel_min is 10. Every name of the sub-pixels now follows one"
        " convention. One section per change, each with what to check. The"
        " screenshots are taken off-screen at 1440×900, of synthetic scenes from"
        " the stage's tests (the metal example, and a ratio fit). The figures and"
        " the table come from the regression harness's references, before and"
        " after; your own files were refitted by the harness.</p>"
        '<p class="lede">Draft 2: each part of ALIS\'s sub-pixel warnings ends with'
        " a full stop (your comment, Q14.11), the Warnings screenshot retaken. Draft"
        " 3: run nsubsigma_min is removed (your comment, Q14.12): ALIS warns where a"
        " profile has fewer than its snip's nsubsigma across its σ; the names table"
        " marks it removed, and All settings… and Warnings are retaken.</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing to see in a still</h2>'
        '<ul>{covered}</ul><p class="tests">Its tests (test_lsffile.py,'
        " test_resolution_keywords.py): {tests}.</p></div>"
        '<ul class="toc">{toc}</ul>{sections}</div>\n'
    ).format(
        title=TITLE,
        draft=DRAFT,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        figs=FIGURE_CSS,
        tables=TABLE_CSS,
        hatch=hatch,
        covered=covered,
        tests=tests,
        toc="".join(toc),
        sections="".join(sections),
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
