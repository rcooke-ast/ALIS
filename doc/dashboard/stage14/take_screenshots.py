"""Screenshots of what the dashboard shows of Stage 14, for the review that closes it.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen, all of
synthetic scenes from the stage's ``gui`` tests (the metal example, and a fit in
the shape of ``tests/dashboard_synthetic.py``'s ratio fit):

- an old name of the sub-pixels typed in the .mod panel: its problem, naming the
  new name, and the right-click that renames it (Task 14.2);
- All settings… filtered to the sub-pixels' settings, with their new names (14.2);
- a data line that records too few sub-pixels: the pre-flight check's note, and
  the right-click that works them out again (14.5);
- Warnings and options to resolve… with ALIS's three sub-pixel warnings and what
  resolves each (14.4, 14.5);
- Set LSFSpline knots…'s Delta Function, its ±spix knots one sub-pixel from the
  centre at nsubpixel_min 10 (14.6).

A right-click's menu is built as the window builds it (its action's text from the
same function) and drawn on its own, since a menu opened with ``QMenu.exec`` blocks
off-screen. Run it from the repository root::

    python doc/dashboard/stage14/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _load(name, path):
    import importlib.util

    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _load("skeleton_screenshots", "doc/dashboard/skeleton/take_screenshots.py")
_S12 = _load("stage12_screenshots", "doc/dashboard/stage12/take_screenshots.py")
pump, shoot = _SK.pump, _SK.shoot
done, shoot_dialog, shoot_menu = _S12.done, _S12.shoot_dialog, _S12.shoot_menu
FIT = 3
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


def screens(window, outdir, work):
    """The screens, each a function that saves its PNG."""
    from types import SimpleNamespace

    from dashboard_synthetic import write_ratio_fit
    from qtpy import QtCore, QtWidgets
    from test_dashboard_results import SUBPIXEL_WARNINGS, store_run

    from alis import bundle as B
    from alis.dashboard import lsfknots as LK
    from alis.dashboard import runs as R
    from alis.dashboard import text as T
    from alis.dashboard.qt import fit as QF
    from alis.dashboard.qt import knots as KN

    def opened(name, panel=False):
        """The metal example packed and opened."""
        path = work / (name + ".model")
        B.pack_to(str(METAL), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        window.set_panel_open(panel)
        pump(0.4)

    def fit_tab(sub):
        window.tabs.setCurrentIndex(FIT)
        window.fit_tab.subtabs.setCurrentIndex(sub)
        pump(1.2)

    def menu_at(widget, rect, action, path):
        """A right-click's menu, as the window builds it, where it would open."""
        menu = QtWidgets.QMenu(window)
        menu.addAction(action)
        shoot_menu(menu, widget.viewport().mapToGlobal(rect.center()), path)

    def old_name():
        opened("old_name", panel=True)
        panel = window.panel
        cursor = panel.editor.textCursor()
        cursor.setPosition(0)
        cursor.insertText("run nsubmin 10\n")
        pump(2.0)
        shoot(window, outdir / "old_name_problem.png")
        item = panel.list.item(0)
        print("problem:", item.text(), "|", item.toolTip())
        (fix,) = panel.fixes(0)
        menu_at(
            panel.list,
            panel.list.visualItemRect(item),
            fix.action,
            outdir / "old_name_menu.png",
        )
        panel.renameRequested.emit(0)
        pump(1.5)
        shoot(window, outdir / "old_name_renamed.png")
        print("line 1:", window.session.project.text.splitlines()[0])
        done(window)

    def settings():
        opened("settings")
        fit_tab(0)
        inspect = window.fit_tab.inspect
        from alis.dashboard.qt import dialogs as D

        dialog = D.AllSettingsDialog(window.session.project, inspect.prefs(), window)
        dialog.filter.setText("nsub")
        shown = [k for k, r in dialog.rows.items() if not r["item"].isHidden()]
        print("settings shown:", shown)
        shoot_dialog(dialog, outdir / "settings.png", (980, 420))
        done(window)

    def preflight():
        opened("preflight")
        project = window.session.project
        text = project.text.replace("label=OI_SiII", "label=OI_SiII   nsubpixel=3")
        window.session.history.do(
            project.step(T.Change((T.Patch(0, project.text, text),)), "Typed")
        )
        window.refresh()
        fit_tab(0)
        inspect = window.fit_tab.inspect
        inspect.show_findings()
        pump(0.6)
        shoot(window, outdir / "preflight_note.png")
        # The Run box close up, its note legible
        box = inspect.findings.parentWidget()
        while box.parentWidget() is not None and box.height() < 300:
            box = box.parentWidget()
        print("box:", type(box).__name__, box.width(), box.height())
        shoot(box, outdir / "preflight_box.png")
        rows = range(inspect.findings.count())
        (num,) = [n for n in rows if "nsubpixel=3" in inspect.findings.item(n).text()]
        item = inspect.findings.item(num)
        finding = item.data(QF.FIX_ROLE)
        print("note:", item.text(), "|", item.toolTip())
        menu_at(
            inspect.findings,
            inspect.findings.visualItemRect(item),
            finding.fix,
            outdir / "preflight_menu.png",
        )
        inspect.fix_finding(finding)
        pump(1.0)
        print("after:", "nsubpixel" in project.text, len(inspect.report.notes))
        done(window)

    def warnings():
        opened("warnings")
        store_run(
            window.session.project,
            METAL,
            chi2_final=357.874162,
            chi2_initial=420.0,
            dof=360,
            iterations=12,
            warnings=SUBPIXEL_WARNINGS,
            origin=R.DASHBOARD,
        )
        window.session.runs_changed()
        window.refresh()
        fit_tab(1)
        window.fit.job = SimpleNamespace(kind="run", warnings=[], message="")
        window.fit.session = window.session
        window._fit_ended(R.COMPLETED)
        pump(0.4)
        shoot(window, outdir / "warnings_results.png")
        print("status bar:", window.statusBar().currentMessage())
        opened_dialogs = []
        window.run_dialog = lambda dialog: opened_dialogs.append(dialog) or 0
        window.fit_tab.results.warnings_button.click()
        shoot_dialog(opened_dialogs[-1], outdir / "warnings_dialog.png", (900, 470))
        done(window)

    def knots():
        path = write_ratio_fit(work / "knots")
        window.import_path(str(path))
        pump(1.0)
        window.set_panel_open(False)
        project = window.session.project
        row = project.rows[0]
        window.ask = lambda kind, title, text, choices, **kw: "Confirm"
        dialog = KN.KnotsDialog(project, row, LK.knots_of(project, row), window.ask)
        dialog.smoothing.setValue(3.0)
        dialog.delta.click()
        pump(0.6)
        print(
            "knots:",
            [round(v, 3) for v in dialog.knots.velocities],
            "step:",
            round(dialog.step, 4),
            "FWHM:",
            round(dialog.fwhm_shown, 3),
        )
        shoot_dialog(dialog, outdir / "knots_delta.png", (980, 640))
        done(window)

    del QtCore
    return [old_name, settings, preflight, warnings, knots]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage14_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    failed = []
    for screen in screens(window, outdir, work):
        if only and screen.__name__ not in only:
            continue
        # Questions take their last choice (Cancel) and dialogs are cancelled,
        # unless a screen answers them
        window.ask = lambda kind, title, text, choices, **kw: choices[-1]
        window.tell = lambda title, text, icon="info": None
        window.run_dialog = lambda dialog: 0
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage14_shots", sys.argv[2:])
