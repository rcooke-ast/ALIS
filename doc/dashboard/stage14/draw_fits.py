def short(rel):
    """A case's short name: its folder and model under fitting_examples/."""
    parts = rel.split("/")
    if parts[0] == "examples":
        stem = parts[-1]
        return parts[1] + ("" if stem == "fit_spectra" else " · " + stem)
    return "{0}/{1}{2}".format(
        parts[2],
        parts[3],
        "" if parts[-1] == parts[3] else " · " + parts[-1],
    )


def numbers(line):
    """The numbers of a function line, each with its keyword (or None)."""
    out = []
    for tok in line.split():
        key, val, _ = _token_parts(tok)
        if val is not None:
            out.append((key, val))
    return out


def param_changes(new, old):
    """Each parameter's |change| over its old error, with its section and function."""
    rows = []
    for name in ("model", "convolution", "shift"):
        nvals, _ = new.sections[name]
        ovals, oerrs = old.sections[name]
        oerr_fn = [ln for ln in oerrs if _is_function_line(ln)]
        j = 0
        for nv, ov in zip(nvals, ovals):
            if ov == BLIND_MARKER:
                j += 1
                continue
            if not _is_function_line(ov):
                continue
            err_line = oerr_fn[j] if j < len(oerr_fn) else ""
            j += 1
            errs = numbers(err_line)
            for k, ((key, a), (_, b)) in enumerate(zip(numbers(nv), numbers(ov))):
                err = errs[k][1] if k < len(errs) else 0.0
                if err > 0.0:
                    rows.append((abs(a - b) / err, name, ov.split()[0], key or k))
    return rows


def runtime(path):
    """A .mod.out's running time, in seconds."""
    found = RUNTIME.search(Path(path).read_text())
    return 3600.0 * float(found.group(1)) if found else float("nan")


def batch(seconds):
    """The harness's batch for a runtime (manifest.py)."""
    minutes = seconds / 60.0
    if minutes < FAST_MAX_MIN:
        return "fast"
    return "medium" if minutes < MEDIUM_MAX_MIN else "slow"


def fit_columns(path):
    """A _fit.dat's wavelength, flux, error and model (its last) columns."""
    cols = np.atleast_2d(np.loadtxt(path)).T
    return cols[0], cols[1], cols[FITDAT_ERROR_COL], cols[-1]


def model_change(case, old_root):
    """The largest change of the model column between the goldens, in errors."""
    worst = 0.0
    for pair in case.data_pairs:
        for golden in pair.reference_fits:
            before = old_root / golden.relative_to(ROOT)
            _, _, err, new = fit_columns(golden)
            _, _, _, old = fit_columns(before)
            keep = (old != SENTINEL) & (new != SENTINEL) & (err != 0)
            if keep.any():
                worst = max(worst, float(np.max(np.abs(new - old)[keep] / err[keep])))
    return worst


def draw_case(case, old_root, path, title):
    """
    One case's fit before and after, over its fitted pixels: per golden, the data
    with both models, the residuals of each in units of the error, and the change
    of the model in units of the error.

    Generated by RJC and Claude.
    """
    goldens = [g for p in case.data_pairs for g in p.reference_fits]
    fig, axes = plt.subplots(
        3,
        len(goldens),
        figsize=(11.5, 6.4),
        squeeze=False,
        sharex="col",
        gridspec_kw={"height_ratios": [3, 1.4, 1.1], "hspace": 0.08},
    )
    for col, golden in enumerate(goldens):
        wave, flux, err, new = fit_columns(golden)
        _, _, _, old = fit_columns(old_root / golden.relative_to(ROOT))
        keep = (new != SENTINEL) & (old != SENTINEL) & (err > 0)
        wave, flux, err, new, old = (a[keep] for a in (wave, flux, err, new, old))
        top, mid, low = axes[:, col]
        top.step(wave, flux, where="mid", color=INK, lw=0.7, label="data")
        top.plot(wave, old, color=OLD_C, lw=1.8, label="before")
        top.plot(wave, new, color=NEW_C, lw=1.0, ls="--", label="after")
        for model, colour, label, width in (
            (old, OLD_C, "before", 1.6),
            (new, NEW_C, "after", 0.8),
        ):
            mid.plot(wave, (flux - model) / err, color=colour, lw=width, label=label)
        mid.axhline(0, color=INK, lw=0.5)
        low.plot(wave, (new - old) / err, color=INK, lw=0.9)
        low.axhline(0, color=INK, lw=0.5)
        low.set_xlabel("Wavelength (Å)")
        if col == 0:
            top.set_ylabel("Flux")
            mid.set_ylabel("Residual / σ")
            low.set_ylabel("Δ model / σ")
            top.legend(loc="lower left", frameon=False, fontsize=9)
        top.set_title(golden.name, fontsize=9, loc="left")
    fig.align_ylabels(axes[:, 0])
    fig.suptitle(title, x=0.01, ha="left", fontsize=11)
    fig.savefig(path, dpi=110, bbox_inches="tight")
    plt.close(fig)


def spline_subpixels(case, shots):
    """
    ``examples/lsf_spline``'s reference evaluated at its best fit, with and without
    its ``nsubpixel=``, against its fit's model.

    Generated by RJC and Claude.
    """
    text = case.mod_out_reference.read_text()
    head = text.split("####")[0]
    data_line = next(
        ln.strip()
        for ln in head.splitlines()
        if "nsubpixel=" in ln and not ln.lstrip().startswith("#")
    )
    (pair,) = case.data_pairs
    (golden,) = pair.reference_fits
    wave, _, err, fit = fit_columns(golden)
    keep = (fit != SENTINEL) & (err != 0)
    result = {"data_line": data_line, "pixels": int(keep.sum())}
    curves = {}
    for label, body in (("with", head), ("without", NSUBPIXEL.sub("", head))):
        work = Path(tempfile.mkdtemp(prefix="stage14_spline_"))
        staged = stage_case(case, work)
        lines = [
            ln for ln in body.splitlines() if not re.match(r"\s*chisq\s+m..iter", ln)
        ]
        mod = staged.model_dir / "again.mod"
        mod.write_text("chisq miniter 0\nchisq maxiter 0\n" + "\n".join(lines) + "\n")
        proc = run_alis(mod, runtime_hrs=case.runtime_hrs)
        said = proc.stdout + proc.stderr
        _, _, _, model = fit_columns(staged.fit_output_for(golden))
        delta = (model - fit)[keep] / err[keep]
        curves[label] = delta
        used = re.findall(r"nsubpixel=(\d+)", mod.with_suffix(".mod.out").read_text())
        result[label] = {
            "max": float(np.max(np.abs(delta))),
            "above_0p1": int(np.sum(np.abs(delta) > 0.1)),
            "nsubpixel": int(used[0]) if used else None,
            "warned": "asks for more sub-pixels" in said,
        }
    fig, axes = plt.subplots(2, 1, figsize=(11.5, 4.6), sharex=True)
    for ax, label, colour, title in (
        (
            axes[0],
            "without",
            OLD_C,
            "Read without its nsubpixel= (as before Task 14.3): {0} sub-pixels per"
            " pixel".format(result["without"]["nsubpixel"]),
        ),
        (
            axes[1],
            "with",
            NEW_C,
            "Read with its nsubpixel={0} (Task 14.3)".format(
                result["with"]["nsubpixel"]
            ),
        ),
    ):
        ax.plot(wave[keep], curves[label], color=colour, lw=0.9)
        ax.axhline(0, color=INK, lw=0.5)
        ax.set_ylabel("Δ model / σ")
        ax.set_title(title, fontsize=10, loc="left")
    lim = 1.1 * max(abs(curves["without"]).max(), 1e-3)
    for ax in axes:
        ax.set_ylim(-lim, lim)
    axes[1].set_xlabel("Wavelength (Å)")
    fig.tight_layout()
    fig.savefig(shots / "spline_subpixels.png", dpi=110)
    plt.close(fig)
    (shots / "spline_subpixels.json").write_text(json.dumps(result, indent=1))
    return result


def main(old_root, shots):
    """
    Write the figures and the table.

    Generated by RJC and Claude.
    """
    old_root, shots = Path(old_root).resolve(), Path(shots)
    shots.mkdir(parents=True, exist_ok=True)
    cases = {
        os.path.relpath(str(c.mod_file.with_suffix("")), ROOT): c
        for c in discover_cases()
    }
    rows = []
    for rel in REGENERATED:
        case = cases[rel]
        old_ref = old_root / case.mod_out_reference.relative_to(ROOT)
        new, old = parse_mod_out(case.mod_out_reference), parse_mod_out(old_ref)
        changes = param_changes(new, old)
        big = max(changes, key=lambda r: r[0]) if changes else (0.0, "", "", "")
        name = short(rel)
        seconds = (runtime(old_ref), runtime(case.mod_out_reference))
        row = {
            "case": name,
            "blind": case.is_blind,
            "chi2": [old.chisq, new.chisq],
            "dof": new.dof,
            "percent": 100.0 * (new.chisq - old.chisq) / old.chisq,
            "sigma": big[0],
            "runtime": seconds,
            "batch": [batch(s) for s in seconds],
            "start": next((v for k, v in STARTS.items() if name.startswith(k)), ""),
        }
        if not case.is_blind:
            row["which"] = "{0} {1} {2}".format(big[2], big[3], big[1]).strip()
            row["model"] = model_change(case, old_root)
            if big[0] > SIGMA or abs(row["percent"]) > 100.0 * PERCENT:
                png = "fit_" + re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_") + ".png"
                draw_case(
                    case,
                    old_root,
                    shots / png,
                    "{0}: χ² {1:.2f} before, {2:.2f} after; the largest change"
                    " {3:.2f}σ ({4})".format(
                        name, old.chisq, new.chisq, big[0], row["which"]
                    ),
                )
                row["figure"] = png
        rows.append(row)
        print(json.dumps(row))
    (shots / "moved.json").write_text(json.dumps(rows, indent=1))
    spline = cases["examples/lsf_spline/model/fit_spectra"]
    print(json.dumps(spline_subpixels(spline, shots)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
