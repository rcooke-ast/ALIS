"""Screenshots of what changed in Stage 12, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen, all of
the synthetic scenes of the stage's ``gui`` tests (``tests/dashboard_synthetic.py``,
``tests/dashboard_fits.py``, and the metal example's spectrum):

- a card's lists with 87Rb I (Task 12.1), and a component excluded from every ion
  taking an ion it never had (12.2);
- a drag's readout on a column density that a link computes, and on one whose link
  has no single input to move (12.3);
- the Regions tab's offer for pixels fitted twice, with Ignore warning, and the Snip
  box's Warnings ignored (12.4);
- the Data tab's row for an emptied unassigned dataset, its data kept, and SNIP
  cutting it again on the Regions tab (12.5, 12.12);
- the zoom bar with ↔ and ↕, and a view zoomed in flux with ⇧ Shift and the wheel
  (12.7);
- the Data tab's Keep a copy in the project, the File menu's Save a copy with
  spectra…, what it says, and the relink question (12.8);
- the Snip box with Set LSFSpline knots…, the dialog on nine knots, after Delta
  Function, and with two knots written too close (12.10).

A dialog or a menu is drawn on its own; a question or a message is drawn as the
window's message box draws it. Run it from the repository root::

    python doc/dashboard/stage12/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

