def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def shoot_dialog(dialog, path, size=None):
    """Draw a dialog on its own, as it opens."""
    if size is not None:
        dialog.resize(*size)
    dialog.show()
    pump(0.4)
    shoot(dialog, path)
    dialog.hide()


def shoot_box(title, text, choices, path, icon="question"):
    """Draw a question or a message as the window's message box draws it."""
    from qtpy import QtWidgets

    box = QtWidgets.QMessageBox()
    box.setWindowTitle(title)
    box.setText(text)
    box.setIcon(
        {
            "question": QtWidgets.QMessageBox.Icon.Question,
            "warning": QtWidgets.QMessageBox.Icon.Warning,
            "info": QtWidgets.QMessageBox.Icon.Information,
        }[icon]
    )
    for num, choice in enumerate(choices):
        role = (
            QtWidgets.QMessageBox.ButtonRole.RejectRole
            if num == len(choices) - 1 and len(choices) > 1
            else QtWidgets.QMessageBox.ButtonRole.AcceptRole
        )
        box.addButton(choice, role)
    shoot_dialog(box, path)


def shoot_menu(menu, at, path):
    """Draw a menu on its own, popped up where it would open."""
    menu.popup(at)
    pump(0.4)
    shoot(menu, path)
    menu.hide()


def screens(window, outdir, work):
    """The screens, each a function that saves its PNG."""
    from dashboard_fits import SII, SPECTRUM, noisy_copy, prepfit_snip
    from dashboard_synthetic import (
        write_linked_fit,
        write_ratio_fit,
        write_rubidium_fit,
        write_twin_snips,
    )
    from qtpy import QtCore, QtWidgets

    from alis import bundle as B
    from alis.dashboard import loadfit as LF
    from alis.dashboard import lsfknots as LK
    from alis.dashboard import session as S
    from alis.dashboard import snips as SN
    from alis.dashboard import sources as SR
    from alis.dashboard.qt import knots as KN

    def imported(path, tab):
        window.import_path(str(path))
        pump(1.0)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(tab)
        pump(0.6)
        return window.tab_widgets[tab]

    def choose(tab, name):
        for item in tab._ion_items():
            if item.text(0) == name:
                tab.tree.setCurrentItem(item)
        pump(0.8)

    def click_ion(card, ion):
        for label in (card.included, card.excluded):
            if 'href="{0}"'.format(ion) in label.text():
                label.linkActivated.emit(ion)
                pump(0.6)
                return
        raise AssertionError(ion)

    def show(tab, element, stage, name):
        if tab.state.get("element") != element:
            tab.element_box.setCurrentIndex(tab.element_box.findText(element))
        if tab.state.get("stage") != stage:
            tab.ion_box.setCurrentIndex(tab.ion_box.findText(stage))
        for num in range(tab.listing.topLevelItemCount()):
            item = tab.listing.topLevelItem(num)
            if item.text(1).startswith(name):
                tab.listing.setCurrentItem(item)
        pump(0.8)

    def drag(view, start, end, state):
        (x0, y0), (x1, y1) = start, end
        view.dragged.emit(x0, y0, x0, y0, "start")
        for f in (1.0 / 3.0, 2.0 / 3.0):
            view.dragged.emit(x0, y0, x0 + f * (x1 - x0), y0 + f * (y1 - y0), "move")
        view.dragged.emit(x0, y0, x1, y1, state)
        pump(0.6)

    def rubidium():
        tab = imported(write_rubidium_fit(work / "rb"), COMPONENTS)
        choose(tab, "Rb I")
        # a2 excluded from both isotopes: its card lists each once
        window.run_dialog = lambda dialog: 1
        click_ion(tab.card_widgets["a2"], "85Rb_I")
        click_ion(tab.card_widgets["a2"], "87Rb_I")
        choose(tab, "Rb I")
        shoot(window, outdir / "rubidium.png")
        done(window)

    def never_had():
        o1 = "voigt ion=16O_I 13.0 2.50420rb 10.0doppb 10000.0tempb specid=0"
        tab = imported(write_linked_fit(work / "never", [o1]), COMPONENTS)
        choose(tab, "H I")
        window.run_dialog = lambda dialog: 1
        click_ion(tab.card_widgets["a1"], "1H_I")
        click_ion(tab.card_widgets["a1"], "2H_I")
        tab.select(window.session.project.component("a1"))
        pump(0.6)
        shoot(window, outdir / "never_had_before.png")
        click_ion(tab.card_widgets["a1"], "16O_I")
        choose(tab, "O I")
        tab.select(window.session.project.component("a1"))
        pump(0.6)
        shoot(window, outdir / "never_had_after.png")
        done(window)

    # H I's log N computed from D I's and a variable that no other line names
    free_link = [
        "voigt ion=1H_I 14.5nha 2.50360ra 25.0doppa 10000.0tempa specid=0",
        "voigt ion=2H_I 10.0nda 2.50360ra 25.0doppa 10000.0tempa specid=0",
        "variable -4.5dh specid=0",
    ]

    def h1_drag(name, lines, link, out):
        tab = imported(write_ratio_fit(work / name, lines, (), [link]), COMPONENTS)
        choose(tab, "H I")
        widget = tab.panel_widgets[0]
        view = widget.view
        x = next(t.value() for t in view.ticks() if t.key == ("component", "a1"))
        drag(view, (x + 5.0, 0.6), (x + 8.0, 0.4), "move")
        shoot(window, outdir / (out + ".png"))
        shoot(widget, outdir / (out + "_panel.png"))
        print(out, "readout:", widget.readout.text())
        view.dragged.emit(x + 5.0, 0.6, x + 8.0, 0.4, "cancel")
        done(window)

    def link_drag():
        h1_drag("link", free_link, "nha(nda,dh) = nda - dh", "link_drag")

    def link_why():
        lines = free_link[:2] + ["variable -4.5FIXDH specid=0"]
        h1_drag("why", lines, "nha(nda,FIXDH) = nda - FIXDH", "link_why")

    def ignore():
        tab = imported(write_twin_snips(work / "twins"), REGIONS)
        show(tab, "H", "I", "Lyα")
        shoot(window, outdir / "ignore_before.png")
        tab.ignore_button.click()
        pump(0.8)
        shoot(window, outdir / "ignore_after.png")
        done(window)

    def emptied():
        (work / "empty").mkdir(parents=True)
        session, _ = S.Session.new(
            str(work / "empty" / "test.model"), [str(SPECTRUM)], z=0.0
        )
