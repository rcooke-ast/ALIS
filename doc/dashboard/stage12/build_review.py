def figure(shots, shot, caption, width):
    """One screenshot with its caption, at the page's width or its own."""
    if width is None:
        return "<figure><figcaption>{0}</figcaption>{1}</figure>".format(
            esc(caption), image(shots, shot, "Screenshot: " + caption)
        )
    return (
        '<figure class="fixed" style="width: {0}px; max-width: 100%">'
        "<figcaption>{1}</figcaption>{2}</figure>".format(
            width, esc(caption), image(shots, shot, "Screenshot: " + caption)
        )
    )


def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    toc = []
    for anchor, eyebrow, title, figures, check, ask in SECTIONS:
        present = [f for f in figures if (shots / f[0]).exists()]
        if not present:
            continue
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        question = (
            '<div class="ask"><b>A question.</b> {0}</div>'.format(esc(ask))
            if ask
            else ""
        )
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul>{4}</div></div><div class="figs">{5}</div></section>'.format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                question,
                "".join(figure(shots, *f) for f in present),
            )
        )
        toc.append(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(eyebrow), anchor, esc(title)
            )
        )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    places = ", ".join("<code>{0}</code>".format(esc(t)) for t in PLACES)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}{figs}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 12 ·'
        " users' feedback, draft {draft}</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 12: the eight points of the Feedback'
        " list (most of them found on RJC's MWC137 project), and the item carried"
        " over from Stage 11. One section per change, each with what to check. Each"
        " screenshot is taken off-screen at 1440×900, of the synthetic scenes of"
        " the stage's tests (fits in the shapes of MWC137's rubidium, its a2, its"
        " a7 link and its specids 6 and 7, and the metal example's spectrum); RJC's"
        " own files were checked with scripts.</p>"
        '<p class="lede">Draft 2: the snips table marks the shared pixels of an'
        " ignored pair “(ignored)”, keeping their count (your comment). Draft 3:"
        " why the emptied unassigned dataset has no source spectrum, and a"
        " question on getting its snip back (the CLEAR section). Draft 4: ↔ and ↕"
        " in place of ⌂x and ⌂y on every zoom bar (your comment). Draft 5: your"
        " response to Q12.15, and what follows it. Draft 6: every dataset keeps its"
        " data (Task 12.12, your response to Q12.16), and every screen retaken."
        " Draft 7: a project saved before opens as it is (your response to"
        " Q12.17).</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing new to see</h2><ul>'
        '{covered}</ul><p class="tests">The places kept (Task 12.6): {places}.'
        "</p></div>"
        '<ul class="toc">{toc}</ul>{sections}</div>\n'
    ).format(
        title=TITLE,
        draft=DRAFT,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        figs=FIGURE_CSS,
        hatch=hatch,
        covered=covered,
        places=places,
        toc="".join(toc),
        sections="".join(sections),
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
