"""Screenshots of the dashboard's Qt skeleton, for review beside the mockups.

Dashboard Stage 3.5 and 3.11. Opens the window off-screen at 1440x900 (the size the
design is judged at, D43) and saves one PNG per tab and project:

- J1358p6522 (``context/fitting_examples/VMP_DLA/J1358p6522``), imported, with its
  D I line blinded as in the mockups;
- Q1243p307 (``context/fitting_examples/DH/Q1243p307``), imported: three datasets;
- ``examples/blind``;
- a new, empty project made from one spectrum;
- the start page, and the Unblind and New project dialogs.

Run it from the repository root::

    python doc/dashboard/skeleton/take_screenshots.py OUTDIR

It needs the gui extra, and works in a temporary ``$ALIS_HOME``.

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import time
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
Q1243 = (
    ROOT
    / "context/fitting_examples/DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
)
BLIND = ROOT / "examples/blind/model/fit_spectra.mod"
SPECTRUM = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"
TABS = ("data", "regions", "components", "fit")


def pump(seconds=0.3):
    """Let the event loop run, and the full check finish."""
    from qtpy import QtCore, QtWidgets

    end = time.time() + seconds
    while time.time() < end:
        QtWidgets.QApplication.processEvents()
        time.sleep(0.01)
    QtCore.QThreadPool.globalInstance().waitForDone(20000)
    QtWidgets.QApplication.processEvents()


def shoot(widget, path):
    """Save a widget as a PNG."""
    pump(0.2)
    widget.grab().save(str(path))
    print("wrote", path)


# The .mod panel is shown as the mockup of each tab shows it: open on the Regions tab
# of J1358p6522 only
PANEL_OPEN = {("j1358", "regions")}


def tabs(window, stem, outdir, subtabs=False):
    """One screenshot per tab (and per Fit sub-tab), the panel as in the mockups."""
    for num, name in enumerate(TABS):
        window.set_panel_open((stem, name) in PANEL_OPEN)
        window.tabs.setCurrentIndex(num)
        shoot(window, outdir / "{0}_{1}.png".format(stem, name))
    if subtabs:
        window.set_panel_open(False)
        fit = window.tab_widgets[3].subtabs
        window.tabs.setCurrentIndex(3)
        for num, name in ((1, "results"), (2, "compare")):
            fit.setCurrentIndex(num)
            shoot(window, outdir / "{0}_fit_{1}.png".format(stem, name))
        fit.setCurrentIndex(0)
    window.set_panel_open(True)


def blind_d_i(window):
    """Blind the D I line of J1358p6522, as the mockups do."""
    from alis.dashboard import edit as E

    session = window.session
    pm = session.project.parsed
    lines = [ln for ln in pm.function_lines("voigt") if ln.ion == "2H_I"]
    with session.history.group("Blind D I"):
        for line in lines:
            pm = session.project.parsed
            session.history.edit(E.set_blind(pm, pm.item_at(line.line)), "Blind")
    window.panel.redraw()
    window.refresh()


def main(outdir):
    """
    Take every screenshot.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP
    from alis.dashboard.qt import dialogs as D

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    window.ask = lambda kind, title, text, choices, **kw: choices[-1]
    pump(0.5)
    shoot(window, outdir / "start.png")
    if J1358.exists():
        window.import_path(str(J1358))
        pump(1.0)
        blind_d_i(window)
        pump(1.0)
        d_i = next(
            ln.line
            for ln in window.session.project.parsed.function_lines("voigt")
            if ln.ion == "2H_I"
        )
        window.panel.go_to_line(d_i)
        window.tabs.setCurrentIndex(1)
        shoot(window, outdir / "j1358_as_imported.png")
        # Align columns, on the .mod panel (drafts 2 and 3, RJC's review)
        window.do_panel_align()
        pump(1.0)
        window.panel.go_to_line(d_i)
        tabs(window, "j1358", outdir, subtabs=True)
        window.tabs.setCurrentIndex(2)
        shoot(window, outdir / "j1358_components_panel.png")
        # The .mod panel in a window of its own (draft 2)
        window.set_panel_window(True)
        window.dock.resize(620, 820)
        window.tabs.setCurrentIndex(0)
        pump(0.5)
        shoot(window, outdir / "j1358_own_window_main.png")
        shoot(window.dock, outdir / "j1358_own_window_panel.png")
        window.set_panel_window(False)
        dialog = D.UnblindDialog(window.session.project, False, window)
        dialog.resize(560, 260)
        shoot(dialog, outdir / "j1358_unblind.png")
        window.session.discard_recovery()
        window.session = None
    if Q1243.exists():
        window.import_path(str(Q1243))
        pump(2.0)
        tabs(window, "q1243", outdir)
        window.session = None
    window.import_path(str(BLIND))
    pump(1.0)
    shoot(window, outdir / "blind_data.png")
    window.session = None
    folder = Path(tempfile.mkdtemp(prefix="alis_new_"))
    session, _ = S.Session.new(str(folder / "J0000.model"), [str(SPECTRUM)], z=0.0)
    window.set_session(session)
    pump(1.0)
    tabs(window, "empty", outdir)
    dialog = D.NewProjectDialog(str(folder), 7.0, window)
    dialog.name.setText("J0000")
    for name in ("OI_SiII.dat", "OI_SiII_linear.dat"):
        dialog.add_spectrum(str(SPECTRUM.parent / name))
    dialog.entries[1]["fwhm"] = 4.5
    dialog._fill()
    dialog.spectra.selectRow(1)
    dialog.redshift.setText("0.0")
    dialog.resize(780, 560)
    dialog.show()
    shoot(dialog, outdir / "new_project.png")
    dialog.hide()
    # The dialog of one spectrum (draft 3)
    spectrum = D.SpectrumDialog(str(folder), 7.0, None, window)
    spectrum.set_file(str(SPECTRUM))
    spectrum.resize(700, 520)
    spectrum.show()
    shoot(spectrum, outdir / "spectrum_dialog.png")
    spectrum.hide()


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "screenshots")
