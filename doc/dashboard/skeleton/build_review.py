def esc(text):
    """Escape text for HTML."""
    return html.escape(str(text))


def mockup_window(slug):
    """
    The window of one mockup page, as its HTML holds it.

    Generated by RJC and Claude.
    """
    text = (MOCKUPS / (slug + ".html")).read_text(encoding="utf-8")
    start = text.index('<div class="win">')
    depth, pos = 0, start
    for match in re.finditer(r"<div\b|</div>", text[start:]):
        depth += 1 if match.group() == "<div" else -1
        if depth == 0:
            pos = start + match.end()
            break
    return text[start:pos]


def mockup_parts():
    """The stylesheet, fonts and shared SVG of the mockup pages."""
    text = (MOCKUPS / "data_new.html").read_text(encoding="utf-8")
    css = re.search(r"<style>(.*?)</style>", text, re.S).group(1)
    fonts = re.search(r'<link rel="stylesheet"[^>]*>', text).group(0)
    hatch = re.search(r"<svg width=\"0\".*?</svg>", text, re.S).group(0)
    return css, fonts, hatch


def image(shots, name, alt):
    """A screenshot as an embedded PNG."""
    data = base64.b64encode((shots / name).read_bytes()).decode("ascii")
    return '<img src="data:image/png;base64,{0}" alt="{1}" loading="lazy">'.format(
        data, esc(alt)
    )


def section(shots, entry):
    """
    One tab: what to check, the differences, the screenshot and the mockup.

    Generated by RJC and Claude.
    """
    anchor, eyebrow, title, shot, slug, check, differ = entry
    notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
    diffs = "".join("<li>{0}</li>".format(esc(t)) for t in differ) or (
        "<li>None beyond the placeholders.</li>"
    )
    if shot:
        left = image(shots, shot, "Screenshot: " + eyebrow + ", " + title)
    else:
        left = '<div class="missing">The tab is disabled in this stage.</div>'
    return (
        '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
        '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
        "</ul></div><div><h3>Differences from the mockup</h3><ul>{4}</ul></div>"
        '</div><div class="compare both"><figure><figcaption>Qt skeleton'
        " (Stage 3)</figcaption>{5}</figure><figure><figcaption>Mockup (Stage 0)"
        '</figcaption><div class="stage">{6}</div></figure></div></section>'
    ).format(anchor, esc(eyebrow), esc(title), notes, diffs, left, mockup_window(slug))


