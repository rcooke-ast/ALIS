def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    for anchor, eyebrow, title, shot, check in SECTIONS:
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul></div></div><div class="compare"><figure>{4}</figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                image(shots, shot, "Screenshot: " + title),
            )
        )
    small = "".join(
        '<figure id="{0}">{1}<figcaption><b>{2}</b>{3}</figcaption></figure>'.format(
            anchor, image(shots, name, title), esc(title), esc(text)
        )
        for anchor, title, name, text in SMALL
        if (shots / name).exists()
    )
    toc = "".join(
        '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
            esc(e[1]), e[0], esc(e[2])
        )
        for e in SECTIONS
    ) + (
        '<li><span class="grp">Points 1, 6 · your report</span><a href="#more">'
        "The other functions, Final for a blind run, and the Instrument group</a></li>"
    )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 8 ·'
        " feedback from users, draft 1</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 8, after the points of the Feedback'
        " list and the four items carried over from Stage 7: one section per change,"
        " each with what to check. Each screenshot is taken off-screen at 1440×900;"
        " the fits are real ALIS runs from the window, of synthetic data in the"
        " shapes of your projects and of the shipped examples.</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing new to see</h2><ul>'
        "{covered}</ul></div>"
        '<ul class="toc">{toc}</ul>{sections}'
        '<section class="mock" id="more"><div class="eyebrow">Points 1 and 6, and'
        ' your report</div><h2>The smaller changes</h2><div class="newgrid">'
        "{small}</div></section></div>\n"
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        covered=covered,
        toc=toc,
        sections="".join(sections),
        small=small,
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
