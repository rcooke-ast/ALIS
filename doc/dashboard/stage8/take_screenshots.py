"""Screenshots of what changed in Stage 8, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen:

- a card whose long redshift shows its start (Task 8.2);
- pure thermal on a component whose T label others share: its plan (Task 8.3);
- a drag of a pure-thermal line past its tick, held at T's bound (Task 8.4);
- the limit pure thermal replaced, kept as a comment, in the .mod panel (Task 8.5);
- the Regions tab zoomed on a fit region's edge (Task 8.6);
- the Snip box's Resolution with each kind of function, and lsf without linetools,
  and the Data tab's Resolution column (Task 8.8);
- examples/lsf_file fitted through its LSF file, in Inspect (Tasks 8.7, 8.8);
- a plain ALIS blind run's results, and Final's note (Task 8.9);
- a continuum fitted alone, in Results (Task 8.10);
- Fit · Results' Instrument group, its shifts named by their snips (2026-11-01).

The fits are real ALIS runs from the window, of synthetic data in the shapes of
RJC's projects and of the shipped examples. Run it from the repository root::

    python doc/dashboard/stage8/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
import shutil
import sys
import tempfile
import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _skeleton():
    """The skeleton's screenshot helpers."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
pump, shoot = _SK.pump, _SK.shoot

EXAMPLES = ROOT / "examples"
METAL = EXAMPLES / "metal_line_abs/model/fit_spectra.mod"
SPECTRUM = EXAMPLES / "metal_line_abs/data/OI_SiII.dat"
LSF = EXAMPLES / "lsf_file/model/test_lsf.dat"
BLIND = EXAMPLES / "blind/model/fit_spectra.mod"


def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def tab(window, num):
    window.tabs.setCurrentIndex(num)
    pump(0.6)
    return window.tab_widgets[num]


def components(window, ion="H I"):
    comp = tab(window, 2)
    for item in comp._ion_items():
        if item.text(0) == ion:
            comp.tree.setCurrentItem(item)
    pump(0.8)
    return comp


def run(window):
    """Run the fit from the window and wait for it."""
    window.qactions["fit.run"].trigger()
    while window.fit.active:
        pump(0.2)
    pump(0.5)


def show_snip(regions, specid):
    """Select a snip's transition in the Regions tab's list."""
    for num in range(regions.listing.topLevelItemCount()):
        item = regions.listing.topLevelItem(num)
        snip = regions.current_snip
        regions.listing.setCurrentItem(item)
        pump(0.1)
        if snip() is not None and snip().specid == specid:
            return
    raise RuntimeError(specid)


def screens(window, work, outdir):
    """Each screen, as a function that takes the window."""
    from dashboard_synthetic import write_ratio_fit, write_shifted_fit

    from alis import bundle as B
    from alis.dashboard import datasets as DS
    from alis.dashboard import edit as E
    from alis.dashboard import fitview as FV
    from alis.dashboard import lines as L
    from alis.dashboard import resolution as RN
    from alis.dashboard import session as S
    from alis.dashboard import snips as SN
    from alis.dashboard import sources as SR

    def long_value():
        # Task 8.2: J101155p294141's z, with 16 digits
        lines = ["voigt ion=1H_I 14.0 2.5007852870610208za1 10.0 0.0ZEROT specid=0"]
        window.import_path(str(write_ratio_fit(work / "long", lines)))
        components(window)
        shoot(window, outdir / "cards_long.png")
        done(window)

    def thermal_plan():
        # Task 8.3: a2's T shares ZEROT with a1 and a line of the Lyα forest
        lines = [
            "voigt ion=1H_I 14.0 2.50360 10.0 0.0ZEROT specid=0",
            "voigt ion=1H_I 13.5 2.50420 10.0 0.0ZEROT specid=0",
            "voigt ion=1Ly_a 13.0 2.50600 20.0 0.0ZEROT specid=0",
        ]
        window.import_path(str(write_ratio_fit(work / "plan", lines)))
        comp = components(window)

        def show(dialog):
            dialog.show()
            pump(0.5)
            shoot(dialog, outdir / "thermal_plan.png")
            return 1

        before = window.run_dialog
        window.run_dialog = show
        menu = comp.card_widgets["a2"].temp.menu()
        next(a for a in menu.actions() if a.text().startswith("Pure thermal")).trigger()
        pump(0.5)
        window.run_dialog = before
        done(window)

    def drag_bound():
        # Task 8.4: begun 5 km/s from the tick, 40 km/s past it: T held at 1 K
        line = "voigt ion=1H_I 14.0 2.50360za1 0.0BX1 70000.0ta1 specid=0"
        lims = ["lim param BX1 [0.0,None]", "lim param ta1 [1.0,None]"]
        window.import_path(str(write_ratio_fit(work / "drag", [line], lims)))
        comp = components(window)
        view = comp.panel_widgets[0].view
        x0, x1, y = 5.0, -40.0, 0.5
        view.dragged.emit(x0, y, x0, y, "start")
        for f in (0.25, 0.5, 0.75, 1.0):
            view.dragged.emit(x0, y, x0 + f * (x1 - x0), y, "move")
            pump(0.3)
        shoot(window, outdir / "drag_bound.png")
        view.dragged.emit(x0, y, x1, y, "finish")
        pump(0.3)
        done(window)

    def limit_back():
        # Task 8.5: pure thermal over b_turb's own limit, which it keeps as a comment
        line = "voigt ion=1H_I 14.0 2.50360za1 5.0bx1 8000.0TA1 specid=0"
        lims = ["lim param bx1 [0.01,None]"]
        window.import_path(str(write_ratio_fit(work / "limit", [line], lims)))
        comp = components(window)
        menu = comp.card_widgets["a1"].temp.menu()
        before = window.run_dialog
        window.run_dialog = lambda dialog: 1
        next(a for a in menu.actions() if a.text().startswith("Pure thermal")).trigger()
        window.run_dialog = before
        window.set_panel_open(True)
        window.refresh()
        num = next(
            n
            for n, text in enumerate(window.session.project.text.splitlines())
            if "# pure thermal; was" in text
        )
        window.panel.select_lines([num])
        pump(0.8)
        shoot(window, outdir / "limit_back.png")
        window.set_panel_open(False)
        done(window)

    def snipped():
        """A new project of metal_line_abs's spectrum: O I 1302 and Si II 1304."""
        path = work / "snips.model"
        if path.exists():
            path.unlink()
        session, _ = S.Session.new(str(path), [str(SPECTRUM)], z=0.0)
        window.set_session(session)
        project = session.project
        spectra = {r.id: SR.spectrum(project, r) for r in project.rows}
        atom = L.atomic(project.registry)
        for ion, rest, low, high in (
            ("16O_I", 1302.16849, 1301.8, 1302.5),
            ("28Si_II", 1304.3702, 1304.0, 1304.7),
        ):
            line = next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)
            session.history.do(
                SN.snip_step(session.project, project.systems[0], line, spectra)
            )
            snip = session.project.snips[-1]
            session.history.do(SN.add_region_step(session.project, snip, low, high))
        window.refresh()
        regions = tab(window, 1)
        regions.element_box.setCurrentIndex(regions.element_box.findText("Si"))
        regions.ion_box.setCurrentIndex(regions.ion_box.findText("II"))
        pump(0.3)
        for num in range(regions.listing.topLevelItemCount()):
            item = regions.listing.topLevelItem(num)
            if item.text(1).startswith("Si II 1304"):
                regions.listing.setCurrentItem(item)
        pump(0.8)
        return regions

    def edges():
        # Task 8.6: the shading ends at the pixels' step edges
        regions = snipped()
        strip = regions.strips[0]
        strip.view.setXRange(1303.95, 1304.15, padding=0)
        pump(0.6)
        shoot(window, outdir / "regions_edges.png")
        done(window)

    def resolution():
        # Task 8.8: the Snip box's Resolution, each kind of function
        regions = snipped()
        regions.current_snip = lambda: window.session.project.snips[-1]
        regions._own_chosen("resolution", 1)
        pump(0.5)
        shoot(regions.snip, outdir / "res_own.png")
        for name, kwargs, shot in (
            ("Afwhm", {}, "res_afwhm.png"),
            ("apod", {}, "res_apod.png"),
            ("lsffile", {"path": str(LSF)}, "res_lsffile.png"),
        ):
            regions.choose_function(name, **kwargs)
            regions._fill_own(window.session.project, window.session.project.snips[-1])
            pump(0.5)
            shoot(regions.snip, outdir / shot)
        # A model that writes voigtconv for the snip: named, with its link
        project = window.session.project
        snip = project.snips[-1]
        change = E.set_keyword(
            project.parsed, snip.data, "resolution", "voigtconv(7.0VC,4.0)"
        )
        window.session.history.do(project.step(change, "voigtconv"))
        window.refresh()
        regions._fill_own(window.session.project, window.session.project.snips[-1])
        pump(0.5)
        shoot(regions.snip, outdir / "res_several.png")
        # lsf where linetools is missing
        window.session.history.undo()
        installed = RN.linetools_installed
        RN.linetools_installed = lambda: False
        asked = window.ask
        window.ask = lambda kind, title, text, choices, **kw: choices[0]
        regions.choose_function("lsf")
        regions._fill_own(window.session.project, window.session.project.snips[-1])
        pump(0.5)
        shoot(regions.snip, outdir / "res_linetools.png")
        RN.linetools_installed = installed
        window.ask = asked
        # The Data tab: the dataset's Resolution, and the snip with its own
        window.session.history.undo()
        data = tab(window, 0)
        data.refresh(window.session)
        pump(0.5)
        shoot(window, outdir / "data_resolution.png")
        done(window)

    def lsf_fit():
        # Tasks 8.7 and 8.8: examples/lsf_file through its LSF file, from the window
        folder = work / "lsf_file"
        shutil.copytree(str(LSF.parents[1]), str(folder))
        path = work / "lsf.model"
        B.pack_to(str(folder / "model/fit_spectra.mod"), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        regions = tab(window, 1)
        regions.current_snip = lambda: window.session.project.snips[0]
        regions._own_chosen("resolution", 1)
        regions.choose_function("lsffile", path=str(LSF))
        run(window)
        tab(window, 3)
        window.fit_tab.subtabs.setCurrentIndex(0)
        window.fit_tab.inspect._model_chosen(FV.FINAL)
        pump(1.0)
        shoot(window, outdir / "lsf_fit.png")
        done(window)

    def blind_run():
        # Task 8.9: examples/blind with the .mod.out a plain ALIS run wrote
        folder = work / "blind"
        shutil.copytree(str(BLIND.parents[1]), str(folder))
        out = (BLIND.parent / (BLIND.name + ".out.reference")).read_text()
        (folder / "model" / (BLIND.name + ".out")).write_text(out)
        window.import_path(str(folder / "model" / BLIND.name))
        pump(1.0)
        tab(window, 3)
        window.fit_tab.subtabs.setCurrentIndex(1)
        pump(0.8)
        shoot(window, outdir / "blind_results.png")
        window.fit_tab.subtabs.setCurrentIndex(0)
        window.fit_tab.inspect._model_chosen(FV.FINAL)
        pump(0.8)
        shoot(window, outdir / "blind_final.png")
        done(window)

    def continuum():
        # Task 8.10: metal_line_abs with no component
        folder = work / "metal"
        shutil.copytree(str(METAL.parents[1]), str(folder))
        model = folder / "model" / METAL.name
        kept = [
            ln
            for ln in model.read_text().splitlines(True)
            if not ln.lstrip().startswith("voigt")
        ]
        model.write_text("".join(kept))
        path = work / "continuum.model"
        B.pack_to(str(model), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        run(window)
        tab(window, 3)
        window.fit_tab.subtabs.setCurrentIndex(1)
        pump(0.8)
        shoot(window, outdir / "continuum_results.png")
        done(window)

    def instrument():
        # RJC's report of 2026-11-01: the shifts named by their snips, open
        mod = write_shifted_fit(work / "shifted")
        path = work / "shifted.model"
        B.pack_to(str(mod), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        project = window.session.project
        for snip in project.snips:
            if snip.row is not None and not snip.row.reference:
                window.session.history.do(
                    DS.snip_shift_step(window.session.project, snip, True)
                )
                break
        window.refresh()
        run(window)
        tab(window, 3)
        window.fit_tab.subtabs.setCurrentIndex(1)
        pump(0.8)
        shoot(window, outdir / "instrument.png")
        done(window)

    return [
        long_value,
        thermal_plan,
        drag_bound,
        limit_back,
        edges,
        resolution,
        lsf_fit,
        blind_run,
        continuum,
        instrument,
    ]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage8_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    # Questions take their last choice (Cancel), and dialogs are cancelled, unless a
    # screen answers them itself
    window.ask = lambda kind, title, text, choices, **kw: choices[-1]
    window.tell = lambda title, text, icon="info": None
    window.run_dialog = lambda dialog: 0
    failed = []
    for screen in screens(window, work, outdir):
        if only and screen.__name__ not in only:
            continue
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage8_shots", sys.argv[2:])
