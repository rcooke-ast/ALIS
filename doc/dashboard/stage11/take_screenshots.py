"""Screenshots of what changed in Stage 11, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen, all of
synthetic fits (``tests/dashboard_fits.py``: the metal example's spectrum, copies
with other noise, and snips cut from them):

- the Regions tab with two snips of one transition in one dataset (Task 11.2);
- Open a fit's question for a fit of several datasets, the New project dialog, the
  dialog that assigns the snips (with a snip of no spectrum, and how unassigned
  snips are loaded), the warning before a snip is cut again, the overlap warning,
  and the preview, with the reference it moves (Tasks 11.1, 11.3–11.5);
- the Components tab's buttons with their "…" (11.6);
- the Data tab's menu of line IDs (11.7);
- a card's question for a label (11.8), and Renumber labels…'s warning (11.9).

A dialog is drawn on its own; a question or a warning is drawn as the window's
message box draws it. Run it from the repository root::

    python doc/dashboard/stage11/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
