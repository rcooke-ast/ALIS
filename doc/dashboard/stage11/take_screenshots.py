import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _skeleton():
    """The skeleton's screenshot helpers."""
    import importlib.util

    path = ROOT / "doc/dashboard/skeleton/take_screenshots.py"
    spec = importlib.util.spec_from_file_location("skeleton_screenshots", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _skeleton()
pump, shoot = _SK.pump, _SK.shoot
DATA, REGIONS, COMPONENTS = 0, 1, 2


def done(window):
    """Close the project, keeping nothing (no question asked)."""
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def shoot_dialog(dialog, path, size=None):
    """Draw a dialog on its own, as it opens."""
    if size is not None:
        dialog.resize(*size)
    dialog.show()
    pump(0.4)
    shoot(dialog, path)
    dialog.hide()


def shoot_box(title, text, choices, path, icon="question"):
    """Draw a question or a warning as the window's message box draws it."""
    from qtpy import QtWidgets

    box = QtWidgets.QMessageBox()
    box.setWindowTitle(title)
    box.setText(text)
    box.setIcon(
        {
            "question": QtWidgets.QMessageBox.Icon.Question,
            "warning": QtWidgets.QMessageBox.Icon.Warning,
        }[icon]
    )
    for num, choice in enumerate(choices):
        role = (
            QtWidgets.QMessageBox.ButtonRole.RejectRole
            if num == len(choices) - 1
            else QtWidgets.QMessageBox.ButtonRole.AcceptRole
        )
        box.addButton(choice, role)
    shoot_dialog(box, path)


def screens(window, outdir, work):
    """The screens, each a function that saves its PNG."""
    import numpy as np
    from dashboard_fits import (
        OI,
        SII,
        SPECTRUM,
        earlier_snip,
        noisy_copy,
        two_exposures,
        write_mod,
    )
    from dashboard_synthetic import write_ratio_fit

    from alis.dashboard import loadfit as LF
    from alis.dashboard import session as S
    from alis.dashboard import sources as SR
    from alis.dashboard.qt import dialogs as D
    from alis.dashboard.qt import window as WN

    def spectra(folder):
        folder.mkdir(parents=True, exist_ok=True)
        src = folder / "specA.dat"
        np.savetxt(str(src), np.loadtxt(str(SPECTRUM))[:, :3])
        return src, noisy_copy(folder, "specB.dat")

    def fit_of(folder, extra=()):
        """O I from specA (va), Si II from specB (vb), and more snips."""
        src, other = spectra(folder / "spectra")
        data = folder / "old" / "data"
        snips = [
            (earlier_snip(data, src, OI, name="specA_16O_I_1302.2_reg.dat"),)
            + ("7.0", "va", "shift=vshift(0.0vsa)"),
            (earlier_snip(data, other, SII, name="specB_28Si_II_1304.4_reg.dat"),)
            + ("5.0", "vb", ""),
        ] + list(extra)
        return src, other, write_mod(folder / "old", snips)

    def regions_two():
        window.import_path(str(two_exposures(work / "two")))
        pump(1.0)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(REGIONS)
        pump(0.6)
        tab = window.tab_widgets[REGIONS]
        tab.show_transition("a", OI[0], OI[1])
        pump(0.6)
        tab.strips[1].view.clicked.emit(1302.0, 0.5)
        pump(0.4)
        shoot(window, outdir / "regions_two.png")
        done(window)

    def open_fit():
        far = noisy_copy(work / "open" / "far", "specC.dat", seed=7)
        src, other, mod = fit_of(
            work / "open",
            [
                (
                    earlier_snip(
                        work / "open" / "old" / "data",
                        far,
                        OI,
                        name="specC_16O_I_1302.2_reg.dat",
                    ),
                )
                + ("6.0", "vc", "")
            ],
        )
        asked = []

        def ask(kind, title, text, choices, default=None, icon="question"):
            asked.append((kind, title, text, choices))
            answer = {
                "open_fit": WN.WITH_SPECTRUM,
                "cut_again": "Cut again",
            }.get(kind)
            return answer if answer in choices else choices[-1]

        def run(dialog):
            if isinstance(dialog, D.NewProjectDialog):
                target = work / "open" / "project"
                target.mkdir(parents=True, exist_ok=True)
                dialog.name.setText("specAB")
                dialog.folder.setText(str(target))
                dialog.add_spectrum(str(src))
                dialog.add_spectrum(str(other))
                dialog.redshift.setText("0.0")
                shoot_dialog(dialog, outdir / "new_project.png")
                return 1
            if isinstance(dialog, D.AssignDialog):
                shoot_dialog(dialog, outdir / "assign.png", (900, 560))
                return 1
            if isinstance(dialog, D.PlanDialog):
                shoot_dialog(dialog, outdir / "preview.png", (900, 520))
                return 0
            return 0

        window.ask, window.run_dialog = ask, run
        window.open_fit(str(mod))
        kind, title, text, choices = next(a for a in asked if a[0] == "open_fit")
        shoot_box(title, text, choices, outdir / "open_fit_question.png")
        done(window)

    def cut_again():
        src, other, mod = fit_of(work / "cut")
        session, _ = S.Session.new(str(work / "cut" / "test.model"), [str(src)], z=0.0)
        window.set_session(session)
        fit = LF.read_fit(str(mod), session.project.registry)
        spec = {r.id: SR.spectrum(session.project, r) for r in session.project.rows}
        holders = LF.snip_holders(session.project, fit, spec)
        asked = []

        def ask(kind, title, text, choices, default=None, icon="question"):
            asked.append((title, text, choices))
            return choices[-1]

        dialog = D.AssignDialog(fit, holders, LF.best_guess(fit, holders), ask=ask)
        dialog.left.clearSelection()
        dialog.move("r1", ["1"])
        title, text, choices = asked[-1]
        shoot_box(title, text, choices, outdir / "cut_again.png", "warning")
        done(window)

    def overlap():
        src, _ = spectra(work / "overlap" / "spectra")
        one = noisy_copy(work / "overlap" / "copies", "e1.dat", seed=1)
        two = noisy_copy(work / "overlap" / "copies", "e2.dat", seed=2)
        data = work / "overlap" / "old" / "data"
        mod = write_mod(
            work / "overlap" / "old",
            [
                (earlier_snip(data, src, OI, name="specA_16O_I_1302.2_reg.dat"),)
                + ("7.0", "va", ""),
                (earlier_snip(data, one, OI, name="e1_16O_I_1302.2_reg.dat"),)
                + ("5.0", "vb", ""),
                (
                    earlier_snip(
                        data, two, OI, name="e2_16O_I_1302.2_reg.dat", centre=1302.3
                    ),
                )
                + ("5.0", "vb", ""),
            ],
            ions=(OI[0],),
        )
        session, _ = S.Session.new(
            str(work / "overlap" / "test.model"), [str(src)], z=0.0
        )
        window.set_session(session)
        asked = []

        def ask(kind, title, text, choices, default=None, icon="question"):
            asked.append((kind, title, text, choices))
            return choices[-1]

        window.ask = ask
        window.run_dialog = lambda dialog: (
            1 if isinstance(dialog, D.AssignDialog) else 0
        )
        window.load_fit(str(mod))
        kind, title, text, choices = next(
            a for a in asked if a[0] == "unassigned_overlap"
        )
        shoot_box(title, text, choices, outdir / "overlap.png", "warning")
        done(window)

    def buttons():
        lines = [
            "voigt ion=1H_I 14.0 2.50360za1 10.0ba1 0.0ta1 specid=0",
            "voigt ion=1H_I 13.8 2.50380za3 10.0ba3 0.0ta3 specid=0",
            "voigt ion=1H_I 13.5 2.50420za2 10.0ba2 0.0ta2 specid=0",
        ]
        window.import_path(str(write_ratio_fit(work / "buttons", lines)))
        pump(1.0)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(COMPONENTS)
        pump(0.8)
        shoot(window, outdir / "buttons.png")
        # Renumber labels…'s warning, with the lines that change
        seen = []
        window.run_dialog = lambda dialog: seen.append(dialog) or 0
        window.qactions["components.renumber"].trigger()
        shoot_dialog(seen[-1], outdir / "renumber.png", (900, 420))
        done(window)

    def card_label():
        lines = [
            "voigt ion=1H_I 14.0 2.50360za1 10.0ba1 0.0ta1 specid=0",
            "voigt ion=1H_I 13.8 2.50380za2 10.0ba2 0.0ta2 specid=0",
            "voigt ion=1H_I 13.5 2.50420 10.0 0.0 specid=0",
            "voigt ion=28Si_II 12.0 2.50420 10.0 0.0 specid=0",
        ]
        window.import_path(str(write_ratio_fit(work / "label", lines)))
        pump(1.0)
        window.tabs.setCurrentIndex(COMPONENTS)
        pump(0.6)
        tab = window.tab_widgets[COMPONENTS]
        card = tab.card_widgets["a3"]
        seen = []
        window.run_dialog = lambda dialog: seen.append(dialog) or 0
        for action in card.badges["ColDens:28Si_II"].menu().actions():
            if action.text() == "Fixed":
                action.trigger()
        shoot_dialog(seen[-1], outdir / "card_label.png")
        done(window)

    def data_ids():
        src, _ = spectra(work / "ids")
        session, _ = S.Session.new(str(work / "ids" / "test.model"), [str(src)], z=0.0)
        window.set_session(session)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(REGIONS)
        pump(0.6)
        window.tab_widgets[REGIONS].show_transition("a", SII[0], SII[1])
        window.tabs.setCurrentIndex(DATA)
        pump(0.6)
        tab = window.tab_widgets[DATA]
        tab.line_ids_menu.setCurrentIndex(tab.line_ids_menu.findText("This transition"))
        pump(0.6)
        shoot(window, outdir / "data_ids.png")
        done(window)

    return [regions_two, open_fit, cut_again, overlap, buttons, card_label, data_ids]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage11_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    failed = []
    for screen in screens(window, outdir, work):
        if only and screen.__name__ not in only:
            continue
        # Questions take their last choice (Cancel) and dialogs are cancelled,
        # unless a screen answers them
        window.ask = lambda kind, title, text, choices, **kw: choices[-1]
        window.tell = lambda title, text, icon="info": None
        window.run_dialog = lambda dialog: 0
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage11_shots", sys.argv[2:])
