def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    toc = []
    for anchor, eyebrow, title, shot, check in SECTIONS:
        if not (shots / shot).exists():
            continue
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul></div></div><div class="compare"><figure>{4}</figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                image(shots, shot, "Screenshot: " + title),
            )
        )
        toc.append(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(eyebrow), anchor, esc(title)
            )
        )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 11 ·'
        " a fit of several spectra, draft 8</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 11: Feedback point 2 (a .mod whose'
        " snips come from several spectra), the bug found on the way, and the three"
        " items carried over from Stage 10. One section per change, each with what"
        " to check. Each screenshot is taken off-screen at 1440×900, of synthetic"
        " fits: the metal example's spectrum (specA), copies with other noise"
        " (specB, specC), and snips cut from them.</p>"
        '<p class="lede">Draft 2: the buttons under the Components tab\'s navigator'
        " are stacked, so that each can be read (your comment). Draft 3: the overlap"
        " warning in your words. Draft 4: the cut-again warning's buttons, Cut again"
        " and Unassign snip. Draft 5: the assignment dialog's message in your"
        " words. Draft 6: Open a fit's question in your words, and the New project"
        " dialog saying only what the .mod names. Draft 7: Unassigned snips, and Each"
        " snip is its own dataset, in the dialog and the overlap warning. Draft 8:"
        " Open with full spectra (recommended)….</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing new to see</h2><ul>'
        "{covered}</ul></div>"
        '<ul class="toc">{toc}</ul>{sections}</div>\n'
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        covered=covered,
        toc="".join(toc),
        sections="".join(sections),
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
