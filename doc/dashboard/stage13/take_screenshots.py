"""Screenshots of what changed in Stage 13, for the review that closes the stage.

Opens the window off-screen at 1440x900 (D43) and saves one PNG per screen, all of
synthetic scenes from the stage's ``gui`` tests (``tests/dashboard_synthetic.py``,
the metal example's spectrum, ``examples/lsf_spline``):

- Inspect and Results of a run with an ``lsfspline`` resolution, its ``.mod.out``
  written as ALIS wrote it before (no ``locations``), its best fit drawn (Task 13.2);
- Results of a run whose outputs do not read: why, and its statistics, and the
  status bar at the end of such a run (13.3);
- Fit statistics of a run stopped at its maximum number of iterations with a
  convergence check that failed: the rows in red, the run history's ⚠, the status
  bar at the end of the run (13.4), and Warnings and options to resolve… (13.10);
- the Data tab and the Regions tab with two datasets of one label, named apart
  (13.6);
- the Snip box with an LSF file in km/s, its drop-down and its note, and the Data
  tab's LSF file dialog (13.7);
- the shortcut sheet's second page, and the Components tab's ⌨ Keys list (13.8).

The fitting process's exit (13.1) and the system's Save dialog (13.5) cannot be
shown in a still; the page names their tests. Run it from the repository root::

    python doc/dashboard/stage13/take_screenshots.py OUTDIR [SCREEN ...]

Generated by RJC and Claude.
"""

import os
import sys
import tempfile
import traceback
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "tests"))


def _load(name, path):
    import importlib.util

    spec = importlib.util.spec_from_file_location(name, ROOT / path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


_SK = _load("skeleton_screenshots", "doc/dashboard/skeleton/take_screenshots.py")
_S12 = _load("stage12_screenshots", "doc/dashboard/stage12/take_screenshots.py")
pump, shoot = _SK.pump, _SK.shoot
done, shoot_dialog = _S12.done, _S12.shoot_dialog
DATA, REGIONS, COMPONENTS, FIT = 0, 1, 2, 3
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
SPLINE = ROOT / "examples/lsf_spline/model/fit_spectra.mod"


def screens(window, outdir, work):
    """The screens, each a function that saves its PNG."""
    from types import SimpleNamespace

    from dashboard_synthetic import write_ratio_fit
    from test_dashboard_datasets import _kms_file
    from test_dashboard_project import _one_label
    from test_dashboard_results import _broken_mod_out, store_run

    from alis import bundle as B
    from alis.dashboard import actions as A
    from alis.dashboard import resolution as RN
    from alis.dashboard import results as RS
    from alis.dashboard import runs as R
    from alis.dashboard.qt import dialogs as D

    def opened(model, name, **info):
        """A model packed and opened, with its reference outputs as its run."""
        path = work / (name + ".model")
        B.pack_to(str(model), str(path), with_outputs=False)
        window.open_path(str(path))
        pump(1.0)
        window.set_panel_open(False)
        store_run(window.session.project, model, **info)
        window.session.runs_changed()
        window.refresh()
        pump(0.6)

    def fit_tab(sub):
        window.tabs.setCurrentIndex(FIT)
        window.fit_tab.subtabs.setCurrentIndex(sub)
        pump(1.2)

    def ended(status=R.COMPLETED):
        window.fit.job = SimpleNamespace(kind="run", warnings=[], message="")
        window.fit.session = window.session
        window._fit_ended(status)
        pump(0.4)

    def spline_run():
        reference = Path(str(SPLINE) + ".out.reference").read_text()
        # As ALIS wrote it before Task 13.2: no locations on the data line (the
        # copy of the input model at the end keeps them)
        lines = reference.splitlines(keepends=True)
        for num, line in enumerate(lines):
            if "resolution=lsfspline(" in line and not line.startswith("#"):
                start = line.index(";locations:")
                lines[num] = line[:start] + line[line.index(")", start) :]
                break
        opened(
            SPLINE,
            "spline",
            mod_out="".join(lines),
            covar=False,
            chi2_final=450.116951,
            chi2_initial=459.613445,
            dof=450,
            iterations=342,
            origin=R.DASHBOARD,
        )
        fit_tab(0)
        shoot(window, outdir / "spline_inspect.png")
        fit_tab(1)
        shoot(window, outdir / "spline_results.png")
        done(window)

    def unreadable():
        opened(
            METAL,
            "unreadable",
            mod_out=_broken_mod_out(),
            covar=False,
            chi2_final=357.874162,
            chi2_initial=420.0,
            dof=360,
            iterations=7,
            origin=R.DASHBOARD,
        )
        fit_tab(1)
        ended()
        shoot(window, outdir / "unreadable_results.png")
        done(window)

    def maxiter():
        opened(
            METAL,
            "maxiter",
            chi2_final=357.874162,
            chi2_initial=420.0,
            dof=360,
            iterations=1000,
            status_code=5,
            reason=RS.MAXITER_REASON,
            convergence={"converged": False, "failed": 2, "total": 9},
            warnings=[
                "sub-pixellation scale (30) has exceeded the warning level of: 10"
            ],
            origin=R.DASHBOARD,
        )
        fit_tab(1)
        ended()
        shoot(window, outdir / "maxiter_results.png")
        results = window.fit_tab.results
        print("statistics:", results.statistics_rows)
        print("status bar:", window.statusBar().currentMessage())
        # Warnings and options to resolve… (Task 13.10)
        opened_dialogs = []
        window.run_dialog = lambda dialog: opened_dialogs.append(dialog) or 0
        results.warnings_button.click()
        shoot_dialog(opened_dialogs[-1], outdir / "maxiter_warnings.png", (760, 300))
        done(window)

    def two_names():
        window.import_path(str(_one_label(work / "names", ["va", "vab"])))
        pump(1.0)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(DATA)
        pump(0.8)
        shoot(window, outdir / "names_data.png")
        window.tabs.setCurrentIndex(REGIONS)
        pump(0.8)
        shoot(window, outdir / "names_regions.png")
        done(window)

    def lsf_kms():
        window.import_path(str(write_ratio_fit(work / "kms")))
        pump(1.0)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(REGIONS)
        pump(0.8)
        tab = window.tab_widgets[REGIONS]
        snip = tab.current_snip()
        if snip.specid not in snip.row.own_resolution:
            tab.res_choice.setCurrentIndex(1)
            tab.res_choice.activated.emit(1)
            pump(0.6)
        kms = _kms_file(work)
        tab.choose_function("lsffile", path=str(kms))
        pump(0.6)
        shoot(window, outdir / "kms_snip_box_A.png")
        tab.res_lsf_unit.setCurrentIndex(1)
        tab.res_lsf_unit.activated.emit(1)
        pump(0.8)
        shoot(window, outdir / "kms_snip_box.png")
        print("note:", tab.res_note.text())
        # The Data tab's dialog, after the file is chosen
        row = window.session.project.rows[0]
        dialog = D.LsfFileDialog(
            "Resolution of {0}".format(row.name),
            RN.read_kernels(str(kms)),
            1215.67,
            unit="kms",
        )
        shoot_dialog(dialog, outdir / "kms_dialog.png", (460, 170))
        done(window)

    def keys():
        window.tabs.setCurrentIndex(COMPONENTS)
        pump(0.4)
        sheet = D.ShortcutsDialog(window.qactions, window, place="Components", page=1)
        shoot_dialog(sheet, outdir / "keys_sheet.png", (900, 720))
        tab_keys = D.TabKeysDialog("Components", lambda: None, window)
        shoot_dialog(tab_keys, outdir / "keys_components.png", (760, 470))
        shoot(window, outdir / "keys_corner.png")
        print("rows:", len(A.VIEW_KEYS))

    return [spline_run, unreadable, maxiter, two_names, lsf_kms, keys]


def main(outdir, only=()):
    """
    Take every screenshot (or those named in ``only``); a screen that fails says
    why, and the others go on.

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    work = Path(tempfile.mkdtemp(prefix="stage13_"))
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    failed = []
    for screen in screens(window, outdir, work):
        if only and screen.__name__ not in only:
            continue
        # Questions take their last choice (Cancel) and dialogs are cancelled,
        # unless a screen answers them
        window.ask = lambda kind, title, text, choices, **kw: choices[-1]
        window.tell = lambda title, text, icon="info": None
        window.run_dialog = lambda dialog: 0
        try:
            screen()
        except Exception:
            failed.append(screen.__name__)
            traceback.print_exc()
            done(window)
    print("written:", sorted(p.name for p in outdir.glob("*.png")))
    print("failed:", failed)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "stage13_shots", sys.argv[2:])
