def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections, toc = [], []
    for anchor, eyebrow, title, figures, check, ask in SECTIONS:
        present = [f for f in figures if (shots / f[0]).exists()]
        if not present:
            continue
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        question = (
            '<div class="ask"><b>A question.</b> {0}</div>'.format(esc(ask))
            if ask
            else ""
        )
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            '</ul>{4}</div></div><div class="figs">{5}</div></section>'.format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                question,
                "".join(figure(shots, *f) for f in present),
            )
        )
        toc.append(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(eyebrow), anchor, esc(title)
            )
        )
    covered = "".join("<li>{0}</li>".format(esc(t)) for t in COVERED)
    tests = ", ".join("<code>{0}</code>".format(esc(t)) for t in TESTS)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}{figs}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 13 ·'
        " users' feedback, draft {draft}</div><h1>{title}</h1>"
        '<p class="lede">What changed in Stage 13: the four points of the Feedback'
        " list (a crash report, your MWC137_02 project, the keys, and LSF files in"
        " km/s) and the item carried over from Stage 12. One section per change,"
        " each with what to check. Each screenshot is taken off-screen at"
        " 1440×900, of synthetic scenes from the stage's tests (the metal example,"
        " examples/lsf_spline, and fits in the shape of MWC137's specids 6 and 7);"
        " your own files were checked with scripts.</p>"
        '<p class="lede">Draft 2: a repeated dataset name takes its number in'
        " parentheses, “K7701 (2)” (your comment). Draft 3: Warnings and options"
        " to resolve… (your comment, Task 13.10, your response to Q13.8), in the"
        " section on fits that may not have converged.</p>"
        '<p class="lede">Leave a comment on anything to change; the changes are made'
        " before the stage closes.</p>"
        '<div class="decide"><h2>Also done, with nothing to see in a still</h2>'
        '<ul>{covered}</ul><p class="tests">Their tests: {tests}.</p></div>'
        '<ul class="toc">{toc}</ul>{sections}</div>\n'
    ).format(
        title=TITLE,
        draft=DRAFT,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        figs=FIGURE_CSS,
        hatch=hatch,
        covered=covered,
        tests=tests,
        toc="".join(toc),
        sections="".join(sections),
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
