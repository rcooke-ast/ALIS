TITLE = "Dashboard Regions Tab"


def build(shots, out):
    """
    Write the review page.

    Generated by RJC and Claude.
    """
    shots = Path(shots)
    css, fonts, hatch = mockup_parts()
    sections = []
    for anchor, eyebrow, title, shot, slug, check, differ in SECTIONS:
        notes = "".join("<li>{0}</li>".format(esc(t)) for t in check)
        diffs = "".join("<li>{0}</li>".format(esc(t)) for t in differ)
        sections.append(
            '<section class="mock" id="{0}"><div class="eyebrow">{1}</div>'
            '<h2>{2}</h2><div class="notes"><div><h3>What to check</h3><ul>{3}'
            "</ul></div><div><h3>Differences from the mockup</h3><ul>{4}</ul>"
            '</div></div><div class="compare both"><figure><figcaption>Regions'
            " tab (Stage 4)</figcaption>{5}</figure><figure><figcaption>Mockup"
            ' (Stage 0)</figcaption><div class="stage">{6}</div></figure></div>'
            "</section>".format(
                anchor,
                esc(eyebrow),
                esc(title),
                notes,
                diffs,
                image(shots, shot, "Screenshot: " + title),
                mockup_window(slug),
            )
        )
    new = "".join(
        '<figure id="{0}">{1}<figcaption><b>{2}</b>{3}</figcaption></figure>'.format(
            anchor, image(shots, name, title), esc(title), esc(text)
        )
        for anchor, title, name, text in NEW
    )
    data = "".join(
        "<figure>{0}<figcaption><b>{1}</b></figcaption></figure>".format(
            image(shots, name, title), esc(title)
        )
        for name, title in DATA
        if (shots / name).exists()
    )
    toc = (
        "".join(
            '<li><span class="grp">{0}</span><a href="#{1}">{2}</a></li>'.format(
                esc(e[1]), e[0], esc(e[2])
            )
            for e in SECTIONS
        )
        + '<li><span class="grp">No mockup</span><a href="#more">A new project,'
        " Normalised, Merge, CLEAR, a hidden continuum</a></li>"
        + '<li><span class="grp">Data tab</span><a href="#data">As it is now,'
        " with draft 1's comments applied</a></li>"
    )
    decide = "".join("<li>{0}</li>".format(esc(t)) for t in DECIDE)
    changes = "".join("<li>{0}</li>".format(esc(t)) for t in CHANGES)
    final = "".join("<li>{0}</li>".format(esc(t)) for t in FINAL)
    body = (
        "<title>{title}</title>\n{fonts}<style>{css}{page}</style>{hatch}"
        '<div class="sheet"><div class="eyebrow">ALIS dashboard · Stage 4 · the'
        " Regions tab, as the stage closes</div><h1>{title}</h1>"
        '<p class="lede">The Regions tab of the ALIS dashboard, built in Stage 4 on'
        " the Data tab's spectrum view, beside the mockups of Stage 0. Each"
        " screenshot is taken off-screen at 1440×900 from real data:"
        " <code>VMP_DLA/J1358p6522</code> (its fit imported, and a new project from"
        " its spectrum), <code>DH/Q1243p307</code> (three datasets) and"
        " <code>metal_line_abs</code>. This is the review at the close of the"
        " stage; the Data tab, reviewed halfway, is at the end as it is now.</p>"
        '<p class="lede">Every action is one step of the history (undo takes it'
        " back), and every value passes the blinding gate. From this tab, a new"
        " project from <code>OI_SiII.dat</code> was taken to a fit whose column"
        " densities agree with the example's reference (O I 13.984 ± 0.015 against"
        " 13.985 ± 0.016; Si II 13.044 ± 0.049 against 13.041 ± 0.050). Leave a"
        " comment on anything to change.</p>"
        '<div class="decide"><h2>What changed since draft 2</h2><ul>{final}</ul>'
        "</div>"
        '<div class="decide"><h2>What changed from draft 1 to draft 2</h2>'
        "<ul>{changes}</ul></div>"
        '<div class="decide"><h2>To decide</h2><ol>{decide}</ol></div>'
        '<ul class="toc">{toc}</ul>'
        '<div class="layoutbar">Layout: <button type="button" data-layout="both"'
        ' aria-pressed="true">Side by side</button><button type="button"'
        ' data-layout="stack" aria-pressed="false">One above the other</button>'
        "</div>{sections}"
        '<section class="mock" id="more"><div class="eyebrow">No mockup</div>'
        '<h2>Screens with no mockup</h2><div class="newgrid">{new}</div>'
        "</section>"
        '<section class="mock" id="data"><div class="eyebrow">Data tab</div>'
        '<h2>The Data tab now</h2><p>Draft 1\'s comments applied: the "!" stays'
        " until Confirm, which checks everything again; Remove… scrolls"
        ' sideways.</p><div class="newgrid">{data}</div></section>'
        "</div>{script}\n"
    ).format(
        title=TITLE,
        fonts=fonts,
        css=css,
        page=PAGE_CSS,
        hatch=hatch,
        decide=decide,
        changes=changes,
        final=final,
        toc=toc,
        sections="".join(sections),
        new=new,
        data=data,
        script=LAYOUT_SCRIPT,
    )
    Path(out).write_text(body, encoding="utf-8")
    return out


if __name__ == "__main__":
    print(build(sys.argv[1], sys.argv[2]))
