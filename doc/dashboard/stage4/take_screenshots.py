"""Screenshots of the dashboard's Data and Regions tabs, for review.

Dashboard Stage 4.7 (Q4.1). Opens the window off-screen at 1440x900 (D43) and saves
one PNG per screen:

- a new project from J1358p6522's spectrum (``context/fitting_examples/VMP_DLA/
  J1358p6522/data/J1358p6522_fluxcal.dat``), z = 3.067258, with Identify a feature
  open after a click on the Lyβ trough (the ``data_new`` mockup);
- Q1243p307, imported: three datasets, their coverage, and HIRES's snips (the
  ``data_datasets`` mockup);
- the screens with no mockup: J1358p6522 imported (its snips, no source, its D I line
  blinded as in the mockups), Q1243p307 after a tie and Confirm, ``examples/blind``,
  the Add file dialog, and the preview of Remove…;
- the Regions tab (Stage 4.13): J1358p6522 imported, Ly7 and its 36 shared pixels
  (the ``regions`` mockup); Q1243p307's O I 1302 in three datasets (the
  ``regions_datasets`` mockup); and, with no mockup, a new project from
  J1358p6522's spectrum (Lyβ snipped, a region drawn, a knot, Normalised), the
  merge's confirmation, CLEAR's preview, and a hidden continuum.

Run it from the repository root (``regions`` takes only the Regions tab's)::

    python doc/dashboard/stage4/take_screenshots.py OUTDIR [regions]

Generated by RJC and Claude.
"""

import os
import shutil
import sys
import tempfile
from pathlib import Path

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ["ALIS_HOME"] = tempfile.mkdtemp(prefix="alis_home_")

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "doc/dashboard/skeleton"))

from take_screenshots import BLIND, J1358, Q1243, blind_d_i, pump, shoot  # noqa: E402

SOURCE = (
    ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/data/J1358p6522_fluxcal.dat"
)
Z_J1358 = 3.067258


def dialog_shot(window, dialog, path):
    """Show a dialog over the window and save it."""
    dialog.show()
    pump(0.3)
    shoot(dialog, path)
    dialog.hide()


def show(tab, element, stage, name):
    """Choose a transition on the Regions tab."""
    if tab.state.get("element") != element:
        tab.element_box.setCurrentIndex(tab.element_box.findText(element))
    if tab.state.get("stage") != stage:
        tab.ion_box.setCurrentIndex(tab.ion_box.findText(stage))
    for num in range(tab.listing.topLevelItemCount()):
        item = tab.listing.topLevelItem(num)
        if item.text(1).startswith(name):
            tab.listing.setCurrentItem(item)
            return
    raise ValueError(name + " is not listed")


def regions_shots(window, outdir, tmp):
    """
    The Regions tab's screenshots.

    Generated by RJC and Claude.
    """
    from alis.dashboard import blinding as BL
    from alis.dashboard import session as S
    from alis.dashboard import snips as SN
    from alis.dashboard.qt import dialogs as D

    # J1358p6522 imported: Ly7, its 36 shared pixels (regions)
    if J1358.exists():
        window.import_path(str(J1358))
        pump(1.0)
        blind_d_i(window)
        window.set_panel_open(True, 420)
        window.tabs.setCurrentIndex(1)
        tab = window.tab_widgets[1]
        show(tab, "H", "I", "Ly7")
        pump(1.0)
        shoot(window, outdir / "regions_j1358.png")
        window.set_panel_open(False)

    # Q1243p307: O I 1302 in three datasets (regions_datasets)
    if Q1243.exists():
        window.import_path(str(Q1243))
        window.set_panel_open(False)
        pump(1.5)
        window.tabs.setCurrentIndex(1)
        tab = window.tab_widgets[1]
        show(tab, "O", "I", "O I 1302")
        pump(1.0)
        shoot(window, outdir / "regions_q1243.png")
        # Merge the snips…: what changes, before it is made
        project = window.session.project
        snip = tab.current_snip()
        pairs = SN.shared_pixels(project, snip)
        also = SN.same_pairs(project, snip, pairs[0])
        plan = SN.merge_all_plan(project, snip, pairs[0].other(snip), also)
        dialog = D.PlanDialog("Merge the snips", plan.plan, BL.Gate(project), "Merge")
        dialog.resize(1100, 560)
        dialog_shot(window, dialog, outdir / "regions_merge.png")

    # A new project from J1358p6522's spectrum: Lyβ snipped, a region, a knot
    if SOURCE.exists():
        session, _ = S.Session.new(
            str(tmp / "J1358p6522_regions.model"),
            [str(SOURCE)],
            z=Z_J1358,
            prefs=window.prefs,
            folder=window.folder,
        )
        window.set_session(session)
        window.set_panel_open(False)
        window.tabs.setCurrentIndex(1)
        pump(1.0)
        tab = window.tab_widgets[1]
        tab.actions_["regions.snip"].trigger()
        pump(0.5)
        row = tab.strips[0].row_id
        lyb = 1025.7223 * (1.0 + Z_J1358)
        # Lyβ is damped: its edges dragged out to ±1500 km/s, then Auto first guess
        low, high = SN.window(1025.7223, Z_J1358, 0.0, 1500.0)
        tab._act("regions.edges", lambda: tab.move_edges(row, low, high))
        tab.actions_["regions.auto"].trigger()
        tab._act("regions.draw", lambda: tab.draw(row, lyb - 12.0, lyb + 12.0))
        tab.zoom.home()
        pump(0.5)
        strip = tab.strips[0]
        x = lyb + 17.5
        tab._act("regions.knot", lambda: tab.knot_at(strip, x, strip.continuum_at(x)))
        pump(0.5)
        shoot(window, outdir / "regions_new.png")
        tab.actions_["regions.normalised"].trigger()
        pump(0.5)
        shoot(window, outdir / "regions_normalised.png")
        tab.actions_["regions.normalised"].trigger()
        # CLEAR's preview
        project = window.session.project
        plan = SN.clear_plan(project, tab.current_snip())
        dialog = D.PlanDialog("CLEAR", plan, BL.Gate(project), "CLEAR")
        dialog.resize(1000, 420)
        dialog_shot(window, dialog, outdir / "regions_clear.png")
        window.session.discard_recovery()

    # A hidden continuum: drawn, and its coefficients never shown
    session, _ = S.Session.new(
        str(tmp / "OI_SiII.model"),
        [str(ROOT / "examples/metal_line_abs/data/OI_SiII.dat")],
        z=0.0,
        prefs=window.prefs,
        folder=window.folder,
        columns={
            str(ROOT / "examples/metal_line_abs/data/OI_SiII.dat"): {
                "wave": 0,
                "flux": 1,
                "error": 2,
            }
        },
    )
    window.set_session(session)
    window.tabs.setCurrentIndex(1)
    tab = window.tab_widgets[1]
    show(tab, "O", "I", "O I 1302")
    tab._act("regions.draw", lambda: tab.draw(tab.strips[0].row_id, 1301.5, 1302.8))
    line = window.session.project.snips[0].continuum.line
    window.blind_lines([line], ask=False)
    window.set_panel_open(True, 420)
    window.refresh()
    pump(1.0)
    shoot(window, outdir / "regions_hidden.png")
    window.set_panel_open(False)
    window.session.discard_recovery()


def main(outdir, only=None):
    """
    Take every screenshot (``only="regions"``: the Regions tab's).

    Generated by RJC and Claude.
    """
    from alis.dashboard import session as S
    from alis.dashboard.qt import app as APP
    from alis.dashboard.qt import dialogs as D

    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    APP.make_application()
    window = APP.open_window(S.Target(S.START))
    window.resize(1440, 900)
    # Every question gets its last choice (Cancel), but closing a project does not
    # save it
    window.ask = lambda kind, title, text, choices, **kw: (
        "Don't save" if "Don't save" in choices else choices[-1]
    )
    pump(0.5)
    tmp = Path(tempfile.mkdtemp())
    if only == "regions":
        regions_shots(window, outdir, tmp)
        return

    # A new project from J1358p6522's spectrum, Identify a feature open (data_new)
    if SOURCE.exists():
        session, _ = S.Session.new(
            str(tmp / "J1358p6522.model"),
            [str(SOURCE)],
            z=Z_J1358,
            prefs=window.prefs,
            folder=window.folder,
        )
        window.set_session(session)
        window.set_panel_open(False)
        pump(1.0)
        tab = window.tab_widgets[0]
        tab.identify.setChecked(True)
        tab.identify_at(1025.7223 * (1.0 + Z_J1358))
        pump(0.5)
        shoot(window, outdir / "data_new.png")
        tab.identify_panel.hide()
        tab.identify.setChecked(False)
        # The Add file dialog, with the spectrum's columns
        dialog = D.SpectrumDialog("", 7.0, parent=window)
        dialog.set_file(str(SOURCE))
        dialog.resize(700, 420)
        dialog_shot(window, dialog, outdir / "data_add_file.png")
        window.session.discard_recovery()

    # Q1243p307: three datasets (data_datasets)
    if Q1243.exists():
        window.import_path(str(Q1243))
        window.set_panel_open(False)
        pump(1.5)
        shoot(window, outdir / "data_q1243.png")
        tab = window.tab_widgets[0]
        # Remove… shows what it changes first
        from alis.dashboard import blinding as BL
        from alis.dashboard import remove as R

        project = window.session.project
        plan = R.plan_dataset(project, project.row("KIRKMAN"))
        dialog = D.PlanDialog("Remove a dataset", plan, BL.Gate(project), "Remove")
        dialog.resize(1000, 520)
        dialog_shot(window, dialog, outdir / "data_remove.png")
        # A tie of KIRKMAN's FWHM to PROCHASKA's, then Confirm
        tab.badge_menu(project.row("KIRKMAN"), "resolution", "Tie to PROCHASKA")
        pump(0.5)
        window.set_panel_open(True, 460)
        tab._cell_clicked(2, 1)
        pump(1.0)
        shoot(window, outdir / "data_q1243_tied.png")
        window.set_panel_open(False)

    # J1358p6522 imported: its snips, no source; D I blinded as in the mockups
    if J1358.exists():
        window.import_path(str(J1358))
        pump(1.0)
        blind_d_i(window)
        window.set_panel_open(False)
        pump(1.0)
        shoot(window, outdir / "data_j1358_imported.png")

    # examples/blind
    folder = tmp / "blind"
    shutil.copytree(str(BLIND.parent.parent), str(folder))
    window.import_path(str(folder / "model" / BLIND.name))
    window.set_panel_open(False)
    pump(1.0)
    shoot(window, outdir / "data_blind.png")

    regions_shots(window, outdir, tmp)


if __name__ == "__main__":
    main(*sys.argv[1:3])
