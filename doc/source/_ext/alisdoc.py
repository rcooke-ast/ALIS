"""ALIS's own Sphinx extension (Documentation Stage 1).

In Stage 1 it registers the lexers of ``alis_lexers.py``: ``alis`` for model files
and ``alis-message`` for the messages ALIS prints. Documentation Stage 4 adds the
directives that write the reference pages from the code.

Generated by Ryan Cooke and Claude.
"""

from alis_lexers import AlisLexer, AlisMessageLexer


def setup(app):
    """
    Register the extension with Sphinx.

    Parameters
    ----------
    app : sphinx.application.Sphinx
        The application building the site.

    Returns
    -------
    dict
        The extension's metadata: safe to read and write in parallel.

    Generated by Ryan Cooke and Claude.
    """
    app.add_lexer("alis", AlisLexer)
    app.add_lexer("alis-message", AlisMessageLexer)
    return {"version": "1", "parallel_read_safe": True, "parallel_write_safe": True}
