"""Pygments lexers for ALIS's documentation (Documentation Stage 1).

- ``alis``: ALIS model files (``.mod``), in code blocks fenced as ```` ```alis ````.
  It marks comments, the blocks' lines, the settings, the model's functions and
  keywords, and a number with its label (``1.0da``, ``8000TA``). Anything else is
  plain text, so that a block never shows an error token.
- ``alis-message``: plain text, for the messages ALIS prints, which the
  Troubleshooting page quotes (Documentation Stage 3), so that a test can find
  them.

They need Pygments alone, so that ``tests/test_docs.py`` can use them without
Sphinx. ``alisdoc.py`` registers them with Sphinx.

Generated by Ryan Cooke and Claude.
"""

from pygments.lexer import RegexLexer, bygroups
from pygments.lexers.special import TextLexer
from pygments.token import (
    Comment,
    Keyword,
    Name,
    Number,
    Operator,
    Punctuation,
    String,
    Text,
    Whitespace,
)

__all__ = ["AlisLexer", "AlisMessageLexer", "SECTIONS"]

# The sections of ALIS's settings (alis/config.py), the first word of a setting
SECTIONS = ("run", "chisq", "plot", "plotscript", "out", "sim", "generate", "iterate")


class AlisLexer(RegexLexer):
    """
    An ALIS model file: settings, then the data, model and link blocks.

    Generated by Ryan Cooke and Claude.
    """

    name = "ALIS model"
    aliases = ["alis"]
    filenames = ["*.mod"]

    _number = r"[+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?"

    tokens = {
        "root": [
            (r"\s+", Whitespace),
            (r"#-->", Comment.Multiline, "block_comment"),
            (r"#.*?$", Comment.Single),
            # The blocks' first and last lines
            (
                r"(data|model|link)(\s+)(read|end)\b",
                bygroups(Keyword.Namespace, Whitespace, Keyword.Namespace),
            ),
            (r"(emission|absorption|zerolevel)\b", Keyword.Declaration),
            # A setting: its section, then its name
            (
                r"(" + "|".join(SECTIONS) + r")(\s+)(\w+)",
                bygroups(Keyword, Whitespace, Name.Variable),
                "line",
            ),
            # The model's limits: fix and lim, a function and its parameter
            (
                r"(fix|lim)(\s+)(\w+)(\s+)(\w+)",
                bygroups(Keyword, Whitespace, Name.Function, Whitespace, Name.Variable),
                "line",
            ),
            # A model line, or a data line's file: the first word, then the rest
            (r"[A-Za-z_]\w*(?=[ \t])", Name.Function, "line"),
            (r"\S+", Text, "line"),
        ],
        "line": [
            (r"\n", Whitespace, "#pop"),
            (r"[^\S\n]+", Whitespace),
            (r"#-->", Comment.Multiline, "block_comment"),
            (r"#.*?$", Comment.Single),
            (r"([A-Za-z_]\w*)(=)", bygroups(Name.Attribute, Operator)),
            # A label never starts as an exponent would (1.0E-10 is a number)
            (
                r"(" + _number + r")((?![eE][+-]?\d)[A-Za-z]+\b)",
                bygroups(Number, Name.Label),
            ),
            (_number + r"\b", Number),
            (r"[\[\](),]", Punctuation),
            (r"'[^'\n]*'|\"[^\"\n]*\"", String),
            (r"[^\s\[\](),=#]+", Text),
            (r"[=#]", Text),
        ],
        "block_comment": [
            (r"<--#", Comment.Multiline, "#pop"),
            (r"[^<]+", Comment.Multiline),
            (r"<", Comment.Multiline),
        ],
    }


class AlisMessageLexer(TextLexer):
    """
    A message ALIS prints, quoted as plain text.

    Generated by Ryan Cooke and Claude.
    """

    name = "ALIS message"
    aliases = ["alis-message"]
    filenames = []
