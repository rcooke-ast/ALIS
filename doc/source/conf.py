"""Sphinx configuration for ALIS's documentation (Documentation Stage 1).

The site is written in Markdown (MyST) with the furo theme, and built on
readthedocs from ``.readthedocs.yaml``. ``doc/_build/`` holds a local build:

    sphinx-build -W --keep-going -b html doc/source doc/_build/html

The pages are documented in ``claude_prompts/documentation_stage0.md`` ("How the
pages are written") and their addresses in ``tests/test_docs.py`` (``PAGES``).

Generated by Ryan Cooke and Claude.
"""

import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

# The site documents the source tree it is built from, so ALIS is imported from
# the repository, ahead of any installed copy; the extension lives in _ext/.
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE / "_ext"))

import alis  # noqa: E402

# -- Project ------------------------------------------------------------------

project = "ALIS"
author = "Ryan Cooke"
copyright = "2024, Ryan Cooke"  # as in LICENSE
release = alis.__version__
version = ".".join(release.split(".")[:2])

# -- General ------------------------------------------------------------------

extensions = [
    "myst_parser",
    "sphinx.ext.autodoc",
    "sphinx.ext.napoleon",
    "alisdoc",
]
source_suffix = {".md": "markdown"}
exclude_patterns = ["_build", "Thumbs.db", ".DS_Store"]
root_doc = "index"
language = "en"

# MyST: ::: fences, definition lists and $…$ maths; every heading down to ### has
# an anchor, so that a link can reach a section (user/gui/fit.html#results)
myst_enable_extensions = ["colon_fence", "deflist", "dollarmath"]
myst_heading_anchors = 3

# The API pages (Developer guide) read numpydoc docstrings
napoleon_google_docstring = False
napoleon_numpy_docstring = True

# -- HTML ---------------------------------------------------------------------

html_theme = "furo"
html_title = "ALIS"
html_baseurl = os.environ.get("READTHEDOCS_CANONICAL_URL", "")
# A page's Markdown, with its comments for maintainers (its sources), is on GitHub,
# not on the site
html_copy_source = False
html_show_sourcelink = False
