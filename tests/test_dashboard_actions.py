"""The registry of actions (dashboard Stage 3.7, F10), with no Qt.

One list of actions builds the menus, the toolbar and the shortcut sheet: every
action has a menu, a description, and a shortcut no other action has.

Generated by RJC and Claude.
"""

import pytest

from alis.dashboard import actions as A

pytestmark = pytest.mark.unit


def test_every_action_has_a_menu_a_text_and_a_tip():
    names = [a.name for a in A.ACTIONS]
    assert len(names) == len(set(names))
    for action in A.ACTIONS:
        assert action.menu in A.GROUPS, action.name
        group = "panel" if action.menu == A.PANEL else action.menu.lower()
        assert action.name.split(".")[0] == group, action.name
        assert action.text and action.tip, action.name


def test_no_two_actions_share_a_shortcut():
    assert A.duplicate_shortcuts() == {}


def test_the_shortcut_sheet_lists_every_action_with_its_shortcut():
    sheet = A.shortcut_sheet()
    assert len(sheet) == len(A.ACTIONS)
    for action, (menu, text, keys, tip) in zip(
        sorted(A.ACTIONS, key=lambda a: A.GROUPS.index(a.menu)), sheet
    ):
        assert menu == action.menu and keys == action.shortcut and tip == action.tip
        assert text.endswith(action.text.rstrip("…"))


def test_the_menus_of_the_design():
    titles = {menu: [a.text for a in A.in_menu(menu)] for menu in A.MENUS}
    assert titles["File"] == [
        "New project…",
        "Open…",
        "Import a fit (.mod)…",
        "Save",
        "Save as…",
        "Export plain files…",
        "Relink spectra…",
        "Preferences…",
        "Close project",
        "Quit",
    ]
    assert titles["Edit"][:2] == ["Undo", "Redo"]
    assert titles["View"][:5] == list(A.TABS)
    assert [A.get(n).shortcut for n in A.TAB_ACTIONS] == [
        "Ctrl+{0}".format(n) for n in range(1, 6)
    ]
    assert "Blind the analysis…" in titles["Model"]
    assert "Blind lines…" in titles["Model"] and "Unblind…" in titles["Model"]
    assert all(a.later for a in A.in_menu("Fit"))
    assert titles["Help"] == ["Keyboard shortcuts", "About ALIS"]


def test_the_toolbar_of_the_mockups():
    assert [a.name for a in A.ACTIONS if a.toolbar] == [
        "file.open",
        "file.save",
        "file.export",
        "edit.undo",
        "edit.redo",
        "help.shortcuts",
    ]


def test_align_columns_belongs_to_the_mod_panel():
    """RJC's review: column alignment lives on the .mod panel only."""
    assert [a.name for a in A.in_menu(A.PANEL)] == ["panel.align"]
    assert all(a.text != "Align columns" for m in A.MENUS for a in A.in_menu(m))
    assert A.get("panel.align").shortcut == "Ctrl+L"
