"""The regression harness's comparison of 1-sigma errors (dashboard Stage 14, Q14.14).

Q0.16: a parameter whose reference error is zero is fixed, tied, or one the data
cannot determine, so its value is not compared and its error must stay zero.

Q14.14: a parameter the data cannot determine leaves the covariance at its bound
(error 0) or stops short of it with an error that swamps its value, as rounding
decides. ``examples/lsf_spline``'s smoothing does the first under numpy 2.4.3 and
the second under 2.5.5. So a zero error is matched by zero, or by an error at least
as large as the parameter's value, both ways round. A small error, which would mean
the parameter became constrained, still fails, and so does a zero error whose value
is blind.

Generated by RJC and Claude.
"""

import pytest
from compare import BLIND_MARKER, _compare_section

pytestmark = pytest.mark.unit

LOCATIONS = "locations=-10.0,-5.0,-3.0,-1.0,0.0,1.0,3.0,5.0,10.0"


def lsfspline(smoothing, error, knot_error="0.0029522"):
    """
    A convolution section like ``examples/lsf_spline``'s: its smoothing and that
    smoothing's error as given, a fitted knot and two fixed ones.
    """
    values = [
        "lsfspline {0}va 0.0000000LFIX 0.2217266vvb 1.0000000CFIX {1}".format(
            smoothing, LOCATIONS
        )
    ]
    errors = [
        "lsfspline {0}va 0.0000000LFIX {1}vvb 0.0000000CFIX {2}".format(
            error, knot_error, LOCATIONS
        )
    ]
    return values, errors


# The reference's smoothing (numpy 2.4.3) and CI's (numpy 2.5.5)
AT_BOUND = lsfspline("2.9292156E-07", "0.0000000E+00")
SHORT_OF_BOUND = lsfspline("0.0820000", "6127.9272242")


def test_a_zero_error_is_matched_by_zero():
    produced = lsfspline("1.0000000E-07", "0.0000000E+00")
    assert _compare_section("convolution", produced, AT_BOUND) == []


def test_a_zero_error_is_matched_by_one_that_swamps_its_value():
    # CI's examples job before Q14.14: "1-sigma error 6127.9272242 vs 0.0"
    assert _compare_section("convolution", SHORT_OF_BOUND, AT_BOUND) == []


def test_the_rule_holds_both_ways_round():
    # A reference made where rounding stops short of the bound
    assert _compare_section("convolution", AT_BOUND, SHORT_OF_BOUND) == []


@pytest.mark.parametrize(
    "error, passes",
    [("0.0820000", True), ("0.0819999", False), ("0.0010000", False)],
)
def test_an_error_smaller_than_its_value_still_fails(error, passes):
    # The parameter became constrained: the data now determine it
    produced = lsfspline("0.0820000", error)
    fails = _compare_section("convolution", produced, AT_BOUND)
    assert (fails == []) is passes
    if not passes:
        (fail,) = fails
        assert fail.startswith("convolution errors line 1, token 1: 1-sigma error")


@pytest.mark.parametrize(
    "knot_error, passes", [("0.0031000", True), ("0.0036000", False)]
)
def test_a_nonzero_error_keeps_its_tolerance(knot_error, passes):
    # 5% and 22% from the reference's 0.0029522 (ERROR_RTOL is 10%)
    produced = lsfspline("2.9292156E-07", "0.0000000E+00", knot_error)
    fails = _compare_section("convolution", produced, AT_BOUND)
    assert (fails == []) is passes


def test_a_blind_value_keeps_its_zero_error_zero():
    # The blind line's error slot is the second; the visible line's is the third,
    # and its error of 5 swamps its c (1.0)
    values = [
        "absorption",
        BLIND_MARKER,
        "voigt ion=16O_I 13.5000000a 0.0000000b 1.0000000c 0.0000000TA",
    ]
    zero = "voigt ion=16O_I 0.0000000a 0.0000000b 0.0000000c 0.0000000TA"
    reference = (values, ["absorption", zero, zero])
    produced = (
        values,
        [
            "absorption",
            "voigt ion=16O_I 6127.9272242a 0.0000000b 0.0000000c 0.0000000TA",
            "voigt ion=16O_I 0.0000000a 0.0000000b 5.0000000c 0.0000000TA",
        ],
    )
    (fail,) = _compare_section("model", produced, reference)
    assert fail.startswith("model errors line 2, token 2: 1-sigma error 6127.9272242")
