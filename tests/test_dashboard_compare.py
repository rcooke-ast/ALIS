def test_one_log_dh_row_whatever_the_parametrisation(j1358):
    first = RS.View(j1358, record=R.run_of(j1358.bundle, 1))
    second = RS.View.latest(j1358)
    assert second.why_not() == ""
    rows = CM.compare(first, second)
    dh = [r for r in rows if r.name == "log D/H"]
    assert len(dh) == 1
    [row] = dh
    # The first from the two column densities (with their covariance), the second
    # the ratio fitted
    assert row.first.startswith("−4.595 ± ") and row.second == "−4.595 ± 0.011"
    assert row.sigma.endswith("σ")
    # D I is in both: its own lines in the first; through the ratio in the second
    groups = {r.group for r in rows}
    names = [r.name for r in rows]
    assert "log N(D I)" in names and "log N(H I)" in names
    assert "Primary system" in groups


def test_a_blinded_d_i_shows_only_its_change_in_sigma(registry):
    project = make_j1358(registry)
    pm = project.parsed
    line = next(ln for ln in pm.function_lines("voigt") if ln.ion == "2H_I/1H_I")
    project.apply(project.step(E.set_blind(pm, pm.item_at(line.line)), "Blind"))
    first = RS.View(project, record=R.run_of(project.bundle, 1))
    second = RS.View.latest(project)
    rows = {r.name: r for r in CM.compare(first, second)}
    dh = rows["log D/H"]
    assert dh.first == dh.second == dh.delta == BL.MASK
    assert re.fullmatch(r"\d+\.\dσ", dh.sigma) and dh.hidden
    assert "blinded" in dh.note
    # D I's total is derived from the hidden ratio too; H I's is not hidden
    assert rows["log N(D I)"].second == BL.MASK
    assert rows["log N(H I)"].first != BL.MASK


