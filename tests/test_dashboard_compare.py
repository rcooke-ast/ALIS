# -- metal_line_abs: T fixed and T free ----------------------------------------------


def test_t_fixed_and_t_free_matched_component_by_component(metal):
    set_text(metal, t_free(metal.text))
    store_run(
        metal,
        METAL,
        mod_out=t_free_out(METAL_OUT.read_text()),
        covar=False,
        chi2_final=350.0,
        dof=359,
        iterations=9,
    )
    first = RS.View(metal, record=R.run_of(metal.bundle, 1))
    second = RS.View.latest(metal)
    rows = rows_of(first, second)
    group = RS._system_name(metal.systems[0])
    temp = rows[(group, "O I a1 T (K)")]
    assert temp.first == "8,000 (fixed)"
    assert temp.second == "12,000 ± 2,000"
    assert temp.delta == "+4,000" and temp.sigma == "2.0σ"
    # b: the same fit, the same error
    b = rows[(group, "O I a1 b (km/s)")]
    assert b.first == b.second == "5.09 ± 0.37" and b.sigma == "0.0σ"
    count = rows[(group, "O I components")]
    assert (count.first, count.second, count.delta, count.sigma) == ("1", "1", "+0", "")
    # The fit's statistics, with no σ
    stat = rows[(CM.FIT, "χ²ν")]
    assert stat.first == "0.994" and stat.second == "0.975" and stat.sigma == ""
    assert rows[(CM.FIT, "Iterations")].delta == "+2"
    # The first run has a covariance, the second none: its totals' σ are its own
    # errors (one parameter each)
    logn = rows[(group, "log N(O I)")]
    assert logn.first == "13.985 ± 0.016" and logn.sigma == "0.0σ"


