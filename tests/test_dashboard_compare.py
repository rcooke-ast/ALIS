def test_errors_propagated_from_the_covariance(metal):
    view = RS.View(metal, record=R.run_of(metal.bundle, 1))
    found, comps = CM.quantities(view)
    oxygen = next(ln for ln in view.model.parsed.lines if ln.ion == "16O_I")
    index = oxygen.param("ColDens").index
    # One parameter: its error, from the covariance's diagonal
    sigma = np.sqrt(view.covariance[index, index])
    logn = next(q for k, q in found.items() if k[0] == "logN" and k[2] == "16O_I")
    assert logn.sigma == pytest.approx(sigma, rel=1e-4)
    assert logn.value == pytest.approx(13.985197)
    [comp] = [c for c in comps if c.ion == "16O_I"]
    assert comp.quantities["T"].fixed and comp.quantities["T"].sigma == 0.0
    assert comp.quantities["v"].value == pytest.approx(
        P.velocity(-5.174350610684e-07, metal.systems[0].z), abs=1e-6
    )


def test_components_are_matched_by_the_nearest_velocity():
    def comp(ident, v, ion="16O_I"):
        return CM.Component("a", ion, ident, v, "Primary system")

    first = [comp("a1", 0.0), comp("a2", 30.0), comp("a3", 100.0)]
