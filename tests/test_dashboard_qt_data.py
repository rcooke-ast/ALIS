def need(path):
    if not path.exists():
        pytest.skip("{0} is not present".format(path.name))


def new_project(window, tmp_path, z=None, spectra=(SPECTRUM,)):
    session, _ = S.Session.new(
        str(tmp_path / "test.model"), [str(p) for p in spectra], z=z
    )
    window.set_session(session)
    return window.tab_widgets[0]


def table_text(tab):
    table = tab.table
    return [
        [table.item(r, c).text() for c in range(table.columnCount())]
        for r in range(table.rowCount())
    ]


# -- Systems and Identify a feature (S24, D35) ---------------------------------------


def test_identify_a_feature_sets_the_primary_z(window, qtbot, tmp_path):
    tab = new_project(window, tmp_path)
    project = window.session.project
    assert project.systems == []
    tab.identify.click()
    assert tab.identify.isChecked() and tab.view.box.mode == "click"
    # A click on the O I 1302 line of the spectrum
    tab.view.clicked.emit(1302.16849 * (1.0 + 2.0e-5), 0.5)
    panel = tab.identify_panel
    assert panel.isVisible()
    panel.element.setCurrentText("O")
    panel.stage.setCurrentText("I")
    for num in range(panel.transition.count()):
        if panel.transition.itemData(num).name == "O I 1302.2":
            panel.transition.setCurrentIndex(num)
    assert panel.current().z == pytest.approx(2.0e-5, abs=1e-7)
    panel.primary.click()
    project = window.session.project
    assert len(project.systems) == 1 and project.systems[0].primary
    assert project.systems[0].z == pytest.approx(2.0e-5, abs=1e-7)
    assert not tab.identify.isChecked() and not panel.isVisible()
    assert float(tab.z_edit.text()) == pytest.approx(2.0e-5, abs=1e-7)
    # One step, which undo takes back
    window.do_edit_undo()
    assert window.session.project.systems == []


def test_the_primary_z_is_typed_and_a_new_system_added(window, qtbot, tmp_path):
    tab = new_project(window, tmp_path, z=0.0)
    tab.z_edit.setText("0.0001")
    tab.z_edit.returnPressed.emit()
    assert window.session.project.systems[0].z == pytest.approx(1e-4)
    # Identify, then "Add as a new system"
    tab.identify.click()
    tab.identify_at(1304.0)
    tab.identify_panel.new.click()
    systems = window.session.project.systems
    assert len(systems) == 2 and not systems[1].primary
    assert tab.others.count() == 1
    # The rows of the other systems: Rename… and Make primary
    other = systems[1]
    window.on_dialog = lambda dialog: (dialog.set("name", "interloper"), 1)[1]
    tab._act("rename", lambda: tab.rename_system(other))
    assert window.session.project.system(other.id).name == "interloper"
    assert tab.others.item(0).text().startswith("interloper")


