def test_add_file_reference_and_zero_level(window, qtbot, tmp_path):
    tab = new_project(window, tmp_path, z=0.0)
    other = tmp_path / "second.dat"
    shutil.copy(str(SPECTRUM), str(other))

    def add(dialog):
        dialog.set_file(str(other))
        return 1

    window.on_dialog = add
    tab.add_file.click()
    project = window.session.project
    assert [r.name for r in project.rows] == ["OI_SiII", "second"]
    assert tab.table.rowCount() == 2 and tab.coverage.isVisible()
    # SNIP O I in both rows, so the reference and the zero level have lines
    spec = {r.id: sources.spectrum(project, r) for r in project.rows}
    atom = L.atomic(project.registry)
    line = next(
        ln for ln in atom.ion_lines("16O_I") if abs(ln.rest - 1302.16849) < 0.01
    )
    window.session.history.do(SN.snip_step(project, project.systems[0], line, spec))
    window.refresh()
    assert "■" in [tab.grid.item(0, c).text() for c in (1, 2)]
    # The reference moves with a click on the second row's ○
    tab._cell_clicked(1, 0)
    project = window.session.project
    assert project.rows[1].reference and not project.rows[0].reference
    assert table_text(tab)[1][4] == "0 · reference"
    # Zero level on, then off
    tab._cell_clicked(0, 5)
    assert window.session.project.rows[0].zero is not None
    assert table_text(tab)[0][5] == "On"
    tab._cell_clicked(0, 5)
    assert window.session.project.rows[0].zero is None


