    assert window.panel._selected == project.lines_of(second)
    # The cursor on the first row's data line selects that row
    tab.show_items(project.items_at(project.rows[0].snips[0].line))
    assert tab.selected == project.rows[0].id
    assert tab.table.currentRow() == 0


