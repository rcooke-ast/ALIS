def test_no_hidden_value_in_the_tab(window, qtbot, tmp_path):
    # examples/blind, its hidden Si II line given values no other text holds
    folder = tmp_path / "blind"
    shutil.copytree(str(BLIND.parent.parent), str(folder))
    model = folder / "model" / BLIND.name
    text = model.read_text().replace(
        "13.0    0.0    1.0da   8000TA", "13.4729 0.000173 1.37da 8123TA"
    )
    model.write_text(text)
    window.import_path(str(model))
    wait_idle(qtbot, window)
    project = window.session.project
    hidden = BL.Gate(project).hidden_values()
    assert hidden
    texts = ui_strings(window)
    tab = window.tab_widgets[0]
    texts += [t for row in table_text(tab) for t in row]
    texts.append(tab.blinded.text())
    for value in hidden:
        for text in texts:
            assert value not in text, (value, text)
    assert tab.blinded.text() == "Blinded: Si II"


