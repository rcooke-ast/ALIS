def dialog_for(window, qtbot, tmp_path, resolution="vfwhm(6.285VFIX)"):
    """A dialog for the fit's dataset, left open for the test to drive."""
    opened(window, qtbot, tmp_path / "fit", resolution)
    project = window.session.project
    row = project.rows[0]
    dialog = KN.KnotsDialog(project, row, LK.knots_of(project, row), window.ask)
    qtbot.addWidget(dialog)
    dialog.show()
    return dialog


def test_a_knot_moves_within_the_rules(window, qtbot, tmp_path):
    dialog = dialog_for(window, qtbot, tmp_path, NINE)
    step = dialog.step
    # Up stops at 1, down at 0
    assert dialog.move_knot(2, -3.0, 1.7) == (-3.0, 1.0)
    assert dialog.move_knot(2, -3.0, -0.4) == (-3.0, 0.0)
    # Sideways, one sub-pixel from its neighbour
    v, _ = dialog.move_knot(2, -0.5, 0.5)
    assert v == pytest.approx(-1.0 - step)
    # An edge sideways only; the centre not at all
    assert dialog.move_knot(0, -12.0, 0.6) == (-12.0, 0.0)
    assert dialog.move_knot(4, 2.0, 0.3) == (0.0, 1.0)
    # The view's drag moves the knot it starts on
    v0, h0 = dialog.knots.points[6]
    dialog.box.dragged.emit(v0, h0, v0, h0, "start")
    dialog.box.dragged.emit(v0, h0, v0 + 0.5, 0.1, "finish")
    assert dialog.knots.points[6] == pytest.approx((v0 + 0.5, 0.1))


def test_knots_are_added_and_deleted(window, qtbot, tmp_path):
    dialog = dialog_for(window, qtbot, tmp_path)
    step = dialog.step
    at = dialog.add_knot(-4.0, 0.3)
    assert dialog.knots.velocities[at] == -4.0 and len(dialog.knots.velocities) == 4
    # Within one sub-pixel of another: none, and the note says why
    assert dialog.add_knot(-4.0 + 0.5 * step, 0.3) is None
    assert "one sub-pixel" in dialog.note.text()
    assert dialog.delete.isEnabled()
    dialog.delete.click()
    assert len(dialog.knots.velocities) == 3
    # The Delete key removes the selected inner knot too
    from qtpy import QtCore
    from qtpy.QtTest import QTest

    dialog.select(dialog.add_knot(4.0, 0.3))
    QTest.keyClick(dialog, QtCore.Qt.Key.Key_Delete)
    assert len(dialog.knots.velocities) == 3
    # Neither an edge nor the centre can be removed
    for index in (0, 1, 2):
        assert not dialog.delete_knot(index)
    dialog.select(0)
    assert not dialog.delete.isEnabled()


def test_knots_written_too_close_are_marked_until_moved(window, qtbot, tmp_path):
    close = (
        "lsfspline(2.0va,0.0LFIX,0.3vb,0.3vc,1.0CFIX,0.0RFIX;"
        "locations:-10.0,-3.0,-2.99,0.0,10.0)"
    )
    dialog = dialog_for(window, qtbot, tmp_path, close)
    assert not dialog.apply_button.isEnabled()
    assert "closer than one sub-pixel" in dialog.note.text()
    assert dialog._too_close() == {1, 2}
    dialog.move_knot(2, -2.0, 0.3)
    assert dialog.apply_button.isEnabled() and dialog.note.text() == ""


def test_the_fwhm_shown_follows_the_smoothing(window, qtbot, tmp_path):
    dialog = dialog_for(window, qtbot, tmp_path)
    first = dialog.fwhm_shown
    nsub = LK.subpixels(
        dialog.project, dialog.snip, dialog.knots.smoothing, dialog.asked
    )
    v, k = LK.kernel(dialog.knots, dialog.wave, dialog.pixel, nsub)
    assert first == pytest.approx(LK.fwhm(v, k))
    assert dialog.fwhm_text.toPlainText() == "FWHM {0:.2f} km/s".format(first)
    dialog.smoothing.setValue(12.0)
    assert dialog.fwhm_shown > first


def test_delta_function(window, qtbot, tmp_path):
    # Prompt 3 (i): a question first; five knots; the edges follow the FWHM
    dialog = dialog_for(window, qtbot, tmp_path)
    before = dialog.knots.points
    window.answers.answers["delta_function"] = "Cancel"
    dialog.delta.click()
    assert dialog.knots.points == before
    kind, title, text = window.answers.asked[-1]
    assert (kind, title) == ("delta_function", "Delta Function")
    assert text == KN.DELTA_QUESTION
    window.answers.answers["delta_function"] = "Confirm"
    dialog.smoothing.setValue(3.0)
    dialog.delta.click()
    step = dialog.step
    assert dialog.knots.velocities == pytest.approx([-18.0, -step, 0.0, step, 18.0])
    # A Gaussian of the field's FWHM (on nsubmin sub-pixels here, to 1%)
    assert dialog.fwhm_shown == pytest.approx(3.0, rel=0.01)
    dialog.smoothing.setValue(4.0)
    assert dialog.knots.velocities[-1] == pytest.approx(24.0)
    # The +spix knot: up it rises, and the kernel with it; outwards it moves;
    # inwards it stops one sub-pixel from the centre
    width = dialog.fwhm_shown
    assert dialog.move_knot(3, step, 0.4) == pytest.approx((step, 0.4))
    assert dialog.fwhm_shown != pytest.approx(width)
    assert dialog.move_knot(3, 2.0, 0.4)[0] == pytest.approx(2.0)
    assert dialog.move_knot(3, 0.0, 0.4)[0] == pytest.approx(step)
    # Once a knot has moved, the edges stay where they are
    dialog.smoothing.setValue(5.0)
    assert dialog.knots.velocities[-1] == pytest.approx(24.0)
    # The −spix knot is deleted; Apply writes the knots as moved
    assert dialog.delete_knot(1)
    count = len(window.session.history.done)
    window.session.history.do(dialog.step_of())
    assert len(window.session.history.done) == count + 1
    written = LK.knots_of(window.session.project, window.session.project.rows[0])
    assert written.velocities == pytest.approx(dialog.knots.velocities)
    assert written.heights == pytest.approx(dialog.knots.heights)
    assert written.smoothing == 5.0
