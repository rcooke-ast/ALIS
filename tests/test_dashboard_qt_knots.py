NINE = (
    "lsfspline(2.14va,0.0LFIX,0.05vb,0.2vc,0.8vd,1.0CFIX,0.8ve,0.2vf,0.05vg,0.0RFIX;"
    "locations:-10.0,-5.0,-3.0,-1.0,0.0,1.0,3.0,5.0,10.0)"
)


@pytest.fixture
def window(qtbot, tmp_path, monkeypatch):
    home = tmp_path / "home"
    monkeypatch.setenv("ALIS_HOME", str(home))
    win = make_window(qtbot, home)
    yield win
    if win.session is not None:
        win.session.discard_recovery()
        win.session = None


def opened(window, qtbot, folder, resolution="vfwhm(6.285VFIX)"):
    path = write_ratio_fit(folder)
    path.write_text(path.read_text().replace("vfwhm(6.285VFIX)", resolution))
    window.import_path(str(path))
    wait_idle(qtbot, window)
    return window.tab_widgets[0]


def dialog_of(window, answer=0):
    """Open dialogs are kept and answered (0: Cancel, 1: Apply)."""
    seen = []

    def run(dialog):
        seen.append(dialog)
        return answer(dialog) if callable(answer) else answer

    window.on_dialog = run
    return seen


def test_the_data_tab_opens_the_dialog_with_three_knots(window, qtbot, tmp_path):
    # Q12.8 (i): a dataset's resolution; the knots start from RJC's three
    tab = opened(window, qtbot, tmp_path / "fit")
    row = window.session.project.rows[0]
    seen = dialog_of(window)
    text = window.session.project.text
    tab.set_function(row, "lsfspline")
    (dialog,) = seen
    assert isinstance(dialog, KN.KnotsDialog) and dialog.windowTitle() == KN.TITLE
    assert dialog.knots.points == [(-10.0, 0.0), (0.0, 1.0), (10.0, 0.0)]
    assert dialog.smoothing.value() == pytest.approx(6.285)
    # Cancel changes nothing
    assert window.session.project.text == text
    # Apply writes the line as one step, which one undo takes back
    count = len(window.session.history.done)
    seen = dialog_of(window, 1)
    tab.set_function(row, "lsfspline")
    assert len(window.session.history.done) == count + 1
    word = window.session.project.rows[0].snips[0].data.keyword("resolution")
    assert word.startswith("lsfspline(6.285") and "locations:-10.0,0.0,10.0" in word
    # The dataset's menu now offers the dialog
    seen = dialog_of(window)
    tab.badge_menu(window.session.project.rows[0], "resolution", RS.KNOTS_TEXT)
    assert len(seen) == 1 and seen[0].knots.velocities == [-10.0, 0.0, 10.0]
    window.qactions["edit.undo"].trigger()
    assert window.session.project.text == text


