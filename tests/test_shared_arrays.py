"""Shared-memory transport of the derivative payload (Stage 4.5).

``alis.shared_arrays`` replaces the arrays in a nested structure with offsets
into one shared segment, so the ``ncpus`` derivative workers read one copy
instead of unpickling their own. That makes three things worth testing: that
what comes back out is what went in, that it really is a view rather than a
copy (otherwise the whole exercise saves nothing), and that segments do not
outlive the fit that created them.

The final group checks the invariant the Jacobian depends on -- that a chunk
sees exactly the cache entries it would have been sent by the Stage 3.4
slicer -- because that is what makes the shared path bitwise-identical to the
pickled one rather than merely close.

Generated by RJC and Claude.
"""

import multiprocessing
import pickle
from dataclasses import dataclass, field
from multiprocessing import shared_memory
from typing import Any

import numpy as np
import pytest

from alis import minimise, shared_arrays

pytestmark = pytest.mark.unit


def _big(n=2048, seed=0):
    """An array comfortably above ``MIN_BYTES``."""
    return np.arange(n, dtype=np.float64) + seed


@dataclass
class _Holder:
    """Stand-in for FitState: a mutable dataclass of arrays."""

    wave: Any = None
    flux: Any = None
    label: str = "snip"


@dataclass
class _Derived:
    """A dataclass with a field ``__init__`` does not accept."""

    wave: Any = None
    derived: int = field(default=0, init=False)


class _MyList(list):
    """A list subclass, which must come back as itself."""


@pytest.fixture
def publisher():
    """A publisher whose segment is always released, even on failure."""
    pub = shared_arrays.Publisher("test")
    try:
        yield pub
    finally:
        shared_arrays._reset_for_tests()
        pub.close()


def _roundtrip(pub, obj):
    handle = pub.publish(obj)
    assert isinstance(handle, shared_arrays.Handle)
    return handle, shared_arrays.hydrate(handle)


# -- what goes in comes out --------------------------------------------------


def test_arrays_survive_the_round_trip(publisher):
    obj = {"a": _big(), "b": [_big(seed=1), _big(seed=2)]}
    _, out = _roundtrip(publisher, obj)
    assert np.array_equal(out["a"], obj["a"])
    assert np.array_equal(out["b"][1], obj["b"][1])


def test_dtype_and_shape_survive(publisher):
    obj = [
        np.arange(1024, dtype=np.int32),
        np.arange(2048, dtype=np.float64).reshape(64, 32),
        np.arange(600, dtype=np.complex128),
    ]
    _, out = _roundtrip(publisher, obj)
    for before, after in zip(obj, out):
        assert after.dtype == before.dtype
        assert after.shape == before.shape
        assert np.array_equal(after, before)


def test_nesting_and_container_types_are_preserved(publisher):
    obj = ([_big()], {"k": (_big(seed=1),)}, _Holder(wave=_big(seed=2)))
    _, out = _roundtrip(publisher, obj)
    assert isinstance(out, tuple) and isinstance(out[0], list)
    assert isinstance(out[1], dict) and isinstance(out[1]["k"], tuple)
    assert isinstance(out[2], _Holder) and out[2].label == "snip"
    assert np.array_equal(out[2].wave, obj[2].wave)


def test_non_array_values_pass_through_untouched(publisher):
    obj = {"arr": _big(), "n": 7, "s": "text", "none": None, "f": 1.5}
    _, out = _roundtrip(publisher, obj)
    assert (out["n"], out["s"], out["none"], out["f"]) == (7, "text", None, 1.5)


def test_a_dataclass_keeps_fields_its_constructor_would_drop(publisher):
    # _walk shallow-copies and assigns field by field rather than going
    # through dataclasses.replace(), which re-runs __init__ -- a field with
    # init=False would come back at its default instead of its value.
    obj = _Derived(wave=_big())
    obj.derived = 42
    _, out = _roundtrip(publisher, obj)
    assert out.derived == 42
    assert np.array_equal(out.wave, obj.wave)


# -- what is not shared ------------------------------------------------------


def test_small_arrays_stay_in_the_pickle(publisher):
    # A reference plus a rebuilt view costs more than copying a few hundred
    # bytes, so publish() should not even create a segment for them.
    small = np.arange(4, dtype=np.float64)
    assert small.nbytes < shared_arrays.MIN_BYTES
    assert publisher.publish({"s": small}) is None


@pytest.mark.parametrize(
    "array",
    [
        pytest.param(np.arange(4096, dtype=np.float64)[::2], id="strided"),
        pytest.param(np.empty(1024, dtype=object), id="object_dtype"),
        pytest.param(np.zeros(1024, dtype=[("a", "f8"), ("b", "i4")]), id="structured"),
    ],
)
def test_arrays_that_cannot_be_shared_are_left_alone(publisher, array):
    # Each of these would have to be repacked to live in a raw buffer, which
    # is what pickle already does well; publish() must not silently reinterpret
    # them.
    assert not shared_arrays._shareable(array)
    out = publisher.publish({"a": array, "keep": _big()})
    hydrated = shared_arrays.hydrate(out)
    assert hydrated["a"].shape == array.shape
    assert hydrated["a"].dtype == array.dtype


def test_container_subclasses_are_not_rebuilt(publisher):
    obj = {"sub": _MyList([_big()]), "plain": _big(seed=1)}
    _, out = _roundtrip(publisher, obj)
    assert type(out["sub"]) is _MyList
    assert isinstance(out["sub"][0], np.ndarray)


def test_hydrate_passes_non_handles_straight_through():
    obj = {"a": _big()}
    assert shared_arrays.hydrate(obj) is obj
    assert shared_arrays.hydrate(None) is None


# -- it is a view, not a copy ------------------------------------------------


def test_hydrated_arrays_are_views_of_the_segment(publisher):
    # The point of the exercise: if these were copies the workers would each
    # hold their own megabytes again and nothing would have been saved.
    handle, out = _roundtrip(publisher, {"a": _big()})
    shm = shared_arrays._ATTACHED[handle.tag][1]
    assert out["a"].base is not None
    assert out["a"].nbytes <= shm.size


def test_hydrated_arrays_are_read_only(publisher):
    # Not a nicety: a write would land in a buffer every other worker is
    # reading at that moment, so this turns a data race into an exception.
    _, out = _roundtrip(publisher, {"a": _big()})
    with pytest.raises(ValueError):
        out["a"][0] = 1.0


def test_the_handle_is_tiny(publisher):
    # The saving is entirely in what pool.map pickles per chunk.
    payload = {"a": _big(50_000)}
    handle = publisher.publish(payload)
    assert len(pickle.dumps(handle)) < 200
    assert len(pickle.dumps(payload)) > 100_000


# -- generations and segment reuse -------------------------------------------


def test_republishing_reuses_the_segment(publisher):
    first = publisher.publish({"a": _big()})
    second = publisher.publish({"a": _big(seed=9)})
    assert second.name == first.name
    assert second.generation == first.generation + 1


def test_a_new_generation_replaces_the_cached_views(publisher):
    # Two things have to be true of this republish for it to test the
    # generation check at all: the layout must change (the cached views alias
    # the segment, so same-shaped data would read the new bytes through the old
    # views and look right), and it must *fit* in the existing segment -- a
    # segment that has to grow gets a new name, and re-attaching drops the
    # caches for a different reason.
    handle = publisher.publish({"a": _big(4096), "b": _big(4096)})
    before = shared_arrays.hydrate(handle)
    assert sorted(before) == ["a", "b"]
    handle = publisher.publish({"a": _big(1024, seed=5)})
    out = shared_arrays.hydrate(handle)
    assert sorted(out) == ["a"]
    assert out["a"].shape == (1024,)
    assert out["a"][0] == 5.0


def test_hydrating_the_same_generation_twice_returns_the_same_object(publisher):
    # model_func keys its device wave cache on the identity of the sub-pixel
    # grid list, so a worker that rebuilt the state per task would invalidate
    # it every time.
    handle = publisher.publish({"a": _big()})
    assert shared_arrays.hydrate(handle) is shared_arrays.hydrate(handle)


def test_a_grown_payload_gets_a_new_segment_and_the_old_one_is_dropped(publisher):
    first = publisher.publish({"a": _big(1024)})
    shared_arrays.hydrate(first)
    outgrown = shared_arrays._ATTACHED[first.tag][1]
    second = publisher.publish({"a": _big(4_000_000)})
    assert second.name != first.name
    out = shared_arrays.hydrate(second)
    assert np.array_equal(out["a"], _big(4_000_000))
    # One mapping per tag: the outgrown segment must actually be unmapped, not
    # merely dropped from the dict, or every worker keeps it for the whole fit.
    assert list(shared_arrays._ATTACHED) == [second.tag]
    assert shared_arrays._ATTACHED[second.tag][0] == second.name
    assert outgrown.buf is None


# -- selecting a subset ------------------------------------------------------


def test_select_returns_only_the_named_entries(publisher):
    cache = {("a", i): _big(seed=i) for i in range(4)}
    handle = publisher.publish(cache)
    out = shared_arrays.hydrate(shared_arrays.select(handle, [("a", 1), ("a", 3)]))
    assert sorted(out) == [("a", 1), ("a", 3)]
    assert np.array_equal(out[("a", 1)], cache[("a", 1)])


def test_select_with_no_keys_means_everything(publisher):
    cache = {("a", i): _big(seed=i) for i in range(3)}
    handle = publisher.publish(cache)
    assert shared_arrays.select(handle, None) is handle
    assert sorted(shared_arrays.hydrate(handle)) == sorted(cache)


def test_select_on_a_missing_handle_is_a_no_op():
    assert shared_arrays.select(None, ["a"]) is None


def test_selecting_a_key_that_was_not_published_raises(publisher):
    # Skipping it would only cost a cache hit -- the derivative recomputes the
    # component to the same value -- so the mistake would never surface on its
    # own. The keys always come from the dict that was published.
    handle = publisher.publish({("a", 0): _big()})
    with pytest.raises(KeyError):
        shared_arrays.hydrate(shared_arrays.select(handle, [("a", 1)]))


# -- lifecycle ---------------------------------------------------------------


def _exists(name):
    """Is a segment of this name still there?

    Asked by attaching rather than by looking in /dev/shm, which only exists on
    Linux -- the unit batch also runs on macOS.
    """
    try:
        shared_memory.SharedMemory(name=name, create=False, track=False).close()
        return True
    except FileNotFoundError:
        return False


def test_close_unlinks_the_segment_and_is_idempotent():
    pub = shared_arrays.Publisher("lifecycle")
    handle = pub.publish({"a": _big()})
    assert _exists(handle.name)
    pub.close()
    assert not _exists(handle.name)
    pub.close()  # must not raise


def test_a_collected_publisher_releases_its_segment():
    pub = shared_arrays.Publisher("collected")
    name = pub.publish({"a": _big()}).name
    del pub
    assert not _exists(name)


def test_publish_falls_back_when_no_segment_can_be_created(publisher, monkeypatch):
    # A container's /dev/shm defaults to 64 MB, so this is the realistic
    # failure. The fit has to carry on with the payload in the pickle.
    def refuse(*args, **kwargs):
        raise OSError(28, "No space left on device")

    monkeypatch.setattr(shared_arrays.shared_memory, "SharedMemory", refuse)
    assert publisher.publish({"a": _big()}) is None


# -- across a process boundary -----------------------------------------------


def _child_sum(handle):
    """Attach in a fresh process and report what the views contain."""
    out = shared_arrays.hydrate(handle)
    return float(out["a"].sum()), bool(out["a"].flags.writeable)


def test_a_separate_process_reads_the_same_arrays(publisher):
    payload = {"a": _big(10_000)}
    handle = publisher.publish(payload)
    with multiprocessing.get_context("spawn").Pool(1) as pool:
        total, writeable = pool.apply(_child_sum, (handle,))
    assert total == pytest.approx(payload["a"].sum())
    assert writeable is False


# -- the invariant the Jacobian rests on -------------------------------------


def _chunk(js):
    return [(j, j, 1e-8, True) for j in js]


def test_selected_keys_are_the_entries_the_chunk_can_reach():
    # The shared path sends key names where the fallback sends a dict, so both
    # are only as right as this selection. Checked against the rule itself --
    # an entry belongs to the chunk exactly when one of the chunk's parameters
    # influences the sp/sn it was cached for -- rather than against the other
    # path, which now shares this code and would agree with any mistake.
    cache = {(sp, sn, 0, 0, 0): _big(seed=sp) for sp in range(3) for sn in range(2)}
    cache[("wave", 1, 0)] = _big(seed=9)
    param_spsn = {0: {(0, 0), (1, 0)}, 1: {(2, 1)}}
    for chunk in (_chunk([0]), _chunk([1]), _chunk([0, 1]), _chunk([7])):
        reach = set()
        for j, _, _, _ in chunk:
            reach |= param_spsn.get(j, set())
        expected = [k for k in cache if minimise._cache_key_spsn(k) in reach]
        keys = minimise._chunk_cache_keys(cache, param_spsn, chunk)
        assert list(keys) == expected
        # Order matters too: both paths build the dict by iterating the cache.
        assert list(minimise._slice_emab(cache, param_spsn, chunk)[2]) == expected


def test_without_an_influence_table_every_key_is_sent():
    cache = {("wave", 0, 0): _big()}
    assert minimise._chunk_cache_keys(cache, None, _chunk([0])) is None
    assert minimise._slice_emab(cache, None, _chunk([0]))[2] is cache


def test_no_cache_selects_nothing():
    assert minimise._chunk_cache_keys(None, {0: {(0, 0)}}, _chunk([0])) is None
    assert minimise._slice_emab(None, {0: {(0, 0)}}, _chunk([0])) == [None, None, None]


def test_worker_chunk_accepts_handles_and_bare_objects(monkeypatch):
    # _worker_chunk has to cope with both, because publishing is best-effort:
    # a payload that could not be shared arrives as itself.
    seen = []

    def fake_funcderiv(state, fvec, j, xp, ifree, hj, emab, oneside):
        seen.append((state[0], emab[2]))
        return [j, np.zeros(2)]

    monkeypatch.setattr(minimise, "_worker_funcderiv", fake_funcderiv)
    functkw = {"state": _big()}
    cache = {("wave", 0, 0): _big(seed=1)}
    args = (
        functkw,
        (False, [], 0.0),
        np.zeros(2),
        np.zeros(1),
        [None, None, cache],
        _chunk([0]),
    )
    minimise._worker_chunk(args)
    assert seen[-1][0] is functkw and seen[-1][1] is cache

    state_pub = shared_arrays.Publisher("worker-state")
    cache_pub = shared_arrays.Publisher("worker-cache")
    try:
        handle = state_pub.publish(functkw)
        selected = shared_arrays.select(cache_pub.publish(cache), [("wave", 0, 0)])
        minimise._worker_chunk(
            (
                handle,
                (False, [], 0.0),
                np.zeros(2),
                np.zeros(1),
                [None, None, selected],
                _chunk([0]),
            )
        )
        assert np.array_equal(seen[-1][0]["state"], functkw["state"])
        assert np.array_equal(seen[-1][1][("wave", 0, 0)], cache[("wave", 0, 0)])
    finally:
        shared_arrays._reset_for_tests()
        state_pub.close()
        cache_pub.close()


def test_a_stale_handle_is_refused_rather_than_misread(publisher):
    # Two payloads must not share a publisher: the second overwrites the
    # first, and without the generation check in the header the first handle
    # would hydrate into the second's contents.
    stale = publisher.publish({"a": _big()})
    publisher.publish({"b": _big(seed=1)})
    with pytest.raises(RuntimeError, match="republished"):
        shared_arrays.hydrate(stale)
