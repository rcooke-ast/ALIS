"""The results of a fit run by the dashboard (dashboard Stage 6.3; S18, S19; Q6.12).

metal_line_abs, made to stop on a bound (``lim voigt bturb [6.0,None]``, its best
fit 5.09 km/s), is fitted through the dashboard's fitting process:

- its b_turb is flagged "at limit", as the minimiser leaves it on the bound;
- the best fit drawn is the model of the run's own ``_fit.dat``;
- the marks equal the run's own ``.report``;
- Continue from best fit then writes the bound, and the model reads.

Generated by RJC and Claude.
"""

import io
import re
from pathlib import Path

import numpy as np
import pytest

from alis import bundle as B
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import results as RS
from alis.dashboard import runs as R
from alis.dashboard import session as S

pytestmark = [pytest.mark.fast, pytest.mark.examples]

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
SETTINGS = ["out verbose 1", "plot fits False", "run ncpus 1"]


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture
def home(tmp_path, monkeypatch):
    folder = tmp_path / "alis_home"
    monkeypatch.setenv(PR.HOME_ENV, str(folder))
    return str(folder)


def test_a_fit_that_stops_on_a_bound(home, tmp_path, registry):
    model = tmp_path / "model" / "fit_spectra.mod"
    model.parent.mkdir()
    (tmp_path / "data").mkdir()
    (tmp_path / "data" / "OI_SiII.dat").write_bytes(
        (METAL.parent.parent / "data" / "OI_SiII.dat").read_bytes()
    )
    text = METAL.read_text().replace(
        "model read\n", "model read\n  lim voigt bturb [6.0,None]\n"
    )
    text = text.replace("1.0da", "8.0da")
    model.write_text(text)
    path = tmp_path / "project.model"
    B.pack_to(str(model), str(path))
    session = S.Session.open(str(path), registry=registry)
    job = R.Run(session, settings=SETTINGS, cwd=str(tmp_path))
    job.start()
    assert job.wait(timeout=600) == R.COMPLETED, job.message
    assert job.take(session)
    project = session.project
    view = RS.View.latest(project)
    assert view.why_not() == ""
    rows = {r.name: r for g in view.table() for r in g.rows}
    assert rows["O I a1 b"].value == "6.00"
    assert rows["O I a1 b"].flags == ["at limit (6)"]
    assert not any(
        "at limit" in f
        for r in rows.values()
        if r is not rows["O I a1 b"]
        for f in r.flags
    )
    # The best fit drawn is the model of the run's own _fit.dat
    record = view.record
    fit = np.loadtxt(io.StringIO(record.text(record.output("_fit.dat"))))
    curve = view.curves()[project.snips[0].data.index]
    window = fit[:, -1] > -1.0e9
    mine = np.isin(curve.wave, fit[window, 0])
    diff = np.abs(curve.model[mine] - fit[window, -1]) / curve.error[mine]
    assert np.nanmax(diff) < 0.01
    # The marks equal its own .report
    report = record.text(record.output(".report"))
    row = next(ln for ln in report.splitlines() if re.match(r"  \S", ln)).split()
    mark = view.marks()[project.snips[0].data.index]
    assert mark.reduced == pytest.approx(float(row[6]), abs=2.0e-3)
    assert mark.runs_z == pytest.approx(float(row[11]), abs=0.02)
    # Continue from best fit writes the bound, and the model reads
    plan = RS.continue_plan(project, view)
    session.history.do(plan.step)
    oxygen = next(ln for ln in project.parsed.lines if ln.ion == "16O_I")
    assert project.parsed.ok and oxygen.param("bturb").start == 6.0
