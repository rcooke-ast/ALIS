"""Batched CPU/GPU dispatch and backend selection (Stage 4.3).

Two groups of tests:

* the hardware-independent ones (``unit`` only) cover the parts that decide
  *what runs where* -- backend resolution, the size threshold, the dispatcher
  lifecycle, device-buffer invalidation, and the row reduction / continuum
  split that :meth:`Dispatcher.batch` has to reproduce from the CPU loop;

* the ``gpu``-marked ones run a real kernel and check the batched device path
  against the per-row CPU loop it replaces, to the 1e-12 of Q4.3, plus the
  multi-GPU worker pool.

Generated by RJC and Claude.
"""

