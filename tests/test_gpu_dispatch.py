def _cpu_reduction(voigt, wave, params, mkey, ae, rows=None):
    """The per-row CPU loop of ``model_func``, for the given rows."""
    idx = range(params.shape[0]) if rows is None else rows
    acc = None
    for mm in idx:
        out = voigt.call_CPU(wave, params[mm, :].reshape(1, -1), ae=ae, mkey=[mkey[mm]])
        if acc is None:
            acc = out.copy()
        elif ae == "em":
            acc += out
        else:
            acc *= out
    return acc


