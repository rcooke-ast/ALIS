@pytest.mark.gpu
@pytest.mark.parametrize("ae", ["ab", "em"])
def test_batched_launch_matches_the_per_row_cpu_loop(device_wave, ae):
    wave, wave_dev = device_wave
    voigt = base.call(getinst=True)["voigt"]
    disp = gpu_dispatch.enable(threshold=0)
    params, mkey = _rows(12), _keys(12)

    combined, cont = disp.batch(type(voigt), voigt, wave_dev, params, mkey, ae)

    assert cont is None
    assert disp.nlaunch == 1  # one launch for twelve profiles
    ref = _cpu_reduction(voigt, wave, params, mkey, ae)
    assert np.max(np.abs(combined - ref)) < GPU_ATOL


@pytest.mark.gpu
def test_the_continuum_split_matches_the_cpu_loop(device_wave):
    wave, wave_dev = device_wave
    voigt = base.call(getinst=True)["voigt"]
    disp = gpu_dispatch.enable(threshold=0)
    cont_rows = [0, 2, 5]
    params, mkey = _rows(6), _keys(6, cont_rows)

    combined, cont = disp.batch(type(voigt), voigt, wave_dev, params, mkey, "ab")

    assert disp.nlaunch == 2
    ref = _cpu_reduction(voigt, wave, params, mkey, "ab")
    ref_cont = _cpu_reduction(voigt, wave, params, mkey, "ab", rows=cont_rows)
    assert np.max(np.abs(combined - ref)) < GPU_ATOL
    assert np.max(np.abs(cont - ref_cont)) < GPU_ATOL


@pytest.mark.gpu
def test_the_device_wave_buffer_is_reused_across_evaluations():
    wave = np.linspace(4250.0, 4260.0, 1024)
    disp = gpu_dispatch.enable(threshold=0)
    grid = [wave]
    disp.note_grid(grid)
    first = disp.wave_device((0, 0, "vshift", b"key"), wave)
    again = disp.wave_device((0, 0, "vshift", b"key"), wave)

    assert again is first
    assert disp.nwave_upload == 1 and disp.nwave_reuse == 1
    np.testing.assert_array_equal(first.copy_to_host(), wave)


def _worker_device(_):
    """Report which device this GPU worker bound (and hold it briefly)."""
    from alis import gpu as _gpu

    time.sleep(0.25)
    return _gpu.current_device()


@pytest.mark.gpu
def test_the_gpu_pool_binds_one_device_per_worker():
    # The multi-GPU claim of Task 4.3: the Pool is sized to ngpus, started with
    # 'spawn' (a CUDA context does not survive fork, Q4.8) and each worker takes
    # a distinct device, so the Jacobian's columns spread over the GPUs.
    from alis import minimise

    ndev = gpu.device_count()
    pool = minimise._make_gpu_pool(ndev, 0, 0)
    try:
        seen = pool.map(_worker_device, range(4 * ndev), chunksize=1)
    finally:
        pool.close()
        pool.join()
    assert set(seen) == set(range(ndev))
