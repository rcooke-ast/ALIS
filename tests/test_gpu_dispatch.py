def _worker_device(_):
    """Report which device this GPU worker bound (and hold it briefly)."""
    from alis import gpu as _gpu

    time.sleep(0.25)
    return _gpu.current_device()


@pytest.mark.gpu
def test_the_gpu_pool_binds_one_device_per_worker():
    # The multi-GPU claim of Task 4.3: the Pool is sized to ngpus, started with
    # 'spawn' (a CUDA context does not survive fork, Q4.8) and each worker takes
    # a distinct device, so the Jacobian's columns spread over the GPUs.
    from alis import minimise

    ndev = gpu.device_count()
    pool = minimise._make_gpu_pool(ndev, 0, 0)
    try:
        seen = pool.map(_worker_device, range(4 * ndev), chunksize=1)
    finally:
        pool.close()
        pool.join()
    assert set(seen) == set(range(ndev))


