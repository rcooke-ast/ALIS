# -- the reduction and the continuum split -----------------------------------


def _numpy_launch(disp, monkeypatch):
    """Replace the kernel launch with the numpy reduction it must reproduce."""
    launched = []

    def fake(disp_self, cls, inst, wave_dev, params, ae, mkey):
        launched.append((np.array(params), list(mkey)))
        disp_self.nlaunch += 1
        rows = np.array([np.full(4, 1.0 + p[0]) for p in params])
        return rows.sum(axis=0) if ae == "em" else rows.prod(axis=0)

    monkeypatch.setattr(gpu_dispatch.Dispatcher, "_launch", fake)
    return launched


def test_batch_reduces_every_row_in_the_group(monkeypatch):
    disp = gpu_dispatch.enable(threshold=0)
    launched = _numpy_launch(disp, monkeypatch)
    params = _rows(3)
    combined, cont = disp.batch(None, None, None, params, _keys(3), "ab")
    assert cont is None
    assert len(launched) == 1
    np.testing.assert_allclose(combined, np.prod(1.0 + params[:, 0]))


def test_batch_sums_for_emission_and_multiplies_for_absorption(monkeypatch):
    disp = gpu_dispatch.enable(threshold=0)
    _numpy_launch(disp, monkeypatch)
    params = _rows(3)
    em, _ = disp.batch(None, None, None, params, _keys(3), "em")
    ab, _ = disp.batch(None, None, None, params, _keys(3), "ab")
    np.testing.assert_allclose(em, np.sum(1.0 + params[:, 0]))
    np.testing.assert_allclose(ab, np.prod(1.0 + params[:, 0]))


def test_batch_splits_out_the_continuum_rows(monkeypatch):
    # The CPU loop decides per row whether to accumulate into mcont, so a mixed
    # group needs a second launch over just those rows.
    disp = gpu_dispatch.enable(threshold=0)
    launched = _numpy_launch(disp, monkeypatch)
    params = _rows(4)
    combined, cont = disp.batch(None, None, None, params, _keys(4, [1, 3]), "ab")
    assert len(launched) == 2
    np.testing.assert_array_equal(launched[1][0], params[[1, 3], :])
    np.testing.assert_allclose(combined, np.prod(1.0 + params[:, 0]))
    np.testing.assert_allclose(cont, np.prod(1.0 + params[[1, 3], 0]))


def test_an_all_continuum_group_needs_only_one_launch(monkeypatch):
    disp = gpu_dispatch.enable(threshold=0)
    launched = _numpy_launch(disp, monkeypatch)
    params = _rows(3)
    combined, cont = disp.batch(None, None, None, params, _keys(3, [0, 1, 2]), "ab")
    assert len(launched) == 1
    assert cont is combined


