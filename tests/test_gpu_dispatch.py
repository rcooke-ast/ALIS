class _FakeBuffer:
    def __init__(self, values):
        self.values = values


def _fake_upload(disp, monkeypatch):
    """Make ``wave_device`` cache without needing a GPU."""

    def to_device(disp_self, key, wave):
        buf = disp_self._wave_cache.get(key)
        if buf is not None:
            disp_self.nwave_reuse += 1
            return buf
        buf = _FakeBuffer(np.array(wave))
        disp_self._wave_cache[key] = buf
        disp_self.nwave_upload += 1
        return buf

    monkeypatch.setattr(gpu_dispatch.Dispatcher, "wave_device", to_device)


