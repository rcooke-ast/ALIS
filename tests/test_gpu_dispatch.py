class _CountingCuda:
    """A ``numba.cuda`` stand-in that records what was uploaded."""

    def __init__(self, ndevices=1):
        self.uploads = 0
        self._ndevices = ndevices

    def to_device(self, array):
        self.uploads += 1
        return array

    def is_available(self):
        return self._ndevices > 0

    def list_devices(self):
        return list(range(self._ndevices))

    def current_context(self):
        # A context that names a device, so current_device() is only correct
        # because of its device_count() guard -- not because asking happens to
        # raise. Without this, removing the guard is unobservable.
        return types.SimpleNamespace(device=types.SimpleNamespace(id=0))


class _FakeNumbaModule:
    def __init__(self, cuda):
        self.cuda = cuda


def test_the_device_wave_cache_is_bounded(monkeypatch):
    # Every distinct (snip, shift-parameter) combination holds a device
    # allocation for as long as it is cached. A fit with a free shift
    # parameter produces a new key on every derivative evaluation, so without
    # the bound this grows until the device runs out of memory -- a failure
    # that would appear as an opaque CUDA error hours into a long fit.
    fake = _CountingCuda()
    monkeypatch.setitem(sys.modules, "numba", _FakeNumbaModule(fake))
    disp = gpu_dispatch.enable(threshold=0)
    wave = np.linspace(1215.0, 1216.0, 8)
    for i in range(gpu_dispatch._WAVE_CACHE_MAX + 1):
        disp.wave_device((0, 0, "Ashift", i), wave)
    assert len(disp._wave_cache) <= gpu_dispatch._WAVE_CACHE_MAX
    assert fake.uploads == gpu_dispatch._WAVE_CACHE_MAX + 1


def test_an_unchanged_grid_is_not_re_uploaded(monkeypatch):
    fake = _CountingCuda()
    monkeypatch.setitem(sys.modules, "numba", _FakeNumbaModule(fake))
