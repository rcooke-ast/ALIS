GPU_ATOL = 1e-12

# Damped Lyman-alpha (rest wavelength, oscillator strength, Gamma).
LYA = (1215.6701, 0.4164, 6.265e8)

KW = {"freq": False, "logN": True, "ColDensScale": 1.0, "continuum": False}


def _rows(n, seed=3):
    """``n`` Voigt parameter rows: logN, z, b, restwave, f, Gamma."""
    rng = np.random.default_rng(seed)
    return np.array(
        [
            [
                13.0 + 1.5 * rng.random(),
                2.5 + 1.0e-4 * rng.random(),
                8.0 + 6.0 * rng.random(),
                LYA[0],
                LYA[1],
                LYA[2],
            ]
            for _ in range(n)
        ]
    )


def _keys(n, continuum=None):
    """``n`` keyword dicts, with ``continuum`` set on the listed rows."""
    cont = set() if continuum is None else set(continuum)
    return [dict(KW, continuum=(i in cont)) for i in range(n)]


