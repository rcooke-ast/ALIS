class _FakeBuffer:
    def __init__(self, values):
        self.values = values


def _fake_upload(disp, monkeypatch):
    """Make ``wave_device`` cache without needing a GPU."""

    def to_device(disp_self, key, wave):
        buf = disp_self._wave_cache.get(key)
        if buf is not None:
            disp_self.nwave_reuse += 1
            return buf
        buf = _FakeBuffer(np.array(wave))
        disp_self._wave_cache[key] = buf
        disp_self.nwave_upload += 1
        return buf

    monkeypatch.setattr(gpu_dispatch.Dispatcher, "wave_device", to_device)


def test_an_unchanged_grid_is_uploaded_once(monkeypatch):
    disp = gpu_dispatch.enable(threshold=0)
    _fake_upload(disp, monkeypatch)
    wave = np.linspace(1200.0, 1300.0, 64)
    grid = [wave]
    for _ in range(5):
        disp.note_grid(grid)
        disp.wave_device((0, 0, "vshift", b"\x00"), wave)
    assert disp.nwave_upload == 1
    assert disp.nwave_reuse == 4


def test_a_rebuilt_grid_invalidates_the_device_buffers(monkeypatch):
    # 'run renew_subpix' rebuilds the sub-pixel grid, so load_subpixels returns
    # a fresh list; a changed identity is exactly the staleness signal.
    disp = gpu_dispatch.enable(threshold=0)
    _fake_upload(disp, monkeypatch)
    wave = np.linspace(1200.0, 1300.0, 64)
    for _ in range(3):
        disp.note_grid([wave])  # a new list each time, as renew_subpix does
        disp.wave_device((0, 0, "vshift", b"\x00"), wave)
    assert disp.nwave_upload == 3
    assert disp.nwave_reuse == 0


