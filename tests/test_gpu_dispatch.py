class _Recorder:
    """Collects what ``alis.gpu`` reports, without going through logging."""

    def __init__(self):
        self.said = []

    def info(self, text, verbose=None):
        self.said.append(text)

    def warn(self, text, verbose=None):
        self.said.append(text)


def test_the_idle_gpu_notice_is_printed_once(monkeypatch):
    # Q4.10 asks for a notice when GPUs are present but unused; alfit resolves
    # the backend once per fit and one ALIS run may build several, so it must
    # not repeat.
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(ndevices=3))
    rec = _Recorder()
    monkeypatch.setattr(gpu, "msgs", rec)
    gpu.resolve_backend(None)
    gpu.resolve_backend(None)
    hits = [t for t in rec.said if "not in use" in t]
    assert len(hits) == 1
    assert "3 CUDA GPU(s)" in hits[0]


def test_an_unusable_gpu_is_reported_not_silently_ignored(monkeypatch):
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(ndevices=0))
    rec = _Recorder()
    monkeypatch.setattr(gpu, "msgs", rec)
    gpu.resolve_backend(2)
    assert any("no GPU is usable" in t for t in rec.said)
    assert any("Falling back to the CPU" in t for t in rec.said)


