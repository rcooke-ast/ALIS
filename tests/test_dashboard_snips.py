def test_a_bad_pixel_is_never_fitted(registry, tmp_path):
    table = np.loadtxt(str(SPECTRUM))
    bad = np.zeros(table.shape[0])
    wave = table[:, 0]
    bad[(wave > 1302.0) & (wave < 1302.2)] = 1.0
    path = tmp_path / "masked.dat"
    np.savetxt(str(path), np.column_stack([table[:, :3], bad]))
    project, _ = modes.get().empty_project(
        [str(path)],
        "test",
        z=0.0,
        columns={str(path): {"wave": 0, "flux": 1, "error": 2, "mask": 3}},
        registry=registry,
    )
    hist = H.History(project)
    hist.do(snip_one(project, registry, *OI))
    snip = project.snip("OI_1302")
    assert snip.data.keyword("columns") == S.COLUMNS_BAD
    assert snip.pixels.bad is not None and snip.pixels.bad.sum() > 0
    hist.do(S.add_region_step(project, snip, 1301.5, 1302.8))
    snip = project.snip("OI_1302")
    # The dashboard leaves the bad pixels out of the fit mask ...
    assert not np.any(S.fitted(snip) & snip.pixels.bad)
    assert not np.any((snip.pixels.mask != 0) & snip.pixels.bad)
    assert errors(project) == []
    # ... and so does ALIS, even if the mask column said otherwise
    from types import SimpleNamespace

    from alis import load
    from alis.config import ArgFlag

    forced = snip.pixels.mask.copy()
    forced[snip.pixels.bad] = 1.0
    content = P.set_mask(project.files[snip.member], snip.data, forced != 0)
    data = project.data_for_run()
    data = {
        k: (content if k.endswith(Path(snip.member).name) else v)
        for k, v in data.items()
    }
    st = SimpleNamespace(_argflag=ArgFlag())
    st._argflag["out"]["verbose"] = -1
    with M.alis_quietly():
        _, datlines, _, _ = load.load_input(st, textstr=project.text.splitlines(True))
        st._atomic = registry.atomic
        st._funcarray = registry.instances()
        load.load_data(st, datlines, data=data)
    assert not np.any(np.isin(st._wavefit[0], snip.pixels.wave[snip.pixels.bad]))


def test_pixels_that_cannot_be_fitted_never_are(project, registry):
    hist = H.History(project)
    hist.do(snip_one(project, registry, *OI))
    snip = project.snip("OI_1302")
