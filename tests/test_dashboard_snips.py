def test_regions_are_the_same_in_every_dataset(registry, tmp_path):
    """Q4.19: a region added, moved or removed in one dataset is the same in every
    dataset of the transition; pixels excluded in one dataset stay excluded."""
    other = tmp_path / "second.dat"
    other.write_bytes(SPECTRUM.read_bytes())
    project = new_project(registry, tmp_path, [SPECTRUM, other])
    hist = H.History(project)
    hist.do(snip_one(project, registry, *OI))
    before = state(project)
    first = project.snip("OI_1302_r1")
    assert [s.specid for s in S.linked_snips(project, first)] == [
        "OI_1302_r1",
        "OI_1302_r2",
    ]
    name = S.linked_name(project, first, "Add a fit region to")
    assert name == "Add a fit region to O I 1302.2 in 2 datasets"
    hist.do(S.linked_step(project, first, [("add", 1301.5, 1302.8)], name))
    regions = [S.regions_of(project.snip(s)) for s in ("OI_1302_r1", "OI_1302_r2")]
    assert regions[0] == regions[1] and len(regions[0]) == 1
    assert S.origin(project, project.snip("OI_1302_r2")) == "copied from OI_SiII"
    # A pixel excluded in the second dataset alone
    hist.do(S.mask_step(project, project.snip("OI_1302_r2"), 1302.0, 1302.0))
    excluded = ~S.fitted(project.snip("OI_1302_r2"))
    # The region's red edge moved in the first: the excluded pixel stays out
    hist.do(
        S.linked_step(
            project,
            project.snip("OI_1302_r1"),
            [("remove", 1302.6, 1302.8)],
            "Move a fit region",
        )
    )
    second = project.snip("OI_1302_r2")
    assert S.regions_of(project.snip("OI_1302_r1"))[0][1] < 1302.6
    assert not (S.fitted(second) & excluded & (second.pixels.wave < 1302.5)).any()
    assert len(S.regions_of(second)) == 2
    # A region dropped in the first: every region it overlaps goes, in both (the
    # second's, split by its excluded pixel, too)
    a, b = S.regions_of(project.snip("OI_1302_r1"))[0]
    hist.do(
        S.linked_step(project, project.snip("OI_1302_r1"), [("drop", a, b)], "Remove")
    )
    assert not S.fitted(project.snip("OI_1302_r1")).any()
    assert not S.fitted(project.snip("OI_1302_r2")).any()
    for _ in range(4):
        hist.undo()
    assert state(project) == before


