    assert S.regions_of(project.snip("OI_1302"))[1][1] == pytest.approx(
        1303.0, abs=0.02
    )
    hist.do(S.remove_region_step(project, project.snip("OI_1302"), 0))
    assert len(S.regions_of(project.snip("OI_1302"))) == 1
    assert errors(project) == []


