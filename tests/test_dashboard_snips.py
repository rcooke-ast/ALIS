# -- Edges (S6, Q2.7, Q4.9(a)) ------------------------------------------------------------


def _pixel_lines(content):
    return [ln for ln in content.decode().splitlines(True) if ln.strip()]


def test_edges_move_in_keeping_lines_and_out_from_the_source(project, registry):
    hist = H.History(project)
    hist.do(snip_one(project, registry, *OI))
    hist.do(S.add_region_step(project, project.snip("OI_1302"), 1301.5, 1302.8))
    snip = project.snip("OI_1302")
    old = _pixel_lines(project.files[snip.member])
    curve_before = CO.evaluate(project, snip)
    low, high = snip.extent
    # Inwards: the lines that stay are unchanged
    hist.do(S.edges_step(project, snip, low + 0.2, high - 0.2))
    inner = _pixel_lines(project.files[project.snip("OI_1302").member])
    assert set(inner) <= set(old) and len(inner) < len(old)
    hist.undo()
    # Outwards: refused without the source, and from it keeps every old line
    with pytest.raises(S.SnipError, match="source spectrum"):
        S.edges_step(project, snip, low - 0.5, high)
    spec = spectra(project)["r1"]
    hist.do(S.edges_step(project, snip, low - 0.5, high + 0.5, spec))
    grown = project.snip("OI_1302")
    lines = _pixel_lines(project.files[grown.member])
    assert (
        lines[len(lines) - len(old) - _red(spec, high, high + 0.5) :][: len(old)] == old
    )
    assert grown.extent[0] == pytest.approx(low - 0.5, abs=0.02)
    # The new pixels are the source's, at full precision, and not fitted
    sel = (spec.wave >= low - 0.5) & (spec.wave <= high + 0.5)
    assert np.array_equal(grown.pixels.wave, spec.wave[sel])
    assert np.array_equal(S.fitted(grown), S.fitted(grown) & (grown.pixels.wave > low))
    # The Legendre's range follows, and its curve does not change
    assert CO.xrange_of(project, grown)[0] == pytest.approx(low - 0.5, abs=0.02)
    inside = (grown.pixels.wave >= low) & (grown.pixels.wave <= high)
    assert np.allclose(CO.evaluate(project, grown)[inside], curve_before, rtol=1e-6)
    assert errors(project) == []


def _red(spec, high, new_high):
    return int(np.count_nonzero((spec.wave > high) & (spec.wave <= new_high)))


