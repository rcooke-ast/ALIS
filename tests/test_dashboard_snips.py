def test_snip_cuts_a_transition_from_its_source(project, registry):
    hist = H.History(project)
    before = state(project)
    step = snip_one(project, registry, *OI)
    assert step.description == "SNIP O I 1302.2 in 1 dataset"
    hist.do(step)
    snip = project.snip("OI_1302")
    # ±300 km/s of 1302.17 Å, from the source, at full precision
    low, high = S.window(OI[1], 0.0)
    spec = spectra(project)["r1"]
    inside = spec.wave[(spec.wave >= low) & (spec.wave <= high)]
    assert np.array_equal(snip.pixels.wave, inside)
    assert snip.pixels.ncols == 4 and snip.pixels.bad is None
    # No fit region until one is drawn (Q4.2): the line says what to do
    assert not S.fitted(snip).any()
    assert any("no fit region yet" in m for m in errors(project))
    # Its data line, its continuum (a Legendre with its range) and its records
    item = snip.data
    assert item.fitrange == ("columns",)
    assert item.keyword("resolution") == "vfwhm(7.0FWHM1)"
    assert item.keyword("loadrange") == "all"
    assert snip.continuum.function == "legendre"
    assert snip.continuum.keyword("min") is not None
    assert project.ui["rows"][0]["specids"] == ["OI_1302"]
    assert project.ui["snips"]["OI_1302"]["ion"] == OI[0]
    assert {"ion": OI[0], "wave": OI[1]} in project.ui["systems"][0]["lines"]
    # The transition is now listed as a snip
    trans = L.snip_transitions(project)["OI_1302"]
    assert (trans.system, trans.ion) == ("a", OI[0])
    # One undo gives back every byte
    hist.undo()
    assert state(project) == before


