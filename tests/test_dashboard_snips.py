# -- Pixels fitted twice (S26, D19, Q4.9) ------------------------------------------------


def _overlapping(project, registry):
    hist = H.History(project)
    hist.do(snip_one(project, registry, *OI))
    hist.do(S.add_region_step(project, project.snip("OI_1302"), 1301.5, 1303.4))
    hist.do(snip_one(project, registry, *SII))
    hist.do(S.add_region_step(project, project.snip("SiII_1304"), 1303.1, 1305.0))
    return hist


def test_overlapping_snips_share_pixels_and_keep_fixes_them(project, registry):
    hist = _overlapping(project, registry)
    pairs = S.shared_pixels(project)
    assert len(pairs) == 1 and pairs[0].count > 10
    before = state(project)
    keep = S.keep_step(project, project.snip("OI_1302"))
    assert keep.description.startswith("Keep {0} shared pixels".format(pairs[0].count))
    hist.do(keep)
    assert S.shared_pixels(project) == []
    assert errors(project) == []
    hist.undo()
    assert state(project) == before


def test_the_metal_line_snips_merge_into_one(project, registry):
    hist = _overlapping(project, registry)
    before = state(project)
    oi, si = project.snip("OI_1302"), project.snip("SiII_1304")
    old_oi = set(_pixel_lines(project.files[oi.member]))
    old_si = set(_pixel_lines(project.files[si.member]))
    plan = S.merge_plan(project, oi, si)
    assert (plan.keep, plan.replaced) == ("OI_1302", "SiII_1304")
    assert any("replaced by OI_1302" in n for n in plan.notes)
    hist.do(plan.step)
    assert [s.specid for s in project.snips] == ["OI_1302"]
    merged = project.snip("OI_1302")
    lines = _pixel_lines(project.files[merged.member])

    # Both files' pixels (their wavelength, flux and error as written), a pixel of
    # both once, in order of wavelength
    def words(found):
        return {tuple(ln.split()[:3]) for ln in found}

    assert words(lines) == words(old_oi) | words(old_si)
    assert len(lines) == len(words(lines))
    assert np.all(np.diff(merged.pixels.wave) > 0)
    assert S.shared_pixels(project) == []
    # One continuum over both, on the union of their ranges
    cont = merged.continuum
    assert cont.specids == ["OI_1302"]
    assert len(project.parsed.function_lines("legendre")) == 1
    assert CO.xrange_of(project, merged)[1] == pytest.approx(merged.extent[1])
    assert errors(project) == []
    assert "SiII_1304" not in project.ui.get("snips", {})
    hist.undo()
    assert state(project) == before


