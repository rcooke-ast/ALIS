J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
OI = ("16O_I", 1302.16849)
SII = ("28Si_II", 1304.3702)


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def state(project):
    return project.text, dict(project.files), project.ui


def errors(project):
    return [p.message for p in V.check(project) if p.severity == V.ERROR]


def transition(registry, ion, rest):
    atom = L.atomic(registry)
    return next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)


def new_project(registry, tmp_path, sources_=None, z=0.0):
    paths = [str(p) for p in (sources_ or [SPECTRUM])]
    project, _ = modes.get().empty_project(paths, "test", z=z, registry=registry)
    return project


def spectra(project):
    return {r.id: sources.spectrum(project, r) for r in project.rows}


def snip_one(project, registry, ion, rest):
    step = S.snip_step(
        project, project.systems[0], transition(registry, ion, rest), spectra(project)
    )
    return step


@pytest.fixture
def project(registry, tmp_path):
    return new_project(registry, tmp_path)


