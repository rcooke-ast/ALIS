"""Snips: SNIP and CLEAR, regions, masks, edges, copying, buffers, shared pixels.

Dashboard Stage 4.2. After every step that leaves each snip a region, ALIS reads the
model and its data (``validate.check``), and one undo gives back the text, the files
and ``ui/project.json`` byte for byte. A bad pixel of the source is carried in the
snip (``badpix``) and never fitted, by the dashboard or by ALIS (Q4.15, Q4.17). On
``metal_line_abs``'s spectrum, the O I 1302 and Si II 1304 snips overlap and merge
into one, after which no pixel is fitted twice.

Generated by RJC and Claude.
"""

