"""Unit tests for the model-evaluation entry point (Stage 4.0).

The return-not-mutate contract dropped the per-call ``copy.copy(state)`` in
``_minimiser_eval`` (safe once ``_pinfl`` is frozen). This checks the observable
consequence -- the state object is passed straight through, not copied -- without
needing the full model stack. The numerical equivalence of the change is covered
by the Stage 0 bitwise gate.

Generated by RJC and Claude.
"""

import pytest

from alis import model_eval

pytestmark = pytest.mark.unit


def test_minimiser_eval_does_not_copy_state(monkeypatch):
    # Spy on myfunct: record the exact state object it is handed.
    seen = {}

    def _spy(
        p,
        fjac=None,
        x=None,
        y=None,
        err=None,
        state=None,
        ddpid=None,
        pp=None,
        getemab=False,
        emab=None,
        output=0,
    ):
        seen["state"] = state
        return [0, "resid"]

    monkeypatch.setattr(model_eval, "myfunct", _spy)
    sentinel = object()
    out = model_eval._minimiser_eval(None, state=sentinel)
    # No copy.copy(state) -> the identical object reaches myfunct.
    assert seen["state"] is sentinel
    assert out == [0, "resid"]
