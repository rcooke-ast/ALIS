"""Removal with dependents (dashboard Stage 2.9, S27, D23).

On the D/H fit of J1358p6522, whose D/H is linked through the variable ``dhrand``,
removing D I must remove its links. On Q1243p307, removing a dataset removes its
snips, its zero level and its shift. After each removal ALIS reads the model without
error (its full set of loaders, with the data in memory), and undoing the removal
gives back the original.

Generated by RJC and Claude.
"""

import json
from pathlib import Path

import pytest

from alis.dashboard import blinding as BL
from alis.dashboard import model as M
from alis.dashboard import project as P
from alis.dashboard import remove as R
from alis.dashboard import validate as V

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
CTX = ROOT / "context/fitting_examples"
DHJ = CTX / "DH/J1358p6522/model/J1358p6522_original.mod"
Q1243 = CTX / "DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
J1358 = CTX / "VMP_DLA/J1358p6522/model/J1358p6522.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def imported(path, registry):
    if not path.exists():
        pytest.skip("model not present: " + str(path.relative_to(ROOT)))
    return P.Project.import_model(str(path), registry=registry)


def state(project):
    return (
        project.text,
        tuple(sorted(project.files.items())),
        json.dumps(project.ui, sort_keys=True),
    )


def remove_and_check(project, plan):
    """Make the removal, check that ALIS reads the result, and undo it."""
    before = state(project)
    step = plan.step(project)
    project.apply(step)
    assert not project.paused, project.parsed.errors
    problems = V.full(
        project.text, project.data_for_run(), project.registry, project.parsed
    )
    assert [p for p in problems if p.severity == "error"] == []
    after = project
    project.revert(step)
    assert state(project) == before
    return after, step


def test_removing_d_i_removes_its_links(registry):
    project = imported(DHJ, registry)
    main = [c for c in project.components if "2H_I" in c.ions][0]
    plan = R.plan_ion(project, main, "2H_I")
    pm = project.parsed
    ratio = [ln for ln in pm.lines if ln.ratio][0]
    variable = pm.function_lines("variable")[0]
    link = pm.links[0]
    assert [(e.line, e.action) for e in plan.lines] == [
        (ratio.line, R.DELETE),
        (variable.line, R.DELETE),
        (link.line, R.DELETE),
    ]
    reasons = {e.line: e.reason for e in plan.lines}
    assert "gives D I as a ratio" in reasons[ratio.line]
    assert "components" in reasons[ratio.line]
    assert "'dhtie'" in reasons[link.line]
    assert "links that used it" in reasons[variable.line]
    before = project.text
    step = plan.step(project)
    project.apply(step)
    assert not project.parsed.links and not project.parsed.function_lines("variable")
    assert "#   random   -4.60dhrand" in project.text  # comments are kept
    assert all("2H_I" not in c.ions for c in project.components)
    problems = V.full(project.text, project.data_for_run(), registry, project.parsed)
    assert [p for p in problems if p.severity == "error"] == []
    project.revert(step)
    assert project.text == before


def test_removing_a_dataset_removes_its_snips_zero_level_and_shift(registry):
    project = imported(Q1243, registry)
    row = project.row("KIRKMAN")
    sids = set(row.specids)
    plan = R.plan_dataset(project, row)
    deleted = {e.line for e in plan.lines if e.action == R.DELETE}
    edited = [e for e in plan.lines if e.action == R.EDIT]
    pm = project.parsed
    assert {s.line for s in row.snips} <= deleted
    assert row.zero.line in deleted
    continua = [
        ln.line for ln in pm.function_lines("legendre") if set(ln.specids) <= sids
    ]
    assert len(continua) == 12 and set(continua) <= deleted
    assert edited and all(any(s in e.before for s in sids) for e in edited)
    assert len(plan.files) == 12
    after, step = remove_and_check(project, plan)
    project.apply(step)
    assert [r.name for r in project.rows] == ["HIRES", "PROCHASKA"]
    assert "vk" not in project.parsed.labels and "SHK" not in project.parsed.labels
    assert not any(sids & set(ln.specids) for ln in project.parsed.lines)
    assert not any("kirkman" in m for m in project.files)


def test_removing_a_component(registry):
    project = imported(J1358, registry)
    comp = project.systems[0].components[0]
    plan = R.plan_component(project, comp)
    assert [e.action for e in plan.lines] == [R.DELETE]
    remove_and_check(project, plan)


def test_removing_a_snip(registry):
    project = imported(J1358, registry)
    snip = project.snip("O2")
    plan = R.plan_snip(project, snip)
    deleted = [e for e in plan.lines if e.action == R.DELETE]
    assert snip.line in {e.line for e in deleted}
    assert snip.continuum.line in {e.line for e in deleted}
    blends = [ln.line for ln in project.parsed.lines if ln.specids == ["O2"]]
    assert set(blends) <= {e.line for e in deleted}
    assert plan.files == [snip.member]
    remove_and_check(project, plan)


def test_removing_a_system(registry):
    project = imported(Q1243, registry)
    system = [s for s in project.systems if round(s.z, 2) == 2.05][0]
    plan = R.plan_system(project, system)
    assert len([e for e in plan.lines if e.action == R.DELETE]) == 7
    after, step = remove_and_check(project, plan)
    project.apply(step)
    assert not [s for s in project.systems if round(s.z, 2) == 2.05]


def test_ties_left_with_one_member_are_noted(registry):
    project = imported(J1358, registry)
    main = project.systems[0].components[1]
    hyd = main.lines_of("1H_I")[0]
    # 'ra' ties H I's and D I's redshifts: removing D I leaves H I alone with it
    plan = R.plan_ion(project, main, "2H_I")
    assert plan.notes == [
        "'ra' will be used on line {0} only: it is no longer tied"
        " to anything.".format(hyd.line + 1)
    ]
    # Removing O I unties nothing: its six lines share 'noi' and 'da' among
    # themselves
    assert R.plan_ion(project, main, "16O_I").notes == []


def test_a_removal_from_a_ui_system_updates_project_json(registry):
    project = imported(Q1243, registry)
    project.apply(project.confirm_structure())
    system = [s for s in project.systems if round(s.z, 2) == 2.05][0]
    plan = R.plan_system(project, system)
    assert plan.ui is not None
    assert system.id not in [s["id"] for s in plan.ui["systems"]]
    before = state(project)
    step = plan.step(project)
    project.apply(step)
    assert system.id not in [s["id"] for s in project.ui["systems"]]
    project.revert(step)
    assert state(project) == before


def test_the_plan_is_shown_through_the_blinding_gate(registry):
    project = imported(DHJ, registry)
    from alis.dashboard import edit as E

    pm = project.parsed
    project.edit(E.set_blind(pm, pm.function_lines("variable")[0]))
    main = [c for c in project.components if "2H_I" in c.ions][0]
    plan = R.plan_ion(project, main, "2H_I")
    gate = BL.Gate(project)
    shown = plan.preview(gate)
    variable = project.parsed.function_lines("variable")[0]
    line = [s for s in shown if s[0] == variable.line][0]
    assert "-4.60" not in line[3] and BL.MASK in line[3]


def test_a_ratio_line_goes_when_its_denominator_does(registry):
    """Removing every H I line removes D I's ratio line, its link and dhrand."""
    project = imported(DHJ, registry)
    system = project.systems[0]
    plan = R.plan_system(project, system)
    pm = project.parsed
    ratio = [ln for ln in pm.lines if ln.ratio][0]
    reasons = {e.line: e.reason for e in plan.lines}
    assert "no H I line is left for its ratio" in reasons[ratio.line]
    assert pm.links[0].line in reasons
    assert pm.function_lines("variable")[0].line in reasons
    remove_and_check(project, plan)
