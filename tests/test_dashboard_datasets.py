def test_the_redshift_moves_nothing(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    system = project.systems[0]
    text, files = project.text, dict(project.files)
    step = D.set_z_step(project, system, 0.0001)
    check_undo(project, hist, step)
    assert project.text == text and project.files == files
    assert project.systems[0].z == 0.0001
    assert project.systems[0].name == "z = 0.00010"
    with pytest.raises(D.DatasetError):
        D.set_z_step(project, project.systems[0], -1.0)


def test_systems_are_added_renamed_and_made_primary(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    hist.do(D.add_system_step(project, 0.5))
    assert [s.id for s in project.systems] == ["a", "b"]
    assert project.systems[0].primary and not project.systems[1].primary
    hist.do(D.rename_system_step(project, project.system("b"), "interloper"))
    assert project.system("b").name == "interloper"
    hist.do(D.make_primary_step(project, project.system("b")))
    assert project.system("b").primary and not project.system("a").primary
    # A project with no system gets a primary
    bare, _ = modes.get().empty_project([str(SPECTRUM)], "b", registry=registry)
    step = D.add_system_step(bare, 2.0)
    bare.apply(step)
    assert bare.systems[0].primary


def test_removing_a_system_lists_its_lines_first(registry):
    if not Q1243.exists():
        pytest.skip("Q1243p307 is not present")
    project = P.Project.import_model(str(Q1243), registry=registry)
    system = next(s for s in project.systems if not s.primary and s.components)
    plan = R.plan_system(project, system)
    assert plan.lines and all(e.reason for e in plan.lines)
    hist = H.History(project)
    before = everything(project)
    hist.do(plan.step(project))
    assert errors(project) == []
    hist.undo()
    assert everything(project) == before


def test_confirming_an_imported_structure(registry):
    if not Q1243.exists():
        pytest.skip("Q1243p307 is not present")
    project = P.Project.import_model(str(Q1243), registry=registry)
    assert any(n.kind == "inferred" for n in project.notices)
