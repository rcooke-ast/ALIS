def test_changing_the_reference_fixes_its_shift_and_frees_the_old(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    first, second = project.rows
    assert first.reference and second.snips[0].data.keyword("shift") is not None
    step = D.set_reference_step(project, second)
    assert step.description == "Make {0} the reference".format(second.name)
    check_undo(project, hist, step)
    first, second = project.rows
    assert second.reference and not first.reference
    # The new reference has no shift (fixed at 0); the old one a free shift
    assert second.snips[0].data.keyword("shift") is None
    shift = first.snips[0].data.param("shift")
    assert shift is not None and shift.free and shift.start == 0.0
    with pytest.raises(D.DatasetError, match="reference already"):
        D.set_reference_step(project, project.rows[1])


def test_the_reference_of_an_imported_fit(registry):
    if not Q1243.exists():
        pytest.skip("Q1243p307 is not present")
    project = P.Project.import_model(str(Q1243), registry=registry)
    hist = H.History(project)
    prochaska = project.row("PROCHASKA")
    check_undo(project, hist, D.set_reference_step(project, prochaska))
    assert project.row("PROCHASKA").reference
    hires = project.row("HIRES")
    assert hires.snips[0].data.param("shift").free
    # The structure is now written out (it was guessed)
    assert [r["name"] for r in project.ui["rows"]] == ["HIRES", "PROCHASKA", "KIRKMAN"]


def test_fwhm_and_shift_values_states_and_ties(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    first, second = project.rows
    assert D.state_of(first, "resolution") == D.FIXED
    assert D.state_of(second, "shift") == D.FREE
    check_undo(project, hist, D.set_value_step(project, first, "resolution", 6.5))
    assert project.rows[0].snips[0].data.param("resolution").start == 6.5
    hist.do(D.set_state_step(project, project.rows[0], "resolution", D.FREE))
    assert D.state_of(project.rows[0], "resolution") == D.FREE
    # Tie the second row's FWHM to the first's (Q0.8): one parameter
    step = D.set_state_step(
        project, project.rows[1], "resolution", D.TIED, project.rows[0]
    )
    check_undo(project, hist, step)
    assert [r.name for r in D.tied_to(project, project.rows[1], "resolution")] == [
        project.rows[0].name
    ]
    assert project.rows[1].snips[0].data.param("resolution").start == 6.5


def test_zero_level_on_and_off(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    row = project.rows[0]
    step = D.zero_level_step(project, row, True)
    check_undo(project, hist, step)
    row = project.rows[0]
    assert row.zero is not None and row.zero.specids == row.specids
    with pytest.raises(D.DatasetError, match="already"):
        D.zero_level_step(project, row, True)
    hist.do(D.zero_level_step(project, row, False))
    assert project.rows[0].zero is None
    assert errors(project) == []


def test_a_zero_level_set_before_the_first_snip(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path, snip=False)
    hist.do(D.zero_level_step(project, project.rows[1], True))
    assert project.ui["rows"][1]["zerolevel"] is True
    spec = {r.id: sources.spectrum(project, r) for r in project.rows}
    atom = L.atomic(registry)
    line = next(
        ln for ln in atom.ion_lines("16O_I") if abs(ln.rest - 1302.16849) < 0.01
    )
    hist.do(S.snip_step(project, project.systems[0], line, spec))
    assert project.rows[0].zero is None
    assert project.rows[1].zero is not None


def test_adding_a_file_adds_a_row_and_its_source(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    third = tmp_path / "third.dat"
    third.write_bytes(SPECTRUM.read_bytes())
    step = D.add_file_step(project, str(third), fwhm=5.0)
    check_undo(project, hist, step)
    row = project.rows[-1]
    assert row.name == "third" and not row.snips and row.source is not None
    assert project.ui["rows"][-1]["fwhm"] == 5.0
    assert len(project.bundle.sources) == 3
    assert sources.spectrum(project, row) is not None


def test_renaming_and_column_roles(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    step = D.rename_row_step(project, project.rows[0], "HIRES")
    check_undo(project, hist, step)
    assert project.rows[0].name == "HIRES"
    with pytest.raises(D.DatasetError, match="Another dataset"):
        D.rename_row_step(project, project.rows[1], "HIRES")
    # A row with snips keeps its column roles (Q4.14)
    with pytest.raises(D.DatasetError, match="CLEAR"):
        D.columns_step(project, project.rows[0], {"wave": 0, "flux": 1, "error": 2})
    empty, _ = two_rows(registry, tmp_path, snip=False)
    hist2 = H.History(empty)
    roles = {"wave": 0, "flux": 1, "error": 2}
    hist2.do(D.columns_step(empty, empty.rows[0], roles))
    assert empty.rows[0].columns == roles


