"""The Data tab's edits: file rows and systems (dashboard Stage 4.4).

Each edit is one step that ALIS reads, and one undo gives back the text, the files,
``ui/project.json`` and the sources. The reference's shift is fixed at 0 and the old
reference's freed (D14); a row with snips keeps its column roles (Q4.14); removing a
system lists its lines first (S27).

Generated by RJC and Claude.
"""

from pathlib import Path

import pytest

from alis.dashboard import datasets as D
from alis.dashboard import history as H
from alis.dashboard import lines as L
from alis.dashboard import model as M
from alis.dashboard import modes
from alis.dashboard import project as P
from alis.dashboard import remove as R
from alis.dashboard import snips as S
from alis.dashboard import sources
from alis.dashboard import validate as V

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
SPECTRUM = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"
Q1243 = (
    ROOT
    / "context/fitting_examples/DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
)


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def everything(project):
    return (
        project.text,
        dict(project.files),
        project.ui,
        [dict(s) for s in project.bundle.sources],
    )


def errors(project):
    return [p.message for p in V.check(project) if p.severity == V.ERROR]


def two_rows(registry, tmp_path, snip=True):
    other = tmp_path / "second.dat"
    other.write_bytes(SPECTRUM.read_bytes())
    project, _ = modes.get().empty_project(
        [str(SPECTRUM), str(other)], "t", z=0.0, registry=registry
    )
    hist = H.History(project)
    if snip:
        spec = {r.id: sources.spectrum(project, r) for r in project.rows}
        atom = L.atomic(registry)
        line = next(
            ln for ln in atom.ion_lines("16O_I") if abs(ln.rest - 1302.16849) < 0.01
        )
        hist.do(S.snip_step(project, project.systems[0], line, spec))
        for one in list(project.snips):
            hist.do(S.add_region_step(project, one, 1301.5, 1302.8))
    return project, hist


def check_undo(project, hist, step):
    """Make a step, check ALIS reads it, undo and redo it; it is left made."""
    before = everything(project)
    hist.do(step)
    assert errors(project) == []
    after = everything(project)
    hist.undo()
    assert everything(project) == before
    hist.redo()
    assert everything(project) == after


