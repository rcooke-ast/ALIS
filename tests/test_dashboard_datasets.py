def test_changing_the_reference_fixes_its_shift_and_frees_the_old(registry, tmp_path):
    project, hist = two_rows(registry, tmp_path)
    first, second = project.rows
    assert first.reference and second.snips[0].data.keyword("shift") is not None
    step = D.set_reference_step(project, second)
    assert step.description == "Make {0} the reference".format(second.name)
    check_undo(project, hist, step)
    first, second = project.rows
