def test_an_edit_keeps_an_imported_structure_marked_guessed(registry):
    if not Q1243.exists():
        pytest.skip("Q1243p307 is not present")
    project = P.Project.import_model(str(Q1243), registry=registry)
    hist = H.History(project)
    step = D.set_state_step(
        project, project.row("KIRKMAN"), "resolution", D.TIED, project.row("PROCHASKA")
    )
    hist.do(step)
    assert project.ui[P.GUESSED] is True and project.inferred
    assert [r.name for r in project.rows] == ["HIRES", "PROCHASKA", "KIRKMAN"]
    hist.do(project.confirm_structure())
    assert P.GUESSED not in project.ui and not project.inferred
