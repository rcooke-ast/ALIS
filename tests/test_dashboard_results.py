def _fit_dat(folder, snip):
    name = Path(snip.member).name.rsplit(".", 1)[0] + "_fit.dat"
    return np.loadtxt(folder / name)


@pytest.mark.parametrize("which", ["metal", "j1358"])
def test_the_best_fit_drawn_is_alis_fit_dat(which, request):
    project = request.getfixturevalue(which)
    folder = METAL_FITS if which == "metal" else J1358_FITS
    view = RS.View.latest(project)
    assert view.why_not() == ""
    curves = view.curves()
    for snip in project.snips:
        curve = curves[snip.data.index]
        ref = _fit_dat(folder, snip)
        window = ref[:, -1] > -1.0e9
        mine = np.isin(curve.wave, ref[window, 0])
        theirs = np.isin(ref[window, 0], curve.wave)
        # To the precision of the values the .mod.out prints
        diff = np.abs(curve.model[mine] - ref[window, -1][theirs]) / curve.error[mine]
        assert np.nanmax(diff) < 0.01, snip.specid
        if which == "j1358":
            # The continuum column of a _fit.dat is ALIS's best-fit continuum line
            cont = np.abs(curve.continuum[mine] - ref[window, 4][theirs])
            assert np.nanmax(cont / curve.error[mine]) < 0.01, snip.specid


