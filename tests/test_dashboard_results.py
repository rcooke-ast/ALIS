# -- Outliers (S29, D27, Q6.11) -------------------------------------------------------


def _push(project, snip, places, sigma):
    """The step that moves some pixels of a snip's file by ``sigma`` errors."""
    member = snip.member
    old = project.files[member]
    lines = old.decode("utf-8").splitlines(keepends=True)
    rows = snip.pixels.rows
    for place in places:
        words = lines[rows[place]].split()
        flux, err = float(words[1]), float(words[2])
        words[1] = repr(flux + sigma * err)
        lines[rows[place]] = " ".join(words) + "\n"
    return P.Step("Move pixels", files={member: (old, "".join(lines).encode("utf-8"))})


def test_outliers_are_reviewed_then_left_out_as_one_step(metal):
    snip = metal.snips[0]
    fitted = np.flatnonzero(S.fitted(snip))
    lone, pair, three = fitted[20], fitted[[60, 61]], fitted[[100, 101, 102]]
    places = [lone, *pair, *three]
    metal.apply(_push(metal, snip, places, 30.0))
    view = RS.View.latest(metal)
    found = RS.outliers(view.curves(), metal)
    out = found[metal.snips[0].data.index]
    assert list(out.pixels) == places
    assert list(out.ticked) == [True, True, True, False, False, False]
    assert np.all(np.abs(out.sigma) > 5.0)
    # A higher threshold, a preference, marks none
    assert RS.outliers(view.curves(), metal, prefs={"fit.outlier_sigma": 100.0}) == {}
    before = dict(metal.files)
    chosen = {out.specid: out.wave[out.ticked]}
    step = RS.outliers_step(metal, chosen)
    assert step.description == "Leave out 3 outliers"
    metal.apply(step)
    now = S.fitted(metal.snips[0])
    assert not now[[lone, *pair]].any() and now[three].all()
    assert int(now.sum()) == len(fitted) - 3
    metal.revert(step)
    assert metal.files == before


