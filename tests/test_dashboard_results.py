def test_no_blinded_value_is_shown(blinded):
    view = RS.View.latest(blinded)
    groups = view.table()
    rows = {r.name: r for g in groups for r in g.rows}
    for name in (
        "O I a1 log N",
        "O I a1 z",
        "O I a1 b",
        "Si II a1 log N",
        "Si II a1 z",
    ):
        assert rows[name].value == BL.MASK and "blinded" in rows[name].flags, name
        assert rows[name].error  # errors are shown (QF.20(b))
    best = best_values(blinded)
    bad = set()
    for index in (3, 4, 5, 10, 11):
        bad |= renderings(best[index])
    shown = RS.copy_text(groups) + repr([r.flags for r in rows.values()])
    view_text = shown + repr(view.statistics())
    assert not [b for b in bad if b in view_text]
    plan = RS.continue_plan(blinded, view)
    blinded.apply(plan.step)
    # The offset line receives values, and is hidden; the blind line stays hidden
    oxygen, silicon = voigt(blinded, "16O_I"), voigt(blinded, "28Si_II")
    assert {oxygen.line, silicon.line} <= set(blinded.hidden_lines())
    masked = BL.Gate(blinded).view().text + plan.step.description + repr(plan.changed)
    assert not [b for b in bad if b in masked]
