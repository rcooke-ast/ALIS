def test_use_best_fit_copies_a_component_into_changed_lines(metal):
    oxygen = voigt(metal, "16O_I")
    edit_value(metal, oxygen.param("ColDens"), 15.0)
    edit_value(metal, voigt(metal, "16O_I").param("bturb"), 9.0)
    before = metal.text
    view = RS.View.latest(metal)
    comp = metal.components[0]
    assert RS.component_reason(metal, view, comp) == ""
    step = RS.component_step(metal, view, comp)
    assert step.description == "Use the best fit of component a1"
    metal.apply(step)
    best = best_values(metal)
    oxygen = voigt(metal, "16O_I")
    assert oxygen.param("ColDens").start == pytest.approx(best[3])
    assert oxygen.param("bturb").start == pytest.approx(best[5])
    assert voigt(metal, "28Si_II").param("ColDens").start == pytest.approx(best[10])
    # The continuum is not the component's
    assert metal.snips[0].continuum.params[0].start == 1.0
    metal.revert(step)
    assert metal.text == before


