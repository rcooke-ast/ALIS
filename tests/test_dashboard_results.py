def test_use_best_fit_continuum_with_its_function_or_range_changed(metal):
    view = RS.View.latest(metal)
    metal.apply(CO.function_step(metal, metal.snips[0], "chebyshev"))
    _check_exact(metal, view, metal.snips[0])
    metal.apply(CO.function_step(metal, metal.snips[0], "legendre"))
    line = metal.snips[0].continuum
    pm = metal.parsed
    change = E.set_keyword(pm, line, "min", "1299.0")
    change = change.then(
        E.set_keyword(
            E.reread(pm, change), E.reread(pm, change).lines[0], "max", "1307.0"
        )
    )
    metal.apply(metal.step(change))
    assert CO.xrange_of(metal, metal.snips[0]) == (1299.0, 1307.0)
    _check_exact(metal, view, metal.snips[0])


def test_use_best_fit_continuum_with_its_order_lowered(metal):
    view = RS.View.latest(metal)
    target = _run_continuum(view, metal, metal.snips[0])
    metal.apply(CO.order_step(metal, metal.snips[0], 1))
    snip = metal.snips[0]
    copy = RS.continuum_copy(metal, view, snip)
    assert copy.largest > 1.0e-3
    # The nearest straight line to the run's continuum, weighted by the errors
    good = snip.pixels.fittable
    nearest = CO.fit(
        metal.registry,
        "legendre",
        1,
        CO.model_wave(metal, snip, snip.pixels.wave),
        target,
        snip.pixels.error,
        good,
        CO.xrange_of(metal, snip),
        clip=None,
    )
    assert np.allclose(
        copy.copy["0"],
        CO.curve(
            metal.registry,
            "legendre",
            nearest.coeffs,
            CO.model_wave(metal, snip, snip.pixels.wave),
            CO.xrange_of(metal, snip),
        ),
        rtol=1e-9,
    )
    fitted = S.fitted(snip)
    dev = np.abs(copy.copy["0"] - target)[fitted] / snip.pixels.error[fitted]
    assert copy.largest == pytest.approx(dev.max())
    assert copy.rms == pytest.approx(np.sqrt(np.mean(dev**2)))
    assert np.allclose(copy.run["0"], target)


