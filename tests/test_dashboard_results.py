def _blind_out(text, offset):
    """
    The metal reference ``.mod.out`` as ALIS writes it for examples/blind: O I with a
    ``blindrange``, its values offset; Si II with ``blind=True``.
    """
    keys = "  blind=False  blindseed=1234  blindrange=-1000000.0,1000000.0"
    out = []
    for line in text.splitlines():
        if line.startswith("# voigt   ion=16O_I"):
            line = line + keys
        elif line.startswith("# voigt   ion=28Si_II"):
            line = line + "  blind=True"
        elif line.startswith("  voigt   ion=16O_I"):
            words = line.split()
            new = []
            for word in words:
                found = re.match(r"^([-+]?[\d.]+(?:E[-+]\d+)?)([A-Za-z]*)$", word)
                if found and word != words[0]:
                    new.append(
                        "{0:.7f}{1}".format(
                            float(found.group(1)) + offset, found.group(2)
                        )
                    )
                else:
                    new.append(word)
            line = "  " + "  ".join(new) + keys
        elif line.startswith("  voigt   ion=28Si_II"):
            line = line + "  blind=True"
        out.append(line)
    return "\n".join(out) + "\n"


