def test_continue_from_best_fit_is_one_step_alis_reads(metal):
    before = metal.text
    view = RS.View.latest(metal)
    plan = RS.continue_plan(metal, view)
    assert plan.skipped == []
    names = {what: set(n) for _, what, n in plan.changed}
    assert names["O I a1"] == {"log N", "z", "b"}
    assert names["the continuum of 0"] == {"coefficient"}
    metal.apply(plan.step)
    assert metal.parsed.ok
    PR.Profile(metal)  # ALIS's loaders read it
    best = best_values(metal)
    for par in metal.parsed.params:
        if par.free and par.index >= 0:
            assert par.start == pytest.approx(best[par.index], rel=1e-9)
    # The temperature is fixed: it keeps its value as written
    assert "8000TA" in metal.text
    metal.revert(plan.step)
    assert metal.text == before


def test_continue_skips_a_parameter_changed_since_the_run(metal):
    silicon = voigt(metal, "28Si_II")
    edit_value(metal, silicon.param("ColDens"), 13.5)
    # A line added since the run
    pm = metal.parsed
    added = voigt(metal, "28Si_II").line + 1
    metal.apply(
        metal.step(
            T.Change(
                (
                    T.insert_lines(
                        pm.text,
                        added,
                        [
                            "    voigt   ion=12C_II  13.0    0.0    1.0da   8000TA   specid=0"
                        ],
                    ),
                )
            )
        )
    )
    view = RS.View.latest(metal)
    plan = RS.continue_plan(metal, view)
    skipped = {(line, tuple(names), why) for line, _, names, why in plan.skipped}
    silicon = voigt(metal, "28Si_II")
    assert (silicon.line, ("log N",), "changed since the run") in skipped
    assert any(line == added for line, *_ in skipped)
    metal.apply(plan.step)
    assert voigt(metal, "28Si_II").param("ColDens").start == 13.5
    best = best_values(metal)
    zpar = voigt(metal, "28Si_II").param("redshift")
    assert zpar.start == pytest.approx(best[11])
    assert voigt(metal, "12C_II").param("ColDens").start == 13.0


