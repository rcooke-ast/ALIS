def store_run(project, stem, mod_out=None, status="completed", covar=True, **info):
    """
    Store a run made from a model's reference outputs as the project's latest run,
    in memory, as ``bundle.execute`` gives one.

    Generated by RJC and Claude.
    """
    stem = str(stem)[: -len(".mod")]
    name = Path(stem).name
    text = (
        mod_out
        if mod_out is not None
        else Path(stem + ".mod.out.reference").read_text()
    )
    files = {name + ".mod.out": text.encode("utf-8")}
    if covar:
        files[name + ".covar"] = Path(stem + ".covar.reference").read_bytes()
    bundle = project.to_bundle()
    model = bundle.members[bundle.model_member]
    now = B.now()
    fields = {
        "started": now,
        "finished": now,
        "host": "test",
        "status": status,
        "model_sha256": B.sha256(model),
    }
    fields.update(info)
    fields = {k: v for k, v in fields.items() if v is not None}
    result = B.RunResult(
        info=fields,
        files=files,
        model_member=bundle.model_member,
        model_bytes=model,
        model_hidden=bundle.hidden_model_lines(),
        inputs={
            m: c
            for m, c in bundle.members.items()
            if m.startswith(B.TREE) and m != bundle.model_member
        },
    )
    B.store(project.bundle, result)
    return R.latest(project.bundle)


