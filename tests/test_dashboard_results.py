def test_a_value_on_its_bound_is_at_limit(metal, registry):
    # The minimiser leaves a parameter that presses on its bound exactly on it
    text = Path(str(METAL)[:-4] + ".mod.out.reference").read_text()
    text = text.replace("5.088151da", "6.0000000da")
    project = P.Project.import_model(str(METAL), registry=registry)
    pm = project.parsed
    start = next(ln.num for ln in pm.text if ln.text.strip() == "model read")
    limit = T.insert_lines(pm.text, start + 1, ["  lim voigt bturb [6.0,None]"])
    project.apply(project.step(T.Change((limit,))))
    store_run(project, METAL, mod_out=text)
    rows = {r.name: r for g in RS.View.latest(project).table() for r in g.rows}
    assert rows["O I a1 b"].flags == ["at limit (6)"]
    oxygen = voigt(project, "16O_I").param("bturb")
    assert RS.at_limit(oxygen, 6.0, "6.0000000") == 6.0
    # Above the bound by more than the value's precision: not at it
    assert RS.at_limit(oxygen, 6.0000002, "6.0000002") is None

    assert RS.at_limit(oxygen, 6.00004, "6.0000E+00") == 6.0


