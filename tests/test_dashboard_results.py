def _report(path):
    rows = {}
    for line in path.read_text().splitlines():
        if re.match(r"  \S", line):
            words = line.split()
            rows[words[0]] = (float(words[6]), float(words[11]))
    return rows


def test_the_marks_equal_the_report(j1358):
    report = _report(J1358.parent / "J1358p6522.mod.report")
    view = RS.View.latest(j1358)
    marks = view.marks()
    flagged = []
    for snip in j1358.snips:
        mark = marks[snip.data.index]
        redchi2, runs_z = report[snip.specid]
        assert mark.reduced == pytest.approx(redchi2, abs=2.0e-3)
        assert mark.runs_z == pytest.approx(runs_z, abs=0.02)
        assert mark.chi2_mark != RS.BAD
        if mark.flagged:
            flagged.append(snip.specid)
            assert mark.runs_mark == RS.BAD
    # Nine snips are flagged, by the runs test alone (Q0.4)
    assert flagged == ["H1", "H2", "H3", "H5", "H6", "H7", "H8", "O1", "O3"]
    # The mockup's amber marks: 2–3σ
    assert marks[j1358.snip("H4").data.index].runs_mark == RS.WARN
    assert marks[j1358.snip("H8").data.index].chi2_mark == RS.WARN
    assert marks[j1358.snip("O4").data.index].runs_mark == RS.GOOD


def test_a_mark_is_computed_as_the_report_computes_it():
    rng = np.random.default_rng(3)
    wave = np.arange(500.0)
    flux = rng.normal(size=500)
    curve = PR.Curve(
        0, "0", wave, flux, np.ones(500), np.zeros(500), None, wave > 100, 0.0
    )
    mark = RS.quality(curve, 3.0)
    resid = flux[100:][1:]
    assert mark.npix == 399
    assert mark.chi2 == pytest.approx(np.sum(resid**2))
    assert mark.deviation == pytest.approx((mark.reduced - 1) / np.sqrt(2 / 399))
    from alis.report import runs_z

    assert mark.runs_z == runs_z(resid)
    # χ²ν is flagged only above; the runs test either way
    low = RS.Quality(100, 50.0, 0.5, -5.0, -4.0)
    assert (low.chi2_mark, low.runs_mark) == (RS.GOOD, RS.BAD)


