def test_continue_under_global_blind_hides_what_it_fills(metal):
    blind = next(s for s in metal.parsed.settings if s.key == "blind")
    metal.apply(
        metal.step(
            T.Change((T.replace_token(metal.parsed.text, blind.tokens[2], "True"),))
        )
    )
    view = RS.View.latest(metal)
    assert view.gate.global_blind
    rows = [r for g in view.table() for r in g.rows]
    assert all(r.value == BL.MASK for r in rows if r.state != RS.FIXED)
    plan = RS.continue_plan(metal, view)
    metal.apply(plan.step)
    gate = BL.Gate(metal)
    assert set(plan.lines) <= set(metal.hidden_lines())
    bad = set()
    for value in best_values(metal).values():
        bad |= renderings(value)
    shown = gate.view().text + plan.step.description + repr(plan.changed)
    assert not [b for b in bad if b in shown and b not in ("0.0",)]
    # The values are there, hidden, in the model
    assert voigt(metal, "16O_I").param("ColDens").start == pytest.approx(13.985197)


