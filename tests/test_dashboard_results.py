# -- Use best fit: a continuum (Q6.17, Q6.20) ------------------------------------------


def _run_continuum(view, project, snip):
    theirs = view.run_snip(snip)
    return CO.evaluate(view.model, theirs, wave=snip.pixels.wave, values=view.vector())


def _check_exact(project, view, snip):
    copy = RS.continuum_copy(project, view, snip)
    assert copy.largest < 1.0e-6 and copy.rms < 1.0e-6
    target = _run_continuum(view, project, snip)
    project.apply(copy.step)
    now = project.snip(snip.specid)
    # The written values give the run's continuum, to the precision of its values
    assert np.allclose(CO.evaluate(project, now), target, rtol=1.0e-8, atol=0)
    return copy, now


def test_use_best_fit_continuum_with_its_order_unchanged(metal):
    view = RS.View.latest(metal)
    snip = metal.snips[0]
    assert RS.continuum_reason(metal, view, snip) == ""
