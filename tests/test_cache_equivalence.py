"""Stage 3.1 cache A/B self-check.

The profile cache (`run cache True`) must be *bitwise-identical* to the
uncached path: reusing an unchanged model component's evaluated array is exactly
equal to recomputing it (reuse is gated on both the component's parameters and
the shifted wavelength grid being unchanged). This test runs each example fit
twice -- ``run cache False`` vs ``run cache True`` -- and asserts the ``.mod.out``
(fitted parameters, errors, chi-squared) *and* the ``.covar`` covariance matrix
are byte-identical, ignoring only the timestamp / running-time header lines and
the injected ``run cache`` echo.

The covariance matrix (computed from the final Jacobian) is the sensitive
check: a shift-varying fit that wrongly reused a component computed at the old
wavelength grid would converge to the same parameters but drift in ``.covar``.

Generated by RJC and Claude.
"""

import os
import re
import shutil
import subprocess
import sys

import pytest
from manifest import REPO_ROOT

RUN_ALIS = REPO_ROOT / "alis" / "scripts" / "run_alis.py"

_STRIP = re.compile(r"Generated by ALIS on|Running Time|run cache")

# (path relative to repo root, mod filename, marker). The fast examples cover
# many absorbers, tied params, emission, phionxs and a Chebyshev continuum; the
# medium helium34 case varies a shift/velocity, so it exercises the
# wavelength-grid cache invalidation and the .covar comparison.
CASES = [
    ("examples/metal_line_abs", "fit_spectra.mod", "fast"),
    ("examples/CNabs", "fit_spectra.mod", "fast"),
    ("examples/emission_line_ratio", "fit_spectra.mod", "fast"),
    ("examples/lls", "fit_spectra.mod", "fast"),
    ("examples/chebyshev", "fit_spectra.mod", "fast"),
    (
        "context/fitting_examples/helium34/Her36",
        "fit_polyvoigt_linear_Thermal_FINAL_MODEL.mod",
        "medium",
    ),
]

# Each case carries its runtime batch marker *and* a source marker derived from
# its top-level directory ("examples" / "context"), exactly as test_regression
# does. The source marker matters: context/fitting_examples/ is not part of the
# repository, so the CI "examples" batch must not select the helium34 case --
# on a clean checkout its directory does not exist and copytree would fail.
_PARAMS = [
    pytest.param(
        path,
        mod,
        id=path.split("/")[-1] if "examples/" in path else path.split("/")[-2],
        marks=[getattr(pytest.mark, mark), getattr(pytest.mark, path.split("/", 1)[0])],
    )
    for path, mod, mark in CASES
]


def _run(model_dir, mod):
    env = dict(os.environ)
    env["MPLBACKEND"] = "Agg"
    proc = subprocess.run(
        [sys.executable, str(RUN_ALIS), "-f", "-w", "-p", "0", mod],
        cwd=str(model_dir),
        env=env,
        capture_output=True,
        text=True,
        timeout=1800,
    )
    assert proc.returncode == 0, (
        f"run_alis {mod} exited {proc.returncode}:\n"
        + (proc.stdout + proc.stderr)[-2000:]
    )


def _clean(path):
    return [ln for ln in path.read_text().splitlines() if not _STRIP.search(ln)]


@pytest.mark.parametrize("path,mod", _PARAMS)
def test_cache_bitwise_equivalence(path, mod, tmp_path):
    off = tmp_path / "off"
    on = tmp_path / "on"
    shutil.copytree(REPO_ROOT / path, off)
    shutil.copytree(REPO_ROOT / path, on)
    # Force the setting explicitly on both copies (robust to the default).
    (off / "model" / mod).write_text(
        "run cache False\n" + (off / "model" / mod).read_text()
    )
    (on / "model" / mod).write_text(
        "run cache True\n" + (on / "model" / mod).read_text()
    )

    _run(off / "model", mod)
    _run(on / "model", mod)

    # .mod.out: fitted parameters, 1-sigma errors, chi-squared.
    assert _clean(off / "model" / (mod + ".out")) == _clean(
        on / "model" / (mod + ".out")
    ), f"{path}: cached .mod.out is not bitwise-identical to uncached"

    # .covar: full covariance matrix (the sensitive, Jacobian-derived check).
    covs_off = sorted((off / "model").glob("*.covar"))
    covs_on = sorted((on / "model").glob("*.covar"))
    assert [c.name for c in covs_off] == [c.name for c in covs_on]
    for co, cn in zip(covs_off, covs_on):
        assert (
            co.read_text() == cn.read_text()
        ), f"{path}: cached {co.name} is not bitwise-identical to uncached"
