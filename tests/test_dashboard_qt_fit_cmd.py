@pytest.fixture
def window(qtbot, tmp_path, monkeypatch):
    monkeypatch.setenv("ALIS_HOME", str(tmp_path / "home"))
    win = make_window(qtbot, tmp_path / "home")
    win.prefs.set("fit.ncpus", 1)
    yield win
    if win.session is not None:
        win.session.discard_recovery()
        win.session = None


def open_metal(window, qtbot, tmp_path):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    wait_idle(qtbot, window)
    return str(path)


def marker(window):
    window.refresh()
    found = window.markers["Fit"]
    return found.state, window.tabs.tabToolTip(3)


def test_the_fit_marker_in_each_state(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    project = window.session.project
    state, tip = marker(window)
    assert state == MK.NONE and tip == "No fit has run yet."
    # A run of the dashboard's: ✓, with its χ² and when
    store_run(project, METAL, chi2_final=357.874162, dof=360, origin=R.DASHBOARD)
    state, tip = marker(window)
    assert state == MK.COMPLETE
    assert tip.startswith("The latest run (completed), χ² = 357.874")
    # A run of run_alis's: named so
    store_run(project, METAL, chi2_final=357.874162, dof=360)
    state, tip = marker(window)
    assert state == MK.COMPLETE and tip.startswith("The latest run (run_alis,")
    # The model changed since: ↻
    par = next(p for p in project.parsed.params if p.name == "ColDens")
    window._run(
        "panel",
        lambda: window.session.history.edit(
            E.set_value(project.parsed, par, 14.5), "Set N"
        ),
    )
    state, tip = marker(window)
    assert state == MK.STALE and tip == "The model has changed since the latest run."
    window.qactions["edit.undo"].trigger()
    assert marker(window)[0] == MK.COMPLETE
    # The last run stopped with an error: !
    project.bundle.members[B.LAST_ERROR] = json.dumps(
        {"time": "2999-01-01T00:00:00", "message": "ALIS stopped\nmore"}
    ).encode()
    state, tip = marker(window)
    assert state == MK.ATTENTION
    assert tip == "The last run stopped with an error: ALIS stopped"
    del project.bundle.members[B.LAST_ERROR]
    # The pre-flight check refuses Run: !
    window.session.history.do(
        project.step(E.set_setting(project.parsed, "sim", "perturb", "10"), "Set")
    )
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(0)
    state, tip = marker(window)
    assert state == MK.ATTENTION and tip.startswith("The pre-flight check refuses Run")


def test_the_regions_tabs_model_draws_the_best_fit(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    project = window.session.project
    window.tabs.setCurrentIndex(1)
    regions = window.tab_widgets[1]
    regions.show_items([project.snips[0]])
    window.qactions["regions.model"].trigger()
    # No run yet: the starting model, with no choice
    assert regions.model_from.isHidden()
    start = regions.strips[0].view._items["model"].getData()[1]
    store_run(project, METAL, chi2_final=357.874162, dof=360)
    window.refresh()
    assert not regions.model_from.isHidden()
    assert regions.model_from.itemText(1) == "Best fit"
    assert "the latest run" in regions.model_from.toolTip()
    regions.model_from.setCurrentIndex(1)
    assert window.session.view["regions"]["model_from"] == "best"
    drawn = regions.strips[0].view._items["model"].getData()[1]
    best = RS.View.latest(project).curves()[project.snips[0].data.index]
    finite = np.isfinite(drawn)
    assert np.allclose(
        np.sort(drawn[finite]), np.sort(best.model[np.isfinite(best.model)])
    )
    assert not np.allclose(np.nanmax(np.abs(drawn - start)), 0.0)
    regions.model_from.setCurrentIndex(0)
    again = regions.strips[0].view._items["model"].getData()[1]
    assert np.allclose(again[np.isfinite(again)], start[np.isfinite(start)])


@pytest.mark.fast
def test_a_run_alis_run_is_taken_in_without_asking(window, qtbot, tmp_path):
    path = open_metal(window, qtbot, tmp_path)
    out = subprocess.run(
        [
            sys.executable,
            "-m",
            "alis.scripts.run_alis",
            path,
            "--set",
            "run ncpus 1",
            "--set",
            "plot fits False",
        ],
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert out.returncode == 0, out.stderr[-2000:]
    asked = len(window.answers.asked)
    window.watch_disk()
    assert len(window.answers.asked) == asked
    assert "outside the dashboard" in window.statusBar().currentMessage()
    record = R.latest(window.session.project.bundle)
    assert record is not None and record.origin == R.COMMAND
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(1)
    window.refresh()
    [row] = window.fit_tab.results.history_rows
    assert row.where.startswith("cmd") and row.run == "Latest"
    assert window.markers["Fit"].tip.startswith("The latest run (run_alis,")
