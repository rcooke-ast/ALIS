"""The Fit marker, command-line runs and the Regions tab's best fit (dashboard Stage
6.9; F12, S31; Q3.8, Q5.8, Q6.14).

- The Fit marker in each state: ○ no run yet; ✓ the latest run, a command-line run
  named so; ↻ the model changed since the run; ! the pre-flight check refuses Run,
  or the last run stopped with an error. (↻ while a run goes is checked by
  ``test_dashboard_qt_fit.py``'s run from the tab.)
- ``run_alis project.model`` while the project is open: the run is taken in
  without asking, and the run history lists it as "cmd" (marked ``fast``: it fits).
  A run kept running when the dashboard closes is shown when the project is next
  opened (``test_dashboard_qt_fit.py``'s closing during a run).
- The Regions tab's Model switch draws the shown run's best fit once a run exists.

Generated by RJC and Claude.
"""

