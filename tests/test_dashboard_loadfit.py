"""Loading snips and a .mod from an earlier analysis (dashboard Task 7.1).

A new project is made from a spectrum, then snips saved by ``prepfit`` (wave, flux,
error and a fit range of 0s and 1s, named ``<stem>_<ion>_<λ>_reg.dat``) are loaded:
each is matched to the spectrum it was cut from and placed at its transition, its fit
range kept. A file that fails any check stops the whole load (Q7.4), and a snip that
shares pixels with one already loaded replaces it (Q7.2). A ``.mod`` brings its model,
as written, and its own snips (Q7.1), with ``run blind`` following the project and its
own FWHM (Q7.3). After every load ALIS reads the model and its data
(``validate.check``), and one undo gives back the text, the files and
``ui/project.json`` byte for byte.

The example of Task 7.1, ``context/fitting_examples/Temperature/J013301m400628/``, is
loaded too when it is present.

Generated by RJC and Claude.
"""

