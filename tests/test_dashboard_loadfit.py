def new_project(registry, paths, z=0.0, blind=False, columns=None):
    project, _ = modes.get().empty_project(
        [str(p) for p in paths],
        "test",
        z=z,
        blind=blind,
        columns=columns,
        registry=registry,
    )
    return project


def spectra(project):
    return {r.id: sources.spectrum(project, r) for r in project.rows}


def state(project):
    return project.text, dict(project.files), project.ui


def errors(project):
    return [p.message for p in V.check(project) if p.severity == V.ERROR]


def load(project, paths):
    return LF.load_snips_plan(project, [str(p) for p in paths], spectra(project))


