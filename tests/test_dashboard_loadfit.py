    # At no system's redshift: the redshift is set first (Q7.4)
    with pytest.raises(LF.LoadError, match="Set the redshift on the Data tab"):
        LF.place(project, "src_16O_I_1302.2_reg.dat", (1310.0, 1312.0))
    unset = new_project(registry, [source], z=None)
    with pytest.raises(LF.LoadError, match="has no system yet"):
        LF.place(unset, "src_16O_I_1302.2_reg.dat", (1301.5, 1302.8))


