def test_a_bad_pixel_mask_of_the_source_is_carried(registry, tmp_path):
    table = np.loadtxt(str(SPECTRUM))[:, :3]
    bad = np.zeros(table.shape[0])
    bad[(table[:, 0] > 1302.0) & (table[:, 0] < 1302.2)] = 1.0
    path = tmp_path / "masked.dat"
    np.savetxt(str(path), np.column_stack([table, bad]))
    project = new_project(
        registry,
        [path],
        columns={str(path): {"wave": 0, "flux": 1, "error": 2, "mask": 3}},
    )
    plain = tmp_path / "plain.dat"
    np.savetxt(str(plain), table)
    snip_file = prepfit_snip(
        tmp_path / "data", plain, OI, name="masked_16O_I_1302.2.dat"
    )
    H.History(project).do(load(project, [snip_file]).step)
    snip = project.snip("OI_1302")
    assert snip.data.keyword("columns") == S.COLUMNS_BAD
    assert snip.pixels.bad.sum() > 0
    assert not np.any(S.fitted(snip) & snip.pixels.bad)
    assert errors(project) == []


