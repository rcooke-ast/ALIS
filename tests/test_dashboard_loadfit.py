def test_prepfit_snips_load_with_their_fit_ranges(registry, source, tmp_path):
    project = new_project(registry, [source])
    hist = H.History(project)
    before = state(project)
    one = prepfit_snip(tmp_path / "data", source, OI)
    two = prepfit_snip(tmp_path / "data", source, SII)
    plan = load(project, [one, two])
    assert plan.ok and not plan.replaced
    assert plan.description == "Load 2 snips (O I 1302.2, Si II 1304.4)"
    hist.do(plan.step)
    for path, (ion, rest, _), specid in ((one, OI, "OI_1302"), (two, SII, "SiII_1304")):
        snip = project.snip(specid)
        old = LF.read_snip_file(str(path))
        # Stored byte for byte, under its own name beside the model's snips
        assert snip.member == "files/data/" + path.name
        assert project.files[snip.member] == path.read_bytes()
        assert np.array_equal(snip.pixels.wave, old.wave)
        assert np.array_equal(S.fitted(snip), old.fit)
        assert snip.data.keyword("columns") == S.COLUMNS
        assert snip.data.keyword("resolution") == "vfwhm(7.0FWHM1)"
        assert snip.continuum is not None and snip.continuum.function == "legendre"
        trans = L.snip_transitions(project)[specid]
        assert (trans.system, trans.ion) == ("a", ion)
        assert project.ui["snips"][specid]["row"] == "r1"
    assert project.ui["rows"][0]["specids"] == ["OI_1302", "SiII_1304"]
    json.dumps(project.ui)
    assert errors(project) == []
    hist.undo()
    assert state(project) == before


