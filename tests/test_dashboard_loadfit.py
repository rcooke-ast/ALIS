def test_a_snip_that_overlaps_one_loaded_replaces_it(registry, source, tmp_path):
    project = new_project(registry, [source])
    hist = H.History(project)
    hist.do(load(project, [prepfit_snip(tmp_path / "a", source, OI)]).step)
    hist.do(load(project, [prepfit_snip(tmp_path / "a", source, SII)]).step)
    before = state(project)
    wider = prepfit_snip(tmp_path / "b", source, OI, half=200.0, fit=(-60.0, 60.0))
    plan = load(project, [wider])
    assert plan.ok
    assert [s.specid for s, _ in plan.replaced] == ["OI_1302"]
    assert plan.notes == [
        "src_16O_I_1302.2_reg.dat replaces the snip OI_1302 of O I 1302.2 in src."
    ]
    # The preview lists the lines that go: the data line and its continuum
    reasons = [p[2] for p in plan.preview(BL.Gate(project))]
    assert "it is the data line of snip OI_1302" in reasons
    assert plan.description == "Load 1 snip (O I 1302.2), replacing 1"
    hist.do(plan.step)
    # The same specid and file name, now holding the wider snip
    assert sorted(s.specid for s in project.snips) == ["OI_1302", "SiII_1304"]
    snip = project.snip("OI_1302")
    assert project.files[snip.member] == wider.read_bytes()
    assert len(project.parsed.function_lines("legendre")) == 2
    assert errors(project) == []
    hist.undo()
    assert state(project) == before


