MOD = """run blind {blind}
chisq miniter 7

data read
  ../data/{one}   specid=0   fitrange=columns   resolution=vfwhm({fwhm}VFIX)   columns=[wave,flux,error,fitrange]   label=OI
  ../data/{two}   specid=1   fitrange=columns   resolution=vfwhm({fwhm}VFIX)   columns=[wave,flux,error,fitrange]   label=SiII
data end

model read
  emission
    legendre 1.0   0.01   scale=[1.0,1.0]   specid=0
    legendre 1.0   0.01   scale=[1.0,1.0]   specid=1
  absorption
    voigt   ion=16O_I     14.0   {z}za   5.0ba   0.0TA   specid=0,1
    voigt   ion=28Si_II   13.0   {z}za   5.0ba   0.0TA   specid=0,1
model end
"""


def write_mod(folder, source, blind="False", fwhm="7.0", z="0.0", one=None, two=None):
    data = folder / "data"
    one = one or prepfit_snip(data, source, OI)
    two = two or prepfit_snip(data, source, SII)
    model = folder / "model"
    model.mkdir(parents=True, exist_ok=True)
    path = model / "old.mod"
    path.write_text(MOD.format(blind=blind, fwhm=fwhm, z=z, one=one.name, two=two.name))
    return path


def test_a_mod_brings_its_model_as_written_and_its_snips(registry, source, tmp_path):
    project = new_project(registry, [source])
    hist = H.History(project)
    # A snip loaded first, then the .mod, whose snips replace it (Q7.1)
    hist.do(load(project, [prepfit_snip(tmp_path / "first", source, OI)]).step)
    before = state(project)
    mod = write_mod(tmp_path / "old", source)
    plan = LF.load_mod_plan(project, str(mod), spectra(project))
    assert plan.ok
    assert [s.specid for s in plan.removed] == ["OI_1302"]
    assert [entry[:2] for entry in plan.loaded] == [
        ("0", "src_16O_I_1302.2_reg.dat"),
        ("1", "src_28Si_II_1304.4_reg.dat"),
    ]
    assert any("O I 1302.2" in n and "go" in n for n in plan.notes)
    assert all("FWHM" not in n for n in plan.notes)
    gate = BL.Gate(project)
    assert {p[2] for p in plan.preview(gate)} == {"replaced by the .mod"}
    hist.do(plan.step)
    assert project.text == mod.read_text()
    assert sorted(project.files) == [
        "files/data/src_16O_I_1302.2_reg.dat",
        "files/data/src_28Si_II_1304.4_reg.dat",
    ]
    assert project.ui["rows"][0]["specids"] == ["0", "1"]
    assert project.ui["snips"]["0"]["ion"] == OI[0]
    assert "knots" not in project.ui
    # Its one component joins the project's system, which stays confirmed
    assert [len(s.components) for s in project.systems] == [1]
    assert not project.inferred
    assert errors(project) == []
    hist.undo()
    assert state(project) == before


def test_run_blind_follows_the_project(registry, source, tmp_path):
    blinded = new_project(registry, [source], blind=True)
    hist = H.History(blinded)
    hist.guard = BL.Guard(blinded)
    mod = write_mod(tmp_path / "a", source, blind="False")
