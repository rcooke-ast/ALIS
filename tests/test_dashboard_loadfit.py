def test_a_snip_matches_the_spectrum_it_was_cut_from(registry, source, tmp_path):
    project = new_project(registry, [source])
    spec = spectra(project)["r1"]
    old = LF.read_snip_file(str(prepfit_snip(tmp_path, source, OI)))
    match = LF.match_row(project, spectra(project), old.wave, old.flux, old.error)
    assert match.row.id == "r1"
    assert np.array_equal(spec.wave[match.index], old.wave)
    # Written with fewer digits, it still matches
    rounded = prepfit_snip(tmp_path, source, OI, fmt="%.7e", name="r_16O_I_1302.2.dat")
    old = LF.read_snip_file(str(rounded))
    assert LF.match_row(project, spectra(project), old.wave, old.flux, old.error)


def test_a_snip_from_another_spectrum_is_refused_with_the_reason(
    registry, source, tmp_path
):
    project = new_project(registry, [source])
    found = spectra(project)
    old = LF.read_snip_file(str(prepfit_snip(tmp_path, source, OI)))
    # The flux changed at three pixels
    flux = old.flux.copy()
    flux[[3, 10, 20]] *= 1.5
    with pytest.raises(LF.LoadError, match="flux differs from src's at 3 pixels"):
        LF.match_row(project, found, old.wave, flux, old.error)
    error = old.error * 2.0
    with pytest.raises(LF.LoadError, match="error differs"):
        LF.match_row(project, found, old.wave, old.flux, error)
    # Half a pixel off the source's pixels
    step = np.median(np.diff(old.wave))
    with pytest.raises(LF.LoadError, match="are not on src's pixels"):
        LF.match_row(project, found, old.wave + 0.5 * step, old.flux, old.error)
    with pytest.raises(LF.LoadError, match="outside the range of src"):
        LF.match_row(project, found, old.wave + 100.0, old.flux, old.error)
    with pytest.raises(LF.LoadError, match="no source spectrum"):
        LF.match_row(project, {}, old.wave, old.flux, old.error)


def test_a_snip_is_placed_at_the_transition_its_name_names(registry, source):
    project = new_project(registry, [source])
    system, line = LF.place(project, "src_16O_I_1302.2_reg.dat", (1301.5, 1302.8))
