def test_the_j013301m400628_snips_and_mod_load(registry):
    if not J0133.is_dir():
        pytest.skip("J013301m400628 is not present")
    project = new_project(registry, [J0133 / "J013301m400628.dat"], z=2.7934)
    hist = H.History(project)
    found = spectra(project)
    spec = found["r1"]
    paths = sorted(glob.glob(str(J0133 / "data" / "*_reg.dat")))
    plan = LF.load_snips_plan(project, paths, found)
    assert plan.ok
    assert plan.description == "Load 2 snips (Lyβ 1025.7, Lyα 1215.7)"
    hist.do(plan.step)
    fitted = {}
    for specid, path in zip(("HI_1025", "HI_1215"), paths):
        snip = project.snip(specid)
        old = LF.read_snip_file(path)
        # The pixels are the spectrum's, and the fit range is the snip's own
        index, _ = LF.positions(spec, snip.pixels.wave)
        assert np.array_equal(spec.wave[index], snip.pixels.wave)
        assert np.array_equal(spec.flux[index], snip.pixels.flux)
        assert np.array_equal(spec.error[index], snip.pixels.error)
        assert np.array_equal(S.fitted(snip), old.fit)
        fitted[specid] = int(S.fitted(snip).sum())
        trans = L.snip_transitions(project)[specid]
        assert (trans.system, trans.ion) == ("a", "1H_I")
