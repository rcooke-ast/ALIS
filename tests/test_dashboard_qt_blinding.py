def open_saved(window, qtbot, model, tmp_path):
    path = tmp_path / "project.model"
    B.pack_to(str(model), str(path), with_outputs=False)
    window.open_path(str(path))
    wait_idle(qtbot, window)
    return str(path)


def ok_button(dialog):
    return dialog.box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok)


def test_the_pill_says_what_is_blinded(window, qtbot, tmp_path):
    open_saved(window, qtbot, BLIND, tmp_path)
    assert window.pill.text() == "Blinded: Si II"
    assert window.pill.property("blinded") == "true"
    window.do_file_close()
    assert window.pill.text() == "Not blinded"


def test_blind_the_analysis_is_one_step_undo_does_not_pass(window, qtbot, tmp_path):
    open_saved(window, qtbot, METAL, tmp_path)
    assert window.pill.text() == "Not blinded"
    # Cancelled: nothing happens
    window.qactions["model.blind"].trigger()
    assert window.pill.text() == "Not blinded"
    window.answers.answers["blind"] = "Blind"
    window.qactions["model.blind"].trigger()
    assert window.pill.text() == "Blind analysis"
    assert not window.qactions["edit.undo"].isEnabled()
    window.qactions["edit.undo"].trigger()
    assert window.session.project.parsed.blind
    # Asked again, it says so
    window.qactions["model.blind"].trigger()
    assert window.answers.asked[-1][2] == "The analysis is blinded already."


def test_blind_lines(window, qtbot, tmp_path):
    open_saved(window, qtbot, METAL, tmp_path)
    project = window.session.project

    def answer(dialog):
        assert isinstance(dialog, D.BlindLinesDialog)
        items = dialog.items()
        # Lines are listed by system, component and ion, with no values
        texts = [i.text(0) for i in items]
        assert any(t.startswith("O I · line") for t in texts)
        assert not any(re.search(r"\d\.\d", t) for t in texts)
        items[0].setCheckState(0, items[0].checkState(0).__class__.Checked)
        return 1

    window.on_dialog = answer
    window.qactions["model.blind_lines"].trigger()
    assert len(project.hidden_lines()) == 1
    assert window.pill.text().startswith("Blinded: ")
    assert not window.qactions["edit.undo"].isEnabled()


def test_unblinding_needs_the_confirmation_and_is_logged(window, qtbot, tmp_path):
    path = open_saved(window, qtbot, BLIND, tmp_path)
    project = window.session.project
    seen = []

    def refuse(dialog):
        assert isinstance(dialog, D.UnblindDialog)
        assert "cannot be undone" in dialog.findChild(QtWidgets.QLabel).text()
        assert not ok_button(dialog).isEnabled()
        dialog.note.setText("A reason")
        assert not ok_button(dialog).isEnabled()
        dialog.confirm.setChecked(True)
        dialog.note.setText("")
        assert not ok_button(dialog).isEnabled()
        seen.append("refused")
        return 0

    window.on_dialog = refuse
    window.qactions["model.unblind"].trigger()
    assert seen == ["refused"] and project.hidden_lines()

    def confirm(dialog):
        dialog.note.setText("The paper is submitted")
        dialog.confirm.setChecked(True)
        assert ok_button(dialog).isEnabled()
        return 1

    # A step to undo, which unblinding clears
    window.panel.editor.selectAll()
    window.on_dialog = confirm
    window.qactions["model.unblind"].trigger()
    assert not project.hidden_lines()
    assert window.pill.text() == "Not blinded"
    assert not window.session.history.done
    shown = window.panel.editor.toPlainText()
    si = next(ln for ln in shown.splitlines() if "28Si_II" in ln)
    assert BL.MASK not in si and "13.0" in si and "blind=False" in si
    log = B.read(path).manifest["unblinding"]
    assert log[-1]["note"] == "The paper is submitted"
    assert not window.session.dirty
    # Nothing is blinded any more
    window.qactions["model.unblind"].trigger()
    assert window.answers.asked[-1][2] == "Nothing is blinded in this project."


def export_to(window, folder, **ticks):
    """Answer Export…'s dialog: the folder, and what is ticked."""

    def answer(dialog):
        dialog.folder.setText(str(folder))
        for key, on in ticks.items():
            dialog.boxes[key].setChecked(on)
        return 1

    window.on_dialog = answer


EVERYTHING = dict(snips=False, start=False, best=False, everything=True)


def test_export_keeps_hidden_values_hidden(window, qtbot, tmp_path):
    # RJC's response to Q7.16: hidden values are written as BLIND, with no question
    open_saved(window, qtbot, BLIND, tmp_path)
    out = tmp_path / "exported"
    out.mkdir()
    export_to(window, out, **EVERYTHING)
    window.qactions["file.export"].trigger()
    model = out / "model" / "fit_spectra.mod"
    words = " ".join(model.read_text().split())
    assert "ion=28Si_II BLIND BLIND BLINDda BLINDTA" in words
    assert "ion=28Si_II 13.0" not in words
    assert [a[0] for a in window.answers.asked] == ["tell"]
    assert "Wrote" in window.answers.asked[-1][2]
    assert "written as BLIND" in window.answers.asked[-1][2]
    # The starting model alone, masked the same way
    export_to(window, tmp_path / "start", snips=False, start=True, best=False)
    window.qactions["file.export"].trigger()
    text = (tmp_path / "start" / "project_start.mod").read_text()
    assert "ion=28Si_II BLIND" in " ".join(text.split())


