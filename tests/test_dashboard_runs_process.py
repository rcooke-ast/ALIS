@pytest.mark.parametrize("global_blind", [False, True])
def test_no_hidden_value_leaves_the_process(home, tmp_path, registry, global_blind):
    path = packed(tmp_path, model=BLIND)
    session = S.Session.open(path, registry=registry)
    settings = SETTINGS + (["run blind True"] if global_blind else [])
    job = R.Run(session, settings=settings)
    job.start()
    seen = []
    while not job.finished:
        seen += job.update()
        time.sleep(0.05)
    assert job.status == R.COMPLETED, job.message
    assert job.take(session)
    run_ = R.latest(session.project.bundle)
    best = run_.mod_out()
    hidden = session.project.bundle.hidden_model_lines()
    assert hidden
    # The hidden line's best-fit values, as the restored .mod.out gives them
    secret_line = next(ln for ln in model_block(best) if "Si_II" in ln)
    secrets = secret_line.split()[2:4]
    stored = B.read(path)
    plain = [
        stored.members[m].decode("utf-8", "replace")
        for m in stored.members
        if m.startswith(B.RUNS) and not m.endswith((".pdf", ".png"))
    ]
    shown = [json.dumps({k: v for k, v in m.items() if k != "values"}) for m in seen]
    shown += job.warnings + [job.message]
    for secret in secrets:
        for text in plain + shown:
            assert secret not in text
    if global_blind:
        assert any(m.endswith(".mod.out") for m in stored.hidden["files"])


