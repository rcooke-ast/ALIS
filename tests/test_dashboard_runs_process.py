def test_stop_keeps_an_interrupted_run_and_cancel_keeps_nothing(
    home, tmp_path, registry
):
    path = packed(tmp_path)
    session = S.Session.open(path, registry=registry)
    job = R.Run(session, settings=SETTINGS)
    job.start()
    wait_for_iteration(job)
    job.stop()
    assert job.wait(timeout=300) == R.INTERRUPTED
    assert job.take(session)
    run_ = R.latest(session.project.bundle)
    assert run_.status == R.INTERRUPTED
    assert run_.values(registry)
    assert run_.errors(registry) is None
    before = B.read(path).members[B.LATEST + "run.json"]
    # With ALIS's workers: Cancel ends them with the process
    job = R.Run(session, settings=SETTINGS[:-1] + ["run ncpus 2"])
    job.start()
    wait_for_iteration(job)
    group = job.process.popen.pid
    assert job.cancel()
    assert job.wait(timeout=60) == R.CANCELLED
    time.sleep(1.0)
    with pytest.raises(ProcessLookupError):
        os.killpg(group, 0)
    assert B.read(path).members[B.LATEST + "run.json"] == before
    assert not job.take(session)


