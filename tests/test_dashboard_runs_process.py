def packed(tmp_path, model=METAL, name="project.model"):
    target = tmp_path / name
    B.pack_to(str(model), str(target))
    return str(target)


def model_block(text):
    """The best-fit model of a ``.mod.out``: its ``model read`` block."""
    lines = text.splitlines()
    start = lines.index("model read")
    return lines[start : lines.index("model end", start) + 1]


def run(session, settings=SETTINGS, cwd=None, timeout=600):
    job = R.Run(session, settings=settings, cwd=cwd)
    job.start()
    job.wait(timeout=timeout)
    return job


def wait_for_iteration(job, timeout=300):
    start = time.time()
    while job.iteration is None and not job.finished:
        job.update()
        if time.time() - start > timeout:
            raise AssertionError("no iteration reported")
        time.sleep(0.02)


def test_a_run_gives_what_run_alis_gives(home, tmp_path, registry):
    path = packed(tmp_path)
    plain = packed(tmp_path, name="plain.model")
    out = subprocess.run(
        [sys.executable, "-m", "alis.scripts.run_alis", plain]
        + [arg for s in SETTINGS for arg in ("--set", s)],
        capture_output=True,
        text=True,
        cwd=str(tmp_path),
        timeout=600,
    )
    assert out.returncode == 0, out.stderr[-2000:]
    expected = R.latest(B.read(plain))
    cwd = tmp_path / "cwd"
    cwd.mkdir()
    session = S.Session.open(path, registry=registry)
    job = run(session, cwd=str(cwd))
    assert job.status == R.COMPLETED, job.message
    assert job.stored == "file"
    assert job.take(session)
    got = R.latest(session.project.bundle)
    assert got.origin == R.DASHBOARD
    assert expected.origin == R.COMMAND
    assert model_block(got.mod_out()) == model_block(expected.mod_out())
    assert got.chi2 == expected.chi2
    assert got.iterations == expected.iterations
    # The χ² of every iteration, ending with the best fit's
    assert [p[0] for p in got.progress] == list(range(1, got.iterations + 1))
    assert got.progress[0][1] == pytest.approx(got.info["chi2_initial"])
    assert got.progress[-1][1] == got.chi2
    assert job.progress == got.progress[: len(job.progress)]
    assert len(job.values) == len(got.values(registry))
    # Nothing written but the project's file
    assert os.listdir(cwd) == []
    assert set(os.listdir(tmp_path)) <= {
        "alis_home",
        "cwd",
        "plain.model",
        "project.model",
    }
    assert not session.dirty


