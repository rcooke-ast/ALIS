"""The fitting process: real fits run from a session (dashboard Stage 6.1; F6, S31;
Q6.2, Q6.3, Q6.14, Q6.15, Q6.19).

- A run of ``examples/metal_line_abs`` handed over in memory gives the best fit that
  ``run_alis project.model`` gives, and the χ² of every iteration; it writes no file
  but the project's own.
- With unsaved changes, the run fits them, and the model on disk is unchanged.
- Stop keeps an "interrupted" run with its values; Cancel keeps nothing.
- A project with no file keeps the run in memory and in its recovery copy, and Save
  writes it.
- On ``examples/blind``, and under global blind, no hidden value reaches the
  messages, ``run.json`` or the plain members of the project's file.

Marked ``fast``: each test runs fits.

Generated by RJC and Claude.
"""

