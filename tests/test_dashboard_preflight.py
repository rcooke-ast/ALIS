def rewrite(project, old, new):
    """Replace a piece of the model's text, as one step."""
    assert old in project.text
    text = project.text.replace(old, new)
    project.apply(project.step(T.Change((T.Patch(0, project.text, text),)), "edit"))
    return project


def param(project, name, line_text):
    line = project.text.splitlines().index(line_text.rstrip("\n"))
    return next(p for p in project.parsed.params if p.name == name and p.line == line)


def set_value(project, name, line_text, value):
    par = param(project, name, line_text)
    project.apply(project.step(E.set_value(project.parsed, par, value), "Set"))


