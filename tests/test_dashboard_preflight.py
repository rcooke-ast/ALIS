def test_no_hidden_value_in_a_message(registry, prefs):
    project = P.Project.import_model(str(BLIND), registry=registry)
    gate = BL.Gate(project)
    hidden = gate.hidden_values()
    assert hidden
    # The hidden Si II line starts at b = 1.0 km/s: no low-b note reveals it
    secret = next(
        p for p in project.parsed.params if gate.is_hidden(p) and p.name == "bturb"
    )
    project.apply(project.step(E.set_value(project.parsed, secret, 0.5), "Set"))
    report = PF.check(project, prefs)
    for finding in report.findings:
        assert finding.line != secret.line or finding.code not in ("at_limit", "low_b")
        for value in BL.Gate(project).hidden_values():
            assert value not in finding.message
