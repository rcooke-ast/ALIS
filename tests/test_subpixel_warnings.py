"""A profile with too few sub-pixels warns (dashboard Stage 14, Task 14.4).

Q14.4 (ii)'s and Q14.7's responses: ALIS warns only where the sub-pixels should be
increased, and the level is the snip's ``nsubsigma``, the sub-pixels a profile
should have across its standard deviation (Q14.12; ``nsubsigma_min`` before).
Beside a data line that records too few
(Task 14.3, ``test_subpixel_names.py``):

- **A best fit that asks for more sub-pixels than its fit used**: a fit's
  sub-pixels are set from its starting values; at the end of the fit, ALIS works out
  what each snip's lines ask for at the best fit, and warns once. Not with
  ``nsubpixel_renew``, whose grid follows the fit.
- **Lines that ask for more than ``nsubpixel_max``**, at load: ALIS capped them in
  silence before.
- **Never of too many**: ``run warn_subpix`` was removed.

The fit of ``examples/lsf_spline`` warns, in ``test_subpixels_fit.py``.

Generated by RJC and Claude.
"""

from types import SimpleNamespace

import numpy as np
import pytest

from alis import load
from alis.config import ArgFlag
from alis.main import build_funcarray

pytestmark = pytest.mark.unit

# A voigt line of b = 10 km/s on pixels of 11.5 km/s asks for 9 sub-pixels per
# pixel to have 5 across its σ (√2 · 5 · 11.5 / 10, rounded up); at b = 2 km/s, 41
MODEL = [
    "emission\n",
    "constant 1.0\n",
    "absorption\n",
    "voigt ion=16O_I 14.0 0.0 10.0 0.0TA\n",
]
BEST = "best fit asks for more sub-pixels"
CAPPED = "nsubpixel_max ("


@pytest.fixture(scope="module")
def spectrum(tmp_path_factory):
    path = tmp_path_factory.mktemp("warnings") / "spec.dat"
    wave = np.linspace(1290.0, 1315.0, 501)
    np.savetxt(str(path), np.column_stack([wave, np.ones_like(wave), wave * 0 + 0.1]))
    return str(path)


def loaded(atomic, path, settings=(), extra=""):
    """The model loaded as ``ClassMain`` loads it, its sub-pixels worked out."""
    st = SimpleNamespace(_atomic=atomic, _argflag=ArgFlag())
    st._argflag["out"]["verbose"] = -1
    # nsubpixel_min as before Task 14.6 (5), so that the line sets the sub-pixels
    load.set_params(["run nsubpixel_min 5"] + list(settings), st._argflag)
    st._funcarray = build_funcarray(st._argflag, atomic)
    line = "  {0} specid=0 fitrange=[1300.0,1305.0] resolution=vfwhm(30.0)".format(path)
    load.load_data(st, [line + " columns=[wave,flux,error] " + extra + "\n"])
    st._modpass = load.load_model(st, MODEL)
    st._links = load.load_links(st, [])
    _, st._levadd = load.load_parinfo(st)
    st._nsubpixel = load.load_subpixels(st, st._modpass["p0"], warn=True)[4]
    return st


def best_fit(state, b):
    """The best-fit values, with the voigt line's b as given."""
    params = np.array(state._modpass["p0"], dtype=float)
    params[list(params).index(10.0)] = b
    return params


def warned(logmsgs, text):
    return [m for m in logmsgs if text in m]


def test_a_best_fit_narrower_than_its_start_warns(atomic_data, spectrum, logmsgs):
    st = loaded(atomic_data, spectrum, ("run nsubpixel_max 50",))
    assert st._nsubpixel == [[9]]
    load.best_fit_subpixel_warnings(st, best_fit(st, 2.0))
    # Before Stage 14, nothing compared them
    (msg,) = warned(logmsgs, BEST)
    assert "Spectrum 0, segment 0: the fit used 9; its best fit asks for 41." in msg
    assert "nsubsigma (5)" in msg and "nsubpixel= removed" in msg


@pytest.mark.parametrize(
    "settings, b",
    [
        (("run nsubpixel_max 50",), 10.0),  # the best fit asks for what was used
        (("run nsubpixel_max 50",), 20.0),  # or for fewer
        (("run nsubpixel_max 50", "run nsubpixel_renew True"), 2.0),
        # nsubpixel_min already gives what 2 km/s asks for
        (("run nsubpixel_max 50", "run nsubpixel_min 41"), 2.0),
    ],
)
def test_a_best_fit_that_asks_for_no_more_does_not_warn(
    atomic_data, spectrum, logmsgs, settings, b
):
    st = loaded(atomic_data, spectrum, settings)
    load.best_fit_subpixel_warnings(st, best_fit(st, b))
    assert warned(logmsgs, BEST) == []


def test_lines_capped_by_nsubpixel_max_warn(atomic_data, spectrum, logmsgs):
    st = loaded(atomic_data, spectrum, ("run nsubpixel_max 6",))
    assert st._nsubpixel == [[6]]
    # Before Stage 14, ALIS capped them in silence
    (msg,) = warned(logmsgs, CAPPED)
    assert msg.startswith("nsubpixel_max (6) leaves 1 snip with too few sub-pixels")
    assert "Spectrum 0, segment 0: its lines ask for 9." in msg
    assert "Raise 'run nsubpixel_max' to 9" in msg


@pytest.mark.parametrize(
    "settings",
    [
        ("run nsubpixel_max 9",),  # the cap leaves them at nsubsigma
        ("run nsubpixel_max 6", "run nsubsigma 3"),
        (),
    ],
)
def test_a_cap_that_leaves_enough_does_not_warn(
    atomic_data, spectrum, logmsgs, settings
):
    loaded(atomic_data, spectrum, settings)
    assert warned(logmsgs, CAPPED) == []


def test_many_sub_pixels_never_warn(atomic_data, spectrum, logmsgs):
    st = loaded(
        atomic_data, spectrum, ("run nsubpixel_min 200", "run nsubpixel_max 300")
    )
    assert st._nsubpixel == [[200]]
    load.best_fit_subpixel_warnings(st, best_fit(st, 10.0))
    # Before Stage 14, warn_subpix warned of a snip on more than 100
    assert [m for m in logmsgs if "sub-pixel" in m.lower()] == []


@pytest.mark.parametrize(
    "settings, extra, text",
    [
        (("run nsubpixel_max 50",), "nsubpixel=3", "Too few sub-pixels are recorded"),
        (("run nsubpixel_max 6",), "", CAPPED),
        (("run nsubpixel_max 50",), "", BEST),
    ],
    ids=["recorded", "capped", "best"],
)
def test_each_part_of_a_warning_is_a_sentence(
    atomic_data, spectrum, logmsgs, settings, extra, text
):
    # RJC's review of Stage 14 (Q14.11's response): the dashboard shows a warning on
    # one line, so each of its parts ends with a full stop, and each snip's line
    # begins with a capital; before, "its lines ask for 8 Remove nsubpixel= …"
    st = loaded(atomic_data, spectrum, settings, extra)
    if text == BEST:
        load.best_fit_subpixel_warnings(st, best_fit(st, 2.0))
    (msg,) = warned(logmsgs, text)
    parts = [ln.strip() for ln in msg.splitlines()]
    assert len(parts) == 3 and all(part.endswith(".") for part in parts), parts
    assert parts[1].startswith("Spectrum 0, segment 0: ")


@pytest.mark.parametrize(
    "levels, said",
    [([[5, 5]], "nsubsigma (5)"), ([[5], [10]], "its snip's nsubsigma")],
)
def test_a_warning_names_the_level_of_its_snips(levels, said):
    # Q14.12: the level is each snip's nsubsigma, named where the snips share one
    state = SimpleNamespace(_datopt={"nsubsigma": levels})
    snips = [(sp, sn) for sp, row in enumerate(levels) for sn in range(len(row))]
    assert load._nsubsigma_text(state, snips) == said
