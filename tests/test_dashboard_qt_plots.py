def test_j1358_draws_in_under_half_a_second(qtbot):
    if not J1358.exists():
        pytest.skip("J1358p6522's spectrum is not present")
    table = np.loadtxt(str(J1358))
    assert table.shape[0] == 40402
    widget = PL.SpectrumView()
    qtbot.addWidget(widget)
    widget.resize(1030, 310)
    widget.show()
    qtbot.waitExposed(widget)
    start = time.perf_counter()
    widget.set_data(table[:, 0], table[:, 1], table[:, 2])
    widget.home()
    widget.grab()
    took = time.perf_counter() - start
    assert took < 0.5, took
    # The gap of its source (4535-5593 Å) is not bridged
    item = widget._items["data"]
    assert np.isnan(item.xData).sum() >= 1


