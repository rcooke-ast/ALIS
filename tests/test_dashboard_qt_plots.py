class FakeDrag:
    """A finished drag across the view, from one wavelength to another."""

    def __init__(self, box, button, start, end):
        from qtpy import QtCore

        self.box = box
        self._button = button
        y = 0.5 * sum(box.viewRange()[1])
        self._start = box.mapViewToScene(QtCore.QPointF(start, y))
        self._end = box.mapViewToScene(QtCore.QPointF(end, y))

    def button(self):
        return self._button

    def buttonDownScenePos(self):
        return self._start

    def scenePos(self):
        return self._end

    def isFinish(self):
        return True

    def accept(self):
        pass


