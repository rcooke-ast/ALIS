def test_each_snip_about_the_transition_it_was_cut_for(j1358):
    system = j1358.systems[0]
    panels = FV.panels(j1358, FV.choices(j1358)[0])
    assert len(panels) == 12
    for panel in panels:
        assert panel.velocity and panel.centre is not None
        own = panel.transition
        assert panel.centre == pytest.approx(own.rest * (1.0 + system.z))
        # Zero velocity at the transition, in the model's frame
        x = panel.x(panel.snip.pixels.wave)
        assert np.nanmin(x) < 0.0 < np.nanmax(x)
        assert panel.home() == (
            pytest.approx(np.nanmin(x)),
            pytest.approx(np.nanmax(x)),
        )
    first = panels[0]
    assert first.title == "Ly8 923.2 · H1" and first.ion == "1H_I"
    # Ly9 inside the Ly8 snip echoes the components
    assert first.transition.others
    # In wavelength: the pixels as they are
    wave = FV.panels(j1358, FV.choices(j1358)[0], FV.WAVELENGTH)[0]
    assert not wave.velocity
    assert np.array_equal(wave.x(first.snip.pixels.wave), first.snip.pixels.wave)
    for (lo, hi), (low, high) in zip(wave.regions(), first.regions()):
        moved = C_KMS * (np.array([lo, hi]) / first.centre - 1.0)
        assert (low, high) == (pytest.approx(moved[0]), pytest.approx(moved[1]))


