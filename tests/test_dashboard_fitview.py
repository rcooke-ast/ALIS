# -- The progress, the status bar and the marker (D38, F6, F12) -------------------------


def job(**fields):
    base = dict(
        progress=[[1, 4002.7], [2, 3900.0]],
        finished=False,
        started=100.0,
        stopping=False,
        iteration=2,
        chi2=3900.04,
        convtest=False,
        process=SimpleNamespace(storing=False),
    )
    base.update(fields)
    return SimpleNamespace(**base)


def test_the_progress_of_a_run_against_the_latest(metal):
    going = FV.progress(metal, job())
    assert going.current == [[1, 4002.7], [2, 3900.0]]
    assert going.previous == [[1, 476.0], [2, 415.0], [7, 357.874162]]
    assert going.name == "the fit in progress" and "Grey" in going.note
    idle = FV.progress(metal)
    assert idle.current == going.previous and idle.previous == []
    assert idle.name == "the latest run"
    # A committed run before it, in grey
    R.commit(metal.bundle, "first")
    store_run(metal, METAL, chi2_final=357.9, dof=360, iterations=7)
    idle = FV.progress(metal)
    assert idle.previous[-1] == [7, 357.874162] and idle.note.endswith("run 1.")
    # A run made on the command line: only its end is known
    assert idle.current == [[7, 357.9]]
    assert idle.note.startswith("Only the end")
    assert FV.progress(imported(METAL, metal.registry)).note == "No fit has run yet."


def test_the_status_bar_and_the_notice():
    assert (
        FV.status_text(job(), now=141.0) == "Running · iteration 2 · χ² 3900.0 · 0:41"
    )
    assert FV.status_text(job(iteration=None), now=103.0) == "Running · starting · 0:03"
    assert FV.status_text(job(stopping=True), now=3700.0) == (
        "Stopping the fit at the end of iteration 2… · 1:00:00"
    )
    stored = job(process=SimpleNamespace(storing=True))
    assert FV.status_text(stored, now=110.0).startswith("Storing the result")
    assert FV.status_text(job(convtest=True), now=100.0).startswith(
        "Convergence check · iteration 2"
    )
    assert FV.marker_text(job()) == "Running: iteration 2."
    assert FV.notice_text(job()) == (
        "The fit in progress: the model is redrawn after each iteration (iteration"
        " 2, χ² 3900.0)"
    )
    assert FV.clock(59) == "0:59" and FV.clock(3601) == "1:00:01"


