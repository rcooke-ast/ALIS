def test_initials_chips_are_the_starting_models_marks(metal):
    # The marks of the model the panels draw (RJC's review of Task 6.5)
    nsig = float(metal.parsed.argflag["out"]["reportsig"])
    start = PR.of(metal).evaluate()
    [chip] = FV.chips(metal, RS.View.latest(metal), initial=True)
    assert chip.quality == RS.quality(start[metal.snips[0].data.index], nsig)
    [final] = FV.chips(metal, RS.View.latest(metal))
    assert final.quality != chip.quality
    # With no run, Initial still has its marks
    [alone] = FV.chips(imported(METAL, metal.registry), initial=True)
    assert alone.quality is not None and alone.note == ""


