def test_nothing_shown_names_a_hidden_value(blinded):
    view = RS.View.latest(blinded)
    assert view.has_best_fit
    bad = set()
    for value in best_values(blinded).values():
        bad |= renderings(value)
    for par in blinded.parsed.params:
        if BL.Gate(blinded).is_hidden(par):
            bad |= renderings(par.start)
    shown = []
    for choice in FV.choices(blinded):
        shown.append(choice.title)
        for panel in FV.panels(blinded, choice):
            shown.append(panel.title)
            for tick in FV.ticks(blinded, panel) + FV.ticks(blinded, panel, view):
                shown.append(tick["label"])
    for chip in FV.chips(blinded, view):
        shown += [chip.title, chip.note] + [t for t, _ in FV.mark_texts(chip.quality)]
    shown += [FV.status_text(job()), FV.notice_text(job())]
    words = set(re.findall(r"\d[\d.]*", " ".join(shown)))
    assert not [b for b in bad if b in words and b not in ("0.0",)]
