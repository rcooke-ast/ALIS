# What no file of the site may name (documentation_stage0.md, "How the pages are
# written"). "dashboard" is allowed inside a path or a name of the code
# (alis/dashboard/, alis.dashboard, scripts/dashboard.py), never as a word.
LEFT_OUT = {
    "prepfit": re.compile(r"prepfit", re.IGNORECASE),
    "the v1.0 manual": re.compile(
        r"alis_v1p0|alis_userguide|tex_files|v1\.0 manual", re.IGNORECASE
    ),
    "context/": re.compile(r"\bcontext/"),
    "dashboard": re.compile(r"(?<![\w/.])dashboard(?![\w/]|\.\w)", re.IGNORECASE),
    "RJC": re.compile(r"\bRJC\b"),
}
# The site's text files; images (doc/source/_static/, from Stage 2) are not read
TEXT_SUFFIXES = {".md", ".py", ".txt", ".css", ".js", ".html", ".yaml", ".cff"}


def page_path(address):
    """The Markdown file of a page."""
    return SOURCE / (address + ".md")


def site_files():
    """Every text file of the site's sources, outside a build, and CITATION.cff."""
    found = sorted(
        path
        for path in SOURCE.rglob("*")
        if path.is_file()
        and path.suffix in TEXT_SUFFIXES
        and "_build" not in path.parts
        and "__pycache__" not in path.parts
    )
    return found + [CITATION]


def load_lexers():
    """The site's lexers (doc/source/_ext/alis_lexers.py), which need Pygments."""
    pytest.importorskip("pygments")
    spec = importlib.util.spec_from_file_location(
        "alis_lexers", SOURCE / "_ext" / "alis_lexers.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_each_page_is_listed_once():
    assert len(PAGES) == len(set(PAGES))


def test_every_page_of_the_outline_exists():
    missing = [address for address in PAGES if not page_path(address).is_file()]
    assert not missing, "pages of PAGES with no file: {0}".format(missing)


def test_no_page_is_missing_from_the_outline():
    found = {
        path.relative_to(SOURCE).with_suffix("").as_posix()
        for path in SOURCE.rglob("*.md")
        if "_build" not in path.parts
    }
    extra = sorted(found - set(PAGES))
    assert not extra, "pages that PAGES does not list: {0}".format(extra)


@pytest.mark.parametrize("address", PAGES)
def test_every_page_has_its_title_and_its_sources(address):
    text = page_path(address).read_text(encoding="utf-8")
    assert text.startswith("# "), "the first line is not the page's title"
    assert re.search(r"^% Sources: \S", text, re.MULTILINE), "no % Sources: comment"


@pytest.mark.parametrize("what", sorted(LEFT_OUT))
def test_no_file_of_the_site_names_what_it_leaves_out(what):
    pattern = LEFT_OUT[what]
    found = []
    for path in site_files():
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines()):
            if pattern.search(line):
                found.append("{0}:{1}".format(path.relative_to(ROOT), number + 1))
    assert not found, "{0} is named in {1}".format(what, found)


def test_about_alis_cites_the_paper_citation_cff_gives():
    yaml = pytest.importorskip("yaml")
    paper = yaml.safe_load(CITATION.read_text(encoding="utf-8"))["preferred-citation"]
    about = ABOUT.read_text(encoding="utf-8")
    authors = paper["authors"]
    cited = "{0} et al. ({1}), ApJ, {2}, {3}".format(
        authors[0]["family-names"], paper["year"], paper["volume"], paper["start"]
    )
    assert paper["journal"] == "The Astrophysical Journal"
    assert cited in about, "About ALIS does not cite {0}".format(cited)
    assert "https://doi.org/" + paper["doi"] in about, "About ALIS lacks the DOI"


def test_the_lexers_have_the_names_the_pages_use():
    lexers = load_lexers()
    assert lexers.AlisLexer.aliases == ["alis"]
    assert lexers.AlisMessageLexer.aliases == ["alis-message"]


def test_the_alis_lexer_reads_every_example_model():
    lexers = load_lexers()
    from pygments.token import Error

    lexer = lexers.AlisLexer()
    models = sorted((ROOT / "examples").rglob("*.mod"))
    assert models, "no example models found"
    bad = {}
    for model in models:
        text = model.read_text(encoding="utf-8")
        errors = [value for token, value in lexer.get_tokens(text) if token in Error]
        if errors:
            bad[str(model.relative_to(ROOT))] = errors[:5]
    assert not bad, "error tokens: {0}".format(bad)
