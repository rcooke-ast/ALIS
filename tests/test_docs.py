"""
The documentation's checks that need no Sphinx (Documentation Stage 1).

``PAGES`` is the one list of the site's pages, by address (a page's path under
``doc/source/``, without ``.md``; on the site, with ``.html``). An address never
changes once Documentation Stage 1 closes: the GUI's Help link and other sites
point at them. CI's ``docs`` job builds the site with no warning; these tests check
what the build cannot:

- every page of ``PAGES`` exists, and no page is missing from it;
- every page has its title and lists its sources, for whoever updates it;
- no file of the site, nor ``CITATION.cff``, names what the site leaves out
  (``prepfit``, the v1.0 manual, ``context/``), or says "dashboard" or "RJC" where
  a user reads it;
- About ALIS and ``CITATION.cff`` cite the same paper;
- the ``alis`` lexer reads every example model with no error token.

Generated by Ryan Cooke and Claude.
"""

import importlib.util
import re
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "doc" / "source"
CITATION = ROOT / "CITATION.cff"
ABOUT = SOURCE / "user" / "about.md"

# Every page of the site, in the order of its sidebar (documentation_stage1.md)
