# -- Writing back, and typing over a mask ------------------------------------------


def test_a_hidden_line_is_hidden_again_when_written_back(blind_project, tmp_path):
    project = blind_project
    path = tmp_path / "blind.model"
    project.save(str(path))
    with zipfile.ZipFile(path) as zfil:
        for name in zfil.namelist():
            assert b"13.4729" not in zfil.read(name), name
    again = B.read(str(path))
    num = voigt(project.parsed, "28Si_II").line
    assert again.model_text().splitlines()[num].strip() == "<hidden:1>"
    assert "13.4729" in again.model_text(restore=True).splitlines()[num]
    reopened = P.Project(again, project.registry)
    assert reopened.text == project.text


def test_typing_over_a_mask_stores_the_value_hidden(blind_project):
    project = blind_project
    gate = BL.Gate(project)
    view = gate.view()
    num = voigt(project.parsed, "28Si_II").line
    line_start = sum(len(t) + 1 for t in view.text.split("\n")[:num])
    col = view.text.split("\n")[num].index(BL.MASK)
    start = line_start + col
    change = view.to_real(start, start + len(BL.MASK), "13.61")
    step = project.edit(change)
    silicon = voigt(project.parsed, "28Si_II")
    assert silicon.param("ColDens").value == 13.61
    assert step.text.patches[0].old == "13.4729"
    gate = BL.Gate(project)
    assert "13.61" not in gate.view().text
    assert gate.view().text.count(BL.MASK) == view.text.count(BL.MASK)
    # Deleting part of a mask, with nothing typed, changes nothing
    assert not gate.view().to_real(start + 1, start + 2, "")
    # An edit outside the masks lands in the right place of the real text
    view = gate.view()
    first = view.text.index("specid=0", view.text.index(BL.MASK))
    change = view.to_real(first, first + len("specid=0"), "specid=0")
    assert change.patches[0].old == "specid=0"
    real = project.text
    assert real[change.patches[0].start : change.patches[0].end] == "specid=0"


