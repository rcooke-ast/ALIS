def test_global_blind_hides_best_fit_values_only(registry):
    project = P.Project.import_model(str(METAL), registry=registry)
    blind = [s for s in project.parsed.settings if s.key == "blind"][0]
    project.edit(
        T.Change((T.replace_token(project.parsed.text, blind.tokens[2], "True"),))
    )
    gate = BL.Gate(project)
    assert gate.global_blind
    nval = voigt(project.parsed, "16O_I").param("ColDens")
    assert gate.value(nval) == "14"
    assert gate.best_fit(nval, 14.2) == BL.MASK
    assert gate.error(nval, 0.05) == "0.05"
    assert gate.chi2_change(-3.25) == "-3.25"
    assert gate.sigma_change(nval, 0.1, 0.05) == "2.0σ"


