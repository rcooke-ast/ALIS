def renderings(value, written=None):
    """The ways a value could be written on the screen."""
    out = {repr(value), "{0:.10g}".format(value)}
    for digits in range(3, 9):
        out.add("{0:.{1}g}".format(value, digits))
        out.add("{0:.{1}f}".format(value, digits - 1))
    if written:
        out.add(written)
    out = {r.lstrip("-+") for r in out}
    # Keep those precise enough to be the value, not a coincidence
    return {r for r in out if len(re.sub(r"[^0-9]", "", r).strip("0")) >= 3}


def forbidden(project, gate):
    """The renderings of every hidden value that no visible value shares."""
    hidden, visible = set(), set()
    for par in project.parsed.params:
        written = par.value_token.text if par.value_token is not None else None
        forms = renderings(par.start, written) | renderings(par.value, written)
        (hidden if gate.is_hidden(par) else visible).update(forms)
    for comp in project.components:
        zpar = comp.main.param("redshift")
        forms = renderings(comp.velocity)
        (hidden if gate.is_hidden(zpar) else visible).update(forms)
    return hidden - visible


def leaks(strings, bad):
    found = []
    for text in strings:
        for word in re.findall(r"[-+]?\d[\d.]*(?:[eE][-+]?\d+)?", text):
            if word.lstrip("-+") in bad:
                found.append((word, text[:120]))
    return found


# -- No hidden value in any string -------------------------------------------------


def test_examples_blind_shows_no_hidden_value(blind_project):
    project = blind_project
    gate = BL.Gate(project)
    silicon = voigt(project.parsed, "28Si_II")
    assert gate.is_hidden(silicon.param("ColDens"))
    assert gate.is_hidden(silicon.param("redshift"))
    # 'da' and 'TA' are set on the O I line, which is not hidden
    assert not gate.is_hidden(voigt(project.parsed, "16O_I").param("bturb"))
    bad = forbidden(project, gate)
    assert {"13.4729", "0.000173"} <= bad
    assert any(r.startswith("51.86") for r in bad)  # Si II's velocity
    strings = BL.strings(project, gate, V.check(project))
    assert leaks(strings, bad) == []
    # Not vacuous: what is not hidden is shown
    text = "\n".join(strings)
    assert "14.0" in text and "1301.0" in text and BL.MASK in text
    # On the hidden line every value is masked; O I's tied b stays shown
    view = gate.view().text.splitlines()
    assert BL.MASK + "da" in view[silicon.line]
    assert "1.0da" in view[voigt(project.parsed, "16O_I").line]


