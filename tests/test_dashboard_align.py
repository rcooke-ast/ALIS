"""Lining the model's values up in columns (dashboard Stage 3, RJC's review, Q3.17).

Aligning changes only the spaces between words: every model reads the same, word for
word and as ALIS reads it, and aligning twice changes nothing more. In J1358p6522
every column density starts in one column, every redshift in the next, and every
``specid=`` of the Legendre continua in one column. It is one undoable step, which
keeps hidden values hidden.

Generated by RJC and Claude.
"""

import re
from pathlib import Path

import pytest

from alis import bundle as B
from alis.dashboard import align as AL
from alis.dashboard import blinding as BL
from alis.dashboard import model as M
from alis.dashboard import project as P
from alis.dashboard import text as T

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
BLIND = ROOT / "examples/blind/model/fit_spectra.mod"


def model_files():
    found = []
    for folder in ("examples", "context/fitting_examples"):
        base = ROOT / folder
        if base.is_dir():
            found += sorted(base.rglob("*.mod"))
            found += sorted(base.rglob("*.mod.out.reference"))
    return found


MODELS = model_files()
EXAMPLES = [p for p in MODELS if "examples" == p.relative_to(ROOT).parts[0]]


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.mark.parametrize("path", MODELS, ids=[str(p.relative_to(ROOT)) for p in MODELS])
def test_aligning_changes_only_spaces_and_twice_is_once(path):
    text = path.read_text(encoding="utf-8")
    once = AL.aligned(text)
    assert AL.aligned(once) == once
    before, after = text.splitlines(), once.splitlines()
    assert len(before) == len(after)
    for old, new in zip(before, after):
        assert old.split() == new.split()
    # Line endings are kept
    assert text.count("\n") == once.count("\n")


@pytest.mark.parametrize(
    "path", EXAMPLES, ids=[str(p.relative_to(ROOT)) for p in EXAMPLES]
)
def test_alis_reads_an_aligned_model_the_same(path, registry):
    text = path.read_text(encoding="utf-8")
    before = M.ParsedModel(text, registry)
    after = M.ParsedModel(AL.aligned(text), registry)
    assert before.ok == after.ok
    assert [(s.category, s.key, s.value) for s in before.settings] == [
        (s.category, s.key, s.value) for s in after.settings
    ]
    assert [(d.file.text, d.specid, d.fitrange) for d in before.data] == [
        (d.file.text, d.specid, d.fitrange) for d in after.data
    ]
    assert [(p.name, p.value, p.label, p.fixed) for p in before.params] == [
        (p.name, p.value, p.label, p.fixed) for p in after.params
    ]


def columns_of(lines, word):
    """The column where each line's ``word``-th word starts."""
    out = []
    for line in lines:
        starts = [m.start() for m in re.finditer(r"\S+", line)]
        out.append(starts[word])
    return out


def test_j1358p6522_lines_up(registry):
    if not J1358.exists():
        pytest.skip("J1358p6522 is not present")
    lines = AL.aligned(J1358.read_text()).splitlines()
    voigt = [ln for ln in lines if ln.strip().startswith("voigt ")]
    assert len(voigt) > 50
    # Column densities, redshifts, b and T: each in one column
    for word in (2, 3, 4, 5):
        assert len(set(columns_of(voigt, word))) == 1
    legendre = [ln for ln in lines if ln.strip().startswith("legendre ")]
    specid = [ln.index("specid=") for ln in legendre]
    assert len(set(specid)) == 1
    settings = [ln for ln in lines[:23] if ln and not ln.startswith("#")]
    assert len(set(columns_of(settings, 2))) == 1


def test_keywords_line_up_by_name():
    text = (
        "model read\n"
        " absorption\n"
        "  voigt ion=1H_I 15.0 2.0 10.0 0.0 specid=A blind=False\n"
        "  voigt ion=16O_I 13.25 2.0 5.0 0.0 blind=True\n"
        "  # voigt ion=12C_II 1 2 3 4\n"
        "  voigt ion=28Si_II 12.5 2.0001 5.0 0.0 specid=A,B  # a note\n"
        "model end\n"
    )
    lines = AL.aligned(text).splitlines()
    assert lines[2].index("blind=") == lines[3].index("blind=")
    assert lines[2].index("specid=") == lines[5].index("specid=")
    # The comment line inside the group is kept; so is the trailing comment
    assert lines[4] == "  # voigt ion=12C_II 1 2 3 4"
    assert lines[5].endswith("specid=A,B  # a note")
    # The values line up too: the column densities start together
    assert lines[2].index("15.0") == lines[3].index("13.25") == lines[5].index("12.5")


def test_groups():
    text = (
        "run ncpus 4\nchisq atol 0.01\n\ndata read\n a.dat specid=0\ndata end\n"
        "model read\n fix voigt temperature True\n emission\n  legendre 1.0 specid=0\n"
        " absorption\n  voigt ion=1H_I 15 2 10 0\n  constant 1.0\nmodel end\n"
    )
    groups = [[ln.num for ln in g] for g in AL.groups(T.ModelText(text))]
    assert groups == [[0, 1], [4], [7], [9], [11], [12]]


def test_align_is_one_step_that_keeps_hidden_values_hidden(registry):
    from alis.dashboard import history as H
    from alis.dashboard import markers as MK

    project = P.Project(B.pack(str(BLIND)), registry)
    history = H.History(project, guard=BL.Guard(project), tracker=MK.Tracker())
    original = project.text
    hidden = BL.Gate(project).hidden_values()
    history.edit(AL.align(project.parsed), "Align columns")
    assert project.text != original
    assert BL.Gate(project).hidden_values() == hidden
    view = BL.Gate(project).view().text
    si = next(ln for ln in view.splitlines() if "28Si_II" in ln)
    assert BL.MASK in si and "13.0" not in si
    assert history.can_undo()
    history.undo()
    assert project.text == original
    # Aligned already: nothing to do
    once = AL.aligned(original)
    assert not AL.align(T.ModelText(once))
