def test_hidden_values_are_written_as_blind(tmp_path, registry):
    # RJC's response to Q7.16: blind parameters and blind models stay hidden
    session = blinded_session(tmp_path, registry)
    project = session.project
    view = RS.View.latest(project)
    assert X.best_fit_reason(project, view) == "" and X.blinded(project, view)
    folder = tmp_path / "out"
    planned, notes = X.plan(session, X.Choice(folder=str(folder)), view)
    assert notes == [X.HIDDEN.format("fit_spectra")]
    start = planned[str(folder / "fit_spectra_start.mod")].decode()
    best = planned[str(folder / "fit_spectra_bestfit.mod.out")].decode()
    (si,) = [ln for ln in start.splitlines() if "ion=28Si_II" in ln]
    assert si.split()[2:6] == ["BLIND", "BLIND", "BLINDda", "BLINDTA"]
    # The best fit: Si II's values, O I's offset ones and the seed, and the input
    # model's copy of Si II
    live = [ln for ln in best.splitlines() if ln.startswith("  voigt")]
    for line in live:
        assert line.split()[2:6] == ["BLIND", "BLIND", "BLINDda", "BLINDTA"]
    assert "blindseed=1234" not in best and "1000000.0" not in best
    (copy,) = [
        ln for ln in best.splitlines() if ln.startswith("#       voigt   ion=28")
    ]
    assert "13.0" not in copy and "BLIND" in copy
    # No masked best-fit value is left, as ALIS wrote it (zeros aside)
    original = view.record.mod_out()
    masked = {p.index for p in view.model.parsed.params if view.gate.masked(p)}
    pm = M.ParsedModel(T.ModelText(original), project.registry)
    words = {
        p.value_token.text
        for p in pm.params
        if p.index in masked and p.value_token is not None
    }
    words = {w for w in words if abs(float(w)) >= 1.0}
    assert len(words) >= 4
    for word in words:
        assert word not in best
    # Everything run_alis needs: masked the same way
    written, notes = X.everything(session, str(folder / "all"))
    assert X.HIDDEN.format("fit_spectra") in notes
    texts = {os.path.basename(w): Path(w).read_text() for w in written if "mod" in w}
    assert "ion=28Si_II BLIND" in " ".join(texts["fit_spectra.mod"].split())
    assert "blindseed=1234" not in texts["fit_spectra.mod.out"]
    assert "plain text" not in " ".join(notes)


