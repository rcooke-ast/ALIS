def blinded_session(tmp_path, registry):
    """metal_line_abs blinded as examples/blind is, with a run as a bundle keeps one:
    O I offset by its blindrange, Si II with blind=True and its real best fit."""
    session = imported(METAL, tmp_path, registry)
    project = session.project
    text = project.text.replace(
        "8000TA   specid=0\n    voigt   ion=28Si_II",
        "8000TA   specid=0   blind=False   blindseed=1234"
        "  blindrange=-1000000.0,1000000.0\n    voigt   ion=28Si_II",
    )
    text = text.replace(
        "8000TA   specid=0\nmodel end", "8000TA   specid=0   blind=True\nmodel end"
    )
    project.apply(project.step(T.Change((T.Patch(0, project.text, text),))))
