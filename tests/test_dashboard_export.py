def test_run_alis_extract_writes_hidden_values_as_blind(tmp_path, monkeypatch):
    # RJC's Prompt 6: run_alis --extract does what Everything run_alis needs does
    from alis import bundle as B
    from alis.scripts import run_alis

    path = tmp_path / "blind.model"
    B.pack_to(str(BLIND), str(path))
    monkeypatch.chdir(tmp_path)
    run_alis.main(run_alis.parser(["--extract", str(path), str(tmp_path / "out")]))
    words = " ".join((tmp_path / "out" / "model" / BLIND.name).read_text().split())
    assert "ion=28Si_II BLIND BLIND BLINDda BLINDTA" in words
    assert "ion=28Si_II 13.0" not in words and "blindseed=1234" not in words
    # Nothing hidden: written byte for byte, as before
    plain = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(plain))
    run_alis.main(run_alis.parser(["--extract", str(plain), str(tmp_path / "m")]))
    written = (tmp_path / "m" / "model" / METAL.name).read_bytes()
    assert written == METAL.read_bytes()


@pytest.mark.fast
def test_run_alis_fits_an_exported_model(tmp_path, registry):
    session = imported(METAL, tmp_path, registry, run=True)
    view = RS.View.latest(session.project)
    folder = tmp_path / "out"
    planned, _ = X.plan(session, X.Choice(folder=str(folder)), view)
    X.write(planned)
    with pytest.raises(FileExistsError):
        X.write(planned)
    result = subprocess.run(
        [sys.executable, "-c", RUN_ALIS, "fit_spectra_start.mod"],
        cwd=folder,
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert result.returncode == 0, result.stderr[-2000:]
    assert (folder / "fit_spectra_start.mod.out").exists()
