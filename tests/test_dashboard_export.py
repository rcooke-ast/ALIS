def _lsf_project(tmp_path, registry):
    """
    ``examples/lsf_file`` fitted through its LSF file, imported: the LSF file goes
    into the project with the model (Stage 8, Task 8.7).

    Generated by RJC and Claude.
    """
    import shutil

    src = ROOT / "examples/lsf_file"
    for part in ("model", "data"):
        shutil.copytree(
            src / part,
            tmp_path / "lsf_file" / part,
            ignore=shutil.ignore_patterns("*.out", "*.reference", "reference_fits"),
        )
    model = tmp_path / "lsf_file/model/fit_spectra.mod"
    mod = model.parent / "fit_lsf.mod"
    text = model.read_text().replace(
        "resolution=Afwhm(0.1va)", "resolution=lsffile(name:test_lsf.dat)"
    )
    # lsffile works in km/s bins, ALIS's default (generate_spectra.mod's)
    mod.write_text(text.replace("run bintype A\n", ""))
    session = imported(mod, tmp_path, registry)
    assert "files/model/test_lsf.dat" in session.to_bundle().members
    return session


