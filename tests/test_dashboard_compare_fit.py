"""Compare two real fits (dashboard Stage 6.7; D41; Q6.9).

metal_line_abs is fitted through the dashboard's process with T fixed at 8000 K
(as written), committed, then fitted with T free, and with O I's column density in
linear form (``logN=False``, made here as ``fit_spectra_linear.mod`` writes it):

- the components are matched one for one, T "(fixed)" against its fit;
- log N(O I) agrees within its error whatever its form;
- σ is the larger of the two runs' errors, from their covariances.

Marked ``fast``: it runs three fits.

Generated by RJC and Claude.
"""

import re
from pathlib import Path

import pytest
from test_dashboard_compare import linear, t_free

from alis import bundle as B
from alis.dashboard import compare as CM
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import results as RS
from alis.dashboard import runs as R
from alis.dashboard import session as S
from alis.dashboard import settings as ST
from alis.dashboard import text as T

pytestmark = [pytest.mark.fast, pytest.mark.examples]

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def fit(session):
    prefs = PR.Preferences(session.folder)
    prefs.set("fit.ncpus", 1)
    job = R.Run(session, settings=ST.run_settings(session.project, prefs))
    job.start()
    assert job.wait(timeout=600) == R.COMPLETED, job.message
    job.take(session)


def edit(session, text):
    project = session.project
    session.history.do(
        project.step(T.Change((T.Patch(0, project.text, text),)), "Edit")
    )


def test_t_fixed_t_free_and_linear_n(tmp_path, monkeypatch, registry):
    monkeypatch.setenv(PR.HOME_ENV, str(tmp_path / "home"))
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    session = S.Session.open(str(path), registry=registry)
    project = session.project
    fit(session)
    assert R.commit(project.bundle, "T fixed") == 1
    fixed_text = project.text
    # T free
    edit(session, t_free(fixed_text))
    fit(session)
    first = RS.View(project, record=R.run_of(project.bundle, 1))
    second = RS.View.latest(project)
    assert first.covariance is not None and second.covariance is not None
    rows = CM.compare(first, second)
    named = {r.name: r for r in rows}
    temp = named["O I a1 T (K)"]
    assert temp.first == "8,000 (fixed)" and " ± " in temp.second
    assert not [r for r in rows if r.note.startswith("only in")]
    logn = named["log N(O I)"]
    assert logn.nsigma is not None and logn.nsigma < 1.0
    # σ is the larger of the two runs' errors
    errors = [
        float(re.search(r"± ([\d.]+)", t).group(1)) for t in (logn.first, logn.second)
    ]
    change = float(logn.delta.replace("−", "-"))
    assert logn.nsigma == pytest.approx(abs(change) / max(errors), abs=0.06)
    # O I's column density in linear form: the same log N(O I)
    edit(session, linear(fixed_text))
    fit(session)
    third = RS.View.latest(project)
    line = next(ln for ln in third.model.parsed.lines if ln.ion == "16O_I")
    assert str(line.keyword("logN")) == "False"
    named = {r.name: r for r in CM.compare(first, third)}
    logn = named["log N(O I)"]
    assert logn.nsigma is not None and logn.nsigma < 0.1
    assert logn.first.split(" ± ")[0] == logn.second.split(" ± ")[0]
    session.close()
