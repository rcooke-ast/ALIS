def test_the_runs_compared_by_default(window, qtbot, tmp_path):
    """The latest run against the newest committed run, or against the one before it
    when the latest run is committed (RJC's review)."""
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    wait_idle(qtbot, window)
    project = window.session.project
    for description in ("first", "second"):
        store_run(project, METAL, chi2_final=357.874162, dof=360)
        R.commit(project.bundle, description)
    window.session.runs_changed()
    compare = show_compare(window, qtbot)
    # The latest run is run 2: against run 1
    window.refresh()
    assert compare.chosen == (1, 2)
    # A newer run, not committed: against run 2
    store_run(project, METAL, chi2_final=356.0, dof=360)
    window.refresh()
    assert compare.chosen == (2, "latest")
