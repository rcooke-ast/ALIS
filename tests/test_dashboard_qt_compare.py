def show_compare(window, qtbot):
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(2)
    qtbot.wait(50)
    return window.fit_tab.compare


def j1358_two_runs(window, qtbot, blind=False):
    if not J1358.exists():
        pytest.skip("J1358p6522 is not present")
    window.import_path(str(J1358))
    wait_idle(qtbot, window, timeout=30000)
    project = window.session.project
    store_run(project, J1358, status="imported", started=None)
    R.commit(project.bundle, "D I's own column density")
    set_text(project, ratio_model(project.text))
    if blind:
        pm = project.parsed
        line = next(ln for ln in pm.function_lines("voigt") if ln.ion == "2H_I/1H_I")
        project.apply(project.step(E.set_blind(pm, pm.item_at(line.line)), "Blind"))
    store_run(project, J1358, mod_out=ratio_out(J1358_OUT.read_text()), covar=False)
    window.session.runs_changed()
    window.refresh()
    return show_compare(window, qtbot)


def test_two_parametrisations_of_d_i(window, qtbot):
    compare = j1358_two_runs(window, qtbot)
    # Run 1 against the latest run, by default
    assert compare.chosen == (1, "latest")
    assert compare.first_menu.currentText() == "Run 1 · D I's own column density"
    assert compare.second_menu.currentText() == "Latest run"
    rows = compare.shown_rows()
    assert rows[0] == ["Primary system"]
    dh = [r for r in rows if r[0] == "log D/H"]
    assert len(dh) == 1 and dh[0][1:5] == [
        "−4.595 ± 0.011",
        "−4.595 ± 0.011",
        "+0.000",
        "0.0σ",
    ]
    header = compare.tree.headerItem()
    assert [header.text(c) for c in range(5)] == [
        "Parameter",
        "Run 1",
        "Latest",
        "Δ (latest − run 1)",
        "|Δ|/σ",
    ]
    assert compare.restore_button.text() == "Restore the latest run's model…"
    # Both best fits on the same data, the second dashed, their difference below
    [widget] = compare.panel_widgets
    assert widget.view._items.get("model") is not None
    assert widget.view._items.get("model2") is not None
    assert widget.resid._item.getData()[0] is not None
    assert "largest difference" in widget.marks.text()
    # Swap
    compare.swap_button.click()
    assert compare.chosen == ("latest", 1)
    assert window.session.view["compare"] == {"first": "latest", "second": 1}
    assert compare.restore_button.text() == "Restore run 1's model…"
    # ‹ › step through the View menu (the Fit tab's keys)
    first = compare.view_menu.currentText()
    window.qactions["fit.next_view"].trigger()
    assert compare.view_menu.currentText() != first
    window.qactions["fit.previous_view"].trigger()
    assert compare.view_menu.currentText() == first
    assert not design_references(ui_strings(window))


def test_a_blinded_d_i_shows_only_its_change(window, qtbot):
    compare = j1358_two_runs(window, qtbot, blind=True)
    rows = {r[0]: r for r in compare.shown_rows() if len(r) > 1}
    dh = rows["log D/H"]
    assert dh[1] == dh[2] == dh[3] == BL.MASK
    assert re.fullmatch(r"\d+\.\dσ", dh[4]) and "blinded" in dh[5]
    project = window.session.project
    view = compare.views[1]
    line = next(ln for ln in view.model.parsed.lines if ln.ion == "2H_I/1H_I")
    hidden = renderings(view.values[line.param("ColDens").index])
    shown = set(re.findall(r"[\d.]+", " ".join(ui_strings(window))))
    assert not (hidden - {"4.6"}) & shown
    assert BL.Gate(project).global_blind is False


def test_restore_is_one_step(window, qtbot, tmp_path):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    wait_idle(qtbot, window)
    project = window.session.project
    store_run(project, METAL, chi2_final=357.874162, dof=360)
    R.commit(project.bundle, "T fixed")
    run_text = project.text
    files = dict(project.files)
    window.session.history.do(_t_free_step(project))
    store_run(project, METAL, chi2_final=355.0, dof=359)
    window.session.runs_changed()
    window.refresh()
    compare = show_compare(window, qtbot)
    compare.choose_runs("latest", 1)
    assert compare.restore_button.text() == "Restore run 1's model…"
    edited = project.text
    seen = []

    def answer(dialog):
        seen.append(dialog)
        assert isinstance(dialog, D.RestoreDialog)
        assert "+   fix voigt temperature True" in dialog.rows()
        return 1

    window.on_dialog = answer
    compare.restore_button.click()
    assert seen and project.text == run_text and project.files == files
    assert window.qactions["edit.undo"].text() == "Undo Restore the model of run 1"
    window.qactions["edit.undo"].trigger()
    assert project.text == edited


def _t_free_step(project):
    text = t_free(project.text)
    return project.step(T.Change((T.Patch(0, project.text, text),)), "T free")


