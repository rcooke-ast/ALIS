"""From a spectrum to a fit, through the dashboard (Stages 4.12, 5.10 and 6.10).

A new project from ``examples/metal_line_abs/data/OI_SiII.dat`` (z = 0, its fourth
column ignored, as the example's model reads it) is driven through the Data,
Regions and Components tabs: SNIP O I 1302 and Si II 1304, the fit region
1301–1305 Å drawn on each, the two snips merged, and the first-guess continuum; then
one click on O I 1302 adds one component with an O I and a Si II line, sharing z and
b (D20), and its temperature is fixed at 8000 K with "Fixed at…", as the example's
model has it. ALIS then fits the bundle, as ``run_alis project.model`` does, and the
column densities agree with the example's ``fit_spectra.mod.out.reference`` within
their errors. Then the same, its last steps on the Fit tab (Stage 6.10): Run, the
best fit agreeing with the reference, Commit…, T made free and Run again, Compare,
Continue from best fit, and Use best fit on the card.

Generated by RJC and Claude.
"""

