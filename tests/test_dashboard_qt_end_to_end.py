"""From a spectrum to a fit, through the dashboard (Stage 4.12).

A new project from ``examples/metal_line_abs/data/OI_SiII.dat`` (z = 0, its fourth
column ignored, as the example's model reads it) is driven through the Data and
Regions tabs: SNIP O I 1302 and Si II 1304, the fit region 1301–1305 Å drawn on
each, the two snips merged, and the first-guess continuum. The two absorption lines
are added by ``edit.add_ion`` (their panel is Stage 5's). ALIS then fits the bundle,
as ``run_alis project.model`` does, and the column densities agree with the
example's ``fit_spectra.mod.out.reference`` within their errors.

Generated by RJC and Claude.
"""

