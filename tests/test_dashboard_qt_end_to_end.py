def run_bundle(path):
    """Run a bundle in this process, as ``run_alis project.model`` does."""
    import matplotlib

    matplotlib.use("Agg")
    from alis.scripts.run_alis import parser

    args = parser([str(path), "-p", "0", "-c", "1", "--set", "run backend cpu"])
    overrides = []
    argflag = load.optarg(argv=args, overrides=overrides, verbose=-1)
    argflag["run"]["modname"] = args.alis_modfile
    B.run(str(path), argflag, overrides, command="test")


def column_densities(path):
    """Each ion's column density and its error, from a ``.mod.out``."""
    values, errors = parse_mod_out(path).sections["model"]
    out = {}
    for ion in IONS:
        value = next(v for v in values if "ion=" + ion + " " in v + " ")
        error = next(e for e in errors if "ion=" + ion + " " in e + " ")
        out[ion] = (float(value.split()[2]), float(error.split()[2]))
    return out


def show(tab, element, stage, name):
    if tab.state.get("element") != element:
        tab.element_box.setCurrentIndex(tab.element_box.findText(element))
    if tab.state.get("stage") != stage:
        tab.ion_box.setCurrentIndex(tab.ion_box.findText(stage))
    for num in range(tab.listing.topLevelItemCount()):
        item = tab.listing.topLevelItem(num)
        if item.text(1).startswith(name):
            tab.listing.setCurrentItem(item)
            return
    raise AssertionError("{0} is not listed".format(name))


def test_from_a_spectrum_to_a_fit(window, qtbot, tmp_path):
    path = tmp_path / "project.model"
    columns = {str(SPECTRUM): {"wave": 0, "flux": 1, "error": 2}}
    session, _ = S.Session.new(str(path), [str(SPECTRUM)], z=0.0, columns=columns)
    window.set_session(session)
    data = window.tab_widgets[0]
    assert data.table.item(0, 2).text().startswith("wave, flux, error")
    # The Regions tab: SNIP each transition, and draw the fit region on each
    window.tabs.setCurrentIndex(1)
    tab = window.tab_widgets[1]
    for element, stage, name in (("O", "I", "O I 1302"), ("Si", "II", "Si II 1304")):
        show(tab, element, stage, name)
        tab.actions_["regions.snip"].trigger()
        row = tab.strips[0].row_id
        tab._act("regions.draw", lambda: tab.draw(row, 1301.0, 1305.0))
    # The two snips fit the same pixels: they are merged into one
    assert not tab.shared_box.isHidden()
    window.on_dialog = lambda dialog: 1
    tab.merge_button.click()
    project = window.session.project
    assert len(project.snips) == 1 and SN.shared_pixels(project) == []
    snip = project.snips[0]
    low, high = SN.regions_of(snip)[0]
    assert len(SN.regions_of(snip)) == 1
    assert low == pytest.approx(1301.0, abs=0.02)
    assert high == pytest.approx(1305.0, abs=0.02)
    # The first-guess continuum
    tab.actions_["regions.auto"].trigger()
    assert window.session.project.snips[0].continuum is not None
    assert window.markers["Regions"].state == MK.COMPLETE
    # The Components tab: one click on O I 1302 adds one component, with an O I
    # and a Si II line sharing z and b (D20)
    window.tabs.setCurrentIndex(2)
    tab = window.tab_widgets[2]
    item = next(i for i in tab._ion_items() if i.text(0) == "O I")
    tab.tree.setCurrentItem(item)
    tab.actions_["components.add_component"].trigger()
    tab.panel_widgets[0].view.clicked.emit(0.0, 0.5)
    (comp,) = window.session.project.components
    assert comp.ions == list(IONS)
    for name in ("redshift", "bturb"):
        assert len({ln.param(name).label for ln in comp.lines}) == 1
    # Its temperature fixed at 8000 K, as the example's model has it
    window.on_dialog = lambda dialog: dialog.set("T", "8000") or 1
    menu = tab.card_widgets[comp.id].temp.menu()
    next(a for a in menu.actions() if a.text() == "Fixed at…").trigger()
    (comp,) = window.session.project.components
    assert comp.temperature_mode == ("fixed", 8000.0)
    assert window.markers["Components"].state == MK.COMPLETE
    window.refresh()
    wait_idle(qtbot, window)
    window.save()
    # ALIS fits it
    run_bundle(path)
    made = B.read(str(path))
    info = json.loads(made.members[B.LATEST + "run.json"])
    assert info["status"] == "completed"
    out = [m for m in made.members if m.startswith(B.LATEST) and m.endswith(".mod.out")]
    assert len(out) == 1
    (tmp_path / "fit.mod.out").write_bytes(made.members[out[0]])
    got = column_densities(tmp_path / "fit.mod.out")
    want = column_densities(REFERENCE)
    for ion in IONS:
        (n, dn), (n0, dn0) = got[ion], want[ion]
        assert abs(n - n0) < max(dn, dn0), (ion, got[ion], want[ion])
