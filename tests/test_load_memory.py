"""Loading the data of a model from memory (dashboard Stage 1.2).

A project bundle holds its snips inside a zip file, and ``run_alis project.model``
reads them without unpacking anything to disk. ``load_data`` therefore accepts a
mapping from each data file's path to that file's bytes. These tests load real
models both ways and require every loaded array to be identical, bit for bit.

Generated by RJC and Claude.
"""

import os
from pathlib import Path

import numpy as np
import pytest

from alis import load
from alis.config import ArgFlag
from alis.main import build_funcarray

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]

# The arrays load_data sets, one per specid (or one list of positions).
ARRAYS = [
    "_wavefull", "_fluxfull", "_fluefull", "_contfull", "_zerofull", "_systfull",
    "_wavefit", "_fluxfit", "_fluefit", "_contfit", "_zerofit",
]


class _State:
    """The attributes ``load_input`` and ``load_data`` read.

    Generated by RJC and Claude.
    """

    def __init__(self, atomic):
        self._argflag = ArgFlag()
        self._argflag["out"]["verbose"] = -1
        self._atomic = atomic
        self._funcarray = build_funcarray(self._argflag, atomic)


def _models():
    """Every shipped example that fits data, plus two context models.

    Generated by RJC and Claude.
    """
    found = sorted(ROOT.glob("examples/*/model/fit_spectra.mod"))
    for rel in ("context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod",
                "context/fitting_examples/DH/Q1243p307/model/"
                "Q1243p307_converge_newstart76.mod"):
        found.append(ROOT / rel)
    return found


def _load(model, atomic, data=None):
    """Read ``model`` and load its data, from disk or from ``data``.

    Generated by RJC and Claude.
    """
    slf = _State(atomic)
    _, datlines, _, _ = load.load_input(slf, filename=model.name)
    load.load_data(slf, datlines, data=data)
    return slf, datlines


@pytest.mark.parametrize("model", _models(), ids=lambda p: str(p.relative_to(ROOT)))
def test_data_loaded_from_memory_are_identical(model, atomic_data, monkeypatch):
    if not model.exists():
        pytest.skip("model not present: " + str(model))
    monkeypatch.chdir(model.parent)
    slf_disk, datlines = _load(model, atomic_data)
    paths = load.data_file_paths(datlines, slf_disk._argflag["run"]["datadirc"])
    if not all(os.path.exists(p) for p in paths):
        pytest.skip("data files not present")
    data = {}
    for path in paths:
        with open(path, "rb") as fil:
            data[path] = fil.read()
    slf_mem, _ = _load(model, atomic_data, data=data)
    assert slf_mem._snipnames == slf_disk._snipnames
    # data_file_paths resolves the names exactly as load_data does
    assert sorted(s for sp in slf_disk._snipnames for s in sp) == sorted(paths)
    assert slf_mem._posnfull == slf_disk._posnfull
    assert slf_mem._posnfit == slf_disk._posnfit
    for name in ARRAYS:
        for a, b in zip(getattr(slf_disk, name), getattr(slf_mem, name)):
            assert np.array_equal(a, b), name


def test_a_data_file_missing_from_memory_stops_with_its_name(
        atomic_data, monkeypatch, logmsgs):
    model = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
    monkeypatch.chdir(model.parent)
    slf = _State(atomic_data)
    _, datlines, _, _ = load.load_input(slf, filename=model.name)
    with pytest.raises(SystemExit):
        load.load_data(slf, datlines, data={"elsewhere.dat": b""})
    assert any("not among the data held in memory" in m for m in logmsgs)


def test_data_in_memory_cannot_be_generated(atomic_data, monkeypatch):
    model = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
    monkeypatch.chdir(model.parent)
    slf = _State(atomic_data)
    _, datlines, _, _ = load.load_input(slf, filename=model.name)
    slf._argflag["generate"]["data"] = True
    with pytest.raises(SystemExit):
        load.load_data(slf, datlines, data={})


def test_data_file_paths_follow_datadirc_and_skip_blank_lines():
    lines = ["  a.dat  specid=0\n", "\n", "  b.dat specid=1  # note\n"]
    assert load.data_file_paths(lines, "../data/") == ["../data/a.dat",
                                                       "../data/b.dat"]
