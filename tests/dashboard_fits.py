"""Synthetic fits of several spectra, for the dashboard's tests (Stage 11).

Copies of the metal example's spectrum with other noise in their flux, snips cut from
them as ``prepfit`` cuts them, and ``.mod`` files that name the snips. A snip cut from
one copy is not the other's: its wavelengths are, its flux is not.

Generated by RJC and Claude.
"""

from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SPECTRUM = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"
C_KMS = 299792.458
OI = ("16O_I", 1302.16849, "16O_I_1302.2")
SII = ("28Si_II", 1304.3702, "28Si_II_1304.4")
DATA_LINE = (
    "  ../data/{name}   specid={specid}   fitrange=columns"
    "   resolution=vfwhm({fwhm}{label})   columns=[wave,flux,error,fitrange]{extra}"
)


def noisy_copy(folder, name="other.dat", seed=1):
    """
    A second spectrum: the source's wavelengths and errors, with other noise in its
    flux.
    """
    table = np.loadtxt(str(SPECTRUM))[:, :3]
    table[:, 1] += np.random.default_rng(seed).normal(0.0, table[:, 2])
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / name
    np.savetxt(str(path), table)
    return path


def prepfit_snip(
    folder,
    source,
    trans,
    half=150.0,
    fit=(-40.0, 40.0),
    ncols=4,
    name=None,
    fmt="%.18e",
    centre=None,
):
    """
    A snip as ``prepfit`` writes it: the source's pixels within ±half km/s of a
    transition (z = 0), with a fit range over ``fit`` km/s.
    """
    table = np.loadtxt(str(source))
    rest = trans[1] if centre is None else centre
    vel = (table[:, 0] / rest - 1.0) * C_KMS
    keep = np.abs(vel) <= half
    regions = ((vel >= fit[0]) & (vel <= fit[1]))[keep].astype(float)
    cols = [table[keep, 0], table[keep, 1], table[keep, 2], regions][:ncols]
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / (name or "src_{0}_reg.dat".format(trans[2]))
    np.savetxt(str(path), np.column_stack(cols), fmt=fmt)
    return path


def write_mod(folder, snips, ions=(OI[0], SII[0]), name="old.mod"):
    """
    A ``.mod`` in ``folder/model`` naming snips in ``folder/data``.

    Parameters
    ----------
    snips : list of tuple
        ``(path, fwhm, label, extra)`` for each data line, its specid its place in
        the list: ``label`` is the resolution's label (one dataset per label, as an
        imported fit groups them), ``extra`` more words for the line.
    ions : tuple
        One component at z = 0 of each ion, in every snip.
    """
    lines = ["run blind False", "", "data read"]
    for num, (path, fwhm, label, extra) in enumerate(snips):
        lines.append(
            DATA_LINE.format(
                name=path.name,
                specid=num,
                fwhm=fwhm,
                label=label,
                extra="   " + extra if extra else "",
            )
        )
    specids = ",".join(str(n) for n in range(len(snips)))
    lines += ["data end", "", "model read", "  emission"]
    for num in range(len(snips)):
        lines.append(
            "    legendre 1.0   0.01   scale=[1.0,1.0]   specid={0}".format(num)
        )
    lines.append("  absorption")
    for ion in ions:
        lines.append(
            "    voigt   ion={0}   13.5   0.0za   5.0ba   0.0TA   specid={1}".format(
                ion, specids
            )
        )
    lines.append("model end")
    model = folder / "model"
    model.mkdir(parents=True, exist_ok=True)
    path = model / name
    path.write_text("\n".join(lines) + "\n")
    return path


def two_exposures(folder, shift=3.0):
    """
    An imported fit of two snips of O I 1302 in one dataset: cut from two copies of
    the spectrum with other noise, and sharing one resolution label (two exposures
    of one instrument, as an imported fit groups them). The second has a shift of
    its own, ``shift`` km/s.
    """
    data = folder / "data"
    one = noisy_copy(folder / "spectra", "exp1.dat", seed=1)
    two = noisy_copy(folder / "spectra", "exp2.dat", seed=2)
    snips = [
        prepfit_snip(data, one, OI, name="exp1_{0}_reg.dat".format(OI[2])),
        prepfit_snip(data, two, OI, name="exp2_{0}_reg.dat".format(OI[2])),
    ]
    return write_mod(
        folder,
        [
            (snips[0], "7.0", "VA", "label=vb"),
            (snips[1], "7.0", "VA", "label=vb   shift=vshift({0}vsx)".format(shift)),
        ],
        ions=(OI[0],),
    )


