def test_q1243_coverage_grid_matches_the_mockup(registry):
    project = P.Project.import_model(str(need(Q1243)), registry=registry)
    covs = [L.coverage_of_snips(r) for r in project.rows]
    assert [c.name for c in covs] == ["HIRES", "PROCHASKA", "KIRKMAN"]
    assert not any(c.source for c in covs)
    primary = next(s for s in project.systems if s.primary)
    grid = L.coverage_grid(project, primary, covs)
    assert len(grid) == 16
    assert [g.name for g in grid[:3]] == ["Ly8 923.2", "Ly7 926.2", "Ly6 930.7"]
    assert [g.rest for g in grid] == sorted(g.rest for g in grid)
    counts = [sum(g.cells[c.row] == L.SNIP for g in grid) for c in covs]
    assert counts == [16, 16, 12]
    # Without source spectra a cell is a snip or nothing (D12)
    assert {v for g in grid for v in g.cells.values()} == {L.SNIP, L.NONE}
    # The other systems' snips are theirs, not the primary's
    others = {t.system for t in L.snip_transitions(project).values()}
    assert len(others) == 5


