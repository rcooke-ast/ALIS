def test_gap_and_edge_flags_on_a_synthetic_spectrum():
    cov = synthetic(gap=(4040.0, 4050.0), bad=(4070.0, 4070.12))
    on, flags = L.place(4020.0, [cov])
    assert on and flags == ()
    # In the gap: no pixels at all
    assert L.place(4045.0, [cov]) == (False, ("gap",))
    # Beyond the data
    assert L.place(4200.0, [cov]) == (False, ("gap",))
    # 2 Å (150 km/s) from the blue end: closer than a snip's half-width
    assert L.place(4002.0, [cov]) == (True, ("edge",))
    # Near the gap's edge, too
    assert L.place(4038.0, [cov]) == (True, ("edge",))
    assert L.place(4038.0, [cov], half_width=100.0) == (True, ())
    # A run of three bad pixels does not split the data; a longer one would
    assert L.place(4070.06, [cov]) == (True, ())
    assert len(cov.runs) == 2


def test_bad_pixels_and_nonpositive_errors_are_not_data():
    wave = np.arange(4000.0, 4100.0, 0.05)
    error = np.full_like(wave, 0.1)
    error[(wave > 4040) & (wave < 4050)] = 0.0
    flux = np.ones_like(wave)
    flux[(wave > 4060) & (wave < 4062)] = np.nan
    bad = (wave > 4080) & (wave < 4090)
    cov = L.coverage_of_spectrum("r1", "x", modes.Spectrum(wave, flux, error, bad))
    assert L.place(4045.0, [cov]) == (False, ("gap",))
    assert L.place(4085.0, [cov]) == (False, ("gap",))
    assert len(cov.runs) == 4


