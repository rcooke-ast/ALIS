def test_line_ids_count_what_they_leave_out(j1358):
    project, _ = j1358
    ids, hidden = L.line_ids(project, 3740.0, 3800.0)
    assert ids and hidden > 0
    kinds = {i.kind for i in ids}
    assert kinds <= {L.HYDROGEN, L.METAL, L.OTHER}
    # The model's ions are labelled in full: every H I and O I line in the range
    hydrogen = [i for i in ids if i.ion == "1H_I"]
    assert {round(i.rest, 1) for i in hydrogen} >= {923.2, 926.2, 930.7}
    # The Lyman alpha forest is labelled as such
    assert any(i.label == "Lyα forest" and i.kind == L.OTHER for i in ids)
    every, none_left = L.line_ids(project, 3740.0, 3800.0, show_all=True)
    assert none_left == 0
    assert len(every) == len(ids) + hidden
    assert [i.observed for i in every] == sorted(i.observed for i in every)


