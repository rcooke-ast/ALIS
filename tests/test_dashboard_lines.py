def test_a_click_on_lybeta_offers_its_redshift(atom, j1358):
    _, cov = j1358
    click = 1025.7223 * (1.0 + Z_J1358)
    cands, first = L.identify(atom, click, cov.span[1])
    lyb = [c for c in cands if c.name == "Lyβ 1025.7"]
    assert len(lyb) == 1 and round(lyb[0].z, 5) == 3.06726
    # Only transitions that put the click at z >= 0
    assert all(c.z >= 0 for c in cands)
    # The first choice is the strongest line whose Lyα is within the data
    assert cands[first].name == "Lyα 1215.7"
    menus = L.candidate_menus(cands)
    assert list(menus)[0] == "H" and list(menus["H"]) == ["I"]
    assert menus["H"]["I"][0].name == "Lyα 1215.7"


def test_identify_skips_a_first_choice_beyond_the_data(atom):
    # Data that end at 2000 Å: Lyα at the z that a click at 1900 Å gives for C IV
    # (1548) is at 1492 Å, within reach; for Lyα itself z=0.56, Lyα at 1900 Å
    cands, first = L.identify(atom, 1900.0, data_max=1800.0)
    assert (1.0 + cands[first].z) * L.LYA <= 1800.0
