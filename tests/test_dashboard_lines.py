def synthetic(low=4000.0, high=4100.0, step=0.05, gap=None, bad=None):
    """A flat spectrum, perhaps with a gap (no pixels) or bad pixels."""
    wave = np.arange(low, high, step)
    if gap is not None:
        wave = wave[(wave < gap[0]) | (wave > gap[1])]
    flux = np.ones_like(wave)
    error = np.full_like(wave, 0.1)
    mask = None
    if bad is not None:
        mask = (wave >= bad[0]) & (wave <= bad[1])
    spec = modes.Spectrum(wave, flux, error, mask)
    return L.coverage_of_spectrum("r1", "synthetic", spec)


