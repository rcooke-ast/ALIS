"""The continuum: evaluated as ALIS does, first guess, order, knots, sharing.

Dashboard Stage 4.3 (S8, S9, S10, D17; Q4.6, Q4.7, Q4.8, Q4.13, Q4.16). The curve the
dashboard draws must equal ALIS's own evaluation, to 1e-12, for every emission line
of the ``examples/`` models. On synthetic data the first guess recovers a known
polynomial under absorption lines, and the BIC picks its order; a refit passes
through every knot; a shared continuum reads in ALIS with its ``min=``/``max=``.

Generated by RJC and Claude.
"""

