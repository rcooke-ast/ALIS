"""prepfit is deprecated (dashboard Stage 6.11, Q6.13(b), D4): it keeps working, and
says once that the dashboard (``alis``) now covers its features.

Generated by RJC and Claude.
"""

import os
import subprocess
import sys

import pytest

pytestmark = pytest.mark.unit


def test_prepfit_says_once_that_the_dashboard_covers_it():
    # In a process of its own: importing prepfit chooses matplotlib's Qt backend
    code = (
        "from alis.prepfit import specplot\n"
        "print(specplot.note_deprecated(), specplot.note_deprecated())\n"
        "print(hasattr(specplot, 'SelectRegions'))\n"
    )
    env = dict(os.environ, QT_QPA_PLATFORM="offscreen")
    out = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, env=env
    )
    if out.returncode != 0 and "Qt" in out.stderr:
        pytest.skip("matplotlib's Qt backend is not available")
    assert out.returncode == 0, out.stderr[-2000:]
    assert out.stdout.splitlines()[-2:] == ["True False", "True"]
    said = out.stdout + out.stderr
    assert said.count("prepfit is deprecated") == 1
    assert "`alis`" in said and "keeps working" in said
