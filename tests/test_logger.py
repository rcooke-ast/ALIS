"""Unit tests for verbosity gating in ``alis.logger``.

Verifies that ``set_verbosity`` maps the ALIS 0/1/2 verbosity to the right
console level and that the ``msgs`` bands (info / warn / work / error) are
emitted or suppressed accordingly. ``error`` must still terminate (SystemExit)
and always be reported.

Generated by RJC and Claude.
"""

import logging

import pytest

from alis import logger

pytestmark = pytest.mark.unit


class _ListHandler(logging.Handler):
    """Capture emitted records into a list (records that pass level gating)."""

    def __init__(self):
        super().__init__(level=logging.DEBUG)
        self.records = []

    def emit(self, record):
        self.records.append(record)


@pytest.fixture
def cap():
    """Attach a capturing handler to the shared 'alis' logger and restore it."""
    log = logger.msgs()
    handler = _ListHandler()
    old_level = log.level
    log.addHandler(handler)
    try:
        yield log, handler
    finally:
        log.removeHandler(handler)
        log.setLevel(old_level)


def _levels(handler):
    return [r.levelname for r in handler.records]


def test_verbose0_suppresses_info_keeps_warning(cap):
    log, handler = cap
    logger.set_verbosity(0)  # -> WARNING
    log.info("info")
    log.warn("warn")
    assert "INFO" not in _levels(handler)
    assert "WARNING" in _levels(handler)


def test_verbose1_shows_info_suppresses_progress(cap):
    log, handler = cap
    logger.set_verbosity(1)  # -> INFO (PROGRESS=15 is below INFO)
    log.info("info")
    log.work("progress")
    assert "INFO" in _levels(handler)
    assert "PROGRESS" not in _levels(handler)


def test_verbose2_shows_progress(cap):
    log, handler = cap
    logger.set_verbosity(2)  # -> DEBUG (show everything)
    log.work("progress")
    assert "PROGRESS" in _levels(handler)


def test_invalid_verbosity_leaves_level_unchanged(cap):
    log, _ = cap
    logger.set_verbosity(1)
    assert log.level == logging.INFO
    logger.set_verbosity(99)  # not in the mapping -> unchanged
    assert log.level == logging.INFO


def test_error_reports_and_exits(cap):
    log, handler = cap
    logger.set_verbosity(0)  # even at the quietest level, errors show
    with pytest.raises(SystemExit):
        log.error("boom")
    assert "CRITICAL" in _levels(handler)  # ERROR band is emitted at CRITICAL
