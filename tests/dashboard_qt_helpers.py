# A reference to the design documents: D5, F12, S26, QF.21(c), Q0.5, Q3.14 ...
DESIGN_REF = re.compile(r"(?<![\w.])(?:[DFS]\d{1,2}|QF\.\d+|Q\d\.\d+)(?![\w])")


class Answers:
    """
    Scripted answers to the window's questions.

    ``answers[kind]`` is the choice for a question of that kind; a question with no
    answer gets its last choice (Cancel). Every question asked is kept in ``asked``.

    Generated by RJC and Claude.
    """

    def __init__(self):
        self.answers = {}
        self.asked = []

    def __call__(self, kind, title, text, choices, default=None, icon="question"):
        self.asked.append((kind, title, text))
        answer = self.answers.get(kind)
        return answer if answer in choices else choices[-1]


def make_window(qtbot, home, registry=None):
    """
    A main window, shown off-screen at 1440x900, with scripted answers.

    Generated by RJC and Claude.
    """
    from qtpy import QtWidgets

    from alis.dashboard import preferences as PR
    from alis.dashboard.qt import style
    from alis.dashboard.qt import window as WN

    style.apply(QtWidgets.QApplication.instance())
    prefs = PR.Preferences(str(home))
    window = WN.MainWindow(prefs, str(home), registry)
    window.answers = Answers()
    window.ask = window.answers
    window.chosen = {}
    window.choose = lambda kind, title, start="", filters="": window.chosen.get(kind)
    window.dialogs = []

    def run_dialog(dialog):
        window.dialogs.append(dialog)
        handler = getattr(window, "on_dialog", None)
        return handler(dialog) if handler else 0

    window.run_dialog = run_dialog
    qtbot.addWidget(window)
    window.resize(1440, 900)
    window.show()
    qtbot.waitExposed(window)
    return window


def pump(qtbot, ms=50):
    """Let the event loop run."""
    qtbot.wait(ms)


def wait_idle(qtbot, window, timeout=10000):
    """
    Wait until the .mod panel has read what was typed and the full check is done.

    Generated by RJC and Claude.
    """
    from qtpy import QtCore

    panel = window.panel
    qtbot.waitUntil(lambda: panel.live is None or not panel.live.dirty, timeout=timeout)
    QtCore.QThreadPool.globalInstance().waitForDone(timeout)
    qtbot.wait(50)


def ui_strings(window):
    """
    Every text the window shows of its own: widgets' texts and tooltips, actions and
    menus, tabs and list items. The model text in the .mod panel is the user's, and
    is left out.

    Generated by RJC and Claude.
    """
    from qtpy import QtGui, QtWidgets

    out = [window.windowTitle()]
    for widget in [window] + window.findChildren(QtWidgets.QWidget):
        if widget is window.panel.editor or widget is window.panel.footer:
            continue
        out.append(widget.toolTip())
        out.append(widget.statusTip())
        out.append(widget.windowTitle())
        for attr in ("text", "placeholderText", "title"):
            method = getattr(widget, attr, None)
            if callable(method):
                try:
                    value = method()
                except TypeError:
                    continue
                if isinstance(value, str):
                    out.append(value)
        if isinstance(widget, QtWidgets.QTabWidget):
            for num in range(widget.count()):
                out += [widget.tabText(num), widget.tabToolTip(num)]
        if isinstance(widget, QtWidgets.QListWidget):
            out += [widget.item(n).text() for n in range(widget.count())]
            out += [widget.item(n).toolTip() for n in range(widget.count())]
        if isinstance(widget, QtWidgets.QComboBox):
            out += [widget.itemText(n) for n in range(widget.count())]
    for action in window.findChildren(QtGui.QAction):
        out += [action.text(), action.toolTip(), action.statusTip(), action.iconText()]
    for menu in window.findChildren(QtWidgets.QMenu):
        out.append(menu.title())
    return [s for s in out if s]


def design_references(strings):
    """
    The strings that name a design document. A function key given as a shortcut
    ("(F1)") is a key, not a reference, and is left out first.

    Generated by RJC and Claude.
    """
    from alis.dashboard import actions as A

    keys = [a.shortcut for a in A.ACTIONS if re.fullmatch(r"F\d{1,2}", a.shortcut)]
    out = []
    for text in strings:
        for key in keys:
            text = text.replace("(" + key + ")", "")
        if DESIGN_REF.search(text):
            out.append(text)
    return out


