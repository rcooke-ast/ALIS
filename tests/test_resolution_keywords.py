"""Each data line's own resolution keywords: ``lsffile``, ``apod`` and ``lsf``.

Dashboard Stage 14, Task 14.1 (Q14.2, Q14.5). ALIS makes one instance of each model
function and loads every data line's resolution on it. The loaders of ``lsffile``,
``apod`` and ``lsf`` kept each line's keywords, and which of them were given, on the
instance, so that a line took what the line before it named: a ``kind``, a ``name``
or a ``grating`` it did not give, and a ``blindrange`` list that gathered every
line's values. Each line now starts from a copy of the function's defaults, as
``base.Base`` and ``lsfspline`` do.

- A line that names no ``kind`` (``apod``) or no ``name`` (``lsf``) after one that
  does is refused ("… must be set"), as it is alone.
- A line's keywords that it does not name are the function's defaults, not the
  line before's (``lsf``'s ``grating``, ``slit`` and ``cen_wave``).
- A ``blindrange`` given on two lines of one function stays each line's own.

``lsffile``'s ``index``, ``name`` and ``unit`` are in ``test_lsffile.py``. Loading
needs no linetools: only ``lsf``'s kernels do.

Generated by RJC and Claude.
"""

import numpy as np
import pytest

from alis import load
from alis.functions.apod import APOD
from alis.functions.lsf import LSF
from alis.functions.lsffile import LSFFile

pytestmark = pytest.mark.unit


def new_modpass():
    mp = {key: [] for key in ("mtyp", "mpar", "mtie", "mfix", "mlim", "mkey", "p0")}
    mp["tpar"] = []
    return mp


def load_lines(cls, lines):
    """Each line's resolution loaded as ALIS loads them: one instance for all."""
    inst, mp = cls(), new_modpass()
    for cntr, text in enumerate(lines):
        mp, _ = load.call_function_load(cls, inst, text, cntr, mp, [str(cntr)])
    return mp


def test_apod_a_line_that_names_no_kind_is_refused_after_one_that_does(logmsgs):
    # Before Stage 14, the second line took the first's 'hanning'
    with pytest.raises(SystemExit):
        load_lines(APOD, ["1.0,kind:hanning", "1.0"])
    assert any("kind must be set" in msg for msg in logmsgs)


def test_apod_each_line_keeps_its_kind():
    mp = load_lines(APOD, ["1.0,kind:hanning", "1.0,kind:welch"])
    assert [key["kind"] for key in mp["mkey"]] == ["hanning", "welch"]


def test_lsf_a_line_that_names_no_name_is_refused_after_one_that_does(logmsgs):
    # Before Stage 14, the second line took the first's 'STIS'
    with pytest.raises(SystemExit):
        load_lines(LSF, ["name:STIS,grating:E140H,slit:0.2x0.09", "grating:G160M"])
    assert any("name must be set" in msg for msg in logmsgs)


def test_lsf_what_a_line_does_not_name_is_the_default():
    mp = load_lines(LSF, ["name:STIS,grating:E140H,slit:0.2x0.09", "name:COS"])
    second = mp["mkey"][1]
    # Before Stage 14: E140H and 0.2x0.09, the first line's
    assert (second["grating"], second["slit"], second["cen_wave"]) == (
        "G130M",
        "None",
        "1309",
    )
    assert (mp["mkey"][0]["grating"], mp["mkey"][0]["slit"]) == ("E140H", "0.2x0.09")


def kernel_file(tmp_path):
    offsets = np.linspace(-1.0, 1.0, 201)
    path = tmp_path / "kernel.dat"
    np.savetxt(
        str(path), np.column_stack([offsets, np.exp(-0.5 * (offsets / 0.1) ** 2)])
    )
    return "name:" + str(path)


@pytest.mark.parametrize("function", ["lsffile", "apod", "lsf"])
def test_a_blindrange_stays_each_line_s_own(function, tmp_path):
    cls, given = {
        "lsffile": (LSFFile, kernel_file(tmp_path)),
        "apod": (APOD, "1.0,kind:uniform"),
        "lsf": (LSF, "name:COS"),
    }[function]
    lines = [given + ",blindrange:0.5", given + ",blindrange:0.7", given]
    # Before Stage 14, all three lines held one list, ['0.5', '0.7']
    assert [key["blindrange"] for key in load_lines(cls, lines)["mkey"]] == [
        ["0.5"],
        ["0.7"],
        [],
    ]


@pytest.mark.parametrize("function", ["lsffile", "apod", "lsf"])
def test_a_boolean_and_an_integer_keyword_stay_each_line_s_own(function, tmp_path):
    # Stage 14's close (test-coverage): the boolean and integer branches of the
    # loaders' copies; a line that names neither takes the defaults
    cls, given = {
        "lsffile": (LSFFile, kernel_file(tmp_path)),
        "apod": (APOD, "1.0,kind:uniform"),
        "lsf": (LSF, "name:COS"),
    }[function]
    default = cls()._keywd["blindseed"]
    lines = [given + ",blind:True,blindseed:7", given]
    keys = load_lines(cls, lines)["mkey"]
    assert [(key["blind"], key["blindseed"]) for key in keys] == [
        (True, 7),
        (False, default),
    ]


@pytest.mark.parametrize(
    "cls, text",
    [(APOD, "1.0,kind:hanning,blindrange:0.5"), (LSF, "name:STIS,blindrange:0.5")],
)
def test_the_defaults_stay_the_defaults(cls, text):
    inst, mp = cls(), new_modpass()
    before = dict(inst._keywd, input=None, blindrange=list(inst._keywd["blindrange"]))
    required = dict(inst._keych)
    for cntr in range(2):
        mp, _ = load.call_function_load(cls, inst, text, cntr, mp, [str(cntr)])
    assert dict(inst._keywd, input=None) == before
    assert dict(inst._keych) == required
