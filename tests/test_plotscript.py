@pytest.mark.examples
def test_a_fit_with_plotscript_none_writes_nothing(tmp_path):
    staged = _run_example(tmp_path, extra=None)
    assert not list(staged.glob("*.plot.py"))


@pytest.mark.examples
def test_the_emitted_script_runs_on_its_own_and_draws_a_figure(tmp_path):
    """The whole point of 5.3: a script that works outside ALIS.

    It is executed in a subprocess that never imports alis, so a lingering
    dependency on ALIS -- or on the `plotting_routines` module the reference
    figures use and which is not distributed -- fails here.
    """
    staged = _run_example(tmp_path, extra="plotscript format metals")
    scripts = list(staged.glob("*.plot.py"))
    assert len(scripts) == 1, "expected exactly one emitted script"
    text = scripts[0].read_text()
    assert "plotting_routines" not in text
    compile(text, str(scripts[0]), "exec")

    env = dict(os.environ)
    env["MPLBACKEND"] = "Agg"
    env["PYTHONPATH"] = ""  # cannot fall back on the repo being importable
    proc = subprocess.run(
        [sys.executable, scripts[0].name],
        cwd=str(staged),
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert proc.returncode == 0, (proc.stdout + proc.stderr)[-2000:]
    figures = list(staged.glob("*_plot.pdf"))
    assert len(figures) == 1
    assert figures[0].stat().st_size > 1000, "figure looks empty"


@pytest.mark.examples
def test_both_transitions_in_one_snip_get_their_own_panel(tmp_path):
    # metal_line_abs fits O I 1302 and Si II 1304 in one range. They are ~460
    # km/s apart, far more than a velocity panel shows, so one panel would drop
    # a line.
    staged = _run_example(tmp_path, extra="plotscript format metals")
    text = next(staged.glob("*.plot.py")).read_text()
    assert "O I 1302" in text
    assert "Si II 1304" in text


def _run_example(tmp_path, extra):
    """Run examples/metal_line_abs in tmp_path, optionally adding a setting."""
    ex = tmp_path / "metal_line_abs"
    shutil.copytree(REPO_ROOT / "examples" / "metal_line_abs", ex)
    model = ex / "model" / "fit_spectra.mod"
    if extra is not None:
        model.write_text(
            model.read_text().replace("out fits True", "out fits True\n" + extra)
        )
    env = dict(os.environ)
    env["MPLBACKEND"] = "Agg"
    proc = subprocess.run(
        [sys.executable, str(RUN_ALIS), "-f", "-w", "-p", "0", model.name],
        cwd=str(model.parent),
        env=env,
        capture_output=True,
        text=True,
        timeout=600,
    )
    assert proc.returncode == 0, (proc.stdout + proc.stderr)[-2000:]
    return model.parent
