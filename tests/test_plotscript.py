"""The standalone plotting script ALIS can emit (Stage 5.3).

Two layers:

* the layout logic, exercised directly with synthetic panels -- cheap, and it
  pins the column/row ordering RJC specified for each format;
* one real fit, run end to end, whose emitted script is then *executed* to check
  it actually draws a figure. A script that is merely syntactically valid is not
  worth much; the thing that matters is that it runs on its own, without ALIS.

Generated by RJC and Claude.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from alis import plotscript
from alis.config import ArgFlag

pytestmark = pytest.mark.unit

REPO_ROOT = Path(__file__).resolve().parent.parent
RUN_ALIS = REPO_ROOT / "alis" / "scripts" / "run_alis.py"


def _panel(restwave, specid="0", ion="1H_I", zabs=0.0):
    return dict(
        datafile="d.dat",
        columns={"wave": 0, "flux": 1, "error": 2, "model": 3},
        centre=restwave * (1.0 + zabs),
        restwave=restwave,
        zabs=zabs,
        ion=ion,
        label="H I {0:.0f}".format(restwave),
        specid=specid,
        fitrange=(restwave - 1.0, restwave + 1.0),
    )


# -- settings ---------------------------------------------------------------


def test_plotscript_is_a_settings_section_and_defaults_to_none():
    cfg = ArgFlag()
    assert "plotscript" in cfg.keys()
    assert cfg["plotscript"]["format"] == "none"


def test_the_settings_parse_from_a_model_file():
    """`set_params` converts by the type of the default, so the awkward ones
    (a word *or* a number, a word *or* a list) are what this pins."""
    from alis import load

    cfg = ArgFlag()
    load.set_params(
        [
            "plotscript format DH",
            "plotscript numcol 4",
            "plotscript residuals True",
            "plotscript velrange -150,150",
            "plotscript fontsize 9.0",
            "plotscript labels False",
        ],
        cfg,
        verbose=0,
    )
    ps = cfg["plotscript"]
    assert ps["format"] == "DH"
    assert int(ps["numcol"]) == 4
    assert ps["residuals"] is True
    assert [float(v) for v in ps["velrange"]] == [-150.0, 150.0]
    assert ps["fontsize"] == 9.0
    assert ps["labels"] is False


def test_numcol_and_velrange_still_accept_auto():
    from alis import load

    cfg = ArgFlag()
    load.set_params(
        ["plotscript numcol auto", "plotscript velrange auto"], cfg, verbose=0
    )
    assert cfg["plotscript"]["numcol"] == "auto"
    assert plotscript._pair(cfg["plotscript"]["velrange"], (-1.0, 1.0)) == (-1.0, 1.0)


# -- layout -----------------------------------------------------------------


def test_metals_defaults_to_three_columns_and_groups_by_ion():
    panels = [
        _panel(1302.0, ion="16O_I"),
        _panel(1526.0, ion="28Si_II"),
        _panel(1304.0, ion="28Si_II"),
        _panel(1260.0, ion="28Si_II"),
    ]
    nrow, ncol, ordered = plotscript._layout("metals", panels, None, 1)
    assert ncol == 3
    assert nrow == 2
    ions = [p["ion"] for p in ordered]
    # every ion's panels are contiguous
    assert ions == sorted(ions)


def test_DH_one_dataset_runs_down_the_left_column_then_the_right():
    """RJC, Q5.9: Ly-alpha top-left, continuing *down*, then the right column."""
    waves = [1215.67, 1025.72, 972.54, 949.74, 937.80, 930.75]
    panels = [_panel(w) for w in waves]
    nrow, ncol, ordered = plotscript._layout("DH", panels, None, 1)
    assert ncol == 2
    assert nrow == 3
    # reading order is row-major, so the left column is entries 0, 2, 4
    left = [ordered[i]["restwave"] for i in (0, 2, 4)]
    right = [ordered[i]["restwave"] for i in (1, 3, 5)]
    assert left == waves[:3], "left column should be the first three, in order"
    assert right == waves[3:], "right column should continue the series"


def test_DH_two_datasets_puts_the_datasets_in_columns():
    """RJC, Q5.11: same transition side by side, so they can be compared."""
    panels = []
    for w in (1215.67, 1025.72):
        for sid in ("A", "B"):
            panels.append(_panel(w, specid=sid))
    nrow, ncol, ordered = plotscript._layout("DH", panels, None, 2)
    assert (nrow, ncol) == (2, 2)
    assert [p["specid"] for p in ordered] == ["A", "B", "A", "B"]
    assert ordered[0]["restwave"] == ordered[1]["restwave"] == 1215.67
    assert ordered[2]["restwave"] == ordered[3]["restwave"] == 1025.72


def test_numcol_overrides_the_default():
    panels = [_panel(1200.0 + i) for i in range(6)]
    _, ncol, _ = plotscript._layout("metals", panels, 2, 1)
    assert ncol == 2


