def test_unblinding_is_confirmed_logged_final_and_clears_the_history(
    home, tmp_path, registry
):
    session = session_of(BLIND, tmp_path, registry)
    project, history = session.project, session.history
    history.type(replace(project, "13.0", "13.4729", line=si_line(project)))
    session.save()
    # A blind run's output, hidden in the bundle as run_alis stores it
    out = "voigt ion=28Si_II 13.4729 0.0 1.0da 8000TA specid=0 blind=True\n"

    def add_run(bundle):
        store = {}
        member = B.LATEST + "files/model/fit_spectra.mod.out"
        bundle.members[member] = B.hide_lines(out, [0], store).encode()
        bundle.hidden["lines"][member] = store

    B.update(session.path, add_run)
    session.take_runs()
    with pytest.raises(BL.BlindingError):
        BL.unblind(project, confirmed=False)
    session.unblind("Paper submitted")
    assert not project.hidden_lines() and not project.parsed.blind
    assert "blind=False" in si_line(project)
    assert not history.done and not history.can_undo()
    assert not session.dirty
    disk = B.read(session.path)
    log = disk.manifest["unblinding"]
    assert log[-1]["note"] == "Paper submitted"
    assert not disk.is_blinded()
    member = B.LATEST + "files/model/fit_spectra.mod.out"
    assert b"13.4729" in disk.members[member]
    assert "13.4729" in BL.Gate(project).view().text


def test_unblinding_a_model_that_relies_on_alis_s_default(home, tmp_path, registry):
    """ALIS blinds a model with no run blind line; unblinding writes one."""
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    history.type(replace(project, "run blind False\n", ""))
    assert project.parsed.blind
    session.unblind("done")
    assert not project.parsed.blind
    assert "run blind False" in " ".join(project.text.split())
