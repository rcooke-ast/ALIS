"""Blinding steps and the guard of the history (dashboard Stage 3.10), with no Qt.

- Switching global blind on, and blinding a line, are each one step, which undo does
  not pass, however they were made (Q3.9, Q3.13, Q3.14).
- An edit that would show a hidden value is refused; deleting a hidden line, or
  typing a new value over it, is not.
- The pill says what is blinded.
- Unblinding is confirmed, logged in the bundle, final, and clears the history.

Generated by RJC and Claude.
"""

import json
from pathlib import Path

import pytest

from alis import bundle as B
from alis.dashboard import blinding as BL
from alis.dashboard import edit as E
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import session as S
from alis.dashboard import text as T

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
BLIND = ROOT / "examples/blind/model/fit_spectra.mod"
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture
def home(tmp_path, monkeypatch):
    monkeypatch.setenv(PR.HOME_ENV, str(tmp_path / "home"))


def session_of(model, tmp_path, registry):
    path = tmp_path / (model.parent.parent.name + ".model")
    B.pack_to(str(model), str(path), with_outputs=False)
    return S.Session.open(str(path), registry=registry)


def replace(project, old, new, line=None):
    """A change of the text, as typing makes it."""
    text = project.text
    start = text.index(old) if line is None else text.index(old, text.index(line))
    return T.Change((T.Patch(start, old, new),), "Typing")


def si_line(project):
    return next(ln for ln in project.text.splitlines() if "28Si_II" in ln)


def test_global_blind_is_a_step_undo_does_not_pass(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    par = next(p for p in project.parsed.params if p.name == "ColDens")
    history.edit(E.set_value(project.parsed, par, 14.5), "Set N")
    assert history.can_undo()
    history.edit(E.set_setting(project.parsed, "run", "blind", "True"), "Blind")
    assert project.parsed.blind
    assert not history.can_undo() and history.undo_description() == ""
    assert history.undo() is None and project.parsed.blind
    # Later steps can be undone, down to it
    par = next(p for p in project.parsed.params if p.name == "ColDens")
    history.edit(E.set_value(project.parsed, par, 14.75), "Set N")
    assert history.undo() is not None
    assert not history.can_undo() and project.parsed.blind


def test_typing_run_blind_true_is_a_step_undo_does_not_pass(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    history.type(replace(project, "run blind False", "run blind True"))
    assert project.parsed.blind and not history.can_undo()


def test_blinding_a_line_is_a_step_undo_does_not_pass(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    item = project.parsed.function_lines("voigt")[0]
    history.edit(E.set_blind(project.parsed, item), "Blind a line")
    assert item.line in project.hidden_lines()
    assert not history.can_undo()


def test_typing_blind_true_is_a_step_undo_does_not_pass(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    line = next(ln for ln in project.text.splitlines() if "16O_I" in ln)
    history.type(
        T.Change(
            (T.Patch(project.text.index(line) + len(line), "", "  blind=True"),),
            "Typing",
        )
    )
    assert len(project.hidden_lines()) == 1
    assert not history.can_undo()
    # More typing right after is a new step, which can be undone
    history.type(replace(project, "chisq ftol", "#chisq ftol"))
    assert history.can_undo()
    history.undo()
    assert not history.can_undo() and project.hidden_lines()


@pytest.mark.parametrize(
    "old, new",
    [("blind=True", "blind=False"), ("blind=True", "blind=no"), ("  blind=True", "")],
    ids=["False", "other", "removed"],
)
def test_an_edit_that_shows_a_hidden_line_is_refused(
    home, tmp_path, registry, old, new
):
    session = session_of(BLIND, tmp_path, registry)
    project, history = session.project, session.history
    before = project.text
    with pytest.raises(BL.RevealError, match="Unblind"):
        history.type(replace(project, old, new, line=si_line(project)))
    assert project.text == before and not history.done


def test_switching_global_blind_off_is_refused(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    history.type(replace(project, "run blind False", "run blind True"))
    before = project.text
    with pytest.raises(BL.RevealError):
        history.type(replace(project, "run blind True", "run blind False"))
    assert project.text == before
    # Deleting the line leaves the analysis blind: ALIS blinds a model that does not
    # say (run blind is True by default), so nothing is shown and it is allowed
    history.type(replace(project, "run blind True\n", ""))
    assert project.parsed.blind


def test_deleting_or_retyping_a_hidden_value_is_allowed(home, tmp_path, registry):
    session = session_of(BLIND, tmp_path, registry)
    project, history = session.project, session.history
    line = si_line(project)
    # Typing a new value over the hidden one: still hidden
    history.type(replace(project, "13.0", "12.5", line=line))
    assert "12.5" not in BL.Gate(project).view().text
    # Deleting the hidden line whole
    line = si_line(project)
    history.type(replace(project, line + "\n", ""))
    assert "28Si_II" not in project.text and not project.hidden_lines()
    assert BL.pill_text(project) == "Not blinded"
    # Undo brings it back, hidden
    history.undo()
    assert project.hidden_lines() and "12.5" not in BL.Gate(project).view().text


def test_unhiding_an_extra_hidden_line_is_refused(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    line = project.parsed.function_lines("voigt")[0].line
    history.do(project.mark_hidden(line))
    assert not history.can_undo()
    step = project.mark_hidden(line)
    step.hidden = (set(project.extra_hidden), set())
    with pytest.raises(BL.RevealError):
        history.do(step)
    assert line in project.hidden_lines()


def test_the_pill_says_what_is_blinded(home, tmp_path, registry):
    session = session_of(METAL, tmp_path, registry)
    project, history = session.project, session.history
    assert BL.pill_text(project) == "Not blinded"
    lines = project.parsed.function_lines("voigt")
