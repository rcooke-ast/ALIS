"""The output writer's helpers, at unit level (Stage 5.5).

`tests/test_writer_round_trip.py` pins the round trip *end to end*, over the 40
committed `.mod.out.reference` files: it re-reads them and checks the reader
accepts them and the free-parameter count does not move. What it cannot do is
run the writer -- those files are the output of fits that take hours -- so the
half of the round trip that produces the file is untested there. This is that
half.

Everything here runs `save.save_model(..., save=False, getlines=True)` on a
model assembled from a 500-pixel synthetic spectrum, so a full `.mod.out` is
produced in milliseconds and can then be fed straight back in. That closes the
loop the reference files leave open, and it is what makes the Stage 5.4 fixes
testable at all:

* the pixel-load buffer is recorded as `bufferpix`, and only where the user
  gave no `loadrange` of their own;
* re-reading reproduces the *identical* wavelength array even though the saved
  file carries the fitted resolution rather than the starting one;
* the Stage 4 settings the writer echoes (`run backend` / `ngpus` /
  `gputhresh` / `shmem`) come back with the same values;
* `save_covar` derives the correlation-matrix image name with `splitext`, not
  with `str.rstrip`.

Generated by RJC and Claude.
"""

import matplotlib
import numpy as np
import pytest

from alis import load, save
from alis.config import ArgFlag
from alis.main import build_funcarray

matplotlib.use("Agg")  # save_covar draws the correlation matrix

pytestmark = pytest.mark.unit

# info = [running time, chi-squared, DOF, iterations, convergence reason]
INFO = [0.0, 12.5, 100, 3, 1]


class _State:
    """The attributes `save_model` reads, filled in by `build` below."""

    def __init__(self, atomic):
        self._argflag = ArgFlag()
        self._argflag["out"]["verbose"] = -1
        self._isonefits = False
        self._chisq_init = 20.0
        self._atomic = atomic
        self._funcarray = build_funcarray(self._argflag, atomic)


def build(path, atomic):
    """Load a model file the way `ClassMain` does, minus the fit."""
    state = _State(atomic)
    parlines, datlines, modlines, lnklines = load.load_input(state, filename=str(path))
    load.load_data(state, datlines)
    state._modpass = load.load_model(state, modlines)
    state._links = load.load_links(state, lnklines)
    state._parlines = parlines
    state._modlines = modlines
    state._lnklines = lnklines
    return state


def nfree(state):
    parinfo, _levadd = load.load_parinfo(state)
    return sum(1 for p in parinfo if not p.get("fixed", 0))


def written(state, params=None):
    """The text `save_model` would write, without writing it."""
    if params is None:
        params = np.array(state._modpass["p0"], dtype=float)
    return save.save_model(
        state,
        params,
        np.zeros(len(params)),
        INFO,
        printout=False,
        getlines=True,
        save=False,
    )


def data_line(text):
    """The one live data line of a written model (comments excluded)."""
    lines = [
        line
        for line in text.split("\n")
        if ".dat" in line and not line.lstrip().startswith("#")
    ]
    assert len(lines) == 1, lines
    return lines[0]


MODEL = """run ngpus 0
run backend cpu
run gputhresh 5000
run shmem False

data read
  {data:s}  specid=0  fitrange=[1300.0,1305.0]  resolution=vfwhm(7.0){extra:s}  columns=[wave,flux,error]
data end

model read
  emission
    legendre 1.0   0.01   specid=0
  absorption
    voigt   ion=16O_I    14.0   0.0   5.0da   8000.0TA   specid=0
    voigt   ion=28Si_II  ColDens=13.0   0.0   5.0da   8000.0TA   damping=2.5   specid=0
model end
"""


@pytest.fixture
def modelfile(tmp_path):
    """A writer of `.mod` files sharing one synthetic spectrum."""
    wave = np.linspace(1290.0, 1315.0, 501)  # 0.05 A pixels
    data = tmp_path / "spec.dat"
    np.savetxt(
        str(data), np.column_stack([wave, np.ones_like(wave), 0.1 * np.ones_like(wave)])
    )

    def make(name="fit.mod", extra="", text=None, replace=None):
        path = tmp_path / name
        if text is None:
            text = MODEL.format(data=str(data), extra=extra)
        if replace is not None:
            text = text.replace(*replace)
        path.write_text(text)
        return path

    return make


@pytest.fixture
def fitted(modelfile, atomic_data):
    return build(modelfile(), atomic_data)


# -- print_model --------------------------------------------------------------


def test_print_model_echoes_a_parameter_only_where_the_user_gave_it(fitted):
    """The Stage 5.4 rule, at the point where it is applied.

    `parout` consults `mkey['input']`, so a parameter left at its default is
    left out -- which matters because voigt's `damping` defaults to *fixed*
    while an echoed suffixless `damping=0.0000000` re-reads as free.
    """
    params = np.array(fitted._modpass["p0"], dtype=float)
    outstring, _arrays = save.print_model(
        params, fitted._modpass, funcarray=fitted._funcarray
    )
    voigt = [ln for ln in outstring.split("\n") if ln.strip().startswith("voigt")]
    assert len(voigt) == 2
    assert "damping=" not in voigt[0], "the first line never named a damping"
    assert "damping=2.5" in voigt[1]


def test_print_model_keeps_the_named_form_for_named_parameters(fitted):
    params = np.array(fitted._modpass["p0"], dtype=float)
    outstring, _arrays = save.print_model(
        params, fitted._modpass, funcarray=fitted._funcarray
    )
    voigt = [ln for ln in outstring.split("\n") if ln.strip().startswith("voigt")]
    assert "ColDens=" not in voigt[0], "given positionally, so echoed positionally"
    assert "ColDens=13.0" in voigt[1], "given by name, so echoed by name"


def test_print_model_preserves_the_tie_labels(fitted):
    params = np.array(fitted._modpass["p0"], dtype=float)
    outstring, _arrays = save.print_model(
        params, fitted._modpass, funcarray=fitted._funcarray
    )
    assert outstring.count("da ") + outstring.count("da\n") >= 2
    assert "TA" in outstring


def test_print_model_blinds_a_component_that_asked_to_be_blinded(
    modelfile, atomic_data
):
    """`run blind` output is *meant* not to be re-readable, which is why the
    five blind references are excluded from the end-to-end round-trip suite."""
    path = modelfile(name="blind.mod", replace=("ion=16O_I ", "ion=16O_I  blind=True "))
    state = build(path, atomic_data)
    params = np.array(state._modpass["p0"], dtype=float)
    outstring, _arrays = save.print_model(
        params, state._modpass, funcarray=state._funcarray
    )
    assert "------ BLIND MODEL ------" in outstring
    # ... and only the blinded component is hidden.
    assert "ion=28Si_II" in outstring


def test_modlines_returns_one_entry_per_component_plus_its_section_headers(fitted):
    params = np.array(fitted._modpass["p0"], dtype=float)
    lines = save.modlines(fitted, params, fitted._modpass)
    assert lines[0] == "emission"
    assert lines[2] == "absorption"
    assert len(lines) == 5  # two headers, one legendre, two voigt


# -- the data line the writer rebuilds ---------------------------------------


def test_the_writer_records_the_pixel_buffer_that_was_actually_loaded(fitted):
    """`bufferpix=[left,right]`, counted against the loaded array (Stage 5.4)."""
    line = data_line(written(fitted))
    assert "bufferpix=[" in line
    token = [t for t in line.split() if t.startswith("bufferpix=")][0]
    nleft, nright = (int(v) for v in token.split("=")[1].strip("[]").split(","))
    wave = fitted._wavefull[0]
    lo, hi = fitted._posnfit[0][0], fitted._posnfit[0][1]
    assert nleft == np.count_nonzero(wave < lo)
    assert nright == np.count_nonzero(wave > hi)
    assert (nleft, nright) != (0, 0), "vfwhm(7.0) should need a buffer"


def test_the_two_sides_of_the_buffer_are_recorded_separately(fitted):
    """The resolution rule extends by a *wavelength*, which is not the same
    number of pixels either side -- `lsf_hst` measures [3492,3490]."""
    line = data_line(written(fitted))
    token = [t for t in line.split() if t.startswith("bufferpix=")][0]
    assert "," in token, "a single number could not express an asymmetric buffer"


def test_an_explicit_loadrange_is_passed_through_untouched(modelfile, atomic_data):
    """1231 `loadrange=all` keywords live in this repo. Replacing one with the
    range this particular fit happened to need would silently narrow it."""
    state = build(modelfile(extra="  loadrange=all"), atomic_data)
    line = data_line(written(state))
    assert "loadrange=all" in line
    assert "bufferpix" not in line


def test_a_user_supplied_bufferpix_is_not_duplicated(modelfile, atomic_data):
    state = build(modelfile(extra="  bufferpix=[6,6]"), atomic_data)
    line = data_line(written(state))
    assert line.count("bufferpix=") == 1
    assert "bufferpix=[6,6]" in line


def _widen_the_resolution(state, vfwhm=40.0):
    """The parameter vector with the resolution moved, as a fit would move it.

    `modpass['line']` tags the resolution's parameters with the data-line
    keyword they came from, which is how they are found without hard-coding an
    index into p0.
    """
    params = np.array(state._modpass["p0"], dtype=float)
    params[state._modpass["line"].index("resolution=vfwhm(7.0)")] = vfwhm
    return params


def test_the_writer_echoes_the_fitted_resolution_not_the_starting_one(
    modelfile, atomic_data
):
    state = build(modelfile(), atomic_data)
    line = data_line(written(state, _widen_the_resolution(state)))
    assert "resolution=vfwhm(40" in line
    assert "vfwhm(7.0)" not in line


@pytest.mark.linetools
def test_a_resolution_sub_keyword_is_written_with_a_colon(modelfile, atomic_data):
    """The `examples/lsf_hst` failure, from the writer's end (Stage 5.4).

    `parout` returns the keyword as `name=STIS`, but `load_data` splits a
    data-line token on `=` and keeps field 1 -- so writing it back like that
    truncates the value to `lsf(name` and the saved file cannot be re-read.
    The five convolution functions that take keywords all undo the colon with
    `instr.replace(":", "=")` on the way in, and purely numeric parameters
    contain no `=`, so the substitution is safe for all of them.
    """
    resolution = "lsf(name:STIS,grating:E140H,slit:0.2x0.09)"
    state = build(
        modelfile(name="lsf.mod", replace=("vfwhm(7.0)", resolution)), atomic_data
    )
    line = data_line(written(state))
    token = [t for t in line.split() if t.startswith("resolution=")][0]
    inside = token[token.index("(") + 1 : token.rindex(")")]
    assert "=" not in inside, token
    assert "name:STIS" in token


# -- the round trip -----------------------------------------------------------


def test_a_saved_model_reloads_the_identical_pixels_after_the_resolution_moved(
    modelfile, atomic_data
):
    """The whole point of Stage 5.4's `bufferpix`.

    The saved file carries the resolution the fit *ended* on. ALIS sizes the
    pixel-load buffer from the resolution at load time, so without a recorded
    buffer the re-read would select a different set of pixels from the run that
    wrote the file -- and the chi-squared would not reproduce.
    """
    first = build(modelfile(), atomic_data)
    saved = modelfile(
        name="fit.mod.out", text=written(first, _widen_the_resolution(first))
    )
    second = build(saved, atomic_data)

    assert "vfwhm(40" in data_line(saved.read_text())
    assert np.array_equal(second._wavefull[0], first._wavefull[0])
    assert np.array_equal(second._wavefit[0], first._wavefit[0])


def test_without_the_recorded_buffer_the_pixels_would_move(modelfile, atomic_data):
    """The control for the test above: strip `bufferpix` from the saved file --
    which is what the writer did before Stage 5.4 -- and the pixels change."""
    first = build(modelfile(), atomic_data)
    text = written(first, _widen_the_resolution(first))
    stripped = "\n".join(
        (
            line.split("  bufferpix=")[0]
            if ".dat" in line and not line.lstrip().startswith("#")
            else line
        )
        for line in text.split("\n")
    )
    second = build(modelfile(name="nobuffer.mod.out", text=stripped), atomic_data)
    assert second._wavefull[0].size != first._wavefull[0].size


def test_the_round_trip_preserves_the_free_parameter_count(modelfile, atomic_data):
    first = build(modelfile(), atomic_data)
    saved = modelfile(name="fit.mod.out", text=written(first))
    assert nfree(build(saved, atomic_data)) == nfree(first)


def test_the_round_trip_preserves_which_parameters_were_named(modelfile, atomic_data):
    """A named parameter must come back named and a positional one positional,
    or the file is a different model even when the numbers agree."""
    first = build(modelfile(), atomic_data)
    saved = modelfile(name="fit.mod.out", text=written(first))
    second = build(saved, atomic_data)
    for i in range(len(first._modpass["mtyp"])):
        assert (
            second._modpass["mkey"][i]["input"] == first._modpass["mkey"][i]["input"]
        ), first._modpass["mtyp"][i]


# -- the settings the writer echoes (Stage 4 additions) ----------------------


STAGE4 = {"backend": "cpu", "ngpus": 0, "gputhresh": 5000, "shmem": False}


def test_the_stage4_settings_are_read_from_the_model_file(fitted):
    for key, value in STAGE4.items():
        assert fitted._argflag["run"][key] == value, key


def test_the_stage4_settings_are_echoed_and_survive_the_round_trip(
    modelfile, atomic_data
):
    """`run backend` / `ngpus` / `gputhresh` / `shmem` arrived in Stage 4 and
    the writer echoes them like any other setting; nothing pinned that."""
    first = build(modelfile(), atomic_data)
    text = written(first)
    for key, value in STAGE4.items():
        assert "run {0:s} {1!s}".format(key, value) in text

    second = build(modelfile(name="fit.mod.out", text=text), atomic_data)
    for key, value in STAGE4.items():
        assert second._argflag["run"][key] == value, key


def test_an_unknown_backend_is_rejected_when_the_file_is_read(modelfile, atomic_data):
    """`check_argflag` catches it at start-up rather than at the first
    Jacobian, so a typo cannot quietly run the fit on the wrong backend."""
    text = MODEL.format(data="x", extra="").replace(
        "run backend cpu", "run backend wibble"
    )
    with pytest.raises(SystemExit):
        build(modelfile(name="bad.mod", text=text), atomic_data)


# -- save_covar ---------------------------------------------------------------


@pytest.mark.parametrize(
    "name,image",
    [
        ("mycovar.dat", "mycovar.png"),
        ("mycovar", "mycovar.png"),  # no extension: the rstrip bug's case
        ("a.b.dat", "a.b.png"),
    ],
)
def test_save_covar_derives_the_image_name_by_replacing_the_extension(
    tmp_path, atomic_data, name, image
):
    """Stage 5.4: this was `filename.rstrip(fnspl[-1]) + 'png'`.

    `str.rstrip` removes any trailing character *in the given set*, not a
    suffix. With no extension to terminate the strip it ate the path itself:
    restoring the old line and running this test writes the image to `png.png`
    in the working directory instead of beside the matrix.
    """
    state = _State(atomic_data)
    state._argflag["out"]["overwrite"] = True
    state._argflag["out"]["covar"] = str(tmp_path / name)
    save.save_covar(state, np.array([[4.0, 1.0], [1.0, 9.0]]))
    assert sorted(p.name for p in tmp_path.iterdir()) == sorted({name, image})


def test_save_covar_writes_nothing_when_there_is_no_covariance(
    tmp_path, atomic_data, logmsgs
):
    state = _State(atomic_data)
    state._argflag["out"]["overwrite"] = True
    state._argflag["out"]["covar"] = str(tmp_path / "mycovar.dat")
    save.save_covar(state, None)
    assert list(tmp_path.iterdir()) == []
    assert any("interupt" in m or "None" in m for m in logmsgs)


# -- the command-line override block (Stage 6.1, Q6.12/Q6.20/Q6.25) ----------


def test_the_override_block_records_only_the_settings_that_may_persist():
    from alis import load

    block = save.cli_override_block(
        [
            ("plot", "dims", "3x3", "0", True),
            ("out", "overwrite", False, True, False),
        ]
    )
    assert "plot dims 0" in block
    assert load.CLI_OVERRIDE_MARK in block
    # the invocation-only one is recorded, but commented, so a re-run does not
    # silently overwrite
    assert "#   out overwrite True" in block
    live = [ln for ln in block.splitlines() if ln and not ln.startswith("#")]
    assert live == [ln for ln in live if "plot dims" in ln]


def test_an_empty_override_list_writes_nothing():
    assert save.cli_override_block([]) == ""
    assert save.cli_override_block(None) == ""


def test_a_previous_block_is_carried_forward_not_duplicated():
    """Re-fitting a `.mod.out` must produce a file that still reproduces the
    run: the earlier overrides carry over, and this run's replace them key by
    key rather than being appended alongside (Q6.25)."""
    from alis import load

    previous = [
        "plot dims 0   {0:s} was 3x3\n".format(load.CLI_OVERRIDE_MARK),
        "out fits True   {0:s} was False\n".format(load.CLI_OVERRIDE_MARK),
    ]
    block = save.cli_override_block(
        [("plot", "dims", "3x3", "1x1", True)], previous=previous
    )
    live = [ln.split() for ln in block.splitlines() if ln and not ln.startswith("#")]
    keys = [(p[0], p[1]) for p in live]
    assert keys.count(("plot", "dims")) == 1, "the replaced setting is not duplicated"
    assert ("out", "fits") in keys, "the untouched one is carried forward"
    assert [p[2] for p in live if p[1] == "dims"] == ["1x1"]


def test_the_writer_strips_a_previous_block_from_the_settings_it_echoes():
    from alis import load

    parlines = [
        "run blind False\n",
        "plot dims 0   {0:s} was 3x3\n".format(load.CLI_OVERRIDE_MARK),
    ]
    assert save.strip_cli_override_block(parlines) == ["run blind False\n"]
