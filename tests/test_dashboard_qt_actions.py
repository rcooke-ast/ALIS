def menu_actions(menu):
    """Every action of a menu and its submenus."""
    out = []
    for action in menu.actions():
        if action.menu() is not None:
            out += menu_actions(action.menu())
        elif not action.isSeparator():
            out.append(action)
    return out


def test_every_action_is_in_a_menu_and_in_the_sheet(window, qtbot):
    native = QtGui.QKeySequence.SequenceFormat.NativeText
    placed = {}
    for title, menu in window.menus.items():
        for action in menu_actions(menu):
            if action.objectName():
                placed[action.objectName()] = title
    # The .mod panel's own actions: a header button each, and its right-click menu
    for button in window.panel.panel_buttons:
        if button.defaultAction() in window.panel.editor.panel_actions:
            placed[button.defaultAction().objectName()] = A.PANEL
    # A tab's own actions: its buttons and keys (Stage 4)
    groups = {tab: group for group, tab in A.TAB_GROUPS.items()}
    for widget in window.tab_widgets:
        for button in getattr(widget, "tab_buttons", []):
            placed[button.defaultAction().objectName()] = groups[widget.name]
    sheet = D.ShortcutsDialog(window.qactions, window)
    qtbot.addWidget(sheet)
    rows = sheet.rows()
    assert len(rows) == len(A.ACTIONS)
    for spec in A.ACTIONS:
        assert placed.get(spec.name) == spec.menu, spec.name
        qaction = window.qactions[spec.name]
        keys = qaction.shortcut().toString(native)
        assert keys == QtGui.QKeySequence(spec.shortcut).toString(native)
        row = [r for r in rows if r[0] == spec.menu and r[3] == spec.tip]
        assert row and row[0][2] == keys, spec.name
        if spec.shortcut:
            assert keys in qaction.toolTip()


def test_a_tabs_keys_belong_to_the_tab(window):
    """A single key acts only while its tab has the focus (Stage 4)."""
    from qtpy import QtCore

    tabs = {w.name: w for w in window.tab_widgets}
    for spec in A.ACTIONS:
        action = window.qactions[spec.name]
        if spec.scope:
            assert action.parent() is tabs[spec.scope], spec.name
            if spec.shortcut:
                assert (
                    action.shortcutContext()
                    == QtCore.Qt.ShortcutContext.WidgetWithChildrenShortcut
                )
        else:
            assert action.parent() is window, spec.name


def test_no_two_actions_share_a_shortcut(window):
    seen = {}
    for name, action in window.qactions.items():
        keys = action.shortcut()
        if keys.isEmpty():
            continue
        for other, their in seen.items():
            assert keys != their, (name, other)
        seen[name] = keys


