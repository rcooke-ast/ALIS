def test_undo_and_redo_across_typing_and_a_panel_step(window, qtbot):
    window.import_path(str(METAL))
    window.panel.read_timer.setInterval(80)
    wait_idle(qtbot, window)
    session = window.session
    texts = [session.project.text]
    # Typing in the .mod panel
    editor = window.panel.editor
    cursor = editor.textCursor()
    cursor.setPosition(editor.toPlainText().index("chisq ftol"))
    editor.setTextCursor(cursor)
    qtbot.keyClicks(editor, "# typed ")
    wait_idle(qtbot, window)
    texts.append(session.project.text)
    # A step made by a panel (Stages 4–6): an edit through the history
    pm = session.project.parsed
    par = next(p for p in pm.params if p.name == "ColDens")
    window._run(
        "panel", lambda: session.history.edit(E.set_value(pm, par, 14.75), "Set N")
    )
    texts.append(session.project.text)
    assert window.qactions["edit.undo"].text() == "Undo Set N"
    assert window.panel.editor.toPlainText().count("14.75") == 1
    # More typing after the panel's step
    qtbot.keyClicks(editor, "x")
    wait_idle(qtbot, window)
    texts.append(session.project.text)
    assert len(set(texts)) == 4
    for expected in reversed(texts[:-1]):
        window.qactions["edit.undo"].trigger()
        assert session.project.text == expected
        assert window.panel.editor.toPlainText() == window.panel.live.shown
    assert not window.qactions["edit.undo"].isEnabled()
    for expected in texts[1:]:
        window.qactions["edit.redo"].trigger()
        assert session.project.text == expected
    assert not window.qactions["edit.redo"].isEnabled()


def test_undo_reads_what_was_typed_first(window, qtbot):
    window.import_path(str(METAL))
    window.panel.read_timer.setInterval(60000)
    wait_idle(qtbot, window)
    session = window.session
    original = session.project.text
    editor = window.panel.editor
    cursor = editor.textCursor()
    cursor.setPosition(editor.toPlainText().index("chisq ftol"))
    editor.setTextCursor(cursor)
    qtbot.keyClicks(editor, "#")
    assert session.project.text == original and window.panel.live.dirty
    assert window.qactions["edit.undo"].isEnabled()
    window.qactions["edit.undo"].trigger()
    assert session.project.text == original
    assert not window.panel.live.dirty


