"""The user's preferences and the recent projects (dashboard Stage 3.2, Q2.2, Q3.3).

Every test works in a temporary folder, given as ``$ALIS_HOME`` or directly, so the
user's own ``~/.alis`` is never read or written.

Generated by RJC and Claude.
"""

import json

import pytest

from alis.dashboard import preferences as P

pytestmark = pytest.mark.unit


@pytest.fixture
def folder(tmp_path, monkeypatch):
    """A temporary ``$ALIS_HOME``."""
    monkeypatch.setenv(P.HOME_ENV, str(tmp_path))
    return tmp_path


def write(folder, data):
    (folder / P.PREFERENCES).write_text(json.dumps(data), encoding="utf-8")


def test_the_folder_is_alis_home_or_dot_alis(tmp_path, monkeypatch):
    monkeypatch.setenv(P.HOME_ENV, str(tmp_path))
    assert P.home() == str(tmp_path)
    assert P.recovery_dir() == str(tmp_path / "recovery")
    monkeypatch.delenv(P.HOME_ENV)
    monkeypatch.setenv("HOME", str(tmp_path / "me"))
    assert P.home() == str(tmp_path / "me" / ".alis")


def test_the_defaults(folder):
    prefs = P.Preferences.load()
    assert prefs.messages == []
    assert prefs["components.columns"] == 3
    assert prefs["components.velocity_range"] == 200.0
    assert prefs["autosave.interval"] == 60.0
    assert prefs["editor.typing_pause"] == 1.0
    assert prefs["editor.read_delay"] == 0.3
    assert prefs["editor.check_delay"] == 2.0
    assert prefs["new_project.fwhm"] == 7.0
    assert prefs["recent.length"] == 10
    assert prefs.settings()[0] == ("run", "ncpus", "-1")
    assert prefs.settings() == list(P.NEW_PROJECT_SETTINGS)


def test_every_default_is_a_value_its_preference_takes():
    for spec in P.SPECS:
        assert spec.check(spec.default) == (
            [tuple(s) for s in spec.default] if spec.kind is list else spec.default
        )
        assert spec.title and spec.help


def test_the_user_file_overrides_the_defaults(folder):
    write(
        folder,
        {
            "components": {"columns": 2, "velocity_range": 350},
            "autosave": {"interval": 120},
            "new_project": {
                "settings": [["run", "ncpus", "4"], ["chisq", "ftol", "1e-8"]]
            },
        },
    )
    prefs = P.Preferences.load()
    assert prefs.messages == []
    assert prefs["components.columns"] == 2
    assert prefs["components.velocity_range"] == 350.0
    assert isinstance(prefs["components.velocity_range"], float)
    assert prefs["autosave.interval"] == 120.0
    assert prefs["editor.read_delay"] == 0.3
    assert prefs.settings() == [("run", "ncpus", "4"), ("chisq", "ftol", "1e-8")]


@pytest.mark.parametrize(
    "section, name, value, why",
    [
        ("components", "columns", 7, "between 1 and 4"),
        ("components", "columns", 2.5, "whole number"),
        ("components", "columns", "two", "not a number"),
        ("components", "columns", True, "not a number"),
        ("autosave", "interval", -1, "between"),
        ("new_project", "settings", [["run", "nosuch", "1"]], "not an ALIS setting"),
        ("new_project", "settings", [["run", "ncpus", "many"]], "not a value"),
        ("new_project", "settings", "run ncpus 4", "not a list"),
    ],
)
def test_a_bad_value_falls_back_to_the_default(
    folder, logmsgs, section, name, value, why
):
    write(folder, {section: {name: value}, "recent": {"length": 4}})
    prefs = P.Preferences.load()
    key = section + "." + name
    assert prefs[key] == P.SPEC[key].check(P.SPEC[key].default)
    assert prefs["recent.length"] == 4
    assert len(prefs.messages) == 1
    assert key in prefs.messages[0] and why in prefs.messages[0]
    assert "default" in prefs.messages[0]
    assert any(key in m for m in logmsgs)


def test_an_unknown_key_is_ignored_with_a_message(folder):
    write(folder, {"components": {"colums": 2}, "nosuch": {"a": 1}, "flat": 3})
    prefs = P.Preferences.load()
    assert prefs["components.columns"] == 3
    assert len(prefs.messages) == 3
    assert all("ignored" in m for m in prefs.messages)
    assert "components.colums" in prefs.messages[0]


def test_a_file_that_cannot_be_read_gives_the_defaults(folder):
    (folder / P.PREFERENCES).write_text("{not json", encoding="utf-8")
    prefs = P.Preferences.load()
    assert prefs["components.columns"] == 3
    assert len(prefs.messages) == 1 and "cannot be read" in prefs.messages[0]


def test_set_save_and_load_again(folder):
    prefs = P.Preferences.load()
    prefs.set("components.columns", 4)
    prefs.set("new_project.fwhm", 2.5)
    with pytest.raises(P.PreferenceError):
        prefs.set("components.columns", 0)
    with pytest.raises(KeyError):
        prefs.set("nosuch.key", 1)
    prefs.save()
    data = json.loads((folder / P.PREFERENCES).read_text(encoding="utf-8"))
    # Only what differs from the defaults is written
    assert data == {"components": {"columns": 4}, "new_project": {"fwhm": 2.5}}
    again = P.Preferences.load()
    assert again["components.columns"] == 4 and again["new_project.fwhm"] == 2.5
    again.reset("components.columns")
    assert again["components.columns"] == 3
    again.reset()
    assert again.changed() == {}


def test_get_gives_a_copy():
    prefs = P.Preferences()
    prefs.get("new_project.settings").append(("run", "ncpus", "2"))
    assert prefs.settings() == list(P.NEW_PROJECT_SETTINGS)


def test_the_recent_list(folder):
    recent = P.Recent(length=3)
    assert recent.paths() == []
    for name in ("a", "b", "c", "d"):
        recent.add(str(folder / (name + ".model")))
    assert [p.split("/")[-1] for p in recent.paths()] == [
        "d.model",
        "c.model",
        "b.model",
    ]
    # Opening one again moves it to the top
    recent.add(str(folder / "b.model"))
    assert recent.paths()[0].endswith("b.model") and len(recent.paths()) == 3
    again = P.Recent(length=3)
    assert again.paths() == recent.paths()
    again.remove(str(folder / "c.model"))
    assert P.Recent().paths() == [str(folder / "b.model"), str(folder / "d.model")]
    # Kept apart from the preferences
    assert (folder / P.RECENT).exists() and not (folder / P.PREFERENCES).exists()


def test_a_damaged_recent_list_is_empty(folder):
    (folder / P.RECENT).write_text("[1, 2", encoding="utf-8")
    assert P.Recent().paths() == []
    (folder / P.RECENT).write_text('{"projects": [3, {"path": 4}]}', encoding="utf-8")
    assert P.Recent().paths() == []
