def test_data_needs_attention_when_a_source_is_missing_or_changed(
    home, tmp_path, registry
):
    spectrum = tmp_path / "spectrum.dat"
    shutil.copy(SPEC4, spectrum)
    session, _ = S.Session.new(str(tmp_path / "new.model"), [str(spectrum)])
    project = session.project
    assert MK.data_marker(project, session.path).state == MK.COMPLETE
    spectrum.rename(tmp_path / "moved.dat")
    marker = MK.data_marker(project, session.path)
    assert marker.state == MK.ATTENTION and "spectrum.dat is missing" in marker.tip
    table = np.loadtxt(tmp_path / "moved.dat")
    np.savetxt(spectrum, table * 1.01)
    marker = MK.data_marker(project, session.path)
    assert marker.state == MK.ATTENTION and "has changed" in marker.tip
    # An embedded copy is never missing
    os.remove(spectrum)
    shutil.copy(tmp_path / "moved.dat", spectrum)
    B.embed_source(project.bundle, project.bundle.sources[0]["id"], session.path)
    os.remove(spectrum)
    assert MK.data_marker(project, session.path).state == MK.COMPLETE


