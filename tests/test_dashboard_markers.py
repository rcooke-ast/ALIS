def states(project, path=None):
    return {name: m.state for name, m in MK.markers(project, path).items()}


def metal_session(tmp_path, registry):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    return S.Session.open(str(path), registry=registry)


def coldens(project):
    return next(p for p in project.parsed.params if p.name == "ColDens")


