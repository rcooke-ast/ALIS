def tidy(project):
    """Apply the fixes of the notices (metal_line_abs has O I and Si II untied)."""
    for _ in range(5):
        notices = [n for n in project.notices if n.fix is not None]
        if not notices:
            return
        project.apply(project.fix_notice(notices[0]))


def test_components_are_out_of_date_after_a_region_edit(home, tmp_path, registry):
    session = metal_session(tmp_path, registry)
    project = session.project
    tidy(project)
    history = session.history
    assert MK.components_marker(project).state == MK.COMPLETE
    assert MK.MARKS not in project.ui
    # Editing a component records the fingerprints, as part of the same step
    history.edit(E.set_value(project.parsed, coldens(project), 14.5), "Set N")
    marks = project.ui[MK.MARKS]
    assert marks["regions"] == MK.regions_fingerprint(project)
    assert MK.components_marker(project).state == MK.COMPLETE
    # A region edit then makes the components out of date
    history.do(project.set_regions(project.snips[0], [(1301.5, 1302.6)]))
    marker = MK.components_marker(project)
    assert marker.state == MK.STALE
    assert "regions have changed" in marker.tip
    # Undo the region edit: up to date again; undo the component edit: no marks
    history.undo()
    assert MK.components_marker(project).state == MK.COMPLETE
    history.undo()
    assert MK.MARKS not in project.ui
    # A region edit with no marks yet keeps the regions as they were
    history.do(project.set_regions(project.snips[0], [(1301.5, 1302.6)]))
    assert MK.components_marker(project).state == MK.STALE
    # Editing the components again brings them up to date, and is saved
    history.edit(E.set_value(project.parsed, coldens(project), 14.25), "Set N")
    assert MK.components_marker(project).state == MK.COMPLETE
    session.save()
    again = S.Session.open(session.path, registry=registry).project
    assert MK.components_marker(again).state == MK.COMPLETE


def fake_run(project, model_bytes, error=None):
    """A run as run_alis project.model records it, and perhaps a later error."""
    info = {
        "status": "completed",
        "finished": "2026-10-06T10:00:00+01:00",
        "host": "here",
        "chi2_final": 512.25,
        "model_sha256": B.sha256(model_bytes),
    }
    project.bundle.members[B.LATEST + "run.json"] = json.dumps(info).encode()
    if error:
        project.bundle.members[B.LAST_ERROR] = json.dumps(
            {"time": error, "message": "Failed to converge\nmore"}
        ).encode()


def test_fit_is_out_of_date_after_an_edit_once_a_run_exists(home, tmp_path, registry):
    session = metal_session(tmp_path, registry)
    project = session.project
    assert MK.fit_marker(project).state == MK.NONE
    fake_run(project, project.model_bytes()[0])
    marker = MK.fit_marker(project)
    assert marker.state == MK.COMPLETE
    assert marker.tip == (
        "The latest run (completed), χ² = 512.25, finished 2026-10-06 10:00 on here."
    )
    session.history.edit(E.set_value(project.parsed, coldens(project), 14.5), "N")
    marker = MK.fit_marker(project)
    assert marker.state == MK.STALE
    assert marker.tip == "The model has changed since the latest run."
    session.history.undo()
    assert MK.fit_marker(project).state == MK.COMPLETE


def test_fit_needs_attention_when_the_last_run_stopped_with_an_error(
    home, tmp_path, registry
):
    session = metal_session(tmp_path, registry)
    project = session.project
    fake_run(project, project.model_bytes()[0], error="2026-10-06T11:00:00+01:00")
    marker = MK.fit_marker(project)
    assert marker.state == MK.ATTENTION
    assert marker.tip == "The last run stopped with an error: Failed to converge"
    # An error older than the latest run is history
    fake_run(project, project.model_bytes()[0], error="2026-10-06T09:00:00+01:00")
    assert MK.fit_marker(project).state == MK.COMPLETE
    # An error with no run at all
    del project.bundle.members[B.LATEST + "run.json"]
    assert MK.fit_marker(project).state == MK.ATTENTION


