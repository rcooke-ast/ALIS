"""The fitting process's standard input, and how the process ends (dashboard Stage 13,
point 2).

Users saw "Python quit unexpectedly" when a fit ended: the process's thread for Stop
waited on its standard input through Python's buffered reader, holding its lock, and
Python's shutdown, closing ``sys.__stdin__``, aborted when it could not take it
(SIGABRT). The input is now read from its descriptor (``runner.Input``).

- The header, the project and the commands are read whole and in order, a project
  larger than a pipe holds included, and a ``stop`` that arrives with the project is
  kept for the command thread.
- The process ends with 0 while the dashboard still holds its standard input open
  (before, −6): shown on a project that cannot be read, which ends the run at once.

Marked ``unit``: no fit is run (the process stops at the project it cannot read).

Generated by RJC and Claude.
"""

import json
import os
import subprocess
import sys
import threading

import pytest

from alis.dashboard import runner as RN

pytestmark = pytest.mark.unit


def _pipe(payload):
    """A pipe's read end, with ``payload`` written into it by a thread, then closed."""
    read, write = os.pipe()

    def feed():
        with os.fdopen(write, "wb") as out:
            out.write(payload)

    thread = threading.Thread(target=feed, daemon=True)
    thread.start()
    return read, thread


def test_input_reads_the_header_the_project_and_the_commands():
    project = bytes(range(256)) * 12000  # 3 MB, more than a pipe holds
    header = json.dumps({"protocol": RN.PROTOCOL, "size": len(project)}).encode()
    read, thread = _pipe(header + b"\n" + project + b"stop\nother\n")
    stdin = RN.Input(read)
    try:
        assert stdin.readline() == header + b"\n"
        assert stdin.read(len(project)) == project
        # What came with the project's tail is kept for the commands
        assert list(stdin) == [b"stop\n", b"other\n"]
        assert stdin.read(10) == b""
        assert stdin.readline() == b""
    finally:
        thread.join(5)
        os.close(read)


def test_a_last_line_with_no_newline_is_read():
    read, thread = _pipe(b"stop")
    try:
        assert list(RN.Input(read)) == [b"stop"]
    finally:
        thread.join(5)
        os.close(read)


def test_the_command_thread_reads_stop():
    read, write = os.pipe()
    commands = RN.Commands(RN.Input(read))
    commands.start()
    try:
        os.write(write, b"something\n")
        assert not commands.stop
        os.write(write, b"stop\n")
    finally:
        os.close(write)
    commands.join(5)
    assert not commands.is_alive()
    assert commands.stop
    os.close(read)


def test_the_process_ends_without_an_abort_with_its_input_held_open():
    data = b"not a project"
    header = {
        "protocol": RN.PROTOCOL,
        "size": len(data),
        "path": None,
        "settings": [],
        "command": "test",
    }
    proc = subprocess.Popen(
        [sys.executable, "-m", "alis.dashboard.runner"],
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
    )
    try:
        proc.stdin.write(json.dumps(header).encode("utf-8") + b"\n" + data)
        proc.stdin.flush()
        messages = []
        for line in proc.stdout:
            messages.append(json.loads(line.decode("utf-8")))
            if messages[-1]["event"] == "finished":
                break
        # The dashboard has not closed the process's standard input: the command
        # thread still waits on it as the process ends (before, −6: SIGABRT)
        assert proc.wait(timeout=60) == 0
    finally:
        if proc.poll() is None:
            proc.kill()
        proc.stdin.close()
        proc.stdout.close()
    assert messages[-1]["status"] == "error"
    assert "not a project bundle" in messages[-1]["message"]
