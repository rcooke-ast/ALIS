def do(project, step):
    """Make a step, and check that undoing it gives back the project's ui exactly."""
    before = json.dumps(project.ui, sort_keys=True)
    project.apply(step)
    assert json.dumps(project.ui, sort_keys=True) != before
    project.revert(step)
    assert json.dumps(project.ui, sort_keys=True) == before
    project.apply(step)
    return step


def made(project, **layout):
    """A new figure; its id."""
    step, fid = FG.new_figure(project, layout=layout or None)
    do(project, step)
    return fid


def entries(project):
    return {e.line: e for e in FG.transitions(project)}


