def test_options_and_apply_to_all_panels(metal):
    fid = made(metal)
    found = entries(metal)
    do(metal, FG.place(metal, fid, 0, 0, found["O I 1302.2"].key))
    do(metal, FG.place(metal, fid, 0, 1, found["Si II 1304.4"].key))
    do(metal, FG.set_cell(metal, fid, 0, 1, "axis", FG.OBSERVED))
    cell = FG.cell_at(FG.figure(metal, fid), 0, 1)[0]
    # A panel whose axis differs from the figure's titles its own x axis (Q9.9)
    assert cell["xtitle"] is True and cell["xrange"] is None
    # Its default range: the velocity range at its transition (Q9.8 (i))
    low, high = FG.x_range(FG.figure(metal, fid), cell, 1304.3702)
    assert low == pytest.approx(1304.3702 * (1 - 125.0 / 299792.458))
    assert high == pytest.approx(1304.3702 * (1 + 125.0 / 299792.458))
    do(metal, FG.set_cell(metal, fid, 0, 1, "xrange", [1303.9, 1304.9]))
    with pytest.raises(FG.FigureError, match="cannot be applied to all panels"):
        FG.set_cell(metal, fid, 0, 1, "xrange", [1303.9, 1304.9], every=True)
    # A velocity range applied to all: the figure's, the panels' own cleared
    do(metal, FG.set_cell(metal, fid, 0, 0, "xrange", [-80.0, 60.0]))
    do(metal, FG.set_cell(metal, fid, 0, 0, "xrange", [-90.0, 90.0], every=True))
    fig = FG.figure(metal, fid)
    assert fig["vrange"] == [-90.0, 90.0]
    assert FG.cell_at(fig, 0, 0)[0]["xrange"] is None
    assert FG.cell_at(fig, 0, 1)[0]["xrange"] == [1303.9, 1304.9]
    # One step sets the flux range on every panel, empty ones too
    step = do(metal, FG.set_cell(metal, fid, 0, 0, "yrange", [0.5, 1.2], every=True))
    assert step.description == "Set yrange on all panels"
    assert {tuple(c["yrange"]) for _, _, c in FG.places(FG.figure(metal, fid))} == {
        (0.5, 1.2)
    }
    with pytest.raises(FG.FigureError, match="first number must be below"):
        FG.set_cell(metal, fid, 0, 0, "yrange", [1.0, 0.0])
    # The figure's own options
    do(metal, FG.set_option(metal, fid, "titles", [True, False]))
    do(metal, FG.set_option(metal, fid, "numbered", True))
    do(metal, FG.set_option(metal, fid, "residuals", FG.INSIDE))
    with pytest.raises(FG.FigureError):
        FG.set_option(metal, fid, "residuals", "below")


def test_q9_12_s_options_are_steps(metal):
    fid = made(metal)
    do(metal, FG.place(metal, fid, 0, 0, entries(metal)["O I 1302.2"].key))
    for key, value in (
        ("corner", "upper right"),
        ("title", "UVES data"),
        ("yticks", [1.0, 0.6, 0.8]),
        ("yright", True),
        ("ions", ["16O_I"]),
        ("components", ["a1"]),
        ("label", "O I"),
    ):
        do(metal, FG.set_cell(metal, fid, 0, 0, key, value))
    cell = FG.cell_at(FG.figure(metal, fid), 0, 0)[0]
    assert cell["yticks"] == [0.6, 0.8, 1.0] and cell["corner"] == "upper right"
    # Those marked ✱ apply to all panels; the others are set panel by panel
    for key, value in (("corner", "upper left"), ("yticks", [0.0, 1.0])):
        do(metal, FG.set_cell(metal, fid, 0, 0, key, value, every=True))
    for key in ("title", "ions", "components", "label"):
        with pytest.raises(FG.FigureError, match="panel by panel"):
            FG.set_cell(
                metal,
                fid,
                0,
                0,
                key,
                None if key in ("ions", "components") else "x",
                every=True,
            )
    with pytest.raises(FG.FigureError, match="corner"):
        FG.set_cell(metal, fid, 0, 0, "corner", "middle")


def test_the_numbers_follow_a_panel_s_place(metal):
    fid = made(metal)
    fig = FG.figure(metal, fid)
    # 3 × 3: x on the bottom row; y on the left and, on its right, the right column
    got = {(r, s): FG.numbers(fig, r, s) for r, s, _ in FG.places(fig)}
    assert got[(0, 0)] == (True, True, False)  # nothing below shows a transition
    o1 = entries(metal)["O I 1302.2"].key
    for row in range(3):
        do(metal, FG.place(metal, fid, row, 1, o1))
    fig = FG.figure(metal, fid)
    assert [FG.numbers(fig, r, 1)[0] for r in range(3)] == [False, False, True]
    # Alone in its row, a panel is numbered on the left
    assert FG.numbers(fig, 0, 1)[1:] == (True, False)
    for col in (0, 2):
        do(metal, FG.place(metal, fid, 0, col, o1))
    fig = FG.figure(metal, fid)
    assert FG.numbers(fig, 0, 0)[1:] == (True, False)
    assert FG.numbers(fig, 0, 1)[1:] == (False, False)
    assert FG.numbers(fig, 0, 2)[1:] == (True, True)
    # An empty cell after a panel counts as no panel: it is the row's last
    do(metal, FG.remove(metal, fid, 0, 2))
    assert FG.numbers(FG.figure(metal, fid), 0, 1)[1:] == (True, True)
    # A panel below with another x axis numbers the one above
    do(metal, FG.set_cell(metal, fid, 1, 1, "axis", FG.REST))
    fig = FG.figure(metal, fid)
    assert FG.numbers(fig, 0, 1)[0] is True
    # The cell's own choice wins
    do(metal, FG.set_cell(metal, fid, 2, 1, "xnumbers", False))
    assert FG.numbers(FG.figure(metal, fid), 2, 1)[0] is False


def test_a_preset_saved_and_loaded_in_another_project(metal, registry, tmp_path):
    fid = made(metal)
    found = entries(metal)
    do(metal, FG.set_grid(metal, fid, 2, 1))
    do(metal, FG.place(metal, fid, 0, 0, found["Si II 1304.4"].key))
    do(metal, FG.place(metal, fid, 0, 1, found["O I 1302.2"].key))
    do(metal, FG.set_cell(metal, fid, 0, 1, "axis", FG.REST))
    home = tmp_path / "home"
    path = FG.save_preset(metal, fid, "my metals", str(home))
    assert Path(path).name == "my metals.json"
    assert FG.saved_presets(str(home)) == ["my metals"]
    with pytest.raises(FG.FigureError, match="dashboard's own"):
        FG.save_preset(metal, fid, "DH", str(home), builtin=("metals", "DH"))
    # Another project: a fresh import, with no figure yet
    other = P.Project.import_model(str(METAL), registry=registry)
    layout = FG.load_preset(other, "my metals", str(home))
    step, new = FG.new_figure(other, layout=layout)
    other.apply(step)
    fig = FG.figure(other, new)
    assert [k["ion"] for _, _, k in FG.shown(fig)] == ["28Si_II", "16O_I"]
    assert fig["preset"] == "my metals" and fig["cells"][0][1]["axis"] == FG.REST


def test_a_cell_whose_snip_is_removed_is_empty_with_a_note(tmp_path, registry):
    project = P.Project.import_model(
        str(write_shifted_fit(tmp_path / "fit")), registry=registry
    )
    fid = made(project)
    lyb = [e for e in FG.transitions(project) if e.line == "Lyβ 1025.7"][1]
    do(project, FG.place(project, fid, 0, 0, lyb.key))
    assert FG.missing(project, fid) == []
    step = RM.plan_snip(project, project.snip(lyb.specid)).step(project)
    project.apply(step)
    [(row, start, note)] = FG.missing(project, fid)
    assert (row, start) == (0, 0)
    assert note == (
        "Lyβ 1025.7 (snip 3) is no longer in the project, so this panel is empty."
    )
    project.revert(step)
    assert FG.missing(project, fid) == []


def test_examples_blind_s_figures_hold_no_hidden_value(registry):
    project = P.Project.import_model(str(BLIND), registry=registry)
    fid = made(project)
    for num, entry in enumerate(FG.transitions(project)):
        do(project, FG.place(project, fid, 0, num, entry.key))
    # No value of the figures is a hidden one, as written
    words = set(re.findall(r"[-+]?[\d.]+", json.dumps(project.ui[FG.FIGURES_KEY])))
    hidden = BL.Gate(project).hidden_values()
    assert hidden and not hidden & words


def test_the_figure_tab_s_marker(metal):
    from alis.dashboard import markers as MK

    assert MK.figure_marker(metal, FG.NO_FIT) == MK.Marker(MK.NONE, FG.NO_FIT)
    assert MK.figure_marker(metal, "").tip.startswith("No figure yet")
