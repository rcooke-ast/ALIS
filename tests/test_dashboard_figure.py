"""The Figure tab's figures, cells and steps (dashboard Stage 9, Task 9.2; D28, D42,
S22; Q9.6–Q9.10, Q9.12). No Qt.

- Every change is one step of ``ui/project.json``, and undo is exact: a figure
  created (its layout copied, every cell empty), renamed and deleted; the grid, a
  span, a drop, a swap, a copy, a drag off; the figure's and the cells' options, and
  Apply to all panels.
- A name must make a file name and be free; a span cannot pass its row's end, and
  sends the cells it covers back to Not shown, as a smaller grid does.
- The same transition from the same snip in two panels, of one figure or two, is
  reported with the panels' names; Lyα of two datasets is not.
- A wavelength panel's default range is the velocity range at its transition; a
  wavelength range cannot be applied to all panels.
- The x and y numbers follow a panel's place, as the reference scripts number
  theirs, unless the cell sets them.
- A preset saved and loaded in another project fills the cells it can; a cell whose
  snip is removed shows nothing, with a note, and comes back on undo.
- ``examples/blind``'s figures hold no hidden value.

Generated by RJC and Claude.
"""

