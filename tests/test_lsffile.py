"""ALIS's ``lsffile`` with a kernel in km/s (dashboard Stage 13, point 4; Q13.6 (a)).

``lsffile`` reads its file's first column as Δλ in Å. With ``unit:kms`` it reads it
as Δv in km/s: the kernel is sampled at each sub-pixel's velocity offset from the
centre one, c·(λ/λc − 1), as ``vfwhm`` makes its Gaussian, and its buffer is the
kernel's width taken to Å at each end of the fit range.

- A Gaussian kernel in km/s gives the model that ``vfwhm`` gives for its FWHM, on
  sub-pixels uniform in log wavelength and in wavelength.
- Without the keyword, or with ``unit:A``, the file is read in Å, as before.
- The buffer of a km/s kernel is ``vfwhm``'s for the same FWHM.
- An unknown unit is refused, with its reason.

The ``.mod.out`` keeping ``unit:kms`` is checked with the other keywords in
``test_save_helpers.py``.

Generated by RJC and Claude.
"""

import numpy as np
import pytest

from alis.functions.lsffile import LSFFile
from alis.functions.vfwhm import vFWHM

pytestmark = pytest.mark.unit

C_KMS = 299792.458
FWHM_SIGMA = 2.0 * np.sqrt(2.0 * np.log(2.0))


def write_kernel(path, fwhm, nsig=15.0, samples=4097):
    """A Gaussian kernel of ``fwhm`` (in the offsets' unit), well sampled."""
    sigma = fwhm / FWHM_SIGMA
    offsets = np.linspace(-nsig * sigma, nsig * sigma, samples)
    np.savetxt(
        str(path), np.column_stack([offsets, np.exp(-0.5 * (offsets / sigma) ** 2)])
    )
    return str(path)


def grid(linear, centre=5000.0, dv=0.25, size=2001):
    """Sub-pixels around ``centre``: uniform in log wavelength (``dv`` km/s), or in
    wavelength (the same step at the centre)."""
    half = np.arange(size) - size // 2
    if linear:
        return centre + half * centre * dv / C_KMS
    return centre * np.exp(half * dv / C_KMS)


def spectrum(wave):
    """A continuum of 1 with two absorption lines, one narrow."""
    centre = wave[wave.size // 2]
    out = 1.0 - 0.8 * np.exp(-0.5 * ((wave - centre) / (centre * 4.0 / C_KMS)) ** 2)
    off = centre * (1.0 + 60.0 / C_KMS)
    return out - 0.5 * np.exp(-0.5 * ((wave - off) / (centre * 1.5 / C_KMS)) ** 2)


def convolved(path, wave, unit=None):
    inst = LSFFile()
    mkey = {"name": path, "index": 0}
    if unit is not None:
        mkey["unit"] = unit
    return inst.call_CPU(wave, spectrum(wave), np.array([1.0]), mkey=mkey)


@pytest.mark.parametrize("linear", [False, True])
@pytest.mark.parametrize("fwhm", [3.0, 7.0])
def test_a_kernel_in_km_s_gives_vfwhm_s_model(tmp_path, linear, fwhm):
    path = write_kernel(tmp_path / "kms.dat", fwhm)
    wave = grid(linear)
    got = convolved(path, wave, unit="kms")
    expected = vFWHM().call_CPU(wave, spectrum(wave), np.array([fwhm]))
    # Away from the ends, where each convolution meets the edge of the array. On
    # sub-pixels linear in wavelength, each takes its velocity offsets from another
    # sub-pixel (vfwhm near the start, lsffile at the centre), and they agree to
    # 2e-4 of the continuum here; on sub-pixels uniform in log wavelength, exactly
    inner = slice(200, wave.size - 200)
    tolerance = 1.0e-3 if linear else 1.0e-4
    assert np.max(np.abs(got[inner] - expected[inner])) < tolerance


def test_a_kernel_in_angstroms_is_read_as_before(tmp_path):
    wave = grid(False)
    path = write_kernel(tmp_path / "A.dat", 5000.0 * 7.0 / C_KMS)
    before = convolved(path, wave)
    assert np.array_equal(convolved(path, wave, unit="A"), before)
    # ...and, at the line's wavelength, as the same kernel in km/s
    kms = write_kernel(tmp_path / "kms.dat", 7.0)
    assert np.max(np.abs(convolved(kms, wave, unit="kms") - before)[200:-200]) < 1e-4


def test_the_buffer_of_a_kernel_in_km_s_is_vfwhm_s(tmp_path):
    path = write_kernel(tmp_path / "kms.dat", 7.0)
    fitrng = [4990.0, 5010.0]
    got = LSFFile().getminmax(["name:" + path, "unit:kms"], fitrng)
    expected = vFWHM().getminmax(["7.0"], fitrng, Nsig=30.0)
    # The kernel's FWHM is read from its samples, to their spacing
    widths = [fitrng[0] - got[0], got[1] - fitrng[1]]
    wanted = [fitrng[0] - expected[0], expected[1] - fitrng[1]]
    assert widths == pytest.approx(wanted, rel=1.0e-2)
    # In Å, its width is taken as Å, as before
    angstroms = LSFFile().getminmax(["name:" + path], fitrng)
    sigma = 7.0 / FWHM_SIGMA
    assert angstroms[0] == pytest.approx(fitrng[0] - 30.0 * sigma, rel=1e-4)


def test_an_unknown_unit_is_refused(tmp_path):
    path = write_kernel(tmp_path / "kms.dat", 7.0)
    mp = {key: [] for key in ("mtyp", "mpar", "mtie", "mfix", "mlim", "mkey", "p0")}
    mp["tpar"] = []
    with pytest.raises(SystemExit):
        LSFFile().load("name:{0},unit:pc".format(path), 0, mp, ["0"])
