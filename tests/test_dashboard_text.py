"""The dashboard's model text (dashboard Stage 2.2).

Reading a model never changes it (QF.5): every model in ``examples/`` and
``context/fitting_examples/``, and every ``.mod.out.reference``, comes back byte for
byte. The text is split into blocks exactly as ``alis.load.load_input`` splits it,
and a patch changes only its own span and can be undone.

Generated by RJC and Claude.
"""

from pathlib import Path

import pytest

from alis import load
from alis.config import ArgFlag
from alis.dashboard import text as T

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]


def model_files():
    """Every ``.mod`` and ``.mod.out.reference`` in the two model folders."""
    found = []
    for folder in ("examples", "context/fitting_examples"):
        base = ROOT / folder
        if base.is_dir():
            found += sorted(base.rglob("*.mod"))
            found += sorted(base.rglob("*.mod.out.reference"))
    return found


MODELS = model_files()


def _ids(paths):
    return [str(p.relative_to(ROOT)) for p in paths]


def test_there_are_models_to_read():
    assert len(MODELS) >= 40


@pytest.mark.parametrize("path", MODELS, ids=_ids(MODELS))
def test_reading_a_model_gives_back_the_same_bytes(path):
    raw = path.read_bytes()
    mtext = T.ModelText(raw.decode("utf-8"))
    assert mtext.text.encode("utf-8") == raw
    joined = "".join(line.text + line.ending for line in mtext.lines)
    assert joined.encode("utf-8") == raw
    for line in mtext.lines:
        for tok in line.tokens:
            assert line.text[tok.start : tok.end] == tok.text
            assert tok.line == line.num


class _Reader:
    def __init__(self):
        self._argflag = ArgFlag()
        self._argflag["out"]["verbose"] = -1


def _alis_split(text):
    """``load_input``'s four lists of lines, or None if it stops."""
    try:
        return load.load_input(
            _Reader(), textstr=text.splitlines(keepends=True), updateself=False
        )
    except SystemExit:
        return None


@pytest.mark.parametrize("path", MODELS, ids=_ids(MODELS))
def test_the_blocks_are_split_as_alis_splits_them(path):
    text = path.read_text()
    split = _alis_split(text)
    if split is None:
        pytest.skip("ALIS does not read this model on its own")
    parlines, datlines, modlines, lnklines = split
    mtext = T.ModelText(text)
    model_kinds = (T.SECTION, T.FIX, T.LIM, T.FUNCTION)

    def mine(*kinds):
        return [ln.text for ln in mtext.lines if ln.kind in kinds]

    def theirs(lines):
        return [ln.rstrip("\r\n") for ln in lines]

    assert mine(T.SETTING) == theirs(parlines)
    assert mine(T.DATA) == theirs(datlines)
    assert mine(*model_kinds) == theirs(modlines)
    assert mine(T.LINK) == theirs(lnklines)
    assert not [p for p in mtext.problems if p.severity == "error"]


# -- Structure ---------------------------------------------------------------------

MINIMAL = """run ncpus 1
data read
  a.dat specid=0
data end
model read
 emission
  constant 1.0 specid=0
model end
"""


def kinds(text):
    return [line.kind for line in T.ModelText(text).lines]


def test_each_line_is_classified():
    assert kinds(MINIMAL) == [
        T.SETTING,
        T.BLOCK,
        T.DATA,
        T.BLOCK,
        T.BLOCK,
        T.SECTION,
        T.FUNCTION,
        T.BLOCK,
    ]
    mtext = T.ModelText(MINIMAL)
    assert mtext.block_lines("data") == (1, 3)
    assert mtext.block_lines("model") == (4, 7)
    assert mtext.block_lines("link") == (None, None)
    assert [ln.block for ln in mtext.lines] == [
        "",
        "data",
        "data",
        "data",
        "model",
        "model",
        "model",
        "model",
    ]


def test_comments_and_long_comments_are_never_content():
    text = MINIMAL.replace(
        " emission\n", " emission\n#-->\n  voigt x\n" "  more\n<--#\n# constant 2.0\n\n"
    )
    mtext = T.ModelText(text)
    assert [ln.kind for ln in mtext.lines[5:12]] == [
        T.SECTION,
        T.COMMENT,
        T.LONG,
        T.LONG,
        T.LONG,
        T.COMMENT,
        T.BLANK,
    ]
    assert not mtext.problems


def test_text_before_a_long_comment_is_still_read():
    text = MINIMAL.replace(
        "  constant 1.0 specid=0\n",
        "  constant 1.0 specid=0  #--> start\n junk\n<--#\n",
    )
    mtext = T.ModelText(text)
    assert mtext[6].kind == T.FUNCTION
    assert mtext[6].words == ["constant", "1.0", "specid=0"]
    assert mtext[6].comment == "#--> start"
    assert [mtext[7].kind, mtext[8].kind] == [T.LONG, T.LONG]


def test_fix_lim_and_settings_lines():
    text = MINIMAL.replace(
        " emission\n",
        " fix voigt temperature True\n" " lim param jc [20.0,21.0]\n emission\n",
    )
    mtext = T.ModelText(text)
    assert [mtext[5].kind, mtext[6].kind] == [T.FIX, T.LIM]
    assert mtext[0].words == ["run", "ncpus", "1"]


def test_a_hidden_line_is_recognised():
    text = MINIMAL.replace("  constant 1.0 specid=0", "  <hidden:1>")
    assert T.ModelText(text)[6].kind == T.HIDDEN


@pytest.mark.parametrize(
    "change, message",
    [
        (("data end\n", ""), "'data end' is missing"),
        (("model end\n", ""), "'model end' is missing"),
        (("data read\n  a.dat specid=0\ndata end\n", ""), "no data block"),
        (("model read\n", "#model read\n"), "no model block"),
        ((" emission\n", " emission\n<--#\n"), "never started"),
        ((" emission\n", " emission\n#--> <--#\n"), "Only one long comment"),
    ],
)
def test_structural_problems_are_found(change, message):
    text = MINIMAL.replace(*change)
    problems = T.ModelText(text).problems
    assert any(message in p.message for p in problems), problems


def test_an_unclosed_long_comment_swallows_the_rest():
    text = MINIMAL.replace(" emission\n", " emission\n#-->\n")
    mtext = T.ModelText(text)
    assert mtext[6].kind == T.COMMENT
    assert all(ln.kind == T.LONG for ln in mtext.lines[7:])
    assert any("'model end' is missing" in p.message for p in mtext.problems)


def test_line_endings_are_kept():
    for newline in ("\n", "\r\n", "\r"):
        text = MINIMAL.replace("\n", newline)
        mtext = T.ModelText(text)
        assert mtext.text == text
        assert mtext.newline() == newline
        assert kinds(text) == kinds(MINIMAL)
    last = MINIMAL.rstrip("\n")
    assert T.ModelText(last)[-1].ending == ""


def test_position_and_offset_agree():
    mtext = T.ModelText(MINIMAL)
    for line in mtext.lines:
        for tok in line.tokens:
            off = mtext.token_offset(tok)
            assert mtext.text[off : off + len(tok.text)] == tok.text
            assert mtext.position(off) == (tok.line, tok.start)
            assert mtext.token_at(tok.line, tok.start) == tok


# -- Values, labels and keywords ---------------------------------------------------


@pytest.mark.parametrize(
    "word, value, label",
    [
        ("5.0da", "5.0", "da"),
        ("14.0", "14.0", None),
        ("1.0E+04ta", "1.0E+04", "ta"),
        ("8.8208335E+03", "8.8208335E+03", None),
        ("1e4", "1", "e4"),
        ("-4.60dhtie", "-4.60", "dhtie"),
        ("0.0000000ZEROT", "0.0000000", "ZEROT"),
        ("3.0672596274ra", "3.0672596274", "ra"),
        ("2.3e-3b", "2.3e-3", "b"),
    ],
)
def test_values_and_labels_split_as_alis_splits_them(word, value, label):
    tok = T.Token(word, 3, 10, 10 + len(word))
    val, lab = T.split_value(tok)
    assert val.text == value
    assert val.start == 10
    if label is None:
        assert lab is None
    else:
        assert lab.text == label
        assert (lab.start, lab.end) == (10 + len(value), 10 + len(word))


def test_keywords_and_function_arguments():
    tok = T.Token("resolution=vfwhm(6.974va)", 0, 4, 29)
    key, val = T.split_keyword(tok)
    assert (key.text, val.text, val.start) == ("resolution", "vfwhm(6.974va)", 15)
    name, args = T.function_args(val)
    assert name.text == "vfwhm"
    assert [(a.text, a.start) for a in args] == [("6.974va", 21)]
    _, args = T.function_args(T.Token("vshiftscale(0.0,1.0SC)", 0, 0, 22))
    assert [(a.text, a.start, a.end) for a in args] == [
        ("0.0", 12, 15),
        ("1.0SC", 16, 21),
    ]
    assert T.split_keyword(T.Token("14.0", 0, 0, 4)) is None


# -- Patches -----------------------------------------------------------------------

LINE = "  voigt   ion=1H_I   13.0ra   2.5   5.0   specid=0   # note\n"


def test_a_longer_value_keeps_the_next_column():
    mtext = T.ModelText(LINE)
    tok = mtext[0].tokens[2]
    val, _ = T.split_value(tok)
    new = mtext.apply(T.Change((T.replace_token(mtext, val, "13.0482"),)))
    assert new.text == "  voigt   ion=1H_I   13.0482ra 2.5   5.0   specid=0   # note\n"
    longer = mtext.apply(T.Change((T.replace_token(mtext, val, "13.048219"),)))
    assert longer.text == (
        "  voigt   ion=1H_I   13.048219ra 2.5   5.0   specid=0" "   # note\n"
    )
    shorter = mtext.apply(T.Change((T.replace_token(mtext, val, "13"),)))
    assert shorter.text == LINE.replace("13.0ra   2.5", "13ra     2.5")


def test_the_last_word_and_tabs_are_left_alone():
    mtext = T.ModelText("  a 1.0\tb 2.0  \n")
    tok = mtext[0].tokens[1]
    assert T.replace_token(mtext, tok, "1.25").new == "1.25"
    last = mtext[0].tokens[-1]
    assert T.replace_token(mtext, last, "2.75").new == "2.75"


def test_lines_are_replaced_inserted_and_deleted():
    mtext = T.ModelText("A\nB\nC")
    assert mtext.apply(T.replace_line(mtext, 1, "BB")).text == "A\nBB\nC"
    assert mtext.apply(T.insert_lines(mtext, 1, ["X", "Y"])).text == "A\nX\nY\nB\nC"
    assert mtext.apply(T.insert_lines(mtext, 3, ["Z"])).text == "A\nB\nC\nZ"
    assert mtext.apply(T.delete_lines(mtext, 1)).text == "A\nC"
    assert mtext.apply(T.delete_lines(mtext, 2)).text == "A\nB"
    assert mtext.apply(T.delete_lines(mtext, 0, 3)).text == ""
    assert mtext.apply(T.replace_lines(mtext, 1, 3, ["Q"])).text == "A\nQ"
    ended = T.ModelText("A\nB\n")
    assert ended.apply(T.insert_lines(ended, 2, ["Z"])).text == "A\nB\nZ\n"
    assert T.ModelText("").apply(T.insert_lines(T.ModelText(""), 0, ["Z"])).text == (
        "Z\n"
    )


def test_lines_are_followed_through_a_patch():
    mtext = T.ModelText("A\nB\nC\nD\n")
    ins = T.insert_lines(mtext, 1, ["X"])
    assert [ins.map_line(mtext, n) for n in range(4)] == [0, 2, 3, 4]
    dele = T.delete_lines(mtext, 1, 3)
    assert [dele.map_line(mtext, n) for n in range(4)] == [0, None, None, 1]
    edit = T.replace_line(mtext, 2, "CC")
    assert [edit.map_line(mtext, n) for n in range(4)] == [0, 1, 2, 3]
    change = T.Change((ins, T.delete_lines(mtext.apply(ins), 0)))
    assert [change.map_line(mtext, n) for n in range(4)] == [None, 1, 2, 3]


def test_layout_copies_the_columns_of_its_template():
    template = T.ModelText(
        "    voigt   ion=1H_I     19.58hia      2.52ra  "
        "    5.7da      6.5E+03      specid=A\n"
    )[0]
    words = ["voigt", "ion=16O_I", "14.0", "2.52ra", "5.7da", "0.0TA", "specid=A"]
    line = T.layout_like(template, words)
    assert line.startswith("    voigt   ion=16O_I    14.0")
    for word, tok in zip(words, template.tokens):
        assert line.index(word) == tok.start
    assert T.layout_like(None, ["a", "b"]) == "  a  b"


def test_overlapping_patches_are_refused():
    with pytest.raises(T.PatchError):
        T.Change.from_spans([T.Patch(0, "ab", "x"), T.Patch(1, "b", "y")])
    with pytest.raises(T.PatchError):
        T.Patch(0, "zz", "y").apply("ab")


# -- Property tests: a patch changes only its own span -----------------------------

hypothesis = pytest.importorskip("hypothesis")
st = hypothesis.strategies

SAMPLE = (ROOT / "examples/metal_line_abs/model/fit_spectra.mod").read_text()
SAMPLE_TEXT = T.ModelText(SAMPLE)
WORDS = [tok for line in SAMPLE_TEXT.lines for tok in line.tokens]
NEW = st.text(alphabet="abcXYZ0123456789.+- ", min_size=0, max_size=12)
NEWLINE_FREE = st.text(alphabet="abcXYZ0123456789.+-", min_size=1, max_size=12)


def _patch(mtext, choice):
    """One patch of each kind, chosen by hypothesis."""
    kind, index, new, count = choice
    nlines = len(mtext)
    if kind == "token":
        words = [t for ln in mtext.lines for t in ln.tokens]
        if not words:
            return T.insert_lines(mtext, 0, [new])
        return T.replace_token(mtext, words[index % len(words)], new or "x")
    if kind == "line":
        return (
            T.replace_line(mtext, index % max(nlines, 1), new)
            if nlines
            else T.insert_lines(mtext, 0, [new])
        )
    if kind == "insert":
        return T.insert_lines(mtext, index % (nlines + 1), [new] * (count + 1))
    first = index % max(nlines, 1)
    return (
        T.delete_lines(mtext, first, min(nlines, first + count + 1))
        if nlines
        else T.insert_lines(mtext, 0, [new])
    )


CHOICE = st.tuples(
    st.sampled_from(["token", "line", "insert", "delete"]),
    st.integers(0, 10_000),
    NEWLINE_FREE,
    st.integers(0, 3),
)


@hypothesis.settings(max_examples=200, deadline=None, database=None)
@hypothesis.given(st.sampled_from(WORDS), NEW)
def test_a_token_patch_changes_only_its_span(token, new):
    patch = T.replace_token(SAMPLE_TEXT, token, new)
    out = patch.apply(SAMPLE)
    assert out[: patch.start] == SAMPLE[: patch.start]
    assert out[patch.start + len(patch.new) :] == SAMPLE[patch.end :]
    # Everything outside the token's own line is untouched
    line = SAMPLE_TEXT[token.line]
    assert patch.start >= line.offset and patch.end <= line.end
    assert patch.inverse().apply(out) == SAMPLE


@hypothesis.settings(max_examples=200, deadline=None, database=None)
@hypothesis.given(st.lists(CHOICE, min_size=1, max_size=8))
def test_any_sequence_of_patches_is_undone_exactly(choices):
    mtext, patches = SAMPLE_TEXT, []
    for choice in choices:
        patch = _patch(mtext, choice)
        out = patch.apply(mtext.text)
        assert out[: patch.start] == mtext.text[: patch.start]
        assert out[patch.start + len(patch.new) :] == mtext.text[patch.end :]
        patches.append(patch)
        mtext = T.ModelText(out)
    change = T.Change(tuple(patches))
    assert change.apply(SAMPLE) == mtext.text
    assert change.inverse().apply(mtext.text) == SAMPLE
    # The text read again is the same text
    assert T.ModelText(mtext.text).text == mtext.text
