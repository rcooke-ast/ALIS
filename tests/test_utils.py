"""Unit tests for the pure conversion helpers in ``alis.utils``.

Covers the roman-numeral <-> ion-charge conversions, the atomic-number ->
element conversion (including its special-case elements), and the
convergence-reason lookup. All are pure functions with no fit dependency.

Generated by RJC and Claude.
"""

import pytest

from alis import utils

pytestmark = pytest.mark.unit


# -- numtorn / rntonum (roman numerals <-> ion charge) -----------------------


def test_numtorn_neutral_state_toggle():
    # subone=False: cnt == 1 is the neutral state ("I").
    assert utils.numtorn(1) == "I"
    assert utils.numtorn(2) == "II"
    # subone=True: cnt == 0 is the neutral state ("I").
    assert utils.numtorn(0, subone=True) == "I"
    assert utils.numtorn(1, subone=True) == "II"


def test_numtorn_selected_values():
    assert utils.numtorn(4) == "IV"
    assert utils.numtorn(9) == "IX"
    assert utils.numtorn(40) == "XL"
    assert utils.numtorn(55) == "LV"


def test_rntonum_maps_to_zero_based_charge():
    # rntonum returns the ion charge (0-based): "I" -> 0, "II" -> 1, ...
    assert utils.rntonum("I") == 0
    assert utils.rntonum("V") == 4
    assert utils.rntonum("XV") == 14


def test_numtorn_rntonum_round_trip():
    # numtorn(subone=True) uses 0 as neutral, matching rntonum's 0-based charge.
    for charge in range(0, 15):
        assert utils.rntonum(utils.numtorn(charge, subone=True)) == charge


def test_numtorn_out_of_range_errors():
    # msgs.error terminates via sys.exit (preserved almsgs semantics).
    with pytest.raises(SystemExit):
        utils.numtorn(56)
    with pytest.raises(SystemExit):
        utils.numtorn(0)  # subone=False -> neutral is 1, so 0 is < 1


# -- numtoelem (atomic number -> element) ------------------------------------


def test_numtoelem_representative_values():
    assert utils.numtoelem(1) == "H"
    assert utils.numtoelem(2) == "He"
    assert utils.numtoelem(6) == "C"
    assert utils.numtoelem(26) == "Fe"
    assert utils.numtoelem(30) == "Zn"


def test_numtoelem_special_case_elements():
    # Z 36, 42, 54 are explicitly allowed past the Z<=30 range.
    assert utils.numtoelem(36) == "Kr"
    assert utils.numtoelem(42) == "Mo"
    assert utils.numtoelem(54) == "Xe"


def test_numtoelem_out_of_range_errors():
    with pytest.raises(SystemExit):
        utils.numtoelem(0)
    with pytest.raises(SystemExit):
        utils.numtoelem(31)  # in-range check fails (not one of 36/42/54)


# -- getreason (convergence-reason id -> message) ----------------------------


def test_getreason_known_ids():
    assert "ftol" in utils.getreason(1)
    assert "maximum number of iterations" in utils.getreason(5).lower()
    assert "atol" in utils.getreason(9)


def test_getreason_unknown_id_is_defensive():
    # An unknown id logs a bug (not sys.exit) and returns the fallback string.
    msg = utils.getreason(999, verbose=0)
    assert "unknown" in msg.lower()
