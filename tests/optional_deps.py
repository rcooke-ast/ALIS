"""
The optional dependencies of ALIS's model functions, for the tests that take every
model of a folder (dashboard Stage 7, Q7.19).

linetools is needed only by the ``lsf`` function. A model that uses it is marked
``linetools``, which ``conftest.py`` skips where linetools is not installed (as on
CI) and runs where it is.

Generated by RJC and Claude.
"""

from pathlib import Path

import pytest


def needs_linetools(path):
    """
    Return True if the model at ``path`` uses the ``lsf`` function.

    That function wraps ``linetools.spectra.lsf.LSF``, and linetools is an
    optional dependency (nothing else in ALIS needs it), so on a machine
    without it such a model cannot be read, and its cases are skipped rather
    than failed -- see the ``linetools`` marker in conftest.

    Matching the literal ``lsf(`` is enough to distinguish it from the
    ``lsfspline(`` and ``lsffile(`` functions, which are pure ALIS.

    Generated by RJC and Claude.
    """
    try:
        return "lsf(" in Path(path).read_text()
    except OSError:
        return False


def marked(paths):
    """
    The models at ``paths``, as the values of a parametrised test: each that uses
    the ``lsf`` function marked ``linetools``.

    Generated by RJC and Claude.
    """
    return [
        pytest.param(p, marks=pytest.mark.linetools) if needs_linetools(p) else p
        for p in paths
    ]
