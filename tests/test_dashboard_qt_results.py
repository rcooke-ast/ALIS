def test_no_hidden_value_in_the_results(window, qtbot):
    window.import_path(str(BLIND))
    wait_idle(qtbot, window)
    project = window.session.project
    offset = R.blind_offset({"blindrange": [-1.0e6, 1.0e6], "blindseed": 1234})
    store_run(project, METAL, mod_out=_blind_out(METAL_OUT.read_text(), offset))
    window.refresh()
    results = show_results(window, qtbot)
    view = results.view
    assert view is not None and results.groups
    gate = BL.Gate(project)
    best = view.values
    bad = set()
    for par in project.parsed.params:
        if gate.is_hidden(par):
            bad |= renderings(par.start)
            if par.index in best:
                bad |= renderings(best[par.index])
    assert bad
    texts = ui_strings(window) + [results.copy()]
    for num in range(results.tree.topLevelItemCount()):
        head = results.tree.topLevelItem(num)
        for k in range(head.childCount()):
            child = head.child(k)
            texts += [child.toolTip(c) for c in range(6)]
    window.tabs.setCurrentIndex(2)
    tab = window.tab_widgets[2]
    tab.show_ion(project.systems[0].id, "28Si_II")
    texts += ui_strings(window)
    shown = set(re.findall(r"\d[\d.]*", " ".join(texts)))
    assert not [b for b in bad if b in shown and b not in ("0.0",)]
    assert BL.MASK in " ".join(texts)
