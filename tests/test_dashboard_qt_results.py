def commit(window, description):
    def answer(dialog):
        assert isinstance(dialog, D.CommitDialog)
        assert not dialog.box.button(dialog.box.StandardButton.Ok).isEnabled()
        dialog.set("description", description)
        return 1

    window.on_dialog = answer
    window.qactions["fit.commit"].trigger()
    window.on_dialog = None


def test_commit_describe_save_show_and_remove(window, qtbot, tmp_path):
    path = open_metal(window, qtbot, tmp_path)
    results = show_results(window, qtbot)
    assert [r.run for r in results.history_rows] == ["Latest"]
    assert results.history.item(0, 1).text() == "Commit… to keep it"
    assert window.qactions["fit.commit"].isEnabled()
    commit(window, "T fixed at 8000 K")
    [row] = results.history_rows
    assert (row.run, row.description) == ("1 · latest", "T fixed at 8000 K")
    assert not window.qactions["fit.commit"].isEnabled()
    assert window.session.dirty and not window.session.history.can_undo()
    # A double-click edits the description in place
    item = results.history.item(0, 1)
    assert item.flags() & QtCore.Qt.ItemFlag.ItemIsEditable
    item.setText("first fit")
    assert R.run_of(window.session.project.bundle, 1).description == "first fit"
    # Saved with Save, and there when the project is opened again
    window.save()
    window.close_session()
    window.open_path(path)
    wait_idle(qtbot, window)
    results = show_results(window, qtbot)
    [row] = results.history_rows
    assert (row.key, row.description) == (1, "first fit")
    # A newer run: the history lists it first; choosing run 1 shows it
    store_run(window.session.project, METAL, chi2_final=360.0, dof=360)
    window.session.runs_changed()
    window.refresh()
    assert [r.run for r in results.history_rows] == ["Latest", "1"]
    results.show_run(1)
    assert window.session.view["shown_run"] == 1
    assert results.table_pane.title.text() == "Results · run 1"
    inspect = window.fit_tab.inspect
    window.fit_tab.subtabs.setCurrentIndex(0)
    qtbot.wait(50)
    assert inspect.shown_label.text() == "Final · run 1"
    # Remove… asks first; the latest run is shown again
    window.fit_tab.subtabs.setCurrentIndex(1)
    qtbot.wait(50)
    results.show_run(1)
    results.remove_button.click()
    assert [k for k, *_ in window.answers.asked][-1] == "remove_run"
    assert R.committed(window.session.project.bundle)
    window.answers.answers["remove_run"] = "Remove"
    results.remove_button.click()
    assert not R.committed(window.session.project.bundle)
    assert window.session.view["shown_run"] is None
    assert [r.run for r in results.history_rows] == ["Latest"]


