# -- J1358p6522: the table, statistics and correlations ------------------------------


def test_j1358s_results_as_in_the_mockup(window, qtbot):
    results = j1358(window, qtbot)
    assert results.table_pane.title.text() == "Results · the latest run"
    rows = results.shown_rows()
    titles = [r[0] for r in rows if len(r) == 1]
    assert titles == [
        "▾ Primary system, z = 3.0672596 · 2 components",
        "▸ Lyα forest (57 lines) · 8 flagged rows shown",
        "▸ Continua (12 legendre) · 54 rows",
        "▸ Instrument · 1 row",
    ]
    cells = {r[0]: r for r in rows if len(r) > 1}
    assert cells["H I a2 z"][1:] == ["3.0672580", "± 0.0000011", "−0.12", "⛓ ra", ""]
    assert cells["D I a2 b"][5] == "! not tied to H I"
    # Q6.12: on no bound, so not "at limit"; the forest's flagged rows shown
    assert cells["Lyα z=2.1786 b"][1:3] == ["0.29", "± 60.55"]
    assert cells["Lyα z=2.1786 b"][5] == "! unconstrained"
    assert not any("at limit" in r[-1] for r in rows if len(r) > 1)
    # Q6.23: no coefficient flagged; Lyα's continuum is below zero only beyond its
    # last fit region, so it is not flagged either (Q6.28)
    assert not any(r[0].startswith("H8 c") for r in rows if len(r) > 1)
    # A click on a group's title opens it, and again closes it
    forest = results.groups[1]
    results.toggle_group(forest)
    assert len(results.shown_rows()) > len(rows) + 40
    assert window.session.view["results"]["open"] == ["forest"]
    results.toggle_group(forest)
    assert results.shown_rows() == rows
    # The statistics
    stats = dict(results.statistics_rows)
    assert stats["χ²"] == "3790.5707 (initial 4002.7099)"
    assert stats["χ²ν"] == "0.9143" and stats["Iterations"] == "14"
    assert results.stats_pane.title.text() == "Fit statistics · the latest run"
    # The correlations of the primary system, the pair under the mouse
    assert results.corr_menu.currentText().startswith("Primary system")
    view = results.corr_view
    assert view.names[0] == "H I a1 log N" and len(view.names) == 11
    assert np.allclose(np.diag(view.matrix), 1.0)
    assert view.pair_text(0, 1).startswith("H I a1 log N – H I a1 z: ")
    results.corr_menu.setCurrentIndex(results.corr_menu.findData(RS.ALL))
    assert len(view.names) > 200
    assert window.session.view["results"]["correlations"] == RS.ALL
    # Copy as table
    text = results.copy()
    assert "D I a2 b\t8.03\t0.08\tfree\tnot tied to H I" in text.splitlines()
    assert QtWidgets.QApplication.clipboard().text() == text
    assert not design_references(ui_strings(window))


