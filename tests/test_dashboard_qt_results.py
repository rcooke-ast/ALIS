# -- Reset FWHM (Q6.21) -------------------------------------------------------------


def test_reset_fwhm_after_continue_on_an_imported_row(window, qtbot, tmp_path):
    # The run's best-fit FWHM differs from the model's, and the FWHM is free
    text = METAL_OUT.read_text().replace("vfwhm(7.000VA)", "vfwhm(6.400va)")
    window.import_path(str(METAL))
    wait_idle(qtbot, window)
    project = window.session.project
    row = project.rows[0]
    window.session.history.do(DS.set_state_step(project, row, "resolution", DS.FREE))
    store_run(project, METAL, mod_out=text)
    window.refresh()
    window.answers.answers = {}
    window.on_dialog = lambda dialog: 1
    window.qactions["fit.continue"].trigger()
    assert project.rows[0].fwhm.start == pytest.approx(6.4)
    window.tabs.setCurrentIndex(0)
    data = window.tab_widgets[0]
    data.refresh(window.session)
    cell = data.table.item(0, 3)
    assert cell.text().endswith("↺") and "Reset FWHM to 7 km/s" in cell.toolTip()
    data.badge_menu(project.rows[0], "resolution", choice="Reset FWHM to 7 km/s")
    assert project.rows[0].fwhm.start == 7.0 and project.rows[0].fwhm.free
    assert not data.table.item(0, 3).text().endswith("↺")
    assert window.qactions["edit.undo"].text() == (
        "Undo Reset the FWHM of {0} to 7 km/s".format(row.name)
    )
    undo(window)
    assert project.rows[0].fwhm.start == pytest.approx(6.4)


def test_reset_fwhm_on_a_row_added_from_a_file(window, qtbot, tmp_path):
    session, _ = S.Session.new(
        str(tmp_path / "new.model"), [str(SPECTRUM)], z=0.0, fwhm={str(SPECTRUM): 6.0}
    )
    window.set_session(session)
    project = session.project
    row = project.rows[0]
    from alis.dashboard import lines as L
    from alis.dashboard import sources

    spec = {row.id: sources.spectrum(project, row)}
    line = next(
        ln
        for ln in L.atomic(project.registry).ion_lines("16O_I")
        if abs(ln.rest - 1302.16849) < 0.01
    )
    session.history.do(SN.snip_step(project, project.systems[0], line, spec))
    data = window.tab_widgets[0]
    window.tabs.setCurrentIndex(0)
    data.type_value(project.rows[0], "resolution", 8.5)
    assert data.table.item(0, 3).text().endswith("↺")
    assert data.reset_text(project.rows[0]) == "Reset FWHM to 6 km/s"
    data.reset_fwhm(project.rows[0])
    assert project.rows[0].fwhm.start == 6.0
    undo(window)
    assert project.rows[0].fwhm.start == 8.5


