"""Relinking moved spectra in the window (dashboard Stage 3.9, F13).

Opening a project whose source spectrum has moved offers to relink it; the Relink
dialog accepts the moved file, and refuses a different one.

Generated by RJC and Claude.
"""

import shutil

import numpy as np
import pytest
from dashboard_qt_helpers import SPECTRUM, make_window, wait_idle

pytestmark = pytest.mark.gui

pytest.importorskip("qtpy.QtWidgets")
pytest.importorskip("pyqtgraph")

from alis.dashboard import markers as MK  # noqa: E402
from alis.dashboard import session as S  # noqa: E402
from alis.dashboard import sources as SR  # noqa: E402
from alis.dashboard.qt import dialogs as D  # noqa: E402


@pytest.fixture
def setup(qtbot, tmp_path, monkeypatch):
    monkeypatch.setenv("ALIS_HOME", str(tmp_path / "home"))
    spectrum = tmp_path / "spectra" / "hires.dat"
    spectrum.parent.mkdir()
    shutil.copy(SPECTRUM, spectrum)
    path = tmp_path / "J0000.model"
    S.Session.new(str(path), [str(spectrum)])
    window = make_window(qtbot, tmp_path / "home")
    yield window, path, spectrum
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def test_opening_offers_to_relink_a_moved_spectrum(setup, qtbot, tmp_path):
    window, path, spectrum = setup
    moved = tmp_path / "moved.dat"
    spectrum.rename(moved)
    other = tmp_path / "other.dat"
    np.savetxt(other, np.loadtxt(SPECTRUM)[:50, :3])
    window.answers.answers["relink"] = "Relink…"
    seen = []

    def answer(dialog):
        assert isinstance(dialog, D.RelinkDialog)
        assert dialog.table.rowCount() == 1
        entry = [e for e, s in dialog.entries() if s == SR.MISSING][0]
        # A different file is refused, with the reason
        window.chosen["open"] = str(other)
        assert not dialog.locate(entry)
        seen.append(dialog.message.text())
        # The moved file is accepted
        window.chosen["open"] = str(moved)
        assert dialog.locate(entry)
        seen.append(dialog.message.text())
        return 1

    window.on_dialog = answer
    window.open_path(str(path))
    wait_idle(qtbot, window)
    assert [a[0] for a in window.answers.asked] == ["relink"]
    assert "not the same spectrum" in seen[0]
    assert "relinked" in seen[1]
    window.refresh()
    assert window.markers["Data"].state == MK.COMPLETE
    assert window.session.dirty
    assert window.session.save()
    assert S.Session.open(str(path)).project.bundle.sources[0]["path"] == str(moved)


def test_relink_from_the_file_menu_with_nothing_to_relink(setup, qtbot):
    window, path, spectrum = setup
    window.open_path(str(path))
    window.on_dialog = lambda dialog: 0
    window.qactions["file.relink"].trigger()
    dialog = window.dialogs[-1]
    assert dialog.table.rowCount() == 0
    assert "present and unchanged" in dialog.message.text()
