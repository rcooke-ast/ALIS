# -- Real fits: restarts and the convergence check (fast) ----------------------------


def wait_run(qtbot, window, timeout=600000):
    qtbot.waitUntil(lambda: not window.fit.active, timeout=timeout)
    qtbot.wait(100)


@pytest.mark.fast
def test_metal_line_abs_restarts_all_agree(window, qtbot, tmp_path):
    path = open_metal(window, qtbot, tmp_path, run=False)
    window.qactions["fit.run"].trigger()
    wait_run(qtbot, window)
    project = window.session.project
    view, _ = window.fit_tab.shown_view()
    assert view is not None and view.covariance is not None

    def answer(dialog):
        if isinstance(dialog, FTL.RestartsDialog):
            assert not dialog.export_button.isEnabled()
            dialog.count.setValue(3)
            dialog.run_button.click()
            return 1
        return 0

    window.on_dialog = answer
    window.qactions["fit.restarts"].trigger()
    assert window.fit.active and window.fit.job.kind == "restarts"
    qtbot.waitUntil(lambda: window.fit.job.restart is not None, timeout=120000)
    assert window.status_fit.text().startswith("Restart ")
    wait_run(qtbot, window)
    found = RT.kept(R.latest(project.bundle))
    assert found is not None and len(found.restarts) == 3
    assert all(r.status == "completed" and r.values for r in found.restarts)
    # The starts were drawn about the best fit, within ±10% and the limits
    best = np.asarray(found.best)
    for restart in found.restarts:
        start = np.asarray(restart.start)
        moved = best != 0
        assert np.all(np.abs(start - best)[moved] <= 0.1 * np.abs(best)[moved] + 1e-12)
    assessed = RT.assess(view, found)
    assert assessed.converged is True, assessed.summary
    # Kept with the run, committed with it, and through Save
    number = R.commit(project.bundle, "with restarts")
    window.session.runs_changed()
    window.save()
    disk = B.read(path)
    assert len(RT.kept(R.run_of(disk, number)).restarts) == 3


@pytest.mark.fast
def test_the_convergence_check_is_shown(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path, run=False)

