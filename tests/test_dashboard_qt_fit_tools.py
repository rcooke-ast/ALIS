"""The Fit tab's tools: Review clipped pixels…, Random restarts… and Export
restarts…, and the convergence check (dashboard Stage 6.8; S21, S29, D27; Q6.10,
Q6.11, Q6.18, Q6.22).

- Review clipped pixels…: an outlier added to metal_line_abs's data is marked at
  5σ, ticked, and left out by Apply as one step that undo reverses; three outliers
  in a row are shown unticked; a click ticks or unticks one, and Accept all and
  Reject all act on a panel; Run is offered after Apply.
- Random restarts…: the restarts kept with the shown run, assessed as ALIS
  assesses them, χ² against a parameter, and Export restarts…, which writes sim
  perturb's form that ``numpy.loadtxt`` reads.
- Real fits (marked ``fast``): metal_line_abs's restarts run from the window all
  agree, are kept with the run, committed with it, and survive Save; ALIS's
  convergence check, run from the window, is shown in the fit statistics.

Generated by RJC and Claude.
"""

