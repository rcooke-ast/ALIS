# -- Random restarts… and Export restarts… (S21; Q6.18, Q6.22) ------------------------


def test_the_restarts_window_and_export(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    project = window.session.project
    view = RS.View.latest(project)
    starts = RT.draw_starts(view, 4, seed=11)
    found = RT.new_kept(view, RT.sim_settings(view))
    found.restarts = made_up(view, starts)
    found.restarts[1].chi2 = 350.0
    RT.keep(project.bundle, B.LATEST, found)
    window.refresh()
    assert window.qactions["fit.export_restarts"].isEnabled()
    seen = []

    def look(dialog):
        seen.append(dialog)
        assert isinstance(dialog, FTL.RestartsDialog)
        assert "4 restarts kept" in dialog.intro.text()
        assert dialog.assessed.summary in dialog.summary.text()
        assert dialog.table.topLevelItemCount() == len(dialog.assessed.rows) > 0
        assert dialog.list.rowCount() == 4
        restarts, run = dialog.drawn()
        assert len(restarts) == 4 and len(run) == 1
        assert dialog.continue_button.isVisible()
        assert dialog.continue_button.text() == "Continue from restart 2…"
        assert dialog.count.value() == 10
        return 0

    window.on_dialog = look
    window.qactions["fit.restarts"].trigger()
    assert seen
    # Export restarts…: sim perturb's form, read by numpy.loadtxt
    target = tmp_path / "restarts.txt"
    window.chosen["save"] = str(target)
    window.qactions["fit.export_restarts"].trigger()
    table = np.loadtxt(str(target))
    assert table.shape == (5, len(found.best) + 1)
    assert table[0, -1] == pytest.approx(357.874162)
    text = target.read_text()
    assert np.allclose(np.loadtxt(io.StringIO(text)), table)


def test_new_restarts_replace_the_kept_ones_after_a_question(window, qtbot, tmp_path):
    """One set of restarts is kept with a run (RJC's review): running new ones when
    some are kept asks first."""
    open_metal(window, qtbot, tmp_path)
    project = window.session.project
    view = RS.View.latest(project)
    found = RT.new_kept(view, RT.sim_settings(view))
    found.restarts = made_up(view, RT.draw_starts(view, 3, seed=13))
    RT.keep(project.bundle, B.LATEST, found)
    window.refresh()
    started = []
    window.run_restarts = lambda view, count, seed=None: started.append(count)

    def run_them(dialog):
        dialog.count.setValue(4)
        dialog.run_button.click()
        return 1

    window.on_dialog = run_them
    window.qactions["fit.restarts"].trigger()
    kind, title, text = window.answers.asked[-1]
    assert kind == "restarts_overwrite"
    assert "has 3 restarts kept with it" in text and "replaces them" in text
    assert started == []
    window.answers.answers["restarts_overwrite"] = "Replace them"
    window.qactions["fit.restarts"].trigger()
    assert started == [4]
    # With none kept, nothing is asked
    del project.bundle.members[B.LATEST + RT.MEMBER]
    asked = len(window.answers.asked)
    window.qactions["fit.restarts"].trigger()
    assert len(window.answers.asked) == asked and started == [4, 4]


