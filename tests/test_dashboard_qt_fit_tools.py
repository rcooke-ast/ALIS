def open_metal(window, qtbot, tmp_path, run=True):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window.open_path(str(path))
    wait_idle(qtbot, window)
    if run:
        store_run(window.session.project, METAL, chi2_final=357.874162, dof=360)
        window.session.runs_changed()
    window.tabs.setCurrentIndex(3)
    window.fit_tab.subtabs.setCurrentIndex(0)
    window.refresh()
    qtbot.wait(50)
    return str(path)


# -- Review clipped pixels (S29, D27, Q6.11) -----------------------------------------


def test_review_clipped_pixels_then_apply(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    project = window.session.project
    snip = project.snips[0]
    fitted = np.flatnonzero(SN.fitted(snip))
    lone, three = fitted[20], fitted[[100, 101, 102]]
    window.session.history.do(_push(project, snip, [lone, *three], 30.0))
    window.refresh()
    inspect = window.fit_tab.inspect
    assert window.qactions["fit.outliers"].isEnabled()
    window.qactions["fit.outliers"].trigger()
    assert inspect.review and inspect.review_banner.isVisible()
    assert "4 fitted pixels beyond 5σ" in inspect.review_banner.label.text()
    assert "Apply leaves the 1 ticked" in inspect.review_banner.label.text()
    [widget] = inspect.panel_widgets
    marked = widget.view.marked()
    assert [m[2] for m in marked] == [True, False, False, False]
    assert not widget.accept_all.isHidden() and not widget.reject_all.isHidden()
    # A click on the middle one of the three ticks it; Reject all unticks them all;
    # Accept all ticks them all
    index = snip.data.index
    inspect.toggle_pixel(index, 2)
    assert [m[2] for m in widget.view.marked()] == [True, False, True, False]
    widget.reject_all.click()
    assert not any(m[2] for m in widget.view.marked())
    widget.accept_all.click()
    assert all(m[2] for m in widget.view.marked())
    inspect.toggle_pixel(index, 1)
    inspect.toggle_pixel(index, 2)
    inspect.toggle_pixel(index, 3)
    # Apply: one step, then Run is offered
    before = dict(project.files)
    window.answers.answers["outliers_run"] = "Later"
    banner = inspect.review_banner
    buttons = [banner.buttons.itemAt(n).widget() for n in range(banner.buttons.count())]
    [apply] = [b for b in buttons if b.text() == "Apply"]
    apply.click()
    assert not inspect.review and not inspect.review_banner.isVisible()
    kinds = [k for k, *_ in window.answers.asked]
    assert kinds[-1] == "outliers_run" and not window.fit.active
    assert window.qactions["edit.undo"].text() == "Undo Leave out 1 outlier"
    now = SN.fitted(project.snips[0])
    assert not now[lone] and now[three].all()
    window.qactions["edit.undo"].trigger()
    assert project.files == before


