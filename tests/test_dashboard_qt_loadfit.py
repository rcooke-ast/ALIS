class Ask:
    """Answers the dialog's warnings, and keeps what was asked."""

    def __init__(self, answer="Cut again"):
        self.answer = answer
        self.asked = []
        self.choices = []

    def __call__(self, kind, title, text, choices, default=None, icon="question"):
        self.asked.append((kind, title, text))
        self.choices.append(list(choices))
        return self.answer if self.answer in choices else choices[-1]


def four_spectra(tmp_path):
    """
    src (the example's spectrum), other (other noise), copy (src itself) and
    broken (src with no error that can be fitted above 1303 Å).
    """
    tmp_path.mkdir(parents=True, exist_ok=True)
    src = tmp_path / "src.dat"
    np.savetxt(str(src), np.loadtxt(str(SPECTRUM))[:, :3])
    other = noisy_copy(tmp_path)
    copy = tmp_path / "copy.dat"
    copy.write_bytes(src.read_bytes())
    table = np.loadtxt(str(SPECTRUM))[:, :3]
    table[table[:, 0] > 1303.0, 2] = -1.0
    broken = tmp_path / "broken.dat"
    np.savetxt(str(broken), table)
    return src, other, copy, broken


def setting(registry, tmp_path):
    """
    A project of the four spectra, and a fit of three snips: O I from src (held by
    copy and broken too), Si II from other, and O I from a spectrum the project
    lacks.
    """
    src, other, copy, broken = four_spectra(tmp_path)
    far = noisy_copy(tmp_path / "far", "far.dat", seed=7)
    data = tmp_path / "old" / "data"
    snips = [
        (prepfit_snip(data, src, OI), "7.0", "VA", ""),
        (prepfit_snip(data, other, SII, name="other_{0}_reg.dat".format(SII[2])),)
        + ("5.0", "vb", "shift=vshift(0.0vsb)"),
        (prepfit_snip(data, far, OI, name="far_{0}_reg.dat".format(OI[2])),)
        + ("6.0", "vc", "shift=vshift(0.0vsc)"),
    ]
    mod = write_mod(tmp_path / "old", snips)
    project, _ = modes.get().empty_project(
        [str(p) for p in (src, other, copy, broken)],
        "test",
        z=0.0,
        registry=registry,
    )
    spectra = {r.id: sources.spectrum(project, r) for r in project.rows}
    fit = LF.read_fit(str(mod), registry)
    holders = LF.snip_holders(project, fit, spectra)
    return project, mod, fit, holders


def make_dialog(qtbot, registry, tmp_path, answer="Cut again"):
    project, mod, fit, holders = setting(registry, tmp_path)
    ask = Ask(answer)
    dialog = D.AssignDialog(fit, holders, LF.best_guess(fit, holders), ask=ask)
    qtbot.addWidget(dialog)
    return dialog, ask


def texts(view):
    return [view.item(n).text() for n in range(view.count())]


def item_of(view, specid):
    for num in range(view.count()):
        item = view.item(num)
        if item.data(QtCore.Qt.ItemDataRole.UserRole) == specid:
            return item
    raise AssertionError("{0} is not listed".format(specid))


def select(view, *specids):
    view.clearSelection()
    for specid in specids:
        item_of(view, specid).setSelected(True)


def drop(view, specids, pos=None):
    """A drop of snips on a list, as Qt delivers it."""
    data = QtCore.QMimeData()
    data.setData(D.SNIP_MIME, "\n".join(specids).encode())
    event = QtGui.QDropEvent(
        QtCore.QPointF(pos or QtCore.QPointF(5.0, 5.0)),
        QtCore.Qt.DropAction.CopyAction,
        data,
        QtCore.Qt.MouseButton.LeftButton,
        QtCore.Qt.KeyboardModifier.NoModifier,
    )
    view.dropEvent(event)
    return event


def dialog_strings(dialog):
    out = [dialog.windowTitle()]
    for widget in [dialog] + dialog.findChildren(QtWidgets.QWidget):
        out.append(widget.toolTip())
        text = getattr(widget, "text", None)
        if callable(text):
            try:
                value = text()
            except TypeError:
                continue
            if isinstance(value, str):
                out.append(value)
        if isinstance(widget, QtWidgets.QListWidget):
            out += texts(widget)
            out += [widget.item(n).toolTip() for n in range(widget.count())]
    return [s for s in out if s]


