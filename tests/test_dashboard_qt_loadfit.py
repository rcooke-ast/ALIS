def overlapping_fit(tmp_path):
    """O I from src, and O I from two copies of other noise in one dataset (vb)."""
    src = tmp_path / "src.dat"
    tmp_path.mkdir(parents=True, exist_ok=True)
    np.savetxt(str(src), np.loadtxt(str(SPECTRUM))[:, :3])
    one = noisy_copy(tmp_path / "copies", "e1.dat", seed=1)
    two = noisy_copy(tmp_path / "copies", "e2.dat", seed=2)
    data = tmp_path / "old" / "data"
    snips = [
        (prepfit_snip(data, src, OI), "7.0", "va", ""),
        (prepfit_snip(data, one, OI, name="e1_16O_I_1302.2_reg.dat"), "5.0", "vb", ""),
        (
            prepfit_snip(data, two, OI, name="e2_16O_I_1302.2_reg.dat", centre=1302.3),
            "5.0",
            "vb",
            "",
        ),
    ]
    return src, write_mod(tmp_path / "old", snips, ions=(OI[0],))


