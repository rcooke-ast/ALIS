def two_spectra_fit(tmp_path, extra=()):
    """
    src and other, and a fit of O I from src (dataset va, 7 km/s, its shift free)
    and Si II from other (dataset vb, 5 km/s, no shift), with more snips after.
    """
    src, other, _, _ = four_spectra(tmp_path / "spectra")
    data = tmp_path / "old" / "data"
    snips = [
        (prepfit_snip(data, src, OI), "7.0", "va", "shift=vshift(0.0vsa)"),
        (prepfit_snip(data, other, SII, name="other_{0}_reg.dat".format(SII[2])),)
        + ("5.0", "vb", ""),
    ] + list(extra)
    return src, other, write_mod(tmp_path / "old", snips)


def new_project_answer(target, name, spectra, z="0.0", seen=None):
    """Fills the New project dialog: its name and folder, spectra and redshift."""

    def answer(dialog):
        if seen is not None:
            seen.append(dialog)
        dialog.name.setText(name)
        dialog.folder.setText(str(target))
        for path in spectra:
            assert dialog.add_spectrum(str(path)) == ""
        dialog.redshift.setText(z)
        return 1

    return answer


def answering(new=None, assign=None, plan=1):
    """The window's dialogs answered: the New project dialog by ``new``, the one
    that assigns snips by ``assign`` (Confirm by default), the preview by ``plan``."""

    def answer(dialog):
        if isinstance(dialog, D.NewProjectDialog):
            return new(dialog) if new else 0
        if isinstance(dialog, D.AssignDialog):
            return assign(dialog) if assign else 1
        return plan(dialog) if callable(plan) else plan

    return answer


