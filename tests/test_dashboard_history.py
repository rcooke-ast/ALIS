"""Undo and redo (dashboard Stage 2.8, F2).

Property tests: any sequence of operations -- edits made in panels, typing in the
``.mod`` panel, region edits that change a snip's file, changes to
``ui/project.json``, hidden lines, drags, and undo and redo between them -- undone in
full gives back the original bytes, and redone gives the same result again.

Generated by RJC and Claude.
"""

import json
from pathlib import Path

import pytest

from alis.dashboard import edit as E
from alis.dashboard import history as H
from alis.dashboard import model as M
from alis.dashboard import project as P
from alis.dashboard import text as T

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture(scope="module")
def metal_bundle():
    from alis import bundle as B

    return B.pack(str(METAL))


def fresh(bundle, registry):
    import copy

    return P.Project(copy.deepcopy(bundle), registry)


def state(project):
    """Everything a step can change, as bytes."""
    return (
        project.text.encode("utf-8"),
        tuple(sorted(project.files.items())),
        json.dumps(project.ui, sort_keys=True),
        tuple(sorted(project.extra_hidden)),
    )


def first_value(project):
    pm = project.parsed
    return [p for p in pm.params if p.value_token is not None and p.role == "model"]


# -- Steps of each kind ------------------------------------------------------------


def test_undo_and_redo_one_step(registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project)
    before = state(project)
    par = first_value(project)[0]
    history.edit(E.set_value(project.parsed, par, 2.5), "Set a value")
    after = state(project)
    assert after != before and history.undo_description() == "Set a value"
    history.undo()
    assert state(project) == before and history.redo_description() == "Set a value"
    history.redo()
    assert state(project) == after
    assert history.redo() is None


def test_typing_is_grouped_by_pause(registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project, pause=1.0)
    before = state(project)
    where = project.text.index("plot labels True") + len("plot labels True")
    for num, char in enumerate(" # note"):
        history.type(T.Change((T.Patch(where + num, "", char),)), now=10.0 + 0.3 * num)
    assert len(history.done) == 1
    # A pause starts a new step
    history.type(T.Change((T.Patch(where + 7, "", "!"),)), now=20.0)
    assert len(history.done) == 2
    history.undo()
    assert project.text.endswith(project.text) and "# note!" not in project.text
    history.undo()
    assert state(project) == before


def test_a_drag_is_one_step(registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project)
    before = state(project)
    with history.group("Drag a component"):
        for value in (13.1, 13.2, 13.3, 13.4):
            par = first_value(project)[1]
            history.edit(E.set_value(project.parsed, par, value))
    assert len(history.done) == 1
    assert history.undo_description() == "Drag a component"
    assert first_value(project)[1].value == 13.4
    history.undo()
    assert state(project) == before


def test_a_new_step_forgets_what_was_undone(registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project)
    par = first_value(project)[0]
    history.edit(E.set_value(project.parsed, par, 2.5))
    history.undo()
    assert history.can_redo()
    history.do(project.set_ui({"format": 1}))
    assert not history.can_redo()


def test_region_and_ui_steps_are_undone(registry):
    if not J1358.exists():
        pytest.skip("model not present")
    project = P.Project.import_model(str(J1358), registry=registry)
    history = H.History(project)
    before = state(project)
    snip = project.snip("H3")
    lo, hi = snip.extent
    history.do(project.set_regions(snip, [(lo + 1.0, lo + 2.0)]))
    history.do(project.confirm_structure())
    history.do(project.fix_notice(project.notices[1]))
    assert len(history.done) == 3
    while history.can_undo():
        history.undo()
    assert state(project) == before


def test_clear(registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project)
    history.do(project.set_ui({"format": 1}))
    history.clear()
    assert not history.can_undo() and not history.can_redo()


# -- Property tests ----------------------------------------------------------------

hypothesis = pytest.importorskip("hypothesis")
st = hypothesis.strategies

OPS = st.lists(
    st.tuples(
        st.sampled_from(
            [
                "value",
                "type",
                "region",
                "regions",
                "ui",
                "hide",
                "drag",
                "undo",
                "redo",
                "break",
            ]
        ),
        st.integers(0, 10_000),
        st.floats(0.5, 30.0, allow_nan=False),
    ),
    min_size=1,
    max_size=10,
)


def operate(project, history, op, clock):
    """Make one operation of a random sequence."""
    kind, num, value = op
    if kind == "undo":
        history.undo()
        return
    if kind == "redo":
        history.redo()
        return
    if kind == "type" or project.paused:
        lines = [ln for ln in project.parsed.text.lines if ln.tokens]
        tok = lines[num % len(lines)].tokens[-1]
        where = project.parsed.text.offset(tok.line, tok.end)
        for k, char in enumerate(" #x"):
            history.type(
                T.Change((T.Patch(where + k, "", char),)), now=clock[0] + 0.1 * k
            )
        clock[0] += 5.0
        return
    if kind == "break":
        end = project.text.index("model end")
        history.edit(T.Change((T.Patch(end, "model end", "model ed"),)))
        return
    if kind == "value":
        pars = first_value(project)
        history.edit(E.set_value(project.parsed, pars[num % len(pars)], value))
    elif kind == "drag":
        with history.group("Drag"):
            for k in range(3):
                pars = first_value(project)
                history.edit(
                    E.set_value(project.parsed, pars[num % len(pars)], value + k)
                )
    elif kind == "region":
        history.do(project.set_regions(project.snips[0], [(1301.0, 1301.0 + value)]))
    elif kind == "regions":
        cut = 1301.0 + (num % 30) / 10.0
        history.do(
            project.set_regions(project.snips[0], [(1301.0, cut), (cut + 0.5, 1305.0)])
        )
    elif kind == "ui":
        history.do(project.set_ui({"format": 1, "note": num}))
    elif kind == "hide":
        history.do(project.mark_hidden(num % len(project.parsed.text)))


@hypothesis.settings(max_examples=40, deadline=None, database=None)
@hypothesis.given(ops=OPS)
def test_any_sequence_is_undone_and_redone_exactly(ops, registry, metal_bundle):
    project = fresh(metal_bundle, registry)
    history = H.History(project)
    original = state(project)
    clock = [0.0]
    for op in ops:
        operate(project, history, op, clock)
    final = state(project)
    count = len(history.done)
    while history.can_undo():
        history.undo()
    assert state(project) == original
    # Redoing what was just undone gives the same result again
    for _ in range(count):
        history.redo()
    assert state(project) == final
