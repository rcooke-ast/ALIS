"""A ``.mod.out`` is evaluated on the sub-pixels its fit used (dashboard Stage 14).

Task 14.3 (``deferred_work.md`` §7.10 (a); Q13.7, Q14.4 (i)). ALIS works out each
snip's sub-pixels per pixel from the starting values. A ``.mod.out`` starts from the
best fit, which can ask for others: ``examples/lsf_spline``'s fit starts at a
smoothing of 4 km/s on 6 sub-pixels (10 since Task 14.6's nsubpixel_min), and its
best fit, 0.12 km/s, asks for 21, so that its ``.mod.out`` run again gave a model
that differed from the fit's by up to 2.3 times the error (Stage 13, Task 13.2; 22 of 460 pixels by more than 0.1 times
it, measured at Stage 14's Task 14.3). ALIS now writes
``nsubpixel=N`` on each data line of the ``.mod.out``, and uses it.

- ``examples/lsf_spline`` fitted on a staged copy, then its own ``.mod.out``
  evaluated at zero iterations: the model is the fit's at every pixel.
- ``examples/metal_line_abs``, whose sub-pixels do not move, the same.
- The fit of ``examples/lsf_spline`` warns that its best fit asks for more
  sub-pixels than it used (Task 14.4); the warnings themselves are tested in
  ``test_subpixel_warnings.py``.

Generated by RJC and Claude.
"""

import re

import numpy as np
import pytest
from alisrun import run_alis, stage_case
from compare import FITDAT_ERROR_COL, SENTINEL
from manifest import discover_cases

pytestmark = pytest.mark.fast

CASES = {case.name: case for case in discover_cases()}
NSUBPIXEL = re.compile(r"\bnsubpixel=(\d+)")


def fit_then_evaluate(case, tmp_path):
    """
    The case fitted on a staged copy, then its own ``.mod.out`` run with no
    iteration: the two models' columns, the ``.mod.out``'s recorded sub-pixels, and
    what the fit wrote to the terminal.
    """
    staged = stage_case(case, tmp_path)
    mod = staged.staged(case.mod_file)
    proc = run_alis(mod, runtime_hrs=case.runtime_hrs)
    (pair,) = case.data_pairs
    (golden,) = pair.reference_fits
    produced = staged.fit_output_for(golden)
    fit = np.loadtxt(produced)
    out = mod.with_suffix(".mod.out").read_text()
    recorded = [int(n) for n in NSUBPIXEL.findall(out.split("####")[0])]
    again = mod.parent / "again.mod"
    lines = [ln for ln in out.splitlines() if not re.match(r"\s*chisq\s+m..iter", ln)]
    again.write_text("chisq miniter 0\nchisq maxiter 0\n" + "\n".join(lines) + "\n")
    produced.unlink()
    run_alis(again, runtime_hrs=case.runtime_hrs)
    evaluated = np.loadtxt(produced)
    return fit, evaluated, recorded, proc.stdout + proc.stderr


@pytest.mark.parametrize(
    "name, moved",
    [
        ("examples/lsf_spline/model/fit_spectra", True),
        ("examples/metal_line_abs/model/fit_spectra", False),
    ],
)
def test_a_mod_out_gives_its_fit_s_model(name, moved, tmp_path):
    fit, evaluated, recorded, said = fit_then_evaluate(CASES[name], tmp_path)
    # One data line, one recorded nsubpixel (before Stage 14, none)
    assert len(recorded) == 1 and recorded[0] >= 1
    keep = fit[:, -1] != SENTINEL
    assert np.array_equal(keep, evaluated[:, -1] != SENTINEL)
    delta = np.abs(evaluated[keep, -1] - fit[keep, -1]) / np.abs(
        fit[keep, FITDAT_ERROR_COL]
    )
    # Before Stage 14, lsf_spline's differed by up to 2.33σ (22 pixels above 0.1σ)
    assert delta.max() < 1.0e-3, (name, recorded, delta.max(), int(np.sum(delta > 0.1)))
    # Its fit started on nsubpixel_min (10) sub-pixels; its best fit asks for more
    # (Task 14.4)
    best = "The best fit asks for more sub-pixels than the fit used"
    assert (best in said) == moved
    if moved:
        assert recorded == [10]
        assert "the fit used 10; its best fit asks for" in said
