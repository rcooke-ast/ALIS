def plain(label):
    """A rich-text label's words."""
    return re.sub("<[^>]+>", "", label.text()).replace("&nbsp;", " ")


def click_ion(card, ion):
    """A click on an ion in a card's lists: under Included ions it excludes it."""
    for label in (card.included, card.excluded):
        if 'href="{0}"'.format(ion) in label.text():
            label.linkActivated.emit(ion)
            return
    raise AssertionError(ion)


def one_step(window, act):
    """Run an action; it must make exactly one step of the history."""
    history = window.session.history
    before = len(history.done)
    act()
    assert len(history.done) == before + 1, history.undo_description()
    return history.undo_description()


def card_menu(card, key, text):
    for action in card.badges[key].menu().actions():
        if action.text() == text:
            return action
    raise AssertionError(text)


