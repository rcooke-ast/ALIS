def tree(tab):
    """The navigator, as ``[(title, [(name, detail), ...]), ...]``."""
    out = []
    for num in range(tab.tree.topLevelItemCount()):
        head = tab.tree.topLevelItem(num)
        rows = [
            (head.child(k).text(0), head.child(k).text(1))
            for k in range(head.childCount())
        ]
        out.append((head.text(0), rows))
    return out


def imported(window, qtbot, path):
    need(path)
    window.import_path(str(path))
    wait_idle(qtbot, window)
    return components(window)


def metal_project(window, tmp_path, cuts):
    """A new project of metal_line_abs's spectrum, with snips cut by the steps."""
    session, _ = S.Session.new(
        str(tmp_path / "test.model"), [str(SPECTRUM)], z=0.0, columns=COLUMNS
    )
    window.set_session(session)
    project = session.project
    spectra = {r.id: SR.spectrum(project, r) for r in project.rows}
    atom = L.atomic(project.registry)
    for ion, rest, low, high in cuts:
        line = next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)
        session.history.do(
            SN.snip_step(session.project, session.project.systems[0], line, spectra)
        )
        snip = session.project.snips[-1]
        spec = spectra[session.project.rows[0].id]
        session.history.do(SN.edges_step(session.project, snip, low, high, spec))
    window.refresh()
    return components(window)


