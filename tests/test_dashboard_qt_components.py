def fit_ready(window, tmp_path):
    """metal_line_abs's spectrum: O I 1302 and Si II 1304 merged, with a continuum."""
    from alis.dashboard import continuum as CO

    tab = metal_project(
        window,
        tmp_path,
        [("16O_I", 1302.16849, 1300.5, 1303.4), ("28Si_II", 1304.3702, 1303.1, 1306.0)],
    )
    session = window.session
    project = session.project
    oi, si = project.snip("OI_1302"), project.snip("SiII_1304")
    session.history.do(SN.add_region_step(project, oi, 1301.0, 1303.4))
    project = session.project
    session.history.do(
        SN.add_region_step(project, project.snip("SiII_1304"), 1303.1, 1305.0)
    )
    project = session.project
    plan = SN.merge_plan(project, project.snip("OI_1302"), project.snip("SiII_1304"))
    session.history.do(plan.step)
    session.history.do(CO.auto_step(session.project, session.project.snips[0]))
    window.refresh()
    return tab


def choose(tab, name):
    """Show an ion of the navigator by its name."""
    for item in tab._ion_items():
        if item.text(0) == name:
            tab.tree.setCurrentItem(item)
