def drag(view, start, end, state="finish"):
    """A left drag in a panel, as its view gives it (Q5.23), in three moves."""
    (x0, y0), (x1, y1) = start, end
    view.dragged.emit(x0, y0, x0, y0, "start")
    for f in (1.0 / 3.0, 2.0 / 3.0):
        view.dragged.emit(x0, y0, x0 + f * (x1 - x0), y0 + f * (y1 - y0), "move")
    view.dragged.emit(x0, y0, x1, y1, state)


