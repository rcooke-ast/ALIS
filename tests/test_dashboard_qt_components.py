def test_n_and_b_hold_one_of_log_n_and_b(window, qtbot, tmp_path):
    from qtpy import QtTest

    tab = fit_ready(window, tmp_path)
    choose(tab, "O I")
    added(window, tab)
    view = tab.panel_widgets[0].view

    def values():
        line = window.session.project.components[0].lines_of("16O_I")[0]
        return line.param("ColDens").start, line.param("bturb").start

    logn0, b0 = values()
    # N: log N alone; the key is the panel's, typed nowhere else
    QtTest.QTest.keyPress(view, QtCore.Qt.Key.Key_N)
    assert tab.drag_keys.held == {"n"}
    one_step(window, lambda: drag(view, (10.0, 0.5), (14.0, 0.3)))
    QtTest.QTest.keyRelease(view, QtCore.Qt.Key.Key_N)
    assert tab.drag_keys.held == set()
    logn1, b1 = values()
    assert logn1 > logn0 and b1 == b0
    # B: b alone (the panels are drawn again after each step)
    view = tab.panel_widgets[0].view
    QtTest.QTest.keyPress(view, QtCore.Qt.Key.Key_B)
    assert tab.drag_keys.held == {"b"}
    one_step(window, lambda: drag(view, (10.0, 0.5), (14.0, 0.3)))
    QtTest.QTest.keyRelease(view, QtCore.Qt.Key.Key_B)
    logn2, b2 = values()
    assert logn2 == logn1 and b2 == pytest.approx(b1 + 4.0, abs=2e-3)


class FakeDrag:
    """A mouse drag in a view box, from one point to another (data coordinates)."""

    def __init__(self, box, button, start, end):
        self.box, self._button = box, button
        self._start = box.mapViewToScene(QtCore.QPointF(*start))
        self._end = box.mapViewToScene(QtCore.QPointF(*end))

    def button(self):
        return self._button

    def buttonDownScenePos(self):
        return self._start

    def lastScenePos(self):
        return self._start

    def scenePos(self):
        return self._end

    def isStart(self):
        return False

    def isFinish(self):
        return True

    def accept(self):
        pass


