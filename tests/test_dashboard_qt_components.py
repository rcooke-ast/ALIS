def test_a_drag_is_one_step(window, qtbot, tmp_path):
    tab = fit_ready(window, tmp_path)
    choose(tab, "O I")
    project = added(window, tab)
    history = window.session.history
    text = project.text
    comp = project.components[0]
    logn0 = comp.lines_of("16O_I")[0].param("ColDens").start
    widget = tab.panel_widgets[0]
    view = widget.view
    (_, _), (vy0, vy1) = view.view_range()
    # Below the continuum: log N and b together, by the drag's movement
    drag(view, (10.0, 0.5), (13.0, 0.3), state="move")
    assert window.session.project.text == text
    assert "log N" in widget.readout.text()
    view.dragged.emit(10.0, 0.5, 13.0, 0.3, "finish")
    assert history.undo_description() == "Drag component a1"
    line = window.session.project.components[0].lines_of("16O_I")[0]
    assert line.param("ColDens").start == pytest.approx(
        logn0 + 2.0 * 0.2 / (vy1 - vy0), abs=2e-4
    )
    assert line.param("bturb").start == pytest.approx(5.0 + 3.0, abs=2e-3)
    window.qactions["edit.undo"].trigger()
    assert window.session.project.text == text
    # Above the continuum: z, by the drag's movement, not to the pointer
    one_step(window, lambda: drag(view, (30.0, 1.2), (34.0, 1.25)))
    comp = window.session.project.components[0]
    assert comp.velocity == pytest.approx(4.0, abs=1e-3)
    assert comp.lines_of("16O_I")[0].param("ColDens").start == logn0


