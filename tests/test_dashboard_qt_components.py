def thermal_b(temperature, mass=1.00794):
    """The b of a pure-thermal line of H I, in km/s."""
    return math.sqrt(temperature * C.THERMAL / mass)


def test_a_drag_narrows_past_the_tick_down_to_the_bound(window, qtbot, tmp_path):
    # Point 6 (Q8.9): a drag could narrow a line only by the distance it began at,
    # and widened it again past the tick
    line = "voigt ion=1H_I 14.0 2.50360za1 0.0BX1 70000.0ta1 specid=0"
    lims = ["lim param BX1 [0.0,None]", "lim param ta1 [1.0,None]"]
    tab = imported(window, qtbot, write_ratio_fit(tmp_path / "fit", [line], lims))
    choose(tab, "H I")
    project = window.session.project
    assert project.components[0].temperature_mode == ("thermal", None)
    text = project.text
    b0 = thermal_b(70000.0)

    def temperature():
        return window.session.project.components[0].main.param("temperature").start

    widget = tab.panel_widgets[0]
    # Begun 5 km/s from the tick, ended 40 km/s past it: T at its bound, one step
    drag(widget.view, (5.0, 0.5), (-40.0, 0.5), state="move")
    # The readout is drawn a few times a second
    qtbot.waitUntil(lambda: "T 1 K, at its limit" in widget.readout.text())
    one_step(window, lambda: widget.view.dragged.emit(5.0, 0.5, -40.0, 0.5, "finish"))
    assert temperature() == 1.0
    window.qactions["edit.undo"].trigger()
    assert window.session.project.text == text
    # Ended at the tick: b narrows by 5 km/s, as before
    view = tab.panel_widgets[0].view
    one_step(window, lambda: drag(view, (5.0, 0.5), (0.0, 0.5)))
    assert thermal_b(temperature()) == pytest.approx(b0 - 5.0, abs=0.01)
    # Away from the tick, on either side: wider by the distance moved
    for start, end in ((5.0, 9.0), (-5.0, -9.0)):
        window.qactions["edit.undo"].trigger()
        view = tab.panel_widgets[0].view
        one_step(window, lambda: drag(view, (start, 0.5), (end, 0.5)))
        assert thermal_b(temperature()) == pytest.approx(b0 + 4.0, abs=0.01)
    # From the left: toward the tick and past it narrows too
