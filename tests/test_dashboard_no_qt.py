"""The dashboard's project model imports no Qt (dashboard Stage 2.1).

Everything in ``alis/dashboard/`` outside its ``qt/`` subpackage (Stage 3) must run
without Qt or pyqtgraph, so that it can be tested with pytest alone and used by
``run_alis`` (Q2.1). Each module is imported in a fresh interpreter, which then
reports whether any Qt binding or pyqtgraph has been loaded.

Generated by RJC and Claude.
"""

import json
import pkgutil
import subprocess
import sys

import pytest

import alis.dashboard

pytestmark = pytest.mark.unit

FORBIDDEN = ("qtpy", "PySide6", "PyQt6", "PyQt5", "PySide2", "pyqtgraph")


def dashboard_modules():
    """Every module of ``alis.dashboard`` except the Qt subpackage."""
    names = ["alis.dashboard"]
    for info in pkgutil.walk_packages(alis.dashboard.__path__, "alis.dashboard."):
        if info.name.split(".")[2] != "qt":
            names.append(info.name)
    return names


MODULES = dashboard_modules()

PROBE = """
import importlib, json, sys
for name in {names!r}:
    importlib.import_module(name)
print(json.dumps(sorted(m for m in sys.modules
                        if m.split('.')[0] in {forbidden!r})))
"""


def test_the_modules_of_the_plan_exist():
    planned = {
        "text",
        "model",
        "edit",
        "project",
        "validate",
        "blinding",
        "history",
        "remove",
        "modes",
    }
    assert planned <= {name.split(".")[-1] for name in MODULES}


def test_every_module_has_a_docstring():
    import importlib

    for name in MODULES:
        doc = importlib.import_module(name).__doc__
        assert doc and doc.strip(), name


def test_no_module_imports_qt():
    code = PROBE.format(names=MODULES, forbidden=FORBIDDEN)
    out = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, check=True
    )
    loaded = json.loads(out.stdout.strip().splitlines()[-1])
    assert loaded == [], f"Qt was imported by the dashboard model: {loaded}"


def test_the_probe_would_notice_qt():
    """Guard the guard: the same probe sees a Qt binding when one is imported."""
    try:
        import qtpy  # noqa: F401
    except Exception:
        pytest.skip("no Qt binding is installed here")
    code = PROBE.format(names=["qtpy"], forbidden=FORBIDDEN)
    out = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, check=True
    )
    assert "qtpy" in json.loads(out.stdout.strip().splitlines()[-1])
