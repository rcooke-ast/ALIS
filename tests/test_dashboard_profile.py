def test_a_linked_parameter_follows_a_dragged_one(registry):
    project = imported(SUMMED, registry)
    profile = PR.Profile(project)
    pm = project.parsed
    label = {p.label: p for p in pm.params if p.label}
    ra, rb, nb, na = label["ra"], label["rb"], label["nb"], label["na"]
    assert rb.linked and na.linked
    values = profile.values({ra.index: 2.0e-5})
    assert values[rb.index] == pytest.approx(2.0e-5 + 0.00010, abs=1e-15)
    values = profile.values({nb.index: 11.0})
    expect = np.log10(
        10.0 ** label["nf"].start
        - (
            10.0**11.0
            + 10.0 ** label["nc"].start
            + 10.0 ** label["nd"].start
            + 10.0 ** label["ne"].start
        )
    )
    assert values[na.index] == pytest.approx(expect, rel=1e-12)
    # The model with the dragged value equals the model with the value written
    dragged = profile.evaluate(profile.values({ra.index: 2.0e-5}))
    project.edit(E.set_value(pm, ra, 2.0e-5))
    written = PR.Profile(project).evaluate()
    for index in dragged:
        assert np.allclose(
            dragged[index].model, written[index].model, atol=1e-12, equal_nan=True
        )


# -- The pixels, χ² and the continuum ------------------------------------------------


def test_the_model_is_placed_on_the_snip_pixels(registry):
    project = imported(BLIND, registry)
    profile = PR.Profile(project)
    (index,) = profile.snips
    curve = profile.evaluate()[index]
    snip = project.snips[0]
    assert np.array_equal(curve.wave, snip.pixels.wave)
    loaded = np.isfinite(curve.model)
    # ALIS loads the fit range and the buffer its convolution needs, not the file
    assert 0 < loaded.sum() < curve.wave.size
    assert curve.fitted.sum() > 0 and not np.any(curve.fitted & ~loaded)
    lo, hi = curve.wave[curve.fitted].min(), curve.wave[curve.fitted].max()
    assert 1301.0 <= lo and hi <= 1305.0
    # Normalised: the model and the data over the continuum; residuals in σ
    assert curve.continuum is not None
    assert np.allclose(
        curve.normalised[loaded], (curve.model / curve.continuum)[loaded]
    )
    assert np.allclose(curve.data_normalised, curve.flux / curve.continuum)
    resid = curve.residuals
    assert np.all(np.isnan(resid[~loaded]))
    assert curve.chi2 == pytest.approx(np.sum(resid[curve.fitted] ** 2), rel=1e-12)


# -- Blinding (D24) -------------------------------------------------------------------


def test_nothing_returned_shows_a_hidden_value(registry):
    # examples/blind, with distinctive values on its blinded Si II line
    project = imported(BLIND, registry)
    for role, value in (("ColDens", 13.4729), ("redshift", 0.000173)):
        pm = project.parsed
        line = [ln for ln in pm.function_lines("voigt") if ln.ion == "28Si_II"][0]
        project.edit(E.set_value(pm, line.param(role), value))
    gate = BL.Gate(project)
    bad = forbidden(project, gate)
    assert "13.4729" in bad
    profile = PR.Profile(project)
    curves = profile.evaluate()
    strings = [repr(profile), repr(curves)] + [repr(c) for c in curves.values()]
    try:
        profile.values({10**6: 1.0})
    except (IndexError, PR.ProfileError) as err:
        strings.append(str(err))
    assert leaks(strings, bad) == []


def test_a_model_that_does_not_read_is_not_drawn(registry):
    project = imported(METAL, registry)
    pm = project.parsed
    line = pm.function_lines("voigt")[0]
    new = pm.text[line.line].text.replace("voigt", "voight", 1)
    project.edit(T.Change((T.replace_line(pm.text, line.line, new),)))
    assert project.paused
    with pytest.raises(PR.ProfileError, match="does not read"):
        PR.Profile(project)


def test_the_profile_is_kept_until_the_text_changes(registry):
    project = imported(METAL, registry)
    first = PR.of(project)
    assert PR.of(project) is first
    pm = project.parsed
    project.edit(E.set_value(pm, pm.function_lines("voigt")[0].param("ColDens"), 13.5))
    second = PR.of(project)
    assert second is not first
    assert not _same(
        second.evaluate()[second.snips[0]].model, first.evaluate()[first.snips[0]].model
    )


def test_the_cost_of_j1358_h1(j1358):
    """J1358p6522's H I snips, as a drag of H I evaluates them (Q5.5)."""
    profile = j1358
    h1 = [ln for c in profile.project.components for ln in c.lines if ln.ion == "1H_I"]
    snips = set()
    for line in h1:
        snips |= profile.affected({line.param("ColDens").index: 20.0})
    assert len(snips) == 8
    profile.evaluate(snips=snips)
    logging.getLogger(__name__).info(
        "J1358p6522 H I: %d snips in %.1f ms", len(snips), 1e3 * profile.cost
    )
    assert profile.cost < 5.0
