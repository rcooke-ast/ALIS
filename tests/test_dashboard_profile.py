def imported(path, registry):
    if not path.exists():
        pytest.skip("model not present: " + str(path.relative_to(ROOT)))
    project = P.Project.import_model(str(path), registry=registry)
    assert not project.paused, project.parsed.errors
    return project


def _fit_models():
    """Every model of ``examples/`` that fits data (not one that generates it)."""
    out = []
    for path in sorted((ROOT / "examples").glob("*/model/*.mod")):
        text = path.read_text()
        if "generate" in path.name or "generate" in text.split("data read")[0]:
            continue
        out.append(path)
    return out + [J1358, Q1243]


# -- ALIS's own state, as run_alis builds it -----------------------------------------


def _alis_state(path):
    """
    ``ClassMain`` on the model file, stopped where ``main.py`` starts to fit: the
    data read from disk, the links applied to the starting values.

    Generated by RJC and Claude.
    """
    from alis.main import ClassMain
    from alis.scripts.run_alis import parser

    class Setup(ClassMain):
        def main(self):
            # main.py, from its start to "NOW PREPARE TO FIT THE DATA!"
            parinfo, self._levadd = load.load_parinfo(self)
            self._pinfl = load.load_par_influence(self, self._modpass["p0"])
            (
                self._wavespx,
                self._contspx,
                self._zerospx,
                self._posnspx,
                self._nexbins,
            ) = load.load_subpixels(self, self._modpass["p0"])
            self._ptied = []
            count = 0
            for info in parinfo:
                if "tied" in info.keys():
                    tied = info["tied"].replace("numpy", "np")
                    self._ptied.append(tied)
                    self._modpass["mlnk"].append([-2 - count, tied])
                    count += 1
                else:
                    self._ptied.append("")
            self._ptied = [t.strip() for t in self._ptied]
            self._qanytied = int(any(self._ptied))
            if self._qanytied:
                self._modpass["p0"] = load.load_tied(self._modpass["p0"], self._ptied)

    cwd = os.getcwd()
    level = logger.msgs().level
    os.chdir(path.parent)
    try:
        with warnings.catch_warnings():
            args = parser(
                [path.name, "-p", "0", "-c", "1", "--set", "run backend cpu", "-v", "0"]
            )
            overrides = []
            argflag = load.optarg(argv=args, overrides=overrides, verbose=0)
            argflag["run"]["modname"] = args.alis_modfile
            return Setup(argflag, cli_overrides=overrides)
    finally:
        os.chdir(cwd)
        logger.msgs().setLevel(level)


@pytest.mark.parametrize(
    "path",
    _fit_models(),
    ids=lambda p: p.parent.parent.name + "/" + p.name,
)
def test_the_model_is_alis_own(path, registry):
    project = imported(path, registry)
    if project.parsed.function_lines("random"):
        pytest.skip("a random line draws new starting values each time it is read")
    profile = PR.Profile(project)
    state = _alis_state(path)
    p0 = state._modpass["p0"]
    theirs = model_eval.model_func(
        state, state._wavefull, p0, state._posnfull, output=1
    )
    # As main.py computes the starting χ², over every fitted pixel at once
    fitted = model_eval.myfunct(p0, state=state, output=2)
    flux, error = np.concatenate(state._fluxfit), np.concatenate(state._fluefit)
    chi2 = np.sum(((flux - fitted) / error) ** 2)
    curves = profile.evaluate()
    assert len(curves) == sum(len(pos) - 1 for pos in state._posnfull)
    for index, curve in curves.items():
        sp, sn = profile._where[index]
        low, high = state._posnfull[sp][sn], state._posnfull[sp][sn + 1]
        offset = profile._pixels[index][0]
        ours = curve.model[offset : offset + high - low]
        assert np.allclose(ours, theirs[sp][low:high], rtol=0, atol=1e-10)
        assert np.array_equal(
            curve.wave[offset : offset + high - low], state._wavefull[sp][low:high]
        )
    assert profile.chi2(curves) == pytest.approx(chi2, rel=1e-10)


# -- Some snips, and what a change reaches ------------------------------------------


@pytest.fixture(scope="module")
def j1358(registry):
    return PR.Profile(imported(J1358, registry))


def _same(a, b):
    return np.array_equal(np.nan_to_num(a, nan=-1.0), np.nan_to_num(b, nan=-1.0))


def test_a_change_reaches_only_the_snips_it_applies_to(j1358):
    profile = j1358
    project = profile.project
    base = profile.evaluate()
    checked = 0
    for comp in project.components:
        for line in comp.lines:
            for role, step in (("ColDens", 0.3), ("redshift", 2.0e-5), ("bturb", 1.0)):
                par = line.param(role)
                if par is None or par.linked:
                    continue
                change = {par.index: profile.start[par.index] + step}
                values = profile.values(change)
                reached = profile.affected(change, values)
                after = profile.evaluate(values)
                changed = {i for i in base if not _same(base[i].model, after[i].model)}
                # Every snip that changes is named, and no other
                assert changed == reached, (comp.id, line.ion, role)
                some = profile.evaluate(values, snips=reached)
                assert set(some) == reached
                for i in reached:
                    assert _same(some[i].model, after[i].model)
                checked += 1
    assert checked > 20
    # O I's lines reach O I's snips only, not the H I snips that have no O I line
    o1 = [ln for c in project.components for ln in c.lines if ln.ion == "16O_I"][0]
    h1 = [ln for c in project.components for ln in c.lines if ln.ion == "1H_I"][0]
    reach_o = profile.affected({o1.param("ColDens").index: 14.0})
    reach_h = profile.affected({h1.param("ColDens").index: 20.0})
    assert reach_o and reach_h and reach_o != reach_h


def test_a_redshift_moved_into_another_snip_reaches_it(registry):
    project = imported(METAL, registry)
    profile = PR.Profile(project)
    si2 = [ln for ln in project.parsed.lines if ln.ion == "28Si_II"][0]
    zpar = si2.param("redshift")
    (index,) = profile.snips
    assert profile.affected({zpar.index: zpar.start}) == {index}
    # Moved far away, Si II no longer falls in the snip, but the snip still changes
    far = profile.values({zpar.index: 0.5})
    assert profile.affected({zpar.index: 0.5}, far) == {index}
    curve = profile.evaluate(far)[index]
    assert not _same(curve.model, profile.evaluate()[index].model)


