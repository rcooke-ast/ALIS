"""The model of each snip, as ALIS computes it (dashboard Stage 5.1; S13, D24).

The model the dashboard draws must be ALIS's own: for every fit model of
``examples/``, and for J1358p6522 and Q1243p307, it equals ``model_eval.model_func``
on the state ``run_alis`` builds (from the files on disk), and its χ² equals the
starting χ² ALIS reports. A change of a parameter reaches only the snips it applies
to; a linked parameter follows a dragged one as ALIS computes it; evaluating some
snips gives the same model as evaluating them all; and nothing the profile returns
shows a hidden value.

Generated by RJC and Claude.
"""

