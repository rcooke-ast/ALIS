"""Random restarts of a run (dashboard Stage 6.8; S21; Q6.10, Q6.18, Q6.22).

- The starts are drawn as ``sim perturb`` draws them after ``sim beginfrom``: about
  the run's best fit, from its covariance, within ±``sim maxperturb`` of each value
  and the limits; fixed and linked parameters unchanged.
- Each restart is the run's model with the draws as its starting values.
- What is kept: the table of restarts, with the run, committed with it, through
  Save (the bundle written and read again), hidden whole while anything is hidden.
- The assessment is ALIS's own (``convergence.assess_restarts``).
- Export restarts…: ``sim perturb``'s form, which ``numpy.loadtxt`` reads, with its
  header and χ² column; a hidden parameter's columns are left out.

The restarts' results here are made up from the run's best fit (no fit is run; the
real restarts are in ``test_dashboard_qt_fit_tools.py``, marked ``fast``).

Generated by RJC and Claude.
"""

