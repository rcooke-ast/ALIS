def shows(window, num, state):
    """Whether tab ``num`` shows the icon of ``state``."""
    have = window.tabs.tabIcon(num).pixmap(28, 28).toImage()
    want = ST.marker_icon(state).pixmap(28, 28).toImage()
    return have == want


def test_the_tabs_show_their_markers(window, qtbot):
    window.import_path(str(METAL))
    wait_idle(qtbot, window)
    project = window.session.project
    info = {
        "status": "completed",
        "finished": "2026-10-06T10:00:00",
        "model_sha256": B.sha256(project.model_bytes()[0]),
    }
    project.bundle.members[B.LATEST + "run.json"] = json.dumps(info).encode()
    window.refresh()
    assert shows(window, 3, MK.COMPLETE)
    assert window.tabs.tabToolTip(3).startswith("The latest run (completed)")
    # An edit makes the Fit tab out of date
    par = next(p for p in project.parsed.params if p.name == "ColDens")
    window._run(
        "panel",
        lambda: window.session.history.edit(
            E.set_value(project.parsed, par, 14.5), "Set N"
        ),
    )
    assert shows(window, 3, MK.STALE)
    assert window.tabs.tabToolTip(3) == "The model has changed since the latest run."
    # The other tabs, and Plot
    assert shows(window, 0, MK.ATTENTION)
    assert shows(window, 2, MK.ATTENTION)
    assert shows(window, 4, MK.NONE)
    assert window.tabs.tabToolTip(4) == "Not yet available"
    window.qactions["edit.undo"].trigger()
    assert shows(window, 3, MK.COMPLETE)


