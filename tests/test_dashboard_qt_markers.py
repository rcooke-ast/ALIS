def test_every_state_has_its_own_icon(qtbot):
    from qtpy import QtWidgets

    ST.apply(QtWidgets.QApplication.instance())
    images = [ST.marker_icon(s).pixmap(28, 28).toImage() for s in MK.ICONS]
    for num, image in enumerate(images):
        assert all(image != other for other in images[num + 1 :])
