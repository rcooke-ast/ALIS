def project_with_run(model, registry, mod_out=None):
    """A project imported from a model, with a run whose best fit is ``mod_out``
    (the model's own text by default: its starting values)."""
    model = Path(model)
    project = P.Project.import_model(str(model), registry=registry)
    store_run(project, model, mod_out=mod_out or model.read_text(), covar=False)
    return project, RS.View.latest(project)


def with_preset(project, view, name, **kwargs):
    step, fid = FG.new_figure(project)
    project.apply(step)
    project.apply(FP.apply(project, fid, name, view=view, **kwargs))
    return fid


def written(project, view, fid, folder, name="test"):
    """The script and what it reads, written into ``folder``; the script's path."""
    out, notes = FS.files(project, view, fid, name)
    paths = FS.write(str(folder), out)
    return Path(next(p for p in paths if p.endswith(".py"))), notes


def run(script, *args, env=NO_TEX):
    done = subprocess.run(
        [sys.executable, "-I", str(script), *args],
        cwd=script.parent,
        env={**env, "MPLBACKEND": "Agg"},
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert done.returncode == 0, done.stderr
    return done


def read_back(script):
    done = subprocess.run(
        [sys.executable, "-I", "-c", READ_BACK, str(script)],
        cwd=script.parent,
        env={**NO_TEX, "MPLBACKEND": "Agg"},
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert done.returncode == 0, done.stderr
    return json.loads(done.stdout)


def imported_modules(script):
    found = set()
    for node in ast.walk(ast.parse(script.read_text())):
        if isinstance(node, ast.Import):
            found |= {a.name.split(".")[0] for a in node.names}
        elif isinstance(node, ast.ImportFrom):
            found.add(node.module.split(".")[0])
    return found


def write_lyman_limit(folder):
    """A Lyα snip and a Lyman-limit snip (913–915.4 Å in the rest frame) of one H I
    component at Z, as ``DH_Lyseries.py`` draws."""
    folder.mkdir(parents=True)
    write_flat(folder / "lya.dat", 1215.6701 * (1.0 + Z), half=4.0)
    rng = np.random.default_rng(4)
    wave = np.arange(913.0, 915.4, 0.004) * (1.0 + Z)
    flux = 1.0 + 0.01 * rng.standard_normal(wave.size)
    np.savetxt(
        folder / "ll.dat", np.column_stack([wave, flux, np.full(wave.size, 0.01)])
    )
    text = (
        "run blind False\n\ndata read\n"
        "  lya.dat  specid=0  fitrange=all  resolution=vfwhm(6.0VFIX)"
        "  columns=[wave,flux,error]\n"
        "  ll.dat  specid=1  fitrange=all  resolution=vfwhm(6.0VFIX)"
        "  columns=[wave,flux,error]\n"
        "data end\n\nmodel read\n emission\n  constant 1.0CONA specid=0,1\n"
        " absorption\n"
        "  voigt ion=1H_I 14.0 {0:.7f}za1 20.0ba1 0.0TA1 specid=0,1\n"
        "model end\n".format(Z)
    )
    path = folder / "ll.mod"
    path.write_text(text)
    return path


@pytest.mark.parametrize(
    "preset", [FP.METALS, FP.DH + "1", FP.DH + "2", FP.BLENDS, FP.HELIUM]
)
def test_each_preset_s_script_runs_alone_and_writes_its_figure(
    preset, tmp_path, registry
):
    if preset == FP.METALS:
        model = METAL
    elif preset == FP.DH + "1":
        model = write_thermal_fit(tmp_path / "fit")
    elif preset == FP.DH + "2":
        model = write_shifted_fit(tmp_path / "fit")
    elif preset == FP.BLENDS:
        model = write_blend(tmp_path / "fit")
    else:
        model = write_helium(tmp_path / "fit")
    project, view = project_with_run(model, registry)
    name = preset.rstrip("12")
    kwargs = {}
    if name == FP.BLENDS:
        kwargs["system"] = next(s.id for s in project.systems if not s.primary)
    fid = with_preset(project, view, name, **kwargs)
    script, notes = written(project, view, fid, tmp_path / "out")
    assert notes == []
    assert script.name == "test_Figure_1.py"
    # Nothing but the standard library, numpy and matplotlib
    assert imported_modules(script) <= {"os", "shutil", "sys", "numpy", "matplotlib"}
    run(script)
    pdf = script.with_suffix(".pdf")
    assert pdf.exists() and pdf.read_bytes().startswith(b"%PDF")


def test_with_latex_where_it_is_installed(tmp_path, registry):
    if shutil.which("latex") is None or shutil.which("dvipng") is None:
        pytest.skip("LaTeX is not installed")
    project, view = project_with_run(METAL, registry)
    fid = with_preset(project, view, FP.METALS)
    script, _ = written(project, view, fid, tmp_path)
    run(script, "with.png", "--dpi", "60", env=dict(os.environ))
    run(script, "without.png", "--dpi", "60")
    # LaTeX's text is not matplotlib's
    with_tex = (script.parent / "with.png").read_bytes()
    assert with_tex != (script.parent / "without.png").read_bytes()


def test_every_colour_is_a_variable_at_the_top(tmp_path, registry):
    project, view = project_with_run(METAL, registry)
    fid = with_preset(project, view, FP.METALS)
    script, _ = written(project, view, fid, tmp_path)
    text = script.read_text()
    top = text[: text.index("PANELS = ")]
    for name in (
        "DATA_COLOUR",
        "MODEL_COLOUR",
        "CONTINUUM_COLOUR",
        "ZERO_COLOUR",
        "RESIDUAL_COLOUR",
        "RESIDUAL_BANDS",
        "TICK_COLOURS",
        "OTHER_TICK_COLOUR",
    ):
        assert "\n" + name + " = " in top
    # No colour is written in the drawing itself
    drawing = text[text.index("PANELS = ") :]
    assert "#" + "D55E00" not in drawing and 'color="' not in drawing
    run(script, "before.png", "--dpi", "50")
    script.write_text(
        text.replace("MODEL_COLOUR = '#D55E00'", "MODEL_COLOUR = '#000000'")
    )
    run(script, "after.png", "--dpi", "50")
    assert (tmp_path / "before.png").read_bytes() != (
        tmp_path / "after.png"
    ).read_bytes()


def test_the_figure_drawn_matches_its_description(tmp_path, registry):
    project, view = project_with_run(write_shifted_fit(tmp_path / "fit"), registry)
    fid = with_preset(project, view, FP.DH)
    # A third row: Lyα of A, spanning both columns, in observed wavelength
    project.apply(FG.set_grid(project, fid, 2, 3))
    lya = next(e for e in FG.transitions(project) if e.line == "Lyα 1215.7")
    project.apply(FG.place(project, fid, 2, 0, lya.key))
    project.apply(FG.set_span(project, fid, 2, 0, 2))
    project.apply(FG.set_cell(project, fid, 2, 0, "axis", FG.OBSERVED))
    script, _ = written(project, view, fid, tmp_path / "out")
    found = read_back(script)
    panels = found["panels"]
    assert len(panels) == 5
    one, wide = panels[0], panels[4]
    # The span: as wide as both columns and the gap between them
    assert wide["box"][0] == pytest.approx(one["box"][0])
    assert wide["box"][1] == pytest.approx(panels[1]["box"][1])
    # The velocity panels: the figure's range, numbered (signed) at the bottom only
    assert one["xlim"] == pytest.approx([-190.0, 190.0])
    assert one["xnumbers"] == [] and panels[2]["xnumbers"]
    assert "$+100$" in panels[2]["xnumbers"]
    # Each column titled; numbers left, then right
    assert [one["title"], panels[1]["title"]] == ["A data", "B data"]
    assert one["left"] and not one["right"] and panels[1]["right"]
    # The wide panel: observed wavelength about Lyα, its own x title
    centre = 1215.6701 * (1.0 + Z)
    assert wide["xlim"][0] == pytest.approx(centre * (1 - 190.0 / 299792.458), rel=1e-5)
    assert wide["xlabel"] == "Observed wavelength (Å)"
    # The shared titles: no shared x title, as the axes differ
    assert found["shared"] == ["", "Normalized Flux"]


def test_dh_lyseries_s_layout(tmp_path, registry):
    project, view = project_with_run(write_lyman_limit(tmp_path / "fit"), registry)
    step, fid = FG.new_figure(project)
    project.apply(step)
    found = FG.transitions(project)
    lya = next(e for e in found if e.line == "Lyα 1215.7")
    limit = next(e for e in found if e.specid == "1")
    project.apply(FG.place(project, fid, 0, 0, lya.key))
    project.apply(FG.place(project, fid, 1, 0, limit.key))
    project.apply(FG.set_span(project, fid, 1, 0, 3))
    project.apply(FG.set_cell(project, fid, 1, 0, "axis", FG.REST))
    project.apply(FG.set_cell(project, fid, 1, 0, "xrange", [913.15, 915.2]))
    project.apply(FG.set_cell(project, fid, 1, 0, "label", "Lyman limit"))
    project.apply(FG.place(project, fid, 2, 1, lya.key))
    script, _ = written(project, view, fid, tmp_path / "out")
    panels = read_back(script)["panels"]
    top, limit_panel, bottom = panels
    # Across all three columns, in the rest frame
    assert limit_panel["box"][1] - limit_panel["box"][0] > 2.9 * (
        top["box"][1] - top["box"][0]
    )
    assert limit_panel["xlim"] == pytest.approx([913.15, 915.2])
    assert limit_panel["xlabel"] == "Rest-frame wavelength (Å)"
    # A tick at each Lyman line in range
    rests = [
        ln.rest
        for ln in L.atomic(project.registry).ion_lines("1H_I")
        if 913.15 <= ln.rest <= 915.2
    ]
    ticks = sorted(x[0] for _, x, y in limit_panel["lines"] if y[0] > 1.0)
    assert len(rests) > 5 and ticks == pytest.approx(sorted(rests))
    assert [t for t, _ in limit_panel["texts"]] == ["Lyman limit"]
    assert top["xlim"] == pytest.approx([-125.0, 125.0])
    assert bottom["box"][0] > top["box"][1]


def test_q9_12_s_options_are_drawn(tmp_path, registry):
    project, view = project_with_run(write_thermal_fit(tmp_path / "fit"), registry)
    fid = with_preset(project, view, FP.DH)
    for key, value in (
        ("title", "HIRES data"),
        ("corner", "upper right"),
        ("yticks", [0.6, 0.8, 1.0]),
        ("ynumbers", True),
        ("yright", True),
    ):
        project.apply(FG.set_cell(project, fid, 0, 0, key, value))
    project.apply(FG.set_option(project, fid, "numbered", True))
    script, _ = written(project, view, fid, tmp_path / "out")
    lya = read_back(script)["panels"][0]
    assert lya["title"] == "HIRES data"
    assert lya["yticks"] == [0.6, 0.8, 1.0]
    assert lya["right"] and not lya["left"]
    label = next(xy for text, xy in lya["texts"] if text == "Lyα")
    assert label == pytest.approx([0.96, 0.95])
    # H I's and D I's ticks, each in its own colour, numbered by component
    colours = FS.COLOURS[FG.SAFE]["TICKS"]
    ticks = [c for c, _, y in lya["lines"] if y[0] > 1.0]
    assert set(ticks) == {colours[0], colours[1]}
    numbers = [t for t, xy in lya["texts"] if t != "Lyα"]
    assert sorted(set(numbers)) == ["1", "2"]
    assert "$+100$" in lya["xnumbers"] and "$-100$" in lya["xnumbers"]


