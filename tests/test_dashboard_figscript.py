def test_exporting_two_figures(tmp_path, registry):
    project, view = project_with_run(METAL, registry)
    one = with_preset(project, view, FP.METALS)
    step, two = FG.new_figure(project, like=one)
    project.apply(step)
    o1 = next(e for e in FG.transitions(project) if e.ion == "16O_I")
    project.apply(FG.place(project, two, 0, 0, o1.key))
    project.apply(FG.rename(project, two, "O I alone"))
    folder = str(tmp_path / "paper")
    planned, scripts, notes = FS.plan(project, view, [one, two], "metal", folder)
    names = sorted(os.path.basename(p) for p in planned)
    # Named after the figures, spaces as underscores (Q9.11); the style and the
    # snip once
    assert names == [
        "alis_publication.mplstyle",
        "metal_Figure_1.py",
        "metal_OI_1302.17_zabs0.0000_fit.dat",
        "metal_O_I_alone.py",
    ]
    assert [os.path.basename(s) for s in scripts] == [
        "metal_Figure_1.py",
        "metal_O_I_alone.py",
    ]
    assert FS.pdf_of(scripts[1]).endswith("metal_O_I_alone.pdf") and notes == []
    # With the snips exported too, their files are Export's own
    planned, _, _ = FS.plan(project, view, [one], "metal", folder, snips=True)
    assert not [p for p in planned if p.endswith("_fit.dat")]


def test_another_system_s_panel_and_a_removed_snip(tmp_path, registry):
    from alis.dashboard import remove as RM

    model = write_blend(tmp_path / "fit")
    project, view = project_with_run(model, registry)
    step, fid = FG.new_figure(project)
    project.apply(step)
    found = FG.transitions(project)
    lya = next(e for e in found if e.line == "Lyα 1215.7")
    si = next(e for e in found if e.line == "Si II 1304.4")
    project.apply(FG.place(project, fid, 0, 0, lya.key))
    project.apply(FG.place(project, fid, 0, 1, si.key))
    data, files, notes = FS.describe(project, view, fid, "blend")
    first, second = data["panels"]
    # The primary's panel from the velocity zero; the interloper's from its own
    # strongest component (log N 13.0, b2)
    assert first["of"] == data["zero"] and first["z"] == data["z_zero"]
    interloper = project.system(si.system)
    assert second["of"] == FP.strongest(project, interloper, view) == "b2"
    assert second["z"] == pytest.approx(data["components"]["b2"])
    # The interloper's snip removed: its panel is left out, with a note
    project.apply(RM.plan_snip(project, project.snip(si.specid)).step(project))
    data, files, notes = FS.describe(project, view, fid, "blend")
    # (the datasets are grouped again without it, so only the line is compared)
    assert [p["name"].split(" · ")[0] for p in data["panels"]] == ["Lyα 1215.7"]
    assert notes == ["Figure 1, row 1, column 2: its snip is no longer in the project."]
