"""The plotting script of a figure, and the shipped style (dashboard Stage 9, Task 9.4;
D42, S22; Q9.2, Q9.8, Q9.9, Q9.12). No Qt; each script runs in a process of its own.

- The script of each preset (metals, DH with one dataset and with two, blends,
  helium) runs under ``python -I`` in a folder of its own, importing nothing but
  numpy and matplotlib, and writes its PDF; with ``latex`` hidden from the path it
  uses matplotlib's text, and with LaTeX (where installed) LaTeX's.
- Every colour is a variable at the top: changing the model's changes the figure.
- The figure the script draws matches its description, read back from matplotlib:
  the spans' widths, each panel's x axis, range, titles and numbers;
  ``DH_Lyseries.py``'s layout (a span of three holding the Lyman limit in rest
  wavelength over 913.15–915.2 Å, a tick at each line); Q9.12's options (a title, a
  label's corner, chosen y ticks numbered on the right, a second ion in its own
  colour, signed velocities, the components' numbers).
- The PDF is the same, byte for byte, when the script runs again.
- The style is shipped in ``alis/data/`` and read by matplotlib.

Generated by RJC and Claude.
"""

