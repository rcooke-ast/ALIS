def test_the_style_is_shipped_and_read_by_matplotlib():
    shipped = resources.files("alis") / "data" / FS.STYLE_NAME
    assert shipped.is_file() and Path(FS.STYLE) == Path(str(shipped))
    # Packaged with alis/data/*
    assert 'alis = ["data/*"]' in (ROOT / "pyproject.toml").read_text()
    import matplotlib
    import matplotlib.style

    params = matplotlib.rc_params_from_file(FS.STYLE, use_default_template=False)
    assert params["font.family"] == ["serif"] and params["text.usetex"] is True
