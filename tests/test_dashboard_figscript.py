def test_every_colour_is_a_variable_at_the_top(tmp_path, registry):
    project, view = project_with_run(METAL, registry)
    fid = with_preset(project, view, FP.METALS)
    script, _ = written(project, view, fid, tmp_path)
    text = script.read_text()
    top = text[: text.index("PANELS = ")]
    for name in (
        "DATA_COLOUR",
        "MODEL_COLOUR",
        "CONTINUUM_COLOUR",
        "ZERO_COLOUR",
        "RESIDUAL_COLOUR",
        "RESIDUAL_BANDS",
        "TICK_COLOURS",
        "OTHER_TICK_COLOUR",
    ):
        assert "\n" + name + " = " in top
    # No colour is written in the drawing itself
    drawing = text[text.index("PANELS = ") :]
