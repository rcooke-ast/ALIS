def shown_numbers(window):
    """Every number the window shows of its own (the .mod panel's text left out)."""
    inspect = window.fit_tab.inspect
    texts = ui_strings(window) + [c.marks.text() for c in inspect.chip_widgets]
    texts += [w.marks.text() for w in inspect.panel_widgets]
    for widget in inspect.panel_widgets:
        texts += [
            line.label.textItem.toPlainText()
            for line in widget.view.ticks()
            if line.label is not None
        ]
    return set(re.findall(r"\d[\d.]*", " ".join(texts)))


@pytest.mark.parametrize("global_blind", [False, True], ids=["lines", "global"])
def test_no_hidden_value_on_the_sub_tab(window, qtbot, global_blind):
    window.import_path(str(BLIND))
    wait_idle(qtbot, window)
    project = window.session.project
    # A run as a bundle stores it: the real values, hidden (a plain run's .mod.out
    # writes "BLIND MODEL" instead)
    offset = R.blind_offset({"blindrange": [-1.0e6, 1.0e6], "blindseed": 1234})
    reference = (METAL.parent / (METAL.name + ".out.reference")).read_text()
    store_run(project, METAL, mod_out=_blind_out(reference, offset))
    if global_blind:
        window.answers.answers["blind"] = "Blind"
        window.do_model_blind()
    window.refresh()
    inspect = show_inspect(window, qtbot)
    assert inspect.mode == FV.FINAL and inspect.shown is not None
    assert model_drawn(inspect.panel_widgets[0]) is not None
    gate = BL.Gate(project)
    best = inspect.shown.values
    bad = set()
    for par in project.parsed.params:
        if gate.is_hidden(par):
            bad |= renderings(par.start)
        if (gate.is_hidden(par) or global_blind) and par.index in best:
            bad |= renderings(best[par.index])
    assert bad
    found = [b for b in bad if b in shown_numbers(window) and b not in ("0.0",)]
    assert not found
    assert not design_references(ui_strings(window))


