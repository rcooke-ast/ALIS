def test_initial_and_final_draw_the_start_and_the_best_fit(window, qtbot):
    inspect = j1358(window, qtbot)
    project = window.session.project
    inspect.show_choice(inspect._choices[-1].key)
    snip = project.snips[-1]
    best = RS.View.latest(project).curves()[snip.data.index]
    start = PR.of(project).evaluate(snips=[snip.data.index])[snip.data.index]
    [widget] = inspect.panel_widgets
    x, y = model_drawn(widget)
    finite = np.isfinite(best.model)
    drawn = y[np.isfinite(y)]
    expected = (best.model / best.continuum)[finite]
    assert np.allclose(np.sort(drawn), np.sort(expected), rtol=1e-6)
    inspect.select("model", FV.INITIAL)
    assert inspect.mode == FV.INITIAL
    assert inspect.shown_label.text().startswith("Initial")
    [widget] = inspect.panel_widgets
    x, y = model_drawn(widget)
    expected = (start.model / start.continuum)[np.isfinite(start.model)]
    assert np.allclose(np.sort(y[np.isfinite(y)]), np.sort(expected), rtol=1e-6)
    assert window.session.view["fit"]["model"] == FV.INITIAL
    # The panel's marks and the chips are those of the model drawn: Initial's
    nsig = float(project.parsed.argflag["out"]["reportsig"])
    initial = PR.of(project).evaluate()
    chips = {c.chip.key: c.chip.quality for c in inspect.chip_widgets}
    for snip in project.snips:
        quality = RS.quality(initial[snip.data.index], nsig)
        assert chips[FV.snip_key(snip)] == quality
    assert widget.marks.text() == fit_marks(chips[FV.snip_key(snip)])
    # And Final's with Final
    inspect.select("model", FV.FINAL)
    assert "runs −9.6 ✕" in inspect.chip_widgets[0].marks.text()


