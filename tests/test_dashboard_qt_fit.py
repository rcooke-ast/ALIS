@pytest.mark.fast
@pytest.mark.parametrize("choice", ["Stop the run", "Keep it running", "Don't close"])
def test_closing_during_a_run(window, qtbot, tmp_path, choice):
    path = open_metal(window, qtbot, tmp_path)
    window.answers.answers["running"] = choice
    window.qactions["fit.run"].trigger()
    qtbot.waitUntil(
        lambda: window.fit.job.iteration is not None or not window.fit.active,
        timeout=300000,
    )
    running = window.fit.active
    closed = window.close_session()
    if not running:
        # The fit ended before the question: nothing was asked
        assert closed
        return
    asked = [a for a in window.answers.asked if a[0] == "running"]
    assert asked and "keep it running" in asked[0][2]
    if choice == "Don't close":
        assert not closed and window.fit.active
        return
    assert closed
    if choice == "Stop the run":
        assert R.latest(B.read(path)).status in (R.INTERRUPTED, R.COMPLETED)
        return
    # Kept running: it stores its result in the file all the same
    deadline = time.time() + 300
    while R.latest(B.read(path)) is None and time.time() < deadline:
        qtbot.wait(200)
    assert R.latest(B.read(path)).status == R.COMPLETED
    # Shown when the project is next opened
    window.open_path(path)
    inspect = show_inspect(window, qtbot)
    assert inspect.mode == FV.FINAL and inspect.shown is not None


