def test_all_settings_makes_one_step(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    inspect = window.fit_tab.inspect
    project = window.session.project
    original = project.text
    seen = []

    def answer(dialog):
        seen.append(dialog)
        assert isinstance(dialog, D.AllSettingsDialog)
        names = {s for s in dialog.rows}
        assert ("sim", "perturb") in names and ("run", "ncpus") in names
        assert "Command line only" in dialog.rows[("sim", "perturb")]["item"].text(4)
        assert not dialog.rows[("run", "blind")]["editor"].isEnabled()
        dialog.filter.setText("maxiter")
        shown = [k for k, r in dialog.rows.items() if not r["item"].isHidden()]
        assert shown == [("chisq", "maxiter")]
        dialog.set_value("chisq", "maxiter", "800")
        dialog.set_value("out", "verbose", "1")
        dialog.reset("chisq", "miniter")
        assert sorted(dialog.changes()) == [
            ("chisq", "maxiter", "800"),
            ("chisq", "miniter", None),
            ("out", "verbose", "1"),
        ]
        return 1

    window.on_dialog = answer
    inspect.all_settings.click()
    assert seen
    assert "chisq maxiter 800" in project.text and re.search(
        r"out +verbose +1", project.text
    )
    assert "miniter" not in project.text
    assert window.qactions["edit.undo"].text() == "Undo Change 3 settings"
    window.qactions["edit.undo"].trigger()
    assert project.text == original


