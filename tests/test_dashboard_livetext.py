"""The ``.mod`` panel's text while the user types (dashboard Stage 3.6), with no Qt.

Each key turns the change of the panel's (masked) text into a patch of the real
text, and the masks move with the text around them; after a pause the patches are
given to the history as one change. An edit that touches a mask asks for the new
value instead, which stays hidden.

Generated by RJC and Claude.
"""

import copy
from pathlib import Path

import pytest
from hypothesis import given, settings
from hypothesis import strategies as st

from alis import bundle as B
from alis.dashboard import blinding as BL
from alis.dashboard import livetext as L
from alis.dashboard import model as M
from alis.dashboard import project as P

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
BLIND = ROOT / "examples/blind/model/fit_spectra.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture(scope="module")
def blind_bundle():
    return B.pack(str(BLIND))


def project_of(bundle, registry, crlf=False):
    bundle = copy.deepcopy(bundle)
    if crlf:
        member = bundle.model_member
        text = bundle.members[member].decode("utf-8")
        bundle.members[member] = text.replace("\n", "\r\n").encode("utf-8")
    return P.Project(bundle, registry)


def type_at(live, at, typed, delete=0):
    """Type at a position of the panel's text, as the editor would."""
    new = live.shown[:at] + typed + live.shown[at + delete :]
    return live.edit(new, cursor=at + len(typed))


def test_diff():
    assert L.diff("abc", "abXc") == (2, 2, "X")
    assert L.diff("abc", "ac") == (1, 2, "")
    start, end, typed = L.diff("abc", "abc")
    assert start == end and typed == ""
    # Repeated characters: the cursor decides where the edit was
    assert L.diff("aa", "aaa", cursor=1) == (0, 0, "a")
    assert L.diff("aa", "aaa", cursor=3) == (2, 2, "a")
    assert L.diff("a  b", "a b", cursor=2) == (2, 3, "")


def test_typing_outside_a_mask_patches_the_real_text(blind_bundle, registry):
    project = project_of(blind_bundle, registry)
    live = L.LiveText(BL.Gate(project).view())
    at = live.shown.index("chisq ftol")
    patch = type_at(live, at, "# ")
    assert patch.new == "# " and patch.start == project.text.index("chisq ftol")
    # After a mask, the text and the masks have moved together
    at = live.shown.index("blind=True")
    type_at(live, at, "x")
    change = live.pending()
    real = change.apply(project.text)
    assert "# chisq ftol" in real and "xblind=True" in real
    assert real == live.real
    # The hidden values are still in the real text, unchanged
    hidden = project.text.splitlines()[23]
    assert hidden.split("blind")[0] in real


def test_a_key_beside_a_mask_does_not_touch_it(blind_bundle, registry):
    project = project_of(blind_bundle, registry)
    live = L.LiveText(BL.Gate(project).view())
    line = live.shown.splitlines()[23]
    start = live.shown.index(line)
    mask = start + line.index(BL.MASK + "da")
    # Just after the mask: the label is edited
    patch = type_at(live, mask + len(BL.MASK), "x")
    assert isinstance(patch, P.T.Patch)
    assert "1.0xda" in live.real
    # Just before it: a space is added
    patch = type_at(live, mask, " ")
    assert " 1.0xda" in live.real


def test_an_edit_inside_a_mask_asks_for_the_value(blind_bundle, registry):
    project = project_of(blind_bundle, registry)
    live = L.LiveText(BL.Gate(project).view())
    line = live.shown.splitlines()[23]
    mask = live.shown.index(line) + line.index(BL.MASK)
    result = type_at(live, mask + 2, "1")
    assert result == L.MaskEdit(mask + 2, mask + 2, "1")
    assert not live.dirty
    # Selecting the whole mask and pasting a value: made as it is, still hidden
    patch = type_at(live, mask, "13.5", delete=len(BL.MASK))
    assert patch.old == "13.0" and patch.new == "13.5"
    # The typed value is shown as typed until the text is read again
    assert "13.5" in live.shown
    project.apply(project.step(live.pending()))
    live = L.LiveText(BL.Gate(project).view())
    assert "13.5" not in live.shown
    # Cutting into a mask asks for the value, which replaces the whole value
    result = type_at(live, mask + 1, "7", delete=1)
    assert isinstance(result, L.MaskEdit) and result.typed == "7"
    patch = live.replace_masked(result.start, result.end, "13.75")
    assert patch.old == "13.5" and patch.new == "13.75"
    real = live.pending().apply(project.text)
    assert real.splitlines()[23].split()[2] == "13.75"
    # The value stays hidden once the text is read again
    project.apply(project.step(live.pending()))
    view = BL.Gate(project).view().text
    assert "13.75" not in view


def test_crlf_line_endings(blind_bundle, registry):
    project = project_of(blind_bundle, registry, crlf=True)
    assert "\r\n" in project.text
    live = L.LiveText(BL.Gate(project).view())
    assert "\r" not in live.shown
    at = live.shown.index("blind=True")
    type_at(live, at, "x")
    at = live.shown.index("model end")
    type_at(live, at, "#")
    real = live.pending().apply(project.text)
    assert "xblind=True\r\n" in real and "#model end\r\n" in real
    # Joining two lines removes the whole \r\n
    at = live.shown.index("data end") - 1
    type_at(live, at, "", delete=1)
    real = live.pending().apply(project.text)
    assert real.count("\r\n") == project.text.count("\r\n") - 1
    assert "\r" not in real.replace("\r\n", "")


@settings(max_examples=60, deadline=None, database=None)
@given(
    edits=st.lists(
        st.tuples(
            st.floats(0, 1),
            st.integers(0, 4),
            st.text(alphabet="ab 1.\n", max_size=4),
        ),
        max_size=8,
    )
)
def test_any_typing_outside_the_masks_keeps_them(edits, blind_bundle, registry):
    """Whatever is typed between the masks, the hidden values are kept exactly."""
    project = project_of(blind_bundle, registry)
    live = L.LiveText(BL.Gate(project).view())
    hidden = [project.text[s[2] : s[3]] for s in live.segments]
    for where, delete, typed in edits:
        at = int(where * len(live.shown))
        result = type_at(live, at, typed, delete)
        if isinstance(result, L.MaskEdit):
            continue
        # The shown text is the real text with the hidden values masked
        assert [live.real[s[2] : s[3]] for s in live.segments] == hidden
        rebuilt, pos = [], 0
        for ds, de, rs, re, _ in live.segments:
            rebuilt.append(live.real[pos:rs])
            rebuilt.append(live.shown[ds:de])
            pos = re
        rebuilt.append(live.real[pos:])
        assert "".join(rebuilt) == live.shown
    assert live.pending().apply(project.text) == live.real


def test_position_and_offset():
    text = "ab\ncde\n\nf"
    assert L.position(text, 4) == (1, 1)
    assert L.offset(text, 1, 1) == 4
    assert L.offset(text, 1, 99) == 6
    assert L.offset(text, 9, 0) == 8


def test_deleting_a_whole_hidden_line_is_made(blind_bundle, registry):
    project = project_of(blind_bundle, registry)
    live = L.LiveText(BL.Gate(project).view())
    lines = live.shown.splitlines(keepends=True)
    start = sum(len(x) for x in lines[:23])
    result = type_at(live, start, "", delete=len(lines[23]))
    assert isinstance(result, P.T.Patch)
    assert "28Si_II" not in live.real
    # Only the masks of the O I line's blind range are left
    assert [live.real[sg[2] : sg[3]] for sg in live.segments] == [
        "1234",
        "-1000000.0,1000000.0",
    ]
    # Retyping a whole hidden line: the values are typed, none is shown
    live = L.LiveText(BL.Gate(project).view())
    result = type_at(
        live,
        start,
        "    voigt ion=28Si_II 12.5 0.0 1.0da 8000TA" " specid=0 blind=True\n",
        delete=len(lines[23]),
    )
    assert isinstance(result, P.T.Patch)
    project.apply(project.step(live.pending()))
    assert "12.5" not in BL.Gate(project).view().text
