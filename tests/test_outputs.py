# -- One fit, both writers ----------------------------------------------------------


def _run(workdir, writer):
    """Fit ``examples/metal_line_abs`` in ``workdir`` with ``writer``."""
    from alis import load
    from alis.main import ClassMain
    from alis.scripts.run_alis import parser

    import matplotlib.pyplot as plt

    plt.close("all")  # each fit starts from a clean pyplot state, as run_alis does
    cwd = os.getcwd()
    os.chdir(workdir / "model")
    try:
        args = parser(["fit_spectra.mod", "-p", "0", "-c", "1",
                       "--set", "run backend cpu", "-v", "0"])
        overrides = []
        argflag = load.optarg(argv=args, overrides=overrides, verbose=0)
        argflag["run"]["modname"] = args.alis_modfile
        ClassMain(argflag, cli_overrides=overrides, writer=writer)
    finally:
        os.chdir(cwd)


def _stage(tmp_path, name):
    dest = tmp_path / name
    src = ROOT / "examples" / "metal_line_abs"
    (dest / "model").mkdir(parents=True)
    shutil.copy(src / "model" / "fit_spectra.mod", dest / "model")
    (dest / "data").mkdir()
    shutil.copy(src / "data" / "OI_SiII.dat", dest / "data")
    return dest


def _without_dates(content):
    """The file with the lines that hold the date or the run time removed."""
    keep = [ln for ln in content.split(b"\n")
            if b"Generated by ALIS on" not in ln and b"Running Time" not in ln]
    return b"\n".join(keep)


@pytest.mark.fast
@pytest.mark.examples
def test_a_fit_writes_the_same_files_to_memory_as_to_disk(tmp_path):
    pytest.importorskip("matplotlib")
    os.environ.setdefault("MPLBACKEND", "Agg")
    disk = _stage(tmp_path, "disk")
    before = {p for p in disk.rglob("*") if p.is_file()}
    _run(disk, None)
    written = {str(p.relative_to(disk / "model")) if p.is_relative_to(disk / "model")
               else os.path.join("..", str(p.relative_to(disk))): p
               for p in disk.rglob("*") if p.is_file() and p not in before}
    written = {os.path.normpath(k): v for k, v in written.items()}

    mem = _stage(tmp_path, "memory")
    before = {p for p in mem.rglob("*") if p.is_file()}
    writer = outputs.MemoryOutputs()
    _run(mem, writer)
    # Nothing was written to disk by the memory run
    assert {p for p in mem.rglob("*") if p.is_file()} == before
    assert sorted(writer.files) == sorted(written)
    for key, path in written.items():
        if key.endswith(".pdf"):
            continue  # holds its creation date
        assert _without_dates(writer.files[key]) == _without_dates(
            path.read_bytes()), key
