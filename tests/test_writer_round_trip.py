"""A saved `.mod.out` must be a valid `.mod` input (Stage 5.5, pinning 5.4).

ALIS documents its output model as re-readable, but until Stage 5.4 it was not:
`examples/lsf_hst`'s echo of `resolution=lsf(name=STIS,...)` crashed the reader
outright, and voigt's `damping=0.0000000` came back as a *free* parameter where
the implicit default is fixed, changing the degrees of freedom. Both were worked
around in the harness itself (`_ZERO_DAMPING_RE`, the hand-fixed
`.mod.out.reference_adjusted` files) precisely because nothing pinned the
round trip. Those workarounds are gone; this is what replaces them.

No fit is run. The committed `.mod.out.reference` files *are* saved models, so
re-reading them is the round trip, and the model block can be parsed without
touching a single data file.

Blind models are excluded, and deliberately so: `run blind` replaces the
parameters with `------ BLIND MODEL ------`, so a blind output is *meant* not to
be re-readable. That exclusion is itself asserted below, so a model cannot drop
out of this suite by quietly becoming unparseable.

Generated by RJC and Claude.
"""

import numpy as np
import pytest

from alis import load
from alis.config import ArgFlag
from alis.main import build_funcarray

pytestmark = pytest.mark.unit

REPO_ROOT = __import__("pathlib").Path(__file__).resolve().parent.parent
BLIND_MARKER = "BLIND MODEL"


def _reference_pairs():
    """(input .mod, saved .mod.out.reference) for every committed reference.

    `context/fitting_examples/` is not tracked, so on a clean checkout this is
    just `examples/` -- which is the point: the test still runs in CI.
    """
    pairs = []
    for root in ("examples", "context/fitting_examples"):
        base = REPO_ROOT / root
        if not base.is_dir():
            continue
        for ref in sorted(base.rglob("*.mod.out.reference")):
            mod = ref.with_name(ref.name[: -len(".out.reference")])
            if mod.is_file():
                pairs.append((mod, ref))
    return pairs


PAIRS = _reference_pairs()
NONBLIND = [p for p in PAIRS if BLIND_MARKER not in p[1].read_text()]
BLIND = [p for p in PAIRS if BLIND_MARKER in p[1].read_text()]


def _ids(pairs):
    return [str(m.relative_to(REPO_ROOT)) for m, _ in pairs]


class _State:
    """The attributes the model-block loaders read, and nothing else."""

    def __init__(self):
        self._argflag = ArgFlag()
        self._argflag["out"]["verbose"] = -1
        self._specid = np.array(["0"])
        self._resn = []
        self._shft = []
        self._emab = []
        self._funcused = []


def parse_model_block(path, atomic):
    """(n parameters, n free) for a model file, without loading any data.

    Only the `model read` block is parsed, so this needs neither the spectra nor
    a fit -- which is what makes it a `unit` test over 40-odd real models.
    """
    state = _State()
    _par, datlines, modlines, lnklines = load.load_input(
        state, filename=str(path), updateself=False
    )
    # specids come from the data block; take them textually rather than loading
    # the spectra, which is the expensive part we are avoiding.
    sids = []
    for line in datlines:
        for token in line.split():
            if token.startswith("specid="):
                for sid in token.split("=", 1)[1].split(","):
                    if sid and sid not in sids:
                        sids.append(sid)
    state._specid = np.array(sids if sids else ["0"])
    state._atomic = atomic
    state._funcarray = build_funcarray(state._argflag, state._atomic)
    state._modpass = load.load_model(state, modlines)
    state._links = load.load_links(state, lnklines)
    parinfo, _levadd = load.load_parinfo(state)
    free = sum(1 for p in parinfo if not p.get("fixed", 0))
    return len(parinfo), free


@pytest.fixture(scope="module")
def atomic():
    # Loaded once: it is the same file for every model and costs ~1s a time.
    return load.load_atomic(_State())


def test_there_are_references_to_check():
    # Guards the guard: an empty parametrisation would make every test below
    # pass vacuously.
    assert len(NONBLIND) >= 20, f"only found {len(NONBLIND)} non-blind references"


@pytest.mark.parametrize("mod,ref", NONBLIND, ids=_ids(NONBLIND))
def test_a_saved_model_is_accepted_by_the_reader(mod, ref, atomic):
    """The `lsf_hst` failure: the reader rejected the file outright.

    `msgs.error` exits, so an unreadable file surfaces as SystemExit.
    """
    try:
        parse_model_block(ref, atomic)
    except SystemExit as err:
        pytest.fail(f"{ref.name} is not a valid model file: {err}")


@pytest.mark.parametrize("mod,ref", NONBLIND, ids=_ids(NONBLIND))
def test_the_round_trip_preserves_the_free_parameter_count(mod, ref, atomic):
    """The `damping=` failure: re-reading changed the degrees of freedom.

    DOF = Npix - Nfree and the pixels do not change, so an unchanged free count
    is exactly the invariant that was broken (helium34: 618 against 621).
    """
    _npar_in, free_in = parse_model_block(mod, atomic)
    _npar_out, free_out = parse_model_block(ref, atomic)
    assert free_out == free_in, (
        f"{mod.name}: {free_in} free parameters, but its saved model "
        f"re-reads as {free_out}"
    )


@pytest.mark.parametrize("mod,ref", BLIND, ids=_ids(BLIND))
def test_blind_models_are_excluded_only_because_they_are_blind(mod, ref, atomic):
    """A model may only leave this suite by being blind, not by being broken.

    Without this, a file that became unparseable for some *other* reason could
    be silently dropped from the round-trip check above.
    """
    assert BLIND_MARKER in ref.read_text()
    with pytest.raises(SystemExit):
        parse_model_block(ref, atomic)


def test_an_explicit_default_damping_would_be_caught(atomic):
    """The mechanism behind the 5.4 bug, pinned directly.

    A suffixless `damping=0.0` is a *free* parameter, while omitting it uses the
    fixed default -- so if the writer ever starts emitting it again, the free
    count above moves. This asserts that difference is real, so the test above
    is known to be capable of catching it.
    """
    state = _State()
    state._atomic = atomic
    state._funcarray = build_funcarray(state._argflag, state._atomic)
    base = [
        "emission",
        "  legendre 1.0   specid=0",
        "absorption",
        "  voigt   ion=1H_I   14.0   0.0   5.0   1000.0   specid=0",
    ]
    withdamp = list(base)
    withdamp[-1] += "   damping=0.0000000"

    def free_of(lines):
        st = _State()
        st._atomic = atomic
        st._funcarray = build_funcarray(st._argflag, st._atomic)
        st._modpass = load.load_model(st, lines)
        st._links = load.load_links(st, [])
        parinfo, _ = load.load_parinfo(st)
        return sum(1 for p in parinfo if not p.get("fixed", 0))

    assert free_of(withdamp) == free_of(base) + 1, (
        "an explicit suffixless damping should add a free parameter; if it does "
        "not, the round-trip test above can no longer detect the 5.4 regression"
    )
