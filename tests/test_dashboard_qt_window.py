def need(path):
    if not path.exists():
        pytest.skip("{0} is not present".format(path.name))


def check_workspace(window, name):
    """The parts every open project shows."""
    assert window.stack.currentIndex() == 1
    assert window.windowTitle().startswith("ALIS dashboard — " + name)
    assert [window.tabs.tabText(n) for n in range(5)] == list(A.TABS)
    assert not window.tabs.isTabEnabled(4)
    assert window.tabs.tabToolTip(4) == "Not yet available"
    fit = window.tab_widgets[3].subtabs
    assert [fit.tabText(n) for n in range(3)] == ["Inspect", "Results", "Compare"]
    assert [m.title() for m in window.menus.values()] == list(A.MENUS)
    assert window.panel.isVisible()
    assert window.panel.editor.toPlainText()
    assert window.status_fit.text() == "No fit running"
    assert window.status_model.text()
    for num, marker in enumerate(window.markers.values()):
        assert window.tabs.tabToolTip(num) if num < 4 else True
        assert not window.tabs.tabIcon(num).isNull()


