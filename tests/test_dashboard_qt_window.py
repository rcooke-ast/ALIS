def test_no_dialog_names_a_design_document(window, qtbot, tmp_path):
    from alis.dashboard.qt import dialogs as D

    window.import_path(str(BLIND))
    wait_idle(qtbot, window)
    session = window.session
    dialogs = [
        D.NewProjectDialog(str(tmp_path)),
        D.SpectrumDialog(str(tmp_path)),
        D.PreferencesDialog(window.prefs),
        D.ShortcutsDialog(window.qactions),
        D.RelinkDialog(session, lambda entry: None),
        D.UnblindDialog(session.project, False),
        D.BlindLinesDialog(session.project),
    ]
    for dialog in dialogs:
        qtbot.addWidget(dialog)
        strings = [dialog.windowTitle()]
        for widget in dialog.findChildren(QtWidgets.QWidget):
            for attr in ("text", "toolTip", "placeholderText"):
                method = getattr(widget, attr, None)
                if callable(method):
                    try:
                        value = method()
                    except TypeError:
                        continue
                    if isinstance(value, str):
                        strings.append(value)
        if isinstance(dialog, D.ShortcutsDialog):
            # The shortcut column holds keys (F1), not references
            strings += [c for row in dialog.rows() for n, c in enumerate(row) if n != 2]
        assert design_references(strings) == [], type(dialog).__name__
