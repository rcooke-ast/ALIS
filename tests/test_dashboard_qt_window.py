def test_the_mod_panel_collapses_to_a_strip(window, qtbot, tmp_path):
    session, _ = S.Session.new(str(tmp_path / "empty.model"), [str(SPECTRUM)])
    window.set_session(session)
    window.panel.hide_button.click()
    assert not window.panel.isVisible() and window.strip.isVisible()
    assert window.session.view["mod_panel"]["open"] is False
    window.strip.click()
    assert window.panel.isVisible() and not window.strip.isVisible()
    window.qactions["view.mod_panel"].trigger()
    assert not window.panel.isVisible()
    # The view is kept in the bundle when the project is closed
    window.qactions["view.fit"].trigger()
    window.do_file_close()
    view = S.Session.open(str(tmp_path / "empty.model")).view
    assert view["tab"] == "Fit" and view["mod_panel"]["open"] is False


