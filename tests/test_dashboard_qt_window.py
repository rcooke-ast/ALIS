    assert "already" in dialog.add_spectrum(str(SPECTRUM))
    assert dialog.sources() == [str(SPECTRUM)]
    dialog.redshift.setText("2.5")
    assert dialog.problem() == ""
    assert dialog.values()["z"] == 2.5
    assert dialog.values()["path"] == os.path.join(str(tmp_path), "x.model")
    assert not dialog.mode.model().item(1).isEnabled()


