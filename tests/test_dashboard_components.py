def test_temperature_modes(metal):
    project, hist, _ = with_component(metal)
    before = state(project)
    registry = project.registry

    def width(comp):
        line = comp.lines_of("16O_I")[0]
        return C.total_b(
            registry,
            "16O_I",
            line.param("bturb").start,
            line.param("temperature").start,
        )

    start = width(project.components[0])
    hist.do(C.temperature(project, project.components[0], "fixed", 8000.0))
    assert project.components[0].temperature_mode == ("fixed", 8000.0)
    hist.do(C.temperature(project, project.components[0], "preset", 1.0e4))
    assert project.components[0].temperature_mode == ("preset", 1.0e4)
    hist.do(C.temperature(project, project.components[0], "free"))
    assert project.components[0].temperature_mode == ("free", None)
    # Pure thermal keeps the line's width: b_turb 0 and fixed, T free
    wide = width(project.components[0])
    hist.do(C.temperature(project, project.components[0], "thermal"))
    comp = project.components[0]
    assert comp.temperature_mode == ("thermal", None)
    assert comp.main.param("bturb").start == 0.0 and comp.main.param("bturb").fixed
    assert width(comp) == pytest.approx(wide, rel=1e-4)
    # And back to a fixed temperature, b_turb free again, the width kept
    hist.do(C.temperature(project, comp, "preset", 100.0))
    comp = project.components[0]
    assert comp.temperature_mode == ("preset", 100.0)
    assert not comp.main.param("bturb").fixed
    assert width(comp) == pytest.approx(wide, rel=1e-3)
    assert errors(project) == []
    assert start == pytest.approx(5.0)
    for _ in range(5):
        hist.undo()
    assert state(project) == before


