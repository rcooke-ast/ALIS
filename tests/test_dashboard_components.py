def test_what_a_link_computes_is_shown_and_not_dragged(registry):
    project = P.Project.import_model(str(SUMMED), registry=registry)
    comps = {c.label: c for c in project.components if c.label}
    # ra's log N is computed by a link, and rb's z from ra's
    assert C.draggable(comps["ra"], "1H_I") == {"z": True, "logn": False, "b": True}
    assert C.draggable(comps["rb"], "1H_I")["z"] is False
    # Dragging ra moves rb, as ALIS computes it: shown there, though not written
    hist = H.History(project)
    ra = comps["ra"]
    hist.do(C.drag_step(project, ra, C.drag(project, ra, "1H_I", z=0.0005)))
    rb = next(c for c in project.components if c.label == "rb")
    assert rb.main.param("redshift").start == pytest.approx(0.0001)
    linked = C.linked_values(project)
    assert C.component_z(rb, linked) == pytest.approx(0.0006)
    # A value no link computes is shown as written
    ra = next(c for c in project.components if c.label == "ra")
    assert C.component_z(ra, linked) == pytest.approx(0.0005)


