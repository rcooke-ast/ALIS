def test_interloper_choices_offer_the_forest_then_other_systems(registry):
    if not Q1243.exists():
        pytest.skip("model not present: " + str(Q1243.relative_to(ROOT)))
    project = P.Project.import_model(str(Q1243), registry=registry)
    primary = project.systems[0]
    other = next(s for s in project.systems if abs(s.z - 2.39869) < 1e-4)
    wave = 1215.6701 * (1.0 + other.z) + 0.5
    choices = C.interloper_choices(project, wave, primary)
    assert [c.text for c in choices[:4]] == [
        "Lyα forest line",
        "Lyα forest line, fixed",
        "H I blend, every Lyman line",
        "H I blend, every Lyman line, fixed",
    ]
    found = [c for c in choices if c.system is not None]
    # The other system whose line ID is there; never the system shown
    assert found[0].system.id == other.id and found[0].ion == "1H_I"
    assert found[0].text.startswith("Lyα 1215.7 of z = 2.39869, at +")
    assert found[0].z == pytest.approx(wave / 1215.6701 - 1.0)
    assert all(c.system.id != primary.id for c in found)
    # One step adds a component to that system; one undo restores the text
    hist = H.History(project)
    before = state(project)
    count = len(other.components)
    step, guesses = C.add_interloper(project, found[0])
    hist.do(step)
    assert len(project.system(other.id).components) == count + 1
    assert set(guesses) == {"1H_I"}
    hist.undo()
    assert state(project) == before


