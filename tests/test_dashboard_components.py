def test_no_detection_and_no_data(registry, tmp_path):
    project = si2_project(registry, synthetic_si2(tmp_path / "si2.dat", 13.0))
    # 100 km/s away from the lines: covered, but nothing there
    guess = C.first_guess(project, "28Si_II", 100.0 / C_KMS, 5.0, 0.0)
    assert guess.note == "not detected"
    assert guess.logn == min(e.limit for e in guess.estimates)
    # The lowest 3σ limit comes from the most sensitive transition, 1260
    best = min(guess.estimates, key=lambda e: e.limit)
    assert round(best.rest) == 1260 and 11.0 < guess.logn < 12.0
    # Where no snip holds a transition: the preference
    guess = C.first_guess(project, "28Si_II", 0.01, 5.0, 0.0)
    assert (guess.logn, guess.note, guess.estimates) == (12.0, "no data", [])


