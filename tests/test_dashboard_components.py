def test_a_drag_gives_values_within_bounds(metal):
    project, hist, _ = with_component(metal)
    comp = project.components[0]
    values = dict(
        (p.name, v) for p, v in C.drag(project, comp, "16O_I", logn=14.3, b=6.0)
    )
    assert values == {"ColDens": 14.3, "bturb": 6.0}
    # log N stops at the dashboard's range; b_turb at voigt.py's 0.5 km/s
    values = dict(
        (p.name, v) for p, v in C.drag(project, comp, "16O_I", logn=30.0, b=0.1)
    )
    assert values == {"ColDens": 23.0, "bturb": 0.5}
    values = dict((p.name, v) for p, v in C.drag(project, comp, "16O_I", logn=1.0))
    assert values == {"ColDens": 8.0}
    # A lim in the model bounds the drag
    pm = project.parsed
    bpar = comp.main.param("bturb")
    hist.do(project.step(E.set_limits(pm, bpar, 2.0, 4.0)))
    comp = project.components[0]
    values = dict((p.name, v) for p, v in C.drag(project, comp, "16O_I", b=9.0))
    assert values == {"bturb": 4.0}
    # The total b gives b_turb at the component's temperature
    hist.do(C.temperature(project, comp, "fixed", 1.0e4))
    comp = project.components[0]
    btot = math.sqrt(3.5**2 + C.thermal_b2(project.registry, "16O_I", 1.0e4))
    values = dict((p.name, v) for p, v in C.drag(project, comp, "16O_I", b=btot))
    assert values["bturb"] == pytest.approx(3.5)


def test_a_drag_is_one_step_and_moves_the_model(metal):
    project, hist, _ = with_component(metal)
    before = state(project)
    comp = project.components[0]
    changes = C.drag(project, comp, "16O_I", z=2.0 / C_KMS, logn=14.1, b=6.5)
    # The profile draws the drag before the text changes
    profile = PR.of(project)
    values = profile.values(C.drag_values(changes))
    moved = profile.evaluate(values)
    still = profile.evaluate()
    index = profile.snips[0]
    assert not np.allclose(moved[index].model, still[index].model, equal_nan=True)
    step = C.drag_step(project, comp, changes)
    assert step.description == "Drag component a1"
    hist.do(step)
    assert errors(project) == []
    comp = project.components[0]
    assert comp.main.param("ColDens").start == 14.1
    assert comp.velocity == pytest.approx(2.0, abs=1e-3)
    # The model of the text now equals the one drawn during the drag
    after = PR.of(project).evaluate()
    assert np.allclose(
        after[index].model, moved[index].model, atol=1e-6, equal_nan=True
    )
    hist.undo()
    assert state(project) == before


