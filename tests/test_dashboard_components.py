def transition(registry, ion, rest):
    atom = L.atomic(registry)
    return next(ln for ln in atom.ion_lines(ion) if abs(ln.rest - rest) < 0.01)


def snipped(registry, path, cuts, z=0.0):
    """A new project from a spectrum, with a snip and a fit region per transition."""
    project, _ = modes.get().empty_project(
        [str(path)], "test", z=z, registry=registry, columns={str(path): COLUMNS}
    )
    hist = H.History(project)
    spectra = {r.id: sources.spectrum(project, r) for r in project.rows}
    for ion, rest, low, high in cuts:
        line = transition(registry, ion, rest)
        hist.do(S.snip_step(project, project.systems[0], line, spectra))
        snip = [s for s in project.snips if s.specid not in done(hist)][0]
        hist.do(S.add_region_step(project, snip, low, high))
    return project, hist


def done(hist):
    """The specids of the snips that already have a fit region."""
    return {s.specid for s in hist.project.snips if S.fitted(s).any()}


