SI2 = {1260.4221: 1.18, 1304.3702: 0.0863, 1526.7066: 0.133, 1808.0129: 0.00208}


def synthetic_si2(path, logn, snr=20.0, seed=1, noise=True):
    """Si II at z = 0, b = 5 km/s, FWHM 7 km/s, S/N per 2.5 km/s pixel."""
    rng = np.random.default_rng(seed)
    wave = 1250.0 * np.exp(np.arange(0.0, math.log(1820.0 / 1250.0), 2.5 / C_KMS))
    fine = 1250.0 * np.exp(np.arange(0.0, math.log(1820.0 / 1250.0), 0.25 / C_KMS))
    tau = np.zeros_like(fine)
    for rest, f in SI2.items():
        tau0 = 1.497e-15 * 10.0**logn * f * rest / 5.0
        vel = C_KMS * (fine / rest - 1.0)
        tau += tau0 * np.exp(-((vel / 5.0) ** 2))
    sigma = 7.0 / 2.3548 / 0.25
    kern = np.exp(-0.5 * (np.arange(-60, 61) / sigma) ** 2)
    flux = np.convolve(np.exp(-tau), kern / kern.sum(), mode="same")
    flux = np.interp(wave, fine, flux)
    error = np.full_like(wave, 1.0 / snr)
    if noise:
        flux = flux + rng.normal(0.0, 1.0 / snr, wave.size)
    np.savetxt(path, np.column_stack([wave, flux, error]))
    return path


def si2_project(registry, path, rests=(1260.4221, 1304.3702, 1526.7066, 1808.0129)):
    cuts = [("28Si_II", r, r * (1 - 150 / C_KMS), r * (1 + 150 / C_KMS)) for r in rests]
    project, _ = snipped(registry, path, cuts)
    return project


def test_the_first_guess_recovers_an_unsaturated_line(registry, tmp_path):
    path = synthetic_si2(tmp_path / "si2.dat", 13.0, snr=50.0, noise=False)
    project = si2_project(registry, path, rests=(1304.3702, 1526.7066, 1808.0129))
    guess = C.first_guess(project, "28Si_II", 0.0, 5.0, 0.0)
    kinds = {round(e.rest): e.kind for e in guess.estimates}
    # 1808 (f = 0.002, 0.9% deep) is below its 3σ limit at S/N 50: set aside
    assert kinds == {1304: "detected", 1527: "detected", 1808: "undetected"}
    assert (guess.note, abs(guess.logn - 13.0) < 0.05) == ("", True)


def test_the_first_guess_takes_the_lowest_detection(registry, tmp_path):
    project = si2_project(registry, synthetic_si2(tmp_path / "si2.dat", 13.0))
    guess = C.first_guess(project, "28Si_II", 0.0, 5.0, 0.0)
    kinds = {round(e.rest): e.kind for e in guess.estimates}
    # At S/N 20, 1260 (93% deep) reaches within 3σ of zero; 1808 is not detected
    assert kinds == {
        1260: "saturated",
        1304: "detected",
        1527: "detected",
        1808: "undetected",
    }
    detected = [e.logn for e in guess.estimates if e.kind == "detected"]
    assert guess.note == "" and guess.logn == min(detected)
    assert abs(guess.logn - 13.0) < 0.2


def test_saturated_everywhere_gives_the_preference(registry, tmp_path):
    path = synthetic_si2(tmp_path / "si2.dat", 15.0)
