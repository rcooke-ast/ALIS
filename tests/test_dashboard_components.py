    before = state(project)
    system = project.systems[0]
    assert C.system_ions(project, system) == ["16O_I", "28Si_II"]
    step, guesses = C.new_component(project, system, 0.0)
    assert step.description == "Add a component to " + system.name
    hist.do(step)
    assert errors(project) == []
    (comp,) = project.components
    assert comp.ions == ["16O_I", "28Si_II"] and comp.label == "za1"
    for line in comp.lines:
        assert line.param("redshift").label == "za1"
        assert line.param("bturb").label == "ba1" and line.param("bturb").start == 5.0
        temp = line.param("temperature")
