@pytest.mark.unit
def test_a_new_project_reads_as_intended(registry, example_spectrum):
    mode = MO.get("voigt")
    project = mode.new_project(
        str(example_spectrum), 0.0, [O_I_1302], fwhm=7.0, registry=registry
    )
    assert not project.paused and project.notices == []
    pm = project.parsed
    assert [d.specid for d in pm.data] == ["OI_1302"]
    data = pm.data[0]
    assert data.param("resolution").label == "FWHM1"
    assert data.param("resolution").fixed and data.shift is None
    assert [ln.function for ln in pm.lines] == ["legendre", "voigt"]
    voigt = pm.lines[1]
    assert [voigt.param(n).label for n in ("redshift", "bturb", "temperature")] == [
        "za1",
        "ba1",
        "TA1",
    ]
    assert voigt.param("temperature").fixed and voigt.param("ColDens").free
    snip = project.snips[0]
    assert snip.pixels.mask is not None and len(snip.regions) == 1
    lo, hi = snip.regions[0]
    # The region is +/-60 km/s, to within a pixel (2.5 km/s here)
    centre = 1302.1685
    assert abs((lo - centre) / centre * 299792.458 + 60.0) < 2.5
    assert abs((hi - centre) / centre * 299792.458 - 60.0) < 2.5
    assert [(s.name, s.primary) for s in project.systems] == [("z = 0.00000", True)]
    assert project.systems[0].components[0].temperature_mode == ("preset", 0.0)
    assert [(r.name, r.reference) for r in project.rows] == [("OI_spectrum", True)]
    source = project.bundle.sources[0]
    assert source["sha256"] == B.sha256(example_spectrum.read_bytes())
    assert json.loads(project.bundle.members["ui/project.json"])["mode"] == "voigt"
    assert V.check(project) == []


@pytest.mark.unit
def test_a_transition_off_the_spectrum_is_refused(registry, example_spectrum):
    mode = MO.get("voigt")
    with pytest.raises(MO.ModeError):
        mode.new_project(str(example_spectrum), 1.0, [O_I_1302], registry=registry)
    with pytest.raises(MO.ModeError):
        mode.new_project(
            str(example_spectrum), 0.0, [("16Xx_I", 1302.1685)], registry=registry
        )


# -- ALIS runs the new project -----------------------------------------------------


def run_bundle(path):
    """Run a bundle in this process, as ``run_alis project.model`` does."""
    import matplotlib

    matplotlib.use("Agg")
    from alis.scripts.run_alis import parser

    args = parser([str(path), "-p", "0", "-c", "1", "--set", "run backend cpu"])
    overrides = []
    argflag = load.optarg(argv=args, overrides=overrides, verbose=-1)
    argflag["run"]["modname"] = args.alis_modfile
    B.run(str(path), argflag, overrides, command="test")
    return json.loads(B.read(str(path)).members[B.LATEST + "run.json"])


@pytest.mark.fast
def test_alis_runs_a_new_project_from_j1358p6522(registry, tmp_path):
    if not FLUXCAL.exists():
        pytest.skip("spectrum not present")
    project = MO.get("voigt").new_project(
        str(FLUXCAL), 3.0672596, [O_I_1039], fwhm=6.974, registry=registry
    )
    assert V.check(project) == []
    path = tmp_path / "J1358p6522.model"
    project.save(str(path))
    info = run_bundle(path)
    assert info["status"] == "completed"
    assert info["chi2_final"] < info["chi2_initial"]
    assert "converge" not in info.get("reason", "") or info["iterations"] > 0
    assert info["model_sha256"] == B.sha256(project.model_bytes()[0])


