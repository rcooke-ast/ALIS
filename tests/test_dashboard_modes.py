@pytest.mark.unit
def test_column_roles_follow_d13():
    wave = np.linspace(1000.0, 1001.0, 5)
    ones, half = np.ones(5), np.full(5, 0.5)
    mask = np.array([0, 1, 1, 0, 1.0])
    assert MO.column_roles(np.column_stack([wave, ones, half])) == {
        "wave": 0,
        "flux": 1,
        "error": 2,
    }
    assert MO.column_roles(np.column_stack([wave, ones, half, mask]))["mask"] == 3
    assert MO.column_roles(np.column_stack([wave, ones, half, half]))["continuum"] == 3
    five = MO.column_roles(np.column_stack([wave, ones, half, mask, half]))
    assert five == {"wave": 0, "flux": 1, "error": 2, "mask": 3}
    with pytest.raises(MO.ModeError):
        MO.column_roles(np.column_stack([wave, ones]))


@pytest.mark.unit
def test_a_continuum_column_is_multiplied_in():
    wave = np.linspace(1000.0, 1001.0, 5)
    data = table_bytes(wave, np.full(5, 0.5), np.full(5, 0.1), np.full(5, 4.0))
    spec = MO.get("voigt").load(data)
    assert np.allclose(spec.flux, 2.0) and np.allclose(spec.error, 0.4)
    assert spec.mask is None and "multiplied" in spec.notes[0]
    roles = {"wave": 0, "flux": 1, "error": 2}
    plain = MO.get("voigt").load(data, columns=roles)
    assert np.allclose(plain.flux, 0.5) and not plain.notes


