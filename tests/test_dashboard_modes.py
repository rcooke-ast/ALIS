O_I_1039 = ("16O_I", 1039.23038)
O_I_1302 = ("16O_I", 1302.1685)


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def table_bytes(*columns):
    out = io.StringIO()
    np.savetxt(out, np.column_stack(columns))
    return out.getvalue().encode()


@pytest.fixture
def example_spectrum(tmp_path):
    """A three-column spectrum: the wave, flux and error of a shipped example."""
    table = np.loadtxt(EXAMPLE_DATA)
    path = tmp_path / "OI_spectrum.dat"
    path.write_bytes(table_bytes(table[:, 0], table[:, 1], table[:, 2]))
    return path


