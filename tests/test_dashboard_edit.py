def test_add_a_continuum_and_a_zero_level(registry):
    pm = parsed(J1358, registry)
    after = apply(
        pm, E.add_continuum(pm, "O4", [1.0, 0.0, 0.0], scale=[1.0, 0.01, 0.01])
    )
    legs = after.function_lines("legendre")
    assert len(legs) == len(pm.function_lines("legendre")) + 1
    new = legs[-1]
    assert new.specids == ["O4"] and [p.value for p in new.params] == [1.0, 0.0, 0.0]
    assert changed(pm, after)[0] == set()
    # J1358p6522 has no zerolevel section: it is made
    assert E.section_lines(pm, "zerolevel") is None
    zero = apply(pm, E.add_zero_level(pm, ["H1", "H2"], 0.01))
    item = zero.function_lines("constant", "zerolevel")[0]
    assert item.specids == ["H1", "H2"] and item.params[0].value == 0.01
    gone, made = changed(pm, zero)
    assert gone == set() and len(made) == 2


