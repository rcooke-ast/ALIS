def test_set_change_and_clear_limits(registry):
    pm = parsed(J1358, registry)
    nval = pm.labels["noi"].params[0]
    after = apply(pm, E.set_limits(pm, nval, 14.0, 16.0))
    cmd = [c for c in after.commands if c.target == "param"]
    assert [(c.name, c.value) for c in cmd] == [("noi", "[14.0,16.0]")]
    assert cmd[0].line == 2 + max(c.line for c in pm.commands) - 1
    assert after.labels["noi"].params[0].limits == (14.0, 16.0)
    gone, made = changed(pm, after)
    assert gone == set() and made == {cmd[0].line}
    again = apply(after, E.set_limits(after, after.labels["noi"].params[0], None, 15.5))
    assert again.labels["noi"].params[0].limits == (None, 15.5)
    assert len(again.text) == len(after.text)
    clear = apply(again, E.clear_limits(again, again.labels["noi"].params[0]))
    assert clear.text.text == pm.text.text


