def test_tie_rows(registry):
    pm = parsed(Q1243, registry)
    proch, hires = rows(pm, "PROCHASKA"), rows(pm, "HIRES")
    after = apply(pm, E.tie_rows(pm, proch, hires, "resolution"))
    assert {d.param("resolution").label for d in rows(after, "PROCHASKA")} == {"vh"}
    assert "vp" not in after.labels
    assert changed(pm, after)[0] == {d.line for d in proch}
    zero = apply(pm, E.tie_rows(pm, proch, hires, "zerolevel"))
    lines = zero.function_lines("constant", "zerolevel")
    assert len(lines) == 2
    assert set(d.specid for d in proch) <= set(lines[0].specids)
    # HIRES has no shift written, so nothing can be tied to it ...
    with pytest.raises(E.EditError):
        E.tie_rows(pm, proch, hires, "shift")
    # ... but HIRES can take PROCHASKA's
    shifted = apply(pm, E.tie_rows(pm, hires, proch, "shift"))
    assert {d.param("shift").label for d in rows(shifted, "HIRES")} == {"SHP"}
