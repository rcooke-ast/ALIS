def test_fix_a_labelled_parameter(registry):
    pm = parsed(J1358, registry)
    zval = voigt(pm, "1H_I").param("redshift")
    assert zval.label == "ra" and zval.free
    after = apply(pm, E.fix(pm, zval))
    assert "RA" in after.labels and "ra" not in after.labels
    assert after.labels["RA"].fixed
