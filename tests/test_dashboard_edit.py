"""Targeted edits of the model text (dashboard Stage 2.4).

Each operation is applied to a real model. The test checks that it changes only the
lines it should, leaving every other byte as it was, and that ALIS's parser (through
the parsed model) reads the result with the structure intended.

Generated by RJC and Claude.
"""

import difflib
from pathlib import Path

import pytest

from alis.dashboard import edit as E
from alis.dashboard import model as M
from alis.dashboard import text as T

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
BLIND = ROOT / "examples/blind/model/fit_spectra.mod"
CTX = ROOT / "context/fitting_examples"
J1358 = CTX / "VMP_DLA/J1358p6522/model/J1358p6522.mod"
Q1243 = CTX / "DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
DHJ = CTX / "DH/J1358p6522/model/J1358p6522_original.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def parsed(path, registry):
    if not path.exists():
        pytest.skip("model not present: " + str(path.relative_to(ROOT)))
    pm = M.ParsedModel(path.read_text(), registry)
    assert pm.ok, pm.errors
    return pm


def apply(pm, change):
    """The model after ``change``, which ALIS must read."""
    after = M.ParsedModel(pm.text.apply(change), pm.registry)
    assert after.ok, after.errors
    return after


def changed(before, after):
    """
    The lines of ``before`` that changed or went, and the lines of ``after`` that
    are new or changed.
    """
    old = before.text.text.splitlines(keepends=True)
    new = after.text.text.splitlines(keepends=True)
    gone, made = set(), set()
    for tag, i1, i2, j1, j2 in difflib.SequenceMatcher(
        None, old, new, autojunk=False
    ).get_opcodes():
        if tag != "equal":
            gone |= set(range(i1, i2))
            made |= set(range(j1, j2))
    return gone, made


def voigt(pm, ion, n=0):
    return [ln for ln in pm.function_lines("voigt") if ln.ion == ion][n]


