@pytest.mark.parametrize(
    "value, text",
    [
        (14.0, "14.0"),
        (1.0e4, "10000.0"),
        (1.0e-7, "1.0E-07"),
        (2.5e22, "2.5E+22"),
        (3.0672596274, "3.0672596274"),
        ("1e4", "1e+4"),
        ("13.5", "13.5"),
    ],
)
def test_values_are_written_as_alis_reads_them(value, text):
    assert E.format_value(value) == text
    assert E.format_value(1.23456789, digits=3) == "1.23"


@pytest.mark.parametrize("bad", ["abc", float("nan"), "inf"])
def test_bad_values_are_refused(bad):
    with pytest.raises(E.EditError):
        E.format_value(bad)


@pytest.mark.parametrize("label", ["1a", "e4", "E12", "a-b", ""])
def test_bad_labels_are_refused(label):
    with pytest.raises(E.EditError):
        E.check_label(label)


def test_set_an_untied_value(registry):
    pm = parsed(METAL, registry)
    oxygen = voigt(pm, "16O_I")
    after = apply(pm, E.set_value(pm, oxygen.param("ColDens"), 14.25))
    assert voigt(after, "16O_I").param("ColDens").value == 14.25
    assert changed(pm, after) == ({oxygen.line}, {oxygen.line})
    line = after.text[oxygen.line].text
    # The next word keeps its column (Q2.6)
    old = pm.text[oxygen.line].text
    assert line.index("0.0    1.0da") == old.index("0.0    1.0da")


