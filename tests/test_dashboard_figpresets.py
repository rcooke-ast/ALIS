"""The Figure tab's presets (dashboard Stage 9, Task 9.3; D28, QF.27). No Qt.

- metals: metal_line_abs's O I and Si II adjacent, in three columns.
- DH: one dataset's Lyman series down the left column and on down the right; two
  datasets one per column, each titled (a synthetic pair, and RJC's Q1243p307);
  J1358p6522's series in two columns (RJC's projects are skipped when absent).
- helium: a synthetic He I fit in a 2 × 2 grid, the residuals inside the panels.
- blends: the system chosen (an interloper in a Lyα snip), each line titled with the
  primary line it blends, the velocities from its strongest component.
- A first figure starts from the preset that suits the project.

Generated by RJC and Claude.
"""

