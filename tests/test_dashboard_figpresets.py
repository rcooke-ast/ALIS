pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"
J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
Q1243 = (
    ROOT
    / "context/fitting_examples/DH/Q1243p307/model/Q1243p307_converge_newstart76.mod"
)
C_KMS = 299792.458


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def imported(path, registry):
    if not Path(path).exists():
        pytest.skip("{0} is not present".format(Path(path).name))
    return P.Project.import_model(str(path), registry=registry)


def figure_of(project, name, **kwargs):
    step, fid = FG.new_figure(project)
    project.apply(step)
    project.apply(FP.apply(project, fid, name, **kwargs))
    return FG.figure(project, fid)


def grid_lines(fig):
    """Each row's cells, as their lines ("" for an empty cell)."""
    return [
        [
            FG.line_text(c["show"]["ion"], c["show"]["rest"]) if c["show"] else ""
            for c in row
        ]
        for row in fig["cells"]
    ]


def write_flat(path, centre, half=3.0, step=0.02):
    """A flat, noisy spectrum about ``centre`` Å."""
    rng = np.random.default_rng(3)
    wave = np.arange(centre - half, centre + half, step)
    flux = 1.0 + 0.01 * rng.standard_normal(wave.size)
    np.savetxt(path, np.column_stack([wave, flux, np.full(wave.size, 0.01)]))


def write_helium(folder):
    """A He I fit of three snips (10833, 3889 and 3188 Å) at z = 0."""
    folder.mkdir(parents=True)
    data = []
    for num, centre in enumerate((10833.3, 3889.75, 3188.67)):
        name = "he_{0}.dat".format(num)
        write_flat(folder / name, centre, half=centre * 150.0 / C_KMS)
        data.append(
            "  {0}  specid={1}  fitrange=all  resolution=vfwhm(3.0VFIX)"
            "  columns=[wave,flux,error]\n".format(name, num)
        )
    text = (
        "run blind False\n\ndata read\n" + "".join(data) + "data end\n\n"
        "model read\n emission\n  constant 1.0CONA specid=0,1,2\n absorption\n"
        "  voigt ion=4He_I 11.0 0.0000000za1 5.0ba1 8000.0TA1 specid=0,1,2\n"
        "model end\n"
    )
    path = folder / "helium.mod"
    path.write_text(text)
    return path


def write_blend(folder):
    """A Lyα snip of H I and D I at Z (the primary system, with the more ions)
    holding an interloper's Si II 1260 (system b), and a Si II 1304 snip of the
    interloper."""
    folder.mkdir(parents=True)
    lya = 1215.6701 * (1.0 + Z)
    zb = (lya + 0.6) / 1260.4221 - 1.0
    write_flat(folder / "lya.dat", lya, half=4.0)
    write_flat(folder / "si1304.dat", 1304.3702 * (1.0 + zb), half=2.0)
    text = (
        "run blind False\n\ndata read\n"
        "  lya.dat  specid=0  fitrange=all  resolution=vfwhm(6.0VFIX)"
        "  columns=[wave,flux,error]\n"
        "  si1304.dat  specid=1  fitrange=all  resolution=vfwhm(6.0VFIX)"
        "  columns=[wave,flux,error]\n"
        "data end\n\nmodel read\n emission\n  constant 1.0CONA specid=0,1\n"
        " absorption\n"
        "  voigt ion=1H_I 14.0 {0:.7f}za1 20.0ba1 0.0TA1 specid=0\n"
        "  voigt ion=2H_I 9.4 {0:.7f}za1 20.0ba1 0.0TA1 specid=0\n"
        "  voigt ion=28Si_II 12.5 {1:.7f}zb1 5.0bb1 0.0TB1 specid=0,1\n"
        "  voigt ion=28Si_II 13.0 {2:.7f}zb2 5.0bb2 0.0TB2 specid=0,1\n"
        "model end\n".format(Z, zb, zb + 10.0 / C_KMS * (1.0 + zb))
    )
    path = folder / "blend.mod"
    path.write_text(text)
    return path


def test_metals_puts_o_i_and_si_ii_side_by_side(registry):
    project = imported(METAL, registry)
    fig = figure_of(project, FP.METALS)
    assert grid_lines(fig) == [["O I 1302.2", "Si II 1304.4", ""]]
    assert (fig["columns"], fig["rows"], fig["size"]) == (3, 1, [7.0, 1.5])
    assert fig["vrange"] == [-125.0, 125.0] and fig["preset"] == FP.METALS
    assert FP.guess(project) == FP.METALS


def test_dh_with_one_dataset_runs_down_the_columns(tmp_path, registry):
    project = imported(write_thermal_fit(tmp_path / "fit"), registry)
    assert FP.guess(project) == FP.DH
    fig = figure_of(project, FP.DH)
    assert grid_lines(fig) == [["Lyα 1215.7", "Lyβ 1025.7"]]
    assert fig["vrange"] == [-190.0, 190.0]


def test_dh_with_two_datasets_has_one_per_column(tmp_path, registry):
    project = imported(write_shifted_fit(tmp_path / "fit"), registry)
    fig = figure_of(project, FP.DH)
    assert grid_lines(fig) == [
        ["Lyα 1215.7", "Lyα 1215.7"],
        ["Lyβ 1025.7", "Lyβ 1025.7"],
    ]
    assert [c["title"] for c in fig["cells"][0]] == ["A data", "B data"]
    datasets = {e.key["specid"]: e.dataset for e in FG.transitions(project)}
    assert [datasets[c["show"]["specid"]] for c in fig["cells"][1]] == ["A", "B"]


def test_dh_from_a_chosen_member(tmp_path, registry):
    # Stage 10 (item 1 carried over): the members with a snip, Lyα first
    project = imported(write_thermal_fit(tmp_path / "one"), registry)
    assert [name for _, name in FP.dh_members(project)] == ["Lyα", "Lyβ"]
    lyb = FP.dh_members(project)[1][0]
    fig = figure_of(project, FP.DH, start=lyb)
    assert [c for row in grid_lines(fig) for c in row if c] == ["Lyβ 1025.7"]
    assert fig["dh_from"] == lyb
    # From Lyα: today's layout
    fig = figure_of(project, FP.DH, start=FP.dh_members(project)[0][0])
    assert grid_lines(fig) == [["Lyα 1215.7", "Lyβ 1025.7"]]
    # Two datasets: one column each, from Lyβ
    project = imported(write_shifted_fit(tmp_path / "two"), registry)
    fig = figure_of(project, FP.DH, start=lyb)
    assert grid_lines(fig) == [["Lyβ 1025.7", "Lyβ 1025.7"]]
    # Below every member with a snip: refused
    with pytest.raises(FP.PresetError, match="from that one up"):
        figure_of(project, FP.DH, start=900.0)
    # A figure saved before reads as Lyα
    step, fid = FG.new_figure(project)
    project.apply(step)
    assert FG.figure(project, fid)["dh_from"] is None
    with pytest.raises(FG.FigureError):
        FG.set_option(project, fid, "dh_from", 1025.7)


def test_j1358p6522_from_ly8(registry):
    # As DH_Ly8-Ly14*.py place them: Ly8 and up, with no lower member
    project = imported(J1358, registry)
    names = [name for _, name in FP.dh_members(project)]
    assert names[0] == "Lyα" and "Ly8" in names
    ly8 = dict((n, r) for r, n in FP.dh_members(project))["Ly8"]
    fig = figure_of(project, FP.DH, start=ly8)
    shown = [c["show"]["rest"] for _, _, c in FG.places(fig) if c["show"]]
    assert max(shown) == pytest.approx(ly8, abs=0.01)
    assert grid_lines(fig)[0][0].startswith("Ly8")


def test_j1358p6522_s_lyman_series_in_two_columns(registry):
    project = imported(J1358, registry)
    fig = figure_of(project, FP.DH)
    assert fig["columns"] == 2
    left = [r[0] for r in grid_lines(fig)]
    assert left[0] == "Lyα 1215.7" and all(name.startswith("Ly") for name in left)
    rests = [c["show"]["rest"] for _, _, c in FG.places(fig) if c["show"]]
    shown = [c for _, _, c in FG.places(fig) if c["show"]]
    if len({FG.entry_of(project, c["show"]).dataset for c in shown}) == 1:
        # One dataset: down the left, then on down the right
        assert rests == sorted(rests, reverse=True) or len(fig["cells"]) > 1


def test_q1243p307_has_one_dataset_per_column(registry):
    project = imported(Q1243, registry)
    fig = figure_of(project, FP.DH)
    titles = [c["title"] for c in fig["cells"][0]]
    assert len(titles) == 2 and all(t.endswith(" data") for t in titles)
    assert titles[0] != titles[1]


def test_helium_is_a_two_by_two_grid_with_residuals_inside(tmp_path, registry):
    project = imported(write_helium(tmp_path / "he"), registry)
    assert FP.guess(project) == FP.HELIUM
    fig = figure_of(project, FP.HELIUM)
    assert (fig["columns"], fig["rows"]) == (2, 2)
    assert fig["residuals"] == FG.INSIDE
    lines = grid_lines(fig)
    assert [name.split()[:2] for name in lines[0] + lines[1][:1]] == [["He", "I"]] * 3
    assert lines[1][1] == ""


def test_blends_titles_each_line_with_the_line_it_blends(tmp_path, registry):
    project = imported(write_blend(tmp_path / "blend"), registry)
    interloper = next(s for s in project.systems if not s.primary)
    fig = figure_of(project, FP.BLENDS, system=interloper.id)
    assert fig["columns"] == 1 and fig["residuals"] == FG.STRIP
    assert grid_lines(fig) == [["Si II 1304.4"], ["Si II 1260.4"]]
    assert [row[0]["title"] for row in fig["cells"]] == ["", "Lyα 1215.7 blend"]
    # The velocities from the interloper's strongest component (log N 13.0)
    assert fig["zero"] == next(
        c.id for c in interloper.components if c.main.param("ColDens").start == 13.0
    )
    with pytest.raises(FP.PresetError, match="interloper"):
        FP.layout(
            project, FP.BLENDS, system=next(s.id for s in project.systems if s.primary)
        )


def test_a_preset_the_project_cannot_fill_says_why(registry):
    project = imported(METAL, registry)
