SECRET = "13.4729"


@pytest.fixture
def home(tmp_path, monkeypatch):
    folder = tmp_path / "alis_home"
    monkeypatch.setenv("ALIS_HOME", str(folder))
    return folder


@pytest.fixture
def window(qtbot, home):
    win = make_window(qtbot, home)
    win.panel.read_timer.setInterval(80)
    yield win
    if win.session is not None:
        win.session.discard_recovery()
        win.session = None


def open_model(window, qtbot, model):
    window.import_path(str(model))
    window.panel.read_timer.setInterval(80)
    window.panel.check_timer.setInterval(150)
    wait_idle(qtbot, window)
    return window.session


def put_cursor(editor, offset):
    cursor = editor.textCursor()
    cursor.setPosition(offset)
    editor.setTextCursor(cursor)


def select(editor, start, end):
    cursor = editor.textCursor()
    cursor.setPosition(start)
    cursor.setPosition(end, QtGui.QTextCursor.MoveMode.KeepAnchor)
    editor.setTextCursor(cursor)


def type_text(qtbot, window, offset, text):
    editor = window.panel.editor
    put_cursor(editor, offset)
    qtbot.keyClicks(editor, text)
    wait_idle(qtbot, window)


@pytest.fixture
def blind(window, qtbot):
    """examples/blind open, with a distinctive value on its hidden Si II line."""
    session = open_model(window, qtbot, BLIND)
    pm = session.project.parsed
    line = [ln for ln in pm.function_lines("voigt") if ln.ion == "28Si_II"][0]
    session.history.edit(E.set_value(pm, line.param("ColDens"), float(SECRET)), "x")
    session.history.clear()
    window.panel.redraw()
    window.refresh()
    return session


def no_secret(window):
    text = window.panel.editor.toPlainText()
    return SECRET not in text and "13.47" not in text


def test_typing_changes_the_text_as_typed_and_one_undo_restores_it(window, qtbot):
    session = open_model(window, qtbot, METAL)
    original = session.project.text
    shown = window.panel.editor.toPlainText()
    at = shown.index("chisq ftol")
    type_text(qtbot, window, at, "# a comment")
    real_at = original.index("chisq ftol")
    assert (
        session.project.text == original[:real_at] + "# a comment" + original[real_at:]
    )
    assert session.dirty and window.isWindowModified()
    assert window.qactions["edit.undo"].text() == "Undo Typing"
    window.qactions["edit.undo"].trigger()
    assert session.project.text == original
    assert window.panel.editor.toPlainText() == shown
    window.qactions["edit.redo"].trigger()
    assert "# a comment" in session.project.text


def test_the_editor_s_own_undo_is_off(window, qtbot):
    open_model(window, qtbot, METAL)
    editor = window.panel.editor
    assert not editor.isUndoRedoEnabled()
    event = QtGui.QKeyEvent(
        QtCore.QEvent.Type.ShortcutOverride,
        QtCore.Qt.Key.Key_Z,
        QtCore.Qt.KeyboardModifier.ControlModifier,
    )
    editor.event(event)
    assert not event.isAccepted()


def test_the_panel_never_holds_a_hidden_value(window, qtbot, blind):
    assert no_secret(window)
    panel = window.panel
    assert BL.MASK in panel.editor.toPlainText()
    # Typing elsewhere, undo, redo, a check: the masks stay
    at = panel.editor.toPlainText().index("chisq ftol")
    type_text(qtbot, window, at, "# x ")
    assert no_secret(window)
    window.qactions["edit.undo"].trigger()
    assert no_secret(window)
    window.qactions["edit.redo"].trigger()
    window.qactions["model.check"].trigger()
    wait_idle(qtbot, window)
    assert no_secret(window)
    texts = [panel.list.item(n).text() for n in range(panel.list.count())]
    assert not any(SECRET in t for t in texts)
    # Copying the text copies the masks
    panel.editor.selectAll()
    panel.editor.copy()
    assert SECRET not in QtGui.QGuiApplication.clipboard().text()


def test_typing_over_a_mask_stores_the_value_still_hidden(window, qtbot, blind):
    panel = window.panel
    asked = []

    def answer(typed):
        asked.append(typed)
        return "13.9"

    panel.ask_hidden_value = answer
    shown = panel.editor.toPlainText()
    line = shown.splitlines()[23]
    mask = shown.index(line) + line.index(BL.MASK)
    type_text(qtbot, window, mask + 2, "1")
    assert asked == ["1"]
    real = blind.project.text.splitlines()[23]
    assert real.split()[2] == "13.9"
    assert "13.9" not in panel.editor.toPlainText()
    assert no_secret(window)
    window.qactions["edit.undo"].trigger()
    assert blind.project.text.splitlines()[23].split()[2] == SECRET
    assert no_secret(window)


def test_problems_appear_on_their_lines_after_the_pause(window, qtbot):
    session = open_model(window, qtbot, METAL)
    panel = window.panel
    shown = panel.editor.toPlainText()
    line = next(n for n, t in enumerate(shown.splitlines()) if "legendre" in t)
    at = shown.index("legendre")
    type_text(qtbot, window, at, "x")
    assert session.project.paused
    assert panel.editor.marks.get(line) == "error"
    texts = [panel.list.item(n).text() for n in range(panel.list.count())]
    assert any(t.startswith("Line {0}:".format(line + 1)) for t in texts)
    assert window.paused_banner.isVisible()
    assert "does not read" in window.status_model.text()
    assert not window.tab_widgets[0].isEnabled()
    # The panel still works: typing it back reads again
    type_text(qtbot, window, at, "")
    put_cursor(panel.editor, at + 1)
    qtbot.keyClick(panel.editor, QtCore.Qt.Key.Key_Backspace)
    wait_idle(qtbot, window)
    assert not session.project.paused
    assert not window.paused_banner.isVisible()
    assert line not in panel.editor.marks


def test_a_stale_full_check_is_dropped(window, qtbot, monkeypatch):
    open_model(window, qtbot, METAL)
    panel = window.panel

    def slow(*args, **kwargs):
        time.sleep(0.4)
        return [T.Problem(None, "warning", "From the full check", "alis")]

    monkeypatch.setattr(MP.V, "full", slow)
    panel.check_now()
    # More typing before the full check returns
    shown = panel.editor.toPlainText()
    put_cursor(panel.editor, shown.index("chisq ftol"))
    qtbot.keyClicks(panel.editor, "#")
    QtCore.QThreadPool.globalInstance().waitForDone(5000)
    qtbot.wait(100)
    assert not any(p.message == "From the full check" for p in panel.problems)
    # Left alone, the full check's result is shown
    wait_idle(qtbot, window)
    panel.check_now()
    QtCore.QThreadPool.globalInstance().waitForDone(5000)
    qtbot.waitUntil(
        lambda: any(p.message == "From the full check" for p in panel.problems),
        timeout=5000,
    )


def test_the_cursor_keeps_its_place_when_the_panel_is_redrawn(window, qtbot, blind):
    panel = window.panel
    shown = panel.editor.toPlainText()
    at = L.offset(shown, 23, 6)
    type_text(qtbot, window, at, "zz")
    cursor = panel.editor.textCursor()
    assert (cursor.blockNumber(), cursor.positionInBlock()) == (23, 8)
    assert "vozzigt" in blind.project.text.splitlines()[23]
    assert no_secret(window)


def test_an_edit_that_would_show_a_hidden_value_is_refused(window, qtbot, blind):
    panel = window.panel
    shown = panel.editor.toPlainText()
    line = shown.splitlines()[23]
    start = shown.index(line) + line.index("blind=True") + len("blind=")
    select(panel.editor, start, start + len("True"))
    qtbot.keyClicks(panel.editor, "False")
    wait_idle(qtbot, window)
    assert "blind=True" in blind.project.text.splitlines()[23]
    assert "blind=True" in panel.editor.toPlainText().splitlines()[23]
    assert no_secret(window)
    assert window.answers.asked[-1][0] == "tell"
    assert "Unblind" in window.answers.asked[-1][2]


def test_deleting_a_hidden_line_is_allowed(window, qtbot, blind):
    panel = window.panel
    shown = panel.editor.toPlainText()
    lines = shown.splitlines(keepends=True)
    start = sum(len(x) for x in lines[:23])
    select(panel.editor, start, start + len(lines[23]))
    qtbot.keyClick(panel.editor, QtCore.Qt.Key.Key_Delete)
    wait_idle(qtbot, window)
    assert "28Si_II" not in blind.project.text
    assert window.pill.text() == "Not blinded"
    window.qactions["edit.undo"].trigger()
    assert "28Si_II" in blind.project.text and no_secret(window)


def test_cross_highlighting(window, qtbot, blind):
    panel = window.panel
    got = []
    panel.itemsAtCursor.connect(got.append)
    put_cursor(panel.editor, L.offset(panel.editor.toPlainText(), 22, 0))
    assert got and any(type(i).__name__ == "Component" for i in got[-1])
    assert panel.footer.text().startswith("Line 23: component")
    comp = blind.project.components[0]
    panel.select_items([comp])
    lines = {
        s.cursor.blockNumber()
        for s in panel.editor.extraSelections()
        if s.format.background().color().name() == "#fdf1d6"
    }
    assert lines == set(blind.project.lines_of(comp))


def test_blind_this_line(window, qtbot):
    session = open_model(window, qtbot, METAL)
    panel = window.panel
    pm = session.project.parsed
    line = pm.function_lines("voigt")[0].line
    assert panel._can_blind(line)
    window.answers.answers["blind_line"] = "Blind"
    panel.blindLineRequested.emit(line)
    assert line in session.project.hidden_lines()
    assert BL.MASK in panel.editor.toPlainText().splitlines()[line]
    assert window.pill.text().startswith("Blinded:")
    # Undo does not pass the step that blinded it
    assert not session.history.can_undo()
    window.qactions["edit.undo"].trigger()
    assert line in session.project.hidden_lines()
    assert not panel._can_blind(line)
