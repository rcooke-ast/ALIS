# -- What alis opens -----------------------------------------------------------------


def test_nothing_opens_the_start_page():
    assert S.launch_target(None) == S.Target(S.START)


def test_a_bundle_opens_that_project(tmp_path):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path))
    assert S.launch_target(str(path)) == S.Target(S.OPEN, str(path))


def test_a_mod_is_imported():
    assert S.launch_target(str(METAL)) == S.Target(S.IMPORT, str(METAL))
    out = ROOT / "examples/metal_line_abs/model/fit_spectra.mod.out.reference"
    with pytest.raises(S.LaunchError):
        S.launch_target(str(out))


def test_a_spectrum_is_refused_with_a_pointer_to_new_project():
    with pytest.raises(S.LaunchError) as err:
        S.launch_target(str(SPEC4))
    assert "choose New project" in str(err.value)
    assert "OI_SiII.dat" in str(err.value)


def test_a_missing_file_a_folder_and_a_false_bundle_are_refused(tmp_path):
    with pytest.raises(S.LaunchError, match="There is no file"):
        S.launch_target(str(tmp_path / "nothing.model"))
    with pytest.raises(S.LaunchError, match="folder"):
        S.launch_target(str(tmp_path))
    fake = tmp_path / "fake.model"
    fake.write_text("not a zip")
    with pytest.raises(S.LaunchError, match="not a project bundle"):
        S.launch_target(str(fake))


