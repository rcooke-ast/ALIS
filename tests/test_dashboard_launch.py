# -- New projects ------------------------------------------------------------------


def test_a_new_project_from_two_spectra_is_written_at_once(
    home, tmp_path, spectra, registry
):
    path = str(tmp_path / "projects" / "J0000.model")
    os.makedirs(os.path.dirname(path))
    session, notes = S.Session.new(
        path, spectra[:2], z=2.5257, blind=False, registry=registry
    )
    assert notes == []
    assert os.path.exists(path) and session.path == path
    assert not session.dirty
    assert PR.Recent().paths()[0] == path
    project = S.Session.open(path, registry=registry).project
    assert project.bundle.model_name == "J0000.mod"
    assert [r.name for r in project.rows] == ["hires", "uves"]
    assert [r.reference for r in project.rows] == [True, False]
    assert all(r.snips == [] for r in project.rows)
    assert [r.source["path"] for r in project.rows] == spectra[:2]
    assert project.rows[0].source["relpath"] == os.path.relpath(
        spectra[0], os.path.dirname(path)
    )
    assert project.rows[0].columns == {"wave": 0, "flux": 1, "error": 2}
    assert [r["fwhm"] for r in project.ui["rows"]] == [7.0, 7.0]
    assert [(s.name, s.z, s.primary) for s in project.systems] == [
        ("z = 2.52570", 2.5257, True)
    ]
    assert not project.inferred and project.notices == []
    assert not project.parsed.blind
    # The model: the settings of the preferences, and empty blocks
    assert project.text.splitlines()[0].split() == ["run", "ncpus", "-1"]
    assert "data read\ndata end\n\nmodel read\nmodel end\n" in project.text
    problems = V.check(project)
    assert [p.severity for p in problems] == ["warning"]
    assert "no data lines yet" in problems[0].message
    assert all(state == "present" for _, state in B.check_sources(project.bundle))


def test_a_new_project_takes_the_preferences_and_can_be_blind(
    home, tmp_path, spectra, registry
):
    prefs = PR.Preferences()
    prefs.set(
        "new_project.settings", [["run", "ncpus", "4"], ["chisq", "atol", "0.01"]]
    )
    prefs.set("new_project.fwhm", 2.5)
    path = str(tmp_path / "blind.model")
    session, notes = S.Session.new(
        path, spectra[2:], blind=True, prefs=prefs, registry=registry
    )
    project = session.project
    assert project.parsed.blind
    # The settings of the preferences, written aligned in columns
    assert project.text.startswith(
        "run    ncpus  4\nchisq  atol   0.01\nrun    blind  True\n"
    )
    assert project.ui["rows"][0]["fwhm"] == 2.5
    assert project.systems == []
    # A fourth column that is not a mask is a continuum, multiplied in (D13)
    assert len(notes) == 1 and "normalised.dat" in notes[0]
    assert "continuum" in notes[0]
    assert project.rows[0].columns == {"wave": 0, "flux": 1, "error": 2, "continuum": 3}


def test_new_refuses_an_existing_file_or_a_wrong_name(home, tmp_path, spectra):
    path = tmp_path / "taken.model"
    path.write_text("x")
    with pytest.raises(S.SessionError, match="already a file"):
        S.Session.new(str(path), spectra[:1])
    with pytest.raises(S.SessionError, match=r"ends in \.model"):
        S.Session.new(str(tmp_path / "wrong.mod"), spectra[:1])
    with pytest.raises(MO.ModeError):
        S.Session.new(str(tmp_path / "none.model"), [])


def test_an_empty_project_round_trips_through_the_bundle(
    home, tmp_path, spectra, registry
):
    path = str(tmp_path / "rt.model")
    session, _ = S.Session.new(path, spectra[:1], z=0.0, registry=registry)
    bundle = B.read(path)
    data = json.loads(bundle.members["ui/project.json"])
    assert data["mode"] == "qso_abs_line" and data["rows"][0]["specids"] == []
    again = S.Session.open(path, registry=registry)
    assert again.project.text == session.project.text
    again.save()
    assert B.read(path).members["ui/project.json"] == bundle.members["ui/project.json"]
