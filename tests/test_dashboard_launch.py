"""The launcher and new projects (dashboard Stage 3.4, F14, Q3.7, Q3.12, Q3.15).

- ``alis [path]`` opens the start page, a project (``.model``) or an imported fit
  (``.mod``); a spectrum is refused, with a message pointing to New project (RJC,
  Q3.7).
- New project makes an empty project from one or more spectra, written at once: its
  model holds the settings of the preferences and empty data and model blocks, and
  each spectrum is one file row (Q3.12).

Generated by RJC and Claude.
"""

