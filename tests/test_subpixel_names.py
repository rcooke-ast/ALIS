"""Every name of the sub-pixels, by one convention (dashboard Stage 14, Task 14.2).

Q14.6's response: a name that counts sub-pixels per pixel begins ``nsubpixel``, and
one that counts them across a profile's standard deviation begins ``nsubsigma``;
``_min`` and ``_max`` bound them. No old name is read (Q14.8 (ii)): each is refused
with a message that names its new one.

- The settings ``nsubsigma`` (5), ``nsubpixel_min`` (10), ``nsubpixel_max`` (21)
  and ``nsubpixel_renew`` (False), and none of the old.
- Each old name, as a setting, through ``--set`` and as a data-line keyword, is
  refused with its new name; ``run warn_subpix`` was removed (Q14.7), and so was
  ``run nsubsigma_min`` (Q14.12), whose warnings now take each snip's ``nsubsigma``.
- The new names give each snip the sub-pixels the old gave (checked against the
  code before the rename, with the old names, in the stage's log).
- A lower ``nsubsigma`` asks for fewer sub-pixels, and is accepted (Q14.12; before,
  one below ``nsubsigma_min`` was refused).
- ``run_alis --list-settings`` lists the new names alone.

The dashboard's side is in ``test_dashboard_settings.py``.

Generated by RJC and Claude.
"""

import re
from types import SimpleNamespace

import numpy as np
import pytest

from alis import config, load
from alis.config import ArgFlag
from alis.main import build_funcarray
from alis.scripts import run_alis

pytestmark = pytest.mark.unit

NEW = {
    "nsubsigma": 5,
    "nsubpixel_min": 10,  # 5 until Task 14.6
    "nsubpixel_max": 21,
    "nsubpixel_renew": False,
}
OLD = {
    "nsubpix": "run nsubsigma",
    "nsubmin": "run nsubpixel_min",
    "nsubmax": "run nsubpixel_max",
    "renew_subpix": "run nsubpixel_renew",
    "warn_subpix": None,
    # Added at Task 14.2, removed at Q14.12: the warnings' level is nsubsigma
    "nsubsigma_min": None,
}
MODEL = [
    "emission\n",
    "constant 1.0\n",
    "absorption\n",
    "voigt ion=16O_I 14.0 0.0 10.0 0.0TA\n",
]


def test_the_settings_by_their_new_names():
    run = ArgFlag()["run"]
    assert {key: run[key] for key in NEW} == NEW
    assert not set(OLD) & set(run.keys())


@pytest.mark.parametrize("old", sorted(OLD))
def test_an_old_setting_is_refused_with_its_new_name(old, logmsgs):
    with pytest.raises(SystemExit):
        load.set_params(["run {0} 5".format(old)], ArgFlag())
    message = config.renamed_setting("run", old)
    assert any(message in msg for msg in logmsgs)
    if OLD[old] is None:
        assert "was removed" in message
    else:
        assert "'{0}'".format(OLD[old]) in message


@pytest.mark.parametrize("old", sorted(OLD))
def test_an_old_name_given_with_set_is_refused(old, logmsgs):
    argv = SimpleNamespace(set=["run {0} 5".format(old)])
    with pytest.raises(SystemExit):
        load.apply_cli_settings(ArgFlag(), argv)
    assert any(config.renamed_setting("run", old) in msg for msg in logmsgs)


@pytest.fixture(scope="module")
def spectrum(tmp_path_factory):
    """501 pixels of 0.05 Å (11.5 km/s at 1302 Å), from 1290 to 1315 Å."""
    path = tmp_path_factory.mktemp("names") / "spec.dat"
    wave = np.linspace(1290.0, 1315.0, 501)
    np.savetxt(str(path), np.column_stack([wave, np.ones_like(wave), wave * 0 + 0.1]))
    return str(path)


def nsubpixel(atomic, path, settings=(), extra="", warn=False):
    """
    The snip's sub-pixels per pixel, as ALIS works them out at load: a voigt line of
    b = 10 km/s, which asks for √2 · nsubsigma · pixel / b, and a resolution of
    30 km/s, which asks for fewer.
    """
    st = SimpleNamespace(_atomic=atomic, _argflag=ArgFlag())
    st._argflag["out"]["verbose"] = -1
    # The fewest sub-pixels per pixel as they were before Task 14.6, so that the
    # numbers below are those the old names gave
    load.set_params(["run nsubpixel_min 5"] + list(settings), st._argflag)
    st._funcarray = build_funcarray(st._argflag, atomic)
    line = "  {0} specid=0 fitrange=[1300.0,1305.0] resolution=vfwhm(30.0)".format(path)
    load.load_data(st, [line + " columns=[wave,flux,error] " + extra + "\n"])
    st._modpass = load.load_model(st, MODEL)
    st._links = load.load_links(st, [])
    _, st._levadd = load.load_parinfo(st)
    return load.load_subpixels(st, st._modpass["p0"], warn=warn)[4][0][0]


@pytest.mark.parametrize(
    "settings, extra, expected",
    [
        ((), "", 9),
        (("run nsubsigma 10",), "", 17),
        ((), "nsubsigma=10", 17),
        (("run nsubpixel_min 12",), "", 12),
        (("run nsubpixel_max 7",), "", 7),
        (("run nsubsigma 20", "run nsubpixel_max 50"), "", 33),
    ],
)
def test_the_new_names_give_the_sub_pixels(
    atomic_data, spectrum, settings, extra, expected
):
    # The numbers the old names gave (nsubpix, nsubmin, nsubmax), before Stage 14
    assert nsubpixel(atomic_data, spectrum, settings, extra) == expected


def test_the_old_data_line_keyword_is_refused_with_its_new_name(
    atomic_data, spectrum, logmsgs
):
    with pytest.raises(SystemExit):
        nsubpixel(atomic_data, spectrum, extra="nsubpix=10")
    assert any("'nsubsigma='" in msg for msg in logmsgs)


@pytest.mark.parametrize(
    "settings, extra",
    [(("run nsubsigma 3",), ""), ((), "nsubsigma=3")],
)
def test_a_lower_nsubsigma_asks_for_fewer(
    atomic_data, spectrum, settings, extra, logmsgs
):
    # Q14.12: before, refused, being below nsubsigma_min (5)
    settings = settings + ("run nsubpixel_min 1",)
    # √2 · 3 · 11.5 / 10 + 0.5, rounded
    assert nsubpixel(atomic_data, spectrum, settings, extra, warn=True) == 5
    assert not [m for m in logmsgs if "sub-pixels" in m]


def test_a_data_line_s_nsubsigma_of_0_is_refused(atomic_data, spectrum, logmsgs):
    # Stage 14's close (test-coverage)
    with pytest.raises(SystemExit):
        nsubpixel(atomic_data, spectrum, extra="nsubsigma=0")
    assert any("nsubsigma must be greater than 0" in msg for msg in logmsgs)


def test_list_settings_lists_the_new_names_alone(capsys):
    with pytest.raises(SystemExit):
        run_alis.parser(["--list-settings"])
    printed = capsys.readouterr().out
    words = set(re.findall(r"\w+", printed))
    assert set(NEW) <= words
    assert not set(OLD) & words


# -- A data line's own nsubpixel (Task 14.3) --------------------------------------


def test_a_data_line_s_nsubpixel_is_used_as_given(atomic_data, spectrum):
    # Whatever nsubpixel_min and nsubpixel_max say (before Stage 14: refused)
    for settings, bounded in (
        (("run nsubpixel_min 10",), 10),
        (("run nsubpixel_max 4",), 4),
    ):
        assert nsubpixel(atomic_data, spectrum, settings, "nsubpixel=6") == 6
        assert nsubpixel(atomic_data, spectrum, settings) == bounded


def test_too_few_recorded_sub_pixels_warn_once(atomic_data, spectrum, logmsgs):
    # The voigt line asks for 9 to have nsubsigma (5) across its σ
    assert nsubpixel(atomic_data, spectrum, extra="nsubpixel=3", warn=True) == 3
    warned = [m for m in logmsgs if "Too few sub-pixels are recorded" in m]
    assert len(warned) == 1
    assert "Spectrum 0, segment 0: nsubpixel=3 on its data line" in warned[0]
    assert "its lines ask for 9." in warned[0] and "nsubsigma (5)" in warned[0]
    assert "Remove nsubpixel= from a data line" in warned[0]


def test_a_data_line_s_own_nsubsigma_is_its_warning_s_level(
    atomic_data, spectrum, logmsgs
):
    # Q14.12: nsubsigma=10 asks for 17 (before, the level was nsubsigma_min)
    nsubpixel(atomic_data, spectrum, extra="nsubpixel=9 nsubsigma=10", warn=True)
    (warned,) = [m for m in logmsgs if "Too few sub-pixels are recorded" in m]
    assert "nsubsigma (10)" in warned and "its lines ask for 17." in warned


@pytest.mark.parametrize(
    "settings, extra",
    # A data line's own nsubsigma sets its level (Q14.12): 1 asks for 2
    [((), "nsubpixel=9"), ((), "nsubpixel=3 nsubsigma=1"), ((), "")],
)
def test_enough_recorded_sub_pixels_do_not_warn(
    atomic_data, spectrum, settings, extra, logmsgs
):
    nsubpixel(atomic_data, spectrum, settings + ("run nsubsigma 5",), extra, warn=True)
    assert not [m for m in logmsgs if "Too few sub-pixels" in m]
