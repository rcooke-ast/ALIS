"""Save keeps a real run of ``run_alis project.model`` (dashboard Stage 3.3, S31, Q1.7).

The project is open, with an edit not yet saved, while ``run_alis project.model``
fits the bundle as it was saved. Save then keeps that run, and the project's model
has changed since it. Marked ``fast`` rather than ``unit``, because it runs a fit.

Generated by RJC and Claude.
"""

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

from alis import bundle as B
from alis.dashboard import edit as E
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import session as S

pytestmark = [pytest.mark.fast, pytest.mark.examples]

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


def test_save_keeps_a_real_run_of_run_alis(tmp_path, monkeypatch, atomic_data):
    monkeypatch.setenv(PR.HOME_ENV, str(tmp_path / "home"))
    path = str(tmp_path / "metal.model")
    B.pack_to(str(METAL), path)
    session = S.Session.open(path, registry=M.Registry(atomic_data))
    par = next(p for p in session.project.parsed.params if p.name == "ColDens")
    session.history.edit(E.set_value(session.project.parsed, par, 13.6), "Set")
    out = subprocess.run(
        [sys.executable, "-m", "alis.scripts.run_alis", path, "-p", "0"],
        capture_output=True,
        text=True,
        cwd=str(tmp_path),
        timeout=600,
    )
    assert out.returncode == 0, out.stderr[-2000:]
    assert session.check_disk() == S.RUNS
    session.save()
    saved = B.read(path)
    info = json.loads(saved.members[B.LATEST + "run.json"])
    assert info["status"] == "completed"
    assert "13.6" in saved.model_text()
    reopened = S.Session.open(path, registry=M.Registry(atomic_data))
    # The run fitted the model as it was saved before the edit
    assert reopened.project.model_changed_since_run()
    assert os.path.exists(path)
