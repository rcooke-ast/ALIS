import sys

import numpy as np
import pytest

from alis import gpu
from alis.functions import base

pytestmark = pytest.mark.unit


@pytest.fixture(autouse=True)
def _clear_probe():
    """Each test starts from an unprobed state (the probe is cached)."""
    gpu.reset_probe_cache()
    yield
    gpu.reset_probe_cache()


# -- the opt-in flag ---------------------------------------------------------


def test_base_does_not_claim_gpu_support():
    assert base.Base(getinst=True).supports_gpu() is False


def test_no_shipped_function_claims_gpu_support_yet():
    # Task 4.1 only defines the contract; the Voigt kernel lands in 4.2. This
    # test documents that and will need updating (deliberately) when it does.
    claimed = [k for k, inst in base.call(getinst=True).items() if inst.supports_gpu()]
    assert claimed == []


def test_opt_in_is_by_flag_not_by_overriding():
    # Several functions used to carry a verbatim copy of the inherited stub,
    # so overriding call_GPU must NOT by itself imply GPU support.
    class Stub(base.Base):
        def call_GPU(self, x, p, ae="em", mkey=None, ncpus=1):
            return self.call_CPU(x, p, ae=ae, mkey=mkey, ncpus=ncpus)

    class Real(base.Base):
        _gpu_supported = True

    assert Stub(getinst=True).supports_gpu() is False
    assert Real(getinst=True).supports_gpu() is True


# -- the fallback ------------------------------------------------------------


def test_call_gpu_falls_back_to_call_cpu_and_returns_the_result():
    # The pre-4.1 stub called call_CPU without returning it, so call_GPU
    # silently produced None. Use `constant`, whose call_CPU ignores mkey, so
    # the check is about the fallback rather than the model's keywords.
    inst = base.call(getinst=True)["constant"]
    x = np.linspace(1200.0, 1300.0, 64)
    p = np.array([[2.5]])

    cpu = inst.call_CPU(x, p, ae="em")
    out = inst.call_GPU(x, p, ae="em")

    assert out is not None
    np.testing.assert_array_equal(out, cpu)


def test_call_gpu_signature_mirrors_call_cpu():
    import inspect

    cpu = inspect.signature(base.Base.call_CPU).parameters
    gpu_sig = inspect.signature(base.Base.call_GPU).parameters
    assert list(cpu) == list(gpu_sig)


# -- the lazy numba boundary -------------------------------------------------


def test_importing_alis_does_not_import_numba():
    # The Stage 4 requirement: a CPU-only install must never import numba (and
    # so needs no CUDA toolchain). Checked in a clean interpreter because this
    # session may legitimately have numba loaded already.
    code = (
        "import sys; import alis, alis.gpu, alis.main, alis.model_eval; "
        "from alis.functions import base; "
        "print('numba' in sys.modules or 'numba.cuda' in sys.modules)"
    )
    proc = subprocess.run(
        [sys.executable, "-c", code], capture_output=True, text=True, check=False
    )
    assert proc.returncode == 0, proc.stderr
    assert proc.stdout.strip().endswith("False"), (
        "importing ALIS pulled in numba:\n" + proc.stdout
    )


def test_missing_numba_degrades_to_cpu_with_a_reason(monkeypatch):
    real_import = builtins.__import__

    def _no_numba(name, *args, **kwargs):
        if name == "numba" or name.startswith("numba."):
            raise ImportError("No module named 'numba'")
        return real_import(name, *args, **kwargs)

    monkeypatch.setattr(builtins, "__import__", _no_numba)
    assert gpu.is_available() is False
    assert gpu.device_count() == 0
    assert "numba" in gpu.unavailable_reason()


def test_broken_cuda_degrades_to_cpu_rather_than_raising(monkeypatch):
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(raise_on_probe=True))
    assert gpu.is_available() is False
    assert "unusable" in gpu.unavailable_reason()


def test_probe_reports_available_devices(monkeypatch):
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(ndevices=4))
    assert gpu.is_available() is True
    assert gpu.device_count() == 4
    assert gpu.unavailable_reason() == ""


def test_select_device_rejects_out_of_range_rank(monkeypatch):
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(ndevices=2))
    assert gpu.select_device(0) is True
    assert gpu.select_device(2) is False
    assert gpu.select_device(-1) is False


def test_select_device_without_a_gpu_returns_false(monkeypatch):
    monkeypatch.setitem(sys.modules, "numba", _FakeNumba(ndevices=0))
    assert gpu.select_device(0) is False


class _FakeCuda:
    """Stand-in for numba.cuda so the probe can be tested without hardware."""

    def __init__(self, ndevices=0, raise_on_probe=False):
        self._ndevices = ndevices
        self._raise = raise_on_probe
        self.selected = None

    def is_available(self):
        if self._raise:
            raise RuntimeError("CUDA driver library cannot be found")
        return self._ndevices > 0

    def list_devices(self):
        return list(range(self._ndevices))

    def select_device(self, rank):
        self.selected = rank


class _FakeNumba:
    def __init__(self, ndevices=0, raise_on_probe=False):
        self.cuda = _FakeCuda(ndevices, raise_on_probe)
