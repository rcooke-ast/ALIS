"""Unit tests for the Stage 4.1 CPU/GPU model-function interface.

Covers the pure, hardware-independent surface: the GPU opt-in flag, the
"no GPU implementation" fallback from ``call_GPU`` to ``call_CPU``, the lazy
``numba`` import boundary, and the probe/selection helpers in ``alis.gpu``.
Nothing here needs a GPU -- the CPU-vs-GPU numerical-equivalence tests are
``gpu``-marked and live with the kernel work (Tasks 4.2/4.6).

Generated by RJC and Claude.
"""

import builtins
