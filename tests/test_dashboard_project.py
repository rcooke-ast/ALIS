@pytest.fixture
def small(registry):
    wave = np.linspace(1299.0, 1307.0, 81)
    return make_project(registry, SMALL, {"data/a.dat": snip_bytes(wave)})


def test_a_model_that_breaks_d20(small):
    untied = [n for n in small.notices if n.kind == "untied"]
    assert len(untied) == 1 and untied[0].lines == [7, 8]
    small.apply(small.fix_notice(untied[0]))
    assert not [n for n in small.notices if n.kind == "untied"]
    labels = {
        ln.param("redshift").label
        for c in small.components
        for ln in c.lines
        if ln.ion in ("16O_I", "28Si_II")
    }
    assert labels == {"za1"}


def test_a_model_that_breaks_d22(small):
    iso = [n for n in small.notices if n.kind == "isotopes"]
    assert len(iso) == 1
    assert "3He I" in iso[0].message and "b_turb" in iso[0].message
    assert iso[0].lines == [9]
    small.apply(small.fix_notice(iso[0]))
    assert not [n for n in small.notices if n.kind == "isotopes"]
    comp = [c for c in small.components if "4He_I" in c.ions][0]
    main = comp.lines_of("4He_I")[0].param("bturb")
    minor = comp.lines_of("3He_I")[0].param("bturb")
    # A fresh label of the scheme: the minor isotope's own 'ba' might be shared
    assert main.label == minor.label == "b{0}1".format(comp.system.id)
    assert minor.value == main.value == 6.0


# -- Regions (Q2.7, Q2.10) ---------------------------------------------------------


def test_regions_of_a_masked_snip_change_only_the_mask(registry):
    project = imported(J1358, registry)
    snip = project.snip("H2")
    old = project.files[snip.member]
    lo, hi = snip.extent
    wanted = [(lo + 1.0, lo + 3.0), (hi - 3.0, hi - 1.0)]
    step = project.set_regions(snip, wanted)
    assert step.text is None and list(step.files) == [snip.member]
    project.apply(step)
    new = project.files[snip.member]
    old_lines, new_lines = old.decode().splitlines(), new.decode().splitlines()
    assert len(old_lines) == len(new_lines)
    for a, b in zip(old_lines, new_lines):
        wa, wb = a.split(), b.split()
        assert wa[:3] == wb[:3] and wa[4:] == wb[4:]
        assert len(a) == len(b)
    got = project.snip("H2").regions
    assert len(got) == 2
    for (glo, ghi), (wlo, whi) in zip(got, wanted):
        assert wlo <= glo < wlo + 0.1 and whi - 0.1 < ghi <= whi
    project.revert(step)
    assert project.files[snip.member] == old


