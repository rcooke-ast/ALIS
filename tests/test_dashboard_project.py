def test_two_regions_switch_a_fitrange_line_to_a_mask(registry):
    project = imported(METAL, registry)
    snip = project.snips[0]
    old = project.files[snip.member]
    step = project.set_regions(snip, [(1301.0, 1302.5), (1303.5, 1305.0)])
    project.apply(step)
    item = project.parsed.data[0]
    assert item.keyword("fitrange") == "columns"
    # The file already has four columns, so the mask is the fifth
    ncols = len(old.decode().splitlines()[0].split())
    assert item.keyword("columns") == "[wave,flux,error,fitrange:{0}]".format(ncols)
    new = project.files[snip.member]
    for a, b in zip(old.decode().splitlines(), new.decode().splitlines()):
        assert b.startswith(a) and len(b.split()) == len(a.split()) + 1
    assert len(project.snips[0].regions) == 2
    wave = project.snips[0].pixels.wave
    mask = project.snips[0].pixels.mask != 0
    want = ((wave >= 1301.0) & (wave <= 1302.5)) | ((wave >= 1303.5) & (wave <= 1305.0))
    assert np.array_equal(mask, want)
    # ALIS, reading the edited bundle from memory, fits exactly those pixels
    bundle = project.to_bundle()
    state = SimpleNamespace(_argflag=ArgFlag())
    state._argflag["out"]["verbose"] = -1
    with M.alis_quietly():
        _, datlines, _, _ = load.load_input(
            state, textstr=bundle.model_text(restore=True).splitlines(True)
        )
        state._atomic = registry.atomic
        state._funcarray = registry.instances()
        load.load_data(state, datlines, data=bundle.data_for_run())
    assert np.array_equal(state._wavefit[0], wave[want])
    project.revert(step)
    assert project.files[snip.member] == old
    assert project.parsed.data[0].keyword("fitrange") == "[1301.0,1305.0]"


def test_a_shared_file_is_copied_before_it_gets_a_mask(registry):
    text = SMALL.replace(
        "data end",
        "  ../data/a.dat  specid=B  fitrange=[1300.5,1301.0]  resolution=vfwhm(7.0VA)"
        "\ndata end",
    ).replace(
        "legendre 1.0  0.0  specid=A",
        "legendre 1.0  0.0  specid=A\n  constant 1.0 specid=B",
    )
    text = text.replace("specid=A\n model end", "specid=A\nmodel end")
    wave = np.linspace(1299.0, 1307.0, 81)
    project = make_project(registry, text, {"data/a.dat": snip_bytes(wave)})
    assert not project.paused, project.parsed.errors
    snip = project.snip("A")
    project.apply(project.set_regions(snip, [(1300.0, 1301.0), (1302.0, 1303.0)]))
    assert project.parsed.data[0].file.text == "../data/a_A.dat"
    assert project.parsed.data[1].file.text == "../data/a.dat"
    assert "files/data/a_A.dat" in project.files
    assert project.files["files/data/a.dat"] == snip_bytes(wave)


def test_snip_edges_move_inwards_only(registry):
    project = imported(J1358, registry)
    snip = project.snip("O1")
    lo, hi = snip.extent
