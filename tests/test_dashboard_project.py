def test_j1358_notices_and_their_fixes(registry):
    project = imported(J1358, registry)
    kinds = [n.kind for n in project.notices]
    assert kinds == ["inferred", "untied", "isotopes"]
    untied = project.notices[1]
    assert "O I" in untied.message and len(untied.lines) == 6
    assert "D I" in project.notices[2].message
    assert "b_turb" in project.notices[2].message
    # The untied fix ties every O I line to 'ra', and nothing else
    before = project.text
    project.apply(project.fix_notice(untied))
    assert [n.kind for n in project.notices] == ["inferred", "isotopes"]
    main = project.systems[0].components[1]
    assert {ln.param("redshift").label for ln in main.lines} == {"ra"}
    changed = {
        n
        for n, (a, b) in enumerate(zip(before.splitlines(), project.text.splitlines()))
        if a != b
    }
    assert changed == set(untied.lines)
    # The isotope fix gives H I's and D I's b_turb a label of the scheme
    project.apply(project.fix_notice(project.notices[1]))
    assert [n.kind for n in project.notices] == ["inferred"]
    main = project.systems[0].components[1]
    hyd, deut = main.lines_of("1H_I")[0], main.lines_of("2H_I")[0]
    assert hyd.param("bturb").label == deut.param("bturb").label == "ba1"
    assert deut.param("bturb").value == hyd.param("bturb").value


def test_cross_highlighting_maps_items_to_lines(registry):
    project = imported(J1358, registry)
    main = project.systems[0].components[1]
    lines = project.lines_of(main)
    assert set(lines) == {ln.line for ln in main.lines}
    snip = project.snip("O1")
