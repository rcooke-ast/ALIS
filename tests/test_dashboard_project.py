def test_saving_over_a_bundle_keeps_its_runs(registry, tmp_path):
    project = imported(METAL, registry)
    path = tmp_path / "metal.model"
    project.save(str(path))

    # A run, and a committed run, added to the bundle on disk meanwhile
    def add_runs(bundle):
        bundle.members[B.LATEST + "run.json"] = b'{"status": "completed"}'
        bundle.members["runs/0001/run.json"] = b'{"status": "completed"}'

    B.update(str(path), add_runs)
    oxygen = project.parsed.function_lines("voigt")[0]
    project.edit(E.set_value(project.parsed, oxygen.param("ColDens"), 14.25))
    project.save(str(path))
    again = B.read(str(path))
    assert B.LATEST + "run.json" in again.members
    assert "runs/0001/run.json" in again.members
    assert "14.25" in again.model_text()


def test_a_mask_written_as_integers_keeps_its_style(registry):
    wave = np.linspace(1299.0, 1307.0, 81)
    mask = (wave > 1301.0) & (wave < 1305.0)
    rows = ["{0:.6f} 1.0 0.1 {1:d}\n".format(w, int(m)) for w, m in zip(wave, mask)]
    text = SMALL.replace(
        "fitrange=[1300.0,1306.0]",
        "fitrange=columns  columns=[wave,flux,error,fitrange]",
    )
    project = make_project(registry, text, {"data/a.dat": "".join(rows).encode()})
    snip = project.snip("A")
    old = project.files[snip.member].decode().splitlines()
    project.apply(project.set_regions(snip, [(1300.0, 1302.0)]))
    new = project.files[snip.member].decode().splitlines()
    assert all(len(a) == len(b) for a, b in zip(old, new))
    assert {line.split()[3] for line in new} == {"0", "1"}
    assert len(project.snip("A").regions) == 1
