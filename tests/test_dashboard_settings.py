"""The settings of a fit (dashboard Stage 6.2; F9; Q6.4, Q6.6(a), Q6.16).

- Every setting of ``ArgFlag`` is offered, or left out with a reason, and has a
  description (``run_alis --list-settings`` prints it).
- A setting set and cleared gives the text back byte for byte; ALIS's own reasons
  refuse a bad value; "Settings you changed" lists what differs from the defaults.
- The dashboard's runs are given its own settings and this computer's on the
  command line; a computer's setting written in the model wins over the preference.
- The "command line only" settings are written like any other.

No Qt.

Generated by RJC and Claude.
"""

from multiprocessing import cpu_count
from pathlib import Path

import pytest

from alis import gpu
from alis.config import ArgFlag
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import project as P
from alis.dashboard import settings as ST

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
METAL = ROOT / "examples/metal_line_abs/model/fit_spectra.mod"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture
def project(registry):
    return P.Project.import_model(str(METAL), registry=registry)


@pytest.fixture
def prefs(tmp_path, monkeypatch):
    monkeypatch.setenv(PR.HOME_ENV, str(tmp_path / "home"))
    return PR.Preferences()


def test_every_setting_is_offered_or_left_out_with_a_reason():
    cfg = ArgFlag()
    offered = {(s.section, s.key): s for s in ST.catalogue()}
    for section in cfg.keys():
        for key in cfg[section].keys():
            if (section, key) in ST.LEFT_OUT:
                assert (section, key) not in offered
                with pytest.raises(ST.SettingError, match="not offered"):
                    ST.setting(section, key)
                continue
            item = offered[(section, key)]
            assert item.help, item.name
            assert item.default == cfg[section][key]
    assert len(offered) + len(ST.LEFT_OUT) == sum(
        len(cfg[s].keys()) for s in cfg.keys()
    )


def test_owners_kinds_and_choices():
    assert ST.setting("run", "ncpus").owner == ST.COMPUTER
    assert ST.setting("out", "verbose").owner == ST.DASHBOARD
    assert ST.setting("sim", "perturb").owner == ST.COMMAND_LINE
    assert ST.setting("generate", "data").owner == ST.COMMAND_LINE
    assert ST.setting("chisq", "maxiter").owner == ST.MODEL
    assert ST.setting("run", "blind").kind == ST.BOOL
    assert ST.setting("chisq", "maxiter").kind == ST.INT
    assert ST.setting("chisq", "atol").kind == ST.FLOAT
    assert ST.setting("out", "covar").kind == ST.WORD
    assert ST.setting("sim", "perturb").kind == ST.ANY
    backend = ST.setting("run", "backend")
    assert backend.kind == ST.CHOICE
    assert backend.choices == tuple(gpu.BACKENDS)
    assert PR.SPEC["fit.backend"].choices == tuple(gpu.BACKENDS)


def test_a_setting_set_and_cleared_gives_the_text_back(project):
    original = project.text
    project.apply(ST.set_step(project, "run", "ncpus", "4"))
    assert "run ncpus 4" in project.text.replace("  ", " ")
    assert ST.model_settings(project)[("run", "ncpus")][0] == "4"
    project.apply(ST.clear_step(project, "run", "ncpus"))
    assert project.text == original
    assert ST.clear_step(project, "run", "ncpus") is None


def test_changing_a_setting_is_one_step_that_undo_reverses(project):
    original = project.text
    step = ST.set_step(project, "chisq", "maxiter", "500")
    project.apply(step)
    assert ST.model_settings(project)[("chisq", "maxiter")][0] == "500"
    project.revert(step)
    assert project.text == original


def test_alis_refuses_a_bad_value(project):
    with pytest.raises(ST.SettingError):
        ST.set_step(project, "chisq", "maxiter", "many")
    with pytest.raises(ST.SettingError, match="one of"):
        ST.set_step(project, "run", "backend", "tpu")
    with pytest.raises(ST.SettingError, match="one word"):
        ST.set_step(project, "out", "covar", "two words")
    assert ST.check_value("run", "blind", "True") is True


def test_the_settings_you_changed(project):
    names = [c.setting.name for c in ST.changed(project)]
    assert "chisq maxiter" in names
    assert "out covar" in names
    # A setting written at its default is not "changed"
    project.apply(ST.set_step(project, "run", "nsubpix", "5"))
    assert "run nsubpix" not in [c.setting.name for c in ST.changed(project)]


def test_what_a_run_is_given(project, prefs):
    # metal_line_abs names its covariance file, so the dashboard asks for none
    given = ST.run_settings(project, prefs)
    assert given[:3] == ["out verbose 1", "plot fits False", "out report True"]
    assert not any(s.startswith("out covar") for s in given)
    # "All bar one" given as the preference has it: ALIS counts -1 on its command
    # line too (Q6.24)
    assert "run backend auto" in given
    assert "run ncpus -1" in given
    assert ST.leaves_no_cpu(0) and ST.leaves_no_cpu(-cpu_count())
    assert not ST.leaves_no_cpu(1 - cpu_count()) and not ST.leaves_no_cpu(2)
    assert not ST.leaves_no_cpu("all")
    prefs.set("fit.ncpus", 6)
    assert "run ncpus 6" in ST.run_settings(project, prefs)
    # A model without a covariance file is given one
    project.apply(ST.clear_step(project, "out", "covar"))
    assert "out covar fit_spectra.covar" in ST.run_settings(project, prefs)
    # The model's own computer setting wins over the preference
    project.apply(ST.set_step(project, "run", "ncpus", "2"))
    assert not any(s.startswith("run ncpus") for s in ST.run_settings(project, prefs))
    assert ST.computer_used(project, prefs)[("run", "ncpus")] == ("2", True)
    assert ST.computer_used(project, prefs)[("run", "backend")] == ("auto", False)


def test_command_line_only_settings_are_written_like_any_other(project):
    assert ST.command_line_only(project) == []
    project.apply(ST.set_step(project, "sim", "perturb", "10"))
    found = ST.command_line_only(project)
    assert [(item.name, value) for item, value, _ in found] == [("sim perturb", "10")]
    project.apply(ST.set_step(project, "generate", "data", "True"))
    assert len(ST.command_line_only(project)) == 2
    project.apply(ST.set_step(project, "generate", "data", "False"))
    assert len(ST.command_line_only(project)) == 1
