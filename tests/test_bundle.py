"""Project bundles: packing, reading, writing, hiding and extracting (dashboard
Stage 1.5, 1.6 and 1.8).

A bundle is a zip file holding a whole fit. Most tests here touch no fit at
all; the few that run one are marked ``fast`` and ``examples`` rather than
``unit``. Running a bundle against the reference outputs is tested by the
regression harness (``test_regression.py::test_bundle``).

Generated by RJC and Claude.
"""

