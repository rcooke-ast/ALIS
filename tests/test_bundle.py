def _rewrite_zip(path, change):
    """Rewrite a zip file, passing each member through ``change(name, data)``."""
    members = _members(path)
    with zipfile.ZipFile(path, "w") as zfil:
        for name, data in members.items():
            zfil.writestr(name, change(name, data))


@UNIT
def test_a_damaged_member_is_refused(packed):
    _rewrite_zip(packed, lambda n, d: d + b"x" if n.endswith(".dat") else d)
    with pytest.raises(bundle.BundleError, match="damaged"):
        bundle.read(str(packed))


@UNIT
def test_a_bundle_from_a_newer_alis_is_refused(packed):
    def newer(name, data):
        if name != "manifest.json":
            return data
        manifest = json.loads(data)
        manifest["version"] = bundle.FORMAT_VERSION + 1
        return json.dumps(manifest).encode()

    _rewrite_zip(packed, newer)
    with pytest.raises(bundle.BundleError, match="newer version"):
        bundle.read(str(packed))


