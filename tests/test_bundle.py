@UNIT
def test_an_interrupted_write_leaves_the_old_bundle_intact(packed, monkeypatch):
    before = packed.read_bytes()
    made = bundle.read(str(packed))
    made.members["ui/state.json"] = b"{}"
    calls = []

    def failing(self, name, data, *args, **kwargs):
        calls.append(name)
        if len(calls) > 1:
            raise OSError("disk full")
        return original(self, name, data, *args, **kwargs)

    original = zipfile.ZipFile.writestr
    monkeypatch.setattr(zipfile.ZipFile, "writestr", failing)
    with pytest.raises(OSError):
        bundle.write(made, str(packed))
    monkeypatch.undo()
    assert packed.read_bytes() == before
    assert sorted(os.listdir(packed.parent)) == ["metal.model", "metal_line_abs"]


@UNIT
def test_a_lock_held_by_another_program_is_waited_for(packed, monkeypatch):
    monkeypatch.setattr(bundle, "LOCK_WAIT", 0.3)
    lock = str(packed) + ".lock"
    with open(lock, "w") as fil:
        fil.write("12345")
    with pytest.raises(bundle.BundleError, match="another program"):
        bundle.update(str(packed), lambda b: None)
    os.utime(lock, (1, 1))  # a lock left by a program that died long ago
    bundle.update(str(packed), lambda b: None)
    assert not os.path.exists(lock)


