@UNIT
def test_messages_that_quote_a_hidden_line_are_masked(logmsgs):
    mask = bundle._MaskHidden({"1": "    " + SI_II})
    load.msgs.addFilter(mask)
    try:
        load.msgs.warn("A parameter that = 13.000000 is not within specified limits"
                       " on line -" + load.msgs.newline() + SI_II)
        load.msgs.warn("Nothing hidden here: 13.0")
    finally:
        load.msgs.removeFilter(mask)
    assert "13.0" not in logmsgs[0] and "<hidden:1>" in logmsgs[0]
    assert logmsgs[1] == "Nothing hidden here: 13.0"


# -- Running a bundle (Stage 1.7) ----------------------------------------------------


def _run(path, *extra):
    """Run a bundle in this process, headless, on the CPU."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    from alis.scripts.run_alis import parser

    plt.close("all")
    args = parser([str(path), "-p", "0", "-c", "1", "--set", "run backend cpu",
                   *extra])
    overrides = []
    argflag = load.optarg(argv=args, overrides=overrides, verbose=-1)
    argflag["run"]["modname"] = args.alis_modfile
    return bundle.run(str(path), argflag, overrides, command="test")


@pytest.mark.fast
@pytest.mark.examples
def test_a_blinded_bundle_run_hides_what_reveals_a_value(tmp_path, capsys, logmsgs):
    model = _stage(tmp_path, "blind")
    path = tmp_path / "run" / "blind.model"
    path.parent.mkdir()
    bundle.pack_to(str(model), str(path))
    _run(path)
    printed = capsys.readouterr().out + "\n".join(logmsgs)
    assert "28Si_II  13" not in printed and "28Si_II 13.0" not in printed
    # Nothing was unpacked to disk
    assert sorted(os.listdir(path.parent)) == ["blind.model"]
    made = bundle.read(str(path))
    out = "runs/latest/files/model/fit_spectra.mod.out"
    hidden = made.hidden["lines"][out]
    assert any(line.lstrip().startswith("voigt   ion=28Si_II") for line in hidden.values())
    for line in hidden.values():
        assert line.encode() not in made.members[out]
    info = json.loads(made.members["runs/latest/run.json"])
    assert info["status"] == "completed" and info["model_sha256"]
    # Extracting writes what a plain run writes
    bundle.extract(made, str(tmp_path / "ext"))
    text = (tmp_path / "ext" / "model" / "fit_spectra.mod.out").read_text()
    assert bundle.BLIND_LINE in text


