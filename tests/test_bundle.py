@UNIT
def test_sources_are_checked_relinked_and_embedded(packed, tmp_path):
    spec = tmp_path / "spectrum.dat"
    spec.write_text("1 2 3\n")
    made = bundle.read(str(packed))
    entry = bundle.add_source(made, str(spec), dataset="HIRES",
                              bundle_path=str(packed))
    assert bundle.check_sources(made, str(packed))[0][1] == "present"
    moved = tmp_path / "moved.dat"
    spec.rename(moved)
    assert bundle.check_sources(made, str(packed))[0][1] == "missing"
    bundle.relink_source(made, entry["id"], str(moved), bundle_path=str(packed))
    assert bundle.check_sources(made, str(packed))[0][1] == "present"
    bundle.embed_source(made, entry["id"], bundle_path=str(packed))
    assert made.members[entry["embedded"]] == b"1 2 3\n"
    moved.write_text("4 5 6\n")
    assert bundle.check_sources(made, str(packed))[0][1] == "changed"
    other = tmp_path / "other.dat"
    other.write_text("7 8 9\n")
    with pytest.raises(bundle.BundleError, match="not the same spectrum"):
        bundle.relink_source(made, entry["id"], str(other))
    bundle.unembed_source(made, entry["id"])
    assert entry["embedded"] is None
    bundle.write(made, str(packed))
    assert bundle.read(str(packed)).sources[0]["dataset"] == "HIRES"


