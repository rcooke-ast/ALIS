def _all_models():
    params = []
    for path in sorted(ROOT.glob("examples/*/model/*.mod")):
        params.append(pytest.param(path, id=str(path.relative_to(ROOT))))
    for path in sorted(ROOT.glob("context/fitting_examples/**/*.mod")):
        params.append(pytest.param(path, id=str(path.relative_to(ROOT)),
                                   marks=pytest.mark.context))
    return params


@UNIT
@pytest.mark.parametrize("model", _all_models())
def test_packing_then_extracting_gives_back_every_file(model, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    try:
        made = bundle.pack(str(model), with_outputs=False)
    except bundle.BundleError as err:
        # Generated data and missing snips cannot be packed, by design
        if "cannot be packed" in str(err) or "does not exist" in str(err):
            pytest.skip(str(err).splitlines()[0])
        raise
    except SystemExit:
        pytest.skip("the model does not load")
    path = tmp_path / "x.model"
    bundle.write(made, str(path))
    written, _ = bundle.extract(bundle.read(str(path)), str(tmp_path / "out"))
    root = Path(str(model.parent))
    for _ in made.model_dir.split("/") if made.model_dir else []:
        root = root.parent
    assert written
    for member in made.members:
        if not member.startswith(bundle.TREE):
            continue
        rel = member[len(bundle.TREE):]
        original = (root / rel).read_bytes()
        assert (tmp_path / "out" / rel).read_bytes() == original, rel


