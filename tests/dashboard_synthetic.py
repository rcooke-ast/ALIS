"""Synthetic fits for the dashboard's tests, written into a folder.

Dashboard Stage 7. :func:`write_ratio_fit` writes a fit in the shape of RJC's
J101155p294141 (``context/fitting_examples/Temperature/``): H I components whose
redshifts carry no label, and D I given by one ratio line, ``ion=2H_I/1H_I``, that
every H I component of its snip shares. Its snip is a flat Lyα spectrum at z = 2.5036,
so that ALIS reads the model; nothing here is fitted.

Generated by RJC and Claude.
"""

from pathlib import Path

import numpy as np

Z = 2.5036
LYA = 1215.6701

# J101155p294141's two components, and its D/H ratio
RATIO_LINES = [
    "voigt ion=1H_I 14.0 2.50360 10.0 10000.0 specid=0",
    "voigt ion=1H_I 13.5 2.50420 10.0 10000.0 specid=0",
    "voigt ion=2H_I/1H_I -4.5974FIXDH specid=0",
]


# J013301m400628's shape: D I's log N computed from H I's by a link (item 2)
LINKED_LINES = [
    "voigt ion=1H_I 14.5nha 2.50360ra 25.0doppa 10000.0tempa specid=0",
    "voigt ion=1H_I 13.5nhb 2.50420rb 10.0doppb 10000.0tempb specid=0",
    "voigt ion=2H_I 10.0nda 2.50360ra 25.0doppa 10000.0tempa specid=0",
    "voigt ion=2H_I 9.0ndb 2.50420rb 10.0doppb 10000.0tempb specid=0",
    "variable -4.5974FIXDH specid=0",
]
LINKS = ["nda(nha,FIXDH) = nha + FIXDH", "ndb(nhb,FIXDH) = nhb + FIXDH"]


def write_ratio_fit(folder, lines=None, extra=(), links=()):
    """
    Write a snip and a ``.mod`` in J101155p294141's shape, and return the ``.mod``.

    Parameters
    ----------
    folder : path
    lines : list of str, optional
        The absorption lines (:data:`RATIO_LINES` by default).
    extra : sequence of str
        Lines written after them, in the model block (commented-out lines, say).
    links : sequence of str
        The lines of a link block, written after the model block.

    Generated by RJC and Claude.
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    wave = np.arange(4252.0, 4266.0, 0.02)
    rng = np.random.default_rng(7)
    flux = 1.0 + 0.01 * rng.standard_normal(wave.size)
    np.savetxt(
        folder / "lya.dat",
        np.column_stack([wave, flux, np.full(wave.size, 0.01)]),
        fmt="%.6f",
    )
    body = "\n".join("  " + ln for ln in list(lines or RATIO_LINES) + list(extra))
    text = (
        "run blind False\n"
        "chisq miniter 1\n"
        "chisq maxiter 1\n"
        "\n"
        "data read\n"
        "  lya.dat  specid=0  fitrange=all  resolution=vfwhm(6.285VFIX)"
        "  columns=[wave,flux,error]\n"
        "data end\n"
        "\n"
        "model read\n"
        " emission\n"
        "  legendre 1.0 0.0 specid=0 scale=1.0,1.0\n"
        " absorption\n" + body + "\nmodel end\n"
    )
    if links:
        text += "\nlink read\n" + "".join("  " + ln + "\n" for ln in links)
        text += "link end\n"
    path = folder / "ratio.mod"
    path.write_text(text)
    return path


def write_linked_fit(folder, extra=()):
    """J013301m400628's shape (item 2): see :data:`LINKED_LINES` and :data:`LINKS`."""
    return write_ratio_fit(folder, LINKED_LINES, extra, LINKS)


# The transitions of a thermal fit: (ion, rest wavelength Å, f, Γ s⁻¹, mass u)
_LYMAN = [
    ("1H_I", 1215.6701, 0.4164, 6.265e8, 1.00794),
    ("1H_I", 1025.7223, 0.07912, 1.897e8, 1.00794),
    ("2H_I", 1215.3394, 0.4164, 6.265e8, 2.0141),
    ("2H_I", 1025.4433, 0.07912, 1.897e8, 2.0141),
]
C_KMS = 299792.458


def _voigt_tau(wave, z, logn, b, rest, fval, gamma):
    """A line's optical depth on a wavelength grid (Å), with b in km/s."""
    from scipy.special import wofz

    lam = rest * 1.0e-8
    dop = rest * b / C_KMS
    u = (wave / (1.0 + z) - rest) / dop
    a = gamma * lam / (4.0 * np.pi * b * 1.0e5)
    prof = wofz(u + 1j * a).real
    return 0.02654 * 10.0**logn * fval * lam / (np.sqrt(np.pi) * b * 1.0e5) * prof


def write_thermal_fit(folder, temperature=15000.0, logn=17.0, dh=-4.6, z=Z):
    """
    Write Lyα and Lyβ snips of H I and D I broadened by temperature alone (no
    turbulence), and a ``.mod`` whose component starts with b_turb free and T fixed,
    beside a turbulent H I component; return the ``.mod``.

    Generated by RJC and Claude.
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(11)
    fwhm = 6.285
    data = []
    for num, rest in enumerate((1215.6701, 1025.7223)):
        centre = rest * (1.0 + z)
        dv = 1.5
        vel = np.arange(-300.0, 300.0 + dv, dv)
        wave = centre * np.exp(vel / C_KMS)
        tau = np.zeros(wave.size)
        for ion, lrest, fval, gamma, mass in _LYMAN:
            if abs(lrest - rest) > 1.0:
                continue
            b = 0.12895 * np.sqrt(temperature / mass)
            col = logn + (dh if ion == "2H_I" else 0.0)
            tau += _voigt_tau(wave, z, col, b, lrest, fval, gamma)
        # The turbulent component, 85 km/s redward
        b2 = 20.0
        zz = z + 85.0 / C_KMS * (1.0 + z)
        for ion, lrest, fval, gamma, mass in _LYMAN[:2]:
            if abs(lrest - rest) < 1.0:
                tau += _voigt_tau(wave, zz, 13.0, b2, lrest, fval, gamma)
        flux = np.exp(-tau)
        sigma = fwhm / 2.3548 / dv
        kern = np.exp(-0.5 * (np.arange(-30, 31) / sigma) ** 2)
        flux = np.convolve(flux, kern / kern.sum(), mode="same")
        flux += 0.01 * rng.standard_normal(wave.size)
        name = "thermal_{0}.dat".format(num)
        np.savetxt(
            folder / name,
            np.column_stack([wave, flux, np.full(wave.size, 0.01)]),
            fmt="%.6f",
        )
        data.append(
            "  {0}  specid={1}  fitrange=all  resolution=vfwhm({2}VFIX)"
            "  columns=[wave,flux,error]\n".format(name, num, fwhm)
        )
    zz = z + 85.0 / C_KMS * (1.0 + z)
    text = (
        "run blind False\n"
        "chisq miniter 3\n"
        "chisq maxiter 200\n"
        "\n"
        "data read\n" + "".join(data) + "data end\n"
        "\n"
        "model read\n"
        " emission\n"
        "  constant 1.0CONA specid=0\n"
        "  constant 1.0CONB specid=1\n"
        " absorption\n"
        "  voigt ion=1H_I {0:.3f} {1:.7f}za1 12.0ba1 10000.0TA1 specid=0,1\n"
        "  voigt ion=2H_I/1H_I {2}FIXDH specid=0,1\n"
        "  voigt ion=1H_I 13.000 {3:.7f}zb1 18.0bb1 0.0TB1 specid=0,1\n"
        "model end\n".format(logn - 0.05, z, dh, zz)
    )
    path = folder / "thermal.mod"
    path.write_text(text)
    return path


TROUGH_MODEL = """run blind False
chisq miniter 3
chisq maxiter 200
out fits False
plot fits False

data read
  ../data/sat.dat  specid=0  fitrange=all  resolution=vfwhm(7.0VFIX)"""
TROUGH_MODEL += """  columns=[wave,flux,error]  label=Lya
data end

model read
 emission
  constant 1.0 specid=0
 absorption
  voigt ion=1H_I 15.4 0.0 18.0 0.0TFIX specid=0
{0}model end
"""
ZERO_SECTION = " zerolevel\n  constant 0.0 specid=0\n"


def write_trough(folder, zero, logn=15.5, b=20.0, sigma=0.01, section=True):
    """
    A saturated Lyα at z = 0 with a zero level, as ALIS applies one (``model_eval``:
    cont × (m + zero) / (cont + zero)), in ``data/``; and its ``.mod`` in ``model/``,
    with ``constant 0.0`` in a ``zerolevel`` section unless ``section`` is False.
    Returns the ``.mod`` (Task 7.7).

    Generated by RJC and Claude.
    """
    from scipy.special import wofz

    folder = Path(folder)
    rng = np.random.default_rng(3)
    vel = np.arange(-400.0, 400.0, 1.5)
    wave = LYA * np.exp(vel / C_KMS)
    lam = LYA * 1.0e-8
    u = (wave - LYA) / (LYA * b / C_KMS)
    a = 6.265e8 * lam / (4.0 * np.pi * b * 1.0e5)
    tau = 0.02654 * 10.0**logn * 0.4164 * lam / (np.sqrt(np.pi) * b * 1.0e5)
    flux = np.exp(-tau * wofz(u + 1j * a).real)
    kern = np.exp(-0.5 * (np.arange(-20, 21) * 1.5 / (7.0 / 2.3548)) ** 2)
    flux = np.convolve(flux, kern / kern.sum(), mode="same")
    flux = (flux + zero) / (1.0 + zero) + sigma * rng.standard_normal(wave.size)
    (folder / "data").mkdir(parents=True, exist_ok=True)
    (folder / "model").mkdir(exist_ok=True)
    np.savetxt(
        folder / "data" / "sat.dat",
        np.column_stack([wave, flux, np.full(wave.size, sigma)]),
        fmt="%.7f",
    )
    path = folder / "model" / "sat.mod"
    path.write_text(TROUGH_MODEL.format(ZERO_SECTION if section else ""))
    return path


def write_shifted_fit(folder, shift=3.0, z=Z):
    """
    Two datasets (A and B) of an H I line's Lyα and Lyβ, B's Lyβ snip shifted by
    ``shift`` km/s; a ``.mod`` with each dataset's own FWHM label and no shift.
    Returns the ``.mod`` (Task 7.13).

    Generated by RJC and Claude.
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(5)
    fwhm, logn, b = 6.285, 14.3, 15.0
    data = []
    specid = 0
    for dataset in ("A", "B"):
        for num, (rest, fval, gamma) in enumerate(
            ((1215.6701, 0.4164, 6.265e8), (1025.7223, 0.07912, 1.897e8))
        ):
            moved = shift if (dataset, num) == ("B", 1) else 0.0
            centre = rest * (1.0 + z)
            dv = 1.5
            vel = np.arange(-200.0, 200.0 + dv, dv)
            wave = centre * np.exp(vel / C_KMS)
            tau = _voigt_tau(
                wave / (1.0 + moved / C_KMS), z, logn, b, rest, fval, gamma
            )
            flux = np.exp(-tau)
            sigma = fwhm / 2.3548 / dv
            kern = np.exp(-0.5 * (np.arange(-30, 31) / sigma) ** 2)
            flux = np.convolve(flux, kern / kern.sum(), mode="same")
            flux += 0.005 * rng.standard_normal(wave.size)
            name = "{0}_{1}.dat".format(dataset, num)
            np.savetxt(
                folder / name,
                np.column_stack([wave, flux, np.full(wave.size, 0.005)]),
                fmt="%.6f",
            )
            data.append(
                "  {0}  specid={1}  fitrange=all  resolution=vfwhm({2}VFIX{3})"
                "  columns=[wave,flux,error]  label={3}\n".format(
                    name, specid, fwhm, dataset
                )
            )
            specid += 1
    text = (
        "run blind False\n"
        "chisq miniter 3\n"
        "chisq maxiter 200\n"
        "\n"
        "data read\n" + "".join(data) + "data end\n"
        "\n"
        "model read\n"
        " emission\n"
        "  constant 1.0CONT specid=0,1,2,3\n"
        " absorption\n"
        "  voigt ion=1H_I 14.2 {0:.7f}za1 12.0ba1 0.0TA1 specid=0,1,2,3\n"
        "model end\n".format(z)
    )
    path = folder / "shifted.mod"
    path.write_text(text)
    return path
