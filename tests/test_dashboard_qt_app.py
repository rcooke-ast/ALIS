def test_the_application_runs_and_closes(home, qtbot):
    app = APP.make_application()
    assert app is QtWidgets.QApplication.instance()
    assert app.property("alis_style") == "QFusionStyle"

    def close_all():
        for widget in QtWidgets.QApplication.topLevelWidgets():
            if isinstance(widget, WN.MainWindow):
                widget.close()

    QtCore.QTimer.singleShot(300, close_all)
    assert APP.run(S.Target(S.START)) == 0


