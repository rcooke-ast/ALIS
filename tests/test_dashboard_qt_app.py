def test_the_start_page_lists_recent_projects_and_unsaved_work(home, qtbot, tmp_path):
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path))
    PR.Recent(str(home)).add(str(path))
    PR.Recent(str(home)).add(str(tmp_path / "gone.model"))
    lost = S.Session.import_model(str(METAL))
    lost.history.edit(_change(lost), "x")
    lost.autosave()
    window = make_window(qtbot, home)
    page = window.start
    texts = [page.recent.item(n).text() for n in range(page.recent.count())]
    assert texts[0].startswith("gone.model") and texts[0].endswith("(missing)")
    assert texts[1].startswith("metal.model")
    assert page.orphan_pane.isVisible() and page.orphans.count() == 1
    # Recover the unsaved work
    page.orphans.setCurrentRow(0)
    page._recover()
    assert window.session.path is None and window.session.dirty
    window.session.discard_recovery()
    window.session = None
    window.show_start()
    assert page.orphans.count() == 0
    # Open a recent project from the list
    page._open_recent(page.recent.item(1))
    wait_idle(qtbot, window)
    assert window.session.path == str(path)
    # The Open recent menu
    window._fill_recent()
    names = [a.text() for a in window.recent_menu.actions()]
    assert names == ["metal.model", "gone.model"]
    assert not window.recent_menu.actions()[1].isEnabled()


def _change(session):
    from alis.dashboard import edit as E

    pm = session.project.parsed
    par = next(p for p in pm.params if p.name == "ColDens")
    return E.set_value(pm, par, 14.25)


def test_an_unexpected_error_is_reported(home, qtbot, logmsgs):
    window = make_window(qtbot, home)

    def broken():
        raise RuntimeError("a bug in the dashboard")

    window._run("broken", broken)
    kind, title, text = window.answers.asked[-1]
    assert title == "Unexpected error"
    assert text == WN.UNEXPECTED
    assert any("a bug in the dashboard" in m for m in logmsgs)


def test_clicking_a_problem_goes_to_its_line(home, qtbot):
    window = make_window(qtbot, home)
    window.import_path(str(METAL))
    wait_idle(qtbot, window)
    panel = window.panel
    shown = panel.editor.toPlainText()
    cursor = panel.editor.textCursor()
    cursor.setPosition(shown.index("legendre"))
    panel.editor.setTextCursor(cursor)
    qtbot.keyClicks(panel.editor, "x")
    wait_idle(qtbot, window)
    item = next(
        panel.list.item(n)
        for n in range(panel.list.count())
        if panel.list.item(n).data(QtCore.Qt.ItemDataRole.UserRole) is not None
    )
    line = item.data(QtCore.Qt.ItemDataRole.UserRole)
    panel.go_to_line(0)
    panel._go_to_problem(item)
    assert panel.editor.textCursor().blockNumber() == line
    window.session.discard_recovery()
    window.session = None
