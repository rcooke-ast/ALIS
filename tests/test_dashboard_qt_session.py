@pytest.fixture
def setup(qtbot, tmp_path, monkeypatch):
    monkeypatch.setenv("ALIS_HOME", str(tmp_path / "home"))
    path = tmp_path / "metal.model"
    B.pack_to(str(METAL), str(path), with_outputs=False)
    window = make_window(qtbot, tmp_path / "home")
    yield window, str(path)
    if window.session is not None:
        window.session.discard_recovery()
        window.session = None


def edit_value(window, value):
    project = window.session.project
    par = next(p for p in project.parsed.params if p.name == "ColDens")
    window._run(
        "panel",
        lambda: window.session.history.edit(
            E.set_value(project.parsed, par, value), "Set N"
        ),
    )


def test_autosave_and_recovery_on_opening(setup, qtbot):
    window, path = setup
    window.open_path(path)
    wait_idle(qtbot, window)
    assert window.status_autosave.text() == "Not autosaved yet"
    edit_value(window, 14.25)
    assert window.isWindowModified()
    window.autosave()
    assert window.autosave_label.text().startswith("autosaved ")
    assert window.status_autosave.text().startswith("Autosaved ")
    # The dashboard stops, as after a crash; opening again offers the copy
    window.session = None
    window.show_start()
    window.answers.answers["recover"] = "Recover"
    window.open_path(path)
    assert window.answers.asked[-1][0] == "recover"
    assert "14.25" in window.session.project.text and window.isWindowModified()


def test_opening_the_saved_project_discards_the_copy(setup, qtbot):
    window, path = setup
    window.open_path(path)
    edit_value(window, 14.25)
    window.autosave()
    window.session = None
    window.answers.answers["recover"] = "Open the saved project"
    window.open_path(path)
    assert "14.25" not in window.session.project.text
    assert S.find_recovery(path) is None


def test_closing_with_unsaved_changes(setup, qtbot):
    window, path = setup
    window.open_path(path)
    edit_value(window, 14.25)
    window.autosave()
    # Cancel keeps the project open
    window.qactions["file.close"].trigger()
    assert window.answers.asked[-1][0] == "unsaved" and window.session is not None
    # Don't save closes it, and removes the recovery copy
    window.answers.answers["unsaved"] = "Don't save"
    copy_path = window.session.recovery_path
    window.qactions["file.close"].trigger()
    assert window.session is None and window.stack.currentIndex() == 0
    assert not __import__("os").path.exists(copy_path)
    assert "14.25" not in B.read(path).model_text()
    # Save saves it
    window.open_path(path)
    edit_value(window, 14.5)
    window.answers.answers["unsaved"] = "Save"
    window.qactions["file.close"].trigger()
    assert "14.5" in B.read(path).model_text()


def test_a_conflict_on_save(setup, qtbot):
    window, path = setup
    window.open_path(path)
    edit_value(window, 14.25)
    other = S.Session.open(path)
    par = next(p for p in other.project.parsed.params if p.name == "ColDens")
    other.history.edit(E.set_value(other.project.parsed, par, 11.5), "x")
    other.save()
    # Cancel: nothing is written
    window.qactions["file.save"].trigger()
    assert window.answers.asked[-1][0] == "conflict"
    assert "11.5" in B.read(path).model_text()
    # Reload: the disk's version
    window.answers.answers["conflict"] = "Reload"
    window.qactions["file.save"].trigger()
    assert "11.5" in window.session.project.text and not window.isWindowModified()
    # Overwrite
    edit_value(window, 14.75)
    par = next(p for p in other.project.parsed.params if p.name == "ColDens")
    other.history.edit(E.set_value(other.project.parsed, par, 11.0), "x")
    other.save(overwrite=True)
    window.answers.answers["conflict"] = "Overwrite"
    window.qactions["file.save"].trigger()
    assert "14.75" in B.read(path).model_text()


def test_save_as_for_an_import(setup, qtbot, tmp_path):
    window, _ = setup
