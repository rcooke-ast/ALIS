def test_a_file_changed_on_disk_and_a_run_finished_outside(setup, qtbot):
    window, path = setup
    window.open_path(path)
    # A run_alis project.model finishing: taken in, with a message
    info = {
        "status": "completed",
        "finished": B.now(),
        "model_sha256": B.sha256(window.session.project.model_bytes()[0]),
    }
    B.update(
        path,
        lambda b: b.members.__setitem__(
            B.LATEST + "run.json", json.dumps(info).encode()
        ),
    )
    window.watch_disk()
    assert "run finished outside" in window.statusBar().currentMessage()
    assert window.markers["Fit"].state == "complete"
    # Another program changes the model: a banner offers to reload
    other = S.Session.open(path)
    par = next(p for p in other.project.parsed.params if p.name == "ColDens")
    other.history.edit(E.set_value(other.project.parsed, par, 11.5), "x")
    other.save()
    window.watch_disk()
    assert window.disk_banner.isVisible()
    assert "changed by another program" in window.disk_banner.label.text()
    window._reload()
    assert "11.5" in window.session.project.text
    assert not window.disk_banner.isVisible()


def test_the_preferences_dialog(setup, qtbot):
    window, path = setup
    window.open_path(path)

    def answer(dialog):
        assert isinstance(dialog, D.PreferencesDialog)
        dialog.fields["autosave.interval"].setValue(120)
        dialog.fields["editor.typing_pause"].setValue(2.5)
        dialog.fields["new_project.settings"].setPlainText(
            "run ncpus 4\nrun nonsense 1"
        )
        dialog.accept()
        assert "not an ALIS setting" in dialog.error.text()
        dialog.fields["new_project.settings"].setPlainText("run ncpus 4")
        dialog.accept()
        return 1

    window.on_dialog = answer
    window.qactions["file.preferences"].trigger()
    assert window.autosave_timer.interval() == 120000
    assert window.session.history.pause == 2.5
    saved = json.loads((window.prefs.path and open(window.prefs.path).read()))
    assert saved["autosave"]["interval"] == 120.0
    assert saved["new_project"]["settings"] == [["run", "ncpus", "4"]]
