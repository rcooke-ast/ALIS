"""The validator (dashboard Stage 2.6, F5).

Each kind of problem in F5's list is made in a small model and must be reported on
the right line. Every model in ``examples/`` gives no errors. ALIS's own loaders (the
full check) run quietly, with the data in memory, and an unexpected exception is
reported with its traceback on the terminal.

Generated by RJC and Claude.
"""

import re
from pathlib import Path

import numpy as np
import pytest

from alis import load
from alis.dashboard import model as M
from alis.dashboard import validate as V

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
EXAMPLES = sorted(ROOT.glob("examples/*/model/*.mod"))
J1358 = ROOT / "context/fitting_examples/VMP_DLA/J1358p6522/model/J1358p6522.mod"
DESIGN_REF = re.compile(r"\b(?:D|F|S|QF|Q)\d")


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def snip(wave, mask=None, level=1.0):
    rows = [wave, np.full_like(wave, level), np.full_like(wave, 0.1)]
    if mask is not None:
        rows.append(mask.astype(float))
    return "".join(
        " ".join("{0:.18e}".format(v) for v in row) + "\n"
        for row in np.column_stack(rows)
    ).encode()


WAVE = np.linspace(1299.0, 1307.0, 801)
B_LINE = (
    "  b.dat  specid=B  fitrange=columns  columns=[wave,flux,error,fitrange]"
    "  resolution=vfwhm(7.0VA)"
)
MODEL = """run ncpus 1
data read
  a.dat  specid=A  fitrange=[1300.0,1306.0]  resolution=vfwhm(7.0VA)
{B_LINE}
data end
model read
 emission
  legendre 1.0  0.0  specid=A
  legendre 1.0  specid=B
 absorption
  voigt  ion=16O_I    14.0  0.00100za  5.0ba   1.0E+03TA  specid=A,B
  voigt  ion=28Si_II  13.0  0.00100za  5.0ba   1.0E+03TA  specid=A
model end
""".replace("{B_LINE}", B_LINE)
DATA = {
    "a.dat": snip(WAVE),
    "b.dat": snip(WAVE, (WAVE > 1301.0) & (WAVE < 1305.0), level=1.1),
}


def problems(registry, text=MODEL, data=None, full=False):
    data = DATA if data is None else data
    pm = M.ParsedModel(text, registry)
    out = V.quick(pm, data)
    if full and not [p for p in out if p.severity == "error"]:
        out = V.order(out + V.full(text, data, registry, pm))
    for prob in out:
        assert not DESIGN_REF.search(prob.message), prob.message
    return out


def found(probs, line, severity, words):
    return any(
        p.line == line and p.severity == severity and words in p.message for p in probs
    )


def test_the_small_model_is_clean(registry):
    assert problems(registry, full=True) == []


# -- F5's list, one problem at a time ----------------------------------------------


@pytest.mark.parametrize(
    "old, new, line, words",
    [
        # block structure
        (" emission\n", " emission\n<--#\n", 7, "never started"),
        ("model end\n", "", None, "'model end' is missing"),
        # unknown functions and ions
        (
            "  legendre 1.0  specid=B",
            "  legendr 1.0  specid=B",
            8,
            "Unknown model function",
        ),
        ("ion=28Si_II", "ion=28Xx_II", 11, "Unknown ion"),
        # a 1e4-style label
        (
            "1.0E+03TA  specid=A\n",
            "1e3  specid=A\n",
            11,
            "Write the exponent with a sign",
        ),
        # a specid with no data line
        ("specid=A,B\n", "specid=A,C\n", 10, "no data line with specid 'C'"),
        # a specid with no continuum
        ("  legendre 1.0  specid=B\n", "", 3, "Specid 'B' has no continuum"),
        # a fitrange with no pixels
        ("fitrange=[1300.0,1306.0]", "fitrange=[1400.0,1406.0]", 2, "holds no pixels"),
    ],
)
def test_each_error_is_on_its_line(registry, old, new, line, words):
    probs = problems(registry, MODEL.replace(old, new))
    assert found(probs, line, "error", words), probs


def test_a_mask_with_no_pixels(registry):
    data = dict(DATA, **{"b.dat": snip(WAVE, np.zeros(WAVE.size, dtype=bool), 1.1)})
    probs = problems(registry, data=data)
    # A mask column with no fitted pixel is a snip with no region yet (Stage 4)
    assert found(probs, 3, "error", "has no fit region yet"), probs


def test_tied_labels_with_different_values(registry):
    probs = problems(
        registry, MODEL.replace("13.0  0.00100za  5.0ba", "13.0  0.00100za  6.0ba")
    )
    assert found(probs, 11, "warning", "'ba' is also used on line 11"), probs
    assert not found(probs, 10, "warning", "'ba'")


def test_a_buffer_narrower_than_the_convolution(registry):
    # The fit reaches the snip's red edge, and FWHM 7 km/s needs ~30 km/s beyond it
    probs = problems(registry, MODEL.replace("[1300.0,1306.0]", "[1300.0,1307.0]"))
    assert found(probs, 2, "warning", "On its red side"), probs
    assert not found(probs, 2, "warning", "On its blue side")
    assert not found(probs, 3, "warning", "side")


def test_a_label_holding_the_value_s_last_digit_is_read_as_written(registry):
    # ALIS used to read 14.01n1a as 14.0 (Q2.12); now there is nothing to warn about
    text = MODEL.replace("14.0  0.00100za", "14.01n1a  0.00100za")
    assert problems(registry, text) == []
    pm = M.ParsedModel(text, registry)
    assert pm.labels["n1a"].params[0].value == 14.01


# -- The full check ----------------------------------------------------------------


def test_the_full_check_places_alis_errors(registry):
    data = {"a.dat": DATA["a.dat"]}
    probs = problems(registry, data=data, full=True)
    assert found(probs, 3, "error", "not among the data held in memory"), probs


def test_the_full_check_finds_what_only_a_fit_would(registry):
    # An isotope missing from the atomic data stops ALIS only when it is evaluated
    text = MODEL.replace("ion=28Si_II", "ion=26Al_II")
    pm = M.ParsedModel(text, registry)
    assert pm.ok
    out = V.full(text, DATA, registry, pm)
    assert found(out, 11, "error", "26Al"), out


def test_a_model_with_no_data_lines_yet(registry, logmsgs):
    """A new project has no snips yet: a warning, not an unexpected error."""
    text = "run ncpus 1\ndata read\ndata end\nmodel read\n emission\nmodel end\n"
    pm = M.ParsedModel(text, registry)
    assert pm.ok
    out = V.full(text, {}, registry, pm)
    assert [(p.line, p.severity, p.message) for p in out] == [
        (None, "warning", V.NO_DATA_LINES)
    ]
    assert not logmsgs


def test_alis_messages_stay_off_the_terminal(registry, logmsgs):
    problems(
        registry,
        MODEL.replace("1.0E+03TA  specid=A\n", "1.0E+03TA  specid=A" "  blind=Maybe\n"),
        full=True,
    )
    assert not logmsgs


def test_an_unexpected_error_goes_to_the_terminal(registry, monkeypatch, logmsgs):
    def broken(*args, **kwargs):
        raise RuntimeError("something nobody expected")

    monkeypatch.setattr(load, "load_model", broken)
    out = V.full(MODEL, DATA, registry)
    assert [(p.line, p.severity, p.message) for p in out] == [
        (None, "error", V.UNEXPECTED)
    ]
    assert any("Traceback" in m and "something nobody expected" in m for m in logmsgs)


# -- Real models -------------------------------------------------------------------


@pytest.mark.parametrize(
    "path", EXAMPLES, ids=[str(p.relative_to(ROOT)) for p in EXAMPLES]
)
def test_every_example_gives_no_errors(path, registry):
    text = path.read_text()
    pm = M.ParsedModel(text, registry)
    lines = [pm.text[d.line].text for d in pm.data]
    data = {}
    for rel in load.data_file_paths(lines, pm.datadirc):
        if (path.parent / rel).is_file():
            data[rel] = (path.parent / rel).read_bytes()
    probs = V.order(V.quick(pm, data) + V.full(text, data, registry, pm))
    errors = [p for p in probs if p.severity == "error"]
    assert errors == []
    for prob in probs:
        assert not DESIGN_REF.search(prob.message), prob.message


def test_a_real_project_is_checked(registry):
    from alis.dashboard import project as P

    if not J1358.exists():
        pytest.skip("model not present")
    project = P.Project.import_model(str(J1358), registry=registry)
    probs = V.check(project)
    assert not [p for p in probs if p.severity == "error"]
    shared = [p for p in probs if "fitted twice" in p.message]
    assert shared and all(p.line is not None for p in shared)
