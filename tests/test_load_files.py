"""The file-format loaders, on small synthetic fixtures (Stage 5.5).

`load_fits` / `load_ascii` / `load_data` were deliberately left out of the
cross-cutting unit-test task (`claude_prompts/refactor_code_unit_tests.md`,
"I/O scope") and deferred to this stage, which reshapes I/O. This is that
deferred work.

Every fixture is a handful of pixels written into `tmp_path`, so nothing here
reads a real spectrum and no fit is run. The one exception is the atomic data,
loaded once per session, because a model-function registry is needed to size
the pixel-load buffer.

Two things are worth more than the rest, and both come from Stage 5.4:

* `bufferpix` reselects the *same* pixels when the fitted resolution differs
  from the starting one -- which is the whole reason the keyword exists;
* a data-line value containing `=` is truncated by the reader, which is why the
  writer emits `lsf(name:STIS,...)` and not `lsf(name=STIS,...)`.

Generated by RJC and Claude.
"""

import numpy as np
import pytest
from astropy.io import fits as pyfits

from alis import load
from alis.config import ArgFlag, ColumnMap
from alis.main import build_funcarray

pytestmark = pytest.mark.unit


class _State:
    """The attributes `load_data` reads, and nothing else.

    A fresh function registry per state, deliberately: `load_model` mutates
    `_fixpar` / `_limits` on the shared function *instances*, so reusing one
    registry would let one test's `fix` line change the next test's model.
    """

    def __init__(self, atomic, verbose=-1):
        self._argflag = ArgFlag()
        self._argflag["out"]["verbose"] = verbose
        self._isonefits = False
        self._atomic = atomic
        self._funcarray = build_funcarray(self._argflag, atomic)


@pytest.fixture
def state(atomic_data):
    return _State(atomic_data)


def _write_spectrum(path, wave, extra=None):
    """A three-column ascii spectrum (flat continuum, constant error)."""
    cols = [wave, np.ones_like(wave), 0.1 * np.ones_like(wave)]
    if extra is not None:
        cols += list(extra)
    np.savetxt(str(path), np.column_stack(cols))
    return path


@pytest.fixture
def spectrum(tmp_path):
    """501 pixels of 0.05 A from 1290 to 1315 A."""
    wave = np.linspace(1290.0, 1315.0, 501)
    return _write_spectrum(tmp_path / "spec.dat", wave), wave


