def test_every_loader_agrees_on_the_nothing_supplied_sentinels(tmp_path):
    """A continuum of ones and a zero level of zeros mean "the user gave none".

    `load_subpixels` (`alis/load.py:1889`) skips the interpolation only when the
    continuum is all ones; anything else is taken as a real continuum and
    multiplies the model (`model_eval.py:572`). `load_fits` used to return
    *zeros*, so a FITS spectrum with no continuum column multiplied the model by
    zero -- fixed 2026-08-04 (RJC). The three loaders must not drift apart
    again, so they are compared against each other rather than each against a
    literal.
    """
    wave = np.linspace(1300.0, 1301.0, 11)
    from_fits = load.load_fits(
        str(_alis_fits(tmp_path / "s.fits", wave)),
        ["wave", "flux", "error"],
        ColumnMap(),
        verbose=-1,
    )
    from_ascii = load.load_ascii(
        str(_write_spectrum(tmp_path / "s.dat", wave)),
        ["wave", "flux", "error"],
        ColumnMap(),
        list(ColumnMap().keys()),
    )
    from_array = load.load_userdata(
        np.vstack([wave, np.ones(wave.size), 0.1 * np.ones(wave.size)]),
        ["wave", "flux", "error"],
        ColumnMap(),
        verbose=-1,
    )
    for name, out in (
        ("fits", from_fits),
        ("ascii", from_ascii),
        ("array", from_array),
    ):
        assert np.allclose(out[3], 1.0), name + ": continuum"
        assert np.allclose(out[4], 0.0), name + ": zero level"


def test_load_fits_keeps_the_continuum_default_when_a_zerolevel_is_given(tmp_path):
    """The companion slip to the fix above.

    Both the continuum and the zero-level branches discard the column they read
    and substitute the default -- but the zero-level branch assigned to `contin`
    rather than `zeroin`. That was invisible while `load_fits` returned zeros
    for the continuum anyway; once it returns ones, a `zerolevel` column put it
    straight back to zeros and the model would again be multiplied by zero.
    """
    wave = np.linspace(1300.0, 1301.0, 11)
    data = np.column_stack(
        [wave, np.ones_like(wave), 0.1 * np.ones_like(wave), np.full(wave.size, 0.3)]
    )
    hdu = pyfits.PrimaryHDU(data.transpose())
    hdu.header["alisfits"] = "fits"
    pyfits.HDUList([hdu]).writeto(str(tmp_path / "z.fits"))

    wfe = ColumnMap()
    wfe["zerolevel"] = 3
    out = load.load_fits(
        str(tmp_path / "z.fits"),
        ["wave", "flux", "error", "zerolevel"],
        wfe,
        verbose=-1,
    )
    assert np.allclose(out[3], 1.0), "continuum"
    assert np.allclose(out[4], 0.0), "zero level"


