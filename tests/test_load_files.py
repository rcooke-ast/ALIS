# -- the sub-keyword separator inside a resolution function (Stage 5.4) -------


def test_a_data_line_value_containing_an_equals_sign_is_truncated(state, spectrum):
    """The mechanism behind the `examples/lsf_hst` failure.

    `load_data` splits each data-line token on `=` and keeps field 1, so any
    value containing a second `=` is cut short. Shown here on `label`, where
    the truncation is visible rather than fatal; on `resolution` it takes the
    function's argument list with it, which is why the writer emits those
    sub-keywords with `:` and why a `.mod.out` saved before Stage 5.4 could not
    be re-read.
    """
    path, _wave = spectrum
    load_one(state, path, label="left=right")
    assert state._datopt["label"][0] == ["left"]


@pytest.mark.linetools
def test_the_lsf_resolution_survives_the_reader_only_in_its_colon_form(
    spectrum, atomic_data
):
    """The same thing on the function it actually bit: `lsf`.

    With `:` the whole call reaches the convolution function; with `=` the
    reader keeps `lsf(name` and the model cannot be loaded at all.
    """
    path, _wave = spectrum
    colon = "lsf(name:STIS,grating:E140H,slit:0.2x0.09)"
    model = ["emission\n", "  legendre 1.0 specid=0\n"]

    good = load_one(_State(atomic_data), path, resolution=colon)
    assert good._resn[0][0] == colon
    load.load_model(good, model)  # loads the convolution function without complaint

    bad = load_one(_State(atomic_data), path, resolution=colon.replace(":", "="))
    assert bad._resn[0][0] == "lsf(name"
    with pytest.raises(BaseException):
        load.load_model(bad, model)


