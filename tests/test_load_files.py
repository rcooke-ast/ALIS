def test_the_loaded_pixels_do_not_move_when_the_resolution_does(spectrum, atomic_data):
    """Why `bufferpix` exists at all (Stage 5.4).

    A saved `.mod.out` records the *fitted* resolution, and ALIS sizes the
    pixel-load buffer from the resolution at load time -- so re-reading a saved
    model would load a different set of pixels from the run that produced it.
    A pixel count does not depend on the resolution, so it does not move.
    """
    path, _wave = spectrum

    def loaded(resolution, **extra):
        st = load_one(_State(atomic_data), path, resolution=resolution, **extra)
        return st._wavefull[0]

    narrow, wide = loaded("vfwhm(7.0)"), loaded("vfwhm(60.0)")
    assert narrow.size != wide.size, "the resolution rule should move the pixels"

    pinned_narrow = loaded("vfwhm(7.0)", bufferpix="[4,4]")
    pinned_wide = loaded("vfwhm(60.0)", bufferpix="[4,4]")
    assert np.array_equal(pinned_narrow, pinned_wide)
    assert pinned_narrow.size == NFIT + 8


