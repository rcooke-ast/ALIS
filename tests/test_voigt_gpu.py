"""GPU Voigt profile: equivalence with the CPU implementation (Stage 4.2).

``call_GPU`` must reproduce ``call_CPU`` to an absolute tolerance of 1e-12
(stage doc Q4.3) in float64 throughout (Q4.6), because the finite-difference
Jacobian -- and hence the covariance matrix ALIS reports as its error bars --
is differenced from these values.

Every test here is marked ``gpu``: they run automatically wherever a CUDA
device is present and skip where one is not (see ``conftest.py``). They are
also marked ``unit`` -- they are fast and isolated, and exercise a single
function with no fits, no subprocesses and no golden files.

Generated by RJC and Claude.
"""

import numpy as np
import pytest

pytestmark = [pytest.mark.gpu, pytest.mark.unit]

# The CPU/GPU agreement required by Q4.3, quoted here so a change to the
# contract has to be made deliberately rather than by loosening an assert.
GPU_ATOL = 1e-12

# Damped Lyman-alpha, the transition most ALIS fits are anchored on.
LYA = (1215.6701, 0.4164, 6.265e8)

# Voigt keyword defaults, as Voigt._keywd defines them.
KW = {"freq": False, "logN": True, "ColDensScale": 1.0}


@pytest.fixture(scope="module")
def cuda():
    """The ``numba.cuda`` module.

    Imported here rather than at module scope so that collection succeeds on a
    machine with no numba; the ``gpu`` marker is what decides whether these
    tests run.

    Generated by RJC and Claude.
    """
    from numba import cuda as _cuda

    return _cuda


@pytest.fixture(scope="module")
def voigt():
    """A Voigt function instance, as the model builder produces it.

    Generated by RJC and Claude.
    """
    from alis.functions import base

    return base.call(getinst=True)["voigt"]


@pytest.fixture
def compare(cuda, voigt):
    """Return a helper that evaluates both paths and returns ``max|GPU-CPU|``.

    Generated by RJC and Claude.
    """

    def _compare(wave, pin, mkey, ae="ab"):
        wave = np.ascontiguousarray(wave, dtype=np.float64)
        pin = np.ascontiguousarray(pin, dtype=np.float64)
        cpu = voigt.call_CPU(wave, pin, ae=ae, mkey=mkey)
        dev = voigt.call_GPU(
            cuda.to_device(wave), cuda.to_device(pin), ae=ae, mkey=mkey
        )
        gpu = dev.copy_to_host()
        assert gpu.shape == cpu.shape
        assert gpu.dtype == np.float64, "Q4.6 requires float64 throughout"
        return np.max(np.abs(gpu - cpu))

    return _compare


WAVE = np.arange(1200.0, 1230.0, 0.001)


# -- the opt-in --------------------------------------------------------------


def test_voigt_claims_gpu_support(voigt):
    assert voigt.supports_gpu() is True


# -- single-component equivalence across the profile regimes -----------------


@pytest.mark.parametrize(
    "name,par",
    [
        # A saturated damped profile: tau ~ 1e6 in the core, so the exp(-tau)
        # underflow and the far damping wings are both exercised.
        ("damped, logN=20", (20.0, 0.0, 10.0) + LYA),
        # Optically thin: the profile is a small perturbation on unity, which
        # is where an absolute 1e-12 is hardest to hold.
        ("weak, logN=12.5", (12.5, 0.0, 5.0) + LYA),
        ("saturated, logN=15", (15.0, 0.0, 20.0) + LYA),
        # Gamma = 0 drives the branch of the Faddeeva that is only reachable
        # when the imaginary part is <= 1e-10, which no damped line reaches.
        ("zero damping", (14.0, 0.0, 8.0, 1215.6701, 0.4164, 0.0)),
        # A large redshift moves the line off the grid entirely: the far wings
        # are the regime where a truncated series shows up first.
        ("off-grid, z=0.5", (18.0, 0.5, 15.0) + LYA),
        ("narrow, b=1.5", (13.0, 0.0, 1.5) + LYA),
        ("broad, b=200", (16.0, 0.0, 200.0) + LYA),
    ],
)
def test_single_component_matches_cpu(compare, name, par):
    assert compare(WAVE, np.array([par]), [KW]) < GPU_ATOL


# -- batching and combination ------------------------------------------------


@pytest.mark.parametrize("ae", ["ab", "em"])
def test_many_components_match_cpu(compare, ae):
    # One launch covers every row, and the rows are reduced inside the kernel,
    # so this checks the accumulation order as well as the profile itself.
    rng = np.random.default_rng(1)
    nrow = 40
    pin = np.column_stack(
        [
            rng.uniform(11.0, 20.0, nrow),
            rng.uniform(0.0, 0.01, nrow),
            rng.uniform(2.0, 40.0, nrow),
            np.full(nrow, LYA[0]),
            np.full(nrow, LYA[1]),
            np.full(nrow, LYA[2]),
        ]
    )
    assert compare(WAVE, pin, [KW] * nrow, ae=ae) < GPU_ATOL


def test_single_row_batch_matches_cpu(compare):
    # The degenerate batch: 'ab' takes a product over one row, 'em' a sum.
    pin = np.array([(17.0, 0.0, 12.0) + LYA])
    assert compare(WAVE, pin, [KW], ae="em") < GPU_ATOL


# -- the keywords ------------------------------------------------------------


def test_linear_column_density_matches_cpu(compare):
    # logN=False makes the column density linear, scaled by ColDensScale.
    kw = {"freq": False, "logN": False, "ColDensScale": 1.0e14}
    assert compare(WAVE, np.array([(3.7, 0.0, 9.0) + LYA]), [kw]) < GPU_ATOL


def test_frequency_axis_matches_cpu(compare):
    # freq=True reinterprets the abscissa, changing both the grid and the way
    # the rest wavelength is converted.
    kw = {"freq": True, "logN": True, "ColDensScale": 1.0}
    freq = 1.0e10 * 299792458.0 / WAVE
    assert compare(freq, np.array([(18.0, 0.0, 12.0) + LYA]), [kw]) < GPU_ATOL


def test_keywords_may_differ_between_rows(compare):
    # mkey is per-row, so a model may mix logN and linear column densities in
    # a single call; the kernel must not hoist either choice out of the loop.
    kw_lin = {"freq": False, "logN": False, "ColDensScale": 1.0e14}
    pin = np.array([(19.0, 0.0, 10.0) + LYA, (3.7, 0.001, 9.0) + LYA])
    assert compare(WAVE, pin, [KW, kw_lin]) < GPU_ATOL


def test_keyword_cache_does_not_confuse_configurations(compare):
    # The encoded keyword array is cached on its contents; a second call with
    # different keywords must not pick up the first call's entry.
    from alis.functions import voigt_gpu

    voigt_gpu.reset_key_cache()
    kw_lin = {"freq": False, "logN": False, "ColDensScale": 1.0e14}
    pin_log = np.array([(19.0, 0.0, 10.0) + LYA])
    pin_lin = np.array([(3.7, 0.0, 10.0) + LYA])
    assert compare(WAVE, pin_log, [KW]) < GPU_ATOL
    assert compare(WAVE, pin_lin, [kw_lin]) < GPU_ATOL
    assert compare(WAVE, pin_log, [KW]) < GPU_ATOL


# -- the call_GPU contract ---------------------------------------------------


def test_call_gpu_returns_a_device_array(cuda, voigt):
    # The contract (base.Base) is that call_GPU launches a kernel and leaves
    # the result on the device; transfers belong to the dispatcher (Task 4.3).
    pin = np.array([(18.0, 0.0, 10.0) + LYA])
    out = voigt.call_GPU(cuda.to_device(WAVE), cuda.to_device(pin), mkey=[KW])
    assert cuda.is_cuda_array(out)
    assert out.shape == (WAVE.size,)


def test_evaluate_honours_a_supplied_destination(cuda):
    from alis.functions import voigt_gpu

    pin = np.array([(18.0, 0.0, 10.0) + LYA])
    dest = cuda.device_array(WAVE.size, dtype=np.float64)
    out = voigt_gpu.evaluate(
        cuda.to_device(WAVE), cuda.to_device(pin), ae="ab", mkey=[KW], out=dest
    )
    assert out is dest
    assert np.all(np.isfinite(dest.copy_to_host()))


# -- the Faddeeva port itself ------------------------------------------------


def test_faddeeva_matches_scipy_wofz(cuda):
    """The ported Faddeeva must match scipy's over the whole physical domain.

    ALIS only ever evaluates ``w(v + i a)`` with ``a >= 0`` (the damping
    constant), so the upper half plane is what has to be right. scipy's
    ``wofz`` is Johnson's Faddeeva package -- the same algorithm the device
    code ports -- so agreement here should be at the ulp level, not merely
    within some engineering tolerance. It is checked directly because the
    end-to-end flux comparison hides errors wherever the profile saturates.

    Generated by RJC and Claude.
    """
    from scipy.special import wofz

    from alis.functions import voigt_gpu

    @cuda.jit
    def _kernel(zr, zi, out):
        i = cuda.grid(1)
        if i >= zr.shape[0]:
            return
        cc = cuda.const.array_like(voigt_gpu._ERFCX_COEFFS)
        ee = cuda.const.array_like(voigt_gpu._EXPA2N2)
        out[i] = voigt_gpu._faddeeva_real(zr[i], zi[i], cc, ee)

    rng = np.random.default_rng(0)
    n = 60000
    zr = 10.0 ** rng.uniform(-8, 4, n) * rng.choice([-1.0, 1.0], n)
    zi = 10.0 ** rng.uniform(-12, 1.5, n)
    # A Voigt-shaped slab (constant small damping) and a zero-damping slab,
    # which between them cover the branch boundaries the random sample
    # straddles only sparsely.
    zr = np.concatenate(
        [zr, np.linspace(-60.0, 60.0, 20000), np.linspace(-40.0, 40.0, 20000)]
    )
    zi = np.concatenate([zi, np.full(20000, 6.06e-4), np.zeros(20000)])

    d_out = cuda.device_array(zr.size, dtype=np.float64)
    _kernel[(zr.size + 127) // 128, 128](cuda.to_device(zr), cuda.to_device(zi), d_out)
    out = d_out.copy_to_host()
    ref = wofz(zr + 1j * zi).real

    assert np.all(np.isfinite(out) == np.isfinite(ref))
    assert np.max(np.abs(out - ref)) < GPU_ATOL
    # Re w is bounded by 1 in the upper half plane, so an absolute tolerance
    # alone would not catch a series truncated in the far wings, where the
    # value is many orders of magnitude below 1 but still multiplied up by the
    # column density to give an optical depth of order unity.
    rel = np.abs(out - ref) / np.maximum(np.abs(ref), 1e-300)
    assert np.max(rel) < 1e-13, f"worst relative error {np.max(rel):.3e}"
