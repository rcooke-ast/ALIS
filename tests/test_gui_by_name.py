"""
Every text a user sees calls the GUI "the GUI" and names Ryan Cooke (Documentation
Stage 1, DQ1.2 and DQ1.3).

Between Ryan Cooke and Claude, "dashboard" and "GUI" are the same thing, and the
code keeps "dashboard" in its names: the package ``alis/dashboard/``, its modules
and constants, its comments and docstrings, and the values it stores. What a user
reads (the window, the files the GUI writes, the ``alis`` command and ALIS's
messages) says "GUI", and never "RJC".

These tests read every string literal of ``alis/`` with ``ast``, docstrings left
out (they are code, DQ1.4):

- one that says "dashboard" must be one of ``KEPT``, the names and stored values
  that stay, each in the file that has it;
- none may say "RJC".

A text that brings either word back then fails the push that adds it.

Generated by Ryan Cooke and Claude.
"""

import ast
import re
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
ALIS = ROOT / "alis"

# The string literals of alis/ that say "dashboard" and stay, by file: code and
# stored values, which no user reads (documentation_stage1.md, "The GUI by name")
KEPT = {
    # The preferences file, ~/.alis/dashboard.json: renaming it would lose every
    # user's preferences
    ("alis/dashboard/preferences.py", "dashboard.json"),
    # Module paths
    ("alis/dashboard/runs.py", "alis.dashboard.runner"),
    ("alis/scripts/dashboard.py", "alis.dashboard.qt"),
    # Stored values: a run's origin in its run.json, and a setting's owner
    ("alis/dashboard/runs.py", "dashboard"),
    ("alis/dashboard/runner.py", "dashboard"),
    ("alis/dashboard/settings.py", "dashboard"),
    # The check that found a problem (Problem.source), which is never shown
    ("alis/dashboard/validate.py", "dashboard"),
    # Names in __all__
    ("alis/dashboard/runs.py", "DASHBOARD"),
    ("alis/dashboard/settings.py", "DASHBOARD"),
    ("alis/dashboard/settings.py", "DASHBOARD_SETTINGS"),
}
DASHBOARD = re.compile(r"dashboard", re.IGNORECASE)
RJC = re.compile(r"\bRJC\b")


def docstrings(tree):
    """The docstrings' nodes of a module, its classes and its functions."""
    found = set()
    for node in ast.walk(tree):
        if isinstance(
            node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)
        ):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                found.add(id(body[0].value))
    return found


def strings():
    """Every string literal of alis/ but its docstrings: (file, line, text)."""
    found = []
    for path in sorted(ALIS.rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        skip = docstrings(tree)
        name = path.relative_to(ROOT).as_posix()
        for node in ast.walk(tree):
            if (
                isinstance(node, ast.Constant)
                and isinstance(node.value, str)
                and id(node) not in skip
            ):
                found.append((name, node.lineno, node.value))
    return found


@pytest.fixture(scope="module")
def literals():
    found = strings()
    assert len(found) > 1000, "too few string literals: is alis/ where it was?"
    return found


def test_no_text_says_dashboard(literals):
    said = [
        "{0}:{1}: {2!r}".format(name, line, text[:80])
        for name, line, text in literals
        if DASHBOARD.search(text) and (name, text) not in KEPT
    ]
    assert not said, "say GUI, not dashboard: {0}".format(said)


def test_every_name_kept_is_still_there(literals):
    there = {(name, text) for name, line, text in literals}
    gone = sorted(KEPT - there)
    assert not gone, "KEPT names what alis/ no longer has: {0}".format(gone)


def test_no_text_says_rjc(literals):
    said = [
        "{0}:{1}: {2!r}".format(name, line, text[:80])
        for name, line, text in literals
        if RJC.search(text)
    ]
    assert not said, "say Ryan Cooke, not RJC: {0}".format(said)
