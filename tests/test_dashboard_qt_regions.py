    tab.strips[0].view.spanned.emit(PL.MASK, 1302.0, 1302.1)
    assert len(SN.regions_of(window.session.project.snip("OI_1302"))) == 2
    window.qactions["edit.undo"].trigger()
    window.qactions["edit.undo"].trigger()
    assert window.session.project.files[member] == before


