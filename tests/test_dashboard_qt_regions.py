def listed(tab):
    return [
        [tab.listing.topLevelItem(n).text(c) for c in range(5)]
        for n in range(tab.listing.topLevelItemCount())
    ]


def show(tab, element, stage, name):
    """Choose a transition in the list by its name's start."""
    if tab.state.get("element") != element:
        tab.element_box.setCurrentIndex(tab.element_box.findText(element))
    if tab.state.get("stage") != stage:
        tab.ion_box.setCurrentIndex(tab.ion_box.findText(stage))
    for num in range(tab.listing.topLevelItemCount()):
        item = tab.listing.topLevelItem(num)
        if item.text(1).startswith(name):
            tab.listing.setCurrentItem(item)
            return item
    raise AssertionError("{0} is not listed".format(name))


