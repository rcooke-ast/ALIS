    inside = (table[:, 0] >= 1301.5) & (table[:, 0] <= 1302.8)
    assert np.all(table[inside, 3] == 1) and np.all(table[~inside, 3] == 0)
    assert tab.fitted_label.text().startswith("Fitted: {0} pixels".format(inside.sum()))
