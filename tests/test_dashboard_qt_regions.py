def test_q1243_regions_are_the_same_in_every_dataset(window, qtbot):
    need(Q1243)
    window.import_path(str(Q1243))
    wait_idle(qtbot, window)
    tab = regions(window)
    show(tab, "O", "I", "O I 1302")
    assert tab.plot.title.text().startswith("O I 1302.2 · 3 datasets")
    assert [tab._row_name(s.row_id) for s in tab.strips] == [
        "HIRES",
        "PROCHASKA",
        "KIRKMAN",
    ]
    before = window.session.project.text
    project = window.session.project
    shifts = {r.name: 1.0 + SN.row_shift(r) / C_KMS for r in project.rows}
    hires = tab.strips[0]
    tab.select_row(hires.row_id)
    # The imported fit's datasets have regions of their own: HIRES's are used in
    # every dataset on request, moved by each dataset's shift
    assert tab.copy_button.text() == "Use HIRES's regions in every dataset"
    tab.copy_button.click()
    got = regions_by_row(tab)
    for name in ("PROCHASKA", "KIRKMAN"):
        # Split only by pixels never fitted
        assert got[name][0][0] == pytest.approx(
            got["HIRES"][0][0] * shifts[name], abs=0.05
        )
        assert got[name][-1][1] == pytest.approx(
            got["HIRES"][-1][1] * shifts[name], abs=0.05
        )
    origins = [tab.datasets.item(n, 3).text() for n in range(3)]
    assert origins == ["drawn here", "copied from HIRES", "copied from HIRES"]
    window.qactions["edit.undo"].trigger()
    assert window.session.project.text == before
    assert [tab.datasets.item(n, 3).text() for n in range(3)][1:] == ["drawn here"] * 2
    # A region removed on HIRES is removed in every dataset, in one step
    hires = tab.strips[0]
    (a, b), *_ = SN.regions_of(window.session.project.snip(hires.snip.specid))
    entries = dict(tab.context_actions(hires, 0.5 * (a + b)))
    entries["Remove this region from every dataset"]()
    assert all(not spans for spans in regions_by_row(tab).values())
    assert window.qactions["edit.undo"].text().endswith("in 3 datasets")
    # A region added on PROCHASKA is added in every dataset
    low, high = 4588.0, 4592.0
    row = tab.strips[1].row_id
    tab._act("regions.draw", lambda: tab.draw(row, low, high))
    got = regions_by_row(tab)
    for name, spans in got.items():
        factor = shifts[name] / shifts["PROCHASKA"]
        assert spans[0][0] == pytest.approx(low * factor, abs=0.05)
        assert spans[-1][1] == pytest.approx(high * factor, abs=0.05)
    window.qactions["edit.undo"].trigger()
    window.qactions["edit.undo"].trigger()
    assert window.session.project.text == before


def test_add_regions_to_all_and_tweak_one_dataset(window, qtbot, tmp_path):
    """RJC's review of draft 2: two tools, as in prepfit (a drag adds, a right-drag
    leaves pixels out), in every dataset or in the selected one alone."""
    second = tmp_path / "second.dat"
    second.write_bytes(SPECTRUM.read_bytes())
    tab = new_project(window, tmp_path, z=0.0, spectra=(SPECTRUM, second))
    show(tab, "O", "I", "O I 1302")
    tab.actions_["regions.snip"].trigger()
    first, other = (s.row_id for s in tab.strips)
    tab.actions_["regions.draw"].trigger()
    tab.strips[0].view.spanned.emit(PL.DRAW, 1301.5, 1302.8)
    got = regions_by_row(tab)
    assert got["OI_SiII"] == got["second"] and len(got["second"]) == 1
    # A right-drag with Add regions to all leaves the pixels out of both
    tab.strips[1].view.spanned.emit(PL.MASK, 1302.6, 1302.8)
    got = regions_by_row(tab)
    assert got["OI_SiII"] == got["second"] and got["second"][0][1] < 1302.6
    # Tweak dataset regions: the selected dataset alone
    tab.actions_["regions.tweak"].trigger()
    assert not tab.actions_["regions.draw"].isChecked()
    tab.strips[1].view.spanned.emit(PL.DRAW, 1303.0, 1303.2)
    tab.strips[1].view.spanned.emit(PL.MASK, 1302.0, 1302.1)
    got = regions_by_row(tab)
    assert len(got["OI_SiII"]) == 1 and len(got["second"]) == 3
    assert tab.selected == other
    assert window.qactions["edit.undo"].text() == "Undo Exclude 9 pixels of OI_1302_r2"
    # While tweaking, removing a region removes it from this dataset alone
    entries = dict(tab.context_actions(tab.strips[1], 1303.1))
    assert "Remove this region from this dataset only" in entries
    assert "Exclude this pixel" in entries
    entries["Remove this region from this dataset only"]()
    got = regions_by_row(tab)
    assert len(got["second"]) == 2 and len(got["OI_SiII"]) == 1
    assert first != other


