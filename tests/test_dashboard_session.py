def test_a_conflicting_change_on_disk_is_detected(home, path, registry):
    session = S.Session.open(path, registry=registry)
    set_value(session, 14.25)
    other = S.Session.open(path, registry=registry)
    set_value(other, 12.5)
    other.save()
    assert session.check_disk() == S.CHANGED
    with pytest.raises(S.Conflict) as err:
        session.save()
    assert err.value.state == S.CHANGED
    assert "changed by another program" in str(err.value)
    # The user chooses: overwrite ...
    session.save(overwrite=True)
    assert "14.25" in B.read(path).model_text()
    # ... or reload
    other.history.edit(
        E.set_value(other.project.parsed, first_param(other.project), 11.0), "x"
    )
    other.save(overwrite=True)
    set_value(session, 13.0)
    session.reload()
    assert not session.dirty
    assert "11.0" in session.project.text
    assert not session.history.can_undo()


