def test_an_unsaved_import_is_saved_with_save_as(home, tmp_path, registry):
    session = S.Session.import_model(str(METAL), registry=registry)
    assert session.path is None
    assert session.dirty
    assert session.check_disk() == S.UNSAVED
    assert session.suggested_path() == B.default_bundle_name(str(METAL))
    with pytest.raises(S.SessionError):
        session.save()
    target = str(tmp_path / "imported.model")
    session.save(target)
    assert session.path == target and not session.dirty
    again = S.Session.open(target, registry=registry)
    assert again.project.text == session.project.text
    assert again.project.files == session.project.files
    assert PR.Recent().paths()[0] == target


def test_an_unsaved_import_is_recovered_from_the_start_page(home, registry):
    session = S.Session.import_model(str(METAL), registry=registry)
    set_value(session, 14.25)
    assert session.autosave()
    found = S.orphans()
    assert len(found) == 1 and found[0]["path"] is None
    assert found[0]["origin"] == str(METAL)
    back = S.Session.from_recovery(found[0], registry=registry)
    assert back.project.text == session.project.text
    assert back.dirty and back.path is None
    S.discard_recovery(found[0])
    assert S.orphans() == []


