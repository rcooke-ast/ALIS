"""Sessions: open, save, save as, autosave and recovery (dashboard Stage 3.3, F1).

- Saving and reopening gives back the text, the files, ``ui/project.json`` and
  ``ui/view.json``, byte for byte.
- After edits a recovery copy exists; reopening, as after a crash, offers it; a
  clean close removes it (Q3.2).
- Save keeps a run that ``run_alis project.model`` wrote meanwhile (Q1.7, Q3.8(a)).
- A conflicting change on disk is detected (Q3.8(b)).
- An unsaved import is saved with Save as (F4).

Every test works in a temporary folder, with its own ``$ALIS_HOME``. No Qt.

Generated by RJC and Claude.
"""

