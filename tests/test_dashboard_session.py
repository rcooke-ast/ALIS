def test_save_and_reopen_byte_for_byte(home, path, registry):
    session = S.Session.open(path, registry=registry)
    set_value(session, 14.25)
    snip = session.project.snips[0]
    session.history.do(session.project.set_regions(snip, [(1301.5, 1302.6)]))
    session.history.do(session.project.confirm_structure())
    session.set_view("tab", "Components")
    session.set_view("mod_panel", {"open": False, "width": 380})
    assert session.dirty
    expected = session.to_bundle()
    session.save()
    assert not session.dirty
    saved = B.read(path)
    tree = [m for m in expected.members if m.startswith(B.TREE)]
    names = tree + [P.PROJECT_JSON, S.VIEW_JSON]
    for name in names:
        assert saved.members[name] == expected.members[name], name
    again = S.Session.open(path, registry=registry)
    assert again.project.text == session.project.text
    assert again.project.files == session.project.files
    assert again.project.ui == session.project.ui
    assert again.view["tab"] == "Components"
    assert again.view["mod_panel"] == {"open": False, "width": 380}
    assert not again.dirty
    # Saving again, unchanged, gives the same members
    again.save()
    for name, data in members(path, names).items():
        assert data == expected.members[name], name


