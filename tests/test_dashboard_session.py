def write_a_run(path, chi2=123.4):
    """Change only the runs of a bundle, as run_alis project.model does."""
    info = {"status": "completed", "chi2_final": chi2, "finished": B.now()}

    def change(bundle):
        bundle.members[B.LATEST + "run.json"] = json.dumps(info).encode("utf-8")
        bundle.members[B.LATEST + "files/model/fit_spectra.mod.out"] = b"# out\n"

    B.update(path, change)


def test_save_keeps_a_run_written_meanwhile(home, path, registry):
    session = S.Session.open(path, registry=registry)
    set_value(session, 14.25)
    write_a_run(path)
    assert session.check_disk() == S.RUNS
    session.save()
    saved = B.read(path)
    assert json.loads(saved.members[B.LATEST + "run.json"])["chi2_final"] == 123.4
    assert B.LATEST + "files/model/fit_spectra.mod.out" in saved.members
    assert "14.25" in saved.model_text()
    assert session.check_disk() == S.SAME


def test_the_runs_written_meanwhile_are_taken_in(home, path, registry):
    session = S.Session.open(path, registry=registry)
    assert session.project.model_changed_since_run() is None
    write_a_run(path)
