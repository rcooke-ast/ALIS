def test_autosave_writes_a_recovery_copy_and_reopening_offers_it(home, path, registry):
    session = S.Session.open(path, registry=registry)
    # Nothing to keep yet
    assert not session.autosave()
    assert not os.path.exists(session.recovery_path)
    set_value(session, 14.25)
    assert session.autosave()
    assert session.autosaved is not None
    assert os.path.exists(session.recovery_path)
    # A second autosave with nothing new writes nothing
    assert not session.autosave()
    # The bundle itself is unchanged: run_alis would fit what was saved
    assert S.Session.open(path, registry=registry).project.text != (
        session.project.text
    )
    edited = session.project.text
    # The dashboard stops here, as after a crash: no close
    note = S.find_recovery(path)
    assert note is not None and note["path"] == os.path.abspath(path)
    recovered = S.Session.open(path, recover=note, registry=registry)
    assert recovered.project.text == edited
    assert recovered.dirty
    # A clean close removes the copy
    recovered.close()
    assert S.find_recovery(path) is None
    assert not os.path.exists(session.recovery_path)


