def first_param(project, name="ColDens"):
    for par in project.parsed.params:
        if par.name == name and par.value_token is not None:
            return par
    raise AssertionError(name)


def set_value(session, value, name="ColDens"):
    """An edit made as a panel makes it: a step of the history."""
    project = session.project
    change = E.set_value(project.parsed, first_param(project, name), value)
    session.history.edit(change, "Set " + name)


def members(path, names):
    bundle = B.read(path)
    return {n: bundle.members.get(n) for n in names}


