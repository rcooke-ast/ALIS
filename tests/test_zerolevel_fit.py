"""A zero level of either sign is fitted (dashboard Stage 7, Task 7.7; Q7.14).

A ``constant`` in the ``zerolevel`` section took ``constant``'s lower limit of 0,
which is a continuum's. A trough that lies below zero, as in RJC's J193957m100241,
then pinned the zero level at 0 with no error. Here a synthetic saturated Lyα, with
a zero level of -0.03 and of +0.05, is fitted from ``constant 0.0`` by ``run_alis``,
and the zero level comes back within 3σ.

Generated by RJC and Claude.
"""

import pytest
from alisrun import run_alis
from dashboard_synthetic import write_trough

pytestmark = pytest.mark.fast


def zero_level(out):
    """The fitted zero level and its error, from a ``.mod.out``."""
    lines = out.read_text().splitlines()
    value = lines[lines.index(" zerolevel") + 1].split()[1]
    error = lines[lines.index("#zerolevel") + 1].split()[2]
    return float(value), float(error)


@pytest.mark.parametrize("zero", [-0.03, 0.05])
def test_a_zero_level_of_either_sign_is_fitted(tmp_path, zero):
    path = write_trough(tmp_path, zero)
    run_alis(path)
    value, error = zero_level(path.parent / "sat.mod.out")
    assert error > 0.0
    assert abs(value - zero) < 3.0 * error, (value, error)
