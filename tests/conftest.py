"""
Pytest bootstrap for the ALIS regression harness (Stage 0).

Makes the harness modules in this directory (manifest, alisrun,
compare) importable when pytest is invoked from the repository root,
and gates the ``slow`` batch behind ``--run-slow`` so the slowest
minimisations (e.g. DH/J0814p5029, ~16 min) only run on demand. The
batch markers (fast / medium / slow) are declared in the top-level
``pytest.ini``.

Generated by RJC and Claude.
"""

import sys
from pathlib import Path

import pytest

# Make manifest.py / alisrun.py / compare.py importable regardless of
# the directory pytest is invoked from.
sys.path.insert(0, str(Path(__file__).resolve().parent))


def pytest_addoption(parser):
    """
    Add ``--run-slow`` to opt into the slow batch.

    The astropy test plugins (present in this environment) register
    the same option; if so, adding it again raises ValueError, which
    is caught so the harness works both with and without them.

    Generated by RJC and Claude.
    """
    try:
        parser.addoption(
            "--run-slow",
            action="store_true",
            default=False,
            help="run the slow batch (>= 10 min/test)",
        )
    except ValueError:
        # Already registered (e.g. by pytest-astropy).
        pass


def pytest_collection_modifyitems(config, items):
    """
    Skip ``slow``-marked tests unless ``--run-slow`` was given.

    Generated by RJC and Claude.
    """
    if config.getoption("--run-slow"):
        return
    skip_slow = pytest.mark.skip(reason="need --run-slow option to run")
    for item in items:
        if "slow" in item.keywords:
            item.add_marker(skip_slow)
