"""Relinking moved spectra (dashboard Stage 3.9, F13), with no Qt.

- A moved source is relinked when its checksum matches.
- A changed file is refused.
- An embedded source is never reported missing.

Generated by RJC and Claude.
"""

import shutil
from pathlib import Path

import numpy as np
import pytest

from alis import bundle as B
from alis.dashboard import model as M
from alis.dashboard import preferences as PR
from alis.dashboard import session as S
from alis.dashboard import sources as SR

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
SPEC4 = ROOT / "examples/metal_line_abs/data/OI_SiII.dat"


@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


@pytest.fixture
def project_with_a_source(tmp_path, monkeypatch, registry):
    monkeypatch.setenv(PR.HOME_ENV, str(tmp_path / "home"))
    spectra = tmp_path / "spectra"
    spectra.mkdir()
    spectrum = spectra / "J0000_hires.dat"
    shutil.copy(SPEC4, spectrum)
    projects = tmp_path / "projects"
    projects.mkdir()
    session, _ = S.Session.new(
        str(projects / "J0000.model"), [str(spectrum)], registry=registry
    )
    return session, spectrum


def only_state(session):
    [(entry, state)] = SR.states(session.project.bundle, session.path)
    return entry, state


def test_a_present_source(project_with_a_source):
    session, spectrum = project_with_a_source
    entry, state = only_state(session)
    assert state == SR.PRESENT and entry["path"] == str(spectrum)
    assert SR.problems(session.project.bundle, session.path) == []
    assert SR.describe(entry, state) == "J0000_hires.dat is present and unchanged."


def test_a_moved_source_is_relinked_when_its_checksum_matches(
    project_with_a_source, tmp_path, registry
):
    session, spectrum = project_with_a_source
    moved = tmp_path / "elsewhere" / "renamed.dat"
    moved.parent.mkdir()
    spectrum.rename(moved)
    entry, state = only_state(session)
    assert state == SR.MISSING
    assert "J0000_hires.dat is missing" in SR.describe(entry, state)
    SR.relink(session.project.bundle, entry["id"], str(moved), session.path)
    entry, state = only_state(session)
    assert state == SR.PRESENT and entry["path"] == str(moved)
    # The project has changed: Save keeps the new place
    assert session.dirty
    session.save()
    again = S.Session.open(session.path, registry=registry)
    assert only_state(again)[1] == SR.PRESENT
    assert only_state(again)[0]["path"] == str(moved)


def test_a_changed_file_is_refused(project_with_a_source, tmp_path):
    session, spectrum = project_with_a_source
    other = tmp_path / "other.dat"
    np.savetxt(other, np.loadtxt(SPEC4)[:100])
    entry, _ = only_state(session)
    with pytest.raises(B.BundleError, match="not the same spectrum"):
        SR.relink(session.project.bundle, entry["id"], str(other), session.path)
    assert only_state(session)[0]["path"] == str(spectrum)
    # The file itself changed where it is: reported, never accepted
    np.savetxt(spectrum, np.loadtxt(SPEC4) * 2.0)
    entry, state = only_state(session)
    assert state == SR.CHANGED
    assert "has changed since it was added" in SR.describe(entry, state)
    with pytest.raises(B.BundleError):
        SR.relink(session.project.bundle, entry["id"], str(spectrum), session.path)


def test_an_embedded_source_is_never_missing(project_with_a_source):
    session, spectrum = project_with_a_source
    bundle = session.project.bundle
    B.embed_source(bundle, bundle.sources[0]["id"], session.path)
    spectrum.unlink()
    entry, state = only_state(session)
    assert state == SR.EMBEDDED
    assert SR.problems(bundle, session.path) == []
    assert "copy kept in the project" in SR.describe(entry, state)


def test_a_source_moved_with_the_project_is_found_beside_it(
    project_with_a_source, tmp_path, registry
):
    session, spectrum = project_with_a_source
    # Move the folder that holds both, as when copying a project to another disk
    new_root = tmp_path / "copy"
    new_root.mkdir()
    shutil.move(str(spectrum.parent), str(new_root / "spectra"))
    shutil.move(str(Path(session.path).parent), str(new_root / "projects"))
    moved = S.Session.open(
        str(new_root / "projects" / "J0000.model"), registry=registry
    )
    assert only_state(moved)[1] == SR.PRESENT


def test_the_checksum_is_read_again_when_the_file_changes(tmp_path):
    path = tmp_path / "a.dat"
    path.write_text("1 2 3\n")
    first = SR.file_sha256(str(path))
    assert SR.file_sha256(str(path)) == first
    path.write_text("1 2 4\n")
    assert SR.file_sha256(str(path)) != first
