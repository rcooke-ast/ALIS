def test_commit_describe_and_remove(path):
    bundle = B.read(path)
    B.store(bundle, result_for(bundle))
    assert R.commit(bundle, "First fit") == 1
    with pytest.raises(R.RunError, match="committed already"):
        R.commit(bundle, "Again")
    assert R.latest(bundle).committed_as == 1
    B.store(
        bundle, result_for(bundle, chi2=350.0, finished="2026-10-18T11:00:00+01:00")
    )
    assert R.latest(bundle).committed_as is None
    assert R.commit(bundle, "Second fit") == 2
    runs = R.committed(bundle)
    assert [r.number for r in runs] == [2, 1]
    assert runs[0].description == "Second fit"
    assert runs[1].chi2 == pytest.approx(357.874)
    assert runs[1].mod_out() is not None
    R.describe(bundle, 1, "T fixed at 8000 K")
    assert R.run_of(bundle, 1).description == "T fixed at 8000 K"
    R.remove(bundle, 2)
    assert R.latest(bundle).committed_as is None
    B.store(
        bundle, result_for(bundle, chi2=340.0, finished="2026-10-18T12:00:00+01:00")
    )
    # A number is never used again
    assert R.commit(bundle, "Third fit") == 3
    assert [r.number for r in R.committed(bundle)] == [3, 1]
    with pytest.raises(R.RunError):
        R.remove(bundle, 2)


def test_the_run_history_is_saved_with_save(home, path, registry):
    B.store(path, result_for(B.read(path)))
    session = S.Session.open(path, registry=registry)
    assert not session.dirty
    R.commit(session.project.bundle, "First fit")
