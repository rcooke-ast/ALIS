def test_a_run_kept_in_memory_for_a_project_with_no_file(home, registry):
    session = S.Session.import_model(str(METAL), registry=registry)
    sent = B.Bundle(manifest=dict(session.project.bundle.manifest))
    sent.members = dict(session.to_bundle().members)
    B.store(sent, result_for(sent))
    members = {m: c for m, c in sent.members.items() if m.startswith(B.RUNS)}
    R.apply_runs(
        session.project.bundle,
        {m: base64.b64encode(c).decode() for m, c in members.items()},
        {"lines": {}, "files": {}},
    )
    session.runs_changed()
    assert R.latest(session.project.bundle).chi2 == pytest.approx(357.874)
    assert session.autosave()
    assert R.latest(B.read(session.recovery_path)) is not None
    target = os.path.join(os.path.dirname(session.recovery_path), "..", "saved.model")
    session.save(target)
    assert R.latest(B.read(target)).chi2 == pytest.approx(357.874)


def test_restoring_a_run_is_one_step(home, path, registry):
    B.store(path, result_for(B.read(path)))
    session = S.Session.open(path, registry=registry)
    R.commit(session.project.bundle, "First fit")
    original = (session.project.text, dict(session.project.files))
    # The model and a snip change after the run
    set_value(session, 14.5)
    snip = session.project.snips[0]
    session.history.do(session.project.set_regions(snip, [(1301.5, 1302.6)]))
    changed = (session.project.text, dict(session.project.files))
    assert changed != original
    session.history.do(R.restore_step(session.project, 1))
    assert session.project.text == original[0]
    assert session.project.files == original[1]
    assert session.project.parsed.ok
    session.history.undo()
    assert (session.project.text, session.project.files) == changed
