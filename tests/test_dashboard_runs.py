"""Runs of a project, without a fit (dashboard Stage 6.1; F7, D26, S31; Q6.7, Q6.19).

- A bundle handed over as bytes reads back as it was written (``bundle.to_bytes``).
- ``bundle.store`` keeps a run's snips once each under ``runs/files/``, and drops
  those no run has any longer.
- What a run holds: its best-fit values, its errors and its covariance, by ALIS's
  number for each parameter, read from metal_line_abs's and J1358p6522's reference
  outputs.
- The run history: commit (numbers never reused), describe, remove; Save writes it,
  and keeps a newer run that ``run_alis`` stored meanwhile; the recovery copy keeps
  it; restoring a run's model and snips is one step, which one undo reverses.

The runs here are made from reference outputs, so no fit is run; the fitting process
itself is tested in ``test_dashboard_runs_process.py`` (marked ``fast``). No Qt.

Generated by RJC and Claude.
"""

