def test_the_values_errors_and_covariance_of_a_run(path, registry):
    bundle = B.read(path)
    B.store(bundle, result_for(bundle))
    run = R.latest(bundle)
    project = P.Project(bundle, registry)
    values = run.values(registry)
    errors = run.errors(registry)
    covar = run.covariance()
    assert covar.shape == (17, 17)
    # O I's column density and Si II's, as the reference prints them
    coldens = [p.index for p in project.parsed.params if p.name == "ColDens"]
    assert values[coldens[0]] == pytest.approx(13.9851970)
    assert values[coldens[1]] == pytest.approx(13.0411835)
    # The errors the .mod.out prints are the covariance's, to its precision
    for index, error in errors.items():
        if error > 0:
            assert error == pytest.approx(np.sqrt(covar[index, index]), rel=1e-5)
    assert errors[coldens[0]] == pytest.approx(0.0155392)


def test_j1358_errors_agree_with_its_covariance(tmp_path, registry):
    target = tmp_path / "j1358.model"
    B.pack_to(str(J1358), str(target))
    bundle = B.read(str(target))
    stem = str(J1358)[: -len(".mod")]
    result = result_for(bundle, stem=stem)
    result.files = {
        "J1358p6522.mod.out": Path(stem + ".mod.out.reference").read_bytes(),
        "J1358p6522.covar": Path(stem + ".covar.reference").read_bytes(),
    }
    B.store(bundle, result)
    run = R.latest(bundle)
    errors = run.errors(registry)
    covar = run.covariance()
    project = P.Project(bundle, registry)
    free = {p.index for p in project.parsed.params if p.free and p.index >= 0}
    assert len(free) > 100
    checked = 0
    for index in free:
        if index in errors and covar[index, index] > 0:
            want = np.sqrt(covar[index, index])
            # Printed to about six significant figures
            assert errors[index] == pytest.approx(want, rel=2e-3, abs=2e-6), index
            checked += 1
    assert checked > 100
    # The FWHM's error, from the covariance
    fwhm = next(p for p in project.parsed.params if p.role == "resolution")
    assert errors[fwhm.index] == pytest.approx(0.171, rel=0.01)


