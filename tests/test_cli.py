"""The `run_alis` command line (Stage 6.1).

The CLI has two halves: `run_alis.parser`, which is argparse, and
`load.optarg`, which copies the parsed namespace onto the `argflag` config and
loads `settings.alis`. Nothing pinned either, which is how the model filename
came to be read from `sys.argv[-1]` instead of from the parser -- so
`run_alis fit.mod -w` tried to fit a file called `-w`. The shipped examples and
the regression harness all put their flags *before* the model file, which is why
it went unnoticed; `tests/alisrun.py` even carried a comment telling future
readers to keep it that way.

No fit is run: `ClassMain` is replaced with a recorder, so these tests exercise
the argument path and stop at the point the fit would start.

Generated by RJC and Claude.
"""

import pytest

import alis.main
from alis.scripts import run_alis

pytestmark = pytest.mark.unit


@pytest.fixture
def captured_argflag(monkeypatch):
    """Run `run_alis.main` and hand back the config it would have fitted with."""
    seen = {}

    def _recorder(argflag, *args, **kwargs):
        seen["argflag"] = argflag
        return None

    monkeypatch.setattr(alis.main, "ClassMain", _recorder)

    def run(argv):
        seen.clear()
        run_alis.main(run_alis.parser(argv))
        assert "argflag" in seen, "ClassMain was never reached"
        return seen["argflag"]

    return run


# -- the parser ---------------------------------------------------------------


def test_the_model_file_is_the_one_positional_argument():
    assert run_alis.parser(["fit_spectra.mod"]).alis_modfile == "fit_spectra.mod"


def test_a_missing_model_file_is_rejected():
    with pytest.raises(SystemExit):
        run_alis.parser([])


@pytest.mark.parametrize(
    "argv", [["fit.mod", "-w"], ["-w", "fit.mod"], ["-p", "0", "fit.mod"]]
)
def test_the_parser_finds_the_model_file_whatever_the_flag_order(argv):
    assert run_alis.parser(argv).alis_modfile == "fit.mod"


# -- the namespace reaches argflag -------------------------------------------


@pytest.mark.parametrize(
    "argv",
    [
        ["fit_spectra.mod"],
        ["-f", "-w", "-p", "0", "fit_spectra.mod"],  # what the harness passes
        ["fit_spectra.mod", "-w"],  # the order that used to break
        ["fit_spectra.mod", "-p", "0"],  # ... and the one that broke it worst
    ],
    ids=["bare", "flags-first", "flag-after", "valued-flag-after"],
)
def test_the_model_file_reaches_argflag_whatever_the_flag_order(captured_argflag, argv):
    """`sys.argv[-1]` is the model file only when nothing follows it.

    The last case is the sharpest: with `-p 0` trailing, the old code set
    `modname` to `'0'`.
    """
    assert captured_argflag(argv)["run"]["modname"] == "fit_spectra.mod"


def test_the_flags_are_applied_to_the_settings(captured_argflag):
    cfg = captured_argflag(["-f", "-w", "-m", "-j", "-l", "-p", "2x2", "fit.mod"])
    assert cfg["out"]["fits"] is True
    assert cfg["out"]["overwrite"] is True
    assert cfg["out"]["model"] is True
    assert cfg["plot"]["only"] is True
    assert cfg["plot"]["labels"] is True
    assert cfg["plot"]["dims"] == "2x2"


def test_the_verbosity_flags_reach_the_settings(captured_argflag):
    assert captured_argflag(["-v", "1", "fit.mod"])["out"]["verbose"] == 1
    assert captured_argflag(["-q", "fit.mod"])["out"]["verbose"] == 0


def test_the_simulation_flags_reach_the_settings(captured_argflag):
    cfg = captured_argflag(["-a", "3", "-r", "5", "-s", "7", "fit.mod"])
    assert cfg["sim"]["repeat"] == 3
    assert cfg["sim"]["random"] == 5
    assert cfg["sim"]["startid"] == 7


def test_the_xaxis_flag_is_mapped_to_its_name(captured_argflag):
    for value, name in enumerate(["observed", "rest", "velocity"]):
        assert captured_argflag(["-x", str(value), "fit.mod"])["plot"]["xaxis"] == name


def test_an_output_name_reaches_the_settings(captured_argflag):
    assert (
        captured_argflag(["-o", "myfit.mod.out", "fit.mod"])["out"]["modelname"]
        == "myfit.mod.out"
    )


def test_flags_that_were_not_given_leave_the_defaults_alone(captured_argflag):
    """Every option is applied under an `if`, so an absent flag must not
    overwrite a value that `settings.alis` or the model file has set."""
    from alis.config import ArgFlag

    defaults = ArgFlag()
    cfg = captured_argflag(["fit.mod"])
    for section, key in (
        ("out", "fits"),
        ("out", "model"),
        ("out", "overwrite"),
        ("plot", "only"),
        ("plot", "labels"),
        ("sim", "repeat"),
        ("sim", "random"),
    ):
        assert cfg[section][key] == defaults[section][key], (section, key)


# -- exit status (Stage 6.1, Q6.11) ------------------------------------------


def test_a_bad_invocation_exits_non_zero(tmp_path):
    """A failure must not look like success to whatever ran ALIS.

    `msgs.error` used to call a bare `sys.exit()`, i.e. status 0, so a mis-typed
    model filename produced "[ERROR] :: The filename does not exist" and an exit
    code the harness read as a pass. This runs the real entry point in a
    subprocess, which is the only way to observe the process status.
    """
    import os
    import subprocess
    import sys
    from pathlib import Path

    run_alis_py = (
        Path(__file__).resolve().parent.parent / "alis" / "scripts" / "run_alis.py"
    )
    env = dict(os.environ)
    env["MPLBACKEND"] = "Agg"
    proc = subprocess.run(
        [sys.executable, str(run_alis_py), "no_such_model.mod"],
        cwd=str(tmp_path),
        env=env,
        capture_output=True,
        text=True,
        timeout=300,
    )
    assert proc.returncode != 0, "a failed run reported success"
    assert "does not exist" in (proc.stdout + proc.stderr)


# -- --set, --list-settings and precedence (Stage 6.1, Q6.7/Q6.12/Q6.24) ------


def test_set_accepts_any_setting(captured_argflag):
    cfg = captured_argflag(
        ["--set", "run backend cpu", "--set", "chisq atol 0.5", "fit.mod"]
    )
    assert cfg["run"]["backend"] == "cpu"
    assert cfg["chisq"]["atol"] == 0.5


def test_set_rejects_a_setting_that_does_not_exist(captured_argflag):
    with pytest.raises(SystemExit):
        captured_argflag(["--set", "run wibble 3", "fit.mod"])
    with pytest.raises(SystemExit):
        captured_argflag(["--set", "wibble backend cpu", "fit.mod"])


def test_set_rejects_a_fragment(captured_argflag):
    with pytest.raises(SystemExit):
        captured_argflag(["--set", "run backend", "fit.mod"])


def test_list_settings_prints_every_section_and_exits(capsys):
    from alis.config import ArgFlag

    with pytest.raises(SystemExit):
        run_alis.parser(["--list-settings"])
    printed = capsys.readouterr().out
    cfg = ArgFlag()
    for section in cfg.keys():
        assert "[{0:s}]".format(section) in printed, section
    # and the values, since the point is to be able to see the defaults
    assert "fstep" in printed and "20.0" in printed


def test_the_gpu_flag_takes_a_count_not_a_boolean(captured_argflag):
    """`-g` was a store_true, so `run ngpus` became the boolean True where the
    config declares an int (Stage 6.1, Q6.19)."""
    assert captured_argflag(["-g", "4", "fit.mod"])["run"]["ngpus"] == 4
    assert captured_argflag(["fit.mod"])["run"]["ngpus"] == 0
    # The count is required: a bare -g would otherwise consume the model file.
    with pytest.raises(SystemExit):
        run_alis.parser(["-g", "fit.mod"])


def test_the_overrides_record_what_the_command_line_changed():
    from alis import load

    overrides = []
    load.optarg(
        argv=run_alis.parser(["-f", "-p", "0", "fit.mod"]),
        verbose=0,
        overrides=overrides,
    )
    changed = {(sec, key): (new, persist) for sec, key, _old, new, persist in overrides}
    assert changed[("out", "fits")] == (True, True)
    assert changed[("plot", "dims")] == ("0", True)


def test_invocation_only_flags_are_marked_not_to_persist():
    """Persisting these would change what a re-run of the .mod.out does: `-j`
    would stop it fitting at all, `-o` would make it clobber the original
    output, `-w` would make it overwrite silently (Q6.20)."""
    from alis import load

    overrides = []
    load.optarg(
        argv=run_alis.parser(["-j", "-w", "-o", "x.out", "-r", "5", "fit.mod"]),
        verbose=0,
        overrides=overrides,
    )
    persist = {(sec, key): keep for sec, key, _old, _new, keep in overrides}
    assert persist[("plot", "only")] is False
    assert persist[("out", "overwrite")] is False
    assert persist[("out", "modelname")] is False
    assert persist[("sim", "random")] is False
