@pytest.fixture(scope="module")
def registry(atomic_data):
    return M.Registry(atomic_data)


def errors(project):
    return [p.message for p in V.check(project) if p.severity == V.ERROR]


def fit(registry, folder, resolution="vfwhm(6.285VFIX)", lines=None):
    """J101155p294141's snip of Lyα, its resolution as given."""
    path = write_ratio_fit(folder, lines)
    path.write_text(path.read_text().replace("vfwhm(6.285VFIX)", resolution))
    project = P.Project.import_model(str(path), registry=registry)
    assert errors(project) == []
    return project, H.History(project)


def test_the_nine_knots_of_an_lsfspline_are_read(registry, tmp_path):
    project, hist = fit(registry, tmp_path, NINE)
    row = project.rows[0]
    knots = LK.knots_of(project, row)
    assert knots.smoothing == 2.14
    assert knots.velocities == [-10.0, -5.0, -3.0, -1.0, 0.0, 1.0, 3.0, 5.0, 10.0]
    assert knots.heights == [0.0, 0.05, 0.2, 0.8, 1.0, 0.8, 0.2, 0.05, 0.0]
    assert LK.knots_of(project, project.snips[0]).heights == knots.heights
    # Written as the dataset's, and read back the same
    text = project.text
    hist.do(LK.knots_step(project, project.rows[0], knots, LK.spix(project, row)))
    assert errors(project) == []
    again = LK.knots_of(project, project.rows[0])
    assert (again.smoothing, again.velocities, again.heights) == (
        knots.smoothing,
        knots.velocities,
        knots.heights,
    )
    hist.undo()
    assert project.text == text


@pytest.mark.parametrize(
    "resolution, smoothing",
    [
        ("vfwhm(6.285VFIX)", 6.285),
        ("vsigma(3.0VFIX)", 3.0 * LK.FWHM_SIGMA),
        ("Afwhm(0.1AFIX)  bintype=A", None),
        ("vfwhm(6.285VFIX,blind=True)", 5.0),
    ],
)
def test_another_function_starts_from_three_knots(
    registry, tmp_path, resolution, smoothing
):
    # Q12.8 (iii) and its response: the resolution before, or 5 km/s
    if "blind" in resolution:
        project, _ = fit(registry, tmp_path)
        gate = BL.Gate(project, hidden_lines={project.snips[0].data.line})
        knots = LK.knots_of(project, project.rows[0], gate)
    else:
        project, _ = fit(registry, tmp_path, resolution)
        knots = LK.knots_of(project, project.rows[0])
    assert knots.points == [(-10.0, 0.0), (0.0, 1.0), (10.0, 0.0)]
    if smoothing is None:
        # 0.1 Å at the snip's middle, as km/s
        wave = DS.resolution_wave(project.rows[0])
        smoothing = 0.1 * C_KMS / wave
    assert knots.smoothing == pytest.approx(smoothing)


