def test_the_kernel_and_its_fwhm():
    # Three knots and no smoothing: a triangle of FWHM 10 km/s; a smoothing widens it
    knots = LK.Knots(0.0, [-10.0, 0.0, 10.0], [0.0, 1.0, 0.0])
    v, k = LK.kernel(knots, 7700.0, 2.0, 10)
    assert k.max() == pytest.approx(1.0)
    assert LK.fwhm(v, k) == pytest.approx(10.0, rel=1e-3)
    knots.smoothing = 5.0
    v, k = LK.kernel(knots, 7700.0, 2.0, 10)
    assert 10.5 < LK.fwhm(v, k) < 12.5
    # The kernel is ALIS's own function on a spike
    from alis.functions.lsfspline import SplineLSF

    x = 7700.0 * np.exp(np.arange(-200, 201) * 0.2 / C_KMS)
    spike = np.zeros(x.size)
    spike[200] = 1.0
    direct = SplineLSF(getinst=True).call_CPU(
        x, spike, np.array([5.0, 0.0, 1.0, 0.0]), mkey={"locations": [-10, 0, 10]}
    )
    v, k = LK.kernel(knots, 7700.0, 2.0, 10)
    at = C_KMS * (x - x[200]) / x[200]
    inside = np.abs(at) <= v.max()
    mine = np.interp(at[inside], v, k)
    assert np.allclose(mine, direct[inside] / direct.max(), atol=1e-6)


def test_the_sub_pixels_alis_uses():
    class Pix:
        wave = 4252.0 + 0.02 * np.arange(500)

    class Snip:
        pixels = Pix()

    class Project:
        class parsed:
            argflag = {"run": {"nsubmin": 5, "nsubmax": 21, "nsubpix": 5}}

    pixel = LK.pixel_kms(Snip())
    asked = int(round(LK.FWHM_SIGMA * 5 * pixel / 2.0 + 0.5))
    assert LK.subpixels(Project(), Snip(), 2.0) == min(max(5, asked), 21)
    assert LK.subpixels(Project(), Snip(), 50.0) == 5
    assert LK.subpixels(Project(), Snip(), 50.0, asked=9) == 9
    assert LK.subpixels(Project(), Snip(), 0.01) == 21


def test_the_step_for_a_snip_of_its_own_and_for_a_dataset(registry, tmp_path):
    path = write_twin_snips(tmp_path)
    project = P.Project.import_model(str(path), registry=registry)
    hist = H.History(project)
    text = project.text
    snip = project.snips[0]
    knots = LK.delta_knots(3.0, LK.spix(project, snip))
    # A snip that takes its dataset's resolution: Its own first
    if snip.specid not in snip.row.own_resolution:
        with pytest.raises(LK.KnotsError, match="Its own first"):
            LK.knots_step(project, snip, knots)
        hist.do(DS.snip_resolution_step(project, snip, True))
    snip = project.snip(snip.specid)
    hist.do(LK.knots_step(project, snip, knots, LK.spix(project, snip)))
    assert errors(project) == []
    item = project.snip(snip.specid).data
    assert item.resolution.name == "lsfspline"
    pars = [p for p in item.params if p.role == "resolution"]
    # The smoothing and the inner heights free; the edges and the centre fixed
    assert [p.fixed for p in pars] == [False, True, False, True, False, True]
    hist.undo()
    if hist.done:
        hist.undo()
    assert project.text == text
    # A dataset's: every line that takes it, sharing its labels
    row = project.rows[0]
    hist.do(LK.knots_step(project, row, knots, LK.spix(project, row)))
    assert errors(project) == []
    words = {s.data.keyword("resolution") for s in project.rows[0].snips}
    assert len(words) == 1 and next(iter(words)).startswith("lsfspline(")
    hist.undo()
    assert project.text == text
    # Knots that break a rule are refused, with the reason
    bad = LK.Knots(3.0, [-10.0, 0.0, 10.0], [0.0, 0.5, 0.0])
    with pytest.raises(LK.KnotsError, match="0 km/s"):
        LK.knots_step(project, project.rows[0], bad)


def test_the_buffer_check_takes_the_kernel_s_reach(registry, tmp_path):
    wide = "lsfspline(3.0va,0.0LFIX,1.0CFIX,0.0RFIX;locations:-200.0,0.0,200.0)"
    project, _ = fit(registry, tmp_path, wide)
    snip = project.snips[0]
    hist = H.History(project)
    hist.do(S.add_region_step(project, snip, 4256.0, 4262.0))
    blue, red = S.buffers(project, project.snip(snip.specid))
    reach = LK.half_width(LK.knots_of(project, project.snips[0]))
    assert blue.need == pytest.approx(reach, rel=1e-6)
    assert red.need == pytest.approx(reach, rel=1e-6)
