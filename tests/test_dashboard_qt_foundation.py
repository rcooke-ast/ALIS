"""The Qt foundation of the dashboard (dashboard Stage 3.1).

- Only ``alis/dashboard/qt/`` imports Qt or pyqtgraph, and it imports Qt only
  through ``qtpy`` (D2).
- The ``alis`` command (F14, named in Q3.15) has a ``--help``, and without the
  ``gui`` extra it says how to install it and stops with status 1.

These tests need no Qt: they read the source and run the command in a fresh
interpreter.

Generated by RJC and Claude.
"""

import ast
import os
import subprocess
import sys
from pathlib import Path

import pytest

from alis.scripts import dashboard as script

pytestmark = pytest.mark.unit

ROOT = Path(__file__).resolve().parents[1]
ALIS = ROOT / "alis"
QT = ALIS / "dashboard" / "qt"
BINDINGS = ("PySide6", "PyQt6", "PyQt5", "PySide2")
GUI_MODULES = BINDINGS + ("qtpy", "pyqtgraph")


def imported_modules(path):
    """
    The top-level names of every module a source file imports.

    Generated by RJC and Claude.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            names |= {alias.name.split(".")[0] for alias in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module and not node.level:
            names.add(node.module.split(".")[0])
    return names


def run(code, *args):
    """
    Run Python code in a fresh interpreter, from the repository root.

    Generated by RJC and Claude.
    """
    env = dict(os.environ)
    env.pop("QT_API", None)
    return subprocess.run(
        [sys.executable, "-c", code, *args],
        capture_output=True,
        text=True,
        cwd=ROOT,
        env=env,
        timeout=120,
    )


def test_the_qt_package_exists_and_says_what_it_is():
    doc = (QT / "__init__.py").read_text(encoding="utf-8")
    assert "only part of ALIS that imports Qt" in doc
    assert "qtpy" in doc


def test_only_the_qt_package_imports_qt_or_pyqtgraph():
    offenders = []
    for path in ALIS.rglob("*.py"):
        if QT in path.parents:
            continue
        found = imported_modules(path) & set(GUI_MODULES)
        if found:
            offenders.append((str(path.relative_to(ROOT)), sorted(found)))
    assert offenders == []


def test_the_qt_package_imports_qt_only_through_qtpy():
    files = sorted(QT.rglob("*.py"))
    assert files, "alis/dashboard/qt/ has no modules"
    offenders = []
    for path in files:
        found = imported_modules(path) & set(BINDINGS)
        if found:
            offenders.append((str(path.relative_to(ROOT)), sorted(found)))
    assert offenders == []


def test_qt_api_defaults_to_pyside6_unless_the_user_chose():
    code = "import os; import alis.dashboard.qt; print(os.environ['QT_API'])"
    assert run(code).stdout.strip() == "pyside6"
    env_code = (
        "import os; os.environ['QT_API'] = 'pyqt6'; import alis.dashboard.qt;"
        " print(os.environ['QT_API'])"
    )
    assert run(env_code).stdout.strip() == "pyqt6"


def test_the_parser():
    assert script.parser([]).path is None
    assert script.parser(["project.model"]).path == "project.model"


def test_help_works():
    out = run(
        "import sys; from alis.scripts.dashboard import console_entry;"
        " sys.argv = ['alis', '--help']; console_entry()"
    )
    assert out.returncode == 0
    assert "usage: alis" in out.stdout
    assert ".model" in out.stdout and "run_alis" in out.stdout


def test_the_installed_command_has_help():
    command = Path(sys.executable).with_name("alis")
    if not command.exists():
        pytest.skip("the alis command is not installed here (pip install -e .)")
    out = subprocess.run(
        [str(command), "--help"], capture_output=True, text=True, timeout=120
    )
    assert out.returncode == 0
    assert "usage: alis" in out.stdout


@pytest.mark.parametrize("args", [[], ["project.model"]])
def test_without_qt_it_says_how_to_install_the_gui_extra(args):
    hide = "; ".join("sys.modules[{0!r}] = None".format(m) for m in GUI_MODULES)
    code = (
        "import sys; {0}; sys.argv = ['alis'] + sys.argv[1:];"
        " from alis.scripts.dashboard import console_entry; console_entry()"
    ).format(hide)
    out = run(code, *args)
    assert out.returncode == 1
    assert 'pip install "alis[gui]"' in out.stderr
    assert "Traceback" not in out.stderr


def test_qt_available_here_when_the_extra_is_installed():
    pytest.importorskip("qtpy.QtWidgets")
    pytest.importorskip("pyqtgraph")
    assert script.qt_available()
