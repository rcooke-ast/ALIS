def test_align_columns_is_on_the_mod_panel(window, qtbot):
    if not J1358.exists():
        pytest.skip("J1358p6522 is not present")
    window.import_path(str(J1358))
    wait_idle(qtbot, window, timeout=30000)
    project = window.session.project
    original = project.text
    # Not on the banner, nor in the menus (RJC's review, draft 3)
    buttons = [
        b.text() for b in window.notice_banner.findChildren(QtWidgets.QPushButton)
    ]
    assert buttons == ["Hide"]
    titles = [a.text() for m in window.menus.values() for a in m.actions()]
    assert "Align columns" not in titles
    # On the panel, beside its window button
    [button] = window.panel.panel_buttons
    assert button.text() == "Align columns" and button.isVisible()
    row = window.panel.header_row
    assert row.indexOf(button) == row.indexOf(window.panel.window_button) - 1
    button.click()
    assert project.text == AL.aligned(original)
    assert window.panel.editor.toPlainText() == window.panel.live.shown
    assert window.qactions["edit.undo"].text() == "Undo Align columns"
    # Aligned already: a message, and no step
    window.qactions["panel.align"].trigger()
    assert "aligned already" in window.statusBar().currentMessage()
    window.qactions["edit.undo"].trigger()
    assert project.text == original
    # In its own window too
    window.set_panel_window(True)
    assert button.isVisible()
    window.set_panel_window(False)


def test_the_panel_in_its_own_window_and_back(window, qtbot, tmp_path):
    path = open_metal(window, qtbot, tmp_path)
    dock = window.dock
    assert dock.isVisible() and not dock.isFloating()
    assert window.panel.window_button.text() == "⧉ Own window"
    window.panel.window_button.click()
    assert dock.isFloating() and dock.isVisible()
    assert window.qactions["view.mod_window"].isChecked()
    assert window.panel.window_button.text() == "↩ Back to the dashboard"
    assert window.session.view["mod_panel"]["window"] is True
    # It still works with the dashboard: typing reaches the project
    editor = window.panel.editor
    cursor = editor.textCursor()
    cursor.setPosition(editor.toPlainText().index("chisq ftol"))
    editor.setTextCursor(cursor)
    qtbot.keyClicks(editor, "# ")
    wait_idle(qtbot, window)
    assert "# chisq ftol" in window.session.project.text
    assert window.isWindowModified()
    # Back into the dashboard
    window.qactions["view.mod_window"].trigger()
    assert not dock.isFloating() and dock.isVisible()
    assert window.session.view["mod_panel"]["window"] is False
    # Its own window is remembered with the project
    window.panel.window_button.click()
    window.answers.answers["unsaved"] = "Save"
    window.do_file_close()
    assert S.Session.open(path).view["mod_panel"]["window"] is True


def test_the_panel_s_width_is_the_user_s(window, qtbot, tmp_path):
    open_metal(window, qtbot, tmp_path)
    window.set_panel_open(True, width=600)
    qtbot.wait(50)
    window.refresh()
    assert abs(window.session.view["mod_panel"]["width"] - 600) <= 30
    # Narrower: down to what its header needs
    window.resizeDocks([window.dock], [300], QtCore.Qt.Orientation.Horizontal)
    qtbot.wait(50)
    window.refresh()
    narrow = window.session.view["mod_panel"]["width"]
    assert narrow <= window.panel.minimumSizeHint().width() + 30 and narrow < 460
    # The header's labels do not run into each other
    name, state = window.panel.name, window.panel.state
    assert name.geometry().right() < state.geometry().left()


