def test_the_spectrum_dialog_asks_for_file_fwhm_and_columns(qtbot, tmp_path):
    dialog = D.NewProjectDialog(str(tmp_path), fwhm=7.0)
    qtbot.addWidget(dialog)
    seen = []

    def answer(spectrum):
        seen.append(spectrum)
        assert spectrum.windowTitle() == "Add a spectrum (ascii)"
        ok = spectrum.box.button(QtWidgets.QDialogButtonBox.StandardButton.Ok)
        assert not ok.isEnabled() and spectrum.problem() == "Choose a file."
        spectrum.set_file(str(SPECTRUM))
        # Guessed: a fourth column that is not 0s and 1s is a continuum
        assert spectrum.columns.choices() == ["wave", "flux", "error", "continuum"]
        assert ok.isEnabled()
        # Ignore any number of columns; every other role once; the three needed
        spectrum.columns.set_role(3, None)
        assert ok.isEnabled()
        spectrum.columns.set_role(2, "flux")
        assert "Flux is given to more than one column" in spectrum.problem()
        assert "choose the error column" in spectrum.problem()
        assert not ok.isEnabled()
        spectrum.columns.set_role(2, None)
        spectrum.columns.set_role(1, None)
        assert spectrum.problem() == "Choose the flux, error columns."
        spectrum.columns.set_role(1, "flux")
        spectrum.columns.set_role(2, "error")
        spectrum.fwhm.setValue(4.25)
        assert ok.isEnabled()
        return 1

    dialog.run_spectrum_dialog = answer
    dialog.add_ascii.click()
    assert len(seen) == 1
    assert dialog.entries == [
        {
            "path": str(SPECTRUM),
            "roles": {"wave": 0, "flux": 1, "error": 2},
            "fwhm": 4.25,
        }
    ]
    assert dialog.spectra.item(0, 4).text() == "wavelength, flux, error"

    # Double-click a spectrum to change it
    def change(spectrum):
        assert spectrum.columns.choices() == ["wave", "flux", "error", None]
        spectrum.fwhm.setValue(5.0)
        return 1

    dialog.run_spectrum_dialog = change
    dialog.edit_spectrum(0)
    assert dialog.entries[0]["fwhm"] == 5.0
    assert dialog.values()["fwhms"] == {str(SPECTRUM): 5.0}


