def test_a_mask_is_a_bad_pixel_mask(qtbot, tmp_path):
    """A pixel whose mask is 1 is left out of the fit, even in a fit region."""
    from alis.dashboard import modes as MO

    table = np.loadtxt(SPECTRUM)[:, :3]
    bad = np.zeros(table.shape[0])
    bad[100:110] = 1.0
    path = tmp_path / "masked.dat"
    np.savetxt(path, np.column_stack([table, bad]))
    # A column of 0s and 1s is guessed as Ignore: most likely a snip's fit range,
    # which a source spectrum does not carry (RJC's review, Q3.19)
    spectrum = D.SpectrumDialog(str(tmp_path))
    qtbot.addWidget(spectrum)
    spectrum.set_file(str(path))
    assert spectrum.columns.choices() == ["wave", "flux", "error", None]
    assert spectrum.entry()["roles"] == {"wave": 0, "flux": 1, "error": 2}
    # Chosen as a mask, it is a bad-pixel mask
    spectrum.columns.set_role(3, "mask")
    spec = MO.get().load(str(path), spectrum.entry()["roles"])
    assert spec.columns["mask"] == 3
    assert spec.mask.dtype == bool and spec.mask.sum() == 10


def test_a_new_project_keeps_the_roles_chosen(window, qtbot, tmp_path):
    table = np.loadtxt(SPECTRUM)
    spectrum = tmp_path / "swapped.dat"
    # Error before flux, and a mask column: roles that D13's rule would not guess
    mask = (np.arange(table.shape[0]) % 7 != 0).astype(float)
    np.savetxt(spectrum, np.column_stack([table[:, 0], table[:, 2], table[:, 1], mask]))
    folder = tmp_path / "projects"
    folder.mkdir()

    def answer(dialog):
        dialog.name.setText("swapped")
        dialog.folder.setText(str(folder))
        roles = {"wave": 0, "error": 1, "flux": 2, "mask": 3}
        assert dialog.add_spectrum(str(spectrum), roles, fwhm=3.5) == ""
        return 1

    window.on_dialog = answer
    window.qactions["file.new"].trigger()
    row = window.session.project.rows[0]
    assert row.columns == {"wave": 0, "error": 1, "flux": 2, "mask": 3}
    assert window.session.project.ui["rows"][0]["fwhm"] == 3.5
